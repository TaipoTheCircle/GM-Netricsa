RAKOW G3A3 ASSAULT RIFLE


WEAPON:    Rakow G3A3 Assault Rifle
AMMO:      7.62x51mm NATO
ROF:       3-round burst

DESCRIPTION:

A modern assault rifle used by soldiers of the Armacham corporation. It is equipped with a low-magnification optical sight, ensuring high accuracy when engaging targets at medium to long ranges.

Unlike most automatic rifles, the G3A3 fires exclusively in three-round bursts. The magazine holds 24 rounds, enough for eight bursts. Thanks to its high accuracy and power, the weapon is effective against armored opponents; however, its small magazine capacity and somewhat awkward hip-fire handling limit its utility in close-quarters combat.

NOTES:

- Not to be confused with the German Heckler & Koch G3A3 rifle.
- The receiver is marked with a 7.62mm caliber designation, though the exact ammunition type has not been officially confirmed.
- Three rounds per trigger pull—ideal for conserving ammunition.
- With good marksmanship, it can serve as a substitute for a sniper rifle at medium ranges.
