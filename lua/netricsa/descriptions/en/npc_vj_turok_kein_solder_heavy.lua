MENDEL-GRUMAN HEAVY WEAPONS SOLDIER


CLASS:      Mendel-Gruman Heavy Weapons Soldier
METABOLISM: Human, Male
PERCEPTION: Heavy Assault Infantry
SIZE:       6,2 ft
ENDURANCE:  Very High
HOSTILITY:  Extreme
WEAPOON:    ORO War horse Heavy Rotary Machine Gun
REWARD:     1000 FC
THREAT:     Very High

DESCRIPTION:

Specialized heavy troopers of the Mendel-Gruman corporation, designed to destroy high-risk targets and suppress the enemy with firepower. Unlike regular MG soldiers, who operate in groups with automatic weapons, these fighters are truly mobile machine gun crews, who, for some reason, didn't require a second man.

They are clad in heavy, dull green military armor. The armor covers most of the body, has a high collar, reinforced wrists, and armored thighs. Their faces are completely hidden behind a bright gray-silver visor. They are noticeably heavier in appearance than standard Mendel-Gruman soldiers and belong to the same heavy category as Elite and Pyro.

The main weapon of the "ORO Warhorse" unit is a large-caliber, six-channel rotary machine gun. It is capable of delivering an extremely dense stream of fire at a high rate of fire. The machine gun requires several moments to spin up its barrels, after which it turns the attack line into a rather unpleasant zone for all living beings.

Therefore, a Warhorse's burst can create a very nasty chain: several hits slow the target, after which subsequent bullets begin to land even more easily.

Despite their heavy armor, the unit has a noticeable weakness: the head. A single well-aimed shot to the head can instantly destroy it, so their armor doesn't make them invulnerable. They can also survive a hit from a partially drawn Perforator arrow, highlighting their significantly higher protection compared to regular soldiers.

In combat, Heavy Weapons Soldiers are typically used as a suppressive force. They appear relatively rarely, but when they do, their task is simple: halt the enemy's advance with a barrage of fire. A few of these soldiers can literally turn an open area into a machine gun corridor.

TIPS:

- Don't expose yourself to his machine gun fire. The Warhorse deals a huge amount of damage.
- Aim for the head. This is their main vulnerability, despite their heavy armor.
- Don't try to out-shoot him with a regular assault rifle. This is a fight where one side clearly has the larger machine gun.
- Use cover and flank. The Heavy Weapons Soldier is especially dangerous where he has room to fire a long burst.
- Don't let multiple Heavy Weapons Soldiers concentrate fire on a single target. Their firepower becomes much more dangerous when they attack together.
- If you have the option of using explosives or powerful weapons, don't save them for this guy. He's one of those guys where the word "heavy" should be taken literally.
