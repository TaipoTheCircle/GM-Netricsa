GRINDER IMPROVISED WEAPON (DISC LAUNCHER)


WEAPON: Grinder Improvised Weapon (Disc Launcher)
AMMO:   Metal Discs
ROF:    Moderate

DESCRIPTION:

A homemade insurgent weapon crafted from salvaged components and industrial machinery parts. It is a heavy device featuring a rotating cutting mechanism, designed to neutralize enemy personnel. It fires sharp-edged metal discs at high velocity, turning ordinary scrap metal into lethal projectiles.

The motor requires time to reach the necessary rotational speed, resulting in a slight delay before firing. The primary fire mode launches spinning cutting discs, while the secondary mode allows the user to strike an enemy with the weapon’s chassis. It can be upgraded to reduce spin-up time, increase ammunition capacity, and enable the use of explosive discs.

NOTES:

- Effective against individual EDF soldiers at short to medium ranges.
- A headshot with a disc can kill an enemy instantly.
- Virtually useless for destroying buildings or heavy structures.
- Built by insurgents using scavenged parts and industrial equipment.
- Can be upgraded to fire explosive discs.
