LEBEDEVA PL-14 PISTOL


WEAPON: Lebedev PL-14 Pistol
AMMO:   9x19mm Parabellum
ROF:    ~40-50 rounds / min
WEIGHT: ~0,8 kg

DESCRIPTION:

This Russian semi-automatic pistol was developed by Dmitry Lebedev's team at the Kalashnikov Concern. It was first presented in 2015 at the Army-2015 forum as a promising pistol for armed forces and law enforcement agencies. The design was later revised and designated the PL-15.

The PL-14 uses the 9x19mm Parabellum cartridge and a 15-round magazine. The pistol was designed with meticulous attention to ergonomics: the grip is comfortably shaped, the controls are designed for ambidextrous use, and the low barrel line is designed to help quickly return the weapon to the aiming line after firing.

At approximately 220 mm in length and weighing approximately 800 grams, the PL-14 is a fairly large but relatively lightweight service pistol. This design later became the basis for the PL-15, PL-15K, and other variants.

NOTES:

- The low barrel line and ergonomic grip are designed for comfortable and rapid firing.
- The controls are designed for use with either right or left hand.
- The PL-14 became the predecessor of the modern Lebedev pistol family.
