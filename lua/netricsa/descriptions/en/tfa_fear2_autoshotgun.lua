VOLLMER ULTRA92 SEMI-AUTOMATIC SHOTGUN


WEAPON: Vollmer Ultra92 Semi-Automatic Shotgun
AMMO:   12-gauge
ACTION: Semi-automatic

DESCRIPTION:

A modern semi-automatic smoothbore shotgun used by Replica heavy units. Developed by the Vollmer Corporation, it is designed for intense combat engagements at short to medium ranges. It utilizes a gas-operated action and a detachable 12-round box magazine.

While the Ultra92 falls short of the SHO Series-3 shotgun in terms of raw per-shot power, it compensates with a higher rate of fire, a tighter shot pattern, and faster reloading. Unlike conventional pump-action shotguns, the entire magazine is replaced, allowing the user to return to the fight quickly.

NOTES:

- Used by Replica heavy infantry.
- The magazine holds 12 rounds (10 rounds in multiplayer mode).
- Based on a combination of design features from the Heckler & Koch CAWS and the Franchi SPAS-12.
- Despite its name, it does not feature a fully automatic firing mode.
- The weapon is reloaded by swapping out the entire magazine rather than loading individual shells—a convenience any soldier would appreciate.
