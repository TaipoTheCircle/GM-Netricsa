"ASHOT" SHOTGUN PISTOL


WEAPON: "Ashot" Shotgun Pistol
AMMO:    12x70 mm
ROF:     1 Round, Manual Reload

DESCRIPTION:

A homemade shotgun pistol, widely used among the inhabitants of post-nuclear Russia. It is crafted from improvised materials—primarily metal pipes and basic mechanical components. Despite its primitive design, it packs a powerful punch at close range and is particularly effective against mutants.

The "Ashot" is a single-shot weapon featuring a break-action reloading mechanism. It uses standard 12-gauge hunting shells. Due to its simple construction, compact size, and the ready availability of ammunition, it is highly popular among stalkers, bandits, and other denizens of the Metro. It supports various modifications, including additional barrels, a stock, optical sights, and an extended barrel.

NOTES:

- One of the most common types of homemade weaponry in the Metro.
- The base version holds only a single round.
- In *Metro Exodus*, variants with two or four barrels are available.
- An extended barrel improves accuracy (shot grouping) and effective range.
- A special incendiary 12x70 mm round.
