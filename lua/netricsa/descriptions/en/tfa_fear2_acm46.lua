SEEGERT ACM46 PISTOL


WEAPON: Seegert ACM46 Pistol
AMMO:   9x19mm Parabellum
ACTION: Semi-automatic

DESCRIPTION:

A modern semi-automatic pistol developed by the Seegert Corporation for armed units. It serves as the standard-issue sidearm for Armacham soldiers, Delta Force units, and Replica Forces.

The ACM46 features a high-strength polymer frame, a stainless steel slide, and tritium-illuminated sights. It operates on a short-recoil principle with a locked-breech mechanism. The magazine holds 18 rounds. It offers good accuracy and decent stopping power, though its effective firing range remains limited.

NOTES:

- The magazine has an 18-round capacity.
- Equipped with tritium sights for low-light conditions.
- Features a universal mounting system for accessories.
- Resembles the German Heckler & Koch USP in appearance.
- Despite being a secondary weapon, it possesses significant firepower.
