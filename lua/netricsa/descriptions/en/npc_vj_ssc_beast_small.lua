YOUNG ALUDRAN REPTILOID, COMMON


CLASS:      Young Aludran Reptiloid, Common
METABOLISM: Cold-Blooded, Reptile-Like
PERCEPTION: Primitive Race
SIZE:       3,94 ft
ENDURANCE:  Medium
HOSTILITY:  High
WEAPONS:    Magic Homing Missiles
REWARD:     5000 FC
THREAT:     Medium

DESCRIPTION:

A small fourhanded reptile living in the Aludran system in the constellation of Canis Major. This primitive race has agreed to fight for Mental in exchange for the spell-casting powers it gave them.

They cast self-propelled fireballs with primitive homing abilities. 

TIPS:

- Keep them under constant fire and try to shoot down their missiles in air.
