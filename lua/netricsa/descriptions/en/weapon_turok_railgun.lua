ORO L66 PULSE RIFLE


WEAPON: ORO L66 Pulse Rifle
AMMO:   Armor-Piercing Depleted Uranium Bullets
ROF:    ~600 rounds / min
WEIGHT: ~4,5 kg

DESCRIPTION:

A precise automatic pulse rifle manufactured by ORO, firing armor-piercing depleted uranium bullets. The weapon boasts high accuracy, low recoil, and a large 100-round magazine, allowing for sustained fire. Its main drawback is rapid overheating during continuous firing.

A grenade launcher is mounted under the barrel for special pulse grenades. These are not designed to destroy a target, but rather to create a powerful shockwave, knocking enemies off their feet and knocking them out of cover. Grenades can be fired either single-shot or in short bursts of three.

NOTES:

- The magazine holds 100 rounds, with a total capacity of up to 400.
- High accuracy and low recoil.
- Uses armor-piercing depleted uranium ammunition.
- Overheats quickly when fired continuously, so short bursts are recommended.
- Alternate fire launches disorienting grenades.
- Grenades knock enemies off their feet and force them out of cover.
- Effective at medium and long ranges due to its accuracy and the ability to use zoomed scopes.
- Particularly common among the elite soldiers of the Mendel-Gruman Corporation.
