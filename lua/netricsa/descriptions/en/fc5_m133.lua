M133 PUMP-ACTION SHOTGUN


WEAPON: M133 Pump-Action Shotgun
AMMO:   12 Gauge
ROF:    ~60 rounds / min

DESCRIPTION:

A powerful close-quarters weapon, particularly effective against normal opponents and animals.

The M133 uses a manual pump-action mechanism. The magazine typically holds approximately 7 rounds, and can be expanded with an extension. Various M133 variants are available, including shortened versions, and can also be equipped with sights, a suppressor, and an extended magazine.

The M133's appearance is a blend of several real-world designs. It is based on the Russian Baikal MP-133, but certain elements, including the forend, resemble other pump-action shotguns.

NOTES:

- Ideal for close-quarters combat and clearing tight spaces.
- The pump-action mechanism makes shooting slower than semi-automatic shotguns, but the design is quite simple.
- Particularly suitable for hunting dangerous animals.
