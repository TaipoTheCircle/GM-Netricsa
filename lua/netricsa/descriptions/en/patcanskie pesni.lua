"BOY'S SONGS" GUITAR


WEAPON: "Boy's Songs" Guitar
AMMO:   Not required

DESCRIPTION:

An unusual guitar designed to play popular songs. Like the "GIMN USSSR" model, it does not require the user to actually play the strings. Simply wave your hand in the air to activate it, and the instrument will automatically begin performing one of its available tracks.

The built-in music collection features eight songs by various artists, including tracks by the bands Lyapis Trubetskoy, Bi-2, and Lyube, as well as songs by Viktor Tsoi and works by Pavel Plamenev.

NOTES:

- Contains eight musical tracks:
- "Warriors of Light" (Lyapis Trubetskoy)
- "No One Writes to the Colonel" (Bi-2)
- "Let's Do It For..." (Lyube)
- "Blood Type" (Viktor Tsoi)
- "Soldiers Are Not Born" (Pavel Plamenev)
- "The Last Day of 2021" (Pavel Plamenev)
- "For Peace on Earth" (Pavel Plamenev)
- "Veteran Detachments" (Pavel Plamenev)
- A simple wave of the hand is all it takes to start the music.
- No strings or musical skills required.
