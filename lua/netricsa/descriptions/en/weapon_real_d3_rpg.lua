ROCKET LAUNCHER


WEAPON: Rocket Launcher
AMMO:   84 mm rockets
ROF:    ~30 shots/min.

DESCRIPTION:

A missile launcher designed to destroy protected targets and large groups of enemies. Uses rocket-propelled ammunition that explodes when it hits a target and causes significant area damage.

The weapon has a high destructive power, but requires caution when used at close range, since the explosion can hit the shooter himself. The magazine holds 5 missiles.

NOTES:

- Huge area damage.
- Particularly effective against large and well-protected targets.
- The magazine is designed for 5 missiles.
- If ordinary bullets are not enough, then it's time to move on to heavier arguments.
