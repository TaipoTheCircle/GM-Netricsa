MENDEL-GRUMAN GRUNT SOLDIER


CLASS:      Mendel-Gruman Grunt Soldier
METABOLISM: Human, Male
PERCEPTION: Standard Grunt
SIZE:       5,9 ft
ENDURANCE:  Average
HOSTILITY:  High
WEAPONS:    ORO FP9 Light Assault Carbine, Frag Grenades
REWARD:     200 FC
THREAT:     Low

DESCRIPTION:

This Grunt is a standard representative of the corporation's armed forces and forms the backbone of its Grunt units. Externally, he is virtually indistinguishable from other Mendel-Gruman Grunt variants: the same light protective armor, tactical gear, and closed helmet with a dynamic visor.

His primary weapon is the ORO FP9 Light Assault Carbine. This versatile weapon allows the soldier to effectively fire at short and medium ranges without forcing him to constantly close in on the enemy. Unlike a shotgun-wielding soldier, the FP9 Grunt prefers to maintain some distance and gradually suppress his target with sustained fire.

The soldier is also equipped with fragmentation grenades, which he uses against enemies behind cover or against enemy groups. Thanks to the combination of his carbine and grenades, he is capable of performing most standard Grunt tasks without the need for specialized weaponry.

Like other standard Mendel-Gruman soldiers, this soldier is not distinguished by exceptional individual durability. His strength lies primarily in numbers, discipline, and coordination with other units. Typically, several Grunt take up positions around the combat zone, intersecting fire, and gradually forcing the enemy out of cover.

The dynamic visor serves as an additional indicator of the soldier's condition: blue indicates normal alertness, yellow indicates heightened awareness, and red indicates maximum combat readiness.

In combat, the FP9 Grunt is the most versatile version of the standard soldier. He lacks the destructive power of a shotgun and can't withstand the same amount of damage as a heavy unit, but he has virtually no limitations in terms of range.

TIPS:

- Don't underestimate them because of their conventional weapons. Several FP9 Grunt can lay down a dense and sustained barrage.
- Use cover, especially if you're facing a large group.
- Grenades are effective against groups, as Grunt often operate in small squads.
- At close range, try not to let them surround you.
- If shotgunners or heavy units are nearby, consider the more dangerous options first, but be mindful of the FP9 Grunt, who will continue to fire from behind them.
- A red visor means full combat readiness. At this point, the soldier is no longer willing to pretend that what's happening doesn't concern him.
