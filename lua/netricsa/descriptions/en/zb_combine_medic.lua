COMBINE OCMU SOLDIER


CLASS:      Combine OCMU Soldier
METABOLISM: Enhanced Human, Biomechanical Enhancements
PERCEPTION: Combine Medic-Assault Unit
HEIGHT:     5,9 ft
ENDURANCE:  High
HOSTILITY:  Extreme
WEAPONS:    SMG1 (MP7), Grenades
REWARD:     500 FC
THREAT:     High

DESCRIPTION:

These are "Overwatch Crisis Management Unit" soldiers. They are a specialized Combine unit created to respond to particularly dangerous crisis situations where regular Overwatch soldiers are insufficient. Their missions include suppressing large pockets of resistance, clearing contaminated or unstable areas, and assisting other Combine units directly on the front lines.

Unlike standard Overwatch soldiers, OCMU soldiers combine the functions of assault infantry and combat medics. Their equipment is designed for extended deployment to combat zones, and their training allows them to quickly shift roles depending on the situation: engaging the enemy, covering the retreat of allies, or providing medical care to injured soldiers.

OCMU soldiers use a limited selection of weapons. Their primary weapon is the SMG1 (MP7), capable of delivering concentrated automatic fire at short and medium ranges. They make extensive use of grenades to clear rooms, destroy cover, and engage groups of enemies.

Despite their medical specialization, it would be extremely dangerous to dismiss OCMU soldiers as harmless. They are well-trained in close combat and operate in an organized manner, trying to stay in a group. If one soldier comes under fire, the others immediately attempt to suppress the shooter with grenades and automatic fire, while simultaneously covering the wounded soldier.

OCMU soldiers are especially likely to appear in situations where the situation is spiraling out of control. Their arrival usually means that the Combine is no longer simply trying to hold territory, but is moving into full-fledged crisis suppression.

TIPS:

- Don't let the OCMUs gain a foothold indoors: their grenades make them especially dangerous in tight spaces.
- In open areas, the SMG1 is less effective, so use your range.
- Try to quickly disable multiple units so they can't cover each other.
- If the OCMUs are accompanied by other Combine units, eliminate the most dangerous marksmen and heavy support first.
- Don't underestimate them because of their medical specialization: they are still fully-fledged Overwatch combat units.
