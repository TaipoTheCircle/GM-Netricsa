PISTOL


WEAPON: Pistol
AMMO:   9x19mm
ROF:    ~400 rounds / min

DESCRIPTION:

A self-loading pistol designed for close-range engagements. Its compact size and light weight make it convenient for constant carry, and the 12-round magazine allows for multiple shots without reloading.

The pistol boasts good accuracy but deals relatively low damage. It is especially useful against single and less-protected targets.

NOTES:

- Simple, reliable, and without unnecessary bells and whistles.
- Good accuracy and low recoil.
- Compact and comfortable for constant carry.
- The magazine holds 12 rounds.
