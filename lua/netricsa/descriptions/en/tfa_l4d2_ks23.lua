KS-23 SPECIAL CARBINE


WEAPON: KS-23 Special Carbine
AMMO:   23x75mm R
ROF:    ~4–5 rounds / min

DESCRIPTION:

A Soviet large-caliber special-purpose carbine, developed in the early 1980s by the Research Institute for Special Equipment of the USSR Ministry of Internal Affairs (MVD) in collaboration with the Central Scientific Research Institute for Precision Machine Engineering (TsNIITochMash). It was adopted for service in 1985 and intended for use by units of the Ministry of Internal Affairs. It is employed for suppressing mass riots, apprehending offenders, and carrying out specialized police operations. The weapon is notable for its unusually large 23mm caliber and a rifled barrel, which was manufactured using blanks originally intended for aircraft cannons.

The carbine operates via a manual, pump-action mechanism, with the forend linked to the bolt. It utilizes specialized 23x75mm R cartridges. Ammunition is fed from an under-barrel tubular magazine with a capacity of 3 rounds, with an additional round capable of being held in the chamber. It is equipped with a wooden stock, open mechanical sights, and a rifled barrel. A wide range of specialized ammunition, designed for various purposes, has been developed for this carbine.

NOTES:

- Developed for the needs of the USSR Ministry of Internal Affairs (MVD).
- Adopted for service in 1985.
- Features a 23mm caliber rifled barrel.
- The magazine holds 3 rounds, with an additional round in the chamber.
- Variants include the KS-23M "Drozd" and the KS-23K.
