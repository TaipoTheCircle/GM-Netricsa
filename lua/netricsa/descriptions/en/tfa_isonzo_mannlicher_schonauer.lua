MANNLICHER-SCHÖNAUER M1903 BOLT-ACTION RIFLE


WEAPON: Mannlicher-Schönauer M1903 Bolt-Action Rifle
AMMO:   6.5x54mm Mannlicher-Schönauer
ROF:    Manual (bolt-action), 5-round capacity

DESCRIPTION:

An Austro-Hungarian bolt-action rifle, designed by Ferdinand Mannlicher and Otto Schönauer in 1900 and adopted by the Greek Army in 1903. Manufactured by Steyr, the rifle was noted for its high build quality, reliability, and a magazine design that was unconventional for its time. It was intended for infantry use, while a shortened carbine variant was employed by cavalry and other units.

The rifle utilizes a manually operated, rotating bolt action. Its most distinctive feature is the five-round rotary magazine—a Schönauer design—housed within the stock. Cartridges are placed into a rotating mechanism that ensures reliable feeding. The rifle is loaded from the top, either via a stripper clip or by inserting individual rounds. It is equipped with open iron sights, featuring an adjustable rear sight leaf.

NOTES:

- Adopted by the Greek Army in 1903.
- Chambered for the 6.5x54mm Mannlicher-Schönauer cartridge.
- The rotary magazine holds 5 rounds.
- Weighs approximately 3.77 kg, with an overall length of about 1226 mm. - The rear sight is graduated up to 2,000 meters.
- A shortened cavalry carbine version also existed.
- The Schönauer rotary magazine ensured smooth and reliable cartridge feeding, becoming one of the key features of the entire design.
