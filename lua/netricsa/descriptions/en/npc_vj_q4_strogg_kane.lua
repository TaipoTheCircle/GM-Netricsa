STROGG MATTHEW KANE FROM THE STROGGOS


CLASS:      Strogg Matthew Kane
METABOLISM: Cybernetic Human-Hybrid
PERCEPTION: Strogg Tactical Infantry
SIZE:       5,9 ft
ENDURANCE:  High (Armor + Cybernetic Enhancements)
HOSTILITY:  Extreme
WEAPONS:    Shotgun, Machine Gun, Hyper Blaster, Railgun
REWARD:     5200 FC
THREAT:     High

DESCRIPTION:

This...Specimen... is quite unusual. A unique case among the Strogg. He was once a human and a corporal in the Space Marine Corps, serving in the elite unit "Rhino Squad." After being captured by the Strogg, Kane underwent a stroggification procedure, which resulted in a significant portion of his body being replaced with cybernetic components.

However, Kane did not become a normal Strogg. His transformation was interrupted before the most crucial stage of the procedure was completed, preventing the neurocyte from fully taking control of his consciousness. As a result, Kane retained his will and continued to fight against those who had transformed him into a cyborg.

After partial stroggification, his body became significantly stronger than a human's. Cybernetic legs increased his speed and physical endurance, and integrated systems allow him to interface with Strogg technology, including their terminals, teleporters, and medical stations. Furthermore, Kane is able to safely pass through some Strogg defensive laser systems that would be deadly to a normal human.

In terms of combat capabilities, Kane is most similar to Tactical Strogg. This is especially noteworthy, as these units were created from the most highly trained individuals and designed to conduct complex combat operations. They use cover, flanking maneuvers, and cooperate with each other, rather than simply running toward the enemy.

Kane, however, retains the skills of a seasoned soldier. He is capable of handling virtually all weapons available to him, quickly switching weapons depending on the situation, and using the environment against the enemy.

But Kane's main distinction isn't his weaponry; it's his understanding of how humans think. And at the same time, he knows how the Strogg operate.

Simply put, to the Strogg, he remains a malfunctioning element that somehow retains the ability to make decisions independently.

TIPS:

- His Strogg designation is 8462-9B.
- Kane is an extremely valuable fighter for the human unit.
- Don't mistake him for a regular Strogg. Despite his appearance, Kane fights on the side of the humans.
- If, for any reason, Kane finds himself an enemy, the situation becomes significantly more difficult than when facing a regular Strogg.
- Kane combines human tactics and Strogg capabilities.
