HALF-QUAKE 2, DANCING PLATFORMS


Sam... SAM! Stay put, don't move!

I'm trying to process what I'm seeing... but my processor seems to have decided to take a vacation. The floor isn't there. At all. But it's there. It's just... invisible. Or it's not there. Or it's there, but we can't see it. Damn, even I'm confused!

...

Now look up. Platforms in the air. Rectangles. Triangles. Hexagons. And even that stupid ">)" symbol, floating around like it doesn't care about physics. These sadists clearly hired an architect with a sick imagination. Or a glitched programmer. Or both.

But worse, Sam. Ahead and behind us are two square buttons. Also with that smiling face ">)". You need to press both. Then the path ahead will open.

Simple? Of course not! Because the Gnaars and Harpies are already flying towards us. And they don't want to play "push the button" with us. They want to play "bite the head off" with you.

Hold on, Sam. You'll have to jump on these crazy platforms, dodge flying creatures, and press buttons. And most importantly, don't look down. There's nothing down there. And if there is, it doesn't want you to see it.

Go ahead! And don't let those platforms fool you. They're just... dancing. Yes, dancing. And they're inviting you to their crazy ball!
