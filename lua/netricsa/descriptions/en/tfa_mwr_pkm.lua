KALASHNIKOV GENERAL-PURPOSE MACHINE GUN, MODERNIZED (PKM)


WEAPON: Kalashnikov General-Purpose Machine Gun, Modernized (PKM)
AMMO:   7.62x54mm R
ROF:    ~650 rounds / min

DESCRIPTION:

A Soviet general-purpose machine gun developed by Mikhail Timofeyevich Kalashnikov and his design team, based on the original PK model. It was adopted for service in 1969. The weapon is designed to engage enemy personnel and weapon systems, as well as to provide fire support for infantry units. Compared to the original model, it features a lighter design, a modified flash suppressor, and several improvements that enhance ease of operation.

It operates on a gas-actuated principle with a rotating bolt locking mechanism. It fires the 7.62x54mm R rifle cartridge. Ammunition is fed via a metal belt, typically holding 100 or 200 rounds (250-round belts are also available). The weapon is equipped with a quick-change barrel, an integral folding bipod, and iron sights. A variant designated as the PKMS was developed for use with a lightweight tripod mount designed by Stepanov.

NOTES:

- Effective against personnel and light cover at medium to long ranges.
- A "night" variant, the PKMN, exists; it is adapted for the mounting of optical and night-vision sights.
- Adopted for service in 1969.
- Weighs approximately 7.5 kg (16.5 lbs) without ammunition.
- The combat rate of fire reaches 250 rounds per minute.
