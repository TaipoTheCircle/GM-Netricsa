SHOCKER


WEAPON: Shocker
AMMO:   Electrical
ROF:    600 strikes / min
WEIGHT: ~1,5 kg

DESCRIPTION:

A compact melee weapon designed to deliver a sustained electrical discharge. When activated, the device continuously shocks the target with electricity without requiring ammunition. Its attack range is approximately 2.2 meters, making it suitable for use against opponents who are dangerous at close range.

The Shocker is especially effective against armored opponents. Compared to a standard machete, it has greater attack speed and range, allowing it to deliver frequent electrical strikes at close range.

NOTES:

- Has no limited ammunition, can attack continuously.
- Inflicts electrical damage upon contact with the target.
- Effective against armored opponents.
- Attack range of approximately 2,2 m.
- Designed exclusively for close-range combat.
