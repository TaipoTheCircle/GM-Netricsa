HALF-QUAKE 2, LETTER TRAP


Well, well... Look at this, Sam! The entire floor is covered in letters-as if the alphabet had puked in this hallway. There's a panel in the center. I'm guessing it'll open the way. But here's the problem: one wrong letter and you'll turn into a meat pie. I've already counted ten ways you can die. Ten! That's a new record, even for you.

...

But there's a word. The word sadists love more than anything else. You know, the one-their "raison d'être", their inspiration, their favorite toy...

S-A-D-I-S-M.

Seven letters. Seven steps to freedom. Or to death-if I'm wrong, but I'm rarely wrong, Sam.

I also noticed someone dropped a diary here. Or maybe he left it there on purpose-those sadists love that kind of trick.

Come on, hero, show those sadists you can crack their alphabet!
