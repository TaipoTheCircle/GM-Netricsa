ARABIAN BEHEADED KAMIKAZE


CLASS:      Beheaded Kamikaze, Arabian
METABOLISM: Cyber-Zombie
PERCEPTION: Insentient, LCU Controlled
SIZE:       6 ft
ENDURANCE:  Very Low
HOSTILITY:  Extreme
WEAPONS:    Hand Grenades
REWARD:     2500 FC
THREAT:     High

DESCRIPTION:

An executed Sirian soldier, raised from the dead by Mental and remote controlled by Life Control Unit (LCU).

The head of the Kamikaze has been ruined, so he is employed for suicidal attacks. Carries two bombs in his hands and activates them when close enough to the target. 


For some unknown reason, Mental decided to create a themed unit of headless kamikazes, outfitting them in brown trousers, black gloves, and a traditional Arab bandana tied around the neck.

TIPS:

- Explodes when killed.
