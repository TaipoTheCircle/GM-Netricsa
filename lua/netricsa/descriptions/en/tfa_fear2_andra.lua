ANDRA FD-99 SUBMACHINE GUN


WEAPON: Andra FD-99 Submachine Gun
AMMO:   5.7x28mm
ROF:    ~900-1000 rounds / min

DESCRIPTION:

A lightweight submachine gun developed by the Andra company for the armed units of the Armacham Technology Corporation. Designed primarily for close-quarters combat, it features a compact build, a folding stock, low recoil, and a high rate of fire. It is fed by a high-capacity 50-round magazine.

The FD-99 fires from a closed bolt and is equipped with a low-magnification red-dot (collimator) sight. It offers a choice between fully automatic fire and three-round bursts. Although the individual rounds have relatively low stopping power, the weapon compensates with a high volume of fire, excellent handling, and a large total ammunition capacity.

NOTES:

- Uses the 5.7x28mm cartridge—an unconventional choice for a submachine gun.
- The magazine holds 50 rounds, with a total ammunition capacity of up to 500 rounds.
- The magazine design is inspired by the FN P90, while the exterior of the receiver resembles the FN F2000.
- Equipped with a red-dot sight and a side-mounted "LIGHTBRINGER" tactical light.
- Its high rate of fire and high-capacity magazine allow the user to literally shower an opponent in lead.
