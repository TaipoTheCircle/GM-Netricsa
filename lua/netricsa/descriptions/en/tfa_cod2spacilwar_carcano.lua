CARCANO M1891 RIFLE


WEAPON: Carcano M1891 Rifle
AMMO:   6.5x52mm Carcano
ROF:    ~10-15 rounds / min
WEIGHT: ~3,78 kg

DESCRIPTION:

The Carcano M1891 is an Italian repeating rifle adopted in 1891. It became the standard rifle of the Italian army and served during World War I and World War II. Approximately 3 million were produced.

The rifle uses a bolt-action mechanism and the 6.5x52mm Carcano cartridge. Feed is provided by an internal 6-round magazine, which is loaded from a special box. Once the ammunition is expended, the empty box automatically ejects from the magazine.

The Carcano had many variants, including shortened carbines for cavalry, artillery, and other special forces. In 1938, a new version chambered for the 7.35x51mm cartridge was introduced, but due to time constraints and difficulties with the production transition, Italy reverted to the 6.5x52mm cartridge.

NOTES:

- Well-suited for medium and long ranges thanks to its rifle cartridge.
- Six rounds are loaded in a single box, which is quite convenient for a bolt-action rifle.
- The Carcano remained the standard Italian rifle for over fifty years, surviving two world wars.
- The most famous Carcano in history belonged to Lee Harvey Oswald and was linked to the assassination of John F. Kennedy.
