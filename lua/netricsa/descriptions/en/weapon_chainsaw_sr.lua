DESCRIPTION:

A gasoline-powered chainsaw developed by the German company Andreas Stihl Maschinenfabrik. Produced from 1967 to 1986, it was designed for felling trees, cutting timber, and performing heavy-duty logging tasks. It is equipped with a single-cylinder, two-stroke engine with a displacement of 61 cc and an anti-vibration handle suspension system, which enhances ease of operation.

The engine produces approximately 5.5 hp and drives the cutting chain via a centrifugal clutch. The chain is lubricated automatically. The saw features a mechanical chain brake, an automatic starter system, and a guide bar ranging from 33 to 63 cm in length. It runs on a fuel mixture of gasoline and specialized two-stroke engine oil.

