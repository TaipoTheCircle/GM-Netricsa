WALTHER WA 2000 SNIPER RIFLE


WEAPON: Walther WA 2000 Sniper Rifle
AMMO:   7.62x51mm NATO (.308 Winchester) / .300 Winchester Magnum / 7.5x55mm Swiss
ROF:    ~30 rounds/min

DESCRIPTION:

A German semi-automatic sniper rifle developed by Carl Walther Waffenfabrik in the early 1980s. It was designed for police units and special services that required a compact, high-precision weapon for urban operations. Its bullpup configuration allows for a relatively short overall length while retaining a full-length 650mm barrel.

The WA 2000 utilizes a gas-operated action with a rotating bolt featuring seven locking lugs. It boasts a modular design, allowing for the barrel and bolt to be swapped to accommodate different types of ammunition. It is equipped with an adjustable wooden stock, a Schmidt & Bender optical sight, and a unique, repositionable bipod. The standard magazine holds 6 rounds, while the version chambered for .300 Winchester Magnum uses a 5-round magazine.

NOTES:

- Only 176 units were produced in total.
- It lacks iron sights, as it is designed exclusively for use with an optical sight.
- Due to the placement of the ejection port, it cannot be fired from the left shoulder.
- Production ceased in 1988 due to high manufacturing costs.
- One of those rifles that looks more expensive than an entire arms depot.
