SWARM MENDER


CLASS:      Swarm Mender
METABOLISM: Alien Biological Creature
PERCEPTION: Biological Medic, Swarm Support
SIZE:       5,2 ft
ENDURANCE:  Medium
HOSTILITY:  High
WEAPONS:    Biological Regenerator, Claws, Acidic Secretion
REWARD:     350 FC
THREAT:     Medium

DESCRIPTION:

Swarm Menders are a specialized variety of Swarm Beetles that act as living medics within alien colonies. They rarely engage in combat, preferring to remain behind the main body of the swarm and support wounded individuals while they continue to fight.

Their bodies produce a special regenerative secretion that accelerates tissue repair in aliens. The Swarm Keeper attaches itself to a damaged individual and covers its wounds with a thin layer of biological material, after which the damaged tissue begins to rapidly regenerate.

However, this process has an unfortunate quirk: the regenerative material doesn't always simply repair the damage. It gradually replaces the damaged tissue with tissue from the Swarm itself. Therefore, individuals repeatedly treated by Swarm Keepers become increasingly covered in a foreign exoskeleton over time.

Swarm Keepers are believed to be one of the reasons why some infected colonies begin to exhibit unusual forms of hybridization. This isn't a problem for the swarm itself. The damaged organism becomes part of the overall biological system and continues to perform its functions.

Swarm Keepers exhibit communal behavior and almost never attempt to save themselves at the expense of other creatures. If a wounded individual is nearby, they will continue healing even under fire until the threat becomes immediate.

When threatened, the Mender can defend itself with its claws and secrete a small amount of corrosive acid, then flee. However, its main strength lies not in its attack, but in its ability to keep a swarm combat-ready for significantly longer than expected.

Because of this, destroying the Mender often becomes a priority for fighters: while it's alive, already damaged aliens can rise again and return to the fight.

TIPS:

- Destroy the Mender first if it's near a group of wounded aliens.
- Don't waste ammunition on its thick exoskeleton unnecessarily: it's not designed for direct combat.
- If the Mender begins healing a powerful enemy, it's best to interrupt the healing first.
- In enclosed spaces, groups in which Menders are positioned behind several rows of combat aliens are especially dangerous.
- After the Mender is destroyed, already damaged aliens become significantly less resilient.
