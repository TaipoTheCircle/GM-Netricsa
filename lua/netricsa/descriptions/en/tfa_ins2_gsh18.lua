GSh-18 SEMI-AUTOMATIC PISTOL


WEAPON: GSh-18 Semi-Automatic Pistol
AMMO:   9x19mm Parabellum, 7N21, 7N31
ROF:    ~15–20 rounds/min

DESCRIPTION:

A Russian semi-automatic pistol developed in the late 1990s at the Tula-based KBP Instrument Design Bureau by designers Vasily Gryazev and Arkady Shipunov. It is intended for use as a personal sidearm for military personnel and members of law enforcement or security agencies. The name is derived from the first letters of the designers' surnames, while the number 18 denotes the magazine capacity. It is characterized by its low weight, polymer frame, and high magazine capacity.

The pistol operates on a short-recoil principle with a rotating barrel locking mechanism. It chambers 9x19mm ammunition, including specialized 7N21 and 7N31 armor-piercing rounds. It is fed by a double-stack box magazine with an 18-round capacity. The weapon features a striker-fired mechanism and an automatic trigger safety. It is equipped with open-type iron sights.

NOTES:

- Effective against individual targets at short range, including those wearing body armor (when using appropriate ammunition).
- The name is derived from the surnames Gryazev and Shipunov, as well as the magazine capacity.
- Adopted for service in the early 2000s.
- The magazine holds 18 rounds.
- It is characterized by its low weight-approximately 500 g, excluding the magazine.
- The specialized 7N31 cartridge offers enhanced penetration capability.
