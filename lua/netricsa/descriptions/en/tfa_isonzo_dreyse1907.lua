DREYSE M1907 SEMI-AUTOMATIC PISTOL


WEAPON: Dreyse M1907 Semi-Automatic Pistol
AMMO:   7.65x17mm Browning (.32 ACP)
ROF:    Semi-automatic, 7-round capacity

DESCRIPTION:

A German semi-automatic pistol designed by Louis Schmeisser between 1905 and 1906. It was manufactured by the company Rheinische Metallwaaren-und Maschinenfabrik in Sömmerda from 1907 to 1915. It was named after the gunsmith Johann Nikolaus von Dreyse, although he had no personal involvement in the pistol's development. This compact firearm was intended for self-defense and for use as a sidearm by military personnel and police officers.

The mechanism operates on a blowback principle and utilizes a striker-fired system. It is fed by a detachable, single-stack magazine with a capacity of seven 7.65mm Browning cartridges. A unique design feature is the hinged attachment of the receiver (upper assembly) to the frame: for cleaning and disassembly, the upper portion of the pistol can be tilted forward. The rear-protruding striker also serves as a cocking indicator.

NOTES:

- Designed by Louis Schmeisser, father of the renowned firearms designer Hugo Schmeisser.
- The weight of the pistol (unloaded) is approximately 710 g.
- The sights are calibrated for engagement at distances of up to approximately 25 meters.
