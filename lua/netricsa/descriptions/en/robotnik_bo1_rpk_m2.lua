KALASHNIKOV LIGHT MACHINE GUN (RPK)


WEAPON: Kalashnikov Light Machine Gun (RPK)
AMMO:   7.62x39 mm
ROF:    ~600 rounds/min

DESCRIPTION:

A Soviet light machine gun developed by Mikhail Kalashnikov, based on the AKM assault rifle and adopted for service in 1961. It was designed to increase the firepower of an infantry squad. It features a longer, heavier barrel, a reinforced receiver, a bipod, and a wooden stock.

The RPK utilizes a gas-operated action with a rotating bolt and is capable of both semi-automatic and fully automatic fire. It is fed by either 40-round box magazines or 75-round drum magazines. Due to its high degree of parts commonality with other Kalashnikov-pattern firearms, the RPK is easy to maintain and highly reliable in the field.

NOTES:

- Developed based on the AKM assault rifle.
- The longer barrel allows for more effective engagement at greater distances.
- The 75-round drum magazine significantly increases the ammunition capacity.
- The RPK has seen numerous modifications, including versions chambered for the 5.45x39 mm cartridge.
- If a standard Kalashnikov isn't enough, simply add a bipod and some extra ammunition.
