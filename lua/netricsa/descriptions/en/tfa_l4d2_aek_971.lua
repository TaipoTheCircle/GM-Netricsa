AEK-971 ASSAULT RIFLE


WEAPON: AEK-971 Assault Rifle
AMMO:   5.45x39 mm
ROF:    ~900 rounds / min

DESCRIPTION:

A Soviet assault rifle developed in 1978 at the Kovrov Mechanical Plant under the direction of designer Stanislav Koksharov. It was created for the "Abakan" trials as a potential replacement for the Kalashnikov family of rifles. It features a traditional layout and utilizes a balanced automatic action designed to reduce recoil and improve firing accuracy.

The rifle operates on a gas-piston principle with a rotating bolt. Its primary design feature is an additional balancer that moves in the opposite direction to the bolt group. It is fed by standard 30-round magazines and offers three firing modes: semi-automatic, fully automatic, and a three-round burst.

NOTES:

- Designed by Stanislav Koksharov.
- Participated in the Soviet "Abakan" trials, where it lost to the AN-94 assault rifle.
- The balanced automatic action reduces muzzle climb during firing.
- Accuracy during burst fire is 1.5 to 2 times better than that of the AK-74M.
- Variants include the AEK-972 (chambered for 5.56x45mm NATO) and the AEK-973 (chambered for 7.62x39mm).
