RGD-5 HAND FRAGMENTATION GRENADE


WEAPON: RGD-5 Hand Fragmentation Grenade
AMMO:   One Grenade
ROF:    One Throw Per Minute

DESCRIPTION:

A Soviet offensive-type hand fragmentation grenade, developed and adopted for service in 1954. It is designed to neutralize enemy personnel through the use of casing fragments and a blast wave. It features a compact, oval-shaped body made of thin steel, consisting of two main parts. Compared to the earlier RG-42, it is lighter and has a more streamlined shape.

It consists of a metal casing, an explosive charge, and a time-delay fuze. A fully assembled grenade weighs approximately 310 grams. TNT is used as the explosive filler. Over the years, various fuzes—specifically the UZRG, UZRGM, and UZRGM-2—have been used. Due to its low weight and compact dimensions, it became widely deployed within the Soviet Army and the armed forces of several other nations.

NOTES:

- Differs from the F-1 grenade by having a lighter casing and lower overall weight.
- Was used by the Soviet Army and continues to be encountered in armed conflicts.
- Adopted for service in 1954.
- Replaced the earlier RG-42 grenade.
- Classified as an offensive-type grenade.
