SPECTRE M4 SUBMACHINE GUN


WEAPON: Spectre M4 Submachine Gun
AMMO:   9x19mm Parabellum
ROF:    ~850 rounds/min

DESCRIPTION:

An Italian submachine gun developed by Roberto Teppa and Claudio Gritti in 1980. It was manufactured by the company SITES starting in 1984. Designed for close-quarters combat, the weapon features a compact size, a folding stock, and a unique trigger mechanism design.

The Spectre M4 utilizes a blowback-operated action and fires from a closed bolt. One of its key features is the use of four-column (quad-stack) magazines with a capacity of 30 or 50 rounds. It also includes a folding forward grip to assist in handling the weapon.

NOTES:

- The 50-round magazine is quite unusual for a submachine gun.
- The stock folds upward, reducing the overall length of the weapon to 350 mm.
- The trigger mechanism allows for the weapon to be carried safely with a round in the chamber.
- Production continued until 2001, although the Italian SITES factory had closed earlier.
