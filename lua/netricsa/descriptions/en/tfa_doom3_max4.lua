PLASMA GUN


WEAPON: Plasma Gun
AMMO:   Plasma Ammo
CC:     ~600 rounds / min

DESCRIPTION:

An energy weapon that uses accelerated plasma bolts to destroy targets. Its high rate of fire and significant damage make it particularly effective at close and medium ranges.

The weapon can fire a continuous stream of plasma, quickly dispatching enemies. Its main drawback is the rapid consumption of ammunition during sustained fire.

NOTES:

- High rate of fire and good damage.
- Energy bolts are effective against fast-moving targets.
- Ammo is consumed relatively quickly during continuous fire.
