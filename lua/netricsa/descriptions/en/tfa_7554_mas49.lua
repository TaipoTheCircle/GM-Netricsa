MAS-49 SEMI-AUTOMATIC RIFLE


WEAPON: MAS-49 Semi-Automatic Rifle
AMMO:   7.5x54mm French
ROF:    Semi-automatic, 10-round capacity

DESCRIPTION:

A French semi-automatic rifle developed and manufactured by the state-owned arms enterprise Manufacture d'armes de Saint-Étienne (MAS). It was based on earlier experimental designs by French gunsmiths and adopted for service in 1949. Intended to replace obsolete bolt-action rifles, it became the primary individual weapon of the French Army in the post-war period. It features a wooden stock, a distinctive gas tube positioned above the barrel, and a simple, reliable design.

The action operates via a direct gas impingement system, where propellant gases are directed straight to the bolt carrier without the use of a separate gas piston. The breech is locked by tilting the bolt. It fires the 7.5x54mm French rifle cartridge and uses a detachable 10-round box magazine. It can also be loaded using 5-round stripper clips, for which guides are provided on the bolt assembly. A mounting rail for an APX optical sight is located on the left side of the receiver.

NOTES:

- Adopted by the French Army in 1949.
- Weighs approximately 4.7 kg with an overall length of 1100 mm.
- Muzzle velocity reaches approximately 820 m/s.
- Effective firing range is about 400 meters; with an optical sight, this can extend to 800 meters.
- There is a shortened variant, the MAS-49/56, which features more compact dimensions and the capability to mount a bayonet.
- The direct gas impingement system later gained widespread recognition through its use in the American AR-15 family of rifles.
