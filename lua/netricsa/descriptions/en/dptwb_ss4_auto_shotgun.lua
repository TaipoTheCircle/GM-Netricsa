FOSTECH ORIGIN 12 AUTOMATIC SHOTGUN


WEAPON: Fostech Origin 12 Automatic Shotgun
AMMO:   12 Gauge Shotgun
ROF:    Automatic, ~120 rounds / min
WEIGHT: ~5 kg

DESCRIPTION:

A powerful close-combat weapon designed to quickly dispatch opponents with a dense stream of pellets. Unlike pump-action shotguns, the weapon does not require manual cocking after each shot, allowing for continuous fire at a high rate.

Each shot releases a large amount of pellets, creating a wide area of effect. This makes the weapon particularly effective against groups of opponents and large targets at close range. At longer ranges, the pellets disperse quickly, significantly reducing their effectiveness.

NOTES:

- High power per shot.
- Fully automatic fire.
- Very effective at close range.
- Well suited for fighting multiple opponents.
- At medium range, effectiveness gradually decreases due to pellet dispersion.
- High rate of fire results in rapid ammunition consumption.
- No manual cocking required between shots.
