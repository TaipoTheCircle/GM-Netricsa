HOMEMADE MUZZLE-LOADING PISTOL "SAMOPAL"


WEAPON: Homemade Muzzle-loading Pistol "Samopal"
AMMO:   Homemade Gunpowder Charge
ROF:    1 Shot, Manual Reloading

DESCRIPTION:

A primitive, improvised firearm constructed from readily available materials. It is a single-shot pistol featuring a metal barrel attached to a wooden stock. It lacks conventional trigger or firing mechanisms and is characterized by an extremely simple design.

An external source of fire is required to ignite the charge. The weapon lacks reliable safety mechanisms and poses a serious danger even to its own user. Despite its crude, makeshift construction, it is capable of firing a live round and inflicting severe injuries.

NOTES:

- Fabricated from a copper tube, a piece of wood, and aluminum wire.
- Created for the production of the film "Brother 2" ("Brat 2").
- Sergei Astakhov and Sergei Bodrov were involved in its creation.
- An extremely unreliable design that can pose a lethal threat.
