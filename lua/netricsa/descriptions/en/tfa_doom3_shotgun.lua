SHOTGUN


WEAPON: Shotgun
AMMO:   12 Gauge
ROF:    ~60 rounds / min

DESCRIPTION:

A pump-action shotgun designed for close-range engagements. It uses 12 gauge shells and can inflict significant damage thanks to the large amount of pellets fired in a single shot.

The gun has an 8-round magazine and requires manual pumping of the forend after each shot. At close range, the shotgun has high stopping power, but its effectiveness quickly diminishes with distance.

NOTES:

- Very powerful at close range.
- Pump-action reloading allows for quick preparation of the next shot.
- The farther the target, the more spread the pellets become.
- If the enemy is too close, they have chosen the wrong distance.
