COMBINE GRAVITY MANIPULATOR


WEAPON: Combine Gravity Manipulator
AMMO:   None Required
ROF:    Alteration of Gravitational Direction

DESCRIPTION:

A specialized Combine device, based on the standard-issue stun baton used by Overwatch and Civil Protection. Unlike the original, which is designed for subduing and neutralizing offenders, this modified version allows the wielder to alter the direction of the gravity acting upon them. The device is intended for traversing vertical surfaces and ceilings, granting access to areas otherwise unreachable by standard infantry units.

To activate it, the user must swing the manipulator toward a chosen surface. Upon contact, the direction of the user's gravity shifts, enabling them to move along walls and ceilings. The device does not need to be held constantly once activated, leaving the wielder's hands free to use firearms or other equipment. However, improper use can lead to a loss of control over one's movement—potentially sending an unwary user flying into the stratosphere.

NOTES:

- Based on the standard Combine stun baton.
- Enables movement along walls and ceilings.
- Does not require continuous handling to maintain the altered gravitational state.
- Particularly useful for bypassing obstacles and launching attacks from unexpected angles.
- Misuse may result in an exceptionally long, involuntary flight.
