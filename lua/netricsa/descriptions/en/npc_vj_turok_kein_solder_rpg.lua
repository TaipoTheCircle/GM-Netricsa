MENDEL-GRUMAN RPG SOLDIER


CLASS:      Mendel-Gruman RPG Soldier
METABOLISM: Human, Male
PERCEPTION: Specialized Anti-Tank Infantry
SIZE:       ~5,9 ft
ENDURANCE:  Average
HOSTILITY:  Extreme
WEAPONS:    ORO "Red Fist" RPG, ORO "Enforcer" Shotgun, Frag Grenades
REWARD:     400 FC
THREAT:     High

DESCRIPTION:

The MG RPG is a specialized unit of the Mendel-Gruman Corporation, designed to employ heavy missile weapons. Externally, it retains the general aesthetics of the corporation's light infantry, but differs from regular soldiers in its metallic gray-silver armor, modified helmet design, and shoulder pads.

This unit's primary weapon is the ORO "Red Fist" RPG. The rocket launcher allows it to engage targets at a distance and inflict serious damage on groups of infantry, vehicles, and other large targets. It is precisely the presence of the rocket launcher that makes the MG RPG a much more dangerous opponent than the standard Infantryman.

However, there is one rather unusual characteristic of this unit: MG RPGs do not necessarily carry RPGs. Most carry ORO "Enforcer" shotguns.

Therefore, the name "RPG" more accurately denotes the unit type than the guaranteed weapon of a specific soldier. Rarely, some units are actually armed with the Red Fist RPG. Moreover, one notable soldier with an RPG is technically considered a regular Infantryman, not a full-fledged MG RPG, which is one of the peculiarities of the final weapons distribution.

MG RPGs usually operate alongside other Mendel-Gruman units. He can take up a vantage point and fire at the enemy from afar while regular infantry keep his attention. He's especially dangerous in a mixed group, as he forces players to simultaneously monitor both the shooters and a possible missile strike.

When using the Enforcer, his behavior becomes more aggressive: he tries to get close to the enemy and utilize the shotgun's high effectiveness at close range. Thus, the same unit type can pose two completely different threats depending on the weapon issued.

TIPS:

- See a flare gun? Consider your day just worse.
- Don't stand in a group near allies: a hit from the Red Fist ORO RPG can hit several soldiers at once.
- Check the weapon in your hands, not just its appearance. A MG RPG may well be armed with an Enforcer instead of an RPG.
- If he's armed with a shotgun, keep your distance and don't let him get close.
- If he's armed with a Red Fist RPG, use cover and try to take him out first.
- Like other light MG units, he's not known for exceptional survivability, so concentrated fire quickly solves the problem.
