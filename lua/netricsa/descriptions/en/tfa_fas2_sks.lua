SIMONOV SELF-LOADING CARBINE (SKS)


WEAPON: Simonov Self-Loading Carbine (SKS)
AMMO:   7.62x39mm
ROF:    ~35-40 rounds/min

DESCRIPTION:

A Soviet self-loading carbine designed by firearms engineer Sergei Gavrilovich Simonov. It was adopted by the Soviet Army in 1949. Intended for engaging enemy personnel at short to medium ranges, it became one of the first mass-produced Soviet weapons chambered for the 7.62x39mm intermediate cartridge. It is characterized by its relatively low weight, wooden stock, and folding bayonet.

The weapon operates on a gas-piston principle, with the breech locked by the tilting of the bolt. It uses the 7.62x39mm intermediate cartridge. Ammunition is fed from an integral 10-round box magazine, which is loaded using a stripper clip. It features iron sights, a gas-operated reloading system, and a folding bayonet. Unlike assault rifles, it is capable of semi-automatic fire only, with the action cycling automatically after each shot.

NOTES:

- Effective against individual and group targets at short to medium ranges.
- Adopted for service in 1949.
- Magazine capacity: 10 rounds.
- Weight: approximately 3.9 kg with a loaded magazine.
- Equipped with a folding spike-style or blade-style bayonet.
- Designed by Sergei Gavrilovich Simonov.
