THE FUTURE SITE OF TEOTIHUACAN, GIANT PIT - CONSTRUCTION HAS BEGUN


Well, Sam, construction is in full swing! The Maya clearly didn't waste any time. In place of the giant pit, there's a fence now. An ordinary stone fence. But one side of it is transparent.

And do you know what's behind that transparent fence? Trees. Real trees. Right in the middle of the pit—where just yesterday there was nothing but bare earth and walls of unknown origin. The Maya certainly know how to surprise you. Or maybe it isn't the Maya. Or maybe they aren't even trees at all.

I'm not sure of anything anymore, Sam!
