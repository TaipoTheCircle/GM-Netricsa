M1A0 CAT-GUN


WEAPON: M1A0 Cat-Gun
AMMO:   9x19mm rounds
ROF:    ~750 rounds / min

DESCRIPTION:

An unusual weapon that takes the form of an orange cat wearing a red collar. Despite its adorable appearance, the M1A0 is one of the most formidable pieces of weaponry around. It fires standard bullets directly from the animal’s mouth.

To wield the Cat-Gun, you must hold it by its front and hind paws. Reloading is accomplished by petting the cat—a simple yet highly unconventional maintenance system that keeps the weapon combat-ready.

NOTES:

- Don’t be fooled by its charming appearance!
- Fires bullets from its own mouth.
- Simply pet the cat to reload.
- Held by the front and hind paws.
- Quite possibly the fluffiest weapon in the entire arsenal.
