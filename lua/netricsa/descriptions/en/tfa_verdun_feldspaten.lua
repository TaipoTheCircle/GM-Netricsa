FELDSPATEN 1887 (M87) ENTRENCHING TOOL


WEAPON: Feldspaten 1887 (M87) Entrenching Tool
AMMO:   N/A
ROF:    Hand-to-hand/Melee Weapon

DESCRIPTION:

A German infantry entrenching tool, adopted by the Imperial German Army in 1887. It was an improved version of the M1874 field spade. The primary change was a new carrying system: per an order dated March 3, 1887, the tool was to be attached to the waist belt, positioned behind the bayonet scabbard. It was used by infantry for constructing fortifications, digging trenches, and preparing individual firing positions.

The tool features a slightly curved steel blade and a short wooden handle. Its total length is approximately 54 cm, with a blade width of about 15-16 cm. It was carried in a specialized sheath attached to the soldier's gear. During the First World War, the edges were frequently sharpened, transforming the standard tool into an effective close-quarters combat weapon.

NOTES:

- Effective in close-quarters combat, particularly within the confines of trenches and dugouts.
- Used for digging individual firing pits and field fortifications.
- Unlike the M1898 model, it lacks a reinforced "stepping" edge (a reinforced top edge for applying foot pressure).
- Total length is approximately 54 cm.
- Utilized by the German Army during the First World War.
