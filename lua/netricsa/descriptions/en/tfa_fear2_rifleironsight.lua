PATTEN 470 ASSAULT RIFLE ELITE


WEAPON: Patten 470 Assault Rifle Elite
AMMO:   5.56x45mm NATO
ROF:    600-750 rounds / min

DESCRIPTION:

A modern assault rifle developed for the armed units of the Armacham Technology Corporation. It features a gas-operated action with a gas piston, offering high reliability and good accuracy. Unlike the standard Patten 470, the Elite version does not come equipped with an ACOG optical sight, giving it a more streamlined appearance.

The Patten 470 Elite includes a fire-mode selector, allowing the user to switch between semi-automatic and fully automatic fire. It utilizes 30-round magazines and retains the core combat specifications of the base model. Its versatility and ease of handling make it well-suited for a variety of combat scenarios.

NOTES:

- A variant of the standard Patten 470 Assault Rifle.
- Does not feature an ACOG optical sight.
- Magazine capacity is 30 rounds.
- Uses 5.56x45mm NATO ammunition.
- Less optics, fewer unnecessary components—more room for old-school aiming.
