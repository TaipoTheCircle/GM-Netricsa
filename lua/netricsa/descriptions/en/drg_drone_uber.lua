SWARM DRONE, ÜBER-BEETLE


CLASS:      Swarm Drone, Über-Bug
METABOLISM: Alien Arthropod
PERCEPTION: Heavy Assault Drone
SIZE:       ~6,8 ft
ENDURANCE:  Very High
HOSTILITY:  High
WEAPONS:    Claws, Jaws, Fangs, Explosive Body
REWARD:     600 FC
THREAT:     Very High

DESCRIPTION:

The Swarm Drone is a significantly larger, more massive, and slower version of the standard drone. Its body is distinguished by extremely developed muscles and a thick chitinous covering, allowing it to withstand a tremendous amount of damage.

The main feature of its structure is its enormous mouthparts. Its mouth is surrounded by numerous long, sharp fangs, arranged in several rows. When attacking, the Über-Bug uses these fangs in conjunction with its forelimbs, inflicting heavy damage to any target within range.

Despite its impressive durability, the Über-Bug is noticeably slower and less maneuverable than a standard drone. It moves slowly forward, relying on its ability to withstand enemy fire.

However, the Über-Bug's most dangerous feature manifests itself upon its death.

Upon death, the creature's body explodes, releasing a large amount of biological material and causing significant damage to nearby targets. Therefore, destroying the Über-Bug at close range can be fatal even after the alien itself has already perished.

Because of this, the Über-Bug remains a threat throughout the entire encounter.

TIPS:

- Avoid finishing the Über-Bug at point-blank range.
- Always leave some distance between you and him before delivering the killing blow.
- Use long-range weapons to destroy him from a safe position.
- His explosion is especially dangerous in confined spaces.
- If he's surrounded by regular drones, first evaluate your options for retreat.
