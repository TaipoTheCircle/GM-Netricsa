USSSR GUN SUBMACHINE GUN


WEAPON: USSSR GUN Submachine Gun
AMMO:   Energy projectiles
ROF:    ~750 rounds / min

DESCRIPTION:

An unusual submachine gun based on the design of the SMG1 (MP7). Instead of conventional bullets, the weapon fires rainbow-colored energy beams; upon impact, these beams form a glowing USSR symbol (☭) at the point of contact. Once manifested, the symbol gradually drifts away and fades out.

Holding the weapon triggers the USSR national anthem. Each initial shot restarts the musical piece from the beginning, and the music fades out once firing ceases. The USSSR GUN also features two alternative firing modes: the first fires multiple energy projectiles simultaneously, functioning much like a shotgun; the second utilizes an under-barrel grenade launcher that fires projectiles shaped like the USSR logo (☭), which produce the same effect upon impact.

NOTES:

- Based on the SMG1 (MP7) submachine gun model.
- Primary fire produces rainbow-colored beams that manifest the Soviet symbol at the point of impact.
- The first alternative firing mode allows for a volley-style attack, similar to a shotgun.
- The under-barrel grenade launcher fires large projectiles bearing the USSR logo (☭).
- The USSR national anthem plays while the weapon is held, restarting with every initial shot.
