ARISAKA TYPE 30 BOLT-ACTION RIFLE


WEAPON: Arisaka Type 30 bolt-Action Rifle
AMMO:   6.5x50mm Arisaka
ROF:    ~10–12 rounds / min

DESCRIPTION:

A Japanese bolt-action rifle developed under the supervision of Colonel Nariake Arisaka in 1897. It was adopted by the Imperial Japanese Army that same year, becoming the first in the "Arisaka" family of rifles. It was created to replace the obsolete Murata rifles. Its design incorporates features borrowed from both Mauser and Mannlicher systems, characterized by a bolt-action mechanism and a wooden stock.

It operates via a manually-operated, rotating bolt system. It uses 6.5x50mm Arisaka ammunition and features an internal 5-round box magazine, which is loaded using a stripper clip. It is equipped with open iron sights and a bayonet mount. While the rifle offers good accuracy, the Russo-Japanese War revealed design flaws, including issues with spent-casing extraction and the reliability of certain bolt components. It was subsequently replaced by the improved Type 38.

NOTES:

- Well-suited for engaging individual targets at medium to long ranges.
- Effective against unarmored personnel.
- Not intended for use against armored vehicles or heavy cover.
- Used by Japanese forces during the Russo-Japanese War.
- There existed a shortened Type 30 carbine.
