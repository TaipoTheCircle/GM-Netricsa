MENDEL-GRUMAN SNIPER SOLDIER


CLASS:      Mendel-Gruman Sniper Soldier
METABOLISM: Human, Male
PERCEPTION: Sniper Unit
SIZE:       5,9 ft
ENDURANCE:  Average
HOSTILITY:  High
WEAPONS:    TRIGLAV 92 Stalker Sniper Rifle, ORO HOG 9mm Pistol, Fragmentation Grenades
REWARD:     500 FC
THREAT:     High

DESCRIPTION:

Specialized soldiers designed to engage high-value targets from long range. Unlike standard infantry, they undergo additional training in marksmanship, camouflage, and observation. Their mission is simple: spot the enemy before they spot them and eliminate them with a single, precise shot.

The sniper's armor has a distinctive dark, almost black color and is complemented by a camouflage suit designed for operations in wooded areas. The design incorporates elements of the equipment of regular infantry and RPG units, but the helmet has its own modifications. The left side of the visor is divided into several separate optical sections, allowing the use of specialized observation systems.

The sniper's primary weapon is the TRIGLAV 92 Stalker. In the hands of a trained shooter, this rifle allows for engagements at significant distances and is especially dangerous against soldiers who consider themselves safe beyond the effective range of conventional weapons.

The sniper does not seek to engage in a protracted firefight. He prefers to take an advantageous position, wait for the opportune moment, and open fire on the most dangerous or vulnerable target. Once his position is detected, he may attempt to change cover and continue the fight from a different vantage point.

Despite his specialization, the sniper is not helpless at close range. He can use the ORO HOG 9mm as a secondary weapon and also carries fragmentation grenades. Therefore, attempting to break through to him won't guarantee an easy victory. Representatives of this class can also carry the FP9 SMG, despite their designation as snipers.

Snipers are lightly armored Mendel-Gruman units and therefore don't have exceptional survivability. Their main defenses are distance, cover, and accuracy. Depriving them of these advantages makes them significantly less dangerous.

TIPS:

- Don't stand in the open. A sniper only needs a few seconds to pick a target.
- Try to first determine the source of the fire and only then emerge from cover.
- At close range, a sniper is significantly less dangerous than at long range.
- Grenades are especially useful if the enemy is hiding behind cover.
- Don't allow a sniper to freely change positions. Losing good cover dramatically reduces his effectiveness.
- If you notice a distinctive dark silhouette and the flash of a gunshot from afar, don't double-check whether it really was a sniper.
