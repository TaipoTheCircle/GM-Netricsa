COLT 9MM SMG SUBMACHINE GUN


WEAPON: Colt 9mm SMG Submachine Gun
AMMO:   9x19 cartridges
ROF:    ~20 rounds / min

DESCRIPTION:

American 9x19 mm Parabellum submachine gun. Based on the M16 automatic rifle, but uses a free-floating bolt action, unlike the M16 prototype, which used a direct gas system. 

NOTES:

- This modification has only a single fire mode.
