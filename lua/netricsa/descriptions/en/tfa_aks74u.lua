AKS-74U Folding Shortened Kalashnikov Assault Rifle


WEAPON: AKS-74U Folding Shortened Kalashnikov Assault Rifle
AMMO:   5.45x39mm
ROF:    ~650-700 rounds / min
WEIGHT: ~2,7 kg

DESCRIPTION:

A shortened version of the AKS-74, developed in the late 1970s for combat vehicle crews, aircraft, and other units requiring the most compact automatic weapon possible. It entered service with the USSR in 1980.

The assault rifle features a barrel length of only approximately 206 mm, a folding stock, and a special muzzle attachment that serves as a flash suppressor and expansion chamber. It uses the standard 5.45x39mm cartridge and holds 30 rounds. Despite its compact size, the AKS-74U retains the general design of the AK-74.

Due to its very short barrel, the AKS-74U is noticeably inferior to the full-size AK-74 in accuracy and effective range, but is much more convenient in tight spaces, transport, and when carried concealed.

NOTES:

- A very compact assault rifle, especially suitable for close-quarters combat.
- Designed for vehicle crews and other soldiers for whom the standard AK-74 was too long.
- When folded, it becomes so short that a full-size AK-74 looks almost like a rifle next to it.
