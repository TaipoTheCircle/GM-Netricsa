M3 "GREASE GUN" SUBMACHINE GUN


WEAPON: M3 "Grease Gun" Submachine Gun
AMMO:   .45 ACP (11.43x23 mm)
ROF:    ~450 rounds / min
WEIGHT: ~3,7 kg

DESCRIPTION:

The M3, famously nicknamed the "Grease Gun", was an American submachine gun from World War II. It was developed as a cheaper and simpler alternative to the expensive and complex Thompson submachine gun. The design is heavily oriented toward mass production: the frame is made primarily of stamped steel, and the parts are welded together.

The M3 uses a blowback action and fires only in automatic mode. It is fed from a 30-round box magazine. A low rate of fire of approximately 450 rounds per minute makes the weapon quite controllable for a submachine gun.

The weapon entered service in 1943 and was initially intended to replace the Thompson submachine gun. An improved version, the M3A1, was later introduced, featuring a simplified design and several changes to the reloading mechanism. Variants chambered for 9x19mm Parabellum were also available.

NOTES:

- The low rate of fire for a submachine gun allows for better control of the weapon when firing bursts.
- The M3's core philosophy is: cheap, simple, and effective. It was deliberately made significantly less labor-intensive to manufacture than the Thompson.
- Thanks to its compact size and folding wire stock, the M3 was particularly well-suited for armored vehicle crews and other soldiers who found a full-powered rifle inconvenient.
- It looks like a mechanic accidentally forgot to lock the garage and went to war with an Grease Gun. But this is really a combat submachine gun.
