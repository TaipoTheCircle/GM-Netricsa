STROGG TANK FROM THE STROGGOS


CLASS:      Strogg Tank
METABOLISM: Biomechanical Cyborg
PERCEPTION: STROGG Heavy Assault Unit
SIZE:       ~8,2 ft
ENDURANCE:  Very High
HOSTILITY:  Extreme
WEAPONALS:  Machine Gun, Missile Launcher, Plasma Weapon
REWARD:     1000 FC
THREAT:     Very High

DESCRIPTION:

The STROGG Tank is one of the heaviest combat units in their army. It is a massive, obstrogged soldier, designed not for stealth or maneuverability, but for direct penetration of enemy defenses. Its body combines organic tissue with metal structures, heavy armor, and integrated weapons systems.

Unlike standard Stroggs, the Tank doesn't need to close in on the enemy quickly. It can engage at a considerable distance using its body-mounted heavy weapons. Its firepower allows it to suppress infantry, destroy cover, and force the enemy to constantly reposition.

The Tank's massive build makes it extremely durable. Despite its size, it is agile enough to pursue its victims and prevent them from retreating endlessly.

TIPS:

- Particularly dangerous in rooms and narrow corridors.
- Don't try to outshoot the Tank with weak weapons.
- Use heavy weapons and explosives.
- Keep moving and don't let it corner you.
- Cover helps evade its fire, but don't rely on it for too long.
- If there are other Stroggs near the Tank, consider eliminating the support units first, otherwise the heavy unit will provide covering fire.
