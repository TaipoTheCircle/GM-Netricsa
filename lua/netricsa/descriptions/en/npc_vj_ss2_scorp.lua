SCORPION SOLDIER, TROOPER


CLASS:      Scorpion Soldier, Trooper
METABOLISM: Endothermic, Viviparous Arthropod
PERCEPTION: Advanced Arachnid Race
SIZE:       9,8 ft
ENDURANCE:  High
HOSTILITY:  Extreme
WEAPONS:    Eviscerator Cannon
REWARD:     125 FC
THREAT:     High

DESCRIPTION:

These arachnids were called "Scorpions" by humans, although the official EDF database calls them "Arachnid Soldiers". However, Scorpion Soldier sounds cooler.

These alien arachnids originate from a distant, harsh planet, where they were the dominant species. They even managed to form an advanced society—at least as advanced as is possible for giant insects.

Mental has formed an alliance with their Matriarch, and she provides her warriors to fight for his cause in exchange for allowing her broods to infest the planets they help Mental conquer.

The troopers are the weakest and smallest of the arachnid swarms, though they are still quite dangerous. They are armed with an Eviscerator-class cannon that rapidly fires plasma projectiles. Their primary role on the battlefield is to destroy enemy infantry in difficult terrain where Mental's regular infantry would have difficulty traversing.

TIPS:

- Keep your distance and avoid their shots by moving to the side.
- Their claws are even more dangerous than their shots.
- Get rid of them with a sniper rifle or explosives.
- Do NOT call them "Arachnoids". They are enraged by comparison to a species far more primitive than themselves.
