THE FUTURE SITE OF TEOTIHUACAN, GIANT PIT - MESSAGE


Sam, stop! We... we aren't in the city. It looks like we've ended up somewhere before the city was even built... Just a pit. A huge pit—the place where Teotihuacan will eventually be constructed.

Look at these walls. They don't look natural. Someone dug this pit. Or maybe they didn't... The walls are of unknown origin, and my sensors can't identify the material. It's not stone, not metal, not anything terrestrial. It's something *else*.

Then a message came through. From some "Creators". They call themselves Taipo and Jack Pofigist. And you know what they wrote? "We were testing a vehicle HUD and bosses for the *Serious Sam 2 NPCs* add-on.".

Seriously? Creators. Gods. Makers. And they're writing about a vehicle HUD? It's like we're in some game mod, not reality!

And then... then it gets totally absurd. A ninja disco. Someone named Onan Arthur. Nonsense about dancing and, apparently, some very strange parties. This clearly has nothing to do with our mission, Sam. Unless Mental has decided to take over the world using discos and ninjas. Although... I wouldn't be surprised!
