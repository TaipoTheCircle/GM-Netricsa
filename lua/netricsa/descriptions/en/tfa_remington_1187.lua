REMINGTON MODEL 11-87 SEMI-LOADING SHOTGUN


WEAPON: Remington Model 11-87 semi-automatic shotgun
AMMO:   12-gauge
ROF:    ~60-80 rounds / min
WEIGHT: ~3,7 kg

DESCRIPTION:

This American semi-automatic shotgun was introduced in 1987. Based on the renowned Remington 1100, it is available in various models, including hunting, police, and tactical models.

The shotgun is gas-operated and chambered for 12- and 20-gauge cartridges. Depending on the model, the magazine capacity is approximately 4-8 rounds. Special police and tactical versions are also available, including the Entry Gun with a shortened barrel.

The semi-automatic system eliminates the need to manually reload the bolt after each shot, allowing for quick follow-up shots. The Model 11-87 has become popular not only as a hunting weapon, but also in police and tactical versions.

