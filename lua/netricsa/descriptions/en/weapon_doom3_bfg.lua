BFG 9000 MASSIVE RIFLE


WEAPON: BFG 9000 Massive Rifle
AMMO:   BFG Cells
ROF:    ~24 rounds / min

DESCRIPTION:

A futuristic energy weapon developed by the UAC corporation. This is the most powerful weapon available, firing a huge green energy bolt. The projectile can damage not only the target upon impact, but also surrounding enemies with energy beams during its flight.

The weapon can be charged by holding the fire button. The longer the charge, the more powerful the shot, but holding it too long causes it to overload and can kill the shooter.

The BFG is especially effective against strong opponents and large groups of enemies. Ammunition is rare, so using it against every zombie you encounter would be like using a chainsaw to chop butter.

NOTES:

- One of the most powerful weapons.
- The energy bolt damages enemies before it explodes.
- Ammo is rare, so it's best to save each charge for more powerful opponents.
