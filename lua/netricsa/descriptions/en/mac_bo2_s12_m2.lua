SAIGA-12 SEMI-AUTOMATIC SHOTGUN


WEAPON: Saiga-12 semi-automatic shotgun
AMMO:   12/70 mm
ROF:    ~468 rounds/min (S12)

DESCRIPTION:

A Russian semi-automatic smoothbore shotgun, developed based on the Kalashnikov assault rifle design and manufactured by the Izhevsk Machine-Building Plant since 1997. It inherits the characteristic layout of the AK family, including a gas-operated action and a rotating bolt, adapted for 12-gauge hunting cartridges.

It utilizes detachable box magazines of varying capacities. Depending on the specific model, it may be equipped with a fixed or folding stock, as well as various types of sighting systems. Compact versions have gained widespread popularity due to their combination of high power and relatively small dimensions.

NOTES:

- Based on the design of the Kalashnikov assault rifle.
- Chambered for 12/70 mm and 12/76 mm "Magnum" cartridges.
- Available with 2-, 4-, 5-, and 8-round magazines, as well as higher-capacity options.
- Some variants are externally almost indistinguishable from a Kalashnikov assault rifle—until you look into the barrel.
- Semi-automatic firing mode.
- Standard 10-round magazine; extended 14-round magazine also available.
- Rate of fire is approximately 468 rounds per minute.
- Also known as the "S12," while another variant is designated as the "Kamchatka-12".
