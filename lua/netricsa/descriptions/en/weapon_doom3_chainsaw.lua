CHAINSAW


WEAPON: Chainsaw
AMMO:   Gasoline

DESCRIPTION:

A powerful hand-held tool with a rotating chain, designed for striking targets at extremely close range. The chain rotates continuously during operation, allowing for rapid successive strikes without the need to reload.

A chainsaw is especially effective against enemies at close range, but requires constant fuel consumption. The main drawback is the need to approach the target at dangerously close range.

NOTES:

- Does not require ammunition, but constantly consumes fuel.
- Very effective at extremely close range.
- Produces a loud, distinctive sound when in use.
- Gasoline has become more valuable these days.
