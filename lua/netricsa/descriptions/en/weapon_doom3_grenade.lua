FRAGMENTATION GRENADE


WEAPON: Fragmentation Grenade
AMMO:   Grenade
ROF:    ~30 throws / min

DESCRIPTION:

A hand-held fragmentation grenade designed to destroy targets with an explosion and shrapnel. It can be used against groups of enemies and to attack targets behind cover. After being thrown, the grenade explodes after a few seconds.

The small size allows you to carry several grenades, but the supply is limited. If used incorrectly, the explosion can pose a danger to the thrower.

NOTES:

- Can't shoot an enemy around a corner? - Just throw the grenade there.
- Effective against groups of enemies.
- Allows you to hit targets behind cover.
- Explodes with a slight delay after being thrown.
