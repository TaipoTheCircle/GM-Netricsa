ROF:    ~120 rounds/min

DESCRIPTION:

A German semi-automatic pistol, this is a shortened variant of the Mauser C96, developed by the Mauser company in the early 1920s. The creation of this version was driven by the restrictions of the Treaty of Versailles, which prohibited Germany from manufacturing pistols with a barrel length exceeding 100 mm. The M1921 features a barrel shortened to 99 mm, a smaller grip, and more compact overall dimensions. Due to its size, it earned the nickname "Bolo"-a reference to the Bolsheviks, among whom the pistol was quite popular.

The weapon operates on a short-recoil principle and utilizes a locking system with a pivoting locking block. It is chambered for the 7.63x25mm Mauser cartridge. Ammunition is fed from an integral box magazine with a 10-round capacity, which is loaded from the top using a stripper clip. It is equipped with open iron sights and an external hammer. The wooden holster can be attached to the pistol to serve as a shoulder stock, allowing for more stable firing.

