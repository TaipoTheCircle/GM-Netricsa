WHISKEY


WEAPON: Whiskey
AMMO:   One Can

DESCRIPTION:

An alcoholic beverage served with ice, known for its potent intoxicating effect. Consuming it gradually blurs the user's vision, making it difficult to perceive the surrounding environment.

The effect wears off over time; however, excessive consumption without breaks can be fatal. Unlike most pieces of equipment, this drink poses a direct threat to its own owner.

NOTES:

- Served with ice.
- Temporarily blurs vision upon consumption.
- The effect fades after some time.
- Continuous consumption can lead to the user's death.
