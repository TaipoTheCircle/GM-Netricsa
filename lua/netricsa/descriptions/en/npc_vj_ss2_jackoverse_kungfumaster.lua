MARTIAL ARTIST MASTER FROM THE CHI-FANG


CLASS:      Martial Artist Master
METABOLISM: Intelligent Being
PERCEPTION: Old Master, Mentor
SIZE:       11,8 ft
ENDURANCE:  Very High
HOSTILITY:  Low
WEAPONS:    Martial Arts
REWARD:     2000 FC
THREAT:     Very High

DESCRIPTION:

He is one of the most respected mentors on the planet. This old and wise warrior has dedicated much of his life to studying martial arts and training a new generation of fighters.

For him, his students were never just subordinates or fighters. He treated them like his own family, caring for their lives, training, and character. In his school, younger students respected their elders, and everyone collectively regarded the master as a father and mentor.

A master had one student who took a completely different path. Embittered and rejected, he turned his back on tradition and dedicated himself to the dark arts.

Over time, he gathered his own followers and became a Master of the Dark Arts.

One day, he attacked his former teacher's school along with his students. Upon arriving, the dark master used his abilities to transform the Master of Martial Arts' students into chickens and take them with him.

This was a terrible blow for the old master.

However, he did not abandon his students.

He set out alone, intending to bring them home.

On his way, the master encountered numerous students of his former student. Despite his age, he demonstrated incredible combat prowess.

Dozens of opponents confronted him, but the master did not retreat.

Every defeated opponent brought him closer to his captured students.

Finally, the master reached the Master of the Dark Arts himself. But the latter had no intention of giving up.

Realizing he would lose in a direct confrontation, the Master of Dark Arts summoned the ancient essence of the dragonoid race.

A long and arduous battle began.

The ancient creature surpassed his ordinary opponent in strength and size, but the old master did not allow fear to overcome him. Using his skill and resourcefulness, he managed to overcome even this monstrous entity.

At the decisive moment, the master tore out its tongue, depriving it of one of its main weapons. Thus, the Master of Dark Arts was finally defeated.

And his spell was broken.

The students, transformed into chickens, regained their original forms.

For his actions, the master became highly revered both on Chi-fan and among the Chinese on Earth.

TIPS:

- Don't underestimate him because of his age. Old age only conceals his vast combat experience.
- Don't touch his students.
