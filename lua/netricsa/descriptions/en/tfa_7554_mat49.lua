MAT-49 SUBMACHINE GUN


WEAPON: MAT-49 Submachine Gun
AMMO:   9x19mm Parabellum
ROF:    ~600 rounds per minute

DESCRIPTION:

A French submachine gun developed by engineers Pierre Monteil and Delamer at the *Manufacture Nationale d'Armes de Tulle* (MAT) in the late 1940s. It was adopted by the French Army in 1949 to replace various aging weapons that had remained in service following the Second World War. The design is characterized by its simple stamped-metal construction, high reliability, and a folding metal stock. It saw extensive use by the French Army, the French Foreign Legion, and airborne units.

The weapon operates on a blowback principle and fires from an open bolt. It is chambered for 9x19mm Parabellum ammunition and utilizes box magazines with a capacity of 20 or 32 rounds. A key design feature is the forward-folding magazine well, which allows the weapon to be made significantly more compact for transport; when folded, the magazine sits parallel to the barrel. It is equipped with a retractable metal stock, iron sights, and a safety mechanism located on the rear of the pistol grip.

NOTES:

- Adopted by the French Army in 1949.
- Over 700,000 units produced.
- Magazines available in 20- or 32-round capacities.
- Effective firing range is approximately 100 meters.
- Weight (without magazine) is approximately 3.5 kg.
- There was a police variant of the MAT-49/54 featuring an extended barrel and a wooden stock.
- During the Vietnam War, North Vietnamese units modified captured MAT-49s to chamber the 7.62x25mm TT cartridge.
