"HELSING" PNEUMATIC RIFLE


WEAPON: "Helsing" Pneumatic Rifle
AMMO:   Metal Arrows (Bolts)
ROF:    Medium, Semi-Automatic

DESCRIPTION:

A homemade pneumatic weapon, crafted by the inhabitants of the Metro and based on a revolver-style design. It features a unique multi-shot system with eight metal barrels arranged in a revolving configuration. It uses compressed air-stored in a dedicated reservoir—to fire projectiles. The weapon is highly accurate, virtually silent, and allows for the reuse of ammunition.

Arrows are fed into the firing position via the rotating barrel assembly. To increase shot power, the reservoir must be pressurized (pumped up); however, excess pressure will gradually bleed off. The weapon is configured like a crossbow and supports the attachment of various magazines, optical sights, and other mechanisms. It can also fire explosive arrows.

NOTES:

- The name is a reference to the crossbow from the film "Van Helsing" (2004).
- It also utilizes an eight-shot rotating barrel assembly.
- Arrows can be retrieved after being fired and used again.
- Pressurizing the reservoir increases both power and firing range.
- Magazines with capacities of 1, 3, 6, and 8 bolts can be attached.
- Both standard and explosive bolts are available.
