BONE SNAKE, SMALL FROM THE KLEER


CLASS:      Bone Snake, Small
METABOLISM: Undead
PERCEPTION: Magical Creature
SIZE:       18 ft
ENDURANCE:  Very Low
HOSTILITY:  Extreme
WEAPONS:    Fireballs
REWARD:     50 FC
THREAT:     Low

DESCRIPTION:

Bone Snakes inhabit the caves of the planet Kleer - they are the monstrous creations of Count Kleerofski himself. They are imbued with greater magical energy than most skeletons, and therefore capable of belching fireballs.

Like a bad fish, the snake is full of small bones that will easily damage you if you dare approach it, or if it doesn't crawl to you.

Although they may appear motionless, they can actually move, though rarely. Can you blame them? Imagine having to jump with every step!

Their long, protruding tongue will taunt us, which we should use to destroy these archaeological artifacts.

TIPS:

- Their slow projectiles are easily avoided by dodging to the side.
- They should be low-priority targets among other enemies.
- They can be destroyed with a shotgun blast at point-blank range.
