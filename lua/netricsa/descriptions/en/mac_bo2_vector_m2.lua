KRISS K10 SUBMACHINE GUN


WEAPON: KRISS K10 Submachine Gun
AMMO:   .45 ACP / 9x19mm / .40 S&W
ROF:    ~1200 rounds/min

DESCRIPTION:

An American experimental submachine gun developed by KRISS USA as an improved version of the KRISS Vector. It was first unveiled in 2011. The weapon utilizes the proprietary Super V delayed-blowback system, which directs the bolt’s movement downward, helping to reduce recoil and muzzle climb.

The K10 features a telescoping stock, a redesigned charging handle, ambidextrous controls, and four Picatinny rails. Its modular design allows for caliber conversion between .45 ACP, 9×19mm, and .40 S&W. It was designed to use 13- or 25-round magazines, with the option to use extended magazines as well.

NOTES:

- Represents the second generation of the KRISS Vector family.
- The charging handle can be configured for either the left or right side.
- The Super V system helps mitigate muzzle climb during firing.
- Despite its advanced design, the K10 remained an experimental prototype. It seems the original Vector was not ready to give way to its younger sibling.
