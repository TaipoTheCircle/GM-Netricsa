DESERT ZOMBIE MACHINE GUNNER, COMMANDO


CLASS:      Desert Zombie Machine Gunner, Commando
METABOLISM: Demonized Undead
PERCEPTION: Zombie Soldier
SIZE:       11,5 ft
ENDURANCE:  Average
HOSTILITY:  High
WEAPON:     Minigun
REWARD:     150 FC
THREAT:     High

DESCRIPTION:

After witnessing how effectively demon-led zombies decimated entire infantry hordes with miniguns, Mental decided to add these soldiers to his arsenal.

Arachnoids were too large, bulky, and slow for mass deployment. Consequently, Mental forged an alliance with the Lord of Hell, who lent him several types of creatures—including these monstrosities.

These zombies are former Marines who underwent a complex demonic transformation ritual. Unlike standard zombies—which are merely possessed by demons—Commandos were completely remade, becoming a hybrid of human and abyss-spawn.

This Commando variant is distinguished by the gear retained from his service in desert regions. Instead of a green T-shirt, he wears desert-pattern trousers and a distinctive German desert helmet, designed for hot, arid climates. This uniform partially persisted after the demonic transformation, even though its original purpose had long since become irrelevant.

Unlike the green T-shirt variant, this Commando retains almost no elements of his upper-body uniform. The desert variant looks lighter, but that certainly doesn't stop it from lugging around a minigun and turning the surrounding area into a solid stream of bullets.

The best way to deal with them is NOT to recklessly rush into their line of fire.

TIPS:

- Take cover from their fire; you might be tempted to go for a "no cover, one-on-one" approach, but using that tactic is more likely to leave you "exposed and dead."
- Their minigun is inaccurate at long range; the further away you are, the better.
- Sniping from a distance is a great way to handle them.
- A rocket to the head solves the problem quickly.
