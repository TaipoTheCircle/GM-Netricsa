MENDEL-GRUMAN SOLDIER-OFFICER


CLASS:      Mendel-Gruman Soldier-Officer
METABOLISM: Human, Male
PERCEPTION: Standard Infantry
SIZE:       5,9 ft
ENDURANCE:  Average
HOSTILITY:  High
WEAPONS:    ORO HOG 9mm Pistol, Frag Grenades
REWARD:     200 FC
THREAT:     Low

DESCRIPTION:

The Officer is the primary and most common soldier of the Mendel-Gruman corporation. These soldiers form the backbone of its armed forces and are encountered throughout virtually the entire planetary operation. Unlike the heavy units, the Officer does not possess any specialized weapons or complex armor. His task is much more prosaic: to move with the group and shoot at anything that does not bear the Mendel-Gruman emblem. The Officer's outfit consists of relatively light but practical armor with numerous pouches and a fully equipped tactical belt. Nearly all vital areas of the body are protected, but the joints are left more mobile. The standard uniform is predominantly dark blue.

The face is covered by a protective helmet with a dynamic visor. Its color changes depending on the soldier's state: blue signifies normal operation, yellow indicates heightened alertness, and red indicates maximum combat readiness. This makes for a rather handy indicator: the soldier literally displays on his face how much he dislikes the current situation.

The Officer's primary weapon is the ORO HOG 9mm pistol. Additionally, the standard soldier carries fragmentation grenades. Under certain circumstances, individual Officers may use other weapons, even though these are not their standard armament.

The Officer's main strength lies not in individual survivability. On their own, they are comparatively weak and perish quickly under concentrated fire. However, Mendel-Gruman compensates for this with numbers and group actions. Officers typically operate in small squads of two or three, trying to use cover and fire simultaneously.

They are capable of moving around the battlefield, changing positions, and attacking from different directions. Therefore, a single Officer poses a moderate threat, while several soldiers can form a dense firing line. This becomes especially dangerous when a regular group is supported by stronger allies.

TIPS:

- Don't underestimate them because of their weak armor. The Officer's main threat lies in their numbers.
- Grenades are especially effective against groups. Several Officers often stand quite close to each other.
- Use cover if several soldiers are working against you simultaneously.
- If you see a red visor, the soldier is already fully combat-ready.
- Watch your surroundings: some fighters may be armed with weapons that are unusual for an Officer.
