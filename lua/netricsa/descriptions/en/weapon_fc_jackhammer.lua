PANCOR JACKHAMMER AUTOMATIC SHOTGUN


WEAPON:   Pancor Jackhammer Automatic Shotgun
AMMO:     12-Gauge Shotgun
ROF:      Automatic, ~171 Rounds / Min
WEIGHT:   ~7,9 kg.

DESCRIPTION:

A heavy close-combat weapon with a high rate of fire and tremendous stopping power. It uses a 10-round magazine and is capable of fully automatic fire. Each shot releases a large amount of pellets, making the weapon particularly effective for clearing rooms and tight passages.

The design is based on an unusual rotating drum magazine. Originally designed as a 12-gauge bullpup shotgun, it never saw mass production, remaining in the prototype stage.

NOTES:

- Fully automatic fire.
- The magazine holds 10 rounds.
- A single shot fires multiple pellets, allowing you to hit large targets with multiple hits.
- Most effective at close range; accuracy and damage decrease sharply at medium and long range.
- Particularly effective in corridors, rooms, and other confined spaces.
- Its heavy weight and high rate of fire make it difficult to fire for extended periods.
- Ammunition is rare, so wasting it unnecessarily is not recommended.
