TULA TOKAREV PISTOL MODEL 1933


WEAPON:    Tula Tokarev Pistol Model 1933
AMMO:      7.62x25mm TT
ROF:       ~30-40 rounds/min.
WEIGHT:    ~0,85 kg.

DESCRIPTION:

A Soviet self-loading pistol designed by Fyodor Tokarev and adopted in the 1930s. It was created as a replacement for the outdated revolvers and foreign pistols in service with the Red Army.

The pistol uses a short-recoil action with tilting barrel locking. The design is relatively simple and easy to manufacture, and the 7.62x25mm cartridge has a high muzzle velocity.

The TT is designed primarily for close-quarters combat. The light weight and relatively high cartridge power allow for quick follow-up shots, and the simple design is well suited for mass military use. The effective range is approximately 50 meters.

NOTES:

- Particularly effective at close range, where the high bullet velocity allows for quick target engagement.
- The lightweight frame and powerful cartridge make the TT a fairly sharp and fast weapon in the hands of an experienced shooter.
- The simplicity of the design was one of the pistol's main advantages, especially in the context of mass military production.
