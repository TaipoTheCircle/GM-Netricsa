SCRIPTED WEAPON


WEAPON: Script Weapon
AMMO:   Universal Ammo
ROF:    ~60 Rounds / min
WEIGHT: ~1,1 kg.

DESCRIPTION:

An extremely powerful pistol of unknown origin. Its appearance usually resembles a standard 9mm pistol, but sometimes takes the form of a .357 Magnum revolver. Despite its compact size, a single shot can instantly kill a target.

The weapon has two fire modes. The first fires single, powerful shots, each using one round. The second mode transforms the weapon into a shotgun-like weapon, firing eight shots at once.

A unique feature of the system is its unique reloading system. If all eight shotgun shells have been used, the weapon can be reloaded, expending eight rounds. However, reloading is optional. If you don't do this, normal fire continues to use the remaining ammo without the additional cost of recharging shotgun mode.

For example, if you have 8 rounds remaining, you can fully use them in shotgun mode and then continue using normal fire without automatically depleting another eight. This allows you to conserve ammunition by switching modes wisely.

NOTES:

- Normal fire can destroy most targets with a single hit.
- Secondary fire fires 8 shotgun shells.
- Reloading shotgun mode requires 8 rounds.
- Reloading is not automatic, so you can conserve ammunition.
- Normal fire is effective at medium to long range.
- Shotgun mode is most effective at close range.
- If you don't reload shotgun mode, the weapon does not consume the additional 8 rounds.
- If you fully deplete your shotgun shells, you must consider your remaining ammunition before reloading.
- Appearance may vary: 9mm pistol or .357 Magnum revolver.
