FM 24/29 LIGHT MACHINE GUN


WEAPON: FM 24/29 Light Machine Gun
AMMO:   7.5x54mm French
ROF:    ~450 rounds / min, automatic fire

DESCRIPTION:

A French light machine gun developed by Lieutenant Colonel Reibel with the assistance of chief armorer Chassaud. It was created in the early 1920s at the *Manufacture d'armes de Châtellerault* and adopted by the French Army in 1925. It was designed to provide infantry squads with mobile fire support. The weapon features a distinctive configuration with a top-mounted box magazine, a wooden stock, and a bipod.

It operates via a gas-actuated system and fires from an open bolt. It uses 7.5x54mm French ammunition and a detachable 25-round box magazine. The weapon is equipped with a pistol grip, a folding bipod, and open iron sights. Its moderate rate of fire allows for controlled bursts, providing effective support for a unit on the battlefield.

NOTES:

- Adopted in 1925, it remained in service with the French Army until the 1960s.
- Well-suited for suppressing infantry groups and covering the advance of friendly forces.
- Effective against unarmored targets at medium to long ranges.
- Capable of penetrating light cover, but not designed to defeat heavy armor.
- The muzzle velocity reaches approximately 830 m/s.
- There was a tank-mounted variant of the MAC 1931, featuring a side-mounted drum magazine with a capacity of 150 rounds.
