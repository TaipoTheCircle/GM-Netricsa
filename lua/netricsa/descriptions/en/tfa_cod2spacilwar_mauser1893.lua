DESCRIPTION:

The Mauser M1893, also known as the Spanish Mauser, was a German repeating rifle designed by Paul Mauser and adopted by the Spanish Army in 1893. It became one of the most famous early Mauser rifles and served as the basis for further development of the design.

The rifle uses a bolt-action mechanism and the 7x57mm Mauser cartridge. The internal magazine holds 5 rounds and is loaded from the top using a clip. One of the key features of the M1893 was its compact magazine, located entirely within the stock, making the design more convenient than previous Mauser models.

The M1893 saw widespread combat use. It became particularly famous during the Spanish-American War of 1898, where Spanish troops used it to produce extremely dense and accurate fire. Experience with the M1893 influenced the subsequent development of American military rifles and ultimately led to the creation of the M1903 Springfield.

The M1893 design had a profound impact on the development of magazine-fed rifles. Other Mauser models were further developed, and in 1898, the famous Gewehr 98 was created.

