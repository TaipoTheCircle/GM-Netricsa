MADSEN LIGHT MACHINE GUN


WEAPON: Madsen light machine gun
AMMO:   6.5x55 mm / 7.92x57 mm / 7.62x54 mm R
ROF:    ~450 rounds/min

DESCRIPTION:

A Danish light machine gun, designed in 1890 and put into mass production in 1900. It is considered the first light machine gun to be produced on an industrial scale. Due to its relatively low weight and the fact that it could be carried by a single soldier, it marked an important milestone in the development of automatic weapons.

The Madsen utilizes a short-recoil operating system and features a highly unusual bolt mechanism design. It is fed from a box magazine located on top of the receiver. Depending on the variant, it used magazines with a capacity of 25, 30, or 40 rounds. The machine gun was manufactured for various rifle calibers and exported to many countries.

NOTES:

- One of the pioneers among light machine guns, appearing even before the First World War.
- It served in the militaries of approximately 30 countries.
- The top-mounted magazine gives it a very distinctive silhouette.
- Production continued until the early 1950s—a true veteran among automatic weapons.
