GNAT


CLASS:        Gnat
METABOLISM:   Insect
PERCEPTION:   Small Creature
SIZE:         Very Small
STAMINA:      Very Low
HOSTILITY:    Low
WEAPON:       Bite
REWARD:       1 FC
THREAT:       Very Low

DESCRIPTION:

A tiny flying gnat found almost everywhere. It poses no serious danger to most creatures but can be quite annoying.

Gnats fly near your head, land on your skin, and bite periodically, forcing you to constantly swat at them. The worst part is that a gnat is rarely alone.

For some reason, Mental's armies didn't even bother to wipe out these insects. Perhaps they simply decided that if an enemy is already annoyed, a little extra aggravation wouldn't hurt.

TIPS:

- Don't pay too much attention to it.
- If a gnat starts getting in your way, just swat it.
- If there are a lot of them, it's best to deal with them immediately before the annoyance turns into a real problem.
- The reward for destroying one is so small that Mental probably won't even notice your achievement.
