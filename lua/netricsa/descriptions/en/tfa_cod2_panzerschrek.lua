PANZERSHREK ANTI-TANK GRENADE LAUNCHER (RPZB. 54)


WEAPON: Panzerschreck anti-tank grenade launcher (RPzB. 54)
AMMO:   88-mm rocket-propelled anti-tank grenade
ROF:    ~1 shot / min
WEIGHT: ~9.5 kg

DESCRIPTION:

The Panzerschreck, or "tank terror," was a German hand-held anti-tank grenade launcher from World War II. Adopted in 1943, it was a rocket-propelled anti-tank weapon with an open launch tube. The grenade had a shaped-charge warhead and could penetrate up to 220 mm of armor.

Unlike the earlier RPzB. 43 Ofenrohr, the Panzerschreck featured a protective metal shield that protected the shooter from the hot propellant gases during firing. The grenade launcher was operated by a two-man crew: a gunner and a loader. The effective range was approximately 150 meters.

NOTES:

- Designed primarily for use against armored vehicles. The cumulative grenade is capable of penetrating even well-protected targets.
- It performs best at close range, where it's easier to hit large armored targets.
- This is the only instance where the phrase "Let's Get Shrek" is followed not by a green ogre, but by an 88mm anti-tank missile.
- The protective shield distinguishes the Panzerschreck from the early Ofenrohr and protects the gunner from hot gases.
