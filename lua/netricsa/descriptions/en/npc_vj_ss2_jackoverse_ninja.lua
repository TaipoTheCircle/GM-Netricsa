DARK NINJA DISCIPLE MASTER OF THE DARK ARTS FROM THE CHI-FANG


CLASS:      Dark Ninja Disciple Master of the Dark Arts
METABOLISM: Humanoid, Male
PERCEPTION: Disciple Of The Dark Arts
SIZE:       5,9 ft
ENDURANCE:  Average
HOSTILITY:  Very High
WEAPONS:    Fists, Legs, Combat Techniques, Shurikens
REWARD:     250 FC
THREAT:     Average

DESCRIPTION:

They were once ordinary students of martial arts schools, but after turning their backs on the traditions of their mentors, they joined their new master and fully embraced his brutal teachings.

Unlike ordinary warriors, dark disciples undergo full-fledged training in martial arts. They are highly skilled in hand-to-hand combat, able to quickly close the distance and attack their opponents with a series of strikes and shuriken throws.

The Master of Dark Arts teaches his followers not only fighting techniques but also various forbidden techniques. Students are capable of delivering powerful kicks, performing jumping attacks, and using sharp combinations of strikes that allow them to quickly knock down an opponent.

However, their devotion to the Master of Dark Arts has a downside. They almost never retreat on their own, even when the situation becomes hopeless. For them, defeat means not just defeat, but shame before their teacher.

When the Master of Dark Arts began his rebellion against his teacher, these students became his core strength. They participated in the capture of the Master of Martial Arts' students, guarded the captives, and fought those who tried to free them.

Later, they had to face the Master of Martial Arts himself. Despite his numerical superiority, his skill was enough to break through their ranks and reach their mentor.

TIPS:

- Don't let them surround you. A group of dark disciples is significantly more dangerous than a single fighter.
- Keep your distance. In close combat, they can quickly unleash a series of attacks.
- At long range, throw two shurikens.
- Use rapid-fire weapons to prevent them from closing the distance.
- Explosives are especially effective against several disciples gathered around a single target.
