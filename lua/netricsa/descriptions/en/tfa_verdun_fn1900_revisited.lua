BROWNING M1900 SEMI-AUTOMATIC PISTOL


WEAPON: Browning M1900 Semi-Automatic Pistol
AMMO:   7.65x17mm Browning
ROF:    ~35 rounds / min

DESCRIPTION:

A Belgian semi-automatic pistol, designed by American inventor John Moses Browning in 1896 and put into mass production by Fabrique Nationale in 1900. It became one of the first commercially successful semi-automatic pistols and saw widespread use among the military, police, and civilians. It is characterized by its compact design, distinctive slide, and the placement of the recoil spring above the barrel.

The pistol operates on a blowback mechanism and chambers the 7.65x17mm Browning cartridge. It is fed by a detachable, single-stack magazine with a 7-round capacity, housed within the grip. It features a single-action, striker-fired mechanism, a manual thumb safety, and open iron sights. The recoil spring is positioned above the barrel and also serves as the striker spring.

NOTES:

- Effective against individual, unarmored targets at short range.
- Magazine capacity: 7 rounds.
- Designed by John Moses Browning.
- Manufactured in Belgium from 1900 to 1912.
- Approximately 700,000 units were produced in total.
