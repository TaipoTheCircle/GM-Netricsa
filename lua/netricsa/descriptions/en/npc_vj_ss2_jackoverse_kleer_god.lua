KLEER GOD FROM THE KLEER


CLASS:        Kleer God
METABOLISM:   Undead, Avatar of War
PERCEPTION:   Supreme Deity of the Kleer
SIZE:         Gigantic
ENDURANCE:    Extreme
HOSTILITY:    Absolute
WEAPONS:      Summoning Waves of Minions (Not the "Despicable Me" kind), Spectral Chain-Balls, Shield Wall, Earth-Shattering Ground Slams
REWARD:       1000000 (Approx) FC
THREAT:       Absolute

DESCRIPTION:

An ancient four-armed war deity once worshipped by the extinct Kleer civilization. When Mental resurrected their skeletal remains for his Horde, he inadvertently awakened their formidable Avatar as well. However, the tyrant could not subjugate the creature; the colossus rebelled against its master's control and now battles absolutely everyone, embodying the pure, primal rage of an entire race.

Visually, this monster is a colossal skeleton clad in heavy dark armor and a horned crown, with sinister green energy spewing from its chest. In combat, it employs spectral magic, materializing flying walls of shield-bearers and attacking with chains. When the Kleer God sustains critical damage, it cowardly dissolves into the darkness, forcing Sam to fend off hordes of phantom servants.

TIPS:

- Demonic symbols glow on its giant arms; focus your fire on them to deal critical damage or even tear off the limbs entirely.
- When it summons a spectral shield wall, do not try to shoot through it; simply jump over this phalanx-like barrier.
- When he vanishes into the darkness, use the appearing phantom Clears for melee combat and melee finishers to fully restore your health.
