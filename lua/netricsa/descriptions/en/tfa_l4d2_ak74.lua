AK-74 ASSAULT RIFLE


WEAPON: AK-74 Assault Rifle
AMMO:   5.45x39 rifle, 40mm underbarrel grenade launcher.
Rates:  700 Rounds / min

DESCRIPTION:

This is the primary weapon of the Soviet/Russian army. It was developed by Mikhail Timofeevich Kalashnikov in 1970 and adopted by the Soviet Army in 1974, hence the name. This assault rifle is renowned for its reliability and effectiveness; it hardly jams, and can fire even after being completely immersed in mud. It has seen service in the Afghan War, the Chechen War, and is currently used in the Soviet Military District. It has a modified version with the "M" suffix; this version has different specifications and is black. This assault rifle is also famous for being used almost worldwide, primarily by terrorist organizations, but also by the militaries of various countries. It also has an underbarrel grenade launcher, the GP-25, which fires 40mm grenades.

NOTES:

- Use it to storm buildings or trenches.
- Use the underbarrel grenade launcher to flush out enemies from cover.
- You can fire at close, medium, and long ranges.
