"ABZATS" AUTOMATIC SHOTGUN


WEAPON: "Abzats" automatic shotgun
AMMO:   12x70 mm
ROF:    ~600 rounds / min

DESCRIPTION:

This heavy automatic shotgun, created by Kuznetsky Most gunsmiths, is based on a shortened DShK machine gun modified for 12-gauge use. The weapon is belt-fed and uses a standard 20-round magazine. Thanks to its high rate of fire and powerful 12x70 mm cartridge, the "Abzats" is capable of literally raining down a hail of pellets on the enemy at close range.

The weapon's heavy weight, strong recoil, and high ammunition consumption are its main drawbacks. With a larger magazine, the capacity increases to 40 rounds. Depending on the modification, it can fire semi-automatically or fully automatically.

NOTES:

- Enormous firepower at close range.
- Belt-fed 20-round magazine with an extended 40-round magazine.
- Fully automatic mode turns the shotgun into a true light machine gun.
- Very heavy, significantly slowing movement.
