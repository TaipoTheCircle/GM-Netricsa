ORO "RED FIST" RPG


WEAPON: ORO "Red Fist" RPG
AMMO:   Rocket-propelled grenades
ROF:    ~15 rounds / min
WEIGHT: ~7-8 kg

DESCRIPTION:

A powerful portable rocket launcher manufactured by ORO. The weapon fires a single rocket at high speed, which explodes upon impact with great destructive force, damaging the target and everything around it. Ammunition is limited, but each rocket is so powerful that a single accurate shot can decide the outcome of a conflict.

The weapon has two modes. The first is a normal, unguided launch, in which the rocket flies directly in the direction of the sight. The second activates the target acquisition system: after locking on, the rocket automatically adjusts its trajectory and pursues the selected target, which is especially useful against fast-moving objects and vehicles.

NOTES:

- Very high damage per rocket. - A large blast radius allows for simultaneous engagement of multiple targets.
- First mode: standard direct launch.
- Second mode: target acquisition and homing using the "fire and forget" principle.
- Effective at medium and long ranges.
- Particularly useful against moving vehicles and large targets.
- The magazine holds one missile, with a total of up to 10 missiles when the weapon is picked up.
- The weapon's heavy weight reduces the shooter's mobility.
