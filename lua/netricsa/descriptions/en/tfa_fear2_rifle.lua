PATTEN 470 ASSAULT RIFLE


WEAPON: Patten 470 Assault Rifle
AMMO:   5.56x45mm NATO
ROF:    600-750 rounds / min

DESCRIPTION:

A modern assault rifle developed for the armed units of the Armacham Technology Corporation. It features a gas-operated action with a gas piston, offering high reliability and good accuracy. It is equipped with an ACOG optical sight, which facilitates aiming at medium to long ranges.

The Patten 470 includes a fire-selector switch, allowing the user to toggle between semi-automatic and fully automatic fire. It uses 30-round magazines, and its high power and effective range make it well-suited for a variety of combat scenarios. The rifle's design incorporates features from several modern assault weapon systems.

NOTES:

- Equipped with an ACOG optical sight.
- The magazine holds 30 rounds; total ammunition capacity can reach 420 rounds.
- The design is largely based on the experimental XM8 rifle.
- Offers good range and high stopping power.
- While the sight aids in precise targeting, firing from the hip is sometimes more convenient in close-quarters combat.
