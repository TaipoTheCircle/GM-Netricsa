"GIMN USSSR" GUITAR


WEAPON: "GIMN USSSR" Guitar
AMMO:    Not required

DESCRIPTION:

An unusual guitar designed to perform the anthem of the Soviet Union. To activate it, simply wave your hand in the air, and the instrument will begin playing the musical composition on its own.

It plays the USSR anthem—featuring both the real-world version and the version from the game "Red Alert 3". It requires no strings, no musical skill, and not even any physical contact with the instrument.

NOTES:

- Plays the USSR anthem (real-world version and the "Red Alert 3" version).
- Activated by waving your hand in the air.
- No musical skills required.
