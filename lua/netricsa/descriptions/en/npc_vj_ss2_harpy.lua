ELLENIERIAN HARPY WITCH FROM THE ELLENIER


CLASS:      Ellenierian Harpy Witch
METABOLISM: Mammal
PERCEPTION: Primitive Warrior
SIZE:       4,9 ft
ENDURANCE:  Low
HOSTILITY:  Average
WEAPONS:    Magic Projectiles, Claws
REWARD:     50 FC
THREAT:     Low

DESCRIPTION:

Ellenierian Harpy Witches are very similar to their Scythian cousins, the main difference being that one species is extinct and the other is not.

Harpies are created from a mixture of chicken legs from a closed SFC (Syrian Fried Chicken) restaurant, floating creatures in capsules, the wings of Flying Kleere, and giant Pigeons from Brimland, among other parts.

They were originally planned to be made from sock models, but instead they were sent to guard Cecil the dragon.

They have two forms of attack: casting magical projectiles from a distance and striking with their claws in close combat.

An annoying creature that flies and irritates by flashing certain body parts. It has learned to carry various nasty creatures like kamikazes through the air, making it even more annoying.

TIPS:

- Destroy individual Harpies in close combat with a Sawed-Off Shotgun or melee weapons.
- Destroy large groups with a machine gun or a weapon with an area-of-effect effect.
- Small and medium groups can be destroyed with a sniper rifle from a distance.
