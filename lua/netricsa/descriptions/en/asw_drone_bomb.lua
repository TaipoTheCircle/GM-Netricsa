SWARM DRONE, ORBER


CLASS:      Swarm Drone, Orber
METABOLISM: Alien Arthropod
PERCEPTION: Assault Drone, Explosive Variant
SIZE:       5,58 ft
ENDURANCE:  Medium
HOSTILITY:  High
WEAPONS:    Claws, Jaws, Energy Spheres
REWARD:     300 FC
THREAT:     High

DESCRIPTION:

Orbers are a special variant of standard drones, distinguished by a brighter yellow coloration and an unusual defensive reaction. Otherwise, they retain the behavior and combat abilities of standard drones, attacking opponents in close combat and attempting to quickly close the distance.

The Orber Drone's main characteristic becomes apparent upon its death. After sustaining fatal damage, its body begins to emit an unstable energy reaction, causing numerous energy spheres to fly in all directions.

The spheres behave like Boomer projectiles: they fly outward, collide with surrounding objects, and explode on impact, damaging everything nearby. Therefore, destroying such a drone at close range can be almost as dangerous as the attack itself.

It is unknown whether the energy release is an intentional defensive reaction or a side effect of these creatures' unusual metabolism. For the swarm, however, this is of little importance: a dead Orber Drone turns its own death into a final blow to the enemy.

This is why fighters quickly learned to distinguish them from regular drones by their bright yellow color. If such an alien approaches a group, it is highly undesirable to destroy it at close range.

TIPS:

- Do not stand near it while it is being killed.
- Its bright yellow coloring allows you to distinguish an Orber Drone from a regular drone.
- If possible, destroy it from a distance.
- The Orbs are especially dangerous in narrow corridors, as they are much more difficult to avoid.
- If an Orber Drone is among other aliens, first assess the area around it: after its death, there will be virtually no safe zone left.
- After the Orbs appear, don't rush back to the corpse. Wait it out first or dodge the flying Orbs.
