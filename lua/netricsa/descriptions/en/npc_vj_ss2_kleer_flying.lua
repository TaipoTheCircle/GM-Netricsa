FLYING KLEER SKELETON FROM KLEER



CLASS:      Flying Kleer Skeleton
METABOLISM: Undead
PERCEPTION: Magical Creature
SIZE:       ~5,9
ENDURANCE:  Low
HOSTILITY:  High
WEAPONS:    Hellcannon Musket (Fireballs)
REWARD:     100 FC
THREAT:     Medium-High

DESCRIPTION:

These winged undead, also known as "Gargoyles", hail from everyone's favorite planet of death and lava-Kleer. Although weak and frail, like most creatures from Kleer, they are armed with a so-called hellcannon, which fires fireballs at enemies.

In reality, this variety was created by mistake when Mental bombarded their planet. Mental scientists discovered the remains of pigeons melted down from Clears, which gave them the idea of ​​creating a flying variant.

They imported giant pigeons from Brimland and, using "Skin-O-Master" technology, removed their skin and flesh and applied them to volunteer Clear soldiers. At a training camp, the newly created beings were forced to watch "Top Shotgun," from which they learned to control their wings and seduce women.

After a short four-year training period, the survivors became part of the Mental Air Force.

Flying Clears are similar in appearance to their regular counterparts, but with a few differences, such as normal feet instead of hooves, hands instead of claws, and a more humanoid head. They use the "Hell Cannon" musket as their weapon.

While a single Clear poses little threat, like most skeletons, they almost always travel in flocks (or, worse, hordes).

TIPS:

- If they're flying low enough, you can take them out with a shotgun blast.
- If they're far away, use a sniper rifle, explosives, or a rapid-fire weapon.
- Try to take them out quickly before you're overwhelmed by fireballs from all directions.
