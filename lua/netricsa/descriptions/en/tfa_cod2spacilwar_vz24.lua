MAUSER VZ. 24 RIFLE


WEAPON: Mauser Vz. 24 rifle
AMMO:   7.92x57mm Mauser
ROF:    ~15-20 rounds / min
WEIGHT: ~4,08 kg

DESCRIPTION:

A Czechoslovakian magazine-fed rifle, developed in 1924 based on the German Mauser 98 design. It was produced in Czechoslovakian arms factories from 1924 to 1944 and became one of the most famous Czechoslovakian rifles of the interwar period.

The rifle uses a longitudinally sliding rotating bolt and a 5-round magazine. The standard version was chambered for 7.92x57mm Mauser, although export versions chambered for other cartridges also existed. With a length of 1100 mm, the Vz. The Vz. 24 was somewhat shorter and more convenient than the classic Mauser 98.

The Vz. 24 was widely exported and saw service in a variety of conflicts. These rifles were used, among other things, in the Spanish Civil War and World War II. After occupying Czechoslovakia, German troops adopted the Vz. 24 under the designation Gewehr 24(t).

NOTES:

- A reliable and accurate rifle, well suited for medium and long ranges.
- A Czechoslovakian answer to the Mauser family, but in a more compact design.
- After occupying Czechoslovakia, the German army simply renamed the Vz. 24 the Gewehr 24(t) and sent it back into service.
