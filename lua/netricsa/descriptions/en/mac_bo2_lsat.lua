LSAT MACHINE GUN


WEAPON: LSAT Machine Gun
AMMO:   5.56x45mm NATO / 5.56mm caseless
ROF:    ~650 rounds/min

DESCRIPTION:

An American experimental machine gun developed as part of the Lightweight Small Arms Technologies (LSAT) program. The project began in 2004 with the goal of creating lighter small arms and ammunition for infantry. It was developed by a group of American defense companies under the leadership of the AAI Corporation.

The key feature of the LSAT is its ability to use two types of ammunition: conventional cased rounds and caseless rounds. The caseless version utilizes specialized ammunition that burns up completely upon firing, which significantly reduces the weight of the ammunition load carried by the soldier. The machine gun employs a belt-fed system and features a unique ammunition feed mechanism.

NOTES:

- Developed as a lighter alternative to the M249 machine gun.
- Caseless ammunition reduces the weight of the ammunition load by approximately 40%.
- The feed system holds 100 conventional rounds or 150 caseless rounds.
- A variant with a shortened 320mm barrel also exists.
