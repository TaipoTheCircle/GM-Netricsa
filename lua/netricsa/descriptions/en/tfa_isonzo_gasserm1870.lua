GASSER M1870 ARMY REVOLVER


WEAPON: Gasser M1870 Army Revolver
AMMO:   11.3x36mm R Gasser
ROF:    Single-action, 6-round capacity

DESCRIPTION:

An Austro-Hungarian army revolver, designed by gunsmith Leopold Gasser in 1870. It was intended primarily for use by the cavalry and other units of the Austro-Hungarian Army. It features a massive, open-frame design, a long barrel, and a large wooden grip. Due to its powerful cartridge, it possessed significant stopping power; however, its substantial size and weight made it a rather cumbersome sidearm.

It operates on a single-action mechanism, requiring the hammer to be cocked manually before each shot. It is fed from a six-round cylinder chambered for the 11.3x36mm R cartridge. Loading is performed via a hinged gate on the right side of the frame, while spent casings are ejected one by one using an extractor rod located beneath the barrel. The open-type sighting system consists of a front sight and a rear sight.

NOTES:

- Designed by Leopold Gasser in 1870.
- Served with the Austro-Hungarian cavalry.
- The cylinder holds 6 rounds.
- It weighs approximately 1.3 kg and has an overall length of 375 mm.
- Variants with shorter barrels also existed.
- The design served as the basis for subsequent models, including the Gasser-Kropatschek M1876.
- In the Balkans, Gasser-system revolvers became widespread, especially in Montenegro.
