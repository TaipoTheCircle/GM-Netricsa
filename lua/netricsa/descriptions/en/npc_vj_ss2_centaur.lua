CENTAUR, WARRIOR FROM ELLENIER


CLASS:      Centaur, Warrior
METABOLISM: Mammal
PERCEPTION: Tribal Warrior
SIZE:       12 ft
ENDURANCE:  Average
HOSTILITY:  Extreme
WEAPOON:    Bow And Arrow
REWARD:     150 FC
THREAT:     High

DESCRIPTION:

These are extremely aggressive and territorial tribal warriors from the planet Ellenier. They are often found in Elven territories, raiding their villages and plundering treasures.

They were initially no less hostile toward Mental's invasion forces until they were recruited into his army.

Mental discovered these creatures and was impressed by their unusual, male-dominated society, but initially found them weaklings. He took them, painted them with war paint, and gave them bows, arrows, and shields.

After certification, they were cleared for combat.

Centaurs quickly fire arrows at their target while trotting toward it. Don't underestimate them-despite their outdated weapons, they are still extremely dangerous and very fast.

TIPS:

- You can dodge their arrows by moving backward or to the side.
- They can catch up to you very quickly-destroy them from a distance.
- They will try to surround you; try not to let this happen if you don't want to be shot at from all sides.
