TOKAREV AUTOMATIC RIFLE MODEL 1940


WEAPON: Tokarev Automatic Rifle Model 1940
AMMO:   7.62x54 mm R
ROF:    ~25-30 (single) / ~700-800 (burst) rounds / min
WEIGHT: ~3,85 kg

DESCRIPTION:

This Soviet automatic rifle was developed in 1942 as an emergency replacement for the scarce light machine guns. Its design is a major modification of the famous SVT-40 semi-automatic rifle, adding a continuous fire mode.

The fire mode selector is integrated with the safety, allowing the shooter to instantly switch between precise single shots and devastating bursts. The weapon is fed from detachable 10-round box magazines, which can also be loaded from above using standard clips.

Despite its design, the AVT-40 proved too light for the powerful 7.62x54mm rifle cartridge. When firing in bursts, the rifle was literally torn from your hands, accuracy dropped, and the thin barrel and mechanism quickly wore out. Because of this, troops were only allowed to fire in bursts during the most critical moments of combat.

NOTES:

- It possesses the killing power of a Mosin rifle, but is capable of raining lead on the enemy with the speed of a submachine gun.
- The 10-round magazine capacity is the shooter's main headache. In automatic fire, the entire ammunition load is exhausted in less than a second.
- The insane recoil in full automatic mode makes the second and third bullets in a burst a gift for the birds. Shoot in short bursts.
- The weapon requires careful maintenance and high-quality lubrication. In the hands of an inexperienced fighter, the AVT-40 quickly turns into a capricious oar that refuses to reload.
