FOLDING KALASHNIKOV AKS-74 ASSAULT RIFLE


WEAPON: Folding Kalashnikov AKS-74 Assault Rifle
AMMO:   5.45x39mm
ROF:    ~600-650 rounds / min
WEIGHT: ~2,97 kg

DESCRIPTION:

A folding version of the AK-74 assault rifle, developed specifically for airborne troops and other highly mobile units. It was adopted in 1979. Unlike the standard AK-74, the AKS-74 features a folding metal stock, making it easier to transport and use in confined spaces.

The assault rifle uses the 5.45x39mm cartridge, has a 30-round magazine, and is capable of single-shot and automatic fire. Its rate of fire is approximately 600-650 rounds per minute. The effective range is estimated at approximately 300-400 meters.

