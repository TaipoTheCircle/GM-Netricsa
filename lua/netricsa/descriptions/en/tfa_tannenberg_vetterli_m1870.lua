VETTERLI-VITALI M1870/87 MAGAZINE RIFLE


WEAPON: Vetterli-Vitali M1870/87 Magazine Rifle
AMMO:   10.4x47mm R Vetterli
ROF:    ~15 rounds / min

DESCRIPTION:

An Italian magazine-fed rifle, created in 1887 by upgrading the single-shot Vetterli M1870. The development of this improvement was entrusted to artillery captain Giuseppe Vitali, who proposed equipping the rifle with a four-round box magazine. This modernization extended the service life of an otherwise aging design, bringing it closer to the requirements of modern infantry.

The rifle operates via a manually-operated, bolt-action mechanism. It chambers the 10.4x47mm R Vetterli cartridge and features an integral four-round box magazine. Loading is accomplished using a specialized clip—constructed from wood and metal—which is inserted entirely into the magazine and subsequently removed by pulling an attached cord. The rifle retains the core characteristics of the original model, including its large-caliber cartridge and iron sights. Later, some of these rifles were converted to chamber the 6.5x52mm Carcano cartridge and were redesignated as the Vetterli-Vitali M1870/87/15.

NOTES:

- Equipped with a four-round magazine designed by Giuseppe Vitali.
- Utilizes a specialized four-round clip featuring a pull-cord for removal.
- The rate of fire is approximately 15 rounds per minute.
- Suitable for engaging individual targets at medium to long ranges.
- Effective against unprotected personnel, though it falls short when compared to more modern rifles.
- During the First World War, some of these rifles were converted to chamber the 6.5x52mm Carcano cartridge.
