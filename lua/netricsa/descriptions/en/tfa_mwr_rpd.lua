DEGTYARYOV LIGHT MACHINE GUN (DP-27)


WEAPON: Degtyaryov Light Machine Gun (DP-27)
AMMMO:  7.62x54mm R
ROF:    ~500-600 rounds per minute

DESCRIPTION:

A Soviet light machine gun developed by firearms designer Vasily Alexeyevich Degtyaryov in 1927. It was adopted by the Red Army that same year and was intended to provide fire support for infantry units. It became one of the primary automatic weapons used by Soviet infantry during the Great Patriotic War. It is distinguished by its characteristic pan magazine, located on top of the receiver, and a wooden stock.

The weapon operates on a gas-actuated principle, with the breech locked by two locking flaps. It fires the 7.62x54mm R rifle cartridge and is fed from a flat, 47-round pan magazine. It features an air-cooled barrel, folding bipod, and iron sights. In 1944, an upgraded version, the DPM, was introduced, incorporating several design changes to improve reliability and ease of use.

NOTES:

- Effective against both groups and individual targets at medium ranges.
- Variants include the DA (for aircraft) and the DT (for tanks).
- Adopted for service in 1927.
- The pan magazine holds 47 rounds.
- Served as the primary light machine gun of the Red Army during the Great Patriotic War.
