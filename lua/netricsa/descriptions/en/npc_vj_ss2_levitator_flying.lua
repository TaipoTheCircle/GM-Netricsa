LEVITATOR, FLYING FROM THE MAGNOR


CLASS:      Levitator, Flying
METABOLISM: Manned Vehicle
PERCEPTION: Reconnaissance Vehicle
SIZE:       74,8 ft
ENDURANCE:  Low
HOSTILITY:  Medium
WEAPONS:    Plasma Cannon
REWARD:     150 FC
THREAT:     Medium

DESCRIPTION:

These are hovercraft designed to patrol Mental's forward bases and scout ahead of the main army. Their engines allow them to navigate any terrain without issue and even fly at low altitude. However, to levitate, they require a lightweight frame, so they have very light armor.

It appears to be an alien humanoid woman with blue skin, suspended within a translucent sphere containing some kind of liquid. This alien may be harmless on its own, but she's in a transport equipped with a plasma cannon, which, like all cannons, will try to finish you off. The spherical structure can hover, allowing it to move freely through the air.

The Levitator capsules were developed after Mental acquired the Magnor, as he needed something to search the swamps and locate the Medallion. Leaving nothing to chance, Mental also designed the capsules to operate underwater. However, due to the high cost of Zombie Soldiers at Toyodo's factories in Hell, Mental had to downgrade the quality of the material used to make the capsules, making them out of cheap, fragile glass.

The Levitators fire their low-power plasma cannons at enemies. They serve primarily as a distraction for the main army, so they should be fairly easy to destroy.

A distinctive feature is the Levitator's ability to regenerate its health. But again, this happens slowly, so the faster you destroy it, the more likely it will be unable to regenerate.

TIPS:

- Avoid their attacks by dodging to the side.
- They have very light armor; a few bullets or any explosive will be enough to solve this problem.
- A shotgun blast from close range is enough to dispatch them.
- Some of them can fly, while others stay close to the ground.
