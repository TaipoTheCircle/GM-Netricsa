BRIGGS SMG


WEAPON:    Briggs SMG
AMMO:      .40 S&W / 9x19mm
ROF:       ~750 rounds/min

DESCRIPTION:

A modern submachine gun based on the design of the Heckler & Koch UMP. It features high accuracy, moderate power, and a solid rate of fire. The weapon is equipped with a red-dot sight that includes a target-recognition system, which changes the color of the reticle when aimed at an enemy.

The Briggs SMG uses 35-round magazines and is capable of fully automatic fire. Thanks to its excellent handling, it is effective in both close-quarters and medium-range combat. However, its ammunition is not particularly effective against heavy armor.

NOTES:

- Based on the German Heckler & Koch UMP submachine gun.
- The sight is capable of distinguishing between enemies and allies.
- The fire selector includes a setting for single-shot fire, even though the weapon only fires in bursts or fully automatically.
