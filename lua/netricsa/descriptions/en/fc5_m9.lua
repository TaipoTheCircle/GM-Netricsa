DESCRIPTION:

The Beretta M9 is the American military version of the Italian Beretta 92F pistol. In 1985, it won the XM9 competition for a new 9mm military pistol, replacing the legendary M1911A1. In 1990, the M9 was officially adopted by the US Armed Forces and has been used in American military operations around the world.

The pistol fires the 9x19mm Parabellum cartridge and uses a 15-round magazine. The M9 is distinguished by its distinctive open-top slide, good accuracy, and high reliability. Since 2017, the US military has gradually replaced the M9 with the M17 and M18.

NOTES:

- Won the competition to replace the M1911A1 and became the US Army's primary pistol.
- Well-suited for accurate shooting at short and medium ranges.
- The distinctive open bolt makes the Beretta M9 one of the most recognizable Beretta models.
