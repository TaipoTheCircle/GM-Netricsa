GEWEHR 88/05 "KOMMISSIONSGEWEHR" INFANTRY RIFLE


WEAPON: Gewehr 88/05 "Kommissionsgewehr" Infantry Rifle
AMMO:   7.92x57mm Mauser
ROF:    ~12 rounds / min

DESCRIPTION:

A German magazine-fed rifle, this is an upgraded version of the Gewehr 1888, which was originally developed by the German Rifle Testing Commission (*Gewehr-Prüfungskommission*). The modernization, which began in 1905, was intended to adapt the older rifles for use with the new pointed-bullet cartridge, the *S-Patrone*. The loading system was also modified, allowing the rifle to utilize standard five-round Mauser stripper clips. It was used by the German Army during the First World War alongside the more modern Gewehr 98.

The rifle operates via a manually-operated, bolt-action mechanism and chambers the 7.92x57mm Mauser cartridge. It is fed from an internal box magazine with a 5-round capacity, loaded from the top using a stripper clip. Unlike the original Gewehr 1888—which used a Mannlicher-style *en-bloc* clip—this upgraded version features guides for Mauser stripper clips and a closed-off opening where the empty *en-bloc* clip would have been ejected. It is equipped with a long barrel encased in a protective sleeve, a wooden stock, and iron sights.

NOTES:

- Effective against individual targets at medium to long ranges.
- The magazine holds 5 rounds.
- It uses the pointed S-Patrone cartridge.
- Approximately 350,000 Gewehr 88 rifles were converted to the 88/05 standard.
