KALASH ASSAULT RIFLE


WEAPON: Kalash Assault Rifle
CARBON: 7.62x39mm
ROF:    ~600 rounds/min.

DESCRIPTION:

A Soviet assault rifle based on the Kalashnikov assault rifle. A powerful and reliable automatic weapon chambered for the 7.62x39mm cartridge. Its high power and good rate of fire make the Kalash particularly effective at close and medium ranges.

NOTES:

- Well suited for close and medium range combat.
- A powerful cartridge allows for serious damage to enemies.
- Its robust design makes it a versatile weapon.
