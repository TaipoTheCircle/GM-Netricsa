M1 "BAZOOKA" ANTI-TANK GRENADE LAUNCHER


Weapon:     M1 "Bazooka" Anti-Tank Grenade Launcher
Cartridges: 60mm Rocket-Propelled Anti-Tank Grenades
Rate:      ~4-6 rounds / min
Weight:    ~6,8-8 kg

DESCRIPTION:

This American hand-held anti-tank grenade launcher was developed in 1942. It featured a double-ended launch tube with an electrically ignited system and was primarily designed for use against armored vehicles. The M1 entered service with the US Army in 1942 and was used beginning with the North African Campaign.

The grenade launcher fires 60mm rocket-propelled grenades with a shaped-charge warhead. Unlike a conventional recoilless rifle, the grenade is equipped with a rocket propellant that accelerates it as it moves along the launch tube. The maximum range was approximately 365 meters, and the effective range was approximately 135 meters.

One of the early features of the M1 was its electric ignition system. The batteries and indicator light were located inside the shoulder rest, so the system allowed for checking for electrical contact before firing.

Later, improved variants appeared, including the M1A1, M9, and M9A1, and the larger 88.9mm caliber M20 "Super Bazooka" was developed further.

NOTES:

- Primary purpose: anti-armored vehicles and fortifications.
- Most effective at relatively close ranges, where it's easier to hit the target.
- The electric ignition mechanism makes the M1 a rather unusual weapon for its time.
- The name "Bazooka" comes from the resemblance of the launch tube to an unusual brass instrument popularized by American comedian Bob Burns.
