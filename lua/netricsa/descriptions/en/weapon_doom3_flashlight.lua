FLASHLIGHT


WEAPON: Flashlight
AMMO:   Batteries
ROF:    60 BPH

DESCRIPTION:

A compact handheld flashlight designed for illuminating dark spaces and searching for objects in low-visibility conditions. It is battery-powered and can be used independently of other equipment.

Despite its simplicity, the flashlight significantly facilitates navigation in dark places. Its small size allows you to carry it with you at all times. It can also be used to pummel weaker enemies.

NOTES:

- Helps illuminate dark spaces.
- Battery-powered.
- Allows you to spot objects and enemies in the dark.
- Provides a useful weapon for beating up enemies when you're out of ammo.
