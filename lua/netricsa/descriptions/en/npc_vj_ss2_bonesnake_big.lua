BONE SNAKE, LARGE FROM THE KLEER


CLASS:      Bone Snake, Large
METABOLISM: Undead
PERCEPTION: Magical Creature
SIZE:       88,5 ft
ENDURANCE:  High
HOSTILITY:  Extreme
WEAPONS:    Fireballs
REWARD:     500 FC
THREAT:     High

DESCRIPTION:

Bone Snakes inhabit the caves of the planet Kleer - they are the monstrous creations of Count Kleerofski himself. They are imbued with greater magical energy than most skeletons, and therefore capable of belching fireballs.

Like a bad fish, the snake is full of small bones that can easily damage you if you dare approach it, or if it doesn't crawl to you.

Although they may appear motionless, they can actually move, though rarely. Can you blame them? Imagine having to jump with every step!

Their long, protruding tongue will tease us, which we must use to destroy these archaeological artifacts.

TIPS:

- Their slow projectiles are easy to avoid by dodging to the side.
- They should be low-priority targets among other enemies.
- Destroy them with explosives or any heavy weapon.
