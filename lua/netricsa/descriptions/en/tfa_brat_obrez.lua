MR-43-SO "Brat-2" BLANK-FIRING SAWED-OFF SHOTGUN


WEAPON: MR-43-SO "Brat-2" Blank-Firing Sawed-Off Shotgun
AMMO:   7.62x54R Blank (Noise / Flash) Cartridges
ROF:    Two Cartridges, Manual Reloading

DESCRIPTION:

A blank-firing, double-barreled firearm manufactured by "Kurs-S" LLC, based on the IZh-43 smoothbore shotgun. It is a shortened version of a classic double-barreled shotgun, featuring distinctive wooden furniture. The model gained fame due to its resemblance to the sawed-off shotgun used by the character Danila Bagrov in the film "Brother 2" ("Brat 2").

The weapon features two barrels, two triggers, and a break-action reloading mechanism. It uses 7.62x54R blank cartridges, which produce a loud report accompanied by smoke and a muzzle flash. It has a capacity of two cartridges. To prevent the use of live ammunition, the barrels are equipped with internal obstructions (baffles).

NOTES:

- Features two barrels and two triggers.
- Reloading is performed by breaking open the barrels.
- An automatic safety engages during the reloading process.
