ORO WAR HORSE MINIGUN


WEAPOON: ORO War Horse Minigun
AMMO:    Large-caliber rounds
ROF:     ~950 rounds per minute
WEIGHT:  ~18 kg

DESCRIPTION:

A heavy, multi-barrel machine gun developed by ORO and used by heavy weapons units. The weapon fires a continuous stream of large-caliber bullets and is highly powerful, but has a noticeable spread.

The barrels must be spun up for a few seconds before firing. They can be spun up in advance to open fire almost instantly when a target appears. The large magazine allows for extended periods of continuous fire without the need to reload.

The alternate mode transforms the War Horse into an autonomous ground turret. Once deployed, it independently fires at enemies and provides cover fire without the need for constant gunner control.

NOTES:

- Very high rate of fire and fire density.
- The barrels must be spun up before firing.
- Effective at medium and long ranges, despite a noticeable spread.
- The magazine holds 250 rounds, and the total ammunition capacity can reach 1000 rounds.
- The second mode turns the weapon into an autonomous machine gun turret.
- Its heavy weight reduces the user's mobility.
- Particularly dangerous against groups of enemies: a continuous stream of high-caliber bullets quickly suppresses an entire position.
