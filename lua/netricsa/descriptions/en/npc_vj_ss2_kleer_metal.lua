KLEER SKELETON, METAL


CLASS:      Kleer Skeleton, Metal
METABOLISM: Undead
PERCEPTION: Magical Creature
SIZE:       9 ft
ENDURANCE:  Very High
HOSTILITY:  Medium
WEAPONS:    Two-Ball Projectiles, Claws, Horns
REWARD:     500 FC
THREAT:     High

DESCRIPTION:

A rare variant of the Kleer Skeleton, composed not of bone, but of metal and numerous spikes.

Mental deemed ordinary bone insufficient for creating a more durable Kleer Skeleton, so he decided to design a metal version. Despite its unusual material, the Metal Kleer retains the same shape and behavior as its bony counterpart.

Thanks to its metal construction, it is significantly tougher than the standard Kleer Skeleton. It cannot be killed simply by inflicting a fatal wound; the Metal Kleer only dies once its body has been completely shattered.

TIPS:

- Do not stop firing until the metal structure completely falls apart.
- Its metal body is significantly tougher than the bones of a standard Kleer Skeleton.
- If it is still moving after sustaining massive damage, you need to smash it even harder.
- The Minigun remains your best friend; it just has to work a little longer this time.
