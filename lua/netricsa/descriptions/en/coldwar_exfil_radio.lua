EXFIL RADIO


WEAPON: Exfil Radio
AMMO:   Not Required
ROF:    Helicopter Extraction

DESCRIPTION:

A portable radio unit designed to summon an extraction helicopter. The device allows you to contact pilots and request an emergency evacuation from the operational zone. Once the signal is transmitted, a helicopter with a two-person flight crew arrives to pick up any nearby personnel.

The helicopter arrives approximately 40 seconds after being called and remains on-site for 40 seconds, waiting for passengers to board. After this time, it departs the extraction zone regardless of how many people have been rescued. Those who fail to board in time will perish, so it is highly advised not to delay.

NOTES:

- Simply use the radio to request an extraction.
- The helicopter arrives in approximately 40 seconds.
- The flight crew consists of two pilots.
- The helicopter remains on the ground for 40 seconds.
- Once the waiting period ends, the helicopter departs; any personnel left behind will perish.
- The radio functions as a transceiver, designed for rapid, real-time communication.
