MAS-36 BOLT-ACTION RIFLE


WEAPON: MAS-36 Bolt-Action Rifle
AMMO:   7.5x54mm French
ROF:    10 rounds per minute

DESCRIPTION:

A French bolt-action rifle developed by a design team led by Captain Monteil and adopted for service in 1936. It was manufactured by the state-owned arms enterprise *Manufacture d'armes de Saint-Étienne* (MAS). It was intended to replace the obsolete Lebel and Berthier rifles. It is distinguished by the unusual shape of its bolt handle—curved forward and downward—as well as a simple, robust design engineered for use in demanding conditions.

The rifle operates via a manually-operated, rotating bolt mechanism. It chambers the 7.5x54mm French rifle cartridge and features an integral 5-round box magazine. It is loaded from the top, either using a stripper clip or by inserting individual rounds. It is equipped with a diopter (aperture) sight and a cruciform-section spike bayonet, which is stored in a dedicated channel beneath the barrel. While the rifle is reliable and accurate, its rate of fire is inferior to that of semi-automatic weapons.

NOTES:

- Well-suited for engaging individual targets at medium to long ranges.
- Not intended for use against armored vehicles or heavily armored targets.
- Effective firing range is approximately 400 meters.
- A paratrooper variant, the CR39, was produced, featuring a folding aluminum stock.
- The powerful rifle cartridge ensures high effectiveness against unarmored personnel.
