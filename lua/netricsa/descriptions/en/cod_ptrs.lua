PTRS-41 ANTI-TANK RIFLE


WEAPON: PTRS-41 Anti-Tank Rifle
AMMO:   14.5x114 mm
ROF:    ~15 rounds / min
WEIGHT: ~20,9 kg

DESCRIPTION:

This Simonov anti-tank self-loading rifle, model 1941, is a Soviet anti-tank weapon designed to combat light and medium tanks, armored vehicles, and fortified firing positions. It was adopted by the Red Army in 1941.

The rifle uses a gas-operated system and fires a powerful 14.5x114 mm armor-piercing cartridge. After firing, the system automatically reloads the weapon, eliminating the need for the shooter to manually operate the bolt after each shot. The PTRS has a five-round magazine with a single-shot loading mechanism.

Despite its enormous weight of almost 21 kg, the PTRS was designed for relatively mobile anti-tank use. Best results were achieved at ranges of approximately 300-400 meters, and the rifle could also be used against armored firing points.

NOTES:

- At close and medium ranges, it can seriously damage light armored vehicles and armored targets.
- It performs best at approximately 300-400 meters, where it combines tremendous power with acceptable accuracy.
- Its weight of almost 21 kg makes carrying the PTRS a separate combat task.
- This is a case where the rifle can be used as an anti-tank weapon, and the enemy gains a great deal of respect for the 14.5 mm caliber after the first shot.
