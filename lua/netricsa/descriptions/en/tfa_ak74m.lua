KALASHNIKOV AK-74M ASSAULT RIFLE


WEAPON: Kalashnikov AK-74M Assault Rifle
AMMO:   5.45x39mm
ROF:    ~600 rounds / min
WEIGHT: ~3,4 kg

DESCRIPTION:

A Soviet and Russian assault rifle, developed as a modernized version of the AK-74. It was adopted in 1991 and became one of the main assault rifles of the Russian Armed Forces. The AK-74M retains the reliability characteristic of the AK family but has received a number of improvements, including a folding plastic stock and a side rail for mounting optical and night sights.

The assault rifle uses the 5.45x39mm cartridge and a 30-round magazine. Thanks to the relatively light cartridge weight and moderate recoil, the AK-74M is easy to control when firing in bursts. The design is designed for operation in a variety of climatic conditions.

NOTES:

- The standard Russian assault rifle in the AK family for many years.
- The 5.45x39mm cartridge produces less recoil than the 7.62x39mm.
- The side rail allows for the installation of various sights.
- The AK-47 was the grandfather, the AK-74 became the son, and the AK-74M arrived at the family council with a folding stock.
