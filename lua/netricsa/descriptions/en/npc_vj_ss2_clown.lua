MARCEL THE CLOWN FROM THE ORAZIO


CLASS:      Marcel the Clown
METABOLISM: Mammal
PERCEPTION: Trained clone
SIZE:       5,9 ft
ENDURANCE:  Low
HOSTILITY:  Extreme
WEAPONS:    Dynamite Pies
REWARD:     450 FC
THREAT:     Extreme

DESCRIPTION:

Marcel the Clown was a former performer who ran the show "Vasaro's Traveling Circus!", also known as "Vasaro's Freak Show," on Sirius. Initially very successful, attendance declined over time until his show was canceled.

With no money, no social support, and no home, Marcel was desperate to take on any job. Mental offered him payment in exchange for creating an army of clones trained to entertain Mental's soldiers, charge at enemies, and explode.

Marcel reluctantly agreed. Now he spends the rest of his life training his clones to make people laugh, ride unicycles, and feign happiness and contentment in Mental's service.

TIPS:

- They can quickly catch up to you and explode - destroy them as quickly as possible.
- This clown has suffered too much internal suffering.
