"UBOYNIK" (KILLER) SEMI-AUTOMATIC SHOTGUN


WEAPON: "Uboynik" (Killer) Semi-Automatic Shotgun
AMMO:   12x70 mm
ROF:    Semi-Automatic, 6-round capacity

DESCRIPTION:

A homemade semi-automatic shotgun, crafted by the Order's gunsmiths following the nuclear war. It features an unconventional design with an exposed revolving cylinder that holds six 12-gauge shells. Instead of a traditional feeding system, it utilizes a unique mechanism with spring-loaded clips to secure the ammunition. It delivers high stopping power at close range and is primarily intended for combat against mutants or adversaries in confined spaces.

The weapon operates via a short-recoil barrel system combined with a toggle-link locking mechanism. After each shot, the action ejects the spent casing and advances the next shell from the cylinder. In the standard configuration, reloading is performed manually—one shell at a time—which is a time-consuming process. Later modifications allow for the use of high-capacity drum or box magazines.

NOTES:

- The standard version utilizes an exposed, six-round revolving cylinder.
- Magazines with capacities of 3, 6, 10, and 20 rounds are available.
- A unique variant equipped with a bayonet exists.
- Supports the attachment of a red-dot sight, infrared scope, suppressor, and laser designator.
- Capable of firing incendiary ammunition.
- The design is reminiscent of revolving-cylinder shotguns such as the Protecta and the MTs-255.
