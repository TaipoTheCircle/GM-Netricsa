BERTHIER 1907/15 INFANTRY RIFLE


WEAPON: Berthier 1907/15 Infantry Rifle
AMMO:   8x50mm R Lebel
ROF:    ~15-20 rounds / min

DESCRIPTION:

A French magazine-fed rifle based on the Berthier system, adopted for service in 1915. It was designed to equip infantry units of the French Army during the First World War. It features a bolt-action mechanism, a wooden stock, and a distinctive Mannlicher-style magazine. It became one of the primary variants of the Berthier rifle series used by the French Army throughout the war.

The rifle operates via a manually-operated bolt-action mechanism and chambers the powerful 8x50mm R Lebel rifle cartridge. It is fed from an internal box magazine with a 3-round capacity, which is loaded using a specialized en-bloc clip. Once the ammunition is expended, the clip is ejected through an opening at the bottom of the receiver. It is equipped with open iron sights and a bayonet mount. In 1916, the M1916 variant was introduced, featuring an enlarged 5-round magazine.

NOTES:

- Effective against individual targets at medium to long ranges.
- The magazine holds 3 rounds.
- Uses a Mannlicher-style en-bloc clip.
- Employed by the French Army during both the First and Second World Wars.
