COMBINE CRAB-SYNTH


CLASS:      Combine Crab-synth
METABOLISM: Biomechanical Synthetic
PERCEPTION: Heavy Assault Unit
SIZE:       7,2 ft
ENDURANCE:  High
HOSTILITY:  Extreme
WEAPONS:    Retractable Minigun, Claws, Ram
REWARD:     800 FC
THREAT:     Very High

DESCRIPTION:

The Crab-synth is an Combine heavy combat vehicle designed to suppress well-armed enemy groups and breach fortified positions. Despite its relatively squat build, the synthet possesses considerable mass and is capable of quickly moving across rough terrain using several powerful limbs.

The main feature of this entity is its retractable minigun, concealed within its hull. Upon detecting a target, the weapon mechanism deploys, unleashing a dense stream of fire on the enemy. The minigun is particularly effective against groups of infantry, light vehicles, and targets that remain in one place for too long.

In close combat, the Crab Synthent can use its own limbs as weapons. However, its primary role is not to hunt alone, but to support other synths. It typically operates in conjunction with Combine Assault Synths, which provide flanking cover and prevent the enemy from focusing all of its fire on the heavy vehicle.

This tactic makes encounters with them particularly frustrating: while the Assault Synths keep the enemy on the move, the Crab Synthent methodically rakes the area with fire from its minigun. The Combine seems to really enjoy solving tactical problems by the "put another gun in."

TIPS:

- Don't try to out-shoot a minigun in the open.
- Constantly change positions, especially if the synth has already deployed its weapon. - First, eliminate the accompanying Assault Synths if they interfere with your fire concentration.
- Use cover and attack from the flanks or rear.
- Powerful explosive weapons are especially effective against heavy hulls.
- If a Crab Synth is left alone, don't relax: its firepower still allows it to quickly turn an open area into a very difficult place to walk.
