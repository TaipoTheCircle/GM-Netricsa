NIKONOV AN-94 "ABAKAN" ASSAULT RIFLE


WEAPON: Nikonov AN-94 "Abakan" Assault Rifle
AMMO:   5.45x39 mm
ROF:    ~600 / 1800 rounds per minute

DESCRIPTION:

A Russian assault rifle developed by Gennady Nikonov as part of the "Abakan" program. It was created as a potential replacement for the AK-74 family of rifles. It features a unique automatic mechanism with a "shifted recoil impulse," which significantly improves accuracy when firing in short bursts.

The defining characteristic of the AN-94 is its two-round burst mode, which fires at a rate of 1,800 rounds per minute. The first and second rounds are discharged almost simultaneously—before the recoil can noticeably affect the weapon's position. In standard fully automatic mode, the rate of fire is approximately 600 rounds per minute. It is compatible with 30- and 45-round magazines from the AK-74, as well as specialized 60-round quad-stack magazines.

NOTES:

- Known as the "Abakan," named after the city where its trials took place.
- The magazine is positioned at a slight angle to the right, a result of its unconventional ammunition-feeding system.
- The two-round burst allows the shooter to land two hits on target almost before the recoil is even felt.
- The design proved so complex and expensive that the AN-94 could not fully replace the AK-74 family.
- Essentially a technical experiment that happened to be fitted with a stock and turned into an assault rifle.
