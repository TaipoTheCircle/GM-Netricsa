ROTH-STEYR M1907 SEMI-AUTOMATIC PISTOL


WEAPON: Roth-Steyr M1907 Semi-Automatic Pistol
AMMO:   8x18mm Roth-Steyr
ROF:    Semi-automatic, 10-round capacity

DESCRIPTION:

An Austro-Hungarian semi-automatic pistol, developed by Czech designer Karel Krnka with the participation of Georg Roth. It was adopted by the cavalry of the Austro-Hungarian Army in 1907 under the official designation *Repetierpistole M.7* and entered service with the troops in 1909. It is considered one of the first semi-automatic pistols to be adopted by a major military power. It was manufactured at the Steyr facilities in Austria and the FEG facilities in Hungary.

The pistol operates on a short-recoil principle, with locking achieved by rotating the barrel approximately 90 degrees. It uses a specific 8x18mm Roth-Steyr cartridge and features a fixed 10-round box magazine housed within the grip. Loading is performed from the top—with the bolt held open—using a specialized stripper clip. The trigger mechanism has an unusual design with a heavy trigger pull, intended to enhance safety when used while mounted on horseback. There is no manual safety.

NOTES:

- One of the first semi-automatic pistols to be adopted by a major military power.
- The 10-round magazine is fixed and is loaded from the top using a specialized stripper clip.
- A heavy trigger pull reduced the likelihood of an accidental discharge while riding on horseback.
- Effective against individual, unarmored targets at close range.
- Used during the First World War, with some examples remaining in service as late as the Second World War.
