ARISAKA TYPE 38 BOLT-ACTION RIFLE


WEAPON: Arisaka Type 38 Bolt-Action Rifle
AMMO:   6.5x50mm SR Arisaka
ROF:    ~10-15 rounds/min

DESCRIPTION:

A Japanese bolt-action rifle, developed in 1905 based on the earlier Type 30 model under the supervision of General Nariake Arisaka. It was adopted by the Imperial Japanese Army that same year. Intended for infantry units, it gradually became the primary service rifle of the Japanese military. Compared to its predecessor, it featured an improved bolt, enhanced reliability, and a dust cover for the receiver to protect against dirt and debris.

The rifle utilizes a manually operated, rotating bolt-action mechanism. It chambers the 6.5x50mm SR Arisaka cartridge and features an internal 5-round box magazine, which is loaded using stripper clips. It is equipped with a wooden stock, open iron sights, and a bayonet mount. Thanks to its long barrel and relatively mild recoil, it offers good accuracy and is comfortable to fire.

NOTES:

- Well-suited for engaging individual targets at medium to long ranges.
- Effective against unarmored personnel.
- Features moderate recoil and good accuracy.
- Not intended for use against armored vehicles or heavy fortifications.
- Saw service during both World War I and World War II.
- There was a shortened version, the Type 38 Carbine.
- The Type 97 sniper rifle was developed based on it.
