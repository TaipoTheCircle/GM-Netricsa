ASSAULT RIFLE


WEAPON: Assault Rifle
AMMO:   Tungsten Flechette Rounds
ROF:    High, Automatic

DESCRIPTION:

The standard-issue assault rifle of the Earth Defense Force (EDF). It serves as the primary weapon for EDF infantry units, designed for sustained automatic fire against enemy personnel. It features a high rate of fire, good accuracy, and is highly effective in engagements at close to medium ranges. It is also found in the arsenals of the Red Faction insurgents and the Marauders.

It does not use standard 40mm rounds; instead, it fires specialized tungsten flechette (dart-like) projectiles. It is fed by a 40-round box magazine. The weapon features an automatic firing mode, as well as a secondary melee attack that allows the user to strike an opponent with the butt of the rifle. Ammunition is widely available, making it easy to resupply.

NOTES:

- Effective against infantry at close to medium ranges.
- Magazine capacity: 40 rounds.
- Uses tungsten flechette (dart-like) ammunition.
- The primary standard-issue weapon for EDF infantry.
- Includes a secondary melee attack (butt-strike).
