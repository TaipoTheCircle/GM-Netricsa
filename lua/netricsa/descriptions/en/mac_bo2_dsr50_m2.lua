DSR-50 LARGE-CALIBER SNIPER RIFLE


WEAPON: DSR-50 Large-Caliber Sniper Rifle
AMMO:   12.7x99mm NATO (.50 BMG)
ROF:    ~10-15 rounds/min

DESCRIPTION:

A German large-caliber sniper rifle developed by DSR-Precision GmbH under the leadership of Ingolf Reuter in 2003. It is an enlarged version of the DSR-1, adapted to fire the powerful .50 BMG cartridge. Its bullpup configuration allows for a relatively compact overall length while accommodating a long 800mm barrel.

The rifle features a hydraulic recoil buffer in the stock and a specialized muzzle device-a "Blast Compensator"-that functions as both a muzzle brake and a suppressor. It is also equipped with an adjustable stock, a bipod, a rear monopod (support under the stock), and mounts for optical sights. It is fed by a detachable 3-round magazine.

NOTES:

- Fires the powerful, large-caliber .50 BMG cartridge.
- The muzzle device helps reduce both recoil and muzzle flash.
- Despite its bullpup design, it weighs approximately 10.3 kg (unloaded).
- The long barrel ensures high accuracy at long ranges.
- Holds three rounds per magazine; every shot truly commands respect.
