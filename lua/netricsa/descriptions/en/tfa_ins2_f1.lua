F-1 HAND FRAGMENTATION GRENADE


WEAPON: F-1 Hand Fragmentation Grenade
AMMO:   One Grenade
ROF:    One Throw Per Minute

DESCRIPTION:

A Soviet defensive hand fragmentation grenade, developed in 1939 by designer Fyodor Ivanovich Khrameev, based on the French F-1 grenade (Model 1915). It is designed to neutralize enemy personnel through the fragmentation of its casing. It features a distinctive cast-iron body with a ribbed surface, which earned it the nickname "limonka" (little lemon). It was used by the Red Army during the Great Patriotic War and subsequently became one of the most recognizable pieces of Soviet weaponry.

The primary components include a cast-iron body, an explosive charge, and a time-delay fuze. Over the years, various fuzes were used, including the Koveshnikov, UZRG, and UZRGM models. The grenade became widespread due to its relatively simple design and mass production. It remained in service long after the end of the Second World War.

NOTES:

