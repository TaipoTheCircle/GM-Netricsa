SHO SERIES-3 COMBAT PUMP-ACTION SHOTGUN


WEAPON: SHO Series-3 Combat Pump-Action Shotgun
AMMO:   10-gauge
ROF:    ~90 rounds/min

DESCRIPTION:

A powerful combat pump-action shotgun developed by the Armacham Technology Corporation (ATC). Designed for engaging adversaries at close range, it features a smoothbore barrel with a cylinder choke and an 8-round tubular magazine. Chambered for 10-gauge shells, it delivers exceptional stopping power.

The SHO Series-3 is highly potent, though it suffers from a limited effective range and a wide shot spread. It is reloaded manually, one shell at a time. The weapon is equipped with tritium-illuminated iron sights and a "LIGHTBRINGER" tactical flashlight. It is primarily utilized by heavily armed ATC units.

NOTES:

- Uses 10-gauge ammunition, which is more powerful than the more common 12-gauge.
- The magazine holds 8 shells.
- Its design incorporates elements reminiscent of both the Remington 870 and the Benelli M4.
- Capable of dealing approximately one-third more damage per shot than the Vollmer Ultra92.
- Reloads one shell at a time-but then again, every shot serves as a potent reminder of why shotguns were invented in the first place.
