STAR SI-35 SUBMACHINE GUN


WEAPON: Star Si-35 Submachine Gun
AMMO:   9x23mm Largo
ROF:    300/700 rounds / min
WEIGHT: ~3,8 kg

DESCRIPTION:

This Spanish submachine gun was developed by Star Bonifacio Echeverria in 1935. It was created for the Spanish armed forces and featured a rather unusual design for its time. Its frame combined metal parts with a wooden stock, and the barrel was housed within a distinctive cylindrical casing.

The Si-35 uses a slow-blowback system and fires from an open bolt. The weapon's main feature is its separate rate of fire selector: the shooter could select single-shot fire, approximately 300 or 700 rounds per minute.

The design was considered fairly reliable, but it was complex and expensive to manufacture. The weapon was produced in limited quantities and eventually gave way to simpler designs. A small number of Si-35s were used in Spain during the final months of the Civil War.

NOTES:

- Three firing modes allow for different uses of the weapon: single shots for precision, 300 rounds per minute for controlled fire, and 700 for continuous bursts.
- The design was quite complex for its class, which was one of the reasons for abandoning further development of the Si-35.
- The weapon had a rifle-type bayonet mount, which is quite substantial for a submachine gun.
- A Spanish submachine gun with three firing rates: even the gun decided that sometimes you want to shoot a little more calmly.
