DESCRIPTION:

A French combat dagger developed during the First World War for use in trench warfare. It was based on earlier trench knives and bayonets, with a design proposed by the knifemaker Astier-Prodon. It was adopted for service in 1916. Intended for close-quarters combat within the confines of trenches, it earned the nickname "Le Vengeur", which translates to "The Avenger."

It features a sturdy, double-edged blade with a diamond-shaped cross-section, a wooden handle, and a metal crossguard to protect the hand. The total length is approximately 28 cm, with a blade length of about 17 cm. Some examples bear the inscription "Le Vengeur de 1870", a reference to France's defeat in the Franco-Prussian War. It was manufactured by several French firms.

NOTES:

- Effective exclusively in close-quarters combat.
- Blade length is approximately 17 cm.
- Weight is approximately 200 grams (excluding the scabbard).
- Used by French infantry and the crews of early tanks.
