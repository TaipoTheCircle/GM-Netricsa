BERETTA M1934 PISTOL


WEAPON: Beretta M1934 Pistol
AMMO:   9x17mm Browning Short (.380 ACP)
ROF:    ~30-40 rounds / min
WEIGHT: ~0,605 kg

DESCRIPTION:

This Italian semi-automatic pistol was developed by Beretta and adopted in 1934. It was designed as a compact military sidearm and was widely adopted by the Italian armed forces. Production continued for decades, with over a million units produced.

The pistol uses a blowback action and Beretta's signature open-top slide, leaving most of the barrel visible. The barrel is fixed during firing, and the pistol itself is characterized by its simple design and ease of maintenance.

The M1934's primary ammunition is the 9x17mm. There was also a closely related variant, the Beretta M1935, chambered for the 7.65x17mm cartridge. The M1934 was used by the Italian army in World War II, and some captured examples were used by other countries.

NOTES:

- A compact and lightweight pistol, well-suited for close-quarters combat.
- The open-top slide has become one of the most recognizable features of classic Beretta pistols.
- The M1934 was produced in huge quantities and remained in production for many decades.
- This pistol even made an appearance in Soviet cinema: it was wielded by the main character, Semyon Semyonovich Gorbunkov, in "The Diamond Arm".
