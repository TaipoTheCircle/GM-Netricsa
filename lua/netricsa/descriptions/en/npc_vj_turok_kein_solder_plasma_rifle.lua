MENDEL-GRUMAN ELITE SOLDIER


CLASS:      Mendel-Gruman Elite Soldier
METABOLISM: Human, Male
PERCEPTION: Heavy Infantry
SIZE:       5,9 ft
ENDURANCE:  High
HOSTILITY:  Very High
WEAPONS:    ORO L66 Pulse Rifle, Pulse Grenades
REWARD:     600 FC
THREAT:     Very High

DESCRIPTION:

Mendel-Gruman Elite Soldiers are a beefed-up version of the corporation's standard infantry. They receive significantly heavier armor and are armed with the modern ORO L66 Pulse Rifle, transforming them from simple marksmen into dangerous assault units.

Unlike standard soldiers, Elites have darker protective gear and a noticeably more massive silhouette. Their armor can withstand a significant number of hits, making it significantly more difficult to quickly eliminate them with conventional small arms.

The Elite's primary weapon, the ORO L66 Pulse Rifle, is a precise automatic rifle firing armor-piercing depleted uranium rounds. The weapon has a large magazine capacity, high accuracy, and a good rate of fire, but overheats during prolonged firing.

The L66 also has a secondary mode: a pulse grenade launcher. These are not particularly effective at inflicting direct damage, but they have a powerful knockback effect, allowing them to knock enemies out of cover and knock them off their feet.

Elites typically operate in squads and can lead groups of lighter soldiers. Their presence on the battlefield dramatically increases the firepower of a Mendel-Gruman squad.

TIPS:

- Prioritize eliminating the Elite if they are with regular infantry.
- Use cover: The L66 is highly accurate and capable of effective fire at long range.
- Watch out for pulse grenades. They can knock you out of cover and leave you open to other soldiers.
- Despite his heavy armor, headshots remain the most effective way to kill him.
- Don't confuse him with the Heavy Weapons MG soldiers: the heavy machine weapons carries the Warhorse, while the elite soldier carries the L66.
