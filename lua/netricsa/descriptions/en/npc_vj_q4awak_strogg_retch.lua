STROGG RETCH FROM THE STROGGOS


CLASS:      Strogg Retch 
METABOLISM: Cybernetic Organism
PERCEPTION: Close Combat Assault Brute
SIZE:       6,8 ft
ENDURANCE:  High
HOSTILITY:  Extreme
WEAPONS:    Cybernetic Limbs, Blade Arm, Integrated Weaponry, Lightning Strikes
REWARD:     900 FC
THREAT:     Very High

DESCRIPTION:

A very rare and little-studied type of Strogg, originating from an unknown military Stroggification program. Its existence is virtually undocumented, and information about it remains only in isolated documents related to experimental Strogg development. Judging by its body structure, it was created as a specialized combat machine for aggressive close combat.

His behavior resembles that of a Strogga berserker. The Retch prefers to immediately close the distance with his opponent, using his massive cybernetic limbs and integrated weaponry. His body is a mixture of organic tissue and heavy mechanical components, with many of his limbs replaced or reinforced with cybernetic constructs.

The Retch appears to be more specialized in melee attacks. His weaponry is integrated directly into his body, allowing him to continue the attack without losing the ability to use his integrated weapon systems. In combat, he is extremely aggressive, constantly moving forward and forcing his opponent to retreat.

TIPS:

- Don't let him get close. In close combat, the Retch is especially dangerous and can quickly close the distance.
- Don't count on slowly wearing him down. His high endurance allows him to withstand significant amounts of fire.
