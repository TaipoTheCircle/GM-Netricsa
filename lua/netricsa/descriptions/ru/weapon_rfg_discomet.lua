ИМПРОВИЗИРОВАННОЕ ОРУЖИЕ ГРИНДЕР (ДИСКОМЁТ)


ОРУЖИЕ:  Импровизированное Оружие Гриндер (Дискомёт)
ПАТРОНЫ: Металлические Диски
СС:      Умеренная

ОПИСАНИЕ:

Самодельное оружие повстанцев, созданное из salvaged-компонентов и деталей промышленного оборудования. Представляет собой тяжёлое устройство с вращающимся режущим механизмом, предназначенное для поражения живой силы противника. Выстреливает металлическими дисками с острыми кромками на высокой скорости, превращая обычные детали металлолома в опасные метательные снаряды.

Перед стрельбой двигатель должен набрать необходимые обороты, поэтому оружию требуется небольшая задержка перед выстрелом. Основной режим выпускает вращающиеся режущие диски, а альтернативный позволяет нанести противнику удар корпусом оружия. Может быть улучшено для сокращения времени раскрутки, увеличения боезапаса и использования взрывных дисков.

ПРИМЕЧАНИЯ:

- Эффективно против отдельных солдат EDF на коротких и средних дистанциях.
- Попадание диска в голову способно мгновенно убить противника.
- Практически бесполезно для разрушения зданий и тяжёлых объектов.
- Создано повстанцами из подручных деталей и промышленного оборудования.
- После улучшения может использовать взрывные диски.
