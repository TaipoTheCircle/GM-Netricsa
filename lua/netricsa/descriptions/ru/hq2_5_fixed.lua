HALF-QUAKE 2, ЛИФТ-ИЛЛЮЗИЙ


Сэм... СЭМ, НЕ СМОТРИ НА СТЕНЫ!

...

Я серьёзно. Этот пёстрый узор - не просто украшение. Он двигается. Стены то сжимаются, то разжимаются... Мой процессор начинает нагреваться, а я всего лишь анализирую это! Что уж говорить о твоей бедной голове.

...

Но вот что интересно, герой. Присмотрись. Узор на полу и потолке одинаковый. Но он движется с разной скоростью. Почему? Потому что это не комната. Это ЛИФТ. Мы едем вниз. Или вверх... Или в сторону. Чёрт его знает, куда нас везут эти садисты!

Мои сенсоры показывают, что мы приближаемся к чему-то большому... Очень большому. Я вижу впереди комнату, а на её стенах... рентгены. Огромные рентгеновские снимки челюстей. Чьих-то челюстей.

Держись, Сэм. У нас нет выбора. Когда лифт остановится - стреляй первым. И не смотри на стены. Я сказала - НЕ СМОТРИ!
