АВТОМАТИЧЕСКАЯ ВИНТОВКА FG-42


ОРУЖИЕ:  Автоматическая Винтовка FG-42
ПАТРОНЫ: 7,92x57 мм Mauser
СС:      Автоматический, ~750-900 выстрелов / мин.
ВЕС:     ~4,2-4,95 кг.

ОПИСАНИЕ:

FG-42, или "Fallschirmjägergewehr 42", автоматическая винтовка, разработанная специально для немецких парашютистов. Задачей было создать одно оружие, способное заменить сразу несколько типов вооружения: винтовку, пистолет-пулемёт и ручной пулемёт.

Винтовка использует мощный винтовочный патрон 7,92x57 мм и способна вести как одиночный, так и автоматический огонь. Необычной особенностью FG-42 является работа механизма в разных режимах: одиночные выстрелы производятся при закрытом затворе, а автоматический огонь ведётся с открытого затвора.

Компактные размеры и сравнительно небольшой вес позволяют использовать FG-42 в маневренном бою, при этом оружие сохраняет мощность полноценной винтовки. На винтовку можно устанавливать оптический прицел, а также использовать сошки и винтовочные гранаты.

ПРИМЕЧАНИЯ:

- Имеет одиночный и автоматический режимы огня.
- Хорошо подходит как для точной стрельбы, так и для подавления противника очередями.
- Может оснащаться оптическим прицелом и использоваться в роли снайперской винтовки.
- Оснащается складными сошками для устойчивой стрельбы.
- Мощный патрон 7,92×57 мм обеспечивает высокую эффективность на средней и дальней дистанции.
- Автоматический огонь быстро расходует небольшой магазин и создаёт серьёзную отдачу.
- Прицельная дальность составляет около 500 м, максимальная заявленная дальность около 1000 м.
- Конструкция предусматривает возможность использования штыка.
- На средней дистанции можно работать короткими очередями, а на дальней лучше переключаться на одиночный огонь.
- Создавалась для десантников, которым требовалось оружие, способное дать им серьёзную огневую мощь сразу после высадки.
- Когда одна винтовка пытается одновременно быть винтовкой, пулемётом и снайперкой, FG-42 просто отвечает: "Да".
