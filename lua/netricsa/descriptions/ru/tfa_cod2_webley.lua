РЕВОЛЬВЕР WEBLEY MK IV


ОРУЖИЕ:  Револьвер Webley Mk IV
ПАТРОНЫ: .455 Webley Mk II
СС:      ~20-30 выстрелов / мин.
ВЕС:     ~1,1 кг.

ОПИСАНИЕ:

Webley Mk IV, также известный как Модель Англо-Бурской Войны, британский револьвер с переломной рамой, принятый на вооружение в 1899 году. Он стал широко использоваться британскими военнослужащими во время Второй англо-бурской войны и получил репутацию надёжного и мощного армейского револьвера.

Револьвер использует мощный патрон .455 Webley Mk II и имеет шестизарядный барабан. Благодаря конструкции с переломной рамой при открывании револьвера одновременно выбрасываются стреляные гильзы, что значительно ускоряет перезаряжание по сравнению с револьверами, где барабан приходится заряжать через отдельную дверцу.

Webley Mk IV работает в режиме двойного действия, поэтому для каждого выстрела достаточно нажать на спусковой крючок. Револьвер отличался прочной конструкцией и высокой надёжностью, что сделало его особенно подходящим для военной службы.

ПРИМЕЧАНИЯ:

- Мощный .455 Webley обеспечивает высокую останавливающую силу на ближней дистанции.
- Переломная рама и автоматическое извлечение шести гильз позволяют довольно быстро перезарядить револьвер.
- Лучше всего подходит для ближнего боя, хотя механический прицел позволяет вести достаточно точную стрельбу.
