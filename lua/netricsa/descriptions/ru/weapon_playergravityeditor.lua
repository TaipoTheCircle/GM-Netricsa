ГРАВИТАЦИОННЫЙ МАНИПУЛЯТОР АЛЬЯНСА


ОРУЖИЕ:  Гравитационный Манипулятор Альянса
ПАТРОНЫ: Не Требуются
СС:      Изменение Направления Гравитации

ОПИСАНИЕ:

Специализированное устройство Альянса, созданное на основе стандартной электродубинки Overwatch и ГО. В отличие от оригинала, предназначенного для подавления и обезвреживания нарушителей, модифицированная версия позволяет своему владельцу изменять направление действующей на него гравитации. Устройство предназначено для перемещения по вертикальным поверхностям и потолкам, открывая доступ к местам, недоступным обычным пехотным подразделениям.

Для активации необходимо взмахнуть манипулятором в сторону выбранной поверхности. После контакта направление гравитации пользователя изменяется, позволяя ему перемещаться по стенам и потолку. При этом держать устройство в руках постоянно необязательно, поэтому владелец может свободно пользоваться огнестрельным оружием и другим снаряжением. Однако неправильное применение способно привести к потере контроля над движением и отправить неосторожного пользователя в стратосферу.

ПРИМЕЧАНИЯ:

- Создан на основе электродубинки Альянса.
- Позволяет ходить по стенам и потолку.
- Не требует постоянного удержания для поддержания изменённой гравитации.
- Особенно полезен для обхода препятствий и атак с неожиданных направлений.
- Неправильное использование может закончиться весьма продолжительным полётом.
