ШТУРМОВАЯ ВИНТОВКА PATTEN 470


ОРУЖИЕ:  Штурмовая Винтовка Patten 470
ПАТРОНЫ: 5,56x45 мм НАТО
СС:      600-750 выстрелов в минуту

ОПИСАНИЕ:

Современная штурмовая винтовка, разработанная для вооружённых подразделений корпорации Armacham Technology Corporation. Отличается газоотводной автоматикой с газовым поршнем, высокой надёжностью и хорошей точностью. Оснащена оптическим прицелом ACOG, обеспечивающим удобное прицеливание на средних и дальних дистанциях.

Patten 470 обладает переключателем режимов огня, позволяющим выбирать между одиночной стрельбой и полностью автоматическим режимом. Использует магазины на 30 патронов, а благодаря высокой мощности и хорошей дальности эффективно подходит для различных боевых ситуаций. Конструкция винтовки сочетает черты нескольких современных штурмовых систем.

ПРИМЕЧАНИЯ:

- Оснащена оптическим прицелом ACOG.
- Магазин вмещает 30 патронов, запас боеприпасов может достигать 420.
- Конструкция во многом основана на экспериментальной винтовке XM8.
- Обладает хорошей дальностью и высокой останавливающей силой.
- Прицел помогает вести точный огонь, но вблизи иногда удобнее стрелять от бедра.
