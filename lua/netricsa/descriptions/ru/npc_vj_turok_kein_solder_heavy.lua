ТЯЖЁЛЫЙ ОРУЖЕЙНЫЙ СОЛДАТ МЕНДЕЛЬ-ГРУМАН 


КЛАСС:        Тяжёлый Оружейный Солдат Мендель-груман
МЕТАБОЛИЗМ:   Человек, Мужчина
ВОСПРИЯТИЕ:   Тяжёлая Штурмовая Пехота
РАЗМЕР:       ~1,9 м.
ВЫНОСЛИВОСТЬ: Очень высокая
ВРАЖДЕБНОСТЬ: Чрезвычайная
ОРУЖИЕ:       Тяжёлый Роторный Пулемёт "ORO Боевой Конь"
НАГРАДА:      1000
УГРОЗА:       Очень Высокая

ОПИСАНИЕ:

Специализированные тяжёлые бойцы корпорации Мендель-груман, предназначенные для уничтожения особо опасных целей и подавления противника огневой мощью. В отличие от обычных солдат МГ, которые действуют группами с автоматическим оружием, эти бойцы являются настоящими мобильными пулемётными расчётами, которым почему-то не понадобился второй человек.

Они облачены в тяжёлую военную броню тускло-зелёного цвета. Броня закрывает большую часть тела, имеет высокий воротник, усиленные запястья и защищённые бёдра. Лицо полностью скрыто за ярким серо-серебристым визором. Внешне заметно массивнее стандартных бойцов Мендель-груман и относятся к той же тяжёлой категории, что Элита и Пиро.

Главное оружие подразделения "ORO Боевой Конь", шестиканальный роторный пулемёт крупного калибра. Он способен выдавать чрезвычайно плотный поток огня с высокой скоростью стрельбы. Пулемёту требуется несколько мгновений на раскрутку стволов, после чего он превращает направление атаки в довольно неприятную зону для всего живого.

Поэтому очередь Боевого Коня способна создать крайне неприятную цепочку: несколько попаданий замедляют цель, после чего последующие пули начинают прилетать ещё легче.

Несмотря на тяжёлую броню, у подразделения имеется заметная слабость: голова. Один точный выстрел в голову способен мгновенно уничтожить его, поэтому их защита не делает их неуязвимыми. Они также способны пережить попадание не полностью натянутой стрелы Перфоратора, что подчёркивает их значительно более высокую защищённость по сравнению с обычными солдатами.

В бою Тяжёлый Оружейный Солдат обычно используются как средство подавления. Они появляются сравнительно редко, но когда появляются, их задача проста: остановить продвижение противника шквалом огня. Несколько таких бойцов способны буквально превратить открытый участок местности в пулемётный коридор.

СОВЕТЫ:

- Не высовывайся под его пулемёт. Боевой Конь наносит огромный поток урона.
- Стреляй в голову. Это их главная уязвимость, несмотря на тяжёлую броню.
- Не пытайся перестрелять его из обычного автомата. Это бой, где у одной стороны пулемёт явно больше.
- Используй укрытия и обход с фланга. Тяжёлый Оружейный Солдат особенно опасен там, где ему есть пространство для длительной очереди.
- Не позволяй нескольким Тяжёлый Оружейным Солдатам сосредоточить огонь на одной цели. Их плотность огня становится гораздо опаснее при совместной атаке.
- Если есть возможность использовать взрывчатку или мощное оружие, не экономь его ради этого парня. Он как раз тот случай, когда слово "тяжёлый" стоит воспринимать буквально.
