САМОЗАРЯДНАЯ ВИНТОВКА GEWEHR 43 (G43)


ОРУЖИЕ:  Самозарядная Винтовка Gewehr 43 (g43)
ПАТРОНЫ: 7,92×57 мм Mauser
СС:      Самозарядный, ~30 выстрелов / мин
ВЕС:     4,33 кг.

ОПИСАНИЕ:

Gewehr 43, также известная как G43, немецкая самозарядная винтовка времён Второй мировой войны. Разработанная в 1943 году, она стала развитием Gewehr 41 с более удачной газоотводной системой. В 1944 году винтовку переименовали в Karabiner 43 (K43), при этом конструкция практически не изменилась.

Винтовка использует газоотводную автоматику с коротким ходом поршня и питается из отъёмного магазина на 10 патронов. Благодаря самозарядному механизму стрелок может быстро производить повторные выстрелы без ручного передёргивания затвора после каждого попадания.

G43 эффективна на средней и дальней дистанции, а возможность установки оптического прицела позволяла использовать отдельные экземпляры в качестве снайперского оружия. Однако оптические прицелы устанавливались лишь на небольшую часть произведённых винтовок.

ПРИМЕЧАНИЯ:

- Хорошая точность и мощный винтовочный патрон делают G43 эффективной на средней и дальней дистанции.
- Самозарядный механизм позволяет быстро делать повторные выстрелы.
- Может оснащаться оптическим прицелом и использоваться как снайперская винтовка.
- 7,92×57 мм обладает высокой мощностью и хорошо подходит для поражения защищённых целей.
- Небольшой магазин приходится часто менять при интенсивной стрельбе.
- Несмотря на самозарядную систему, это не автоматическая винтовка. Очередями штатный G43 не стреляет.
- Эффективная дальность составляет около 500 метров.
- В 1944 году получила новое обозначение Karabiner 43, или K43.
- Если есть оптика, лучше использовать G43 для точного огня по отдельным целям. Если оптики нет, винтовка отлично справляется с ролью мощного самозарядного оружия поддержки.
- Десять патронов, самозарядность и 7,92 мм. У врага есть время подумать, но совсем немного.
