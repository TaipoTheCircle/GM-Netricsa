РУЧНОЙ ПУЛЕМЁТ ДЕГТЯРЁВА ДП-27


ОРУЖИЕ:  Ручной Пулемёт Дегтярёва ДП-27
ПАТРОНЫ: 7,62x54 мм R
СС:      ~500-600 Выстрелов / Мин

ОПИСАНИЕ:

Советский ручной пулемёт, разработанный оружейным конструктором Василием Алексеевичем Дегтярёвым в 1927 году. Принят на вооружение Красной армии в том же году и предназначался для огневой поддержки стрелковых подразделений. Стал одним из основных образцов автоматического оружия советской пехоты в годы Великой Отечественной войны. Отличается характерным дисковым магазином, расположенным сверху ствольной коробки, и деревянным прикладом.

Работает по принципу отвода пороховых газов с запиранием канала ствола при помощи двух боевых упоров. Использует винтовочный патрон 7,62x54 мм R. Питание осуществляется из плоского дискового магазина вместимостью 47 патронов. Оснащён воздушным охлаждением ствола, складными сошками и механическими прицельными приспособлениями. В 1944 году появилась модернизированная версия ДПМ, получившая ряд конструктивных изменений для повышения удобства эксплуатации и надёжности.

ПРИМЕЧАНИЯ:

- Эффективен против групповых и одиночных целей на средних дистанциях.
- Существуют авиационный вариант ДА и танковый вариант ДТ.
- Принят на вооружение в 1927 году.
- Дисковый магазин вмещает 47 патронов.
- Основной ручной пулемёт Красной армии во время Великой Отечественной войны.
