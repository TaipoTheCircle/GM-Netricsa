ЕДИНЫЙ ПУЛЕМЁТ MG 34


ОРУЖИЕ:  Единый Пулемёт MG 34
ПАТРОНЫ: 7,92x57 мм Mauser
СС:      ~800-900 выстрелов / мин.
ВЕС:     ~12 кг.

ОПИСАНИЕ:

Немецкий единый пулемёт, разработанный в межвоенный период и принятый на вооружение в 1934 году. Он создавался как универсальное оружие, способное выполнять роль лёгкого ручного, станкового и танкового пулемёта в зависимости от установленного оборудования.

Пулемёт использует автоматику с коротким ходом ствола и отличается очень высокой для своего времени скорострельностью. Питание осуществляется преимущественно пулемётными лентами, также существовали варианты с барабанными магазинами. Благодаря возможности быстро сменить ствол MG 34 способен поддерживать длительный огонь, хотя интенсивная стрельба быстро нагревает ствол.

Главная особенность MG 34 заключается именно в универсальности: один и тот же пулемёт мог использоваться пехотой на сошках, устанавливаться на станок или применяться как вооружение бронетехники.

ПРИМЕЧАНИЯ:

- Очень высокая скорострельность делает MG 34 особенно эффективным для подавления противника на ближней и средней дистанции.
- На станке пулемёт способен вести точный огонь по удалённым и групповым целям.
- При интенсивной стрельбе ствол быстро нагревается, поэтому возможность его замены становится настоящим спасением.
- Один пулемёт, три роли: пехота, станок и танк. Универсальность, доведённая до немецкой педантичности.
