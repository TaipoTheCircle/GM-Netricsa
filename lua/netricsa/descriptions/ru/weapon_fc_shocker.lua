ШОКЕР


ОРУЖИЕ:  Шокер
ПАТРОНЫ: Электрическая энергия
СС:      600 ударов / мин
ВЕС:     ~1,5 кг.

ОПИСАНИЕ:

Компактное оружие ближнего боя, предназначенное для длительной атаки электрическим разрядом. При активации устройство непрерывно поражает цель электричеством, не требуя боеприпасов. Дальность атаки составляет около 2,2 метра, что позволяет использовать его против противников, которые опасны при прямом сближении.

Шокер особенно эффективен против защищённых противников. По сравнению с обычным мачете он обладает большей скоростью и дальностью атаки, позволяя наносить частые электрические удары на короткой дистанции.

ПРИМЕЧАНИЯ:

- Не имеет ограниченного боезапаса, может атаковать непрерывно.
- Наносит электрический урон при контакте с целью.
- Эффективен против защищённых противников.
- Дальность атаки около 2,2 м.
- Предназначен исключительно для ближнего боя.
