ПРОТИВОТАНКОВЫЙ ГРАНАТОМЁТ ПАНЦЕРШРЕК (RPZB. 54)


ОРУЖИЕ:  Противотанковый гранатомёт Панцершрек (RPzB. 54)
ПАТРОНЫ: 88-мм реактивная противотанковая граната
СС:      ~1 выстрел / мин.
ВЕС:     ~9,5 кг.

ОПИСАНИЕ:

Панцершрек, или "гроза танков", немецкий ручной противотанковый гранатомёт времён Второй мировой войны. Он был принят на вооружение в 1943 году и представлял собой реактивное противотанковое оружие с открытой пусковой трубой. Граната имела кумулятивную боевую часть и могла пробивать до 220 мм брони.

В отличие от более раннего RPzB. 43 Ofenrohr, Панцершрек получил защитный металлический щиток, прикрывавший стрелка от раскалённых пороховых газов при выстреле. Гранатомёт обслуживался расчётом из двух человек: наводчика и заряжающего. Эффективная дальность составляла около 150 метров.

ПРИМЕЧАНИЯ:

- Предназначен прежде всего для борьбы с бронетехникой. Кумулятивная граната способна поражать даже хорошо защищённые цели.
- Лучше всего раскрывается на ближней дистанции, где проще попасть по крупной бронецели.
- Это единственный случай, когда после фразы "Давай Достанем Шрека" появляется не зелёный огр, а 88-мм противотанковая ракета.
- Защитный щиток отличает Панцершрек от раннего "Офенрора" и защищает стрелка от горячих газов.
