ПИСТОЛЕТ-ПУЛЕМЁТ MP 41


ОРУЖИЕ:  Пистолет-Пулемёт MP 41
ПАТРОНЫ: 9x19 мм Parabellum
СС:     ~500 выстрелов / мин.
ВЕС:    ~3,9 кг.

ОПИСАНИЕ:

Немецкий пистолет-пулемёт времён Второй мировой войны, разработанный Луисом Шмайссером на основе хорошо зарекомендовавшего себя MP 40. Главным отличием стала новая деревянная ложа и переработанный ударно-спусковой механизм. В отличие от MP 40, MP 41 способен вести как одиночный, так и автоматический огонь.

Оружие использует автоматику со свободным затвором и стреляет с открытого затвора. Переключатель режимов расположен непосредственно над спусковым крючком. Питание осуществляется из коробчатого магазина на 32 патрона.

MP 41 получил деревянный приклад вместо складного металлического приклада MP 40, что сделало оружие более похожим на традиционную винтовку. Перекидной целик рассчитан на дистанции 100 и 200 метров. Серийное производство осуществляла компания C.G. Haenel, однако выпуск вскоре был прекращён после судебного разбирательства с Erma, производителем MP 40. Всего изготовили около 26 000 экземпляров, преимущественно для Waffen-SS и полиции.

ПРИМЕЧАНИЯ:

- Не путать с MP 41 (R).
- Хорошо подходит для ближней и средней дистанции, а одиночный огонь позволяет вести более точную стрельбу.
- Темп около 500 выстрелов в минуту делает автоматический огонь достаточно контролируемым по сравнению с более скорострельными пистолетами-пулемётами.
- Деревянная ложа придаёт MP 41 внешний вид небольшой винтовки и делает её заметно отличающейся от MP 40.
