ГИТАРА "ПАЦАНСКИЕ ПЕСНИ"


ОРУЖИЕ:  Гитара "Пацанские песни"
ПАТРОНЫ: Не требуются

ОПИСАНИЕ:

Необычная гитара, предназначенная для воспроизведения популярных песен. Как и модель "ГИМН СССР", не требует непосредственной игры на струнах. Для активации достаточно ударить рукой в воздух, после чего инструмент самостоятельно начинает исполнять одну из доступных композиций.

Встроенный музыкальный сборник включает восемь песен отечественных исполнителей. Среди них композиции групп "Ляпис Трубецкой", "БИ-2", "Любэ", песни Виктора Цоя и произведения Павла Пламенева.

ПРИМЕЧАНИЯ:

- Содержит восемь музыкальных композиций:
- "Воины света" (Ляпис Трубецкой).
- "Полковнику никто не пишет" (БИ-2).
- "Давай за..." (Любэ).
- "Группа крови" (Виктор Цой).
- "Солдатами не рождаются" (Павел Пламенев).
- "Последний день 2021" (Павел Пламенев).
- "Для мира на земле" (Павел Пламенев).
- "Отряды ветеранов" (Павел Пламенев).
- Для запуска музыки достаточно взмаха рукой.
- Струны и музыкальные навыки не требуются.
