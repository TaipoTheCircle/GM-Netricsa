СНАЙПЕРСКАЯ ВИНТОВКА ТРИГЛАВ 92 СТАЛКЕР


ОРУЖИЕ:  Снайперская Винтовка ТРИГЛАВ 92 Сталкер
ПАТРОНЫ: Винтовочные Патроны
СС:     ~30 выстрелов / мин.
ВЕС:    ~4,5 кг.

ОПИСАНИЕ:

Высокоточная снайперская винтовка производства ТРИГЛАВ, предназначенная для поражения целей на больших дистанциях. Оружие отличается практически идеальной точностью при использовании прицела и высокой убойной силой, позволяющей уничтожать большинство небольших целей одним выстрелом.

Винтовка использует продольно-скользящий затвор, поэтому после каждого выстрела требуется время на перезарядку. Магазин вмещает 5 патронов. На корпусе расположен индикатор боезапаса, показывающий количество оставшихся патронов.

Прицел имеет несколько уровней увеличения: 2x, 5x и 10x, что позволяет вести огонь как на средней, так и на экстремально большой дистанции. При стрельбе без прицела точность значительно снижается, поэтому использовать Сталкера в таком режиме рекомендуется только в крайнем случае.

ПРИМЕЧАНИЯ:

- Исключительно высокая точность при стрельбе через прицел.
- Большинство небольших целей уничтожается одним попаданием.
- Имеет увеличение 2x / 5x / 10x.
- Магазин рассчитан на 5 патронов.
- Продольно-скользящий затвор создаёт заметную задержку между выстрелами.
- Предназначена прежде всего для дальней и экстремально дальней дистанции.
- Стрельба от бедра значительно менее точна.
