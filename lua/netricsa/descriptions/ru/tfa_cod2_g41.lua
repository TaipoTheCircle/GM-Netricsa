САМОЗАРЯДНАЯ ВИНТОВКА GEWEHR 41 (G.41)


ОРУЖИЕ:  Самозарядная винтовка Gewehr 41 (G.41)
ПАТРОНЫ: 7,92x57 мм Mauser
СС:      ~15-20 выстрелов / мин.
ВЕС:     ~4,9 кг.

ОПИСАНИЕ:

Gewehr 41, или G.41, немецкая самозарядная винтовка времён Второй мировой войны, разработанная в 1941 году компаниями Mauser и Walther. Она создавалась для немецкой армии как современная самозарядная замена обычной магазинной винтовке. На вооружение в итоге приняли вариант G.41(W) производства Walther.

Винтовка использует газоотводную автоматику и мощный винтовочный патрон 7,92x57 мм Mauser. Магазин встроенный, на 10 патронов, и пополняется при помощи стандартных обойм. После выстрела автоматика сама выбрасывает гильзу и досылает следующий патрон, поэтому стрелку не требуется вручную работать затвором.

Gewehr 41 получилась довольно тяжёлой и сложной. В войсках отмечались чувствительность к загрязнению и различные задержки при стрельбе. Уже в 1943 году её начали заменять более совершенной Gewehr 43, которая была легче и получила съёмный магазин.

ПРИМЕЧАНИЯ:

- Хорошо подходит для средней и дальней дистанции, где мощный винтовочный патрон раскрывает себя лучше всего.
- Самозарядная автоматика позволяет значительно быстрее делать повторные выстрелы, чем из Karabiner 98k.
- Встроенный магазин на 10 патронов заряжается обоймами, поэтому отдельный съёмный магазин носить не требуется.
