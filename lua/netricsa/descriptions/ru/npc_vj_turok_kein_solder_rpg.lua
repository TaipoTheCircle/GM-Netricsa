СОЛДАТ-РАКЕТЧИК МЕНДЕЛЬ-ГРУМАН


КЛАСС:        Солдат-Ракетчик Мендель-Груман
МЕТАБОЛИЗМ:   Человек, Мужчина
ВОСПРИЯТИЕ:   Специализированная Противотанковая Пехота
РАЗМЕР:       ~1,8 м.
ВЫНОСЛИВОСТЬ: Средняя
ВРАЖДЕБНОСТЬ: Чрезвычайная
ОРУЖИЕ:       РПГ ORO "Красный Кулак", Дробовик ORO "Исполнитель", Осколочные Гранаты
НАГРАДА:      400
УГРОЗА:       Высокая

ОПИСАНИЕ:

МГ РПГ является специализированным подразделением корпорации Мендель-Груман, предназначенным для применения тяжёлого ракетного вооружения. Внешне он сохраняет общую эстетику лёгкой пехоты корпорации, однако отличается от обычных солдат металлической серо-серебристой окраской брони, изменённой конструкцией шлема и плечевой защитой.

Основным оружием этого подразделения считается РПГ ORO "Красный Кулак". Ракетная установка позволяет поражать цели на расстоянии и наносить серьёзный урон группам пехоты, технике и другим крупным целям. Именно наличие ракетницы делает МГ РПГ гораздо более опасным противником, чем стандартный Пехотинец.

Однако существует одна довольно странная особенность этого подразделения: МГ РПГ вовсе не обязательно носит РПГ. Большинство носит Дробовики ORO "Исполнитель".

Поэтому название "РПГ" скорее обозначает тип подразделения, чем гарантированное оружие конкретного бойца. Встречаются и редкие экземпляры, действительно вооружённые РПГ "Красный Кулак". Причём один из заметных бойцов с РПГ технически вообще считается обычным Пехотинец, а не полноценным МГ РПГ, что является одной из особенностей финального распределения вооружения.

МГ РПГ обычно действует вместе с другими подразделениями Мендель-Груман. Он может занимать выгодную позицию и вести огонь по противнику издалека, пока обычные пехотинцы удерживают его внимание. В составе смешанной группы особенно опасен, поскольку заставляет одновременно следить и за стрелками, и за возможным ракетным ударом.

При использовании "Исполнителя" его поведение становится более агрессивным: такой боец старается приблизиться к противнику и использовать высокую эффективность дробовика на короткой дистанции. Таким образом, один и тот же тип подразделения способен представлять две совершенно разные угрозы в зависимости от выданного оружия.

СОВЕТЫ:

- Увидел ракетницу? Считай, что день стал хуже.
- Не стой группой рядом с союзниками: попадание РПГ ORO "Красный Кулак" может зацепить сразу нескольких бойцов.
- Проверяй оружие в руках, а не только внешний вид. МГ РПГ вполне может оказаться с "Исполнителем" вместо РПГ.
- Если он вооружён дробовиком, держи дистанцию и не позволяй ему приблизиться.
- Если вооружён РПГ "Красный Кулак", используй укрытия и старайся вывести его из строя первым.
- Как и остальные лёгкие подразделения МГ, он не отличается исключительной живучестью, поэтому сосредоточенный огонь быстро решает проблему.
