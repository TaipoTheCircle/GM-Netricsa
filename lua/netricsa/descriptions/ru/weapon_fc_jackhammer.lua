АВТОМАТИЧЕСКИЙ ДРОБОВИК PANCOR JACKHAMMER


ОРУЖИЕ:  Автоматический Дробовик Pancor Jackhammer
ПАТРОНЫ: Дробовые Патроны 12 калибра
СС:      Автоматический, ~171 выстр./мин
ВЕС:     ~7,9 кг.

ОПИСАНИЕ:

Тяжёлое оружие ближнего боя с высокой скорострельностью и огромной останавливающей силой. Он использует магазин на 10 патронов и способен вести полностью автоматический огонь. Каждый выстрел выпускает большое количество дроби, благодаря чему оружие особенно эффективно при зачистке помещений и тесных проходов.

Конструкция основана на необычной схеме с вращающейся барабанной кассетой. Изначально создавался как буллпап-дробовик под 12-й калибр, однако серийно так и не выпускался, оставшись на стадии прототипов.

ПРИМЕЧАНИЯ:

- Полностью автоматический режим огня.
- Магазин рассчитан на 10 патронов.
- Один выстрел выпускает множество дробей, позволяя поражать крупные цели несколькими попаданиями.
- Наиболее эффективен на ближней дистанции, на средней и дальней точность и урон резко снижаются.
- Особенно эффективен в коридорах, помещениях и других тесных пространствах.
- Большой вес и высокая скорострельность делают оружие неудобным для длительного ведения огня.
- Боеприпасы встречаются нечасто, поэтому расходовать их без необходимости не рекомендуется.
