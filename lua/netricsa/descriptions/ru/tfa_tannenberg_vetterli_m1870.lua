МАГАЗИННАЯ ВИНТОВКА VETTERLI-VITALI M1870/87


ОРУЖИЕ:  Магазинная Винтовка Vetterli-Vitali M1870/87
ПАТРОНЫ: 10,4x47 мм R Vetterli
СС:      ~15 Выстрелов / Мин

ОПИСАНИЕ:

Итальянская магазинная винтовка, созданная в 1887 году путём модернизации однозарядной Vetterli M1870. Разработка усовершенствования была поручена капитану артиллерии Джузеппе Витали, предложившему оснастить винтовку четырёхзарядным коробчатым магазином. Модернизация позволила продлить срок службы уже устаревающей конструкции и приблизить её к требованиям современной пехоты.

Работает по принципу ручного перезаряжания с продольно-скользящим поворотным затвором. Использует патрон 10,4x47 мм R Vetterli и встроенный коробчатый магазин на 4 патрона. Заряжание производится специальной обоймой из дерева и металла, которая вставляется в магазин целиком, после чего извлекается за специальный шнур. Винтовка сохранила основные особенности исходной модели, включая крупнокалиберный патрон и механические прицельные приспособления. Впоследствии часть винтовок была переделана под патрон 6,5x52 мм Carcano и получила обозначение Vetterli-Vitali M1870/87/15.

ПРИМЕЧАНИЯ:

- Оснащена четырёхзарядным магазином системы Джузеппе Витали.
- Использует специальную четырёхпатронную обойму с вытяжным шнуром.
- Скорострельность составляет примерно 15 выстрелов в минуту.
- Подходит для поражения одиночных целей на средних и дальних дистанциях.
- Эффективна против незащищённой живой силы, но уступает более современным винтовкам.
- Во время Первой мировой войны часть винтовок была переделана под патрон 6,5x52 мм Carcano.
