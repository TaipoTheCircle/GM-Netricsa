САМОЗАРЯДНЫЙ КАРАБИН СИМОНОВА СКС


ОРУЖИЕ:  Самозарядный Карабин Симонова СКС
ПАТРОНЫ: 7,62x39 мм
СС:      ~35-40 Выстрелов / Мин

ОПИСАНИЕ:

Советский самозарядный карабин, разработанный оружейным конструктором Сергеем Гавриловичем Симоновым. Принят на вооружение Советской армии в 1949 году. Предназначен для поражения живой силы противника на ближних и средних дистанциях. Стал одним из первых серийных образцов советского оружия под промежуточный патрон образца 1943 года. Отличается сравнительно небольшим весом, деревянной ложей и складным штыком.

Работает по принципу отвода пороховых газов с запиранием канала ствола перекосом затвора. Использует промежуточный патрон 7,62x39 мм. Питание осуществляется из постоянного коробчатого магазина вместимостью 10 патронов, который снаряжается при помощи обоймы. Оснащён механическими прицельными приспособлениями, газоотводной автоматикой и складным штыком. В отличие от автоматов, способен вести только одиночный огонь с автоматической перезарядкой после каждого выстрела.

ПРИМЕЧАНИЯ:

- Эффективен против одиночных и групповых целей на ближних и средних дистанциях.
- Принят на вооружение в 1949 году.
- Магазин вмещает 10 патронов.
- Масса составляет около 3,9 кг со снаряжённым магазином.
- Оснащается складным игольчатым или клинковым штыком.
- Разработан Сергеем Гавриловичем Симоновым.
