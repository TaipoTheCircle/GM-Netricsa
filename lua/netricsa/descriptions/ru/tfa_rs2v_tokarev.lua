ПИСТОЛЕТ ТУЛЬСКИЙ ТОКАРЕВА МОДЕЛИ 1933


ОРУЖИЕ:  Пистолет Тульский Токарева Модели 1933
ПАТРОНЫ: 7,62x25 мм ТТ
СС:      ~30-40 выстрелов / мин.
ВЕС:     ~0,85 кг.

ОПИСАНИЕ:

Советский самозарядный пистолет, разработанный Фёдором Токаревым и принятый на вооружение в 1930-х годах. Он создавался как замена устаревшим револьверам и иностранным пистолетам, находившимся на вооружении Красной армии.

Пистолет использует автоматику с коротким ходом ствола и запиранием его перекосом. Конструкция получилась достаточно простой и технологичной в производстве, а патрон 7,62x25 мм обладает высокой начальной скоростью пули.

ТТ предназначен прежде всего для ближнего боя. Небольшой вес и достаточно высокая мощность патрона позволяют быстро вести повторные выстрелы, а простая конструкция хорошо подходит для массового армейского использования. Эффективная дальность составляет около 50 метров.

ПРИМЕЧАНИЯ:

- Особенно эффективен на ближней дистанции, где высокая скорость пули позволяет быстро поражать цели.
- Лёгкий корпус и мощный патрон делают ТТ довольно резким и быстрым оружием в руках опытного стрелка.
- Простота конструкции была одним из главных достоинств пистолета, особенно в условиях массового военного производства.
