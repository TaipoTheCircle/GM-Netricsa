HALF-QUAKE 2, ТАНЦУЮЩИЕ ПЛАТФОРМЫ


Сэм... СЭМ! Стой на месте, не двигайся!

Я пытаюсь обработать то, что вижу... но мой процессор, кажется, решил взять отпуск. Пола нет. Вообще. Но он есть. Он просто... невидимый. Или его нет. Или он есть, но мы его не видим. Чёрт, даже я запуталась!

...

А теперь посмотри наверх. В воздухе платформы. Прямоугольники. Треугольники. Шестиугольники. И даже эта дурацкая символика ">)", которая летает так, будто ей вообще наплевать на физику. Садисты явно наняли архитектора с больным воображением. Или глюканувшего программиста. Или и то, и другое.

Но хуже другое, Сэм. Впереди и позади нас - две квадратные кнопки. Тоже с этой улыбающейся рожей ">)". Надо нажать обе. Тогда откроется путь дальше.

Просто? Нет, конечно! Потому что к нам уже летят Гнаары и Гарпии. И они не хотят играть с нами в "нажми на кнопку". Они хотят поиграть с тобой в "откуси голову".

Держись, Сэм. Тебе придётся прыгать по этим безумным платформам, уворачиваться от летающих тварей, и нажимать кнопки. И главное - не смотри вниз. Там ничего нет. А если что-то и есть - оно не хочет, чтобы ты его видел.

Вперёд! И не дай этим платформам сбить тебя с толку. Они просто... танцуют. Да, танцуют. И они приглашают тебя на свой безумный бал!
