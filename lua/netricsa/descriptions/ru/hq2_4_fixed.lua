HALF-QUAKE 2, КОМНАТА С НИЗКИМ ПОТОЛКОМ


Сэм! Заметил? Враги тут не только менталовские - теперь ещё и серые вортигонты. Садисты явно наняли новый персонал. И этот персонал выглядит очень недовольным своей работой... или это просто их лицо такое?

...

Посмотри наверх. На потолке - кнопка. А по бокам комнаты - ещё кнопки, но они заблокированы смертельным барьером. Угадай, что нужно сделать? Да, ты прав: допрыгнуть до потолка, нажать кнопку, снять барьер, бежать к боковой кнопке, нажать её, и снова к потолку. И так - пока все кнопки не будут нажаты.

Но предупреждаю: время ограничено. Если не уложишься - барьер активируется снова. И он убивает. Не ранит, не отбрасывает, а УБИВАЕТ. Садисты явно решили добавить в шоу немного кардио.

Бегай быстрее, Сэм! И не дай себя догнать этим серым вортигонтам - они, кажется, хотят попросить тебя о помощи... или ударить электричеством. С ними не угадаешь!
