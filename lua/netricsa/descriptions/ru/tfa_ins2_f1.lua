РУЧНАЯ ОСКОЛОЧНАЯ ГРАНАТА Ф-1


ОРУЖИЕ:  Ручная Осколочная Граната Ф-1
ПАТРОНЫ: Одна Граната
СС:      Один Бросок За Минуту

ОПИСАНИЕ:

Советская ручная осколочная граната оборонительного типа, разработанная в 1939 году конструктором Фёдором Ивановичем Храмеевым на основе французской гранаты F-1 образца 1915 года. Предназначена для поражения живой силы противника осколками корпуса. Получила характерный чугунный корпус с рифлёной поверхностью, за который получила прозвище "лимонка". Применялась Красной армией во время Великой Отечественной войны и впоследствии стала одним из наиболее узнаваемых образцов советского вооружения.

Основными элементами конструкции являются чугунный корпус, разрывной заряд и запал дистанционного действия. В разные годы использовались запалы Ковешникова, УЗРГ и УЗРГМ. Граната получила широкое распространение благодаря сравнительно простой конструкции и массовому производству. Оставалась на вооружении и после окончания Второй мировой войны.

ПРИМЕЧАНИЯ:

- Предназначена преимущественно для оборонительного применения.
- Стала одним из символов советского вооружения времён Великой Отечественной войны.
- Разработана в СССР в 1939 году.
- Создана с использованием конструктивной основы французской F-1.
- Прозвище "лимонка" связано с характерной формой корпуса.
