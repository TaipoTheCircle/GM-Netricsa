ТЕОТИУАКАН, ДОЛИНА МОНОЛИТОВ - ЗАЛ ДРЕВНИХ БОГОВ


Сэм, мы на месте. Долина Монолитов. Только идолы, каменный пол и... тишина. Ни заборов, ни стен, ни этих ваших "прозрачных чудес майя". Просто зал с богами, которые смотрят на нас.

Смотри. Пернатый Змей - Кетцалькоатль, он же Кукулькан. Отвечал за ветер, небо, воду и мудрость. Если он решит дать тебе прыгучесть или скорость - не отказывайся. Ветер в спину ещё никому не мешал!

Рядом - резной каменный столб. Стела майя. Историческая хроника, календарь, память предков. Если найдёшь на ней подсказку - читай внимательно. Может, там написано, как выбраться из этого безумия.

Дальше - сидящий идол. Домашний божок. Такие обычно прячут сокровища или аптечки. Ударь его - может, выпадет что-то полезное. Или ничего. Но попробовать стоит!

Огромная каменная голова ольмеков. Смотрит сурово. В общем, обойди её с умом!

Постамент с Ягуаром. Хозяин джунглей, бог ночи и войны. Если рядом с ним вдруг заиграет агрессивная музыка и полезут враги - не удивляйся. Это его работа!

И наконец - высокий тотемный бог, Атлант из Тулы. Воин-тольтек, небесная опора, страж ворот. Поставь его рядом с чем-то важным - и он будет охранять. Или просто смотреть, как ты проходишь мимо.

Знаешь, Сэм, здесь нет ловушек, нет врагов, нет заборов. Только боги. Древние, каменные, молчаливые. И каждый из них что-то значит.

Иди спокойно. Осмотрись. Может, эти боги расскажут тебе больше, чем все наши датчики и сенсоры вместе взятые!

Идём, Сэм. Здесь красиво, но нам нужно двигаться дальше!
