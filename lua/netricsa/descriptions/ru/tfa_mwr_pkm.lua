ЕДИНЫЙ ПУЛЕМЁТ КАЛАШНИКОВА МОДЕРНИЗИРОВАННЫЙ ПКМ


ОРУЖИЕ:  Единый Пулемёт Калашникова Модернизированный ПКМ
ПАТРОНЫ: 7,62x54 мм R
СС:      ~650 Выстрелов / Мин

ОПИСАНИЕ:

Советский единый пулемёт, разработанный Михаилом Тимофеевичем Калашниковым и его конструкторской группой на основе ПК. Принят на вооружение в 1969 году. Предназначен для поражения живой силы и огневых средств противника, а также обеспечения огневой поддержки пехотных подразделений. По сравнению с исходной моделью получил облегчённую конструкцию, изменённый пламегаситель и ряд усовершенствований, повышающих удобство эксплуатации.

Работает по принципу отвода пороховых газов с запиранием канала ствола поворотом затвора. Использует винтовочный патрон 7,62x54 мм R. Питание осуществляется металлической пулемётной лентой на 100 или 200 патронов, также существуют ленты на 250 патронов. Оснащён быстросъёмным стволом, складными сошками и механическими прицельными приспособлениями. Для использования со станка был разработан вариант ПКМС с облегчённым треножным станком конструкции Степанова.

ПРИМЕЧАНИЯ:

- Эффективен против живой силы и лёгких укрытий на средних и дальних дистанциях.
- Существует ночной вариант ПКМН, приспособленный для установки оптических и ночных прицелов.
- Принят на вооружение в 1969 году.
- Весит около 7,5 кг без боеприпасов.
- Боевая скорострельность достигает 250 выстрелов в минуту.
