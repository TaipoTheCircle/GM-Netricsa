ПИСТОЛЕТ-ПУЛЕМЁТ MP 38


ОРУЖИЕ:  Пистолет-пулемёт MP 38
ПАТРОНЫ: 9x19 мм Parabellum
СС:      ~600 выстрелов / мин
ВЕС:     ~4,8 кг

ОПИСАНИЕ:

Немецкий пистолет-пулемёт, разработанный фирмой ERMA и принятый на вооружение в 1938 году. Он создавался прежде всего как компактное оружие для танкистов, мотопехоты, десантников и командиров. MP 38 стал одним из первых серийных пистолетов-пулемётов со складным металлическим прикладом.

Оружие использует автоматику со свободным затвором и ведёт только автоматический огонь. Питание осуществляется из коробчатого магазина на 32 патрона. Рукоятка перезаряжания расположена слева, что позволяет правой рукой продолжать удерживать оружие за пистолетную рукоятку.

MP 38 отличался довольно умеренным темпом стрельбы и плавной работой автоматики. Это делало его хорошо управляемым при стрельбе очередями. Позднее его производство сменил более технологичный и дешёвый MP 40, поэтому MP 38 был выпущен сравнительно небольшой серией.

ПРИМЕЧАНИЯ:

- Умеренная скорострельность позволяет достаточно уверенно контролировать оружие при стрельбе очередями.
- Особенно хорошо подходит для ближнего и среднего боя.
- Складной приклад делает MP 38 удобным для танкистов, десантников и бойцов, которым важно компактное оружие.
- MP 38 стал важным этапом в развитии немецких пистолетов-пулемётов, а его конструкция стала основой для последующего MP 40.
