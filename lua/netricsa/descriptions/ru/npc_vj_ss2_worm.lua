ПОДЗЕМНАЯ ЛИЧИНКА С МАГНОРА


КЛАСС:        Подземная Личинка
МЕТАБОЛИЗМ:   Насекомое
ВОСПРИЯТИЕ:   Стационарное Подземное Существо
РАЗМЕР:       ~2,5 м.
ВЫНОСЛИВОСТЬ: Неуязвимая
ВРАЖДЕБНОСТЬ: Высокая
ОРУЖИЕ:       Рвотная масса
НАГРАДА:      100
УГРОЗА:       Средняя

ОПИСАНИЕ:

Крайне необычный представитель насекомоподобных существ с Магнора. Личинка отказалась от нормального жизненного цикла и превратилась в своеобразную живую артиллерийскую установку, обитающую внутри стен, пещер и других подземных участков.

Существо практически никогда не покидает своего укрытия. Из окружающей породы наружу периодически показывается его огромная пасть, после чего личинка извергает в сторону противника большое количество зелёной рвотной массы. Попадание наносит значительный урон и может быстро вывести из строя неосторожного противника.

Атака имеет циклический характер. После очередного извержения личинка на некоторое время замолкает, прежде чем снова раскрыть пасть и начать новую атаку. Поэтому при прохождении заражённого участка можно попытаться использовать промежутки между плевками, чтобы быстро перебраться в безопасное место.

Главная проблема заключается в том, что убить личинку практически невозможно. Её организм обладает настолько высокой устойчивостью, что обычное оружие не причиняет ей никакого вреда. Кроме Пушки SBC.

Ментал Лично использует их для создания Циклопов-Альбиносов.

СОВЕТЫ:

- Пушка SBC - Твой Лучший Друг против этого Рыгающего недразумения.
- Следи за моментом, когда пасть раскрывается. Это главный сигнал к немедленному уклонению.
- После плевка появляется короткое окно, когда личинка бездействует. Используй его, чтобы двигаться вперёд.
- Не стой перед её укрытием и не жди следующей атаки.
- Если проход позволяет, просто пробеги мимо неё.
