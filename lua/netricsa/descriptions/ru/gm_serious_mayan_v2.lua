ТЕОТИУАКАН, ЗАКАТНЫЕ ДВОРЫ - ПРИБЫТИЕ


Сэм... посмотри на это. Теотиуакан. Город Богов. В переводе с ацтекского - "Где люди становятся богами". Ну что ж, сейчас мы проверим, насколько это правда.

Вокруг - полуразрушенные жилые кварталы, зажатые между каменных стен. Когда-то здесь были культовые центры, дома жрецов, защитные укрепления. А теперь... теперь здесь только Менталовские твари, которые обосновались в каждом доме, как будто они здесь прописались.

Деревья проросли сквозь камни, дворы заросли, и каждый угол может стать ловушкой.

Кстати, видишь ступенчатые зиккураты над горизонтом? Они доминируют над всем городом. Жрецы когда-то проводили там ритуалы. Теперь и там сидят утвари и выцеливают во в всё, что движется.

А ещё здесь есть озеро. Почти спокойное. Но я не верю в тишину в местах, где побывал Ментал.

Тут же ещё есть каменная башня. Она ведёт выше - в пригород, где когда-то жили простые люди. До того, как Ментал добрался сюда. До того, как маги Арк-Аль-Маги покинули это место.

Когда-то здесь жили те, кто знал тайны сирианцев. Маги, которые могли бы помочь нам. Но они ушли. Или не совсем... Сейчас эта башня - единственный путь наверх. И там, наверху, нас ждут менталовские уроды, которые уже захватили всё, что можно захватить.

Пригород был последним оплотом цивилизации в этом городе. Теперь он - ещё одна арена для бойни.

Будь осторожен, Сэм. В таких местах обычно прячутся самые опасные твари. Или самые полезные артефакты. Или и то, и другое одновременно!

Идём к башне. Посмотрим, что осталось от магов Арк-Аль... И насколько хорошо Ментал укрепился здесь!
