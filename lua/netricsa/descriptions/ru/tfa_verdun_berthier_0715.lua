ПЕХОТНАЯ ВИНТОВКА BERTHIER 1907/15


ОРУЖИЕ:  Пехотная Винтовка Berthier 1907/15
ПАТРОНЫ: 8x50 мм R Lebel
СС:      ~15-20 Выстрелов / Мин

ОПИСАНИЕ:

Французская магазинная винтовка, разработанная на основе системы Бертье и принятая на вооружение в 1915 году. Предназначалась для оснащения пехотных подразделений французской армии во время Первой мировой войны. Отличается продольно-скользящим затвором, деревянной ложей и характерным магазином системы Манлихера. Стала одним из основных вариантов винтовок Бертье, использовавшихся французской армией в годы войны.

Работает по принципу ручного перезаряжания с продольно-скользящим затвором. Использует мощный винтовочный патрон 8x50 мм R Lebel. Питание осуществляется из постоянного коробчатого магазина вместимостью 3 патрона, снаряжаемого специальной обоймой целиком. После израсходования патронов обойма выпадает через отверстие в нижней части ствольной коробки. Оснащена открытыми механическими прицельными приспособлениями и креплением для штыка. В 1916 году появилась модификация M1916 с увеличенным магазином на 5 патронов.

ПРИМЕЧАНИЯ:

- Эффективна против одиночных целей на средних и дальних дистанциях.
- Магазин вмещает 3 патрона.
- Использует обойму системы Манлихера.
- Использовалась французской армией во время Первой и Второй мировых войн.
