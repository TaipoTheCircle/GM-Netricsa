РУЧНОЙ ПУЛЕМЁТ LSAT


ОРУЖИЕ:     Ручной Пулемёт LSAT
ПАТРОНЫ:    5,56×45 мм НАТО / безгильзовые 5,56 мм
СС:         ~650 выстрелов / мин

ОПИСАНИЕ:

Американский экспериментальный ручной пулемёт, разработанный в рамках программы Lightweight Small Arms Technologies. Проект стартовал в 2004 году и был направлен на создание более лёгкого стрелкового оружия и боеприпасов для пехоты. Разработкой занималась группа американских оборонных компаний под руководством AAI Corporation.

Главной особенностью LSAT стала возможность использования двух типов боеприпасов: обычных гильзовых и безгильзовых. Безгильзовая версия использует специальные патроны, полностью сгорающие при выстреле, что позволяет значительно уменьшить вес носимого боекомплекта. Пулемёт оснащён ленточной системой питания, а также отличается необычной конструкцией механизма подачи патронов.

ПРИМЕЧАНИЯ:

- Разрабатывался как более лёгкая альтернатива пулемёту M249.
- Безгильзовые патроны позволяют уменьшить вес боеприпасов примерно на 40%.
- Магазин вмещает 100 обычных или 150 безгильзовых патронов.
- Существует вариант с укороченным 320-мм стволом.
