ШТУРМОВАЯ ВИНТОВКА PATTEN 470 ELITE


ОРУЖИЕ:  Штурмовая Винтовка Patten 470 Elite
ПАТРОНЫ: 5,56x45 мм НАТО
СС:      600-750 выстрелов / мин

ОПИСАНИЕ:

Современная штурмовая винтовка, разработанная для вооружённых подразделений корпорации Armacham Technology Corporation. Отличается газоотводной автоматикой с газовым поршнем, высокой надёжностью и хорошей точностью. В отличие от стандартной Patten 470, версия Elite не оснащается оптическим прицелом ACOG, что придаёт ей более простой внешний вид.

Patten 470 Elite обладает переключателем режимов огня, позволяющим выбирать между одиночной стрельбой и полностью автоматическим режимом. Использует магазины на 30 патронов и сохраняет основные боевые характеристики базовой модели. Благодаря универсальности и хорошей управляемости подходит для различных боевых ситуаций.

ПРИМЕЧАНИЯ:

- Является вариантом стандартной Patten 470 Assault Rifle.
- Не оснащена оптическим прицелом ACOG.
- Магазин вмещает 30 патронов.
- Использует патроны калибра 5,56x45 мм НАТО.
- Меньше оптики, меньше лишних деталей, больше места для прицеливания по старинке.
