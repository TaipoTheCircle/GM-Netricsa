БУДУЩЕЕ МЕСТО ПОСТРОЙКИ ТЕОТИУАКАНА, ГИГАНТСКАЯ ЯМА - СООБЩЕНИЕ


Сэм, стой! Мы... мы не в городе. Похоже мы попали туда, где его ещё даже нет... Только яма. Огромная яма, вокруг которой когда-нибудь построят Теотиуакан.

Смотри на эти стены. Они не похожи на естественные. Кто-то вырыл эту яму. Или не вырыл... Стены неизвестного происхождения, и мои сенсоры не могут определить, из чего они сделаны. Это не камень, не металл, не что-то земное. Это что-то ДРУГОЕ.

И тут пришло сообщение. От каких-то "Творцов". Они называют себя Taipo и Джек Пофигист. И знаешь, что они пишут? "Мы тут тестировали Худ для транспортов и боссов для аддона Serious Sam 2 Npc's".

Серьёзно? Творцы. Боги. Создатели. И они пишут про какой-то ХУД для транспортов? Как будто мы в каком-то игровом моде, а не в реальности!

А дальше... дальше полный бред. Дискотека ниндзя. Какой-то Онан Артур. Чушь про танцы и, видимо, очень странные вечеринки. Это явно не относится к нашей миссии, Сэм. Если только Ментал не решил захватить мир с помощью дискотек и ниндзя. Хотя... я бы не удивилась!
