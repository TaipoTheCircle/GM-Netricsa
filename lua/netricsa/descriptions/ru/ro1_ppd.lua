ПИСТОЛЕТ-ПУЛЕМЁТ ДЕГТЯРЁВА ППД-40


ОРУЖИЕ:  Пистолет-пулемёт Дегтярёва ППД-40
ПАТРОНЫ: 7,62x25 мм ТТ
СС:      ~1000 выстрелов / мин.
ВЕС:     ~3,63 кг без магазина

ОПИСАНИЕ:

ППД-40, пистолет-пулемёт системы Дегтярёва образца 1940 года, советский пистолет-пулемёт, созданный Василием Дегтярёвым. Он стал развитием ранних вариантов ППД и получил широкое применение во время советско-финской войны и в начальный период Великой Отечественной войны. ППД стал первым пистолетом-пулемётом, официально принятым на вооружение Красной армии.

ППД-40 использует автоматику со свободным затвором и стреляет патроном 7,62x25 мм ТТ. Оружие способно вести автоматический огонь с темпом около 1000 выстрелов в минуту. Для питания применялись коробчатые магазины на 25 патронов и барабанные магазины большой ёмкости, первоначально на 73 патрона, позднее на 71.

В отличие от более ранних ППД, вариант 1940 года был значительно упрощён для ускорения и удешевления производства. Однако конструкция всё равно оставалась достаточно сложной и дорогой по сравнению с появившимися позднее ППШ и ППС.

ППД-40 имел деревянную ложу и характерный перфорированный кожух ствола. Большой барабанный магазин позволял создать очень плотный огонь на ближней дистанции, хотя его конструкция могла быть менее надёжной при подаче патронов.

ПРИМЕЧАНИЯ:

- Очень высокая скорострельность позволяет буквально заливать противника огнём на ближней дистанции.
- Лучше всего раскрывается в ближнем бою, особенно при использовании барабанного магазина.
- Барабанный магазин на 71-73 патрона выглядит внушительно, но увеличивает массу оружия и не отличался идеальной надёжностью.
