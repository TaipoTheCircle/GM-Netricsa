АВТОМАТ КАЛАШНИКОВА СКЛАДНОЙ АКС-74


ОРУЖИЕ:  Автомат Калашникова Складной АКС-74
ПАТРОНЫ: 5,45x39 мм
СС:      ~600-650 выстрелов / мин.
ВЕС:     ~2,97 кг.

ОПИСАНИЕ:

Cкладной вариант автомата АК-74, разработанный специально для воздушно-десантных войск и других высокомобильных подразделений. Был принят на вооружение в 1979 году. В отличие от обычного АК-74, АКС-74 получил складывающийся металлический приклад, благодаря чему стал удобнее при перевозке и использовании в ограниченном пространстве.

Автомат использует патрон 5,45x39 мм, магазин на 30 патронов и способен вести одиночный и автоматический огонь. Темп стрельбы составляет примерно 600-650 выстрелов в минуту. Эффективная дальность оценивается примерно в 300-400 метров.

ПРИМЕЧАНИЯ:

- Десантники счастливы.
- Создавался прежде всего для десантников и высокомобильных подразделений.
- Складной приклад делает автомат значительно удобнее при перевозке.
- Патрон 5,45x39 мм обеспечивает меньшую отдачу по сравнению с АКМ под 7,62x39 мм.
