ПРОТИВОТАНКОВЫЙ ГРАНАТОМЁТ RPzB. 43 "ОФЕНРОР"


ОРУЖИЕ:  Противотанковый гранатомёт RPzB. 43 "Офенрор"
ПАТРОНЫ: 88-ммРеактивная Противотанковая Граната
СС:      ~4-6 выстрелов / мин.
ВЕС:     ~9,5 кг.

ОПИСАНИЕ:

Немецкий ручной противотанковый гранатомёт времён Второй мировой войны. Он появился в 1943 году как развитие идеи американской "Базуки" и предназначался для борьбы с танками и другой бронетехникой.

Граната запускается из открытой металлической трубы с помощью реактивного двигателя. В отличие от более позднего Панцершрека, RPzB. 43 не имел защитного щитка, поэтому стрелку приходилось использовать специальную защиту лица и глаз. При выстреле позади трубы образуется мощная струя горячих газов, поэтому находиться непосредственно за гранатомётом было крайне опасно.

88-мм кумулятивная граната обладала высокой бронепробиваемостью и позволяла поражать большинство танков того периода. Эффективная дальность стрельбы составляла примерно 150 метров.

ПРИМЕЧАНИЯ:

- Предназначен прежде всего для уничтожения танков и других бронированных целей.
- Реактивная струя выходит прямо из задней части трубы, поэтому стрелку требовалось соблюдать особую осторожность.
- В отличие от Панцершрека, защитного щитка здесь нет. Позднее его появление стало одним из главных улучшений конструкции.
- "Офенрор" переводится как "Печная Труба". Но после появления Панцершрека ситуация стала ещё смешнее: сначала была печная труба, потом появился Шрек. Видимо, немецкая противотанковая промышленность действительно пошла по "сказочному" пути.
