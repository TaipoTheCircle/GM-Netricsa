ПИСТОЛЕТ-ПУЛЕМЁТ MP-41(R)


ОРУЖИЕ:  Пистолет-Пулемёт MP-41(R)
ПАТРОНЫ: 9x19 мм Parabellum
СС:      ~1000 выстрелов / мин.
ВЕС:     ~3,8-4,5 кг.

ОПИСАНИЕ:

MP-41(R) был немецким вариантом трофейного советского ППШ-41, переделанным под немецкий пистолетный патрон 9x19 мм Parabellum. Переделка появилась в 1944 году на фоне нехватки боеприпасов к захваченным ППШ, которые в немецком обозначении проходили как MP-717(R). Для использования немецких боеприпасов в конструкцию внесли изменения, позволившие применять стандартные магазины от MP-40.

По сути, MP-41(R) сохранил основу ППШ-41, включая характерную компоновку и деревянные элементы, но получил немецкую систему питания и патрон 9x19 мм. Оружие могло вести как одиночный, так и автоматический огонь. Темп стрельбы составлял около 1000 выстрелов в минуту, а эффективная дальность оценивалась примерно в 200-300 метров.

Всего было изготовлено более 10 000 таких переделанных пистолетов-пулемётов. Получился довольно необычный гибрид: советская конструкция ППШ, немецкий патрон и магазин от MP-40.

ПРИМЕЧАНИЯ:

- Очень высокая скорострельность позволяет создавать плотный огонь на ближней и средней дистанции.
- Главная особенность MP-41(R) заключается в сочетании советской основы ППШ с немецким 9-мм боеприпасом и магазином MP-40.
- Благодаря возможности одиночного огня оружие можно использовать более экономно, не превращая каждый контакт в непрерывную очередь.
- ППШ надел немецкую форму, взял магазин от MP-40 и отправился обратно на фронт. История оружия иногда любит такие кроссоверы.
