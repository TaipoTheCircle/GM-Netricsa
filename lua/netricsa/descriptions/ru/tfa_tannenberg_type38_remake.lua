МАГАЗИННАЯ ВИНТОВКА АРИСАКА ТИП 38


ОРУЖИЕ:  Магазинная Винтовка Арисака Тип 38
ПАТРОНЫ: 6,5x50 мм SR Arisaka
СС:      ~10-15 Выстрелов / Мин

ОПИСАНИЕ:

Японская магазинная винтовка, разработанная в 1905 году на основе предыдущей модели Тип 30 под руководством генерала Нариакэ Арикасы. Принята на вооружение Императорской армии Японии в том же году. Предназначалась для оснащения пехотных подразделений и постепенно стала основным стрелковым оружием японской армии. По сравнению с предшественницей получила усовершенствованный затвор, повышенную надёжность и защитную крышку ствольной коробки от попадания грязи и пыли.

Работает по принципу продольно-скользящего поворотного затвора с ручным перезаряжанием. Использует патрон 6,5x50 мм SR Arisaka и встроенный коробчатый магазин на 5 патронов. Заряжание производится при помощи обоймы. Оснащена деревянной ложей, открытыми механическими прицельными приспособлениями и креплением для штыка. Благодаря длинному стволу и относительно небольшому импульсу отдачи отличается хорошей точностью и удобством стрельбы.

ПРИМЕЧАНИЯ:

- Хорошо подходит для поражения одиночных целей на средних и дальних дистанциях.
- Эффективна против незащищённой живой силы.
- Обладает умеренной отдачей и хорошей точностью.
- Не предназначена для борьбы с бронетехникой и тяжёлыми укрытиями.
- Использовалась во время Первой и Второй мировых войн.
- Существовала укороченная версия Тип 38 Carbine.
- На её основе была создана снайперская винтовка Тип 97.
