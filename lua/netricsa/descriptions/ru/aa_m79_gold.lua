ГРАНАТОМЁТ M79 GOLD


ОРУЖИЕ:  Гранатомёт M79 GOLD
ПАТРОНЫ: 40x46 мм
СС:      ~6-7 выстрелов / мин.
ВЕС:     ~2,93 кг.

ОПИСАНИЕ:

Американский однозарядный ручной гранатомёт, разработанный для поражения противника на дистанциях, недоступных обычным ручным гранатам. Он получил широкое распространение во время войны во Вьетнаме и использовался как лёгкое средство огневой поддержки пехоты.

Гранатомёт имеет переламывающийся ствол, через который устанавливается один 40-мм выстрел. После выстрела ствол открывается, стреляная гильза извлекается, после чего можно установить следующий боеприпас. Такая конструкция делает M79 простым и достаточно надёжным оружием, хотя стрелку приходится перезаряжать его после каждого выстрела.

M79 способен использовать различные типы 40-мм боеприпасов, включая осколочные, дымовые и другие специальные выстрелы. Основное назначение оружия заключается в поражении групп противников и целей за укрытиями.

ПРИМЕЧАНИЯ:

- Особенно эффективен против групп противников и целей, находящихся за укрытиями.
- На средней дистанции позволяет доставлять гранаты значительно дальше, чем обычный ручной бросок.
- Не стоит забывать о радиусе действия гранаты. Слишком близкий выстрел способен превратить проблему в коллективную.
- Однозарядная конструкция требует перезарядки после каждого выстрела, поэтому промах лучше не превращать в серию из трёх промахов.
- "Пум!" - звук, после которого противнику обычно становится очень интересно, куда именно прилетела граната.
