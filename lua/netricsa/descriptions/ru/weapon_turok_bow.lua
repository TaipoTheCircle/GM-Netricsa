СОСТАВНОЙ ЛУК ORO C9 "ПЕРФОРАТОР"


ОРУЖИЕ:  Составной Лук ORO C9 "Перфоратор"
ПАТРОНЫ: Стальные И Взрывные Стрелы

ОПИСАНИЕ:

Современный составной лук, рассчитанный на бесшумное поражение целей на большой дистанции. При полном натяжении стрела получает огромную пробивную силу, позволяя одним выстрелом уничтожить противника или пригвоздить его к стене.

Вторичный режим использует Tek-стрелы со взрывным наконечником. Обычных стрел можно носить до 50, а специальных Tek-стрел до 10. Благодаря оптическому увеличению лук отлично подходит для скрытой стрельбы и дальних выстрелов.

ПРИМЕЧАНИЯ:

- Работает практически бесшумно.
- Полностью натянутая стрела способна буквально прибить врага к стене.
- Tek-стрелы превращают тихий лук в довольно шумный способ решения проблем.
