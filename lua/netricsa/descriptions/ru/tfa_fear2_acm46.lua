ПИСТОЛЕТ SEEGERT ACM46


ОРУЖИЕ:     Пистолет Seegert ACM46
ПАТРОНЫ:    9x19 мм Парабеллум
СС:         Полуавтоматический

ОПИСАНИЕ:

Современный самозарядный пистолет, разработанный корпорацией Seegert для вооружённых подразделений. Используется в качестве штатного личного оружия солдат Armacham, подразделений Delta Force и Replica Forces.

ACM46 оснащён полимерной рамкой повышенной прочности, затвором из нержавеющей стали и тритиевыми прицельными приспособлениями. Работает по принципу отдачи ствола с коротким ходом и использует запираемый затвор. Магазин вмещает 18 патронов. Отличается хорошей точностью и приличной останавливающей способностью, однако эффективная дальность стрельбы остаётся ограниченной.

ПРИМЕЧАНИЯ:

- Магазин рассчитан на 18 патронов.
- Оснащён тритиевыми прицельными приспособлениями для стрельбы при слабом освещении.
- Имеет универсальную крепёжную систему для дополнительных аксессуаров.
- Внешне напоминает немецкий Heckler & Koch USP.
- Несмотря на статус запасного оружия, обладает весьма приличной огневой мощью.
