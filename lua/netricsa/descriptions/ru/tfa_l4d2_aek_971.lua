АВТОМАТ АЕК-971


ОРУЖИЕ:  Автомат АЕК-971
ПАТРОНЫ: 5,45x39 мм
СС:      ~900 выстрелов / мин

ОПИСАНИЕ:

Советский автомат, разработанный в 1978 году на Ковровском механическом заводе под руководством конструктора Станислава Кокшарова. Создавался для участия в конкурсе "Абакан" в качестве перспективной замены автоматам семейства Калашникова. Отличается традиционной компоновкой и использованием сбалансированной автоматики, предназначенной для уменьшения отдачи и повышения кучности стрельбы.

Работает на принципе отвода пороховых газов с запиранием поворотом затвора. Главная особенность конструкции заключается в наличии дополнительного балансира, движущегося в противоположном направлении относительно затворной группы. Питается из стандартных магазинов на 30 патронов. Имеет три режима огня: одиночный, автоматический и очередями с отсечкой по три выстрела.

ПРИМЕЧАНИЯ:

- Разработан Станиславом Кокшаровым.
- Участвовал в советском конкурсе "Абакан", уступив автомату АН-94.
- Сбалансированная автоматика уменьшает подброс ствола при стрельбе.
- Кучность очередями превосходит аналогичный показатель АК-74М в 1,5-2 раза.
- Существуют варианты АЕК-972 под патрон 5,56x45 мм НАТО и АЕК-973 под 7,62x39 мм.
