ВИНТОВКА LEE-ENFIELD


ОРУЖИЕ:  Винтовка Lee-Enfield
ПАТРОНЫ: .303 British (7,7×56 мм R)
СС:      ~20–30 выстрелов / мин.
ВЕС:     ~3,96 кг.

ОПИСАНИЕ:

Британская магазинная винтовка с продольно-скользящим затвором, служившая основной винтовкой британских вооружённых сил и армий Содружества на протяжении первой половины XX века. На вооружении Великобритании она официально находилась с 1895 по 1957 год.

Винтовка использует магазин на 10 патронов, который можно быстро снаряжать обоймами по пять патронов. Благодаря удачной конструкции затвора стрелок способен быстро производить повторные выстрелы, не теряя положения прицела. Именно высокая скорость работы затвора стала одной из главных особенностей Lee-Enfield.

Основным боеприпасом является .303 British. В зависимости от модели масса винтовки составляет примерно 4 кг. Эффективная дальность стрельбы находится примерно в районе 500 метров.

ПРИМЕЧАНИЯ:

- Эффективна на средней и дальней дистанции.
- Быстрый затвор позволяет очень быстро делать повторные выстрелы.
- Магазин можно быстро заполнить двумя пятизарядными обоймами.
- Мощный патрон .303 British обеспечивает хорошую дальность и поражающую способность.
- Обученный стрелок способен вести огонь значительно быстрее, чем можно ожидать от обычной винтовки с ручным затвором.
- На дальней дистанции винтовка раскрывает себя лучше всего, особенно при стрельбе по отдельным целям.
- Это не автоматическое оружие, поэтому после каждого выстрела необходимо работать затвором.
- Особенно хорошо подходит для стрелка, который умеет быстро работать с затвором и не тратить патроны попусту.
