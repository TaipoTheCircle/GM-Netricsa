КЛИМАТ:         Мягкий, влажный
СПУТНИКИ:       Неизвестно
ЛАНДШАФТ:       Огромные каньоны, гигантские грибные леса, открытые равнины, поля мега-злаков
РАСПОЛОЖЕНИЕ:   Неизвестная звёздная система, контролируемая Ордой Ментала
МЕСТНЫЕ РАСЫ:   Гигантские голуби, порабощённые фермеры Бримленда
ПРИНАДЛЕЖНОСТЬ: Фермеры Бримленда (Ранее), Орда Ментала (Сейчас)
МЕСТА:          Каньоны гнездования, Грибные леса, Поля мега-злаков, Каменные солончаки, Базы тренировочных лагерей

ОПИСАНИЕ:

Представляет собой уникальный мир, чьи природные условия идеально подходят для существования гигантских летающих существ. Планета обладает плотной атмосферой, облегчающей удержание в воздухе массивных тел, низкой гравитацией, позволяющей крупным существам взлетать без колоссальных затрат энергии, и высоким уровнем кислорода, обеспечивающим сверхэффективный метаболизм для полета тяжелых птиц.

Ландшафт планеты формируют огромные каньоны, заменяющие городские карнизы для гнездования птиц титанических размеров, гигантские грибные леса, выдерживающие вес многотонных особей, и обилие открытых равнин, необходимых для разбега и посадки крупных летающих существ. Кормовая база включает поля мега-злаков с семенами размером с арбуз, гигантских насекомых и каменные солончаки.

После завоевания планеты силами Ментала Бримленд был перепрофилирован в военный комплекс. Местные гигантские голуби стали основой для создания Летающих Клиров - гибридных существ, сочетающих плоть птиц и скелеты скота, погибших при бомбардировке планеты Клир. Процесс слияния осуществляется с помощью технологии "Скин-о-мастер", которая соединяет органическую и костяную ткани, создавая послушных и смертоносных летающих солдат.

После четырёх лет интенсивных тренировок и генетической адаптации эти существа были интегрированы в Военно-воздушные силы Ментала. Планета продолжает функционировать как инкубатор, где голубей выращивают, скрещивают и обучают для последующей отправки в зоны боевых действий.

КЛЮЧЕВЫЕ МЕСТА:

- Каньоны гнездования: Естественные скальные образования, используемые для выведения и первичного содержания гигантских голубей до начала их трансформации.
- Грибные леса: Массивные лесные массивы, служащие укрытиями для тренировочных лагерей и временных складов.
- Поля мега-злаков: Основная кормовая зона для взрослых особей, также используемая для откорма молодняка перед процедурой слияния.
- Каменные солончаки: Места добычи минералов, необходимых для укрепления костной ткани голубей перед имплантацией скелетов Клиров.
- Базы тренировочных лагерей: Укреплённые комплексы, где осуществляется финальная подготовка и боевое слаживание Летающих Клиров перед отправкой.
