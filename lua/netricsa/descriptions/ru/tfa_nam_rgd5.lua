РУЧНАЯ ОСКОЛОЧНАЯ ГРАНАТА РГД-5


ОРУЖИЕ:  Ручная Осколочная Граната РГД-5
ПАТРОНЫ: Одна Граната
СС:      Один Бросок За Минуту

ОПИСАНИЕ:

Советская ручная осколочная граната наступательного типа, разработанная и принятая на вооружение в 1954 году. Предназначена для поражения живой силы противника осколками корпуса и взрывной волной. Имеет компактный овальный корпус из тонкой стали, состоящий из двух основных частей. По сравнению с более ранней РГ-42 отличается меньшей массой и более обтекаемой формой.

Состоит из металлического корпуса, разрывного заряда и запала дистанционного действия. Снаряжённая граната весит около 310 граммов. В качестве взрывчатого вещества используется тротил. В разные годы применялись запалы УЗРГ, УЗРГМ и УЗРГМ-2. Благодаря небольшому весу и компактным размерам получила широкое распространение в Советской армии и армиях ряда других государств.

ПРИМЕЧАНИЯ:

- Отличается от Ф-1 более лёгким корпусом и меньшей массой.
- Использовалась в Советской армии и продолжает встречаться в вооружённых конфликтах.
- Принята на вооружение в 1954 году.
- Заменила более раннюю гранату РГ-42.
- Относится к наступательному типу.
