АВТОМАТ КАЛАШНИКОВА АК-74М


ОРУЖИЕ:  Автомат Калашникова АК-74М
ПАТРОНЫ: 5,45x39 мм
СС:      ~600 выстрелов / мин.
ВЕС:     ~3,4 кг.

ОПИСАНИЕ:

Советский и российский автомат, созданный как модернизированный вариант АК-74. Он был принят на вооружение в 1991 году и стал одним из основных автоматов Вооружённых сил России. АК-74М сохранил характерную для семейства АК надёжность, но получил ряд улучшений, включая складной пластиковый приклад и боковую планку для установки оптических и ночных прицелов.

Автомат использует патрон 5,45x39 мм и магазин на 30 патронов. Благодаря сравнительно небольшой массе патрона и умеренной отдаче АК-74М удобно контролировать при стрельбе очередями. Конструкция рассчитана на эксплуатацию в различных климатических условиях.

ПРИМЕЧАНИЯ:

- Основной российский автомат семейства АК на протяжении многих лет.
- Патрон 5,45x39 мм обеспечивает меньшую отдачу по сравнению с 7,62x39 мм.
- Боковая планка позволяет устанавливать различные прицелы.
- АК-47 был дедушкой, АК-74 стал сыном, а АК-74М пришёл на семейный совет уже со складным прикладом.
