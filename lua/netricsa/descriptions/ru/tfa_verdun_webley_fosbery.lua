АВТОМАТИЧЕСКИЙ РЕВОЛЬВЕР WEBLEY-FOSBERY


ОРУЖИЕ:   Автоматический револьвер Webley-Fosbery
ПАТРОНЫ:  .455 Webley Mk II
СС:       ~60-80 выстрелов / мин.
ВЕС:      ~1,24 кг.

ОПИСАНИЕ:

Необычный британский автоматический револьвер, разработанный полковником Джорджем Фосбери и выпускавшийся компанией Webley & Scott с 1901 по 1924 год. Он сочетал мощный патрон .455 Webley с автоматической перезарядкой, что для револьвера того времени было весьма необычным решением.

Главная особенность конструкции заключается в том, что после выстрела верхняя часть револьвера со стволом, барабаном и курком откатывается назад под действием отдачи. При этом специальный зигзагообразный паз на барабане заставляет его повернуться и одновременно взводит курок. Таким образом, следующий выстрел можно сделать практически сразу после предыдущего.

Версия под .455 Webley имела шестизарядный барабан. Существовал также вариант под .38 ACP с восьмизарядным барабаном. Всего было изготовлено около 4750 револьверов, поэтому сегодня Webley-Fosbery является довольно редким образцом.

ПРИМЕЧАНИЯ:

- Автоматическая система позволяет быстро производить повторные выстрелы без ручного взведения курка.
- Особенно интересен для точной и скоростной стрельбы, поскольку работа автоматики частично смягчает ощущение отдачи.
- Знаменитые зигзагообразные канавки на барабане являются частью механизма перезарядки, а не просто украшением.
