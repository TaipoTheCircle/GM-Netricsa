ПИСТОЛЕТ-ПУЛЕМЁТ СССР ПУШКА


ОРУЖИЕ:  Пистолет-пулемёт СССР Пушка
ПАТРОНЫ: Энергетические снаряды
СС:      ~750 выстрелов / мин 

ОПИСАНИЕ:

Необычный пистолет-пулемёт, созданный на основе конструкции SMG1 (MP7). Вместо обычных пуль оружие выпускает радужные энергетические лучи, которые при попадании формируют в месте удара светящийся символ СССР ☭. После появления символ постепенно улетает и исчезает.

При удержании оружия начинает звучать гимн СССР. Каждый первый выстрел перезапускает музыкальную композицию с самого начала, а после прекращения стрельбы музыка затихает. Для того чтобы опять начать играть. СССР Пушка имеет два альтернативных режима огня: первый выпускает несколько энергетических снарядов одновременно, напоминая стрельбу из дробовика; второй использует подствольный гранатомёт, запускающий снаряды в форме логотипа USSSR ☭ с аналогичным эффектом при попадании.

ПРИМЕЧАНИЯ:

- Основан на модели пистолета-пулемёта SMG1 (MP7).
- Основной огонь создаёт радужные лучи и советскую символику в точках попадания.
- Первый альтернативный режим позволяет вести залповый огонь, подобно дробовику.
- Подствольный гранатомёт выпускает крупные снаряды с логотипом СССР ☭.
- Гимн СССР сопровождает оружие и перезапускается при каждом первом выстреле. 
