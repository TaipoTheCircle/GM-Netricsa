РПГ ORO "КРАСНЫЙ КУЛАК"


ОРУЖИЕ:  РПГ ORO "Красный Кулак"
ПАТРОНЫ: Реактивные Гранаты
СС:      ~15 выстрелов / мин.
ВЕС:     ~7-8 кг.

ОПИСАНИЕ:

Мощная переносная ракетная установка производства ORO. Оружие запускает одну ракету с высокой скоростью, которая при попадании взрывается с большой разрушительной силой, поражая цель и всё вокруг неё. Боезапас ограничен, однако каждая ракета обладает настолько высокой мощностью, что один точный выстрел способен решить исход столкновения.

Оружие имеет два режима. Первый представляет собой обычный неуправляемый запуск, при котором ракета летит прямо в направлении прицела. Второй активирует систему захвата цели: после фиксации ракета самостоятельно корректирует траекторию и преследует выбранную цель, что особенно полезно против быстро движущихся объектов и техники.

ПРИМЕЧАНИЯ:

- Очень высокий урон одной ракеты.
- Большой радиус взрыва позволяет поражать несколько целей одновременно.
- Первый режим: обычный прямой запуск.
- Второй режим: захват цели и самонаведение по принципу "выстрелил и забыл".
- Эффективен на средней и дальней дистанции.
- Особенно полезен против движущейся техники и крупных целей.
- Магазин рассчитан на 1 ракету, общий запас при подборе оружия составляет до 10 ракет.
- Большой вес оружия снижает мобильность стрелка.
