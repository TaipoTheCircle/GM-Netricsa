АВТОМАТИЧЕСКАЯ ВИНТОВКА БРАУНИНГ M1918 (BAR)


ОРУЖИЕ:  Автоматическая Винтовка Браунинг M1918 (BAR)
ПАТРОНЫ: .30-06 Springfield (7,62×63 мм)
СС:      ~500–650 выстрелов / мин.
ВЕС:     ~7,25 кг.

ОПИСАНИЕ:

Автоматическая Винтовка Браунинг, более известная как BAR, представляет собой американский ручной пулемёт, разработанный Джоном Мозесом Браунингом. Созданный в период Первой мировой войны, он сочетает винтовочную мощность патрона .30-06 с возможностью вести автоматический огонь.

BAR питается из коробчатого магазина на 20 патронов. Оружие отличается высокой мощностью и хорошей точностью, однако его значительный вес и небольшой магазин делают длительный непрерывный огонь менее удобным. В бою BAR может использоваться как для точных одиночных выстрелов, так и для коротких очередей по группам противников.

ПРИМЕЧАНИЯ:

- Эффективен на средней и дальней дистанции благодаря мощному винтовочному патрону.
- Высокая точность позволяет использовать его не только для подавления, но и для поражения отдельных целей.
- Стандартный магазин вмещает 20 патронов.
- Мощный патрон .30-06 способен эффективно поражать хорошо защищённые и удалённые цели.
- Большой вес делает оружие неудобным для длительного ведения огня с рук.
- При автоматической стрельбе лучше использовать короткие очереди, чтобы контролировать отдачу и не опустошить магазин за считанные секунды.
- Это скорее тяжёлая автоматическая винтовка, чем современный ручной пулемёт.
- Если противник думает, что винтовка должна стрелять медленно, BAR может его разочаровать.
