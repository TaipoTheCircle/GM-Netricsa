ПИСТОЛЕТ-ПУЛЕМЁТ ANDRA FD-99


ОРУЖИЕ:  Пистолет-Пулемёт Andra FD-99
ПАТРОНЫ: 5,7x28 мм
СС:      ~900-1000 выстрелов / мин

ОПИСАНИЕ:

Лёгкий пистолет-пулемёт, разработанный компанией Andra для вооружённых подразделений корпорации Armacham Technology Corporation. Предназначен преимущественно для ближнего боя. Отличается компактной конструкцией, складным прикладом, низкой отдачей и высокой скорострельностью. Питание осуществляется из вместительного магазина на 50 патронов.

FD-99 использует стрельбу с закрытого затвора и оснащён коллиматорным прицелом с небольшим увеличением. Позволяет выбирать между автоматическим огнём и очередями по три выстрела. Несмотря на сравнительно небольшую мощность отдельных попаданий, оружие компенсирует её высокой плотностью огня, хорошей управляемостью и большим боезапасом.

ПРИМЕЧАНИЯ:

- Использует необычный для пистолета-пулемёта патрон 5,7x28 мм.
- Магазин вмещает 50 патронов, общий запас может достигать 500.
- Конструкция магазина вдохновлена FN P90, а внешний вид корпуса напоминает FN F2000.
- Оснащён коллиматорным прицелом и боковым фонарём LIGHTBRINGER.
- Высокая скорострельность и вместительный магазин позволяют буквально засыпать противника свинцом.
