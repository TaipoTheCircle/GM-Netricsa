САМОЗАРЯДНАЯ ВИНТОВКА MAS-49


ОРУЖИЕ:  Самозарядная Винтовка MAS-49
ПАТРОНЫ: 7,5x54 мм French
СС:      Полуавтоматический Огонь, 10 Патронов

ОПИСАНИЕ:

Французская самозарядная винтовка, разработанная и производившаяся государственным оружейным предприятием Manufacture d'armes de Saint-Étienne (MAS). Создана на основе предыдущих экспериментальных разработок французских оружейников и принята на вооружение в 1949 году. Предназначалась для замены устаревших магазинных винтовок и стала основным индивидуальным оружием французской армии в послевоенный период. Отличается деревянной ложей, характерным расположением газоотводной трубки над стволом и простой, надёжной конструкцией.

Автоматика работает за счёт прямого отвода пороховых газов к затворной раме, без использования отдельного газового поршня. Запирание осуществляется перекосом затвора. Использует французский винтовочный патрон 7,5x54 мм и съёмный коробчатый магазин на 10 патронов. Также допускается заряжание при помощи обойм на 5 патронов, для чего предусмотрены направляющие на затворной группе. Слева на ствольной коробке расположена специальная направляющая для установки оптического прицела APX. 

ПРИМЕЧАНИЯ:

- Принята на вооружение французской армии в 1949 году.
- Масса составляет около 4,7 кг, общая длина 1100 мм.
- Начальная скорость пули достигает примерно 820 м/с.
- Эффективная дальность стрельбы составляет около 400 метров, с оптическим прицелом может достигать 800 метров.
- Существует укороченная модификация MAS-49/56, получившая более компактные габариты и возможность установки штыка.
- Прямой отвод пороховых газов позднее получил широкую известность благодаря применению в американских винтовках семейства AR-15.
