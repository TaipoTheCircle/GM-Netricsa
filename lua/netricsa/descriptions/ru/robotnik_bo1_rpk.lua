РУЧНОЙ ПУЛЕМЁТ КАЛАШНИКОВА РПК


ОРУЖИЕ:     Ручной пулемёт Калашникова РПК
ПАТРОНЫ:    7,62x39 мм
СС:         ~600 выстрелов / мин

ОПИСАНИЕ:

Советский ручной пулемёт, разработанный Михаилом Калашниковым на базе автомата АКМ и принятый на вооружение в 1961 году. Предназначен для повышения огневой мощи пехотного отделения. Отличается удлинённым и утяжелённым стволом, усиленной ствольной коробкой, сошками и деревянным прикладом.

РПК использует газоотводную автоматику с поворотным затвором и способен вести одиночный и автоматический огонь. Питание осуществляется из коробчатых магазинов на 40 патронов или барабанных на 75 патронов. Благодаря унификации с автоматами Калашникова пулемёт прост в обслуживании и надёжен в эксплуатации.

ПРИМЕЧАНИЯ:

- Создан на основе автомата АКМ.
- Удлинённый ствол позволяет эффективнее вести огонь на увеличенных дистанциях.
- Барабанный магазин на 75 патронов заметно увеличивает запас боеприпасов.
- РПК получил множество модификаций, включая варианты под патроны 5,45x39 мм.
- Если обычного Калашникова недостаточно, можно просто добавить сошки и побольше патронов.
