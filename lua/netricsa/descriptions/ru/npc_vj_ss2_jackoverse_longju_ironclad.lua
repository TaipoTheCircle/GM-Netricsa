ОПИСАНИЕ:

Лунцзюй, известный в своём народе как Железночешуй, является древним воином с Дракониуса, происходившим из воинственной расы драконоидов. Его народ придерживался строгих самурайских законов и ценил честь, боевое мастерство и силу превыше всего.

Когда-то Лунцзюй был живым воином и прославился многочисленными победами. Однако его жизнь закончилась в одном из сражений. Вместо того чтобы окончательно исчезнуть, его дух каким-то образом сохранился, превратившись в подобие древнего божества, заключённого в материальном теле.

Позднее некий Мастер тёмных искусств сумел обманом подчинить Лунцзюя и заточить его в собственном посохе. С тех пор Железночешуй вынужден служить своему хозяину, сохранив при этом боевые навыки и ярость, накопленные за долгие годы существования.

Внешне Лунцзюй напоминает массивного драконоида, облачённого в тяжёлую самурайскую броню. Несмотря на драконье происхождение, он не имеет ни хвоста, ни крыльев, а его тело больше напоминает ожившую статую древнего воина. На голове расположено шесть глаз, позволяющих ему одновременно контролировать окружающее пространство.

Его левая рука была полностью заменена массивной ядровой пушкой. Оружие способно выпускать тяжёлые ядра, превращая самого Лунцзюя в ходячее осадное орудие. Один такой выстрел способен нанести огромный физический ущерб и пробить тяжёлую защиту.

Вторая рука вооружена вытягивающейся боевой булавой. При атаке оружие может резко увеличиваться в длине, позволяя Лунцзюю поражать противников на расстоянии, недоступном обычному бойцу ближнего боя. Удар этой булавы способен смять броню и человека вместе с ней.

Среди его врагов ходят легенды о способности создавать летающие глаза в пространстве. Согласно этим рассказам, глаза способны самостоятельно следить за противниками и даже выпускать лазерные лучи. Достоверность этих сведений неизвестна, однако встречавшие Лунцзюя утверждают, что чувствовали на себе взгляд сразу из нескольких направлений.

Сам Лунцзюй практически не проявляет эмоций. Он не ведёт себя как обычный зверь или безумный монстр. В бою он сохраняет дисциплину древнего воина, методично выбирая цели и уничтожая наиболее опасных противников.

Его броня выдерживает огромное количество повреждений, а сверхъестественная природа делает Железночешуя значительно более живучим, чем обычного драконоида.

СОВЕТЫ:

- Не подходи близко. Вытягивающаяся булава превращает ближний бой с Лунцзюем в крайне плохую идею.
- Следи за ядрами. Его ядровая пушка способна нанести огромный урон даже тяжёлым целям.
- Если легенды о летающих глазах и лазерных атаках верны, Железночешуй может обнаружить противника с нескольких направлений.
- Не недооценивай его из-за отсутствия крыльев. Лунцзюй не нуждается в них, чтобы оставаться чрезвычайно опасным противником.
- Помни, что перед тобой не просто монстр. Это древний воин, сохранивший боевой опыт даже после смерти.
