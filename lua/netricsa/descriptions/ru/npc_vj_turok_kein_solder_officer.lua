СОЛДАТ-ОФИЦЕР МЕНДЕЛЬ-ГРУМАН


КЛАСС:        Солдат-Офицер Мендель-Груман
МЕТАБОЛИЗМ:   Человек, Мужчина
ВОСПРИЯТИЕ:   Стандартная Пехота
РАЗМЕР:       ~1,8 м.
ВЫНОСЛИВОСТЬ: Средняя
ВРАЖДЕБНОСТЬ: Высокая
ОРУЖИЕ:       Пистолет ORO HOG 9mm, Осколочные Гранаты
НАГРАДА:      200
УГРОЗА:       Низкая

ОПИСАНИЕ:

Является основным и наиболее распространённым солдатом корпорации Мендель-Груман. Именно эти бойцы составляют костяк её вооружённых сил и встречаются на протяжении практически всей операции на планете. В отличие от тяжёлых подразделений, Офицер не обладает каким-либо специализированным вооружением или сложной бронёй. Его задача куда прозаичнее: идти в составе группы и стрелять во всё, что не имеет эмблемы Мендель-Груман.

Экипировка Офицера представляет собой относительно лёгкую, но практичную броню с большим количеством подсумков и полностью укомплектованным тактическим поясом. Защищены практически все жизненно важные участки тела, однако суставы оставлены более подвижными. Стандартная форма встречается преимущественно в тёмно-синем варианте.

Лицо закрыто защитным шлемом с динамическим визором. Его цвет меняется в зависимости от состояния бойца: синий означает обычное состояние, жёлтый повышенную настороженность, а красный максимальную боевую готовность. Получается довольно удобный индикатор: солдат буквально показывает на лице, насколько сильно ему сейчас не нравится происходящее.

Основным оружием Офицер является Пистолет ORO HOG 9mm. Кроме того, стандартный солдат располагает осколочными гранатами. При определённых обстоятельствах отдельные Офицеры могут использовать и другое оружие, не смотря на то, что это не является их обычным вооружением.

Главная сила Офицера заключается не в индивидуальной живучести. Напротив, сами по себе они сравнительно слабы и довольно быстро погибают под сосредоточенным огнём. Однако Мендель-Груман компенсирует это численностью и групповыми действиями. Обычно Офицеры действуют небольшими отрядами по два-три человека, стараясь использовать укрытия и вести огонь одновременно.

Они способны перемещаться по полю боя, менять позиции и атаковать с разных направлений. Поэтому один Офицер представляет умеренную угрозу, тогда как несколько бойцов уже способны создать плотную стрелковую линию. Особенно неприятно становится, когда обычную группу поддерживают более сильные союзники.

СОВЕТЫ:

- Не недооценивай их из-за слабой брони. Главная опасность Офицера заключается в количестве.
- Гранаты особенно эффективны против групп. Несколько Офицеров часто стоят достаточно близко друг к другу.
- Используй укрытия, если против тебя одновременно работает несколько бойцов.
- Если видишь красный визор, солдат уже находится в полной боевой готовности.
- Следи за окружением: отдельные бойцы могут оказаться вооружены необычным для Офицера оружием.
