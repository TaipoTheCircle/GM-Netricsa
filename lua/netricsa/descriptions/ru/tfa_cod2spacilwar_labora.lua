ПИСТОЛЕТ-ПУЛЕМЁТ LABORA FONTBERNAT M-1938


ОРУЖИЕ:  Пистолет-пулемёт Labora Fontbernat M-1938
ПАТРОНЫ: 9x23 мм Largo
СС:      ~750 выстрелов / мин.
ВЕС:     ~4,38 кг.

ОПИСАНИЕ:

Labora Fontbernat M-1938, также известный как Labora, испанский пистолет-пулемёт каталонского происхождения, разработанный в 1936 году и выпускавшийся в 1936-1938 годах на фабрике №15. Он использовался обеими сторонами Гражданской войны в Испании, а небольшая часть оружия продолжила службу и после войны. Всего было изготовлено примерно 1000-2000 экземпляров.

Пистолет-пулемёт изготовлен преимущественно из обработанной стали и использует автоматику со свободным затвором. Оружие рассчитано на мощный испанский патрон 9x23 мм Largo и получает боеприпасы из коробчатого магазина на 36 патронов. При темпе около 750 выстрелов в минуту Labora способен создавать довольно плотный огонь на ближней дистанции.

Конструкция M-1938 довольно массивная для пистолета-пулемёта: при пустом магазине оружие весит около 4,38 кг. При этом его производство было сравнительно ограниченным, поэтому сегодня Labora Fontbernat является гораздо менее известным образцом испанского оружия Гражданской войны.

ПРИМЕЧАНИЯ:

- Всего около пары тысяч экземпляров, зато успел повоевать практически со всеми сторонами испанского конфликта.
- Темп около 750 выстрелов в минуту позволяет вести очень плотный огонь на ближней дистанции.
- Оружие использовалось и республиканцами, и националистами во время Гражданской войны в Испании.
- Патрон 9x23 мм Largo мощнее распространённого 9x19 мм Parabellum, но это делает оружие довольно специфическим.
