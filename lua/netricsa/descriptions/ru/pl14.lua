ПИСТОЛЕТ ЛЕБЕДЕВА PL-14


ОРУЖИЕ:  Пистолет Лебедева PL-14
ПАТРОНЫ: 9x19 мм Parabellum
СС:     ~40-50 выстрелов / мин.
ВЕС:    ~0,8 кг.

ОПИСАНИЕ:

Российский самозарядный пистолет, разработанный командой Дмитрия Лебедева в концерне "Калашников". Впервые он был представлен в 2015 году на форуме "Армия-2015" как перспективный пистолет для вооружённых сил и правоохранительных органов. Позднее конструкция была переработана и получила обозначение PL-15.

PL-14 использует патрон 9x19 мм Parabellum и магазин на 15 патронов. Пистолет создавался с большим вниманием к эргономике: рукоятка имеет удобную форму, органы управления рассчитаны на использование обеими руками, а низкая линия ствола должна помогать быстрее возвращать оружие на линию прицеливания после выстрела.

При длине около 220 мм и массе около 800 граммов PL-14 получился достаточно крупным, но сравнительно лёгким служебным пистолетом. В дальнейшем именно эта разработка стала основой семейства PL-15, PL-15K и других вариантов.

ПРИМЕЧАНИЯ:

- Низкая линия ствола и эргономичная рукоятка рассчитаны на удобную и быструю стрельбу.
- Органы управления выполнены с расчётом на использование как правой, так и левой рукой.
- PL-14 стал предшественником современного семейства пистолетов Лебедева.
