ПРОТИВОТАНКОВЫЙ ГРАНАТОМЁТ M1 "БАЗУКА"


ОРУЖИЕ:  Противотанковый Гранатомёт M1 "Базука"
ПАТРОНЫ: 60-мм реактивные противотанковые гранаты
СС:      ~4-6 выстрелов / мин.
ВЕС:     ~6,8-8 кг.

ОПИСАНИЕ:

Американский ручной противотанковый гранатомёт, разработанный в 1942 году. Он представлял собой открытую с обеих сторон пусковую трубу с электровоспламенительной системой и предназначался прежде всего для борьбы с бронетехникой. На вооружение американской армии M1 поступил в 1942 году и применялся начиная с Североафриканской кампании.

Гранатомёт использует 60-мм реактивные гранаты с кумулятивной боевой частью. В отличие от обычного безоткатного орудия, граната оснащена реактивным зарядом, который разгоняет её при движении по пусковой трубе. Максимальная дальность составляла около 365 метров, а эффективная около 135 метров.

Одной из особенностей раннего M1 была электровоспламенительная система. Батарейки и контрольная лампочка находились внутри плечевого упора, поэтому перед выстрелом система позволяла проверить наличие электрического контакта.

Позднее появились усовершенствованные варианты, включая M1A1, M9 и M9A1, а развитием идеи стала более крупная M20 "Супер Базука" калибра 88,9 мм.

ПРИМЕЧАНИЯ:

- Основное назначение, борьба с бронетехникой и укреплениями.
- Эффективнее всего работает на относительно небольшой дистанции, где проще попасть по цели.
- Электрический механизм воспламенения делает M1 довольно необычным оружием для своего времени.
- Название "Базука" появилось благодаря сходству пусковой трубы с необычным духовым музыкальным инструментом, который популяризировал американский комик Боб Бёрнс.
