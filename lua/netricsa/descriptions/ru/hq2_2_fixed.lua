HALF-QUAKE 2, БУКВЕННАЯ ЛОВУШКА


Ну и ну... Посмотри на это, Сэм! Весь пол усеян буквами - как будто алфавит блеванул в этом коридоре. В центре - панель. Догадываюсь, она откроет нам путь дальше. Но вот проблема: одна неверная буква - и ты превратишься в мясной пирог. Я уже насчитала десять способов, как ты можешь умереть. Десять! Это новый рекорд даже для тебя.

...

Но тут есть слово. Слово, которое садисты обожают больше всего на свете. Ну, знаешь, то самое - их "raison d'être", их вдохновение, их любимая игрушка...

S-A-D-I-S-M.

Семь букв. Семь шагов к свободе. Или к смерти - если я ошибаюсь, но я редко ошибаюсь, Сэм.

Так же я заметила, что-то кто-то обронил тут дневник. Или специально оставил - эти садисты любят такие фокусы.

Давай, герой, покажи этим садистам, что их алфавит тебе по зубам!
