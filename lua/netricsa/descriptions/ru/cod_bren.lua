РУЧНОЙ ПУЛЕМЁТ BREN


ОРУЖИЕ:  Ручной Пулемёт Bren
ПАТРОНЫ: .303 British (7,7×56 мм R)
СС:      ~500-520 выстрелов / мин
ВЕС:     ~10 кг.

ОПИСАНИЕ:

Британский ручной пулемёт, созданный на основе чехословацкого ZB vz. 26 и принятый на вооружение британской армии в 1930-х годах. Оружие отличалось высокой надёжностью, хорошей точностью и сравнительно низкой скорострельностью, что позволяло стрелку лучше контролировать огонь.

Bren использует газоотводную автоматику и питается из коробчатого магазина, установленного сверху. Стандартный магазин вмещает 30 патронов. Необычное верхнее расположение магазина также позволило сделать линию подачи боеприпасов прямой и упростить конструкцию механизма.

На стволе установлен массивный пламегаситель, а сам ствол можно быстро заменить при перегреве. Оружие обычно использовалось с сошками для ведения устойчивого огня по противнику.

ПРИМЕЧАНИЯ:

- Эффективен на средней и дальней дистанции.
- Невысокая скорострельность помогает контролировать оружие и экономить боеприпасы.
- Магазин устанавливается сверху, поэтому при использовании оптического прицела конструкция требует специального решения.
- Сошки позволяют вести точный и стабильный огонь из положения лёжа.
- Ствол можно быстро заменить при сильном нагреве.
- Большой вес делает Bren неудобным при постоянном перемещении.
- Патрон .303 British обладает высокой мощностью и позволяет эффективно поражать цели на значительном расстоянии.
- Для длительного огня лучше использовать короткие очереди, а не пытаться превратить Bren в промышленный пылесос для боеприпасов.
- Надёжность и точность сделали его одним из наиболее известных британских ручных пулемётов Второй мировой войны.
