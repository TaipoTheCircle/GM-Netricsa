МОШКА


КЛАСС:        Мошка
МЕТАБОЛИЗМ:   Насекомое
ВОСПРИЯТИЕ:   Мелкое Существо
РАЗМЕР:       Очень Маленький
ВЫНОСЛИВОСТЬ: Очень Низкая
ВРАЖДЕБНОСТЬ: Низкая
ОРУЖИЕ:       Укус
НАГРАДА:      1
УГРОЗА:       Очень Низкая

ОПИСАНИЕ:

Мелкая летающая мошка, встречающаяся практически повсюду. Не представляет серьёзной опасности для большинства существ, однако способна довольно сильно раздражать.

Мошки летают рядом с головой, садятся на кожу и периодически кусают, заставляя постоянно отмахиваться от них. Самое неприятное заключается в том, что одна мошка редко бывает одна.

По неизвестной причине некоторые армии Ментала даже не удосужились уничтожить этих насекомых. Возможно, они просто решили, что если враг уже раздражён, то дополнительная артиллерия ему не помешает.

СОВЕТЫ:

- Не обращай на неё слишком много внимания.
- Если мошка начала мешать, просто прихлопни её.
- Если их стало много, лучше разобраться с ними сразу, пока раздражение не превратилось в настоящую проблему.
- Награда за уничтожение настолько мала, что Ментал, вероятно, даже не заметит твоего достижения.
