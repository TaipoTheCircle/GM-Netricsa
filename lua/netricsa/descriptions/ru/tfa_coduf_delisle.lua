Карабин DE LISLE COMMANDO


ОРУЖИЕ:   КАРАБИН DE LISLE COMMANDO
ПАТРОНЫ:  .45 ACP (11,43x23 мм)
СС:       ~15-25 выстрелов / мин.
ВЕС:      ~3,74 кг.

ОПИСАНИЕ:

Британский бесшумный карабин времён Второй мировой войны, разработанный специально для специальных подразделений. В его основе использована конструкция винтовки Lee-Enfield, переделанная под пистолетный патрон .45 ACP. Главной особенностью оружия стал огромный встроенный глушитель, занимающий значительную часть длины ствола.

Использование дозвукового .45 ACP вместе с интегрированным глушителем позволяло значительно снизить звук выстрела. При этом стрелок вручную работал затвором после каждого выстрела, что позволяло не производить лишнего шума от автоматической перезарядки.

De Lisle выпускался крайне небольшими сериями, поскольку предназначался прежде всего для британских коммандос и других специальных подразделений. Всего было произведено около 129 экземпляров. Карабин применялся во Второй мировой войне, а позднее использовался и в Корейской войне и Малайской чрезвычайной ситуации.

ПРИМЕЧАНИЯ:

- Один из самых тихих образцов огнестрельного оружия своего времени, причём глушитель был встроен прямо в конструкцию карабина.
- Эффективная дальность составляла около 185 метров, что делало его заметно практичнее бесшумных пистолетов для более удалённых целей.
- Ручной затвор позволял стрелку не досылать следующий патрон сразу после выстрела, сохраняя максимальную скрытность.
- De Lisle: когда обычный Lee-Enfield решил стать тише, короче и внезапно обзавёлся огромным глушителем.
