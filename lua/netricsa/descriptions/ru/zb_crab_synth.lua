КРАБ-СИНТЕНТ АЛЬЯНСА


КЛАСС:        Краб-синтент Альянса
МЕТАБОЛИЗМ:   Биомеханический синтент
ВОСПРИЯТИЕ:   Тяжёлая штурмовая единица
РАЗМЕР:       2,2 м.
ВЫНОСЛИВОСТЬ: Высокая
ВРАЖДЕБНОСТЬ: Чрезвычайная
ОРУЖИЕ:       Выдвижной Миниган, Клешни, Таран
НАГРАДА:      800
УГРОЗА:       Очень высокая

ОПИСАНИЕ:

Краб-синтент является тяжёлой боевой машиной Альянса, предназначенной для подавления хорошо вооружённых групп противника и прорыва укреплённых позиций. Несмотря на относительно приземистое телосложение, синтент обладает значительной массой и способен быстро перемещаться по пересечённой местности, используя несколько мощных конечностей.

Главная особенность данной сущности заключается в выдвижном минигане, скрытом внутри корпуса. При обнаружении цели оружейный механизм раскрывается, после чего синтент обрушивает на противника плотный поток огня. Миниган особенно эффективен против групп пехоты, лёгкой техники и целей, которые слишком долго остаются на одном месте.

В ближнем бою краб-синтент способен использовать собственные конечности в качестве оружия. Однако его основная задача заключается не в одиночной охоте, а в поддержке других синтентов. Обычно он действует совместно со штурмовыми синтентами Альянса, которые прикрывают его с флангов и не позволяют противнику сосредоточить весь огонь на тяжёлой машине.

Такая тактика делает столкновение с ними особенно неприятным: пока штурмовые синтенты заставляют противника двигаться, краб-синтент методично поливает территорию огнём из минигана. Альянс, похоже, действительно любит решать тактические задачи методом "поставить ещё одну пушку".

СОВЕТЫ:

- Не пытайся перестрелять миниган на открытой местности.
- Постоянно меняй позицию, особенно если синтент уже развернул оружие.
- Сначала уничтожай сопровождающих штурмовых синтентов, если они мешают сосредоточить огонь.
- Используй укрытия и атакуй с флангов или сзади.
- Мощное взрывное оружие особенно эффективно против тяжёлого корпуса.
- Если краб-синтент остался один, не расслабляйся: его огневая мощь всё ещё позволяет ему быстро превратить открытую площадку в очень плохое место для прогулок.

