ШТУРМОВАЯ ВИНТОВКА M16A1


ОРУЖИЕ:  Штурмовая Винтовка M16A1
ПАТРОНЫ: 5,56x45 мм NATO (M193)
СС:      Автоматический, 650-750 выстр. / мин
ВЕС:     2,97 кг.

ОПИСАНИЕ:

Американская штурмовая винтовка под патрон 5,56x45 мм, предназначенная для ведения точного и плотного огня на средней дистанции. Винтовка отличается сравнительно небольшим весом, низкой отдачей и хорошей кучностью, благодаря чему удобна как для одиночной стрельбы, так и для автоматического огня.

Оружие использует магазин на 20 или 30 патронов и работает за счёт отвода пороховых газов с запиранием поворотным затвором. M16A1 способна развивать высокую скорострельность, а эффективная дальность стрельбы составляет около 450 метров.

ПРИМЕЧАНИЯ:

- Высокая точность и относительно низкая отдача.
- Может вести одиночный и автоматический огонь.
- Использует магазины на 20 или 30 патронов.
- Эффективна преимущественно на средней и дальней дистанции.
- Небольшой вес делает винтовку удобной для длительного ношения.
- Патрон 5,56x45 мм обеспечивает хорошую пробивную способность против лёгких целей.
