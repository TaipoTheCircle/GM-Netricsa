ШТУРМОВАЯ ВИНТОВКА STG 44


ОРУЖИЕ:  Штурмовая Винтовка STG 44
ПАТРОНЫ: 7,92x33 мм Kurz
СС:      ~600 выстрелов / мин.
ВЕС:     ~5,2 кг.

ОПИСАНИЕ:

StG 44, или Sturmgewehr 44, немецкая штурмовая винтовка, разработанная во время Второй мировой войны. Она стала одним из первых массово производившихся образцов оружия нового класса и была создана для заполнения промежутка между пистолетами-пулемётами и полноценными винтовками.

Главным новшеством StG 44 стал промежуточный патрон 7,92x33 мм Kurz. Он был слабее стандартного винтовочного патрона 7,92x57 мм, зато позволял сделать оружие более удобным для автоматического огня и сохранить хорошую эффективность на средней дистанции. Винтовка использует газоотводную автоматику и способна вести как одиночный, так и автоматический огонь.

StG 44 имела эффективную дальность около 600 метров при одиночной стрельбе, тогда как огонь очередями был наиболее эффективен примерно до 300 метров. Именно сочетание высокой огневой мощи, компактности и промежуточного патрона стало основой концепции современного автомата.

ПРИМЕЧАНИЯ:

- Отлично подходит для ближней и средней дистанции, где сочетает точность винтовки и плотность автоматического огня.
- Автоматический режим позволяет эффективно подавлять противника, а одиночный помогает экономить боеприпасы и точнее работать по удалённым целям.
- StG 44 фактически стала одним из главных представителей нового класса оружия, который сегодня называют штурмовыми винтовками.
- Пистолет-пулемёт? Винтовка? Немцы решили: "А почему бы не всё сразу?".
