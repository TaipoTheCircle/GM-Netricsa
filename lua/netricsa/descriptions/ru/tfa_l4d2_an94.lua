АВТОМАТ НИКОНОВА АН-94 "АБАКАН"


ОРУЖИЕ:     Автомат Никонова АН-94 "Абакан"
ПАТРОНЫ:    5,45x39 мм
СС:         ~600 / 1800 выстрелов / мин

ОПИСАНИЕ:

Российский автомат, разработанный Геннадием Никоновым в рамках программы "Абакан". Создавался как перспективная замена автоматам семейства АК-74. Отличается необычной конструкцией автоматики со смещённым импульсом отдачи, позволяющей значительно повысить точность стрельбы короткими очередями.

Главная особенность АН-94 заключается в режиме стрельбы по два патрона с темпом 1800 выстрелов в минуту. Первый и второй выстрелы происходят практически одновременно, прежде чем отдача успевает заметно повлиять на положение оружия. При обычной автоматической стрельбе темп составляет около 600 выстрелов в минуту. Использует магазины на 30 и 45 патронов от АК-74, а также специальные четырёхрядные магазины на 60 патронов.

ПРИМЕЧАНИЯ:

- Известен под названием "Абакан", по имени города, где проходили испытания.
- Магазин расположен под небольшим углом вправо, что связано с необычной системой подачи патронов.
- Двухвыстрельная очередь позволяет отправить два патрона в цель практически до того, как стрелок почувствует отдачу.
- Конструкция оказалась настолько сложной и дорогой, что АН-94 не смог полностью заменить семейство АК-74.
- Настоящий технический эксперимент, который случайно получил приклад и стал автоматом.
