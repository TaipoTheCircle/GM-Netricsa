ВИНТОВКА SPRINGFIELD M1903


ОРУЖИЕ:  Винтовка Springfield M1903
ПАТРОНЫ: .30-06 Springfield (7,62x63 мм)
СС:      ~15-20 выстрелов / мин.
ВЕС:     ~3,95 кг.

ОПИСАНИЕ:

Американская магазинная винтовка с продольно-скользящим затвором, разработанная на основе конструкции Mauser и принятая на вооружение армии США в начале XX века. Наиболее известной стала версия под патрон .30-06 Springfield, использовавшаяся в обеих мировых войнах.

Винтовка предназначена для точного огня на средних и больших дистанциях. Продольно-скользящий затвор обеспечивает надёжную работу механизма и позволяет стрелку вручную досылать следующий патрон после каждого выстрела. M1903 также выпускалась в снайперских вариантах с оптическими прицелами.

Springfield M1903 сочетает мощный винтовочный патрон, хорошую точность и относительно небольшую массу. Благодаря этому она подходила как для обычной пехоты, так и для специализированных стрелков.

ПРИМЕЧАНИЯ:

- Особенно эффективна на средней и дальней дистанции, где точность M1903 раскрывается лучше всего.
- Когда нужна американская винтовка старой школы: никаких очередей, только затвор, прицел и очень убедительный аргумент.
- Снайперские варианты с оптикой позволяют использовать винтовку для поражения отдельных целей на больших расстояниях.
- Патрон .30-06 обладает высокой мощностью и хорошей дальностью.
