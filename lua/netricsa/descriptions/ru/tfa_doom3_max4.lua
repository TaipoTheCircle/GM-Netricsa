ПЛАЗМЕННАЯ ПУШКА


ОРУЖИЕ:  Плазменная пушка
ПАТРОНЫ: Плазменные боеприпасы
СС:      ~600 выстрелов / мин.

ОПИСАНИЕ:

Энергетическое оружие, использующее ускоренные плазменные сгустки для поражения целей. Благодаря высокой скорострельности и значительному урону особенно эффективна на ближней и средней дистанции.

Оружие способно выпускать непрерывный поток плазмы, быстро уничтожая противников. Главным недостатком является быстрый расход боеприпасов при длительной стрельбе.

ПРИМЕЧАНИЯ:

- Высокая скорострельность и хороший урон.
- Энергетические сгустки эффективно поражают быстро движущиеся цели.
- Боеприпасы расходуются довольно быстро при непрерывном огне.
