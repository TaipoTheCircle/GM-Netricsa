СОЛДАТ-ПЕХОТИНЕЦ МЕНДЕЛЬ-ГРУМАН


КЛАСС:        Солдат-Пехотинец Мендель-Груман
МЕТАБОЛИЗМ:   Человек, Мужчина
ВОСПРИЯТИЕ:   Стандартная пехота
РАЗМЕР:       ~1,8 м.
ВЫНОСЛИВОСТЬ: Средняя
ВРАЖДЕБНОСТЬ: Высокая
ОРУЖИЕ:       Лёгкий Штурмовой Карабин ORO FP9, Осколочные Гранаты
НАГРАДА:      200
УГРОЗА:       Низкая

ОПИСАНИЕ:

Данный Пехотинец является стандартным представителем вооружённых сил корпорации и составляет основу её пехотных подразделений. Внешне он практически не отличается от других вариантов пехоты Мендель-Груман: та же лёгкая защитная броня, тактическое снаряжение и закрытый шлем с динамическим визором.

Его основным оружием является лёгкий штурмовой карабин ORO FP9. Это универсальное оружие позволяет солдату эффективно вести огонь на короткой и средней дистанции, не заставляя его постоянно приближаться к противнику. В отличие от бойца с дробовиком, FP9-пехотинец предпочитает сохранять некоторую дистанцию и постепенно подавлять цель непрерывным огнём.

Солдат также оснащён осколочными гранатами, которые использует против противников за укрытиями или скоплений врагов. Благодаря сочетанию карабина и гранат он способен выполнять большинство обычных задач пехоты без необходимости специализированного вооружения.

Как и остальные стандартные бойцы Мендель-Груман, этот солдат не отличается выдающейся индивидуальной прочностью. Его преимущество заключается прежде всего в численности, дисциплине и взаимодействии с другими подразделениями. Обычно несколько пехотинцев занимают позиции вокруг зоны боевых действий, ведут перекрёстный огонь и постепенно заставляют противника покидать укрытия.

Динамический визор служит дополнительным индикатором состояния бойца: синий цвет означает обычное состояние, жёлтый повышенную настороженность, а красный максимальную боевую готовность.

В бою FP9-пехотинец является наиболее универсальным вариантом стандартного солдата. Он не обладает разрушительной мощью дробовика и не способен выдерживать такой же объём повреждений, как тяжёлые подразделения, зато практически не имеет серьёзных ограничений по дистанции боя.

СОВЕТЫ:

- Не недооценивай их из-за обычного вооружения. Несколько FP9-пехотинцев способны создать плотный и продолжительный огонь.
- Используй укрытия, особенно если против тебя действует целая группа.
- Гранаты эффективны против скоплений, поскольку пехотинцы часто действуют небольшими отрядами.
- На близкой дистанции старайся не позволять им окружить тебя.
- Если рядом находятся дробовики или тяжёлые бойцы, сначала обрати внимание на более опасные варианты, но не забывай о FP9-пехоте, которая продолжит вести огонь из-за их спины.
- Красный визор означает полную боевую готовность. В этот момент солдат уже не собирается делать вид, что всё происходящее его не касается.
