ТЁМНЫЙ УЧЕНИК-НИНДЗЯ МАСТЕРА ТЁМНЫХ ИСКУССТВ С ЧИ-ФАНГ


КЛАСС:         Тёмный Ученик-Ниндзя Мастера Тёмных Искусств
МЕТАБОЛИЗМ:    Гуманоид, Мужчина
ВОСПРИЯТИЕ:    Ученик Тёмных Искусств
РАЗМЕР:        ~1,8 м.
ВЫНОСЛИВОСТЬ:  Средняя
ВРАЖДЕБНОСТЬ:  Очень Высокая
ОРУЖИЕ:        Кулаки, Ноги, Боевые Приёмы, Сюрикены
НАГРАДА:       250
УГРОЗА:        Средняя

ОПИСАНИЕ:

Когда-то они были обычными учениками боевых школ, однако после того, как отвернулись от традиций своих наставников, примкнули к своему новому учителю и полностью приняли его жестокое учение.

В отличие от обычных воинов, тёмные ученики проходят полноценную подготовку в боевых искусствах. Они прекрасно владеют рукопашным боем, умеют быстро сокращать дистанцию и атаковать противника сериями ударов и киданием сюрикенов.

Мастер Тёмных Искусств обучает своих последователей не только технике боя, но и различным запрещённым приёмам. Ученики способны наносить мощные удары ногами, выполнять прыжковые атаки и использовать резкие комбинации ударов, которые позволяют им быстро сбить противника с ног.

Однако их преданность Мастеру Тёмных Искусств имеет и обратную сторону. Они практически никогда не отступают самостоятельно, даже когда положение становится безнадёжным. Для них поражение означает не просто проигрыш, а позор перед своим учителем.

Когда Мастер Тёмных Искусств начал своё восстание против своего учителя, именно эти ученики стали его основной силой. Они участвовали в захвате учеников Мастера Боевых Искусств, охраняли пленников и сражались с теми, кто пытался освободить их.

Впоследствии им пришлось столкнуться с самим Мастером Боевых Искусств. Несмотря на численное преимущество, его мастерства оказалось достаточно, чтобы пробиться через их ряды и добраться до их наставника.

СОВЕТЫ:

- Не позволяй им окружить себя. Группа тёмных учеников значительно опаснее одного бойца.
- Держи дистанцию. В ближнем бою они способны быстро провести серию ударов.
- На дальней дистанции кидают двумя сюрикенами.
- Используй скорострельное оружие, чтобы не дать им сократить расстояние.
- Взрывчатка особенно эффективна против нескольких учеников, собравшихся вокруг одной цели.
