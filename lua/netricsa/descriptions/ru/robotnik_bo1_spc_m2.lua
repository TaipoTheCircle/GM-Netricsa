ПИСТОЛЕТ-ПУЛЕМЁТ SPECTRE M4


ОРУЖИЕ:     Пистолет-пулемёт Spectre M4
ПАТРОНЫ:    9x19 мм Парабеллум
СС:         ~850 выстрелов / мин

ОПИСАНИЕ:

Итальянский пистолет-пулемёт, разработанный Роберто Теппой и Клаудио Гритти в 1980 году. Производился компанией SITES с 1984 года. Оружие предназначено для ближнего боя и отличается компактными размерами, складным прикладом и необычной конструкцией ударно-спускового механизма.

Spectre M4 использует автоматику со свободным затвором и ведёт огонь с закрытого затвора. Одной из главных особенностей являются четырёхрядные магазины ёмкостью 30 или 50 патронов. Также предусмотрен передний складной упор для удобства удержания оружия.

ПРИМЕЧАНИЯ:

- Магазин на 50 патронов выглядит довольно необычно для пистолета-пулемёта.
- Приклад складывается вверх, уменьшая общую длину оружия до 350 мм.
- Ударно-спусковой механизм позволяет безопасно носить патрон в патроннике.
- Производство продолжалось до 2001 года, хотя итальянский завод SITES закрылся раньше.
