БОЕВОЙ ПОМПОВЫЙ ДРОБОВИК SHO SERIES-3


ОРУЖИЕ:  Боевой Помповый Дробовик SHO Series-3
ПАТРОНЫ: 10-й калибр
СС:      ~90 выстрелов / мин

ОПИСАНИЕ:

Мощный помповый боевой дробовик, разработанный корпорацией Armacham Technology Corporation. Предназначен для поражения противников на коротких дистанциях. Оснащён гладким стволом с цилиндрическим сужением и трубчатым магазином на 8 патронов. Благодаря использованию 10-го калибра обладает чрезвычайно высокой останавливающей силой.

SHO Series-3 отличается высокой мощностью, но имеет небольшую дальность эффективной стрельбы и широкое рассеивание дроби. Перезарядка производится вручную, по одному патрону за раз. Оружие оснащено тритиевой подсветкой механического прицела и фонарём LIGHTBRINGER. Используется преимущественно тяжеловооружёнными подразделениями ATC.

ПРИМЕЧАНИЯ:

- Использует 10-й калибр, более мощный, чем распространённый 12-й.
- Магазин вмещает 8 патронов.
- В конструкции угадываются черты Remington 870 и Benelli M4.
- Способен нанести примерно на треть больше урона за выстрел, чем Vollmer Ultra92.
- Перезарядка по одному патрону. Зато каждый выстрел напоминает противнику, зачем придумали дробовики.
