ПИСТОЛЕТ BROWNING HI-POWER


ОРУЖИЕ:  Пистолет Browning Hi-Power
ПАТРОНЫ: 9x19 мм Parabellum
СС:      ~40-50 выстрелов / мин.
ВЕС:     ~0,88 кг.

ОПИСАНИЕ:

Browning Hi-Power, также известный как Browning GP 35 или P-35, бельгийский самозарядный пистолет, разработанный Джоном Браунингом и Дьёдонне Сэвом. Разработка была завершена в 1935 году, после чего пистолет получил широкое распространение по всему миру и находился на вооружении различных армий и силовых структур десятилетиями.

Пистолет использует автоматику с коротким ходом ствола и запиранием по схеме Браунинга. Основным боеприпасом является распространённый патрон 9x19 мм Parabellum. Одной из главных особенностей Hi-Power стал двухрядный магазин на 13 патронов, что для 1935 года было весьма большой вместимостью для армейского пистолета.

Hi-Power отличается относительно небольшой массой, хорошей эргономикой и удобной рукояткой. Благодаря сочетанию вместительного магазина, надёжной автоматики и умеренной отдачи он подходит для быстрого ведения повторных выстрелов на ближней дистанции.

ПРИМЕЧАНИЯ:

- Браунинг хотел сделать хороший пистолет, а в итоге сделал ещё и магазин, который для своего времени выглядел почти как чит.
- Хорошо подходит для ближней дистанции и позволяет быстро делать повторные выстрелы.
- Магазин на 13 патронов был одним из главных преимуществ Hi-Power на момент появления пистолета.
- Пистолет получил настолько широкое распространение, что его различные варианты использовались примерно в 50 странах.
