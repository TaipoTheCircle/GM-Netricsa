ПРОТИВОТАНКОВОЕ РУЖЬЁ ПТРС-41


ОРУЖИЕ:  Противотанковое Ружьё ПТРС-41
ПАТРОНЫ: 14,5x114 мм
СС:      ~15 выстрелов / мин.
ВЕС:     ~20,9 кг.

ОПИСАНИЕ:

Противотанковое самозарядное ружьё системы Симонова образца 1941 года, советское противотанковое оружие, созданное для борьбы с лёгкими и средними танками, бронемашинами и защищёнными огневыми точками. На вооружение РККА оно было принято в 1941 году.

Ружьё использует газоотводную автоматику и стреляет мощным патроном 14,5x114 мм с бронебойными боеприпасами. После выстрела автоматика самостоятельно перезаряжает оружие, поэтому стрелку не приходится вручную работать затвором после каждого выстрела. ПТРС имеет пятизарядный магазин с пачечным заряжанием.

Несмотря на огромную массу почти 21 кг, ПТРС предназначалось для относительно мобильного противотанкового применения. Лучшие результаты достигались на дистанциях около 300-400 метров, а использовать ружьё можно было и против броневых огневых точек.

ПРИМЕЧАНИЯ:

- На ближней и средней дистанции способно серьёзно повредить лёгкую бронетехнику и броневые цели.
- Лучше всего раскрывается примерно на 300-400 метрах, где сочетает огромную мощность и приемлемую точность.
- Вес почти 21 кг превращает переноску ПТРС в отдельную боевую задачу.
- Это тот случай, когда винтовку можно использовать как противотанковое оружие, а противник после первого выстрела начинает очень уважать калибр 14,5 мм.
