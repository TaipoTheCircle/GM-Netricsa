ПРОТИВОТАНКОВЫЙ ГРАНАТОМЁТ ПАНЦЕРФАУСТ


ОРУЖИЕ:  Противотанковый Гранатомёт Панцерфауст
ПАТРОНЫ: Кумулятивная Противотанковая Граната
СС:      ~1 выстрел / мин.
ВЕС:     ~5-9,4 кг.

ОПИСАНИЕ:

Немецкий одноразовый противотанковый гранатомёт времён Второй мировой войны. Он создавался как простое и доступное средство борьбы с бронетехникой, которым могли пользоваться даже недостаточно подготовленные бойцы. В отличие от реактивных гранатомётов, Панцерфауст не имел маршевого ракетного двигателя: метательный заряд сгорал внутри пусковой трубы, разгоняя кумулятивную гранату.

Граната имела крупную кумулятивную боевую часть и могла пробивать до примерно 200 мм стали у распространённых вариантов. Существовали версии Панцерфауст 30, 60 и 100, названия которых соответствовали их номинальной эффективной дальности в метрах. Последующие варианты получили улучшенные боевые части и большую дальность.

Оружие было особенно опасно в городских боях, где небольшая дистанция до бронетехники позволяла использовать его наиболее эффективно. После выстрела пусковая труба стандартного Панцерфауста не предназначалась для повторного использования.

ПРИМЕЧАНИЯ:

- Особенно опасен для бронетехники на ближней дистанции.
- Чем ближе цель находится к эффективной дистанции конкретной модели, тем надёжнее можно рассчитывать на поражение бронецели.
- Панцерфауст выбрасывает мощную струю газов назад, поэтому позади стрелка должно оставаться свободное пространство.
- Название переводится как "броневой кулак". И это тот случай, когда название вообще не пыталось быть скромным.
