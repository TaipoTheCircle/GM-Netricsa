МАГАЗИННАЯ ВИНТОВКА МАНЛИХЕРА-ШЁНАУЭРА M1903


ОРУЖИЕ:  Магазинная Винтовка Манлихера-Шёнауэра M1903
ПАТРОНЫ: 6,5x54 мм Mannlicher-Schönauer
СС:      Ручное Перезаряжание, 5 Патронов

ОПИСАНИЕ:

Австро-венгерская магазинная винтовка, разработанная Фердинандом Манлихером и Отто Шёнауэром в 1900 году и принятая на вооружение греческой армии в 1903 году. Производилась компанией Steyr и отличалась высоким качеством изготовления, надёжностью и необычной для своего времени конструкцией магазина. Предназначалась для вооружения пехоты, а укороченный вариант карабина использовался кавалерией и другими подразделениями.

Работает по принципу продольно-скользящего поворотного затвора с ручным перезаряжанием. Главной особенностью является пятизарядный роторный магазин системы Шёнауэра, расположенный внутри ложи. Патроны укладываются в специальный вращающийся механизм, обеспечивающий надёжную подачу боеприпасов. Заряжание производится сверху, при помощи обоймы или по одному патрону. Винтовка оснащена открытыми механическими прицельными приспособлениями с регулируемой прицельной планкой.

ПРИМЕЧАНИЯ:

- Принята на вооружение греческой армии в 1903 году.
- Использует патрон 6,5x54 мм Mannlicher-Schönauer.
- Роторный магазин вмещает 5 патронов.
- Масса составляет около 3,77 кг, общая длина около 1226 мм.
- Прицельная планка имеет разметку до 2000 метров.
- Существовал укороченный кавалерийский карабин.
- Роторный магазин Шёнауэра обеспечивал плавную и надёжную подачу патронов, став одной из главных особенностей всей конструкции.
