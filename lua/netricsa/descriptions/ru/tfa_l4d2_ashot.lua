КАРТЕЧНЫЙ ПИСТОЛЕТ "АШОТ"


ОРУЖИЕ:  Картечный Пистолет "Ашот"
ПАТРОНЫ: 12x70 мм
СС:      1 Патрон, Ручная Перезарядка

ОПИСАНИЕ:

Самодельный картечный пистолет, широко распространённый среди жителей постъядерной России. Изготавливается из подручных материалов, преимущественно металлических труб и простых механических компонентов. Несмотря на примитивную конструкцию, обладает высокой убойной силой на коротких дистанциях и особенно эффективен против мутантов.

Ашот представляет собой однозарядное оружие с переломным механизмом перезарядки. Использует стандартные охотничьи патроны 12-го калибра. Благодаря простой конструкции, небольшим габаритам и доступности боеприпасов пользуется большой популярностью среди сталкеров, бандитов и других обитателей Метро. Предусмотрена установка различных модификаций, включая дополнительные стволы, приклад, оптические приспособления и удлинённый ствол.

ПРИМЕЧАНИЯ:

- Один из наиболее распространённых видов самодельного оружия в Метро.
- Базовая версия вмещает всего один патрон.
- В Metro Exodus доступны варианты с двумя и четырьмя стволами.
- Удлинённый ствол повышает кучность и эффективную дальность стрельбы.
- Существует специальный зажигательный боеприпас 12x70 мм.
