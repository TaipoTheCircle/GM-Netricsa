СНАЙПЕРСКАЯ ВИНТОВКА WALTHER WA 2000


ОРУЖИЕ:     Снайперская винтовка Walther WA 2000
ПАТРОНЫ:    7,62x51 мм НАТО (.308 Winchester) / .300 Winchester Magnum / 7,5x55 мм Swiss
СС:         ~30 выстрелов / мин

ОПИСАНИЕ:

Немецкая самозарядная снайперская винтовка, разработанная компанией Carl Walther Waffenfabrik в начале 1980-х годов. Создавалась для полицейских подразделений и специальных служб, которым требовалось компактное и высокоточное оружие для работы в городских условиях. Благодаря компоновке буллпап винтовка получила сравнительно небольшую длину при сохранении полноценного 650-мм ствола.

WA 2000 использует газоотводную автоматику с поворотным затвором и семью боевыми упорами. Отличается модульной конструкцией, позволяющей менять ствол и затвор под различные боеприпасы. Оснащается регулируемой деревянной ложей, оптическим прицелом Schmidt & Bender и необычной передвижной сошкой. Магазин рассчитан на 6 патронов, а для варианта под .300 Winchester Magnum используется магазин на 5 патронов.

ПРИМЕЧАНИЯ:

- За весь период производства было выпущено всего 176 экземпляров.
- Не имеет открытых прицельных приспособлений, поскольку рассчитана на использование оптики.
- Из-за расположения окна выброса гильз стрелять с левого плеча невозможно.
- Производство прекратили в 1988 году из-за высокой стоимости изготовления.
- Одна из тех винтовок, которые выглядят дороже, чем целый оружейный склад.
