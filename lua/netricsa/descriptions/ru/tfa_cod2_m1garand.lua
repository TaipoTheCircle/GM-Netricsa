САМОЗАРЯДНАЯ ВИНТОВКА M1 ГАРАНД


ОРУЖИЕ:  Самозарядная Винтовка M1 Гаранд
ПАТРОНЫ: .30-06 Springfield (7,62×63 мм)
СС:      ~40-50 выстрелов / мин.
ВЕС:     ~4,32 кг.

ОПИСАНИЕ:

Американская самозарядная винтовка времён Второй мировой войны, разработанная Джоном Гарандом. Она стала основным оружием американской пехоты и сочетала мощный винтовочный патрон с возможностью быстро производить повторные выстрелы без ручного передёргивания затвора.

Винтовка работает за счёт отвода пороховых газов и использует поворотный затвор. Боевое питание осуществляется из специальной пачки на 8 патронов, которая устанавливается сверху. После расходования всех патронов пустая пачка автоматически выбрасывается с характерным металлическим звуком.

M1 Гаранд отличается хорошей точностью, мощностью и эффективной дальностью около 550 метров. Благодаря самозарядной системе она позволяет вести значительно более быстрый огонь, чем обычные магазинные винтовки с ручным затвором.

ПРИМЕЧАНИЯ:

- Отлично подходит для средней и дальней дистанции, особенно против отдельных целей.
- Самозарядная система позволяет быстро делать повторные выстрелы, не отвлекаясь на ручную перезарядку после каждого выстрела.
- После последнего выстрела пустая пачка выбрасывается с характерным "дзынь!". Именно этот звук стал одной из самых известных особенностей Гаранд.
- Береги большой палец при зарядке. Большой палец Гаранда появился не на пустом месте.
