ОПИСАНИЕ:

Китайский дракон Чи-фана представляет собой огромное змееподобное существо, обитающее в отдалённых районах этой планеты. Несмотря на внушительные размеры и внешность, способную вызвать панику у любого неподготовленного наблюдателя, дракон является пассивным существоми и не проявляет агрессии без серьёзной причины.

Его тело покрыто плотной чешуёй, а длинная гибкая форма позволяет ему с лёгкостью перемещаться между скалами, равнинами и водоёмами. Дракон способен подниматься в воздух и парить над поверхностью без каких-либо видимых крыльев, что является одной из наиболее загадочных особенностей его биологии.

Чи-фанские драконы предпочитают спокойные места, особенно крупные водоёмы, горные долины и территории, удалённые от крупных поселений. Они большую часть времени проводят в медленном перемещении, отдыхе или наблюдении за окружающей средой.

Дракон не охотится на разумных существ и не воспринимает их как добычу. В большинстве случаев при встрече с человеком он просто продолжает свой путь.

Особенно интересной особенностью вида являются редкие визиты отдельных особей на Землю. По неизвестной причине некоторые драконы с Чи-фана время от времени появляются в районах, связанных с китайской культурой.

Именно эти редкие появления, вероятно, и стали причиной возникновения многочисленных древних рассказов о драконах.

Земные наблюдатели могли видеть лишь огромного змееподобного зверя, парящего среди облаков, появляющегося возле рек или исчезающего в тумане. Неудивительно, что за тысячи лет реальные встречи постепенно превратились в легенды.

Истории о драконах, управляющих водой, приносящих дождь, живущих среди облаков и обладающих сверхъестественной силой, вполне могли возникнуть как сильно преувеличенные описания реальных визитов этих существ.

Сам дракон, разумеется, ничего об этом не знает.

СОВЕТЫ:

- Не атакуй его первым. Дракон не настроен враждебно.
- Не паникуй из-за его размеров: огромный размер не означает агрессивное поведение.
- На самом деле это просто очень большой, очень древний и совершенно незаинтересованный в человеческих проблемах обитатель Чи-фана.
