СОЛДАТ-ПЕХОТИНЕЦ МЕНДЕЛЬ-ГРУМАН С ДРОБОВИКОМ


КЛАСС:        Солдат-пехотинец Мендель-Груман
МЕТАБОЛИЗМ:   Человек, Мужчина
ВОСПРИЯТИЕ:   Стандартная Пехота, Штурмовик Ближнего Боя
РАЗМЕР:       ~1,8 м.
ВЫНОСЛИВОСТЬ: Средняя
ВРАЖДЕБНОСТЬ: Высокая
ОРУЖИЕ:       Дробовик ORO "Исполнитель", Осколочные Гранаты
НАГРАДА:      250
УГРОЗА:       Средняя

ОПИСАНИЕ:

Этот пехотинец является специализированным вариантом стандартного бойца корпорации. Внешне он практически ничем не отличается от обычного пехотинца: та же защитная броня, тот же шлем с динамическим визором и та же стандартная экипировка. Разница заключается в оружии, поскольку вместо обычного стрелкового вооружения этому солдату выдают ORO "Исполнитель".

"Исполнитель" предназначен для ведения боя на короткой дистанции и превращает такого пехотинца в опасного штурмовика. В отличие от обычного солдата, которому выгодно держаться на среднем расстоянии, дробовик требует приблизиться к противнику, после чего один удачный залп способен нанести серьёзный урон.

Из-за этого дробовики обычно действуют несколько агрессивнее остальных пехотинцев. Они стараются сократить дистанцию, обходить укрытия с фланга и заставлять противника вступать в ближний бой. В тесных коридорах, помещениях и других ограниченных пространствах такой солдат особенно опасен: расстояние, на котором обычный пехотинец постепенно теряет эффективность, для него становится идеальной зоной поражения.

При этом сам стрелок не обладает повышенной прочностью. Его броня остаётся практически такой же, как у стандартного пехотинца, поэтому он не превращается в тяжёлого бойца только потому, что получил дробовик. Мендель-Груман просто взял обычного солдата, выдал ему оружие, которое говорит само за себя: "подойди поближе и выстрели как следует", и отправил его искать неприятности на свою пятую точку.

Дробовики особенно эффективны в составе обычных подразделений. Пока одни солдаты ведут огонь с расстояния и заставляют противника держаться за укрытием, стрелок с "Исполнителем" может попытаться обойти позицию и атаковать с близкой дистанции.

Как и остальные пехотинцы Мендель-Груман, он использует динамический визор. Синий цвет обозначает обычное состояние, жёлтый повышенную настороженность, а красный полную боевую готовность.

СОВЕТЫ:

- Не позволяй ему приблизиться. Чем меньше дистанция, тем опаснее "Исполнитель".
- На открытом пространстве он менее эффективен, чем обычный стрелок с автоматическим оружием.
- Следи за флангами. Дробовик особенно опасен, когда солдат пытается обойти укрытие.
- Гранаты эффективны против групп, особенно если дробовик находится среди нескольких обычных солдат.
- Если визор стал красным, пехотинец уже обнаружил угрозу и готов открывать огонь. Лучше не проверять, насколько близко он хочет подойти.
