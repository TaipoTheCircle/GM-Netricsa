РУЧНАЯ ОСКОЛОЧНАЯ ГРАНАТА MK 1


ОРУЖИЕ:  Ручная Осколочная Граната MK 1
ПАТРОНЫ: Взрывчатое Вещество
СС:      Одно Применение
ВЕС:     ~0,45 кг.

ОПИСАНИЕ:

Американская ручная осколочная граната времён Первой мировой войны, разработанная в 1917 году. Она стала одной из первых американских попыток создать собственную стандартную осколочную гранату и создавалась как простое и надёжное средство поражения пехоты.

Граната имела характерный рифлёный корпус с 32 насечками и использовала временной фрикционный запал. Для приведения механизма в действие требовалось снять предохранительную чеку, убрать верхний колпачок и активировать рычаг перед броском.

Однако на практике Mk 1 оказалась далеко не такой простой, как рассчитывали её создатели. Проблемы с воспламенением запала привели к тому, что гранату довольно быстро сняли с вооружения и уже в 1918 году заменили улучшенной Mk 2.

ПРИМЕЧАНИЯ:

- Предназначена для поражения противника осколками корпуса при взрыве.
- Механизм оказался слишком сложным в реальных боевых условиях, из-за чего граната быстро получила репутацию не самого удачного решения.
- Если граната не сработала, это ещё не значит, что можно расслабиться. История Mk 1 как раз показывает, почему.
- Использовалась американскими войсками в Первой мировой войне, но прослужила недолго.
