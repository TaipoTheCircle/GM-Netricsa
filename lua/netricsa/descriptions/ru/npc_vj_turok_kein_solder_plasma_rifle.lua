СОЛДАТ-ЭЛИТА МЕНДЕЛЬ-ГРУМАН


КЛАСС:        Солдат-Элита Мендель-Груман
МЕТАБОЛИЗМ:   Человек, Мужчина
ВОСПРИЯТИЕ:   Тяжёлая Пехота
РАЗМЕР:       ~1,9 м.
ВЫНОСЛИВОСТЬ: Высокая
ВРАЖДЕБНОСТЬ: Очень высокая
ОРУЖИЕ:       Импульсная Винтовка ORO L66, Импульсные Гранаты
НАГРАДА:      600
УГРОЗА:       Очень Высокая

ОПИСАНИЕ:

Элитные солдаты Мендель-Груман являются усиленным вариантом стандартной пехоты корпорации. Они получают значительно более тяжёлую броню и вооружаются современной импульсной винтовкой ORO L66, превращаясь из обычных стрелков в опасные штурмовые подразделения.

В отличие от стандартных солдат, элиты имеют более тёмную защитную экипировку и заметно более массивный силуэт. Их броня способна выдерживать значительное количество попаданий, поэтому быстро уничтожить такого бойца обычным стрелковым оружием значительно сложнее.

Главное оружие элиты, Импульсная Винтовка ORO L66, является точной автоматической винтовкой, стреляющей бронебойными сердечниками из обеднённого урана. Оружие обладает большой ёмкостью магазина, высокой точностью и хорошей скорострельностью, однако при длительной стрельбе перегревается.

L66 также оснащена вторичным режимом: пусковой установкой импульсных гранат. Они практически не предназначены для нанесения прямого урона, зато обладают мощным отбрасывающим эффектом, позволяя выбивать противников из укрытий и сбивать их с ног.

Элиты обычно действуют в составе подразделений и могут возглавлять группы более лёгких солдат. Их появление на поле боя резко повышает огневую мощь отряда Мендель-Груман.

СОВЕТЫ:

- В первую очередь уничтожай элиту, если он находится вместе с обычной пехотой.
- Используй укрытия: L66 обладает высокой точностью и способна вести эффективный огонь на большой дистанции.
- Следи за импульсными гранатами. Они могут выбить тебя из укрытия и оставить открытым для остальных солдат.
- Несмотря на тяжёлую броню, выстрелы в голову остаются наиболее эффективным способом его уничтожения.
- Не путай его с солдатами МГ Тяжёлое Вооружения: тяжёлый пулемётчик носит "Боевого Коня", а элитный солдат именно L66.
