РОБО-КИБОРГ С ДЖЕОНОЗИСА


КЛАСС:        Робо-Киборг
МЕТАБОЛИЗМ:   Полностью Механический Организм
ВОСПРИЯТИЕ:   Автономная Система Охраны И Нейтрализации Целей
РАЗМЕР:       ~2,2 м.
ВЫНОСЛИВОСТЬ: Крайне Высокая
ВРАЖДЕБНОСТЬ: Низко-Чрезвычайная
ОРУЖИЕ:       Пушка Смерти, лазеры XL2, Огнемёт, Пила, Встроенный Нож, Паучьи Конечности
НАГРАДА:      10000
УГРОЗА:       Чрезвычайно Высокая

ОПИСАНИЕ:

Робо-киборг с Джеонозиса представляет собой крайне редкий прототип боевого дроида, разработанный на заводах Конфедерации Независимых Систем. Изначально он создавался как то, что должно было переломить ход войны с республикой, однако завод был уничтожен.

После разгрома Конфедерации прототип оказался в распоряжении Галактической Империи. Имперские специалисты быстро оценили его боевые возможности и передали машину в эксплуатацию, однако воспроизвести конструкцию они так и не смогли. Завод, на котором был создан дроид, давно прекратил существование, а инженеры, отвечавшие за его разработку, погибли или исчезли. Поэтому каждый сохранившийся экземпляр фактически является невосполнимым военным активом.

В обычном состоянии дроид находится внутри специальной капсулы, где его механические конечности складываются, а сама машина переходит в режим ожидания. В таком состоянии он может находиться практически неограниченное время, не проявляя никакой активности.

При обнаружении постороннего дроид первоначально не атакует. Он выходит из капсулы и спокойно предупреждает нарушителя, требуя покинуть охраняемую территорию. Это одна из немногих ситуаций, когда встреча с ним может закончиться без перестрелки.

Однако после нападения или отказа покинуть зону охраны протокол меняется полностью.

Дроид переходит в боевой режим и превращается в чрезвычайно опасную универсальную платформу. Его главная особенность заключается в огромном количестве встроенного вооружения. Одна из систем представляет собой "Пушку Смерти", достаточно мощную для уничтожения даже тяжёлой техники и транспортов. Против неё обычная броня практически бесполезна.

Четыре руки робота являются многофункциональными. Они способны трансформироваться в энергетические излучатели, работающие по принципу лазерного ружья XL2. Благодаря этому дроид может одновременно вести огонь по нескольким целям и практически не оставлять противнику безопасного направления для атаки.

Одна из конечностей - это огнемёт. При необходимости дроид способен использовать другую руку для сварки и модификации системы прямо во время эксплуатации. После такой модернизации пламя становится синим и значительно более интенсивным.

В конструкции огнемёта также предусмотрен встроенный нож, позволяющий использовать эту конечность для ближнего боя.

Другая рука оснащена мощной пилой. Если противник каким-либо образом сумел пережить дальние атаки и приблизился к машине, дроид способен перейти к механическому расчленению цели буквально на месте.

Но наиболее необычной особенностью являются его ноги.

Стандартные ноги могут складываться, после чего заменяются или трансформируются в крабоподобные паучьи конечности. Такая конфигурация значительно повышает мобильность машины, позволяет быстро менять направление движения и эффективно уклоняться от огня.

Дроид способен не только стремительно перемещаться по земле, но и летать. Поэтому классическая тактика "Спрятаться За Стеной И Переждать Атаку" против него работает крайне плохо. Он может обойти препятствие, сменить высоту или атаковать с совершенно неожиданного направления.

Несмотря на практически невероятную живучесть, Робо-киборг не является абсолютно неуязвимым. Его можно уничтожить при достаточной огневой мощи и правильной тактике. Однако сделать это крайне сложно: машина способна выдерживать повреждения, которые вывели бы из строя большинство других дроидов.

Фактически перед противником оказывается не один робот, а целая коллекция оружейных платформ, собранных в одном корпусе.

Именно поэтому Империя старается не отправлять его без крайней необходимости. Потеря такого дроида невосполнима, поскольку технология его производства давно утрачена.

СОВЕТЫ:

- Если встретил его в одиночку, считай, что тебе крайне не повезло.
- Не атакуй первым, если Робо-Киборг просто охраняет территорию. Он может ограничиться предупреждением.
- Если бой начался, не рассчитывай на укрытие. Робо-Киборг  способен летать и менять направление атаки.
- Держись подальше от огнемёта и пилы. В ближнем бою он особенно опасен.
- Следи за трансформацией конечностей.
- Тяжёлая техника также не гарантирует безопасность из-за его пушки смерти.
- Если Робо-Киборг перешёл на паучью конфигурацию, приготовься к резким манёврам и уклонениям.
