БУДУЩЕЕ МЕСТО ПОСТРОЙКИ ТЕОТИУАКАНА, ГИГАНТСКАЯ ЯМА - СТРОЙКА НАЧАЛАСЬ


Ну вот, Сэм, стройка кипит! Майя явно не теряли времени даром. Вместо гигантской ямы - забор. Обычный каменный забор. А у одного из них сторона - прозрачная.

И знаешь, что за этим прозрачным забором? Деревья. Настоящие деревья. Посреди ямы, где ещё вчера была только голая земля и стены неизвестного происхождения. Майя, конечно, умеют удивлять. Или это не майя. Или это вообще не деревья.

Я уже ни в чём не уверена, Сэм!
