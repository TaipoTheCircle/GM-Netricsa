ВИНТОВКА МОСИНА ОБРАЗЦА 1891/30


ОРУЖИЕ:  Винтовка Мосина Образца 1891/30
ПАТРОНЫ: 7,62×54 мм R
СС:      ~10 выстрелов / мин
ВЕС:     ~4,5 кг

ОПИСАНИЕ:

Винтовка Мосина, более известная как "Трёхлинейка" или "Мосинка", представляет собой магазинную винтовку с продольно-скользящим затвором, принятым на вооружение Российской империи в 1891 году. Оружие прошло через множество войн и модернизаций и оставалось на вооружении разных стран на протяжении многих десятилетий.

Винтовка использует мощный патрон 7,62x54 мм R и имеет фиксированный магазин. После каждого выстрела стрелок вручную работает затвором, извлекая гильзу и досылая следующий патрон. Магазин заряжается обоймами по пять патронов.

Мосинка отличается простой и прочной конструкцией, хорошей дальностью и достаточно высокой мощностью. Существовали пехотные, драгунские, карабинные и снайперские варианты, поэтому оружие применялось в самых разных условиях.

ПРИМЕЧАНИЯ:

- Особенно эффективна на средней и дальней дистанции, где мощный винтовочный патрон раскрывает себя во всей красе.
- Простая конструкция делает винтовку подходящей для эксплуатации в суровых условиях.
- Опытный стрелок может довольно быстро работать затвором, несмотря на ручную перезарядку.
- "Мосинка" пережила столько эпох, что некоторые противники могут быть моложе самой винтовки.
