ОХОЛОЩЁННЫЙ ОБРЕЗ МР-43-СО "БРАТ-2"


ОРУЖИЕ:  Охолощённый Обрез МР-43-СО "Брат-2"
ПАТРОНЫ: Светозвуковые Патроны 7,62x54R
СC:      Два Патрона, Ручная Перезарядка

ОПИСАНИЕ:

Охолощённое двуствольное оружие, изготовленное компанией ООО "Курс-С" на основе гладкоствольного ружья ИЖ-43. Представляет собой укороченную версию классического двуствольного ружья с характерными деревянными элементами отделки. Модель получила известность благодаря сходству с обрезом, использованным Данилой Багровым в фильме "Брат 2".

Оружие оснащено двумя стволами, двумя спусковыми крючками и переломным механизмом перезарядки. Использует светозвуковые патроны 7,62x54R, создающие громкий выстрел с дымом и вспышкой. Вместимость составляет два патрона. Для предотвращения использования боевых боеприпасов стволы оснащены специальными рассекателями.

ПРИМЕЧАНИЯ:

- Имеет два ствола и два спусковых крючка.
- Перезарядка осуществляется переламыванием стволов.
- Автоматический предохранитель активируется при перезарядке.
