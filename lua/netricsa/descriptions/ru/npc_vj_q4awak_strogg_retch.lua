ОТВРАТНЫЙ СТРОГГ СТРОГГОВ C СТРОГГОСА


КЛАСС:        Отвратный Строгг Строггов
МЕТАБОЛИЗМ:   Кибернетический Организм
ВОСПРИЯТИЕ:   Штурмовой Громила Ближнего Боя
РАЗМЕР:       ~2,1 м.
ВЫНОСЛИВОСТЬ: Высокая
ВРАЖДЕБНОСТЬ: Чрезвычайная
ОРУЖИЕ:       Кибернетические Конечности, Рука-Клинок, Встроенное Вооружение, Удары Молнией
НАГРАДА:      900
УГРОЗА:       Очень высокая

ОПИСАНИЕ:

Очень редкий и малоизученный тип строгга, происходящий из неизвестной программы военной строггификации. Его существование практически не документировано, а сведения о нём сохранились лишь в отдельных материалах, связанных с экспериментальными разработками строггов. Судя по строению тела, он создавался как специализированная боевая машина для агрессивного ближнего боя.

По своим повадкам он напоминает строгга-берсерка. Отвратный предпочитает немедленно сокращать дистанцию с противником, используя свои массивные кибернетические конечности и встроенное вооружение. Его тело представляет собой смесь органической ткани и тяжёлых механических компонентов, причём значительная часть конечностей заменена или усилена кибернетическими конструкциями.

Отвратный выглядит более специализированным исключительно на рукопашной атаке. Его вооружение интегрировано непосредственно в тело, что позволяет ему продолжать атаку, не теряя возможности использовать встроенные системы вооружения. В бою он действует крайне напористо, постоянно двигаясь вперёд и заставляя противника отступать.

СОВЕТЫ:

- Не подпускай его близко. В ближнем бою Отвратный особенно опасен и способен быстро разорвать дистанцию.
- Не рассчитывай на медленное изматывание. Высокая выносливость позволяет ему выдерживать значительный объём огня.
