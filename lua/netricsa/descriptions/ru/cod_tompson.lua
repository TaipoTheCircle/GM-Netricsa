ТОМПСОН МОДЕЛИ 1921


ОРУЖИЕ:  Томпсон Модели 1921
ПАТРОНЫ: .45 ACP
СС:      Автоматический, ~800 Выстрелов / Мин.
ВЕС:     ~4,9 кг.

ОПИСАНИЕ:

Томпсон Модели 1921, также известный как "Томми-ган", ранняя версия знаменитого американского пистолета-пулемёта, созданного Джоном Талиаферро Томпсоном. Модель 1921 отличалась высоким качеством изготовления, высокой скорострельностью и мощным патроном .45 ACP.

Оружие использует автоматику со свободным затвором с замедлением открытия и способно вести автоматический и одиночный огонь. Питание осуществляется из коробчатого магазина на 20 или 30 патронов либо из барабанного магазина на 50 или 100 патронов.

Благодаря тяжёлому патрону и высокой плотности огня Томпсон особенно эффективен на ближней дистанции, где способен быстро подавить несколько целей.

ПРИМЕЧАНИЯ:

- Высокая останавливающая сила на ближней дистанции.
- Эффективен преимущественно на ближней и средней дистанции.
- Большая масса и высокая скорострельность затрудняют контроль оружия при непрерывной стрельбе.
- Модель 1921 отличается тщательной обработкой и более высокой стоимостью производства по сравнению с последующими упрощёнными версиями Томпсона.
