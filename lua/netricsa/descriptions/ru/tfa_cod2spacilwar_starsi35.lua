ПИСТОЛЕТ-ПУЛЕМЁТ STAR SI-35


ОРУЖИЕ:  Пистолет-Пулемёт Star Si-35
ПАТРОНЫ: 9x23 мм Largo
СС:      300 / 700 выстрелов / мин.
ВЕС:     ~3,8 кг.

ОПИСАНИЕ:

Испанский пистолет-пулемёт, разработанный компанией Star Bonifacio Echeverria в 1935 году. Оружие создавалось для испанских вооружённых сил и отличалось довольно необычной для своего времени конструкцией. Корпус сочетал металлические детали с деревянным прикладом, а ствол находился внутри характерного цилиндрического кожуха.

Si-35 использует автоматику с замедленным откатом затвора и ведёт огонь с открытого затвора. Главная особенность оружия заключается в наличии отдельного переключателя темпа стрельбы: стрелок мог выбрать одиночный огонь, примерно 300 или 700 выстрелов в минуту.

Конструкция считалась достаточно надёжной, однако получилась сложной и дорогой в производстве. Оружие выпускалось ограниченно и в итоге уступило место более простым конструкциям. Небольшое количество Si-35 использовалось в Испании в последние месяцы Гражданской войны.

ПРИМЕЧАНИЯ:

- Три режима огня позволяют использовать оружие по-разному: одиночные выстрелы для точности, 300 выстрелов/мин для контролируемого огня и 700 для плотных очередей.
- Конструкция получилась довольно сложной для своего класса, что стало одной из причин отказа от дальнейшего развития Si-35.
- Оружие имело крепление для штыка винтовочного типа, что для пистолета-пулемёта выглядит весьма серьёзно.
- Испанский пистолет-пулемёт с тремя скоростями стрельбы: даже оружие решило, что иногда хочется пострелять поспокойнее.
