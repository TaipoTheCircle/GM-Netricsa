ПИСТОЛЕТ-ПУЛЕМЁТ MP28


ОРУЖИЕ:  Пистолет-пулемёт MP28
ПАТРОНЫ: 9x19 мм Парабеллум
СС:      ~550-600 выстрелов / мин

ОПИСАНИЕ:

Немецкий пистолет-пулемёт, разработанный Хьюго Шмайссером в 1928 году как дальнейшее развитие MP18. Оружие получило переводчик огня, позволявший выбирать между одиночной и автоматической стрельбой, а также более удобный рядный магазин.

MP28 использовал свободный затвор и магазин на 20 или 32 патрона. Благодаря простоте конструкции и большому количеству экспортных вариантов он получил распространение в разных странах и участвовал во множестве конфликтов своего времени.

ПРИМЕЧАНИЯ:

- Прямой потомок MP18, но с более удобным управлением огнём.
- Выпускались варианты под несколько разных патронов.
- Конструкция оказалась настолько удачной, что породила несколько зарубежных копий.
- Выглядит солидно, стреляет бодро, а весит почти как маленькая гиря.
