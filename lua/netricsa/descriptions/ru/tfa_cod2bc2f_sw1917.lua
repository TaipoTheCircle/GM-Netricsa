РЕВОЛЬВЕР SMITH & WESSON МОДЕЛИ 1917


ОРУЖИЕ:  Револьвер Smith & Wesson Модель 1917
ПАТРОНЫ: .45 ACP
СС:      ~40 выстрелов / мин.
ВЕС:     ~1,1 кг.

ОПИСАНИЕ:

Американский армейский револьвер, разработанный во время Первой мировой войны из-за нехватки штатных самозарядных пистолетов. Он был принят на вооружение армии США в 1917 году и выпускался как компанией Smith & Wesson, так и Colt.

Револьвер использует мощный патрон .45 ACP и имеет барабан на шесть патронов. Поскольку .45 ACP изначально предназначался для самозарядных пистолетов, для его использования в револьвере применялись специальные полукруглые обоймы, удерживающие по три патрона и позволяющие одновременно заряжать и извлекать их из барабана.

Модель 1917 отличается крупной и прочной конструкцией, хорошей останавливающей силой и достаточно высокой надёжностью. После окончания Первой мировой войны револьверы продолжали использоваться американскими военнослужащими и полицией, а отдельные экземпляры оставались востребованными ещё долгие годы.

ПРИМЕЧАНИЯ:

- Благодаря мощному .45 ACP хорошо подходит для точной стрельбы на ближней и средней дистанции.
- Крупный патрон обеспечивает высокую останавливающую силу, несмотря на сравнительно невысокую скорострельность.
- Использование полукруглых обойм позволяет быстро заряжать сразу по три патрона.
