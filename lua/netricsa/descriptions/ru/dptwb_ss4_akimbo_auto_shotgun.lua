АВТОМАТИЧЕСКИЙ ДРОБОВИК НАЧАЛО ФОСТЕЧ 12


ОРУЖИЕ:  Автоматический дробовик Начало Фостеч 12
ПАТРОНЫ: Дробовые Патроны 12 Калибра
СС:      Автоматический, ~120 выстрелов / мин.
ВЕС:     ~5 кг.

ОПИСАНИЕ:

Мощное оружие ближнего боя, предназначенное для быстрого уничтожения противников плотным потоком дроби. В отличие от помповых дробовиков, оружие не требует ручного передёргивания после каждого выстрела, что позволяет вести непрерывный огонь с высокой скоростью.

Каждый выстрел выпускает большое количество дроби, создавая широкую область поражения. Это делает оружие особенно эффективным против групп противников и крупных целей на короткой дистанции. На более дальних расстояниях дробь быстро рассеивается, поэтому эффективность заметно снижается.

ПРИМЕЧАНИЯ:

- Высокая мощность каждого выстрела.
- Полностью автоматическая стрельба.
- Очень эффективен на ближней дистанции.
- Хорошо подходит для борьбы с несколькими противниками.
- На средней дистанции эффективность постепенно снижается из-за рассеивания дроби.
- Большая скорострельность приводит к быстрому расходу боеприпасов.
- Не требует ручного передёргивания затвора между выстрелами.
