ОГНЕМЁТ ESUS "САТАНА 93Т"


ОРУЖИЕ:  Огнемёт ESUS "Сатана 93Т"
ПАТРОНЫ: Газ, Зажигательный Гель

ОПИСАНИЕ:

Мощный огнемёт ближнего действия, выпускающий поток раскалённого пламени. Оружие наносит огромный урон на короткой дистанции и способно буквально поджарить всё, до чего доберётся.

Вторичный режим превращает "Сатана 93Т" в гранатомёт с напалмовыми зарядами. Граната летит на большое расстояние и после взрыва создаёт область пламени. Особенно эффективно оружие против больших насекомых и другой живности.

ПРИМЕЧАНИЯ:

- Основной режим отлично подходит для ближнего боя.
- Напалмовая граната превращает дальнюю цель в очень плохую новость.
- Может подрывать геотермальные источники, вызывая мощный взрыв.
- Если враг не сгорел, значит, он ещё не достаточно близко.
