ТАНК СТРОГГОВ С СТРОГГОСА


КЛАСС:        Танк Строггов
МЕТАБОЛИЗМ:   Биомеханический Киборг
ВОСПРИЯТИЕ:   Тяжёлая Штурмовая Единица Строггов
РАЗМЕР:       ~2,5 м.
ВЫНОСЛИВОСТЬ: Очень Высокая
ВРАЖДЕБНОСТЬ: Чрезвычайная
ОРУЖИЕ:       Пулемёт, Ракетная Установка, Плазменное Оружие
НАГРАДА:      1000
УГРОЗА:       Очень Высокая

ОПИСАНИЕ:

Танк Строггов является одной из наиболее тяжёлых боевых единиц их армии. Это массивный обстроггированный солдат, созданный не для скрытности или манёвренности, а для прямого прорыва обороны противника. Его тело сочетает органические ткани с металлическими конструкциями, тяжёлой бронёй и встроенными системами вооружения.

В отличие от обычных строггов, Танку не требуется быстро приближаться к противнику. Он способен вести бой на значительном расстоянии, используя установленное на теле тяжёлое вооружение. Его огневая мощь позволяет подавлять пехоту, разрушать укрытия и заставлять противника постоянно менять позицию.

Массивная конструкция делает Танка крайне живучим. Несмотря на размеры, он достаточно подвижен, чтобы преследовать своих жертв и не позволять им бесконечно отступать.

СОВЕТЫ:

- Особенно опасен в помещениях и узких коридорах.
- Не пытайся перестрелять Танка из слабого оружия.
- Используй тяжёлое вооружение и взрывчатку.
- Постоянно двигайся и не позволяй ему зажать тебя в углу.
- Укрытие помогает пережить его огонь, но не стоит рассчитывать на него слишком долго.
- Если рядом с Танком находятся другие строгги, сначала оцени возможность уничтожить поддержку, иначе тяжёлый юнит будет прикрывать их своим огнём.
