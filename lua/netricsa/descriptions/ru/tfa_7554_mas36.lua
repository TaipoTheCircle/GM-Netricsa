МАГАЗИННАЯ ВИНТОВКА MAS-36


ОРУЖИЕ:  Магазинная Винтовка MAS-36
ПАТРОНЫ: 7,5x54 мм French
СС:      10 выстрелов в минуту

ОПИСАНИЕ:

Французская магазинная винтовка, разработанная коллективом конструкторов под руководством капитана Монтейля и принятая на вооружение в 1936 году. Производилась государственным оружейным предприятием Manufacture d'armes de Saint-Étienne (MAS). Предназначалась для замены устаревших винтовок Lebel и Berthier. Отличается необычной формой рукояти затвора, загнутой вперёд и вниз, а также простой и прочной конструкцией, рассчитанной на эксплуатацию в сложных условиях.

Работает по принципу продольно-скользящего поворотного затвора с ручным перезаряжанием. Использует французский винтовочный патрон 7,5x54 мм и встроенный коробчатый магазин на 5 патронов. Заряжание производится сверху при помощи обоймы или по одному патрону. Оснащена диоптрическим прицелом и четырёхгранным игольчатым штыком, который хранится в специальном канале под стволом. Винтовка отличается надёжностью и хорошей точностью, однако уступает самозарядным образцам по скорострельности.

ПРИМЕЧАНИЯ:

- Хорошо подходит для поражения одиночных целей на средних и дальних дистанциях.
- Не предназначена для борьбы с бронетехникой и тяжело бронированными целями.
- Эффективная дальность стрельбы около 400 метров.
- Существовала десантная версия CR39 со складным алюминиевым прикладом.
- Мощный винтовочный патрон обеспечивает высокую эффективность против незащищённой живой силы.
