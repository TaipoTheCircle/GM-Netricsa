ПИСТОЛЕТ-ПУЛЕМЁТ BERETTA MAB 38


ОРУЖИЕ:  Пистолет-Пулемёт Beretta MAB 38
ПАТРОНЫ: 9x19 мм Parabellum
СС:      ~600 выстрелов / мин.
ВЕС:     ~4,2 кг.

ОПИСАНИЕ:

Beretta MAB 38, также известная как Modello 38, итальянский пистолет-пулемёт, разработанный Тулио Мареньони и представленный в 1938 году. Оружие создавалось с упором на надёжность, точность и высокое качество изготовления. Несмотря на сравнительно большую массу, MAB 38 получила репутацию одного из наиболее удачных итальянских образцов стрелкового оружия Второй мировой войны.

Пистолет-пулемёт использует автоматику со свободным затвором и ведёт огонь с открытого затвора. Интересной особенностью ранних вариантов были два спусковых крючка: передний предназначался для одиночного огня, а задний для непрерывного. Таким образом, стрелку не требовалось переключать отдельный режим огня.

MAB 38 применялась итальянскими армейскими, полицейскими и специальными подразделениями, включая десантников и штурмовые части. Благодаря хорошей точности оружие оставалось эффективным не только в ближнем бою, но и на дистанциях около 200 метров.

ПРИМЕЧАНИЯ:

- Отличается хорошей точностью для пистолета-пулемёта и особенно хорошо показывает себя на ближней и средней дистанции.
- Два спусковых крючка позволяют выбирать между одиночным и автоматическим огнём буквально пальцем, без отдельного переключателя.
- MAB 38 долго считался оружием для наиболее хорошо оснащённых подразделений, включая итальянских десантников и штурмовиков.
- Тяжеловат, основательно сделан и стреляет очень прилично. Итальянцы явно решили, что пистолет-пулемёт тоже заслуживает хорошей сборки.
