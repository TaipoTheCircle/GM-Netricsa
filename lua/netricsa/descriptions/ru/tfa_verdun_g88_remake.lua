ПЕХОТНАЯ ВИНТОВКА GEWEHR 88/05 "KOMMISSIONSGEWEHR"


ОРУЖИЕ:  Пехотная Винтовка Gewehr 88/05 "Kommissionsgewehr"
ПАТРОНЫ: 7,92x57 мм Mauser
СС:      ~12 Выстрелов / Мин

ОПИСАНИЕ:

Немецкая магазинная винтовка, представляющая собой модернизированную версию Gewehr 1888, разработанную Германской стрелковой испытательной комиссией. Модернизация началась в 1905 году и была направлена на приспособление старых винтовок к использованию нового остроконечного патрона S-Patrone. Также была изменена система заряжания, благодаря чему винтовка получила возможность использовать стандартные пятизарядные обоймы Маузера. Применялась германской армией во время Первой мировой войны наряду с более современными Gewehr 98.

Работает по принципу ручного перезаряжания с продольно-скользящим затвором. Использует винтовочный патрон 7,92x57 мм Mauser. Питание осуществляется из постоянного коробчатого магазина вместимостью 5 патронов, снаряжаемого обоймой сверху. В отличие от первоначальной Gewehr 1888, использовавшей пачку Манлихера, модернизированная версия получила направляющие для обоймы Маузера и закрытое отверстие для выброса пустой пачки. Оснащена длинным стволом с защитным кожухом, деревянной ложей и механическими прицельными приспособлениями.

ПРИМЕЧАНИЯ:

- Эффективна против одиночных целей на средних и дальних дистанциях.
- Магазин вмещает 5 патронов.
- Использует остроконечный патрон S-Patrone.
- Около 350 000 винтовок Gewehr 88 было переоборудовано до стандарта 88/05.
