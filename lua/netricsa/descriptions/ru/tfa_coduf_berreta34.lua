ПИСТОЛЕТ BERETTA M1934


ОРУЖИЕ:  Пистолет Beretta M1934
ПАТРОНЫ: 9x17 мм Browning Short (.380 ACP)
СС:      ~30-40 выстрелов / мин.
ВЕС:     ~0,605 кг.

ОПИСАНИЕ:

Итальянский самозарядный пистолет, разработанный фирмой Beretta и принятый на вооружение в 1934 году. Он создавался как компактное армейское оружие и получил широкое распространение в итальянских вооружённых силах. Производство продолжалось десятилетиями, а всего было выпущено более миллиона экземпляров.

Пистолет использует автоматику со свободным затвором и характерный для Beretta открытый сверху кожух-затвор, благодаря которому большая часть ствола остаётся на виду. Ствол при стрельбе неподвижен, а сам пистолет отличается простой конструкцией и удобством обслуживания.

Основным боеприпасом M1934 является 9x17 мм. Существовал также близкий вариант Beretta M1935 под патрон 7,65x17 мм. M1934 применялась итальянской армией во Второй мировой войне, а отдельные экземпляры после захвата использовались и другими странами.

ПРИМЕЧАНИЯ:

- Компактный и лёгкий пистолет, хорошо подходящий для ближней дистанции.
- Открытый сверху кожух-затвор стал одной из самых узнаваемых черт классических пистолетов Beretta.
- M1934 выпускалась в огромных количествах и оставалась в производстве много десятилетий.
- Этот пистолет успел засветиться даже в советском кино: Его Держал главный герой Семён Семёнович Горбунков в "Бриллиантовой Руке".
