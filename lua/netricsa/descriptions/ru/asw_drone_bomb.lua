ТРУТЕНЬ РОЯ, ОРБЕР


КЛАСС:        Трутень Роя, Орбер
МЕТАБОЛИЗМ:   Инопланетное Членистоногое
ВОСПРИЯТИЕ:   Штурмовой Трутень, Взрывная Разновидность
РАЗМЕР:       1,7 м.
ВЫНОСЛИВОСТЬ: Средняя
ВРАЖДЕБНОСТЬ: Высокая
ОРУЖИЕ:       Когти, Челюсти, Энергетические Сферы
НАГРАДА:      300
УГРОЗА:       Высокая

ОПИСАНИЕ:

Орберы являются особой разновидностью обычных трутней, отличающейся более яркой жёлтой окраской и необычной защитной реакцией. В остальном они сохраняют поведение и боевые способности стандартных трутней, атакуя противников в ближнем бою и стараясь быстро сократить дистанцию.

Главная особенность Трутня-Орбера проявляется в момент его гибели. После смертельного повреждения его тело начинает выделять нестабильную энергетическую реакцию, после чего во все стороны разлетаются многочисленные энергетические сферы.

Сферы ведут себя подобно снарядам Бумера: они летят наружу, сталкиваются с окружающими объектами и взрываются при контакте, нанося урон всему, кто оказался поблизости. Поэтому уничтожение такого трутня на близкой дистанции может оказаться почти столь же опасным, как и сама атака.

Неизвестно, является ли энергетический выброс намеренной защитной реакцией или побочным эффектом необычного метаболизма этих существ. Для роя это, впрочем, не имеет особого значения: погибший Трутень-Орбер превращает собственную смерть в последний удар по противнику.

Именно поэтому бойцы быстро научились отличать их от обычных трутней по ярко-жёлтому цвету. Если такой пришелец приближается к группе, уничтожать его вплотную крайне нежелательно.

СОВЕТЫ:

- Не стой рядом с ним в момент убийства.
- Ярко-жёлтая окраска позволяет отличить Трутня-Орбера от обычного трутня.
- По возможности уничтожай его на дистанции.
- В узких коридорах Сферы особенно опасны, поскольку уклониться от них значительно сложнее.
- Если Трутень-Орбер находится среди других пришельцев, сначала оцени пространство вокруг него: после смерти безопасной зоны рядом практически не останется.
- После появления сфер не спеши возвращаться к трупу. Сначала пережди или уклонись от разлетающихся сфер.
