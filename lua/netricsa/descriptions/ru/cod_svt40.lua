САМОЗАРЯДНАЯ ВИНТОВКА СВТ-40


ОРУЖИЕ:  Саморядная Винтовка СВТ-40
ПАТРОНЫ: 7,62x54 мм R
СС:      ~30 выстрелов / мин.
ВЕС:     ~3,8 кг.

ОПИСАНИЕ:

СВТ-40, самозарядная винтовка системы Токарева образца 1940 года, советская военная винтовка времён Великой Отечественной войны. Она создавалась как современная замена магазинным винтовкам и должна была значительно повысить огневую мощь пехотного отделения. На вооружение СВТ-40 была принята в 1940 году и выпускалась до 1945 года.

Винтовка использует газоотводную автоматику с запиранием перекосом затвора. В отличие от Мосина, после выстрела СВТ-40 автоматически выбрасывает гильзу и досылает следующий патрон, позволяя стрелку быстро делать повторные выстрелы без ручного движения затвором. Питание осуществляется из съёмного магазина на 10 патронов.

СВТ-40 имела эффективную дальность около 400 метров и начальную скорость пули около 830 м/с. Существовал также снайперский вариант, однако из-за недостаточной кучности его производство было прекращено в 1942 году.

Позднее на основе СВТ-40 была создана АВТ-40, способная вести автоматический огонь. Однако интенсивная стрельба очередями оказалась слишком тяжёлой для конструкции, поэтому автоматический вариант имел проблемы с надёжностью и живучестью деталей.

ПРИМЕЧАНИЯ:

- Хорошо подходит для средней и дальней дистанции, особенно при одиночной стрельбе.
- Самозарядная система позволяет значительно быстрее делать повторные выстрелы, чем из обычной магазинной винтовки.
- Винтовка требовала более тщательного ухода и правильной регулировки газовой системы, чем простая Мосинка.
- СВТ-40: советская попытка сделать пехотную винтовку современной. Автоматика есть, магазин есть, а вот характер всё равно суровый.
