СПЕЦИАЛЬНЫЙ КАРАБИН КС-23


ОРУЖИЕ:  Специальный Карабин КС-23
ПАТРОНЫ: 23x75 мм R
СС:      ~4-5 Выстрелов / Мин

ОПИСАНИЕ:

Советский специальный карабин крупного калибра, разработанный НИИ специальной техники МВД СССР совместно с ЦНИИточмашем в начале 1980-х годов. Принят на вооружение в 1985 году и предназначался для оснащения подразделений Министерства внутренних дел. Используется для пресечения массовых беспорядков, задержания правонарушителей и выполнения специальных полицейских задач. Отличается необычно крупным калибром 23 мм и нарезным стволом, при изготовлении которого использовались заготовки от авиационных пушек.

Работает по принципу ручного перезаряжания с подвижным цевьём, связанным с затвором. Использует специальные патроны калибра 23x75 мм R. Питание осуществляется из подствольного трубчатого магазина вместимостью 3 патрона, ещё один патрон может находиться в патроннике. Оснащён деревянным прикладом, открытыми механическими прицельными приспособлениями и нарезным стволом. Для карабина разработана широкая номенклатура специальных боеприпасов различного назначения.

ПРИМЕЧАНИЯ:

- Разработан для нужд МВД СССР.
- Принят на вооружение в 1985 году.
- Использует нарезной ствол калибра 23 мм.
- Магазин вмещает 3 патрона, дополнительно 1 патрон в патроннике.
- Существуют модификации КС-23М "Дрозд" и КС-23К.
