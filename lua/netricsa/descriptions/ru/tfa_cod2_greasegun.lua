ПИСТОЛЕТ-ПУЛЕМЁТ M3 "МАСЛЁНКА"


ОРУЖИЕ:  Пистолет-пулемёт M3 "маслёнка"
ПАТРОНЫ: .45 ACP (11,43x23 мм)
СС:      ~450 выстрелов / мин.
ВЕС:     ~3,7 кг.

ОПИСАНИЕ:

M3, получивший знаменитое прозвище "Маслёнка", американский пистолет-пулемёт времён Второй мировой войны. Он был разработан как более дешёвая и простая альтернатива дорогому и сложному Томпсону. Конструкция максимально ориентирована на массовое производство: корпус изготовлен преимущественно из штампованной стали, а детали соединяются сваркой.

M3 использует автоматику со свободным затвором и ведёт только автоматический огонь. Питание осуществляется из коробчатого магазина на 30 патронов. Невысокий темп стрельбы около 450 выстрелов в минуту делает оружие довольно управляемым для пистолета-пулемёта.

Оружие поступило в войска в 1943 году и первоначально предназначалось для замены Томпсона. Позднее появилась улучшенная версия M3A1, отличавшаяся упрощённой конструкцией и рядом изменений в механизме перезаряжания. Существовали также варианты под 9x19 мм Parabellum.

ПРИМЕЧАНИЯ:

- Низкая для ПП скорострельность позволяет лучше контролировать оружие при ведении очередей.
- Главная философия M3: дёшево, просто и сердито. Его специально сделали значительно менее трудоёмким в производстве, чем Томпсону.
- Благодаря компактности и складному проволочному прикладу M3 особенно хорошо подходил экипажам бронетехники и другим бойцам, которым полноценная винтовка была неудобна.
- Выглядит так, будто механик случайно забыл закрыть гараж и вышел на войну с маслёнкой. Но это действительно боевой пистолет-пулемёт.
