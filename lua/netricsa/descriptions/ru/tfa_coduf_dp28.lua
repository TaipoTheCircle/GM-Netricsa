РУЧНОЙ ПУЛЕМЁТ ДП-28


ОРУЖИЕ:  Ручной Пулемёт ДП-28
ПАТРОНЫ: 7,62x54 мм R
СС:      ~500-600 выстрелов / мин.
ВЕС:     ~11,8 кг.

ОПИСАНИЕ:

ДП-28, более известный как ДП, или "Дегтярёв пехотный", советский ручной пулемёт, разработанный Василием Дегтярёвым и принятый на вооружение РККА в 1927 году. Он создавался как оружие огневой поддержки пехоты и массово применялся во время Великой Отечественной войны.

Пулемёт использует газоотводную автоматику и ведёт огонь с открытого затвора. Его главная внешняя особенность, знаменитый плоский дисковый магазин, установленный сверху, получил среди бойцов прозвище "тарелка". Поздние магазины вмещали 47 патронов.

ДП устанавливался на складных сошках и предназначался прежде всего для поддержки пехоты. Несмотря на сравнительно небольшую боевую скорострельность, он позволял создавать плотный огонь на дистанциях до нескольких сотен метров. При интенсивной стрельбе тонкий ствол быстро нагревался, поэтому оружие требовало ведения огня короткими очередями.

ПРИМЕЧАНИЯ:

- Хорошо подходит для подавления противника на ближней и средней дистанции, особенно при стрельбе с упора.
- Верхний дисковый магазин стал одной из самых узнаваемых особенностей ДП. Выглядит необычно, зато позволяет использовать патрон с выступающей закраиной.
- Для стрельбы по глубокому снегу существовало специальное приспособление, напоминавшее небольшой снегоступ, чтобы сошки не проваливались.
