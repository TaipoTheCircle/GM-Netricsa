САМОЗАРЯДНЫЙ ПИСТОЛЕТ DREYSE M1907


ОРУЖИЕ:  Самозарядный Пистолет Dreyse M1907
ПАТРОНЫ: 7,65x17 мм Browning (.32 ACP)
СС:      Полуавтоматический Огонь, 7 Патронов

ОПИСАНИЕ:

Немецкий самозарядный пистолет, разработанный конструктором Луисом Шмайссером в 1905-1906 годах. Производился компанией Rheinische Metallwaaren-und Maschinenfabrik в Зёммерде с 1907 по 1915 год. Получил название в честь оружейника Иоганна Николауса фон Дрейзе, хотя сам он к разработке пистолета отношения не имел. Компактное оружие предназначалось для самообороны и использования в качестве личного оружия военнослужащих и сотрудников полиции.

Автоматика работает по принципу отдачи свободного затвора, ударный механизм ударникового типа. Питание осуществляется из однорядного съёмного магазина на 7 патронов калибра 7,65 мм Browning. Одной из необычных особенностей конструкции является шарнирное крепление затворной коробки к рамке: для чистки и разборки верхняя часть пистолета откидывается вперёд. Выступающий назад ударник также служит индикатором взведения.

ПРИМЕЧАНИЯ:

- Разработан Луисом Шмайссером, отцом знаменитого оружейного конструктора Хуго Шмайссера.
- Масса незаряженного пистолета составляет около 710 г.
- Прицельные приспособления рассчитаны на стрельбу примерно до 25 метров.
