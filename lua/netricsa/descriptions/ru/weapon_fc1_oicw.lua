ШТУРМОВАЯ ВИНТОВКА ОИБО


ОРУЖИЕ:     Объективное Индивидуальное Боевое Оружие (ОИБО)
ПАТРОНЫ:    Патроны 5,56x45 мм
СС:         ~650 Выстрелов / Мин

ОПИСАНИЕ:

Штурмовой винтовка, сочетающий в себе быстрострельные баллистические патроны. Предназначена в качестве боевого оружия нового поколения. Обеспечивает точный автоматический огонь, позволяя мгновенно подавлять противника.

ПРИМЕЧАНИЯ:

- Разработано как универсальное пехотное оружие.
