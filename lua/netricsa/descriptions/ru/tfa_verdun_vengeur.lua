ОКОПНЫЙ КИНЖАЛ MODÈLE 1916 "LE VENGEUR"


ОРУЖИЕ:  Окопный Кинжал Modèle 1916 "Le Vengeur"
ПАТРОНЫ: Отсутствуют
СС:      Ручное Оружие

ОПИСАНИЕ:

Французский боевой кинжал, разработанный во время Первой мировой войны для использования в траншейных боях. Создан на основе ранних окопных ножей и штыков, а его конструкция была предложена производителем ножей Astier-Prodon. Принят на вооружение в 1916 году. Предназначался для ближнего боя в условиях тесных траншей и получил прозвище "Le Vengeur", что переводится как "Мститель".

Оснащён прочным обоюдоострым клинком с ромбовидным поперечным сечением, деревянной рукоятью и металлической гардой для защиты кисти. Общая длина составляет около 28 см, длина клинка около 17 см. Некоторые экземпляры имеют надпись "Le Vengeur de 1870", отсылающую к поражению Франции во Франко-прусской войне. Производился несколькими французскими предприятиями.

ПРИМЕЧАНИЯ:

- Эффективен исключительно в ближнем бою.
- Длина клинка составляет около 17 см.
- Масса составляет около 200 граммов без ножен.
- Использовался французской пехотой и экипажами первых танков.
