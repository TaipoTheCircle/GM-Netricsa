ОПИСАНИЕ:

Убер-Жук Дрон Роя представляет собой значительно увеличенную, более массивную и медлительную разновидность обычного дрона. Его тело отличается чрезвычайно развитой мускулатурой и толстым хитиновым покровом, позволяющим выдерживать огромное количество повреждений.

Главная особенность его строения заключается в огромном ротовом аппарате. Вокруг пасти расположено множество длинных острых клыков, образующих несколько рядов. При атаке Убер-Жук использует их вместе с передними конечностями, нанося тяжёлые повреждения любой цели, оказавшейся рядом.

Несмотря на внушительную прочность, Убер-Жук обладает заметно меньшей скоростью и манёвренностью по сравнению с обычным дроном. Он медленно продвигается вперёд, полагаясь на свою способность выдерживать огонь противника.

Однако наиболее опасная особенность Убер-Жука проявляется после его смерти.

При гибели тело существа взрывается, выбрасывая наружу большое количество биологического содержимого и нанося значительный урон находящимся поблизости целям. Таким образом, уничтожение Убер-Жука на близкой дистанции может оказаться смертельным даже после того, как сам пришелец уже погиб.

Из-за этого Убер-Жук представляет угрозу на протяжении всего столкновения.

СОВЕТЫ:

- Не добивай Убер-Жука в упор.
- Всегда оставляй между собой и ним дистанцию перед нанесением смертельного удара.
- Используй дальнобойное оружие, чтобы уничтожить его с безопасного положения.
- В тесных помещениях его взрыв особенно опасен.
- Если он окружён обычными дронами, сначала оцени возможность отступления.

