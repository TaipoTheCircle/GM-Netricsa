HALF-QUAKE 2, КАБИНКА "ЖИЗНЬ И СМЕРТЬ"


Сэм, стой! Посмотри, что тут у нас... Очередной "подарок" от наших друзей-садистов.

Это кабинки. Всего две кнопки: "Жизнь" и "Смерть". Нажмёшь на "Жизнь" - и ты полностью вылечишься. Переломы, раны, даже твоя вечная усталость - всё пройдёт. Нажмёшь на "Смерть"... ну, ты понял. Летальный исход. Без вариантов.

...

И да, только один раз. Нельзя переиграть, нельзя попросить второй шанс. Как в жизни, Сэм. Только в жизни у тебя не было кнопки с надписью "Смерть".

Эти кабинки будут встречаться нам по всему шоу. Так что запомни: если ты на грани - жми на "Жизнь". Но если тебе вдруг захочется проверить, работает ли "Смерть" - пожалуйста, только без меня. У меня ещё много дел, например, анализировать твои ошибки!

Идём дальше. И не вздумай нажимать на кнопку Смерти из любопытства! Иначе какой ты крутой после этого?
