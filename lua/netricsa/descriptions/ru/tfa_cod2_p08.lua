ПИСТОЛЕТ ЛЮГЕРА P08 "ПАРАБЕЛЛУМ"


ОРУЖИЕ:  Пистолет Люгера P08 "Парабеллум"
ПАТРОНЫ: 9x19 мм Parabellum
СС:      ~32 выстрела / мин.
ВЕС:     ~0,88 кг.

ОПИСАНИЕ:

Немецкий самозарядный пистолет, разработанный Георгом Люгером на основе конструкции Борхардта. Оружие стало одним из наиболее узнаваемых пистолетов начала XX века и использовалось германскими вооружёнными силами, а также рядом других стран.

Пистолет использует необычную систему запирания с шарнирно-рычажным механизмом. После выстрела ствол и затвор немного отходят назад, после чего система рычагов складывается, открывая затвор и обеспечивая перезарядку. Необычно наклонённая рукоятка способствует удобному удержанию и точной стрельбе.

P08 особенно ценится за точность и удобство прицеливания. Стандартный вариант использует 9x19 мм Parabellum, однако существовали и версии под 7,65x21 мм.

ПРИМЕЧАНИЯ:

- Очень точный пистолет для своего времени, особенно эффективный на ближней и средней дистанции.
- Характерный шарнирный затвор делает P08 одним из самых узнаваемых пистолетов в истории.
- Его необычная рукоятка не просто для красоты, она действительно способствует удобному хвату и точному наведению.
- "Парабеллум" буквально означает: "Хочешь мира, готовься к войне". Тут название само себя представило.
