САМОЗАРЯДНЫЙ ПИСТОЛЕТ MAUSER C96 M1921 "БОЛО"


ОРУЖИЕ:  Самозарядный Пистолет Mauser C96 M1921 "Боло"
ПАТРОНЫ: 7,63x25 мм Mauser
СС:      ~120 Выстрелов / Мин

ОПИСАНИЕ:

Немецкий самозарядный пистолет, представляющий собой укороченную модификацию Mauser C96, разработанную компанией Mauser в начале 1920-х годов. Появление этой версии было связано с ограничениями Версальского договора, запрещавшими Германии производить пистолеты с длиной ствола более 100 мм. M1921 получил укороченный до 99 мм ствол, уменьшенную рукоять и более компактные габариты. Благодаря своим размерам получил прозвище "Боло", связываемое с большевиками, среди которых пистолет пользовался популярностью.

Работает по принципу использования отдачи ствола с коротким ходом и имеет систему запирания с качающимся затворным упором. Использует пистолетный патрон 7,63x25 мм Mauser. Питание осуществляется из постоянного коробчатого магазина вместимостью 10 патронов, снаряжаемого сверху при помощи обоймы. Оснащён открытыми механическими прицельными приспособлениями и внешним курком. Деревянная кобура может использоваться в качестве приставного приклада, позволяя вести более устойчивую стрельбу.

ПРИМЕЧАНИЯ:

- Кобура может использоваться в качестве приклада.
- Эффективен против одиночных незащищённых целей на коротких и средних дистанциях.
- Производился с 1921 по 1930 год.
- Ствол укорочен до 99 мм.
- Магазин вмещает 10 патронов.
- Использовался Красной армией и различными военными формированиями Восточной Европы.
