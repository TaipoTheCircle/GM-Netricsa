МАСТЕР БОЕВЫХ ИСКУССТВ С ЧИ-ФАНГ


КЛАСС:        Мастер Боевых Искусств
МЕТАБОЛИЗМ:   Разумное Существо
ВОСПРИЯТИЕ:   Старый Мастер, Наставник
РАЗМЕР:       3,6 м.
ВЫНОСЛИВОСТЬ: Очень Высокая
ВРАЖДЕБНОСТЬ: Низкая
ОРУЖИЕ:       Боевые Искусства
НАГРАДА:      2000
УГРОЗА:       Очень Высокая

ОПИСАНИЕ:

Он является одним из наиболее уважаемых наставников планеты. Старый и мудрый воин посвятил большую часть своей жизни изучению боевых искусств и обучению нового поколения бойцов.

Для него ученики никогда не были просто подчинёнными или бойцами. Он относился к ним как к собственной семье, заботился об их жизни, обучении и характере. В его школе младшие ученики уважали старших, а все вместе относились к мастеру как к отцу и наставнику.

У мастера был один ученик, который пошёл совершенно иным путём. Озлоблённый и отверженный, он отвернулся от традиций и посвятил себя тёмным искусствам.

Со временем он собрал собственных последователей и стал Мастером Тёмных Искусств.

Однажды он напал на школу своего бывшего учителя вместе со своими учениками. Придя, тёмный мастер использовал свои способности, чтобы превратить учеников Мастера Боевых Искусств в куриц и забрать их с собой.

Для старого мастера это стало тяжелейшим ударом.

Однако он не бросил своих учеников.

Он отправился в путь один, намереваясь вернуть их домой.

На своём пути мастер столкнулся с многочисленными учениками своего бывшего ученика. Несмотря на возраст, он продемонстрировал невероятное боевое мастерство.

Против него выступали десятки противников, но мастер не отступал.

Каждый поверженный противник приближал его к пленным ученикам.

Наконец мастер добрался до самого Мастера Тёмных Искусств. Но тот не собирался сдаваться.

Понимая, что он проиграет в прямом столкновении, Мастер Тёмных Искусств призвал древнюю сущность расы драконоидов.

Началась долгая и тяжёлая битва.

Древнее существо превосходило обычного противника по силе и размерам, однако старый мастер не позволил страху взять верх. Используя своё мастерство и находчивость, он сумел одолеть даже эту чудовищную сущность.

В решающий момент мастер оторвал ему язык, лишив его одного из главных средств воздействия. Так Мастер Тёмных Искусств был окончательно повержен.

А его заклинание было разрушено.

Ученики, превращённые в куриц, вновь обрели свой первоначальный облик.

За свои поступки мастер стал чрезвычайно почитаемым как на Чи-фане, так и среди земных китайцев.

СОВЕТЫ:

- Не недооценивай его из-за возраста. Старость лишь скрывает огромный боевой опыт.
- Не трогай его учеников.
