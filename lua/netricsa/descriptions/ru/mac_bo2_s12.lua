САМОЗАРЯДНОЕ РУЖЬЁ САЙГА-12


ОРУЖИЕ:     Самозарядное ружьё Сайга-12
ПАТРОНЫ:    12/70 мм
СС:         ~468 выстрелов / мин (S12)

ОПИСАНИЕ:

Российское самозарядное гладкоствольное ружьё, разработанное на базе автомата Калашникова и выпускаемое Ижевским машиностроительным заводом с 1997 года. Унаследовало характерную компоновку семейства АК, включая газоотводную автоматику и поворотный затвор, адаптированные под охотничьи патроны 12-го калибра.

Использует сменные коробчатые магазины различной ёмкости. В зависимости от модификации оснащается обычным или складным прикладом, а также различными прицельными приспособлениями. Компактные варианты получили широкую популярность благодаря сочетанию высокой мощности и относительно небольших размеров.

ПРИМЕЧАНИЯ:

- Создана на основе конструкции автомата Калашникова.
- Выпускается под патроны 12/70 и 12/76 мм "Магнум".
- Встречаются магазины на 2, 4, 5 и 8 патронов, а также увеличенные варианты.
- В некоторых исполнениях внешне почти не отличается от автомата Калашникова, пока не заглянешь в ствол.
- Полуавтоматический режим стрельбы.
- Магазин на 10 патронов, с увеличенным магазином на 14.
- Скорострельность около 468 выстрелов в минуту.
- Встречается под обозначением S12, а в другом варианте получил название Kamchatka-12.
