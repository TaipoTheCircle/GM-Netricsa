АВТОМАТ КАЛАШНИКОВА СКЛАДНОЙ УКOРОЧЕННЫЙ АКС-74У


ОРУЖИЕ:  Автомат Калашникова Складной Укороченный АКС-74У
ПАТРОНЫ: 5,45x39 мм
СС:      ~650-700 выстрелов / мин.
ВЕС:     ~2,7 кг.

ОПИСАНИЕ:

Укороченный вариант АКС-74, разработанный в конце 1970-х годов для экипажей боевых машин, авиатехники и других подразделений, которым требовалось максимально компактное автоматическое оружие. На вооружение СССР он начал поступать в 1980 году.

Автомат получил ствол длиной всего около 206 мм, складной приклад и специальную дульную насадку, выполняющую функции пламегасителя и расширительной камеры. Использует стандартный патрон 5,45x39 мм и магазин на 30 патронов. Несмотря на компактность, АКС-74У сохранил общую конструкцию АК-74.

Из-за очень короткого ствола АКС-74У заметно уступает полноразмерному АК-74 в кучности и эффективной дальности, зато гораздо удобнее в тесных помещениях, транспорте и при скрытом ношении.

ПРИМЕЧАНИЯ:

- Очень компактный автомат, особенно удобный для ближней дистанции.
- Создавался для экипажей техники и других бойцов, которым обычный АК-74 был слишком длинным.
- В сложенном состоянии становится настолько коротким, что полноценный АК-74 рядом с ним выглядит уже почти как винтовка.
