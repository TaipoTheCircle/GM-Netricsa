ВИНТОВКА MAUSER OVIEDO 1916


ОРУЖИЕ: Винтовка Mauser Oviedo 1916
ПАТРОНЫ: 7x57 мм Mauser
СС:     ~15-20 выстрелов / мин.
ВЕС:    ~3,7 кг.

ОПИСАНИЕ:

Испанская магазинная винтовка, выпускавшаяся на оружейном заводе в Овьедо на основе конструкции Mauser 1893. Она была принята на вооружение Испании в 1916 году и стала одним из многочисленных вариантов испанского Mauser.

Винтовка использует продольно-скользящий затвор и патрон 7x57 мм Mauser. Магазин вмещает 5 патронов и заряжается сверху при помощи обоймы. По конструкции Oviedo 1916 близка к испанскому Mauser M1893, однако имеет ряд отличий, связанных с производством и особенностями испанской службы.

Впоследствии многие винтовки были переделаны под другие боеприпасы и модернизированы. Часть Oviedo 1916 получила обозначение M1916, а позднее некоторые экземпляры были переделаны под патрон 7,62x51 мм NATO.

ПРИМЕЧАНИЯ:

- Испанский Mauser, произведённый в Овьедо, поэтому название здесь буквально рассказывает половину биографии винтовки.
- Хорошо подходит для средней и дальней дистанции благодаря точному и мощному винтовочному патрону.
- Надёжный продольно-скользящий затвор системы Mauser стал основой конструкции.
- Винтовка настолько долго оставалась полезной, что успела пережить несколько поколений боеприпасов и военных конфликтов.
