ПУЛЕМЁТ MG-88 "ИСПОЛНИТЕЛЬ"


ОРУЖИЕ:  Пулемёт MG-88 "Исполнитель"
ПАТРОНЫ: 5,56x45 мм
СС:      ~600 выстрелов / мин.

ОПИСАНИЕ:

Скорострельное автоматическое оружие, предназначенное для ведения плотного огня на ближней и средней дистанции. Оружие использует патроны 5,56x45 мм и магазин на 60 патронов, что позволяет долго вести огонь без частой перезарядки.

MG-88 обладает хорошей точностью и умеренной отдачей, однако при непрерывной стрельбе быстро расходует боезапас. Благодаря большой ёмкости магазина особенно хорошо подходит для борьбы с группами противников.

ПРИМЕЧАНИЯ:

- Большой магазин на 60 патронов позволяет долго стрелять без перезарядки.
- Хорошая точность делает его универсальным оружием.
- Подходит для плотного огня на ближней и средней дистанции.
