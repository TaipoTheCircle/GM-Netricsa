КАРАБИН M1 CARBINE


ОРУЖИЕ:  Карабин M1 Carbine
ПАТРОНЫ: .30 Carbine (7,62×33 мм)
СС:      ~40-50 выстрелов / мин.
ВЕС:     ~2.36 кг.

ОПИСАНИЕ:

Лёгкий американский самозарядный карабин времён Второй мировой войны, созданный как более компактная и удобная альтернатива полноразмерной винтовке для военнослужащих второй линии, экипажей техники и других бойцов, которым требовалось лёгкое оружие с большей мощностью, чем у пистолета.

Карабин использует газоотводную автоматику и патрон .30 Carbine. Благодаря небольшой массе, мягкой отдаче и компактным размерам M1 Carbine оказался особенно удобен в ближнем бою и при быстром перемещении. Эффективная дальность составляет около 275 метров.

В отличие от более позднего M2, стандартный M1 Carbine ведёт только одиночный огонь. Вариант M2 получил возможность автоматической стрельбы со скоростью около 750 выстрелов в минуту.

ПРИМЕЧАНИЯ:

- Отлично подходит для ближней и средней дистанции, особенно там, где полноразмерная винтовка была бы слишком громоздкой.
- Очень лёгкий карабин позволяет быстро перемещаться и почти не утомляет стрелка.
- M1 Carbine выглядит как уменьшенная винтовка, но ведёт себя скорее как очень серьёзный карабин.
- Мягкая отдача делает быстрые повторные выстрелы довольно удобными.
