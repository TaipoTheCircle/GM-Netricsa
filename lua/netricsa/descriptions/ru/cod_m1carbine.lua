КАРАБИН M1A1 CARBINE


ОРУЖИЕ:  Карабин M1A1 Carbine
ПАТРОНЫ: .30 Carbine (7,62x33 мм)
СС:      ~40-50 выстрелов / мин.
ВЕС:     ~2,5 кг.

ОПИСАНИЕ:

Американский самозарядный карабин времён Второй мировой войны, созданный на базе M1 Carbine специально для десантников и бойцов, которым требовалось компактное и лёгкое оружие. Главным отличием M1A1 стал складной металлический приклад, позволивший значительно уменьшить габариты карабина при транспортировке.

Карабин использует газоотводную автоматику и патрон .30 Carbine. Благодаря небольшой массе, компактным размерам и мягкой отдаче M1A1 особенно удобен в ближнем и среднем бою, а также при быстром перемещении. Эффективная дальность составляет около 275 метров.

В отличие от более позднего M2, стандартный M1A1 ведёт только одиночный огонь. Автоматическая версия M2 появилась позднее и получила возможность стрельбы очередями.

ПРИМЕЧАНИЯ:

- Складной приклад делает M1A1 особенно удобным для десантников и позволяет экономить место при переноске.
- Отлично подходит для ближней и средней дистанции, особенно там, где полноценная винтовка была бы слишком громоздкой.
- Небольшой вес и мягкая отдача позволяют быстро перемещаться и комфортно делать повторные выстрелы.
