САМОДЕЛЬНЫЙ ПОДЖИГНОЙ ПИСТОЛЕТ "САМОПАЛ"


ОРУЖИЕ:  Самодельный Поджигной Пистолет "Самопал"
ПАТРОНЫ: Самодельный Пороховой Заряд
СС:      1 Выстрел, Ручная Перезарядка

ОПИСАНИЕ:

Примитивное самодельное огнестрельное оружие, изготовленное из подручных материалов. Представляет собой однозарядный пистолет с металлическим стволом, закреплённым на деревянной основе. Не имеет привычных механизмов ударно-спускового устройства и отличается крайне простой конструкцией.

Для воспламенения заряда используется внешний источник огня. Оружие не имеет надёжных предохранительных механизмов и представляет серьёзную опасность даже для самого владельца. Несмотря на кустарное исполнение, способно производить настоящий выстрел и причинять тяжёлые травмы.

ПРИМЕЧАНИЯ:

- Изготовлен из медной трубки, деревянной заготовки и алюминиевой проволоки.
- Создавался для съёмок фильма "Брат 2".
- В изготовлении участвовали Сергей Астахов и Сергей Бодров.
- Крайне ненадёжная конструкция, способная представлять смертельную опасность.
