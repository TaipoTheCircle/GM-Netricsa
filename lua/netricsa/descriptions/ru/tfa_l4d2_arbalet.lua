ПНЕВМАТИЧЕСКАЯ ВИНТОВКА "ХЕЛЬСИНГ"


ОРУЖИЕ:  Пневматическая Винтовка "Хельсинг"
ПАТРОНЫ: Металлические Стрелы (Болты)
СС:      Средняя, Полуавтоматический Огонь

ОПИСАНИЕ:

Самодельное пневматическое оружие, созданное жителями Метро на основе револьверной конструкции. Представляет собой необычную многозарядную систему с восемью металлическими стволами, расположенными по револьверному принципу. Для стрельбы используется сжатый воздух, накапливаемый в специальном резервуаре. Отличается высокой точностью, практически бесшумной работой и возможностью повторного использования боеприпасов.

Подача стрел осуществляется посредством вращающегося блока стволов. Для повышения мощности выстрела необходимо накачать резервуар, однако избыточное давление постепенно стравливается. Оружие получило арбалетную конфигурацию с возможностью установки различных магазинов, оптических приспособлений и механизмов. Также может использовать взрывные стрелы.

ПРИМЕЧАНИЯ:

- Название отсылает к арбалету из фильма "Ван Хельсинг" (2004).
- Так же использует восьмизарядный вращающийся блок стволов.
- Стрелы можно подбирать после выстрела и использовать повторно.
- Перекачка резервуара повышает мощность и дальность стрельбы.
- Доступна установка магазинов на 1, 3, 6 и 8 болтов.
- Предусмотрены обычные и взрывные болты.
