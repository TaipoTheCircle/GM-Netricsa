САМОЗАРЯДНЫЙ ПИСТОЛЕТ BROWNING M1900


ОРУЖИЕ:  Самозарядный Пистолет Browning M1900
ПАТРОНЫ: 7,65x17 мм Browning
СС:      ~35 Выстрелов / Мин

ОПИСАНИЕ:

Бельгийский самозарядный пистолет, разработанный американским конструктором Джоном Мозесом Браунингом в 1896 году и запущенный в серийное производство компанией Fabrique Nationale в 1900 году. Стал одним из первых коммерчески успешных самозарядных пистолетов и получил широкое распространение среди военных, полиции и гражданского населения. Отличается компактной конструкцией, характерным кожухом-затвором и расположением возвратной пружины над стволом.

Работает по принципу отдачи свободного затвора. Использует пистолетный патрон 7,65x17 мм Browning. Питание осуществляется из съёмного однорядного магазина вместимостью 7 патронов, расположенного в рукоятке. Оснащён ударниковым ударно-спусковым механизмом одинарного действия, флажковым предохранителем и открытыми механическими прицельными приспособлениями. Возвратная пружина расположена над стволом и одновременно выполняет функцию боевой пружины ударника.

ПРИМЕЧАНИЯ:

- Эффективен против одиночных незащищённых целей на коротких дистанциях.
- Магазин вмещает 7 патронов.
- Разработан Джоном Мозесом Браунингом.
- Выпускался в Бельгии с 1900 по 1912 год.
- Всего произведено около 700 000 экземпляров.
