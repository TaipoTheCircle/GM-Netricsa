АРМЕЙСКИЙ РЕВОЛЬВЕР GASSER M1870


ОРУЖИЕ:  Армейский Револьвер Gasser M1870
ПАТРОНЫ: 11,3x36 мм R Gasser
СС:      Одиночный Огонь, 6 Патронов

ОПИСАНИЕ:

Австро-венгерский армейский револьвер, разработанный оружейником Леопольдом Гассером в 1870 году. Предназначался прежде всего для вооружения кавалерии и других подразделений австро-венгерской армии. Отличается массивной конструкцией с открытой рамкой, длинным стволом и крупной деревянной рукоятью. Благодаря мощному патрону обладал высокой останавливающей силой, однако значительные размеры и масса делали его довольно громоздким личным оружием.

Работает по принципу одинарного действия, перед каждым выстрелом курок необходимо взводить вручную. Питание осуществляется из шестизарядного барабана под патрон 11,3x36 мм R. Заряжание производится через откидную дверцу с правой стороны рамки, а стреляные гильзы извлекаются по одной при помощи шомпола-экстрактора, расположенного под стволом. Прицельные приспособления открытого типа состоят из мушки и целика.

ПРИМЕЧАНИЯ:

- Разработан Леопольдом Гассером в 1870 году.
- Состоял на вооружении австро-венгерской кавалерии.
- Барабан вмещает 6 патронов.
- Масса составляет около 1,3 кг, а общая длина достигает 375 мм.
- Существовали варианты с укороченным стволом.
- На основе конструкции появились последующие модели, включая Gasser-Kropatschek M1876.
- На Балканах револьверы системы Гассера получили широкое распространение, особенно в Черногории.
