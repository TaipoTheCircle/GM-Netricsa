ХРАНИТЕЛЬ РОЯ


КЛАСС:        Хранитель Роя
МЕТАБОЛИЗМ:   Инопланетное Биологическое Существо
ВОСПРИЯТИЕ:   Биологический Медик, Поддержка Улья
РАЗМЕР:       1,6 м.
ВЫНОСЛИВОСТЬ: Средняя
ВРАЖДЕБНОСТЬ: Высокая
ОРУЖИЕ:       Биологический регенератор, Когти, Кислотные Выделения
НАГРАДА:      350
УГРОЗА:       Средняя

ОПИСАНИЕ:

Хранители Роя являются специализированной разновидностью жуков роя, выполняющей роль живых медиков внутри инопланетных колоний. Они редко вступают в бой первыми, предпочитая находиться позади основной массы роя и поддерживать раненых особей, пока те продолжают сражаться.

Их организм вырабатывает особый регенеративный секрет, который ускоряет восстановление тканей пришельцев. Хранитель прикрепляется к повреждённой особи и покрывает её раны тонким слоем биологического материала, после чего повреждённые ткани начинают быстро восстанавливаться.

Однако этот процесс имеет неприятную особенность: регенеративный материал не всегда просто восстанавливает повреждения. Он постепенно замещает повреждённые ткани тканями самого улья. Поэтому особи, многократно подвергавшиеся лечению Хранителями, со временем становятся всё более покрытыми чужеродным экзоскелетом.

Именно Хранители Роя считаются одной из причин, по которой некоторые заражённые колонии начинают демонстрировать необычные формы гибридизации. Для самого роя это не является проблемой. Повреждённый организм становится частью общей биологической системы и продолжает выполнять свои функции.

Хранитель Роя обладает коллективным поведением и практически никогда не пытается спасти себя ценой гибели других существ. Если рядом находится раненая особь, он будет продолжать лечение даже под огнём, пока угроза не станет непосредственной.

В случае опасности Хранитель способен защищаться когтями и выделять небольшое количество едкой кислоты, а затем убегать. Однако его главная сила заключается не в нападении, а в способности удерживать рой в боеспособном состоянии значительно дольше, чем ожидалось.

Из-за этого уничтожение Хранителя часто становится приоритетной задачей для бойцов: пока он жив, уже повреждённые пришельцы могут вновь подняться и вернуться в бой.

СОВЕТЫ:

- Уничтожай Хранителя первым, если он находится рядом с группой раненых пришельцев.
- Не трать боеприпасы на его толстый экзоскелет без необходимости: он не предназначен для прямого боя.
- Если Хранитель начал лечить сильного противника, лучше сначала прервать лечение.
- В закрытых помещениях особенно опасны группы, в которых Хранители находятся за несколькими рядами боевых особей.
- После уничтожения Хранителя уже повреждённые пришельцы становятся значительно менее живучими.
