ПИСТОЛЕТ-ПУЛЕМЁТ СУДАЕВА ППС-43


ОРУЖИЕ:  Пистолет-Пулемёт Судаева ППС-43
ПАТРОНЫ: 7,62x25 мм ТТ
СС:      ~600-700 выстрелов / мин.
ВЕС:     ~3,67 кг.

ОПИСАНИЕ:

ППС-43, пистолет-пулемёт системы Алексея Судаева, советское оружие времён Великой Отечественной войны. Он создавался как более лёгкая, компактная и дешёвая альтернатива ППШ-41, особенно удобная для разведчиков, десантников, экипажей боевых машин и бойцов, которым приходилось действовать в тесных условиях.

Конструкция ППС отличается простотой и широким применением штампованных деталей, соединённых сваркой и заклёпками. Автоматика работает за счёт свободного затвора, а оружие ведёт только автоматический огонь. При этом благодаря сравнительно невысокому темпу стрельбы ППС хорошо контролируется короткими очередями.

ППС-43 получил складной металлический приклад и коробчатый магазин. Его эффективная дальность составляет примерно 100-200 метров, а наиболее рациональным считается огонь короткими очередями по 2-5 выстрелов.

ПРИМЕЧАНИЯ:

- Особенно эффективен на ближней и средней дистанции, где короткие очереди позволяют удерживать оружие под контролем.
- Благодаря штампованной конструкции ППС получился значительно проще и дешевле в производстве, чем многие его предшественники.
- Компактный складной приклад сделал его особенно удобным для разведчиков, десантников и экипажей техники.
- ППШ был тяжёлым и прожорливым, а Судаев посмотрел на него и решил: "Можно ведь сделать попроще".
