ПОЛУАВТОМАТИЧЕСКИЙ ДРОБОВИК "УБОЙНИК"


ОРУЖИЕ:  Полуавтоматический Дробовик "Убойник"
ПАТРОНЫ: 12x70 мм
СС:      Полуавтоматический Огонь, 6 Патронов

ОПИСАНИЕ:

Самодельный полуавтоматический дробовик, созданный оружейниками Ордена после ядерной войны. Отличается необычной конструкцией с открытым револьверным барабаном, в котором размещаются шесть патронов 12-го калибра. Вместо традиционной схемы подачи используется оригинальный механизм с пружинными зажимами, удерживающими боеприпасы. Обладает высокой убойной силой на коротких дистанциях и предназначен преимущественно для борьбы с мутантами и противниками в тесных помещениях.

Работает за счёт короткого хода ствола и рычажно-шарнирного механизма запирания. После каждого выстрела автоматика извлекает стреляную гильзу и подаёт следующий патрон из барабана. Перезарядка стандартной версии производится вручную, по одному патрону за раз, что занимает немало времени. В более поздних модификациях предусмотрена установка барабанных и коробчатых магазинов увеличенной ёмкости.

ПРИМЕЧАНИЯ:

- В стандартной версии использует открытый шестизарядный барабан.
- Доступны магазины на 3, 6, 10 и 20 патронов.
- Существует уникальная версия со штык-ножом.
- Поддерживает коллиматорный и инфракрасный прицелы, глушитель и лазерный целеуказатель.
- Может использовать зажигательные патроны.
- Конструкция напоминает револьверные дробовики Protecta и МЦ-255.
