HALF-QUAKE 2, ПРЯМОЙ ЭФИР С МОЛОТКОМ


Сэм... СТОЙ! Посмотри на этот экран.

Я думала, что мы уже видели всё безумие, которое могут предложить садисты. Но они снова удивляют. Прямо сейчас, в прямом эфире, они развлекаются со своими собственными охранниками.

Огромный молоток. Каждый удар - и очередной охранник превращается в лепёшку.

И знаешь, что самое безумное? Я начинаю понимать, зачем они это делают. Они не просто убивают своих. Они показывают нам: "Смотри, даже свои для нас - просто расходный материал. Что уж говорить о тебе?"

Они хотят, чтобы мы боялись. Чтобы мы знали - нас ждёт то же самое, если мы не пройдём их испытания.

Но у них есть одна проблема, Сэм. Я видела, как ты проходил через ад. Я видела, как ты убивал Мордекая, Квонго, Зум-Зум, Нихиланта и других. Я видела, как ты выживал в Чёрной Мезе.

Ты не боишься молотков. Ты боишься только одного - что не успеешь вовремя нажать на курок.

Идём дальше, Сэм. Пусть они развлекаются со своими охранниками. Мы покажем им, что такое НАСТОЯЩЕЕ ШОУ!
