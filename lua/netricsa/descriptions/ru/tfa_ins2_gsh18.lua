САМОЗАРЯДНЫЙ ПИСТОЛЕТ ГШ-18


ОРУЖИЕ:  Самозарядный Пистолет ГШ-18
ПАТРОНЫ: 9x19 мм Parabellum, 7Н21, 7Н31
СС:      ~15-20 Выстрелов / Мин

ОПИСАНИЕ:

Российский самозарядный пистолет, разработанный в конце 1990-х годов в Тульском конструкторском бюро приборостроения конструкторами Василием Грязевым и Аркадием Шипуновым. Предназначен для использования в качестве личного оружия военнослужащих и сотрудников силовых структур. Название образовано от первых букв фамилий разработчиков, а число 18 обозначает вместимость магазина. Отличается небольшой массой, полимерной рамкой и высокой вместимостью магазина.

Работает по принципу использования отдачи при коротком ходе ствола с его поворотным запиранием. Использует пистолетные патроны 9x19 мм, включая специальные бронебойные 7Н21 и 7Н31. Питание осуществляется из двухрядного коробчатого магазина на 18 патронов. Оснащён ударниковым ударно-спусковым механизмом и автоматическим предохранителем на спусковом крючке. Прицельные приспособления открытого типа.

ПРИМЕЧАНИЯ:

- Эффективен против одиночных целей на коротких дистанциях, в том числе защищённых бронежилетами при использовании соответствующих боеприпасов.
- Название происходит от фамилий Грязева и Шипунова, а также вместимости магазина.
- Принят на вооружение в начале 2000-х годов.
- Магазин вмещает 18 патронов.
- Отличается малой массой, около 500 г без магазина.
- Специальный патрон 7Н31 обладает повышенной пробивной способностью.
