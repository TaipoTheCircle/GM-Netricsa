ПУЛЕМЁТ БРАУНИНГ M1919


ОРУЖИЕ:  Пулемёт Браунинг M1919
ПАТРОНЫ: .30-06 Springfield (7,62x63 мм)
СС:      ~4000600 выстрелов / мин.
ВЕС:     ~14 кг.

ОПИСАНИЕ:

Browning M1919, американский станковый пулемёт с воздушным охлаждением ствола, разработанный на основе пулемёта Browning M1917. На вооружение он был принят после Первой мировой войны и широко использовался американскими войсками во Второй мировой, Корейской и Вьетнамской войнах.

M1919 использует автоматику с коротким ходом ствола и рычажным запиранием. В американском варианте M1919A4 применялся патрон .30-06 Springfield, а питание осуществлялось из матерчатой ленты на 250 патронов. В отличие от M1917, водяного охлаждения здесь нет, поэтому ствол охлаждается воздухом.

Пулемёт выпускался в нескольких вариантах, включая более лёгкий M1919A6, который получил приклад и сошки и мог использоваться как ручной пулемёт. При этом базовый M1919A4 со станком весил ещё больше, поэтому это оружие было прежде всего средством огневой поддержки.

ПРИМЕЧАНИЯ:

- Длинная лента на 250 патронов позволяет вести продолжительный огонь без постоянной смены боеприпасов.
- Хорошо подходит для подавления целей на средней и дальней дистанции.
- В отличие от M1917, M1919 получил воздушное охлаждение, что сделало конструкцию более удобной для различных вариантов установки.
