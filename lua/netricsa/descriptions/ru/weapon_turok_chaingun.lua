МИНИГАН "ORO БОЕВОЙ КОНЬ"


ОРУЖИЕ:  Миниган "ORO Боевой Конь"
ПАТРОНЫ: Крупнокалиберные патроны
СС:      ~950 выстр. / мин
ВЕС:     ~18 кг.

ОПИСАНИЕ:

Тяжёлый многоствольный пулемёт, разработанный компанией ORO и используемый подразделениями тяжёлого вооружения. Оружие выпускает непрерывный поток крупнокалиберных пуль и обладает высокой мощностью, однако отличается заметным разбросом.

Перед открытием огня стволы необходимо раскрутить в течение нескольких секунд. Их можно раскрутить заранее, чтобы практически мгновенно открыть огонь при появлении цели. Большой магазин позволяет долго вести непрерывный огонь, не отвлекаясь на перезарядку.

Альтернативный режим превращает Боевого Коня в автономную наземную турель. После установки она самостоятельно ведёт огонь по противникам и обеспечивает прикрытие без постоянного управления стрелком.

ПРИМЕЧАНИЯ:

- Очень высокая скорострельность и плотность огня.
- Перед стрельбой стволы необходимо раскрутить.
- Эффективен на средней и дальней дистанции, несмотря на заметный разброс.
- Магазин вмещает 250 патронов, общий боезапас может достигать 1000 патронов.
- Второй режим превращает оружие в автономную пулемётную турель.
- Большой вес снижает мобильность пользователя.
- Особенно опасен против групп противников: непрерывный поток крупнокалиберных пуль быстро подавляет целую позицию.
