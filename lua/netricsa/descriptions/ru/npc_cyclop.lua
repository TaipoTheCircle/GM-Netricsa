ЦИКЛОП ПОЛИФЕМ


КЛАСС:        Циклоп-Полифем
МЕТАБОЛИЗМ:   Великан, Мужчина
ВОСПРИЯТИЕ:   Дикое Людоедское Существо
РАЗМЕР:       ~4,5 м.
ВЫНОСЛИВОСТЬ: Очень Высокая
ВРАЖДЕБНОСТЬ: Чрезвычайная
ОРУЖИЕ:       Кулаки, Хватка, Зубы
НАГРАДА:      1500
УГРОЗА:       Очень Высокая

ОПИСАНИЕ:

Огромный жестокий одноглазый циклоп и крайне опасный людоед, который захватывал людей и пожирал их. Это массивное существо обладает чудовищной физической силой и способно без особых усилий расправляться с обычными противниками в ближнем бою.

Полифем практически не различает понятия "враг" и "добыча". Любое живое существо, оказавшееся поблизости, может привлечь его внимание. Он способен схватить противника и попытаться съесть его прямо на месте, поэтому приближаться к циклопу крайне опасно.

Его единственный глаз обеспечивает хорошее зрение, однако основным преимуществом Полифема остаются размеры и физическая мощь.

Получив серьёзные повреждения, он может внезапно со всех ног броситься на противника, громко ревя и пытаясь сократить расстояние как можно быстрее.

Особенно опасен Полифем в тесных помещениях. Огромные размеры могут мешать ему маневрировать, но одновременно сильно ограничивают возможности противника уклониться. В замкнутом пространстве встреча с ним быстро превращается из боя в очень плохой ужин.

СОВЕТЫ:

- Не вступай с ним в ближний бой. Это практически гарантированный билет в меню.
- Используй дальнобойное оружие и постоянно сохраняй дистанцию.
- Тяжело раненный Полифем может начать бегать.
- Используй препятствия и узкие проходы, чтобы не дать ему быстро добраться до цели.
- Если Полифем начал орать, убегай как можно дальше.
