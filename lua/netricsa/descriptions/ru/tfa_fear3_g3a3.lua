ШТУРМОВАЯ ВИНТОВКА RAKOW G3A3


ОРУЖИЕ:     Штурмовая винтовка Rakow G3A3
ПАТРОНЫ:    7,62×51 мм НАТО
СС:         3-выстрельные очереди

ОПИСАНИЕ:

Современная штурмовая винтовка, используемая солдатами корпорации Armacham. Оснащена оптическим прицелом с небольшим увеличением, обеспечивающим высокую точность при стрельбе на средних и дальних дистанциях.

В отличие от большинства автоматических винтовок, G3A3 ведёт огонь исключительно очередями по три патрона. Магазин вмещает 24 патрона, чего хватает на восемь очередей. Благодаря высокой точности и мощности оружие эффективно против бронированных противников, однако небольшой магазин и не самая удобная стрельба от бедра ограничивают его возможности в ближнем бою.

ПРИМЕЧАНИЯ:

- Не путать с немецкой винтовкой Heckler & Koch G3A3.
- На корпусе имеется маркировка калибра 7,62 мм, но точный тип патрона официально не подтверждён.
- Три выстрела за одно нажатие. Для экономии боеприпасов самое то.
- При хорошей меткости способна заменить снайперскую винтовку на средней дистанции.
