ВИСКИ


ОРУЖИЕ:  Виски
ПАТРОНЫ: Одна Рюмка

ОПИСАНИЕ:

Алкогольный напиток со льдом, обладающий выраженным опьяняющим эффектом. При употреблении постепенно затуманивает зрение пользователя, затрудняя восприятие окружающей обстановки.

Эффект со временем проходит, однако чрезмерное употребление без перерывов может привести к летальному исходу. В отличие от большинства предметов снаряжения, этот напиток способен представлять непосредственную угрозу собственному владельцу.

ПРИМЕЧАНИЯ:

- Подаётся со льдом.
- При употреблении временно затуманивает зрение.
- Эффект проходит спустя некоторое время.
- Непрерывное употребление может привести к смерти пользователя.
