ИМПУЛЬСНАЯ ВИНТОВКА ORO L66


ОРУЖИЕ:  Импульсная Винтовка ORO L66
ПАТРОНЫ: Бронебойные Пули Из Обеднённого Урана
СС:      ~600 выстрелов / мин.
ВЕС:     ~4,5 кг.

ОПИСАНИЕ:

Точная автоматическая импульсная винтовка производства ORO, использующая бронебойные пули из обеднённого урана. Оружие отличается высокой точностью, низкой отдачей и большим магазином на 100 патронов, что позволяет вести продолжительный огонь. Основным недостатком является быстрый перегрев при непрерывной стрельбе.

Под стволом установлен гранатомёт для специальных импульсных гранат. Они не столько предназначены для уничтожения цели, сколько создают мощную ударную волну, сбивая противников с ног и выбрасывая их из-за укрытий. Гранаты можно выпускать как по одной, так и короткой очередью из трёх.

ПРИМЕЧАНИЯ:

- Магазин рассчитан на 100 патронов, общий боезапас может достигать 400.
- Высокая точность и низкая отдача.
- Использует бронебойные боеприпасы из обеднённого урана.
- Быстро перегревается при непрерывной стрельбе, поэтому рекомендуется вести огонь короткими очередями.
- Альтернативный огонь запускает дезориентирующие гранаты.
- Гранаты сбивают противников с ног и выбивают их из укрытий.
- Эффективен на средней и дальней дистанции благодаря точности и возможности использовать увеличение прицела.
- Особенно распространён среди элитных бойцов Корпорации Мендель-Груман.
