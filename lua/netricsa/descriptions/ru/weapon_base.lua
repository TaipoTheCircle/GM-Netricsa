СКРИПТОВОЕ ОРУЖИЕ


ОРУЖИЕ:  Скриптовое Оружие
ПАТРОНЫ: Универсальные Патроны
СС:      ~60 выстрелов / мин.
ВЕС:     ~1,1 кг.

ОПИСАНИЕ:

Чрезвычайно мощный пистолет неизвестного происхождения. Внешне обычно напоминает стандартный 9-мм пистолет, однако иногда принимает форму револьвера .357 Магнум. Несмотря на компактные размеры, обычный выстрел способен мгновенно уничтожить цель.

Оружие обладает двумя режимами огня. Первый выпускает одиночные мощные выстрелы, каждый из которых использует один патрон. Второй режим превращает оружие в подобие дробовика и выпускает сразу 8 дробовых выстрелов.

Особенностью системы является нестандартная перезарядка. Если все восемь зарядов дробового режима были использованы, оружие можно перезарядить, потратив 8 патронов. Однако перезарядка не является обязательной. Если этого не делать, обычный режим продолжает использовать оставшиеся патроны без дополнительного расхода на восстановление дробового режима.

Например, если осталось 8 патронов, пользователь может полностью использовать их для дробового режима, после чего продолжить расходовать обычные патроны без автоматического списания ещё восьми. Это позволяет экономить боезапас при грамотном переключении режимов.

ПРИМЕЧАНИЯ:

- Обычный огонь способен уничтожить большинство целей одним попаданием.
- Альтернативный огонь выпускает 8 дробовых зарядов.
- Перезарядка дробового режима требует 8 патронов.
- Перезарядка не происходит автоматически, поэтому боезапас можно экономить.
- Обычный режим эффективен на средней и дальней дистанции.
- Дробовой режим наиболее эффективен на ближней дистанции.
- Если дробовой режим не перезаряжать, оружие не забирает дополнительные 8 патронов.
- При полном расходовании дробового заряда необходимо учитывать оставшийся боезапас перед перезарядкой.
- Внешний вид может отличаться: 9-мм пистолет или револьвер .357 Магнум.
