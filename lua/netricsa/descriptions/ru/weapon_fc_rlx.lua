ПУСКОВАЯ УСТАНОВКА СВЕТОВЫХ ГРАНАТОМЕТОВ RLX-9157 М202А1


ОРУЖИЕ:  Пусковая Установка Световых Гранатомётов RLX-9157 М202А1
ПАТРОНЫ: 66-мм ракеты M74
СС:      ~30 выстр. / мин
ВЕС:     ~12 кг.

ОПИСАНИЕ:

Тяжёлая многозарядная ракетная установка, предназначенная для поражения противников и уничтожения целей взрывом. Представляет собой переносную систему с несколькими направляющими, позволяющую выпускать ракеты одну за другой без немедленной перезарядки после каждого выстрела.

Ракеты обладают высокой разрушительной силой и особенно эффективны против групп противников, укреплений и крупных целей. Большой боезапас установки позволяет быстро произвести несколько пусков подряд, превращая её в крайне опасное оружие поддержки.

Несмотря на внушительные размеры, M202A1 остаётся переносным оружием и может использоваться одним бойцом.

ПРИМЕЧАНИЯ:

- Многозарядная ракетная установка.
- Ракеты наносят значительный взрывной урон.
- Эффективна против групп целей и тяжёлых противников.
- Наиболее эффективна на средней и дальней дистанции.
- Взрыв опасен для самого пользователя при стрельбе слишком близко к препятствию или цели.
