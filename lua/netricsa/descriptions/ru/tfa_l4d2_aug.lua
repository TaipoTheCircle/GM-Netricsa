ШТУРМОВАЯ ВИНТОВКА STEYR AUG


ОРУЖИЕ:  Штурмовая Винтовка Steyr AUG
ПАТРОНЫ: 5,56x45 мм НАТО
СС:      ~680-750 выстрелов / мин

ОПИСАНИЕ:

Австрийская штурмовая винтовка с компоновкой буллпап, разработанная в 1977 году и принятая на вооружение в 1978-м. Магазин расположен за спусковым крючком, благодаря чему AUG получилась компактной при сохранении полноценной длины ствола.

Оружие отличается модульной конструкцией, пластиковым корпусом и характерным встроенным оптическим прицелом у ранних вариантов. Используются магазины на 30 или 42 патрона, а различные версии получили укороченные стволы, тяжёлые стволы и другие варианты оснащения.

ПРИМЕЧАНИЯ:

- Буллпап делает винтовку заметно короче обычной при сопоставимой длине ствола.
- Один из самых узнаваемых силуэтов среди штурмовых винтовок.
- Выглядит так, будто её проектировали сразу с прицелом на будущее.
- Разбирается и собирается довольно необычно благодаря модульной конструкции.
