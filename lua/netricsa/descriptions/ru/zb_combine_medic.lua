ОРУЖИЕ:       SMG1 (MP7), Гранаты
НАГРАДА:      500
УГРОЗА:       Высокая

ОПИСАНИЕ:

Это Солдаты "Подразделения По Управлению Кризисными Ситуациями Overwatch", они являются специализированным подразделением Альянса, созданным для реагирования на особо опасные кризисные ситуации, где обычных солдат Overwatch оказывается недостаточно. В их задачи входит подавление крупных очагов сопротивления, зачистка заражённых или нестабильных районов, а также оказание помощи другим подразделениям Альянса непосредственно на передовой.

В отличие от стандартных солдат Overwatch, бойцы OCMU совмещают функции штурмовой пехоты и боевых медиков. Их экипировка предназначена для длительного пребывания в зоне боевых действий, а подготовка позволяет быстро менять роль в зависимости от ситуации: вести огонь по противнику, прикрывать отступление союзников или оказывать медицинскую помощь повреждённым бойцам.

OCMU принципиально используют ограниченный набор вооружения. Основным оружием служит SMG1 (MP7), позволяющий вести плотный автоматический огонь на коротких и средних дистанциях. Для зачистки помещений, разрушения укрытий и поражения групп противника они активно используют гранаты.

Несмотря на медицинскую специализацию, считать бойцов OCMU безобидными крайне опасно. Они хорошо обучены ближнему бою и действуют организованно, стараясь держаться группой. Если один из бойцов оказывается под огнём, остальные немедленно пытаются подавить стрелка гранатами и автоматическим огнём, одновременно прикрывая раненого.

OCMU особенно часто появляются там, где ситуация выходит из-под контроля. Их прибытие обычно означает, что Альянс больше не пытается просто удерживать территорию, а переходит к полноценному кризисному подавлению.

СОВЕТЫ:

- Не позволяй OCMU закрепиться в помещении: гранаты делают их особенно опасными в тесных пространствах.
- На открытой местности SMG1 менее эффективен, поэтому используй дистанцию.
- Старайся быстро выводить из строя несколько бойцов, чтобы они не могли прикрывать друг друга.
- Если OCMU сопровождают другие подразделения Альянса, сначала устрани наиболее опасных стрелков и тяжёлую поддержку.
- Не недооценивай их из-за медицинской специализации: это всё ещё полноценные боевые единицы Overwatch.
