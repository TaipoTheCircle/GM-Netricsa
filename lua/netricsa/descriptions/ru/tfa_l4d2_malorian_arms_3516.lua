ПИСТОЛЕТ МАЛОРИАН АРМС 3516


ОРУЖИЕ:  Пистолет Малориан Армс 3516
ПАТРОНЫ: Специальные крупнокалиберные боеприпасы
СС:      ~200 выстрелов / мин.
ВЕС:      ~4,3 кг.

ОПИСАНИЕ:

Культовый тяжёлый пистолет, изготовленный компанией Малориан Армс специально для рокербоя Джонни Сильверхенда. Это уникальный пистолет, рассчитанный на крайне мощный огонь и созданный как индивидуальное оружие Джонни.

Версия 3516 является полуавтоматическим пистолетом с магазином на 10 патронов. Оружие относится к классу Power и способно использовать рикошеты. Его особенность заключается в возможности пробивать укрытия, а специальная атака позволяет превратить выстрел в настоящий огненный сюрприз для противника.

Малориан Армс 3516 отличается огромными для пистолета размерами и массой около 4,3 кг. В предыдущих версиях оружие было ещё более экстремальным: существовала 14-мм версия, а позднейшая история 3516 связана с боеприпасом уровня .577 Nitro Express.

ПРИМЕЧАНИЯ:

- Может превращать рукопашную атаку в огненную атаку, расходуя оставшиеся патроны.
- Способен использовать рикошеты и пробивать препятствия.
- Создан для Джонни Сильверхенда, поэтому обычным пистолетом его назвать довольно трудно.
