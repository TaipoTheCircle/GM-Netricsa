МАССИВНАЯ ВИНТОВКА BFG 9000


ОРУЖИЕ:  Массивная Винтовка BFG 9000
ПАТРОНЫ: BFG Клетки
СС:      ~24 выстрела / мин.

ОПИСАНИЕ:

Футуристическое энергетическое оружие, разработанное корпорацией UAC. Это самое мощное оружие, стреляющее огромным зелёным энергетическим сгустком. Снаряд способен поражать не только цель при попадании, но и окружающих противников энергетическими лучами во время полёта.

Оружие можно заряжать, удерживая кнопку стрельбы. Чем дольше заряд, тем мощнее выстрел, однако слишком долгое удержание приводит к перегрузке и может убить самого стрелка.

BFG особенно эффективна против сильных противников и больших групп врагов. Боеприпасы встречаются редко, поэтому использовать её против каждого встречного зомби было бы примерно как колоть масло бензопилой.

ПРИМЕЧАНИЯ:

- Один из самых мощных образцов оружия.
- Энергетический сгусток наносит урон врагам ещё до взрыва.
- Боеприпасы встречаются редко, поэтому каждый заряд лучше беречь для серьёзных противников.
