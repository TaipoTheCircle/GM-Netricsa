БЕНЗОПИЛА


ОРУЖИЕ:  Бензопила
ПАТРОНЫ: Бензин

ОПИСАНИЕ:

Мощный ручной инструмент с вращающейся зубчатой цепью, предназначенный для поражения целей на крайне близкой дистанции. При работе цепь непрерывно вращается, позволяя наносить быстрые последовательные удары без необходимости перезарядки.

Бензопила особенно эффективна против противников, находящихся вплотную, однако требует постоянного расхода топлива. Главным недостатком является необходимость подойти к цели на опасно близкое расстояние.

ПРИМЕЧАНИЯ:

- Не требует патронов, но постоянно расходует топливо.
- Очень высокая эффективность на крайне близкой дистанции.
- При работе издаёт громкий характерный звук.
- Ныне бензин стал ценнее.
