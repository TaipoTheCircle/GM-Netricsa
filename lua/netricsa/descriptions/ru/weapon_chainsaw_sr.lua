БЕНЗИНОВАЯ ЦЕПНАЯ ПИЛА STIHL 041 AV


ОРУЖИЕ:  Бензиновая Цепная Пила STIHL 041 AV
ПАТРОНЫ: Бензин И Масло Для Двухтактных Двигателей
СС:      Непрерывная Работа

ОПИСАНИЕ:

Бензиновая цепная пила, разработанная немецкой компанией Andreas Stihl Maschinenfabrik. Выпускалась с 1967 по 1986 год и предназначалась для валки деревьев, распиловки древесины и выполнения тяжёлых лесозаготовительных работ. Оснащена одноцилиндровым двухтактным двигателем объёмом 61 см³ и системой антивибрационной подвески рукояток, повышающей удобство эксплуатации.

Двигатель развивает мощность около 5,5 л. с. и приводит в движение режущую цепь через центробежную муфту сцепления. Смазка цепи осуществляется автоматически. Пила оснащена механическим цепным тормозом, системой автоматического запуска стартера и направляющей шиной длиной от 33 до 63 см. Работает на топливной смеси бензина и специального масла для двухтактных двигателей.

ПРИМЕЧАНИЯ:

- Особенно эффективна против древесины и других мягких материалов.
- Пригодна для распиловки крупных деревянных объектов.
- Может использоваться против незащищённых противников, включая зомби на очень близкой дистанции, однако требует непосредственного контакта.
- Выпускалась с 1967 по 1986 год.
- Объём двигателя составляет 61 см³.
- Мощность двигателя около 5,5 л. с.
- Масса около 7,26 кг. с шиной и цепью длиной 33 см.
