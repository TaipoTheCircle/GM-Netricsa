ПОЛУАВТОМАТИЧЕСКИЙ ДРОБОВИК VOLLMER ULTRA92


ОРУЖИЕ:     Полуавтоматический Дробовик Vollmer Ultra92
ПАТРОНЫ:    12-й калибр
СС:         Полуавтоматический

ОПИСАНИЕ:

Современное самозарядное гладкоствольное ружьё, используемое тяжёлыми подразделениями Replica. Разработано корпорацией Vollmer и предназначено для интенсивных боевых столкновений на коротких и средних дистанциях. Использует газоотводную автоматику и съёмный коробчатый магазин на 12 патронов.

Ultra92 уступает дробовику SHO Series-3 по мощности отдельного выстрела, однако компенсирует это более высокой скорострельностью, плотной группировкой дроби и быстрой перезарядкой. В отличие от обычных помповых ружей, магазин заменяется целиком, позволяя быстро вернуться в бой.

ПРИМЕЧАНИЯ:

- Используется тяжёлыми солдатами Replica.
- Магазин вмещает 12 патронов, в многопользовательском режиме 10.
- Основан на сочетании конструктивных черт Heckler & Koch CAWS и Franchi SPAS-12.
- Несмотря на название, полностью автоматического режима стрельбы не имеет.
- Перезарядка сразу всего магазина, а не по одному патрону. Удобство, которое оценит каждый солдат.
