РУЧНОЙ ПУЛЕМЁТ FM 24/29


ОРУЖИЕ:  Ручной Пулемёт FM 24/29
ПАТРОНЫ: 7,5x54 мм French
СС:      ~450 Выстрелов / Мин, Автоматический Огонь

ОПИСАНИЕ:

Французский ручной пулемёт, разработанный подполковником Рейбелем при участии главного оружейного мастера Шосса. Создан в начале 1920-х годов на предприятии Manufacture d'armes de Châtellerault и принят на вооружение французской армии в 1925 году. Предназначался для обеспечения пехотных отделений мобильной огневой поддержкой. Отличается характерной компоновкой с верхним расположением коробчатого магазина, деревянным прикладом и сошками.

Автоматика работает за счёт отвода пороховых газов, стрельба ведётся с открытого затвора. Использует патроны 7,5x54 мм French и съёмный коробчатый магазин на 25 патронов. Оружие оснащено пистолетной рукоятью, складными сошками и открытыми механическими прицельными приспособлениями. Умеренный темп стрельбы позволяет вести контролируемый огонь очередями, обеспечивая поддержку подразделения на поле боя.

ПРИМЕЧАНИЯ:

- Принят на вооружение в 1925 году, оставался в службе французской армии до 1960-х годов.
- Хорошо подходит для подавления групп пехоты и прикрытия продвижения союзников.
- Эффективен против незащищённых целей на средних и дальних дистанциях.
- Может поражать лёгкие укрытия, но не предназначен для пробития тяжёлой брони.
- Начальная скорость пули достигает примерно 830 м/с.
- Существовала танковая модификация MAC 1931 с боковым дисковым магазином на 150 патронов.
