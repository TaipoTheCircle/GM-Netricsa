ОПИСАНИЕ:

Пакет с метамфетамином характерного голубого цвета, известным под названием Голубое Небо. При употреблении вызывает выраженное стимулирующее воздействие на организм пользователя, значительно увеличивая скорость передвижения. При этом восприятие окружающего мира практически полностью нарушается, делая ориентацию в пространстве крайне затруднительной.

Продолжительное употребление может привести к летальному исходу. Сочетание с виски ещё сильнее усугубляет последствия и делает подобный эксперимент особенно опасным.

