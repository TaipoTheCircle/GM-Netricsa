САПЁРНАЯ ЛОПАТА FELDSPATEN 1887 (M87)


ОРУЖИЕ:  Сапёрная Лопата Feldspaten 1887 (M87)
ПАТРОНЫ: Отсутствуют
СС:      Ручное Оружие

ОПИСАНИЕ:

Немецкая пехотная сапёрная лопата, принятая на вооружение Германской императорской армии в 1887 году. Представляла собой усовершенствованный вариант полевой лопаты M1874. Основным изменением стала новая система ношения: согласно распоряжению от 3 марта 1887 года лопатку стали крепить к поясному ремню за чехлом штыка. Использовалась пехотой для оборудования укреплений, рытья окопов и индивидуальных стрелковых позиций.

Оснащена стальным слегка изогнутым полотном и короткой деревянной рукоятью. Общая длина составляет около 54 см, ширина полотна около 15-16 см. Лопатка носилась в специальном чехле, закреплённом на солдатском снаряжении. Во время Первой мировой войны её нередко затачивали по краям, превращая обычный инструмент в эффективное оружие ближнего боя.

ПРИМЕЧАНИЯ:

- Эффективна в ближнем бою, особенно в тесных окопах и траншеях.
- Использовалась для рытья стрелковых ячеек и полевых укреплений.
- В отличие от модели M1898, не имела усиленной наступной кромки.
- Общая длина составляет около 54 см.
- Применялась германской армией во время Первой мировой войны.
