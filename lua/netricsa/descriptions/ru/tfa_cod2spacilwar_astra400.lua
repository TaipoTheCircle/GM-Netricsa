ПИСТОЛЕТ ASTRA 400


ОРУЖИЕ:  Пистолет ASTRA 400
ПАТРОНЫ: 9x23 мм Largo
СС:      ~30-40 выстрелов / мин.
ВЕС:     ~1,14 кг.

ОПИСАНИЕ:

Испанский самозарядный пистолет, разработанный компанией Astra-Unceta y Cia и принятый на вооружение испанской армии в 1921 году. Он создавался как замена более старому Campo-Giro и получил широкое применение во время Гражданской войны в Испании.

Пистолет использует автоматику со свободным затвором, что довольно необычно для оружия под мощный патрон 9x23 мм Largo. Несмотря на такую конструкцию, Astra 400 отличалась хорошей надёжностью, точностью и сравнительно небольшой отдачей.

Интересной особенностью конструкции является способность Astra 400 использовать не только штатный 9x23 мм Largo, но и некоторые другие 9-мм боеприпасы, включая 9x19 мм Parabellum и 9x22 мм Browning Long.

ПРИМЕЧАНИЯ:

- Хорошо подходит для ближнего боя и достаточно точен для своего класса.
- Свободный затвор под настолько мощный патрон делает Astra 400 довольно необычным представителем самозарядных пистолетов.
- Пистолет оставался на вооружении Испании несколько десятилетий, а во время Второй мировой войны поставлялся и Германии под обозначением Pistole 642(f).
