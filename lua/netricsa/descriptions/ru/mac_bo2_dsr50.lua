КРУПНОКАЛИБЕРНАЯ СНАЙПЕРСКАЯ ВИНТОВКА DSR-50


ОРУЖИЕ:     Крупнокалиберная снайперская винтовка DSR-50
ПАТРОНЫ:    12,7x99 мм НАТО (.50 BMG)
СС:         ~10-15 выстрелов / мин

ОПИСАНИЕ:

Немецкая крупнокалиберная снайперская винтовка, разработанная компанией DSR-Precision GmbH под руководством Ингольфа Рейтера в 2003 году. Представляет собой увеличенную версию DSR-1, приспособленную для использования мощного патрона .50 BMG. Компоновка буллпап позволяет сохранить сравнительно небольшую общую длину оружия при использовании длинного 800-мм ствола.

Винтовка оснащена гидравлическим амортизатором отдачи в прикладе и специальным дульным устройством Blast Compensator, сочетающим функции дульного тормоза и глушителя. Также предусмотрены регулируемый приклад, сошка, дополнительная опора под прикладом и крепления для оптических прицелов. Питание осуществляется из съёмного магазина на 3 патрона.

ПРИМЕЧАНИЯ:

- Использует мощный крупнокалиберный патрон .50 BMG.
- Дульное устройство помогает уменьшить отдачу и дульную вспышку.
- Несмотря на компоновку буллпап, весит около 10,3 кг без патронов.
- Длинный ствол позволяет получить высокую точность на больших дистанциях.
- Три патрона в магазине. Каждый выстрел буквально требует уважения.
