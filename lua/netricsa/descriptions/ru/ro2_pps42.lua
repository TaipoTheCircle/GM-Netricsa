ПИСТОЛЕТ-ПУЛЕМЁТ СУДАЕВА ППС-42


ОРУЖИЕ:  Пистолет-Пулемёт Судаева ППС-42
ПАТРОНЫ: 7,62x25 мм ТТ
СС:      ~600-700 выстрелов / мин.
ВЕС:     ~3,63 кг.

ОПИСАНИЕ:

ППС-42, пистолет-пулемёт системы Судаева образца 1942 года, советское оружие, разработанное во время Великой Отечественной войны. Он создавался как более лёгкая, компактная и дешёвая в производстве альтернатива ППШ-41, особенно подходящая для боёв в окопах, тесных помещениях, а также для разведчиков, десантников и экипажей боевых машин.

ППС-42 использует автоматику со свободным затвором и ведёт только автоматический огонь. Благодаря относительно длинному ходу подвижных частей темп стрельбы получился ниже, чем у многих других пистолетов-пулемётов, что делает оружие более управляемым при стрельбе очередями.

Питание осуществляется из коробчатого магазина на 35 патронов. Оружие имеет складной металлический приклад, а большая часть конструкции изготовлена из штампованной стали с использованием сварки и клёпки. Именно простота производства стала одной из главных особенностей ППС.

ППС-42 стал первой серийной версией конструкции Судаева. Уже в 1943 году его сменил улучшенный ППС-43 с укороченным стволом и рядом конструктивных изменений.

ПРИМЕЧАНИЯ:

- Особенно эффективен на ближней и средней дистанции, где короткие очереди позволяют достаточно точно удерживать огонь.
- Конструкция рассчитана на массовое военное производство: много штампованных деталей, минимум сложной обработки.
- Складной приклад делает ППС-42 удобнее для разведчиков, десантников и экипажей техники.
- ППШ был слишком большим? Судаев просто сделал его компактнее, легче и технологичнее.
