РУЧНОЙ ПУЛЕМЁТ MADSEN


ОРУЖИЕ:     Ручной пулемёт Madsen
ПАТРОНЫ:    6,5x55 мм / 7,92x57 мм / 7,62x54 мм R
СС:         ~450 выстрелов / мин

ОПИСАНИЕ:

Датский ручной пулемёт, разработанный в 1890 году и запущенный в серийное производство в 1900-м. Считается первым ручным пулемётом, массово выпускавшимся промышленностью. Благодаря сравнительно небольшому весу и возможности переноски одним солдатом он стал важным этапом в развитии автоматического оружия.

Мадсен использует автоматику с коротким ходом ствола и отличается весьма необычной конструкцией затворного механизма. Питание осуществляется из коробчатого магазина, расположенного сверху ствольной коробки. В зависимости от модификации применялись магазины на 25, 30 или 40 патронов. Пулемёт выпускался под различные винтовочные боеприпасы и экспортировался во множество стран.

ПРИМЕЧАНИЯ:

- Один из пионеров ручных пулемётов, появившийся ещё до Первой мировой войны.
- Состоял на вооружении армий примерно 30 стран.
- Верхнее расположение магазина придаёт ему весьма необычный силуэт.
- Производство продолжалось до начала 1950-x годов. Настоящий ветеран автоматического оружия.
