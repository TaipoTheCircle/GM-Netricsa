ПИСТОЛЕТ-ПУЛЕМЁТ MAT-49


ОРУЖИЕ:  Пистолет-Пулемёт MAT-49
ПАТРОНЫ: 9x19 мм Parabellum
СС:      ~600 Выстрелов / Мин

ОПИСАНИЕ:

Французский пистолет-пулемёт, разработанный инженерами Пьера Монтейля и Деламера на предприятии Manufacture Nationale d'Armes de Tulle (MAT) в конце 1940-x годов. Принят на вооружение французской армии в 1949 году и предназначался для замены устаревших образцов оружия, использовавшихся после Второй мировой войны. Отличается простой штампованной конструкцией, высокой надёжностью и складным металлическим прикладом. Широко применялся французской армией, Иностранным легионом и воздушно-десантными подразделениями.

Работает по принципу отдачи свободного затвора и ведёт огонь с открытого затвора. Использует патроны 9x19 мм Parabellum и коробчатые магазины на 20 или 32 патрона. Главной особенностью конструкции является складывающаяся вперёд шахта магазина, позволяющая сделать оружие значительно компактнее при транспортировке. В сложенном положении магазин располагается параллельно стволу. Оснащён выдвижным металлическим прикладом, открытыми прицельными приспособлениями и предохранителем на задней стороне пистолетной рукояти.

ПРИМЕЧАНИЯ:

- Принят на вооружение французской армии в 1949 году.
- Выпущено более 700 000 экземпляров.
- Магазины рассчитаны на 20 или 32 патрона.
- Эффективная дальность стрельбы составляет около 100 метров.
- Масса без магазина составляет примерно 3,5 кг.
- Существовала полицейская модификация MAT-49/54 с удлинённым стволом и деревянным прикладом.
- Во время войны во Вьетнаме северо-вьетнамские подразделения переделывали захваченные MAT-49 под патрон 7,62x25 мм ТТ.
