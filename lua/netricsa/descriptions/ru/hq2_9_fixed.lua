HALF-QUAKE 2, ПОГОНЯ ОТ РУКИ


Сэм... Беги. Просто беги. Не останавливайся. Не смотри назад. Но если хочешь знать, что преследует нас... это огромная панель с изображением руки. Она сожмёт всё на своём пути. И нас заодно.

Да, садисты включили грустную музыку. Очевидно, они хотят, чтобы мы запомнили этот момент.

Впереди ящики. Толкай их. Быстро. В некоторых дырки - не попади в них, застрянешь. В некоторых местах пола просто нет. И, конечно, в конце тебя ждут два серых вортигонта, чтобы поприветствовать.

У нас есть время, пока рука не начала сжиматься. Только не думай о том, что произойдёт, когда она догонит. Беги, Сэм. Беги быстрее, чем когда-либо. Это не шутка.

Я засекла таймер. У нас около минуты. Может, меньше. Не останавливайся. Даже если музыка говорит тебе, что ты проиграл. Ты не проиграешь. Я знаю.

А теперь - ВПЕРЁД!
