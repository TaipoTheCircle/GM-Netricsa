HALF-QUAKE 2, ПАРКУР БЕЗУМИЯ


Ну, Сэм, мы на месте! Очередной "подарок" от садистов. Паркур. Просто прыгай по кубам и доберись до панели с этой дурацкой рожей ">)". Звучит просто, да? Конечно, нет!

Мои сенсоры показывают, что эти кубы - не просто кубы. Они явно имеют какой-то подвох. Может быть, они исчезают, когда ты на них наступаешь. Может быть, они взрываются. А может быть, они просто хотят, чтобы ты упал и разбился.

Знаешь, я не удивлюсь, если они просто обидятся на тебя за то, что ты на них наступил. Садисты любят добавлять характер даже в свои платформы.

В общем, Сэм, пришло время показать этим кубам, кто здесь король паркура! Доберись до панели ">)" на полу. Она активирует наш путь дальше.

И помни: не доверяй кубам! Они явно заодно с садистами. И они хотят, чтобы ты упал. Но ты же Сэм! Ты падал и не в такие... безумные места!

Давай, прыгай! И не смотри вниз, там ничего хорошего! Я уже вижу, что после этой панели нас ждёт что-то новое... и я уверена, что это будет весело!
