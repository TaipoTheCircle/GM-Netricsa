ПИСТОЛЕТ-ПУЛЕМЁТ KRISS K10


ОРУЖИЕ:     Пистолет-пулемёт KRISS K10
ПАТРОНЫ:    .45 ACP / 9×19 мм / .40 S&W
СС:         ~1200 выстрелов / мин

ОПИСАНИЕ:

Американский экспериментальный пистолет-пулемёт, разработанный компанией KRISS USA в качестве усовершенствованной версии KRISS Vector. Впервые представлен в 2011 году. Оружие использует фирменную систему Super V с замедленным затвором, направляющую его движение вниз и помогающую уменьшить отдачу и подброс ствола.

K10 получил телескопический приклад, изменённую рукоятку взведения, двусторонние органы управления и четыре планки Пикатинни. Модульная конструкция позволяет менять калибр между .45 ACP, 9x19 мм и .40 S&W. Предусматривались магазины на 13 или 25 патронов, а также возможность использования удлинённых магазинов.

ПРИМЕЧАНИЯ:

- Представляет собой второе поколение семейства KRISS Vector.
- Рукоятку взведения можно переставлять на левую или правую сторону.
- Система Super V помогает уменьшить подброс ствола при стрельбе.
- Несмотря на перспективную конструкцию, K10 так и остался экспериментальным образцом. Похоже, Vector решил не уступать место младшему брату.
