СОЛДАТ-СНАЙПЕР МЕНДЕЛЬ-ГРУМАН


КЛАСС:        Солдат-Снайпер Мендель-Груман
МЕТАБОЛИЗМ:   Человек, Мужчина
ВОСПРИЯТИЕ:   Снайперское Подразделение
РАЗМЕР:       ~1,8 м.
ВЫНОСЛИВОСТЬ: Средняя
ВРАЖДЕБНОСТЬ: Высокая
ОРУЖИЕ:       Снайперская Винтовка ТРИГЛАВ 92 Сталкер, Пистолет ORO HOG 9mm, Осколочные Гранаты
НАГРАДА:      500
УГРОЗА:       Высокая

ОПИСАНИЕ:

Специализированные бойцы, предназначенные для поражения особо важных целей с большой дистанции. В отличие от стандартных пехотинцев, они проходят дополнительную подготовку по стрельбе, маскировке и наблюдению. Их задача проста: заметить противника раньше, чем противник заметит их, и устранить его одним точным выстрелом.

Броня снайпера имеет характерный тёмный, практически чёрный цвет и дополнена камуфляжным костюмом, рассчитанным на действия в лесистой местности. В конструкции используются элементы экипировки обычных пехотинцев и RPG-подразделений, однако шлем имеет собственную модификацию. Левая часть визора разделена на несколько отдельных оптических секций, позволяющих использовать специализированные системы наблюдения.

Основным оружием снайпера является ТРИГЛАВ 92 Сталкер. В руках подготовленного стрелка эта винтовка позволяет поражать цели на значительном расстоянии и особенно опасна против бойцов, которые считают себя находящимися в безопасности за пределами эффективной дальности обычного оружия.

Снайпер не стремится вступать в затяжную перестрелку. Он предпочитает занять выгодную позицию, дождаться подходящего момента и открыть огонь по наиболее опасной или уязвимой цели. После обнаружения его позиции может попытаться сменить укрытие и продолжить бой с другой точки.

Несмотря на специализацию, снайпер не является беспомощным на близкой дистанции. В качестве дополнительного вооружения он может использовать ORO HOG 9mm, а также располагает осколочными гранатами. Поэтому попытка прорваться к нему вплотную не гарантирует лёгкой победы. Представители этого класса также могут иметь FP9 SMG, несмотря на своё обозначение как снайперов.

Снайперы относятся к лёгкобронированным подразделениям Мендель-Груман и поэтому не обладают выдающейся живучестью. Их главная защита - дистанция, укрытие и точность. Если лишить их этих преимуществ, они становятся значительно менее опасными.

СОВЕТЫ:

- Не стой на открытом пространстве. Снайперу достаточно нескольких секунд, чтобы выбрать цель.
- Старайся первым делом определить, откуда ведётся огонь, и только после этого высовывайся из укрытия.
- На близкой дистанции снайпер значительно менее опасен, чем на дальней.
- Гранаты особенно полезны, если противник засел за укрытием.
- Не позволяй снайперу спокойно менять позиции. Потеря хорошего укрытия резко снижает его эффективность.
- Если заметил характерный тёмный силуэт и вспышку выстрела издалека, не проверяй второй раз, действительно ли это был снайпер.
