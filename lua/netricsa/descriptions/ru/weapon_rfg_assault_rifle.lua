ШТУРМОВАЯ ВИНТОВКА ASSAULT RIFLE


ОРУЖИЕ:  Штурмовая Винтовка Assault Rifle
ПАТРОНЫ: Tungsten Flechette Патроны
СС:      Высокая, Автоматический Огонь

ОПИСАНИЕ:

Стандартная штурмовая винтовка Вооружённых сил Земли (EDF). Представляет собой основное оружие пехотных подразделений EDF, предназначенное для ведения интенсивного автоматического огня по живой силе противника. Отличается высокой скорострельностью, хорошей точностью и достаточной эффективностью в перестрелках на ближних и средних дистанциях. Также встречается в арсенале повстанцев Red Faction и мародёров.

Использует 40-мм? Нет, специальные стреловидные вольфрамовые боеприпасы Tungsten Flechette. Питание осуществляется из коробчатого магазина вместимостью 40 патронов. Оружие оснащено автоматическим режимом стрельбы и дополнительной атакой прикладом, позволяющей нанести горизонтальный удар в ближнем бою. Боеприпасы широко распространены, поэтому пополнять запас обычно не составляет труда.

ПРИМЕЧАНИЯ:

- Эффективна против пехоты на ближних и средних дистанциях.
- Магазин вмещает 40 патронов.
- Использует вольфрамовые стреловидные боеприпасы.
- Основное штатное оружие пехоты EDF.
- Дополнительная атака позволяет ударить противника прикладом.
