САМОЗАРЯДНЫЙ ПИСТОЛЕТ ROTH-STEYR M1907


ОРУЖИЕ:  Самозарядный Пистолет Roth-Steyr M1907
ПАТРОНЫ: 8x18 мм Roth-Steyr
СС:      Самозарядный Огонь, 10 Патронов

ОПИСАНИЕ:

Австро-венгерский самозарядный пистолет, разработанный чешским конструктором Карелом Крнкой при участии Георга Рота. Принят на вооружение кавалерии Австро-Венгерской армии в 1907 году под официальным обозначением Repetierpistole M.7, а с 1909 года поступил в войска. Считается одним из первых самозарядных пистолетов, принятых на вооружение крупной военной державой. Производился на предприятиях Steyr в Австрии и FEG в Венгрии.

Работает по принципу использования отдачи ствола при его коротком ходе. Запирание осуществляется поворотом ствола примерно на 90 градусов. Использует специальный пистолетный патрон 8x18 мм Roth-Steyr и несъёмный коробчатый магазин на 10 патронов, расположенный в рукоятке. Заряжание производится сверху при открытом затворе с помощью специальной обоймы. Ударно-спусковой механизм имеет необычную конструкцию с тяжёлым спуском, повышающим безопасность при использовании верхом на лошади. Ручной предохранитель отсутствует.

ПРИМЕЧАНИЯ:

- Один из первых самозарядных пистолетов, принятых на вооружение крупной военной державой.
- Магазин на 10 патронов несъёмный, заряжается сверху специальной обоймой.
- Тяжёлый спуск снижал вероятность случайного выстрела при кавалерийской езде.
- Эффективен против одиночных незащищённых целей на коротких дистанциях.
- Использовался во время Первой мировой войны, а отдельные экземпляры сохранялись на вооружении вплоть до Второй мировой.
