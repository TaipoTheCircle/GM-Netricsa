МУХА С МАГНОРА


КЛАСС:        Муха
МЕТАБОЛИЗМ:   Насекомое
ВОСПРИЯТИЕ:   Нейтральное Существо
РАЗМЕР:       ~2,5 м.
ВЫНОСЛИВОСТЬ: Очень Низкая
ВРАЖДЕБНОСТЬ: Нейтральная
ОРУЖИЕ:       Отсутствует
НАГРАДА:      100
УГРОЗА:       Отсутствует

ОПИСАНИЕ:


Муха представляет собой гигантское летающее насекомое, способное по размерам значительно превосходить человека.

На первый взгляд её можно принять за обычную крупную муху, однако при ближайшем рассмотрении становится понятно, что перед тобой полноценный летающий охотник фекалиями размером практически с небольшую машину.

В отличие от большинства существ, с которыми приходится сталкиваться, мухи не являются противниками и не проявляют никакой агрессии. Они просто занимаются своими насекомьими делами, летая поблизости и совершенно не интересуясь происходящим.

Обычно их можно заметить группами возле различных органических отходов и других малоприятных мест.

Муху можно уничтожить практически любым оружием. Её тело обладает настолько малой живучестью, что одного попадания достаточно для мгновенной смерти.

После смерти они оставляют небольшое количество брони. Получается странная, но вполне рабочая схема: муха ничего тебе не сделала, ты её убил, а она ещё и оставила броню.

СОВЕТЫ:

- Прихлопнуть газетой. Если нет газеты - подойдёт любое дальнобойное оружие.
- Если решил уничтожить, достаточно одного попадания.
- Если убьёшь, не забудь взять броню.
- Если рядом находятся настоящие враги, сначала займись ими. Муха может подождать.
- Крайне Любят Говно.
