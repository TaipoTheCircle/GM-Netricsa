ЭКСТРЕННОЕ РАДИО


ОРУЖИЕ:  Экстренное Радио
ПАТРОНЫ: Не Требуются
СС:      Вызов Вертолёта

ОПИСАНИЕ:

Портативная радиостанция, предназначенная для вызова эвакуационного вертолёта. Устройство позволяет связаться с пилотами и запросить экстренную эвакуацию из зоны операции. После передачи сигнала на вызов прибывает вертолёт с двумя пилотами, готовый забрать находящихся поблизости бойцов.

Вертолёт прибывает приблизительно через 40 секунд после вызова и остаётся на месте в течение 40 секунд, ожидая посадки пассажиров. По истечении этого времени он покидает зону эвакуации независимо от количества спасённых. Те, кто не успел попасть на борт, погибают, поэтому медлить с посадкой крайне не рекомендуется.

ПРИМЕЧАНИЯ:

- Для вызова эвакуации достаточно воспользоваться рацией.
- Вертолёт прибывает примерно через 40 секунд.
- Экипаж состоит из двух пилотов.
- Время ожидания на земле составляет 40 секунд.
- После окончания ожидания вертолёт улетает, оставшиеся на земле бойцы погибают.
- Рация является приёмопередающим устройством, предназначенным для оперативной радиосвязи.
