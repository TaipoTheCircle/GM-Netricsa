ГИТАРА "ГИМН СССР"


ОРУЖИЕ:  Гитара "ГИМН СССР"
ПАТРОНЫ: Не требуются

ОПИСАНИЕ:

Необычная гитара, предназначенная для исполнения гимна Советского Союза. Для активации достаточно ударить рукой в воздух, после чего инструмент самостоятельно начинает воспроизводить музыкальную композицию.

Исполняет гимн СССР в версии из реальной жизни и игры "Red Alert 3". Не требует струн, навыков игры или даже непосредственного контакта с инструментом.

ПРИМЕЧАНИЯ:

- Воспроизводит гимн СССР из реальной жизни и "Red Alert 3".
- Для активации достаточно взмахнуть рукой в воздух.
- Музыкальные навыки не требуются.
