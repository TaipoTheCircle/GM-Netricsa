ПУЛЕМЁТ MACH 2


ОРУЖИЕ:  Пулемёт Mach 2
ПАТРОНЫ: 7,62x51 мм
СС:      ~900 выстрелов / мин.

ОПИСАНИЕ:

Мощный скорострельный пулемёт, предназначенный для ведения плотного автоматического огня. Благодаря высокой скорострельности способен быстро поражать несколько целей и эффективно подавлять противника на ближней и средней дистанции.

Пулемёт использует коробчатый магазин и отличается высокой скоростью стрельбы. Главным недостатком является быстрый расход боеприпасов, поэтому при длительной стрельбе запас патронов уменьшается очень быстро.

ПРИМЕЧАНИЯ:

- Очень высокая скорострельность.
- Особенно эффективен против нескольких целей одновременно.
- Быстро расходует боеприпасы при непрерывной стрельбе.
