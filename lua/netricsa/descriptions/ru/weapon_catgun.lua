КОТОПУШКА M1A0


ОРУЖИЕ:  Котопушка M1A0
ПАТРОНЫ: 9x19 мм патроны
CC:      ~750 выстрелов / мин 

ОПИСАНИЕ:

Необычное оружие, представляющее собой рыжего кота с красным ошейником. Несмотря на очаровательную внешность, M1A0 является одним из самых грозных образцов вооружения. Стрельба осуществляется непосредственно из пасти животного, откуда вылетают обычные пули.

Для удержания котопушки необходимо взяться за переднюю и заднюю лапы. Перезарядка производится поглаживанием кота. Простая, но весьма необычная система обслуживания позволяет поддерживать оружие в боевой готовности.

ПРИМЕЧАНИЯ:

- Не обманывайтесь очаровательной внешностью!
- Стреляет пулями из собственного рта.
- Для перезарядки достаточно погладить кота.
- Удерживается за передние и задние лапы.
- Возможно, самое пушистое оружие в арсенале.
