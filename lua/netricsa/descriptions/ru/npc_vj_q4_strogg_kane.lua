ОПИСАНИЕ:

Этот...Экземпляр... довольно не обычен. Представляет собой уникальный случай среди Строггов. Некогда он был человеком и капралом Корпуса космической пехоты, служившим в элитном подразделении "Отряд Носорог". После захвата Строггами Кейн подвергся процедуре строггификации, в результате которой значительная часть его тела была заменена кибернетическими компонентами.

Однако Кейн не стал обычным Строггом. Его превращение было прервано до завершения самого важного этапа процедуры, поэтому нейроцит не успел полностью взять его сознание под контроль. В результате Кейн сохранил собственную волю и продолжил сражаться против тех, кто превратил его в киборга.

После частичной строггификации его тело стало значительно сильнее человеческого. Кибернетические ноги повысили скорость и физическую выносливость, а встроенные системы позволяют ему взаимодействовать с технологией Строггов, включая их терминалы, телепортеры и медицинские станции. Более того, Кейн способен безопасно проходить через некоторые защитные лазерные системы Строггов, которые смертельно опасны для обычного человека.

По своим боевым возможностям Кейн наиболее близок к Тактическим Строггам. Это особенно примечательно, поскольку именно такие подразделения создавались из наиболее подготовленных людей и предназначались для ведения сложных боевых операций. Они используют укрытия, фланговые манёвры и взаимодействуют друг с другом, а не просто бегут навстречу противнику.

Кейн при этом сохраняет навыки опытного солдата. Он способен обращаться практически со всем доступным ему вооружением, быстро менять оружие в зависимости от ситуации и использовать окружение против противника.

Но главное отличие Кейна заключается не в его вооружении, а в том понимает, как думают люди. И одновременно знает, как действуют Строгги.

Проще говоря - для Строггов он остаётся неисправным элементом, который каким-то образом сохранил способность самостоятельно принимать решения.

СОВЕТЫ:

- Его обозначение Строгга - 8462-9B.
- Кейн является чрезвычайно ценным бойцом для человеческого подразделения.
- Не принимай его за обычного Строгга. Несмотря на внешний вид, Кейн сражается на стороне людей.
- Если по какой-либо причине Кейн оказался противником, ситуация становится значительно сложнее, чем при столкновении с обычным Строггом.
- Кейн сочетает человеческую тактику и возможности Строггов.
