МАГАЗИННАЯ ВИНТОВКА АРИСАКА ТИП 30


ОРУЖИЕ:  Магазинная Винтовка Арисака Тип 30
ПАТРОНЫ: 6,5x50 мм Arisaka
СС:      ~10–12 Выстрелов / Мин

ОПИСАНИЕ:

Японская магазинная винтовка, разработанная под руководством полковника Нариакэ Арикасы в 1897 году. Принята на вооружение Императорской армии Японии в том же году и стала первой винтовкой семейства "Арисака". Создавалась для замены устаревших винтовок Мурата. Конструкция сочетает решения, заимствованные из систем Маузера и Манлихера, отличаясь продольно-скользящим затвором и деревянной ложей.

Работает по принципу ручного перезаряжания с продольно-скользящим поворотным затвором. Использует патрон 6,5x50 мм Arisaka и встроенный коробчатый магазин на 5 патронов, заряжаемый при помощи обоймы. Оснащена открытыми механическими прицельными приспособлениями и креплением для штыка. Винтовка обладает хорошей точностью, однако во время Русско-японской войны выявились недостатки конструкции, включая проблемы с экстракцией гильз и надёжностью отдельных элементов затвора. Впоследствии была заменена более совершенной Тип 38.

ПРИМЕЧАНИЯ:

- Хорошо подходит для поражения одиночных целей на средних и дальних дистанциях.
- Эффективна против незащищённой живой силы.
- Не предназначена для борьбы с бронетехникой и тяжёлыми укрытиями.
- Использовалась японскими войсками во время Русско-японской войны.
- Существовал укороченный карабин Тип 30.
