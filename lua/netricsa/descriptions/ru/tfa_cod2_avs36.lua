АВТОМАТИЧЕСКАЯ ВИНТОВКА АВС-36


ОРУЖИЕ:  Автоматическая винтовка АВС-36
ПАТРОНЫ: 7,62x54 мм R
СС:      ~20-25 выстрелов / мин. одиночный, ~40 выстрелов / мин. автоматический
ВЕС:     4,05 кг. без штыка и магазина

ОПИСАНИЕ:

АВС-36, автоматическая винтовка системы Симонова образца 1936 года, советская автоматическая винтовка и первая серийно выпускавшаяся автоматическая винтовка, принятая на вооружение РККА после автомата Фёдорова. Она была разработана Сергеем Симоновым и официально принята на вооружение в 1936 году.

Винтовка использует газоотводную автоматику с коротким ходом газового поршня и оригинальное клиновое запирание. Питание осуществляется из съёмного двухрядного магазина на 15 патронов. АВС-36 могла вести как одиночный, так и автоматический огонь, причём автоматический режим первоначально рассматривался скорее как средство для чрезвычайных ситуаций.

Прицельная дальность механического прицела доходила до 1500 метров. Винтовка могла оснащаться штыком, а её масса со штыком, прицелом и магазином достигала примерно 6 кг. Несмотря на передовую для своего времени конструкцию, АВС-36 отличалась сложностью и рядом проблем с надёжностью, поэтому в итоге была заменена более удачной СВТ-38/40.

Всего было произведено, по разным оценкам, около 35-65 тысяч АВС-36. Оружие успело принять участие в боях на Халхин-Голе, советско-финской войне и начальном периоде Великой Отечественной войны.

ПРИМЕЧАНИЯ:

- Автоматический режим позволяет резко увеличить плотность огня, но для обычной стрельбы лучше подходит одиночный.
- Мощный винтовочный патрон 7,62x54 мм R делает АВС-36 серьёзным оружием на средней и дальней дистанции.
- Клиновое запирание выглядит довольно необычно для винтовки и стало одной из характерных особенностей конструкции Симонова.
