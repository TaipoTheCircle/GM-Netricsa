ТОМПСОН МОДЕЛИ M1A1


ОРУЖИЕ:  Томпсон Модели M1A1
ПАТРОНЫ: .45 ACP
СС:      Автоматический, ~700-750 выстрелов / мин.
ВЕС:     ~4,9 кг.

ОПИСАНИЕ:

Томпсон M1A1, также известный как "Томми-ган", американский пистолет-пулемёт, разработанный как упрощённая военная версия более ранних моделей Томпсона. M1A1 появился в 1942 году, а его производство продолжалось до 1944 года. Он был создан для массового военного использования и отличался более простой и дешёвой конструкцией по сравнению с ранними моделями.

В отличие от раннего Томпсона, M1A1 получил значительно упрощённый механизм. Вместо сложной системы с замедлением открытия затвора использовался свободный затвор, а ударник был неподвижно закреплён на затворе. Также был установлен фиксированный ударник и упрощённый дульный компенсатор отсутствовал.

M1A1 использует патрон .45 ACP и способен вести только автоматический огонь. Питание осуществляется из коробчатых магазинов на 20 или 30 патронов. Благодаря тяжёлой пуле и довольно умеренному темпу стрельбы оружие остаётся относительно управляемым при коротких очередях.

ПРИМЕЧАНИЯ:

- Мощный патрон .45 ACP делает M1A1 особенно эффективным на ближней дистанции.
- Лучше всего подходит для ближнего и среднего боя, особенно при стрельбе короткими очередями.
- M1A1 значительно проще ранних Томпсонов, что позволило быстрее и дешевле производить его для армии.
