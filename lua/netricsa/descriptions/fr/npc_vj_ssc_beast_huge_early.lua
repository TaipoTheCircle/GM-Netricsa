DÉBUT REPTILOÏDE D'ALUDRAN, ÉPOUSE DE HIGHLANDER


CLASSE : Premier reptiloïde d'Aludran, Highlander's Bride
MÉTABOLISME : à sang froid, ressemblant à un reptile, femelle
PERCEPTION : race primitive
TAILLE : 110 pieds
ENDURANCE : très élevée
HOSTILITÉ : très élevée
ARMES : missiles à tête chercheuse magiques
RÉCOMPENSE : 40000 FC
MENACE : élevée

DESCRIPTIF :

Un grand reptile à quatre mains vivant dans le système Aludran dans la constellation de Canis Major. Cette race primitive a accepté de se battre pour Mental en échange de pouvoirs de lancement de sorts.
Il lance des boules de feu automotrices dotées de capacités de guidage primitives. 
La race des Highlanders est nettement plus grande et plus dangereuse que les créatures ordinaires vivant dans les plaines. Lorsqu'ils étaient furieux, les Higlanders lançaient leurs missiles en succession très rapide. Les femelles Highlander sont encore plus dangereuses, non seulement en raison de leur taille énorme, mais aussi parce que leur constitution biologique leur impose un syndrome prémenstruel toute l'année.

CONSEILS :

- Gardez-les sous le feu constant et essayez d'abattre leurs missiles en l'air.
- Évitez leurs missiles indestructibles et ne vous approchez pas trop d'eux.