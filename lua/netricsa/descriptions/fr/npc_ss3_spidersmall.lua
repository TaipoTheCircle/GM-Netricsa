ÉPIDER ANTARESIEN HATCHÉ DE ANTARES PRIME


CLASSE:      Épice antarésienne hachurée
MÉTABOLISME: Alien, Arachnid
PERCEPTION: Créature d'arachnie
TAILLE:       1 pi
ENDURANCE:  Très faible
HOSTILITÉ:  Moyenne
ARMES:    Beurre acide, bitte
RÉCOMPENSE:     100 FC
MENACE:     Faible

DESCRIPTION:

La forme éclosante d'Arachnides Antrésiens - arachnides extraterrestres géants de la planète Antares Prime. Un adversaire extrêmement faible avec un exosquelette mince, mais il compense sa vulnérabilité avec des chiffres et une surprise. La plupart du temps, des cocons sensibles au bruit éclosent. Ils peuvent ramper le long des murs et des plafonds, attaquer avec de l'acide empoisonné de loin ou s'accrocher à leurs victimes de près. Leurs boules acides peuvent ricocheter les surfaces. Bien qu'ils ne soient pas dangereux individuellement, un essaim de dizaines de ces araignées peut rapidement entourer et épuiser même un combattant expérimenté.

CONSEILS:

- Ils peuvent sortir des pieds, du plafond, ou sortir de leurs cocons après un coup de feu fort.
- À portée de main, ils peuvent être écrasés instantanément avec votre pied. Ça ne gâche pas les munitions et c'est rapide.
- Le fusil est efficace contre les groupes.
- Le lugehammer tue en un seul coup, ne gaspille pas les munitions, mais vous laisse vulnérable pour la durée de la balançoire.
