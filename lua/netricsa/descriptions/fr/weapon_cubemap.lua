CUBEMAP


ARME:      Carte Cube

DESCRIPTION:

Utilitaire développeur qui produit un ensemble de sphères de test réfléchissantes (sondes Cubemap) utilisées pour prévisualiser et capturer des réflexions d'environnement. Une fois activé, l'outil place plusieurs sphères avec différents préréglages matériels dans le monde afin que les artistes et les concepteurs de niveaux puissent vérifier l'éclairage spéculaire, les réflexions et le mélange de cubemap. Pas un élément de combat - purement diagnostique et visuel.

REMARQUES:

- Vérifiez l'éclairage spéculaire.