MISS THAVEL OF FONDAMENTAL PAPER EDUCATION


CLASSE:      Mlle Thavel
MÉTABOLISME: Organisme du papier / Entité mythique
PERCEPTION: Professeur de langues
TAILLE:       ~9 pi
ENDURANCE:  élevé
HOSTILITÉ:  Extrême
ARMES:    Mains griffées géantes, dents pointues, règle (comme symbole d'autorité), transformation Wendigo
RÉCOMPENSE:     1000 FC
MENACE:     Très élevé

DESCRIPTION:

Le plus jeune de trois professeurs de langues meurtriers. Dans sa forme normale, elle a la peau blanche-neige, les cheveux noirs retors, trois cubes de lettres sur la tête (par ordre alphabétique), et porte une robe blanche tatouée. Son arme principale est ses mains énormes, noires, griffées, capables de couper des livres, et probablement des étudiants, en deux. Elle possède une forme cachée et plus terrifiante, la Wendigo, dans laquelle les bois poussent sur sa tête, son corps se couvre de fourrure, et ses vêtements deviennent encore plus tabassés. Cette transformation évoque sa nature mythique, insatiable et prédatrice, allant au-delà de la simple punition de l'échec scolaire. Comme ses collègues, elle est cruelle et impitoyable.

CONSEILS:

- Au combat, elle est mortelle grâce à ses griffes. Ses attaques sont rapides et balayantes. Dans sa forme Wendigo, sa force, sa vitesse et peut-être sa férocité augmentent considérablement.
- La peur intense dans la victime ou leur propre rage peut déclencher la transformation en un Wendigo. (Ce n'est pas certain). Rester calme peut retarder ou empêcher cette forme.