H.E.C.U. AH-64 GUNSHIP


CLASSE:      H.E.C.U. AH-64 Apache Gunship
MÉTABOLISME: aucun (mécanique, pilote humain)
PERCEPTION: Hélicoptère d ' attaque militaire
TAILLE:       ~58 pieds de long
ENDURANCE:  très élevé (armé, évasif)
HOSTILITÉ:  extrême (voir et détruire)
ARMES:    lance-chaînes, fusées, missiles homogénés
RÉCOMPENSE:     5000 FC
MENACE:     catastrophique

DESCRIPTION:

L'Apache est un vaisseau militaire lourdement armé déployé par l'U.S.E.C. pour éliminer les cibles de grande valeur et supprimer la résistance dans les zones ouvertes. Son armure composite éloigne les tirs de petites armes, et son agilité dans l'air rend difficile de frapper même avec des armes lourdes. Armé d'un canon à chaîne à tir rapide, de roquettes non guidées et parfois de missiles homogénés, il peut facilement dévaster l'infanterie et les véhicules.

Le rugissement des pales du rotor suivi d'un feu entrant est une condamnation à mort pour quiconque est pris à découvert. Les Apaches se coordonnent habituellement avec les troupes terrestres, agissant comme des bourreaux aéroportés pendant que les marines avancent. La confrontation directe sans explosifs ni armes énergétiques est futile.

CONSEILS:

- La couverture est votre meilleur allié - ne jamais combattre un Apache en plein air.
- Les explosifs (RPG ou armes montées) sont le seul vrai compteur.
- Les missiles d'hommage sont mortels.
- S'il est abattu, restez clair - les débris et les explosions secondaires peuvent être mortels.
