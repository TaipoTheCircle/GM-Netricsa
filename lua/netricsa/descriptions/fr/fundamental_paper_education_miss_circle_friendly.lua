PRÉVUE MISS CIRCLE DE L'ENSEIGNEMENT FONDAMENTAL


CLASSE:      Mlle Circle
MÉTABOLISME: Organisme de papier (enseignante mutante)
PERCEPTION: Professeur de mathématiques
TAILLE:       9,7 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extreme (moins d'élèves)
ARMES: Cercle prothétique géant, griffes pointues
RÉCOMPENSE:     10000 FC
MENACE:     Très élevé

DESCRIPTION:

Le principal antagoniste des "Fundamentals of Behavior", professeur de mathématiques à la Paper School. Exceptionnellement grande, avec de longs cheveux noirs qui s'éteignent aux cornes. À la place de sa main gauche, elle a un cercle géant et détachable nommé "M. Circle", qui sert à la fois d'outil d'enseignement et d'arme mortelle. Elle fait preuve d'extrême cruauté et de cannibalisme envers les étudiants qui échouent à ses examens (Abby, Lana). Elle a des favoris (Oliver, Zip, Edward), mais peut même les réprimander pour avoir enfreint les règles. Elle peut changer sa taille et possède une immense force physique, lui permettant de casser les meubles de l'école. Sa personnalité est un mélange effrayant de gaieté et de rage soudaine et impitoyable. Elle est le seul personnage à parler dans l'animation originale (avec une voix japonaise synthétisée). Elle a une faiblesse connue : un amour fanatique des cookies Oreo.

CONSEILS:

- Son cercle est une arme variée et mêlée avec d'immenses dégâts. Elle la manie avec maîtrise.
- Elle attaque méthodiquement et impitoyablement.
- Des cookies d'oréo. Une offre ou un coup d'Oréo pourrait l'apaiser, déclenchant un éclat de joie et dévorant le plaisir. Elle déteste Kit-Kats.
- Quelques coups de feu d'un fusil à double barre vont faire tomber ce professeur.