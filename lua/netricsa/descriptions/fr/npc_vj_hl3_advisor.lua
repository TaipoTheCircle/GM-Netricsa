CONSEILLER


CLASSE:      Combiner le conseiller
MÉTABOLISME: Organisme psionique parasitaire 
PERCEPTION: Combiner le contrôleur psionique supérieur
TAILLE:       ~12 pi
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    Domination psionique, prise télékinétique, proboscis Tentacle, Levitation slam
RÉCOMPENSE:     2200 FC
MENACE:     Catastrophes

DESCRIPTION:

Combiner les conseillers sont les véritables surveillants de l'occupation de la Terre, rarement vus par les soldats communs mais profondément craint même parmi les Overwatch. Ces êtres grotesques, ressemblant à des limaces, flottent dans un champ d'énergie psionique, leur corps gonflé et soutenu par la technologie extraterrestre.

Ils commandent Combinez les forces à travers les réseaux télépathiques, étendant leur volonté directement aux soldats transhumains et aux humains esclaves. Au combat, ils libèrent des pouvoirs psioniques terrifiants - arrêter les ennemis à mi-étape, les écraser avec une force invisible, ou les frapper contre les murs. Leur proboscis alimentaire est capable de percer les crânes et d'extraire la matière neurale, un processus utilisé à la fois pour la subsistance et l'interrogatoire.

Bien que rarement exposé sur le champ de bataille, quand les conseillers apparaissent, il indique absolu Combinez la domination dans la région. Leur présence signifie qu'aucune action n'est invisible et qu'aucune résistance ne peut durer longtemps.

CONSEILS:

- Éviter tout contact direct avec les yeux; le verrou psionique affaiblit la résistance.
