MONTANT DES FORCES SPÉCIALES DU SECTEUR DELTA


CLASSE:      Groupe des forces spéciales
MÉTABOLISME: Humain, Homme
PERCEPTION: Groupe des opérations spéciales Elite
TAILLE:       ~5,9 pi
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Beretta 92FS, Armat M41A Pulse Rifle, Sentry Guns, munitions expérimentales
RÉCOMPENSE:     4000 FC
MENACE:     Catastrophes

DESCRIPTION:

Les forces spéciales du secteur Delta sont une unité militaire d'élite placée sous le commandement direct de l'homme en costume d'affaires qui porte une valise. Ils sont hostiles à toutes les factions - personnel noir Mesa, HECU, et les créatures Xen. Très entraînés et blindés, ils fonctionnent avec une efficacité impitoyable, souvent des installations de recherche ou des avant-postes Xen pour sécuriser des artefacts anormaux.

Ils ont recours à une coordination supérieure, à des armes de pointe et à un soutien lourd, y compris des véhicules et des armes de garde. Les rencontres avec eux sont marquées par une puissance de feu écrasante et la précision tactique, ce qui en fait l'une des menaces les plus meurtrières du conflit.

CONSEILS:

- L'utilisation couvre largement - ils sont précis et disciplinés.
- Perturbez leurs formations pour réduire l'efficacité des équipes.
- Préparez-vous pour les armes lourdes et les tourelles.
- Attendez-vous à un homme en costume d'affaires qui porte une valise là où ils apparaissent.
