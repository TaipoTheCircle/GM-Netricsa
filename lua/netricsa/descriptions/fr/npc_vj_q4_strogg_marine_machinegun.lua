STRAGG GUN GUARD DE MACHINE DE STRAGGOS


CLASSE:      Variante de la Garde de Strogg
MÉTABOLISME: Cybernétique (Human-Strogg Hybrid)
PERCEPTION: Ciblage visuel + suivi du mouvement
TAILLE:       6 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Haut
ARMES:    Mitrailleuse intégrée (bras droit), tir par balle
RÉCOMPENSE:     500 FC
MENACE:     Moyenne

DESCRIPTION:

Les mitrailleuses sont l'un des types d'infanterie les plus courants. Ces anciens soldats humains ont été transformés chirurgicalement en drones semi-mécaniques, leurs bras droits remplacés par des mitrailleuses lourdes. Malgré leur cybernétisme brut, ils sont des combattants efficaces, abattre les tirs de répression avec une intensité effrayante.

Leurs systèmes de ciblage sont imprécis, ce qui les fait balayer de façon erratique d'un côté à l'autre, mais leur volume de balles les rend mortels à proximité du milieu. Ils patrouillent souvent des couloirs industriels ou des installations essentielles, servant de troupes de première ligne non durables.

CONSEILS:

- Bien que faible, la Garde de mitrailleuse peut infliger une quantité décente de dommages si vous en êtes proche. Essayez de vous en éloigner si vous le voyez, puis attaquez.
- N'importe quelle arme agit contre elle, mais la mitrailleuse devrait être utilisée pour conserver les munitions pour les armes plus fortes. Le fusil est bon s'ils s'approchent.
- Un groupe de gardes mitrailleurs peut être assez puissant, alors essayez de les détruire dès que vous pouvez.
- Les explosifs peuvent détruire la plupart des groupes en un seul coup.
- Avec d'autres ennemis, la Machine Gun Guard est un canon. Il va simplement vous distraire pendant que vous attaquez des cibles plus fortes, alors essayez de vous en débarrasser dès que vous pouvez.