SHREK, LE TANK DE ZOMBIE DU FAR FAR


CLASSE:      Shrek, le réservoir de zombies
MÉTABOLISME: Mutant biologique de l'Ogre
PERCEPTION: Grand chasseur Elite Infected melee
TAILLE:       10 pieds
ENDURANCE:  Extrêmement élevé
HOSTILITÉ:  Absolu
ARMES:    Feux, rochers, béliers, tirets, rugissements
RÉCOMPENSE:     5000 FC
MENACE:     Absolu

DESCRIPTION:

This specimen of Infected evokes mixed feelings in survivors: d'une part, ils voient un mutant énorme, vert, chauve déchirant des morceaux d'asphalte et les jetant. D'autre part, la chanson "Smash Mouth All Star" blare de sa poitrine. Shrek a apparemment avalé une radio juste avant d'être infecté, et maintenant le haut-parleur est coincé quelque part dans son estomac, blassant "Hé maintenant, vous êtes une étoile, mettez votre jeu, allez jouer!" à plein volume.

Sinon, son comportement est identique à celui d'un Tank classique. Il ne ressent aucune douleur, n'hésite pas à s'arrêter aux obstacles, et a un but : briser les survivants dans le mur. Ses mouvements préférés arrachent un morceau de trottoir et le jettent sur sa cible, et si la distance se ferme, il l'écrase simplement avec sa main lourde. L'impact est si puissant que le survivant est repoussé d'un bon dix mètres.

Parfois, Shrek gronde. Un Tank régulier crie si fort que ça déchire les oreilles. Celui-ci gronde tout aussi fort, mais après le rugissement, le haut-parleur blaronne, "Je ne suis pas l'outil le plus pointu de la remise". Les survivants ne savent pas s'il faut rire ou pleurer. La plupart choisissent de pleurer.

L'origine de ce spécimen est inconnue. Certains disent que le labo essayait de croiser le virus avec un écosystème marécageux. D'autres disent que c'est juste un grand gars en cuir vert qui aimait trop ce morceau et l'a emmené à la tombe. D'autres encore tirent sans poser de questions.

CONSEILS:

- Shrek jette des pierres. Ils volent lentement, mais ils font mal.
- Il est mortel au combat. Ne vous approchez pas si vous ne voulez pas vous transformer en bourrasque.
- Vous pouvez dire à quel point Shrek est proche par le volume.
- Si vous entendez tant à faire, tant à voir, et le sol sous vous tremble. Cours.
- Vous pouvez le tuer, mais il faudra une tonne de munitions et de chance.
- Ils disent que si vous écoutez attentivement, le refrain jouera. Mais vous n'écouterez probablement pas, vous serez content s'il se ferme.
