CREEPER FESTIF DU MINECRAFT


CLASSE:      Crèche festive
MÉTABOLISME: Poudre végétale
PERCEPTION: Mob hostile, Lanceur Dynamite
TAILLE:       5,5 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Extrêmement élevé
ARMES:    Blocs TNT
RÉCOMPENSE:     200 FC
MENACE:     Moyenne

DESCRIPTION:

C'est ce qui arrive quand un fluker régulier décide que se faire exploser sur place est ennuyeux et c'est beaucoup plus amusant de lancer des explosifs à distance.

Contrairement à son homologue vert classique, qui se balance et siffle, le Creeper Festif agit comme un lâche pyromane. Il apparaît la nuit, comme des rampants réguliers, mais au lieu de frapper un ennemi, il commence à jeter des blocs de dynamite (TNT). Il recule constamment, essayant de maintenir sa distance.

Les explosions de ces TNT sont équivalentes en puissance aux boules de feu d'un ghast. Ils ne causent pas beaucoup de dégâts, mais si vous manquez quelques coups de suite, votre santé va chuter. Parfois, une fois jetés, les TNT enflamment le sol, ajoutant au problème.

Si un Crèche Festif est frappé par la foudre, il devient chargé. Dans ce mode, la force de son explosion TNT augmente à celle d'un fluage régulier. Rester près d'un est très découragé.

CONSEILS:

- La Festive Creeper n'a pas d'arme, donc la meilleure tactique est de la frapper avec une épée. Il ne pourra pas lancer de dynamite à bout portant.
- Il est à l'abri du feu, ce qui signifie qu'il est inutile de le mettre en feu. Lava ne fera aucun dommage non plus.
- Ses TNT ne volent pas très vite, donc vous pouvez les éviter si vous continuez à bouger.
- Ne le laissez pas s'échapper. Plus il est loin de vous, plus il a de temps pour les jeter.
- Si vous voyez un festif festif chargé, surtout près des bâtiments, tuez-le le plus rapidement possible ou fuyez. Les explosions avec la force d'un rampant régulier peuvent détruire toutes vos créations.
