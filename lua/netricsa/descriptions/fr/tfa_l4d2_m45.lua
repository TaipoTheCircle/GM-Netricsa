MITRAILLEUSE MACHINE CARL GUSTAF M/45


ARME : Mitraillette Carl Gustaf M/45
MUNITIONS : Parabellum 9x19 mm
ROF : ~600 tours/min
POIDS : ~3,43 kg

DESCRIPTIF :

Le Carl Gustaf M/45, également connu sous le nom de « K suédois », est une mitraillette suédoise développée après la Seconde Guerre mondiale pour remplacer la mitraillette Suomi en service dans l'armée suédoise. Elle a été adoptée en 1945. L'arme était réputée pour sa conception simple, sa grande fiabilité et ses bonnes performances dans les climats froids et lorsque le mécanisme était mouillé.

Le M/45 utilise une action de retour de flamme et tire la cartouche Parabellum 9x19 mm. Il est alimenté par des chargeurs de 36 ou 50 cartouches. Le M/45B standard utilisait des chargeurs de 36 cartouches, tandis qu'une première variante du M/45 pouvait également utiliser des chargeurs Suomi de 50 cartouches.

La mitraillette est devenue célèbre bien au-delà de la Suède. Les forces spéciales américaines et la CIA l'ont notamment utilisé pendant la guerre du Vietnam, où il était officieusement surnommé le « K suédois ».

REMARQUES :

- Fonctionne bien dans les climats froids et résiste à la pénétration d'eau dans le mécanisme.
- Sa conception simple et sa grande fiabilité en ont fait l'une des mitraillettes suédoises les plus célèbres.
- Les Suédois ont fabriqué une mitraillette qui a tellement plu aux Américains qu'ils l'ont simplement emportée au Vietnam, ce qui lui a valu son propre surnom, le "K suédois".