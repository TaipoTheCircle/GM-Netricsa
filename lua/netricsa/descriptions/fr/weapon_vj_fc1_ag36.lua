G36 ASSAULT RIFLE WTCH AG36 SOUS GRENADE LAUNCHER


ARME: G36 avec module AG36
MUNITIONS:   5.56x45 mm OTAN (primaire) / 40×46 mm grenades à faible vitesse (sous baril)
CADENCE DE TIR:    ~750 tours/min

DESCRIPTION:

Le package G36 + AG36 est une plate-forme de fusils d'assaut moderne équipée d'un lance-grenades de 40 mm. Le G36 offre un feu automatique et semi-automatique fiable avec une bonne maîtrise et une bonne précision à des gammes intermédiaires. L'AG36 ajoute un effet de zone explosive pour le nettoyage, le déni de l'espace ou l'utilisation de véhicules légers - tous sans changer d'arme primaire.

REMARQUES:

- Décharge polyvalente : tir de précision/suppresseur de fusil (G36) combiné avec capacité explosive de zone (AG36).
- L'AG36 tire un projectile d'arc - compte pour la chute à des intervalles moyens/longs.
- Méfiez-vous de l'automutilation dans les espaces confinés lors du tir de grenades; utilisez le couvercle.
- Le montage modulaire permet de retirer rapidement AG36 pour revenir à l'opération de fusil autonome.
- Optique souvent inclure des marquages ou des solutions de visée pour le lance-grenades pour aider les engagements de 50-400 m.