AR-15 PISTOLE AUTOCHTONE


ARME:      AR-15
AMMUNITION:  Cartouches MM 5,56x45
CADENCE DE TIR:         ~20 tours/min

DESCRIPTION:

Le pistolet AR-15 est une arme à canon court assemblée à l'aide du récepteur d'un fusil AR-15, mais avec des pièces pour créer un pistolet qui peut être tenu et tiré d'une main.

REMARQUES:

- Grâce à son calibre, ce pistolet a une bonne pénétration.
- À ne pas confondre avec le fusil AR-15.






