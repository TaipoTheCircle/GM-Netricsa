STORMTROOPER DE CLONE DE LA KAMINO


CLASSE:      Clone Stormtrooper
MÉTABOLISME: Clone humain, Homme
PERCEPTION: Elite Stormroopers de l'Empire Galactique
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrême
ARMES:    E-101 Rifle
RÉCOMPENSE:     800 FC
MENACE:     Haut

DESCRIPTION:

Elite oragetroopers de l'Empire Galactique, incarnant la volonté de fer de l'Empereur et servant à intimider la population. Ce soldat est vêtu d'une armure blanche, mais est en fait humain et lié aux orques seulement par l'armure. Il fait partie de l'Empire Galactique et est allié à Mental. Ils ont obtenu leur armure de la coentreprise Mental-Altani sur Oratio, où le minerai d'Orks et les ingénieurs impériaux le transforment en équipement de combat. D'où l'armure Ork portant l'insigne de Mental.

Le soldat lui-même est un clone de l'un des guerriers réussis, Jack Fat. Ils portent un fusil E-101, qu'ils utilisent pour envoyer des ennemis à moyenne et longue portée.

L'armure comporte 18 segments, offrant une mobilité élevée et une protection efficace contre la plupart des types d'armes légères. Les filtres casque intégrés protègent contre les armes chimiques et biologiques et permettent de respirer dans le vide. Un système de communication intégré au casque permet une coordination en temps réel.

Ces serviteurs sans visage du Nouvel Ordre, par la force et la brutalité, ont porté la volonté de l'Empereur à des milliers d'étoiles dans toute la galaxie. Pendant l'apogée de l'Empire, les orageurs sont devenus l'incarnation vivante de sa puissance, de son impitoyable et de sa peur. À de rares exceptions près, tous les orageurs portaient une armure blanche, les distinguant des autres unités militaires impériales.

Les orageurs impériaux ont évolué à partir des soldats clones de la Grande Armée de la République. À la fin des guerres de Clone, en 19 BBY, la République Galactique a été réorganisée en Premier Empire Galactique. La Grande Armée fut transformée en Stormtrooper Corps, et les clones furent renommés "Stormtroopers".

Ils sont alliés de Mental et reçoivent des renforts, des transports, du matériel et d'autres fournitures de lui. En échange, ils fournissent leurs troupes pour des opérations qui nécessitent une infanterie massive hautement disciplinée.

CONSEILS:

- Leur fusil E-101 a un taux de feu élevé mais est inexact à longue portée.
- Leur armure est blanche, les rendant invisibles dans la neige.
- N'essayez pas de négocier.
- Si un orageur embarque dans un transport, détruisez le transport.
