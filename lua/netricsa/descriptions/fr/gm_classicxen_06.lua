XEN, ASCENT AU PORTAL


Tu y es presque. Au sommet de cette abomination d'une usine se trouve le portail qui mène directement sur le chemin vers Nihilanth lui-même. Le seul moyen ? Des ascenseurs organiques. Oui, vous avez bien entendu - les locaux ont apparemment été fatigués des boutons et des câbles normaux, donc ils ont créé des plates-formes géantes qui vous portent vers le haut quand vous vous tenez sur eux.


Mais bien sûr, Nihilanth ne va pas juste sortir le tapis de bienvenue. Le portail crache des contrôleurs à intervalles réguliers, chacun désireux de vous faire frire avec des explosions psychiques. Considérez-les comme les pires portiers de l'univers.

Objective: survivre à l'ascenseur, éviter le comité d'accueil, et atteindre le portail. L'autre côté est l'endroit où commence la salle du trône de Nihilanth - ou se termine, selon la façon dont vous effectuez.