Y.S.M. MARINE


CLASSE:       Y.S.M. Marine
MÉTABOLISME:  Humain, Homme
PERCEPTION:  Bouclier jaune PMC, Maraudeur contractuel
TAILLE:        5,9 pieds
ENDURANCE:   Moyenne
HOSTILITÉ:   Haut
WEAPONATORY: M4A1 Carbine, MP7, SPAS-12 fusil de chasse
RÉCOMPENSE:      500 FC
MENACE:      Haut

DESCRIPTION:

Il s'agit d'un membre d'une compagnie militaire privée qui opère selon le principe de "entendre un appel de détresse, prendre les sacs de pillage". Ces mercenaires ont intercepté le signal de la base Delta et sont arrivés à l'installation non pour secourir, mais pour piller.

Leur apparence est typique des mercenaires de la fin des années 1990 : gilets tactiques, gilets, bandanas, lunettes et autres gadgets. Leur schéma de couleur est gris foncé avec des accents jaunes (d'où le nom). Sur leurs épaules et les bérets sont des patchs avec un bouclier et l'abréviation Y.S.M. Ils sont armés d'armes automatiques : MP7, M4A1 et parfois SPAS-12.

Their mission is to remove anything unsafe from the base: équipements expérimentaux, données de recherche, échantillons de matières exotiques, armes, médicaments, et même champignons étranges qui ont grandi après une cascade de résonance. Tout cela sera ensuite vendu sur le marché noir à des sociétés privées, des gouvernements, d'autres CPM ou des syndicats criminels.

Y.S.M. a également été embauché spécifiquement pour saisir et détruire certaines données et certains appareils liés à la téléportation. Et pour créer un nouveau type d'armée privée, en utilisant la technologie capturée pour simplement faire chanter le gouvernement et les entreprises, en utilisant des matériaux classifiés.

CONSEILS:

- Les Marines ont une armure. Un pistolet ordinaire pourrait ne pas les pénétrer la première fois. Visez la tête.
- Ils utilisent des couvertures et des sprints. Ne tombez pas dans les balles.
- Les grenades et les explosifs sont efficaces contre les groupes.
- Un coup de tête va l'exploser.
- N'essayez pas de négocier. Ils se fichent de ton histoire. Ils veulent vos affaires et votre mort si vous êtes dans le chemin.
