MESA BLACK, CORE DE TENTACLE


Sam, la séquence de purge a été un succès. Le feu du réacteur a fait son travail, et l'énorme tentacule qui a dirigé ce silo n'est plus qu'un calamari alien carbonisé. Son corps s'est effondré dans les profondeurs, ne laissant derrière lui que son noyau grotesque, toujours en contact avec l'énergie résiduelle.

D'ici, l'environnement change. Le bassin extérieur entourant le silo est partiellement inondé et les systèmes de confinement ont échoué. Les barils de déchets radioactifs, jaunes vifs et bien brillants, dérivent lentement dans un courant circulaire autour de la chambre. Il s'agit moins d'un système d'élimination des déchets et plus d'un carrousel mortel.

Hazards:

Recommendation: continuez à avancer le long des corniches étroites. Ne nagez pas, ne touchez pas les barils, et ne pensez certainement pas à la pêche. Avec la tente morte, votre chemin vers l'avant est ouvert, mais Black Mesa ne manque pas d'horreurs bientôt.