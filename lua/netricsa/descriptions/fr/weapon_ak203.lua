RISQUE D'ASSAULT AK-203


ARME:      AK-203 fusil d'assaut
AMMUNITION:  7,62x39 mm
CADENCE DE TIR:         ~900 tours/min

DESCRIPTION:

Une modification moderne du fusil d'assaut emblématique, connu pour sa fiabilité et sa durabilité. Il tire de puissantes cartouches de calibre 7,62 mm avec un recul modéré. Il est efficace à portée moyenne et capable d'un feu soutenu pour la suppression ou l'engagement direct. Divers modules peuvent y être attachés.

REMARQUES:

- Haute durabilité et facilité d'utilisation.
- Recul modéré; contrôlable en courts éclats.
- Efficace contre les cibles non armées et légèrement blindées.
- La capacité des chargeurs nécessite un rechargement périodique pendant les combats prolongés.
- Ce fusil d'assaut peut être modifié à l'aide de différents modules.