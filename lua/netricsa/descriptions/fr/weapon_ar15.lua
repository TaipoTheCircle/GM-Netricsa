RIFLE SÉMI-AUTOMATIQUE AR-15


ARME:     AR-15
AMMUNITION: 5,56x45 mm
CADENCE DE TIR:        ~950 tours/min

DESCRIPTION:

AR-15 est le nom d'une famille de fusils semi-automatiques selon le modèle Colt AR-15 ou similaire. À l'origine, l'ArmaLite AR-15, son prédécesseur, était un dérivé réduit du modèle ArmaLite AR-10 d'Eugène Stoner et avait un sélecteur de feu. ArmaLite a vendu le brevet et les marques à Colt en 1959, ce qui a donné lieu au Colt AR-15, sans le sélecteur d'incendie. Après l'expiration de la plupart des brevets sur le Colt AR-15 en 1977, de nombreux fabricants d'armes à feu ont commencé à produire des copies de ce fusil sous divers noms. Jusqu'à l'expiration des brevets, Colt conservait la marque AR-15 et était le seul fabricant à pouvoir qualifier ses armes à feu de « AR-15 ».

REMARQUES:

- Bon pour la défense ou la fusillade.
- Le fusil le plus commun aux États-Unis.
- L'oreille de Trump a été tuée avec ce fusil.