RENFORCEMENT DE LA RESISTANCE


CLASSE:      Chasseur rebelle résistant
MÉTABOLISME: Biomécanique synthétique
PERCEPTION: Unité de soutien à la résistance lourde
TAILLE:       7,8 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Aiguille, Ram, Lames
RÉCOMPENSE:     700 FC
MENACE:     Très élevé

DESCRIPTION:

Le Resistance Rebel Hunter est un standard Combiner synthétique qui a été capturé et reprogrammé avec succès par les ingénieurs de résistance. Après avoir été piraté, ses systèmes de contrôle ont été complètement réécrits, ce qui l'a conduit à abandonner l'Alliance et à défection à la Rébellion.

Ce chasseur se distingue facilement de l'original en apparence. Sa coque a été repeinte noir mat, la lueur du capteur bleu familier a été remplacée par une orange vive, et le haut de la coque porte le symbole reconnaissable Lambda, qui est devenu l'emblème de la Résistance.

Malgré le changement de propriétaire, les capacités de combat du véhicule demeurent pratiquement inchangées. Le chasseur est encore capable de sauter à grande vitesse, de surmonter les obstacles et de fermer instantanément la distance vers l'ennemi. Ses puissants avant-postes sont utilisés pour délivrer des coups lourds et perçants, capables de pénétrer l'armure légère et d'empêcher même une infanterie lourde.

L'arme primaire reste le lanceur intégré, mais le système reprogrammé utilise des fletchettes oranges. Au moment de l'impact, ces projectiles s'intègrent dans la cible ou la surface, puis détonent après un court délai, ce qui constitue un danger pour le personnel et les véhicules.

Contrairement aux synthés, les chasseurs reprogrammés reconnaissent les résistants comme alliés et les soutiennent activement dans le combat. Ils accompagnent les équipes d'assaut, défendent les positions fortifiées et sont capables de poursuivre de façon indépendante les unités de Combiner jusqu'à ce que la menace soit complètement éliminée.

Bien que ces machines se battent maintenant du côté de l'humanité, elles restent les mêmes synthés de combat mortels. Toute erreur lors de la reprogrammation peut entraîner une réversion aux protocoles d'origine, de sorte que chaque Hunter est constamment surveillé par les ingénieurs de résistance.

CONSEILS:

- Évitez de s'attarder dans les zones ouvertes : les fletchettes explosent avec un léger retard et affectent une grande zone.
- Après le dérapage, le chasseur perd rapidement la vitesse, lui donnant l'occasion de riposter.
- La zone la plus vulnérable reste la tête et le capteur central.
- Un armement explosif puissant perturbe efficacement la stabilité du synthé et permet son incapacité plus rapide.
- Malgré le symbolisme de résistance, le spécimen hostile conserve toute la létalité de l'Alliance Hunter original.
