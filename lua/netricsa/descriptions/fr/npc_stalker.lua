ÉTIQUETTE DE COMBINE


CLASSE:      Mélanger Stalker
MÉTABOLISME: Cyborg transhumain 
PERCEPTION: Travailleurs transhumains esclaves
TAILLE:       ~6,5 pi
ENDURANCE:  Moyenne 
HOSTILITÉ:  Faible
ARMES:    Coupe laser, Membres hydrauliques, Implants d'obéissance
RÉCOMPENSE:     200 FC
MENACE:     Faible-moyenne

DESCRIPTION:

Les cratères sont parmi les résultats les plus horribles des expériences du Combine sur les prisonniers humains. Une fois libérés, hommes et femmes ont été mutilés, lobotomisés et reconstruits en drones de cyborg. Leurs yeux sont remplacés par des volets métalliques, des bouches scellées et des corps tordus d'augmentations qui les dépouillent d'autonomie.

Principalement utilisé dans les installations de Nova Prospekt et de Citadel, Stalkers sert de drones de construction et de gardiens de prison. Ils utilisent des machines, maintiennent la technologie et font respecter la domination de Combine. Lorsqu'ils sont menacés, ils libèrent les faisceaux de leurs coupes laser, capables de couper à travers des résistants et même des couvertures lumineuses.

Leur présence est un triste rappel de la cruauté du Combiné - qu'un destin humain peut être réduit à un outil d'oppression, sans identité gauche que l'obéissance.

CONSEILS:

- Visez la tête et le torse exposés.
- On trouve souvent des écureuils dans des zones fortifiées; attendez-vous à combiner des unités de soutien à proximité.
