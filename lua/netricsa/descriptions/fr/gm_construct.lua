CONSTRUCTION, OBSERVATION


À première vue, c'est juste construire. Des murs vides. Ouvrez le ciel. Des formes familières. Mais quelque chose se sent... éteint.

Les capteurs détectent une anomalie de faible énergie dans l'une des salles d'entretien sombres. Pas de bruit, pas de mouvement, mais les signatures de chaleur scintillent - comme quelqu'un debout parfaitement dans l'ombre. Regarde.

Chaque fois que vous tournez le dos, vous pouvez jurer que l'air change. La porte semble un peu plus sombre. Une figure est peut-être là - ou peut-être que c'est juste votre esprit cousant une forme dans la statique.

Recommendation: continuez de bouger. Ne traînez pas dans les couloirs sombres. Et si vous sentez quelqu'un regarder, vous n'avez probablement pas tort.