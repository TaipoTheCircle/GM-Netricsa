WILLIAM AFTON, L'ÉLITE DE SURVEILLANCE DANS L'ÉLITE



CLASSE:      William Afton, l'élite de surveillance derrière l'abattage
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Tueur solitaire, chasseur de soldats de l'Alliance
TAILLE:       5,9 pieds
ENDURANCE:  Extrêmement élevé
HOSTILITÉ:  Absolu
ARMES:    AR2, OICW, SPAS-12, grenades
RÉCOMPENSE:     9000 FC
MENACE:     Critique

DESCRIPTION:

William Afton est un tueur en série de soldats de l'Alliance, un être qui, il y a longtemps, a cessé d'être simplement humain. Il portait un costume Overwatch Elite, mais il était violet, le distinguant même parmi l'Elite. Avec Wallace Breen, Afton était à l'avant-garde de la marque de cafétéria de la Citadel, travaillant dans une variété de postes dans les établissements de l'Alliance. Derrière la façade du "service", Afton cachait un prédateur, étudiant méthodiquement les faiblesses de ceux qui l'entouraient.

Avec le temps, les esprits enragés de ses victimes ont piégé Afton dans son propre costume, transformant l'armure en prison et en sarcophage. À partir de ce moment, il est devenu un massacre vivant. Son sang est violet, et son corps affiche une vitalité anormale, comme s'il avait déjà partiellement franchi la frontière entre la vie et la mort.

Afton est un sociopathe prononcé. Son narcissisme imprègne toute son action, alimentant sa nature manipulatrice. Il ne tue pas, il domine. Cibler habilement les endroits vulnérables, Afton lance des soldats de l'Alliance dans des pièces isolées où il les exécute en privé. Il se vante de la douleur de ceux qui l'entourent, faisant de la peur un outil.

Au fond, Afton comprend son inutilité, mais compense pour cela avec un sentiment déformé de grandeur, exagérant les réalisations des autres et les revendiquant pour lui-même. Il est obsédé par les progrès de la science et de la technologie, les voyant comme le chemin vers son objectif cher - l'immortalité. Une crainte religieuse de l'enfer le rend encore plus cruel : Afton veut vivre éternellement, à tout prix.

Au combat, il utilise toutes les armes disponibles, variant de la répression méthodique à la lutte sanglante. Il prend son temps. Il joue.

CONSEILS:

- Ne jamais être seul avec lui - c'est exactement ce qu'il veut.
- Il est peu probable qu'il soit tué rapidement.
- Dangereux à n'importe quelle portée.