BALL PIG DU MOBIUS


CLASSE:      Porc à boule
MÉTABOLISME: Badnik mécanique
PERCEPTION: Bombardier robot de combat
TAILLE:       ~4 pi
ENDURANCE:  Faible
HOSTILITÉ: Moyenne
ARMES:    Bombes à billes métalliques
RÉCOMPENSE:     150 FC
MENACE:     Moyenne

DESCRIPTION:

Le Bal Pig est un robot Badnik créé par le mauvais Dr. Eggman dans le cadre de son armée de machines. Sa conception ressemble à un organisme mécanique de type porc avec un corps arrondi, debout sur deux jambes mécaniques et armé d'un dispositif intégré directement dans son ventre. C'est à travers cette armure circulaire qu'elle tire des bombes à billes métalliques qui rebondissent et endommagent des cibles.

Its attack method is simple but effective in narrow corridors and on inclines: le Bal Pig grimpe souvent plus haut sur les pentes ou au bord des quais et descend ses bombes, où ils rebondissent le long du sol et se tordent, créant un piège mortel pour quiconque essaie de passer.

Malgré son apparence, inspirée par un vrai cochon, c'est une machine de guerre froide. Il a été parmi les premiers modèles Badnik utilisés lors des premières invasions d'Eggman, et il apparaît encore dans différents mondes aujourd'hui.

CONSEILS:

- Il vaut mieux l'attaquer de loin ou d'en haut.
- Les bombes rebondissent en anticipant leur trajectoire et leur esquive.
- Lorsqu'il est détruit, le Bal Pig libère souvent un animal en otage, comme d'autres Badniks.
