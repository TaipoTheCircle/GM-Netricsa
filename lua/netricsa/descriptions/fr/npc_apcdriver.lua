COMMANDE APC DRIVER


CLASSE:      Combiner le pilote APC
MÉTABOLISME: Artificiel / mécanique
PERCEPTION: Drone de contrôle synthétique (Mine-Type AI)
TAILLE:       ~1,5 ft
ENDURANCE:  Faible 
HOSTILITÉ:  Moyenne 
ARMES:    Aucun directement; commandes montées canons APC + fusées
RÉCOMPENSE:     250 FC
MENACE:     Moyenne-haute

DESCRIPTION:

Le Combine APC Driver est un drone sphérique spécialisé, similaire visuellement à une Combine rollermine, qui fonctionne comme un système de pilote automatique pour les porteurs de personnel blindés lorsqu'aucun pilote humain ou transhumain n'est disponible. Une fois connectée, la sphère s'intègre dans les systèmes de l'APC, accordant au véhicule le contrôle autonome de ses armes et de ses mouvements.

Seul, le chauffeur est presque inoffensif et incapable d'attaquer. À l'intérieur d'un APC, cependant, il devient une extension dangereuse de la puissance de Combiner, contrôlant les canons lourds, les mitrailleuses montées et les lance-roquettes avec la précision de la machine. Lorsqu'il est détruit ou éjecté, l'APC cesse de fonctionner et devient immobile.

CONSEILS:

- Concentrez-vous sur la destruction de l'APC lui-même ; le chauffeur ne partira pas à moins d'être forcé.
- Les explosifs peuvent désactiver le conducteur plus rapidement que les coups de feu directs.
- Si elle est prise à l'extérieur de son véhicule, elle peut être neutralisée avec un minimum d'effort.
- Ne sous-estimez pas un APC contrôlé par le conducteur.
