CARCANO RIFLE M1891


ARME: Carcano M1891 Rifle
MUNITIONS:   6.5x52mm Carcano
CADENCE DE TIR:    ~10-15 tours/min
POIDS: ~3,78 kg

DESCRIPTION:

Le Carcano M1891 est un fusil à répétition italien adopté en 1891. Il devint le fusil standard de l'armée italienne et servit pendant la Première Guerre mondiale et la Seconde Guerre mondiale. Environ 3 millions ont été produits.

Le fusil utilise un mécanisme d'action du boulon et la cartouche de 6.5x52mm Carcano. Le flux est fourni par un magazine interne de 6 tours, qui est chargé à partir d'une boîte spéciale. Une fois les munitions dépensées, la boîte vide s'éjecte automatiquement du magazine.

Le Carcano avait de nombreuses variantes, dont des carabines raccourcies pour la cavalerie, l'artillerie et d'autres forces spéciales. En 1938, une nouvelle version en chambre pour la cartouche 7,35x51mm a été introduite, mais en raison des contraintes de temps et des difficultés liées à la transition de production, l'Italie est revenue à la cartouche 6,5x52mm.

REMARQUES:

- Bien adapté pour les gammes moyennes et longues grâce à sa cartouche de fusil.
- Six cartouches sont chargées dans une seule boîte, ce qui est très pratique pour un fusil à action de boulon.
- Le Carcano est resté le fusil italien standard pendant plus de cinquante ans, survivant de deux guerres mondiales.
- Le plus célèbre Carcano de l'histoire appartenait à Lee Harvey Oswald et était lié à l'assassinat de John F. Kennedy.
