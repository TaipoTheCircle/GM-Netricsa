FUSIL CARCANO M1891


ARME : Fusil Carcano M1891
MUNITIONS : Carcano 6,5x52 mm
ROF : ~10-15 tours/min
POIDS : ~3,78 kg

DESCRIPTIF :

Le Carcano M1891 est un fusil à répétition italien adopté en 1891. Il est devenu le fusil standard de l'armée italienne et a servi pendant la Première et la Seconde Guerre mondiale. Environ 3 millions ont été produits.

Le fusil utilise un mécanisme à verrou et la cartouche Carcano de 6,5 x 52 mm. L'alimentation est assurée par un chargeur interne de 6 cartouches, chargé à partir d'une boîte spéciale. Une fois les munitions épuisées, la boîte vide est automatiquement éjectée du chargeur.

Le Carcano avait de nombreuses variantes, notamment des carabines raccourcies pour la cavalerie, l'artillerie et d'autres forces spéciales. En 1938, une nouvelle version chambrée pour la cartouche 7,35x51 mm fut introduite, mais en raison de contraintes de temps et de difficultés liées à la transition de production, l'Italie revint à la cartouche 6,5x52 mm.

REMARQUES :

- Bien adapté aux moyennes et longues portées grâce à sa cartouche fusil.
- Six cartouches sont chargées dans une seule boîte, ce qui est assez pratique pour un fusil à verrou.
- Le Carcano est resté le fusil italien standard pendant plus de cinquante ans, survivant à deux guerres mondiales.
- Le Carcano le plus célèbre de l'histoire appartenait à Lee Harvey Oswald et était lié à l'assassinat de John F. Kennedy.