MESA BLACK, IL A ENCORE



Sam, tu viens d'entrer dans la pièce avec le réservoir géant de l'ichthyosaure et la pièce de la machine à piston massif poussant le métal comme si c'était le cas.

Quelque chose de trop calme. Là, de l'autre côté de la pièce, un homme en costume d'affaires-brief-case dans des stands à main qui regardent. Il ne bouge pas, ne crie pas. Juste observe. Lui, le fantôme dans le costume, apparaissant à nouveau.

Il sait que vous êtes là. Probablement vous attendre. Ou pas...