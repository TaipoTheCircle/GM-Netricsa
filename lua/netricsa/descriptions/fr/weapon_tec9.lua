TEC-9 PISTOLE AUTOCHTONE


ARME:      Intratec TEC-DC9
MUNITIONS:        cartouches 9x19
CADENCE DE TIR:         ~20 tours/min

DESCRIPTION:

Un pistolet à chargement automatique a été mis au point en Suède dans les années 80. Publié sur le marché en 1984. Il était populaire auprès des gangs à Los Angeles jusqu'à ce qu'Intratec ferme aux États-Unis.

REMARQUES:

- Un bon pistolet pour la guerre des bidonvilles.




