ROUTE DE COUPE, ARMES


ARME:      Roach de choc (arme biologique)
MUNITIONS:        Charges bioélectriques (régénération)
CADENCE DE TIR:         ~120 chocs/min

DESCRIPTION:

Bio-organisme étranger capturé et armé Lorsqu'elle est maintenue, elle se verrouille sur le bras de l'utilisateur et rejette des flux d'énergie bio-électrique aux cibles. Fonctionne comme une arme vivante, régénérant constamment ses propres munitions.

REMARQUES:

- Des munitions illimitées dues à la régénération naturelle.
- Feu primaire : boulons électriques rapides efficaces à portée moyenne.
- Feu secondaire : courant continu d'électricité pour dommages subis.
