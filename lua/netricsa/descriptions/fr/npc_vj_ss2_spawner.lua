ESPAGNE


CLASSE:      Pâtisserie
MÉTABOLISME: Véhicule contrôlé par l'IA
PERCEPTION: IA primaire
TAILLE:       24 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Très élevé
ARMES:    Bombes à plasma
RÉCOMPENSE:     500 FC
MENACE:     Extrême

DESCRIPTION:

C'est un Rollerball modifié, conçu pour se téléporter et créer des ennemis faibles.

Contrairement à d'autres drones mentaux, les spawners sont des bastions lourds et lents avec une immense puissance de feu. Ils sont l'un des véhicules les plus blindés et lourdement armés.

Ils utilisent un canon à plasma pour tirer des bombes à plasma à longue portée sur leur cible. Ces bombes, tout en causant des dommages minimes dans la zone, infligent des dommages d'impact massifs à tout ce qu'elles ont touché. Cela les rend excellents pour détruire des cibles stratégiques telles que les installations de communication, les dépôts d'approvisionnement, les dépôts de munitions et les navires de guerre. Ce sont l'une des principales raisons pour lesquelles les forces de Mental détruisent nos bases coloniales.

Utilisez une puissance de feu puissante pour la détruire rapidement, et essayez de ne pas être touché. Si les structures et les grands navires ne peuvent pas supporter beaucoup de coups, alors vous non plus.

CONSEILS:

- Utilisez un canon ou des explosifs pour le détruire rapidement.
- En raison de son immense puissance de feu, il devrait être une cible prioritaire.
- Évitez ses attaques. Je sais que tu entends ça beaucoup, mais sérieusement, ne te fais pas frapper cette fois.
