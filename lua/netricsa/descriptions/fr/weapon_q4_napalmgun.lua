NAPALM LAUNCHER


ARME: Lanceur Napalm
MUNITIONS: Balles de Napalm (boucles de feu)
CADENCE DE TIR: ~30 coups/min

DESCRIPTION:

une arme qui tire des boules de feu qui s'enflamme en frappant quelque chose. Utilisé pour le déni de zone et le contrôle des mouvements dans les couloirs ou les points d'étranglement. Pas très efficace contre les cibles blindées mais utile pour les ennemis faibles ou moyens.

REMARQUES:

- projectile de type balistique - but doit tenir compte de l'arc et de la chute.
- Les ennemis faibles vs fortement blindés; mieux utilisé pour supprimer plutôt que de finir.