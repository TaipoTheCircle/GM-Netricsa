GRUB SWARM


CLASSE:      Groupe de swarm
MÉTABOLISME: Xénobiologique
PERCEPTION: Forme de vie immature
TAILLE:       0,98 ft
ENDURANCE:  Très faible
HOSTILITÉ:  Aucune
ARMES:    Aucune
RÉCOMPENSE:     10 FC
MENACE:     Mineur

DESCRIPTION:

Un Grub est l'une des premières étapes du développement des organismes du Swarm. Ces créatures émergent le plus souvent de sacs de couvées spécialisés qui s'ouvrent lors de la détection de proies ou de l'exposition à des températures élevées.

Contrairement à la plupart des membres du Swarm, Grub est incapable d'attaquer les adversaires et sont pratiquement sans défense. Leur système nerveux primitif leur permet seulement de réagir au mouvement et de suivre de grands objets vivants.

Malgré l'absence de menace directe, la présence de Grub peut servir d'indicateur important de l'activité de Swarm à proximité. La découverte des sacs de couvées indique habituellement la présence d'organismes plus dangereux dans la région.

Au fur et à mesure que le Grub se développe, ils subissent de nouveaux stades de métamorphose, se transformant progressivement en représentants à part entière de leur espèce. Les formes de vie précises qui émergent de ce processus font encore l'objet de débats entre xénobiologistes.

La plupart des combattants éprouvent d'abord de la compassion pour les membres du Swarm en rencontrant le Grub. Cela se poursuit généralement jusqu'à ce qu'ils découvrent ce qu'ils deviennent.

CONSEILS:

- Ne soyez pas distrait par le Grub au combat.
- Leur présence indique souvent que quelque chose de bien plus dangereux est proche.
- Un petit organisme inoffensif aujourd'hui peut devenir un problème majeur demain.
