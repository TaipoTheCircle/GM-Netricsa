HALF-QUAKE SHOW, FALSE HOPE


SOMOS est mort.

Le métal refroidi. Les étincelles sont mortes. Les applaudissements, hélas, n'ont pas suivi.

Et maintenant vous étiez dans le téléporteur, avec le sentiment que la fin était juste au coin de la rue. Liberté, dénouement, morale... quoi qu'il arrive habituellement à la fin.

Erreur.

Tu es allongé sur une dalle de pierre. Vos bras et vos jambes sont immobilisés, comme des expositions dans un musée des souffrances des autres. Au-dessus de vous est un plafond clairement conçu par quelqu'un qui déteste les surfaces horizontales. Une pointe. Gros. Convainquant. Avec l'intention philosophique d'entrer dans ta tête et de mieux me connaître.

La voix des haut-parleurs vous remercie. Politement. Avec l'enthousiasme d'un département des RH de l'entreprise qui vous vire pour toujours.

"Merci de mourir".

Classique.

Quelque part au-delà des murs, des cris, des coups de feu et d'étranges fins peuvent être entendus. Les forces mentales sont en train d'éclaircir le spectacle. Participants, personnel, sécurité-tout est enchevêtré dans un grand, épisode très cher.

Et je vais écrire mon testament en code binaire... Merci Sam, au revoir.