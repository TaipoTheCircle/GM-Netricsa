BON DE GOATVILLE


CLASSE:       Chèvre
MÉTABOLISME:  Herbivore (mais agit comme le chaos incarné)
PERCEPTION:  Mammifères ongulés
TAILLE:        ~3 pieds aux épaules
ENDURANCE:   Élevée (immune à la plupart des dommages physiques)
HOSTILITÉ:   Neutre chaotique
ARMES:     Tête de cul, ragdoll chaos, lécher
RÉCOMPENSE:      200 FC
MENACE:      Moyenne

DESCRIPTION:

La chèvre folle est une chèvre qui défie la physique qui transforme tout environnement en chaos pur. Il charge d'abord les voitures, les objets et les gens, les envoyant voler avec une force impossible. En dépit d'être juste une chèvre, sa capacité à ragdoll à volonté, à lécher et à faire glisser des objets, et à survivre aux explosions en fait une catastrophe de marche (et de bave).

CONSEILS:

- Ne sous-estimez pas le cul; il peut lancer même des objets lourds.
- Si c'est des ragdolls - ce n'est pas mort, je me fous de la physique.
- Chaos suit où qu'il aille ; évite de se tenir près d'objets fragiles.
