SYNTHÈSE PLASMA GRENADE


ARME: Grenade du plasma
MUNITIONS:   Noyau de plasma autoportant
CADENCE DE TIR:    Jetable / Jetable
POIDS: 1,6 lbs

DESCRIPTION:

Développée par les scientifiques de Combine, la Grenade Plasma est une arme expérimentale alimentée par un noyau électrique autonome. Lorsqu'il est détoné, il libère une décharge plasmatique puissante qui non seulement étourdit et immobilise brièvement les ennemis, mais provoque également des brûlures dévastatrices d'énergie.

REMARQUES:

- Ne laissez pas les mains ennemies atteindre cette arme.
- Efficace contre l'infanterie.