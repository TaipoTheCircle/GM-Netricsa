MP-7 SUBMACHINE GUN


ARME:     MP-7
AMMUNITION: 4,6 x 30 mm
CADENCE DE TIR:        ~950 tours/min

DESCRIPTION:

La mitrailleuse MP-7 est une mitrailleuse développée au début des années 2000 par la société allemande Heckler & Koch. C'est une arme automatique en chambre pour la cartouche de 4.6×30 mm spécialement conçue. Le MP7 est conçu comme une petite mitrailleuse avec un chargeur inséré dans la poignée du pistolet, un support télescopique pliant et une poignée auxiliaire pliante à l'avant. Le mécanisme automatique du MP7 est basé sur un moteur à gaz avec un piston à gaz à court terme, et le boulon est verrouillé en tournant la diapositive. La conception intègre certaines caractéristiques du fusil d'assaut HK G36, comme l'utilisation intensive de matériaux polymères, le mécanisme automatique similaire et la conception du mécanisme de déclenchement. Il a été utilisé pendant la guerre en Afghanistan, est également utilisé par les services de répression dans les pays de l'OTAN, et est utilisé par les criminels.

REMARQUES:

- Compact et léger.
- Le stock et la poignée tactique peuvent être repliés.
- Il peut être modifié en ajoutant une vue ou un laser.