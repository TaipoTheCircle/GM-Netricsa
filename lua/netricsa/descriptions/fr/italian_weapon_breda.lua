MODÈLE DE BRÉDA 30 MACHINE LUMIÈRE


ARME: Breda Mod. 30 mitrailleuse légère
MUNITIONS:   6,5x52mm Mannlicher-Carcano
CADENCE DE TIR:    ~500 tours/min
POIDS: ~10,6 kg

DESCRIPTION:

Cette mitrailleuse légère italienne a été adoptée par l'armée italienne en 1930 pendant la Seconde Guerre mondiale. Il a été utilisé par l'infanterie italienne pendant la Seconde Guerre italo-étiopienne et la Seconde Guerre mondiale. Environ 30 000 ont été produits.

La mitrailleuse utilise une action à courte distance et des feux en mode automatique seulement. Il est alimenté à partir d'un magazine fixe de 20 tours, qui est chargé à l'aide de clips spéciaux. L'une des caractéristiques de conception inhabituelles était la nécessité de lubrifier les cartouches avant de tirer pour assurer le bon fonctionnement.

Breda Mod. Les 30 avaient une conception assez complexe, un taux de feu lent pour une mitrailleuse légère, et un certain nombre de problèmes concernant la fiabilité de son alimentation en munitions. Cependant, il est resté la mitrailleuse légère standard de l'armée italienne pendant une grande partie de la Seconde Guerre mondiale.

REMARQUES:

- C'est lourd pour une mitrailleuse légère, pesant plus de 10 kg.
- Les cartouches doivent être lubrifiées avant le feu. Oui, la mitrailleuse italienne voulait littéralement ses munitions « huilées ».
- Le chargeur non amovible de 20 tours ralentit considérablement le rechargement.
