PIGLIN CROSSBOWMAN DU RÉSEAU MINECRAFT


CLASSE:      Piglin Crossbowman
MÉTABOLISME: Un humanoïde de type cochon
PERCEPTION: Course guerrière primitive de la Nether
TAILLE:       6,3 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Conditionnel
ARMES:    Acrobatie
RÉCOMPENSE:     450 FC
MENACE:     Moyenne

DESCRIPTION:

Piglin Crossbowmen constituent exactement la moitié de la population adulte de porcins - l'autre moitié préfère les épées dorées et les combats serrés.

Comme toute leur espèce, ils sont obsédés par l'or au point d'identifier un ami ou un ennemi uniquement par la présence d'armure dorée sur leur corps.

Appearance: Un arbalète ne diffère d'un sabre que par ses armes et sa tactique. Au lieu de se précipiter dans la mêlée, il garde sa distance et tire des arbalètes toutes les deux secondes. Il recule, essayant de ne pas laisser sa cible s'approcher trop, mais s'il frappe un mur ou une falaise, il continue à tirer.

Contrairement aux bandits de Vindicator, les arbalètes ne préchargent pas leurs armes; ils ne rechargent qu'après être entrés au combat.

Les arbalètes vivent dans les mêmes endroits que les autres forêts folkloriques pourpre, les terres vierges et surtout dans les bastions, où ils gardent les trésors des intrus. Ils craignent le feu bleu des âmes, des frères zombifiés et des zoglins, mais cette lâcheté disparaît instantanément dès qu'ils repèrent un ennemi.

Si des arbalètes parviennent à faire tomber une grande cible, ils se rassemblent sur les lieux du meurtre et tiennent une petite célébration avec des cris de grognement caractéristiques. Ils aiment particulièrement danser après une chasse au porc.

CONSEILS:

- Portez une armure dorée. Un détail et ils ne vous toucheront pas.
- Ils sont nombreux dans les bastions, et ils n'aiment pas quand leur trésor d'or est touché.
