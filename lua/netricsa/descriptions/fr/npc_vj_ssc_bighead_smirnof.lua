GRANDE CHAMBRE, S-199 SMIRNOF


CLASSE:      Grande tête, S-199 Smirnof
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     7777 FC
MENACE:     Annoyance

DESCRIPTION:

Les grosses têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs. Ils portent l'uniforme de Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais sur le niveau de difficulté "Je suis Ugh-Zan", ils gagnent du feu et des modificateurs de glace. Ils frayent spontanément dans des zones secrètes, bloquant les passages avec leur nombre.

S-199 Smirnof n'est pas de Croteam. Il a grandi dans l'atelier de gmod. Il a commencé à faire de simples nextbots, puis a appris à importer des répliques exactes d'armes Call of Duty dans GMod. Son cerveau fonctionne comme ça : il voit quelque chose dans le jeu et comprend comment l'assembler.

Il a rencontré Jack l'Indépendant, et tout a commencé. Ensemble, ils mettent en place tout le jeu Far Cry 1 dans GMod. Son œuvre célèbre est "(VJ BASE) Quake 4 SNPCs." C'est lui qui écrit des descriptions claires pour ses armes pour GM-Netricsa de Typo. Il a aidé avec Serious Sam: Classic SNPCs (EXTRA), fixant quelques NPCs. Teachs Typo comment fixer les textures et les ragdolls dans Blender.

Jack et lui ont construit le Sniper Assassin de The Suffering. Ils se disputent parfois sur des choses insignifiantes, mais ils font toujours l'amitié est plus important.

Il n'aime pas faire de nouvelles connaissances. Sa description dit clairement: "Ne me faites pas simplement passer un message en tant qu'ami. Dis-moi d'abord pourquoi. Si vous voulez juste être amis, je vous refuserai." Son cercle se compose de Jack, Typo, et de son vieil ami Barsik, avec qui il joue. Il est poli envers les autres, mais garde sa distance. Il n'est pas méchant; il apprécie simplement son temps et son énergie pour ceux dont il se soucie déjà.

CONSEILS:

- Utilisez un couteau ou un pistolet pour dégager un chemin.
- Sur la difficulté "Je suis Ugh-Zan", les détruire à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.
