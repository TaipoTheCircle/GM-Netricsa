À PROPOS :

Le système de transport automatique de Simonova a été créé en 1941, l'organisation du projet soviétique a été conçue pour les travailleurs de la région. Lёгкими и средними танками, бронемашинами и защищёнными огневыми точками. Le RPC a été nommé en 1941.

Vous pouvez utiliser un gaz d'échappement automatique et votre véhicule mesure 14,5 x 114 mm avec des tuyaux en bronze. Une fois que vous avez utilisé la machine automatiquement, vous ne pouvez pas activer le moteur après le chargement выстрела. ПТРС имеет пятизарядный магазин с пачечным заряжанием.

Ne pas prendre en charge une masse corporelle de 21 kg, le PTP est prévu pour une utilisation de produit mobile non autorisée. De nombreux résultats s'appliquent à une distance allant de 300 à 400 mètres, en utilisant peut-être des gens et des projets de bronzage точек.

