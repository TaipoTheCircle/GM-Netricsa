ОПИСАНИЕ:

Le système de sécurité automobile de Simonova a été créé en 1941, l'organisation du projet soviétique a été conçue pour les travailleurs de la région. Lёгкими и средними танками, бронемашинами и защищёнными огневыми точками. Le RPC a été nommé en 1941.

Vous pouvez utiliser un gaz d'échappement automatique et votre véhicule mesure 14,5 x 114 mm avec des tuyaux en bronze. Une fois que vous avez utilisé la machine automatiquement, vous ne pouvez pas activer le moteur après le chargement выстрела. ПТРС имеет пятизарядный магазин с пачечным заряжанием.

Несмотря на огромную массу почти 21 кг, ПТРС предназначалось для относительно мобильного противотанкового применения. Лучшие результаты достигались на дистанциях около 300-400 метров, а использовать ружьё можно было и против броневых огневых точек.

