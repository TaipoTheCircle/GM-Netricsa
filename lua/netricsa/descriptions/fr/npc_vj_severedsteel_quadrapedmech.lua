THOR, PDG D'EDENSYS BIOTECH


CLASSE:      Thor, PDG d'EdenSys BioTech
MÉTABOLISME: Humain, Homme
PERCEPTION: CEO d'EdenSys BioTech
TAILLE:       9,8 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    Bataille Quadrupedal, lanceurs de missiles, champ de force, Ram
RÉCOMPENSE:     25000 FC
MENACE:     Critique

DESCRIPTION:

Thor Erickson, mieux connu sous le nom de PDG d'EdenSys BioTech, est le premier dirigeant de la société et l'homme responsable d'innombrables expériences de clones, le contrôle total de l'entreprise, et l'élimination de toute personne qui menace les intérêts de la société.

Malgré sa position, Thor n'est pas un combattant professionnel. Il évite l'engagement direct dans la bataille et préfère commander ses troupes à partir d'un endroit sûr. Toutefois, si les circonstances l'obligent à se rendre sur le champ de bataille, il le fait à l'intérieur d'une meche de combat quadrupède lourde, conçue spécifiquement pour protéger la haute direction de la société.

Le mech est une plateforme de marche massive équipée de servos puissants et d'armes lourdes. Sa principale méthode d'attaque consiste à lancer des volley-balls successifs de missiles homogénés, capables de couvrir de vastes zones et de forcer les adversaires à se repositionner constamment.

Si une cible s'approche trop, le mech s'accélère brusquement et les béliers. La masse du véhicule est si grande qu'une collision peut immédiatement détruire la plupart des adversaires ou les jeter à une distance considérable.

La caractéristique principale de la mech est son générateur de champ de force intégré. Une fois activé, une barrière d'énergie rouge se forme autour du mech, bloquant complètement tous les dommages entrants. Pendant que le champ est actif, Thor devient pratiquement invulnérable et continue à tirer sans risque. Le générateur fonctionne pendant un temps limité, après quoi il doit recharger.

CONSEILS:

- Ne gaspillez pas les munitions pendant que le champ de force est actif. Attendez qu'il soit désactivé.
- Continuez de bouger pour éviter les salvos.
- Ne jamais se tenir devant le 'Mech pendant qu'il s'accélère : il est presque toujours fatal.
- Utiliser le couvert entre les salves de missiles et l'attaque seulement lorsque le champ de force est désactivé.
- Malgré la puissance de la machine, Thor lui-même dépend complètement de son 'Mech. Une fois détruit, le directeur devient beaucoup plus vulnérable.
