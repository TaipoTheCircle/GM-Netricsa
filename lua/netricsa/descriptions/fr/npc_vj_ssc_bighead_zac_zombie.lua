ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     100 FC
MENACE:     Annoyance

DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan", ils gagnent le feu et les modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Zach Rand, connu sous le surnom de "Goldfinger", occupe une place spéciale dans le panthéon Croteam-une place moulée dans l'or de la gratitude. Son crâne exagéré ne brille pas tant avec une expertise technique qu'avec la valeur du support fourni, dont la nature reste un mystère au fil des ans. Son nom apparaît dans les crédits du tout premier jeu de la série, The First Encounter, tout au long de Classics: Revolution, indiquant une relation longue et significative pour le studio.

Peut-être était-il l'un des premiers et des plus perspicaces testeurs, dont les conseils ont sauvé le projet des erreurs mortelles. Ou peut-être a-t-il apporté un soutien moral, voire matériel inestimable, aux premières étapes, les plus difficiles. Le surnom "Goldfinger" évoque quelque chose d'exceptionnel, quelque chose d'"or", que ce soit une compétence unique, une découverte rare ou simplement un cœur d'or.

Il était vivant, mais après que quelqu'un l'ait tué, il est sorti d'un Zombie démoniaque.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager le chemin.
- Sur la difficulté "Je suis Ugh-Zan", les éliminer à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.