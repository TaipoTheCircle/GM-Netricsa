ICE AXE


ARME: Hache de glace
MUNITIONS:   Aucune
CADENCE DE TIR:    ~1 prise / seconde
POIDS: 1,2 kg

DESCRIPTION:

Une arme utilisée pour percer et détruire les obstacles, ainsi que pour la défense dans le combat manuel. La hache de glace a une vitesse de frappe élevée et peut pénétrer les structures lumineuses et l'armure ennemie. Sa conception permet des frappes ciblées tout en maintenant la maniabilité de l'utilisateur.

REMARQUES:

- Efficace contre un seul adversaire et des cibles légèrement blindées.
- Peut être utilisé pour briser la glace et les barrières en bois.
- Design compact et léger, il est facile à transporter dans des conditions difficiles.