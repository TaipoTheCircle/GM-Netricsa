MJOLNIR GUN


ARME: Gun Mjolnir
MUNITIONS:   Ammo 9mm / Énergie de foudre
CADENCE DE TIR:    ~60 RPM

DESCRIPTION:

Un pistolet compact imprégné de la puissance d'un ancien artefact de tonnerre. Bien qu'il ressemble à une arme 9mm standard, sa vraie puissance n'est révélée que dans les mains d'un utilisateur digne.

Le mode de tir primaire déclenche une frappe éclair ciblée à un point ciblé. Le boulon descend du ciel avec une force dévastatrice, frappant instantanément la cible et laissant une zone carbonisée de dommages.

The alternate fire mode is used primarily for demonstration purposes: la foudre éclaire le ciel sans causer de dommages significatifs, créant un effet visuel terrifiant et exerçant une pression psychologique sur l'ennemi.

REMARQUES:

- Le feu primaire déclenche une puissante foudre sur la cible.
- Firing sous l'utilisateur est extrêmement dangereux - l'utilisateur n'a pas de défense de niveau Thor.
- Un autre feu crée la foudre dans le ciel sans intimidation significative.
- Efficace à n'importe quelle portée avec une ligne de vue claire vers le ciel.
- Ne travaille qu'entre les mains d'une personne « digne ».
