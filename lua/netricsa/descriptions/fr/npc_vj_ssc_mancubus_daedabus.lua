DAEDABUS DE HELL


CLASSE:      Daedabus
MÉTABOLISME: Mammifère démoniaque mutant
DEFINITION: Behemoth modifié
TAILLE:       13 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    Deux canons à gaz explosifs verts
RÉCOMPENSE:     5000 FC
DANGER:     Absolu

DESCRIPTION:

Un démon personnalisant l'imperfection et l'avidité humaines, la gloutonnerie et l'oisiveté. Il a une peau incroyablement épaisse, des jambes éléphantines massives et une petite tête. Afin de détruire et de faire rôtir ses victimes, le Daedabus a deux canons implantés dans ses avant-bras qui tirent des boules d'acides explosifs.

Au lieu de la chair démoniaque habituelle, son corps a acquis une teinte vert marécageux, et à la place de ses deux yeux, il y a maintenant un seul, grand oeil vert qui brille d'énergie Argent. Cette énergie n'a pas changé sa personnalité, il est toujours aussi mauvais, stupide et destructeur que jamais, mais elle l'a rendu physiquement plus fort.

Contrairement au Mancubus régulier avec ses lance-flammes, le Daedabus tire un gaz explosif vert, acide, la même substance qui remplit les barils explosifs aux bases de UAC.

Comme beaucoup d'autres denizens de l'Enfer, le Daedabus a été acheté par Mental du Seigneur de l'Enfer pour renforcer sa Horde. Maintenant ces démons verts errent sur les planètes contrôlées par Mental, semant la mort partout où leurs pieds lourds marchent.

CONSEILS:

- Ils tirent au hasard, alors restez derrière.
- Ne conservez pas les munitions à moins de vouloir mourir.
