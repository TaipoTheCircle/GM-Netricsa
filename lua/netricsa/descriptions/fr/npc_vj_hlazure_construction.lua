MÉTABOLISME: Humain, Homme
PERCEPTION: Entrepreneur civil de l'installation Black Mesa
TAILLE:       ~5,9 pi
ENDURANCE:  faible
HOSTILITÉ:  aucune 
ARMES:    outils improvisés 
RÉCOMPENSE:     500 FC
MENACE:     négligeable

DESCRIPTION:

Les travailleurs de la construction sont des entrepreneurs civils employés à Black Mesa pour la réparation des installations, l'entretien des structures et l'expansion des complexes souterrains. Reconnus par leurs gilets oranges, leurs chapeaux durs et leurs outils de travail, ils sont des non-combattants pris dans le chaos de la Cascade de Résonance.

Bien qu'ils ne soient pas entraînés au combat, leur connaissance pratique de l'infrastructure de Black Mesa en fait des alliés étonnamment précieux. Ils peuvent naviguer dans des tunnels d'entretien restreint, déverrouiller des zones scellées et parfois prêter une assistance improvisée avec des outils. Cependant, leur manque d'armure et d'expérience de combat les rend très vulnérables aux créatures Xen et aux unités militaires hostiles.

Certains témoins oculaires suggèrent que, malgré leur statut civil, quelques travailleurs ont défendu les scientifiques et le personnel de sécurité avec des engins de construction, se tenant debout jusqu'à ce que l'évacuation soit impossible.

