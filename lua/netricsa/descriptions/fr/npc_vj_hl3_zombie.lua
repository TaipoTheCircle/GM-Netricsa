ZOMBIE, ARCTIQUE


CLASSE:      Gratte de tête de zombie, Terre (Arctique)
MÉTABOLISME: Animateur parasitaire, adapté au froid
PERCEPTION: Entité zombifiée
TAILLE:       6-7 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Griffes, morsure, cambriolage
RÉCOMPENSE:     220 FC
MENACE:     Moyenne

DESCRIPTION:

L'Arctic Zombie Headcrab est un être humain infesté d'un crâne terrestre laineux et adapté au froid constant. Le parasite conserve le contrôle du système nerveux de l'hôte, mais le froid modifie significativement le comportement et l'apparence de la créature.

Le corps de l'hôte est souvent enveloppé de débris de vêtements d'hiver, d'uniformes congelés ou de costumes fusionnés à la chair. Le cabillaud, recouvert de fourrure épaisse, s'enfonce profondément dans le crâne, se protégeant davantage du froid.

CONSEILS:

- Visez le headcrab-la fourrure la protège partiellement, mais des coups précis sont encore efficaces.