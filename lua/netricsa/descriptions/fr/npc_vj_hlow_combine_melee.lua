VENDU D'EXPLOITATION DE LA COMBINE


CLASSE:      Combiner le soldat Melee Overwatch
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner Melee Punisher
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Très élevé
ARMES:    Stun Baton modifié
RÉCOMPENSE:     400 FC
MENACE:     Moyenne

DESCRIPTION:

L'unité Combine Overwatch Melee Soldier est une unité de Combine rare mais quelque peu méchante, conçue pour les situations où le tir est inapproprié ou impossible. Il combat exclusivement au combat rapproché, en comptant sur la vitesse, l'agression, et un bâton astucieux modifié capable d'étourdir, de briser des os et de paralyser des cibles.

L'armure de ce soldat est délibérément simplifiée et pratiquement inexistante. La mobilité radio portable sacrifiée Combine : le soldat est plus rapide que les soldats standard, couvre facilement de courtes distances et peut rapidement engager d'autres soldats. Un casque blanc avec une visière bleue recouvre le visage.

Ces soldats étaient le plus souvent utilisés dans les prisons, les couloirs étroits et la répression des émeutes. Leur tâche est simple : atteindre la cible et les battre.

Malgré leur faible armure, les soldats melee sont mortels au combat.

CONSEILS:

- Ne le laisse pas s'approcher trop près de lui, son bâton va rapidement l'empêcher.
- Utilisez la distance et les armes à feu.
- Vulnérable à cause du blindage.
- Il est plus dangereux que les soldats.