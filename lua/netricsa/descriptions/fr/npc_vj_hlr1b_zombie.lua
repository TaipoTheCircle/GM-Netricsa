ZOMBIE DU CŒUR DE PURPLE


CLASSE:      Cramoisi Zombie, violet
MÉTABOLISME: Hôte humain + Casse-tête violet
PERCEPTION: Entité zombifiée
TAILLE:       6 pieds
ENDURANCE:  Moyenne-haute
HOSTILITÉ:  Haut (lent mais implacable)
ARMES:    Attaques de méléès ( griffes, luttes)
RÉCOMPENSE:     250 FC
MENACE:     Modéré individuellement, élevé en groupes

DESCRIPTION:

Lorsqu'un cabillaud violet infecte avec succès un humain, il crée une variante Zombie qui est plus forte et plus résistante que les zombies cabillauds communs. Le parasite violet modifie le tissu de l'hôte, lui donnant une endurance accrue et une apparence extraterrestre grotesque. Ces zombies sont lents mais implacables, formant souvent des hordes coordonnées.

CONSEILS:

- Les armes à feu ou les explosifs sont efficaces en raison de leur vitesse lente.
- Éviter tout contact étroit - les attaques à la mêlée sont dangereuses.
- Les groupes peuvent se coincer; prioriser les cibles.