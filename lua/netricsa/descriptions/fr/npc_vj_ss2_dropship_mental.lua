APC 404-08180 DROPSHIP


CLASSE:      APC 404-08180 Dropship
MÉTABOLISME: Unité de transport aérien, balançoire blindée
PERCEPTION: Transport d'atterrissage / Transporteur de personnel blindé aéroporté
TAILLE:       19,7 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Faible
ARMES:    Aucune
RÉCOMPENSE:     100 FC
MENACE:     Haut

DESCRIPTION:

C'est un vrai véhicule blindé volant avec un confort cinq étoiles. Mental, qui se fiche généralement du bien-être de ses soldats, a été généreux ici. À l'intérieur, le navire a tout : un jacuzzi, des chaises en cuir, une télévision à plasma et un espace pour deux douzaines de soldats blindés. Les murs sont si épais qu'aucune attaque ne dérange ceux à l'intérieur.

De l'extérieur, le Dropship ressemble à une énorme boîte volante gris-orange avec des moteurs. Il n'y a pas d'armes sur le navire-il n'est pas conçu pour le combat; son but est de livrer les soldats à leur destination et puis de s'envoler.

CONSEILS:

- Le Dropship n'a pas d'armes. Vous pouvez vous approcher et tirer sur les soldats qui débarquent sur la rampe.
- Détruire le Dropship est possible, mais difficile. Il faut plusieurs coups du lanceur de fusée. La meilleure arme est le CH-181 Hoverbike avec son taux de tir élevé.
- Le meilleur moment pour attaquer est pendant que le Dropship vole. Il se déplace lentement en ligne droite et ne peut pas répondre.
- Ne perdez pas de temps à détruire le navire pendant le débarquement. C'est plus facile de tuer les soldats qui sautent, comme ça vous conserverez les munitions et ne serez pas distrait de la menace principale.
- Il y a un jacuzzi à l'intérieur. Si jamais vous capturez ce Dropship, vérifiez d'abord si Mental y a laissé une bouteille de champagne.
