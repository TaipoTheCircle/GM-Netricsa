MÉTABOLISME: Pâtisserie
PERCEPTION: Élément artéfact unique
TAILLE:       5,5 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Passif
ARMES:    Explosion
RÉCOMPENSE:     50 FC
MENACE:     Moyenne

DESCRIPTION:

Ceci est le résultat d'une expérience génétique étrange, quelque part entre la magie, la pâtisserie, et peut-être une mauvaise blague de modder fou.

Contrairement à ses frères à poudre verte, celui-ci est complètement inoffensif en termes de dommages. Ça ressemble à un cookie en pain court.

La principale caractéristique de cette mafia est son explosion. Quand il frappe un ennemi, il ne détruit pas les structures et ne cause pas de dommages. Au lieu de cela, il s'enfonce discrètement dans une multitude de shards en forme de biscuit qui volent dans toutes les directions. Ces cookies peuvent être ramassés, et chacun rétablit instantanément une petite quantité de faim et de santé.

Contrairement à la nourriture ordinaire, les cookies de la mafia n'ont aucun effet négatif, autre qu'un léger sentiment de culpabilité pour avoir juste "tué" un doux vivant.

CONSEILS:

- Ne t'inquiète pas. Ça n'explose pas les blocs ni n'endommage pas. Mais si vous détestez les bonbons, vous pouvez ignorer.
- Un meilleur ami à l'estomac vide. Si vous êtes hors de la nourriture et loin de chez vous, c'est un vrai cadeau du ciel.
- Souvenez-vous : ces cookies ont une date d'expiration d'environ 3 mois, après quoi ils deviennent un zombie régulier. Je plaisante.
