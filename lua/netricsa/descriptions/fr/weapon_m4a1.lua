M4A1 CARBINE


ARME:       M4A1
AMMUNITION:   Munitions: 5,56x45 MM
CADENCE DE TIR:          950 tours/min

DESCRIPTION:

La carbine M4A1 est une carbine très célèbre et efficace. Il est utilisé par presque tous les pays de l'OTAN et a été développé aux États-Unis. Il est basé sur le M16A2 et était initialement destiné à armer les équipages de véhicules de combat et les équipages d'armes et de matériel militaire. Cette arme a été utilisée dans presque tous les conflits modernes à travers le monde. Il peut être fortement modifié en ajoutant des vues, des vues laser, des poignées tactiques, etc.

REMARQUES:

- Cette carbine est très bonne pour les bâtiments ou les tranchées.
- Il a un bouton de fermeture rapide, qui accélère grandement le rechargement.
- Modifier cette arme autant que possible, car des modifications peuvent être très utiles au combat.
- Utilisez le commutateur de mode incendie pour conserver les munitions.