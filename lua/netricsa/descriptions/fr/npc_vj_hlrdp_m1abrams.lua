M1 ABRAMS


CLASSE:      Y.S.M. M1 Abrams
MÉTABOLISME: Mécanique, Mercénaire contrôlé
PERCEPTION: Véhicule blindé moyen, soutien d'infanterie
TAILLE:       15,4 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrême
ARMES:    Lancement de missiles
RÉCOMPENSE:     5000 FC
MENACE:     Très élevé

DESCRIPTION:

Il s'agit d'une version plus légère et plus petite du célèbre char, utilisé par le Y.S.M. pour les raids rapides et le soutien d'infanterie à la base Delta. Contrairement à l'original lourd et peu souple, cette modification sacrifie l'armure et la taille pour la vitesse et la mobilité.

L'aspect du véhicule est distinctif : camouflage gris foncé avec des rayures jaune vif sur les côtés et la tourelle. Sa taille plus petite lui permet de manœuvrer dans des espaces de rue serrés et même de passer à travers des zones où un char régulier serait coincé. L'armure est plus mince-il est conçu pour protéger contre les armes légères et les explosifs, mais un coup direct d'un RPG ou d'un missile antichar réduira le véhicule à la ferraille.

Le Y.S.M. Abrams tire plus fréquemment, lançant un missile toutes les quelques secondes. Les missiles ont une bonne précision et un rayon de tir, mais moins de puissance de tir d'armure que le modèle original.

Ils se déplacent rapidement, tirent avec précision et peuvent changer de position en quelques secondes.

CONSEILS:

- Cette version est plus petite et plus rapide, mais son armure est plus faible. Un ou deux plans RPG bien adaptés peuvent le désactiver.
- Utilisez la couverture-les missiles arrivent rapidement, et si vous hésitez, le prochain arrivera dans quelques secondes.
- N'attaque pas la tête. Allez sur le flanc ou l'arrière.