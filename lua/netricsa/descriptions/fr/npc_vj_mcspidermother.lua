L'ESPRIT SUPÉRIEUR DU MINECRAFT


CLASSE:      Mère Spider
MÉTABOLISME: Arthropodes, Arachnid
PERCEPTION: Mob hostile, chef de famille
TAILLE:       2,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrêmement élevé
ARMES:    Bite, saut, escalade murale, coordination de pack
RÉCOMPENSE:     300 FC
MENACE:     Haut

DESCRIPTION:

Il ne s'agit pas seulement d'un prédateur solitaire, mais d'un véritable matriarche, voyageant dans l'Overworld entouré de sa couvée. Contrairement aux araignées ordinaires, qui mènent une vie solitaire, l'araignée-mère n'est jamais seule.

À la tombée de la nuit, cette bête dangereuse va à la chasse, accompagnée de 3 à 6 araignées, dont une est assise sur son dos. La mère araignée ressemble à une araignée normale en apparence, mais son comportement est radicalement différent. Elle est le centre de l'unité de combat, et l'essaim entier agit comme un seul organisme.

The mother spider behaves like a normal spider: elle attaque en basse lumière ou lorsqu'elle est provoquée. Mais le principal danger réside dans ses bébés. Tous les bébés suivent leur mère sans relâche et attaquent toute cible qu'elle choisit. Si vous frappez l'araignée mère, l'essaim entier vous attaquera. Si vous frappez un bébé, la mère et les autres frères et sœurs seront en colère.

Les bébés sur le dos de leur mère sont particulièrement traîtres – ils sont protégés par son corps et peuvent soudainement sauter au milieu d'un combat.

CONSEILS:

- Tuez les oisillons d'abord. Moins les petites araignées sont en vie, plus l'attaque de l'essaim sera faible.
- Ne vous laissez pas encerclés. La Mère Spider et sa couvée essaieront de vous piéger.
- Utilisez des armes de destruction massive. Un coup d'épée bien aiguisé avec le sort de la Blast Wave ou un Harm Potion bien placé peut détruire plusieurs éclosions à la fois.
- Soyez prudent la nuit. La Mère Spider n'est trouvée que la nuit et toujours avec sa couvée.
- La récompense pour avoir tué l'araignée mère est petite-quelques fils et un oeil d'araignée rare-mais la sécurité de la zone dégagée en vaut la peine.
