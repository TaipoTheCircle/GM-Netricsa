LE PRÉSIDENT ZOMBIE COMMON, S.E.C.U.


CLASSE:      Race de tête Zombie Fréquent, S.E.C.U.
MÉTABOLISME: Hôte humain + cratère parasitaire commun
PERCEPTION: Entité zombifiée
TAILLE:       6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut (lent mais implacable)
ARMES:    Attaques de Melee ( griffes, balançoires)
RÉCOMPENSE:     250 FC
MENACE:     Modéré individuellement, élevé en groupes

DESCRIPTION:

Zombie H.E.C.U. sont d'anciens soldats de l'unité de combat de l'environnement dangereux infectés par des cratères Xen. Leur entraînement militaire a disparu, laissant seulement le parasite extraterrestre en contrôle. Ils conservent l'imposant gros de l'armure de S.E.C.U., les rendant plus résistants que les zombies ordinaires.

Ces zombies sont lents mais implacables, en utilisant la force brute pour battre et mutiler toute personne à proximité. Les rencontres sont particulièrement terrifiantes dans les couloirs ou les espaces confinés, car l'armure H.E.C.U. offre une protection supplémentaire.

CONSEILS:

- Gardez la distance - leurs frappes sont fortes et peuvent épingler des cibles.
- Les armes à feu sont efficaces en raison de la lenteur des mouvements.
- Méfiez-vous des groupes - leur masse combinée et armure peuvent coincer les proies facilement.