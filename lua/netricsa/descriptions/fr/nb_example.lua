DESCRIPTION:

Cet exemple en peau de Mossman NPC est un humanoïde placeholder utilisé pour les tests et le développement. Bien qu'elle ressemble à l'allié scientifique Black Mesa, elle effectue des comportements scénarisés uniquement debout, marchant, tournant ou réagissant aux déclencheurs. Elle n'attaque pas, mais elle peut ouvrir les portes, marcher dans les chambres et fournir une présence visuelle pour les démos.

Think of her as a training dummy with Mossman cosplay: inoffensif, parfois gênant, et parfait pour vérifier les animations ou les interactions environnementales.

CONSEILS:

- Utile pour tester le comportement AI sans ajouter de vraies menaces.
- Peut déclencher des événements scriptés ou suivre des points de repère.
- Idéal pour voir comment les modèles humanoïdes interagissent avec l'environnement.
