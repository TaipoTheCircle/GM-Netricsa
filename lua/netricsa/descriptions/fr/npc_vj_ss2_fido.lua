FIDO THE SPIKY BULLDOG


CLASSE:      Fido le Bulldog Spiky
MÉTABOLISME: Mammifère
PERCEPTION: Chien de garde
TAILLE:       3 pieds
ENDURANCE:  faible
HOSTILITÉ:  élevé
ARMES:    morsures
RÉCOMPENSE:     50 FC
MENACE:     faible

DESCRIPTION:

Les chiens Fido sont parmi les plus populaires de l'Empire Mental, et sont largement utilisés comme chiens de garde et d'attaque. Ou du moins c'est ce que pensent la plupart des humains.

Les chiens Fido ne sont en fait rien de plus que des animaux domestiques qui vont attaquer ceux qui menacent leurs propriétaires. Les forces de Mental sont autorisées à amener leurs chiens au combat, comme la façon dont les humains sortent leurs chiens pour une promenade, seulement avec plus d'armes et de sang.

Heureusement, leur écorce est pire que leur morsure; restez loin et armez-les.

CONSEILS:

- Joignez-vous à eux ou sautez sur eux.
- Essayez de les aligner ; ils vont se piétiner l'un sur l'autre en essayant de vous atteindre.
- Utilisez des armes à tir rapide ou des armes de dommages de zone pour les sortir rapidement.
