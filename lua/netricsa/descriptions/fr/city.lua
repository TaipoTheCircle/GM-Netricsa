VILLE, LE DERNIER PLAN DE ZEROZERO


La carte city.bsp est considérée comme une suite directe de xmasxmas.bsp et buck.bsp et l'une des dernières œuvres connues de la carte mystérieuse zéro zéro, qui a disparu d'Internet en 2013.

Le fichier a été trouvé dans une archive chiffrée, le mot de passe auquel il s'est avéré être simple: "Noël". À l'ouverture, le joueur est présenté avec une ville vide.

Pas de fenêtres. Pas de portes. Pas de vie. Les bâtiments s'étendent vers le haut dans le ciel gris sans fin, comme le paysage inachevé du rêve de quelqu'un d'autre.

Quelque chose, une forme étrange, habite au centre de la ville. Le monde semble le contourner. Si vous restez là trop longtemps, alors...