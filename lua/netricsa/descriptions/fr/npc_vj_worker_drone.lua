MOTEUR DE COPIER 9


CLASSE:      Travailleur Drone
MÉTABOLISME: Mécanique / Énergie
PERCEPTION: Drone / Unité civile
TAILLE:       ~4 pi
ENDURANCE:  Faible 
HOSTILITÉ:  Aucune 
ARMES:    Aucune
RÉCOMPENSE:     150 FC
MENACE:     Très faible

DESCRIPTION:

Les drones sont des drones civils standard. Ils sont conçus pour l'entretien, la logistique et le travail manuel à bord des installations ou des environnements urbains. Complètement non communistes, ils évitent activement les conflits et fuient toute entité hostile, à l'exception de leur propre espèce.

Bien que sans défense, les drones ouvriers servent d'indicateur visuel des dangers environnementaux et de la présence ennemie. Observer leur comportement peut avertir des menaces voisines, les rendant étonnamment utiles malgré leur nature passive.

CONSEILS:

- Les drones travailleurs sont inoffensifs et peuvent fournir un contexte narratif ou environnemental.
