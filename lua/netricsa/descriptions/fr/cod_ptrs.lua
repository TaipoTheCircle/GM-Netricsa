RISQUE D'ANTI-TANK


ARME: PTRS-41 Rifle antidérapant
MUNITIONS:   14,5 x 114 mm
CADENCE DE TIR:    ~15 tours/min
POIDS: ~20,9 kg

DESCRIPTION:

Ce fusil antichar Simonov, modèle 1941, est une arme antichar soviétique conçue pour combattre les chars légers et moyens, les véhicules blindés et les positions de tir fortifiées. Il a été adopté par l'Armée rouge en 1941.

Le fusil utilise un système à gaz et tire une puissante cartouche à armure de 14,5x114 mm. Après le tir, le système recharge automatiquement l'arme, éliminant la nécessité pour le tireur d'utiliser manuellement le boulon après chaque tir. Le PTRS a un magazine à cinq tours avec un mécanisme de chargement simple.

Malgré son énorme poids de près de 21 kg, le PTRS a été conçu pour une utilisation antichar relativement mobile. Les meilleurs résultats ont été obtenus à des distances d'environ 300 à 400 mètres, et le fusil pourrait également être utilisé contre les points de tir blindés.

REMARQUES:

- À portée étroite et moyenne, il peut sérieusement endommager les véhicules blindés légers et les cibles blindées.
- Il fonctionne mieux à environ 300-400 mètres, où il combine une puissance énorme avec une précision acceptable.
- Son poids de près de 21 kg fait du PTRS une tâche de combat séparée.
- C'est un cas où le fusil peut être utilisé comme arme antichar, et l'ennemi gagne beaucoup de respect pour le calibre de 14,5 mm après le premier tir.
