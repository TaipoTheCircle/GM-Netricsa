PALE PIG DE L'EXPLOITATION MINECRAFT


CLASSE:      Porc pâle
MÉTABOLISME: Mammifère chaud
PERCEPTION: Animal passif des biomes de neige
TAILLE:       3 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Faible
ARMES:    Aucune
RÉCOMPENSE:     50 FC
MENACE:     Minimal

DESCRIPTION:

Une rare variété de porc, adaptée à la vie dans les biomes de neige et distinguée de ses homologues roses par son teint plus terne et plus pâle. Le manque de pigmentation causé par l'environnement rude est plus que compensé par son charme, comme les habitants le remarquent à juste titre.

Pale pigs behave no differently from regular pigs: ils errent dans les plaines enneigées, évitent la lave et les falaises, et fuient pendant quelques secondes lorsqu'ils sont endommagés.

CONSEILS:

- Cherche des porcs pâles dans des biomes enneigés. Ils se sentent chez eux.
- Leur manque de pigment n'affecte pas leur utilité : ils peuvent être élevés, montés et utilisés comme source de nourriture.
- Les porcs pâles sont un excellent camouflage dans la neige attention à ne pas les manquer.
- Si vous élevez un porc pâle avec d'autres variétés, les porcelets peuvent avoir n'importe quelle couleur des parents.
