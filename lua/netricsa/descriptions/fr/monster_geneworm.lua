DIRECTION GÉNÉRALE DE LA DIMENSION X


CLASSE:      Gene Worm
MÉTABOLISME: Parasitique + hybride bio-constructeur
PERCEPTION: Apex Overlord de la race X
TAILLE:       Plus de 100 pieds (surplombant le fossé dimensionnel)
ENDURANCE:  Extrêmement élevé
HOSTILITÉ:  Total général
ARMES:    Crache acide, spores, onde de choc psionique, assignation des minions Race X
RÉCOMPENSE:     9000 FC
MENACE:     Cataclysmique

DESCRIPTION:

Le Gene Worm est le colossal seigneur de la Race X, une monstruosité biomécanique qui sert d'arme ultime dans leur invasion. Émergent d'une faille dimensionnelle, il apparaît comme un titan massif de vers avec des mandibules grotesques, des armures et des sacs pulsants. Son corps est conçu pour terraformer et dominer les environnements extraterrestres, semer des terres avec Race X formes de vie tout en annihilant l'opposition avec des attaques dévastatrices.

La biologie de la créature est une fusion de tissu parasitaire et de génétique conçue, ce qui en fait une arme vivante et une chambre de naissance mobile. Il projette de l'acide corrosif et produit des gousses qui libèrent des minions agressifs pour le protéger. Sa présence psychique peut dénerver même des soldats entraînés, des esprits écrasants avec des impulsions extraterrestres.

Lors de l'Incidence Black Mesa, le Gene Worm a été le fer de lance de l'invasion Race X - son arrivée réussie aurait solidifié leur pied sur Terre. Il a fallu une puissance de feu militaire lourde et un sacrifice extrême pour la détruire avant que la brèche dimensionnelle ne soit complètement stabilisée.

CONSEILS:

- Visez les points faibles de la tête (yeux) pour exposer le point faible.
- Préparez-vous à ce que les minions frayent constamment; détruisez-les rapidement.
- La seule façon de vaincre ce monstre est d'attaquer le point faible sur le ventre.
