ARACHNOID, ADULTE DU SCORPIUS


CLASSE:      Arachnoide, adulte
MÉTABOLISME: ectothermes, arthropodes
PERCEPTION: race primitive sensible
TAILLE:       20-25 pieds
ENDURANCE:  élevé
HOSTILITÉ:  extrême
ARMES:    fusil à chaîne, piqûre de queue
RÉCOMPENSE:     5000 FC
MENACE:     élevé

DESCRIPTION:

Un saint guerrier d'une race primitive descendait des arthropodes. Très dangereux en raison de ses croyances religieuses.
Les deux griffes de l'arachnoide sont implantées avec des mitrailleuses équipées d'un dispositif de récupération des munitions. Son corps est recouvert d'un exosquelette qui le protège des balles, des explosifs et du feu.

CONSEILS:

- Merde dangereuse - ne pas approcher trop près.
- Ils s'enfuient.
