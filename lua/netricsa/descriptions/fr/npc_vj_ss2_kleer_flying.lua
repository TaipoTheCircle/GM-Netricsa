SQUELETTE VOLANT DE KLEER DE KLEER



CLASSE : Squelette volant de Kleer
MÉTABOLISME : Mort-vivant
PERCEPTION : Créature Magique
TAILLE : ~5,9
ENDURANCE : Faible
HOSTILITÉ : Élevée
ARMES : Mousquet Hellcannon (Boules de feu)
RÉCOMPENSE : 100 FC
MENACE : moyenne à élevée

DESCRIPTIF :

Ces morts-vivants ailés, également connus sous le nom de « Gargouilles », sont originaires de la planète de la mort et de lave-Kleer préférée de tous. Bien que faibles et frêles, comme la plupart des créatures de Kleer, ils sont armés d'un soi-disant canon infernal, qui tire des boules de feu sur les ennemis.

En réalité, cette variété a été créée par erreur lorsque Mental a bombardé leur planète. Les spécialistes des maladies mentales ont découvert les restes de pigeons fondus de Clears, ce qui leur a donné l'idée de créer une variante volante.

Ils ont importé des pigeons géants de Brimland et, en utilisant la technologie « Skin-O-Master », ont retiré leur peau et leur chair et les ont appliqués à des soldats volontaires de Clear. Lors d'un camp d'entraînement, les êtres nouvellement créés ont été forcés de regarder "Top Shotgun", à partir duquel ils ont appris à contrôler leurs ailes et à séduire les femmes.

Après une courte période de formation de quatre ans, les survivants ont rejoint la Mental Air Force.

Les Flying Clears ont une apparence similaire à leurs homologues ordinaires, mais avec quelques différences, telles que des pieds normaux au lieu de sabots, des mains au lieu de griffes et une tête plus humanoïde. Ils utilisent le mousquet "Hell Cannon" comme arme.

Même si un seul Clear représente peu de menace, comme la plupart des squelettes, ils voyagent presque toujours en groupes (ou, pire, en hordes).

CONSEILS :

- S'ils volent assez bas, vous pouvez les éliminer d'un coup de fusil de chasse.
- S'ils sont loin, utilisez un fusil de précision, des explosifs ou une arme à tir rapide.
- Essayez de les éliminer rapidement avant d'être submergé par des boules de feu venant de toutes les directions.