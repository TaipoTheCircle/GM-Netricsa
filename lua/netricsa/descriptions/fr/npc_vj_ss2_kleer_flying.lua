KLEER FLYING SKELETON DE KLEER



CLASSE:      Squelette volante
MÉTABOLISME: Morts
PERCEPTION: Créature magique
TAILLE:       ~5,9
ENDURANCE:  Faible
HOSTILITÉ:  Haut
ARMES:    Masque Hellcannon (balles d'incendie)
RÉCOMPENSE:     100 FC
MENACE:     Moyenne-haute

DESCRIPTION:

Ces morts-vivants ailés, également connus sous le nom de "Gargoyles", viennent de la planète préférée de tous les morts et de la lave-Kleer. Bien que faibles et fragiles, comme la plupart des créatures de Kleer, ils sont armés d'un soi-disant canon d'enfer, qui tire des boules de feu sur les ennemis.

En réalité, cette variété a été créée par erreur lorsque Mental a bombardé leur planète. Les scientifiques mentaux ont découvert les restes de pigeons fondus de Clears, ce qui leur a donné l'idée de créer une variante volante.

Ils ont importé des pigeons géants de Brimland et, en utilisant la technologie "Skin-O-Master", ont enlevé leur peau et leur chair et les ont appliqués à des soldats libres volontaires. Dans un camp d'entraînement, les nouveaux êtres ont été contraints de regarder « Top Shotgun », d'où ils ont appris à contrôler leurs ailes et à séduire les femmes.

Après une courte période d'entraînement de quatre ans, les survivants font partie de la Force aérienne mentale.

Flying Clears sont semblables en apparence à leurs homologues réguliers, mais avec quelques différences, comme les pieds normaux au lieu de sabots, les mains au lieu de griffes, et une tête plus humanoïde. Ils utilisent le mousqueton "Hell Cannon" comme arme.

Alors qu'un seul clair pose peu de menace, comme la plupart des squelettes, ils voyagent presque toujours dans des troupeaux (ou, pire, des hordes).

CONSEILS:

- S'ils volent assez bas, tu peux les sortir avec un coup de fusil.
- S'ils sont loin, utilisez un fusil, des explosifs ou une arme à feu rapide.
- Essayez de les sortir rapidement avant d'être submergé par des boules de feu de toutes les directions.
