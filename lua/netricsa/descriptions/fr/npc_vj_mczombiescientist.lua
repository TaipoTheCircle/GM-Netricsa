SCIENTIFIQUE DE ZOMBIE DU MINECRAFT


CLASSE:      Zombie Scientifique
MÉTABOLISME: Morts
PERCEPTION: Un mort intelligent, lance-pions
TAILLE:       6,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Faiblesse et dommages Potions
RÉCOMPENSE:     300 FC
MENACE:     Moyenne

DESCRIPTION:

C'est une espèce rare non morte dont le cerveau conserve assez de matière grise pour se souvenir de vieilles habitudes. Contrairement à ses frères sans esprit, qui se contentent d'inculper, ce spécimen préfère la tactique d'un alchimiste. Il ne s'engage pas dans un combat rapproché ; il enferme sa cible avec des potions à distance.

Il porte un manteau de labo blanc sur une chemise bleue, des lunettes sombres, une cravate brune et une ceinture. Il ressemble presque à un employé vivant, si vous ignorez sa peau verte. Il semble qu'il soit mort juste à son bureau, puis tout simplement debout et poursuivi ses expériences-cette fois sur les créatures vivantes.

Au combat, le Zombie Scientist utilise deux types de potions. Une potion endommagée endommage directement la cible, tandis qu'une potion faible réduit la puissance d'attaque, laissant la victime presque sans défense contre d'autres mafia. Le scientifique évite le combat en melee-si un ennemi se rapproche trop, les morts-vivants préfèrent se retirer et reprendre le tir à distance.

Il ne brûle pas au soleil comme les zombies normaux-apparemment son manteau le protège des rayons UV tout aussi bien que de l'acide.

CONSEILS:

- Ne laisse pas le scientifique à portée de lance. Fermez vite et attaquez au combat.
- Il est impuissant au combat et ne pourra pas utiliser de potions.
- Dodge potions-ils volent dans un arc.
- Utilisez un bouclier. Il ne bloque pas l'effet de la potion, mais il réduit les dommages directs des coups.
- Si vous êtes affaibli, reculez derrière la couverture et attendez l'effet. Combattre dans cet état signifie une mort certaine.
- Les potions endommagent les autres.
