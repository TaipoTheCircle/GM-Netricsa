POTATO


ARME: Pommes de terre
MUNITIONS:   Pommes de terre
CADENCE DE TIR:    ~10-15 lancers / min.
POIDS: ~150-250 g

DESCRIPTION:

La pomme de terre, aussi connue comme simple pomme de terre, est utilisée au lieu d'une grenade pour l'entraînement des soldats de l'Armée rouge soviétique. Le lanceur reçoit quatre pommes de terre et doit les jeter aux cibles d'entraînement. Les pommes de terre ne causent aucun dommage et sont incapables de tuer l'ennemi.

Malgré leurs origines totalement pacifiques, la pomme de terre semble et est utilisée comme un objet de lancement improvisé.

REMARQUES:

- Utilisation primaire : l'entraînement lance une cible. L'efficacité du combat est pratiquement inexistante.
- "Comrade Commissar, pourquoi avons-nous des pommes de terre au lieu de grenades ?"
- L'approvisionnement standard est de quatre pommes de terre.
