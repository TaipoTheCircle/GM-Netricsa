DEUXIÈME PLANTE DU SYSTÈME MEDUSA


PLANET:       La deuxième planète du système Méduse
TYPE:         Planète terrestre
CLIMATE:      Atmosphère tempérée, inébranlable, précipitations occasionnelles
MOONS:        Inconnu
TERRAIN:      Plaines désertiques, falaises scintillantes, pierres rondes éparpillées
LOCATION:     Le système des étoiles de Medusa, périphérie de la galaxie de la Voie lactée
NATIVE RACES: Roches
AFFILIATION:  Inconnu
LOCATIONS:    "Pegasus" Landing Plain, Illusion Spawn Sites

DESCRIPTION:

C'est un monde silencieux et désolé, sa plaine rocheuse parsemée de pierres rondes ressemblant à des pommes de terre. Vue depuis l'orbite, elle semble sombre et inhospitalière. L'atmosphère de la planète est totalement inapte à la respiration humaine; le climat est tempéré et les précipitations abondantes. Des sources d'hydrocarbures lourds ont été découvertes sous la surface.

La caractéristique la plus unique de la planète est ses habitants indigènes. La flore locale est clairsemée, mais les véritables maîtres du monde sont des êtres intelligents d'origine inorganique, indistinguables extérieurement des pierres ordinaires.

These beings possess astonishing abilities: Ils peuvent se souvenir des images qu'ils ont jamais vues. Les pierres peuvent reproduire ce qu'elles ont vu, ou même ce qu'elles ont lu dans l'esprit des visiteurs, sous forme de mirages tridimensionnels et réalistes. On croit qu'ils le font par ennui, pour animer la vie quotidienne sans joie sur la planète déserte.

Lorsque le « Pegasus » a atterri sur cette planète, les passagers ont assisté à une série d'apparitions fantomatiques : une procession de mousquetaires des « Trois Mousquetaires », puis eux-mêmes, et plus tard les pirates spatiaux qu'ils poursuivaient. Toutes ces images étaient des illusions créées par les habitants.

Le mystère fut résolu lorsque la fille du professeur Seleznev prit l'une des pierres, la lueur qui s'évanouissait lentement, et la pierre se transforma en capitaine de l'espace, l'un de ceux qui avaient déjà subi un désastre sur cette planète et avaient été « enregistrés » dans la mémoire de la pierre.

KEY LOCATIONS:

- Plaine d'atterrissage « Pegasus » : Une partie de la plaine rocheuse désolée où le navire de recherche a atterri. C'est ici que des manifestations massives d'illusions ont été observées.
- Zones d'activité illusoire accrue : Zones d'amas de pierres sensibles, où la probabilité de mirages est la plus élevée. Les coordonnées de ces zones sont instables, car les pierres peuvent se déplacer lentement.
- Emplacement du capitaine : Le point sur la plaine où la pierre a été découverte, qui contenait l'image d'un des capitaines disparus.
