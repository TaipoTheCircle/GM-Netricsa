CHI-FANG


PLANET:       Chi-Fang
TYPE:         Planète terrestre, Planète industrielle
CLIMATE:      Température
MOONS:        1 lune
TERRAIN:      Villes
LOCATION:     Système d'étoiles inconnues dans la Voie lactée.
NATIVE RACES: Chi-Che, anciennement Horde Mentale (Toutes races)
ALLIANCE:     Ancien Empire du Prince Chan et du Chi-Fang (anciennement), Nouveau Empire du Chi-Fang
LOCATIONS:    Chi Che Ville, Chi Che Port, Parc d'attractions Chan, Palais Chan

DESCRIPTION:

L'architecture de cette planète s'inspire de l'esthétique de la Chine préindustrielle. Les villes sont construites avec des pagodes densément emballées avec des toits incurvés distinctifs, ce qui indique une forte densité de population dans des vallées habitables entourées de sommets montagneux interdits. Elle dispose d'une infrastructure portuaire bien développée, ce qui signifie que ses principales routes commerciales sont par eau.

La planète a été capturée par les forces de Mental par la subjugation de son souverain. Le prince Chan, chef de Chi-Fang, a conclu un accord avec Mental, recevant une armée de ninjas non-morts en échange de la loyauté. Jusqu'à récemment, ces troupes patrouillaient les rues de la ville et les terrains du palais.

KEY LOCATIONS:

- Port Chi-Che: Un centre de transport animé reliant la planète au monde extérieur.
- Chan Amusement Park : Un complexe construit sur ordre de Prince Chan, dont trois roues géantes Ferris.
- Le palais du prince Chan : la résidence du souverain. Les chambres intérieures comprennent un jardin entouré de murs en verre et une salle du trône. La zone extérieure du palais est décorée de statues de dragon et mène à une pagode.
