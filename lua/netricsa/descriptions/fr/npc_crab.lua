CRAB DU ZENOZOIK


CLASSE:      Crabe
MÉTABOLISME: Arthropodes, xénomorphe
PERCEPTION: Arthropodes
TAILLE:       ~1,3 pi
ENDURANCE:  Faible
HOSTILITÉ:  Moyenne
ARMES:    Projectiles organiques (touffes de biomasse éjectées ou scindées minéralisées)
RÉCOMPENSE:     25 FC
MENACE:     Faible

DESCRIPTION:

Un arthropodes côtier qui habite les plans d'eau de Zenozoik, les lacs et les plages. Il a une carapace bleue et des membres rouge vif. Il est territorial, attaquant toute créature qu'il perçoit comme une menace avec des projectiles organiques. Son attaque consiste à éjecter une substance visqueuse avec suffisamment de force pour causer des dommages à portée moyenne. Ils ne sont pas particulièrement mobiles au combat, préférant tirer d'une seule position. On les trouve souvent en groupes de 2-4, ce qui peut être problématique sur des sentiers étroits près de l'eau.

CONSEILS:

- Éviter l'acide corrosif répandu par les crabes.
- Une arbalète ou une arme à portée est efficace contre eux. Les coups de pied sont utiles dans le combat rapproché.
