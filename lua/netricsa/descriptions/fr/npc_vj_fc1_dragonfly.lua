DRAGUE DU KRIEGER ARCHIPELAGO


CLASSE:      Volée
MÉTABOLISME: Insecte, prédateur
PERCEPTION: Insecte prédateur
TAILLE:       0,13 ft
ENDURANCE:  Faible
HOSTILITÉ:  Aucune
ARMES:    Aucune
RÉCOMPENSE:     1 FC
MENACE:     Aucune

DESCRIPTION:

Insecte volant prédateur, souvent trouvé près des plans d'eau et dans les espaces ouverts de l'archipel. Il se distingue par sa grande maniabilité et sa vitesse de vol. Il peut planer dans l'air et changer brusquement de direction. Il ne représente aucune menace. Sa présence ajoute vivacité et réalisme à l'atmosphère tropicale, surtout aux jours ensoleillés près de l'eau.

CONSEILS:

- Pas un ennemi ou une ressource. Il est inutile d'attaquer.