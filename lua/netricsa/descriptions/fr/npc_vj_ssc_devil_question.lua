UGH-ZAN "?", L'AUTEUR


CLASSE:      Ugh-Zan "?", le Pitiful Sorcier
MÉTABOLISME: Expérience synthétique-organique
PERCEPTION: Clé hybride Ug-Zan III
TAILLE:       150 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Extrême
ARMES:    Des fusées faibles, des renforts, de la lévitation
RÉCOMPENSE:     698000 FC
MENACE:     Moyenne

DESCRIPTION:

Ugh-Zan "?", le Pitiful Sorcerer, est une abomination grise, tordue à quatre bras né d'une expérience de clonage ratée de la légendaire Ugh-Zan III. Quand il n'y avait pas encore de candidats pour Ugh-zan. Lorsque les scientifiques de Mental ont tenté de reproduire l'ADN du grand seigneur de guerre, quelque chose s'est terriblement mal passé - le résultat a été un être mal formé, instable avec une puissance risible et une amertume sans fin. Et comme Mental ne savait pas comment l'appeler, il lui a donné un surnom en l'honneur de sa forme corporelle "?".

En raison de sa force pathétique et de son incapacité à se régénérer, Mental l'a dépouillé de tout honneur et l'a scellé dans une capsule d'exposition au Musée d'Ugh-Zans, une exposition vivante d'échec. Pourtant, après des siècles d'humiliation, le Pitiful Sorcer a échappé à son confinement, alimenté par la haine et la folie.

Or, obsédé par la vengeance, il cherche à détruire "Sérieux" Sam Stone, celui qui regardait une fois se moquer de sa prison de verre.

Malgré sa faiblesse, Ugh-Zan "? " n'est pas inoffensif - il peut flotter, libérer des volley de faibles fusées, et appeler de petits renforts dans des tentatives désespérées de prouver sa valeur à son maître longtemps oublié.

CONSEILS:

- Ses fusées sont faibles mais imprévisibles.
- Evitez d'être entouré par ses minions.
- Ne sous-estime pas sa rage, il peut se battre avec une férocité surprenante.
