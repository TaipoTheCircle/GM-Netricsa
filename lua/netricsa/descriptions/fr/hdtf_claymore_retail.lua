M18A1 MINE CLAYMORE ANTI-PERSONNEL


ARME: M18A1 Claymore (mine antipersonnel directionnelle)
MUNITIONS:   Charge C-4 avec 700 billes en acier
CADENCE DE TIR:    Dispositif à usage unique
POIDS: 1,6 kg

DESCRIPTION:

Une mine anti-personnel dirigée conçue par les États-Unis a été développée dans les années 1950 et largement utilisée pour la défense du périmètre et les embuscades. Lors de la détonation, la charge projette ~700 boules d'acier vers l'avant, produisant un motif de feuille-comme des fragments mortels-semblant plus à un coup de feu dense que la fragmentation aléatoire. L'appareil est déployé incurvé vers l'approche ennemie attendue et utilise un simple cadre d'observation pour viser; le boîtier est célèbrement marqué « FRONT TOWARD ENEMY ».

REMARQUES:

- Efficacité: env. 60° arc et efficace jusqu'à ~50 m; létalité la plus élevée à proximité (probabilité de blessure notable à ~5-15 m, avec des blessures possibles plus loin).
- Distances de sécurité: US FM 20-32 prescrit des lignes directrices de sécurité (exemple de distances de sécurité: 250 m vers l'avant pour les forces amicales, 100 m vers les côtés/arrière - utilisation lors de l'emboutissage).
- Limites : à usage unique, risque pour les non-combattants dans les zones peuplées, il faut placer soigneusement, camoufler et calculer le secteur.