CHUM-TOAD DE XEN


CLASSE:      Crapaud
MÉTABOLISME: Créature amphibie à base de Xen
PERCEPTION: Xen Amphibien
TAILLE:       ~1 pi de long, squat et corps rond
ENDURANCE:  Faible
HOSTILITÉ:  Faible (essentiellement passif)
ARMES:    Faible morsure, peut sauter de courtes distances quand surpris
RÉCOMPENSE:     50 FC
MENACE:     Minimal

DESCRIPTION:

Le Chum-Toad est une petite créature de type amphibiens Xen avec un corps rotund, Big Eye et ses membres stubby. Bien qu'une fois théorisé par les scientifiques de Black Mesa pour être lié aux cratères en raison de sa forme squat, le Chum-Toad est plus d'une curiosité inoffensive qu'un prédateur. Sa peau épaisse et caoutchouteuse et sa faible coloration lui permettent de survivre dans des cavernes humides de Xen et des enceintes de laboratoire.

Certains spécimens ont été introduits dans Black Mesa pour l'étude, où ils ont été observés en grande partie dociles. Contrairement à la plupart des espèces de Xen, les Chum-Toads ne sont pas conçus pour le combat - ce sont des mangeurs de fond et des charognards.

Fait intéressant, leur matériel génétique a été utilisé dans des expériences horribles (comme la création de Diablo ou Magenta Slaves), prouvant que même l'organisme Xen le plus faible peut être armé.

CONSEILS:

Ils ne menacent pas le personnel qualifié.
- Peut être ignoré dans la plupart des rencontres.
