FN P90 SUBMACHINE GUN


ARME:    FN P90 
5,7x28 mm
CADENCE DE TIR:       ~900 tours/min

DESCRIPTION:

Le FN P90 est une arme de défense personnelle compacte développée par la société belge FN Herstal à la fin des années 1980. Il a été créé pour les équipages de véhicules blindés et les unités arrière, où la grande capacité de chargeur et le bas recul sont importants.

Il utilise des cartouches spéciales 5,7x28 mm capables de pénétrer l'armure du corps moderne tout en conservant un faible recul. Grâce à son magazine haut de gamme de 50 tours et à sa conception bullup, l'arme reste courte mais très efficace au combat rapproché.

REMARQUES:

- Haute précision et faible recul - idéal pour le combat à portée étroite et moyenne.
- Pénétrat les armures de classe II et IIIA.
- Souvent utilisé par des forces spéciales à travers le monde.
- Conception ergonomique et contrôle ambidextre.