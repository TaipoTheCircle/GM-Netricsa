FUSION SUBMACHINE GUN


ARME: Sous-machine à impulsions de fusion
MUNITIONS:   Munitions balistiques de fusion / Munitions à impulsions thermiques
CADENCE DE TIR:    ~450 RPM

DESCRIPTION:

L'arme standard d'automates, largement utilisée par les unités d'assaut, les raideurs et les maraudeurs. Sa conception est caractérisée par une exécution brute, une mauvaise ergonomie et une précision médiocre, mais elle compense cela avec facilité de fabrication et une forte densité de feu.

L'arme est conçue pour de courtes explosions de tirs automatiques. Le mode principal d'incendie est un éclatement à cinq tours, suivi d'un bref retard de stabilisation. Un mauvais système de dissipation de chaleur rend la mitrailleuse Fusion Pulse sujette à la surchauffe lors d'une utilisation prolongée, réduisant ainsi sa fiabilité dans les engagements prolongés.

Malgré la puissance modérée des frappes individuelles, la densité du feu permet une suppression efficace des cibles et une pression constante sur le champ de bataille.

REMARQUES:

- Utilisé par les automates Assault, Raider et Marauder.
- Une rafale de 5 balles assure un incendie systématique.
- Surchauffe lors d'un tir prolongé dû à un mauvais refroidissement.
- Efficace à proximité et à moyenne distance.
- Une mauvaise ergonomie et une dispersion élevée réduisent la précision à de longues distances.
- Un rechargement (~4 secondes) est nécessaire après 30 coups.
- La faible pénétration des armures permet de combattre les cibles légèrement blindées.
