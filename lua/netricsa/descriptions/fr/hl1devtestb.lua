DEVTEST, RÉACTEUR


Cette carte d'essai jette le joueur directement dans la chambre centrale du réacteur. Par une grande fenêtre d'observation, le mystérieux homme avec la mallette peut être vu tranquillement regarder le chaos - se tenant à côté d'un Vortigaunt, comme si aucun d'eux ne remarque la bataille en cours.

A l'intérieur, les choses sont beaucoup moins calmes. Les Houndeyes envahissent les couloirs.

Et juste quand vous pensez que ce ne sont que des créatures Xen... l'armée fait son mouvement. S.E.C.U. les soldats attendent dans l'une des pièces, prêts à vous embusquer et à vous capturer.