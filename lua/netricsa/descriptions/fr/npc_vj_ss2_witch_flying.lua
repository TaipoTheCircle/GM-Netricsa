YAGODA LE WITCH DE MAGNOR


CLASSE:      Yagoda La sorcière
MÉTABOLISME: Mammifère, ancienne beauté
PERCEPTION: Sorcière
TAILLE:       4,6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Projectiles magiques
RÉCOMPENSE:     50 FC
MENACE:     Haut

DESCRIPTION:

Elle était essentiellement l'une des plus belles filles de la galaxie, mais quand elle et sa sœur étaient prêtes à participer aux concours de beauté de Mental, elles se sont transformées en sorcières laides. Après cette erreur, ils ont été facilement repêchés dans l'armée de Mental.

Yagoda est la sœur jumelle de Dynja ; ensemble, ce sont les sorcières les plus célèbres de la planète Magnor. Ils sont réputés pour leur nature sadique, leur maîtrise de leur art et leur affection pour l'alcool.

C'est une sorcière qui maîtrise le sort de Clone Miroir et l'utilise pour se reproduire. Voyant le potentiel en elle, Mental lui a offert une offre de vodka à vie en échange de ses services. Elle a accepté avec joie.

Yagoda vole de façon erratique, tentant d'encercler l'ennemi tout en pleuvant des attaques magiques.

CONSEILS:

- Elle est très maniable et difficile à frapper; pour la détruire, utiliser des armes à feu rapides ou viser soigneusement avec un fusil de sniper.
- Elle devrait être une cible prioritaire, car les tirs aériens peuvent être trop efficaces.
- Alors qu'un tir d'un fusil scié peut la tuer au combat, s'approcher d'elle est extrêmement difficile.
- Si vous êtes encerclé, essayez de bouger constamment à gauche et à droite tout en reculant pour essayer de briser son encerclement.
