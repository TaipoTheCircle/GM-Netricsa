HOUSK DU MINECRAFT SURVEILLANCE


CLASSE:      Souris
MÉTABOLISME: Desert Undead
PERCEPTION: La foule hostile
TAILLE:       6,2 pi
ENDURANCE:  Haut
HOSTILITÉ:  Haut
ARMES:    Mains, effet « faim »
RÉCOMPENSE:     160 FC
MENACE:     Moyenne

DESCRIPTION:

C'est un zombie qui a été exposé au soleil depuis trop longtemps et est maintenant immunisé contre le mal. Contrairement à leurs homologues réguliers, ces créatures ne brûlent pas dans le désert pendant la journée parce que leur peau séchée a depuis longtemps perdu sa sensibilité à la lumière ultraviolette. Visuellement, un Husk est 2 cm plus haut qu'un zombie normal, l'empêchant de serrer à travers les espaces à deux blocs.

Ils terrorisent les déserts, les savanes et d'autres biomes chauds. Ils errent en groupes de 2 à 4 individus lorsque les niveaux de lumière sont inférieurs à 7, exclusivement à l'extérieur.

La caractéristique principale de la Husk est son attaque "Hunger". S'il est les mains vides (pas d'armes), son toucher draine votre faim plus vite que le sable draine l'eau. La durée de l'effet dépend de la difficulté et de la difficulté régionale: de 7 à 30 secondes. Un bouclier bloque les dégâts et la faim, alors gardez-le prêt.

Sinon, le Husk se comporte comme un zombie normal : il suit les victimes, les villageois, les golems de fer et les œufs de tortue à une distance de 40 mètres. Il peut ramasser des objets, casser des portes et mettre des embuscades. Si un Husk entre dans l'eau, il commencera à trembler après 30 secondes, et après encore 15 secondes, il se transformera en un zombie normal. Ce processus est irréversible, même si vous le retirez en terre sèche. Ce zombie peut alors devenir un zombie noyé s'il continue à s'asseoir dans l'eau.

À la mort, une coquille laisse derrière elle une chair pourrie et parfois une carotte, une pomme de terre ou un lingot de fer. Une pomme de terre cuite tombe si la foule est brûlée. Si la coque était équipée, elle tombe avec une chance de 100%. À Halloween, ils peuvent frayer avec une citrouille sur la tête.

CONSEILS:

- Les défenses ne brûlent pas au soleil, ne s'attendent pas à ce qu'elles meurent le matin.
- Frapper un museau inflige toujours la faim ont toujours un approvisionnement en nourriture ou un bouclier.
- Chase une masse en eau-après 45 secondes, il se transformera en un zombie régulier, qui est plus facile à contrôler.
- Les hatchlings sont rapides et peuvent tout monter. Ne les laissez pas vous entourer.
- Pour une goutte garantie, utilisez l'enchantement "Loot III".
- Les défenses sont un peu plus grandes que les zombies-ils sont parfois coincés dans des lacunes où les morts-vivants peuvent passer.
