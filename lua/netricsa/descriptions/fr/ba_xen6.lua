LE MONDE FRONTIER DE XEN, LE TEMPS DE L'ÉTAT!


Voilà, Sam. Ça a marché.

Le portail s'est ouvert et, comme prévu, nous a rendus là où tout a commencé. Les terres de Xen. Paysages autochtones, chaos familier et sentiment que le monde est sur le point de se libérer complètement de ses amarres.

La guerre fait rage. De nombreuses troupes mentales. Beaucoup. Ils combattent les forces de Xen, pas vraiment distinguer qui est natif et qui est transitoire. L'air craque avec l'énergie, l'espace tremble, et la réalité essaie de ne pas regarder dans cette direction.

La voix de Rosenberg vient du portail. Il vous appelle "Calhoun". Il a tort. Mais honnêtement, ce n'est pas notre problème. Le principal est qu'il est là. Et le portail fonctionne. Pour l'instant.

La mauvaise nouvelle est autre chose. Le portail est instable. C'est déchirant, flippant, et agissant comme si c'était sur le point d'abandonner l'existence. Nous devons reculer. Oui, je sais. Ce n'est pas ton style. Tu préfères rester, arranger ça, finir ça, et seulement alors partir.

Mais il n'y a pas le choix. Si on n'avance pas maintenant, le passage pourrait se fermer. Pour toujours. Et Xen redeviendra une impasse, pas un couloir.

Où il mène est inconnu.

Quand il ferme est également inconnu.

Alors joue, Sam.

Retraite.

Parfois le meilleur coup est un pas en arrière.
