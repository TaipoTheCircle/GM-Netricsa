COMMON DE ZOMBIE AU CŒUR


CLASSE:      Cervelle Zombie, Fréquent
MÉTABOLISME: hôte humain + cratère commun parasitaire
PERCEPTION: Entité zombifiée
TAILLE:       6 pieds de haut
ENDURANCE:  moyenne
HOSTILITÉ:  haut (lent mais implacable)
ARMES:    attaque de melee ( griffes, balançoires), lutte
RÉCOMPENSE:     200 FC
MENACE:     modéré individuellement, élevé en groupes

DESCRIPTION:

La tête commune Zombie est une fusion tragique d'un hôte humain et d'une tête commune. Contrairement aux variantes de la Terre, le cramoisi commun s'enfonce en permanence dans le crâne de l'hôte, laissant le crâne de l'homme visible sous sa carapace extraterrestre. Une fois infecté, l'hôte perd tout libre arbitre et devient un prédateur lent et implacable.

Ces zombies Headcrab sont encombrants et faciles à éviter à distance, mais ils sont implacables et vont poursuivre leurs proies jusqu'à ce qu'ils soient assez près pour frapper. Le lien permanent du cabillaud fait de cette créature un horrifiant rappel de l'ingéniosité parasitaire de Xen - aucune pitié, aucune évasion, juste un conduit marchant et gémissant pour l'agression extraterrestre.

CONSEILS:

- Gardez la distance; les attaques à la mêlée sont dangereuses si elles se connectent.
- Les armes à feu fonctionnent bien en raison de leur mouvement lent.
- Ne sous-estimez pas les groupes - tout en ralentissant individuellement, ils peuvent coincer facilement les proies.