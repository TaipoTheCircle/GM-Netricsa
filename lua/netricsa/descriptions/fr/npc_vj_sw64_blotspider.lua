SPIDER BLOT DE LA CHAQUE BROADSIDE


CLASSE:      Araignée blottée
MÉTABOLISME: Étourne
PERCEPTION: Predator-Stalker
TAILLE:       19,7 pieds
ENDURANCE:  Infinite
HOSTILITÉ:  Absolue (présumablement)
ARMES: Dent
RÉCOMPENSE:     Vie ou mort
MENACE:     Très élevé

DESCRIPTION:

Blot était autrefois le premier personnage de Rex Broadside et le personnage le plus aimé, un petit lapin dans une casquette et des salopettes qui sont venus à la vie à l'écran et ont volé le cœur du public. Mais Rex, inexpérimenté, a signé un contrat qui renonçait aux droits de son personnage, et Blot a disparu de sa vie. Des années plus tard, après la mort de Rex, Broadside Animation a racheté les droits, mais pas pour faire des dessins animés.

Dans un laboratoire secret, Blot est devenu la base d'une expérience horrible pour créer des costumes de vie étoilés dans lesquels ils ont tenté d'implanter la conscience humaine afin de ressusciter Rex. La première tentative a été monstrueuse. La coquille brute et imparfaite déforme l'image du lapin mignon au-delà de la reconnaissance. Les restes d'un humain sont encore visibles à l'intérieur.

Comme Starling a subi d'autres transformations dans le monde déformé, une forme encore plus monstrueuse est apparue - le Blot-Spider. Son corps a acquis de longues jambes d'araignée cassantes, le transformant d'un chasseur qui se cache dans les coins en un prédateur rapide conçu pour terrifier sa proie.

Contrairement à d'autres formes, le Blot-Spider ne se cache ni ne se déguise. Il traque. Swiftly, sans relâche, forçant sa proie à fuir sans regarder en arrière.

CONSEILS:

- Cette forme de Blot ne se contente pas de chasser. Ne restez pas immobile.
- Ses jambes d'araignée lui permettent de bouger rapidement. Cherche une couverture où il ne peut pas te joindre.
- Contrairement à la Blot régulière, qui saute tout simplement des barils, cette forme n'a probablement pas de faiblesses. Seul vol.
