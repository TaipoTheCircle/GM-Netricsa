MITRAILLEUR ZOMBIE DU DÉSERT, COMMANDO


CLASSE:      Mitrailleur zombie du désert, Commando
MÉTABOLISME: Mort-vivant démonisé
PERCEPTION:  Soldat zombie
TAILLE:      3,5 m (11,5 pi)
ENDURANCE:   Moyenne
HOSTILITÉ:   Élevée
ARME:        Minigun
RÉCOMPENSE:  150 FC
MENACE:      Élevée

DESCRIPTION:

Après avoir constaté l'efficacité avec laquelle des zombies sous commandement démoniaque décimaient des hordes entières d'infanterie à l'aide de miniguns, Mental a décidé d'intégrer ces soldats à son arsenal.

Les Arachnoïdes étaient trop grands, encombrants et lents pour un déploiement de masse. Mental a donc noué une alliance avec le Seigneur des Enfers, qui lui a prêté plusieurs types de créatures, dont ces monstruosités.

Ces zombies sont d'anciens Marines ayant subi un rituel complexe de transformation démoniaque. Contrairement aux zombies classiques — simplement possédés par des démons —, les Commandos ont été entièrement remodelés pour devenir des hybrides mi-humains, mi-créatures des abysses.

Cette variante « Commando » se distingue par l'équipement conservé de son service dans les régions désertiques. Au lieu du t-shirt vert, il porte un pantalon à motif désertique et un casque allemand caractéristique, conçu pour les climats chauds et arides. Cet uniforme a partiellement subsisté après la transformation démoniaque, bien que sa fonction initiale n'ait plus aucune utilité.

Contrairement à la variante en t-shirt vert, ce Commando ne conserve pratiquement aucun élément de l'uniforme couvrant le haut de son corps. Cette variante désertique semble plus légère, mais cela ne l'empêche nullement de trimballer un minigun et de transformer les environs en un déluge ininterrompu de balles.

La meilleure façon de les affronter est de NE PAS se précipiter imprudemment dans leur ligne de mire.

CONSEILS:

- Mettez-vous à l'abri pour éviter leurs tirs ; vous pourriez être tenté par une approche « sans abri, en duel », mais cette tactique risque fort de vous laisser « exposé et mort ».
- Leur minigun manque de précision à longue portée ; plus vous êtes loin, mieux c'est.
- Les éliminer au fusil de précision à distance est une excellente stratégie.
- Une roquette en pleine tête règle le problème rapidement.