DESERT ZOMBIE MACHINE GUNNER, COMMANDO


CLASSE:      Desert Zombie Machine Gunner, Commando
MÉTABOLISME: Démonstration
PERCEPTION: Zombie Soldat
TAILLE:       11,5 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARME:     Minigune
RÉCOMPENSE:     150 FC
MENACE:     Haut

DESCRIPTION:

Après avoir vu à quel point les zombies dirigés par des démons ont décimé des hordes entières d'infanterie avec des mini-guns, Mental a décidé d'ajouter ces soldats à son arsenal.

Les arachnoïdes étaient trop grands, volumineux et lents pour être déployés en masse. Par conséquent, Mental a forgé une alliance avec le Seigneur de l'Enfer, qui lui a prêté plusieurs types de créatures, y compris ces monstruosités.

Ces zombies sont d'anciens Marines qui ont subi un rituel de transformation démoniaque complexe. Contrairement aux zombies standard – qui sont simplement possédés par les démons – les Commandos ont été complètement refaits, devenant un hybride de l'humain et de l'abîme-spawn.

Cette variante Commando se distingue par l'équipement retenu de son service dans les régions désertiques. Au lieu d'un T-shirt vert, il porte un pantalon pour le désert et un casque pour le désert allemand, conçu pour les climats chauds et arides. Cet uniforme a partiellement persisté après la transformation démoniaque, même si son but originel était depuis longtemps devenu hors de propos.

Contrairement à la variante du T-shirt vert, ce Commando ne conserve presque aucun élément de son uniforme du haut du corps. La variante du désert semble plus légère, mais cela ne l'empêche certainement pas de traîner autour d'un mini-gun et de transformer la région environnante en un solide flux de balles.

La meilleure façon de les traiter n'est PAS de se précipiter imprudemment dans leur ligne de feu.

CONSEILS:

- Couvrez-vous de leur feu; vous pourriez être tenté d'aller vers une approche « sans couverture, individuelle », mais l'utilisation de cette tactique est plus susceptible de vous laisser « exposé et mort »
- Leur minigun est inexact à long terme; plus vous êtes loin, mieux c'est.
- C'est une bonne façon de les manipuler.
- Une fusée à la tête résout le problème rapidement.
