BÉRETTA M9 PISTOL


ARME: Beretta M9 Pistol
MUNITIONS:   Parabellum 9x19mm
CADENCE DE TIR:    ~40 tours/min
POIDS: ~0,95 kg

DESCRIPTION:

La Beretta M9 est la version militaire américaine du pistolet italien Beretta 92F. En 1985, il remporte la compétition XM9 pour un nouveau pistolet militaire 9mm, remplaçant le légendaire M1911A1. En 1990, le M9 a été officiellement adopté par les forces armées américaines et a été utilisé dans les opérations militaires américaines à travers le monde.

Le pistolet tire la cartouche de Parabellum 9x19mm et utilise un chargeur de 15 tours. Le M9 se distingue par sa slide ouverte, sa bonne précision et sa grande fiabilité. Depuis 2017, l'armée américaine a progressivement remplacé le M9 par le M17 et le M18.

REMARQUES:

- A gagné la compétition pour remplacer le M1911A1 et est devenu le pistolet principal de l'armée américaine.
- Bien adapté pour un tir précis à courte et moyenne portée.
- Le boulon ouvert distinctif fait du Beretta M9 l'un des modèles Beretta les plus reconnaissables.
