ARTHUR


CLASSE:      Onan Arthur
MÉTABOLISME: Mammifère
PERCEPTION: Un guerrier intelligent et fort
TAILLE:       8,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Conditionnel
ARMES:    Axe magique antique "Excalibur"
RÉCOMPENSE:     400 FC
MENACE:     Haut

DESCRIPTION:

Un membre du clan des bibliothécaires Onan, une rare combinaison de détenteurs de connaissances et de guerriers. Contrairement à beaucoup de ses semblables, il n'était pas idiot et a fait preuve d'intelligence et de force dès sa jeunesse. Malgré son apparence menaçante, Arthur est connu comme l'un des héros les plus gentils et aide souvent ceux qui ont des problèmes.

Le point culminant de son voyage a été la bataille au sommet du volcan, où il a vaincu le Grand Lava Golem et saisi l'Ancienne Axe Magique - un artefact d'incroyable puissance destructrice, qui dans ses mains sert non pour la destruction, mais pour la défense. Cette hache est considérée comme l'un des artefacts les plus dangereux, mais Arthur l'utilise avec sagesse.

Onan Arthur a combattu les sorcières, mais lors d'un choc, il a été forcé de se retirer pour sauver son propre cul. Plus tard, il battit les Romains et Sanya, prouvant une fois de plus que sa férocité et sa bonté vont de pair avec sa volonté de défendre son monde. Sa victoire sur le golem, les Romains et Sanya en firent une légende parmi les bibliothécaires Onan.

CONSEILS:

- Arthur n'attaque pas d'abord ceux qui ne posent aucune menace.
- Si vous voyez Arthur se retirer, ne présumez pas que c'est de la lâcheté. Il pourrait sauver quelqu'un ou son propre cul.
- N'essaie pas de voler sa hache. C'est inutile et mortel.
- Si vous avez des ennuis et qu'Arthur est à vos côtés, considérez-vous chanceux.