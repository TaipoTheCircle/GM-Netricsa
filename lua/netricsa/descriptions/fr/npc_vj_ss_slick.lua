DESCRIPTION:

A typical teenager in bright clothes: un sweat à capuche orange, un jean bleu, des baskets blanches et une casquette en arrière. Il a les cheveux foncés, les yeux foncés et un sourire distinctif - il apprécie clairement chaque course.

HE est un artiste graffiti qui, avec son ami Tricky et d'autres enfants, décore des voitures de métro dans des villes du monde entier. Son thème préféré est les pandas, qui apparaissent souvent dans ses dessins.

Son but est de fuir. Pour échapper à l'inspecteur et à son chien, qui maintiennent l'ordre sur le chemin de fer. Pour un temps infini. Sur les rails, sur les toits des trains, à travers les tunnels et les quais.

En course, Jake utilise un skateboard pour la vitesse, un jetpack pour le vol et un aimant pour attirer les pièces. Ses principaux ennemis approchent des trains et des impasses.

