M1A1 ABRAMS


CLASSE:      M1A1 Abrams
MÉTABOLISME: Mécanique, pilote humain
PERCEPTION: Véhicule blindé lourd
TAILLE:       ~32 pieds
ENDURANCE:  Extrêmement élevé
HOSTILITÉ:  Extrême
ARMES:    Lance-roquettes 
RÉCOMPENSE:     8000 FC
MENACE:     Catastrophes

DESCRIPTION:

Le M1A1 Abrams est un char lourdement armé déployé par les forces de l'U.S.E.C., modifié pour délivrer des barrages de roquettes dévastateurs. Son armure renforcée protège contre la plupart des armes légères et des explosifs légers, tandis que les roquettes peuvent détruire les véhicules, les structures et les groupes d'infanterie. Son avance lente mais délibérée lui permet de contrôler les zones clés, d'aplatir les obstacles et de dominer le combat au sol.

CONSEILS:

- Gardez toujours la couverture; les fusées ont un large rayon de tir et peuvent frapper à distance.
- Utilisez des armes à haute explosion ou à armure pour l'endommager.
- Les manœuvres d'assaut sont essentielles - les assauts frontaux sont quasi suicidaires.
- Éviter les terrains ouverts où le char peut tirer librement des roquettes.
