DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme de Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan", ils reçoivent des modificateurs de feu et de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Damir Perovic est l'un des quatre piliers sur lesquels repose tout l'empire Croteam. Son crâne surdimensionné contient non seulement le cerveau du développeur, mais aussi l'idée même, le germe du studio, qui a surgi en 1989 dans le cadre d'une équipe d'école faisant le 2D side-scroller "Kids". Avec trois camarades de classe, il est passé des étudiants de l'école Nikola Tesla de Zagreb aux co-fondateurs de l'un des studios de jeux les plus emblématiques de Croatie.

Alors que les autres co-fondateurs sont devenus les visages publics de la société, Damir est resté dans l'ombre, servant d'artiste de soutien et programmeur supplémentaire dans les premières étapes. Sa contribution est fondamentale : il était là quand Croteam est né dans un appartement ordinaire, établissant les principes de camaraderie et de passion qui ont permis au studio de survivre des décennies et de créer les mondes de Serious Sam et The Talos Principe. Sa présence parmi les Croteamers est un hommage à leurs origines mêmes, au génie tranquille dont le travail dans l'ombre a jeté les bases de tout le chaos bruyant et fou qui a suivi.

Il était une fois vivant, mais après que vous l'ayez tué dans le Temple de Hatshepsut, il est ressuscité d'entre les morts - devenant un zombie démoniaque.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager le chemin.
- Sur la difficulté "Je suis Ugh-Zan", les éliminer à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.