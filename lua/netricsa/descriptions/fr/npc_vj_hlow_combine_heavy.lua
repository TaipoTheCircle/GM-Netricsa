SURVEILLANCE DE LA COMBINE


CLASSE:      Combiner Overwatch Gunner prison lourde
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner l'unité de lutte contre l'incendie
TAILLE:       5,9 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    Combiner Minigun
RÉCOMPENSE:     1200 FC
MENACE:     Critique

DESCRIPTION:

Le Combine Overwatch Heavy Prison Gunner est un point d'incendie à pied, construit à partir de la base de personnel de Nova Prospekt, mais conçu pour beaucoup plus que des murs de prison. Son armure est multicouche, pondérée et rembourrée avec des amortisseurs, ce qui lui permet de tirer continuellement sans perdre de stabilité.

À l'extérieur, il ressemble à un garde de prison standard Nova Prospekt : visières jaunes, armure distinctive. Cependant, il est immédiatement abandonné par de nombreux éléments d'identification jaune, avertissant les alliés qu'ils ne traitent pas d'un garde, mais d'un dispositif de suppression.

Ces soldats sont utilisés pour réprimer les émeutes, protéger les points stratégiques, escorter les convois et attaquer les positions fortifiées.

CONSEILS:

- Ne jamais entrer dans une ligne de feu ouverte - le mini-gun est impitoyable.
- Utilisez des explosifs ou des armes lourdes.