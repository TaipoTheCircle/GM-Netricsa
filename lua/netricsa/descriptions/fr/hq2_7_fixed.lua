HALF-QUAKE 2, PARCOUR D'INSANITÉ


Sam, on est là ! Un autre cadeau des sadiques. Parkour. Il suffit de sauter sur les cubes et d'atteindre le panneau avec ce stupide ">) visage. Ça semble simple, non ? Bien sûr !

Mes détecteurs indiquent que ces cubes ne sont pas seulement des cubes. Ils ont clairement une sorte de tour. Peut-être qu'ils disparaissent quand tu marches sur eux. Peut-être qu'ils explosent. Ou peut-être qu'ils veulent que tu tombes.

Tu sais, je ne serais pas surpris qu'ils t'en veuillent d'avoir marché dessus. Les sadistes aiment ajouter du caractère même à leurs plateformes.

Sam, il est temps de montrer à ces cubes qui sont le roi du parkour ! Atteindre le panneau «>» sur le plancher. Il active notre chemin vers l'avant.

And remember: ne fais pas confiance aux cubes ! Ils sont clairement en ligue avec les sadiques. Et ils veulent que tu tombes. Mais vous êtes Sam ! Tu es tombé dans des endroits pires... fous !

Allez, saute ! Et ne regarde pas en bas, ce n'est pas bon ! Je peux déjà voir quelque chose de nouveau qui nous attend après ce panel... et je suis sûr que ce sera amusant !
