HALF-QUAKE 2, PARKOUR DE LA FOLIE


Eh bien, Sam, nous sommes là ! Un autre "cadeau" des sadiques. Parkour. Sautez simplement sur les cubes et atteignez le panneau avec ce stupide visage ">)". Cela semble simple, non ? Bien sûr que non!

Mes capteurs indiquent que ces cubes ne sont pas de simples cubes. Ils ont clairement une sorte de truc. Peut-être qu'ils disparaissent lorsque vous marchez dessus. Peut-être qu'ils explosent. Ou peut-être qu’ils veulent juste que tu tombes et que tu t’écrases.

Vous savez, je ne serais pas surpris s'ils se fâchent contre vous parce que vous leur avez marché dessus. Les sadiques aiment ajouter du caractère même à leurs plateformes.

Alors, Sam, il est temps de montrer à ces cubes qui est le roi du parkour ! Atteignez le panneau ">)" au sol. Cela active notre chemin vers l’avant.

Et rappelez-vous : ne faites pas confiance aux cubes ! Ils sont clairement de mèche avec les sadiques. Et ils veulent que tu tombes. Mais tu es Sam ! Vous êtes tombé dans des endroits pires... fous !

Allez, saute ! Et ne baissez pas les yeux, ce n'est pas bon ! Je vois déjà quelque chose de nouveau qui nous attend après ce panel... et je suis sûr que ce sera amusant !