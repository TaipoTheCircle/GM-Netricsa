VENDU COMBINE OCMU


CLASSE:      Combiner le soldat OCMU
MÉTABOLISME: Améliorations humaines et biomécaniques améliorées
PERCEPTION: Combiner l'unité d'agression médicale
HEIGHT:     5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    SMG1 (MP7), Grenades
RÉCOMPENSE:     500 FC
MENACE:     Haut

DESCRIPTION:

Ce sont des soldats de l'unité de gestion de crise. Il s'agit d'une unité mixte spécialisée créée pour répondre à des situations de crise particulièrement dangereuses où les soldats réguliers Overwatch sont insuffisants. Leurs missions comprennent la suppression de grandes poches de résistance, le nettoyage des zones contaminées ou instables, et l'aide d'autres unités Combiner directement sur les lignes de front.

Contrairement aux soldats de l'Overwatch standard, les soldats de l'OCMU combinent les fonctions d'infanterie d'assaut et les médecins de combat. Leur équipement est conçu pour un déploiement prolongé dans les zones de combat, et leur entraînement leur permet de changer rapidement de rôle selon la situation : engager l'ennemi, couvrir la retraite des alliés, ou fournir des soins médicaux aux soldats blessés.

Les soldats de l'OCMU utilisent une sélection limitée d'armes. Leur arme principale est le SMG1 (MP7), capable de déclencher un tir automatique concentré à courte et moyenne portée. Ils utilisent des grenades pour nettoyer les pièces, détruire la couverture et engager des groupes d'ennemis.

Malgré leur spécialisation médicale, il serait extrêmement dangereux de considérer les soldats de l'OCMU comme inoffensifs. Ils sont bien entraînés au combat étroit et opèrent de manière organisée, en essayant de rester dans un groupe. Si un soldat prend feu, les autres tentent immédiatement de supprimer le tireur avec des grenades et des tirs automatiques, tout en couvrant le soldat blessé.

Les soldats de l'OCMU sont particulièrement susceptibles d'apparaître dans des situations où la situation s'aggrave. Leur arrivée signifie généralement que le Combine n'essaie plus simplement de maintenir le territoire, mais passe à la suppression complète des crises.

CONSEILS:

- Ne laissez pas les OCMU prendre pied à l'intérieur : leurs grenades les rendent particulièrement dangereux dans les espaces restreints.
- Dans les zones ouvertes, le SMG1 est moins efficace, alors utilisez votre gamme.
- Essayez de désactiver rapidement plusieurs unités pour qu'elles ne puissent pas se couvrir.
- Si les OCMU sont accompagnés par d'autres unités Combiner, éliminer d'abord les tireurs les plus dangereux et le support lourd.
- Ne les sous-estimez pas en raison de leur spécialisation médicale : ils sont toujours des unités de combat Overwatch à part entière.
