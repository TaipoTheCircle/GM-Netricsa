COMBINEZ LE SOLDAT OCMU


CLASSE : Combiner le soldat OCMU
MÉTABOLISME : Améliorations humaines et biomécaniques améliorées
PERCEPTION : Combinez l'unité Medic-Assault
HAUTEUR : 5,9 pieds
ENDURANCE : Élevée
HOSTILITÉ : Extrême
ARMES : SMG1 (MP7), Grenades
RÉCOMPENSE : 500 FC
MENACE : Élevée

DESCRIPTIF :

Il s’agit de soldats de l’« Overwatch Crisis Management Unit ». Il s'agit d'une unité spécialisée du Combine créée pour répondre à des situations de crise particulièrement dangereuses où les soldats réguliers d'Overwatch sont insuffisants. Leurs missions consistent notamment à supprimer de larges poches de résistance, à nettoyer les zones contaminées ou instables et à aider d'autres unités du Combine directement sur les lignes de front.

Contrairement aux soldats Overwatch standard, les soldats OCMU combinent les fonctions d’infanterie d’assaut et de médecins de combat. Leur équipement est conçu pour un déploiement étendu dans les zones de combat, et leur formation leur permet de changer rapidement de rôle en fonction de la situation : engager l'ennemi, couvrir la retraite des alliés ou prodiguer des soins médicaux aux soldats blessés.

Les soldats de l'OCMU utilisent une sélection limitée d'armes. Leur arme principale est le SMG1 (MP7), capable de délivrer un tir automatique concentré à courte et moyenne portée. Ils utilisent largement les grenades pour nettoyer les pièces, détruire les abris et engager des groupes d'ennemis.

Malgré leur spécialisation médicale, il serait extrêmement dangereux de considérer les soldats de l’OCMU comme inoffensifs. Ils sont bien entraînés au combat rapproché et opèrent de manière organisée, en essayant de rester en groupe. Si un soldat est sous le feu des tirs, les autres tentent immédiatement de réprimer le tireur avec des grenades et des tirs automatiques, tout en couvrant simultanément le soldat blessé.

Les soldats de l’OCMU sont particulièrement susceptibles d’apparaître dans des situations où la situation devient incontrôlable. Leur arrivée signifie généralement que le Combine n’essaie plus simplement de conserver un territoire, mais s’oriente vers une véritable suppression de crise.

CONSEILS :

- Ne laissez pas les OCMU prendre pied à l'intérieur : leurs grenades les rendent particulièrement dangereuses dans les espaces restreints.
- Dans les zones ouvertes, le SMG1 est moins efficace, utilisez donc votre portée.
- Essayez de désactiver rapidement plusieurs unités afin qu'elles ne puissent pas se couvrir.
- Si les OCMU sont accompagnées par d'autres unités du Combine, éliminez en premier les tireurs d'élite et les supports lourds les plus dangereux.
- Ne les sous-estimez pas en raison de leur spécialisation médicale : ce sont toujours des unités de combat Overwatch à part entière.