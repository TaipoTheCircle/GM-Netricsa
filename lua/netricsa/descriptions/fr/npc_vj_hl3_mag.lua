M. ARNE MAGNUSSON


CLASSE:      Dr Arne Magnusson
MÉTABOLISME: Humain, Homme
PERCEPTION: Scientifique humain / Commandant de la résistance
TAILLE:       6 pieds
ENDURANCE:  Moyenne (plus ancienne, mais plus dure)
HOSTILITÉ:  Faible (pour les alliés), Haut (pour combiner)
ARMES:    Magnusson Device, langue forte
RÉCOMPENSE:     1000 FC
MENACE:     Moyen (directement), Haut (en tant que stratège et inventeur)

DESCRIPTION:

Le Dr Arne Magnusson est l'un des principaux dirigeants de la Résistance, surveillant les opérations de la base de la Forêt Blanche. Gruff, impatient, et souvent critique, il a peu de tolérance pour les erreurs - mais sous son extérieur abrasif réside un dévouement inébranlable à la survie de l'humanité.

Vétéran de Black Mesa, Magnusson est un survivant de la Cascade Résonance et porte à la fois les cicatrices et la connaissance de ce désastre. Son génie d'ingénierie a donné naissance au Magnusson Device, une arme explosive expérimentale conçue spécifiquement pour détruire Combine Striders. Malgré sa nature peu conventionnelle, l'appareil s'est révélé être l'un des plus grands outils de la Résistance pour faire tourner la marée de la bataille.

Bien qu'il ne soit pas un soldat de première ligne, Magnusson commande le respect et la peur dans une mesure égale parmi les rangs de la Résistance. Son éclat n'est égalé que par son tempérament court, et pourtant dans des moments critiques, son leadership est indispensable.

CONSEILS:

- Ses appareils Magnusson sont la clé pour détruire Striders-utilisez-les sagement.
- Son écorce est pire que sa morsure-ignorer les cris, suivre le plan.
- Gardez-le vivant. Sa connaissance du Combiné est irremplaçable.
- Soyez prêt à critiquer constamment le micro-ondes de Black Mesa.
