TRIP DE JOUR, HEURE D'ALLER


Sam, nous sommes incroyablement chanceux d'être ici. Ce train est une fin divine, même s'il est accroché, comme le disent les ingénieurs locaux, « par des cordes et des prières ». Allons voir ce qu'il y a là.

Le train est tout. Il tire un tas de voitures: trois voitures compartimentées, six sièges réservés, et une vide, pour la variété. À l'intérieur, vous pouvez ouvrir les portes, allumer les lumières, et même grimper sur les toits inclus.

Le levier principal dans la cabine du conducteur est l'interrupteur d'arrêt/démarrage, donc vous décidez quand aller et quand sortir et explorer les environs. Au fait, il y a plus d'un itinéraire : il y a trois boucles interchangeables, donc le paysage va changer.

Nous parcourons la campagne jusqu'à la ville. Et ainsi de suite, sans fin. La boucle est fermée, donc vous pouvez vous détendre et regarder par la fenêtre.

Features:

Le train est plein de boutons pour allumer et désactiver tout. Vous aimez appuyer sur les boutons ? C'est l'endroit pour toi.

Il y a des secrets. Ils ne diraient pas où exactement, mais il y a certainement des endroits cachés.

Montez dans un compartiment ou une voiture-lit, tirez le levier d'arrêt chaque fois que vous voulez regarder autour, et n'oubliez pas les boutons. Si la technologie commence à planter, soyez juste reconnaissant que nous voyageons même. Allons-y, Sam !
