M. ROSENBERG


CLASSE:      Dr Rosenberg
MÉTABOLISME: Humain, Homme
PERCEPTION: Chercheur principal, Division de physique théorique
TAILLE:       6 pieds
ENDURANCE:  Faible 
HOSTILITÉ:  Aucune
ARMES:    Aucune
RÉCOMPENSE:     300 FC 
MENACE:     Négligeable

DESCRIPTION:

Le Dr Rosenberg est un scientifique principal de Black Mesa et l'un des esprits les plus expérimentés travaillant dans l'établissement. Reconnu par ses cheveux blancs et son comportement calme, Rosenberg se spécialise dans la théorie de la téléportation et la recherche interdimensionnelle, lui donnant un rôle crucial dans la compréhension de la technologie Xen et des phénomènes de résonance.

Lors de l'incident de Black Mesa, Rosenberg s'est révélé être l'un des rares scientifiques capables de rester composé sous une pression catastrophique. Sa priorité devint la survie et l'évacuation, tant pour lui-même que pour ses collègues. Malgré son manque de capacités de combat, la connaissance des systèmes de téléportation et des protocoles d'évacuation de Rosenberg en fait un allié critique pour le personnel de sécurité et le personnel survivant.

Bien que fragile et non armé, la valeur de Rosenberg réside dans l'intellect et non dans le combat - sa survie assure que la connaissance la plus sensible de Black Mesa ne meurt pas avec l'incident.

CONSEILS:

- Je ne vois aucun problème.
