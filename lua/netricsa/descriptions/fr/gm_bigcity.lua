GRANDE VILLE URBAINE


Big city is exactly what its name suggests: une métropole étendue conçue pour le chaos. De larges avenues, des gratte-ciels imposants, des blocs industriels et des toits sans fin forment un environnement massif de bac à sable. Contrairement aux zones d'essai confinées de Construire ou le vide de l'herbe plate, Grande ville prospère sur la verticalité et l'échelle.

Key features include:

Centre-ville avec gratte-ciel et places ouvertes, parfait pour les chasses sur le toit et les nids de sniper.

Zones industrielles avec entrepôts, tunnels et passages souterrains cachés.

Routes et ponts pour les essais de véhicules et les batailles à grande échelle.

Toits et intérieurs qui permettent une traversée créative et des embuscades.

C'est la ville qui ne dort jamais, mais qui n'a jamais eu de véritables citoyens. Les rues vides résonnent avec le son de vos propres pas, laissant l'impression troublante.