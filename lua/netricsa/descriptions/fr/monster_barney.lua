OFFICIER DE SÉCURITÉ DU MESA BLACK


CLASSE:      Agent de sécurité Black Mesa
MÉTABOLISME: Homme, agent de sécurité, homme
PERCEPTION: Guerrier de sécurité de Mesa noir
TAILLE:       6 pieds de haut
ENDURANCE:  moyenne
HOSTILITÉ:  haut vers les intrus, amical vers le joueur
ARMES:    pistolet, fusil, complexe d'autorité
RÉCOMPENSE:     1 FC (Il promet de la bière et ne la rend pas)
MENACE:     modérée individuellement, élevée si la sauvegarde arrive

DESCRIPTION:

Barney est le gardien de sécurité de Black Mesa, un homme loyal qui connaît les couloirs mieux que quiconque. Équipé d'un pistolet, parfois d'un fusil de chasse et d'un sens obstiné du devoir, il patrouille les couloirs et tente d'empêcher l'installation de sombrer dans le chaos total.

Ami du joueur, Barney peut combattre les extraterrestres, sauver les scientifiques en détresse. Son jeu de compétences est étonnamment polyvalent, bien qu'il soit encore humain et paniquera si une tente ou Gargantua apparaît. Il a une capacité étrange à apparaître juste à temps pour sauver le joueur d'une grêle de Hornets ou d'un voyou Alien Grunt.

CONSEILS:

- Restez près de Barney, il peut aider dans les combats.
- Ne comptez pas sur lui comme un tank - il est courageux, mais humain.
- Écoutez attentivement leurs cris - ils pourraient indiquer un danger à proximité.