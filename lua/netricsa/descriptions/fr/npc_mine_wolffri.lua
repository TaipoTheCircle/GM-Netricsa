DE L'EXERCICE MINECRAFT


CLASSE:      Loup
MÉTABOLISME: Mammifère chaud
PERCEPTION: Animaux neutres / Tamables
TAILLE:       2,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Modéré
ARMES:    Fangs
RÉCOMPENSE:     60 FC
MENACE:     Moyenne

DESCRIPTION:

Les loups sont des prédateurs sauvages du Minecraft Overworld, habitant des forêts, de la taïga et des biomes enneigés. Dans leur état neutre, ils n'attaquent pas, mais deviennent extrêmement agressifs s'ils sont provoqués ou attaqués par un autre loup.

Un loup apprivoisé devient un fidèle compagnon de combat. Il suit son maître, les protège au combat et attaque des cibles frappées par son maître.

La santé d'un loup peut être facilement déterminée par la position de sa queue : plus la queue est basse, plus elle est gravement blessée.

CONSEILS:

- Utilisez les os pour apprivoiser.
- Nourrir la viande de loup pour la guérison et la reproduction.
- Les loups sont particulièrement efficaces contre les squelettes et les zombies, mais sont vulnérables à la lave et aux explosions.