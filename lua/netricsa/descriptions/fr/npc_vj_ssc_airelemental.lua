KUKULKÁN, LE DIEU VIN


CLASSE:      Kukulkán, Le Dieu du Vent
MÉTABOLISME: inorganique
PERCEPTION: ancienne divinité
TAILLE:       variable
ENDURANCE:  extrême
HOSTILITÉ:  faible
ARMES:    tornades, boules de tornade
RÉCOMPENSE:     500000 FC
MENACE:     élevé

DESCRIPTION:

Une ancienne divinité maya, Kukulkán n'a rien à voir avec Mental. En fait, c'est un bon dieu. On pense que Kukulkán contrôle le vent donc il est très favorisé par les Mayas. Cependant, il est aussi le gardien d'un portail que les Siriens ont laissé, et il faut dire un portail très sérieux! Kukulkán ne peut pas être détruit - mais il est un joueur équitable - quand défait, il s'évaporera dans l'air mince et ouvrira le portail pour le vainqueur comme un signe de respect. Il est vraiment un dieu de toutes les manières possibles.

CONSEILS:

- Évitez les torsions ou vous serez plus près du ciel en un rien de temps.
- Kukulkán est très résistant aux balles, utilisez plutôt des armes explosives.
