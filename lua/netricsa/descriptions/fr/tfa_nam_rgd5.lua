GRENADE DE FRAGMENTATION À LA MAIN RGD-5


ARME: RGD-5 Grenade de fragmentation des mains
MUNITIONS:   Une Grenade
CADENCE DE TIR:    Un lancer par minute

DESCRIPTION:

Une grenade à fragmentation de la main de type offensive soviétique, développée et adoptée pour le service en 1954. Il est conçu pour neutraliser le personnel ennemi par l'utilisation de fragments d'enveloppes et d'une vague d'explosion. Il dispose d'un corps compact de forme ovale en acier fin, composé de deux parties principales. Par rapport au RG-42 précédent, il est plus léger et a une forme plus épurée.

Il se compose d'un boîtier en métal, d'une charge explosive et d'une fumée à retardement. Une grenade entièrement assemblée pèse environ 310 grammes. TNT est utilisé comme charge explosive. Au fil des ans, on a utilisé diverses fumées, en particulier l'UZRG, l'UZRGM et l'UZRGM-2. En raison de son faible poids et de ses dimensions compactes, il est devenu largement déployé au sein de l'armée soviétique et des forces armées de plusieurs autres nations.

REMARQUES:

- Different de la grenade F-1 en ayant un boîtier plus léger et moins de poids global.
- A été utilisé par l'armée soviétique et continue d'être rencontré dans les conflits armés.
- Adopté en 1954.
- Remplacé la grenade RG-42.
- Classé comme une grenade offensive.
