SCORPION MEILLEUR DEMON, VENDU DE LA PLANTE TROPIQUE


CLASSE:       Scorpion du démon des bêtes, Soldat
MÉTABOLISME:  Exobiologique, Arthropodes
PERCEPTION:  Scorpion de combat
TAILLE:        10 pieds
ENDURANCE:   Haut
HOSTILITÉ:   Extrême
ARMES:     Scorpion-comme la queue pique
RÉCOMPENSE:      6000 FC
MENACE:      Haut

DESCRIPTION:

Soldat Démon de la Bête - Jeunes spécimens de créatures agressives des planètes tropicales, autrefois indépendantes, mais personnellement attirées par Solgar, l'homme droit de Mental. Depuis, ils sont devenus une partie à part entière de la Horde, servant de créatures d'assaut à la mêlée.

L'apparence du scorpion ressemble à un arachnoïde qui a décidé de devenir un réservoir. La coquille lisse, vert brillant, le corps segmenté, trois paires de jambes, et la tête massive créent l'impression d'un bélier battant vivant. Au sommet de sa tête se trouve une barre verte ressemblant à un casque, serrée à la coquille. Deux paires d'yeux sont situées sur les côtés de la tête, offrant une excellente vision même en faible lumière. Dans le noir, les yeux brillent d'un vert sinistre.

Le casque améliore la protection de la tête et rend la créature particulièrement résistante au feu frontal.

La queue montante, rappelant les scorpions de type Terre, est utilisée pour les frappes puissantes.

Le Scorpion de Bête manque d'attaques variées et repose uniquement sur la vitesse, la pression et la force physique, cherchant à fermer la distance le plus rapidement possible.

CONSEILS:

- Il se précipite immédiatement vers la cible.
- Ne cache pas, ne recule pas, ne considère pas l'avenir.
- Les explosifs C4 sont la meilleure méthode de dialogue.
- Un scorpion est mortel au combat.
- Si le scorpion est déjà à proximité, tu as tout mal fait.