SWARM BUZZER


CLASSE:      Buzzer de swarm
MÉTABOLISME: Xénobiologique
PERCEPTION: Prédateur volant
TAILLE:       1,6 ft
ENDURANCE:  Très faible
HOSTILITÉ:  Haut
WEAPOON:    Sting venimeux, attaque aérienne
RÉCOMPENSE:     75 FC
MENACE:     Faible

DESCRIPTION:

Les buzzers sont de petits organismes volants de Swarm adaptés au harcelage et au harcèlement de grands adversaires. Individuellement, ils posent rarement une menace sérieuse, mais leur apparition signifie généralement le début de nouveaux problèmes.

Leur principale méthode de chasse est les attaques rapides d'en haut. En utilisant leur grande maniabilité, le Buzzer plonge brusquement vers sa cible, frappant avec son stinger venimeux, puis monte à nouveau. Leur petite taille en fait une cible difficile même pour les tireurs expérimentés.

Le venin Buzzer n'est pas particulièrement mortel, mais il peut causer de la douleur, une désorientation et une diminution de la concentration. C'est pourquoi ces créatures sont particulièrement dangereuses lors des rencontres avec d'autres membres du Swarm. Bien que la proie soit distrait par le ravageur volant, les grands prédateurs ont la possibilité de se refermer.

Les observations montrent que les Buzzers font rarement preuve de prudence et attaquent souvent des cibles beaucoup plus grandes qu'eux-mêmes. Apparemment, l'évolution a compensé leur manque d'instinct de conservation de soi avec la capacité de se reproduire rapidement.

CONSEILS:

- N'ignorez pas Buzzers, même quand vous combattez des adversaires plus dangereux.
- Utilisez des armes à fort taux de tir ou à visée automatique.
- Regarde l'air au-dessus de toi.
- Si vous entendez un bruit agaçant autour de vous, cela signifie que quelqu'un est déjà déterminé à ruiner votre journée.
