SURVEILLANCE DES COMBINES


CLASSE:      Combiner le bombardier Overwatch
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Soutenir l'incendie et la répression des incendies
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Très élevé
ARMES:    Launcheur de Grenade Triple-Shot Overwatch
RÉCOMPENSE:     700 FC
MENACE:     Haut

DESCRIPTION:

Le Combine Overwatch Bomber est un avertissement de marche qui couvre n'est plus sûr. Il arbore une armure légère, bleu ciel, conçue pour des opérations dans des environnements enneigés, des complexes de hauteur et des zones industrielles stériles. Une visière bleue met l'accent sur son rôle de dispositif de suppression à longue portée.

L'arme primaire ressemble à un fusil de chasse massif, mais au lieu d'un coup de feu, elle tire une explosion de trois grenades dans un seul volley. Cette explosion couvre une zone à la fois, transformant les couloirs, les escaliers et les barricades en un chaos instantané. Le Combine utilise ces soldats pour déloger l'ennemi de positions fortifiées sans tirs prolongés.

Les grenades sont programmées pour une détonation optimale, rendant la fuite presque inutile. Même si la première grenade manque la cible, les deuxième et troisième terminent généralement le travail. Le soldat travaille méthodiquement, ciblant les concentrations ennemies et les voies d'évacuation potentielles.

CONSEILS:

- Ne vous cachez pas dans la couverture standard.
- Il est moins dangereux en plein air qu'en intérieur.