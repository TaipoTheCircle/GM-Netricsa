GUN TRANQUILIZEUR


ARME:      Beretta M9
MUNITIONS:        Fléchettes pour tranquillisant
CADENCE DE TIR:         ~10 tours/min

DESCRIPTION:

Une Beretta M9 qui a été modifiée pour tirer des fléchettes contenant un agent tranquillisant. Ce poste est utilisé par des services spéciaux dans différents pays.

REMARQUES:

- Si vous voulez soumettre quelqu'un sans le tuer, cette arme est idéale.
- Il est préférable de viser la tête, car quand la fléchette frappe le cerveau, la substance à l'intérieur fonctionne plus vite.


