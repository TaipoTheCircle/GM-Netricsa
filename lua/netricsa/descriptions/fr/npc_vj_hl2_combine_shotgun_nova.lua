COMBINE SURVEILLANCE PRISON SHOTGUNNER


CLASSE:      Combiner Overwatch Prison Shotgunner
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Infanterie transhumaine (Unité d'exécution des peines - fusil de chasse)
TAILLE:       5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Feux de chasse SPAS-12
RÉCOMPENSE:     400 FC
MENACE:     Haut

DESCRIPTION:

Le soldat de la prison Combine Overwatch Shotgun sert d'exécuteur lourd de Nova Prospekt. Contrairement aux soldats de la prison, ces unités sont équipées de fusils de chasse pour réprimer brutalement les soulèvements, les brèches dans les cellules ou les tentatives d'évasion. Leurs tactiques se concentrent sur la peur et l'énorme puissance de feu à proximité, chargeant souvent des couloirs étroits vers des cibles de tir à portée de point.

L'utilisation d'unités de fusils dans les prisons est délibérée - leur pouvoir destructeur dans les quartiers proches garantit que les prisonniers survivent rarement aux tentatives d'évasion. Leur armure plus légère, comparée à celle des soldats fusils de chasse de première ligne, les rend plus agiles dans les salles confinées de Nova Prospekt, bien qu'elles soient encore beaucoup plus difficiles que l'infanterie standard.

Fidèles au Combiné, ces soldats agissent comme des bourreaux dans les émeutes et comme des troupes de choc pendant le « traitement » des prisonniers de masse. Rencontrer quelqu'un dans les couloirs sombres de la prison signifie généralement la mort est à quelques secondes.

CONSEILS:

- Gardez la distance - leurs fusils sont dévastateurs.
- Utilisez des explosifs ou des tirs rapides pour épuiser leurs équipes avant qu'elles ne se rapprochent.
- Les fournitures sont parfois entreposées dans des armoires près des routes de patrouille des unités de fusils de chasse.
