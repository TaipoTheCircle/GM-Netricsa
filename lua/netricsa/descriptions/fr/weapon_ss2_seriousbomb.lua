SÉRIEUX BOMB


ARME:    Bombe grave
RANGE:     700 pieds
EFFECT:    mort instantanée à toutes les créatures de portée

DESCRIPTION:

Bombe grave - Miniature Big Bang, pétard atomique, mort instantanée avec un sourire. Quoi que vous regardiez, ce bébé va secouer votre monde. Appuyez simplement sur ce déclencheur et regardez vos ennemis se désintégrer dans une explosion aveuglante, pendant que vous attendez dans la sécurité du Life-Preserving-Quantum-Field(TM).
En raison de leur taille, vous ne serez jamais en mesure de porter plus de trois d'entre eux.

REMARQUES:

- ces jouets sont très rares, alors pensez bien avant de les activer.