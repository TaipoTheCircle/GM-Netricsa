COMBINE SURVEILLANCE ARCTIQUE PRISON SHOTGUNNER


CLASSE:      Combiner Overwatch Arctic Prison Shotgunner
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner l'unité de lutte contre les agressions
TAILLE:       5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Spas-12 fusil de combat, Grenades
RÉCOMPENSE:     700 FC
MENACE:     Haut

DESCRIPTION:

La prison de Overwatch Arctic Soldat avec fusil de chasse est un soldat de la coalition qui a été initialement affecté à l'installation Nova Prospekt, mais qui a été temporairement redéployé dans les régions arctiques. Cette pratique est utilisée lorsque les zones pénitentiaires connaissent un excédent de main-d'œuvre, tandis que les secteurs éloignés souffrent d'une pénurie d'unités d'assaut.

Après le retraitement dans le système Nova Prospekt, leur psyché est presque complètement supprimé, et l'obéissance est assurée par une surveillance constante et des impulsions de douleur. Au combat, ils agissent sans hésitation ni auto-préservation.

Il porte un camouflage blanc et gris arctique, modifié par rapport à l'équipement de prison standard. La visière du casque brille orange-une caractéristique des soldats de prison, révélant leur origine même dans l'obscurité neigeuse. "Nova Prospekt" est clairement écrit sur son dos en bleu, servant à la fois de marque et de rappel de l'endroit où le soldat sera renvoyé s'il désobéit.

Comme d'autres fusils de chasse Combine, ce soldat est conçu pour le combat de quartier rapproché. Dans les stations arctiques, les tunnels de glace et les complexes polaires abandonnés, il est utilisé pour le nettoyage brutal, la répression des émeutes et l'élimination des cibles où l'infanterie standard est jugée inefficace.

CONSEILS:

- Ne comptez pas sur ses soldats mis en garde.
- La visière orange est perceptible, mais il réagit plus vite qu'il ne semble.
- Le panneau de Nova Prospekt signifie que le soldat n'a rien à perdre.
- Dans les espaces confinés, le fusil le rend mortel.
