HÔTEL BRICK, AMÉLIORATION DU POSTE-APOCALYPSE


Sam, pendant que nous voyageions, un propriétaire local de harceleurs et de dachas a rénové la maison en briques. Elle a acquis toutes les infrastructures nécessaires. Maintenant c'est un véritable country club pour les survivants, avec une piscine et un garage.

Certes, il n'y a toujours pas de portes, mais qui sommes-nous pour nitpick ?

Le paysage a subi des changements importants. La civilisation avance :

Une quatrième voiture. Il y en a quatre. Il n'a pas non plus de roues, mais le groupe est devenu plus bondé. Ils se garent au mieux.

Garage à briques. Un garage à part entière de la même brique rouge a jailli derrière la maison. Il n'y a aucune tradition familiale, apparemment.

À l'intérieur se trouve le lieu sacré d'un mécanicien : une clé et un moteur se trouvent bien sur une table en bois. Pas cloué, pas vissé. Je suis allongé là.

Piscine. A gauche de la maison, à droite sur l'herbe, une piscine est apparue. C'est du plastique blanc, une forme rectangulaire classique. C'est plein d'eau. Mais tu peux nager dedans. L'eau, au fait, est propre. Je crois.

Un arbre migrateur. Un des onze arbres a été transplanté dans un autre coin de la propriété. Soit le paysagiste a fait du travail, soit l'arbre l'a demandé lui-même. Visuellement, rien n'a changé, mais le fait reste – la flore vit maintenant selon le nouveau plan directeur.

Dans la maison, les mêmes fournitures que nous avons déjà explorées (bonjour, Sofia, avec ses 112 dîners). Mais une nouvelle porte est apparue... ou plutôt une nouvelle ouverture :

Une nouvelle chambre. Sans porte, naturellement. À l'intérieur, spartan minimalisme: un placard vide, table et lit. Pas de matelas. Un cadre nu. Apparemment, c'est une suite pour ceux qui n'ont pas peur de dormir sur du contreplaqué et de suspendre des vêtements dans un espace vide.

Supplies are in place: patates douces, pommes (les meilleurs du monde), 112 repas de Sofia, collations Jabber, jus, boisson vanille, soda alimentaire et pommes de terre fraîches. Les caisses (une grande, quatre petites) ne s'ouvrent toujours pas. L'horloge est suspendue. Les fusils sont cloués dans le placard, se moquant de leur apparence.

Le garage est un atelier de réparation potentiel. Le moteur et la clé ne sont pas seulement allongés autour. Avec une certaine ingéniosité (et peut-être des roues pour ces voitures au ralenti), nous pouvons faire tourner au moins une des quatre épaves.

La piscine est une source d'eau. Invalable pendant un siège. Et c'est aussi agréable de prendre un bain après une bagarre avec des extraterrestres. Cependant, il n'y a nulle part où se réchauffer après – le lit n'a pas de matelas.

La nouvelle chambre peut être utilisée comme un point de contrôle ou une chambre. Si on trouve un matelas. Ou du foin.

En route.
