UNE CONSTRUCTION DU GRASS DE FLAT, UN LIEU BEAUTIF


Avant que vous ne soyez pas juste l'herbe plate. C'est un plan si infini que l'herbe elle-même doute de sa propre existence, aussi large que l'esprit d'un crâne avant un saut.

À l'horizon, haut au-dessus du sol, le panneau "FlattyWood" brille - en grandes lettres confiantes, comme si quelqu'un avait construit un spectacle de prix Hollywood pour la meilleure scène ici.

Quelques bâtiments haut de gamme et construction en béton, vides et gris, comme les décors oubliés d'un sombre film d'arthouse;

Un étang que vous regardez et pensez reflète simplement votre fatigue des batailles constantes...