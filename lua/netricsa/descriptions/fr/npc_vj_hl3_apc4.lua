TRAQUE DE COMBINE


CLASSE:      Combiner la piste
MÉTABOLISME: Plateforme mécanisée avec commandes intégrées
PERCEPTION: Combiner les transports lourds
TAILLE:       29,5 pieds
ENDURANCE:  Extrêmement élevé
HOSTILITÉ:  Extrême
ARMES:    Tourelle de mitrailleuse intégrée (commandée de l'intérieur)
RÉCOMPENSE:     3200 FC
MENACE:     Critique

DESCRIPTION:

Le Combine Track est un transport Combine spécialisé, similaire à celui du APC Transporter, mais adapté au transport des Soldats Répliquants Combine. Sa forme est plus rationnelle et plus fermée, et la coque semble solide et solide, comme si elle était moulée. La principale différence est l'absence complète de verre, de cockpits ouverts et de postes de commande externes.

Le véhicule est commandé exclusivement de l'intérieur. La navigation se fait par l'intermédiaire d'un système de capteurs externes, de caméras tactiques et de modules d'analyse Combine. L'équipage ne voit pas le monde directement, seulement par un filtre de données. Cela réduit la vulnérabilité du véhicule et élimine complètement les erreurs humaines.

La tourelle du Combine Track est également contrôlée de l'intérieur. L'opérateur est directement connecté au système de ciblage.

CONSEILS:

- Pas de verre, pas de points faibles.
- Déploye des soldats.
