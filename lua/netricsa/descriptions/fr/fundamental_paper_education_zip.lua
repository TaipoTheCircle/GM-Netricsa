ZIP DE L'ENSEIGNEMENT DU PAPIER FONDAMENTAL


CLASSE:      Zip
MÉTABOLISME: Papier anthropomorphe dragon organisme
PERCEPTION: Dragon Bully
TAILLE:       ~3,2 pi
ENDURANCE:  Haut
HOSTILITÉ:  Déceptif
ARMES:    Griffes, queue de dragon épilée, pyrokinesis
RÉCOMPENSE:     40 FC
MENACE:     Très élevé

DESCRIPTION:

Un étudiant à la Paper School, l'un des trois tyrans et le complice d'Oliver. Elle a des cheveux à deux tons (noir et blanc) avec l'équation incorrecte "2 + 2 = 8" écrite dessus, symbolisant son mépris pour les règles. Elle porte une robe blanche et un poncho recouvert de dessins enfantins, créant un contraste glacial avec sa nature cruelle. Joueuse, trompeuse et sadique, elle aime l'intimidation et les "jokes" mortels (c'est probablement elle qui a écrit "EXIT" sur la porte de la chambre de l'exox). Elle ne fait que faire preuve de bonté envers son jeune frère. Elle est la "favorite" de Miss Circular et possède clairement des capacités inhumaines.

CONSEILS:

- Sa ruse et sa cruauté sont masquées par le jeu. C'est un maître de blagues et de pièges mortels.