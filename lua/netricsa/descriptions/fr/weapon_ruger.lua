RÈGLE 10 / 22


ARME:     RÈGLE 10/22
MUNITIONS:       .22 cartouches LR 
CADENCE DE TIR:        ~40-60 tours/min 

DESCRIPTION:

Un fusil semi-automatique compact en chambre pour cartouches de .22 Long Rifle, d'abord présenté par Sturm, Ruger & Co. en 1964. Basé sur une action de boulon fiable à court terme avec un cadre de boulon rotatif; livré de série avec un chargeur rotatif de 10 tours. Connu pour sa durabilité, sa conception simple et son accessibilité, il est populaire pour l'entraînement, le tir récréatif, la chasse aux petits gibiers et aux parasites, ainsi que dans les disciplines sportives. Il est disponible en de nombreuses variantes et configurations (Carbine, Target, Tactical, Ruger 10/22 Takedown, etc.) et dispose d'un marché étendu pour le réglage et les accessoires (systèmes de visionnage, stocks, avant-postes, compensateurs de barils, magazines étendus, etc.).

REMARQUES:

- Largement utilisé comme arme d'entraînement et de "recréation"; dans certains pays, des versions civiles sportives et de chasse sont disponibles avec des restrictions.
- Cause très peu de dommages dus à son petit calibre 22. LR.