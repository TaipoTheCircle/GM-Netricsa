MÉTHODE TACTIQUE DE L'ÉLÉMENT DE SOLDIER CLONÉ


CLASSE:      Soldat cloné Remington 870 MCS Un fusil tactique
MÉTABOLISME: Clone humain modifié de façon cybernétique
PERCEPTION: Cyber-infanterie mentale
TAILLE:       6 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Moyenne
ARMES:    12-gauge Remington 870 MCS Tir tactique, coup de pied
RÉCOMPENSE:     300 FC
MENACE:     Faible

DESCRIPTION:

L'infanterie de base de l'armée de Mental, créée par le clonage et modifiant cybernétiquement les soldats capturés ou décédés de l'Alliance de Défense de la Terre. Ils ont un casque métallique distinctif avec cinq capteurs rouges à la place d'un visage, leur permettant de voir dans une mauvaise visibilité. Leur libre arbitre est supprimé par une unité de contrôle de la vie implantée, ne laissant que les instincts de combat de base et la capacité de recevoir des ordres. Ils portent un camouflage standard et une armure légère. Malgré leurs modifications, ils conservent des vestiges de l'humanité : ils ressentent de la douleur, peuvent boiter lorsqu'ils sont blessés et s'agonisent avant la mort. Au combat, ils utilisent la couverture, rechargent et opèrent en groupes.

CONSEILS:

- Dangereux à portée de main. Gardez vos distances. Tué avec un seul coup de fusil ou plusieurs coups à longue portée.
