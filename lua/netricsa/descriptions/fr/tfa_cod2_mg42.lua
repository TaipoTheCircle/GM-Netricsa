MG 42 GENERAL-PURPOSE MACHINE GUN


ARME:  MG 42 Pistolet à machine d'usage général
MUNITIONS:    7.92x57mm Mauser
CADENCE DE TIR:     ~900-1500 tours/min.
POIDS:  - 11,57 kg.

DESCRIPTION:

Une mitrailleuse à usage général allemande de la Seconde Guerre mondiale, développée en 1942 comme un successeur plus simple et moins cher du MG 34. Il a été conçu en mettant l'accent sur la haute fiabilité, le progrès technologique et l'immense puissance de feu.

La mitrailleuse utilise une action de court-recoil avec un boulon verrouillé à rouleaux. Il est alimenté par une ceinture métallique, et l'arme tire continuellement. Son taux élevé de feu est l'une de ses principales caractéristiques.

Le canon se réchauffe rapidement lors d'un tir prolongé, de sorte que la conception permet un remplacement rapide. Le MG 42 pourrait être utilisé comme mitrailleuse légère sur un bipode ou monté sur un trépied. Après la guerre, la conception a été développée en de nombreuses variantes, dont le MG3.

REMARQUES:

- Son taux élevé de feu permet un feu extrêmement dense et une suppression efficace de l'ennemi.
- Le barillet détachable permet de continuer le tir intensif malgré une chaleur intense.
- Lorsqu'elle est montée, la mitrailleuse est particulièrement efficace contre les cibles éloignées et groupées.
- Des soldats américains et britanniques l'ont surnommé "Hitler's Saw".
