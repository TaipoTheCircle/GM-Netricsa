QUIVRE DE XEN


CLASSE:      Quitter
MÉTABOLISME: Inconnu
PERCEPTION: Curieux vagabond
TAILLE:       5 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Aucune
ARMES:    Aucune
RÉCOMPENSE:     150 FC
MENACE:     Aucune

DESCRIPTION:

Ces petits Quivers ont été envoyés de Xen pour... juste calmer, vraiment. Ils font des bruits extraterrestres bizarres, ouvrent les portes comme s'ils possédaient l'endroit, et n'ont absolument aucun intérêt à attaquer quoi que ce soit. La plupart d'entre eux sont des experts pour éviter les conflits et observer poliment les humains.

CONSEILS:

Ce sont les créatures les plus amicales que vous rencontrerez : pas de combat, juste la curiosité.
Écoutez leurs bruits extraterrestres - c'est leur façon de dire "bonjour".
Ils peuvent ouvrir les portes, alors ne soyez pas surpris si on vous aide.
