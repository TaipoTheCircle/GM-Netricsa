MACHETE


ARME: Machette
MUNITIONS:   Aucun (arme de fusion)
CADENCE DE TIR:    ~75 oscillations/min

DESCRIPTION:

La machette est un couteau long, large et à une seule extrémité utilisé comme un outil agricole dans la jungle et les milieux tropicaux, et également réutilisé comme arme de mêlée. Versatile en fonction - couper la végétation, préparer la nourriture, ou faire des coups mortels au besoin.

REMARQUES:

- Pas besoin de munitions.
- Excellent dans le combat étroit, particulièrement contre les ennemis non armés ou légèrement blindés.
- Utile à la fois pour les tâches de survie et de combat.
- Poids léger et grande lame le rendent efficace, mais peut être encombrant dans les espaces restreints.