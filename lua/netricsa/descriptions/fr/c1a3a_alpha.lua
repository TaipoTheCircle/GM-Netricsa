COMPLEXE DE SÉCURITÉ BLACK MESA, OÙ EST TOUT LE MONDE ?


Les Houndeyes errent ici, les crânes, et quelque part dans les profondeurs, à en juger par le son, un Bullsquid. Ils ne se cachent pas. Ils sont là. Ils se sentent confiants, chez eux. Parce que c'est leur maison maintenant. Et ils n'attendaient pas de visiteurs.

Et entre eux sont les forces de Mental. Soldats en armure familière, fusils à plasma prêts. Ils ne combattent pas les créatures. Ils divisent le territoire. Comme les propriétaires qui sont venus prendre la relève.

L'ascenseur qu'il nous faut est au-dessus.

Mais pour y parvenir, nous devons traverser plusieurs autres secteurs. L'entrée de l'ascenseur est gardée par une tourelle de plafond. Celui en haut, encastré dans le béton, regarde en bas et attend que quelqu'un apparaisse dans la zone de mort. Smart, rapide, avec une vision à 360 degrés.

Heureusement, nous avons Zipper. Et il y a la scie circulaire, et beaucoup d'autres armes. Et il y a ce qu'ils peuvent faire ensemble avec un morceau de fer qui est suspendu au plafond depuis trop longtemps.
