DESCRIPTION:

Ces soldats étaient autrefois de véritables SEAL de la marine américaine, maîtres des raids surprises et des opérations de sauvetage dans les zones les plus dangereuses du monde.

Ils ont agi dans le cadre d'une équipe capable de contourner toute sécurité et d'éliminer une cible derrière les lignes ennemies, risquant parfois leur vie pendant quelques minutes d'avantage stratégique.

À l'origine, ce soldat était un expert en assaut pour l'équipe 6 du SEAL, responsable du nettoyage des bâtiments, de la descente d'installations fortifiées et du travail dans des couloirs serrés.

Il aimait les solutions fortes - un fusil était son meilleur ami.

Après son transfert au Combine, on lui a donné un costume de combat rapproché brun et un casque orange pour le distinguer visuellement des soldats Overwatch standard.

CONSEILS:

- Ils ne plaisantent pas, il tire vite et avec précision.