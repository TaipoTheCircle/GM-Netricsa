GEWEHR 43 (G43) RIFLE AUTOCHTONE


ARME: Gewehr 43 (G43) Fuseau autoportant
MUNITIONS:   7.92x57mm Mauser
CADENCE DE TIR:    Autochargement, ~30 tours/min
POIDS: 4,33 kg

DESCRIPTION:

Le Gewehr 43, aussi connu sous le nom de G43, était un fusil allemand à chargement automatique de la Seconde Guerre mondiale. Développé en 1943, il a été un développement de la Gewehr 41 avec un système à gaz plus avancé. En 1944, le fusil est rebaptisé Karabiner 43 (K43), bien que sa conception demeure pratiquement inchangée.

Le fusil utilise un système à piston à gaz et à courte portée et est alimenté par un chargeur à 10 tours amovible. Le mécanisme semi-automatique permet au tireur de tirer rapidement des coups de suivi sans faire tourner manuellement le boulon après chaque coup.

Le G43 est efficace à moyenne et longue portée, et la capacité de monter une vue optique a permis à certains modèles d'être utilisés comme armes de sniper. Cependant, les lunettes optiques n'étaient installées que sur un petit pourcentage des fusils produits.

REMARQUES:

- Une bonne précision et une puissante cartouche de fusil rendent le G43 efficace à portée moyenne et longue.
- Le mécanisme semi-automatique permet un suivi rapide.
- Peut être équipé d'une vue optique et utilisé comme fusil de sniper.
- Le calibre 7.92x57mm offre une puissance élevée et est bien adapté pour engager des cibles durcies.
- Le petit magazine nécessite des changements fréquents pendant les tirs intenses.
- Malgré son système semi-automatique, ce n'est pas un fusil automatique. La norme G43 ne tire pas en éclats.
- La portée effective est d'environ 500 mètres.
- En 1944, il a été rebaptisé Karabiner 43, ou K43.
- S'il est équipé d'optique, le G43 est le mieux utilisé pour un feu précis sur des cibles individuelles. Sans optique, le fusil se comporte admirablement comme une puissante arme de soutien semi-automatique.
- Dix rounds, semi-automatiques et 7,92mm. L'ennemi a le temps de réfléchir, mais peu de temps.
