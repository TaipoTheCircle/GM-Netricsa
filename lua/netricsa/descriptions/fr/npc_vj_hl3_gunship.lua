GUNSHIP COMBINE


CLASSE:      Combiner les armes à feu
MÉTABOLISME: Synthétique / Biomécanique
PERCEPTION: Synthétisation d'agression aérienne
TAILLE:       - 40-45 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    Canon à impulsions lourdes (avant), canon à chaîne ventrale (belle)
RÉCOMPENSE:     5000 FC
MENACE:     Très élevé

DESCRIPTION:

Le Combine Gunship est un synthé d'assaut volant déployé par le Combine. Il ressemble à un étrange hybride de conception organique et mécanique, avec un corps arrondi, deux ailes ressemblant à des palmes près de l'avant, un grand rotor, et des composants mécaniques (tubes exposés, parties brillantes) qui trahissent sa nature synthétique.

Il patrouille le ciel au-dessus des territoires critiques Combiner (Citadel, Nova Prospekt, avant-postes clés), pleuvoir un tir précis de canons à impulsions et parfois des explosions de canons à ventre plus lourds (bien que le canon à ventre soit pour la plupart inutilisé sauf dans les commandes spéciales). Très maniable, capable de tourner à 180° en vol, il évite les fiançailles et les combats à distance, en utilisant sa vitesse et son agilité pour rester au-dessus des menaces.

CONSEILS:

- Utiliser des armes explosives (RPG, grenades) plutôt que des armes légères - c'est surtout imperméable aux balles.
- Continuez à bouger et utilisez la couverture. Les canonniers préfèrent les attaques à longue portée et l'avantage de hauteur.
- Faites attention à son avertissement avant qu'il ne commence à tirer - vous donne une brève chance de se cacher.
- Évitez de vous exposer dans les zones ouvertes, en particulier sous les pistes de vol.
- Essayez d'attaquer des points aveugles (ci-dessous, derrière ou sur les côtés) pour réduire l'exposition à son arme.
