SUR SANYA DU KRIEGER ARCHIPELAGO


CLASSE:      Super Sanya
MÉTABOLISME: Mutant trigénique hyper-accéléré
PERCEPTION: Bruiser mutant supersonique
TAILLE:       7,2 pi
ENDURANCE:  Très haut, Extrêmement bas
HOSTILITÉ:  Hyper-agressive
ARMES:    Bottes supersoniques, rame rapide, booms sonores, griffes
RÉCOMPENSE:     2500 FC
MENACE:     Critique

DESCRIPTION:

Un sous-produit unique et défectueux des expériences du Dr Egger pour surmonter l'hydrophobie chez Trigens. Au lieu d'être guéri, le mutant a acquis une super vitesse pathologique. Ses jambes mutées se sont transformées en « bottes supersoniques » biomécaniques qui génèrent un champ de force, lui permettant de traverser l'eau et les surfaces verticales, laissant derrière elle une vague sonore explosive. Cependant, sa psyché n'a pas survécu aux changements : il souffre d'hydrophobie paradoxale et d'illusions de grandeur, se croyant lui-même un « gigachad sur les stéroïdes ». Au combat, il bouge si vite qu'il ne laisse derrière lui qu'un flou bleu et un boom sonore. Il est aussi simple que tous les Gros Garçons, mais sa simplicité est maintenant mesurée en kilomètres par seconde.

CONSEILS:

- Il fait une guerre personnelle avec le Dr Egger, le croyant responsable de son état.
- Comme une graisse normale, il a un implant brillant sur sa poitrine, mais il ne peut être frappé que quand il cesse de bouger.
- Utilisez un fusil de chasse, des mitrailleuses lourdes ou des armes à effet de surface (comme un lance-flammes) pour couvrir la zone où il pourrait être.
