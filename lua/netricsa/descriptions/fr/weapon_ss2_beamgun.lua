BIENVENUE


ARME: Pistolet à faisceaux
MUNITIONS:   Cellules plasmatiques
CADENCE DE TIR:    ~300 tours/min

DESCRIPTION:

Arme à énergie avec quatre cristaux de baril bleu et un central. Incendie un faisceau continu lorsque la gâchette est maintenue, mais a un retard de démarrage lorsque les barils de cristal tournent à pleine vitesse. Dommages très élevés; idéal pour nettoyer les hordes d'ennemis faibles ou faire face à des ennemis plus résistants.

REMARQUES:

Pas de temps de déplacement projectile.
- Excellent contre les ennemis non armés ou groupés.