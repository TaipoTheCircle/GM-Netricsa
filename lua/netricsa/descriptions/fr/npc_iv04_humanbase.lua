VENDU


CLASSE:      Soldat rebelle
MÉTABOLISME: Humains
PERCEPTION: Chasseur de résistance humaine
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Pistol, SMG, fusil de chasse, Grenades
RÉCOMPENSE:     200 FC
MENACE:     Moyenne

DESCRIPTION:

Les soldats rebelles sont membres de la Résistance humaine, organisée pour lutter contre l'occupation de Combine. Ce sont des humains ordinaires entraînés rapidement à manier des armes à feu et à coordonner des attaques, souvent improvisantes dans les zones de combat urbaines et rurales.

Ils opèrent dans des escadrons, couvrent des civils, assurent la sécurité des routes d'approvisionnement et fournissent un soutien essentiel aux principaux agents comme Gordon Freeman ou Alyx Vance. Bien que moins avancés que Combiner des forces, leur adaptabilité, leur moral et leur nombre en font des adversaires redoutables.

Les rebelles comptent sur le travail d'équipe et les tactiques de frappe et de course plutôt que sur la force brute. Leur résilience vient de l'engagement envers la survie de l'humanité plutôt que de l'armement supérieur, et on les voit souvent coordonner avec des véhicules comme le Merkava Tank ou aider des scientifiques et des médecins sur le terrain.

CONSEILS:

- Protégez-les-ils sont les plus efficaces dans les groupes.
- Leur fournir des munitions et des trousses pour maintenir la pression en première ligne.
- Utilisez-les pour repérer les zones et les embuscades.
- Les équipes rebelles peuvent submerger même les unités légèrement blindées si elles sont coordonnées.
