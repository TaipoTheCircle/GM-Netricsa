RXZ-200 PLASMA TURRET
\

CLASSE:      RXZ-200 Turret plasma
MÉTABOLISME: Construction alimentée en énergie
PERCEPTION: Emplacement stationnaire, hybride d'un canon plasma et d'un lecteur laser
TAILLE:       ~3,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Varie avec le tireur
ARMES:    Sphères de plasma
RÉCOMPENSE:     400 FC
MENACE:     Haut

DESCRIPTION:

C'est le résultat de l'ingénierie de Mental, qui a décidé que les mitrailleuses classiques n'étaient pas suffisantes et il était temps de passer à l'énergie. La conception est simple : un corps ovale avec un cercle violet au centre, équipé d'un canon plasma et d'un système de ciblage copié à partir de tourelles laser.

Contrairement à la version de la mitrailleuse, la tourelle plasma tire des sphères simples de plasma violet, pas des éclats. Une seule sphère est parfaitement précise et peut détruire presque n'importe quelle cible avec un seul coup-être un Orc ordinaire, un vaisseau armé, ou même Mental lui-même, si malchanceux. Au moment de l'impact, le plasma explose, endommageant tout à proximité.

Mental a combiné son canon plasma avec le système de contrôle de la tourelle laser, créant une arme hybride qui peut être utilisée par n'importe qui : les soldats Horde et les Orcs de la planète Orazio.

Les tortues sont généralement intégrées dans les bases de Mental sur Sirius et d'autres planètes.

Au combat, la tourelle plasma est dangereuse à n'importe quelle portée. Son seul inconvénient est son faible taux d'incendie. Quelques secondes passent entre les tirs, et s'il y a beaucoup d'ennemis et qu'ils se rapprochent, la tourelle peut ne pas avoir le temps de recharger.

Mais si un canonnier est à l'intérieur, ils sont protégés par la coque et peuvent utiliser la tourelle comme source supplémentaire de santé-il absorbe les dommages et, s'il est détruit, éjecte simplement le pilote.

CONSEILS:

Si vous voyez un ennemi derrière une tourelle, sortez-les d'abord. Une tourelle sans canon n'est qu'un morceau de métal.
- Une tourelle est indispensable contre des cibles blindées.
- Les explosifs détruisent une tourelle plus vite que les armes légères.
- Si vous voyez des jambes orcish sortir de derrière une tourelle, il y a quelqu'un.
