EXIGENCES APPHIBIÉES DE XEN


CLASSE:      Taureau amphibie
MÉTABOLISME: Amphibiens carnivores
PERCEPTION: Prédateur sous-marin
TAILLE:       8-9 pieds
ENDURANCE:  Moyenne-haute
HOSTILITÉ:  Extrême
ARMES:    4 tentacules, griffes, cils de queue, cracher toxique 
RÉCOMPENSE:     450 FC
MENACE:     Haut

DESCRIPTION:

Le calmar amphibie est une sous-espèce aquatique rare du calmar sauvage de Xen. Contrairement à ses proches terrestres, cette bête s'est adaptée aux eaux profondes, avec un cadre musclé en crocodile, une peau d'écailles vertes, et seulement quatre tentacules nourrissants puissants autour de sa mâchoire. Ses poumons amphibies lui permettent de prospérer aussi bien sous l'eau que sur la terre, bien qu'il préfère se cacher dans les rivières, les canaux et les cavernes inondées.

Lorsqu'ils sont provoqués, les Bullsquids amphibies attaquent avec des griffes vicieuses, des coups de queue et des ruisseaux de cracher toxiques même lorsqu'ils sont submergés. Sa construction crocodilienne lui accorde une forte vitesse de nage, en faisant un prédateur du sommet dans les deux domaines.

CONSEILS:

- Évitez d'entrer dans l'eau quand des calmars amphibies sont présents - ils s'embusquent d'en bas.
- La crache toxique se disperse rapidement dans l'eau, donc gardez la distance même en nageant.
- Les explosifs et les armes de type harpon sont les plus efficaces sous l'eau.
- Le combat terrestre est plus sûr, mais leur morsure de charge peut écraser les os en quelques secondes.
