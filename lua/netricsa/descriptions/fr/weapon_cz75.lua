CZ 75 PISTOLE AUTOCHTONE


ARME:      CZ 75
AMMUNITION:  cartouches 9x19
CADENCE DE TIR:         ~20 tours/min

DESCRIPTION:

Un pistolet autochargeur a été mis au point en Tchécoslovaquie en 1975. Le pistolet a été conçu par les frères Josef et Frantisek Koucky dans la ville de Uhersky Brod. Initialement, la conception était destinée à l'exportation et était positionnée comme un remplacement moderne des pistolets « lourds » de la police et de l'armée logés pour la cartouche 9×19 Parabellum.

REMARQUES:

- Facile à transporter.
- Cette version du pistolet tire un seul coup.







