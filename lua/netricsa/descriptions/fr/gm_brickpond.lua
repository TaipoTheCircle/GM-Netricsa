BRICK POND, LES FEMMES DE LA MORT


Sam, cet endroit est comme cette pièce dans un film d'horreur où vous n'êtes pas censé aller, mais vous êtes déjà parce que la porte est ouverte, et la curiosité est votre pire ennemi.

A première vue, c'est un quartier ordinaire. Des murs de briques, un étang, quelques maisons. Silence, douceur, bonheur de la brique.

Et puis vous remarquez les détails. Et vous réalisez que quelqu'un est mort ici. Et pas seulement mort, mais resté ici pour toujours.

Les murs en brique forment une sorte de cour ou d'extrémité morte. Au centre se trouve un petit étang. L'eau est toujours comme un miroir dans une maison hantée.

Tout autour est le silence. Seulement le vent. C'est le principal ingénieur du son ici. Des hurlements, des murmures. Cela crée le sentiment que vous n'êtes pas seul, même s'il n'y a pas d'âme autour. Sauf une.

Qu'y a-t-il ici 

La première maison est "Open". Vous pouvez entrer. À l'intérieur, il y a quatre boîtes. Et rien d'autre. Pas de chaises, pas de tables, pas de fournitures de Sophia. Juste quatre boîtes vides. En attendant que tu regardes à l'intérieur et sois déçu.

La deuxième maison est fermée. Tu ne peux pas entrer. La porte est fermée ? Cassé ? Tout simplement pas conçu? Peu importe. L'important, c'est que derrière le mur de cette maison, dans un espace muré, se trouve un cadavre massacré. Dans son propre sang. Quelqu'un n'est pas mort, il l'a déchiré. Et laissé là, derrière le mur. Pour rappel. Ou comme un avertissement.

Vous ne pouvez pas voir le cadavre directement. Mais maintenant vous savez qu'il est là. Derrière le mur. Dans une maison vous ne pouvez pas entrer.

Le vent. Ce n'est pas qu'un bruit de fond ici. C'est comme la voix de cet endroit. Il s'estompe, puis se renforce, puis commence à hurler si fort que les boules d'oie descendent même ma colonne vertébrale, et je n'ai pas de dos.

Un étang. De l'eau sombre dans laquelle personne ne nage.

Cet endroit n'est pas pour vous. Et pas pour moi. C'est pour celui qui reste derrière le mur. "Pour toujours" (Tazik29).
