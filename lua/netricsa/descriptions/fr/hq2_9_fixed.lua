HALF-QUAKE 2, CHASE À MAIN


Cours. Courez. Ne t'arrête pas. Ne regarde pas en arrière. Mais si vous voulez savoir ce qui nous poursuit... c'est un énorme panneau avec une main dessus. Il écrasera tout sur son chemin. Et nous aussi.

Oui, les sadiques ont allumé une musique triste. Apparemment, ils veulent qu'on se souvienne de ce moment.

Il y a des boîtes devant. Poussez-les. Vite. Certains ont des trous et vous serez coincés. Dans certains endroits, il n'y a tout simplement pas de plancher. Et, bien sûr, à la fin, deux Vortigaunts gris vous attendent.

Nous avons le temps avant que la main ne commence à serrer. Ne pense pas à ce qui arrivera quand il rattrapera. Cours, Sam. Cours plus vite que jamais. Ce n'est pas une blague.

J'ai réglé la minuterie. Nous avons une minute. Peut-être moins. Ne t'arrête pas. Même si la musique vous dit que vous avez perdu, vous ne perdrez pas. Je le sais.

Allez !
