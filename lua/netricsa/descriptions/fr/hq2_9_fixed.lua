DEMI-SÉISMEMENT 2, CHASE À MAIN


Sam... Cours. Courez. Ne vous arrêtez pas. Ne regarde pas en arrière. Mais si vous voulez savoir ce qui nous poursuit... c'est un énorme panel avec une main dessus. Il écrasera tout sur son passage. Et nous aussi.

Oui, les sadiques ont mis de la musique triste. Apparemment, ils veulent que nous nous souvenions de ce moment.

Il y a des cartons devant. Poussez-les. Rapidement. Certains ont des trous : manquez-les et vous resterez coincé. À certains endroits, il n’y a tout simplement pas de sol. Et bien sûr, à la fin, deux Vortigaunts gris vous attendent.

Nous avons le temps avant que la main ne commence à se serrer. Ne pensez simplement pas à ce qui se passera une fois le retard atteint. Cours, Sam. Courez plus vite que jamais. Ce n’est pas une blague.

J'ai réglé la minuterie. Il nous reste environ une minute. Peut-être moins. Ne vous arrêtez pas. Même si la musique vous dit que vous avez perdu, vous ne perdrez pas. Je sais cela.

Maintenant, ALLEZ !