BIG-HEAD, MATT "LUTROSIS"


CLASSE:      Grande tête, Matt "Lutrose" McGill
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:    Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     100 FC
MENACE:     Annoyance

DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme de Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan" ils gagnent le feu et les modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Matt « Lutrosis » McGill est l'un de ces héros méconnus dont le travail constitue la base de la stabilité et du polissage du jeu. Son crâne surdimensionné est le résultat direct d'innombrables heures passées à trouver des bugs, à tester la mécanique, et à envoyer des rapports détaillés aux développeurs de Croteam. Tandis que d'autres appréciaient le produit fini, Lutrosis luttait contre les Kleers tombant à travers les textures, les portes bloquées et les échecs de progrès pour empêcher que cela arrive aux autres.

Son surnom dans les crédits est un signe de la plus haute reconnaissance du studio. Il incarne une communauté de fans dévoués qui ne se contentent pas de jouer, mais participent activement à la création, se transformant des consommateurs en co-créateurs de qualité.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager le chemin.
- Sur la difficulté "Je suis Ugh-Zan", détruisez-le à distance à cause de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.