TYRANNOSAURUS REX DE LA PLANTE TERRAFORME


CLASSE:      Tyrannosaurus Rex
MÉTABOLISME: Carnivore, Théropode
PERCEPTION: Prédateur Apex
TAILLE:       17 pieds
ENDURANCE:  Extrême
HOSTILITÉ:  Absolu
ARMES:    Crâne, mâchoires, dents, queue, griffes
RÉCOMPENSE:     5000 FC
MENACE:     Absolu

DESCRIPTION:

Ce n'est pas qu'un dinosaure. C'est le seul dinosaure qui n'a pas besoin d'être présenté. Quand les gens disent "Dinosaure", c'est celui qui vient à l'esprit. Le roi des lézards tyranniques.

L'apparence du T-Rex est familière à tout le monde : un crâne massif large à l'arrière et rétréci à l'avant, ce qui fait que les yeux se font face en avant, offrant une vision binoculaire meilleure que celle d'un faucon. Le cou est court et épais, sinon il ne pourrait pas supporter une telle tête.

La question de savoir si un Tyrannosaurus rex chasse ou fouille est un débat d'une décennie.

CONSEILS:

- N'essayez pas de fuir en ligne droite. C'est plus rapide qu'il ne semble.
