STROGG GRONTE DES STROGGOS


CLASSE:      Grunt de Strogg
MÉTABOLISME: Organisme cybernétique / bio-augmenté
PERCEPTION: Infanterie Strogg Melee
TAILLE:       6 pieds de haut
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Poinçon/pouce Melee, parfois mitrailleuse rotative à épaule
RÉCOMPENSE:     400 FC
MENACE:     Moyenne-haute

DESCRIPTION:

Grunt est un strogg humanoïde, de taille humaine, avec une construction de singe, des dents pointues, trois yeux, et des conteneurs stroyents verts le long des bras et du dos.

Ils préfèrent se charger en melee-punching ou pounking à l'ennemi. Ils utilisent parfois une arme à épaule pour tirer de loin, mais c'est rare. Lorsqu'ils sont suffisamment endommagés, ils peuvent "frenzy" - injecter stroyent à partir de leurs conteneurs, en augmentant la santé et les dommages de mêlée. En frénésie, ils rugissent et brillent en vert.



CONSEILS:

- Gardez votre distance; leur charge de mêlée est dangereuse.
- Utilisez une mitrailleuse, visez la tête.
- Ne les laissez pas fermer, utiliser la mobilité et les attaques.