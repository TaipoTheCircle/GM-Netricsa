M1 "BAZOOKA" ANTI-TANK GRENADE LAUNCHER


ARME:     M1 "Bazooka" Launcheur Anti-Tank Grenade
Cartridges: Grenades antidérapantes de 60 mm
Rate:      ~4-6 tours/min
POIDS:    ~6,8-8 kg

DESCRIPTION:

Ce lance-grenades antichar portatif américain a été développé en 1942. Il était équipé d'un tube de lancement à double extrémité avec un système enflammé électriquement et était principalement conçu pour être utilisé contre les véhicules blindés. Le M1 est entré en service avec l'armée américaine en 1942 et a été utilisé à partir de la campagne nord-africaine.

Le lance-grenades tire des grenades de 60 mm avec une ogive en forme de charge. Contrairement à un fusil sans recul classique, la grenade est équipée d'un propulseur de fusée qui l'accélère en se déplaçant le long du tube de lancement. La portée maximale était d'environ 365 mètres, et la portée effective était d'environ 135 mètres.

L'une des premières caractéristiques du M1 était son système d'allumage électrique. Les batteries et le voyant lumineux étaient situés à l'intérieur de l'épaule, de sorte que le système permettait de vérifier le contact électrique avant le tir.

Plus tard, des variantes améliorées sont apparues, y compris les M1A1, M9 et M9A1, et le calibre plus grand M20 "Super Bazooka" a été développé plus loin.

REMARQUES:

- Objectif principal : véhicules anti-armures et fortifications.
- Plus efficace à des distances relativement proches, où il est plus facile de toucher la cible.
- Le mécanisme d'allumage électrique fait du M1 une arme assez inhabituelle pour son temps.
- Le nom "Bazooka" vient de la ressemblance du tube de lancement à un instrument en laiton inhabituel popularisé par le comédien américain Bob Burns.
