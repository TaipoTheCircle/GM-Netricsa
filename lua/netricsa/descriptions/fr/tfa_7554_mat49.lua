MAT-49 SUBMACHINE GUN


ARME: Gun sous-machine MAT-49
MUNITIONS:   Parabellum 9x19mm
CADENCE DE TIR:    ~600 tours par minute

DESCRIPTION:

Une mitrailleuse française développée par les ingénieurs Pierre Monteil et Delamer à la *Fabrication Nationale d'Armes de Tulle* (MAT) à la fin des années 1940. Il a été adopté par l'armée française en 1949 pour remplacer diverses armes vieillissantes qui étaient restées en service après la Seconde Guerre mondiale. Le design se caractérise par sa construction simple en métal estampillé, sa grande fiabilité et son stock en métal pliant. L'armée française, la Légion étrangère française et les unités aériennes l'ont largement utilisé.

L'arme fonctionne selon un principe de rappel et tire d'un boulon ouvert. Il est en chambre pour les munitions 9x19mm Parabellum et utilise des chargeurs de boîte d'une capacité de 20 ou 32 tours. Une caractéristique de conception clé est le puits de pliage avant, qui permet de rendre l'arme beaucoup plus compacte pour le transport; une fois plié, le magazine est parallèle au baril. Il est équipé d'un matériel en métal rétractable, de vues en fer et d'un mécanisme de sécurité situé à l'arrière de la poignée du pistolet.

REMARQUES:

- Adopté par l'armée française en 1949.
- Plus de 700 000 unités produites.
- Magazines disponibles en 20 ou 32 tours.
- La portée de tir est d'environ 100 mètres.
- Le poids (sans chargeur) est d'environ 3,5 kg.
- Il y avait une variante de police du MAT-49/54 avec un canon étendu et un stock de bois.
- Pendant la guerre du Vietnam, les unités nord-vietnamiennes ont modifié les MAT-49s capturés pour chambrer la cartouche TT 7,62x25mm.
