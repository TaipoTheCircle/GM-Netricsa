FÉMIKAZÉ


CLASSE:      Fémikaze décapité
MÉTABOLISME: Cyber-zombie
PERCEPTION: Insensible, contrôlé par LCU
TAILLE:       6 pieds
ENDURANCE:  Très faible
HOSTILITÉ:  Extrême
ARMES:    Grenades à main
RÉCOMPENSE:     350 FC
MENACE:     Haut

DESCRIPTION:

Le Fémikaze est une variante féminine du kamikaze décapité de Sirius, créé par Mental en utilisant le LCU. Sa tête est manquante, donc elle repose entièrement sur la télécommande et des algorithmes d'agression intégrés. Son objectif premier est de se rapprocher le plus possible de sa cible et d'exploser avec les grenades qu'elle détient.

À l'extérieur, il a l'air « fashionable et menaçant » : son T-shirt imite un corps nu avec un maillot de bain rouge, un jean et des baskets rouges éclatantes. Les bombes sont des accessoires, mais leur effet est beaucoup moins décoratif.

CONSEILS:

- Explose dès la mort.
- Gardez vos distances et utilisez des armes à longue portée.
Dans un groupe, il transforme n'importe quelle zone en champ d'explosion chaotique.
- Les apparences peuvent être trompeuses: un T-shirt élégant et des baskets ne réduisent pas le danger.