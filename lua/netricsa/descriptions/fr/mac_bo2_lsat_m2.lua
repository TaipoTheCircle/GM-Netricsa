MACHINE DE LSAT


ARME: Pistolet automatique LSAT
MUNITIONS:   5.56x45mm OTAN / 5.56mm sans boîtier
CADENCE DE TIR:    ~650 tours/min

DESCRIPTION:

Une mitrailleuse expérimentale américaine a été mise au point dans le cadre du programme Lightweight Small Arms Technologies (LSAT). Le projet a débuté en 2004 dans le but de créer des armes légères et des munitions pour l'infanterie. Il a été développé par un groupe de sociétés de défense américaines sous la direction de l'AAI Corporation.

The key feature of the LSAT is its ability to use two types of ammunition: rondes classiques casées et sans cases. La version sans cas utilise des munitions spécialisées qui brûlent complètement au tir, ce qui réduit considérablement le poids des munitions transportées par le soldat. La mitrailleuse utilise un système alimenté à la ceinture et dispose d'un mécanisme unique d'alimentation en munitions.

REMARQUES:

- Développé comme une alternative plus légère à la mitrailleuse M249.
- Les munitions sans cases réduisent le poids de la charge de munitions d'environ 40%.
- Le système d'alimentation contient 100 rondes conventionnelles ou 150 rondes sans cases.
- Il existe également une variante avec un canon de 320 mm raccourci.
