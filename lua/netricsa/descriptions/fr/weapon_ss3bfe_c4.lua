C-4 EXPLOSIFS


ARME: C-4 Explosifs
MUNITIONS:   C-4 Charges
CADENCE DE TIR:    Détonation manuelle
POIDS: 1,1 lbs

DESCRIPTION:

Explosifs plastiques de qualité militaire. Extrêmement stable et fiable. Ne détonera pas d'impact ou d'incendie, nécessitant un détonateur pour l'initiation.
Possède une énorme puissance destructrice. Peut être moulé dans n'importe quelle forme pour un placement efficace sur les véhicules, les structures ou les groupes ennemis.

REMARQUES:

- Idéal pour placer des embuscades, éliminer des cibles lourdes et créer des chemins à travers les débris.
- La détonation contrôlée permet des dommages précis et minimise les risques pour l'utilisateur.
