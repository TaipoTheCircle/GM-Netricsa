PISTOLET ORO HOG 9MM


ARME : Pistolet ORO HOG 9 mm
MUNITIONS : munitions de 9 mm
ROF : semi-automatique, cadence de tir élevée
POIDS : ~1 kg

DESCRIPTIF :

Ce pistolet compact standard d'ORO est utilisé comme arme de secours principale par diverses forces armées. Malgré sa petite taille, il offre une bonne précision et une puissance élevée à courte portée. Le chargeur contient 15 cartouches et la capacité totale de munitions peut atteindre 150 cartouches.

L'arme dispose de deux modes de tir. Le mode principal permet un tir semi-automatique rapide, tandis que le mode secondaire tire une courte rafale de trois cartouches. Grâce à sa taille compacte, le HOG peut être utilisé à deux reprises, augmentant considérablement la cadence de tir.

REMARQUES :

-Haute précision et bonne puissance à courte portée.
- Le mode secondaire tire une rafale de 3 coups.
- La rafale augmente le recul et épuise rapidement le chargeur.
- Plus efficace à courte portée.
- Peut être utilisé simultanément à deux mains.
- L'indicateur sur le corps de l'arme indique le niveau des munitions : une fois les munitions épuisées, il passe du jaune au rouge.