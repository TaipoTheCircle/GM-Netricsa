BIO-MECHANOID, ESPAGNE


CLASSE:      Biomécanoïde, Spawner
MÉTABOLISME: cyborg endotherme
PERCEPTION: génétiquement programmé
TAILLE:       20 pieds debout
ENDURANCE:  moyenne
HOSTILITÉ:  élevé
ARMES:    nids de sauterelles
RÉCOMPENSE:     4500 FC
MENACE:     élevé

DESCRIPTION:

Un mécanisme biologique cultivé dans les réservoirs biologiques de Mental. Son génome est programmé pour lui donner biologiquement des parties mécaniques et des fentes latérales où des nids de sauterelles de marais améliorés cybernétiques sont attachés et directement connectés à son système nerveux.
Ajusté à l'attaque sans penser. On suppose que ses nids sont liés spatialement à la plus grande fraye des marais-hoppers de la galaxie, de sorte qu'elle peut libérer des quantités infinies de marais-hoppers, jusqu'à destruction.

CONSEILS:

- Si elle n'est pas éliminée rapidement, elle va bientôt envahir tout le lieu avec des sauterelles de marais.
- Quand il sera tué, il libérera une plus grande quantité de sauterelles de marais sur la mort, alors attention.