COUPE DE MOOSHROOM BROWN DU MINECRAFT


CLASSE:      Vache brune
MÉTABOLISME: Mammifère à sang chaud
PERCEPTION: Animaux sauvages / fongiques
TAILLE:       5,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Faible
ARMES:    Aucune
RÉCOMPENSE:     150 FC
MENACE:     Faible

DESCRIPTION:

La Vache brune est une espèce inhabituelle de Biome de Champignon, une fusion de chair de vache organique et d'un écosystème fongique. Les champignons bruns avec des taches beiges poussent sur le dos, et son corps est recouvert de cuir de vache tacheté rougeâtre.

CONSEILS:

- Les soupes de champignons sont un moyen rapide de reconstituer la santé et la satiété.
- Après avoir coupé les champignons, elle deviendra une vache ordinaire.
