MODÈLE DE RIFLE DE MOINS 1891/30


ARME: Modèle de ricochet Mosin-Nagant 1891/30
MUNITIONS:   7,62 x 54 mm R
CADENCE DE TIR:    ~10 tours/min
POIDS: ~4,5 kg

DESCRIPTION:

Le fusil Mosin-Nagant, plus connu sous le nom de "Three-Line" ou "Mosinka", est un fusil à effet de boulon, à répétition adopté par l'Empire russe en 1891. L'arme a survécu à de nombreuses guerres et modernisations, restant en service dans divers pays pendant de nombreuses décennies.

Le fusil tire la puissante cartouche R 7,62x54mm et dispose d'un chargeur fixe. Après chaque tir, le tireur actionne manuellement le boulon, éjecte la cartouche épuisée et en chambre le tour suivant. Le magazine est chargé de clips à cinq tours.

La Mosinka se distingue par sa conception simple et robuste, sa bonne gamme et sa puissance relativement élevée. Des variantes d'infanterie, de dragon, de carbine et de sniper existaient, de sorte que l'arme était utilisée dans une grande variété de conditions.

REMARQUES:

- Particulièrement efficace à moyenne et longue portée, où la puissante cartouche de fusil brille vraiment.
- Sa conception simple rend le fusil adapté pour une utilisation dans des conditions difficiles.
- Un tireur expérimenté peut utiliser le boulon assez rapidement, malgré le rechargement manuel.
- La Mosinka a survécu à tant d'époques que certains adversaires peuvent être plus jeunes que le fusil lui-même.
