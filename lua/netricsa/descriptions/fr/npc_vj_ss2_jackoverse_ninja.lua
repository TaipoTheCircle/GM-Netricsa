DARK NINJA DÉCIPLE MAÎTRE DES ARTS DARK DU FANG CHI


CLASSE:      Disciple noir Ninja maître des arts sombres
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Disciple des arts sombres
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Très élevé
ARMES:    Fists, jambes, techniques de combat, Shurikens
RÉCOMPENSE:     250 FC
MENACE:     Moyenne

DESCRIPTION:

Ils étaient autrefois des élèves ordinaires des écoles d'arts martiaux, mais après avoir tourné le dos aux traditions de leurs mentors, ils ont rejoint leur nouveau maître et ont pleinement embrassé ses enseignements brutaux.

Contrairement aux guerriers ordinaires, les disciples noirs suivent une formation complète en arts martiaux. Ils sont hautement qualifiés dans le combat main à main, capables de fermer rapidement la distance et d'attaquer leurs adversaires avec une série de frappes et de lancers shuriken.

Le maître des arts noirs enseigne à ses disciples non seulement les techniques de combat, mais aussi diverses techniques interdites. Les étudiants sont capables de donner des coups de pied puissants, effectuer des attaques de saut, et en utilisant des combinaisons pointues de frappes qui leur permettent d'abattre rapidement un adversaire.

Cependant, leur dévotion au Maître des Arts Noirs a un inconvénient. Ils ne reculent presque jamais seuls, même lorsque la situation devient désespérée. Pour eux, la défaite signifie non seulement la défaite, mais la honte devant leur professeur.

Lorsque le maître des arts sombres a commencé sa rébellion contre son professeur, ces étudiants sont devenus sa force centrale. Ils ont participé à la capture des étudiants du Master of Martial Arts, gardé les captifs, et ont combattu ceux qui ont essayé de les libérer.

Plus tard, ils ont dû affronter le maître des arts martiaux lui-même. Malgré sa supériorité numérique, sa compétence était suffisante pour franchir leurs rangs et atteindre leur mentor.

CONSEILS:

- Ne les laissez pas vous entourer. Un groupe de disciples sombres est beaucoup plus dangereux qu'un seul combattant.
- Gardez vos distances. Au combat rapproché, ils peuvent rapidement déclencher une série d'attaques.
- À long terme, lancez deux shurikens.
- Utilisez des armes à feu rapide pour les empêcher de fermer la distance.
- Les explosifs sont particulièrement efficaces contre plusieurs disciples rassemblés autour d'une seule cible.
