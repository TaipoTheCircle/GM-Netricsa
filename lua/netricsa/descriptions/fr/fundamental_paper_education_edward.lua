EDWARD DE L'ENSEIGNEMENT DU PAPIER FONDAMENTAL


CLASSE:      Édouard
MÉTABOLISME: Organisme anthropomorphe du papier
PERCEPTION: Inventeur-Bully
TAILLE:       ~3,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Appareils faits maison, griffes pointues, queue
RÉCOMPENSE:     30 FC
MENACE:     Moyenne

DESCRIPTION:

L'un des trois principaux tyrans de l'école de papier, avec Oliver et Zip. Reconnaissable par ses cheveux blancs, ses petites cornes noires, ses lunettes rondes et sa queue noire ressemblant à une queue de diable. Il a des mains et des pieds noirs avec des doigts pointus. Il porte une chemise noire et blanche et de grandes bottes. Contrairement à la force brute d'Oliver, Edward est une brute débrouillarde et technologique. Il a créé le drone qu'il a utilisé pour enlever Claire et la jeter dans la fosse. Il s'intéresse probablement aux sciences et à l'ingénierie. Comme ses complices, il est un favori de Miss Circinus et jouit de l'impunité. Il possède une résilience accrue.

CONSEILS:

- Méfiez-vous de son intelligence et de ses dispositifs technologiques.