FNX45 PISTOLE AUTOCHTONE


ARME:     FNX-45
AMMUNITION: .45 cartouches ACP
CADENCE DE TIR:        ~30 tours/min

DESCRIPTION:

Un pistolet à chargement automatique fabriqué conjointement par la Belgique et les États-Unis, une partie de la ligne FNX. Introduit en 2012 pour la cartouche ACP .45.

REMARQUES:

- Un excellent pistolet fiable, très bien adapté pour le transport.



