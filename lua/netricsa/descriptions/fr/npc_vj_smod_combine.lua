COMBINE S.E.C.U. SOLDIER


CLASSE:      Combiner S.E.C.U. Soldat
MÉTABOLISME: Augmenté Humain
PERCEPTION: Infanterie d'assaut
TAILLE:       5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Haut
ARMES:    OICW, AR2, SPAS-12
RÉCOMPENSE:     850 FC
MENACE:     Haut

DESCRIPTION:

Combinez les soldats de S.E.C.U. sont les Marines américains survivants qui ont survécu à l'enfer de Black Mesa. Ceux qui n'ont pas été déchirés par les créatures de Xen ont finalement affronté un ennemi bien plus impitoyable - le Combiné. Certains ont été éliminés en tant que témoins potentiellement dangereux, mais les plus expérimentés, disciplinés et moralement brisés ont été recrutés de force.

Le Combiné a évalué leur expérience de combat comme « exceptionnellement utile ». Contrairement aux soldats de Surveillant standard, les U.S.E. ont conservé un degré important de pensée autonome et de flexibilité tactique - juste assez pour être utiles et sécuritaires. Ils ont subi une augmentation partielle, améliorant leurs réflexes et supprimant le stress post-traumatique, mais leur personnalité n'a pas été complètement réécrite.

Ils portent un camouflage bleu. Certains portent des respirateurs noirs, d'autres des balaclavas et des casques tactiques anciens, légèrement modifiés avec la technologie Combine.

CONSEILS:

- Ne les sous-estimez pas, ce ne sont pas des recrues Overwatch, mais des survivalistes vétérans.
- Ils sont dangereux dans les espaces confinés, surtout avec SPAS-12.
- Ils agissent parfois avec des manœuvres et des embuscades non conventionnelles.
- Derrière leur sang-froid, les souvenirs de Black Mesa... Freeman, et la colère est toujours à l'abri.