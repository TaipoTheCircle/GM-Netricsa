ICE PLANET


PLANET:       Planète de glace
TYPE:         Planète terrestre, Cryo-World
CLIMATE:      Gel profond
MOONS:        Inconnu
TERRAIN:      Couverture de glace solide, plans d'eau non congelés, ponts de glace
LOCATION:     Système étoile inconnu
NATIVE RACES: Eléments de glace, Mamutman des neiges, Mamuts des neiges, Bête des neiges
ALLIANCE:     Horde mentale
LOCATIONS:    Pont de glace, Monolithes noirs, Camps de Mamutman

DESCRIPTION:

La planète glacée est un monde complètement recouvert de glace, rappelant visuellement les régions polaires de la Terre, comme l'Antarctique. Sa surface est constituée de champs de glace interminables, entrecoupés de zones ouvertes d'eau non gelée.

Les habitants indigènes de la planète sont des créatures élémentales de glace composées de glace pure.

Snow Mamutman-une race humanoïde primitive adaptée aux conditions froides difficiles-habitent également la planète. Les Mamutmans utilisent des Mamuts de neige, des créatures volumineuses et chaotiques ressemblant à des mammouths comme des animaux de meute et pour la bataille. Les boules de neige constituent une menace distincte.

Au fond des champs de glace s'élèvent deux mystérieuses structures monolithes noires d'origine inconnue, accessibles uniquement par un long pont de glace couvrant des eaux non gelées.

KEY LOCATIONS:

- Pont de Glace : Une traversée au-dessus des eaux non gelées menant à deux mystérieux monolithes noirs.
- Monolithes noirs : Deux structures mystérieuses d'origine inconnue, situées de l'autre côté du pont de glace.
- Camps de Mamutman : Établissements de la race humanoïde locale, où sont conservés les Mamuts des neiges apprivoisés.
