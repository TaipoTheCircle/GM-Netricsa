GRANDE ANGEL, RYAN


CLASSE:      Un grand ange, Ryan
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:    Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     100 FC
MENACE:     Annoyance

DESCRIPTION:

Big Heads sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme de Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan", ils gagnent du feu et des modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Ryan est l'un des "cerveaux" les plus énigmatiques du panthéon Croteam. Contrairement à ses collègues avec des crédits détaillés, ses contributions restent indéchiffrables, comme un artefact effacé sur un ancien rouleau. Son crâne surdimensionné tient un secret: peut-être a-t-il corrigé un bug critique la dernière nuit avant le maître d'or, écrit le script pour un œuf de Pâques oublié, ou tout simplement livré cette pizza qui a sauvé l'équipe pendant la crise. Son nom est perdu dans les annales du développement, mais le fait qu'il soit sur la liste est une preuve irréfutable qu'il a contribué quelque chose.

Il est un rappel que derrière chaque jeu emblématique se trouve non seulement le génie des développeurs principaux, mais aussi les contributions tranquilles de dizaines de "quelques-uns", sans qui le produit final serait juste un peu moins parfait.

Il était une fois vivant, mais après que quelqu'un l'ait tué, il a été ressuscité - devenir un ange.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager le chemin.
- Sur la difficulté "Je suis Ugh-Zan", les détruire à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.
