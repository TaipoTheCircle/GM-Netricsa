AU TEMPS DU COMPLEXE DE SÉCURITÉ


On est arrivés ! La destination est le complexe de sécurité Black Mesa. Le passage est autorisé. On dirait que ton déguisement fonctionne jusqu'ici.

Mais avant d'entrer, tournez-vous. Il y a un autre train derrière toi. Il y va. Pas le Sam qui a été confondu avec Freeman. Pas un doppelganger. Réel. Gordon Freeman. Vous êtes en retard ? Ou peut-être que tout se passe selon un calendrier invisible ?

Il passe, silencieux, concentré, avec ce look caractéristique de Rock. Et quelque part dehors, derrière les murs, l'horloge tourne déjà avant le désastre.