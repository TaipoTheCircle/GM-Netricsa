Cannon rotatif ROTANT CANNON


CLASSE:      Cannon rotatif
MÉTABOLISME: machine
PERCEPTION: système de défense automatique
TAILLE:       12 pieds
VIEW ANGLE: 360 degrés 
HOSTILITÉ:  élevé
ARMES:    boulettes de canon
RÉCOMPENSE:     1000 FC
MENACE:     élevé

DESCRIPTION:

Mental a été étonné par le concept de votre arme la plus puissante et a donc essayé de créer quelque chose de similaire. Mental amélioré un canon médiéval ordinaire avec un système de chargement automatique, radar et des munitions réapprovisionner, ce qui en fait une unité de défense autonome assez efficace et dangereuse. La version améliorée de ce dispositif est placée sur une base tournante qui lui permet une attaque complète de 360 degrés.

CONSEILS:

- Évitez les boulettes de canon par mouvement constant.