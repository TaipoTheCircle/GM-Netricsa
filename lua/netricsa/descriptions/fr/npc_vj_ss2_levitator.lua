LÉVITATEUR, SOL DU MAGNOR


CLASSE : Lévitateur, Sol
MÉTABOLISME : Véhicule habité
PERCEPTION : Véhicule de reconnaissance
TAILLE : 74,8 pieds
ENDURANCE : Faible
HOSTILITÉ : Moyenne
ARMES : Canon à plasma
RÉCOMPENSE : 150 FC
MENACE : Moyenne

DESCRIPTIF :

Il s'agit d'aéroglisseurs conçus pour patrouiller les bases avancées de Mental et repérer l'armée principale. Leurs moteurs leur permettent de naviguer sur n’importe quel terrain sans problème et même de voler à basse altitude. Cependant, pour léviter, ils nécessitent un cadre léger, ils ont donc une armure très légère.

Il semble s'agir d'une femme humanoïde extraterrestre à la peau bleue, suspendue dans une sphère translucide contenant une sorte de liquide. Cet extraterrestre est peut-être inoffensif en soi, mais il se trouve dans un transport équipé d'un canon à plasma qui, comme tous les canons, tentera de vous achever. La structure sphérique peut planer, lui permettant de se déplacer librement dans les airs.

Les capsules Levitator ont été développées après que Mental ait acquis le Magnor, car il avait besoin de quelque chose pour fouiller les marais et localiser le médaillon. Ne laissant rien au hasard, Mental a également conçu les capsules pour fonctionner sous l’eau. Cependant, en raison du coût élevé des soldats zombies dans les usines Toyodo en Enfer, Mental a dû dégrader la qualité du matériau utilisé pour fabriquer les capsules, les fabriquant à partir de verre fragile et bon marché.

Les Lévitateurs tirent avec leurs canons à plasma de faible puissance sur les ennemis. Ils servent principalement de distraction pour l'armée principale, ils devraient donc être assez faciles à détruire.

Une caractéristique distinctive est la capacité du Lévitateur à régénérer sa santé. Mais encore une fois, cela se produit lentement, donc plus vous le détruisez rapidement, plus il est probable qu'il ne puisse pas se régénérer.

CONSEILS :

- Évitez leurs attaques en esquivant sur le côté.
- Ils ont une armure très légère ; quelques balles ou n'importe quel explosif suffiront à résoudre ce problème.
- Un coup de fusil de chasse à bout portant suffit à les éliminer.
- Certains d'entre eux peuvent voler, tandis que d'autres restent près du sol.