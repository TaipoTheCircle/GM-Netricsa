SITE DE CONSTRUCTION EN URSS, TEMPS NUIT


Un chantier familier a été transporté dans les années 1970, dans les pays du Bloc socialiste.

Et tu sais, c'est même confortable ici. Aucune de ces sombres "dépressions des années 90".

Juste lumineux (littéralement) rétro.

Tout cela a lieu en été. Beaucoup de verdure, un lac, un champ, un village à l'horizon. Et oui, il y a de la musique.

Si ça commence à vous distraire de sauver l'humanité, il suffit de cliquer sur la source du son, et ça va s'éteindre.
:
Un endroit idéal pour les embuscades dans les appartements et les cours. Les fenêtres cassées ajoutent de la profondeur tactique – vous pouvez sauter à travers eux de grenades ou, inversement, s'envoler en criant "Pour la patrie!".

Et la bibliothèque... les livres qui brûlent doivent être beaux. Allons explorer l'espace vital, Sam. N'entrez pas dans des appartements sans frapper - il y a soudain un bibliothécaire avec une hache.
