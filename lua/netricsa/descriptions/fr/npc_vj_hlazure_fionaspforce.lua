FIONA, LE COMMANDANT NOIR


CLASSE:      Fiona, le commandant d'assaut des opérations noires
MÉTABOLISME: Humain, femme
PERCEPTION: Black Ops Assassin Leader
TAILLE:       ~5,9 pi
ENDURANCE:  Haut 
HOSTILITÉ:  Extrême
ARMES:    Beretta
RÉCOMPENSE:     5000 FC
MENACE:     Catastrophes

DESCRIPTION:

Fiona est le commandant de la division Black Ops Assassin, un chef impitoyable qui dirige des opérations secrètes pendant l'incident Black Mesa. Contrairement aux assassins standard, elle opère au plus haut niveau, en coordination directe avec les forces spéciales du secteur Delta et l'homme mystérieux en costume d'affaires avec une mallette.

Son équipe se spécialise dans les grèves chirurgicales, la récupération des renseignements et l'élimination totale des témoins. Fiona elle-même est plus rapide, plus morte et beaucoup plus disciplinée que les assassins réguliers, incarnant la précision du commandement Black Ops. Son partenariat avec l'homme mystérieux dans le costume d'affaires associés suggère qu'elle est profondément ancrée dans le programme interdimensionnel plus large derrière l'incident.

CONSEILS:

- Ne luttez jamais, elle est évasive.
Elle attaque rarement sans renfort.
- Surveillez les frappes coordonnées avec les forces du Secteur Delta.
- Son alliance avec l'homme de la mallette indique des objectifs au-delà du simple combat.
