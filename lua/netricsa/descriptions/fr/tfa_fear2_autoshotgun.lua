VOLLMER ULTRA92 SHOTGUN SÉMI-AUTOMATIQUE


ARME: Vollmer Ultra92 fusil semi-automatique
MUNITIONS:   12 calibres
ACTION: Semi-automatique

DESCRIPTION:

Un fusil de chasse semi-automatique moderne utilisé par Replica unités lourdes. Développé par la société Vollmer, il est conçu pour des engagements de combat intenses à courte ou moyenne portée. Il utilise une action à gaz et un magazine de 12 tours amovible.

Alors que l'Ultra92 est en deçà du fusil SHO Series-3 en termes de puissance brute par tir, il compense avec un taux de tir plus élevé, un motif de tir plus serré et un rechargement plus rapide. Contrairement aux fusils à pompe classiques, le magazine entier est remplacé, ce qui permet à l'utilisateur de revenir rapidement au combat.

REMARQUES:

- Utilisé par Replica infanterie lourde.
- Le magazine compte 12 tours (10 tours en mode multijoueur).
- Basé sur une combinaison de caractéristiques de conception du Heckler & Koch CAWS et du Franchi SPAS-12.
- Malgré son nom, il ne dispose pas d'un mode de tir entièrement automatique.
- L'arme est rechargée en échangeant l'intégralité du magazine plutôt que de charger des obus individuels — une commodité que tout soldat apprécierait.
