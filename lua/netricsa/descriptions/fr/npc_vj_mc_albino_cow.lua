ALBINO COW DE L'OUVERTURE MINECRAFT


CLASSE:      Vache Albino
MÉTABOLISME: Mammifère chaud
PERCEPTION: Animaux passifs
TAILLE:       ~4,6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Faible
ARMES:    Aucune
RÉCOMPENSE:     50 FC
MENACE:     Minimal

DESCRIPTION:

Une variété extrêmement rare de vaches, répertoriée comme un exemple de «pauvreté chez les animaux est assez rare». Il diffère des vaches ordinaires dans sa fourrure entièrement blanche et sa peau pâle. Ses sabots sont brun clair, ses cornes sont beiges, son nez est rosé, et ses yeux sont rouges pâles, le marquant comme un vrai albinos.

An albino cow behaves no differently from a normal cow: il erre dans les prairies, les landes, respire et évite l'eau, la lave et les falaises. Lorsqu'il est endommagé, il s'enfuit pendant quelques secondes et revient ensuite à ses activités passives.

Sinon, c'est une vache normale, juste très pâle et avec des yeux rouges, ce qui lui donne un look légèrement fou, bien qu'il ne l'ait pas su.

CONSEILS:

- Une excellente exposition pour un collectionneur de foules rares.
- Si vous avez un stylo de telles vaches, prenez soin d'eux.
- Ils laitent, produisent de la viande et du cuir, et moo.
- Les yeux rouges ne brillent pas dans le noir.
