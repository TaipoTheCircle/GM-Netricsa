DE ZENOZOIK


CLASSE:      Poule
MÉTABOLISME: Avian
PERCEPTION: Oiseaux domestiques / sauvages
TAILLE:       1,5 pi
ENDURANCE:  Très bas
HOSTILITÉ:  Pratiquement absent
ARMES:    Bec
RÉCOMPENSE:     2 FC
MENACE:     Négligiblement faible

DESCRIPTION:

Un oiseau sauvage commun dans les colonies et à la périphérie de Zenozoik. Contrairement aux corbeaux, les poulets sont caractérisés par une intelligence extrêmement faible et un manque total de capacité de combat. Leur comportement est caractérisé par un vol chaotique à toute menace. Ils sont célèbres pour être la cible d'un acte particulier de force brute dans le monde de Zenozoik - leurs têtes sont souvent arrachées. Ils ne se rassemblent pas dans des troupeaux agressifs, mais peuvent créer de la panique en se mettant au hasard sur le chemin.

CONSEILS:

- Les attaquer est inutile et peut attirer une attention inutile.
- Sans défense. Ils ne posent aucune menace, mais ils peuvent accidentellement provoquer l'agression d'autres créatures s'ils sont chassés.
- Il y a des rumeurs de poulets qui ont explosé.
