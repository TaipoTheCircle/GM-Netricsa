PISTOLE DE WALTER P22


ARME:           Walther P22
MUNITIONS:             22 LR
CADENCE DE TIR:              15 tours/min

DESCRIPTION:

Le pistolet Walther P22 est un pistolet de sport et d'entraînement de calibre 22 allemand fabriqué par Carl Walther Sportwaffen GmbH. Le cadre du pistolet est fait de polymères résistants aux chocs, tandis que le canon et la lame sont en acier. Il est équipé d'un mécanisme de déclenchement à double action. Les dispositifs de sécurité comprennent une sécurité mécanique, une sécurité automatique qui verrouille le mécanisme lorsque le chargeur n'est pas correctement inséré, et une serrure qui verrouille le cadre de la diapositive, empêchant le tir et le démontage. Le modèle P22 ressemble au modèle précédent Walther P99, mais il est d'environ un quart plus court. Le pistolet est livré avec des vues interchangeables et des panneaux d'adhérence pour permettre de personnaliser l'arme à la main du tireur.

REMARQUES:

- Vous pouvez y attacher un silencieux et être un tueur silencieux.
- Le fait qu'il s'agit d'un pistolet de sport le rend moins efficace au combat que les pistolets conventionnels.
- Un descendant lointain du bon vieux Walther P38.
