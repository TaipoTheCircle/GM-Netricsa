LE CREEPER GHST DU MINECRAFT


CLASSE:      Ghost Creeper
MÉTABOLISME: Entité éthérée autre que mondiale
PERCEPTION: Le fantôme de Creeper, Ethereal Undead
TAILLE:       5,5 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Variantes
ARMES:    La crise d'énergie éthérée
RÉCOMPENSE:     200 FC
MENACE:     Moyenne

DESCRIPTION:

C'est une variante de l'Elemental Creeper qui apparaît comme une créature grise translucide. C'est l'incarnation de l'essence résiduelle d'un Creeper qui est mort, mais au lieu de disparaître dans l'oubli, il reste gelé entre les mondes.

Il peut passer par la foule.

La caractéristique principale du Ghost Creeper est son explosion. Il ne détruit pas les blocs, mais émet plutôt une vague d'énergie éthérée pure quand il explose. Cette vague est mortelle pour toutes les créatures vivantes dans son rayon, mais elle est complètement sûre pour l'environnement.

Malgré leur nature fantomatique, ces rampants sont encore vulnérables à l'acier et à la magie, bien que les attraper hors de garde peut nécessiter une agilité remarquable ou l'utilisation d'équipements spéciaux.

CONSEILS:

- Si vous rencontrez un Ghost Creeper, ne paniquez pas. Vous pouvez essayer de l'éviter, car sa vitesse est lente, sauf si elle est dans un paquet.
- Ne le combattez jamais à l'intérieur. Bien qu'il ne détruise pas les blocs, son attaque est difficile à éviter dans un couloir étroit.
- Une arme à haut dommage ou l'enchantement "Strength" sur un arc aidera à le tuer avant qu'il ne commence à charger son explosion.
