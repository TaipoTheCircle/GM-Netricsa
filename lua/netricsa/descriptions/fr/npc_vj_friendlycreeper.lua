CREEPER AGRICOLE DU MINECRAFT


CLASSE:      Crèche amicale
MÉTABOLISME: Poudre végétale
PERCEPTION: Mob passif, animal de compagnie Tamable
TAILLE:       5,5 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Faible
ARMES:    Microexplosion
RÉCOMPENSE:     50 FC
MENACE:     Moyenne

DESCRIPTION:

C'est un flippant rose. Contrairement à ses frères verts et agressifs, cette variété rampante est totalement passive et même amicale. Sa couleur rose n'est pas seulement une texture, mais un marqueur de sa nature paisible, une sorte de « sceau de qualité » pour ceux qui sont fatigués d'exploser toutes les cinq minutes.

Contrairement à d'autres membres de son espèce, ce rampant prend tout calmement. Il ne siffle pas dans le noir, ne se faufile pas derrière vous, et ne détruit pas les structures. Même si quelqu'un arrive accidentellement, il ne réagira pas avec l'agression, mais il partira tout simplement.

Pour dompter un Crèche ami, vous devez le nourrir de poudre. Après cela, un cœur apparaît sur sa poitrine, et le malade devient un animal loyal.

Il suit son maître comme un loup apprivoisé.

Il attaque les foules hostiles en utilisant des microexplosions qui endommagent les ennemis.

Le flippant lui-même reste indemne.

Pour guérir un Crèche ami, vous pouvez lui donner des fleurs.

CONSEILS:

- N'essayez pas de tuer un Crise ami. Ce n'est pas seulement cruel, mais aussi inutile.
- Si vous trouvez un rampant rose, domptez-le immédiatement. C'est l'une des rares mafia qui te protégera au lieu de te tuer.
- L'abattage nécessite de la poudre à canon, qui peut être obtenue à partir de rampeurs réguliers.
- Au combat, le Friendly Creeper est efficace contre les hordes de petites foules comme les zombies et les squelettes.
- N'essayez pas de l'utiliser pour l'exploitation des ressources. Les explosions ne détruisent pas les blocs.
- Si vous avez plusieurs rampants rose apprivoisés, ils peuvent travailler dans un paquet. Cela agit comme un petit groupe d'explosifs rose qui vous protège de tous les malheurs du Nether et du Overworld.
