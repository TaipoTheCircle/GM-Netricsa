KS-23 CARBINE SPÉCIALE


ARME: KS-23 Carbine spéciale
MUNITIONS:   23x75mm R
CADENCE DE TIR:    4 à 5 tours/min

DESCRIPTION:

Une carbure à usage spécial de gros calibre soviétique, développée au début des années 80 par l'Institut de recherche pour les équipements spéciaux du Ministère de l'intérieur de l'URSS (MVD), en collaboration avec l'Institut central de recherche scientifique pour l'ingénierie des machines de précision (TsNIITochMash). Elle a été adoptée en 1985 et destinée aux services du Ministère de l ' intérieur. Elle est employée pour réprimer les émeutes massives, appréhender les délinquants et mener des opérations policières spécialisées. L'arme est remarquable pour son calibre de 23 mm et son canon fusillé, qui ont été fabriqués à l'aide de ébauches destinées à l'origine aux canons d'aéronefs.

La carbine fonctionne au moyen d'un mécanisme manuel d'action de la pompe, avec l'avant lié au boulon. Il utilise des cartouches R spécialisées de 23x75mm. Les munitions sont alimentées à partir d'un magazine tubulaire sous-barrel d'une capacité de 3 tours, avec un tour supplémentaire pouvant être maintenu dans la chambre. Il est équipé d'un matériel en bois, de vues mécaniques ouvertes et d'un canon à fusil. Une vaste gamme de munitions spécialisées, conçues à diverses fins, a été mise au point pour cette carbine.

REMARQUES:

- Développé pour les besoins du Ministère de l ' intérieur de l ' URSS.
- Adopté pour le service en 1985.
- Avec un canon de 23 mm.
- Le magazine tient 3 tours, avec un tour supplémentaire dans la chambre.
- Les variantes comprennent le KS-23M "Drozd" et le KS-23K.
