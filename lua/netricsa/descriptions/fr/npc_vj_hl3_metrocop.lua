INTERCEPTEUR DE PROTECTION CIVILE COMBINE


CLASSE:      Combiner l'intercepteur de protection civile
MÉTABOLISME: Humain, Homme
PERCEPTION: Combiner l'Unité de protection civile de l'Arctique, Intercepteur
TAILLE:       6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    SMG3 (HK MP7), Manhack
RÉCOMPENSE:     250 FC
MENACE:     Moyenne-élevée

DESCRIPTION:

L'Intercepteur de Protection Civile Combine est une unité de Protection Civile spécialisée, adaptée aux opérations dans les régions neigeuses et arctiques. Ces unités servent à patrouiller les villes glacées, les stations polaires et les régions éloignées où les forces standard du CP perdent leur mobilité et leur orientation.

Il porte un costume de protection camouflage gris et blanc qui se marie avec le paysage enneigé. L'uniforme est renforcé par des ceintures, des pochettes et des supports d'équipement conçus pour des opérations longues et sans surveillance à froid extrême. Les armures noires protègent le torse, et les bottes noires lourdes assurent la stabilité sur la glace et la neige.

Leur principale caractéristique est un masque avec deux grands objectifs bleus brillants qui servent d'imagerie thermique et de capteurs de vision nocturne. Ces lentilles permettent à l'Intercepteur de détecter des cibles à travers des blizzards, du brouillard et des rideaux de neige, ce qui en fait une mauvaise visibilité.

Ils sont armés d'un SMG3 (HK MP7), une arme à feu rapide compacte idéale pour un combat à portée étroite et moyenne dans des espaces confinés. Si nécessaire, l'Intercepteur peut déployer le Manhack, l'utiliser pour la reconnaissance, la poursuite de fugitifs ou la pression atmosphérique.

Les intercepteurs agissent rapidement, se livrent rarement à des combats prolongés et préfèrent des tactiques de pression, d'encerclement et de finissage.

CONSEILS:

- Ne comptez pas sur la couverture dans une tempête de neige- ses capteurs sont meilleurs qu'ils apparaissent.
- Le Manhack est souvent utilisé pour désorienter avant une attaque.
- Le MP7 est mortel à proximité en raison de son taux élevé de feu.
