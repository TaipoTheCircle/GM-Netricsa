ARMES AMÉLIORÉES DE GRANDE (LANCE-DISC)


ARME: Arme improvisée (Luncher disc)
MUNITIONS:   Disques métalliques
CADENCE DE TIR:    Modéré

DESCRIPTION:

Une arme d'insurgé maison fabriquée à partir de composants récupérés et de pièces de machines industrielles. Il s'agit d'un appareil lourd doté d'un mécanisme de coupe tournant, conçu pour neutraliser le personnel ennemi. Il tire des disques métalliques tranchants à grande vitesse, faisant de la ferraille ordinaire des projectiles mortels.

Le moteur a besoin de temps pour atteindre la vitesse de rotation nécessaire, ce qui entraîne un léger retard avant le tir. Le mode de tir primaire lance des disques de coupe tournants, tandis que le mode secondaire permet à l'utilisateur de frapper un ennemi avec le châssis d'arme. Il peut être amélioré pour réduire le temps de rotation, augmenter la capacité de munitions et permettre l'utilisation de disques explosifs.

REMARQUES:

- Efficace contre les soldats EDF à courte ou moyenne portée.
- Un coup de tête avec un disque peut tuer un ennemi instantanément.
- Pratiquement inutile pour détruire des bâtiments ou des structures lourdes.
- Construit par des insurgés utilisant des pièces et des équipements industriels.
- On peut passer aux disques explosifs.
