LAVA GNAAR MALE DE LA PLANTE DE LAVA


CLASSE:      Lava Gnaar, Homme
MÉTABOLISME: Mammifère
PERCEPTION: Bête de guerre entraînée
TAILLE:       4 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Morceaux, coups de poing
RÉCOMPENSE:     600 FC
MENACE:     Faible

DESCRIPTION:

Un petit animal bipède sans tête, un œil et une grande bouche. Originaire de Sirius, et entraîné par Mental à attaquer les forces opposées. Les mâles sont plus petits, rouge vif de couleur et pas aussi dur que les femelles.

Les Gnaars de lava sont étroitement liés aux Gnaars réguliers, mais ils se sont pleinement adaptés à la vie sur une planète volcanique couverte de mers de lave, de roches brûlantes et d'éruptions constantes. Leur peau a acquis une teinte rouge vif et est devenue significativement plus épaisse, protégeant leur corps des températures extrêmement élevées.

Ils rôdent sans cesse les terres de déchets volcaniques à la recherche de proies et défendent farouchement leur territoire.

Malgré leur intelligence primitive, ils n'hésiteront pas à sauter sur leurs adversaires, en essayant de les déchirer avec leurs mâchoires puissantes et de longues griffes.

CONSEILS:

- Ils n'ont pas d'armes, gardez vos distances.
- Certains spécimens peuvent voler.
- Il y a des rapports de Gnaars invisibles.
