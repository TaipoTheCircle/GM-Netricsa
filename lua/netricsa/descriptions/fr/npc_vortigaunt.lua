VORTIGAUNT DE XEN


CLASSE:      Vortigaunt
MÉTABOLISME: mammifères intelligents (réfugié de Xen)
PERCEPTION: Race Alien intelligente
TAILLE:       6 pieds
ENDURANCE:  moyenne-élevée
HOSTILITÉ:  faible (par rapport à la résistance)
ARMES:    éclair vert, rituels de guérison, connaissance de la ruche
RÉCOMPENSE:     520 FC
MENACE:     élevé

DESCRIPTION:

Après la chute du Nihilanth, les Vortigaunts furent libérés de l'esclavage psychique. Beaucoup ont fui vers la Terre, où ils ont rejoint la Résistance de l'humanité contre le Combiné. Philosophiques et profondément spirituels, ils vénèrent la "Vortessence", un champ psionique partagé qui relie leur espèce. Ils apparaissent comme des alliés, guérissant les blessés et maniant même leur foudre contre les soldats et les fourmis. Une fois ennemis, ils sont maintenant des compagnons de confiance.

CONSEILS:

- Les protéger au combat; ils constituent un soutien inestimable.
- Surveillez leurs rituels, ils peuvent guérir et autonomiser les alliés.
- Ils en savent plus sur le destin et le Combiné qu'ils ne le révèlent.
