RÉACTEURS BLACK MESA LAMBDA, QUITTER AVANT LA PROCHAINE TOUR


Le couloir s'ouvre dans une petite salle de contrôle. À l'intérieur, un seul scientifique se tient, pâle, branché, et refuse absolument de jouer au héros. Il n'ouvrira pas la porte tant qu'il n'est pas certain que la zone immédiate est claire - pas « presque morte », pas « probablement morte », mais définitivement morte. La paranoïa est un excellent trait de survie dans cet endroit, et il l'a en pique.

Ils veulent remettre le prototype de Gluon Cannon - une mauvaise petite réponse à de très gros problèmes. C'est dangereux, expérimental, et précisément le genre de chose que vous voulez quand la prochaine vague n'est pas seulement un autre ensemble de grognements.

Mission snapshot:

Objective: clarifier les couloirs immédiats et confirmer « aucune signature hostile » au scientifique.

RÉCOMPENSE: l'accès au canon Gluon et l'entrée complète dans la zone centrale du réacteur.