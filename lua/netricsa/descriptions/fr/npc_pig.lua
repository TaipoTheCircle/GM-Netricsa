PIG DOMESTIQUE DU ZENOZOIK


CLASSE:      Porc domestique
MÉTABOLISME: Mammifères, ongulés à orteil uniforme
PERCEPTION: Animaux sauvages / domestiques
TAILLE:       1,6 ft
ENDURANCE:  Faible
HOSTILITÉ:  Aucune
ARMES:    Aucune
RÉCOMPENSE:     3 FC
MENACE:     Aucune

DESCRIPTION:

Un porc domestique commun trouvé dans les établissements et les fermes de Zenozoik. Rien de différent de ses homologues terrestres, sauf qu'il habite un monde bien étranger. Complètement inoffensif, il n'attaque ni n'interagit avec ses adversaires.

CONSEILS:

- L'attaquer est inutile et peut attirer une attention inutile.
- Lorsqu'il est frappé, il fait une masse caractéristique et se retourne maladroitement. Il ne tente pas de riposter.
