RISQUE D'ASSAULT


ARME: Rifle d'assaut
MUNITIONS:   Tours de flechette de tungstène
CADENCE DE TIR:    Haute, automatique

DESCRIPTION:

Le fusil d'assaut standard de la Force de défense de la Terre (FDE). Il sert d'arme principale pour les unités d'infanterie EDF, conçues pour des tirs automatiques soutenus contre le personnel ennemi. Il présente un taux élevé d'incendie, une bonne précision, et est très efficace dans les engagements à proximité de gammes moyennes. Il se trouve également dans les arsenaux des insurgés de la Faction Rouge et des Maraudeurs.

Il n'utilise pas des projectiles standard de 40mm ; au lieu de cela, il allume des projectiles spécialisés en flechette de tungstène (comme des darts). Il est alimenté par un magazine de 40 tours. L'arme dispose d'un mode de tir automatique, ainsi que d'une attaque secondaire à la mêlée qui permet à l'utilisateur de frapper un adversaire avec le cul du fusil. Les munitions sont largement disponibles, ce qui facilite leur réapprovisionnement.

REMARQUES:

- Efficace contre l'infanterie à proximité de portée moyenne.
- Capacité du chargeur : 40 tours.
- Utilise des munitions flechette de tungstène.
- L'arme principale de l'infanterie EDF.
- Comprend une attaque secondaire à la mêlée.
