VINDICATEUR DE L'EXPLOITATION MINECRAFT


CLASSE:      Vindicateur
MÉTABOLISME: Villageur maléfique, bandit
PERCEPTION: Vicieuse melee fighter, infanterie lourde des Illagers
TAILLE:       6,2 pi
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Axe de fer
RÉCOMPENSE:     200 FC
MENACE:     Très élevé

DESCRIPTION:

Ce psychopathe grisé prouve que les villageois peuvent être non seulement utiles mais aussi mortels. Ce sont des « villageois mauvais », ou, comme on les appelle officiellement, des Illagers. Tandis qu'un villageois normal échange avec vous et construit des fermes, un Vindicator veut simplement vous couper en deux avec une hache. Et il s'en fiche que vous soyez juste en visite.

Ces figures sombres sont apparues pour la première fois en tant que gardiens des forêts Mansions, où elles hantent encore certaines pièces. Plus tard, ils ont été repérés lors de patrouilles de bandits et, ce qui est le plus inquiétant, ils ont fait des raids dans des villages.

Le Vindicator porte une veste, un pantalon et des bottes sombres. Il a une expression sérieuse et en colère, rappelant sa parenté avec les villageois. Quand il est oisif, il se tient debout les bras croisés sur sa poitrine, comme son cousin épris de paix. Mais dès qu'il repère un ennemi (vous ou un villageois), il tire sa hache de fer et charge.

La principale caractéristique du Vindicator est l'agressivité et la vitesse incroyables. Il court vers sa cible plus vite que la vitesse de marche du joueur, donnant des coups dévastateurs avec sa hache. Cette hache n'est pas juste dangereuse, elle peut pénétrer les boucliers, les désactiver pendant 5 secondes.

Contrairement à leurs proches Forsworn, les Vindicators peuvent briser les portes en bois lors de raids sur les difficultés normales et difficiles (comme les zombies, seulement plus vite).

CONSEILS:

- Si vous n'êtes pas armé, n'approchez pas. Une hache peut être fatale.
- Utilisez un arc ou arbalète. Garder votre distance contre un Vindicator est la meilleure stratégie.
- Ne comptez pas sur votre bouclier: son attaque va pénétrer, et vous allez prendre des dommages.
- Dans le Woodland Mansion, regardez les coins. Les vinaigrettes sont souvent en embuscade dans de petites pièces.
- Si vous voyez un Vindicator nommé Johnny, courez immédiatement dans la direction opposée. Il détruira non seulement vous, mais aussi toutes les autres foules sur son chemin.
