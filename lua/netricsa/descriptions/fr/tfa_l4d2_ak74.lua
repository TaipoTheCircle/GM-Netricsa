RISQUE D'ASSAULT AK-74


ARME: AK-74 Rifle d'assaut
MUNITIONS:   fusil 5,45x39, lance-grenades de 40 mm.
Rates:  700 tours/min

DESCRIPTION:

C'est l'arme principale de l'armée soviétique/russe. Il a été développé par Mikhail Timofeevich Kalashnikov en 1970 et adopté par l'armée soviétique en 1974, d'où son nom. Ce fusil d'assaut est réputé pour sa fiabilité et son efficacité; il ne se bloque guère et peut tirer même après avoir été complètement immergé dans la boue. Il a vu le service pendant la guerre d'Afghanistan, la guerre de Tchétchénie, et est actuellement utilisé dans le district militaire soviétique. Il a une version modifiée avec le suffixe "M" ; cette version a des spécifications différentes et est noire. Ce fusil d'assaut est également célèbre pour être utilisé presque partout dans le monde, principalement par des organisations terroristes, mais aussi par les militaires de divers pays. Il dispose également d'un lance-grenades sous-marin, le GP-25, qui tire des grenades de 40 mm.

REMARQUES:

- Utilisez-le pour les bâtiments ou les tranchées.
- Utilisez le lance-grenades pour chasser les ennemis de la couverture.
- Vous pouvez tirer à portée étroite, moyenne et longue.
