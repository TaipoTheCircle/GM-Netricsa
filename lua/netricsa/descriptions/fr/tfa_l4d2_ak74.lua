FUSIL D'ASSAUT AK-74


ARME : Fusil d'assaut AK-74
MUNITIONS : Fusil 5,45x39, lance-grenades sous canon de 40 mm.
Tarifs : 700 tours/min

DESCRIPTIF :

C’est l’arme principale de l’armée soviéto-russe. Il a été développé par Mikhaïl Timofeevich Kalachnikov en 1970 et adopté par l'armée soviétique en 1974, d'où son nom. Ce fusil d'assaut est réputé pour sa fiabilité et son efficacité ; il ne se bloque pratiquement pas et peut tirer même après avoir été complètement immergé dans la boue. Il a servi pendant la guerre d'Afghanistan et la guerre de Tchétchénie et est actuellement utilisé dans le district militaire soviétique. Il existe une version modifiée avec le suffixe « M » ; cette version a des spécifications différentes et est noire. Ce fusil d'assaut est également célèbre pour être utilisé presque dans le monde entier, principalement par des organisations terroristes, mais aussi par les militaires de divers pays. Il dispose également d'un lance-grenades sous le canon, le GP-25, qui tire des grenades de 40 mm.

REMARQUES :

- Utilisez-le pour prendre d'assaut des bâtiments ou des tranchées.
- Utilisez le lance-grenades sous le canon pour chasser les ennemis de leur abri.
- You can fire at close, medium, and long ranges.
