VENDU DE L'ÉLITE DE LA COMBINE À JAUNE


CLASSE:      Jaune-Eyed Overwatch Combiner Elite
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner la force de frappe Elite
TAILLE:       5,9 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    AR2 Fuseau d'impulsion, boules d'énergie
RÉCOMPENSE:     850 FC
MENACE:     Très élevé

DESCRIPTION:

Le Combine Yellow-Eyed Overwatch Elite est un soldat d'élite déguisé en soldat Combine. Son armure a le schéma de couleur bleu et blanc standard des soldats réguliers, lui permettant de se fondre dans des formations et d'accabler les ennemis dans un faux sentiment de sécurité.

Sa seule particularité est sa visière jaune. Alors que son apparence ressemble aux soldats de la prison d'élite de Nova Prospekt, son statut est considéré comme celui d'une unité régulière. C'est intentionnel : le Combine intègre ces soldats dans des unités standard pour améliorer discrètement leur efficacité de combat.

En termes d'implants, de temps de réaction et d'entraînement tactique, il est tout à fait équivalent à un soldat d'élite. Au combat, il agit froidement, coordonne le tir des soldats réguliers et est le premier à s'engager dans des cibles particulièrement dangereuses. Les boules d'énergie sont utilisées pour chasser les ennemis hors de la couverture, après quoi il termine la cible avec un tir d'impulsion précis.

CONSEILS:

- Si vous voyez une grande visière jaune parmi les soldats réguliers, c'est une mauvaise nouvelle.
- Il ressemble à un privé, mais il tire comme une élite.
- Détruisez-le d'abord, sa présence rend l'équipe plus dangereuse.
- Ne le confondez pas avec un soldat d'élite : il opère sur le terrain et est plus mobile.
