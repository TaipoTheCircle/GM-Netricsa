MP-40 SOUS-MACHINE AVEC SILENCER


ARME: MP 40 pistolet sous-machine avec silencieux
MUNITIONS:   Parabellum 9x19mm
CADENCE DE TIR:    500-550 RPM
POIDS: 8,75 livres

DESCRIPTION:

Le MP 40 est une mitrailleuse allemande classique, largement utilisée pendant la Seconde Guerre mondiale. Compact, fiable et facile à manipuler, il est devenu l'arme standard des parachutistes, des équipages de chars et des commandants de peloton d'infanterie. Son stock de métal pliant et sa forme épurée ont permis un transport efficace, et son taux de feu modéré l'ont rendu gérable au combat rapproché.

Alors que le MP 40 était moins puissant que le fusil à longue portée, il était supérieur dans les combats urbains, les embuscades et les espaces confinés où la mobilité et le feu suppressif étaient primordial. Connu pour son profil emblématique et son son distinctif, il demeure l'une des armes à feu les plus reconnaissables de l'histoire.

REMARQUES:

- Très efficace au combat rapproché.
- Capacité limitée des magazines (32 tours) - recharger fréquemment.
- L'exactitude baisse rapidement à longue portée.
- Peut être équipé d'un suppresseur et d'un grand magazine.
