RAT DE LA TERRE


CLASSE:      Rat
MÉTABOLISME: Mammifère
PERCEPTION: Environnement dangereux Rodent
TAILLE:       ~1 pi
ENDURANCE:  Faible
HOSTILITÉ:  Faible
ARMES:    aucune
RÉCOMPENSE:     5 FC
MENACE:     Négligeable

DESCRIPTION:

Rats Mesa noirs standard trouvés dans les couloirs des installations et les zones d'entretien. La plupart sont passifs et s'éloignent des humains, causant des nuisances mineures.

CONSEILS:

- Sans danger - ignorer si les objectifs ne sont pas nécessaires.
- Peut être utilisé pour distraire les ennemis dans les espaces restreints.
