ALPHA GUARD DE SÉCURITÉ


CLASSE:      Garde de sécurité, Alpha
MÉTABOLISME: Humain, Homme
PERCEPTION: Guerrier de sécurité de Mesa noir
TAILLE ~6 pi
ENDURANCE:  moyen (vestige d'armure légère)
HOSTILITÉ:  neutre pour le personnel Black Mesa, hostile aux créatures Xen et menaces externes
ARMES:    pistolet de service, baton.
RÉCOMPENSE:     150 FC
MENACE:     modérée

DESCRIPTION:

Les gardes de sécurité Alpha ont été la première vague de forces gouvernementales déployées à Mesa noire après la Cascade de résonance. Contrairement aux unités de l'U.S.E., leurs ordres priorisaient le confinement et la survie, et non l'éradication des témoins. À leur arrivée, ils ont rapidement compris le danger critique sous l'installation : une installation de missiles dissimulée, armée et instable. Toute erreur de calcul pourrait faire exploser l'ogive et anéantir la Mesa noire.
Reconnaissant la gravité de la situation, les Alpha Guards ont mis de côté les différences et ont travaillé côte à côte avec les scientifiques et le personnel de sécurité sur place. Ensemble, ils ont tenté de tenir les lignes contre les créatures Xen et de maintenir le contrôle des secteurs vitaux de l'installation, en espérant empêcher la destruction totale. Bien que légèrement équipés par rapport aux renforts ultérieurs, leur détermination à stabiliser la crise en fait une partie essentielle de la fragile défense de Black Mesa.

