LE SADISME


ARME: Épée du sadisme
MUNITIONS:   Résonance énergétique cristalline
CADENCE DE TIR:    ~75 hits/min

DESCRIPTION:

Une lame cristalline légendaire fabriquée à partir d'une émeraude verte rare d'origine inconnue. Le matériau possède un treillis super dense, permettant à la lame de couper presque n'importe quel matériau, y compris l'armure de l'Alliance et la chair de classe Strider.

Les organisateurs de HALF-QUAKE ont trouvé l'artefact dans des ruines anciennes et l'ont adapté pour le spectacle. À l'impact, l'épée crée une onde de résonance qui déchire la cible au niveau moléculaire.

REMARQUES:

- Désintègre la plupart des entités avec une seule grève.
- Efficace à proximité, catastrophiquement mortelle pour les adversaires dans les couloirs étroits.
- Il faut un wielder fort.
