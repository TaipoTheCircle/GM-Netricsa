DEMI-SÉISME 2, PIÈGE À LETTRE


Eh bien, eh bien... Regarde ça, Sam ! Tout le sol est couvert de lettres, comme si l'alphabet avait vomi dans ce couloir. Il y a un panneau au centre. Je suppose que cela ouvrira la voie. Mais voici le problème : une mauvaise lettre et vous vous transformerez en tourte à la viande. J'ai déjà compté dix façons de mourir. Dix! C'est un nouveau record, même pour toi.

...

Mais il y a un mot. Le mot que les sadiques aiment plus que toute autre chose. Vous savez, celui-là, leur "raison d'être", leur inspiration, leur jouet préféré...

S-A-D-I-S-M.

Sept lettres. Sept étapes vers la liberté. Ou à mort, si je me trompe, mais je me trompe rarement, Sam.

J'ai aussi remarqué que quelqu'un avait laissé tomber un journal ici. Ou peut-être qu’il l’a laissé là exprès – ces sadiques adorent ce genre de truc.

Allez, héros, montre à ces sadiques que tu peux déchiffrer leur alphabet !