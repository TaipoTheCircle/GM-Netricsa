HALF-QUAKE 2, LETTRE TRAP


Et bien... Regarde ça, Sam ! Tout le sol est couvert de lettres-comme si l'alphabet avait vomi dans ce couloir. Il y a un panneau au centre. Je suppose que ça ouvrira le chemin. Mais voici le problème: une mauvaise lettre et vous vous transformerez en tarte à la viande. J'ai déjà compté dix façons de mourir. Dix ! C'est un nouveau record, même pour toi.

...

Mais il y a un mot. Le mot sadique aime plus que tout. Tu sais, la raison d'être, leur inspiration, leur jouet préféré...

S-A-D-I-S-M.

Sept lettres. Sept pas vers la liberté. Ou à mort, si j'ai tort, mais rarement, Sam.

J'ai aussi remarqué que quelqu'un avait laissé tomber un journal. Ou peut-être qu'il l'a laissé là exprès, ces sadiques adorent ce genre de truc.

Allez, héros, montre à ces sadiques que tu peux casser leur alphabet !
