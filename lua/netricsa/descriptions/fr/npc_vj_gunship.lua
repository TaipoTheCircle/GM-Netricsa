GUNSHIP AUTOMATON AÉRIEN DE PATROL DU CYBESTAN


CLASSE:      Automaton patrouille aérienne Gunship
MÉTABOLISME: Mécanique
PERCEPTION: Navire de patrouille aérienne
TAILLE:       13 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Absolu
ARMES:    Canons à tir rapide, missiles
RÉCOMPENSE:     2000 FC
MENACE:     Haut

DESCRIPTION:

Il s'agit d'un patrouilleur automaton conçu pour soutenir les troupes terrestres et détruire l'infanterie Super-Terre. Extérieurement, il ressemble à un drone agrandi avec deux moteurs principaux et des ailes delta distinctives. Des canons à tir rapide sont montés sur les côtés du fuselage, et des lanceurs de missiles sont montés sur les ailes.

Il vole en l'air, tire sur les positions de Helldiver, et peut les poursuivre à basse altitude. Il peut être détruit avec des RPG, des autocannon ou des Stratagems.

Ils patrouillent les zones d'atterrissage, surveillent les avant-postes d'Automaton et attaquent les Helldivers qui restent trop longtemps à un endroit.

It has several weak points: Moteurs et ailes.

CONSEILS:

- Quand vous entendez le son des moteurs, cherchez une couverture. Il peut attaquer de n'importe quelle direction.
- Ne restez pas ouvert. Il vous tirera dessus de l'air.
- Pour la détruire, utilisez des RPG ou des autocannon. Le fusil consomme trop de cartouches.
- Si le vaisseau plane, c'est le meilleur moment pour attaquer. Tirez sur les moteurs ou les ailes.
- Ils arrivent souvent en groupe. Détruisez-les un par un pour ne pas être pris dans un feu croisé.
- Si vous avez déclenché un Stratagem, assurez-vous que le vaisseau ne dérange pas votre chute de renfort.
- N'essayez pas de le dépasser. C'est plus rapide que toi. Il vaut mieux essayer de le perturber.
