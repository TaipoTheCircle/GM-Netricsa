T-MECH, MAJOR


CLASSE:      T-Mech rouge, commandant
MÉTABOLISME: Endotherme Cyborg
PERCEPTION: Bête de guerre entraînée
TAILLE:       36 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Très élevé
ARMES:    Lanceurs de fusées
RÉCOMPENSE:     500 FC
MENACE:     Extrême

DESCRIPTION:

Il est le fils du biomécanoïde rouge. Après que Sam ait tué ce dernier, le mécanicien a juré de tuer notre sauveur.

La coloration rouge de son museau n'est pas un accident. C'est un trait hérité de la lignée biomécanique rouge d'où il provient. Cette caractéristique a été conservée dans le tissu biomécanique lors de la création du Méchanosaur, c'est pourquoi son museau a conservé cette couleur rouge vif distinctive.

T-Mechs - Un tyrannosaurus à croûte de cigares à pattes de poulet. Très blindé. Armé de deux lance-roquettes.

Les T-Mech sont les biomécanoïdes de la prochaine génération - bien que peu différents dans leur rôle de combat, ce sont les progrès scientifiques qui sont impressionnants. Auparavant, les biomécanoïdes étaient des robots génétiquement programmés dont les armes étaient directement reliées à leurs systèmes nerveux. Ils ne pensaient pas vraiment pour eux-mêmes, c'était essentiellement leur réflexe. Les T-Mech, cependant, sont capables de pensées semi-cohésives et se décident quand ils veulent attaquer. Ces connaissances peuvent être utilisées pour améliorer de nombreux modèles biomécaniques anciens de Mental.

Comme les biomécanoïdes majeurs, les T-Mech tireront deux missiles contre leurs cibles. Cependant, ils sont demi-dinosaure, ce qui les rend d'autant plus intimidants. Ils ont même inspiré les réalisateurs siriens à faire un nouveau film, « Primordial Park ». Il a été cassé les dossiers de la billetterie depuis sa libération.

CONSEILS:

- Leurs missiles sont parmi les plus puissants que vous rencontrerez dans la Horde de Mental - les éviter ou les abattre.
