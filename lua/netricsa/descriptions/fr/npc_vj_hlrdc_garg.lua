GARGANTUA DREAMCAST DE XEN


CLASSE:      Gargantua, Dreamcast
MÉTABOLISME: prédateur xénobiologique massif
PERCEPTION: Tank blindé de Xen
TAILLE:       ~15 pieds de haut, 30 pieds de long
ENDURANCE:  extrême
HOSTILITÉ:  très élevé
ARMES:    bras de lance-flammes, force brute, feu
RÉCOMPENSE:     5000 FC
MENACE:     catastrophique

DESCRIPTION:

Le Gargantua est un haut-lieu de Xen. Son corps musclé et blindé lui permet d'éliminer le feu des armes légères pendant qu'il incinère les ennemis avec ses bras de lance-flammes. Malgré sa taille, il est étonnamment rapide et peut sauter pour écraser les intrus avec une force dévastatrice.

Les Gargantuas sont des chasseurs solitaires mais incroyablement territoriaux. Ils semblent presque inarrêtables, forçant même les combattants les plus confiants à repenser les attaques frontales. Leur combinaison terrifiante de puissance de feu et de force brute en fait des prédateurs apex dans n'importe quel environnement Xen.

CONSEILS:

- Gardez la distance : les lance-flammes peuvent fondre la plupart des couvertures.
- Utiliser des explosifs et des armes lourdes; les armes classiques sont presque inutiles.
- Les risques environnementaux comme l'effondrement des structures peuvent aider même les chances.
