GRANDE TÊTE, TOMISLAV PONGRAC


CLASSE:      Grosse tête, Tomislav Pongrac
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:    Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     100 FC
MENACE:     Annoyance

DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme de Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan", ils reçoivent des modificateurs de feu et de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Tomislav Pongrac est une encyclopédie marche du développement du jeu et de l'incarnation de la philosophie « scientifique folle » de Croteam. Son crâne surdimensionné abrite une incroyable gamme de compétences, appliquées sur des décennies. Il a commencé à travailler avec pixel art sur Amiga et DOS, a progressé à travers l'art 3D et le design de niveau pour le classique Serious Sam: The First and The Second Encounter, puis est devenu le concepteur de niveau principal pour Serious Sam II.

Mais ses talents ne se limitaient pas à une seule série. Il a été directeur créatif et concepteur de jeu pour le jeu de course d'arcade frénétique Gas Guzzlers, et a travaillé sur le design sonore, la modélisation 3D, les textures et même la cinématique. Son pinacle en tant que visionnaire était le simulateur de survie hardcore SCUM (2018), où il a été réalisateur, directeur créatif et concept-artiste original. Tomislav est la preuve vivante qu'un véritable développeur de Croteam n'est pas fixé sur une seule discipline ; c'est le couteau suisse de l'armée du studio, capable de respirer la vie dans un projet à n'importe quel stade et dans n'importe quel rôle.

CONSEILS:

- Utilisez un couteau ou un pistolet pour dégager la voie.
- Sur la difficulté "Je suis Ugh-Zan", les éliminer à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.
