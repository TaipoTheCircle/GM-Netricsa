XL4-P BEAM GUN "GHOSTBUSTER"


ARME:    Turbine XL4-P "Ghostbuster"
MUNITIONS:      Cellules électriques X7
CADENCE DE TIR:       En continu
WEIGTH:    21 livres

DESCRIPTION:

Une branche encore plus expérimentale de la recherche originale XL2 Lasergun, cette arme incroyablement rare tire un faisceau continu mortel qui coupe tout. Seulement utilisé par quelques soldats EDF hautement entraînés pour des essais de terrain secrets, l'arme a rapidement obtenu le surnom "Ghostbuster", en raison de sa nature similaire comme une arme de faisceau d'un certain film.
En utilisant les mêmes cellules de puissance que le XL2 Lasergun, cette arme a été conçue à l'origine pour remplacer le Minigun volumineux et lourd, cependant qu'il n'est jamais entré dans la production de masse, la plupart des soldats croyaient que cette « super arme » n'est que la substance des légendes.

REMARQUES:

- Utilisez-le pour couper rapidement à travers des masses d'ennemis de taille moyenne.