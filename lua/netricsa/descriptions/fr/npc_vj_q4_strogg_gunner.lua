STRAGG GUNNER DE STROGGOS


CLASSE:      Strogg Gunner
MÉTABOLISME: Organisme cybernétique (Strogg bio-augmenté)
PERCEPTION: Strogg Ranged Support / Combattant de niveau intermédiaire
TAILLE:       ~7 pi de haut 
ENDURANCE:  Élevée (durabilité moyenne) 
HOSTILITÉ:  Haut
ARMES:    Nailgun (projectiles à incendie), Lanceur de grenades 
RÉCOMPENSE:     600 FC
MENACE:     Haut

DESCRIPTION:

Le Gunner est une formidable unité de Strogg, imposant en stature et mortel dans le combat varié. Il a un Nailgun greffé à la place de son avant-bras droit et un lanceur de grenade qu'il utilise pour lober des explosifs rebondissant vers sa cible. Lorsqu'il tire des grenades, il donne un avertissement visible, câlinant son bras de lance avant de déclencher le tir.

Contrairement aux Stroggs orientés melee, le Gunner préfère s'asseoir en arrière, garder les couloirs ou les salles, supprimer les ennemis avec des clous, et soutenir les unités plus lourdes. Son mouvement plus lent le rend moins mobile que les autres, mais sa puissance variée compense grandement. Sous-estimer un Gunner peut être mortel - son barrage d'ongles et grenades chronométrées peut déchiqueter à travers la santé et l'armure si vous êtes pris dans l'ouverture.

CONSEILS:

- Les armes lourdes ou les attaques explosives fonctionnent mieux que les armes à feu.
- Engagez-vous à mi-chemin : à portée de main, vous risquez d'être frappé par des coups de pistolet et des grenades.
