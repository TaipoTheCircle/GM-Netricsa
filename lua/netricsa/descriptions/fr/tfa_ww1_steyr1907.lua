PISTOL SÉMI-AUTOMATIQUE


ARME: Roth-Steyr M1907 Pistol semi-automatique
MUNITIONS:   8x18mm Roth-Steyr
CADENCE DE TIR:    Capacité semi-automatique, 10 tours

DESCRIPTION:

Un pistolet semi-automatique austro-hongrois, développé par le designer tchèque Karel Krnka avec la participation de Georg Roth. Il a été adopté par la cavalerie de l'armée austro-hongroise en 1907 sous la désignation officielle * Repetierpistole M.7* et est entré en service avec les troupes en 1909. Il est considéré comme l'un des premiers pistolets semi-automatiques à être adopté par une puissance militaire majeure. Elle a été fabriquée dans les installations de Steyr en Autriche et de la FEG en Hongrie.

Le pistolet fonctionne selon un principe de court-recoil, avec un verrouillage obtenu en tournant le canon à environ 90 degrés. Il utilise une cartouche Roth-Steyr 8x18mm spécifique et dispose d'un chargeur de 10 ronds fixe logé dans la poignée. Le chargement est effectué depuis le haut, le boulon étant ouvert, à l'aide d'un clip de strip-teaseuse spécialisé. Le mécanisme de déclenchement a une conception inhabituelle avec une forte poussée de déclenchement, destiné à améliorer la sécurité lorsqu'il est monté à cheval. Il n'y a pas de sécurité manuelle.

REMARQUES:

- Un des premiers pistolets semi-automatiques à être adopté par une puissance militaire majeure.
- Le magazine 10 tours est fixe et est chargé depuis le haut à l'aide d'un clip de strip-teaseuse spécialisé.
- Une forte détente a réduit la probabilité d'une décharge accidentelle lors de l'équitation.
- Efficace contre les cibles individuelles et non armées à proximité.
- Utilisé pendant la Première Guerre mondiale, avec quelques exemples restant en service aussi tard que la Seconde Guerre mondiale.
