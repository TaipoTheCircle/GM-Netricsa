LE CREEPER DE ZOMBIE DU MINECRAFT


CLASSE:      Crèche de zombies
MÉTABOLISME: Morts
PERCEPTION: La foule hostile
TAILLE:       5,5 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrêmement élevé
ARMES:    Autodestruction, infecter les villageois
RÉCOMPENSE:     110 FC
MENACE:     Très élevé

DESCRIPTION:

C'est un hybride qui se produit lorsque deux ennemis familiers se combinent en un cocktail de cauchemar.

Le Zombie Creeper ressemble à un rampant classique, mais avec des éléments zombies : la peau verte, habillée de chiffons zombies, et son visage emblématique. Il n'explose pas immédiatement après avoir vu le joueur, mais se comporte initialement comme un zombie.

Comme un zombie, il suit les villageois. Comme un flippant régulier, il explose quand il se rapproche de sa cible.

Contrairement aux zombies réguliers, les zombies n'ont pas peur de la lumière du jour. Ils ne brûlent pas, ce qui signifie qu'ils peuvent être rencontrés à tout moment de la journée.

Ils ignorent le mécanicien rampant (sniché) et courent simplement pour mordre et exploser.

Comme les zombies, ils peuvent attaquer en groupes, créant une réaction en chaîne des explosions.

CONSEILS:

- Gardez vos distances. La meilleure arme contre eux est un arc ou arbalète. Ne les laissez pas s'approcher.
- Utilisez l'environnement. Des passages étroits, de l'eau ou de la lave peuvent les ralentir ou les détruire avant d'exploser.
- Cours et attaque. Si vous êtes forcé de vous battre dans un combat rapproché, utilisez la technique "hit and run": courir, frapper, et immédiatement sauter en arrière.
- Bloquez avec votre épée, mais rappelez-vous que le blocage n'arrêtera pas l'explosion.
- Lorsqu'il est tué, il peut déposer jusqu'à 4 blocs de dynamite (TNT).
