FROST LASER RIFLE


ARME: Rifle laser de gel
MUNITIONS:   Perles d'énergie glacée
CADENCE DE TIR:    Doubles tirs

DESCRIPTION:

Le FROST Laser Rifle est une version modifiée du fusil laser standard, adapté pour une utilisation dans des conditions extrêmement froides. La structure de l'arme est renforcée par des matériaux résistants à la chaleur, et le corps dispose d'un design mis à jour avec des éléments jaunes et bleus servant de marqueurs visuels de sa spécialisation en temps froid.

L'arme conserve le principe de fonctionnement du modèle de base, tirant deux impulsions d'énergie dans une rangée avec chaque poussée de la détente. Cependant, au lieu de faisceaux standard, le fusil tire des lasers de glace bleue infusés d'énergie cryonique. Au moment de l'impact, ceux-ci non seulement infligent des dommages, mais aussi ralentissent l'ennemi en refroidissant rapidement les tissus, les armures et les mécanismes d'entraînement.

Le Rifle Laser Frost est alimenté par un noyau plasma modifié avec cryostabilisation, empêchant la surchauffe et la dégradation des composants dans les températures de congélation. Un réacteur intégré recharge continuellement l'arme à travers un magazine, assurant un fonctionnement stable dans des conditions de combat prolongées et arctiques.

REMARQUES:

- Entièrement adapté aux températures froides et basses.
- Chaque tir émet une double impulsion glacée, ralentissant l'ennemi.
- L'effet cryo réduit la mobilité des cibles vivantes et le temps de réaction des adversaires mécaniques.
- Particulièrement efficace à portée moyenne et pendant le feu de groupe.
- Moins de puissance pénétrante contre l'armure lourde, mais compense cela avec un effet de ralentissement.
- Pour l'infanterie légère et les unités opérant dans les zones froides.