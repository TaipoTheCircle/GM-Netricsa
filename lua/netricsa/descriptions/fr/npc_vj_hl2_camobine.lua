SURVEILLANCE DE LA COMBINE


CLASSE:      Combiner Overwatch Ghillie Soldier
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner l'unité de reconnaissance à longue distance et le sniper
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrême
ARMES:    Rifle de sniper MK2 Overwatch, AR2 Pulse Rifle
RÉCOMPENSE:     1600 FC
MENACE:     Très élevé

DESCRIPTION:

Le Combine Overwatch Ghillie Soldier est une ombre que vous ne remarquez que lorsque vous faites une erreur. Le Combine utilise ces soldats pour chasser les commandants de la Résistance, surveiller les itinéraires clés et supprimer tranquillement les activités dans les zones où la présence de Overwatch est indésirable.

Contrairement à la plupart des soldats, il manque une visière éclatante. Au lieu de cela, il a des lentilles optiques qui obscurcissent sa ligne de vue et l'empêchent de se démasquer. Son armure est entièrement recouverte de buissons artificiels, d'herbe et de fibres d'un costume de ghillie adapté à l'environnement environnant. De loin, il ressemble à un morceau du paysage qui a soudainement décidé de tirer.

Son arme principale est le fusil de sniper Overwatch MK2, capable d'enlever une cible avant même qu'ils se rendent compte qu'ils sont en danger. Le AR2 est utilisé comme arme secondaire en cas de détection ou de combat rapproché, bien qu'à ce stade, il préfère se repositionner plutôt que d'essayer d'être un héros.

CONSEILS:

- Ne t'attarde jamais en plein air - c'est ce qu'il attend.
- Changez de position après le premier coup.
- Les explosifs et le feu sont efficaces contre l'envahissement, même si vous n'êtes pas sûr qu'il soit là.