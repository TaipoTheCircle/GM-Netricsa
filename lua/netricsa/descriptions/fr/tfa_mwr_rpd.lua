GUN DE LUMIÈRE DE GTYARYOV (DP-27)


ARME: Degtyaryov mitrailleuse légère (DP-27)
AMMMO:  7,62 x 54 mm R
CADENCE DE TIR:    ~500-600 tours par minute

DESCRIPTION:

Une mitrailleuse soviétique développée par le concepteur d'armes à feu Vasily Alexeyevitch Degtyaryov en 1927. Elle a été adoptée par l'Armée rouge la même année et avait pour but de fournir un soutien au feu aux unités d'infanterie. Il est devenu l'une des armes automatiques primaires utilisées par l'infanterie soviétique pendant la Grande Guerre patriotique. Il se distingue par son magazine de pan caractéristique, situé sur le dessus du récepteur, et un stock en bois.

L'arme fonctionne selon un principe actionné au gaz, avec la crasse verrouillée par deux volets de verrouillage. Il tire la cartouche de fusil 7,62x54mm R et est alimenté par un chargeur plat de 47 tours. Il dispose d'un canon refroidi à l'air, bipode pliant, et des vues de fer. En 1944, une version améliorée, le DPM, a été introduite, intégrant plusieurs changements de conception pour améliorer la fiabilité et la facilité d'utilisation.

REMARQUES:

- Efficace contre les deux groupes et les cibles individuelles à fourchettes moyennes.
- Les variantes comprennent le DA (pour les aéronefs) et le DT (pour les réservoirs).
- Adopté pour le service en 1927.
- Le magazine a 47 tours.
- A servi comme mitrailleuse principale de l'Armée Rouge pendant la Grande Guerre Patriotique.
