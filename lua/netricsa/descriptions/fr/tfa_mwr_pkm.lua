KALASHNIKOV GENERAL-PURPOSE MACHINE GUN, MODERNISÉ (PKM)


ARME: Kalachnikov General-Purpose mitrailleuse, modernisé (PKM)
MUNITIONS:   7,62 x 54 mm R
CADENCE DE TIR:    ~650 tours/min

DESCRIPTION:

Une mitrailleuse soviétique à usage général développée par Mikhail Timofeyevitch Kalachnikov et son équipe de conception, basée sur le modèle PK original. Il a été adopté pour le service en 1969. L'arme est conçue pour engager le personnel ennemi et les systèmes d'armes, ainsi que pour fournir un soutien au tir aux unités d'infanterie. Par rapport au modèle original, il dispose d'un design plus léger, d'un suppresseur flash modifié, et de plusieurs améliorations qui améliorent la facilité de fonctionnement.

Il fonctionne selon un principe actionné au gaz avec un mécanisme de verrouillage rotatif. Il tire la cartouche de fusil 7.62x54mm R. Les munitions sont alimentées par une ceinture métallique, contenant généralement 100 ou 200 cartouches (des ceintures rondes de 250 sont également disponibles). L'arme est équipée d'un canon à changement rapide, d'un bipode repliable intégral et de vues en fer. Une variante appelée PKMS a été développée pour être utilisée avec un trépied léger conçu par Stepanov.

REMARQUES:

- Efficace contre le personnel et le couvert léger à moyenne et longue portée.
- Une variante "nuit", le PKMN, existe ; elle est adaptée pour le montage de visions optiques et nocturnes.
- Adopté pour le service en 1969.
- Pese environ 7,5 kg (16,5 lb) sans munitions.
- Le taux de tir atteint 250 balles par minute.
