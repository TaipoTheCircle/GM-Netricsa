PARASITE "BETA"


CLASSE:      Parasite "Beta"
MÉTABOLISME: Xénobiologique
PERCEPTION: Parasite
TAILLE:       3,2 ft
ENDURANCE:  Très faible
HOSTILITÉ:  Très élevé
ARMES:    Infecter, sauter, griffes
RÉCOMPENSE:     60 FC
MENACE:     Haut

DESCRIPTION:

Le "Beta" Swarm Parasite est une petite sous-espèce, mais extrêmement agressive, spécialisée dans l'infection des grands organismes. Il éclos des œufs et commence presque immédiatement à chercher la proie la plus proche, en utilisant ses longs membres postérieurs pour faire des sauts rapides.

Lors d'une attaque, le parasite tente de s'attacher à la victime et d'injecter du matériel infectieux dans son corps. Si un organisme infecté meurt avant de nettoyer l'infection, une nouvelle génération de parasites mûrit rapidement à l'intérieur, et éclata bientôt.

Comparativement aux parasites provenant d'autres essaims, les individus de Beta Swarm se distinguent par leur tête allongée, certains avec une carapace verte et des membres plus longs. Malgré ces différences, leur cycle de vie et leurs méthodes d'attaque sont pratiquement identiques.

Seul, les parasites posent rarement une menace sérieuse. Cependant, lorsqu'ils apparaissent en masse, ils peuvent rapidement propager l'infection dans toute l'équipe, surtout lorsqu'ils travaillent de concert avec d'autres organismes du Swarm.

CONSEILS:

- Détruisez les parasites avant qu'ils ferment la distance.
- S'il est infecté, trouver immédiatement un moyen d'éliminer l'infection de l'organisme.
- Ne laissez pas les parasites entourer le groupe, surtout dans les passages étroits.
- Détruire les œufs d'abord pour empêcher les parasites de frayer.
- Les armes automatiques et le feu sont particulièrement efficaces contre ces créatures.
