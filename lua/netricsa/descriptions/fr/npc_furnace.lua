MÉTAUX DE FURNACE SOLIC DU MOBIUS


CLASSE:      Four à métal sonique
MÉTABOLISME: Robot de tueur mécanique
PERCEPTION: Destruction et machine à cuisiner / Chef personnel d'Eggman
TAILLE:       3,3 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Absolu
ARMES:    Four à coffre intégré, boules de feu, griffes, super vitesse
RÉCOMPENSE:     10000 FC
MENACE:     Absolu

DESCRIPTION:

C'est Metal Sonic, réutilisé pour ses propres buts cannibales par le fou Docteur Eggman, connu sous le nom de faim. Au lieu de simplement vaincre Sonic, Furnace doit le capturer, le cuire dans la fournaise dans sa poitrine, et le servir à Eggman pour le dîner.

Furnace est un tueur au sang froid et calculateur. Son but premier est d'obéir aux ordres de son créateur, et il s'approche de cela avec le plus grand sérieux. Il n'est pas seulement une machine sans esprit ; il est capable d'analyser le comportement de sa proie, de repérer leurs faiblesses, et de les utiliser contre eux. Dans un scénario, Furnace fait même semblant de sa propre rupture pour faire tomber Sonic dans un faux sentiment de sécurité avant l'attaque décisive.

Visuellement, Furnace diffère de Metal Sonic classique. Il semble plus industriel et utilitaire, construit à partir de couches brutes de métal et de boulons. La caractéristique la plus frappante est sa poitrine, qui est un véritable fourneau avec une grille contenant un feu enflammé. Contrairement à Metal Sonic, il n'essaie pas de prouver sa supériorité dans une course ; il veut simplement tuer.

C'est un adversaire redoutable, capable de combattre Sonic sur un pied d'égalité. Son arsenal comprend :

Furnace: Son arme primaire. Peut s'ouvrir pour piéger une victime à l'intérieur ou émettre de puissants jets de flamme.

Super Speed: Capable d'atteindre des vitesses assez rapides pour chasser un Sonic en course.

Fireballs: Peut tirer des flammes sur une distance.

Sharp Claws: Utilisé au combat rapproché.

Physical Strength: Beaucoup plus fort que le son métallique ordinaire.

Durability: Très résistant et capable de résister à de puissantes attaques.

CONSEILS:

- Ne le sous-estime jamais. Il est intelligent et peut prédire vos mouvements.
- Ils disent que Furnace est capable de détruire même son créateur si les circonstances l'exigent. Gardez ça à l'esprit.
