TANTACLE DE XEN


CLASSE:      Tentacle
MÉTABOLISME: xénofaune carnivore
PERCEPTION: Tentecle de l'énorme créature
TAILLE:       30-40 ft (émergences du puits)
ENDURANCE:  extrêmement élevé
HOSTILITÉ:  extrême
ARMES:    détection sonore, frappes dévastatrices
RÉCOMPENSE:     1200 FC
MENACE:     catastrophique (dans les zones confinées)

DESCRIPTION:

Le Tentacle est un prédateur souterrain massif de Xen, rencontré dans les zones de cascades de résonance où il se propage des fosses profondes. Aveugle, elle repose entièrement sur le son et les vibrations pour localiser les proies. Tout bruit attirera son attention instantanément, suivi de coups d'os de ses appendices en forme de fouet.

Sa peau blindée la rend pratiquement invulnérable aux armes classiques. Les victimes sont souvent jetées dans le sol avant même de se rendre compte qu'elles ont été détectées. La seule vraie façon de l'éliminer est de détruire son noyau, enfoui au fond de la surface.

CONSEILS:

- Restez silencieux - marcher, tirer, ou même recharger trop fort vous fera tuer.
- Les explosifs ou les armes à énergie sont inefficaces contre son armure.
La patience et la furtivité sont les clés de la survie.