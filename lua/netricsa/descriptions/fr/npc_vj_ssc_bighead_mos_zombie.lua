ZOMBIE, NIKOLA MOSETTIG


CLASSE:      Big-Head Zombie, Nikola Mosettig
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:    Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     100 FC
MENACE:     Annoyance

DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme de Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan" ils gagnent le feu et les modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Nikola Mosettig est l'incarnation vivante de "l'inverse". Quand il a rejoint Croteam avec son ami Ivan Mika, il a rêvé d'une carrière de concepteur de niveau, mais le destin a décrété autrement, l'envoyant au département de programmation. Son crâne exagéré contient 15 ans d'humilité et de croissance professionnelle - d'un programmeur de contenu responsable des scripts, des déclencheurs et de la logique d'interaction dans les jeux, au directeur de la technologie de l'information. Pendant tout ce temps, il regarda avec une tristesse tranquille que Ivan créa des paysages monumentaux, tandis qu'il écrivit avec ardeur ce qui devait se passer lorsque le joueur marchait sur cette tuile.

C'est Nikola qui a été irrité par la mauvaise couverture de sortie de l'éditeur, et c'est lui qui a assisté et participé au déménagement dans un bureau spacieux, marquant une nouvelle étape dans la vie du studio. Son histoire est un hymne à tous ceux dont les rêves dans le développement de jeu n'étaient pas tout à fait ce qu'ils semblaient, mais qui ont néanmoins trouvé leur place et sont devenus une partie indispensable de la machine qui a cimenté les plans grandioses des concepteurs en code de travail. "On ne peut pas se débarrasser de lui" - cette blague du développeur cache le profond respect d'un homme dont le dévouement au projet s'est révélé plus fort que ses ambitions inexploitées.

Il était vivant, mais après que quelqu'un l'ait tué, il est sorti d'un Zombie démoniaque.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager un chemin.
- Sur la difficulté "Je suis Ugh-Zan", détruisez-le à distance à cause de leurs modificateurs. - Oui. Dans un groupe de groupes, un lugehammer avec une frappe horizontale est efficace.