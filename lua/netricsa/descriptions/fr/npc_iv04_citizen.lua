CITOYENS


CLASSE:      Les citoyens
MÉTABOLISME: Humains
PERCEPTION: Résistance humaine / Civil
TAILLE:       ~5-6 pieds
ENDURANCE:  Faible-moyenne
HOSTILITÉ:  Faible (sauf armée contre Combine)
ARMES:    Varie - pistolet, SMG, fusil de chasse, armes trouvées
RÉCOMPENSE:     Aucune
MENACE:     Faible-moyenne

DESCRIPTION:

Les citoyens sont la population humaine opprimée vivant sous la domination de Combiner dans la ville 17 et au-delà. La plupart d'entre eux vivent dans des logements délabrés, sous la surveillance et la pression constantes de la protection civile. Malgré leur soumission apparente, beaucoup soutiennent secrètement la Résistance, offrant des fournitures, des informations et des refuges aux rebelles.

Inspirés par des dirigeants comme Eli Vance ou Gordon Freeman, les citoyens prennent les armes et se battent aux côtés de la Résistance. Bien qu'ils soient mal entraînés et légèrement armés, leur nombre et leur détermination en font souvent une force décisive contre les patrouilles du Combine.

Leur loyauté, cependant, a un coût: beaucoup sont capturés, «traités», et transformés en soldats Stalkers ou Overwatch. Chaque citoyen armé sait qu'il risque plus que la mort, il risque de perdre toute son humanité.

CONSEILS:

- Faible seul, mais dangereux en groupe avec des armes à feu.
- Ils peuvent fournir des munitions, des trousses ou agir en tant que coéquipiers si vous gagnez leur confiance.
