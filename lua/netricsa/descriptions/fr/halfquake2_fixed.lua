Alors, Sam. Le premier test.

Ou, comme ils aiment le dire ici, la première "torture"

Pour le spectacle, vous n'êtes plus un héros, un soldat, ni même une erreur de chronologie. Vous êtes la victime. C'est ainsi que l'annonceur vous a présenté, avec le même ton que vous entendiez lors de l'annonce d'une publicité ou d'un bulletin météorologique.

Le test commence par une série de pièces. Simple. Tout droit. Vraiment honnête.

Dans la première pièce, les Vortigaunts sont libérés. Pas de volants. Un classique. Les règles du spectacle ne leur ont pas été expliquées, mais ce n'est pas nécessaire. Leur travail est d'être un obstacle. Le vôtre, c'est d'aller de l'avant et de ne pas s'attarder sur les humanismes.

La prochaine pièce est plus intéressante. Des espions. Un bouton. Une porte. Pour passer, vous devez entrer et appuyer sur le bouton. La porte s'ouvrira. Les pointes se déplacent vers le bouton. Juste vers vous. Le plan des organisateurs est clair : leur donner de l'espoir, puis tester à quelle vitesse vous pouvez retourner dans la pièce précédente et plonger à travers une porte ouverte. Le timing est tout. Une erreur est aussi décisive, mais cette fois c'est définitif.

Ensuite, une piscine de lave. Trois dalles. Jumpable. Dès que vous sortez d'une dalle, elle s'effondre. Le spectacle aime le mouvement et décourage le doute. Linger, et tu feras partie du décor.

Puis plus de pics. Parce que la tradition doit être respectée.

L'ascenseur vous emmènera à un étage, où une pièce pleine de tourelles vous attend. Oui, les mêmes. Veuillez acheter chez Black Mesa. Les affaires, c'est les affaires.

Quelque part parmi cette splendeur est un bouton caché. Trouvez-le, et vous pourrez avancer. Mais pas directement. Vous devrez marcher le long d'un mince rebord jusqu'à la porte. C'est miné. Vous pouvez l'approcher, mais vous ne pouvez pas l'entrer. Tu devras te retourner et rentrer. Alors un autre passage s'ouvrira. Ailleurs. Logique ? Non, efficace ? Absolument.

Et, bien sûr, tout cela sera généreusement assaisonné avec les troupes de Mental. Parce que le spectacle doit évoluer. Et les téléspectateurs aiment quand les enjeux sont relevés.

