GUN MÉDICAL ELITE COMBINE


ARME: Combiner le pistolet médical Elite
MUNITIONS:   AR2 Pulse Rounds / Capsules Biomed (Antlion Larvas)
CADENCE DE TIR:    Beam de guérison + Feu d'impulsion sous l'eau

DESCRIPTION:

Le Combine Elite Medical Gun est un outil de soutien tactique multifonctionnel qui combine la guérison pour les alliés et le feu suppressif pour l'ennemi. Son corps dispose d'un schéma de couleur blanc et gris avec une poignée noire et une section de guérison vert brillant.

Une mince tige d'émetteur noir dépasse l'avant de l'arme, ce qui génère un faisceau médical concentré. Le premier mode d'incendie crée un courant de guérison soutenu qui rétablit l'activité tissulaire et neuroimpulsive chez les organismes alliés en utilisant des biomatériaux recyclés provenant d'oeufs de larve d'antlion.

Le second mode active un module d'impulsion sous-barrel qui allume des rondes d'énergie standard AR2 directement sous la trajectoire du faisceau de guérison. Cela permet au médecin de guérir simultanément les alliés et de supprimer les ennemis sans changer d'armes.

Le système est conçu pour les unités d'élite Combinez, où chaque soldat doit combiner soutien et puissance de feu.

REMARQUES:

- La section verte de la coque affiche le niveau d'agent de guérison.
- Efficace dans les équipes mobiles et les équipes d'assaut d'élite.
- Dommage inférior par rapport aux fusils à impulsion à pleine puissance, mais compense pour cela avec sa fonction de guérison.
