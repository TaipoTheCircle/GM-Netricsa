FICHE DE F2


ARME: GIAT FR F2 Sniper Rifle
MUNITIONS:   OTAN 7,62x51mm
CADENCE DE TIR:    ~15 tours/min
POIDS: ~5,8 kg avec optique
LENGTH: ~1 200 mm

DESCRIPTION:

Le GIAT FR F2 est le fusil de sniper standard de l'armée française, développé comme une amélioration majeure du FR F1. Ses principales caractéristiques comprennent un canon flottant plus épais avec un manchon thermique qui réduit la distorsion thermique pendant le tir, ainsi qu'une meilleure ergonomie des stocks. Le fusil est conçu pour l'engagement précis des cibles à moyenne et longue portée et est apprécié pour sa stabilité et sa fiabilité sur le terrain.

REMARQUES:

- Haute précision dans un feu à tir unique; idéal pour les engagements à longue portée.
- La conception à l'action du boulon offre une excellente précision, mais limite la vitesse du feu.
- Efficace contre la main-d'œuvre et les cibles légèrement blindées; contre l'armure lourde, des coups précis sont nécessaires.