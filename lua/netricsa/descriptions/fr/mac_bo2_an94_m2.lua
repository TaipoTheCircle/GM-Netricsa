NIKONOV AN-94 "ABAKAN" RIFLE D'ASSAULT


ARME: Nikonov AN-94 "Abakan" Assault Rifle
MUNITIONS:   5,45x39 mm
CADENCE DE TIR:    ~600 / 1800 tours par minute

DESCRIPTION:

Un fusil d'assaut russe développé par Gennady Nikonov dans le cadre du programme "Abakan". Il a été créé pour remplacer la famille des fusils AK-74. Il dispose d'un mécanisme automatique unique avec une "impulsion de recul déplacée", ce qui améliore significativement la précision lors du tir en courtes rafales.

La caractéristique déterminante de l'AN-94 est son mode d'éclatement à deux tours, qui tire à 1 800 tours par minute. Les premier et deuxième tours sont déchargés presque simultanément — avant que le recul ne puisse affecter sensiblement la position de l'arme. En mode standard entièrement automatique, la vitesse d'incendie est d'environ 600 tours par minute. Il est compatible avec les magazines de 30 et 45 tours de l'AK-74, ainsi qu'avec les magazines spécialisés de 60 tours quad-stack.

REMARQUES:

- Connu comme l'"Abakan", nommé d'après la ville où ses procès ont eu lieu.
- Le magazine est placé légèrement à droite, résultat de son système non conventionnel d'alimentation en munitions.
- L'éclatement à deux tours permet au tireur d'atterrir deux coups sur la cible presque avant que le recul ne se fasse sentir.
- La conception s'est révélée si complexe et coûteuse que l'AN-94 ne pouvait pas remplacer complètement la famille AK-74.
- Essentiellement une expérience technique qui était équipée d'un stock et transformée en fusil d'assaut.
