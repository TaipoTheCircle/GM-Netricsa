HALF-QUAKE SHOW MINI TURRET


CLASSE:      Mini tourelle HALF-QUAKE Show
MÉTABOLISME: Mécanique
PERCEPTION: Unité de défense automatisée
TAILLE:       ~2 pi
ENDURANCE:  Faible-moyenne
HOSTILITÉ:  Extrême
ARMES:    Petite mitrailleuse à feu rapide
RÉCOMPENSE:     250 FC
MENACE:     Modéré

DESCRIPTION:

Lorsque le HALF-QUAKE Sadistic Show a réalisé que les acteurs ne mouraient pas assez, la décision a été prise d'acheter un lot de tourelles automatisées de Black Mesa. Le contrat a été signé et l'équipement a été émis, mais avec une seule condition : tout l'équipement doit être correctement marqué.

Le Mini Turret est une version compacte de la tourelle blindée standard, adaptée pour l'installation dans des espaces à bas plafond, des puits de ventilation et d'autres endroits où une version pleine dimension ne peut tout simplement pas s'adapter.

Après avoir transféré la propriété à HALF-QUAKE, le logo «>) a été poncé sur le dessus de chaque tourelle en peinture blanche.

Mini Turrets peuvent être montés sur le plancher, le mur ou le plafond. Ils peuvent attendre des heures dans l'obscurité, alimentés par une batterie de secours, et ne sont activés que lorsque les détecteurs de mouvement détectent une cible proche.

Grâce à sa rotation à 360 degrés, il est impossible de se cacher derrière elle-il tourne simplement et continue à tirer.

CONSEILS:

- Des explosifs ou des tirs précis peuvent rapidement le désactiver.
- Vérifiez l'espace au-dessus et au-dessous de vous-même petites tourelles peuvent couvrir des angles inattendus.
- Évitez de vous tenir dans des couloirs ou des espaces étroits où il peut efficacement vous cibler.
- Utiliser la couverture dans l'environnement pour minimiser l'impact de son tir de mitrailleuse.
