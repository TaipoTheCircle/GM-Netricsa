BOID VERT DE UH-1


CLASSE:      Poudre verte
MÉTABOLISME: inconnu
PERCEPTION: Sous-espèces de Xen
TAILLE:       ~3 pieds d'envergure
ENDURANCE:  Faible
HOSTILITÉ:  Aucune
ARMES:    Aucune
RÉCOMPENSE:     60 FC
MENACE:     Aucune

DESCRIPTION:

Le Boïde vert est une sous-espèce rare du Boïde Xen familier, d'abord documenté à bord du navire de recherche UH-1. Avec une luminescence verte vibrante, ils glissent dans des espaces confinés dans des troupeaux synchronisés. Comme leurs cousins Xen, ils sont tout à fait inoffensifs, servant de spectacles vivants plutôt que de prédateurs.

Les chercheurs croient que leur lueur peut être une forme de communication ou de cohésion de groupe, leur permettant de former des modèles aériens plus serrés même dans l'obscurité. Malgré leur apparence extraterrestre, ils restent curieux, créatures dociles sans agression envers les humains ou d'autres êtres.

CONSEILS:

- Ne leur faites pas de mal, ils ne représentent aucune menace.
- Surveillez leurs habitudes de rassemblement pour trouver des indices sur les dangers environnementaux à proximité.
