VICTIMES DE LA HALF-QUAKE SHOW


CLASSE:      Victime
MÉTABOLISME: Humain, Cyborg, Homme
PERCEPTION: Prisonnier du spectacle, Pawn rebelle
TAILLE:       ~6,2 pi
ENDURANCE:  Variable
HOSTILITÉ:  Haut
ARMES:    MP5, SPAS-12 fusil de chasse
RÉCOMPENSE:     500 FC
MENACE:     Haut

DESCRIPTION:

À première vue, c'est un robot sans âme. Armure verte, formes angulaires, une démarche lourde. Mais derrière l'armure se trouve la chair humaine. Sang, muscle, désespoir et haine. Son visage est caché derrière un masque métallique, mais si vous regardez de près, vous pouvez voir quelque chose de vivant. Quelque chose qui a perdu espoir il y a longtemps, mais n'a pas perdu sa rage.

Il s'est retrouvé à l'émission Half-Quake pour "sa terrible erreur dans la vie". Les sadiques ne disent pas lequel. Peut-être qu'il a tué la mauvaise personne. Peut-être qu'il a traversé le mauvais sadique. Ou peut-être qu'il n'y avait aucune erreur. Ils avaient simplement besoin d'un corps pour un nouvel épisode. Et il a été choisi pour ce corps.

Il est armé d'un MP5 et d'un fusil SPAS-12. Pas parce qu'ils lui ont donné des armes. Mais parce qu'il les a prises aux gardes qu'il a tués dans les épisodes précédents. Il déteste le spectacle. Il veut s'échapper. Il veut détruire cet endroit. Mais surtout, il ne veut plus jamais mourir.

La victime est morte plusieurs fois. Il a été coupé, brûlé, noyé, explosé, poignardé, nourri à des monstres. Mais il se lève encore. Encore et encore. Les sadiques pensent que cela rend le spectacle plus intéressant. La victime elle-même pense que c'est une malédiction. Mais chaque fois qu'il ouvre les yeux après une autre mort, il prend les bras et avance, déterminé à mettre fin aux cauchemars.

CONSEILS:

- Ne tirez pas sur la victime. Ce n'est pas ton ennemi.
- Si vous le rencontrez dans les couloirs de Shaw, restez près. Il sait où sont les gardes, où sont les pièges et où est la sortie.
- La victime ne fait confiance à personne. Ne vous attendez pas à ce qu'elle partage ses munitions avec vous. Mais elle peut te couvrir dans une bagarre.
- Les sadiques le détestent. Somos aussi. Le fait qu'elle soit encore en vie (dans un sens) les irrite plus que toute rébellion.
- N'essayez pas de le sauver. Il n'a pas besoin de sauver. Il a besoin de vengeance. Et à la fin, il va détruire Shaw ou mourir pour la dernière fois. Pour de bon.
