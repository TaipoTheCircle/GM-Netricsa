CHELEZYAKA


PLANET:       Shelezyaka
TYPE:         Planète terrestre, planète Factory
CLIMATE:      Espace airless, fluctuations de température
MOONS:        Inconnu
TERRAIN:      Une plaine sulfurique plate recouverte de poussière
LOCATION:     Une partie lointaine de la galaxie de la Voie Lactée, hors du sentier battu, près de la planète Sheshineru
NATIVE RACES: Robots (descendants de l'équipage d'un navire robotisé écrasé), Robobeasts
ALLIANCE:     Civilisation robotique indépendante
LOCATIONS:    Port spatial désertique, Habitats de robots, Habitats de Robobest

DESCRIPTION:

Shelezyaka est une planète qui est un exemple clair de la transformation complète (et de l'épuisement) du monde par une civilisation technologique. C'était autrefois un monde ordinaire avec une atmosphère, de l'eau, des mers, des montagnes, de la végétation et des animaux. Il y a de nombreuses années, un navire automatisé transportant des robots de service universel obsolètes s'est écrasé ici.

Les robots survivants ont commencé à se reproduire activement en utilisant les ressources minérales locales. Pendant le processus d'industrialisation, ils ont complètement épuisé les ressources de la planète: l'oxygène a été brûlé dans les fours, l'eau a été éliminée (pour prévenir la rouille et utiliser pour refroidir les moteurs), les montagnes ont été rasées, et les mers ont été drainées. Shelezyaka est maintenant devenue une sphère grise, plate, recouverte de poussière, sans atmosphère ni aucun signe de vie.

A famous entry in the galactic directory reads: "Pas de ressources minérales. Pas d'eau. Pas de végétation. Habité par des robots.".

Les indigènes sont les descendants de ces mêmes robots. Ils sont courts, lourds, forts et durables (« construits pour durer »). Ils sont simples, mais capricieux et facilement offensés. Chacun a une lumière indicatrice sur son front. Ce sont des artisans qualifiés, mais leur civilisation reste à un niveau technologique primitif, sans ordinateur ni agriculture. Leur délicatesse préférée est l'huile de tournesol.

Lorsque la faune de la planète est morte en raison de conditions inappropriées, les robots ont créé des animaux mécaniques pour combler le vide. Plus tard, lorsque les pièces manquaient, les animaux robotisés furent démontés et se replièrent dans un état semi-sauvage. Ils sont divisés en types de « souris » et de « chat »; tous se déplacent sur des roues et peuvent grincer, tandis que les rapaces peuvent lécher avec une langue de fer. Ils sont domptables.

KEY LOCATIONS:

- Cosmodrome désert : Le seul site d'atterrissage, toujours poussiéreux et désert. Au fil des ans, un seul visiteur a visité ici - le pirate de l'espace Rat.
- Établissements de robots : Zones habitées par les habitants indigènes de la planète. Les robots aiment donner des conseils et, lorsqu'ils ne travaillent pas, préfèrent s'asseoir ou s'allonger.
- Habitats Robo-Best : Territoires habités par des animaux mécaniques sauvages. Ici, vous pouvez rencontrer des troupeaux de voyous ou de voyous.
