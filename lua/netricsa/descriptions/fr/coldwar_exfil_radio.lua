RADIO D'EXFIL


ARME: Exfil Radio
MUNITIONS:   Non requis
CADENCE DE TIR:    Extraction d'hélicoptère

DESCRIPTION:

Une unité radio mobile conçue pour convoquer un hélicoptère d'extraction. L'appareil vous permet de contacter les pilotes et de demander une évacuation d'urgence de la zone opérationnelle. Une fois le signal transmis, un hélicoptère avec un équipage de deux personnes arrive pour récupérer tout le personnel à proximité.

L'hélicoptère arrive environ 40 secondes après avoir été appelé et reste sur place pendant 40 secondes, en attendant que les passagers embarquent. Après cette période, elle quitte la zone d'extraction, peu importe le nombre de personnes sauvées. Ceux qui échouent à monter à bord dans le temps périront, il est donc fortement conseillé de ne pas retarder.

REMARQUES:

- Utilisez simplement la radio pour demander une extraction.
- L'hélicoptère arrive dans environ 40 secondes.
- L'équipage de conduite se compose de deux pilotes.
- L'hélicoptère reste au sol pendant 40 secondes.
- Une fois la période d'attente terminée, l'hélicoptère part; tout membre du personnel laissé derrière périra.
- La radio fonctionne comme un émetteur, conçu pour une communication rapide en temps réel.
