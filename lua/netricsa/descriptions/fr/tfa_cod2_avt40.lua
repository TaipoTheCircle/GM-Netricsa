MODULE AUTOMATIQUE TOKAREV 1940


ARME: Modèle tokarev de rafale automatique 1940
MUNITIONS:   7,62 x 54 mm R
CADENCE DE TIR:    ~25-30 (simple) / ~700-800 (brut) rondes / min
POIDS: ~3,85 kg

DESCRIPTION:

Ce fusil automatique soviétique a été développé en 1942 comme un remplacement d'urgence pour les mitrailleuses légères rares. Sa conception est une modification majeure du célèbre fusil semi-automatique SVT-40, ajoutant un mode feu continu.

Le sélecteur de mode incendie est intégré à la sécurité, permettant au tireur de basculer instantanément entre des tirs précis et des rafales dévastatrices. L'arme est alimentée par des chargeurs détachables de 10 ronds, qui peuvent également être chargés depuis le dessus à l'aide de clips standard.

Malgré sa conception, l'AVT-40 s'est révélé trop léger pour la puissante cartouche de fusil 7,62x54mm. En tirant en éclats, le fusil a été littéralement arraché de vos mains, la précision a chuté, et le canon mince et le mécanisme s'est rapidement épuisé. De ce fait, les troupes n'ont été autorisées à tirer qu'en éclats pendant les moments de combat les plus critiques.

REMARQUES:

- Il possède le pouvoir de tuer un fusil Mosin, mais il est capable de pleuvoir du plomb sur l'ennemi à la vitesse d'un mitrailleur.
- La capacité de 10 tours est la principale migraine du tireur. En cas d'incendie automatique, toute la charge de munitions est épuisée en moins d'une seconde.
- Le recul en mode automatique complet fait des deuxième et troisième balles d'une explosion un cadeau pour les oiseaux. Tirez en petits éclats.
- L'arme nécessite un entretien minutieux et une lubrification de haute qualité. Aux mains d'un combattant inexpérimenté, l'AVT-40 se transforme rapidement en une aviron capricieuse qui refuse de se recharger.
