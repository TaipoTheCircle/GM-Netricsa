FUSIL AUTOMATIQUE TOKAREV MODÈLE 1940


ARME : Fusil automatique Tokarev modèle 1940
MUNITIONS : 7,62x54mm R
ROF : ~25-30 (simple) / ~700-800 (rafale) tours/min
POIDS : ~3,85 kg

DESCRIPTIF :

Ce fusil automatique soviétique a été développé en 1942 pour remplacer d'urgence les rares mitrailleuses légères. Sa conception est une modification majeure du célèbre fusil semi-automatique SVT-40, en y ajoutant un mode de tir continu.

Le sélecteur de mode de tir est intégré à la sécurité, permettant au tireur de basculer instantanément entre des tirs simples précis et des rafales dévastatrices. L'arme est alimentée par des chargeurs amovibles de 10 cartouches, qui peuvent également être chargés par le haut à l'aide de clips standard.

Malgré sa conception, l'AVT-40 s'est avéré trop léger pour la puissante cartouche de fusil de 7,62 x 54 mm. Lors du tir en rafale, le fusil était littéralement arraché de vos mains, la précision diminuait et le canon fin et le mécanisme s'usaient rapidement. Pour cette raison, les troupes n’étaient autorisées à tirer en rafale que pendant les moments les plus critiques du combat.

REMARQUES :

- Il possède le pouvoir meurtrier d'un fusil Mosin, mais est capable de faire pleuvoir du plomb sur l'ennemi avec la vitesse d'une mitraillette.
- La capacité du chargeur de 10 cartouches est le principal casse-tête du tireur. En tir automatique, la totalité de la charge de munitions est épuisée en moins d'une seconde.
- Le recul insensé en mode entièrement automatique fait des deuxième et troisième balles en rafale un cadeau pour les oiseaux. Tirez par courtes rafales.
- L'arme nécessite un entretien minutieux et une lubrification de haute qualité. Entre les mains d'un combattant inexpérimenté, l'AVT-40 se transforme rapidement en une rame capricieuse qui refuse de recharger.
