CHOPPER DU MOBIUS


CLASSE:      Coupeur
MÉTABOLISME: Hydro-Animal-Batterie
PERCEPTION: Garde du périmètre ambuscade
TAILLE:       4 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Moyenne
ARMES:    Hull, Jaws
RÉCOMPENSE:     300 FC
MENACE:     Faible

DESCRIPTION:

Lorsque M. Eggman a eu à faire face au problème de la protection des ponts et des voies navigables, il a tourné son attention vers les piranhas. Leurs attaques rapides de l'eau sont devenues la base du projet Chopper. Les premiers modèles ont été assemblés à partir de tout ce qui flottait autour: la coque d'un perroquet rouge, les nageoires d'un ancien ventilateur, les dents d'un râteau de jardin, et le moteur d'un broyeur à café Mriya.

Chopper est le seul Badnik qui ne poursuit pas sa cible, mais attend patiemment sous l'eau. Il s'accroche dans l'eau, barrant ses dents, regardant la surface. Dès qu'une silhouette apparaît au-dessus du pont, Chopper saute droit vers le haut, en direction droite de l'estomac du voyageur. Si l'attaque échoue, elle retombe et tente de nouveau après un certain temps. Dans les modifications ultérieures, il a appris à nager horizontalement et même mettre en place des embuscades de groupe.

Un liquide huileux glisse à l'intérieur de sa coque, remplaçant son cerveau. La seule commande stockée dans sa mémoire est: "S'il est sombre au-dessus, mordent".

CONSEILS:

- Attaque quand elle saute, pendant qu'elle est suspendue en l'air.
Ne restez pas immobile quand vous traversez le pont.
- Certains modèles sont capables de poursuivre des cibles sous l'eau.
