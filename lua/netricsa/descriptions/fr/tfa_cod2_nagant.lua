NAGANT M1895 REVOLVER


ARME: Nagant M1895 Revolver
MUNITIONS:   7.62x38mm Nagant
CADENCE DE TIR:    ~14-20 tours/min
POIDS: ~0,88 kg (avec cartouches)

DESCRIPTION:

Ce légendaire revolver à sept balles a été développé par les armuriers belges, les frères Nagant, pour l'Empire russe. Malgré son âge vénérable, il devint un symbole du soldat soviétique et fut largement utilisé dans l'Armée rouge aux côtés de pistolets plus modernes.

La principale caractéristique technique du Nagant est son système unique d'étanchéité au gaz. Lorsque le marteau est coiffé, le cylindre glisse sur le barillet, et l'encolure du boîtier de la cartouche entre dans la fente. Ceci élimine complètement les fuites de gaz entre le cylindre et le barillet, ce qui augmente non seulement la vitesse du museau, mais permet également d'utiliser efficacement le revolver avec un silencieux.

L'arme possède une fiabilité phénoménale et une résistance à la contamination. En raison de l'impossibilité de décharger de façon accidentelle si elle est larguée et de la serrure rigide du cylindre, elle est très respectée par les équipages de chars, les éclaireurs et les officiers.

REMARQUES:

- Très précis pour un pistolet, mais vient au prix d'une gâchette raide lors du cocking.
- La conception unique permet l'installation d'un suppresseur Bramit, faisant du revolver un outil silencieux d'assassinat.
- Une véritable « arme de dernière chance » qui continuera à tirer même si elle est récupérée du fond d'un marécage.
