NAGANT M1895 REVOLVER


ARME : Nagant M1895 Revolver
MUNITIONS : 7.62x38mm Nagant
ROF : ~14-20 rounds / min
Weight: ~0,88 kg (with cartridges)

DESCRIPTIF :

This legendary seven-shot revolver was developed by the Belgian gunsmiths, the Nagant brothers, for the Russian Empire. Despite its venerable age, it became a symbol of the Soviet soldier and was widely used in the Red Army alongside more modern pistols.

La principale caractéristique technique du Nagant est son système unique d'étanchéité aux gaz. Lorsque le chien est armé, le barillet glisse sur le canon et le col de la douille pénètre dans la culasse. Cela élimine complètement les fuites de gaz entre le cylindre et le canon, ce qui augmente non seulement la vitesse initiale, mais permet également d'utiliser efficacement le revolver avec un silencieux.

The weapon boasts phenomenal reliability and resistance to contamination. Due to the impossibility of accidental discharge if dropped and the rigid cylinder lock, it was highly respected among tank crews, scouts, and officers.

REMARQUES :

- Highly accurate for a pistol, but comes at the cost of a stiff trigger pull when cocking.
- La conception unique permet l'installation d'un suppresseur Bramit, transformant le revolver en un outil d'assassinat silencieux.
- Une véritable "Arme de la Dernière Chance" qui continuera à tirer même si elle est récupérée au fond d'un marais.
