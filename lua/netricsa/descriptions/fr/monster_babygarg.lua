BÉBÉ GARGANTUA DE XEN


CLASSE:      Gargantua, bébé
MÉTABOLISME: prédateur xénobiologique miniature
PERCEPTION: Stade précoce de Gargantua
TAILLE:       5-6 pieds de haut
ENDURANCE:  moyenne
HOSTILITÉ:  modérée
ARMES:    petites explosions de lance-flammes, bouffées de chaleur
RÉCOMPENSE:     300 FC
MENACE:     faible individuellement, modérée en groupes

DESCRIPTION:

Le bébé Gargantua est ce qui arrive quand un Gargantua saute quelques étapes évolutionnaires. Il a encore un penchant pour le feu et les choses qui éclatent, mais son caractère court est généralement plus hilarant que mortel. Pensez-y comme un enfant pyromane avec une super force.

Le bébé Gargantuas est souvent vu se promener après les plus grands ou les imiter dans la destruction chaotique et adorable. en meutes, ces petites punaises peuvent créer le chaos presque aussi efficacement que leurs parents.

CONSEILS:

- Ne sous-estimez pas la beauté - il vient avec la fumée et le feu.
- Les regrouper peut faire une petite rencontre étonnamment désordre.
- Les risques environnementaux comme l'effondrement des structures peuvent aider même les chances.