DESCRIPTIF :

Ces arachnides étaient appelés « Scorpions » par les humains, bien que la base de données officielle d'EDF les appelle « Soldats arachnides ». Cependant, Scorpion Soldier semble plus cool.

Ces arachnides extraterrestres sont originaires d’une planète lointaine et hostile, où ils constituaient l’espèce dominante. Ils ont même réussi à former une société avancée, au moins aussi avancée que celle des insectes géants.

Mental a formé une alliance avec leur matriarche, et elle propose à ses guerriers de se battre pour sa cause en échange de permettre à ses couvées d'infester les planètes qu'ils aident Mental à conquérir.

Les soldats sont les plus faibles et les plus petits des essaims d’arachnides, même s’ils restent assez dangereux. Ils sont armés d'un canon de classe Eviscerator qui tire rapidement des projectiles à plasma. Leur rôle principal sur le champ de bataille est de détruire l'infanterie ennemie sur un terrain difficile où l'infanterie régulière de Mental aurait du mal à traverser.

CONSEILS :

- Gardez vos distances et évitez leurs tirs en vous déplaçant sur le côté.
- Leurs griffes sont encore plus dangereuses que leurs tirs.
- Débarrassez-vous-en avec un fusil de sniper ou des explosifs.
- Ne les appelez PAS « Arachnoïdes ». Ils sont enragés par la comparaison avec une espèce bien plus primitive qu’eux.