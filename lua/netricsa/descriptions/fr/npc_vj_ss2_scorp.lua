VENDU SCORPION, TROOPER


CLASSE:      Scorpion Soldat, Trooper
MÉTABOLISME: Arthropodes endothermiques Viviparus
PERCEPTION: Course Arachnid avancée
TAILLE:       9,8 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Éviscération Cannon
RÉCOMPENSE:     125 FC
MENACE:     Haut

DESCRIPTION:

Ces arachnides ont été appelés « Scorpions » par les humains, bien que la base de données officielle EDF les appelle « Soldats Arachnides ». Cependant, Scorpion Soldier semble plus cool.

Ces arachnidés extraterrestres proviennent d'une planète lointaine et dure, où ils étaient l'espèce dominante. Ils ont même réussi à former une société avancée, au moins aussi avancée que possible pour les insectes géants.

Mental a formé une alliance avec leur Matriarche, et elle fournit à ses guerriers de se battre pour sa cause en échange de permettre à ses couvées d'infester les planètes qu'elles aident à conquérir Mental.

Les soldats sont les plus faibles et les plus petits essaims d'arachnie, bien qu'ils soient encore très dangereux. Ils sont armés d'un canon de classe Eviscerator qui tire rapidement des projectiles plasmatiques. Leur rôle principal sur le champ de bataille est de détruire l'infanterie ennemie en terrain difficile où l'infanterie régulière de Mental aurait du mal à traverser.

CONSEILS:

- Gardez votre distance et évitez leurs tirs en se déplaçant sur le côté.
- Leurs griffes sont encore plus dangereuses que leurs tirs.
- Débarrassez-vous d'eux avec un fusil ou des explosifs.
- Ne les appelez pas "Arachnoïdes". Ils sont enragés par rapport à une espèce beaucoup plus primitive qu'eux-mêmes.
