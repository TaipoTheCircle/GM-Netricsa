MG 34 GENERAL-PURPOSE MACHINE GUN


ARME: MG 34 mitrailleuse générale
MUNITIONS:   7,92x57mm Mauser
CADENCE DE TIR:    ~800-900 tours/min
POIDS: ~12 kg

DESCRIPTION:

Une mitrailleuse allemande à usage général s'est développée pendant l'entre-deux-guerres et a été adoptée en 1934. Il a été conçu comme une arme polyvalente, capable de servir de mitrailleuse légère, de mitrailleuse lourde ou de mitrailleuse-citerne, selon l'équipement installé.

La mitrailleuse utilise une action de courte durée et a un taux de feu très élevé pour son temps. Il est alimenté principalement par des ceintures; il existe aussi des variantes avec des magazines à tambour. Grâce à la capacité de changer rapidement de barils, le MG 34 est capable d'un feu soutenu, bien qu'un tir intense réchauffe rapidement le baril.

La caractéristique principale du MG 34 est sa polyvalence : la même mitrailleuse pourrait être utilisée par l'infanterie sur un bipode, montée sur un trépied ou utilisée comme armement pour les véhicules blindés.

REMARQUES:

- Son taux de feu extrêmement élevé rend le MG 34 particulièrement efficace pour supprimer les ennemis à des distances proches et moyennes.
- Montée sur un trépied, la mitrailleuse est capable de déclencher un tir précis à des cibles éloignées et groupées.
- Le baril se réchauffe rapidement lors d'un feu intense, ce qui permet de le remplacer par un véritable sauveur de vie.
- Une mitrailleuse, trois rôles : infanterie, trépied et char. La polyvalence est parfaite à la rigueur allemande.
