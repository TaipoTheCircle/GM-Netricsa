DEMI-QUAKE 2, CHAMBRE BAS PLAFOND


Sam ! Avis? Les ennemis ici ne sont pas seulement des Mentaliens, ce sont aussi des Vortigaunts gris désormais. Les sadiques ont clairement embauché du nouveau personnel. Et ce personnel a l'air très mécontent de son travail... ou est-ce juste ses expressions ?

...

Chercher. Il y a un bouton au plafond. Et il y a d'autres boutons sur les côtés de la pièce, mais ils sont bloqués par une barrière mortelle. Devinez ce que vous devez faire ? Ouais, tu as raison : saute au plafond, appuie sur le bouton, enlève la barrière, cours vers le bouton latéral, appuie dessus, puis retourne au plafond. Et ainsi de suite-jusqu'à ce que tous les boutons soient enfoncés.

Mais je vous préviens : le temps est limité. Si vous n’y parvenez pas, la barrière se réactivera. Et ça tue. Ça ne fait pas mal, ça ne vous renverse pas, ça TUE. Les sadiques ont clairement décidé d'ajouter un peu de cardio au show.

Cours plus vite, Sam ! Et ne laissez pas ces Vortigaunts gris vous rattraper : ils semblent vouloir vous demander de l'aide... ou vous zapper avec de l'électricité. Avec eux, on ne sait jamais !