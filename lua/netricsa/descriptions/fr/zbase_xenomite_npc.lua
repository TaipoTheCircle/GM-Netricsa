XÉNOMIE DE L'EAU


CLASSE:      Swarm Xenomie
MÉTABOLISME: Xénobiologique
PERCEPTION: Organisme symbiotique
TAILLE:       1,3 pi
ENDURANCE:  Très faible
HOSTILITÉ:  Absolu
ARMES:    Attaque de saut, blast acide
RÉCOMPENSE:     25 FC
MENACE:     Moyenne

DESCRIPTION:

La Xenomie est une petite forme de vie parasitaire soulevée par Reapers pour défense et offense. Elle passe la majeure partie de sa courte vie près de son parent, en attendant qu'une proie appropriée émerge.

Malgré sa taille modeste, la Xenomie est extrêmement dangereuse. Lorsqu'il repère une proie, il fait un saut rapide et tente de se refermer. Contrairement à la plupart des créatures de Swarm, son but principal n'est pas de tuer son adversaire, mais de se détruire à proximité.

Le corps de la Xenomie est rempli de composés acides instables. À la mort ou aux dommages critiques, la créature explose, dispersant la biomasse corrosive. Le contact avec ces substances peut causer des brûlures chimiques graves même quelques secondes après la détonation.

La durée de vie de la Xenomie est extrêmement courte. Apparemment, l'évolution de l'organisme a complètement abandonné la survie à long terme en faveur d'une efficacité maximale lors d'une seule attaque.

CONSEILS:

- Détruisez Xenomies à distance.
- Ne les laisse pas s'approcher.
- Après la mort de la créature, éloignez-vous des restes acides.
- Si la créature ne vit que pour exploser près de vous, il est trop tard pour discuter avec son but dans la vie.
