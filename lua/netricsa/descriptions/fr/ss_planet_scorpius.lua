SCORPIUS


PLANET:       Scorpius
TYPE:         Planète terrestre, Wasteland
CLIMATE:      Aride, dure
MOONS:        Aucune
TERRAIN:      Desert de barren, de nombreux sommets de montagne déchiquetés
LOCATION:     Dans la constellation Scorpius
NATIVE RACES: Arachnoïdes
ALLIANCE:     Autrefois un monde Arachnoide indépendant, maintenant Mental Horde (Toutes les races)
LOCATIONS:    Chambre haute du Conseil, déchets fanatiques

DESCRIPTION:

La surface de la planète est un désert sans vie, brûlé, rappelant les paysages martiens, mais avec une brume rouge foncé inquiétante. Un brouillard épais enveloppe les sommets de la montagne qui s'élève du désert. Cet environnement rude a façonné le caractère des habitants et a alimenté leur fanatisme extrême.

Sur cette planète, Mental a découvert une race primitive mais intelligente, les Arachnoïdes. Se présentant à eux comme un messie, Mental a rassemblé une faction de fanatiques religieux parmi eux.

Avec son aide, ces fanatiques ont détruit le Haut Conseil de Scorpius et effacé des millénaires de leur propre culture, interdisant les reliques du passé.

Cela a conduit à une guerre civile brutale, au cours de laquelle les Arachnoïdes se sont exterminés.

La jeune génération a commencé à être conscrite de force dans l'armée de Mental, provoquant un mouvement de résistance parmi les survivants cherchant à saboter les plans de Tah-Um de l'intérieur.

KEY LOCATIONS:

- Chambre du Haut Conseil : L'ancien centre de la civilisation arachnoïde, où les connaissances millénaires ont été préservées.
- Déchets fanatiques : Régions contrôlées par des cultivateurs, où des fouilles actives et le recrutement forcé ont lieu.
