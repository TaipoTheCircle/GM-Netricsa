XM214-A MINIGUN


ARME:    XM214-A Minigune
MUNITIONS:      balles de 5,56 mm
CADENCE DE TIR:       1200 balles/min
POIDS:    30 livres

DESCRIPTION:

Passant de Gatling à Vulcain et M134, XM214-A est une nouvelle dans l'armement d'infanterie. Autoalimenté et complet avec un magazine intégré et un adaptateur de recul, c'est l'arme personnelle la plus puissante disponible.

REMARQUES:

- Utiliser pour une confrontation de courte à longue portée avec des ennemis difficiles ou l'élimination massive d'un grand nombre de petits adversaires.
- Dépense les munitions rapidement.