DEUX MODÈLES SMITH & WESSON 28 RÉVOLEURS


GUN:         DEUX MODÈLES SMITH & WESSON 28 RÉVOLEURS
CALCULATION: .357 Magnum
CADENCE DE TIR:         40 RPM

DESCRIPTION:

Le Smith & Wesson Model 28, ou Highway Patrolman, est l'arme de service standard pour les policiers d'Abbott et de nombreux autres organismes d'application de la loi du Maryland. Il tire la cartouche .357 Magnum et tient six rondes. C'est une arme extrêmement mortelle. Ceux qui sont habiles à utiliser une telle arme peuvent être beaucoup plus dangereux avec deux d'entre eux. Comme les règlements sur les armes à feu à Abbott sont assez laxistes, ces pistolets sont trouvés en abondance partout où les agents les stockent. Les munitions sont également très faciles à obtenir. Vous pouvez d'abord les obtenir auprès de l'agent principal, soit en le tuant lorsqu'il quitte la salle de bains, soit en l'électrocutant dans la salle de fauteuil électrique. Un deuxième revolver, à double usage, se trouve au chapitre 2, « Descent », après avoir rencontré les trois fantômes de l'île et exploré la folie et la créature, mais avant de rencontrer les premiers tireurs qui exécutent l'officier lié. Tirez le levier pour faire exploser le générateur dans la pièce inondée que vous passez, et le deuxième revolver peut être trouvé caché dans le mur derrière lui.

