STORMTROOPER DE CLONE, SNIPER DU KAMINO


CLASSE:      Clone Stormtrooper, Sniper
MÉTABOLISME: Clone humain, Homme
PERCEPTION: Elite Marksman de l'Empire Galactique
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrême
ARMES:    Rifle de sniper « RAPTOR » amélioré avec designateur laser
RÉCOMPENSE:     1200 FC
MENACE:     Très élevé

DESCRIPTION:

Les snipers sont le niveau suivant de la hiérarchie du Stormtrooper Corps et sont recrutés exclusivement parmi les clones les plus disciplinés et précis. Ils sont facilement identifiés par leur armure grise, délivrée aux soldats qui ont subi un entraînement spécial pour le combat à longue portée.

L'arme primaire du sniper est un fusil « RAPTOR » modernisé, équipé d'optiques de haute précision et d'un designateur laser. Le laser permet de suivre les cibles en mouvement et réduit considérablement le temps de visée, tandis que ses puissantes munitions piercing d'armure peuvent pénétrer la plupart des types connus d'équipement de protection individuelle.

Contrairement aux troupes d'assaut classiques, les tireurs embusqués se livrent rarement à des combats ouverts. Ils occupent des hauteurs de commandement, des toits ou des positions fortifiées, d'où ils éliminent les cibles les plus dangereuses, laissant le reste à l'infanterie de ligne. Même après la détection, ils maintiennent leur sang-froid et continuent à tirer jusqu'au dernier moment possible.

Alliés à Mental, ces soldats sont appréciés pour leur capacité à éliminer l'ennemi avant que les forces principales ne s'engagent. Beaucoup de commandants préfèrent envoyer quelques snipers d'abord avant de commettre des unités entières à l'attaque. Perdre un tel tireur est désagréable, mais perdre un commandant à un seul tir bien aisé est beaucoup plus désagréable.

CONSEILS:

- Si vous remarquez un laser rouge, quelqu'un vous a déjà repéré.
- Ne restez pas trop longtemps dans les espaces ouverts.
- La fumée, la couverture et le mouvement constant réduisent considérablement leur efficacité.
- L'armure grise est moins visible que le blanc. Malheureusement, ils tirent à l'envers.
