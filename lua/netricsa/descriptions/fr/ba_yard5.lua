MESA BLACK WAREHOUSE, FREIGHT YARD


Alors récapitulons, Sam.

Le conteneur bleu s'est avéré plein de Vortigaunts. Le rouge, les scientifiques. Logique suivie, surprises découvertes, confiance dans le codage couleur complètement détruit.

Un autre conteneur nous accueille dehors. Bien sûr, il est rouge. Si le système a fonctionné une fois, il doit certainement être inspecté. Il est garé dans le train, le dernier espoir de sortir de ce trajet. Rosenberg est là ? C'est inconnu. Mais la probabilité est plus élevée que les deux précédentes, et dans Black Mesa, c'est une raison d'optimisme.

Bloquer soigneusement l'entrée du contenant avec les tapis et les bobines. Pas symboliquement, littéralement. Quelqu'un a décidé que le meilleur moyen de le garder était de placer quelque chose de lourd et de le clouer avec des planches. Un plan conçu pour les personnes qui ne peuvent pas perturber l'environnement pour le progrès. Vous n'êtes malheureusement pas l'un d'eux.

La mécanique est simple. Tu casses les planches et les bobines tombent. Les bobines tombent, et le passage s'ouvre. Les lois de la physique, contrairement aux lois de la raison humaine, s'appliquent toujours ici.

Le secteur est surveillé par des soldats de l'UE. Les mêmes visages, les mêmes fusils, la même certitude qu'avant. Dans la pièce suivante, derrière la tablette, se trouve un réservoir d'Abrams. Des soldats à l'intérieur. Apparemment, ils considèrent le tank comme un argument convaincant avec un homme qui a déjà vécu à travers la fin du monde.

Si Rosenberg est vraiment dans ce conteneur, il a de la chance.

Sinon, nous avons simplement déplacé des objets lourds à nouveau pour le moral.

En tout cas, Sam, le choix est clair.

Arrêtez. Laissez tomber les bobines.

Le chemin de fer n'a pas vu un tel passager depuis longtemps.