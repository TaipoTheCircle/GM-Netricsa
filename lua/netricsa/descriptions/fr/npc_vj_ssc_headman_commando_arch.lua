ARCHÉOLOGUE Décapitée, COMMANDO FÉMININ DE L'ÎLE MYSTÉRIEUSE


CLASSE : Archéologue décapité, femme commando
MÉTABOLISME : Cyber-Zombie
PERCEPTION : Insensible, contrôlé par LCU
TAILLE : 6 pieds
ENDURANCE : Moyenne
HOSTILITÉ : Moyenne
ARMES : munitions magiques, grenades à main
RÉCOMPENSE : 3000 FC
MENACE : Moyenne

DESCRIPTIF :

Un archéologue décapité d'une île mystérieuse, ressuscité des morts par Mental et télécommandé par Life Control Unit (LCU). 

Le Commando porte sa propre tête dans une main pour recevoir des informations audiovisuelles. Vétéran aguerri de l'unité des forces spéciales Beheaded Troops et vétéran de nombreux combats, la commando féminine est un adversaire bien plus dangereux et puissant que ses camarades recrues « Orange ». Elle tire cinq projectiles magiques à partir d'un lance-roquettes intégré à sa tête et lance également cinq grenades à main à la fois. Contrairement aux autres soldats décapités, la commando féminine utilise une tactique de combat différente : lorsqu'elle sent qu'elle est sur le point de mourir, elle se jette sur l'ennemi avec ses dernières forces et explose lorsqu'elle se rapproche suffisamment de sa cible. Le commando est invulnérable à ses propres roquettes, mais peut être endommagé par ses propres grenades.

CONSEILS :

- Évitez ses grenades.
- Après avoir subi suffisamment de dégâts, la commando féminine passe en mode kamikaze.