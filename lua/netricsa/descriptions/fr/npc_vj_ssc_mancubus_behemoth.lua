MANCUBUS, DE L'ACIER


CLASSE:      Mancubus, Behemoth
MÉTABOLISME: Mammifère démoniaque
DEFINITION: Personnalité faible de la glutennerie
TAILLE:       13 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Haut
ARMES:    Deux RPG
RÉCOMPENSE:     1000 FC
MENACE:     Moyenne

DESCRIPTION:

C'est un démon affaibli, personnifiant l'imperfection humaine et l'avidité, la gloutonnerie et l'oisiveté. Il a une peau incroyablement épaisse, des jambes éléphantines massives et une petite tête. Pour détruire et exploser ses victimes, deux RPG sont implantés dans les avant-bras du Mancubus, tirant des roquettes.

Mental les a achetés au Seigneur de l'Enfer, avec Zombie Soldiers et d'autres non-morts, pour renforcer sa Horde.

Les yeux des Béhémoth ne sont pas verts comme ceux des Mancubus ordinaires, mais rouge vif, brûlant avec le feu de la haine.

Sa peau a une teinte bleue, mais au lieu du sang rouge, une substance verte toxique coule de ses veines - un signe sûr d'un rituel raté.

Au lieu de lance-flammes intégrés, le Behemoth a des lance-roquettes attachés à ses coudes, remplaçant ses membres. Contrairement au Mancubus ordinaire, qui tire des boules de feu, le Behemoth tire deux roquettes à la fois. Ces fusées volent jusqu'à ce que la cible soit détruite.

Le Behemoth lui-même est significativement plus faible en défense que le Mancubus classique. Quelques coups de fusil peuvent le renvoyer en enfer.

CONSEILS:

- Malgré sa taille, le Behemoth n'est pas particulièrement durable.
- Deux coups de feu et le démon ne sera qu'un endroit humide.
- Évitez les missiles et ne restez pas en liberté.
