DESCRIPTION:

Il a toujours été spéculé que l'Ugh-Zan vicieux n'est pas une dynastie de monstres immortels, mais une seule entité incorporelle qui réincarne dans différents corps (habituellement ceux avec au moins quatre bras), expliquant l'apparence différente de la créature entre ses incarnations. Les candidats Ugh-Zan en sont la preuve.
Formés par un culte fanatique des adorateurs d'Ugh-Zan ("Zanlites"), les candidats sont des clones produits en masse d'Ugh-Zan 3, à différents stades de croissance. Après la mort d'Ugh-Zan 3, ceux-ci ont été créés et sont constamment en entraînement de combat épuisant pour croître à la même taille et la même force que l'original. Au fur et à mesure qu'ils grandissent, de plus en plus d'armes d'Ugh-Zan 3 sont capables de manier.
Finalement, un seul candidat d'Ugh-Zan restera, et l'esprit d'Ugh-Zan se réincarnera à l'intérieur.

CONSEILS:

- Utilise les armes les plus puissantes et les sorts magiques connus
- Livré en différentes tailles avec des armes variées
