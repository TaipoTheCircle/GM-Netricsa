TÉLÉCOPIEUR


CLASSE:      Swarm Drone, Über-Bug
MÉTABOLISME: Arthropodes étrangers
PERCEPTION: Drone d'assaut lourd
TAILLE:       ~6,8 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Haut
ARMES:    Griffes, Jaws, Fangs, Corps explosif
RÉCOMPENSE:     600 FC
MENACE:     Très élevé

DESCRIPTION:

Le Drone Swarm est une version beaucoup plus grande, plus massive et plus lente du drone standard. Son corps se distingue par des muscles extrêmement développés et une épaisse couverture chitineuse, lui permettant de supporter une quantité énorme de dommages.

La caractéristique principale de sa structure est ses énormes parties de bouche. Sa bouche est entourée par de nombreuses longues crosses pointues, disposées en plusieurs rangées. Lors de l'attaque, le Über-Bug utilise ces crocs en conjonction avec ses membres antérieurs, infligeant de lourds dommages à toute cible à portée.

Malgré sa durabilité impressionnante, le Über-Bug est nettement plus lent et moins maniable qu'un drone standard. Elle avance lentement, en s'appuyant sur sa capacité à résister au feu ennemi.

Cependant, la caractéristique la plus dangereuse du Über-Bug se manifeste à sa mort.

À la mort, le corps de la créature explose, libérant une grande quantité de matériel biologique et causant des dommages importants aux cibles voisines. Par conséquent, la destruction du Über-Bug à proximité peut être fatale même après que l'étranger lui-même a déjà péri.

Pour cette raison, le Über-Bug reste une menace tout au long de la rencontre.

CONSEILS:

- Évitez de terminer le Über-Bug à bout portant.
- Laissez toujours une distance entre vous et lui avant de donner le coup de mort.
- Utilisez des armes à longue portée pour le détruire en toute sécurité.
- Son explosion est particulièrement dangereuse dans les espaces confinés.
- S'il est entouré de drones, évaluez d'abord vos options de retraite.
