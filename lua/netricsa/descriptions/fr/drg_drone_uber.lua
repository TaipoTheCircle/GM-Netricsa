DRONE ESSAIS, ÜBER-SCARABÉE


CLASSE : Swarm Drone, Über-Bug
MÉTABOLISME : Arthropode extraterrestre
PERCEPTION : Drone d'assaut lourd
TAILLE : ~6,8 pieds
ENDURANCE : Très élevée
HOSTILITÉ : Élevée
ARMES : Griffes, Mâchoires, Crocs, Corps Explosif
RÉCOMPENSE : 600 FC
MENACE : Très élevée

DESCRIPTIF :

Le Swarm Drone est une version nettement plus grande, plus massive et plus lente du drone standard. Son corps se distingue par une musculature extrêmement développée et une épaisse couverture chitineuse, lui permettant de résister à d'énormes dégâts.

La principale caractéristique de sa structure réside dans ses énormes pièces buccales. Sa bouche est entourée de nombreux crocs longs et pointus, disposés sur plusieurs rangées. Lorsqu'il attaque, l'Über-Bug utilise ces crocs en conjonction avec ses membres antérieurs, infligeant de lourds dégâts à toute cible à portée.

Malgré sa durabilité impressionnante, l'Über-Bug est nettement plus lent et moins maniable qu'un drone standard. Il avance lentement, en s’appuyant sur sa capacité à résister aux tirs ennemis.

Cependant, la caractéristique la plus dangereuse de l'Über-Bug se manifeste dès sa mort.

À sa mort, le corps de la créature explose, libérant une grande quantité de matière biologique et causant des dégâts importants aux cibles proches. Par conséquent, détruire l’Über-Bug à courte distance peut être fatal même après que l’extraterrestre lui-même ait déjà péri.

Pour cette raison, l'Über-Bug reste une menace tout au long de la rencontre.

CONSEILS :

- Évitez de terminer l'Über-Bug à bout portant.
- Laissez toujours une certaine distance entre vous et lui avant de porter le coup fatal.
- Utilisez des armes à longue portée pour le détruire depuis une position sûre.
- Son explosion est particulièrement dangereuse dans les espaces confinés.
- S'il est entouré de drones réguliers, évaluez d'abord vos options de retraite.