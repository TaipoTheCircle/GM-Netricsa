GRANDE ZOMBIE, TOM BAKER


CLASSE:      Zombie à grandes têtes, Tom Baker
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     100 FC
MENACE:     Annoyance

DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme de Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont totalement inoffensifs, mais sur le niveau de difficulté "I Am Ugh-Zan" ils gagnent feu et des modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Tom Baker est un pont vivant reliant le monde de Croteam avec le vaste univers de 2K Games et d'autres grands studios. Son crâne surdimensionné est une archive contenant de l'expérience de travail sur plus de 150 jeux, des hits cultes comme BioShock, Borderlands, XCOM, Civilization, et Mafia à des projets de niche et des jeux d'enfants sous licence. Dans le cadre de Serious Sam, il a fait partie de l'équipe de conception de The Second Encounter et a ensuite travaillé sur la publication de Serious Sam II dans le cadre de l'équipe européenne de Take-Two Interactive.

Sa carrière illustre l'évolution d'un membre de l'équipe de conception à un gestionnaire principal de conception, en supervisant les processus créatifs sur les projets AAA. Tom est l'épitome d'un concepteur de jeu professionnel, multi-talent, quelqu'un qui comprend la mécanique de jeu à un niveau systémique et peut appliquer cette expérience à la fois le chaos indépendant de Croteam et les blockbusters de 2K.

Il était une fois vivant, mais après que vous l'ayez tué dans le Temple de Hatshepsut, il est ressuscité d'entre les morts - devenant un zombie démoniaque.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager le chemin.
- Sur la difficulté "Je suis Ugh-Zan", les éliminer à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.
