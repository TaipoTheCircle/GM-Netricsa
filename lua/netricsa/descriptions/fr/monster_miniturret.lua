NOIR MESA MINI TURRET


CLASSE:      Mini tourelle Mesa noire
MÉTABOLISME: Constrtuction mécanique
PERCEPTION: Unité de défense automatisée compacte
TAILLE:       ~2 pi
ENDURANCE:  moyenne
HOSTILITÉ:  extrême
ARMES:    petite mitrailleuse à feu rapide
RÉCOMPENSE:     250 FC
MENACE:     modérée

DESCRIPTION:

Le Mini Turret est une variante compacte du Turret blindé Black Mesa standard. Il conserve des capacités de ciblage automatisées et une fonctionnalité d'incendie rapide, mais il est plus petit, plus léger et plus maniable. Comme son homologue grandeur nature, il peut être monté sur des planchers ou des plafonds, permettant un déploiement polyvalent dans des espaces restreints.

Bien qu'elle soit moins blindée que la version complète, elle demeure mortelle contre les cibles non protégées, capable de supprimer les intrus et de défendre les points d'accès critiques. Sa petite taille le rend plus difficile à repérer jusqu'à ce qu'il ouvre le feu.

CONSEILS:

- Des explosifs ou des tirs précis peuvent le désactiver rapidement.
- Vérifiez ci-dessus et ci-dessous - même les petites tourelles peuvent couvrir des angles inattendus.
- Évitez de vous tenir dans des couloirs ou des étranglements où il peut vous cibler efficacement.
- Utiliser une couverture environnementale pour minimiser l'exposition à ses tirs de mitrailleuses.
