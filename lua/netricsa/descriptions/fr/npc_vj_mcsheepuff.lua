FICHE DU MINECRAFT AUTRE MONDE


CLASSE:      Ovins
MÉTABOLISME: Biologique, flottant
PERCEPTION: Animaux flottants pacifiques
TAILLE:       4 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Aucune
ARMES:    Aucune
RÉCOMPENSE:     50 FC
MENACE:     Zéro

DESCRIPTION:

Ces créatures à fourrure habitent des îles flottantes dans le ciel et sont parmi les créatures les plus paisibles de ce monde étrange.

Ils ressemblent à des moutons ordinaires, mais leur laine semble fluffier et plus légère, comme tissée à partir de nuages. Leur coloration peut varier – blanc, bleu, rose, lime et cyan, les moutons colorés étant beaucoup plus rares que les moutons blancs.

C'est la principale différence avec les moutons réguliers. Ils peuvent « gonfler » et se lancer haut dans les airs (comme une fusée), puis glisser lentement vers le bas. Cela les fait parfois tomber de l'île et s'écraser.

Ils paissent sur l'herbe nuageuse, la mangent et la transforment en saleté.

Ils peuvent être élevés avec du blé, des oranges ou des bleuets.

Lorsqu'ils sont cisaillés avec des cisailles, ils déposent la laine nuageuse, un matériau spécial de cette dimension. Une fois cisaillé, un mouton perd sa capacité de voler jusqu'à ce qu'il repousse sa laine en mangeant de l'herbe.

CONSEILS:

- Pour obtenir beaucoup de laine nuageuse, troupeau de moutons dans un stylo avec de l'herbe et les tondre toutes les quelques minutes.
- Une fois qu'un mouton est rasé, il ne peut pas voler - c'est le moment idéal pour le troupeau à la sécurité.
- Contrairement aux moutons ordinaires, cette espèce peut être une source précieuse de ressources pour l'élaboration d'articles de la dimension éthérée.
- N'essayez pas de les utiliser pour le transport. Ils sont incontrôlables.
