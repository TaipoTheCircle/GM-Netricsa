LE SIÈGE DE ZOMBIE COMMUN, LA GUARDE DE SÉCURITÉ OFF-DUTY


CLASSE:      Garde de sécurité hors du service 
MÉTABOLISME: Hôte humain + cratère parasitaire commun
PERCEPTION: Entité zombifiée
TAILLE:       6 pieds
ENDURANCE:  Faible-moyenne
HOSTILITÉ:  Modéré 
ARMES:    Griffes, Grappling
RÉCOMPENSE:     100 FC
MENACE:     Faible individuellement, modéré en groupes

DESCRIPTION:

OffDuty Zombies sont d'anciens gardes de sécurité Black Mesa qui n'étaient ni armés ni armés. Infectés par des cratères, ils se battent sans but mais attaquent tout à proximité avec des frappes grossières. Leur manque d'armure les rend moins résistants que S.E.C.U., ou zombies blindés, mais ils posent toujours une menace dans les groupes.

La transformation met l'accent sur la vulnérabilité tragique du personnel non préparé lors de l'épidémie de Xen, qui transforme des gardes-somnies inoffensifs en prédateurs lents.

CONSEILS:

- Gardez la distance ; leurs attaques sont lentes mais peuvent vous attraper.
- Les armes à feu sont efficaces; la mêlée est risquée.
- Les groupes peuvent coincer les proies, donc prioriser soigneusement les cibles.
