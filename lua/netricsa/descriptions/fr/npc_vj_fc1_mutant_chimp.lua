CHAMPANZE MUTÉE DE L'ARCHIPELAGO KRIEGER


CLASSE:      Chimpanzé muté
MÉTABOLISME: Trigène - un primate mutant.
PERCEPTION: Chasseur tactique
TAILLE:       1,1 ft
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Des griffes, des attaques.
RÉCOMPENSE:     400 FC
MENACE:     Haut

DESCRIPTION:

Le plus monstrueusement déformé de tous les primates, trigènes. Ne ressemblant qu'à des chimpanzés, ils ont acquis des caractéristiques reptiliennes : un museau allongé, quatre yeux jaunes et des membres à trois doigts avec des chiffres fourchus. Les restes de fourrure ne restent que le long de la colonne vertébrale. Idéales pour les attaques furtives, elles peuvent pénétrer les puits de ventilation grâce à leur petite taille.

CONSEILS:

- Critiquement vulnérable aux coups de tête - malgré leur vitesse, les tirs de précision sont efficaces.
- Gardez votre distance - à distance, leurs attaques à grande vitesse sont presque inarrêtables.
