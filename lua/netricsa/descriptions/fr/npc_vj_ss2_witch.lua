DYNJA L'ALCHEMISTE DE MAGNOR


CLASSE:      Dynja l'alchimiste
MÉTABOLISME: Mammifère, ancienne beauté
PERCEPTION: Sorcière
TAILLE:       4,6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Crânes magiques, chaudron, mains
RÉCOMPENSE:     50 FC
MENACE:     Haut

DESCRIPTION:

Elle était essentiellement l'une des plus belles filles de la galaxie, mais quand elle et sa sœur étaient prêtes à participer aux concours de beauté de Mental, elles se sont transformées en sorcières laides. Après cette erreur, ils furent facilement enrôlés dans l'armée de Mental.

Dynja est la sœur jumelle de Yagoda ; ensemble, ce sont les sorcières les plus célèbres de la planète Magnor. Ils sont réputés pour leur nature sadique, leur maîtrise de leur art et leur affection pour l'alcool.

C'est une alchimiste qui maîtrise l'art de créer des potions de clonage et les utilise pour se reproduire (auto-fermeture). Vu son potentiel, Mental lui a offert une offre de vodka à vie en échange de ses services. Elle a accepté avec joie.

Dynja se cache sur le sol, invoquant des crânes magiques de son chaudron pour traquer ses ennemis.

CONSEILS:

- Ils préfèrent attaquer autant que possible, plutôt que de déplacer ou d'éviter vos attaques.
- Les explosifs et les tirs de sniper peuvent les sortir facilement.
- Bien qu'un canon à double canon puisse les emporter à portée de main, il est mal conseillé de les approcher.
- Les crânes vont vous poursuivre, alors restez en mouvement si vous ne voulez pas être effrayé.
