BRICK, BRICK EST JEUNE FRÈRE


Sam, on dirait qu'on est tombés sur un parent minimaliste de ces maisons en brique qu'on a explorées. Si la version précédente était un « village urbain » avec une piscine et des bâtiments de deux étages, celui-ci est un désespérant obscène et suburbain au carré.

Deux maisons, brique, herbe, et un manque total d'indices de civilisation. Ils n'ont même pas creusé d'étang.

Devant nous se trouve une pelouse lisse et verte, sur laquelle reposent exactement deux bâtiments:

Deux maisons carrées en brique. Sans portes. C'est déjà une tradition. Apparemment, l'architecte s'est inspiré du concept de « l'hospitalité est une illusion, les ouvertures sont la réalité »

Les deux sont en brique rouge, les deux carrés, les deux silencieux.

Rien d'autre. Pas de clôture, pas d'arbres, pas de voitures. Juste la maison #1, la maison #2, et toi.

Première maison (alias "Staircase"):

Il y a un escalier au deuxième étage. Ça marche, ça mène. Il n'est pas cassé, pas cloué, pas gardé par un gnome. Juste des escaliers.

Au deuxième étage, il y a une fenêtre. Pas de verre. Un projet, une vue, la chance de se pencher et de crier: «Qui êtes-vous? Allez à F..." Ou se pencher et se faire tirer dessus. Une fenêtre est une chose.

Deuxième Maison (alias "Empty") :

Il n'y a pas de deuxième étage. Aucune.

Il n'y a rien dedans.

Cet endroit est une géométrie pure. Deux maisons, herbe, ciel. Pas de distractions, pas de provisions de Sophia, pas de piscines. Juste toi, l'ennemi, et une brique. Ici, tout dépend de votre vitesse de réaction et de votre capacité à utiliser la seule fenêtre au deuxième étage.

On peut commencer.
