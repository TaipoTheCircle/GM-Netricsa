RPG-7


ARME:             RPG-7
AMMUNITION:         Rockets pour RPG-7
CADENCE DE TIR:                1 tir/min

DESCRIPTION:

Le lance-grenade antichar portatif 7 est un lance-grenade antichar réutilisable soviétique. Conçu pour combattre les chars, les unités d'artillerie autopropulsées et d'autres véhicules blindés, il peut être utilisé pour détruire la main-d'oeuvre dans les abris, ainsi que pour combattre les cibles aériennes à basse vitesse. Le lance-grenades a été développé par GSKB-47 (aujourd'hui NGPP Bazalt) et adopté par les forces armées de l'Union soviétique en 1961. Le concepteur principal était Valentin Konstantinovich Firulin (gagnant du prix Lénine pour la création de cette arme). Plus de 9 millions d'unités ont été produites. Il est utilisé dans presque tous les conflits armés depuis 1968 et est toujours en service auprès des forces armées de nombreux États et pays. Grâce à l'émergence de nouvelles munitions, le RPG-7 constitue une menace importante pour les armes et l'équipement militaires modernes, et c'est pourquoi il demeure en demande au XXIe siècle.

REMARQUES:

- Efficacité contre les réservoirs légers et moyens.
- Livré avec une vue optique PGO-7V.
- Un seul coup, doit être rechargé après chaque coup.