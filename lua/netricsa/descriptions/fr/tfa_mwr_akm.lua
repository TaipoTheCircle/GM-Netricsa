MODERNIZED KALASHNIKOV ASSAULT RIFLE


ARME : Modernized Kalashnikov Assault Rifle
MUNITIONS : 7.62x39
ROF : ~600 tr/min

DESCRIPTIF :

Il s'agit d'une version modifiée de l'AK-47, développée par Mikhaïl Timofeevich Kalachnikov en 1950 et adoptée par l'URSS en 1959. Elle est très appréciée des terroristes et des guérilleros. Il a participé à presque toutes les guerres du monde, notamment la guerre du Vietnam, la guerre en Afghanistan, la guerre en Tchétchénie, la guerre en Irak et l'opération militaire spéciale. C'est un fusil d'assaut très fiable et populaire.

REMARQUES :

- It has greatly influenced the world, creating numerous copies and modifications.
- Il est très bien adapté à l'assaut.
- In the forests of Vietnam, the sound of its gunfire can be heard in the trees.
