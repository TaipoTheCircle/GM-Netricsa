DESCRIPTION:

Ivan le « Biker de l'espace » est le plus ancien connu des candidats à l'épreuve de Black Mesa, avant la désignation donnée plus tard à Gordon Freeman. Reconnu par sa barbe robuste, sa lourde construction et sa combinaison de danger orange caractéristique d'un modèle plus ancien, Ivan incarne la vision originale d'un sujet d'essai prêt à entrer dans des expériences de résonance à haut risque.

Contrairement aux scientifiques ordinaires, l'apparition d'Ivan est étonnamment militante, conduisant à des rumeurs internes selon lesquelles il a été choisi non seulement pour ses aptitudes techniques, mais aussi pour sa résilience face au danger. Bien qu'il n'ait pas de capacités extraordinaires au-delà de celle d'un humain ordinaire, son regard imposant lui a valu le surnom de « Biker de l'espace » parmi le personnel.

Ivan reste une figure symbolique de l'histoire de Black Mesa.

