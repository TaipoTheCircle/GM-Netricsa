NUMÉRO DE GENMOD-262 DE UH-1


CLASSE:      Genmod-262's Snark
MÉTABOLISME: Carnivore agressif
PERCEPTION: Insecte étranger
TAILLE:       ~1 pi
ENDURANCE:  Faible
HOSTILITÉ:  Extrême
ARMES:    Bite, griffes, explosifs à mort
RÉCOMPENSE:     150 FC
MENACE:     Haut

DESCRIPTION:

Ces Snarks sont engendrés directement de Genmod-262 dans l'univers UH-1. Contrairement aux pièges ordinaires, ils sont exceptionnellement rapides et imprévisibles, ce qui les rend extrêmement difficiles à frapper ou à contrôler. Ils se déplacent dans des motifs chaotiques, essaimant des cibles et explosant à la mort, causant des dommages supplémentaires aux ennemis voisins.

Malgré leur petite taille, leur agression et leur nombre font d'eux un danger grave. Même les combattants expérimentés luttent pour les contenir une fois qu'ils apparaissent.

CONSEILS:

- Les cibles statiques sont rapidement dépassées.
- Utilisez des armes de surface pour contrer les essaims.
- Éviter les quartiers proches; leur mort explosive peut être mortelle dans des espaces restreints.
- Cibler la source (Genmod-262) pour arrêter le frai.
