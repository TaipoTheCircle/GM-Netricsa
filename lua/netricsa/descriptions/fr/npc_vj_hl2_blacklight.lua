COMBINE PROTECTION CIVILE COP BLACKLIGHT


CLASSE:      Combiner Protection Civile Blacklight Cop
MÉTABOLISME: Humain sous contrôle Combiner
PERCEPTION: Unité spéciale de répression de la police
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Revolver, SMG, Manhacks
RÉCOMPENSE:     400 FC
MENACE:     Moyenne

DESCRIPTION:

Le Blacklight Cop Combine Civil Protection est un agent d'exécution urbain spécialisé conçu pour fonctionner dans des zones contaminées, chimiquement dangereuses et instables. Sa combinaison de protection complète souligne moins l'élitisme que la fonctionnalité et la survie dans des conditions où le policier moyen ne durerait pas longtemps.

Le casque couvre complètement le visage et est équipé d'une visière bleuâtre avec un système V-HUD. Des marquages tels que "V-HUD", "PREX INDUSTRIEL" et "ARAVO-08" peuvent être vus en surface, indiquant l'origine industrielle et la nature expérimentale de l'équipement. Un respirateur intégré filtre l'air, protégeant le porteur du gaz, des spores et du rayonnement de la lumière noire, d'où son nom.

L'armure de corps noire à garniture blanche porte le marquage « C17:i4o », qui relie directement le soldat à la ville 17 et aux forces de sécurité internes du Combine. La tenue est complétée par un pantalon noir, des bottes noires et des gants, et un étui est toujours présent sur la ceinture pour une réponse rapide.

Au combat, le Blacklight Cop agit durement, mais pas de manière militaire. Le revolver est utilisé pour les intimidations et les exécutions ciblées, le SMG est pour le contrôle de la foule, et les Manhacks sont déployés dans des espaces confinés, tournant les rues et les entrées dans des zones de mort chaotiques. Ces flics travaillent souvent en équipe, débarrassant les quartiers tranquillement... en combinant les normes.

CONSEILS:

- Ne le sous-estimez pas à cause de son statut de "cop" - Manhacks change rapidement la marée de la bataille.
- La visière protège contre la cécité, mais pas contre les coups directs.
- Dans les espaces confinés, la priorité est de le tuer avant le déploiement des Manhacks.
