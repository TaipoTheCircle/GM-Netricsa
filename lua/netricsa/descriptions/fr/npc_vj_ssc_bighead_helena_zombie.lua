ZOMBIE, HELENA HUNSKI


CLASSE:      Big-Head Zombie, Helena Hunski
MÉTABOLISME: Humanoïde, femelle
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     100 FC
MENACE:     Annoyance

DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme de Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan", ils gagnent le feu et les modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Helena Hunski est l'une de ces "cervelles" invisibles mais vitales dont le travail reste en coulisses, mais sans lesquelles le mécanisme entier connu sous le nom de Croteam ne fonctionnerait pas. Son crâne exagéré est le résultat d'un multitâche et d'une compréhension profonde du fonctionnement intérieur du studio. Alors que les programmeurs et les concepteurs ont créé le chaos à l'écran, Elena, en tant qu'assistante d'affaires et membre de l'équipe, a assuré l'ordre et l'organisation dans le monde réel.

Ses contributions à la série, reconnues dans les crédits de Serious Sam: The Second Encounter and Serious Sam II, sont un rappel que derrière chaque grand tireur n'est pas seulement un codeur brillant ou artiste, mais aussi des personnes coordonnant le travail, la résolution d'innombrables problèmes organisationnels, et le maintien de la cohésion d'équipe. En tant que parent probable d'un des fondateurs du studio, Davor Hunski, elle incarne l'esprit familial et le dévouement qui caractérisent Croteam depuis des décennies.

Elle était une fois vivante, mais après que quelqu'un l'ait tuée, elle est sortie des morts - devenant une Démonstration Zombie.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager le chemin.
- Sur la difficulté "Je suis Ugh-Zan", les éliminer à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.