SIRIAN WERABULL, WINTER


CLASSE:      Sirian Werebull, hiver
MÉTABOLISME: mammifère
PERCEPTION: animal de travail
TAILLE:       9 pieds
ENDURANCE:  faible
HOSTILITÉ:  moyenne
ARMES:    cornes
RÉCOMPENSE:     2000 FC
MENACE:     moyenne

DESCRIPTION:

Croisé avec des gènes mélangés de Sirians et une sorte de bétail. Le Werebull se comporte comme un taureau ordinaire et attaque avec ses cornes en chargeant.

CONSEILS:

- Éviter ses attaques de charge en s'écartant.
