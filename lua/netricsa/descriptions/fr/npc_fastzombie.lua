FAST HEADCRAB ZOMBIE


CLASSE:      Zombie de tête, rapide
MÉTABOLISME: Hôte parasitaire
PERCEPTION: Entité zombifiée
TAILLE:       6 pieds
ENDURANCE:  très rapide
HOSTILITÉ:  Extrême
ARMES:    Griffes, sauts, vitesse élevée
RÉCOMPENSE:     250 FC
MENACE:     Moyenne-élevée

DESCRIPTION:

Contrairement à leurs frères lents, les zombies rapides sont entraînés par l'énergie agitée. Une fois humain, leur corps a été déformé par le headcrab dans une forme squelettique qui se déplace avec une agilité terrifiante. Ils sprintent à quatre pattes et sautent sur les toits, criant comme des prédateurs à la chasse. Leur endurance est faible, mais leur vitesse et leur poursuite sans relâche en font l'un des ennemis les plus impitoyables à affronter.

CONSEILS:

- Ne les laissez pas fermer la distance.
- De courtes explosions de feu peuvent les arrêter en mi-charge.
