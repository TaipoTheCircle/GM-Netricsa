MESA BLACK, RAIN PAR LES CAFETERIA


Sam le garde ! Préparez-vous à une courte visite des « attractions gastronomiques » de Black Mesa. Maintenant, nous allons passer la cafétéria, où la pizza de Big Tony et le Taco de Tesla sont nichés contre un trou dans le rocher. L'endroit est populaire : Otis Lorey, par exemple, traîne souvent ici.

Keep your eyes peeled: il y a des "Monstres Généraux" et des "Acteurs Généraux" qui se cachent parmi les scientifiques et les gardiens. Ce qu'ils sont vraiment est inconnu. Où ils vivent aussi. Pourquoi se déguisent-ils - encore plus. Mais ils ne sont pas venus pour le café.

They copy the behavior of the staff: ils se tiennent à des machines à café, en feuilletant des papiers, prétendant être pressés par les affaires. Mais mon instinct me dit que ces "collegues" attendent dans les ailes. Peut-être qu'ils regardent. Ils prévoient peut-être une surprise. Ou peut-être que l'un d'eux te regarde déjà et décide d'appuyer sur le bouton d'alarme.

Jusqu'ici, tout est calme. La cafétéria est éclairée, les clients (réels ou non) parlent, et elle sent la pizza et les tacos. Mais rappelez-vous : à Black Mesa, même une pause déjeuner peut être la dernière.

Gardez votre main près de l'étui. Et ne regarde pas les signes - et si ce n'est pas de la nourriture, mais de l'appât?

Allez-y, "garde". Le prochain arrêt est inconnu.