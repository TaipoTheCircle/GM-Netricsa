DIEU KLEER DE LA PLANÈTE KLEER


CLASSE:      Dieu Kleer
MÉTABOLISME: Mort-vivant, Avatar de la guerre
PERCEPTION:  Divinité suprême des Kleer
TAILLE:      Gigantesque
ENDURANCE:   Extrême
HOSTILITÉ:   Absolue
ARMES:       Invocation de vagues de sbires (pas ceux de « Moi, moche et méchant »), boulets spectraux enchaînés, mur de boucliers, frappes au sol sismiques
RÉCOMPENSE:  1000000 FC (environ)
MENACE:      Absolue

DESCRIPTION:

Une ancienne divinité guerrière à quatre bras, autrefois vénérée par la civilisation Kleer aujourd'hui disparue. Lorsque Mental a ressuscité leurs dépouilles squelettiques pour les intégrer à sa Horde, il a involontairement réveillé leur redoutable Avatar. Cependant, le tyran n'a pas réussi à soumettre la créature ; le colosse s'est rebellé contre le contrôle de son maître et combat désormais tout le monde sans distinction, incarnant la rage pure et primitive de toute une race.

Visuellement, ce monstre est un squelette colossal vêtu d'une lourde armure sombre et coiffé d'une couronne à cornes, d'où s'échappe une sinistre énergie verte. Au combat, il utilise une magie spectrale, matérialisant des murs volants de porteurs de boucliers et attaquant à l'aide de chaînes. Lorsque le Dieu Kleer subit des dégâts critiques, il se dissout lâchement dans les ténèbres, obligeant Sam à repousser des hordes de serviteurs fantomatiques.

CONSEILS :

- Des symboles démoniaques brillent sur ses bras gigantesques ; concentrez vos tirs dessus pour infliger des dégâts critiques ou même arracher complètement ses membres.
- Lorsqu'il invoque un mur de boucliers spectral, n'essayez pas de tirer à travers ; sautez simplement par-dessus cette barrière semblable à une phalange.
- Lorsqu'il disparaît dans les ténèbres, profitez des Kleer fantomatiques qui apparaissent pour engager le combat au corps à corps et utiliser des exécutions au contact afin de restaurer entièrement votre santé.
