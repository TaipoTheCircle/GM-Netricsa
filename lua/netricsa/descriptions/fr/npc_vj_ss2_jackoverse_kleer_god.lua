LE DIEU CLÉ DU CLÉ


CLASSE:        Kleer Dieu
MÉTABOLISME:   Mort, Avatar de la guerre
PERCEPTION:   Déité suprême du Kleer
TAILLE:         Gigantique
ENDURANCE:    Extrême
HOSTILITÉ:    Absolu
ARMES:      Invoquer des vagues de mines (pas le genre "Moi dépraçable"), des chaînes spectrales, des murs de bouclier, des clams de terre
RÉCOMPENSE:       1000000 (env.) FC
MENACE:       Absolu

DESCRIPTION:

Une ancienne divinité de guerre à quatre armes autrefois adorée par la civilisation Kleer éteinte. Quand Mental a ressuscité leurs restes squelettiques pour sa Horde, il a par inadvertance réveillé leur formidable Avatar aussi. Cependant, le tyran ne pouvait pas subjuguer la créature ; le colosse se rebella contre le contrôle de son maître et combat maintenant absolument tout le monde, incarnant la pure et primitive rage d'une race entière.

Visuellement, ce monstre est un squelette colossal vêtu d'une lourde armure sombre et d'une couronne cornée, avec une énergie vert sinistre qui jaillit de sa poitrine. Au combat, il utilise la magie spectrale, matérialisant les murs volants des porteurs de boucliers et attaquant avec des chaînes. Quand le Dieu Kleer subit des dommages critiques, il se dissout lâchement dans les ténèbres, forçant Sam à se débarrasser des hordes de serviteurs fantômes.

CONSEILS:

- Les symboles démoniaques brillent sur ses bras géants; concentrez votre feu sur eux pour infliger des dommages critiques ou même déchirer les membres entièrement.
- Lorsqu'il appelle un mur de bouclier spectral, n'essayez pas de le traverser; sautez simplement sur cette barrière de type phalanx.
- Quand il disparaît dans l'obscurité, utilisez l'apparence fantôme Clears pour le combat et les finis de melee pour rétablir votre santé.
