ALPHA BULLSQUID DE XEN


CLASSE:      Taureau, Alpha
MÉTABOLISME: apex omnivore
PERCEPTION: Predator terrestre
TAILLE:       10-12 pieds
ENDURANCE:  très élevé
HOSTILITÉ:  extrême
ARMES:    griffes, crampons de queue, 9 rameaux de tente, crampons toxiques (plus forts)
RÉCOMPENSE:     750 FC
MENACE:     très élevé

DESCRIPTION:

L'Alpha Bullsquid est un cousin colossal et plus terrifiant du Bullsquid standard. Marqué par sa carapace jaune-noire, ses yeux rouges brillants et ses neuf puissants javelots de tentacules (comparativement aux six de ses parents inférieurs), ce prédateur domine son territoire. Ses vrilles blanches ronflent de façon menaçante devant elle, tandis que sa crache toxique accrue brûle avec une plus grande puissance, capable de fondre à travers l'armure et la chair. Plus grand et plus fort qu'un calmar normal, redouté même par d'autres espèces exotiques. La rencontre n'est pas seulement dangereuse, c'est généralement fatal.

CONSEILS:

- C'est plus précis et plus mort qu'un Bullsquid normal.
- Continuez à bouger; sa queue élargie a une portée étendue.
- Des explosifs lourds ou des armes de calibre élevé sont le seul moyen sûr de les faire tomber.
