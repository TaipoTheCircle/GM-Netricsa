MOLOTOV COCKTAIL


ARME: Cocktail Molotov (incendiaire improvisé)
MUNITIONS:   Solution inflammable
CADENCE DE TIR:    ~6 lancers/min (dépend de l'utilisateur)

DESCRIPTION:

Un dispositif incendiaire improvisé - une bouteille remplie de liquide inflammable et d'un fusible - utilisé pour enflammer des cibles, créer des zones de feu persistantes et empêcher le mouvement ennemi. À l'impact, la bouteille se brise, allume le carburant déversé et crée une zone de combustion qui cause des dommages au fil du temps et entrave le mouvement.

REMARQUES:

- Crée un patch de gravure avec des dommages-sur-temps et le potentiel de mettre à proximité des objets inflammables à la lumière.
- Bon pour adoucir ou canaliser les groupes, bloquer les points d'étranglement et détruire la couverture lumineuse; dangereux dans les espaces confinés en raison du risque d'auto-dommage.
- Une seule utilisation, approvisionnement limité; inefficace vs armure lourde et ennemis résistants au feu.