ENGEL DE L'ENSEIGNEMENT DU PAPIER FONDAMENTAL


CLASSE:      Engel
MÉTABOLISME: Organisme anthropomorphe du papier
PERCEPTION: Étudiant de l'école de papier
TAILLE:       5 pieds
ENDURANCE:  Moyenne (plus forte que les étudiants standard)
HOSTILITÉ:  Faible (seulement les attaques en défense)
ARMES:    Griffes pointues (4 doigts pointus), force physique
RÉCOMPENSE:     2
MENACE:     Moyenne

DESCRIPTION:

Étudiant de l'école de papier. Ami d'enfance et protecteur de Claire. Distingué par ses longs cheveux blancs, retors, ramenés dans une queue de cheval, avec deux plumes (bleu et orange rouge) sur la tête. Il porte l'uniforme classique de l'école : une chemise blanche à manches rayées, une salopette noire et des tibias rayés. Ses mains sont noires, avec quatre doigts tranchants, ressemblant à des griffes, et il a aussi une petite queue blanche. Il est gentil, attentionné et désintéressé par nature, prêt à se risquer pour les autres, comme en témoigne l'affrontement direct avec Mlle Circle pour sauver Claire. Il possède une force physique et une résilience accrues par rapport aux élèves normaux (il a résisté au coup de poing d'un enseignant).

Il a le lien le plus étroit avec Claire (amis de l'enfance). Il est aussi ami avec Bubble. Il a probablement respecté Oliver comme un enfant, mais ils sont maintenant ennemis en raison de leurs différentes visions du monde.

CONSEILS:

- Il est le plus capable des étudiants connus.
- Son principal moteur est de protéger Claire.