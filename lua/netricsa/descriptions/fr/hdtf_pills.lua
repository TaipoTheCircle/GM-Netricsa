PAIEMENTS


ITEM: Antidouleurs (comprimés consommables)
USE TIME: prestation intégrale

DESCRIPTION:

Lorsqu'ils sont pris, les analgésiques assurent une récupération rapide de la santé : une partie de la santé est rétablie instantanément. Il s'agit d'un traitement d'urgence sur le terrain lorsqu'une trousse médicale n'est pas disponible. Ils ne réparent pas les membres perdus ou les traumatismes internes graves - ils fonctionnent comme un soutien médical temporaire.

REMARQUES:

- Une guérison instantanée.
- Ne pas guérir l'intoxication / infection / radiation - médicaments spécialisés requis.