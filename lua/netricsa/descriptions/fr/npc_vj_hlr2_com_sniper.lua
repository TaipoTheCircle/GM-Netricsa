VENDU D'EXPLOITATION DE LA COMBINE


CLASSE:      Combiner le soldat sniper Overwatch
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Transhuman Infantry (spécialiste à longue distance)
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrême
ARMES:    Combiner le sniper Rifle MK2
RÉCOMPENSE:     500 FC
MENACE:     Haute-Extrême

DESCRIPTION:

Le Sniper Sniper Combine Overwatch est une unité transhumaine spécialisée conçue pour l'élimination et la suppression à longue distance. Contrairement à d'autres d'infanterie Combine, leur apparence est plus bâclée et tonifiée - leurs visières manquent de l'optique lumineuse emblématique pour éviter de donner leur position. Cela leur permet de se fondre dans des ruines, des toits ou des tours de garde en prison, ce qui les rend difficiles à détecter jusqu'à ce qu'il soit trop tard.

Ils sont maîtres de patience et de précision, tenant généralement des positions de veille pendant des heures tout en traquant les mouvements ennemis. Leurs fusils de sniper peuvent éliminer les cibles avec un seul tir, semer la panique dans les équipes et forcer les survivants à se couvrir.

Sniper Soldats sont souvent déployés pour protéger les actifs clés Combinez, gardez les extérieurs de la prison comme Nova Prospekt, et créer des zones de mort dans les rues de la ville. Silencieux, mortel et presque invisible jusqu'à ce qu'ils tirent.

CONSEILS:

- Évitez de rester à l'abri - toujours se déplacer entre la couverture.
- Des grenades à fumée ou des explosifs peuvent les chasser.
