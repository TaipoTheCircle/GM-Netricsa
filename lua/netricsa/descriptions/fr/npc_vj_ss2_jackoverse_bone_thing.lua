DESCRIPTION:

C'est une des formes de vie les plus mystérieuses et les plus dangereuses de la planète Kleer. Malgré de nombreux témoignages oculaires, l'origine de la créature reste inconnue. Il n'appartient à aucune sous-espèce connue de l'armée de Mental et ne ressemble à aucun représentant de la faune locale.

Lors de la première rencontre, la Chose est facilement confondue avec une statue inhabituelle assemblée à partir des os de diverses créatures Kleer. Il est complètement immobile et peut rester indéfiniment. Cependant, si l'observateur se détourne ou perd la vue de la créature, même pendant un moment, elle change de position ou apparaît nettement plus proche.

Après plusieurs de ces mouvements, le comportement de la créature change considérablement. Il émet un cri assourdissant et perçant et commence à poursuivre sa cible à pleine vitesse. La vitesse de la Thing est si élevée qu'il n'y a pas de cas connus d'évasion réussie.

Le contact physique avec la créature entraîne invariablement la mort immédiate de la victime.

Les tentatives pour détruire la chose ont échoué. Les armes à feu, les explosifs, les armes à énergie et les systèmes de combat lourds n'ont eu aucun effet notable sur ces armes. Selon les données disponibles, la créature est indestructible par des moyens connus.

Son aspect combine les caractéristiques du squelette de Kleer et du serpent à os de Kleer. Cela a conduit les chercheurs à supposer que la Thing peut être une forme évolutive inconnue de ces espèces ou de leur descendant commun. Cependant, aucune preuve n'a été trouvée à l'appui de cette théorie.

Les résidents de Kleer évitent les zones où la chose osseuse a été repérée. Même les chasseurs et les anciens combattants les plus expérimentés préfèrent ne pas s'engager avec eux, et les rapports de son apparition entraînent l'évacuation immédiate des colonies voisines.

CONSEILS:

- Si vous pensez que c'est juste une statue, ne sautez pas aux conclusions.
- Tant que la créature reste en vue, elle reste inactive.
- Ne perds pas de vue.
- Si elle commence à se déplacer et à vous poursuivre, la seule ligne de conduite raisonnable est de quitter la zone immédiatement. Il n'existe actuellement aucune façon connue de détruire la chose osseuse.
