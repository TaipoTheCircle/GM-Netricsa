PROTECTEUR STRAGG STREAM DE STRAGGOS


CLASSE:      Protecteur de flux strogg
MÉTABOLISME: Guerrier bio / biomécanique
PERCEPTION: Unité de combat Elite Strogg
TAILLE:       8,2 pi
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    Cannon plasma Spike, Missiles d'hommage
RÉCOMPENSE:     2000 FC
MENACE:     Très élevé

DESCRIPTION:

Le Défecteur de Stream est un gardien d'élite de Strogg créé pour protéger l'énergie et les installations stratégiques clés sur la planète Stroggos. Ces créatures agissent en tant que défenseurs du Flow et du Nexus, chargés de prévenir la destruction de complexes d'infrastructures complexes en envahissant les forces humaines.

Au combat, le Défectueux du Stream combine une combinaison réussie d'incendies à longue portée et à proximité. Il est armé d'un puissant canon à plasma, capable de délivrer des tirs sporadiques, et des missiles hooming qui poursuivent l'ennemi au moindre mouvement.

CONSEILS:

- Utilisez des armes lourdes pour détruire efficacement les missiles.
- La manipulation et la couverture sont critiques : une attaque directe et positionnelle est rarement réussie.
- Leurs missiles peuvent être détruits en vol si vous agissez rapidement et avec précision.