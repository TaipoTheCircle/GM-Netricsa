CHEMIN D'HORAIRE DE XEN


CLASSE:      Houndeye, Dreamcast
MÉTABOLISME: xénofaune à la chasse aux paquets
PERCEPTION: Oiseau commun adulte
TAILLE:       ~3 pieds de haut, 4 pieds de long
ENDURANCE:  moyenne
HOSTILITÉ:  haute en boîtes
ARMES:    ondes de choc sonores, vitesse, coordination des paquets
RÉCOMPENSE:     400 FC
MENACE:     modéré individuellement, élevé en groupes

DESCRIPTION:

L'Alpha Houndeye est un petit prédateur Xen ressemblant à un croisement entre un chien et un porc-épic surexcité. Il chasse en meute, en se fiant aux impulsions sonores pour désorienter les proies avant de se refermer pour l'attaque. Malgré son apparence apparemment odieux et ses bourrasques hautes, une meute de Houndeyes peut submerger même des intrus bien armés.

Ces créatures sont très sociales et communiquent via des shrieks ultrasoniques qui peuvent briser les tympans à portée de main. Les scientifiques spéculent sur leurs attaques sonores explosives sont une adaptation évolutive pour compenser leurs griffes et dents faibles.

CONSEILS:

- Engager les yeux rouges à distance pour éviter leurs ondes de choc.
- Tirer peut provoquer tout le paquet - attention.
- Exploiter leur mentalité de pack : les attirer en risques environnementaux peut transformer leur coordination contre eux.