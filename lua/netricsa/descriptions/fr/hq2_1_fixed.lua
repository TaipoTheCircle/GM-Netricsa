HALF-QUAKE 2, BIENVENUE À LA SHOW


Sam ! Réveille-toi, héros ! Vous venez de voir trois clowns transparents qui ne comprenaient même pas pourquoi ils étaient transparents. Ils t'appellent un "moteur idiot", je dois m'en souvenir, c'est drôle. Et oui, ils ne s'attendaient pas à ce que tu survives au premier tour.

Bienvenue dans "Half-Quake 2". Sérieusement ? Les sadistes ne pouvaient même pas trouver un nom décent pour la deuxième saison ? C'est leur problème. Le principal, c'est qu'on est là, et qu'on est prêts à leur montrer comment faire un spectacle !

Les sadistes ont rouvert leurs portes, et maintenant vous êtes sur leur route préférée. Tu te souviens de ce sentiment quand tu étais coincé entre les dimensions ? Moi aussi.

Cet endroit est le salon d'un nouveau candidat. Ou une antichambre à l'enfer, je n'ai pas encore décidé. Mais je sais une chose : si vous avez un costume HEV, une scie et mon soutien, nous vous sortirons d'ici. Il ne reste qu'à trouver un moyen de sortir de ce cirque.

Oh, et ne faites pas attention à ces gars "transparents", ils pensent qu'ils sont des hôtes cool. Mais nous savons qui est le véritable gagnant !

Ne reste pas planté là, Sam. Il y a un nouveau tour devant, et je veux vous voir déchirer leur script à nouveau!