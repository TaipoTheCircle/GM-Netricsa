HALF-QUAKE 2, BIENVENUE AU SPECTACLE


Sam... Sam ! Réveille-toi, héros ! Vous venez de voir trois clowns transparents qui ne comprenaient même pas pourquoi ils étaient transparents. Ils vous traitent de "moteur stupide" - il faudra que je m'en souvienne, c'est drôle. Et oui, ils ne s’attendaient clairement pas à ce que vous surviviez au premier tour.

Bienvenue dans "Half-Quake 2". Sérieusement? Les Sadiques n'ont même pas pris la peine de trouver un nom décent pour la deuxième saison ? D'accord, c'est leur problème. L'essentiel, c'est qu'on est là, et qu'on est prêts à leur montrer comment faire le show !

Les Sadiques ont rouvert leurs portes et vous voilà désormais à bord de leur manège préféré. Vous souvenez-vous de ce sentiment lorsque vous étiez coincé entre les dimensions ? Moi aussi.

Cet endroit est le salon d'un nouveau candidat. Ou une antichambre de l'enfer, je n'ai pas encore décidé. Mais je suis sûr d'une chose : si vous avez une combinaison HEV, une scie et mon soutien, nous vous sortirons d'ici. Il ne reste plus qu'à trouver une issue à ce cirque.

Oh, et ne faites pas attention à ces gars « transparents », ils pensent qu'ils sont des hôtes sympas. Mais nous savons qui est le vrai gagnant ici !

Ne reste pas là, Sam. Il y a un nouveau tour à venir, et je veux vous voir déchirer à nouveau leur script !