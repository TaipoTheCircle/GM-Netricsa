SOLDAT-OFFICIER MENDEL-GRUMAN


CLASSE : Soldat-officier Mendel-Gruman
MÉTABOLISME : humain, masculin
PERCEPTION : infanterie standard
TAILLE : 5,9 pieds
ENDURANCE : Moyenne
HOSTILITÉ : Élevée
ARMES : Pistolet ORO HOG 9 mm, Grenades à fragmentation
RÉCOMPENSE : 200 FC
MENACE : Faible

DESCRIPTIF :

L'officier est le soldat principal et le plus commun de la société Mendel-Gruman. Ces soldats constituent l’épine dorsale de ses forces armées et sont présents tout au long de l’opération planétaire. Contrairement aux unités lourdes, l'officier ne possède pas d'armes spécialisées ni d'armures complexes. Sa tâche est bien plus prosaïque : se déplacer avec le groupe et tirer sur tout ce qui ne porte pas l'emblème Mendel-Gruman. La tenue de l'officier se compose d'une armure relativement légère mais pratique avec de nombreuses pochettes et une ceinture tactique entièrement équipée. Presque toutes les zones vitales du corps sont protégées, mais les articulations restent plus mobiles. L'uniforme standard est majoritairement bleu foncé.

Le visage est recouvert d'un casque de protection à visière dynamique. Sa couleur change en fonction de l'état du soldat : ​​le bleu signifie un fonctionnement normal, le jaune indique une vigilance accrue et le rouge indique une préparation au combat maximale. C’est un indicateur plutôt pratique : le soldat affiche littéralement sur son visage à quel point il n’aime pas la situation actuelle.

L'arme principale de l'officier est le pistolet ORO HOG 9 mm. De plus, le soldat standard porte des grenades à fragmentation. Dans certaines circonstances, les officiers peuvent utiliser d'autres armes, même si celles-ci ne font pas partie de leur armement standard.

La principale force de l'officier ne réside pas dans sa capacité de survie individuelle. À eux seuls, ils sont relativement faibles et périssent rapidement sous un feu concentré. Mais Mendel-Gruman compense cela par des chiffres et des actions de groupe. Les officiers opèrent généralement en petites escouades de deux ou trois, essayant d'utiliser simultanément la couverture et le feu.

Ils sont capables de se déplacer sur le champ de bataille, de changer de position et d'attaquer depuis différentes directions. Par conséquent, un seul officier constitue une menace modérée, tandis que plusieurs soldats peuvent former une ligne de tir dense. Cela devient particulièrement dangereux lorsqu’un groupe régulier est soutenu par des alliés plus forts.

CONSEILS :

- Ne les sous-estimez pas à cause de leur faible armure. La principale menace de l'officier réside dans leur nombre.
- Les grenades sont particulièrement efficaces contre les groupes. Plusieurs officiers se tiennent souvent assez près les uns des autres.
- Utilisez une couverture si plusieurs soldats travaillent simultanément contre vous.
- Si vous voyez une visière rouge, le soldat est déjà prêt au combat.
- Surveillez votre environnement : certains combattants peuvent être armés d'armes inhabituelles pour un Officier.