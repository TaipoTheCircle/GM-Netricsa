MENDEL-GRUMAN VENDU-OFFICIER


CLASSE:      Mendel-Gruman Soldat-Officier
MÉTABOLISME: Humain, Homme
PERCEPTION: Infanterie Standard
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Pistolet ORO HOG 9mm, Frag Grenades
RÉCOMPENSE:     200 FC
MENACE:     Faible

DESCRIPTION:

L'officier est le soldat principal et le plus courant de la société Mendel-Gruman. Ces soldats forment l'épine dorsale de ses forces armées et sont rencontrés pendant presque toute l'opération planétaire. Contrairement aux unités lourdes, l'officier ne possède aucune arme spécialisée ou armure complexe. Sa tâche est beaucoup plus prosaïque : se déplacer avec le groupe et tirer sur tout ce qui ne porte pas l'emblème Mendel-Gruman. La tenue de l'officier consiste en une armure relativement légère mais pratique avec de nombreuses pochettes et une ceinture tactique entièrement équipée. Presque toutes les zones vitales du corps sont protégées, mais les articulations sont laissées plus mobiles. L'uniforme standard est principalement bleu foncé.

Le visage est recouvert d'un casque de protection avec une visière dynamique. Sa couleur change selon l'état du soldat : le bleu signifie une opération normale, le jaune indique une vigilance accrue et le rouge indique une disponibilité maximale au combat. Cela fait un indicateur assez pratique : le soldat montre littéralement sur son visage combien il déteste la situation actuelle.

L'arme principale de l'officier est le pistolet ORO HOG 9mm. De plus, le soldat standard porte des grenades à fragmentation. Dans certaines circonstances, certains officiers peuvent utiliser d'autres armes, même s'il ne s'agit pas de leur armement standard.

La principale force de l'officier n'est pas la survie individuelle. De leur propre chef, ils sont relativement faibles et périssent rapidement sous un feu concentré. Cependant, Mendel-Gruman compense cela avec des nombres et des actions de groupe. Les officiers opèrent généralement dans de petites escouades de deux ou trois, essayant de se couvrir et de tirer simultanément.

Ils sont capables de se déplacer autour du champ de bataille, de changer de position et d'attaquer de différentes directions. Par conséquent, un seul officier constitue une menace modérée, tandis que plusieurs soldats peuvent former une ligne de tir dense. Cela devient particulièrement dangereux lorsqu'un groupe régulier est soutenu par des alliés plus forts.

CONSEILS:

- Ne les sous-estimez pas à cause de leur faible armure. La principale menace de l'officier réside dans leur nombre.
- Les grenades sont particulièrement efficaces contre les groupes. Plusieurs officiers se tiennent souvent très proches.
- Couvrez si plusieurs soldats travaillent contre vous simultanément.
- Si vous voyez une visière rouge, le soldat est déjà prêt au combat.
- Surveillez vos environs : certains combattants peuvent être armés d'armes inhabituelles pour un officier.
