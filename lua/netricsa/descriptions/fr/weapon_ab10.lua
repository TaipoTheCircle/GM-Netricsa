AB-10 PISTOLE AUTOCHTONE


ARME:      AB-10
AMMUNITION:  cartouches 9x19
CADENCE DE TIR:         ~20 tours/min

DESCRIPTION:

Un pistolet semi-automatique fabriqué aux États-Unis, une modification du pistolet Intratec TEC-9. Libéré en 1995.

REMARQUES:

- Comme le TEC9, le pistolet était populaire auprès des gangsters, mais n'a pas atteint la même popularité dans la culture pop.






