LE RÉACTEUR NOIR MESA CORE, LES PORTAUX


La salle des réacteurs n'est plus un moteur, c'est une faille. Les portails fleurissent comme des tumeurs malignes, des arcs crépitants d'énergie. Les scientifiques que vous devez joindre sont juste au-delà, mais les chemins directs sont partis; seuls les portails instables relient ce secteur au leur.

Et voici le problème: entrez dans le mauvais, et vous serez craqué dans un évent de rayonnement, un puits d'effondrement, ou pire - rien du tout. L'analyse télémétrique indique une combinaison sûre : 2 → 1 → 7. Suivez cette séquence et vous allez filer le labyrinthe propre.

Points of interest:

L'instabilité du portail. Attendez trop longtemps et vous perdrez votre chance - ou pire, atterrissez quelque part au hasard.

L'Observateur. Près de l'un des portails actifs est l'homme en costume d'affaires. Toujours silencieux, toujours à regarder. Il n'interfère pas, ne réagit pas aux menaces, mais sa présence proche n'est pas un accident. C'est soit un avertissement, soit une confirmation.