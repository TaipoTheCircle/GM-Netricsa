CLAWDOVIC


ARME: Clawdovic
MUNITIONS:   Lui-même 
CADENCE DE TIR:    ~60 Clawdovics/minute 

DESCRIPTION:


Le Clawdovic est un perroquet psychotique kamikaze armé d'une bombe. Malgré son aspect un peu maladroit, cet oiseau est capable d'abattre même les rhinocéros. En vol, il scrute quelque chose d'intelligible (Kurly...), mais il semble être lisible...

C'est une arme biologique d'oiseau de la planète M'Digbo, utilisée par les Simbas. Il a été modifié en utilisant une fleur toxique pour transformer son estomac en une bombe qui explose à l'impact. Lorsqu'il est lancé, Clawdovic agit comme un projectile homogéné : il vole vers l'ennemi que l'utilisateur regarde.

REMARQUES:

- L'homogénéité est imparfaite : sur des distances moyennes à longues, un mouvement soudain de la cible peut faire manquer ou voler Clawdovic.
- L'utiliser à proximité peut entraîner l'automutilation de l'explosion.
- Des ennemis très efficaces contre des ennemis de type patron et de grandes cibles aéroportées comme les Cyclopes Albino ou les hélicoptères d'attaque.
- L'approvisionnement en munitions est limité.