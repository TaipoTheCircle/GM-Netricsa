LA RESISTANCE


La Résistance est un réseau lâche de rebelles, d'humains et de Vortigaunts, unis par un objectif commun : libérer la Terre de la tyrannie du Combiné et réclamer leur droit à la liberté et à la santé mentale. Ils ne constituent pas une armée unifiée, mais des centaines de petites poches opérant dans l'ombre.

The Resistance is led by figures whose names evoke both hope and outrage: Eli Vance, Alyx Vance, Barney Calhoun, et d'autres leaders chevronnés qualifiés pour exploiter le pouvoir de la science.

Their actions are divided: certains scientifiques travaillent sur des technologies qui pourraient briser la tyrannie du Combine, tandis que d'autres forment des unités armées prêtes à combattre directement, indépendamment des pertes.