BABY DE L'ESPRIT DU MINECRAFT


CLASSE:      Bébé d'araignée
MÉTABOLISME: Arthropodes, Arachnid
PERCEPTION: Bande neutre
TAILLE:       1,5 pi
ENDURANCE:  Faible
HOSTILITÉ:  Moyenne
ARMES:    Bite, vitesse, coordination avec les frères et sœurs
RÉCOMPENSE:     50 FC
MENACE:     Moyenne

DESCRIPTION:

Cette petite créature, mais extrêmement ennuyeuse, suit sa mère où qu'elle aille. Avec la mère araignée et d'autres frères et sœurs, ils forment une armée mobile d'araignées, prête à détruire quiconque s'approche de leur matriarche.

Tant que leur mère est en vie, les bébés se comportent comme des soldats disciplinés. Ils la suivent sans aucun doute et attaquent toute cible qu'elle choisit. Ses jeunes attaquent en groupes et entourent leurs proies, en utilisant leur vitesse et leur petite taille pour les confondre.

Mais le vrai plaisir commence quand la mère araignée meurt. Les jeunes, privés de leur chef, tombent dans le désespoir. Ils commencent à "crier", abandonnent instantanément leur attaque actuelle, et perdent tout intérêt pour elle. Des tueurs impitoyables, ils deviennent des orphelins effrayés. Dans cet état, ils sont agressifs seulement en réponse à l'agression - s'ils sont frappés, ils se défendront, mais ne attaqueront pas.

Les jeunes ne errent pas seuls, mais n'apparaissent que lorsqu'ils sont accompagnés de leur mère. De plus, un jeune est toujours assis sur le dos de la mère, la rendant encore plus dangereuse et protégeant les jeunes des premiers coups.

CONSEILS:

- Si vous ne voulez pas combattre un groupe de petites créatures, essayez de ne pas attaquer les jeunes jusqu'à ce que vous tuiez la mère. Ils pourraient crier et appeler à l'aide des autres.
- Une fois que tu auras tué la mère, tu n'auras pas à finir les éclosions. Ils cesseront d'être hostiles jusqu'à ce que tu les touches. C'est un excellent moyen de conserver les ressources.
- N'oubliez pas que si vous décidez de les finir, ils se défendront farouchement.
- En raison de leur petite taille et de leur vitesse élevée, ils sont difficiles à frapper à bout portant. Utilisez des armes avec une large zone d'effet ou d'attaque d'en haut.
- Lorsque vous luttez contre une famille d'araignées, essayez de détruire d'abord les éclosions (surtout celles sur le dos) pour priver la mère de son soutien.
