COMBINE ELITE DROPSHIP


CLASSE Combiner Elite Dropship
MÉTABOLISME Entièrement synthétique
PERCEPTION Dropship à grande vitesse des unités d'élite et standard
TAILLE ~55-65 ft (avec conteneur)
ENDURANCE extrême
HÔTILITÉ Critical
ARMES Aucune
REMARQUE 6000 FC
MEILLEURE Très élevée

DESCRIPTION

Le Combine Elite Dropship est un transporteur de troupes synthétique avancé conçu pour le Dropship rapide des unités d'élite Combine, y compris les soldats d'élite et les équipes de frappe standard. Contrairement aux Dropships standard, ce modèle est optimisé pour une vitesse maximale et un profil de combat minimal.

La coque du Synthétique est peinte en noir et blanc avec des panneaux composites renforcés, la distinguant visuellement des Dropships standards. Le conteneur est conçu pour transporter 3-5 soldats à la fois. Après le déploiement, le conteneur reste ouvert même lorsque le Dropship se retire, accélérant le cycle de déploiement et réduisant le temps passé dans la zone de destruction.

Il n'y a pas de modules d'armes, car le concept de la plate-forme est basé sur le principe d'entrée rapide, de déchargement et de sortie. L'Elite Dropship est pratiquement invulnérable aux armes standard et vulnérable uniquement aux missiles RPG V2, où deux frappes suffisent à détruire ou à désactiver de manière critique.

TIPS

- Utiliser le RPG V2; les autres armes sont inefficaces.
- Deux coups précis suffisent pour faire tomber le Dropship.
- Attaque pendant la descente et le débarquement, lorsque la trajectoire est prévisible.
- Le conteneur ne se ferme pas pendant le retrait, ce qui le rend vulnérable au feu sur le compartiment intérieur.
- La destruction d'un vaisseau d'élite Dropship pourrait perturber le déploiement de troupes d'élite et changer le cours de la bataille.
