LAMBDA ANTLION DE XEN


CLASSE:      Lambda Antlion
MÉTABOLISME: Insectoïde
PERCEPTION: Creature d'Alien semblable à des insectes
TAILLE:       4-5 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Griffes, ailes (petites rafales), tactiques d'essaim
RÉCOMPENSE:     250 FC
MENACE:     Moyenne

DESCRIPTION:

Lambda Antlions sont des prédateurs insectoïdes de Xen, attirés vers la Terre avant l'incursion du Combine. Ils errent dans des zones sablonneuses en essaims, éclatant du sous-sol pour embusquer des proies. Agiles et inlassables, ils ont envahi par de simples nombres plutôt que par la force individuelle. Malgré leur agression, ils peuvent être pacifiés ou même commandés par l'utilisation de phéropodes spéciaux récoltés à partir de cadavres d'Antlion Guards. Leur bourdonnement comme un insecte annonce une attaque entrante, souvent quelques instants avant que le sable éclate sous vos pieds.

CONSEILS:

- Évitez de marcher sur le sable; les vibrations les attirent instantanément.
- Utilisez des phéropodes pour transformer des essaims en alliés.
