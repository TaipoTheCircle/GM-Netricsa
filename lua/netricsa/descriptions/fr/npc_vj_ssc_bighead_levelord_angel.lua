MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:    Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     100 FC
MENACE:     Annoyance

DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme de Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont totalement inoffensifs, mais sur le niveau de difficulté "I Am Ugh-Zan" ils gagnent feu et des modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Richard Bailey "Levelord" Gray est un vrai patriarche de la conception de niveau de jeu, dont le crâne surdimensionné contient des décennies d'expérience, du sarcasme, et un incroyable sens du plaisir. Ce vétéran de la guerre froide, ancien ingénieur aérospatial et ancien ancien sous-marin soviétique a trouvé sa véritable vocation dans la création d'espaces virtuels. C'est lui, avec Allen Bloom, qui a créé les meilleurs niveaux de l'emblématique Duke Nukem 3D, gravé à jamais dans l'histoire l'expression "Vous n'êtes pas censé être ici."

While Levelord himself modestly denies direct involvement in the development of Serious Sam: La première rencontre, son esprit et ses principes sont invisibles dans le jeu. Croteam, comme tout le monde du jeu, a été fortement influencé par son travail. Sa philosophie-qu'un jeu devrait être amusant d'abord et avant tout, et qu'un niveau devrait être thématiquement cohérent et équilibré comme un bon restaurant-est devenu le lynchpin pour des générations de concepteurs, y compris l'équipe croate. Sa vie ultérieure en Russie et son travail sur le 20ème anniversaire du duc Nukem ne font qu'ajouter à son aura comme le « cerveau » le plus coloré et le plus durable de cette galerie.

Il était vivant, mais après que vous l'ayez tué dans le Temple de Hatshepsut, il a été ressuscité, devenant un ange.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager le chemin.
- Sur la difficulté "Je suis Ugh-Zan", les détruire à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.