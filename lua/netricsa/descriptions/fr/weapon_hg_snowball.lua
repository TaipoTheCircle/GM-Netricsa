NOWBALL


ARME:      NOWBALL
CADENCE DE TIR:         ~1 lancer/sec.

DESCRIPTION:

Des lumps de neige qui ont été moulées à la main. Des boules de neige peuvent être lancées n'importe où. Ils disent que si vous ajoutez une pierre ou une neige jaune à l'intérieur, vous pouvez rendre la boule de neige plus dangereuse.

REMARQUES:

- Objet inutile, ne peut être utilisé que pour peindre les joueurs et les murs.
- Mais si un joueur est en mode ragdoll, vous pouvez se casser le cou avec une boule de neige (apparemment, cela peut avoir été corrigé).