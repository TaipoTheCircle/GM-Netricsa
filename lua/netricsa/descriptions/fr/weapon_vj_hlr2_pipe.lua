PIE METAL


ARME:      Tube métallique
CADENCE DE TIR:         ~60 balançoires/min

DESCRIPTION:

Arme improvisée utilisée par les 17 réfugiés et les civils de la ville. Simple mais robuste, le tuyau métallique cause des dommages de force émoussables à portée étroite. Principalement une arme de dernier ressort pour l'autodéfense contre les forces ou les têtes de corps.

REMARQUES:

- Utilisation illimitée; pas de munitions nécessaires.
- Efficace dans les quartiers proches seulement.
- Dédommage légèrement les ennemis faibles.
- Fonctions comme outil pratique dans les situations de survie.