KATE, L'ÉTALKER


CLASSE:      Kate, le Stalker
MÉTABOLISME: Humain, femme
PERCEPTION: Pré obsédé
TAILLE:       5,3 pi
ENDURANCE:  Haut
HOSTILITÉ:  Absolu
ARMES:    Force physique, vitesse, instincts animaux
RÉCOMPENSE:     300
MENACE:     Haut

DESCRIPTION:

Elle était autrefois une fille ordinaire, explorant les bois derrière sa maison avec son amie Lauren et son amie d'enfance Carl. Mais une rencontre a tout changé.

Comme enfants, Kate et Carl ont rencontré Slenderman dans les bois. Carl a réprimé l'horreur, mais Kate, apparemment, s'est toujours souvenue.

Des années plus tard, ils retournèrent dans les bois pour confirmer ou nier leurs craintes d'enfance. Carl a subi de graves hallucinations, et Kate a disparu. Elle a été retrouvée inconsciente dans les bois, avec une caméra cassée et une pile de dessins étranges. Deux semaines à l'hôpital, puis un retour à la maison qui n'était pas un retour à la vie normale.

Puis vint la mort de sa mère. Elle a essayé de vendre la maison et de partir.

Karl prévoyait de se suicider et de faire des cauchemars avec lui. Kate ne pouvait pas. Elle s'est enfuie, laissant son amie mourir seule.

Après une autre attaque de Slenderman, Kate est devenue la Stalker. Elle vit dans l'ancienne mine Kullman, où elle chasse tous ceux qui s'y aventurent.

Une partie de Kate vit encore quelque part à l'intérieur et essaie d'aider ceux qui suivent ses traces.

CONSEILS:

- Elle est plus rapide que toi.
- La lampe de poche l'aveugle momentanément. Utilisez-le pour fuir.
- L'écriture sur les murs ne ment pas. Lisez et faites ce qu'on vous dit.
