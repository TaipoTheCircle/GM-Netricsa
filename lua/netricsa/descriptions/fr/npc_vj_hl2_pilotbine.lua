PILOTE DE SURVEILLANCE DE LA COMBINE


CLASSE:      Combiner le pilote Overwatch
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner l'unité d'air
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    OICW, SMG
RÉCOMPENSE:     850 FC
MENACE:     Moyenne

DESCRIPTION:

Le pilote Combine Overwatch est un combattant spécialisé chargé de contrôler les avions Combine Contrairement aux soldats standard, leur valeur première n'est pas dans les tirs de précision, mais dans le contrôle de l'espace aérien et le déploiement rapide des forces.

Ils portent un casque pilote avec un respirateur intégré et des lunettes bleues intégrées, directement liées aux systèmes de navigation Combine. Les lunettes affichent l'altitude, la vitesse, les cibles et les zones de défense aérienne, permettant au pilote de fonctionner même dans les tempêtes de neige, les brouillages radio et l'obscurité complète.

Bien que les pilotes ne soient pas conçus pour le combat en première ligne, le Combine les équipe d'armes polyvalentes. L'OICW permet de tirer à la fois sur l'infanterie et sur les cibles derrière la couverture, tandis que le SMG est utilisé en cas d'atterrissage d'urgence ou tout en défendant la zone d'atterrissage. Les augmentations améliorent la sensibilisation spatiale et la résistance à la force G, transformant le pilote en une force dont il faut tenir compte dans la force aérienne du Combine.

CONSEILS:

- Pas de complications.
- Le casque du pilote le distingue du reste.