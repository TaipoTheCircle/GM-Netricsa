GOST DU MONDE DU FATUM


CLASSE:      Le fantôme mondial de Fatum
MÉTABOLISME: Soutenu par l'énergie de Fatum
PERCEPTION: Créature éthérée, gardienne des cimetières de Fatum
TAILLE:       8,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Projectiles de lava, griffes de melee
RÉCOMPENSE:     300 FC
MENACE:     Moyenne

DESCRIPTION:

Les fantômes du monde de la Fatum sont des créatures vertes et translucides vêtues de longues robes qui rappellent les robes des grands sorciers. Leur patrie est les cimetières des nécropoles distordues de Fatum où la ligne entre la vie et la mort a depuis longtemps perdu son sens. Là, ils servaient de tuteurs.

Ces créatures servent sans condition Fatum. Et comme Doom agit dans l'intérêt de Mental, les wraiths sont formellement considérés comme faisant partie de sa Horde, bien qu'ils ne manifestent ni individualité ni hésitation.

Au combat, les wraiths utilisent des boulons d'énergie fondus qui ressemblent à de la lave. Ils lancent ces projectiles à portée moyenne et attaquent avec leurs griffes à portée étroite. Malgré leur nature éphémère, leurs frappes infligent de réels dommages physiques et énergétiques.

CONSEILS:

- Ne pas s'attarder dans les zones ouvertes: les projectiles de lave sont efficaces dans une trajectoire droite.
- Évitez les combats rapprochés : leurs griffes sont dangereuses même par l'armure.
