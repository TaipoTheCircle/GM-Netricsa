PIGÉON


CLASSE:      Pigeon
MÉTABOLISME: Oiseaux
PERCEPTION: Oiseau aviaire urbain
TAILLE:       ~1,5 ft
ENDURANCE:  Faible
HOSTILITÉ:  Faible
ARMES:    Bec, griffes
RÉCOMPENSE:     2 FC
MENACE:     Très faible

DESCRIPTION:

Les pigeons sont communs dans les zones urbaines, coexistant avec les humains et d'autres espèces sauvages. Ils sont passifs, souvent vus dans les troupeaux sur les toits, les rues et les places. Bien qu'inoffensifs, ils peuvent réagir à des perturbations soudaines, s'envoler et créer des signaux visuels.

CONSEILS:

- Nourriture.
