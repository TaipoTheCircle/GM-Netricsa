KUNG FU ZOMBIE, MAÎTRE DU FANG CHI


CLASSE:      Kung Fu Zombie, Maître
MÉTABOLISME: Morts
PERCEPTION: Zombie Artiste Martial
TAILLE:       12 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Haut
ARMES:    Invocation de l'Esprit
RÉCOMPENSE:     150 FC
MENACE:     Haut

DESCRIPTION:

Alors que la plupart des minions de Mental reçoivent une formation minimale, Kung Fu Zombies a reçu une formation approfondie en regardant des films d'action des années 80 et 90.

Certains de ces zombies ont maîtrisé l'art du kung fu et ont appris les voies de la magie. On peut voir des maîtres planer dans l'air, appelant les esprits dragons à détruire leurs ennemis. Ces esprits poursuivront l'ennemi de leur maître et exploseront, libérant l'énergie magique au contact.

Les Maîtres étaient à l'origine des acteurs de la planète Chi-Fang. Avec l'arrivée de Mental, les Maîtres se sont révélés être des combattants fiables, mais Mental a décidé d'augmenter leur pouvoir. Les Maîtres ont été transformés en adversaires volants mortels: leurs jambes ont été coupées (qui ont ensuite été données aux Soldats Bull) et on leur a donné la capacité de lancer des sorts magiques de dragon mortels (levitation, créant un faisceau de force d'énergie).

Malheureusement, ces changements ont donné aux Maîtres une étrange envie de chanter constamment. Ils chantaient mal. En fait, ils étaient dégoûtants. En raison de ce défaut, Mental a dû attacher des masques d'acier à leur visage pour que personne ne puisse entendre leur chant et cela n'endommagerait pas son audition.

CONSEILS:

- S'ils s'approchent assez, enfoncez-les dans le mur avec un fusil à double barre.
- Ils vont essayer de garder leur distance pour qu'ils puissent appeler les esprits à attaquer.
- Les esprits vont vous poursuivre, alors continuez à bouger si vous voulez les éviter.
