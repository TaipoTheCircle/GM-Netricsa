L'ESPRIT ANTARESIEN DU JUVENILE DE LA PRIME ANTARES


CLASSE:      Araignée juvénile d'antarésie
MÉTABOLISME: Alien, arachnid
PERCEPTION: Créature d'arachnie
TAILLE:       6,5 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Crache acide améliorée, forte morsure
RÉCOMPENSE:     1000 FC
MENACE:     Moyenne

DESCRIPTION:

Le stade juvénile de l'araignée antarésienne est plus grand, plus fort et plus dangereux que ses parents éclos. Il a un exosquelette développé qui le protège du feu des armes légères, et des mâchoires plus puissantes. Comme l'écloserie, il peut grimper les murs et les plafonds, en mettant des embuscades. Conserve la capacité de cracher de l'acide (plus puissant et à plus longue portée) et est également mortelle dans le combat étroit. Souvent trouvé dans des groupes, il agit comme un combattant hybride varié/maléfique, distrayant et harcelant les ennemis.

CONSEILS:

- Un seul tir précis d'un fusil à double canon ou un coup puissant d'un marteau tue instantanément.
- Deux coups de fusil à pompe, fusil d'assaut ou fusil de sniper sont efficaces. Les balles acides peuvent être abattues en plein air.
- Utilisez une fusée éclairante, un lance-grenades ou un C4. Dans une pincée, utilisez un pistolet SBC ou un mini-gun.
