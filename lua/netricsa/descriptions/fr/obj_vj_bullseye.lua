BULLSEYE


CLASSE:      Oiseaux
MÉTABOLISME: Entité scénique
PERCEPTION: Proxy cible / Entité rédirecte
TAILLE:       ~1 pi 
ENDURANCE:  Faible 
HOSTILITÉ:  Neutre 
ARMES:    Aucune 
RÉCOMPENSE:     1 FC
MENACE:     Très faible

DESCRIPTION:

Bullseye est une entité scénique spéciale utilisée en interne par le moteur (et les map makers) pour rediriger les dommages. Essentiellement, c'est un proxy cible: tout ce qui est lié à Bullseye aura ses dommages ou son rayon de feu redirigé vers la position de Bullseye. Par exemple, vous pouvez placer un Bullseye invisible dans une pièce, relier les modèles NPC à elle, et faire des attaques visant ces NPC frappés à l'emplacement réel de Bullseye à la place.

En termes de gameplay, Bullseye est invisible et intangible ; il ne se bat ni ne réagit. Son rôle est purement technique - utilisé dans les cartes pour permettre "shoot through walls" ou rediriger des attaques pour des énigmes, pièges, ou des événements scriptés.

CONSEILS:

- Comprendre Bullseye permet aux mappers de produire des balles téléportées, des parois vitrées ou des déclencheurs à distance.
