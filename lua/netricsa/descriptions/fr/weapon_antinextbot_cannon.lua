ANTI-NEXTBOT CANNON


ARME: Cannon anti-nextbot
MUNITIONS:   Énergie gravitationnelle surchargée / faisceau d'annihilation
CADENCE DE TIR:    Faisceau continu

DESCRIPTION:

L'arme anti-nextbot la plus avancée, basée sur le canon à gravité surchargé amélioré. L'arme combine la technologie gravitationnelle et les explosions d'énergie destructrices, formant un faisceau de puissance colossale.

Le premier mode concentre l'énergie dans un endroit étroit, libérant un faisceau capable de détruire instantanément des groupes de cibles dans une seule zone. Il est utilisé pour effacer les concentrations ennemies et tenir des positions clés.

Le second mode active une explosion d'énergie complète, couvrant toute la zone. À ce stade, l'utilisateur est automatiquement protégé par un champ spécial qui les isole complètement des effets de l'arme. Tous les autres êtres vivants dans la zone d'explosion sont immédiatement détruits – aucune exception.

REMARQUES:

- Mode 1: destruction massive de cibles dans une seule zone avec un faisceau.
- Mode 2: Nettoie complètement l'emplacement de toutes les créatures vivantes.
- L'utilisateur est protégé par un champ d'énergie lors de l'activation du second mode.
- Ne fait pas de discrimination entre les cibles - les alliés et les neutres sont également détruits.
- Efficace à n'importe quelle portée, en particulier dans les espaces confinés.
