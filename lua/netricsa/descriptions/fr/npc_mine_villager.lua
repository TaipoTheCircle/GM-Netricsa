VILLAGER DU MINECRAFT


CLASSE:      Villageur
MÉTABOLISME: Humanoïde chaud
PERCEPTION: Humanoïde passif intelligent
TAILLE:       6,2 pi
ENDURANCE:  Faible
HOSTILITÉ:  Très faible
ARMES:    Aucune
RÉCOMPENSE:     100 FC
MENACE:     Minimal

DESCRIPTION:

Les villageois sont les premiers représentants de la civilisation intelligente dans le monde de Minecraft. Ces humanoïdes sont reconnaissables par leurs gros nez, leurs sourcils sillonnés et leur invariable habitude de traverser leurs bras, comme si le monde leur devait quelque chose. Ils communiquent en utilisant des sons caractéristiques, qui, selon certains, sont soit une forme simplifiée de parole, soit une agression passive.

Villagers live in villages where they lead a measured life: ils travaillent, échangent, dorment et paniquent à la vue des zombies. Chaque villageois peut avoir une profession déterminée par son bloc de travail, qui constitue la base de l'économie du village. La monnaie principale est les émeraudes, qui sont beaucoup plus précieuses pour les villageois que pour le reste du monde.

Les villageois sont incapables de combattre et comptent entièrement sur les golems de fer, qu'ils craignent et considèrent simultanément comme un héros.

CONSEILS:

- Faire du commerce et changer de métier.
- Éviter les conflits directs.
- Craignez les foules hostiles.
- Un villageois peut pardonner, mais n'oublie jamais.
