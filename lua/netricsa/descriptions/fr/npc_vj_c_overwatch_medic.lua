MÉDICAMENT DE SURVEILLANCE DES COMBINES


CLASSE:      Combiner Overwatch Elite Medic
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner le combat sur le terrain
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Combiner Elite Medic Gun (poutre de guérison et mitrailleuse alt-fire), flacons de guérison
RÉCOMPENSE:     1200 FC
MENACE:     Très élevé

DESCRIPTION:

Le Combine Overwatch Elite Medic n'est pas un sauveur, mais un membre du personnel de soutien d'un abattoir. Il porte une combinaison blanche avec des rayures noires sur les jambes et des panneaux d'épaule noirs. Les rayures oranges sur les épaules forment une croix - le symbole médical Combine, qui est plus d'un avertissement qu'une promesse d'aide.

Le casque est équipé d'un respirateur et de grandes lentilles bleues convexes, donnant au médicament un aspect insecte. Un tube s'étend du respirateur à une boîte médicale sur le dos, où le contenu des larves d'antlion sont entreposés.

Le Medicannon de la Combine tire un faisceau de guérison qui livre des oeufs de larve d'antlion transformés aux alliés. Le Combine extrait les jus de guérison des larves et les utilise comme biocarburant pour la régénération des tissus.

Des flacons de guérison supplémentaires sont fixés au côté du médecin, utilisés pour le rétablissement d'urgence des soldats. Le mode alternatif du médecin active une mitrailleuse intégrée, permettant au médecin de se défendre et de terminer les ennemis directement sous le faisceau de guérison.

Au combat, l'Elite Medic se livre rarement à une attaque directe. Il pend derrière les unités Elite, les transformant en soldats quasi-immortels pendant qu'il reste sous couverture.

CONSEILS:

- Tuez le médecin d'abord, sinon les soldats d'élite deviendront pratiquement impossibles à tuer.
Son armure est plus faible que celle des élites de combat, mais il est généralement entouré de gardes.
- Son rayon de guérison donne sa position avec une lueur lumineuse, alors utilisez-le.
- Son feu secondaire est dangereux à proximité, alors ne le sous-estimez pas.
