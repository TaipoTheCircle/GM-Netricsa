UN HOMME D'HONNEUR DU NIRN


CLASSE:      Gardien impérial
MÉTABOLISME: Impérial, Homme
PERCEPTION: Gardien de l'Ordre de la Cité Impériale / Enforceur de Loi
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Conditionnel
ARMES:    Argent Longsword, parfois destructive magie
RÉCOMPENSE:     200 FC
MENACE:     Moyenne

DESCRIPTION:

Ce sont les piliers de l'ordre et de la loi dans la ville impériale de Cyrodiil. Ces combattants, revêtus d'armure distinctive de la Légion, sont des représentants de la Légion impériale et accomplissent le difficile devoir de maintenir l'ordre dans la capitale provinciale.

L'apparence du Watchman inspire le respect et une certaine intimidation. Ils sont revêtus d'une armure d'acier de la Légion, dont un casque massif, et portent une longue épée d'argent. Leur travail est d'être visible, donc les criminels potentiels réfléchissent à deux fois avant de violer la loi. Certains gardiens maîtrisent les sorts de destruction, les rendant dangereux non seulement au combat rapproché, mais aussi à portée de main.

La fonction première d'un gardien est la justice. Si vous commettez un crime, qu'il s'agisse d'un meurtre, d'un vol ou d'une agression, le gardien le plus proche se précipitera immédiatement de votre côté en criant : « Halt, abomination criminelle ! » Vous aurez le choix : payer une amende, aller en prison ou résister. Si vous décidez de vous rendre, le gardien confisquera toutes les marchandises volées et vous escortera au château pour purger votre peine.

Résister à l'arrestation est une mauvaise idée. Les gardiens se battent habilement et de manière cohérente, et si vous refusez de vous rendre, ils n'hésiteront pas à tirer leurs épées en criant: «Payez avec votre sang!»

Il y a plusieurs unités spécialisées de la montre impériale. Les gardiens de la prison surveillent la prison impériale et utilisent une masse d'argent au lieu d'une épée. Ils portent toujours des clés cellulaires, qui peuvent être utiles pour un prisonnier avec une bonne dextérité manuelle.

Malheureusement, certains gardiens sont vulnérables à la corruption. Par exemple, le capitaine Audens Avidius a été pris en train d'extorquer de l'argent aux marchands. Des gardiens honnêtes, comme le capitaine Itius Hein, sont prêts à aider à attraper des criminels, mais ils auront besoin de preuves irréfutables.

CONSEILS:

- Si vous prévoyez de vous livrer à des activités criminelles, faites-le dans des zones isolées et évitez d'être vu par des gardiens. Leur vue et leur ouïe sont excellentes.
- Si on vous repère voler et qu'un garde approche, votre meilleure option est de payer une amende. Résister à l'arrestation entraîne presque toujours la mort.
- Portez assez d'or pour couvrir l'amende. Si vous n'avez pas d'argent, vos seules options sont la prison ou le combat.
- N'oubliez pas qu'après avoir purgé votre peine, tous les objets volés seront confisqués. Cachez-les dans un endroit sûr avant de vous rendre aux autorités.
- Écoutez ce que disent les gardes. Ils offrent souvent des conseils utiles sur la ville, ses quartiers et les derniers événements.
