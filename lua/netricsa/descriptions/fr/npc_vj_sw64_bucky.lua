BOUCHEZ LA BANDE DE LA BROADSIDE


CLASSE:      Bouclez le castor
MÉTABOLISME: Castor anthropomorphe
PERCEPTION: Ancien acteur devenu tueur en série
TAILLE:       5 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Absolu
ARMES:    Dents, agilité / force physique, costume, objets improvisés
RÉCOMPENSE:     300 FC
MENACE:     Absolu

DESCRIPTION:

La star de Broadside Animation et le visage de l'entreprise. Un grand castor brun avec un sourire permanent et deux grandes dents avant. Il a été créé par Rex Broadside après avoir accidentellement perdu les droits sur son premier personnage, Blot the Rabbit. L'inspiration est venue quand sa mère lui a apporté une gaufre qui lui rappelait une queue de castor.

Les premières caricatures de Bucky étaient sombres et violentes-chaque épisode a présenté la mort du castor à la fin, qui a alimenté sa haine pour son créateur. Plus tard, le personnage fut adouci et des amis furent ajoutés : Olivia l'Otter, Giovanni l'Oie, et Walter le frère du Walrus. Bucky devint un fan favori, son visage reconnaissable à des millions, et ses étagères de magasins remplis de marchandises sous licence.

Brandon Lester était un acteur engagé pour porter le costume Bucky au parc à thème de Broadside Beach. Il voulait le poste et semble l'avoir obtenu, en le prenant d'un autre candidat, plus joyeux. Mais un jour, Brandon est mort d'une overdose de fentanyl.

Au lieu d'enterrer son corps, Broadside Animation l'utilisa pour une expérience terrible. Le corps de Brandon a été fusionné avec la chair mystérieuse des grottes de Nulla Terra, créant "Starling"-un costume de Bucky vivant qui n'a pas besoin d'un acteur à l'intérieur. C'était le premier Starling public.

Après sa transformation, Brandon a commencé à tuer.

His Victims:

Olivia Finch (Olivia l'Otter) : Brandon l'a noyée dans le lac près du complexe d'habitation des employés. Son corps a ensuite été utilisé pour créer le Starling d'Olivia.

Gary Wilson (Giovanni l'Oie) : Brandon s'est cassé le visage dans un mur puis a poussé la tête dans une friteuse profonde. Gary est devenu le Starling de Giovanni.

Nathan Stewart (Walter the Walrus): Brandon l'a tué avec une chaise en bois dans les bureaux de Broadside Animation. Nathan est devenu Starling de Walter.

CONSEILS:

- Écoutez ses demandes si vous ne voulez pas voir ce qui le rend fou.
- Vos actions ont des conséquences.
