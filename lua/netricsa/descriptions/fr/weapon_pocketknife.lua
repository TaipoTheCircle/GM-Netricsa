KNIFE DE POCKET


ARME:    Couteau de poche

DESCRIPTION:

Un couteau de poche standard. Conçu pour être utilisé dans diverses situations où un couteau est nécessaire, y compris dans les combats.

REMARQUES:

- La pression LMB + R vous permet de changer le type d'attaque.
- En mode coupe, il est recommandé de viser les membres pour provoquer des saignements artériels.
- La pression de RMB sur un élément sécurisé par bande vous permet de commencer à le délier.