ENDER CREEPER DE LA FIN MINECRAFT


CLASSE:      Ender Creeper
MÉTABOLISME: Poudre hybride
PERCEPTION: Ender Creature Hybrid, Chasseur Elite
TAILLE:       5,5 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Absolu
ARMES:    Téléportation, Cible Homing, Explosion, Bite
RÉCOMPENSE:     300 FC
MENACE:     Absolu

DESCRIPTION:

Ceci est le résultat d'une mutation d'un fluctuant normal qui a été exposé à l'énergie d'ender dans la fin pendant trop longtemps.

L'Ender Creeper diffère d'un rampant normal non seulement en couleur mais aussi en vitesse et visiblement l'intelligence. En se déplaçant, il laisse une trace de particules violettes, semblable à la téléportation de l'Enderman.

L'Ender Creeper hérite des capacités de l'Enderman : il peut téléporter de courtes distances, esquiver des flèches et des attaques. Lorsqu'il est tiré avec un arc ou une arbalète, il disparaît instantanément et réapparaît derrière ou sur le côté, prêt à attaquer. Parfois, il peut se téléporter devant sa victime, bloquant leur chemin.

Il suit sa cible, téléporte pour attaquer d'une direction inattendue, puis explose.

CONSEILS:

- N'essayez pas de tirer avec un arc ou une arbalète. Il va se téléporter, et tu vas gâcher tes flèches.
- Utilisez de l'eau pour désactiver sa téléportation.
- En melee combat, frappez rapidement avec votre épée, ne lui donnez pas le temps de réagir.
- L'Ender Creeper n'explose pas instantanément. Si vous entendez un sifflement, sautez ou utilisez un bouclier.
- Tuer un Ender Creeper a une chance de laisser tomber un Ender Pearl. C'est un excellent moyen de cultiver des perles si vous ne voulez pas tuer Endermen.
