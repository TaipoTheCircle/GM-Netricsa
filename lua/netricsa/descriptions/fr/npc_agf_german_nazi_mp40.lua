VENDU NAZI


CLASSE:      Soldat nazi
MÉTABOLISME: Humain, Homme
PERCEPTION: Infanterie Wehrmacht
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extreme (vers les ennemis du Reich)
ARMES:    Mi-40 mitrailleuse, grenades, couteau de combat
RÉCOMPENSE:     250 FC
MENACE:     Moyenne

DESCRIPTION:

Fantassins allemands classiques de la Seconde Guerre mondiale, les soldats nazis sont fidèles à leur régime et entraînés à combattre avec une efficacité impitoyable. Armés principalement du MP-40, ils excellent dans le combat à mi-chemin et se déplacent souvent en escadrons pour couvrir les avancées de l'autre. Leur service inébranlable à l'Allemagne les rend déterminés et dangereux.

Au combat, ils comptent sur des tirs suppressifs, des tactiques d'embuscade et de simples chiffres. Bien que leur équipement ne soit pas aussi avancé que les futures armées, leur discipline et leur coordination en font des ennemis redoutables sur le terrain.

CONSEILS:

- Gardez votre distance; le MP-40 est le plus efficace à proximité.
- Les grenades peuvent perturber les équipes avant qu'elles ne t'écrasent.
- Utiliser un couvercle pour éviter les éclatements concentrés.
- Des soldats isolés de leur groupe pour les neutraliser plus facilement.
