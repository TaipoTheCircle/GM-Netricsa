MITRAILLEUSE MG-88 ENFORCER


ARME : Mitrailleuse MG-88 Enforcer
MUNITIONS : 5.56x45mm
ROF : ~600 tr/min

DESCRIPTIF :

Une arme à tir rapide et de puissance moyenne conçue pour des tirs intenses à courte et moyenne portée. L'arme utilise des munitions de 5,56 x 45 mm et un chargeur de 60 cartouches, permettant un tir prolongé sans rechargement fréquent.

Le MG-88 a un bon recul modéré, mais lors d'une enquête continue, son recul s'use rapidement. Sa grande capacité de chargeur le rend particulièrement bien adapté pour engager des adversaires.

REMARQUES :

- Grand chargeur de 60 coups. Permet un tir prolongé sans rechargement.
- Une bonne précision en fait une arme polyvalente.
- Convient aux tirs intenses à portée proche et moyenne.
