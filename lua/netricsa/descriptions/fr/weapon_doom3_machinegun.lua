MG-88 GUN DE MACHINE ENFORCER


ARME: MG-88 Pistolet à machines d'exécution
MUNITIONS:   5.56x45mm
CADENCE DE TIR:    ~600 RPM

DESCRIPTION:

Une arme à feu rapide de puissance moyenne conçue pour des tirs lourds à proximité de portée moyenne. L'arme utilise des munitions de 5,56 x 45 mm et un chargeur de 60 tours, permettant un tir prolongé sans rechargement fréquent.

Le MG-88 a un bon recul modéré, mais au cours d'une enquête continue, son recul s'épuise rapidement. Sa grande capacité de magazine le rend particulièrement adapté pour engager des adversaires.

REMARQUES:

- Grand magazine 60 tours. Permet un feu prolongé sans rechargement.
- Une bonne précision en fait une arme polyvalente.
- Convient pour un feu lourd à proximité de gammes moyennes.
