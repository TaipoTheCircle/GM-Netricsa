GUN PHYSIQUE


ARME:      Outil de manipulation physique (Gun physique)
MUNITIONS:        Aucun (manipule des objets de physique)

DESCRIPTION:

Outil avancé pour ramasser, tourner et déplacer des objets avec précision. Permet à l'utilisateur de manipuler l'environnement ou les objets à distance, y compris le levage, la rotation et le gel des objets en plein air. Volé de la science d'ouverture par Black Mesa.

REMARQUES:

- Utilisation infinie; pas de munitions traditionnelles nécessaires.
- Capable de lancer des objets comme des armes improvisées.
- Utile pour la construction, les puzzles et l'improvisation de combat.
- Nécessite des compétences pour un positionnement et un contrôle précis.