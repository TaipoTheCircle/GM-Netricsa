OUI


CLASSE:      Yeti
MÉTABOLISME: Mammifère intelligent
PERCEPTION: Ami Giant et homme de famille
TAILLE:       ~22 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Faible
ARMES:    Griffes, force
RÉCOMPENSE:     300 FC
MENACE:     Moyenne

DESCRIPTION:

Cet homme de famille bienveillant vit avec sa famille dans les rudes terres enneigées et apporte des proies à la maison tous les jours - surtout des sangliers. Il combine supériorité physique et tempérament pacifique, préférant éviter les conflits dans la mesure du possible.

Un jour, un homme l'a rencontré accidentellement et a commencé à prendre des photos. Les Yeti n'avaient pas peur et même posé, ne réalisant pas les conséquences. Après que les images aient paru dans les nouvelles, les Yeti ont été considérés comme une menace, et un chasseur a été envoyé pour le traquer. Cependant, en voyant la famille aimante du Yeti, le chasseur n'a pas pu accomplir sa mission. Il a pris contact avec le Président des États-Unis et signalé que l ' alarme n ' était pas fondée.

Malgré cela, la zone 51 continue de chasser les Yeti, la considérant comme une créature rare et potentiellement dangereuse. Cela fait de sa vie et de la vie de sa famille une cible constante pour les agences de renseignement. Chaque jour, les Yeti sont contraints de vérifier la zone pour détecter les signes d'une présence non autorisée et de protéger le périmètre d'éventuelles interférences des services de renseignement.

Le Yeti passe la plupart de son temps à chercher des ressources à des températures extrêmement froides. Elle passe ses soirées en famille, assurant leur sécurité et leur confort. Sa priorité absolue est le bien-être de ses proches, et il est prêt à tout pour y parvenir.

CONSEILS:

- Le Yeti n'est pas agressif. Si vous le rencontrez dans la neige, ne paniquez pas ou essayez de le tuer.
- Ne vous approchez pas de sa maison ou de sa famille. C'est la seule chose qui peut l'irriter.
- Si vous le voyez par accident, partez. Il ne suit pas les gens.
- N'essayez pas de prendre une photo de lui. Il pourrait attirer l'attention de la zone 51.
Dans un combat, le Yeti n'est dangereux que si sa famille est en danger. Si vous ne menacez pas ses proches, il ne vous touchera pas.
