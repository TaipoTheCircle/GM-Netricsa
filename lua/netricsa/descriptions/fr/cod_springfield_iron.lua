FUSIL SPRINGFIELD M1903


ARME : Springfield M1903 Rifle
MUNITIONS : .30-06 Springfield (7.62x63mm)
ROF : ~15-20 rounds / min
POIDS : ~3,95 kg

DESCRIPTIF :

Ce fusil à répétition américain à verrou, basé sur le modèle Mauser, a été adopté par l'armée américaine au début du XXe siècle. La version la plus célèbre était chambrée pour la cartouche Springfield .30-06, utilisée pendant les deux guerres mondiales.

The rifle is designed for accurate fire at medium and long ranges. The bolt-action mechanism ensures reliable operation and allows the shooter to manually chamber the next round after each shot. The M1903 was also produced in sniper versions with optical sights.

The Springfield M1903 combines a powerful rifle cartridge, good accuracy, and a relatively light weight. This made it suitable for both regular infantry and specialist marksmen.

REMARQUES :

- Particularly effective at medium and long ranges, where the M1903's accuracy shines.
- When you need an old-school American rifle: no bursts, just a bolt, scope, and a very convincing argument.
- Sniper variants with optics allow the rifle to be used for engaging individual targets at long ranges.
- The .30-06 cartridge offers high power and good range.
