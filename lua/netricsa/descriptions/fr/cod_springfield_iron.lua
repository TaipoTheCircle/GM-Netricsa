RIFLE DE SPRINGFIELD M1903


ARME: Springfield M1903 Rifle
MUNITIONS:   .30-06 Springfield (7.62x63mm)
CADENCE DE TIR:    ~15-20 tours/min
POIDS: ~3,95 kg

DESCRIPTION:

Ce fusil à action de boulon américain, basé sur le modèle Mauser, a été adopté par l'armée américaine au début du XXe siècle. La version la plus célèbre a été assemblée pour la cartouche .30-06 Springfield, qui a été utilisée dans les deux guerres mondiales.

Le fusil est conçu pour un feu précis à portée moyenne et longue. Le mécanisme d'action du boulon assure un fonctionnement fiable et permet au tireur de chambrer manuellement le tour suivant après chaque tir. Le M1903 a également été produit en version sniper avec des vues optiques.

Le Springfield M1903 combine une puissante cartouche de fusil, une bonne précision et un poids relativement léger. Cela le rendait adapté à la fois pour l'infanterie régulière et les tireurs spécialistes.

REMARQUES:

- Particulièrement efficace à moyenne et longue portée, où la précision du M1903 brille.
- Quand vous avez besoin d'un fusil américain à l'ancienne : pas d'éclats, juste un boulon, une portée, et un argument très convaincant.
- Les variantes de sniper à optique permettent d'utiliser le fusil pour attaquer des cibles individuelles à de longues distances.
- La cartouche .30-06 offre une grande puissance et une bonne gamme.
