PNJ, LE PLAYEUR MIMICE


CLASSE:      Le joueur NPC, le joueur mimique
MÉTABOLISME: Humains
PERCEPTION: CNP humain / Mimique
TAILLE:       ~5,9 pi
ENDURANCE:  Moyen (même caractère que le joueur standard)
HOSTILITÉ:  Variable (comportement du joueur de copie; peut attaquer si le joueur attaque)
ARMES:    L'inventaire des joueurs de miroirs (armes, grenades, melee, etc.)
RÉCOMPENSE:     100 FC
MENACE:     Élevé (si hostile)

DESCRIPTION:

Le joueur NPC, également connu sous le nom de Mimic Player, est un NPC très inhabituel qui réplique toutes les actions du joueur. Que ce soit pour sauter, tirer ou utiliser des objets, ce NPC reflète les mouvements et les interactions du joueur en temps réel.

Il est conçu comme une expérience de bac à sable ou un défi de gameplay, créant des scénarios imprévisibles et souvent chaotiques. Au combat, le joueur mimique peut devenir une menace mortelle s'il reproduit les actions offensives du joueur, tournant efficacement vos propres compétences contre vous.

CONSEILS:

- Observez son comportement pour anticiper son prochain mouvement-il reflète toutes vos entrées.
- Peut être utilisé pour la résolution de puzzle ou des scénarios de gameplay expérimentaux.
- S'il est armé, il utilisera des armes aussi efficacement que le joueur.
- Évitez de provoquer inutilement l'agression est copié et augmente rapidement.
