BÉRETTA M9 PISTOL


ARME:       Beretta M9
Ammunition:   9x19 mm
CADENCE DE TIR:          15 tours/min

DESCRIPTION:

Le pistolet Beretta M9 est un pistolet à chargement automatique pour la cartouche Parabellum 9×19 mm, une version du pistolet italien Beretta 92F pour les forces armées américaines. Il est fabriqué aux États-Unis par une filiale de Beretta. Il diffère des pistolets de la série 92F fabriqués en Italie dans son cycle de production simplifié et plus court, la production automatisée d'un certain nombre de pièces qui sont faites à la main par les maîtres armuriers en Italie, et une inscription estampillée sur le côté gauche de la diapositive d'acier. Depuis 1986, l'étui M12 de Bianchi International est utilisé comme étui à hanche standard pour le pistolet. Il a été utilisé dans presque toutes les guerres américaines depuis 1989. Il est populaire auprès des gangsters. C'est aussi une arme civile.

REMARQUES:

- C'est lourd et puissant.
- Vous pouvez le tenir avec les deux mains et sauter en tirant au ralenti.
- Vous pouvez être volé ou tué avec, mais vous pouvez aussi vous défendre avec.