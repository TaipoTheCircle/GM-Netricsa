CREEPER DU MINECRAFT


CLASSE:      Pompiers
MÉTABOLISME: Pyrotechnique
PERCEPTION: Mob hostile, Pyro à pied
TAILLE:       5,5 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Extrême
ARMES:    Auto-détonation avec propagation du feu
RÉCOMPENSE:     150 FC
MENACE:     Moyenne-haute

DESCRIPTION:

C'est ce qui se passe quand un rampant régulier décide que l'explosion est trop ennuyeux, et que le feu est l'élément vrai. Cette variété de rampants élémentaires diffère de leurs homologues de la poudre à canon dans leur feuillage orange vif, qui ressemble à des braises et des flammes fumantes. C'est difficile d'en repérer un dans le désert ou dans la Nether, mais quand on est à proximité, vous le saurez instantanément.

Fire creepers primarily inhabit hot biomes: les déserts, les savanes, les mesas et, bien sûr, la Nether. Ils n'ont pas peur de la lave et peuvent prospérer dans des endroits où des rampants réguliers seraient incinérés.

En explosant, un pulvérisateur de feu ne détruit pas les blocs avec la même force qu'un pulvérisateur régulier, mais sa vague d'explosion répand le feu sur une distance considérable. Toute la zone située dans le rayon du souffle est engouffrée de flammes, qui se propagent rapidement au bois, aux feuilles, à la laine et à d'autres matériaux inflammables. Une telle explosion peut transformer une forêt en un inferno flamboyant, et une maison en bois en cendres en quelques secondes.

CONSEILS:

- Ne combattez pas les pompiers près des bâtiments en bois. Une explosion et votre maison sera réduite en cendres.
- C'est particulièrement dangereux dans la forêt. Les flammes s'étendent rapidement aux arbres, et vous pouvez vous retrouver entouré par le feu.
- Si vous êtes dans le désert ou dans le monde, soyez doublement prudent. Dans le désert, les rampants se mélangent dans le sable, et dans la Nether, le feu est partout.
- Gardez un seau d'eau à portée de main. Une explosion peut rapidement éteindre un feu qui s'étend.
- Les pompiers n'accordent pas d'expérience ni ne laissent tomber de précieuses ressources, autres que la poudre à canon et parfois le charbon.
- Tuer un rampant de feu a une chance de laisser tomber la poudre, qui est utilisée pour fabriquer des explosifs élémentaires. Les explosifs fabriqués à partir de poudre d'incendie créent une boule de feu lorsqu'ils sont détonés, en dégageant tout ce qui les entoure.
