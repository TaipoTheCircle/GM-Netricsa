BOUG MORTAL "BETA"


CLASSE:        Bug Mortier "Beta"
MÉTABOLISME:   Xénobiologique
PERCEPTION:   Unité d'artillerie
TAILLE:         9 pieds
ENDURANCE:    Moyenne
HOSTILITÉ:    Haut
ARMES:      Projectiles biologiques explosifs
RÉCOMPENSE:       650 FC
MENACE:       Haut

DESCRIPTION:

Le "Beta" Swarm Mortar Bug est une variante de siège spécialisée conçue pour éliminer les ennemis de longue portée. Contrairement aux Drones ou aux Rangers, son corps est presque entièrement dédié à une seule tâche : la production et le lancement de munitions organiques.

Une mare massive domine la moitié avant de son torse; à l'intérieur, des biocapsules explosives se forment. Au moment de l'impact, ils adhèrent aux surfaces et détonent après quelques secondes. Cela permet au Bug Mortar de bloquer les passages, de forcer les proies à s'abriter et de disperser les formations défensives.

La physiologie de la créature diffère significativement de la plupart des autres membres du Swarm "Beta". Ses organes visuels sont sous-développés ou dissimulés sous des couches de tissus; il navigue probablement à l'aide de vibrations, de parfums et d'autres capteurs biologiques. Cela explique pourquoi le Bug Mortar opère rarement seul, préférant rester sous la protection d'unités plus mobiles.

Malgré sa létalité, la créature n'est pas adaptée au combat des quartiers proches. Sa masse massive et son anatomie spécialisée rendent le Bug Mortar beaucoup moins maniable que la plupart des autres unités de Swarm.

CONSEILS:

- Regardez où atterrissent les projectiles.
- Ne laissez pas le Bug Mortar maintenir le feu.
- Exploitez son manque de mobilité.
- Si une créature de la taille d'un petit véhicule ouvre sa mâchoire dans votre direction, il est préférable de ne pas attendre le résultat de l'expérience.
