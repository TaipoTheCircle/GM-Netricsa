MANCUBUS, LE STRAPJACK DU HELL


CLASSE:      Mancubus, ScrapJack
MÉTABOLISME: Mammifère démoniaque reconstruit
DEFINITION: Corps de béhémoth modifié
TAILLE:       13 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Deux RPG
RÉCOMPENSE:     3000 FC
MENACE:     Haut

DESCRIPTION:

Un démon personnalisant l'imperfection et l'avidité humaines, la gloutonnerie et l'oisiveté. Il a une peau incroyablement épaisse, des jambes éléphantines massives et une petite tête. Afin de détruire et d'exploser les victimes, deux RPG qui tirent Rockets sont implantés dans les avant-bras du mancubus.

Ces Mancubus tués de la manière la plus horrible ont été refondus, tournant écarlate. Leur peau prend la couleur du sang séché, et leur essence change. Mental, toujours à la recherche de moyens de renforcer sa Horde, a acheté plusieurs douzaines de ces créatures du Seigneur de l'enfer (avec les soldats zombies et autres morts-vivants) et les a envoyés pour repurposition.

Au lieu de lance-flammes, des lance-roquettes ont été greffés sur leurs avant-bras. Deux RPG tirent continuellement jusqu'à la mort de l'ennemi. Même si l'ennemi se cache derrière un mur, les fusées voleront encore et encore, réduisant méthodiquement la couverture à un tamis, puis le tireur à la viande hachée.

Contrairement à un Mancubus Flamethrower régulier, le Mancubus ScrapJack est plus faible en défense. Soudée à partir des morceaux de différents démons, elle manque d'armure monolithique et peut être tuée plus rapidement. Mais seulement si vous pouvez y arriver avant qu'il transforme tout autour en un cratère d'explosions.

CONSEILS:

- A couvert. Les fusées sont aléatoires, et un mur de pierre peut vous sauver la vie, mais seulement pour une courte période.
- Ils tirent sans fin. Ne les attendez pas à manquer de munitions. Ils n'en ont pas.
- Tuez-les vite. Oui, ils sont plus faibles qu'un Mancubus ordinaire, mais chaque seconde que vous attendez augmente les chances de vous transformer en bordel.
- Ne restez pas ouvert. Les fusées ont une large diffusion, et se cacher aux coins est le seul moyen de survivre.
- Ne les laissez pas viser. Si vous voyez un Mancubus pointant ses lance-roquettes sur vous, passez immédiatement sur le côté. Ils ne tirent pas instantanément, mais une fois qu'ils commencent, ils sont presque impossibles à arrêter.
- Utilisez des explosifs. Un C4 bien placé peut le détruire plus rapidement que 5 coups de fusil.
