KWONGO, LE GIANT GORILLA DE M'DIGBO


CLASSE:       Kwongo, la Gorille géante
MÉTABOLISME:  Primate géant
PERCEPTION:  Déité de la tribu Simba
TAILLE:        427 pieds
ENDURANCE:   Extrême
HOSTILITÉ:   Absolu
ARMES:     Fists, lancer des bâtiments
RÉCOMPENSE:      50000 FC
MENACE:      Absolu

DESCRIPTION:

Un gorille géant, plus grand que les gratte-ciels de la ville, avec fourrure grise et yeux rouges.

C'était autrefois une divinité locale adorée par la tribu Simba sur la planète M'Digbo. Mais à un moment donné, Kwongo a acquis un morceau du médaillon, un artefact nécessaire pour combattre Mental.

Au combat, Kwongo est pratiquement invulnérable aux armes classiques. Rifles, fusils de chasse et même lance-roquettes ne laissent que des rayures sur sa peau. La seule façon d'infliger des dommages graves est d'utiliser des catapultes spéciales, que le Simbas charge avec des boules de lave. Pendant que Kwongo s'approche lentement de vous, il lance périodiquement des maisons et les écrase avec ses poings.

Après la mort, Kwongo sera mangé - toute la tribu va rôtir ses restes sur un énorme feu de joie.

CONSEILS:

- Gérez les tourelles. C'est le seul moyen de protéger les Simbas et de descendre les maisons volantes.
- Si les catapultes ne suffisent pas, terminez-les avec l'arme la plus puissante qu'il vous reste.
