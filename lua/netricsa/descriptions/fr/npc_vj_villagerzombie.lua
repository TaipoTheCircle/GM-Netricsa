ZOMBIE VILLAGER DU MINECRAFT


CLASSE:      Zombie Villager
MÉTABOLISME: Villageur infecté
PERCEPTION: La foule hostile
TAILLE:       6,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Mains
RÉCOMPENSE:     200 FC
MENACE:     Moyenne

DESCRIPTION:

Ceci est le résultat d'une rencontre tragique entre un villageois normal et un zombie normal. Une seule bouchée suffit au marchand méfiant pour se transformer en ce simulacre pâle, ne conservant qu'un nez reconnaissable et les restes de vêtements. À l'extérieur, il diffère d'un zombie normal dans sa muselière caractéristique et plus grande taille - 0,9 cm de plus que ses autres zombies, ce qui lui permet parfois de se coincer dans les portes.

Les villageois zombies frayent dans les mêmes endroits que les zombies réguliers, mais avec une moindre chance. Ils peuvent parfois être rencontrés dans la taïga et dans les igloos, où l'un de ces zombies est enfermé dans le sous-sol derrière les bars.

Zombie villagers behave similarly to regular zombies: ils poursuivent les victimes, les villageois, et les golems de fer, peuvent briser les portes, et ramasser des objets. Mais il y a une différence importante, une pour laquelle beaucoup sont prêts à risquer leur vie : ils peuvent être guéris.

The healing process goes like this: d'abord, le villageois zombie est affaibli avec une potion ou une citrouille explosive, puis donné une pomme dorée. Après quelques minutes, le tremblement commence, et après une minute ou deux, le villageois revient à la normale. Le villageois guéri offre des réductions sur le commerce, parfois symboliques-jusqu'à un émeraude pour tout.

CONSEILS:

- Si tu vois un villageois zombie, ne le tue pas tout de suite. Isolez-le d'autres zombies pour que vous puissiez le guérir plus tard.
Pour le guérir, il faut une potion de faiblesse et une pomme dorée. Les deux peuvent être fabriqués ou trouvés dans les poitrines.
- Les sous-sols Igloo contiennent toujours un villager zombie et tout ce qu'il faut pour le guérir.
- Un villageois guéri offre de bonnes réductions. Si vous avez de la chance, vous pouvez avoir un outil en diamant pour quelques émeraudes.
- Il y a aussi des bébés zombies. Ils sont aussi rapides et guéris selon les mêmes règles.
- Les villageois de Zombie peuvent frayer avec un poulet. C'est rare, mais ça arrive.
