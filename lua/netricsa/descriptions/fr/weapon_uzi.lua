IMI UZI SUBMACHINE GUN


ARME:     IMI UZI
AMMUNITION: Cartouches de parabellum 9×19 mm
CADENCE DE TIR:        ~600 tours/min

DESCRIPTION:

Une mitrailleuse compacte auto-chargeuse/automatique avec un boulon télescopique et un simple mécanisme de rétractation par inertie (mécanisme de tir à bol ouvert dans les premières versions). Développé par Uzi Gal en Israël à la fin des années 1940 et 1950. Le chargeur est situé dans la poignée de pistolet, ce qui rend l'arme compacte et pratique pour le transport et le contrôle cachés pendant les tirs à main unique. Il dispose d'un design simple, d'une grande fiabilité dans des conditions difficiles et d'une facilité d'entretien. Il a été largement utilisé par les forces militaires, policières et de sécurité et a été produit en plusieurs versions (Standard, Mini, Micro) et des modifications pour d'autres calibres.

REMARQUES:

- La compacité et le taux de feu cyclique élevé sont compensés par une précision relativement faible à des distances supérieures à 50-100 m.
- Simple à fabriquer et à entretenir, populaire au 20ème siècle; les versions civiles et d'exportation avec des restrictions de mode de feu.


