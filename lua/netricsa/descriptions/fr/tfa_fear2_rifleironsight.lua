PATTEN 470 RISQUE D'ASSAULT


ARME: Patten 470 Coups de poing Elite
MUNITIONS:   5.56x45mm OTAN
CADENCE DE TIR:    600 à 750 tours/min

DESCRIPTION:

Un fusil d'assaut moderne a été mis au point pour les unités armées de l'Armacham Technology Corporation. Il dispose d'une action à gaz avec un piston à gaz, offrant une haute fiabilité et une bonne précision. Contrairement à la norme Patten 470, la version Elite n'est pas équipée d'une vue optique ACOG, ce qui lui donne un aspect plus épuré.

Le Patten 470 Elite comprend un sélecteur en mode feu, permettant à l'utilisateur de basculer entre feu semi-automatique et feu entièrement automatique. Il utilise des magazines de 30 tours et conserve les spécifications de combat de base du modèle. Sa polyvalence et sa facilité de manipulation le rendent bien adapté à une variété de scénarios de combat.

REMARQUES:

- Une variante du modèle standard Patten 470 Assault Rifle.
- Ne comporte pas de vision optique ACOG.
- La capacité du chargeur est de 30 rounds.
- Utilise des munitions de 5,56x45mm de l'OTAN.
- Moins d'optique, moins de composants inutiles – plus de place pour la visée de l'ancienne école.
