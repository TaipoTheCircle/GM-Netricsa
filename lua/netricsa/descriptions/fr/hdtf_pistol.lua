M9 PISTOL


ARME:      M9 Pistol
MUNITIONS:        Parabellum 9x19mm
CADENCE DE TIR:         Semi-automatique, ~15 rds/min efficace

DESCRIPTION:

Arme secondaire militaire et de maintien de l'ordre largement utilisée. Offre une bonne précision et un faible recul, ce qui le rend fiable pour des plans de suivi rapides. Servit comme arme de poing standard pour de nombreux soldats de l'U.E.C. dans le conflit de Black Mesa.

REMARQUES:

- Précis et facile à contrôler.
- Léger mais limité en puissance d'arrêt.
- Déclassé par les armes latérales de calibre lourd comme le .357 Magnum ou l'aigle du désert.