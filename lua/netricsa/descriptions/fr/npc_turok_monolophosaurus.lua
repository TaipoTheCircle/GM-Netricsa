MONOLOPHOSAURUS DE LA PLANTE TERRAFORME


CLASSE:      Monolophosaurus
MÉTABOLISME: Carnivore, Théropode
PERCEPTION: Prédateur ambuscade
TAILLE:       ~8,2 pi
ENDURANCE:  Haut
HOSTILITÉ:  Extrêmement élevé
ARMES:    Jaws, griffes, crête unique sur la tête
RÉCOMPENSE:     1000 FC
MENACE:     Haut

DESCRIPTION:

Le Monolophosaurus ressemble à une version plus petite du Dilophosaurus, mais avec une différence clé : au lieu de deux crêtes sur sa tête, il a une seule crête.

D'où le nom « lézard à tête unique ». Autrement, il est un prédateur typique de taille moyenne, maigre, rapide et, à en juger par ses relations familiales, plus avancé que le Dilophosaurus primitif.

CONSEILS:

- Il n'y a pas grand chose à recommander.
- Ne les laissez pas se rapprocher, les frapper avec des explosifs, ne les laissez pas vous tuer.
