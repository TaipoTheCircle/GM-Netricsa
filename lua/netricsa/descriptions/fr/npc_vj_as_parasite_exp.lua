PARASITE EXPLOSIVE "BETA"


CLASSE:      Parasite explosif "Beta"
MÉTABOLISME: Xénobiologique
PERCEPTION: Exemples d'agression
TAILLE:       3,2 ft
ENDURANCE:  Très faible
HOSTILITÉ:  Très élevé
ARMES:    Attaque de saut, Détonation biologique
RÉCOMPENSE:     70 FC
MENACE:     Moyenne-haute

DESCRIPTION:

Le Parasite Explosif "Beta" est une variante de parasite spécialisée, adaptée non pas pour infecter ses hôtes, mais pour détruire instantanément sa cible au prix de sa propre vie. Sa structure corporelle est pratiquement identique à celle d'un Swarm Parasite standard « Beta », mais son abdomen élargi ressemble au sac abdominal d'un Harvester et est rempli d'agents biologiques explosifs instables.

Ces créatures sont extrêmement agressives et se précipitent immédiatement vers la cible vivante la plus proche après leur apparition. En atteignant leur victime, le parasite fait un long saut et détone à l'impact, frappant l'ennemi avec une vague d'explosion et dispersant des fragments organiques corrosifs.

Les parasites explosifs apparaissent le plus souvent après la mort d'un Swarm Harvester "Beta", qui libère plusieurs de ces créatures à la fois. Grâce à leur petite taille et à leur vitesse élevée, ils peuvent rapidement surmonter les obstacles et constituer une menace grave dans les espaces restreints ou pendant le combat avec d'autres membres du Swarm.

Alors que chaque parasite ne dure que jusqu'à ce qu'il attaque, leur déploiement de masse permet au Swarm d'écraser les défenses ennemies, les forçant à constamment se concentrer sur des cibles qui approchent rapidement.

CONSEILS:

- Détruire les parasites de loin, les empêcher de se rapprocher.
- Après la mort de la moissonneuse, attendez-vous à ce que plusieurs parasites explosifs frayent immédiatement.
- Une seule explosion peut causer des dommages à plusieurs combattants.
- Les armes à forte intensité de feu ou les dommages à la zone sont les plus efficaces contre ces créatures.
