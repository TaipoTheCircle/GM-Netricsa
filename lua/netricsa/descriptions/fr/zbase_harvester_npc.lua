HARVESTISSEUR DE L'EAU


CLASSE:      Harvester de swarm
MÉTABOLISME: Xénobiologique
PERCEPTION: Spicimen de soutien
TAILLE:       8,2 pi
ENDURANCE:  Faible
HOSTILITÉ:  Haut
ARMES:    Xénomite Spawn, peau corrosive
RÉCOMPENSE:     500 FC
MENACE:     Haut

DESCRIPTION:

La Harvester est une forme spécialisée de Swarm, conçue pour reproduire rapidement des organismes de combat directement sur le champ de bataille. Contrairement à la plupart des membres du genre, il attaque rarement les ennemis directement, préférant créer des Xenomies et les déployer contre des cibles détectées.

La caractéristique la plus remarquable de la moissonneuse est un grand orgue brillant sur son dos. Les xénomites éclosent dedans, et peu après avoir mûri, ils quittent le corps de l'hôte. Leur reproduction rapide permet à un seul Harvester de créer un essaim entier de ces créatures en peu de temps.

Lorsqu'il est menacé, la moissonneuse tente d'augmenter la distance par rapport à l'ennemi, continuant à se reproduire même en se retirant. Cela rend la destruction d'un Harvester souvent plus difficile qu'il pourrait apparaître au départ.

Après la mort, l'organisme subit une brève libération post mortem, au cours de laquelle les xénoticks restants quittent le corps et commencent immédiatement à attaquer. Pour cette raison, détruire un Harvester ne signifie pas toujours la fin de la menace.

Malgré ses défenses relativement faibles, le tissu Harvester contient une grande quantité de substances corrosives. Le contact avec son corps peut causer de graves dommages même après la mort de la créature.

CONSEILS:

- Détruire les moissonneuses avant de créer un gros essaim.
- Ne les laissez pas se replier dans des zones sûres.
- Préparez les xénoticks à apparaître après la destruction de la cible.
- Si le Harvester a vécu assez longtemps, cela signifie que bientôt il devra faire face à plus d'un ennemi.
