MESA BLACK, AVANT L'INCIDENT


La téléportation se termine... mais pas là où vous vous attendiez. Pas de Xen ruiné, pas de séquelles. Au lieu de cela, vous vous tenez à Mesa Noire avant la catastrophe. Les laboratoires sont intacts, les scientifiques sont calmes, et tout sent le mauvais café et l'ozone.

Et encore une fois, ils t'ont trompé pour Freeman. Je me plaignais, mais apparemment, dans chaque chronologie, les gens adorent ce nom. Quelque part ailleurs dans cette installation étendue, un autre "Sam c'est vous mais pas vous" se prépare à activer le Spectromètre Anti-Mass. On sait tous les deux comment ça se passe.

Pendant ce temps, vous êtes entraîné dans un autre projet. Les chercheurs ici murmurent sur un test parallèle - un portail prototype, indépendant de l'expérience principale. Ils veulent que tu la surveilles pendant que le spectromètre s'amuse dans une autre aile.

Deux expériences. Deux catastrophes, en attente de collision. L'un est l'histoire. L'autre... va être écrit.

Du bon côté, ça veut dire que tu seras blâmé pour la moitié de l'apocalypse. Progrès !