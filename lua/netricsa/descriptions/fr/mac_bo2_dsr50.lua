DSR-50 RIVEAU DE LARGE-CALIBRE


ARME: DSR-50 Rifle de sniper en gros calibre
MUNITIONS:   12,7x99mm OTAN (50 BMG)
CADENCE DE TIR:    ~10-15 tours/min

DESCRIPTION:

Un fusil de sniper allemand à gros calibre développé par DSR-Precision GmbH sous la direction d'Ingolf Reuter en 2003. Il s'agit d'une version agrandie de la DSR-1, adaptée au feu de la puissante cartouche BMG .50. Sa configuration bullup permet une longueur hors tout relativement compacte tout en accueillant un long baril de 800mm.

Le fusil dispose d'un tampon de recul hydraulique dans le stock et d'un dispositif de muselière spécialisé - un "Blast Compensator" - qui fonctionne à la fois comme un frein de muselière et un suppresseur. Il est également équipé d'un stock réglable, d'un bipode, d'un monopode arrière (support sous le stock) et de montures pour visions optiques. Elle est alimentée par un magazine détachable de 3 tours.

REMARQUES:

- Fait feu à la puissante cartouche de calibre 50 BMG.
- Le dispositif de muselière aide à réduire le recul et le flash de muselière.
- Malgré sa conception bullup, il pèse environ 10,3 kg (déchargement).
- Le long baril assure une grande précision à de longues portées.
- Il tient trois tours par magazine; chaque tir commande vraiment le respect.
