DOUANE 45 W/ TMAR


ARME:    Shofield .45 avec TMAR
MUNITIONS:      45 Colt
CADENCE DE TIR:       action unique, rechargement manuel
MAGAZINE:  6 balles + TMAR 
POIDS:    2 livres, 5 oz
LENGTH:    12 3/4"

DESCRIPTION:

Replique du modèle original de cavalerie Shofield 1875, modifié pour une précision accrue. Une arme solide et fiable, mais normalement pas très efficace pour les situations de combat en raison de son faible taux de tir.
Celui-ci est équipé d'un petit Récupérateur de munitions techno-magiques (TMAR) capturé des forces de Mental, pour fournir une quantité infinie de munitions. Utile comme défense de dernier ressort et pour l'élimination des ennemis les plus faibles à long terme.

REMARQUES:

- Peut être utilisé en combinaison avec le système de détection des cibles de NETRICSA pour une prise de vue à longue portée précise.