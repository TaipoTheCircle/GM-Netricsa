STROGG SENTRY FROM STROGGOS


CLASSE:      Strogg Sentry
MÉTABOLISME: Organisme cybernétique, symbiose
PERCEPTION: gunner volant de garde
TAILLE:       ~5 pi
ENDURANCE:  Faible
HOSTILITÉ:  Moyenne
ARMES:    Deux mitrailleuses de haute précision
RÉCOMPENSE:     150 FC
MENACE:     Moyenne

DESCRIPTION:

Le Strogg est un Strogg volant spécialisé conçu pour protéger des zones clés comme le Nexus et les tunnels Hub. Il s'agit d'un corps ovale sans jambes qui plane dans l'air, avec une paire de mitrailleuses à la place des bras et un récipient de liquide vert sous lequel se trouve un symbiote humanoïde. Ces ennemis sont des difficultés moyennes, apparaissant en groupes de 2-4. Leur principale force réside dans leur taux de feu, leur précision et leur capacité à éviter rapidement les projectiles qui se déplacent lentement. Malgré leurs faibles dommages individuels, leur barrage constant peut rapidement épuiser votre santé et votre armure, vous distrayant des ennemis plus dangereux.

CONSEILS:

- Concentrez-vous sur le conteneur vert ci-dessous - attaques contre elle infligent deux dommages.
- Utilisez une mitrailleuse ou un fusil à portée de main. Le canon Lightning est idéal.
- Couvrez-vous pendant leurs rafales, attaquant pendant les pauses. Lorsque vous apparaissez dans un groupe, éliminez d'abord les Sentinelles pour éviter les distractions.
- Ils ne poursuivent pas par les portes - vous pouvez reculer pour se regrouper.