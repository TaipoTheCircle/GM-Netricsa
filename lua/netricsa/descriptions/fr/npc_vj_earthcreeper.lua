CREEPER DE LA TERRE DU MINECRAFT


CLASSE:      Crise de la Terre
MÉTABOLISME: Terres inorganiques
PERCEPTION: Hostile
TAILLE:       5,5 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Haut
ARMES:    Blast terrestre
RÉCOMPENSE:     60 FC
MENACE:     Moyenne

DESCRIPTION:

Ce type rampant résout le problème des explosions un peu différemment. Son corps est brun, et sa tête ressemble à un bloc de terre avec une pointe verte, lui permettant de se fondre dans le paysage et se faufiler sur les ennemis non détectés.

Au lieu de détruire tout ce qui l'entoure ou de causer des dommages, le Crise crée un tas chaotique de blocs de terre lorsqu'il explose. Cette explosion ne nuit pas à votre santé, mais ses effets peuvent être dévastateurs pour votre terrain et vos bâtiments. Il est souvent décrit comme "inutile" (relativement parlant) au combat, mais très ennuyeux en raison de la façon dont il transforme une pelouse soignée en un tas de terre aléatoire dispersée.

CONSEILS:

- Ce flippant ne nuit pas à votre santé, mais il représente une menace sérieuse pour votre base et vos bâtiments.
- Ne la laissez jamais exploser près de chez vous à moins de vouloir l'enterrer sous la Terre. Il vaut mieux le tuer à distance.
- Il est facilement reconnaissable par son corps brun et sa tête verte, qui se mélange avec l'herbe.
- À la mort, vous pouvez piller de la saleté ordinaire.
- Les rampants tamés peuvent être utiles en tant que défenseurs, mais le Crise de la Terre laisse encore un désordre même après avoir été apprivoisé.
