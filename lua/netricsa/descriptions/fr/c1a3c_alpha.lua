COMPLEXE DE SÉCURITÉ NOIR MESA, CHAMBRE DE CONTRÔLE


Sam, on est arrivés. Le centre informatique est derrière nous, les calamars sont encore dans leur flaque, et devant nous est la salle de contrôle.

Une petite pièce remplie de consoles, d'écrans clignotants et d'un seul levier, qui, à en juger par tout, est notre salut.

Il suffit d'activer l'entrée du bunker et de rentrer.
