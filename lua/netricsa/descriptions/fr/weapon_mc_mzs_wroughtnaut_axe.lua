AXE DES MÉTAUX


ARME: Axe de mille métaux
CADENCE DE TIR:    ~0,9 hits/seconde
POIDS: 9,5 kg

DESCRIPTION:

Une arme massive forgée à partir d'alliages de métaux multiples, possédant une force et une lourdeur exceptionnelles. Il combine puissance mortelle et résistance à la destruction : la hache ne rompt jamais au combat et reste efficace même avec une utilisation constante.

Au combat, l'arme propose plusieurs types d'attaques : des coupures standard, de larges balançoires pour des attaques de groupe, et de puissantes frappes verticales au sol, créant une onde de choc qui se propage à travers le sol et impacte les ennemis à distance, les faisant voler. La portée de l'onde de choc dépend de la distance par rapport à la cible.

REMARQUES:

- Efficace contre des cibles et des groupes à moyenne portée.
- Une large balançoire endommage toutes les cibles dans un cône devant l'utilisateur.
- Un clam vertical au sol crée une onde de choc, repoussant et endommageant les cibles derrière.
- L'indestructibilité absolue en fait un outil fiable pour des affrontements prolongés.