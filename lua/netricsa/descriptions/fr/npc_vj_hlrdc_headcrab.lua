LE CŒUR DRAMATIQUE DE XEN


CLASSE:      Gratte-tête, Dreamcast
MÉTABOLISME: xénofaune parasite
PERCEPTION: Armes biologiques
TAILLE:       ~1-2 pi
ENDURANCE:  moyenne individuellement
HOSTILITÉ:  haut (sur fixation)
ARMES:    morsure, fixation parasitaire permanente
RÉCOMPENSE:     150 FC
MENACE:     modéré individuellement, élevé en groupes

DESCRIPTION:

Common Headcrabs sont les parasites Xen classiques connus pour s'attacher en permanence à la tête d'un hôte. Contrairement à la variante de la Terre, qui peut sauter et errer indépendamment, le cramoisi commun s'enfonce dans le crâne et reste lié à vie (ou jusqu'à ce qu'il soit tué), transformant l'hôte en un cramoisi commun Zombie ou un cramoisi runner Zombie, qui finit par évoluer en un gonome.

The fusion is horrifying: le crâne de l'hôte est visible sous la carapace extraterrestre, et le contrôle de la créature est absolu. Une fois attaché, le crâne dicte le mouvement, l'agression et le comportement, faisant de l'hôte un prédateur lent et implacable.

CONSEILS:

- Évitez d'être mordu - une fois attaché, le retrait est presque impossible sans tuer l'hôte.
- Les armes à feu ou les explosifs sont efficaces contre l'hôte et le parasite simultanément.
- Gardez un œil sur les groupes; les essaims de tête commune peuvent rapidement envahir les intrus.