IL N'Y A QUE DES MILLIERS DE PERSONNES, QUI SE RENDENT PARTOUT


Sam, nous sommes arrivés à un endroit qui semble être sorti d'une carte postale qu'ils ont oublié d'envoyer. Des collines vertes, de l'air pur, une route qui s'étend à l'horizon... et pas une âme. Juste le vent, l'herbe, et le sentiment que le monde avait simplement été éteint sans avertir les résidents.

Imaginez des champs verts sans fin, fusionnant doucement en collines basses. Et l'artère principale de cet endroit est la route. Il souffle entre les collines, monte les collines, plonge dans les basses terres, et... tout simplement se termine. Il ne frappe pas un mur, ne mène pas à une porte, mais disparaît dans l'herbe, comme si quelqu'un l'avait dessiné et oublié de le terminer.

Qu'y a-t-il ici 

Les collines sont une excellente couverture naturelle et des positions d'embuscade.

La route est le point de repère parfait. Si vous êtes perdu, suivez-le. Il ne mènera nulle part, mais il vous donnera l'illusion d'une destination.

Le silence ici n'est pas naturel. Même le vent rougit comme si on avait peur de réveiller les collines. Garde les yeux ouverts, Sam. Si quelqu'un arrive dans un endroit aussi désert, c'est soit un fantôme, soit une très mauvaise nouvelle. Ou peut-être juste un harceleur local qui aime aussi la paix et le calme. Mais il y a peu d'espoir pour un harceleur.

Allons voir où mène cette route.

Spoiler: nulle part.
