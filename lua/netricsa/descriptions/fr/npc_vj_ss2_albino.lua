ALBINO CYCLOPS DE MAGNOR


CLASSE:      Cyclopes Albino
MÉTABOLISME: Carnivores
PERCEPTION: Mutant semblable à un ver
TAILLE:       ~22 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Orbe d'énergie d'hommage, smack main
RÉCOMPENSE:     800 FC
MENACE:     Haut

DESCRIPTION:

A l'origine des vers géants de la planète Magnor, les Cyclopes d'Albino ont été terriblement transformés par des bras et des jambes mentales dans une expérience génétique tordue. Leurs corps n'ont pas tout à fait reçu le mémo, donc ils restent horriblement grands et étrangement proportionnés. Ils frappent la peur dans le cœur même des plus courageux avec deux attaques de signature:

Orb blast: Incendie une sphère d'énergie qui se verrouille sur les joueurs - manœuvres évasives sont essentielles.

Arm smash: Si tu es assez bête pour t'approcher, prépare-toi à te faire prendre avec une force caverneuse.

CONSEILS:

- Ce sont des cibles faciles pour les lance-roquettes et les lance-grenades.
- Utilisez des armes comme les Clawdovic, des roquettes ou des armes lourdes pour les démonter rapidement.
- Un tir parfait du SBC Cannon peut effacer un coup de chance.