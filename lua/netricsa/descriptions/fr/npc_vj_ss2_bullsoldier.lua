SOLDAT-TAUREAU


CLASSE : Soldat taureau
MÉTABOLISME : Mammifère
PERCEPTION : Soldat entraîné
TAILLE : 12 pieds
ENDURANCE : Moyenne
HOSTILITÉ : Moyenne
ARMES : lanceurs de roquettes doubles
RÉCOMPENSE : 200 FC
MENACE : Moyenne

DESCRIPTIF :

Ce sont des hybrides grands et musclés de bovins siriens et d'humanoïdes. Ils dominent la plupart des autres soldats et peuvent résister à de nombreux coups avant de s'effondrer.

Leurs jambes ne font pas réellement partie de leur propre corps, mais ce sont les jambes d'artistes martiaux (après qu'elles ont été coupées) qui leur ont été cousues.

Ils se sont révélés très efficaces au combat et les commandants mentaux ont commencé à les utiliser plus fréquemment.

Ils peuvent souvent être vus à l’arrière ou au sommet de grandes structures, tirant sur les ennemis de loin. Cependant, ne vous attendez pas à ce qu’ils évitent les combats rapprochés.

CONSEILS :

- Vous pouvez abattre leurs missiles.
- Essayez de ne pas vous laisser frapper au visage par leurs missiles, ce serait très douloureux.