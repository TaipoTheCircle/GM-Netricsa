HARPOONE


ARMES: Harpon
MUNITIONS:    Aucune
CADENCE DE TIR:     ~1 lancer action/seconde
POIDS:  3,5 kg

DESCRIPTION:

Le harpon est une longue arme de melee utilisée pour attaquer des cibles à portée proche de moyenne. C'est une tige de fer durable avec une pointe aiguisée, conçue pour percer des matériaux denses et créer un effet étonnant sur l'impact.

Lorsqu'il est lancé, le harpon perce la cible et s'enrôle fermement dans la surface, verrouillant l'ennemi en place. Il est efficace contre les adversaires uniques et peut les immobiliser.

REMARQUES:

- Peut être utilisé comme arme improvisée en l'absence d'armes à feu.
- Au moment de l'impact, il immobilise fermement la cible, rendant plus difficile la résistance.
- Peut être combiné avec d'autres armes pour le combat rapproché.