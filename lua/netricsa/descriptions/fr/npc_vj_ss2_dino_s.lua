VULGARIS VÉLOCIRAPTEUR DU M'DIGBO


CLASSE:      Velociraptor Vulgaris
MÉTABOLISME: Reptile
PERCEPTION: Compagnon Mont / Combat
TAILLE:       5 pieds
ENDURANCE:  Très faible
HOSTILITÉ:  Varie avec Rider
ARMES:    Boules de feu
RÉCOMPENSE:     200 FC
MENACE:     Haut

DESCRIPTION:

Ce lézard extraterrestre vert semble avoir été sorti directement du film Jurassic Park de 1993 sans plumes. Il vit sur la planète M'Digbo et, contrairement à ses frères terrestres, peut respirer le feu.

L'apparence du Velociraptor ressemble à une culture pop classique dromaeosauride : des écailles vertes, des griffes pointues, une longue queue et une bouche pleine de petites dents. Pas de plumes, pas de pack d'intelligence, juste une fureur pure, sans adultère, attelée et dirigée contre les ennemis de Mental.

Au combat, le Velociraptor est indispensable. Il court vite, évite les attaques ennemies, et tire des boules de feu de sa bouche. Une telle boule de feu tue un ennemi faible en un seul coup, et plus fort après quelques secondes de feu continu. Le principal problème est sa santé. Le Velociraptor est aussi fragile que le verre. Quelques coups et le lézard est parti.

CONSEILS:

- En roulant, gardez vos distances et tirez des volleys de boules de feu contre les ennemis.
- Sa santé est faible. Si vous voyez quelqu'un vous tirer dessus, dodge. Un coup peut envoyer un lézard dans l'autre monde.
- N'essayez pas de tuer les ennemis de près avec un lézard-il va mourir plus vite que vous pouvez infliger des dommages.
