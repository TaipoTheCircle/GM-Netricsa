CREEPER CHARGÉ DE L'EXERCICE MINECRAFT


CLASSE:      Accusé
MÉTABOLISME: Électromagnétique-Plante-Chemique
PERCEPTION: Une version améliorée de la norme Creeper
TAILLE:       5,5 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrême
ARMES:    Blast électrique plus grand
RÉCOMPENSE:     700 FC
MENACE:     Moyenne-haute

DESCRIPTION:

Le Creeper chargé est le même personnage vert que le Creeper standard, seul son corps est maintenant rempli d'énergie électrique débridée.

Il explose avec plus de force que la normale, endommageant tous les blocs et les foules dans un rayon.

Les Cris chargés sont créés par des éclairs.

CONSEILS:

- Le rayon d'avarie et la défense sont deux fois plus élevés que le crieur standard.
