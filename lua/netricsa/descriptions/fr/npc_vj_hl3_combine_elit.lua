SURVEILLANCE DES COMBINES


CLASSE:      Combiner Overwatch Elite Arctic Guard
MÉTABOLISME: Humain augmenté, Homme
PERCEPTION: Unité d ' infanterie, de sécurité et d ' assaut transhumains
TAILLE:       5,9 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    AR2 V2 fusil à impulsions, boules d'énergie
RÉCOMPENSE:     900 FC
MENACE:     Très élevé

DESCRIPTION:

La Overwatch Combine Elite Arctic Guard est une variante spécialisée d'infanterie d'élite conçue pour protéger les biens stratégiques, le personnel clé et les zones critiques dans les climats extrêmes. Contrairement aux Commandos, les gardes sont moins susceptibles de se livrer à des progrès rapides, mais ils sont presque aussi efficaces au combat.

Ils sont facilement reconnaissables par leur armure blanche éblouissante et leur visière rouge unique. Un manteau est facultatif : certains Gardiens le portent sur leurs épaules comme signe de statut ou d'affiliation avec une unité spécifique, tandis que d'autres l'abandonnent entièrement pour une plus grande mobilité et une visibilité réduite dans les vents forts et les tempêtes de neige.

Comme les autres soldats d'élite Overwatch, leur armure est équipée d'un système de survie intégré. Un respirateur est relié à un tube épais qui traverse l'épaule gauche et à un sac à dos à oxygène sur le dos portant le logo Combine. Le système assure une respiration stable, filtre les toxines et protège les gardes contre les températures extrêmes, leur permettant de maintenir des positions dans les zones arctiques pendant des heures sans support externe.

CONSEILS:

- L'absence d'un manteau n'indique pas un grade inférieur ou une menace.
- Ils opèrent presque toujours par paires ou dans le cadre d'une équipe de sécurité.
