FEUILLE DU MINECRAFT


CLASSE:      Ovins
MÉTABOLISME: Mammifère chaud
PERCEPTION: Domestique / Sauvage
TAILLE:       3 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Faible
ARMES:    Aucune
RÉCOMPENSE:     40 FC
MENACE:     Faible

DESCRIPTION:

Les moutons sont des herbivores paisibles qui paissent les plaines, les forêts et les montagnes de Minecraft. Ils viennent dans une variété de couleurs de laine (blanc, noir, gris, gris clair, brun, rose), leur permettant de produire une variété de laine teinte.

Les moutons peuvent être ciseaux pour obtenir de la laine, et ils peuvent être élevés avec du blé. Après le cisaillement, la laine repousse progressivement.

Les moutons errent en groupes et paissent lentement, ce qui en fait des cibles faciles pour la récolte des ressources.

CONSEILS:

Au lieu de les tuer, leur laine peut être régénérée.
- L'agneau est une bonne source de nourriture.
- La laine peut être utilisée pour construire un lit et fournir un repos du travail dur.
