TOR, LE COMMANDANT XEN


CLASSE:      Tor, le commandant Xen
MÉTABOLISME: inconnu
PERCEPTION: Elite Overlord de Xen
TAILLE:       9-10 pieds
ENDURANCE:  élevé
HOSTILITÉ:  extrême
ARMES:    personnel (explosion sonore, lévitation), convocations Alien Grunts
RÉCOMPENSE:     500 FC
MENACE:     épique

DESCRIPTION:

Tor, le commandant Xen, est l'exécuteur de droite du Nihilanth, avec un pouvoir énorme et une intelligence stratégique. Il porte un personnel d'énergie capable de déclencher des explosions sonores dévastatrices et de léviter les ennemis pour les dommages de suivi. En outre, Tor peut convoquer Alien Grunts sur le champ de bataille, renforçant sa présence et des intrus accablants. Son approche est annoncée par des grognements profonds et des sons inquiétants, signalant un danger imminent. Tor est un lieutenant clé dans la hiérarchie des Xen, qui commande respect et peur de toutes les créatures de son domaine.

CONSEILS:

- Concentrez le feu sur les Grunts pour réduire la pression sur le champ de bataille.
- Utilisez des armes à feu pour interrompre ses attaques.
- Restez mobile pour éviter ses puissantes capacités sonores et lévitation.
