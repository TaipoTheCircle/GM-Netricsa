PISTOLET M1911


ARME : M1911 Pistol
MUNITIONS : .45 ACP
ROF : Semi-automatic, ~60 rounds / minute
POIDS : ~1,1 kg

DESCRIPTION :

Ce pistolet semi-automatique américain chambré pour la cartouche .45 ACP se caractérise par sa conception simple, sa grande fiabilité et son pouvoir d'arrêt important. Conçu par John Browning et adopté par l'armée américaine en 1911.

Le pistolet utilise un chargeur à 7 cartouches et fonctionne sur le principe d'un mécanisme à verrou verrouillé à recul court. Grâce à son gros calibre, le M1911 est capable d'engager efficacement des cibles à courte et moyenne portée.

REMARQUES :

- Chargeur 7 coups.
- Pouvoir d'arrêt élevé de la cartouche .45 ACP.
- Bonne précision à courte et moyenne portée.
- Conception simple et fiable.
- Efficace principalement à courte et moyenne portée.
- La petite capacité du chargeur nécessite un rechargement rapide.
- Le mécanisme semi-automatique permet des prises de vue rapides.