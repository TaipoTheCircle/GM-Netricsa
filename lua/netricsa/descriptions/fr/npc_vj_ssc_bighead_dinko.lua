GRANDE CHAMBRE, DINKO PAVICIQUE


CLASSE:       Grande tête, Dinko Pavicic
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:        5,9 pieds
ENDURANCE:     Faible
HOSTILITÉ:   Neutre
ARMES:     Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:      100 FC
MENACE:      Annoyance

DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan" ils gagnent le feu et les modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Dinko Pavicic est l'un des piliers du style visuel de Croteam. Son crâne exagéré est le résultat direct de sa combinaison unique de génie artistique et de pensée stratégique. Commençant en tant qu'artiste 2D sur les premiers jeux Serious Sam, Dinko a aidé à façonner les visuels frappants et reconnaissables de la franchise à ses débuts.

Cependant, son talent s'étendait bien au-delà de l'industrie du jeu. En 2006, il s'est vu décerner un Emmy Award pour l'exceptionnel Titre Sequence Design aux 78ème Academy Awards, confirmant ainsi son statut de maître de classe mondiale en design visuel. Cette expérience unique - de la création d'un pixel art pour un tireur emblématique à travailler sur un événement majeur Hollywood - fait de lui l'un des esprits les plus polyvalents et influents dans le panthéon de Krotimovtsy.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager le chemin.
- Sur la difficulté "Je suis Ugh-Zan", les éliminer à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.