PISTOLET LEBEDEVA PL-14


ARME : Pistolet Lebedev PL-14
MUNITIONS : Parabellum 9x19 mm
ROF : ~40-50 tours/min
POIDS : ~0,8kg

DESCRIPTIF :

Ce pistolet semi-automatique russe a été développé par l'équipe de Dmitri Lebedev au sein de l'entreprise Kalachnikov. Il a été présenté pour la première fois en 2015 lors du forum Army-2015 comme un pistolet prometteur pour les forces armées et les forces de l'ordre. La conception a ensuite été révisée et désignée PL-15.

Le PL-14 utilise la cartouche Parabellum 9x19 mm et un chargeur de 15 coups. Le pistolet a été conçu avec une attention méticuleuse à l'ergonomie : la poignée est de forme confortable, les commandes sont conçues pour une utilisation ambidextre et la ligne de canon basse est conçue pour aider à ramener rapidement l'arme sur la ligne de visée après le tir.

D'une longueur d'environ 220 mm et pesant environ 800 grammes, le PL-14 est un pistolet de service assez grand mais relativement léger. Cette conception est devenue plus tard la base des PL-15, PL-15K et d'autres variantes.

REMARQUES :

- La ligne de canon basse et la poignée ergonomique sont conçues pour un tir confortable et rapide.
- Les commandes sont conçues pour être utilisées avec la main droite ou gauche.
- Le PL-14 est devenu le prédécesseur de la famille moderne des pistolets Lebedev.