LEBEDEVA PL-14 PISTOL


ARME: Lebedev PL-14 Pistol
MUNITIONS:   Parabellum 9x19mm
CADENCE DE TIR:    ~40-50 tours/min
POIDS: ~0,8 kg

DESCRIPTION:

Ce pistolet semi-automatique russe a été développé par l'équipe de Dmitry Lebedev à Kalachnikov. Il a été présenté pour la première fois en 2015 au forum Army-2015 comme un pistolet prometteur pour les forces armées et les forces de l'ordre. La conception a ensuite été révisée et a désigné la PL-15.

Le PL-14 utilise la cartouche 9x19mm Parabellum et un magazine de 15 tours. Le pistolet a été conçu avec une attention méticuleuse à l'ergonomie: la poignée est confortablement façonnée, les commandes sont conçues pour une utilisation ambidextre, et la ligne basse baril est conçue pour aider à ramener rapidement l'arme à la ligne de visée après le tir.

À environ 220 mm de longueur et pesant environ 800 grammes, le PL-14 est un pistolet de service assez grand mais relativement léger. Cette conception est devenue la base des PL-15, PL-15K et d'autres variantes.

REMARQUES:

- La ligne basse et la poignée ergonomique sont conçues pour un tir rapide et confortable.
- Les commandes sont conçues pour être utilisées à droite ou à gauche.
- Le PL-14 est devenu le prédécesseur de la famille moderne de pistolets Lebedev.
