GRANDE TÊTE, GEINBEERG


CLASSE:      Grosse tête, Geinbeerg
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     300 FC
MENACE:     Annoyance

DESCRIPTION:

Les grosses têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs. Ils portent l'uniforme du Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan" ils gagnent le feu et les modificateurs de glace. Ils apparaissent spontanément dans des zones secrètes, bloquant les passages avec leur nombre.

Geinbeerg est un spécimen unique, dont le cerveau est hypertrophié non par le codage, mais en explorant les anomalies numériques. Il n'est pas affilié à Croteam, mais il est une partie importante de l'écosystème de la communauté GMod. Sa spécialité est de prendre des captures d'écran impressionnantes.

Sa plus grande réussite a été de créer des captures d'écran des cartes maudites zéro zéro pour le projet "GM-Netricsa" de Taipo. Alors que d'autres craignaient même de charger des cartes comme city.bsp ou xmasxmas.bsp, Geinbeerg les entra hardiment, prit des images documentaires et survécut (sans même s'en rendre compte). Il devint un sauveur involontaire pour Taipo, terrifié par les horreurs de l'ARG. Geinbeerg ne soupçonne même pas que son courage ait sauvé son collègue des attaques de panique.

J'ai rencontré Taipo sur le canal de Te4m Telegram, où je parlais d'une histoire de piège qui, au lieu du modèle promis, cachait le NPC Interloper du GMod ARG.

CONSEILS:

- Utilisez un couteau ou un pistolet pour dégager la voie.
- Sur la difficulté "Je suis Ugh-Zan", les détruire à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.