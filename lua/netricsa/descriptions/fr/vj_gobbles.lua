GOBBLES LEARNOSAUR


CLASSE:      Gobbles Learnosaur
MÉTABOLISME: Dinosaure, Apprendre
PERCEPTION: Membre de l'équipe de soutien
TAILLE:       5,6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Aucune
ARMES:    Attache, connaissance, courage entraîné
RÉCOMPENSE:     120 FC
MENACE:     Haut

DESCRIPTION:

C'est un dinosaure violet aux yeux roses, un ventre blanc et des assiettes rose clairsemées sur le dos. Il porte une cravate bleue avec un "G" blanc au milieu. Il provient du jeu éducatif préscolaire "Gobbles & the Learnosaurs", où il était le personnage principal.

Dans son monde d'origine, Gobbles et son ami Stegosaurus se sont aventurés dans la grotte du méchant Cromugn pour récupérer les consonnes volées. Ils ont réussi, mais la victoire du héros a conduit à la destruction du monde. Cromugn a été dévoré par un pilier de feu, Stegosaurus a été écrasé (coupé en deux), et Gobbles a été sauvé au dernier moment par Kit et Kaboodle, qui l'a recruté à l'équipe "Support".

Gobbles est un dinosaure nerveux, timide et non préparé qui panique constamment. Kaboodle le considère comme un fardeau et suggère de le laisser à son destin, mais Kit est gentil avec lui, lui offrant du jus et le rassurant constamment. Gobbles essaie de prouver son utilité, mais c'est difficile. Cependant, derrière cette lâche façade se trouve une personnalité sensible capable de courage.

Gobbles est un dinosaure prêt à tout apprendre sous le soleil. Il a enseigné aux Flapeurs à lire et à écrire, et il a lui-même appris le courage du monde autour de lui et de ses héros.

CONSEILS:

- Gobbles n'est pas un combattant. Sa force réside dans sa capacité à remarquer les détails et à prendre soin de ses amis.
