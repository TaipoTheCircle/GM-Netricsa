DOG


CLASSE:      Chien
MÉTABOLISME: Mécanique 
PERCEPTION: Machine de guerre de résistance
TAILLE:       ~8-10 pieds
ENDURANCE:  Très élevé 
HOSTILITÉ:  Faible
ARMES:    Strength, Scrap Projectiles, Armes Improvisées
RÉCOMPENSE:     1000 FC
MENACE:     Haut

DESCRIPTION:

Le chien est un robot massif et loyal construit par Eli Vance et continuellement amélioré par sa fille Alyx. Conçu à l'origine comme un « animal » mécanique et un garde du corps, Dog est devenu une puissance imposante de force et de résilience. Malgré son cadre intimidant, il partage une personnalité ludique, presque enfantine, il aime les jeux de récupération, se baladant facilement autour d'objets énormes.

Au combat, cependant, le chien se transforme en une machine d'épave : se déchirer Combiner les forces, jeter des voitures comme des projectiles, ou se briser à travers des barrières fortifiées. Son mélange unique de force brute et de précision mécanique le rend indispensable à la Résistance.

La loyauté du chien envers Alyx est absolue. Il la protège à tout prix, se chargeant souvent dans des situations impossibles avec un élan inarrêtable.

CONSEILS:

- Chien peut soulever et jeter des objets plus lourds que n'importe quel humain utiliser sa force pour effacer les chemins.
- Résistant au feu de la plupart des armes; mieux vaut le laisser tirer le feu ennemi.
- Quand Dog va sur une rampe, reste clair ami ou ennemi, son élan peut écraser n'importe quoi sur son chemin.
