ARCHER DE XEN


CLASSE:      Archer
MÉTABOLISME: Carnivore amphibie étranger
PERCEPTION: Prédateur sous-marin Alien
TAILLE:       ~4 pieds de long
ENDURANCE:  Moyenne
HOSTILITÉ: Haut
ARMES:    Cracher acide (rangé), morsure aiguë (mélé)
RÉCOMPENSE:     300 FC
MENACE:     Modéré

DESCRIPTION:

L'Archer est un prédateur aquatique de couleur rouge de Xen. Il se cache dans les piscines et les passages inondés, embusquant des proies avec des éclats de crachat acide. Si on s'approche de trop près, il s'empare de mâchoires pointues. Les archers sont agressifs, territoriaux et vont souvent attaquer à vue, crachant des volley avant de se refermer pour le meurtre.

CONSEILS:

- Gardez la distance et déplacez-vous de façon imprévisible pour éviter de cracher.
- Mieux vaut utiliser des explosifs ou un feu rapide tout en restant hors de l'eau.
- Dangereux en groupes - les isoler si possible.
