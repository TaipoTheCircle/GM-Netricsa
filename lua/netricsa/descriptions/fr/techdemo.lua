CENTRE DE TECHNOLOGIE DU MESA BLACK, CORRIDEUR DE MALADIE SCIENTIFIQUE


Sam, nous sommes dans un endroit qui, même selon les normes de Black Mesa, semble étrange. Un long couloir. Avec une courbe. Et les portes. Beaucoup de portes. Derrière chacun, un laboratoire. Petit, mais chacun avec son propre thème. Sa propre obsession. Sa petite catastrophe, qui attend d'être déclenchée.

Nous descendons le couloir. Une porte à gauche. Une porte à droite. À la fin, un virage, et au-delà, plus de portes. Pas de fenêtres. Pas de panneaux, sauf les plaques sur les portes elles-mêmes. Black Mesa a étudié ici tout ce qui ne correspondait pas à d'autres secteurs. Tout ce qui semblait trop inutile pour le budget de base, mais trop intéressant à jeter.

Qu'y a-t-il derrière les portes ?

Lumière colorée. Un laboratoire où ils ont étudié les effets de différentes longueurs d'onde sur la psyché. Les résultats sont probablement dans des coffres quelque part. Ou sur les murs - sous la forme de taches laissées par ceux qui regardaient trop longtemps.

Des échantillons droïdes. Unités de test robot. Certains sont vides. Certains sont alimentés.

Transparence. Recherche sur les matériaux qui laissent passer la lumière mais pas les balles. Ou vice versa. Ou ne laisser passer que la peur.

Panthérai. Une créature vivante a été découverte dans l'une des pièces. Pas un spécimen. Pas une exposition. Juste un panthérai. D'où ça vient ? Pourquoi a-t-elle été amenée ici ? Pourquoi est-il encore là ? Il y a plus de questions que de réponses. La réponse est simple : n'y entrez pas sans armes.

PolyRobot Zentraedi. Module tactique de combat. Créé ici. Testé ici. Probablement considéré comme un succès. Ou pas. Mais le module est quelque part, derrière une des portes. Attendez. Regarde. Écouter. Et danser...

N'ouvrez pas toutes les portes. Si le signe semble menaçant, il l'est probablement. Si le panneau est inoffensif, c'est probablement un piège.
