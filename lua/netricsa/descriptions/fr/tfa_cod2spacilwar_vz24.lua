MAUSER VZ. 24 RIFLE


ARME: Mauser Vz. 24 fusil
MUNITIONS:   7.92x57mm Mauser
CADENCE DE TIR:    ~15-20 tours/min
POIDS: ~4,08 kg

DESCRIPTION:

Un fusil de la Tchécoslovaquie, développé en 1924 sur la base du modèle allemand Mauser 98. Il a été produit dans les usines d'armes tchécoslovaques de 1924 à 1944 et est devenu l'un des plus célèbres fusils tchécoslovaques de l'entre-deux-guerres.

Le fusil utilise un boulon rotatif coulissant longitudinalement et un chargeur de 5 tours. La version standard a été en chambre pour 7.92x57mm Mauser, bien que les versions d'exportation en chambre pour d'autres cartouches existaient également. Avec une longueur de 1100 mm, le Vz. Le Vz. 24 était un peu plus court et plus pratique que le Mauser 98 classique.

Le Vz. 24 a été largement exporté et a vu le service dans une variété de conflits. Ces fusils ont été utilisés, entre autres, pendant la guerre civile espagnole et la Seconde Guerre mondiale. Après avoir occupé la Tchécoslovaquie, les troupes allemandes ont adopté le Vz. 24 sous la désignation Gewehr 24(t).

REMARQUES:

- Un fusil fiable et précis, bien adapté pour les gammes moyennes et longues.
- Une réponse tchécoslovaque à la famille Mauser, mais dans un design plus compact.
- Après avoir occupé la Tchécoslovaquie, l'armée allemande a simplement rebaptisé le Vz. 24 le Gewehr 24(t) et l'a renvoyé en service.
