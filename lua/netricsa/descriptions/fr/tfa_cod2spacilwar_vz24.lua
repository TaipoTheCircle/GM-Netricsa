MAUSER VZ. FUSIL 24


ARME : Mauser Vz. 24 fusil
MUNITIONS : Mauser 7,92x57mm
ROF : ~15-20 tours/min
POIDS : ~4,08 kg

DESCRIPTIF :

Un fusil tchécoslovaque alimenté par chargeur, développé en 1924 sur la base du modèle allemand Mauser 98. Il a été produit dans les usines d'armement tchécoslovaques de 1924 à 1944 et est devenu l'un des fusils tchécoslovaques les plus célèbres de l'entre-deux-guerres.

Le fusil utilise un boulon rotatif coulissant longitudinalement et un chargeur à 5 cartouches. La version standard était chambrée pour Mauser 7,92 x 57 mm, bien que des versions d'exportation chambrées pour d'autres cartouches existaient également. D'une longueur de 1100 mm, le Vz. Le Vz. 24 était un peu plus court et plus pratique que le Mauser 98 classique.

Le Vz. Le 24 a été largement exporté et a servi dans divers conflits. Ces fusils ont été utilisés, entre autres, pendant la guerre civile espagnole et la Seconde Guerre mondiale. Après avoir occupé la Tchécoslovaquie, les troupes allemandes adoptèrent le Vz. 24 sous la désignation Gewehr 24(t).

REMARQUES :

- Une carabine fiable et précise, bien adaptée aux moyennes et longues portées.
- A Czechoslovakian answer to the Mauser family, but in a more compact design.
- Après avoir occupé la Tchécoslovaquie, l'armée allemande a simplement rebaptisé Vz. 24 Gewehr 24(t) et l'a remis en service.
