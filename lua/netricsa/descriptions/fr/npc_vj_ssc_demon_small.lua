DÉMON, TINY, RÉPÉTILIDE DEFENSE


CLASSE:      Démon réptiloïde de Fiendian, minuscule
MÉTABOLISME: sang-froid, comme un reptile
PERCEPTION: race primitive modifiée
TAILLE:       0,4 pi
ENDURANCE:  moyenne
HOSTILITÉ:  élevé
ARMES:    projectile de lavanball, griffes
RÉCOMPENSE:     5000 FC
MENACE:     moyenne

DESCRIPTION:

Une autre mutation hideuse, grâce à Notorius Mental. Un simple organisme semblable à un lézard de Fiendia Prime a été croisé et muté pendant plusieurs générations, et a finalement été renforcé avec un squelette de titane. Il a une capacité unique de former un trou noir miniature à travers lequel il peut invoquer des boules flottantes de lave fondue dans l'existence. Des forces magiques faibles maintiendront ce projectile ardent cohérent pour une courte période de temps. Comme il vole dans l'air, il se refroidira et explosera finalement.

Au cours d'expériences avec la réduction des créatures, ce micro-reptilien a conservé toutes les capacités dangereuses de son prototype géant, y compris la création de trous noirs miniatures et de gouttières de lave fondue. Son squelette en titane est devenu une micro-armure pratiquement indestructible. Étant si minuscule, il est pratiquement invisible dans la grande herbe, les crevasses et les débris. Il peut être tué en marchant littéralement dessus, mais sa taille même le rend mortel.

CONSEILS:

- Les projectiles sont indestructibles, alors évitez-les jusqu'à ce qu'ils explosent.
- Monte dessus et il mourra.