ICHTHYOSAUR DE XEN


CLASSE:      Ichthyosaure
MÉTABOLISME: prédateur aquatique
PERCEPTION: Prédateur aquatique Alien
TAILLE:       15-20 pieds
ENDURANCE:  élevé
HOSTILITÉ:  extrême
ARMES:    mâchoires, vitesse, embuscade d'en bas
RÉCOMPENSE:     600 FC
MENACE:     très élevé (dans l'eau)

DESCRIPTION:

L'Ichthyosaur est un terrifiant prédateur aquatique apporté de Xen pendant la cascade de résonance. Bien que ressemblant à un requin ou un reptile muté, il s'agit d'une espèce extraterrestre adaptée au combat sous-marin. Avec ses énormes mâchoires et sa puissante queue, il se déplace avec une vitesse effrayante dans son élément, attaquant souvent d'en bas avant que la victime se rende compte qu'il est là. Sur la terre elle est impuissante, mais dans l'eau elle est king-fast, implacable, et presque impossible à échapper. Les survivants de Black Mesa s'en souviennent comme l'une des créatures les plus redoutées qui se sont déclenchées pendant l'incident.

CONSEILS:

Évitez les eaux profondes dans la mesure du possible.

- Utiliser des explosifs ou une fumée rapide est un suicide.
- Restez près de la surface ; la visibilité vous permet de réagir.