ALUDRAN REPTILOID, COMMUN


CLASSE:      Aludran Reptiloid, Fréquent
MÉTABOLISME: sang-froid, comme un reptile
PERCEPTION: race primitive
TAILLE:       15 pieds
ENDURANCE:  moyenne
HOSTILITÉ:  élevé
ARMES:    missiles magiques
RÉCOMPENSE:     5000 FC
MENACE:     moyenne

DESCRIPTION:

Un grand reptile à quatre mains vivant dans le système Aludran dans la constellation de Canis Major. Cette race primitive a accepté de se battre pour le Mental en échange des pouvoirs qu'elle leur a conférés.
Ils ont lancé des boules de feu autopropulsées avec des capacités primitives.

CONSEILS:

- Gardez-les sous un feu constant et essayez d'abattre leurs missiles dans l'air.
