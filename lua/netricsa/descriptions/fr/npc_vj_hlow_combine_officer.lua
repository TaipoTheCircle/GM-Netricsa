OFFICIER DE SURVEILLANCE DE LA COMBINE


CLASSE:      Combiner l'agent Elite Overwatch
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner commandement et reconnaissance
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrême
ARMES:    Pistolet silencieux, rappel de renfort
RÉCOMPENSE:     800 FC
MENACE:     Très élevé

DESCRIPTION:

L'Officier Elite de l'Overwatch Combine est le commandant de terrain de l'Overwatch Combine, combinant les fonctions de reconnaissance, de coordination et de suppression psychologique. Il porte un uniforme tactique sombre avec une armure de genou renforcée, des bottes noires et un béret noir, soulignant son statut parmi les soldats ordinaires.

Son casque a été remplacé par une version avec une visière lumineuse blanche et jaune, qui sert de scanner tactique et d'interface de commande. Une cape grise est drapée sur ses épaules, servant d'élément de camouflage et de symbole de rang. Une radio à longue portée est attachée à son dos, lui permettant d'appeler les renforts de l'élite Combiner les transports.

Il est armé d'un pistolet silencieux pour assassinat furtif et la répression des témoins. Lorsqu'il détecte une menace, l'officier utilise un pistolet éclairant pour appeler des escadrons de soldats, de combattants d'élite ou de drones de soutien. Son travail n'est pas de se livrer à des combats prolongés, mais de gérer la bataille, transformant un incident localisé en une opération combinée à grande échelle.

CONSEILS:

- Tuez l'officier avant qu'il appelle des renforts.
Le pistolet silencieux fait de lui un chasseur presque invisible.
- La radio est son plus grand atout. Sans ça, c'est un simple commandant.
- Ne le sous-estimez pas : il se tire rarement, mais il décide qui vous tirera dessus.
