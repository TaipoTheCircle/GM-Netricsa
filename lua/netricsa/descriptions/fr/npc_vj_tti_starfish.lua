BIG PATRICK STAR DU BOTTOM BIKINI


CLASSE:      Grand Patrick Star
MÉTABOLISME: Organisme étoilé
PERCEPTION: Une étoile vivante, Deadbeat Sea Star, dangereuse pour les autres
TAILLE:       8,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Très élevé
ARMES:    Tête de club
RÉCOMPENSE:     5000 FC
MENACE:     Haut

DESCRIPTION:

Big Patrick Star est le fidèle ami et collègue d'EpongeBob, connu pour son incroyable stupidité, qui le rend mortel. Il se nourrit de Crabby Patties, fait de poissons, et attaque avec son arme principale - sa tête, qu'il utilise pour casser n'importe quoi en vue.

Il n'a pas d'yeux, mais il peut « téléporter » de courtes distances quand sa victime se détourne, comme le SCP-173. Sa bouche est énorme et ovale, remplie de dents, et le sang violet jaillit de chaque coup. Il n'a pas de pantalon. Malgré son immobilisme apparent, sa téléportation le rend extrêmement imprévisible et mortel.

CONSEILS:

- Maintenez le contact visuel - dès que vous vous détournez, Patrick se rapprochera instantanément.
- Ranged combat est votre meilleure option; éviter le contact direct.
- Planifiez vos manœuvres et gardez constamment un œil sur lui pour éviter d'être dans sa zone de mort.
- La stupidité de Patrick est mortelle - ne le sous-estimez pas.