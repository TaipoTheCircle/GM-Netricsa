ORAZIO


PLANET:       Orazio
TYPE:         Planète terrestre, Planète minière
CLIMATE:      Instable, dur
MOONS:        Inconnu
TERRAIN:      Cratères profonds, mines à ciel ouvert, zones industrielles
LOCATION:     Secteur inconnu de la galaxie
NATIVE RACES: Orcs, Horde mentale (toutes races)
ALLIANCE:     Altani CorpOrazion (anciennement), Mental-Altani CorpOrazion (actuellement)
LOCATIONS:    Orazio Deep Mines, installation d'essais de véhicules de combat

DESCRIPTION:

Un monde inhospitalier avec une écologie extrêmement instable. Les couches profondes du sol sont dominées par un environnement acide et radioactif, rendant la planète impropre à la vie normale à la surface. Le paysage est marqué par d'innombrables mines, carrières et terrasses industrielles-résistants de l'extraction minérale à grande échelle.

La planète est devenue la nouvelle demeure des orques, exilée par l'Empire Zorg après l'interdiction du pool chimique mutagène. Les exilés ont fondé ici la société minière Altani, qui a rapidement réussi grâce aux riches gisements.

Des machines spécialisées - la PRIME-209 et la Tech-X- ont été créées pour travailler dans les profondeurs mortelles et radioactives.

Quand Mental a appris la société prospèreOrazion, il a proposé une alliance avec les orcs. À la suite de la fusion, la société Orazion a été rebaptisée Mental-Altani, et ses véhicules miniers ont subi le programme de conversion de véhicules de combat, recevant des armes lourdes pour le service avec la Horde.

KEY LOCATIONS:

- Orazio Deep Mines: Un réseau de tunnels et d'arbres s'étendant à plusieurs kilomètres sous la surface. En raison de la forte radioactivité, le travail ici est effectué exclusivement par des véhicules télécommandés.
- Installation d'essais de véhicules de combat : Une ancienne carrière transformée en centre d'essais pour les versions armées de robots miniers dans le cadre du « Programme de remise en état ».
