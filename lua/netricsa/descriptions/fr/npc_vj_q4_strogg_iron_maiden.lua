STROGG IRON MAIDEN DE STROGGOS


CLASSE:      Strogg Iron Maiden
MÉTABOLISME: Cybernétique / Biomécanique Soldat
PERCEPTION: Groupe des attaques aériennes
TAILLE:       7,5 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Lance-missile (manipulateur de gauche), Scream d'énergie, Close Combat "Claw"
RÉCOMPENSE:     1800 FC
MENACE:     Haut

DESCRIPTION:

Le Strogg Iron Maiden est une unité de combat volante de l'armée de Strogg, une créature cybernétique semi-vivante avec un corps supérieur ressemblant à une figure féminine et des rubans d'énergie flottants à la place des jambes, lui permettant de planer dans l'air.

Elle est équipée d'un puissant lance-roquettes sur son bras gauche et peut tirer une série de fusées avec un rayon d'explosion important. Sa grande maniabilité et sa capacité de téléporter brièvement lui permettent d'échapper aux attaques directes, faisant d'elle une adversaire dangereuse à moyen et à long terme.

À portée de main, Iron Maiden utilise un cri d'énergie supertonale de courte durée qui non seulement inflige des dommages mais désoriente également la cible. Dans les cas extrêmes, elle peut attaquer avec sa « griffe » - une griffe mécanique.

CONSEILS:

- En raison du rayon d'explosion de la fusée, éviter les espaces ouverts et rester derrière la couverture.
- Iron Maiden peut se téléporter.
- Sa mélasse supertonale désoriente la cible.