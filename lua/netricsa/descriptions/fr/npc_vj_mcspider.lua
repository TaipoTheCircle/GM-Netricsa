L'ESPRIT DU MINECRAFT


CLASSE:      Araignée
MÉTABOLISME: Arthropodes
PERCEPTION: Hostile
TAILLE:       2,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Variable
ARMES:    Bites, saut, escalade murale
RÉCOMPENSE:     120 FC
MENACE:     Moyenne

DESCRIPTION:

L'araignée est un cauchemar classique. Pendant la journée, il se comporte presque de façon décente et ignore généralement tout le monde, comme s'il faisait semblant d'être un élément de paysage ordinaire. Mais avec l'apparition de l'obscurité, il se souvient qu'il est, en fait, un prédateur et commence à attaquer activement.

La caractéristique principale de l'araignée est sa capacité à grimper les surfaces verticales. Les murs, les clôtures et les maisons ne sont pas un obstacle, mais une invitation.

Parfois, les araignées apparaissent avec des "passagers" supplémentaires, formant le célèbre jockey d'araignée, ce qui augmente considérablement le niveau de problèmes par mètre carré.

CONSEILS:

- Pendant la journée, l'araignée est neutre - vous pouvez attaquer d'abord sans risque.
