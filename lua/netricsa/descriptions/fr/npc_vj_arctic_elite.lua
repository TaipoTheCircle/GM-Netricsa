EXTRAIT ARCTIQUE DE COMBINE


CLASSE:      Combiner le soldat Arctic Elite Overwatch
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner Strike Elite
TAILLE:       5,9 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    AR2 Fuseau d'impulsion, boules d'énergie
RÉCOMPENSE:     1100 FC
MENACE:     Très élevé

DESCRIPTION:

Le Combine Overwatch Arctic Elite est une version spécialisée du Combine Elite, conçu pour le combat dans le pergélisol, les blizzards et les villes polaires mortes. Son camouflage blanc se mêle pratiquement à la glace environnante, et les éléments gris-bleu de son équipement remplacent les détails rouges familiers, rendant sa silhouette froide, sans émotion, et presque fantôme.

Une seule visière bleue brille à travers la tempête de neige, détectant les signatures thermiques et les mouvements à une distance considérable. Des rayures bleues courent sur les deux côtés de ses jambes, servant d'éléments d'identification et de technique de son armure, ainsi qu'un marqueur visuel de son statut d'élite.

Ces soldats sont déployés dans des régions où les forces conventionnelles de la coalition perdent rapidement leur efficacité au combat. Les implants renforcés les protègent contre l'hypothermie, et leur système de survie leur permet de se battre pendant des heures sans couverture ni réapprovisionnement. Leur tactique est standard pour l'élite Overwatch : feu coordonné, suppression avec des boules d'énergie et élimination méthodique de la résistance.

CONSEILS:

- Leur camouflage blanc les rend difficiles à repérer dans la neige.
- Les boules d'énergie sont particulièrement dangereuses dans les passages glacés étroits.