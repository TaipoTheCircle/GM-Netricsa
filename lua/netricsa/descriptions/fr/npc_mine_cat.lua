CAT DU MINECRAFT SURVEILLANCE


CLASSE:      Chat
MÉTABOLISME: Mammifère à sang chaud
PERCEPTION: Animaux domestiques / neutres
TAILLE:       2,6 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Faible
WEAPONALS:  Aucune
RÉCOMPENSE:     10 FC
MENACE:     Faible

DESCRIPTION:

Les chats sont des créatures neutres apprivoisées dans le Minecraft Overworld, le plus souvent dans les jungles, les villages et les cabanes de sorcières. Une fois apprivoisés, ils deviennent des compagnons fidèles et vous suivent autour, régulièrement assis, couchés ou en train de se friser.

Cats have an innate repellent instinct: les rampants et les fantômes évitent les chats, les rendant non seulement décoratifs mais aussi stratégiquement utiles. Les chats viennent dans une variété de couleurs, de noir et orange à tacheté et siamois.

Un chat apprivoisé peut apporter des cadeaux dans les plumes du matin, de la viande pourrie, du fil, et d'autres petits articles les laissant près de son propriétaire endormi.

CONSEILS:

- Utilisez la morue crue ou le saumon pour apprivoiser.
- Gardez les chats près de votre base pour les protéger contre les fantômes et les rampants.
- Différentes couleurs de chat peuvent être recueillies et élevées.
