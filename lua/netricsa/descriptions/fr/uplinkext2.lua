MESA BLACK, ACCÈS LIBRE


Sam, j'espère que tu es prêt, parce que ce n'est pas juste un couloir plein de soldats. Dès que les portes de l'ascenseur s'ouvriront, vous vous retrouverez à regarder un campement de S.E.C.U. fortement fortifié.

Ils ont installé des sacs de sable, des mitrailleuses montées et des champs de feu qui se chevauchent. De toute évidence, ils ne veulent personne près de ce bâtiment. Malheureusement, c'est exactement là que se trouve l'antenne de liaison ascendante.

Your task remains the same: atteindre la salle de contrôle, ajuster le tableau, et envoyer le signal. Sans cette transmission, le complexe Lambda reste scellé, et la dernière chance de survie de Black Mesa disparaît.