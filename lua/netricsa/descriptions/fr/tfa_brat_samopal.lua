HOMEMADE MAZZLE-LOADING PISTOL "SAMOPAL"


ARME: Pistolet "Samopal" fait maison
MUNITIONS:   Charge de poudre artisanale
CADENCE DE TIR:    1 Shot, Rechargement manuel

DESCRIPTION:

Une arme à feu primitive improvisée construite à partir de matériaux facilement disponibles. Il s'agit d'un pistolet à simple tir muni d'un canon métallique attaché à un stock de bois. Il manque de mécanismes conventionnels de déclenchement ou de tir et se caractérise par une conception extrêmement simple.

Une source externe d'incendie est nécessaire pour enflammer la charge. L'arme manque de mécanismes de sécurité fiables et constitue un grave danger pour son propre utilisateur. Malgré sa construction brute et de fortune, il est capable de tirer un rond vif et d'infliger de graves blessures.

REMARQUES:

- Fabriqué à partir d'un tube de cuivre, d'un morceau de bois et de fils d'aluminium.
- Créé pour la production du film "Brother 2" ("Brat 2").
- Sergei Astakhov et Sergei Bodrov ont participé à sa création.
- Une conception extrêmement peu fiable qui peut constituer une menace mortelle.
