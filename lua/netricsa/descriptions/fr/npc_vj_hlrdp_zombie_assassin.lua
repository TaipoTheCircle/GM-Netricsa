Y.S.M. ZOMBIE HEADCRAB FEMALE ASSASSIN, COMMUN


CLASSE:      Y.S.M. Casse-tête de zombies Assassin femelle, commune
MÉTABOLISME: Hôte humain + tête parasite de Xen
PERCEPTION: Entité zombifiée, ancienne opérationnelle Elite
TAILLE:       5,6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrême
ARMES:    Griffes, morsure, prise de vol
RÉCOMPENSE:     700 FC
MENACE:     Très élevé

DESCRIPTION:

C'est un membre d'élite de la compagnie militaire privée Y.S.M., que Headcrab a rencontré. Son costume en latex a conservé la technologie d'invisibilité, et le headcrab zombie a appris à l'utiliser instinctivement. Elle devient presque complètement invisible en passant par les couloirs de la base Delta. Son entraînement acrobatique reste intact, elle court aussi vite.

Seul un léger éclat lui donne. Quand elle attaque, son invisibilité s'efface : elle devient visible juste assez longtemps pour couler ses griffes dans sa victime, puis disparaît dans l'obscurité. Un coup de tête détache la tête de la victime.

CONSEILS:

- Elle devient visible en attaquant.
- Un fusil avec une portée est plus efficace qu'une arme de précision-il est plus facile de frapper la silhouette chatoyante.
- Elle n'a pas d'armure, juste du latex. Un ou deux coups et elle tombe. Mais la frapper est un défi.
- Elle est particulièrement dangereuse avec d'autres zombies.
