SCORPION MEILLEUR DEMON, ADULTE DE LA PLANTE TROPIQUE


CLASSE:      Scorpion du démon de la bête, adulte
MÉTABOLISME: Exobiologique, Arthropodes
PERCEPTION: Scorpion de combat pour adultes
TAILLE:       20 pieds
ENDURANCE:  Extrême
HOSTILITÉ:  Extrême
ARMES:    La queue mortelle
RÉCOMPENSE:     12000 FC
MENACE:     Absolu

DESCRIPTION:

C'est ce qu'un jeune Scorpion devient s'il est autorisé à vivre assez longtemps pour tuer encore quelques milliers de personnes. Solgar mentore personnellement les spécimens les plus prometteurs, sélectionnant ceux qui ont fait leurs preuves au combat et leur permettant de survivre à l'âge adulte. Les résultats sont impressionnants.

Un scorpion adulte est remarquablement différent de son homologue juvénile. La carapace verte brillante du juvénile s'obscurcit avec l'âge, devenant un vert noirâtre profond et sombre, presque mélangé à l'obscurité.

La tête est protégée par une barre ressemblant à un casque avec un éclat métallique subtil. Les yeux sur les côtés de la tête brillent dans le noir avec une lumière bleue et froide.

La queue de l'adulte est plus longue, plus épaisse et plus mortelle.

CONSEILS:

- Utilisez des explosifs, beaucoup. C4, grenades, fusées, tout ce que vous avez.
- Ne le laissez pas s'approcher, ça vous tuera plus vite que vous ne pouvez tirer.
