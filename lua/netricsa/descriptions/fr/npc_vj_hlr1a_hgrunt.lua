ALPHA S.E.C.U. MARINE


CLASSE:      Alpha H.E.C.U. Marine
MÉTABOLISME: Humain, Homme
PERCEPTION: Équipe expérimentale des États-Unis
TAILLE:       6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrême
ARMES:    Colt M4 Carbine, Grenades.
RÉCOMPENSE:     700 FC
MENACE:     Modéré (seule), élevé (en équipes)

DESCRIPTION:

Les Grunts Alpha H.E.C.U. sont la première vague de soldats déployés dans des zones de résonance. Leur équipement et leur entraînement de combat diffèrent des unités standard : armure légère, protocoles tactiques simplifiés, et un accent sur les assauts rapides. Ils se déplacent agressivement et imprudemment, se chargeant souvent au combat sans coordination adéquate.

Contrairement aux principales divisions de l'U.S.E., ces unités comptent rarement sur des embuscades ou des manœuvres avancées. Leur rôle principal est la pénétration rapide et le déminage des zones hostiles à tout prix, même si les pertes sont élevées. De ce fait, Alpha H.E.C.U. est souvent considéré comme une force durable, envoyé en avant comme une sonde vivante pour affaiblir la résistance avant l'arrivée des équipes principales.

CONSEILS:

- Sensible à la suppression sous un feu lourd.
- Utilisez des grenades plus fréquemment que des soldats réguliers.
- Dangereux dans les quartiers proches mais mal adapté pour des engagements prolongés.
