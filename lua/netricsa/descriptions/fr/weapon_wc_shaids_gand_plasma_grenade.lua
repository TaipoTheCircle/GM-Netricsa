PLASMA GRENADE


ARME:      Grenade du plasma
MUNITIONS:        Noyau plasmatique autochargé
CADENCE DE TIR:         À usage unique / lancé
POIDS:      1,6 lbs

DESCRIPTION:

Développée par les scientifiques de Lord Anton, la Grenade Plasma est une arme expérimentale alimentée par un noyau électrique autonome. Lors de la détonation, il libère une violente décharge de plasma qui non seulement décharge et immobilise les ennemis pendant un court laps de temps, mais provoque également des brûlures dévastatrices d'énergie.

Instable et imprévisible, cette arme est considérée comme trop dangereuse pour être émise en masse, car même une mauvaise manipulation pendant l'armement pourrait entraîner un déversement accidentel. Seules les unités de confiance des forces d'Anton sont autorisées à utiliser cette technologie - ses effets sur les cibles organiques et mécaniques en font l'un des dispositifs les plus redoutés sur le champ de bataille.

REMARQUES:

- Paralyse temporairement les ennemis pris dans son rayon d'explosion.
- Ne le laissez pas tomber dans les mains ennemies.
- Efficace contre l'infanterie et la robotique légère.