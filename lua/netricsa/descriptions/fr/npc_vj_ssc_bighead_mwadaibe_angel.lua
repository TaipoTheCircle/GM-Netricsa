GRANDE ANGEL, CENTRE "MWADAIBE"


CLASSE:       Big-Head Angel, Sean "mwadaibe" Centre
MÉTABOLISME:  Humanoïde, Homme
PERCEPTION:  Fanatique enthousiaste
TAILLE:        5,9 pieds
ENDURANCE:     Faible
HOSTILITÉ:   Neutre
ARMES:     Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:      100 FC
MENACE:      Annoyance

DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme de Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan" ils gagnent le feu et les modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Le Sean "mwadaibe Center" est un autre rouage clé du légendaire collectif de modding A Few Viss Loose, dont le travail a été officiellement reconnu et gravé à jamais dans la tradition de la série. Son crâne exagéré témoigne de sa profonde compréhension de l'équilibre, de la conception des flux et de la dynamique pure et débridée des batailles en ligne. En collaboration avec l'équipe, il a travaillé sur le fameux mod Deathmatch de The Second Encounter, créant et perfectionnant ces 20 cartes folles qui ont inspiré toute une génération de joueurs de Serious Sam esports.

His contribution goes beyond mere fan art: c'était un projet collaboratif à part entière, où la passion de la communauté a rencontré la confiance du studio. Sean et ses collègues n'ont pas seulement donné au jeu un contenu supplémentaire - ils ont prolongé sa durée de vie, établi son statut culte en multijoueur, et prouvé que les idées les plus brillantes peuvent naître à l'intersection du développement professionnel et de la dévotion des fans.

Il était une fois vivant, mais après que quelqu'un l'ait tué, il a été ressuscité - devenir un ange.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager le chemin.
- Sur la difficulté "Je suis Ugh-Zan", les éliminer à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.
