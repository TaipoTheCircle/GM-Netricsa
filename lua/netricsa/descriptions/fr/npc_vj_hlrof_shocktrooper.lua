TROOPER DE LA DIMENSION X


CLASSE:      Troyeur de choc
MÉTABOLISME: Carnivore/bioélectrique
PERCEPTION: Infanterie lourde de course X
TAILLE:       7-8 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Fusil bio-électrique, griffes, coups de pied
RÉCOMPENSE:     400 FC
MENACE:     Haut

DESCRIPTION:

Les Shock Troopers sont l'infanterie principale de la Race X, élevée en tant que soldats d'élite et commandants de champ de bataille. Tournée et musclée, leur corps est armuré d'un plateau de chitin naturel, leur donnant une résistance impressionnante contre les armes conventionnelles. Leur arme de signature est le Choc Roach, un bio-organisme vivant qui sert de souffleur d'énergie. Le soldat et le cafard partagent un lien symbiotique - quand le soldat tombe, le cafard se détache et continue à se battre comme une créature indépendante.

Les chasseurs de choc utilisent également les Drones de Pit comme unités de soutien, les conduisant vers l'avant comme éclaireurs consomptibles et attaquants de première ligne. Leur tactique est organisée et efficace, contrairement à l'agression féroce de la faune Xen. Au combat, les Choc Troopers avancent régulièrement, allongeant le feu bio-électrique et utilisant leur masse pour écraser les ennemis en mêlée.

Leur présence sur Terre lors de l'Incident Black Mesa était un signe que Race X cherchait une invasion à grande échelle, rivalisant avec Xen elle-même.

CONSEILS:

- Prioriser le Shock Roach-l'arme est puissante mais a un tir limité.
- Les explosifs et les armes lourdes fonctionnent mieux contre leur armure épaisse.
- Préparez-vous à affronter les Choock Roaches après la mort du soldat.
- Évitez de fermer les quartiers - ils excellent en melee si permis de fermer la distance.
- De rares chocs à peau orange peuvent apparaître; ils sont plus forts et plus résistants que leurs homologues verts.
