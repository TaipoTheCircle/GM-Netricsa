ROLLERMINE DE LA COMBINE


CLASSE:      Mélanger Rollermine
MÉTABOLISME: Entièrement synthétique (noyau d'énergie composite)
PERCEPTION: Dispositif explosif autonome
TAILLE:       ~1,5 pi de diamètre
ENDURANCE:  Faible
HOSTILITÉ:  Haut
ARMES:    Décharge de choc magnétique, Auto-détonation explosive, Attaque
RÉCOMPENSE:     75 FC
MENACE:     Faible-moyenne

DESCRIPTION:

Le Combine Rollermine est une petite mais dangereuse arme autonome déployée par le Combine comme un outil de déni de zone. Conçus pour rouler rapidement à travers le terrain, ces dispositifs sphériques utilisent l'attraction magnétique pour s'accrocher aux véhicules ou aux ennemis, les choquant avec des éclats d'électricité haute tension.

Bien qu'individuellement faibles, les Rollermines excellent dans les essaims, perturbant les mouvements de résistance, embuscade les équipes et arrêtant les véhicules en les verrouillant. Leur coquille légère les rend vulnérables aux tirs de petites armes, mais leur agilité et leur comportement inlassable les rendent frustrants à éliminer dans la chaleur du combat.

Lorsqu'ils sont détruits, leur noyau instable Combine peut exploser.

CONSEILS:

- Utilisez le pistolet Gravity pour éloigner Rollermines ou les retourner aux ennemis.
- Continuez à bouger; ils sont rapides mais prévisibles en entrant.
