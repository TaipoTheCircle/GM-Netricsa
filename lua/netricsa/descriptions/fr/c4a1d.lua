XEN, CAPSULES INFANTRES


Les rangées et les rangées de biocapsules s'étirent, chacune d'entre elles craquant des troupes à moitié formées, certaines dormantes, d'autres envoûtant la vie. Les murs hument d'énergie, l'air épais avec l'odeur du lisier génétique et de l'ozone.

Chaque grogne, chaque soldat, chaque lame naît ici.