VENDU DE SNIPER MENDEL-GRUMAN


CLASSE:      Mendel-Gruman Sniper Soldat
MÉTABOLISME: Humain, Homme
PERCEPTION: Groupe des snipers
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    TRIGLAV 92 Sniper Sniper Rifle, ORO HOG 9mm Pistol, Grenades de fragmentation
RÉCOMPENSE:     500 FC
MENACE:     Haut

DESCRIPTION:

Des soldats spécialisés conçus pour atteindre des cibles de grande valeur à long terme. Contrairement à l'infanterie standard, ils suivent une formation supplémentaire en masquage, camouflage et observation. Leur mission est simple : repérer l'ennemi avant de les repérer et les éliminer avec un seul coup précis.

L'armure du sniper a une couleur foncée, presque noire et est complétée par un costume de camouflage conçu pour les opérations dans les zones boisées. La conception intègre des éléments de l'équipement des unités régulières d'infanterie et de RPG, mais le casque a ses propres modifications. Le côté gauche de la visière est divisé en plusieurs sections optiques distinctes, permettant l'utilisation de systèmes d'observation spécialisés.

L'arme principale du sniper est le TRIGLAV 92 Stalker. Dans les mains d'un tireur entraîné, ce fusil permet des fiançailles à des distances importantes et est particulièrement dangereux contre les soldats qui se considèrent en sécurité au-delà de la portée efficace des armes classiques.

Le tireur d'élite ne cherche pas à se livrer à une longue fusillade. Il préfère prendre une position avantageuse, attendre le moment opportun et ouvrir le feu sur la cible la plus dangereuse ou la plus vulnérable. Une fois sa position détectée, il peut tenter de changer de couverture et poursuivre le combat à partir d'un point de vue différent.

Malgré sa spécialisation, le sniper n'est pas impuissant à bout portant. Il peut utiliser le ORO HOG 9mm comme arme secondaire et porte également des grenades à fragmentation. Par conséquent, essayer de le rejoindre ne garantira pas une victoire facile. Les représentants de cette classe peuvent également porter le SMG du FP9 malgré leur désignation comme snipers.

Les snipers sont des unités Mendel-Gruman légèrement blindées et n'ont donc pas de survie exceptionnelle. Leurs principales défenses sont la distance, la couverture et la précision. Les priver de ces avantages les rend nettement moins dangereux.

CONSEILS:

- Ne restez pas ouvert. Un tireur d'élite n'a besoin que de quelques secondes pour choisir une cible.
- Essayez d'abord de déterminer la source de l'incendie et de sortir de la couverture.
- À distance, un tireur d'élite est nettement moins dangereux qu'à longue distance.
- Les grenades sont particulièrement utiles si l'ennemi se cache derrière la couverture.
- Ne laissez pas un tireur d'élite changer librement de position. Perdre une bonne couverture réduit considérablement son efficacité.
- Si vous remarquez une silhouette sombre et le flash d'un coup de feu de loin, ne revérifiez pas si c'était vraiment un sniper.
