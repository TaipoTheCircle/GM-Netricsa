SOLDAT SNIPER MENDEL-GRUMAN


CLASSE : Soldat tireur d'élite Mendel-Gruman
MÉTABOLISME : humain, masculin
PERCEPTION : Unité de tireurs d'élite
TAILLE : 5,9 pieds
ENDURANCE : Moyenne
HOSTILITÉ : Élevée
ARMES : Fusil de précision TRIGLAV 92 Stalker, pistolet ORO HOG 9 mm, grenades à fragmentation
RÉCOMPENSE : 500 FC
MENACE : Élevée

DESCRIPTIF :

Soldats spécialisés conçus pour attaquer des cibles de grande valeur à longue distance. Contrairement à l'infanterie standard, ils suivent une formation supplémentaire en adresse au tir, en camouflage et en observation. Leur mission est simple : repérer l'ennemi avant qu'il ne le repère et l'éliminer d'un seul tir précis.

L'armure du tireur d'élite a une couleur foncée distinctive, presque noire, et est complétée par une combinaison de camouflage conçue pour les opérations dans les zones boisées. La conception intègre des éléments de l'équipement des unités régulières d'infanterie et de RPG, mais le casque a ses propres modifications. Le côté gauche de la visière est divisé en plusieurs sections optiques distinctes, permettant l'utilisation de systèmes d'observation spécialisés.

L'arme principale du tireur d'élite est le TRIGLAV 92 Stalker. Entre les mains d'un tireur entraîné, ce fusil permet des engagements à des distances importantes et est particulièrement dangereux contre les soldats qui s'estiment en sécurité au-delà de la portée efficace des armes conventionnelles.

Le tireur d’élite ne cherche pas à s’engager dans un échange de tirs prolongé. Il préfère prendre une position avantageuse, attendre le moment opportun et ouvrir le feu sur la cible la plus dangereuse ou la plus vulnérable. Une fois sa position détectée, il peut tenter de se mettre à couvert et de poursuivre le combat depuis un point de vue différent.

Malgré sa spécialisation, le tireur d’élite n’est pas impuissant à bout portant. Il peut utiliser l'ORO HOG 9 mm comme arme secondaire et porte également des grenades à fragmentation. Par conséquent, tenter de le rejoindre ne garantira pas une victoire facile. Les représentants de cette classe peuvent également porter le SMG FP9, malgré leur désignation de tireurs d'élite.

Les tireurs d'élite sont des unités Mendel-Gruman légèrement blindées et n'ont donc pas de capacité de survie exceptionnelle. Leurs principales défenses sont la distance, la couverture et la précision. Les priver de ces avantages les rend nettement moins dangereux.

CONSEILS :

- Ne restez pas à l'air libre. Un tireur d’élite n’a besoin que de quelques secondes pour choisir une cible.
- Essayez d'abord de déterminer la source de l'incendie et sortez ensuite de votre abri.
- À courte portée, un tireur d'élite est nettement moins dangereux qu'à longue portée.
- Les grenades sont particulièrement utiles si l'ennemi se cache à l'abri.
- Ne laissez pas un tireur d'élite changer librement de position. Perdre une bonne couverture réduit considérablement son efficacité.
- Si vous remarquez une silhouette sombre distinctive et l'éclair d'un coup de feu de loin, ne vérifiez pas s'il s'agissait réellement d'un tireur d'élite.