ASHEN COW DU MINECRAFT SURVEILLANCE


CLASSE:      Vache d'Ashen
MÉTABOLISME: Mammifère chaud
PERCEPTION: Animaux passifs
TAILLE:       ~4,6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Faible
ARMES:    Aucune
RÉCOMPENSE:     60 FC
MENACE:     Minimal

DESCRIPTION:

Une rare variété de vache commune, originaire de la steppe. Contrairement à ses parents tachetés, cette vache est entièrement grise, avec une bande longitudinale plus foncée le long de son dos, et les extrémités de ses cornes sont également grises.

Le comportement de la vache Ashen n'est pas différent de celui d'une vache commune : elle paît, erre sans but et évite la lave et les falaises. Lorsqu'il est endommagé, il fuit pendant quelques secondes, puis se calme.

Mais il a une caractéristique unique, confirmée par des milliers de survivants: les rampants l'éviter. Il n'y aura jamais d'explosion près d'une vache d'Ashen.

Ils ne s'approchent tout simplement pas. Ils tournent autour, changent leur trajectoire, même si la vache est directement sur leur chemin. Personne ne sait pourquoi. Certains disent que sa peau grise sent quelque chose qui effraie les créatures de la plante et de la poudre.

CONSEILS:

- Si tu trouves une vache, ne la tue pas. Mets-la dans ta base.
- Vous pouvez construire en toute sécurité des structures en bois autour d'elle; les rampants ne le feront pas.
- Racontez-les – Les vaches d'Ashen se reproduisent comme des vaches régulières, produisant la même progéniture.
- Inutile au combat, mais inestimable en agriculture.
- Protège la base des Cris.
