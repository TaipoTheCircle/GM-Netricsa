LÉGIONNAIRE IMPERIAL DU NIRN


CLASSE:      Légionnaire impérial
MÉTABOLISME: Impérial, Homme
PERCEPTION: Soldat professionnel de la Légion impériale
TAILLE:       5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Conditionnel
ARMES:    Acier / épée impériale, arc impérial avec flèches en acier, bouclier impérial
RÉCOMPENSE:     300 FC
MENACE:     Haut

DESCRIPTION:

C'est la principale force militaire de l'Empire, une armée professionnelle qui maintient l'ordre à travers Tamriel depuis des centaines d'années. Ses origines remontent à la Première ère, lorsque les Légions Alessiennes ont d'abord uni le Cyrodiil sous la domination humaine. À l'ère moderne, malgré les guerres et les crises, la Légion demeure une force disciplinée et formidable.

La structure de la Légion est organisée et étroite. Il est divisé en légions et cohortes numérotées. Les candidats sont tenus de posséder non seulement la force brute, mais aussi l'endurance, la vertu et la fiabilité. La Légion est réputée pour ses membres politiques inclusifs de toutes les races et les religions sont les bienvenues dans ses rangs. Bien que le noyau de la Légion soit les Impériaux, les Nords et les Gardes-Rouges, les Bretons, les Orsimers et même Dunmer se trouvent parmi ses soldats.

L'équipement d'un légionnaire dépend de l'époque et de l'emplacement du service. Pendant la crise de l'Oblivion à Cyrodiil, ils portèrent de lourdes armures en acier avec des éléments d'armure de plaque romaine, armés de longues épées. Dans Skyrim, la situation est plus complexe - les ressources sont rares, et la majorité des soldats portent une armure en cuir léger avec des inserts en acier. C'est une mesure nécessaire, car la Légion reçoit peu de renforts dans les provinces et est contrainte de recruter des milices locales, parfois en abaissant leurs normes.

Les légionnaires sont soumis à une discipline stricte. Ils patrouillent les routes, gardent les forts et participent à des batailles à grande échelle. À Skyrim, ils mènent une guerre prolongée contre les rebelles. Les légionnaires utilisent des tactiques « d'épée et de bouclier » : ils prennent des coups ennemis avec leurs boucliers et contre-attaques.

Pendant la crise d'oblivion, ils étaient l'élite, mais la guerre avec le Thalmor et la crise prolongée ont paralysé l'armée. Dans Skyrim, les soldats sont souvent insatisfaits de l'Empire, mais ils le servent soit par tradition, soit parce qu'ils le considèrent comme le seul bastion contre le Thalmor.

CONSEILS:

- Si vous prévoyez de vous battre du côté de l'Empire, votre équipement sera supérieur à celui de votre adversaire. Les légionnaires sont bien armés et organisés.
- En combattant un Légionnaire, rappelez-vous leur tactique. Ne vous précipitez pas dans des manœuvres de flancs, de magie ou d'unités de protection.
- Les meilleures armes contre les légionnaires lourdement blindés sont des sorts et des armes qui ignorent l'armure.
- Dans la province de Skyrim, les légionnaires sont plus vulnérables en raison de leur armure légère. Utilisez des armes lourdes pour drainer rapidement leur santé.
- Si vous êtes un criminel, restez loin des légionnaires. Contrairement aux gardes de la ville, ils ont le droit de vous arrêter en dehors des villes.
- Quand vous rejoignez la Légion, vous jurez un serment sacré d'allégeance à l'Empereur. La briser sera considérée comme une trahison.
