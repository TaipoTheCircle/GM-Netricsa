BOIS


PLANET:       Terre
TYPE:         La planète terrestre, la terre natale de l'humanité
CLIMATE:      Varié (de l'Arctique au tropical)
MOONS:        1 lune
TERRAIN:      Continents, océans, chaînes de montagnes, déserts
LOCATION:     Système solaire, bras d'orion (Milky Way)
NATIVE RACES: Humains
ALLIANCE:     Espace humain indépendant; partiellement occupé par la Horde mentale (à divers moments)
LOCATIONS:    Égypte, Tunguska, Carcassonne, Pompéi, Teotihuacan, Krvavice

DESCRIPTION:

La troisième planète du système solaire. La terre natale de l'humanité et le centre de la civilisation humaine. Il a un satellite naturel, la Lune.

Le paysage de la planète est extrêmement diversifié : des calottes polaires aux jungles équatoriales, des tranchées océaniques profondes aux sommets les plus élevés. Environ 70 % de la surface est couverte d'eau.

La Terre attire depuis longtemps l'attention des civilisations extraterrestres. Il y a des milliers d'années, elle a été visitée par les Siriens, qui ont influencé le développement des cultures anciennes, en particulier en Égypte. Plus tard, la planète est devenue à plusieurs reprises la cible d'invasions par la Horde Mentale, cherchant à détruire l'humanité.

Pendant la guerre, les Forces de défense unies ont utilisé d'anciens artefacts siriens, dont le Gardien du temps, pour résister aux envahisseurs.

KEY LOCATIONS:

- Egypte: Une région où de nombreuses preuves de la présence de Sirian demeurent. Les Grands Pyramides, Karnak, Louxor, la Vallée des Rois, et les complexes souterrains contenant des générateurs siriens sont situés ici. - Tunguska : Le site d'une invasion massive par les forces de Mental, où un gigantesque portail Horde a ouvert pendant l'offensive Tunguska.
- Carcassonne : Une ville fortifiée où le groupe « Troika-A » était basé lors d'une des opérations contre les forces de Mental.
- Pompéi: Une ancienne ville romaine près de laquelle une arme satellite a été activée pour dissuader les forces ennemies.
- Teotihuacan: Une ancienne ville maya où les Siriens ont laissé un de leurs portails de temps.
- Krwavice: Une ville polonaise médiévale où un important artefact connu sous le nom de "Livre de la Sagesse" a été découvert.
