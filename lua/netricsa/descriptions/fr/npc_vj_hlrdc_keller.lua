DESCRIPTION:

Le Dr Richard Keller est une haute autorité administrative et scientifique au sein du Centre de recherche Black Mesa pendant la cascade de résonance. Distingué par sa dépendance à l'égard d'un fauteuil roulant motorisé en raison d'un handicap physique, Keller commande néanmoins un immense respect grâce à son intelligence aiguë, son leadership décisif et sa maîtrise de la théorie interdimensionnelle.

En tant qu'une des figures les plus élevées, Keller supervise et dirige les actions des Drs Gina Cross et Colette Green, assurant la stabilité des expériences et le confinement des catastrophes au sein de Black Mesa. Son expertise en téléportation et en contrôle de résonance le rend indispensable au maintien de la structure opérationnelle pendant les événements catastrophiques.

Bien que incapable de combattre directement, Keller exerce son influence en coordonnant les scientifiques, la sécurité et les systèmes des postes de commandement. Ses connaissances, sa discipline et sa résolution aident le personnel survivant à traverser le chaos de l'incident.

La survie de Keller représente la préservation des plus hauts niveaux de leadership scientifique et administratif de Black Mesa, ce qui en fait l'un des civils les plus stratégiques pendant la crise.

