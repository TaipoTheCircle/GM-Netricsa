PIGLIN SWORDSMAN DU PAYS-BAS


CLASSE:       Épées de Pigline
MÉTABOLISME:  Un humanoïde de type cochon
PERCEPTION:  Course guerrière primitive de la Nether
TAILLE:        6,3 pieds
ENDURANCE:   Moyenne
HOSTILITÉ:   Conditionnel
ARMES:     Sabre dorée (parfois enchantée)
RÉCOMPENSE:      400 FC
MENACE:      Moyenne

DESCRIPTION:

Une des deux races principales de créatures semblables à des porcs qui habitent la Nether. Contrairement à leurs parents zombifiés, ils conservent une certaine intelligence, la capacité de parler leur propre langue grogneuse et, surtout, une passion pour l'or.

This passion is so strong that it defines their entire behavior: les porchins ne sont neutres que pour ceux qui portent au moins un morceau d'armure dorée.

Sans elle, ils deviennent immédiatement agressifs.

Les éperons représentent exactement la moitié de la population adulte de porcins (l'autre moitié préfère les arbalètes). Ils sont armés d'épées dorées, qui peuvent être enchantées, et attaquent au combat rapproché, balayant leurs armes aussi farouchement que les champions dans les maisons forestières.

Les Piglins habitent les forêts et les friches de la Nether, ainsi que des forteresses imposantes où ils gardent des trésors et des blocs d'or. Dans les bastions, ils sont souvent rejoints par des frères fervents et forts avec des axes d'or qui sont immunisés contre les distractions impliquant de l'or.

Les Piglins craignent le feu d'âme et leurs frères zombifiés, à la vue desquels ils fuient.

Ils ne peuvent pas nager, se noyer dans l'eau, et ne sont pas à l'abri du feu ou de la lave, malgré la vie en enfer.

CONSEILS:

- Portez une armure en or. Même une pièce empêchera les cochons de t'attaquer.
- N'ouvrez pas les coffres ou cassez les blocs d'or devant eux- cela provoque l'agression même par l'armure.
- Les hommes d'épée sont dangereux au combat, mais plutôt lents.
