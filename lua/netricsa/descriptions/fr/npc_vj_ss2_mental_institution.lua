INSTITUTION MENTALE


CLASSE:      Institution mentale
MÉTABOLISME: Mégastructure mécanique blindée
PERCEPTION: Lanière mécanique de Mental
TAILLE:       984 pieds
ENDURANCE:  Immense
HOSTILITÉ:  Extrême
ARMES:    Lance-feu, canons d'artillerie, batteries de missiles, roues mortelles
RÉCOMPENSE:     5000 FC
MENACE:     Catastrophes

DESCRIPTION:

L'Institution mentale est une gigantesque pyramide mobile qui sert de base centrale et de repaire personnel à Mental. C'est une citadelle mécanisée autonome, conçue uniquement pour la guerre totale et la destruction de tout intrus.

La structure est entièrement couverte de segments blindés et de plates-formes d'armes. Un noyau de contrôle blindé est logé à l'intérieur, activé lors de la détection d'une menace. Une fois activée, la forteresse lance des vagues d'avions de chasse, y compris des chasseurs "fatso kamikaze" qui tombent sur des cibles et explosent à l'impact, causant des dommages dévastateurs.

Dans le même temps, la forteresse bombarde la région environnante avec des boules de feu à plasma, des obus de canon lourds et des salves massives de missiles. Des bombardiers manipulables Chaika larmentent des bombes à sous-munitions, faisant de la surface autour de la forteresse une zone de destruction totale.

Lorsque les défenses sont affaiblies, le noyau central s'ouvre temporairement, permettant aux attaquants d'attaquer les composantes clés de la structure. À l'heure actuelle, les énormes modules de combat autonomes à roues tournantes qui se déplacent le long de la surface de sortie des compartiments inférieurs. Tout contact avec eux entraîne la destruction instantanée de la cible.

L'institution mentale n'est pas une structure ordinaire, c'est une machine de destruction à pied, capable d'écraser des armées, de raser des villes et de fonctionner comme un écosystème de combat autonome.

CONSEILS:

- Prioriser la destruction des "fatso kamikazes" - ils infligent le plus de dommages.
- Les bombardiers agiles sont dangereux, mais secondaires.
- Lorsque le noyau est exposé, attaquer aussi agressivement que possible avec des armes lourdes.
- Ne restez pas immobile pendant les tirs d'artillerie, sauf si vous voulez finir comme Kwongo.