UNE MAISON DE BRICK, DES DECHETS ET DES TROIS


Sam, cet endroit sent comme un harceleur qui a décidé de s'installer et de stocker son placard pour l'hiver nucléaire. Devant nous se trouve une maison de brique solitaire, debout sur l'herbe verte, comme si elle était simplement placée là et oubliée.

Il n'y a pas de ville à proximité, pas de voisins. Juste 11 arbres.

La maison est robuste, brique rouge, le toit est en place. Mais il y a quelques nuances:

Il n'y a pas de porte. Du tout. Juste une ouverture, avec un vide noir. Soit ils l'ont enlevé, soit il n'y a jamais été.

Deux fenêtres de chaque côté de l'entrée.

A droite, trois voitures. Avant, ils pouvaient s'enfuir, mais maintenant, ils sont juste rouillés sans roues. Ils sont là comme un rappel : il n'y a pas d'évasion d'ici.

Il y a un entrepôt, pas une maison. Quelqu'un se préparait clairement à la fin du monde:

Deux lampes suspendues au plafond. La lumière suffit à voir ce qu'il y a dedans.

Five drawers: un grand, quatre petits. Serré. Ils n'ouvrent pas, ne cassent pas, ne bougent pas. Ils s'assoient là, se moquent.

Sur le mur droit est une horloge. Ça marche ? Ça tourne ? Ça ne dit jamais l'heure ? Inconnu. Mais c'est là.

Il y a aussi une armoire avec deux armes. Mais ne t'inquiète pas, Sam. Ils sont cloués. Quelqu'un est venu, a accroché les armes, et les a sécurisés pour que vous ne puissiez pas les déplacer. Comme un avertissement. Ou comme une haine.

Fournitures - c'est là que l'or est:

Et voilà où commence le plaisir. Quelqu'un a adopté une approche très prudente de la survie:

"Pommes de terre douces" - un aliment de base de l'alimentation.

"Les pommes-la plus belle du monde." Les meilleures pommes du monde. C'est écrit.

"Les fours à micro-ondes de Sofia"-112 comptent. Les repas micro-ondes de Sofia. 112 pièces. Sofia est soit un génie de la logistique, soit juste un vrai cuisinier.

"Jabber's Assorted Snacks" - des collations variées de Jabber. Quelque chose pour chaque goût.

"Rolee Juice Boissons" - jus. Des vitamines.

"Vanilla Drink" - boisson vanille. Pour la variété.

"Diet Soda" - soda diététique. Une figure est importante, même dans l'apocalypse.

"Pommes de terre fraîches" - pommes de terre fraîches. Juste des pommes de terre. Frais.

Une maison est un point de défense idéal, sinon pour un "mais". Il n'y a pas de porte. N'importe qui peut entrer. Donc c'est plus un piège qu'une forteresse. Si les ennemis se présentent, la seule issue est par la même ouverture où se trouvait la porte.

Les fournitures sont une grande motivation pour défendre cet endroit. Avec cet ensemble, vous pouvez survivre un hiver, deux hivers, et quelques mois de plus. Mais les armes sont clouées, alors nous devrons nous battre avec ce que nous avons apporté.

Si nous décidons de nous installer ici, la première chose que nous faisons est de chercher une porte. Ou des planches pour monter à l'entrée. Et on va essayer d'ouvrir ces boîtes. Parce que qui sait ce qu'il y a dedans ? Peut-être qu'ils vont contenir des clés de voiture. Ou les clés de ces armes. Ou juste plus de conserves. Mais la curiosité, Sam, va nous améliorer.

Rentrons. Mais reste calme.
