SPIDER-JOCKEY DU MINECRAFT SURVEILLANCE


CLASSE:      Spider-Jockey
MÉTABOLISME: Arthropodes + morts-vivants
PERCEPTION: Tandem tactique
TAILLE:       11 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Très élevé
ARMES:    Saut d'araignée, précision du squelette, tir élevé
RÉCOMPENSE:     350 FC
MENACE:     Très élevé

DESCRIPTION:

Le Spider-Jockey est un exemple rare mais extrêmement désagréable de deux ennemis relativement ordinaires qui décident soudainement de travailler ensemble. L'araignée massive fonctionne comme une plate-forme mobile, une unité d'assaut, et un véhicule de livraison, tandis que le squelette ci-dessus fait ce qu'il fait le mieux - tir à sang froid.

CONSEILS:

- Séparez-les le plus rapidement possible - individuellement, ils sont beaucoup moins dangereux.
