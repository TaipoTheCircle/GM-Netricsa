XEN, L'HISTOIRE DE NIHILANTH


Après avoir traversé le portail, nous sommes arrivés à l'un des sites les plus critiques de Xen : l'usine de Nihilanth. Ce n'est pas une simple forteresse, mais une machine vivante - un endroit où la technologie extraterrestre et la matière organique fusionnent dans un cycle de production sans fin.

L'atmosphère suffoque. Chaque paroi pulse comme la chair, conduit les battements d'énergie, et l'air vibre avec le bourdonnement constant des machines. Les vortigaunts, liés par des chaînes psychiques, sont contraints d'utiliser des dispositifs massifs - plates-formes de levage, conduits d'alimentation, et de maintenir les cuves où des armées entières sont cultivées.

C'est l'origine de l'infanterie extraterrestre. Les soldats de choc, les grogneurs, même les gardiens blindés sont élevés ici, en forme de biocapsules, et préparés pour une guerre sans fin.

En entrant, sa voix frappa l'air:

"Nous sommes tous esclaves... Nous sommes tous esclaves... Nous sommes tous..."

Nihilanth lui-même connaît la vérité - il est autant prisonnier que ceux qu'il a en esclavage.