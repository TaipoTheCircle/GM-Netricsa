METROCOPTE TACTIQUE DE PROTECTION CIVILE DE LA COMBINE


CLASSE:      Combiner la protecion civile tactique MetroCop
MÉTABOLISME: Humain, Homme
PERCEPTION: Combiner l'unité de lutte contre les agressions policières
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Pistol, SMG
RÉCOMPENSE:     450 FC
MENACE:     Moyenne

DESCRIPTION:

Le MetroCop tactique est une unité de transition entre la Protecion Civile régulière et les forces paramilitaires du Combine. Il est moins bien équipé, mais nettement plus agressif que les patrouilleurs ordinaires. Les pantalons de camouflage de l'armée verte l'identifient comme une unité d'assaut de rue, et le manque de manches met l'accent sur la mobilité et le combat rapproché, plutôt que sur une apparence formelle.

L'armure du corps noir couvre les organes vitaux et contient des amortisseurs intégrés, empêchant un coup de tête de causer la mort immédiate. Cela fait du Metrocop tactique un adversaire inopinément résistant pour ceux habitués à tout régler avec un seul coup précis.

Il porte l'arme standard d'un pistolet et d'un SMG, mais il est plus agressif, ferme activement la distance et essaie de surpasser ses cibles. Il est souvent utilisé pour le nettoyage des bâtiments, le contrôle des émeutes et les opérations dans les zones qui nécessitent une approche difficile, mais toujours « semblable à la police ».

CONSEILS:

- Ne compte pas sur les coups de tête.
- Dangereux à portée moyenne et étroite, surtout à l'intérieur.
- Mieux vaut l'éliminer de loin ou l'empêcher d'exploser.