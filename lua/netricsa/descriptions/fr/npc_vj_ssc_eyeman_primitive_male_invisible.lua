GNAAR PRIMTIF, MAL


CLASSE:      Gnaar primitif, Homme
MÉTABOLISME: Mammifère
PERCEPTION: Animal de guerre formé
TAILLE:       4 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Faible
ARMES:    Morceaux, coups de poing
RÉCOMPENSE:     700 FC
MENACE:     Très faible

DESCRIPTION:

Un petit animal bipède sans tête, un œil et une grande bouche. Originaire de Sirius, et entraîné par Mental à attaquer les forces opposées. Les mâles portent un pantalon en peau de léopard et sont plus petits et plus faibles que les femelles.

Ce sont les voisins des Gnaars tropicaux, qui faisaient autrefois partie de la même tribu, mais qui ont pris un chemin différent. Tandis que la branche tropicale stagnait dans son développement, ces gnaars trouvèrent une nouvelle foi : ils servaient fidèlement les Shamans femelles, accomplissant leur volonté et gagnant le droit de porter des marques distinctives.

Un mâle primitif diffère de son homologue tropical non pas en taille ou en forme, mais en coloration. Les primitrices ne portent que des motifs rouges partiels, appliqués sur leur corps sous forme de tatouages rituels et de rayures. Le détail le plus remarquable est le pantalon imprimé léopard, porté uniquement par les mâles de cette sous-espèce.

Dans leur temps libre, les gnaars primitifs se livrent à des activités inhabituelles. Ils peignent des tatouages de serpents jaunes et des égratignures sur des guêpes, revendiquant ainsi le bétail pour le leur. Les guêpes ne s'objectent apparemment pas, ou ont simplement peur de désobéir aux chamans. De plus, les Gnaars primitifs commercent souvent avec leurs voisins tropicaux, échangeant des marchandises volées pour ce dont ils ont besoin.

Malgré toutes ces différences culturelles, les Gnaars primitifs restent des serviteurs fidèles de Mental.

CONSEILS:

- Ils n'ont pas d'armes.
- Certains spécimens peuvent léviter.
- Des individus rares auraient été invisibles.
- La sous-espèce primitive est plus organisée que la sous-espèce tropicale, mais pas plus puissante.
