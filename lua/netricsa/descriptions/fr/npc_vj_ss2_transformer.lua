HUGO BOSS DU SIRIUS


CLASSE:      Hugo Boss 
MÉTABOLISME: Mécanique, Boss Robot
PERCEPTION: Robot-déstresse de bataille géant programmé et jouet de mental
TAILLE:       29,5 pieds
ENDURANCE:  Extrême
HOSTILITÉ:  Absolu
ARMES:    Fists, Lasers d'antenne, Lanceurs de fusées à épaule, Arm-Cannon, Jetpack Ram
RÉCOMPENSE:     5000 FC
MENACE:     Absolu

DESCRIPTION:

Le robot le plus avancé de toute l'armée de Mental. C'est le "pinnacle de l'ingénierie de Horde" : blindé au point d'invulnérabilité proche, armé aux dents, et capable de voler. En apparence, il ressemble à un jouet venu à la vie - un énorme robot avec une antenne sur sa tête, des lumières clignotantes, et sonne comme ceux d'un jouet d'enfant. Mais ce jouet tue.

Quand Mental décida de créer une armée capable de supprimer les poches de résistance dans l'univers, il se rendit compte que les soldats ordinaires ne suffisaient pas. Quelque chose de plus était nécessaire. Un symbole était nécessaire.

Le projet a été initialement appelé "CSS-00" - "Combat Siege System". Ce devait être un robot capable de détruire seul des armées entières et de résister aux attaques d'une flotte spatiale.

Mais Mental, qui n'a jamais eu bon goût, a insisté sur les changements.

"Faites comme un jouet", dit-il à l'ingénieur en chef.

"Mais, Maître, c'est une machine de combat!"

"J'ai dit, fais que ça ressemble à un jouet."

La deuxième exigence de Mental était une certaine « boîte »

"Le patron devrait sortir de la boîte. Cela ajoute du drame."

"On peut juste le mettre dans le hangar."

"En dehors de la boîte ! Et écrivez dessus 'Boss in the Box' pour que tout le monde sache."

Les ingénieurs soupiraient et roulaient leurs manches. La boîte a été faite. L'écriture a été appliquée. Hugo était emballé.

Plus tard, Hugo a été déployé sur le satellite Kronor, où il garde le système de contrôle du canon laser qui pénètre le bouclier Sirius.

Et il n'épargnera pas une âme.

CONSEILS:

- Hugo est invulnérable dans la première phase.
- Attaquez-le pendant le vol.
- Méfiez-vous des missiles et des boulets de canon.
