DÉMON, STORMCALLER, RÉPONDANT FÉDÉRAL


CLASSE:      Démon réptiloïde de Fiendian, Stormcaller
MÉTABOLISME: Brouillé à froid, comme un reptile
PERCEPTION: Race primitive modifiée
TAILLE:       30 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Haut
ARMES:    Tornades, griffes
RÉCOMPENSE:     8000 FC
MENACE:     Moyenne

DESCRIPTION:

Une autre mutation hideuse, grâce à Notorius Mental. Un simple organisme semblable à un lézard de Fiendia Prime a été croisé et muté pendant plusieurs générations, et a finalement été renforcé avec un squelette de titane. Il a une capacité unique de torsion de l'air environnant, atteignant des vitesses de vent jusqu'au niveau des tornades F2. Ces tornades miniatures finiront par se stabiliser et se dissiper, mais elles feront des ravages dans l'intervalle.

CONSEILS:

- Les tornades vont jeter des objets autour et rediriger des projectiles.
- Il n'y a aucun moyen de détruire les tornades du démon... Evitez-les jusqu'à ce qu'ils se dissipent.
