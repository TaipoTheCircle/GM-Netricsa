SHPAGIN 41 SUBMACHINE GUN (PPSH-41)


ARME:    Pistolet sous-machine Shpagin 41 (PPSH-41)
MUNITIONS:      7.62x25 Rondes
CADENCE DE TIR:       ~1000 Rondes / Min


DESCRIPTION:

La mitrailleuse Shpagin 41 a été développée par Georgy Shpagin pendant la Grande Guerre Patriotique. Il fut adopté par l'Armée rouge le 21 décembre 1940 et servit des soldats soviétiques jusqu'à Berlin puis en Mandchourie. Le PPSh-41 est considéré comme une arme de victoire et a à juste titre le statut d'arme légendaire. Cette arme est célèbre pour son taux élevé de tir et son aspect quelque peu inhabituel. Il utilise un magazine à tambour de 71 tours, qui était très gênant, et a ensuite été remplacé par un magazine de 35 tours, qui était beaucoup plus pratique. Dans les années 1960, il a été retiré du service dans l'armée soviétique et remplacé par le fusil d'assaut Kalachnikov. Mais ce n'était pas la fin de son histoire. Il a continué à être utilisé dans les conflits de la guerre froide, comme la guerre de Corée (1950-1953), la guerre d'Indochine (1946-1954), la guerre du Vietnam (1955-1975), etc. Aujourd'hui, cette arme appartient à de nombreux collectionneurs et amateurs d'armes ordinaires, et elle est également utilisée dans les guerres modernes, comme l'Afghanistan, l'Irak et le conflit russo-ukrainien.

REMARQUES:

- Ce pistolet à sous-machine est très efficace à portée étroite et moyenne, donc gardez l'ennemi sous le feu.
- Il a des modes à la fois automatiques et à prise unique, qui peuvent être commutés entre. Choisissez le mode de tir en fonction de la situation.
Cette arme peut être utilisée pour réprimer les ennemis du peuple.
