BIG-HEAD, DED123 228


CLASSE:      Grande tête, DED123 228
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     500 FC
MENACE:     Annoyance

DESCRIPTION:

Les grosses têtes sont de minces humanoïdes avec des crânes exagérés contenant le cerveau des développeurs. Ils portent l'uniforme Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan", ils reçoivent des modificateurs de feu et de glace. Ils apparaissent spontanément dans des zones secrètes, bloquant les passages avec leur nombre.

DED123 228 est une race rare de fan-enthousiasme, dont le crâne surdimensionné contient non seulement un amour pour le jeu, mais aussi un sentiment exagéré de justice et de respect pour la créativité des autres. Il est le créateur du mod "TROPICAL GNAARS - Ennemis Reskin" pour Serious Sam Classics: Revolution, où il a donné aux Gnaars classiques un camouflage tropical vibrant.

Quand Taipo a demandé l'autorisation de porter ses Gnaars tropicaux à GMod pour l'ajout "Sérieux Sam: Classic SNPC's (EXTRA)", DED123 228 n'a pas obstrué, demandé de commission, ou ignoré la demande. Il a généreusement donné son avis, comprenant qu'il élargirait l'univers de sa création et ravirait plus de joueurs.

Le croquis original et le design appartiennent à son ami Froel Hoates.

Il était une fois vivant, mais après que quelqu'un l'ait tué, il a été ressuscité - devenir un ange.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager un chemin.
- Sur la difficulté "Je suis Ugh-Zan", les détruire à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.
