GUERRE BLOODÉE DE LA HALF-QUAKE SHOW


CLASSE:      La garde du sang blessée
MÉTABOLISME: Humain, Homme
PERCEPTION: La garde et la victime des procès du spectacle
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Neutre
ARMES:    Pistol
RÉCOMPENSE:     60 FC
MENACE:     Faible

DESCRIPTION:

C'est un garde blessé dans l'uniforme gris que le spectacle sadique HALF-QUAKE donne à ceux qui acceptent de travailler pour eux pour la nourriture et une promesse de ne pas nuire à leur famille. L'uniforme est gris, non descriptif, avec un logo ">)" caché par le sang sur le dos. Les gardes portent eux-mêmes des armures, des casques et plusieurs jours de chaume. Et du sang. Beaucoup de sang. Leur propre et les autres'.

Chaque gardien doit éventuellement subir des tests sadiques. C'est une condition du contrat qu'ils ont signé sans lire la page finale. Les sadistes aiment les tourmenter. C'est leur nature. Les gardes sont battus, empoisonnés, ils sont forcés de traverser des labyrinthes de mort, et puis, s'ils survivent, ils sont autorisés à entrer dans l'arène en tant que « personnel de service » pour les victimes réelles du spectacle. Ceux qui ne survivent pas (presque toujours) font partie du paysage.

C'est votre allié temporaire et réticent. Il déteste les sadistes autant que vous, mais il est trop brisé pour se rebeller. Au mieux, il pourrait se détourner au bon moment. Au pire, il va simplement s'asseoir contre le mur et regarder jusqu'à ce qu'il soit tiré pour inaction.

Des gardes sont armés. Mais même avec des armes, ce ne sont pas des combattants. Ce sont des victimes qui n'ont pas encore réalisé qu'elles étaient déjà mortes.

CONSEILS:

- Ne les tuez pas. Ce sont les seuls qui peuvent vous aider avec des conseils ou des munitions.
- Si un gardien dit "Run", alors cours. Il a beaucoup vu.
- Les gardes savent où se trouvent les cellules, les cachettes et les sorties. Suivez-les s'ils vont quelque part avec un but.
- N'essayez pas de les sauver. Tu ne peux pas. Tu ne mourras qu'avec eux. Et ils mourront de toute façon.
