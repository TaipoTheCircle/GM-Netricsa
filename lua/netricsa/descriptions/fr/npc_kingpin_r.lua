KINGPIN R, ARCHPSION DE XEN


CLASSE:      Kingpin R, Archpsion de Xen
MÉTABOLISME: Essence psionique
PERCEPTION: Entité psionique de Xen
TAILLE:       12-15 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Très élevé
ARMES:    Blasts psioniques, contrôle mental, projectiles d'énergie orange, coups de foudre (incinération des cibles aux cendres)
RÉCOMPENSE:     10000 FC
MENACE:     Extrêmement élevé

DESCRIPTION:

Connu sous le nom d'Archipsion de Xen, le Kingpin est l'un des seigneurs de guerre psioniques les plus terrifiants de Xen. Sa forme grotesque - un cerveau exposé massif avec quatre paupières et une queue de vers pour la locomotion - est un moteur vivant de domination psychique et de destruction élémentaire.

La créature est constamment entourée d'un bouclier psionique, rendant les attaques directes presque inutiles jusqu'à ce que son énergie soit perturbée. Il lance des boulons de plasma orange et convoque des arcs de foudre capables de réduire la chair et la pierre à la fois à des cylindres.

Ce qui rend l'ArchPsion encore plus dangereuse est sa capacité à invoquer des hordes de bêtes xéniennes pour se battre à ses côtés. Parmi celles-ci, il y a des variantes uniques de calmars, chacun muté pour le combat élémentaire:

Devilsquid - à base de feu, crache des projectiles incendiaires qui enflamment tout.

Frostsquid - à base de glace, vaporise liquide de congélation qui immobilise les ennemis.

Poisonsquid - Violet, sécréte l'acide venimeux qui corrode les armures et empoisonne la chair.

Toxicsquid - Vert, propage des nuages biles corrosifs qui s'attardent et s'étouffent.

Hybridesquid - Blanc, agile, crache des boulons plasma blancs à grande vitesse.

Taureau standard - Prédateur classique, agressif et nombreux.

Les légendes parmi les créatures Xen décrivent le Kingpin comme un « lien vivant » de tempêtes psioniques - un commandant qui incarne le contrôle et la destruction.

CONSEILS:

- Concentrez-vous sur la perturbation de son bouclier psionique avant de faire de vrais dégâts.
- Restez mobile pour éviter ses coups de foudre et les impulsions de contrôle mental.
- Préparez-vous aux vagues de créatures convoquées - le contrôle de la foule est vital.
- Les engins anti-incendie et anti-toxine sont fortement recommandés.
