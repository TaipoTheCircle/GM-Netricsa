PROTECTION CIVILE DES COMBINES MINI METROCOP


CLASSE:      Combiner la protection civile Mini Metrocop
MÉTABOLISME: Humain, Homme
PERCEPTION: Opérateur du synthé de combat embarqué
TAILLE:       0,9 ft
ENDURANCE:  Faible
HOSTILITÉ:  Haut
ARMES:    MiniStrider Pulse Rifle Operator, pistolet
RÉCOMPENSE:     300 FC
MENACE:     Faible

DESCRIPTION:

Le Mini Metrocop est une unité expérimentale du personnel de Combine, réduite et logée dans la coque MiniStrider. Ces opérateurs effectuent l'entretien, le ciblage et le contrôle du fusil à impulsion embarqué, agissant comme une partie vivante du synthé de combat. Leurs corps sont soumis à une compression extrême, une stabilisation biomécanique et une fixation neuronale au système MiniStrider.

Contrairement aux plates-formes synthétiques entièrement autonomes, les MiniStriders avec de tels opérateurs présentent un comportement tactique plus flexible. Les réflexes humains et la capacité d'improviser leur permettent de choisir plus rapidement des cibles, d'ajuster le feu et de réagir aux menaces non conventionnelles. Essentiellement, c'est la tentative du Combine de combiner une machine froide et un esprit humain soumis dans un seul corps.

Dans de rares cas, lorsqu'un MiniStrider est détruit, le champ de compression déstabilise partiellement, et l'opérateur peut revenir à sa taille normale. Cependant, ce processus est incompatible avec la vie : la surcharge de tissus, d'organes et du système nerveux entraîne une mort inévitable, souvent en même temps que la destruction du synthétique lui-même.

Ces agents ne sont pas considérés comme des combattants à part entière et sont officiellement inscrits sur la liste des « ressources d'entretien durable ».

CONSEILS:

- Détruire un MiniStrider empêche automatiquement l'opérateur. - Un comportement plus précis de MiniStrider peut indiquer la présence d'un opérateur vivant à l'intérieur.
