VENDU D ' ANTI-VÉHICULE


CLASSE:      Combiner le surveillant antivéhicule Trooper
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Unité spécialisée antivéhicules
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Très élevé
ARMES:    SMG, lanceur de fusées, missiles antivéhicules
RÉCOMPENSE:     750 FC
MENACE:     Haut

DESCRIPTION:

L'Overwatch Anti-Vehicle Trooper est pratiquement indistinguable d'un standard Combiner soldat. Presque la même armure, la même posture, la même visière bleue froide. Une énorme erreur - il l'erreur pour "ordinaire". Son vrai rôle n'est révélé que lorsque des véhicules apparaissent sur le terrain.

Un lance-roquettes est monté sur le dos du soldat, et il peut être récupéré instantanément dès que le système reconnaît une cible dans un véhicule. Les véhicules, les véhicules blindés et les véhicules blindés improvisés de la résistance sont sa première priorité.

Le canon à sous-machine amélioré est utilisé pour l'autodéfense et la suppression de l'infanterie tandis que les soldats prennent position pour des véhicules d'attaque. Cependant, les combats prolongés ne lui posent aucun problème. Il agit rapidement, frappe fort et tente de changer de position immédiatement après avoir lancé une fusée, sachant que le feu de retour suivra immédiatement.

Le Combine utilise ces soldats pour neutraliser la mobilité de résistance. Un soldat antivéhicule a réduit un convoi de véhicules à la ferraille en quelques secondes.

CONSEILS:

- Ne l'approchez jamais dans un véhicule.
- Tuez-le d'abord, puis utilisez le véhicule.