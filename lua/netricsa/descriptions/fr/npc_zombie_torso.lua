ZOMBIE AU CŒUR


CLASSE:      TêteCrab Zombie, Torso
MÉTABOLISME: hôte parasitaire
PERCEPTION: Entité zombifiée
TAILLE:       3 pieds
ENDURANCE:  très faible
HOSTILITÉ:  élevé
ARMES:    griffes, morsure, saut court
RÉCOMPENSE:     100 FC
MENACE:     faible

DESCRIPTION:

Le Torso Zombie est les restes mutilés d'un hôte humain, animé par un cratère même après avoir perdu la plupart de son corps. Souvent rencontrées en rampant dans l'épave ou jetées à l'écart au combat, ces créatures se traînent en avant avec une vitesse surprenante, tremblant d'agonie alors que le parasite les pousse vers l'avant. Malgré leur état pitoyable, ils conservent suffisamment de force pour griffer à la proie ou tenter une morsure. Leur persistance grotesque les rend plus inquiétants que dangereux.

CONSEILS:

- Un seul coup bien placé suffit.
- Ne les laissez pas vous distraire pendant les grandes batailles - ils sont souvent utilisés comme "bruit" aux côtés de zombies plus forts.
- Surveillez vos bases dans les zones sombres; ils ont tendance à ramper hors des débris soudainement.
