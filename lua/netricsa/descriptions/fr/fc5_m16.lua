RISQUE D'ASSAULT M16


ARME: Rifle d'assaut M16
MUNITIONS:   5.56x45mm OTAN
CADENCE DE TIR:    ~650-750 tours/min
POIDS: ~2,88 kg

DESCRIPTION:

Ce fusil d'assaut américain, développé à partir de l'AR-15 par le designer Eugene Stoner, a été adopté pour la première fois en 1964 et a été largement utilisé pendant la guerre du Vietnam. Le M16 est devenu l'un des fusils d'assaut les plus fabriqués au monde, et diverses modifications sont encore en usage aujourd'hui.

Le fusil utilise un boulon rotatif à gaz et est en chambre pour la cartouche de 5,56x45mm. Les premiers modèles M16 et M16A1 utilisaient les munitions M193. Il est alimenté à partir de 20 ou 30 box magazines.

L'une des caractéristiques clés du M16 était son poids extrêmement léger pour un fusil d'assaut. Sa conception légère, son faible recul et son fort taux de feu l'ont bien adapté au feu lourd. De nombreuses variantes sont apparues plus tard, dont les M16A1, M16A2, M16A3 et M16A4.

REMARQUES:

- Fusil léger avec un taux élevé de feu, particulièrement adapté pour le feu automatique.
- Faible recul permet un bon contrôle de l'arme pendant l'éclatement.
- Le M16 pèse moins de trois kilos sans magazine. Pour un fusil, c'est pratiquement un régime.
- Le fusil qui a remplacé le M14 et a finalement acquis toute une famille de parents.
