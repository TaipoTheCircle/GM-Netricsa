RAZOR WING DE LA PLANTE TERRAFORME


CLASSE:      Aile rasoir
MÉTABOLISME: Insectoïde
PERCEPTION: Insecte volant prédatoire
TAILLE:       5,9 pieds
ENDURANCE:  Très faible
HOSTILITÉ:  Extrêmement élevé
ARMES:    Crache acide, piqûre, vitesse
RÉCOMPENSE:     150 FC
MENACE:     Haut

DESCRIPTION:

Les ailes de rasoir sont ce que vous obtenez si vous traversez une libellule avec un scorpion, ajoutez quelques jambes supplémentaires, et relâchez tout sur un continent volcanique.

Razor Wings a vécu une fois profondément sous terre jusqu'à ce qu'une éruption volcanique pousse leur ruche hors d'existence. Depuis, ces créatures causent régulièrement des problèmes à quiconque s'aventure dans sa zone de nidification.

Au combat, Razor Wings compte sur la vitesse et le nombre. Ils volent dans l'air plus vite qu'un humain peut courir au sol, et attaquer dans un essaim.

Leur arme principale est la crachat acide. L'acide non seulement se nourrit de la chair, mais ralentit également le mouvement.

Razor Wings eux-mêmes meurent d'un seul coup d'arme, mais le problème est qu'il y en a toujours beaucoup. Beaucoup.

CONSEILS:

- Un coup, un monstre. Ne sauvez pas les munitions, mais ne paniquez pas.
- Les armes à feu rapides sont la meilleure solution au problème des essaims.
- Si une aile de rasoir crache, détendez-vous. L'acide te colle et te ralentit.
- Ne te laisse pas encerclé. Dans un champ ouvert, un essaim vous fera tomber dans quelques secondes.
