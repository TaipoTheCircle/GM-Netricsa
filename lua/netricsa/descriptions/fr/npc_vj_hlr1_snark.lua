NARK DE XEN


CLASSE:      Snork
MÉTABOLISME: insectoïde carnivore (origine Xen)
PERCEPTION: Insecte étranger
TAILLE:       6 en
ENDURANCE:  extrêmement faible
HOSTILITÉ:  absurdement élevé
ARMES:    morsure, tactique d'essaim, autodestruction (par accident)
RÉCOMPENSE:     50 FC
MENACE:     moyenne (en groupes)

DESCRIPTION:

Le Snark est essentiellement un cafard qui a bu trop de café et décidé que la violence était un mode de vie. Originaire de Xen, ces petites créatures sont libérées d'œufs comme des grenades biologiques. Une fois relâchés, ils se précipitent immédiatement vers la forme de vie la plus proche, mordant furieusement avec zéro sentiment d'auto-préservation.

Malheureusement pour eux (mais chanceux pour vous), ils ont aussi une durée de vie hilarantement courte - s'ils ne vous tuent pas rapidement, ils explosent juste dans une bouffée d'enthousiasme gory. Les résistants plaisantent souvent que les Snarks sont des « bombardiers de suicide avec ADHD »

CONSEILS:

- Ne panique pas. Un Snark est juste un soulagement comique.
- Une douzaine de snarks ? La comédie se transforme en horreur.

PRO TIP: 

- Jetez-les dans une foule d'ennemis pour un maximum de chaos.
