DESCRIPTION:

Adrian Shepard est caporal de marine des États-Unis et membre de l'unité de combat pour l'environnement dangereux d'élite (U.S.E.C.), affecté au centre de recherche Black Mesa, où un incident inattendu impliquant des étrangers et une brèche dans les barrières spatiales-énergie a éclaté.

Il fait partie d'une partie d'atterrissage envoyée d'abord pour éliminer la menace étrangère, puis pour couvrir l'incident et « neutraliser les témoins ». Cependant, après que son hélicoptère de transport ait été abattu, Shepard se retrouve séparé de son équipe et contraint de se battre pour la survie dans l'escalade du chaos.

He has standard Marine gear: armure corporelle, masque à gaz, lunettes de vision nocturne, et une arme de l'U.S.E.C., faisant de lui un adversaire dangereux pour les forces spéciales de Mesa et d'Ops noires, ainsi que d'autres forces qui émergent pendant les événements.

CONSEILS:

- Son expérience de combat le rend dangereux à portée de main, mais sans équipement lourd, il est vulnérable.
