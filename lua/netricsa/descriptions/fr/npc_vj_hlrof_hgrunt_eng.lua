S.E.C.U


CLASSE:      H.E.C.U. Ingénieur de combat
MÉTABOLISME: Humain, Homme
PERCEPTION: Spécialiste en génie
TAILLE:       6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut 
ARMES:    Pistol, couteau de combat, explosifs déployables, torche à souder
RÉCOMPENSE:     600 FC
MENACE:     Modéré individuellement, élevé dans les situations tactiques

DESCRIPTION:

C'est un spécialiste formé au combat qui manipule activement l'environnement pour contrôler l'accès et piéger les intrus. À l'aide de torches de soudage et d'explosifs, ils peuvent couper à travers des portes verrouillées pour entrer dans des zones restreintes ou SEALexits, forçant les ennemis dans des espaces confinés.

Bien qu'ils ne soient pas des combattants de première ligne, ils se défendent agressivement avec des pistolets et des couteaux, et leur capacité à manipuler des portes les rend particulièrement dangereux dans les couloirs et les installations fermées. Ils opèrent souvent en paires ou en petits groupes, assurant des points d'étranglement tandis que le reste de l'équipe avance.

CONSEILS:

- Empêcher les ingénieurs d'atteindre les portes - ils peuvent vous piéger ou vous flanquer autrement.
- Les explosifs, ou les attaques variées peuvent les neutraliser avant de terminer la soudure.
- Soyez conscient des environs - une fois qu'une porte est scellée, les voies d'évacuation sont limitées.
