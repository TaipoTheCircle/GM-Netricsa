MESA BLACK, EXPÉRIMENT DE PARALLÈLE BAD


Vous avez sauté dans leur version improvisée de la clé siriane à l'éternité. Pendant un moment, ça a marché - vous étiez à nouveau à l'intérieur de Xen, sentant son air sans poids, entendant son humiliation sans fin. Mais avant de pouvoir agir, les Vortigaunts sont intervenus. Ils t'ont traînée en te jetant du portail et en entrant dans Black Mesa une fois de plus.

Dans le même temps, dans une autre aile, l'Anti-Mass Spectrometer s'est effondré sous les soins d'un autre Sam. La cascade de résonance a percé l'installation, et votre expérience a également été brisée. Le prototype Time-Lock a explosé - instable, cassé, effacé. Un grogneur extraterrestre a réussi à passer avant l'explosion... seulement pour être déchiré avec la machine elle-même.

Maintenant, tout est déroutant. Le spectromètre est détruit. Le Time-Lock a été détruit. Toute l'installation craque aux coutures. Quelque part dehors, l'autre vous êtes déjà sur le chemin vers Nihilanth.

Ce qui signifie que vous avez une fenêtre étroite. Avancez tant que vous le pouvez.

Bonne nouvelle - vous n'avez pas à sauver le monde deux fois. Mauvaise nouvelle - tu dois encore te sauver.