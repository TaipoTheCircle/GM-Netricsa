KALASHNIKOV LUMIÈRE MACHINE GUN (RPK)


ARME: Kalashnikov mitrailleuse légère (RPK)
MUNITIONS:   7,62x39 mm
CADENCE DE TIR:    ~600 tours/min

DESCRIPTION:

Une mitrailleuse soviétique mise au point par Mikhail Kalachnikov, basée sur le fusil d'assaut AKM et adoptée pour le service en 1961. Il a été conçu pour augmenter la puissance de feu d'une unité d'infanterie. Il dispose d'un canon plus long et plus lourd, d'un récepteur renforcé, d'un bipode et d'un stock en bois.

Le RPK utilise une action au gaz avec un boulon rotatif et est capable de feu semi-automatique et entièrement automatique. Elle est alimentée par des magazines de 40 tours ou 75 tours de tambour. En raison de son degré élevé de parties communes avec d'autres armes à feu Kalachnikov-pattern, le RPK est facile à entretenir et très fiable sur le terrain.

REMARQUES:

- Développé sur la base du fusil d'assaut AKM.
- Le baril plus long permet un engagement plus efficace à de plus grandes distances.
- Le magazine à tambour de 75 tours augmente considérablement la capacité de munitions.
- Le RPK a connu de nombreuses modifications, y compris des versions en chambre pour la cartouche de 5,45x39 mm.
- Si un Kalachnikov standard ne suffit pas, ajoutez simplement un bipode et quelques munitions supplémentaires.
