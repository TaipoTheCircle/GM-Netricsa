MARSH-HOPPER DE LA KENTAURE RIGILE, HUE


CLASSE:      Marsh-Hopper de Rigil Kentaurus, Énorme
MÉTABOLISME: amphibiens terrestres
PERCEPTION: animaux sauvages
TAILLE:       26 pieds (debout)
ENDURANCE:  aucune
HOSTILITÉ:  extrême
ARMES:    éclaboussures toxiques
RÉCOMPENSE:     5000 FC
MENACE:     très faible

DESCRIPTION:

Un étrange organisme issu de friches marécageuses du système de Rigil Kentaurus. Ils vivent en grands groupes et ont l'instinct suicidaire de protéger leur territoire. Dans les ravages dévastateurs, tous les individus essaient de sauter à l'intrus et d'exploser, en se gonfleant trop. Au moment de l'explosion, la boue toxique contenue dans leurs intestins éclabousse la cible.

Le favori de Mental et le sommet de ses expériences de taille est le Léviathan rouge, deux fois plus grand que son prédécesseur déjà gigantesque. Son corps cramoisi se sert de milliers de litres de liquide toxique. Mais le secret principal et la surprise pour quiconque décide de l'attaquer sont à l'intérieur. Mental a placé une soixantaine de Leapers microscopiques dans des bulles d'incubateurs spéciales dans son corps. Tuer le Léviathan n'est que le début d'un vrai cauchemar. À sa mort, le corps explose, libérant non seulement une mer de poison, mais aussi un essaim de minuscules, presque invisibles, incroyablement rapides et mortelles Leapers qui attaquent instantanément toutes les choses vivantes dans le rayon de l'explosion.

CONSEILS:

- Ne le laisse pas se rapprocher. Attaque de portée maximale.
- Détruisez le corps. Préparez-vous à reculer immédiatement ou à utiliser une arme à feu (flamethrower, lance-grenades) contre l'essaim des micro-lacets qui s'est échappé. - Oui. Il vaut mieux déclencher son explosion à distance, en utilisant des explosifs à distance ou des leurres pour détruire le corps principal et l'essaim caché en même temps, sans se rapprocher trop.