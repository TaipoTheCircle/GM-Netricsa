MESA BLACK, LE CAPSULE DE LA GUERRE XEN


Ouf... sortir de cette usine de broyage semblait sortir d'un broyeur de viande. Et juste quand je pensais que la journée ne pouvait plus nous surprendre, devinez quoi ? Oui.

Tout en analysant le secteur que nous venons d'entrer, j'ai pris quelque chose d'inhabituel-quelque chose de bien plus grand que les cabillauds ou même les vortiguants. Il s'avère que nous venons de trébucher sur la première observation confirmée d'un guerrier Xen. Pas votre alien moyen grogne, pas monsieur. Ce type est la vraie affaire, un commandant de première ligne décoré du côté Xen (et un déserteur). Il est enfermé dans une cellule de confinement, gardé, étudié... mais très vivant.

Historical data cross-check: Les Grunts Alien sont considérés comme l'épine dorsale des troupes de choc interdimensionnelles. Plus fort, plus intelligent, et avec assez de puissance de feu pour prendre des équipes entières. Ils n'étaient jamais censés se présenter aussi tôt dans le conflit. Ce qui fait sa présence ici... disons juste "concernant"

Voici la partie intéressante : la télémétrie suggère qu'il est juste là. Regarde. Presque comme s'il attendait quelque chose... ou quelqu'un. Et entre nous, je n'aime pas ce regard.

Donc, pour résumer :

Nous avons échappé à la mort par convoyeur.

Nous sommes accueillis par les chiens.

Et oh oui, nous venons de rencontrer le premier Alien Grunt de cette guerre.

