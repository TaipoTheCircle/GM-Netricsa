TRENCH DAGGER MODÈLE 1916 "LE VENGEUR"


ARME: Trench Dagger Modèle 1916 "Le Vengeur"
MUNITIONS:   N/A
CADENCE DE TIR:    Armes à main

DESCRIPTION:

Une dague de combat française s'est développée pendant la Première Guerre mondiale pour être utilisée dans la guerre des tranchées. Il était basé sur des couteaux de tranchée et des baïonnettes, avec un design proposé par le couturier Astier-Prodon. Il a été adopté pour le service en 1916. Prévue pour des combats de quartiers rapprochés dans les limites des tranchées, elle a valu le surnom « Le Vengeur », qui se traduit par « Le Vengeur »

Il dispose d'une lame robuste à double tranchant avec une section en forme de diamant, une poignée en bois et un garde-corps en métal pour protéger la main. La longueur totale est d'environ 28 cm, avec une longueur de lame d'environ 17 cm. Quelques exemples portent l'inscription « Le Vengeur de 1870 », une référence à la défaite de la France dans la guerre franco-prussienne. Il a été fabriqué par plusieurs entreprises françaises.

REMARQUES:

- Efficace exclusivement dans le combat à proximité.
- La longueur de la lame est d'environ 17 cm.
- Le poids est d'environ 200 grammes (à l'exclusion du fourreau).
- Utilisé par l'infanterie française et les équipages des premiers chars.
