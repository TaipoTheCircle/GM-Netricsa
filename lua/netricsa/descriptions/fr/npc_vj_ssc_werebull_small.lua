SIRIAN WEREBULL, MOUSSE


CLASSE:      Sirian Werebull, souris
MÉTABOLISME: mammifère
PERCEPTION: animal de travail
TAILLE:       0,8 ft
ENDURANCE:  faible
HOSTILITÉ:  moyenne
ARMES:    cornes
RÉCOMPENSE:     2000 FC
MENACE:     moyenne

DESCRIPTION:

Croisé avec des gènes mélangés de Sirians et une sorte de bétail. Le Werebull se comporte comme un taureau ordinaire et attaque avec ses cornes en chargeant.

Mental, essayant d'améliorer leur adaptabilité, accidentellement ajouté des gènes de souris, ce qui a entraîné une réduction spectaculaire de la taille. Les hybrides miniatures ont échappé aux laboratoires et infesté les donjons de la Perse antique, s'adaptant à la vie dans les trous de souris. En maintenant les habitudes de leur ancêtre, ils attaquent de l'obscurité de leurs tunnels, visant à arracher leur proie avec leurs cornes tranchantes mais microscopiques. Ils sont dangereux principalement en raison de leur surprise et de leur nombre.

CONSEILS:

- Éloignez-vous de la ligne d'attaque.
- Si vous entendez un bruit dans le terrier, c'est lui.