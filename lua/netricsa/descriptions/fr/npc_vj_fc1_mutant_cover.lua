COUVERTURE MUTANT (MERCENAIRE) DE L'ARCHIPELAGO KRIEGER


CLASSE:      Mutant de couverture (mercenaire)
MÉTABOLISME: Mutation trigénique précoce
PERCEPTION: Opérateur de couverture tactique
TAILLE:       7,5 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Adaptatif
ARMES:    Lance-missile, M249, fusil de chasse
RÉCOMPENSE:     2004 CF
MENACE:     Critique

DESCRIPTION:

Le mutant de couverture se distingue par sa carapace biologique développée sur ses épaules et une double rangée de dents. Il conserve une intelligence élevée et peut produire des modes de parole complexes. Il fait preuve de souplesse dans le combat, en utilisant diverses armes, dont un lanceur de missiles guidé.

CONSEILS:

- Sa carapace protège uniquement son haut du corps.
