LUMIÈRES


ARME: Pistolet éclair
MUNITIONS: Charges énergétiques
CADENCE DE TIR: ~550 tours/min


DESCRIPTION:

Le Lightning Gun tire des arcs continus de foudre qui percent à travers plusieurs cibles en ligne droite, apportant des dommages subis au fil du temps. Excellent pour engager des ennemis dans de longs couloirs ou formations groupées. Le faisceau apparaît comme une décharge électrique reliant le tireur et la cible.

REMARQUES:

- Capable de percer plusieurs cibles le long d'une ligne de feu.
- Efficacité réduite par les obstacles et les blocages de la ligne de vue.
- La consommation d'énergie est élevée - le feu gaspillé dans les réserves d'égouts vides.
- Mieux utilisé à partir de positions préparées avec un mouvement latéral minimal des ennemis.