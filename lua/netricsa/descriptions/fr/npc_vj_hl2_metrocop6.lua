PROTECTION CIVILE DES COMBINES


CLASSE:      Combiner la protection civile Metrocop Shield Guard
MÉTABOLISME: Humain, Homme
PERCEPTION: Garde de protection civile contre les agressions
TAILLE:       9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Haut
ARMES:    Bouclier tactique, stun Stun-Stick
RÉCOMPENSE:     350 FC
MENACE:     Moyenne

DESCRIPTION:

Le Shield MetroCop est un agent de protection civile spécialisé, conçu pour réprimer les émeutes et contrôler les foules denses de citoyens. Contrairement aux patrouilleurs réguliers, il opère sur les lignes de front, absorbant les coups, les coups de feu et les tentatives désespérées de résistance.

Son uniforme tactique noir est orné de panneaux jaunes sur les épaules et les avant-bras, servant de marqueurs visuels de son rôle et de son unité. Un masque blanc cache complètement son visage, empêchant les ennemis de lire ses émotions ou intentions.

L'équipement primaire est un bouclier tactique gris avec un symbole de combinaison jaune. Le bouclier est utilisé non seulement pour la défense, mais aussi comme moyen de pression: il peut être utilisé pour repousser, épingler les adversaires contre les murs, et briser les formations de foule. Derrière le bouclier, le Guardian avance lentement et sans relâche, poussant les adversaires dans des zones prédéterminées.

L'apparition des Gardiens avec des boucliers marque presque toujours le début de la phase de suppression active.

CONSEILS:

- Attaque par les flancs ou par derrière - une attaque frontale est inefficace.
- Le bouclier réduit les dommages, mais limite la visibilité du porteur.
