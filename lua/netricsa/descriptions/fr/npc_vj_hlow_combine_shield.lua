COMBINE SURVEILLANCE SHIELDIER


CLASSE:      Combiner Overwatch Shieldier
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner l'infanterie de protection contre les agressions
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Combiner le pistol, le bouclier tactique
RÉCOMPENSE:     450 FC
MENACE:     Moyenne

DESCRIPTION:

Le Shieldier Overwatch est un mur mobile de feu Combine, conçu pour avancer sous le feu. Il ne porte pas d'armure lourde, s'appuyant sur un bouclier noir massif avec des marques CMB qui couvre presque tout son corps. Le bouclier est recouvert d'un revêtement composite et peut résister au feu et aux éclats de fusil automatiques.

Les visières bleues identifient la variante standard Overwatch, mais le comportement de ce soldat est différent. Il ne cherche pas la couverture, il devient la couverture. Le soldat avance lentement, couvrant ses alliés et permettant aux unités d'assaut de progresser derrière lui.

Le pistolet est utilisé de derrière le bouclier avec une main, le plus souvent pour la suppression à portée de main. Au combat rapproché, le soldat peut tirer le pistolet, frapper les ennemis et les ouvrir pour finir.

Ces soldats sont utilisés dans les couloirs, pendant la clairière, la répression des émeutes et les opérations de rue où la défense frontale est essentielle. Le Combine les utilise comme barricades mobiles sous lesquelles le reste de l'infanterie avance.

CONSEILS:

- Ne tirez pas sur le bouclier-il vaut mieux flanquer ou au-dessus.
- Les explosifs et le feu sont efficaces pour le tuer.
- Il est vulnérable de part et d'autre, surtout sans soutien. - Oui. S'il s'approche, préparez-vous à des coups.