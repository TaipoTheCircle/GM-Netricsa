PRESCRIPTIONS DE PRESCRIPTION


CLASSE:      Frost Snark
MÉTABOLISME: Insecte carnivore (mutation cryogène)
PERCEPTION: Insecte étranger, glace vivante
TAILLE:       6 pouces
ENDURANCE:  Faible
HOSTILITÉ:  Très élevé
ARMES:    Morceaux de givre
RÉCOMPENSE:     100 FC
MENACE:     Haut

DESCRIPTION:

Il s'agit d'une mutation naturelle du snark commun, originaire des régions glacées de Xen. Là où les vents hurlent si fort qu'ils refroidissent les os et la glace dure des milliers d'années, les pièges communs ne peuvent survivre. Mais l'évolution a trouvé un moyen: ceux qui survivent ont évolué en insectes bleus dont les coquilles brillent de l'intérieur avec une lumière glacée et froide.

Contrairement à leurs frères, qui explosent avec un enthousiasme débordant secondes après l'éclosion, les pièges de gel ne sont pas sensibles à l'autodestruction. Ils peuvent vivre longtemps. Très longtemps. Et tout ce temps, ils vont essayer de vous geler. Ou vous dévorer. Ou les deux.

Ils portent une coquille complètement bleue avec des veines bleuâtres qui pulsent comme de la glace dans un glacier. De loin, ils brillent et réfléchissent la lumière, ce qui les rend faciles à repérer. Mais dès que vous vous approchez, ils disparaissent de la vue, se mêlant à la neige et à la glace.

Une morsure de givre n'est pas seulement douloureuse, elle gèle sa cible. Un coup, et tu commences à ralentir. Deux, et vous ne pouvez plus courir. Trois, et vous restez là, une statue sans défense de chair et de glace, jusqu'à ce que le paquet vous termine. Les survivants disent que ces créatures s'attaquent délibérément en groupes pour s'infliger un effet glacial, paralysant leurs victimes avant de pouvoir tirer.

Comme leurs voisins de type feu, les pièges au givre sont constamment en conflit avec les calmars au givre. Le conflit dure aussi longtemps qu'avec leurs homologues du feu. Personne ne se souvient de la cause. Peut-être que les taureaux ont marché sur la banquise préférée de quelqu'un. Peut-être que les pièges ont mangé des cristaux. Ou peut-être qu'ils se détestent tout simplement à cause de leur couleur de coquille.

Quand on meurt, un givre ne meurt pas simplement. Elle se désintègre en morceaux de glace, laissant derrière elle une flaque d'eau gelée qui dure longtemps.

CONSEILS:

- Ne t'approche pas trop d'un givre. Il n'explose pas comme un noir normal, mais sa morsure gèle.
- Vous pouvez les repérer à distance par la glace qu'ils produisent. Utilisez un fusil à sniper.
- Ils sont doublement dangereux. Gardez vos distances.
- Frost Snarks ne meurt pas tout seul.
- Si vous voyez un paquet, utilisez des explosifs. Ils n'ont pas peur du froid, mais une explosion est une autre question.
- Frost Snarks et Frost Bullsquids se détestent. Si possible, mettez-les l'un contre l'autre. Qu'ils se tuent.
- Les grenades thermiques fonctionnent mieux contre elles que les grenades régulières. La chaleur et le froid sont de mauvais fellows.
