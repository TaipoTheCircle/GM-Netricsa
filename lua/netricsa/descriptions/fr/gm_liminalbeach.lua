BORDER BEACH, OÙ TOUT EST EN DANGER


Sam, j'ai analysé cet endroit et... Je suis sans voix.

Et si je le fais, ils sont perdus quelque part entre "WTF!?" et "Pourquoi cet endroit se sent-il si effrayant?".

Imaginez une plage qui n'a jamais vu le soleil, une piscine où personne n'est jamais tombé, et un gratte-ciel construit simplement parce qu'ils pouvaient.

Ajoutez à ça une poupée haut en haut, vous regardant clairement, et vous avez Border Beach.

Le ciel ici est un personnage en soi. Des nuages lourds et épais s'accrochent si bas qu'il semble que vous puissiez sauter d'une planche de plongée pour les atteindre.

Qu'y a-t-il ici 

Une immense piscine, l'absurdité ultime. Pourquoi avoir une piscine sur une plage ? C'est comme apporter un thermos de thé dans un sauna. Mais c'est là. L'eau est noire, toujours, comme un miroir que vous avez peur de regarder. A proximité sont des tables et des chaises en bois.

Comme si quelqu'un avait prévu un pique-nique sur le bord de la réalité, mais a changé d'avis à la dernière minute.

Le gratte-ciel obélisque est un monolithe qui monte droit dans les nuages. C'est clairement la force dominante ici. Énorme, sombre, écrasante. Tu le regardes et tu te sens comme une fourmi devant une chaussure. Il ne reste pas là, il... presse. Avec sa présence.

La poupée là-haut-et ça, Sam, est la chose la plus étrange. Quelque part là-haut, sur un rebord, se trouve une petite poupée. Il ne bouge pas, il ne fuit pas, il s'assied et regarde en bas. Chez nous. Ou par nous. Je dirais que c'est la blague stupide de quelqu'un, mais il n'y a pas de blagues dans un endroit comme celui-ci.

Je n'ai pas de données claires. Mes algorithmes ne peuvent pas traiter cet endroit complètement. La logique est brisée ici, la géométrie est brisée, le but même de l'existence de cette plage est brisé. C'est l'espace liminal dans sa forme la plus pure-un endroit qui devrait être familier mais se sent étranger. Vous êtes censé vous détendre ici, mais vous voulez courir sans regarder en arrière.

Tu sais, Sam... marchons vite sur cette plage, allons ailleurs, et prétendons qu'on n'était pas là. Allons-y. Et pour l'amour du ciel, ne regarde pas en arrière.
