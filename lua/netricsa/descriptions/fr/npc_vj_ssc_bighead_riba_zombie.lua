ZOMBIE, ROYAUME-ROMAN


CLASSE:      Big-Head Zombie, Roman Ribaric
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:    Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     100 FC
MENACE:     Annoyance

DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme de Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais sur le niveau de difficulté "Je suis Ugh-Zan", ils gagnent du feu et des modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Roman Ribaric n'est pas seulement le cofondateur et le PDG de longue date de Croteam. C'est le principal moteur, le visionnaire et le principal instigateur de toute la folie que vous voyez à l'écran. Son crâne surdimensionné est la source de l'impulsion initiale : c'est lui qui a rêvé du nom "Sérieux Sam", qui a remplacé le titre de travail "Dans la chair". Non seulement il a développé des stratégies d'affaires, mais il a aussi respiré la vie dans l'ennemi le plus célèbre de la série, enregistrant le cri légendaire et déchirant du Kamikaze sans tête.

Sa philosophie de gestion-indépendance et de créer des jeux que vous voulez jouer-a permis à Croteam de survivre et de prospérer. Son génie caché en tant que concepteur s'est manifesté dans l'idée du niveau secret "Sacred Yards" dans The First Encounter, qui peut être complété sans tuer un seul ennemi-un joueur secret seulement découvert 14 ans plus tard. Roman est le cerveau qui a d'abord généré l'idée, puis créé les conditions pour que cette idée évolue dans le chaos, la créativité et les jeux emblématiques. Sans son sommeil et ses cris, rien n'existerait.

Il était une fois vivant, mais après que vous l'ayez tué dans le Temple de Hatshepsut, il est sorti d'un Zombie démoniaque.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager le chemin.
- Sur la difficulté "Je suis Ugh-Zan", les détruire à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.