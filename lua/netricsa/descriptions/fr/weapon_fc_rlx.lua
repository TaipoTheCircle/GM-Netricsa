RLX-9157 M202A1 LAUNCHER FLASH


ARME: RLX-9157 M202A1 Lance-roquettes Flash
MUNITIONS:   66mm M74 Rockets
CADENCE DE TIR:    ~30 rondes / min
POIDS: ~12 kg

DESCRIPTION:

Un lance-roquettes lourd et à tir multiple conçu pour engager des ennemis et détruire des cibles avec une force explosive. Il s'agit d'un système portable avec plusieurs tubes de lancement, permettant de tirer des fusées l'une après l'autre sans avoir à recharger immédiatement après chaque tir.

Les fusées sont très destructrices et particulièrement efficaces contre des groupes d'ennemis, de fortifications et de grandes cibles. La grande capacité de munitions du lanceur permet de lancer plusieurs fois, ce qui en fait une arme de soutien extrêmement dangereuse.

Malgré sa taille impressionnante, le M202A1 reste portable et peut être utilisé par un seul soldat.

REMARQUES:

- Un lance-roquettes multi-coups.
- Les fusées causent d'importants dégâts explosifs.
- Efficace contre des groupes de cibles et des adversaires lourds.
- Le plus efficace à moyen ou long terme.
- L'explosion est dangereuse pour l'utilisateur si elle est trop près d'un obstacle ou d'une cible.
