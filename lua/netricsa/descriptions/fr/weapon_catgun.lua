M1A0 CAT-GUN


ARME: M1A0 Cat-Gun
MUNITIONS:   tours 9x19mm
CADENCE DE TIR:    ~750 tours/min

DESCRIPTION:

Une arme inhabituelle qui prend la forme d'un chat orange portant un collier rouge. Malgré son apparence adorable, le M1A0 est l'un des plus formidables pièces d'armes autour. Il tire des balles standard directement de la bouche de l'animal.

Pour manier le Cat-Gun, vous devez le tenir par ses pattes avant et arrière. Le rechargement se fait en caressant le chat, un système d'entretien simple mais hautement non conventionnel qui maintient l'arme prête au combat.

REMARQUES:

- Ne soyez pas dupé par son apparence charmante !
- Des balles de sa bouche.
- Il suffit de caresser le chat pour recharger.
- Les pattes avant et arrière.
- L'arme la plus flufiante de tout l'arsenal.
