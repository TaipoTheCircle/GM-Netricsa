COMMANDANT ZORG DE BEELMEZ IV


CLASSE:      Zorg, commandant
MÉTABOLISME: mammifère
PERCEPTION: race des guerriers
TAILLE:       7 pieds
ENDURANCE:  faible
HOSTILITÉ:  faible
ARMES:    laser d'éclatement de balayage
RÉCOMPENSE:     800 FC
MENACE:     faible

DESCRIPTION:

Mental a transporté ces soldats sur la Terre d'une partie inconnue de l'univers. Ils étaient autrefois une race de guerriers redoutables mais comme ils ont conquis plus de planètes qu'ils ne savaient quoi faire, ils ont décidé de ralentir pendant un certain temps. La plupart de la population a pris des vacances de longue date sur l'une des plus belles planètes tropicales de leur système; mais comme ils ne baignaient que du soleil de 10h à 16h, après quelques années, la plupart d'entre eux n'avaient plus de peau sur leur corps. Seulement quelques-uns des chanceux (avec des bouts de peau laissés), ont immédiatement été promus aux commandants - ce qui signifiait généralement obtenir un plus gros pistolet, porter des sous-vêtements en public, et ne pas laisser des taches sanglantes sur tout ce qu'ils touchent.

CONSEILS:

- Ils balayent la zone devant eux avec plusieurs prises laser.