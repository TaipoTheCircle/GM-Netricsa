LANCEMENT PORTABLE


ARME: Lanceur portable
MUNITIONS:   Missiles de fusées chauffés (ogives HEAT)
CADENCE DE TIR:    ~17,6 tours/min.

DESCRIPTION:

Une arme d'infanterie lourde utilisée par les lance-missiles pour détruire les véhicules blindés, les fortifications et les concentrations denses de cibles. C'est un système de lanceur portable qui tire des projectiles de fusée chauffés avec une puissance pénétrante élevée.

L'ogive en forme de charge est conçue pour détruire les fortifications et pénétrer l'armure lourde, tandis que l'explosion crée une zone de dommages supplémentaires dangereux pour le personnel. Malgré son taux de tir relativement faible, chaque missile possède une puissance destructrice importante et peut renverser la vague de combat avec un seul coup précis.

En raison de sa masse et de son taux de tir limité, l'arme est plus souvent utilisée à distance ou à l'abri, ce qui permet aux lance-missiles de soutenir les équipes d'assaut par des tirs lourds.

REMARQUES:

- efficace contre les véhicules blindés, les fortifications et les cibles lourdes.
- L'explosion cause des dégâts et crée une onde de choc.
- Plus efficace à moyen et long terme.
- Dangereux à portée de main; le tir à proximité de l'utilisateur entraîne souvent des conséquences fatales.
- L'ogive en forme de charge est capable de détruire les fortifications et de pénétrer l'armure lourde.
- La lenteur de la vitesse pratique du feu est compensée par sa puissance destructrice élevée.
