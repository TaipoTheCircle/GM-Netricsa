POISSON HEADCRAB ZOMBIE


CLASSE:      Cervidés Zombie, Poison
MÉTABOLISME: hôte parasitaire (têtes multiples)
PERCEPTION: Entité zombifiée
TAILLE:       7-8 pieds
ENDURANCE:  très élevé
HOSTILITÉ:  très élevé
ARMES:    griffes, tubercules de poison
RÉCOMPENSE:     400 FC
MENACE:     élevé

DESCRIPTION:

Cette créature grotesque est le résultat d'un hôte humain dépassé non par un, mais plusieurs cratères-spécifiquement la variété toxique. Leur cadre enflammé et pourri s'échelonne lentement mais est presque impossible à ignorer. Le parasite conduit le corps dans une frénésie, déchirant et jetant des égratignures toxiques aux ennemis. La chair de l'hôte s'accroche lâchement à ses os, ce qui la rend plus morte que l'homme. Chaque gémissement qu'il prononce est un rappel glacial de ce qui vivait autrefois à l'intérieur.

CONSEILS:

- Restez loin, les cambrioleurs de poison peuvent vous paralyser instantanément.
- Ciblez les cratères qui s'accrochent à son corps pour une mort plus facile.
