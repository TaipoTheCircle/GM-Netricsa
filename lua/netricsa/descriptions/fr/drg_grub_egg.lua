SWARM GRUB SAC


CLASSE:      Swarm Grub Sac
MÉTABOLISME: Xénobiologique
PERCEPTION: Organisme stationnaire
TAILLE:       4 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Faible
ARMES:    Décharge de Grub
RÉCOMPENSE:     75 FC
MENACE:     Faible

DESCRIPTION:

Le Swarm Grub Sac est un sac organique stationnaire dans lequel le Swarm Grub se développe. Sa coque externe est solide et élastique, capable de résister à des dommages mécaniques importants et à des fluctuations de température.

Le Swarm Grub Sac contient quatre Grub matures, prêts à éclore. Lorsqu'elle est exposée au feu, à de fortes vibrations ou à l'approche de grands objets vivants, la coque s'ouvre, se divisant en plusieurs volets. Le Grub est expulsé et commence immédiatement à chercher une cible.

On trouve habituellement des Sacs de Grub en groupes sur les murs, les plafonds et dans les endroits difficiles d'accès. Leur fonction principale est d'assurer le développement sûr de la progéniture de l'essaim jusqu'à ce que les proies apparaissent.

Malgré la faible menace directe, un grand nombre de Sacs Grub actifs dans un seul endroit est un signe de forte densité d'essaims et l'émergence imminente de formes de vie plus dangereuses.

CONSEILS:

- Détruisez le Grub Sack avant d'ouvrir.
Un seul Grub Sack n'est rien. Les problèmes commencent quand il y en a beaucoup.
- Le feu et les explosifs sont les meilleurs moyens contre les Sacs de Grub.
- Une fois le Grub Sack ouvert, ne perdez pas de temps sur le Grub.
- Le bruit et le mouvement sont tout ce qu'il faut pour réveiller la couvée.
