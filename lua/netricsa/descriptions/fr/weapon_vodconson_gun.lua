L'ASSAULTE DE VODKONSON


ARME: L'assaut de Vodkonson
MUNITIONS:   Bouteilles Vodka
CADENCE DE TIR:    ~1800 coups/min

DESCRIPTION:

Le Rifle d'assaut de Vodkonson est une arme primitive mais extrêmement efficace. La vodka accélère les mains de l'utilisateur vers des niveaux surhumains. L'utilisateur insère manuellement les capsules dans la bouteille, mais le fait si rapidement que l'arme semble arracher les capsules de l'air mince.

Les casquettes volent à une vitesse incroyable grâce à la force du bras fou du tireur, se transformant en projectiles mortels capables de déchirer toute créature ou structure.

REMARQUES:

- L'utilisateur éprouve une force incroyable et la vitesse du bras après avoir bu de la vodka.
- Les chapeaux déchirent la chair, l'armure et les synthés grâce à la vitesse supersonique.
- Peut être utilisé pour jouer à Skittles avec une variété d'ennemis.
