VENDU D'HYBRID PRISON SURVEILLANCE DE LA COMBINE


CLASSE:      Combiner le soldat de prison hybride Overwatch
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner l'unité d'assaut punitif à longue et à moyenne portée
TAILLE:       5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    AR2 Rifle d'impulsions, SMG, Grenades
RÉCOMPENSE:     650 FC
MENACE:     Haut

DESCRIPTION:

Le soldat de la prison hybride Combine Overwatch est une version améliorée du soldat de Nova Prospekt, déployé temporairement ou de façon permanente à l'extérieur des complexes pénitentiaires. Le Combine utilise ces soldats dans des situations où les forces standard sont insuffisantes et où le déploiement des forces d'élite est impossible.

Le soldat est revêtu d'une armure renforcée de style prison et équipé d'un casque tactique avec une visière protectrice. La visière jaune souligne son affiliation avec la garde et les forces d'assaut de Nova Prospekt. Malgré son aspect protecteur, la visière n'est pas complètement à l'épreuve des balles.

CONSEILS:

Ne surestimez pas les têtes de visière.
- La meilleure option est la distance et le feu précis.