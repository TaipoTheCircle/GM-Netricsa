LES CRÉATURES DE XEN


Les créatures de Xen sont un empire d'êtres déchirés de leurs dimensions et fusionnés par une volonté extraterrestre. Autrefois un monde frontalier, Xen était un refuge pour ceux qui fuyaient les menaces de leur monde.

A la tête de Xen se dresse le Nihilanth, gigantesque seigneur psionique qui a rassemblé tous les habitants sensibles, de Vortigaunts à Bullsquids, sous son contrôle. Son pouvoir n'est pas maintenu par la peur, mais par le contrôle de l'esprit : les êtres de Xen sentent les pensées les uns des autres, vivant dans un seul nœud énergétique.