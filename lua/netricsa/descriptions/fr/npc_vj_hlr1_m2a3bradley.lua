S.E.C.U. M2A3 BRADLEY FIV


CLASSE:      M2A3 Bradley IFV
MÉTABOLISME: Mécanique, pilote humain
PERCEPTION: Véhicule de combat d'infanterie
TAILLE:       ~32 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    Mitrailleuse principale, lance-roquettes, trappe de déploiement arrière
RÉCOMPENSE:     7000 FC
MENACE:     Catastrophes

DESCRIPTION:

Le M2A3 Bradley est un véhicule blindé polyvalent déployé par les forces de l'UEH. Son armement principal est une mitrailleuse à haut calibre, capable de supprimer efficacement l'infanterie. De plus, le Bradley est équipé d'un lance-roquettes pour gérer les véhicules, les structures ou les forces ennemies concentrées.

A unique feature of the Bradley is its rear troop deployment hatch: il peut transporter des escouades de marins ou de personnel des opérations noires et les déployer directement dans les zones de combat, créant des menaces à plusieurs niveaux. Sa combinaison de puissance de feu, de mobilité et de transport de troupes en fait un véhicule d'assaut de première ligne et un multiplicateur de force.

CONSEILS:

- Couvrez-vous pour éviter les tirs de mitrailleuses et les roquettes.
- Détruire le Bradley empêche rapidement le déploiement des troupes.
- La couverture ou les explosifs sont essentiels pour endommager le châssis blindé.
- Surveiller l'infanterie sortant de l'écoutille arrière - même si le véhicule est détruit, les troupes déployées restent dangereuses.
