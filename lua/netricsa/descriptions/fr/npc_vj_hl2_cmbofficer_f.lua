AGENT DE LA PROTECTION CIVILE DES COMBINES


CLASSE:      Combiner le spécialiste de la protection civile
MÉTABOLISME: Humains
PERCEPTION: Commandement de la protection civile
TAILLE:       6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Moyenne
ARMES:    Pistol, Revolver, SMG, AR2, SPAS-12, OICW
RÉCOMPENSE:     350 FC
MENACE:     Moyenne

DESCRIPTION:

Les agents de protection civile sont le lien entre les policiers de la rue et les loyalistes. Contrairement aux soldats réguliers de la protection civile, ils évitent les masques à gaz, préférant garder leurs visages ouverts.

Leur apparence varie. Certains portent une armure de protection civile standard, tandis que d'autres préfèrent les bérets, les insignes, les épaulettes et d'autres bibelots qui mettent l'accent sur le rang et les privilèges personnels. L'uniforme est moins standardisé, mais il souligne parfaitement la différence entre ceux qui donnent des ordres et ceux qui reçoivent des charges Stun-Stick.

Les officiers sont officiellement tenus de maintenir l'ordre, de coordonner les patrouilles et de faire rapport directement aux structures combinées. Mais de façon informelle, les choses sont plus compliquées. Certains, utilisant leur accès à l'information et aux communications, transmettent secrètement les données à la Résistance.

Au combat, un agent de protection civile est plus dangereux qu'un métrocop ordinaire grâce à leur expérience et à leur sang-froid, mais ils sont encore humains sans augmentation significative.

CONSEILS:

- Ne sous-estimez pas leur expérience, même s'ils sont trop "civils"
- Certains officiers en savent plus qu'ils ne le disent.