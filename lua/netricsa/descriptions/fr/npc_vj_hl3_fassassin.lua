SURVEILLANCE DE LA COMBINE


CLASSE:      Combiner l'Assassin femelle Overwatch
MÉTABOLISME: Augmentations humaines, féminines et biomécaniques améliorées
PERCEPTION: Elite Transhuman Operative, Assassin
HEIGHT:     5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Pistolets, Grenades
RÉCOMPENSE:     800 FC
MENACE:     Très élevé

DESCRIPTION:

L'Assassine mixte féminine est un agent transhumain spécialisé conçu pour éliminer les cibles clés, supprimer la résistance et mener des opérations secrètes derrière les lignes ennemies. Son entraînement acrobatique et neurochimique en fait un chasseur, un espion et une force de frappe.

Les origines de l'assassin sont liées aux programmes de Overwatch pour créer des opérateurs capables d'opérer indépendamment des unités principales. Comme d'autres combattants transhumains, elle a subi des modifications biomécaniques, mais sa spécialisation nécessite des adaptations accélérées du réseau neuronal, lui permettant d'anticiper les mouvements ennemis, d'opérer en silence complet et de s'adapter à l'évolution des conditions de combat.

Son équipement tactique est adapté aux attaques rapides de la foudre et à la fureur.

CONSEILS:

- Dans la plupart des cas, elle lance des grenades avant d'attaquer.
- Ses pas sont silencieux, alors gardez les yeux ouverts.
- Son œil rouge la laisse dans le noir.
