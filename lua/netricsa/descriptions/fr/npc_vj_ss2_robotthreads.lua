ROBOT SÉRIEN, PATROL DES SIRIUS


CLASSE:      Robot Sirian, Patrouille
MÉTABOLISME: Mécanique, énergie
PERCEPTION: Unité de garde, patrouille
TAILLE:       ~6,56 pi
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Cannon laser Et caméra
RÉCOMPENSE:     1500 FC
MENACE:     Haut

DESCRIPTION:

C'est un garde automatisé que Mental a affecté pour patrouiller les niveaux inférieurs de Siriuspolis pour s'assurer que personne ne vagabonde où il ne devrait pas.

Il a un corps gris avec des accents rouges vifs - de sorte que l'ennemi peut le repérer de loin et avoir le temps de se chier. La bande de roulement rouge qu'elle chevauche fait un bruit de claquage métallique distinctif qui peut faire un bavardage des dents d'un combattant non préparé.

La tête du robot est ovale, le même gris que son corps principal, mais avec des yeux rouges qui scannent l'espace pour les créatures vivantes. Au-dessus de sa tête se trouve une antenne et une crête d'épis tranchants-purement pour intimidation, car le robot ne peut percer personne avec sa tête. Son cou est segmenté, presque comme un ressort, lui permettant de tourner la tête n'importe où.

La caméra bleue sur le côté de sa tête n'est pas juste une caméra. C'est un canon. Il transmet des images directement au centre de commandement de l'armée de Mental. Il tire aussi des rayons laser. Le robot vise d'abord sa cible avec un petit pointeur laser, puis tire son canon principal.

CONSEILS:

- Très dangereux.
- Ne reste pas dans sa ligne de feu.
- Contrairement à beaucoup d'alliés de Mental, celui-ci n'est pas un tas de briques.

