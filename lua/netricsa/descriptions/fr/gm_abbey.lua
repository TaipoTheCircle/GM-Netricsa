ABBEY, BASE DE SAN PIETRO APOSTOLO


Sam, à en juger par ce que nous avons déménagé, cet endroit était autrefois un centre de pèlerinage, et maintenant il est devenu le cadre parfait pour une embuscade et une fusillade. Avant nous est une ancienne basilique, ou plutôt, ce qui en reste après des années de négligence... ou après la visite d'hier de l'artillerie de Mental.

L'architecture locale a été clairement inspirée par de grandes cathédrales, peut-être la basilique de San Pietro elle-même.

Mais ce ne sont que des ruines...
