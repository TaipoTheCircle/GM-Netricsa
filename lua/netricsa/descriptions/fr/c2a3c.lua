MESA BLACK, GENERATEUR LIBRE



Sam, tu as trébuché dans un autre secteur du complexe du générateur - cette fois, des rangées de chambres de congélateur industriel, leurs portes gelées fermées, de l'air si froid qu'il brûle tes poumons. L'ondensation s'accroche à chaque surface.

Thermal scans confirm two hostile forces locked in combat:

Faune Xen - vortigauns et headcrabs.

Mental's horde - Zorgs et décapitations, forçant leur chemin dans le couloir opposé.

Le résultat? Un champ de bataille gelé où vous êtes pris dans le feu croisé. Les douilles d'Ammo scatter sur la glace, les arcs de foudre extraterrestres entre les poutres en acier.

Recommendation: laissez-les mincer le nombre de l'autre, puis frapper lorsque les deux côtés saignent. Le froid ralentit le temps de réaction - utilisez-le à votre avantage. Et Sam ? Essayez de ne pas vous faire brûler au congélateur.