ROCKET MISSILE LAUNCHER


ARME:      Lance-missiles de fusée
MUNITIONS:        Boulons technomagiques
CADENCE DE TIR:         ~90 missiles/min

DESCRIPTION:

Un armement brut mais omniprésent parmi l'infanterie non morte de Mental, le Rocket Missile Launcher canalise l'énergie arcane dans une volée de missiles enflammés. Produit en masse et presque sans poids, chaque unité harcele un réservoir caché de flux magique, bien qu'un boulon à la fois.

REMARQUES:

- Faible dommage par tir, donc pas fiable pour les cibles hautement prioritaires ou blindées.