FLACON DE SERGEANT STORMTROOPER


CLASSE:      Drone du sergent Stormtrooper
MÉTABOLISME: Aéronefs sous contrôle AI
PERCEPTION: Reconnaissance tactique, scanner aérien
TAILLE:       1 pi
ENDURANCE:  Très faible
HOSTILITÉ:  Moyenne
ARMES:    Cannon laser dans "Eye"
RÉCOMPENSE:     25 FC
MENACE:     Haut

DESCRIPTION:

Un jour, le sergent Stormtrooper a vu le droïde de reconnaissance standard de Mental et, en quelques secondes, a tracé mentalement une version miniature. Contrairement à la version originale, ce drone dispose d'un « œil » rouge, un scanner capable d'analyser le terrain et de transmettre des données en temps réel.

Le drone du sergent est un avion léger conçu pour la reconnaissance et la surveillance tactiques. Il vole dans l'air, balaye la zone et identifie les menaces. Son « œil » rouge lui permet de voir même dans de mauvaises conditions de visibilité, comme le brouillard, la nuit et la fumée.

Au combat, le drone utilise des lasers conçus non pour causer de graves dommages, mais pour supprimer et distraire. Si le drone détecte un ennemi, il transmet immédiatement les coordonnées au sergent et peut également demander des renforts.

Le drone flottant est également utilisé pour les zones de patrouille et la surveillance des mouvements de troupes. Contrairement à l'original de Mental Floater Drone, ce modèle n'a pas de système de sanctions seulement chercher et détruire.

CONSEILS:

- Le drone est facile à détruire avec n'importe quelle arme, mais une arme à feu rapide est préférable.
- Si le drone vous repère, il transmet vos coordonnées au sergent. Changer de position immédiatement ou détruire le drone.
- L'œil rouge est un point faible. Le frapper désactive instantanément le drone.
- Ne bougez pas. Le drone tire un laser, mais sa précision diminue à mesure que la cible bouge.
- S'il y a plusieurs drones, ils peuvent coordonner le feu. Détruisez-les un par un, les empêchant de former un groupe.
- Le drone est les yeux du sergent. Si vous le voyez, ça veut dire que le sergent est déjà au courant de vous. Il est temps de partir.
