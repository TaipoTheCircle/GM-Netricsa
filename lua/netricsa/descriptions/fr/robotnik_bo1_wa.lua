RIVEAU DE LA WALTER WA 2000


ARME: Walther WA 2000 Sniper Rifle
MUNITIONS:   7,62x51mm OTAN (308 Winchester) / 0,300 Winchester Magnum / 7,5x55mm Suisse
CADENCE DE TIR:    ~30 tours/min

DESCRIPTION:

Un fusil de sniper semi-automatique allemand développé par Carl Walther Waffenfabrik au début des années 1980. Il a été conçu pour les unités de police et les services spéciaux qui ont besoin d'une arme compacte de haute précision pour les opérations urbaines. Sa configuration bullup permet une longueur hors tout relativement courte tout en conservant un baril de 650 mm de longueur.

Le WA 2000 utilise une action à gaz avec un boulon rotatif comportant sept glissières de verrouillage. Il dispose d'une conception modulaire, permettant l'échange du canon et du boulon pour accueillir différents types de munitions. Il est équipé d'un support en bois réglable, d'une vue optique Schmidt & Bender et d'un bipode repositionnable unique. Le magazine standard compte 6 tours, tandis que la version en chambre pour .300 Winchester Magnum utilise un magazine 5 tours.

REMARQUES:

- Seulement 176 unités ont été produites.
- Il manque des vues en fer, car il est conçu exclusivement pour une utilisation avec une vue optique.
- En raison du positionnement du port d'éjection, il ne peut pas être tiré de l'épaule gauche.
- La production a cessé en 1988 en raison de coûts de fabrication élevés.
- Un fusil qui a l'air plus cher qu'un dépôt d'armes.
