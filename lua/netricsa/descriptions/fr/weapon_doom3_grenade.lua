FRAGMENTATION GRENADE


ARME : Fragmentation Grenade
MUNITIONS : Grenade
ROF : ~30 lancers/min

DESCRIPTIF :

Une grenade à fragmentation portative conçue pour détruire des cibles avec une explosion et des éclats d'obus. Il peut être utilisé contre des groupes d’ennemis et pour attaquer des cibles à couvert. Après avoir été lancée, la grenade explose au bout de quelques secondes.

The small size allows you to carry several grenades, but the supply is limited. If used incorrectly, the explosion can pose a danger to the thrower.

REMARQUES :

- Can't shoot an enemy around a corner? - Just throw the grenade there.
- Effective against groups of enemies.
- Vous permet de toucher des cibles à couvert.
- Explodes with a slight delay after being thrown.
