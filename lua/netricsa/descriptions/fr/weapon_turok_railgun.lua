ORO L66 RIFLE PULSE


ARME: ORO L66 Rifle d'impulsion
MUNITIONS:   Bullets d'uranium appauvri en armure
CADENCE DE TIR:    ~600 tours/min
POIDS: ~4,5 kg

DESCRIPTION:

Un fusil à impulsions automatique précis fabriqué par ORO, tirant des balles d'uranium appauvri. L'arme est dotée d'une grande précision, d'un faible recul et d'un grand magazine 100 tours, permettant un feu soutenu. Son principal inconvénient est la surchauffe rapide pendant la cuisson continue.

Un lance-grenades est monté sous le canon pour des grenades à impulsions spéciales. Ceux-ci ne sont pas conçus pour détruire une cible, mais plutôt pour créer une puissante onde de choc, frapper les ennemis de leurs pieds et les frapper hors de la couverture. Les grenades peuvent être tirées soit par balle, soit par rafales courtes de trois.

REMARQUES:

- Le magazine compte 100 tours, d'une capacité totale de 400.
- Haute précision et faible recul.
- Utilise des munitions à l'uranium appauvri.
- Surchauffe rapidement en cas de tir continu, des rafales courtes sont donc recommandées.
- Un autre tir lance des grenades désorientantes.
- Les grenades frappent les ennemis et les forcent à s'abriter.
- Efficace à moyenne et longue portée en raison de sa précision et de la possibilité d'utiliser des champs zoomés.
- Particulièrement fréquent parmi les soldats d'élite de la Société Mendel-Gruman.
