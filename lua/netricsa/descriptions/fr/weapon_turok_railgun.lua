FUSIL À IMPULSIONS ORO L66


ARME : Fusil à impulsion ORO L66
MUNITIONS : balles perforantes à l'uranium appauvri
ROF : ~600 tours/min
POIDS : ~4,5kg

DESCRIPTIF :

Un fusil à impulsion automatique précis fabriqué par ORO, tirant des balles perforantes à l'uranium appauvri. L'arme offre une grande précision, un faible recul et un grand chargeur de 100 cartouches, permettant un tir soutenu. Son principal inconvénient est une surchauffe rapide lors d'une cuisson continue.

Un lance-grenades est monté sous le canon pour les grenades à impulsions spéciales. Ceux-ci ne sont pas conçus pour détruire une cible, mais plutôt pour créer une puissante onde de choc, faisant tomber les ennemis et les mettant hors de portée. Les grenades peuvent être tirées soit en un seul coup, soit en courtes rafales de trois.

REMARQUES :

- Le chargeur contient 100 cartouches, pour une capacité totale allant jusqu'à 400.
- Haute précision et faible recul.
- Utilise des munitions perforantes à l'uranium appauvri.
- Surchauffe rapidement lors d'un tir continu, des rafales courtes sont donc recommandées.
- Des tirs alternatifs lancent des grenades désorientantes.
- Les grenades font tomber les ennemis et les forcent à se mettre à couvert.
- Efficace à moyenne et longue portée grâce à sa précision et la possibilité d'utiliser des lunettes zoomées.
- Particulièrement courant parmi les soldats d'élite de la Corporation Mendel-Gruman.