ADMINISTRATEUR DE COMBINE


CLASSE:      Combiner l'administrateur
MÉTABOLISME: Chaleureux, humain
PERCEPTION: Humains, hauts fonctionnaires
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Moyenne
ARMES:    Revolver, Glock 17, grève des fesses
RÉCOMPENSE:     700 FC
MENACE:     Moyenne

DESCRIPTION:

Combiner les administrateurs sont des hauts fonctionnaires qui résident dans les citadelles de leur ville. Ils sont responsables de la gouvernance des villes sur Terre, telles que la ville 10, la ville 8 et d'autres. Contrairement à Wallace Breen, qui gouverne l'ensemble de la Terre et de la ville 17, ces administrateurs opèrent au niveau régional, respectant strictement les procédures bureaucratiques et le maintien de l'ordre.

Male and female administrators wear a standard uniform: une veste marron et une cravate orange. En cas de conflit personnel, ils sont armés de revolvers et de Glock 17, et dans un combat rapproché, ils utilisent un cul comme arme. Malgré leur statut officiel, ils sont capables de défense agressive et n'hésitent pas à supprimer la résistance si nécessaire.

CONSEILS:

- Les administrateurs gardent leur distance et connaissent bien leurs itinéraires.
- Ils sont bien gardés.
