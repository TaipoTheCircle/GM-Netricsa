"CANTIQUES DE BOU"


ARME: Guitare "Boy's Songs"
MUNITIONS:   Non requis

DESCRIPTION:

Une guitare inhabituelle conçue pour jouer des chansons populaires. Comme le modèle "GIMN USSSR", il n'exige pas de l'utilisateur de jouer les chaînes. Il suffit d'agiter votre main dans l'air pour l'activer, et l'instrument commencera automatiquement à exécuter une de ses pistes disponibles.

La collection de musique intégrée comprend huit chansons de différents artistes, dont des morceaux des groupes Lyapis Trubetskoy, Bi-2 et Lyube, ainsi que des chansons de Viktor Tsoi et des œuvres de Pavel Plamenev.

REMARQUES:

- Contient huit titres musicaux :
- "Les guerriers de la lumière" (Lyapis Trubetskoy)
- "Personne n'écrit au colonel" (Bi-2)
- "Faisons-le pour..."
"Type de sang" (Viktor Tsoi)
- "Les soldats ne sont pas nés"
- "Le dernier jour de 2021" (Pavel Plamenev)
- "Pour la paix sur Terre" (Pavel Plamenev)
- "Détachements anciens" (Pavel Plamenev)
- Une simple vague de la main est tout ce qu'il faut pour démarrer la musique.
- Pas besoin de cordes ou de compétences musicales.
