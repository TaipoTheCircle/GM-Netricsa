DRONE ESSAIS, ORBÈRE


CLASSE : Drone essaim, Orber
MÉTABOLISME : Arthropode extraterrestre
PERCEPTION : Drone d'assaut, variante explosive
TAILLE : 5,58 pieds
ENDURANCE : Moyenne
HOSTILITÉ : Élevée
ARMES : Griffes, Mâchoires, Sphères d'énergie
RÉCOMPENSE : 300 FC
MENACE : Élevée

DESCRIPTIF :

Les Orbers sont une variante spéciale des drones standards, se distinguant par une coloration jaune plus brillante et une réaction défensive inhabituelle. Sinon, ils conservent le comportement et les capacités de combat des drones standards, attaquant leurs adversaires au corps à corps et tentant de réduire rapidement la distance.

La principale caractéristique de l'Orber Drone devient apparente à sa mort. Après avoir subi des dommages mortels, son corps commence à émettre une réaction énergétique instable, faisant voler de nombreuses sphères d'énergie dans toutes les directions.

Les sphères se comportent comme des projectiles Boomer : elles volent vers l'extérieur, entrent en collision avec les objets environnants et explosent à l'impact, endommageant tout ce qui se trouve à proximité. Par conséquent, détruire un tel drone à courte distance peut être presque aussi dangereux que l’attaque elle-même.

On ne sait pas si la libération d'énergie est une réaction défensive intentionnelle ou un effet secondaire du métabolisme inhabituel de ces créatures. Pour l'essaim, cela n'a cependant que peu d'importance : un Orber Drone mort transforme sa propre mort en un coup final porté à l'ennemi.

C’est pourquoi les combattants ont rapidement appris à les distinguer des drones classiques par leur couleur jaune vif. Si un tel extraterrestre s'approche d'un groupe, il est hautement déconseillé de le détruire à bout portant.

CONSEILS :

- Ne vous tenez pas près de lui pendant qu'il est en train d'être tué.
- Sa coloration jaune vif permet de distinguer un Orber Drone d'un drone ordinaire.
- Si possible, détruisez-le à distance.
- Les Orbes sont particulièrement dangereux dans les couloirs étroits, car ils sont beaucoup plus difficiles à éviter.
- Si un Orber Drone se trouve parmi d'autres extraterrestres, évaluez d'abord la zone qui l'entoure : après sa mort, il ne restera pratiquement plus de zone de sécurité.
- Après l'apparition des orbes, ne vous précipitez pas vers le cadavre. Attendez d'abord ou évitez les orbes volants.