TÉLÉCOPIEUR, ORBER


CLASSE:      Swarm Drone, Orber
MÉTABOLISME: Arthropodes étrangers
PERCEPTION: Drone d'assaut, variante explosive
TAILLE:       5,58 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Griffes, mâchoires, sphères énergétiques
RÉCOMPENSE:     300 FC
MENACE:     Haut

DESCRIPTION:

Les orbères sont une variante spéciale des drones standard, caractérisée par une coloration jaune plus vive et une réaction défensive inhabituelle. Sinon, ils conservent le comportement et les capacités de combat des drones standard, attaquant les adversaires dans le combat étroit et tentant de fermer rapidement la distance.

La caractéristique principale de l'Orber Drone devient apparente à sa mort. Après avoir subi des dommages mortels, son corps commence à émettre une réaction d'énergie instable, faisant voler de nombreuses sphères d'énergie dans toutes les directions.

The spheres behave like Boomer projectiles: ils volent vers l'extérieur, entrent en collision avec des objets environnants, et explosent sur l'impact, endommageant tout ce qui se trouve à proximité. Par conséquent, la destruction d'un tel drone à portée rapprochée peut être presque aussi dangereuse que l'attaque elle-même.

On ignore si la libération d'énergie est une réaction défensive intentionnelle ou un effet secondaire du métabolisme inhabituel de ces créatures. Pour l'essaim, cependant, ce n'est pas important: un mort Orber Drone transforme sa propre mort en un coup final à l'ennemi.

C'est pourquoi les combattants ont rapidement appris à les distinguer des drones réguliers par leur couleur jaune vif. Si un tel extraterrestre s'approche d'un groupe, il est hautement indésirable de le détruire à proximité.

CONSEILS:

- Ne t'approche pas pendant qu'il est tué.
- Sa coloration jaune vif vous permet de distinguer un drone Orber d'un drone régulier.
- Si possible, détruisez-le à distance.
- Les Orbes sont particulièrement dangereux dans les couloirs étroits, car ils sont beaucoup plus difficiles à éviter.
- Si un drone d'Orber est parmi d'autres extraterrestres, évaluez d'abord la zone qui l'entoure : après sa mort, il ne restera pratiquement plus de zone de sécurité.
- Après l'apparition des Orbes, ne retournez pas au cadavre. Attendez d'abord ou évitez les Orbes volants.
