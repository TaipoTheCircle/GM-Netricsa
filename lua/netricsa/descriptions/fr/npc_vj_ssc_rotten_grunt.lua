ZORG ROTTEN DE BEELMEZ IV


CLASSE:      Zorg pourri
MÉTABOLISME: Mammifère
PERCEPTION: Vétéran Warrior Race
TAILLE:       6,5 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Extrême
ARMES:    Cannon SBC
RÉCOMPENSE:     700 FC
MENACE:     Haut

DESCRIPTION:

Mental a transporté ces soldats sur Terre d'une partie inconnue de l'univers. Ils étaient autrefois une race de guerriers redoutables mais comme ils ont conquis plus de planètes qu'ils ne savaient quoi faire, ils ont décidé de ralentir pendant un certain temps. La plupart de la population a pris des vacances de longue date sur l'une des plus belles planètes tropicales de leur système; mais comme ils ne baignaient que du soleil de 10h à 16h, après quelques années, la plupart d'entre eux n'avaient plus de peau sur leur corps.

Après quelques années, les effets sont devenus irréversibles. La peau a littéralement pourri, les tissus ont commencé à se décomposer, et les guerriers autrefois puissants ont été réduits à marcher, à demi-découpés carcasses.

Tout commandant avisé aurait annulé ces combattants. Mais Mental n'a jamais été connu pour son bon sens.

Ayant découvert toute une armée d'anciens combattants à moitié décédés, il a décidé de les remettre en service et de les armer d'un lourd canon SBC. Cette arme puissante tire une boule de canon massive capable de détruire pratiquement n'importe quelle cible avec un seul coup. Le seul problème est que les Rotten Zorgs eux-mêmes sont loin d'être parfaits pour manier cette arme. Ce n'est pas rare qu'un tir déplacé entraîne la mort du tireur.

Malgré leur horrible condition, ces créatures ont conservé l'expérience de combat de dizaines de campagnes militaires. Ils sont lents, facilement mortellement blessés, et beaucoup moins durables que même les mercenaires ordinaires de Mental, mais un seul coup bien aéré de leur canon peut instantanément changer le résultat d'une bataille.

Ironiquement, ces anciens combattants en décomposition sont parmi les plus anciens soldats de l'armée de Mental. Ils ont participé aux premières conquêtes de la Horde bien avant l'invasion de la Terre et ont été transférés ici d'un secteur lointain et inconnu de la galaxie.

