ARACHNOIDE, ARRÊT DU SCORPIUS


CLASSE:      Arachnoide, Hatchling
MÉTABOLISME: Éctotherme, arthropodes
PERCEPTION: Course intelligente primitive
TAILLE:       8 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Mitrailleuse à queue
RÉCOMPENSE:     1000 FC
MENACE:     Moyenne

DESCRIPTION:

Une sainte éclosion d'une race primitive descendait des arthropodes. Très dangereux en raison de ses croyances religieuses.

Un jeune, pas complètement formé arachnoide de la planète Scorpius, qui adore Mental comme un messie. Il a un exosquelette plus léger et moins durable que les adultes. Il est armé d'une mitrailleuse légère qui remplace un de ses membres.

Cette arme possède une grande précision et des munitions illimitées grâce à un régénérateur technomagique, mais elle est sujette à la surchauffe après une longue explosion, donnant aux ennemis le temps d'attaquer. Il peut également attaquer avec un stinger venimeux au combat rapproché. Il s'agit d'une unité d'infanterie de l'armée de Mental qui produit en masse, compensant sa faible survie par son nombre et sa puissance de feu dense.

CONSEILS:

- La queue est dangereuse. Ne vous approchez pas trop.
- Quand elle est en colère, elle tire même à travers la sienne.
- Après une longue explosion, il arrête de tirer une seconde pour se refroidir - le moment parfait pour une contre-attaque.
- Utilisez un fusil de sniper, un fusil d'assaut ou un lance-roquette.
