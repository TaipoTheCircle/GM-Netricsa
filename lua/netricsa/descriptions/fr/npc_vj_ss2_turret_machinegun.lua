MH-110 MACHINE GUN TURRET


CLASSE:      MH-110 Tourelle de mitrailleuse
MÉTABOLISME: Mécanique 
PERCEPTION: Stationnaires
TAILLE:       ~3,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Varie avec le tireur
ARMES:    Deux mitrailleuses de 110 mm
RÉCOMPENSE:     300 FC
MENACE:     Moyenne

DESCRIPTION:

Quand Mental a conçu ses bases, il a fondé sa pensée sur un principe simple: «Tout ce qui bouge doit être soit un esclave, soit un cadavre». Pour ceux qui ont refusé de devenir l'un ou l'autre, il a développé des tourelles fixes de mitrailleuse - des barils jumeaux capables de broyer la chair plus rapidement que l'ennemi ne l'a même réalisé.

La plupart se sont mis d'accord sur la première option.

Il a deux mitrailleuses, jumelées, et un approvisionnement infini en munitions (la caisse est la source de la création magique de munitions), ainsi qu'un système de ciblage qui permet même ceux qui n'ont jamais vu une arme auparavant de tirer.

Le taux de feu de la tourelle est tel qu'en quelques secondes, elle peut transformer un paquet de Gnaars en un gâchis sanglant, ou un Cyclope en tamis.

Les tourelles sont habituellement installées dans les bases de Mental, qui peuvent être capturées et utilisées contre leur maître.

Si un ennemi est derrière la tourelle, il pleut des balles sur tout ce qui bouge. Si vous délogez l'ennemi et sautez en vous-même, vous pouvez déclencher un feu d'artifice.

CONSEILS:

- Si tu vois une tourelle avec un ennemi, sors-les d'abord. Une tourelle sans canon n'est qu'un morceau de métal.
- Contre les créatures rapides, une tourelle est indispensable. Les balles vous atteignent instantanément.
- Si tu vois quelqu'un qui a les jambes orcish derrière une tourelle, ça veut dire qu'il y a quelqu'un.
