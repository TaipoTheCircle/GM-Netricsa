RISQUE D'ASSAULT


ARME: Patten 470 Fuite d'assaut
MUNITIONS:   5.56x45mm OTAN
CADENCE DE TIR:    600 à 750 tours/min

DESCRIPTION:

Un fusil d'assaut moderne a été mis au point pour les unités armées de l'Armacham Technology Corporation. Il dispose d'une action à gaz avec un piston à gaz, offrant une haute fiabilité et une bonne précision. Il est équipé d'une vue optique ACOG, ce qui facilite la visée à moyenne à longue portée.

Le Patten 470 comprend un commutateur coupe-feu permettant à l'utilisateur de basculer entre feu semi-automatique et feu entièrement automatique. Il utilise des magazines de 30 tours, et sa grande puissance et sa gamme efficace le rendent bien adapté à une variété de scénarios de combat. La conception du fusil intègre des caractéristiques de plusieurs systèmes modernes d'armes d'assaut.

REMARQUES:

- Équipé d'une vue optique ACOG.
- Le magazine contient 30 cartouches; la capacité totale de munitions peut atteindre 420 cartouches.
- La conception est largement basée sur le fusil expérimental XM8.
- Offre une bonne portée et une puissance d'arrêt élevée.
- Alors que la vue aide dans le ciblage précis, tir de la hanche est parfois plus pratique dans le combat de quartier rapproché.
