GRANDE ANGEL, MICHAEL HARRIS


CLASSE:      Un grand ange, Michael Harris
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:    Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     100 FC
MENACE:     Annoyance

DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme de Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan" ils gagnent le feu et les modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Michael Harris (à ne pas confondre avec le criminel du même nom) est l'un des bêta-testeurs clés de Croteam, ayant apporté une contribution significative au débogage et au polissage des jeux les plus importants de la série. Son crâne surdimensionné est le résultat direct de centaines d'heures passées à trouver de petits bugs, à vérifier l'équilibre et à effectuer des tests de stabilité sur The First Encounter, The Second Encounter, Serious Sam 2 et leurs remasters HD.

Contrairement aux développeurs célèbres, les noms des testeurs restent souvent dans l'ombre, mais leur rôle est inestimable. C'était des spécialistes comme Michael Harris qui ont agi comme la dernière ligne de défense entre une construction rugueuse et le produit final, attraper des erreurs de collision, des problèmes de performance, et des incohérences logiques qui pourraient autrement ruiner l'expérience du joueur. Ses nombreuses années de travail sont créditées comme "Ajout Testing and Support" - une caractéristique modeste mais vitale, sans laquelle aucun Serious Sam jeu serait si poli et stable.

Il était vivant, mais après que vous l'ayez tué dans le Temple de Hatshepsut, il a été ressuscité, devenant un ange.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager le chemin.
- Sur la difficulté "Je suis Ugh-Zan", les éliminer à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.