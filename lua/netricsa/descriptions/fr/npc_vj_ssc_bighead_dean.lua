GRANDE CHAMBRE, DEAN SEKULIQUE


CLASSE:      Grande tête, Dean Sekulic
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:    Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     100 FC
MENACE:     Annoyance

DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan", ils gagnent le feu et les modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Dean Sekulic est l'un de ces titans cachés dont le génie technique a fait briller et couler le monde de Serious Sam même pendant les moments les plus intenses de batailles avec des milliers d'ennemis. Son crâne exagéré est un résultat direct de son immersion profonde dans l'architecture de rendu et la bataille sans fin pour l'optimisation. En tant que programmeur principal et concepteur de rendu chez Croteam depuis le premier jeu, il a été la clé de la création de Serious Engine 2 pour Serious Sam 2 (2005), où ses efforts comprenaient la mise en œuvre de technologies de pointe telles que HDR, flower, parallax mapping, et un système d'ombre complexe basé sur des tampons d'ombre.

Son approche pragmatique et pleine d'esprit au développement - "Je n'achète pas les conneries de relations publiques que NVidia et ATI spew" - est devenue légendaire parmi les amateurs de game tech. Maître de l'optimisation, Dean croyait que les joueurs voulaient un jeu qui « court et joue bien », pas une démo lente des dernières fonctionnalités. Sa contribution à la série, jusqu'à son travail sur Serious Sam 4 (2020), a assuré la signature de la série, un style visuel dynamique et incroyablement dynamique qui a enduré des années.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager le chemin.
- Sur la difficulté "Je suis Ugh-Zan", les détruire à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.