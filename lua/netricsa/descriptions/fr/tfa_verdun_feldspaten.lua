FELDSPATEN 1887 (M87) OUTILS D'ENTRÉE


ARME: Feldspaten 1887 (M87) Outil de saisie
MUNITIONS:   N/A
CADENCE DE TIR:    Armes à main/à manches

DESCRIPTION:

Un outil d'ancrage d'infanterie allemand, adopté par l'armée impériale allemande en 1887. Il s'agissait d'une version améliorée du champ M1874. Le changement principal était un nouveau système de transport : selon un ordre daté du 3 mars 1887, l'outil devait être attaché à la ceinture, placée derrière le fourreau de baïonnette. Il a été utilisé par l'infanterie pour construire des fortifications, creuser des tranchées et préparer des positions de tir individuelles.

L'outil dispose d'une lame en acier légèrement courbée et d'une poignée en bois courte. Sa longueur totale est d'environ 54 cm, avec une largeur de lame d'environ 15-16 cm. Il était porté dans une gaine spécialisée attachée à l'équipement du soldat. Au cours de la Première Guerre mondiale, les bords ont souvent été aiguisés, transformant l'outil standard en une arme de combat efficace à quartier rapproché.

REMARQUES:

- Efficace dans les combats de quartier rapproché, en particulier dans les limites des tranchées et des étangs.
- Utilisé pour creuser des fosses individuelles et des fortifications de terrain.
- Contrairement au modèle M1898, il manque un bord de « pas » renforcé (un bord supérieur renforcé pour appliquer la pression du pied).
- La longueur totale est d'environ 54 cm.
- Utilisé par l'armée allemande pendant la Première Guerre mondiale.
