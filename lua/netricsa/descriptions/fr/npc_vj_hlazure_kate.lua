TAUX


CLASSE:      C'est pas vrai
MÉTABOLISME: Humain, femme
PERCEPTION: Garde de sécurité (niveau 3), Centre de recherche Black Mesa
TAILLE:       5,6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Neutre pour le personnel de Mesa noire; hostile pour les créatures et les forces hostiles
ARMES:    Pistolet Glock 17
RÉCOMPENSE:     500 FC
MENACE:     Modéré

DESCRIPTION:

Kate, également connue sous son nom de code Azure Sheep. Elle sert de garde de sécurité de niveau 3 au Centre de recherche Black Mesa et se distingue par son apparence particulière par rapport à d'autres membres du personnel de sécurité féminin. Sportant un béret, des lunettes et un gilet Kevlar, Kate est à la fois un officier compétent et une figure centrale dans le récit.

Lors des événements du Black Mesa Incident, Kate devient un allié clé de Justin Barns. Elle aide à naviguer dans le chaos de l'établissement, affrontant les créatures Xen et les forces hostiles des Ops Noirs. Leur partenariat se transforme en une relation plus profonde, avec Kate devenant l'intérêt amoureux de Barns.

CONSEILS:

- Soutien au combat: Kate est compétente avec son Glock 17 et peut aider dans les combats de feu.
- Missions d'escorte : En raison de ses compétences au combat et de ses connaissances de l'établissement, elle est précieuse pendant les opérations d'escorte ou de sauvetage.
- Vulnérabilité : Bien qu'elle soit capable, elle n'est pas invincible ; elle est protégée dans des situations de combat intenses.
