BLASER MARINE


ARME: Blaster
MUNITIONS:   Aucune (énergie infinie)
CADENCE DE TIR:    ~360 tours/min

DESCRIPTION:

Le Blaster est le pistolet à énergie standard donné à chaque Marine Il tire de petites explosions d'énergie avec une simple poussée de la détente; en maintenant la détente charge un tir plus fort. Une LED arrière brille lorsqu'elle est complètement chargée. Comprend également une lampe de poche sous-barre pour éclairer les zones sombres.

REMARQUES:

- Le tir chargé inflige des dommages beaucoup plus élevés (environ 50), mais nécessite du temps pour charger.
- N'utilise pas de munitions et ne nécessite pas de rechargement - énergie infinie.
- Lampe de poche intégrée aide dans les sections sombres sans changer d'arme.