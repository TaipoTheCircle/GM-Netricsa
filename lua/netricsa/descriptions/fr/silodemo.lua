BLACK MESA LOBBY, SILO DEMO


Sam, on est dans le silo. Pas une version live, pas une version complète-une démo. Un endroit où Black Mesa a testé des moteurs de fusée, et maintenant teste nos nerfs.

Ils ont grandi ici. Ou est descendu ici. Ou ont été soufflés par les vents d'un effondrement interdimensionnel. Trois créatures de classe Tentacle. Bien que les tentacules eux-mêmes sont un seul organisme avec des tentacules fonctionnant séparément.

Problem: pas de lance-flammes. Pas de moteur de fusée pour les viser. Rien qui puisse les faire frire. Et sans feu, ces créatures sont immortels. Ce n'est pas la peine de faire quoi que ce soit. C'est écrit dans les protocoles. Et les protocoles Black Mesa sont généralement écrits dans le sang de ceux qui les ont ignorés.

La seule façon qui ait jamais fonctionné (parfois accidentellement, en raison de bugs et de désespoir) est d'obtenir le bon moment et de tirer le canon de poutre continuellement à la racine des tentacules. Pas le tronc, pas les ventouses, mais là où la chair rencontre le sol. Ils ont une sorte de centre nerveux. Ça pourrait marcher. Peut-être pas. Mais il n'y a pas le choix.

Actuellement, trois gardes les combattent. Ils ne sont pas impatients de mourir, mais ils n'ont nulle part où se retirer. Ils tirent avec tout ce qu'ils ont. Les tentacules s'en fichent. Les gardes sont de la viande. Ce n'est qu'une question de temps avant qu'ils tombent.

Et il y a des S.E.C.U. troués dans une des chambres.

Ils sont juste assis à l'abri et attendent. Pour quoi ? Des renforts. Peut-être notre mort. Peut-être pour que tout se résolve. Mais cet endroit ne mène nulle part. C'est une impasse. Au-delà, il n'y a que des murs, des tuyaux et des tentacules.

La seule issue est de tuer les créatures. Ou mourir.
