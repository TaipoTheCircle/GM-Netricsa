"BETA" DRONE DE LA MER, LARGE


CLASSE:        "Beta" Swarm Drone, Grand
MÉTABOLISME:   Xénobiologique
PERCEPTION:   Prédateur à emballage lourd
TAILLE:         9,8 pieds
ENDURANCE:    Haut
HOSTILITÉ:    Très élevé
ARMES:      Griffes, dents, masse corporelle
RÉCOMPENSE:       600 FC
MENACE:       Haut

DESCRIPTION:

Le Grand Drone est un spécimen exceptionnellement surdimensionné du "Beta" Swarm. Contrairement aux drones d'élite, qui se distinguent par leur coloration, cette sous-espèce semble presque identique aux spécimens standard. Il possède la même peau verte, les mêmes trois yeux, et la même insatiable envie de déchirer toute chose vivante. La différence ne devient apparente que lorsque la créature se tient à côté d'un drone standard.

Les raisons de cette croissance anormale demeurent inconnues. Selon une théorie, certaines larves reçoivent significativement plus de nutriments que d'autres. Une autre théorie pose que le Swarm manque simplement la capacité d'arrêter de grandir au bon moment.

Sa taille accrue a donné à la créature une musculature plus puissante et des organes internes nettement renforcés. Par conséquent, le Grand Drone peut résister à des dommages qui auraient longtemps tué un spécimen standard et délivrer des coups assez puissants pour envoyer une victime volant plusieurs mètres.

Malgré sa taille imposante, le Grand Drone conserve une grande partie de l'agilité de ses petits parents. C'est une surprise particulièrement désagréable pour quiconque s'attend à ce qu'un tel monstre bouge lentement et pondéralement.

CONSEILS:

- Ne laissez pas sa taille vous tromper. C'est plus rapide qu'il ne semble.
- Gardez vos distances et utilisez des armes puissantes.
- Si des drones ordinaires sont repérés à proximité, éliminez d'abord la cible la plus dangereuse.
- Quand Swarm "Beta" décide de créer un plus grand drone, tout le monde à proximité souffre habituellement.
