BODEGA DE KIT


CLASSE:      Kit Bodega
MÉTABOLISME: Cat anthropomorphe, Cyborg
PERCEPTION: Membre de l'équipe "Soutien"
TAILLE:       5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Variable
ARMES:    Griffes, Blaster, PDA, Kibble Star Star Cannon
RÉCOMPENSE:     200 FC
MENACE:     Variable

DESCRIPTION:

C'est un chat anthropomorphe aux fourrures beiges, aux cheveux bruns, aux yeux roses et aux lunettes à cadre jaune avec des verres rouges.

Elle porte une combinaison jaune avec une bande zigzag blanche, complétée par un sous-armeur noir, des bretelles épaisses et des greaves avec des greaves rappelant les pattes de chat. Son nom complet se traduit par "Entrepôt d'équipement" (Kit - kit, Bodega - entrepôt), reflétant sa capacité à matérialiser des objets.

Kit vient d'un monde de jeu habité par des chats anthropomorphes, où elle et son partenaire, Kaboodle, étaient les personnages principaux. Ils ont juré de protéger leur village contre les méchants Malice et Mayhem, mais grâce à leur victoire, le monde a été détruit par un cataclysme, tuant tout le monde sauf Kit et Kaboodle. Au dernier moment, le mystérieux Twilight les a sauvés, les recrutant dans l'équipe de soutien.

Kit et Kaboodle ont maintenant pour tâche de voyager dans différents mondes et d'empêcher les héros locaux de vaincre les méchants. L'ironie du destin : ils sont forcés de jouer le rôle de méchants pour sauver les mondes de la destruction qui suit inévitablement la victoire du héros. Les héros sauvés d'autres mondes sont les Gobbles (un dinosaure) et les Flapeurs (un dauphin).

Kit se distingue par son courage, son optimisme et son ingéniosité. La destruction de sa terre natale l'a laissée avec un profond traumatisme psychologique : tout monde ressemblant à sa terre natale évoque des souvenirs de la destruction de son village, parfois la poussant à agir avec imprudence. Elle se blâme pour son incapacité à contrôler ses émotions, mais cette même émotion lui donne l'énergie de sauver ceux qui peuvent encore être sauvés.

Dans la bataille, Kit utilise un blaster, un PDA pour changer son apparence, et dans une situation critique, elle se combine avec Kaboodle pour former l'armure "Kibble Star", devenant la foudre rapide et obtenant l'accès au Kibble Star Cannon - un faisceau de puissance destructrice.

CONSEILS:

- Le monde sera détruit après la victoire du héros, pas après la défaite. Souvenez-vous de cela lors du choix d'un côté.
- Protégez-la, car le destin des mondes est avec elle.
