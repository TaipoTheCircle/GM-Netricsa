GSh-18 PISTOL SÉMI-AUTOMATIQUE


ARME: Pistolet semi-automatique GSh-18
MUNITIONS:   Parabellum 9x19mm, 7N21, 7N31
CADENCE DE TIR:    ~15-20 tours/min

DESCRIPTION:

Un pistolet semi-automatique russe a été mis au point à la fin des années 1990 par les concepteurs Vasily Gryazev et Arkady Shipunov, au bureau de conception d'instruments de Tula. Il est destiné à être utilisé comme arme secondaire personnelle pour le personnel militaire et les membres des forces de l ' ordre ou des organismes de sécurité. Le nom est dérivé des premières lettres du nom des concepteurs, tandis que le numéro 18 indique la capacité du magazine. Il se caractérise par son faible poids, son cadre en polymère et sa grande capacité de magazines.

Le pistolet fonctionne selon un principe de court-recoil avec un mécanisme de verrouillage rotatif en baril. Il abrite des munitions 9x19mm, y compris des cartouches spécialisées 7N21 et 7N31. Elle est alimentée par un magazine à double stack avec une capacité de 18 tours. L'arme est munie d'un mécanisme d'attaque et d'une sécurité de déclenchement automatique. Il est équipé de vues en fer de type ouvert.

REMARQUES:

- Efficace contre des cibles individuelles à courte portée, y compris celles portant une armure corporelle (lorsqu'elles utilisent des munitions appropriées).
- Le nom est dérivé des noms de famille Gryazev et Shipunov, ainsi que de la capacité du magazine.
- Adopté pour le service au début des années 2000.
- Le magazine tient 18 tours.
- Il se caractérise par son faible poids-environ 500 g, à l'exclusion du magazine.
- La cartouche 7N31 spécialisée offre une capacité de pénétration accrue.
