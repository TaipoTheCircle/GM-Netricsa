ENDERMAN DE LA FIN MINECRAFT


CLASSE:      Enderman
MÉTABOLISME: Indéfini
PERCEPTION: Mob téléport neutre / mystérieux extraterrestre
TAILLE:       9,5 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Neutre
ARMES:    Punch
RÉCOMPENSE:     1000 FC
MENACE:     Haut

DESCRIPTION:

Une des créatures les plus mystérieuses, dont les véritables origines sont encore débattues. Son nom est une combinaison des mots « Fin » (la dimension qu'il est censé habiter) et « hommes » (humains). Selon les théories des fans, les endermen étaient autrefois des gens ordinaires qui ont fui vers la fin pour échapper à une catastrophe. Là, se nourrissant de fruits de chœur, ils mutèrent : ils grandirent, perdirent leur couleur de peau, apprirent à se téléporter et à construire des villes d'enders.

L'aspect des endermen est terrifiant : un corps long, mince, complètement noir, des yeux violets brillants, et une bouche d'où émanent des particules violettes, semblables à celles d'un portail à la Nether. Les Endermen errent dans le monde calmement jusqu'à ce que vous les regardiez directement dans les yeux.

Endermen are unique in that they are the only mob that can naturally spawn in all three dimensions:

Overworld: La nuit dans la plupart des biomes.

Netherworld: Le plus souvent dans la forêt déchirée.

The End: Leur habitat principal. Ici, ils frayent dans d'énormes groupes.

Endermen behavior boils down to two things: téléportation et blocs mobiles. Il peut soulever et déplacer certains blocs (dirt, sable, cactus, fleurs), laissant le chaos dans son sillage. Si un Enderman tient un bloc, il le laissera tomber quand il mourra.

Quand il est oisif, un Enderman fait simplement le tour, ignorant le joueur. Cependant, viser un crosshair à lui ou frapper il fait enrager. Le corps de l'Enderman commence à trembler, sa bouche s'ouvre, et il laisse sortir un cri terrifiant et électroniquement déformé. Puis le combat commence :

Les Enderman téléportent derrière l'ennemi ou sur leurs côtés, livrant des coups puissants de ses mains.

Tout projectile (flèche, boule de neige, œuf) provoque la téléportation avant l'impact. Il est impossible de tuer un Enderman avec un arc.

L'eau et la pluie endommagent Endermen. Lorsqu'ils sont exposés à l'eau ou sous la pluie, ils paniquent et se téléportent.

CONSEILS:

- Mettez une citrouille sculptée sur votre casque. Votre vision sera altérée, mais l'Enderman n'aggrora pas peu importe combien vous la fixez.
- Les Endermen mesurent presque 3 blocs. Construisez un maigre-à 2 blocs hors du sol. Vous pouvez frapper les jambes de l'Enderman, mais il ne pourra pas vous atteindre.
- Appuyez sur le dos contre un mur ou un coin. Cela empêchera l'Enderman de se téléporter derrière vous.
- Frapper les jambes de l'Enderman va l'empêcher de se téléporter dans la douleur.
- Jeter de l'eau à vos pieds créera une barrière. Les Endermen ont peur de l'eau et ne s'approcheront pas.
- La meilleure arme est une épée. Frappe vite, essayant de garder l'ennemi devant toi.
- Les endermites détestent les endermites (petits insectes violets) et les chassent même si vous les regardez.
- Si un Enderman meurt alors qu'il tient un bloc, ce bloc est abandonné. L'exception est les blocs non-loot (comme le substrat rocheux). Il y a des légendes fan sur le White Enderman, qui semble apparaître rarement, mais officiellement ce n'est qu'un bug de texture ou un mod.