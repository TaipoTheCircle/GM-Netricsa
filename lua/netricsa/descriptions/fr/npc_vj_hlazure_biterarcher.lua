BITER DE XEN


CLASSE:      Créature aquatique Xen (prédateur)
MÉTABOLISME: Carnivore amphibie étranger
PERCEPTION: Prédateur sous-marin Alien
TAILLE:       ~3,5 pieds de long
ENDURANCE:  Faible
HOSTILITÉ:  Haut
ARMES:    Morsure pointue (mélange seulement)
RÉCOMPENSE:     200 FC
MENACE:     Faible-modéré

DESCRIPTION:

Le Biter est la variante verte de la même espèce de Xen que l'Archer. Contrairement à son parent rouge, il manque de capacités variées et repose entièrement sur la morsure. Les biters sont rapides sous l'eau et tenteront d'écraser leurs proies, accablantes par leur nombre plutôt que de cracher de l'acide.

CONSEILS:

- Gardez-les à distance avec des armes variées - ils ne peuvent pas attaquer à distance.
- Les fusils de chasse ou les armes à feu rapides sont efficaces s'ils se rapprochent.
- Plus facile à envoyer que Archers, mais dangereux si ignoré en groupes.
