SOLDAT D'ÉLITE MENDEL-GRUMAN


CLASSE : Soldat d'élite Mendel-Gruman
MÉTABOLISME : humain, masculin
PERCEPTION : infanterie lourde
TAILLE : 5,9 pieds
ENDURANCE : Élevée
HOSTILITÉ : Très élevée
ARMES : Fusil à impulsion ORO L66, Grenades à impulsion
RÉCOMPENSE : 600 FC
MENACE : Très élevée

DESCRIPTIF :

Les soldats d'élite Mendel-Gruman sont une version renforcée de l'infanterie standard de la société. Ils reçoivent un blindage nettement plus lourd et sont armés du fusil à impulsion moderne ORO L66, les transformant de simples tireurs d'élite en unités d'assaut dangereuses.

Contrairement aux soldats standards, les Elites ont un équipement de protection plus sombre et une silhouette nettement plus massive. Leur blindage peut résister à un nombre important de coups, ce qui rend beaucoup plus difficile leur élimination rapide avec des armes légères conventionnelles.

L'arme principale de l'Elite, le fusil à impulsion ORO L66, est un fusil automatique précis tirant des cartouches à l'uranium appauvri perforantes. L'arme a une grande capacité de chargeur, une grande précision et une bonne cadence de tir, mais surchauffe lors d'un tir prolongé.

Le L66 dispose également d'un mode secondaire : un lance-grenades à impulsion. Ceux-ci ne sont pas particulièrement efficaces pour infliger des dégâts directs, mais ils ont un puissant effet de recul, leur permettant de mettre les ennemis hors de leur abri et de les faire tomber.

Les élites opèrent généralement en escouades et peuvent diriger des groupes de soldats plus légers. Leur présence sur le champ de bataille augmente considérablement la puissance de feu d'une escouade Mendel-Gruman.

CONSEILS :

- Donnez la priorité à l'élimination des Elites s'ils font partie de l'infanterie régulière.
- Utiliser une couverture : Le L66 est très précis et capable de tirer efficacement à longue portée.
- Attention aux grenades à impulsions. Ils peuvent vous mettre à couvert et vous laisser exposé aux autres soldats.
- Malgré son armure lourde, les tirs à la tête restent le moyen le plus efficace de le tuer.
- Ne le confondez pas avec les soldats Heavy Weapons MG : les mitrailleuses lourdes portent le Warhorse, tandis que le soldat d'élite porte le L66.