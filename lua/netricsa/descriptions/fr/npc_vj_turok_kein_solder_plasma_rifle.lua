VENDU ELITE MENDEL-GRUMAN


CLASSE:      Mendel-Gruman Elite Soldat
MÉTABOLISME: Humain, Homme
PERCEPTION: Infanterie lourde
TAILLE:       5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Très élevé
ARMES:    ORO L66 Rifle d'impulsions, Grenades d'impulsions
RÉCOMPENSE:     600 FC
MENACE:     Très élevé

DESCRIPTION:

Mendel-Gruman Elite Soldiers sont une version améliorée de l'infanterie standard de la société. Ils reçoivent une armure beaucoup plus lourde et sont armés de l'ORO L66 Pulse Rifle moderne, les transformant de simples tireurs en unités d'assaut dangereuses.

Contrairement aux soldats standard, les Elites ont un équipement de protection plus foncé et une silhouette nettement plus massive. Leur armure peut résister à un nombre important de coups, ce qui rend beaucoup plus difficile de les éliminer rapidement avec des armes légères classiques.

L'arme primaire de l'Elite, le ORO L66 Pulse Rifle, est un fusil automatique précis tirant des balles d'uranium appauvri. L'arme a une grande capacité de chargeur, une grande précision, et un bon taux de tir, mais surchauffe pendant les tirs prolongés.

Le L66 a également un mode secondaire : un lance-grenades à impulsions. Ceux-ci ne sont pas particulièrement efficaces pour infliger des dommages directs, mais ils ont un puissant effet de retour, leur permettant de frapper les ennemis hors de la couverture et les abattre de leurs pieds.

Les élites opèrent généralement en escadrons et peuvent diriger des groupes de soldats plus légers. Leur présence sur le champ de bataille augmente considérablement la puissance de feu d'une équipe Mendel-Gruman.

CONSEILS:

- Privilégier l'élimination de l'élite s'ils sont avec l'infanterie régulière.
- Couverture d'utilisation: Le L66 est très précis et capable d'un feu efficace à longue portée.
- Méfiez-vous des grenades. Ils peuvent te sortir de la couverture et te laisser ouvert aux autres soldats.
Malgré sa lourde armure, les coups de tête restent le moyen le plus efficace de le tuer.
- Ne le confondez pas avec les soldats du MG des armes lourdes : les armes lourdes portent le cheval de guerre, tandis que le soldat d'élite porte le L66.
