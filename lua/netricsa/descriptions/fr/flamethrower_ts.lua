UN FAMÉTHROWEUR DOMADIEN


ARME: Lance-flammes maison
MUNITIONS:   Essence
CADENCE DE TIR:    Feu continu
POIDS: 9 kg (vide),
14 kg (plein)

DESCRIPTION:

Un lance-flammes fait maison. Créé en combinant une pompe à vélo, une boîte à essence et des fusées éclairantes. Il consomme des munitions rapidement, mais s'avère très utile contre les monstres vulnérables au feu. Cette arme expérimentale utilise l'essence pour créer une flamme puissante. Le lance-flammes est très efficace contre de grandes concentrations de troupes ennemies (tant vivantes que non vivantes), avec un flot de flammes atteignant même ceux qui se cachent. Le fait qu'ils continueront à brûler pendant quelques secondes avant de mourir ne fait qu'accroître l'effet. Certains appellent ce type d'arme "la mettre et l'oublier"

REMARQUES:

- Efficace contre les grandes concentrations de troupes ennemies