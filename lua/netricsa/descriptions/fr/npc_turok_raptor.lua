UTHARAPTEUR DU PLANET TERRAFORMÉ


CLASSE:      Utahraptor
MÉTABOLISME: Prédateur, Théropod
PERCEPTION: Chasseur de paquets
TAILLE:       ~8,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrêmement élevé
ARMES:    Griffes, dents, vitesse, tactique de pack
RÉCOMPENSE:     400 FC
MENACE:     Haut

DESCRIPTION:

C'est la principale unité de combat de la population de dinosaures de la planète et la principale migraine pour quiconque s'aventure dans la jungle sans armes lourdes. Si vous imaginez les rapaces comme de petits lézards agiles haut du genou, laissez tomber. Ces créatures sont aussi grandes qu'un homme, pèsent près d'une demi-tonne, et ont des griffes qui peuvent déchirer l'armure du corps comme du carton.

Les Utahraptors ressemblent à un hybride d'un oiseau et d'un lézard, avec un tueur distinct courbé. Leurs longues pattes arrière leur permettent d'atteindre une vitesse respectable et d'effectuer des sauts brusques et latéraux.

La principale caractéristique des Utahraptors est qu'ils chassent en meute. Un seul rapace est dangereux, mais le vrai enfer commence quand il y en a trois, cinq, voire une douzaine. Ils entourent, flanquent, distraient et frappent par derrière. Si vous les laissez vous entourer, vous ne pouvez même pas essayer de vous échapper.

CONSEILS:

- Ne bougez pas. Les rapaces sont plus rapides que vous, mais leur trajectoire d'attaque est prévisible.
