CINQUANTE-CINQUANTE-DEUXIÈME SESSION


CLASSE:      Feux Snark
MÉTABOLISME: Insecte carnivore (mutation du feu)
PERCEPTION: Insecte étranger, Embers vivants
TAILLE:       6 pouces
FINANCEMENT Faible
HOSTILITÉ:  Très élevé
ARMES:    Bite de feu
RÉCOMPENSE:     100 FC
MENACE:     Haut

DESCRIPTION:

C'est une mutation naturelle du snark commun, qui a surgi dans les régions de feu de Xen. Lorsque la lave coule et que l'air est brûlant, les pièges communs ne peuvent survivre. Mais la nature de Xen a trouvé une solution : ceux qui survivent se sont transformés en insectes noirs et rouges dont les coquilles brillent de l'intérieur, comme les braises enflammées.

Contrairement à leurs frères, qui vivent quelques secondes et qui explosent de l'enthousiasme pur, les pièges au feu ne sont pas soumis à l'autodestruction. Ils peuvent vivre longtemps. Très longtemps. Et tout ce temps, ils essaieront de te dévorer. Ou vous mettre en feu. Ou les deux en même temps.

Ils ont un corps noir avec des veines rouges vives qui pulsent comme de la lave dans un volcan. De loin, ils brillent et réfléchissent la lumière, ce qui les rend faciles à repérer. Mais dès que vous vous approchez, ils disparaissent de la vue, se mélangeant dans l'ombre et les roches chaudes.

Une morsure de feu n'est pas seulement douloureuse, elle enflamme sa cible. Un coup, et tu es en feu. Deux, et tu n'auras pas le temps de t'éteindre. Les survivants disent que ces créatures attaquent délibérément des groupes pour que leurs victimes n'aient pas le temps de réagir à de multiples incendies.

Fire Snarks sont constamment en conflit avec les calmars du Diable, leurs voisins dans les régions de feu. Le conflit dure depuis des siècles. Personne ne se souvient comment tout a commencé. C'était peut-être sur le territoire. Peut-être que c'était fini. Ou peut-être que les Taureaux du Diable ont simplement refusé de reconnaître que le rouge sur les coquilles des Snarks n'était pas « rose », comme ils le prétendaient.

Quand il est tué, un Fire Snark ne meurt pas simplement. Il se désintègre en morceaux de lave fondue qui volent dans toutes les directions.

CONSEILS:

- Ne vous approchez pas trop d'un Fire Snark. Ça n'explose pas comme un Snark, mais sa morsure le met en feu.
- Ils peuvent être vus de loin par leur lueur. Utilisez un fusil à sniper.
- Ils sont doublement dangereux au combat. Gardez vos distances.
- Les snarks ne meurent pas seuls.
- Si vous voyez un paquet, utilisez des explosifs. Il y a déjà du feu partout, un peu plus ne ferait pas de mal.
- Le feu et les taureaux se détestent. Si possible, mettez-les l'un contre l'autre. Qu'ils se tuent.
