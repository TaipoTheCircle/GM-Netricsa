ANTI-NEXTBOT LASER V1


ARME: Laser V1 anti-bot suivant
MUNITIONS:   AR2 Énergie pulsée / Charges laser
CADENCE DE TIR:    Faisceau continu

DESCRIPTION:

Une version améliorée du fusil AR2, spécialement adapté pour combattre les Nextbots. Il comporte un système de hiérarchisation des cibles, permettant la destruction effective d'entités anormales sans destruction inutile de l'environnement.

Le mode 1 active un laser focalisé qui détruit instantanément toutes les cibles vivantes et hostiles, ignorant complètement les accessoires et les objets environnementaux. Cela le rend idéal pour repérer la clairière dans des espaces confinés.

Le mode 2 désactive le filtrage et permet d'endommager les ennemis et les accessoires. Il est utilisé contre les Nextbots résistants ou non conventionnels lorsque la force brute et la destruction complète de la zone sont nécessaires.

REMARQUES:

- Mode 1: Destroys cibles, ignorant les accessoires et les objets environnementaux.
- Mode 2: Dédommage tout, y compris les objets et la couverture.
- Très efficace contre les Nexbots standard.
- Le mode 2 est dangereux pour l'environnement.
- Efficace à moyenne et longue portée.
