SURVEILLANCE DE LA COMBINE


CLASSE:      Combiner Overwatch Superior Sniper
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Unité de reconnaissance et de grève à longue distance
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Combiner la précision de l'action de phase Sniper Rifle
RÉCOMPENSE:     700 FC
MENACE:     Très élevé

DESCRIPTION:

Le sniper Overwatch Superior est une version expérimentale du standard Combine Sniper, conçu pour une efficacité maximale à toutes les gammes. Son casque blanc est équipé de deux visières optiques bleues situées au centre. La première visière est optimisée pour les champs de combat rapprochés et urbains, tandis que la seconde est pour l'observation et la prise de vue à très grande distance.

L'armure du soldat est légère, bleue et blanche, ce qui réduit la protection mais augmente la mobilité et la vitesse. Le Combine croit que le meilleur tireur d'élite est celui qui ne peut pas être abattu à temps.

La principale caractéristique de l'arme est son faisceau de visée d'énergie. En mode normal, il est bleu, mais une fraction de seconde avant le tir, il change en rouge, signalant la phase critique de ciblage.

CONSEILS:

- Si le faisceau devient rouge, changez de position immédiatement.
- Il a une armure faible, mais une précision parfaite.
- Ne restez jamais dans les zones ouvertes si c'est à proximité.
