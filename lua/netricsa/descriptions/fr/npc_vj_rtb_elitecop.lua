NT1 PROTECTION CIVILE


CLASSE:      RTB Combiner la protection civile Elite
MÉTABOLISME: Humain très conditionné, mâle (stade pré-Surveillance)
PERCEPTION: Transhuman Law Enforcement (Unité Elite)
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne-haute
HOSTILITÉ:  Haut
ARMES:    Stun Stun-Stick, 9mm Pistol, SMG1, Barreaux explosifs, Manhack
RÉCOMPENSE:     350 FC
MENACE:     Moyenne-haute

DESCRIPTION:

La RTB Combine Civil Protection Elite représente l'échelon supérieur des forces de police métropolitaines, servant d'étape de transition entre la protection civile standard et les soldats Overwatch. Dotés d'armures renforcées et d'équipement de communication plus avancé, ils sont déployés dans la répression des émeutes, des patrouilles à grande échelle et des raids hautement prioritaires contre les cellules de résistance.

Contrairement aux Metro Cops, ces élites ont subi un conditionnement et une augmentation plus lourds, les rendant plus forts, plus disciplinés et plus morts au combat. Leurs masques disposent de filtres renforcés et de tons plus foncés, souvent avec des optiques améliorées pour leur donner un aspect intimidant.

Au combat, les Elites de Protection Civile opèrent avec une meilleure coordination et une puissance de feu plus lourde, en utilisant des tactiques de suppression pour chasser les ennemis de la couverture. Ils ne sont pas encore aussi durables que la véritable infanterie Overwatch, mais représentent une grave escalade lorsqu'ils sont déployés dans les villes occupées.

CONSEILS:

- Souvent des équipes de chefs d'officiers réguliers.
- S'il est rencontré, il se peut que les renforts de Combine ne soient pas loin derrière.
