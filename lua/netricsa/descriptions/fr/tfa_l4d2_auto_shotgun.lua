"UBOYNIK" (KILLER)


ARME: Fusil semi-automatique "Uboynik" (Killer)
MUNITIONS:   12 x 70 mm
CADENCE DE TIR:    Capacité semi-automatique, 6 tours

DESCRIPTION:

Un fusil semi-automatique fait maison, fabriqué par les armuriers de l'Ordre après la guerre nucléaire. Il dispose d'une conception non conventionnelle avec un cylindre tournant exposé qui contient six coquilles de calibre 12. Au lieu d'un système d'alimentation traditionnel, il utilise un mécanisme unique avec des clips à ressort pour sécuriser les munitions. Il fournit une puissance d'arrêt élevée à distance et est principalement destiné à lutter contre les mutants ou les adversaires dans des espaces confinés.

L'arme fonctionne par l'intermédiaire d'un système de baril de court-recoil combiné avec un mécanisme de verrouillage à bascule. Après chaque coup, l'action éjecte le boîtier épuisé et avance la coque suivante du cylindre. Dans la configuration standard, le rechargement est effectué manuellement, un shell à la fois, ce qui prend du temps. Des modifications ultérieures permettent l'utilisation de fûts ou de boîtes à tambour de grande capacité.

REMARQUES:

- La version standard utilise un cylindre tournant à six tours exposé.
- Des magazines d'une capacité de 3, 6, 10 et 20 tours sont disponibles.
- Une variante unique équipée d'une baïonnette existe.
- Supporte la fixation d'une vue rouge point, d'une portée infrarouge, d'un suppresseur et d'un designateur laser.
- Capable de tirer des munitions incendiaires.
- La conception rappelle les fusils à cylindre tournant comme la Protecta et les MT-255.
