USSSR GUN SOUS-MACHINE GUN


ARME: GUN sous-machine USSSR
MUNITIONS:   Projectiles énergétiques
CADENCE DE TIR:    ~750 tours/min

DESCRIPTION:

Un pistolet à sous-machine inhabituel basé sur la conception du SMG1 (MP7). Au lieu de balles conventionnelles, l'arme tire des faisceaux d'énergie de couleur arc-en-ciel; à l'impact, ces faisceaux forment un symbole de l'URSS éclatant au point de contact. Une fois manifesté, le symbole dérive progressivement et s'efface.

La tenue de l'arme déclenche l'hymne national de l'URSS. Chaque premier tir redémarre la pièce musicale dès le début, et la musique s'efface une fois que le tir cesse. L'USSSR GUN dispose également de deux modes de tir alternatifs : le premier tire simultanément plusieurs projectiles énergétiques, fonctionnant comme un fusil de chasse ; le second utilise un lance-grenades sous-barrel qui tire des projectiles en forme de logo de l'URSS qui produisent le même effet sur l'impact.

REMARQUES:

- Basé sur le modèle de mitrailleuse SMG1 (MP7).
- Le feu primaire produit des poutres de couleur arc-en-ciel qui manifestent le symbole soviétique au point d'impact.
- Le premier mode de tir alternatif permet une attaque de style volley, similaire à un fusil.
- Le lance-grenades sous-barrel tire de grands projectiles portant le logo de l'URSS.
- L'hymne national de l'URSS joue pendant que l'arme est retenue, redémarrant avec chaque tir initial.
