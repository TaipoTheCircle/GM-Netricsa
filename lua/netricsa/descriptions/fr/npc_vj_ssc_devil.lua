C'est la troisième incarnation du vilain Ugh-Zan, dernier des géants de Warlock. Ugh-Zan a le rang de grand amiral dans l'armée mentale, et a servi le mal pendant des millions d'années.
Aussi grande qu'une montagne, assez bien armée pour affronter un croiseur intergalactique, dotée de pouvoirs magiques invisibles et de la capacité de régénération, ce grand guerrier est l'une des créatures les plus dangereuses de l'univers.
Ugh-Zan a été envoyé par Mental pour superviser le nettoyage final de la planète Terre.

