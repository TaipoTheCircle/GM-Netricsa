SURVEILLANCE DE LA RIFLE D'ÉBAUCHE MK1


ARME:      Sniper Rifle MK1
MUNITIONS:        Combiner des snipers à grande vitesse
CADENCE DE TIR:         Semi-automatique, ~30 rds/min

DESCRIPTION:

Fusil de sniper prototype développé pour Combiner des snipers d'élite pendant les premiers stades de l'occupation. Équipé d'une portée de précision, il tire des rondes hyper-vitesse capables de neutraliser instantanément des cibles légèrement blindées ou non blindées. Contrairement au dernier MK2, cette version avait une conception plus expérimentale.

REMARQUES:

- Extrêmement mortel à long terme; souvent fatal avec un seul coup.
- Le feu semi-automatique permet un suivi plus rapide que le MK2.
- Rare et limité aux unités de tireurs d'élite.
- Représente la transition vers le Sniper Rifle MK2 finalisé.