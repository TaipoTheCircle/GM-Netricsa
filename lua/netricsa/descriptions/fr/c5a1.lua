XEN, APRÈS-MÊME


Le Nihilanth est mort. La faille est fermée. Xen se tait...

Mais avant même que vous puissiez reprendre votre souffle, la réalité scintille et vous êtes sorti du champ de bataille. Tu réapparais dans un vide stérile et sans fin. Un homme en costume d'affaires bon marché se tient devant vous, mallette à la main, sourire faible mais rasoir.

Il vous informe que toutes vos armes, votre costume de S.E.V. - même vos sous-vêtements - ont été confisquées. "Biens du gouvernement", dit-il, "appartenant à une entité, Prospero". Son ton est poli, mais chaque mot ressemble à un contrat que tu n'as jamais signé.

Puis il commence à parler de toi. Il t'appelle "FREEMAN", un nom que tu commences à détester. Il loue votre performance, admire votre efficacité, et pourtant chaque compliment ressemble à une cage.

He offers you a choice:

Reste ici, désarmé, entouré d'étrangers qui te déchireront probablement.

Ou entrez dans un portail de stase brillant, où vous "attendrez" jusqu'à ce que ses employeurs décident de vous réveiller. Ça pourrait être demain. Peut-être jamais.

L'homme attend. Les pulsations du portail. C'est l'heure de choisir.