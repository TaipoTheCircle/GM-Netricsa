BUG SOLDIER DU PLANET TERRAFORMÉ


CLASSE:      Soldat Bug
MÉTABOLISME: Insectes
PERCEPTION: Prédateur d'embuscade souterraine
TAILLE:       Grandes
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrêmement élevé
WEAPONSL:   Pincers, bûcherons, toxines
RÉCOMPENSE:     300 FC
MENACE:     Haut

DESCRIPTION:

Ces créatures ressemblent à un scorpion plus grand que la vie, seulement avec une expression plus vicieuse et un manque total d'intérêt pour autre chose que tuer.

Les soldats de Bug habitent profondément sous la surface, où ils creusent des tunnels et attendent que quelque chose de chaud et charnu tombe d'en haut. Parfois, ils émergent pour chasser ou simplement rappeler aux dinosaures locaux qui sont en charge.

Au combat, les Bug Soldiers se précipitent vers leur cible et essaient de les coincer. Le combat étroit est leur fort. Leurs pincers attrapent, leurs piqûres, et si cela ne suffit pas, chaque Bug contient une toxine capable de tuer un humain en quelques secondes.

CONSEILS:

- Un fusil à bout portant est le moyen le plus rapide de tuer un Bug tombé.
- Ne vous approchez pas d'un Bug tombé jusqu'à ce que vous soyez sûr qu'il est vraiment mort.
