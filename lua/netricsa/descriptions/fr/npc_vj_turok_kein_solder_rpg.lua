SOLDAT RPG MENDEL-GRUMAN


CLASSE : Soldat RPG Mendel-Gruman
MÉTABOLISME : humain, masculin
PERCEPTION : Infanterie antichar spécialisée
TAILLE : ~5,9 pieds
ENDURANCE : Moyenne
HOSTILITÉ : Extrême
ARMES : RPG ORO "Red Fist", fusil de chasse ORO "Enforcer", grenades à fragmentation
RÉCOMPENSE : 400 FC
MENACE : Élevée

DESCRIPTIF :

Le MG RPG est une unité spécialisée de la société Mendel-Gruman, conçue pour utiliser des armes de missiles lourds. Extérieurement, il conserve l'esthétique générale de l'infanterie légère de la corporation, mais diffère des soldats ordinaires par son armure gris-argent métallique, la conception modifiée de son casque et ses épaulettes.

L'arme principale de cette unité est le RPG ORO "Red Fist". Le lance-roquettes lui permet d'engager des cibles à distance et d'infliger de sérieux dégâts à des groupes d'infanterie, des véhicules et d'autres cibles de grande taille. C'est précisément la présence du lance-roquettes qui fait du MG RPG un adversaire bien plus dangereux que le Infantryman standard.

Il y a cependant une caractéristique assez inhabituelle de cette unité : les MG RPG ne transportent pas forcément de RPG. La plupart portent des fusils de chasse ORO "Enforcer".

Par conséquent, le nom « RPG » désigne plus précisément le type d’unité que l’arme garantie d’un soldat spécifique. Rarement, certaines unités sont réellement armées du RPG Red Fist. De plus, un soldat notable doté d'un RPG est techniquement considéré comme un fantassin ordinaire, et non comme un MG RPG à part entière, ce qui est l'une des particularités de la distribution finale des armes.

Les MG RPG opèrent généralement aux côtés d’autres unités Mendel-Gruman. Il peut prendre un point d'observation et tirer à distance sur l'ennemi pendant que l'infanterie régulière maintient son attention. Il est particulièrement dangereux dans un groupe mixte, car il oblige les joueurs à surveiller simultanément les tireurs et une éventuelle frappe de missile.

Lorsqu'il utilise l'Enforcer, son comportement devient plus agressif : il essaie de se rapprocher de l'ennemi et d'utiliser la grande efficacité du fusil à pompe à courte portée. Ainsi, un même type d’unité peut représenter deux menaces complètement différentes selon l’arme utilisée.

CONSEILS :

- Vous voyez un pistolet lance-fusées ? Considérez votre journée comme pire.
- Ne restez pas en groupe à proximité d'alliés : un coup du RPG Red Fist ORO peut toucher plusieurs soldats à la fois.
- Vérifiez l'arme que vous avez entre les mains, pas seulement son apparence. Un RPG MG pourrait très bien être armé d'un Enforcer au lieu d'un RPG.
- S'il est armé d'un fusil de chasse, gardez vos distances et ne le laissez pas s'approcher.
- S'il est armé d'un RPG Red Fist, utilisez un abri et essayez de l'éliminer en premier.
- Comme les autres unités MG légères, il n'est pas connu pour sa capacité de survie exceptionnelle, donc un tir concentré résout rapidement le problème.