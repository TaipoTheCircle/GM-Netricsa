MENDEL-GRUMAN RPG SOLDATEUR


CLASSE:      Mendel-Gruman RPG Soldat
MÉTABOLISME: Humain, Homme
PERCEPTION: Infanterie anti-tank spécialisée
TAILLE:       ~5,9 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrême
ARMES:    ORO "Red Fist" RPG, ORO "Enforcer" fusil de chasse, Frag Grenades
RÉCOMPENSE:     400 FC
MENACE:     Haut

DESCRIPTION:

Le MG RPG est une unité spécialisée de la société Mendel-Gruman, conçue pour utiliser des armes à missiles lourds. De l'extérieur, il conserve l'esthétique générale de l'infanterie légère de la société, mais diffère des soldats réguliers dans son armure métallique gris-argent, la conception modifiée du casque et les épaulettes.

L'arme principale de cette unité est le RPG "Red Fist". Le lance-roquettes lui permet d'attaquer des cibles à distance et d'infliger de graves dommages à des groupes d'infanterie, de véhicules et d'autres cibles importantes. C'est précisément la présence du lance-roquettes qui fait du MG RPG un adversaire beaucoup plus dangereux que le standard Infantryman.

Cependant, il y a une caractéristique assez inhabituelle de cette unité : les RPG MG ne portent pas nécessairement de RPG. La plupart portent des fusils ORO "Enforcer".

Par conséquent, le nom « GPR » indique plus précisément le type d'unité que l'arme garantie d'un soldat donné. Rarement, certaines unités sont en fait armées du RPG Red Fist. De plus, un soldat remarquable avec un RPG est techniquement considéré comme un soldat d'infanterie ordinaire, et non comme un MG RPG à part entière, ce qui est l'une des particularités de la distribution finale des armes.

Les RPG MG opèrent habituellement aux côtés d'autres unités Mendel-Gruman. Il peut prendre un point de vue et tirer sur l'ennemi de loin tandis que l'infanterie régulière garde son attention. Il est particulièrement dangereux dans un groupe mixte, car il force les joueurs à surveiller simultanément les tireurs et une éventuelle frappe de missiles.

En utilisant l'Exercice, son comportement devient plus agressif : il essaie de se rapprocher de l'ennemi et d'utiliser la haute efficacité du fusil à portée rapprochée. Ainsi, le même type d'unité peut poser deux menaces complètement différentes selon l'arme émise.

CONSEILS:

- Tu vois une fusée ? Considérez votre journée pire.
- Ne restez pas dans un groupe proche des alliés : un coup du RPG de Red Fist ORO peut frapper plusieurs soldats en même temps.
- Vérifiez l'arme dans vos mains, pas seulement son apparence. Un RPG MG peut bien être armé d'un Enforcer au lieu d'un RPG.
- S'il est armé d'un fusil, gardez vos distances et ne le laissez pas approcher.
- S'il est armé d'un RPG de Red Fist, utilisez une couverture et essayez de le sortir d'abord.
- Comme d'autres unités MG, il n'est pas connu pour sa survivabilité exceptionnelle, un incendie concentré résout rapidement le problème.
