VORTIGAUNT (ÉCRAN)


CLASSE:      HALF-QUAKE Show Vortigaunt, Esclave
MÉTABOLISME: Mammifère intelligent
PERCEPTION: Race d'esclaves
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Forced
ARMES:    Décharge bioélectrique, griffes
RÉCOMPENSE:     300 FC
MENACE:     Moyenne

DESCRIPTION:

Lorsque le salon sadiste HALF-QUAKE s'est engagé avec Black Mesa, Vortigaunts est venu avec l'équipement et les headcrabs. Beaucoup. Ils ont été amenés en lots, entreposés dans des entrepôts, et pendant un certain temps, personne ne savait quoi en faire, parce qu'un mammifère intelligent est plus difficile à programmer qu'un parasite.

The problem was solved simply: Les vieux circuits psioniques de Nihilanth ont été soumis, et chaque Vortigaunt avait une marque blanche apposée sur leur visage avec un stylo marqueur ">) " avant de continuer. La marque est permanente, non pas parce qu'elle est apposée, mais parce que les Vortigaunts ont peur de la retirer.

Ils ne veulent pas se battre. Ils se souviennent encore de la liberté, et leurs sons sont un appel pour que quelqu'un les tire enfin.

À la vue d'un ennemi, un Vortigaunt décharge son énergie bioélectrique accumulée, libérant des éclairs verts des deux mains.

CONSEILS:

- La foudre frappe loin et fait mal. Ne regardez pas les coins inutilement.
- Ils sont plus effrayants en groupe que seuls.
