OMEGA MUTANT DE L'ARCHIPELAGO KRIEGER


CLASSE:      Mutant oméga
MÉTABOLISME: Mutation trigénique finale
PERCEPTION: Plateforme de combat
TAILLE:       12 pieds
ENDURANCE:  Maximum
HOSTILITÉ:  Absolu
ARMES:    Lance-missiles, mini-missiles
RÉCOMPENSE:     5000 FC
MENACE:     Catastrophes

DESCRIPTION:

Omega est l'aboutissement des expériences de Krieger, la forme finale et la plus avancée de Trigens. Réminiscence visuelle de l'homme gras, mais supérieur dans tous les sens. Équipé d'une lourde armure et d'un arsenal intégré, il se transforme en forteresse à pied. Il utilise une combinaison d'armes : des missiles tirés à la main, tandis que des lance-missiles montés à l'épaule recouvrent une zone de mini-missiles.

Il agit comme un point de tir mobile, alternant entre les modes d'attaque pour attaquer des cibles à n'importe quelle portée. Les fusils de chasse sont efficaces contre les ennemis avoisinants, les roquettes contre les groupes éloignés et les mini-volleys ne laissent aucune place à la couverture. Son armure absorbe des dommages importants, le rendant pratiquement invulnérable aux armes standard.

CONSEILS:

- Utilisez des armes lourdes - seuls les lance-grenades et les explosifs sont efficaces contre son armure.
- Continuez à bouger - rester debout égale la mort d'une fusée volley.
Ses armes primaires sont concentrées dans l'hémisphère avant.
- Chercher une couverture des mini-pignons en se déplaçant à l'intérieur ou derrière des structures solides.
