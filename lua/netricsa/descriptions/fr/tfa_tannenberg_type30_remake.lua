RIVEAU D'ACTION DE L'ARISAKA TYPE 30


ARME: Arisaka Type 30 à action de boulon
MUNITIONS:   6,5x50mm Arisaka
CADENCE DE TIR:    ~10–12 tours/min

DESCRIPTION:

Un fusil de chasse japonais a été mis au point sous la supervision du colonel Nariake Arisaka en 1897. Elle a été adoptée par l'armée impériale japonaise la même année, devenant la première famille de fusils « Arissaka ». Il a été créé pour remplacer les fusils Murata obsolètes. Sa conception intègre des caractéristiques empruntées aux systèmes Mauser et Mannlicher, caractérisés par un mécanisme d'action des boulons et un stock en bois.

Il fonctionne à l'aide d'un système de boulon rotatif à commande manuelle. Il utilise des munitions d'Arisaka 6,5x50mm et dispose d'un chargeur interne de 5 ronds, qui est chargé à l'aide d'un clip de strip-teaseuse. Il est équipé de vues en fer ouvert et d'une monture baïonnette. Bien que le fusil offre une bonne précision, la guerre russo-japonaise a révélé des défauts de conception, y compris des problèmes avec l'extraction en cascade et la fiabilité de certains composants de boulons. Il a ensuite été remplacé par le type 38 amélioré.

REMARQUES:

- Bien adapté pour engager des cibles individuelles à moyenne à longue portée.
- Efficace contre le personnel non armé.
- Non destiné à être utilisé contre les véhicules blindés ou les couvertures lourdes.
- Utilisé par les forces japonaises pendant la guerre russo-japonaise.
- Il existait une carbine de type 30 raccourcie.
