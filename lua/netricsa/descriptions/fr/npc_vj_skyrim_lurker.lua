LURKER DE L'APOCRYPA


CLASSE:      Lurker
MÉTABOLISME: Daedric Spawn, Amphibie
PERCEPTION: Gardien des livres noirs
TAILLE:       17 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Très élevé
ARMES:    Griffes, Pieds d'embouteillage, Tentacles toxiques, Spice acide
RÉCOMPENSE:     1000 FC
MENACE:     Haut

DESCRIPTION:

Créatures daédriques originaires des eaux brumeuses d'Apocryphe, le plan d'Hermaeus Mora. Dans la nature, ils gardent des tomes de connaissances interdites, où ils attaquent maintenant les habitants et les voyageurs aléatoires.

Les lurkers ressemblent à un hybride de poissons, de crapauds et de gorilles, avec des éléments d'eau profonde. Ils ont trois orteils sur chaque pied et les jambes arrière massives qu'ils ont empilés, agitant le sol. Les tentacules peuvent jaillir de leur bouche pour des attaques à moyenne portée, et leur cracher acide peut corroder l'armure en quelques secondes.

CONSEILS:

- La crache acide a une longue portée. Dodge ou couvrez-vous.
- Si un lurker attaque avec ses tentacules, reculez.
- Il vaut mieux les tuer de loin avant qu'ils ne s'approchent.
- Ils sont vulnérables au froid.
