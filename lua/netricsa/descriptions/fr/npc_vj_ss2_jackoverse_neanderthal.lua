SAVAGE DUBINOV DE M'DIGBO


CLASSE:      Savage Dubinov
MÉTABOLISME: Mammifère
PERCEPTION: Savage amical, Renegade
TAILLE:       6,8 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Moyenne
ARMES:    Club épicé, Jumelles à os maison, Compétences de chasse
RÉCOMPENSE:     400 FC
MENACE:     Faible

DESCRIPTION:

Un représentant unique des Primitives de la planète M'Digbo. Tandis que ses compagnons de tribus, dirigés par le mystérieux "Mommy", ont fait un pacte avec Mental, acceptant de devenir ses soldats en échange d'un approvisionnement sans fin de strings en peau de léopard, Dubinov a choisi un chemin différent. Il a volontairement renoncé aux normes sociales agressives de son peuple, en faisant un sauvage étonnamment amical.

Dubinov surpasse de manière significative la moyenne primaire dans le développement intellectuel et social. Il possède une jumelle artisanale unique, habilement conçue à partir des os des ennemis et des animaux tombés. Contrairement à ses parents, il préfère chasser le sanglier. Il vit dans les tropiques de la planète avec sa femme, menant une vie paisible, selon des critères sauvages.

Le matin de Dubinov commence dans sa grotte, située au cœur des tropiques. D'abord, il quitte sa demeure et se dirige vers le ruisseau de montagne le plus proche. Ce rituel est immuable : il boit de l'eau propre et se lave complètement, se préparant à un nouveau jour de chasse et observant l'horizon à travers ses jumelles osseuses.

CONSEILS:

- Dubinov n'est pas un ennemi. Ne l'attaquez pas.
- Si vous le rencontrez dans les tropiques, vous pouvez parler. Il vous dira beaucoup de choses intéressantes sur la planète M'Digbo et ses habitants.
- Ses jumelles ne sont pas qu'un jouet. Dubinov peut repérer le danger bien avant qu'il ne se rapproche.
- Si vous l'aidez à chasser, il partagera de la viande et peut-être même vous enseigner quelques trucs simples.
- N'essayez pas de voler ses jumelles. C'est impoli, et Dubinov est très attaché à ses biens.
- La femme de Dubinov est une autre histoire. Il y a des rumeurs sur elle, mais il ne la montre à personne.