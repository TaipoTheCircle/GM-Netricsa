THOMPSON M1928 SUBMACHINE GUN


ARME: M1928 Thompson mitrailleuse mitrailleuse
MUNITIONS:   .45APS
RR:     600 RPM
LENGTH: 25,4 cm

DESCRIPTION:

La mitrailleuse Thompson (aussi connue sous le nom de "Tommy Gun"), popularisé dans les années 1930 par Al Capone et d'autres gangsters, offre une puissance d'arrêt décente, se recharge rapidement, et est la mitrailleuse de l'île. Moins populaire auprès des officiers que le revolver, c'est néanmoins une arme commune. On le trouve d'abord au sommet de l'escalier à côté d'un petit bureau dans le chronomètre de la Deuxième Guerre mondiale, où Tork se souvient du colonel qui criait sur un soldat.

REMARQUES:

- Feu en rafales courtes et longues.
- Al Capone envoie ses salutations.
