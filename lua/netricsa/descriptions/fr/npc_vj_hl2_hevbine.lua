M. OMBINE S.E.V


CLASSE:      Combiner le soldat H.E.V. Overwatch
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Unité expérimentale d'assaut combinée
TAILLE:       5,9 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    OICW, fusil à impulsion AR2
RÉCOMPENSE:     1400 FC
MENACE:     Très élevé

DESCRIPTION:

Le Soldat Combine H.E.V. Overwatch est la preuve directe que le Combine n'invente pas, ils prennent. Après avoir saisi la technologie de Black Mesa, la technologie du costume H.E.V. a été repensée. Le résultat est une combinaison de combat bleu avec les insignes Combiner, conçu à la fois pour protéger le porteur et pour maximiser l'efficacité de combat jusqu'à leur mort.

L'apparence du soldat ressemble à un scientifique en costume de S.E.V., mais la ressemblance est trompeuse. La Combine considère le soldat comme une ressource durable, mais extrêmement dangereuse.

Armés d'un OICW et d'un AR2, ces soldats sont capables de combattre à n'importe quelle portée, en combinant des tirs automatiques avec des grenades sous-marines. Ils sont souvent utilisés dans des situations où les unités de Surveillance standard subissent des pertes excessives et où les forces d'élite sont toujours « redondantes ».

CONSEILS:

- L'OICW le rend particulièrement dangereux derrière la couverture.
- Une endurance élevée ne signifie pas l'invulnérabilité - les explosifs fonctionnent toujours aussi bien.