LLAMA DU MINECRAFT SURVEILLANCE


CLASSE:       Lama
MÉTABOLISME:  Mammifères, ongulés à orteil uniforme
PERCEPTION:  Un troupeau neutre
TAILLE:        6,3 pieds
ENDURANCE:   Moyenne
HOSTILITÉ:   Conditionnel
ARMES:     Craquage
RÉCOMPENSE:      120 FC
MENACE:      Minimal

DESCRIPTION:

Dans la nature, on trouve des lamas dans les savanes et les collines balayées par le vent.

Les lamas sont des créatures neutres par nature. Ils n'attaquent pas, mais s'ils sont frappés, le chameau offensé tourne et crache directement au visage de l'agresseur. La crache vole comme un projectile, inflige un point de dégâts, et ne prend pas feu. Parfois, un lama manque et frappe un autre lama, puis des querelles éclatent dans la meute pour déterminer qui doit qui.

Les lamas ont une haine particulière pour les loups. En voyant un chien sauvage, un lama crache sans avertissement, qu'il ait été touché ou non. Les loups, à leur tour, craignent les lamas forts et s'enfuient toujours.

Les lamas peuvent être domptés. Pour ce faire, montez-les à plusieurs reprises jusqu'à ce qu'ils cessent de vous jeter.

Un lama apprivoisé est un animal idéal.

Outre une poitrine, vous pouvez décorer un lama avec un tapis.

CONSEILS:

- Ne frappe pas les lamas d'abord. Les dommages de la crache sont négligeables, mais il laisse un mauvais goût dans la bouche.
- Si vous rencontrez un marchand itinérant avec des lamas, vous pouvez prendre les lamas pour vous-même en délirant la laisse.
