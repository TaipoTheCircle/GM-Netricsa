WITCH ELLÉNIERIEN DE L'ELLÉNIER


CLASSE:      Witch Harpy Ellenierian
MÉTABOLISME: Mammifère
PERCEPTION: Guerrier primitif
TAILLE:       4,9 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Moyenne
ARMES:    Projectiles magiques, griffes
RÉCOMPENSE:     50 FC
MENACE:     Faible

DESCRIPTION:

Ellenierian Harpy Witches sont très semblables à leurs cousins scythiens, la principale différence étant que l'une des espèces est éteinte et l'autre non.

Les harpies sont créées à partir d'un mélange de cuisses de poulet d'un restaurant fermé SFC (Syrian Fried Chicken), de créatures flottantes en capsules, des ailes de Flying Kleere et de Pigeons géants de Brimland, entre autres.

Ils étaient initialement prévus pour être fabriqués à partir de modèles de chaussettes, mais au lieu de cela ils ont été envoyés pour garder Cecil le dragon.

They have two forms of attack: de lancer des projectiles magiques à distance et de frapper avec leurs griffes dans le combat étroit.

Une créature gênante qui vole et irrite en clignotant certaines parties du corps. Il a appris à transporter diverses créatures méchantes comme les kamikazes dans l'air, ce qui le rend encore plus ennuyeux.

CONSEILS:

- Détruisez des Harpies en combat rapproché avec un fusil à sciage ou des armes de mêlée.
- Détruire de grands groupes avec une mitrailleuse ou une arme ayant un effet de surface.
- Les petits et moyens groupes peuvent être détruits à l'aide d'un fusil à sniper à distance.
