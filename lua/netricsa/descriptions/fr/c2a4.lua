MESA BLACK, SURFACE CESAP


Sam, contre toute attente, tu es sorti du compacteur - apparemment, la poubelle monte vraiment au sommet. Votre évasion improvisée des caisses et des puits de ventilation vous a amené dehors. Pour la deuxième fois dans les heures... l'air frais.

Mais ne célèbrez pas encore. Ce n'est pas la liberté. Vous avez fait surface dans une zone industrielle restreinte sur le terrain de Black Mesa. La disposition suggère qu'une usine de traitement - des tuyaux massifs, des réservoirs de stockage et des machines lourdes dominent l'horizon.

Du bon côté ? Au moins la vue est meilleure que d'être écrasé dans la pâte.