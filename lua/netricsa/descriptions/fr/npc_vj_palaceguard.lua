PALADINE DE GUARD IMPERIAL DE NIRN


CLASSE:      Garde Impériale Paladin
MÉTABOLISME: Impérial, Homme
PERCEPTION: Haute garde du Palais Impérial / Infanterie Elite
TAILLE:       5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Conditionnel
ARMES:    Longs mots en acier fin, bouclier de la Garde impériale
RÉCOMPENSE:     1000 FC
MENACE:     Haut

DESCRIPTION:

Le Palais Impérial au cœur de Cyrodiil est gardé par l'élite de l'élite - les Paladins de la Garde Impériale. Tandis que les gardes ordinaires patrouillent dans les rues de la ville impériale, ces guerriers en armure cérémonielle protègent la résidence de l'Empereur lui-même et les salles des anciens.

Leur apparence commande le respect. Un ensemble complet d'armures, comprenant un casque, des bottes, des griffes et des bretelles, crée l'image d'un gardien permanent de la loi. Ils manient invariablement des armes de haute qualité - une longue épée d'acier fin et un bouclier de garde impériale robuste.

Ces gardes sont généralement sympathiques et accueillent les visiteurs, leur rappelant les règles de l'étiquette : « Veuillez vous comporter tranquillement par respect pour le Palais Impérial » ou « Souvenez-vous, l'intrusion dans le Palais Impérial est une infraction grave. Ne dépassez pas les premier et deuxième étages. » Ils sont prêts à fournir des directions à différentes parties de la ville et pointent guildes et tavernes.

Cependant, leur hospitalité a ses limites.

Tuer un paladin n'est pas une mince affaire. Leur armure est décente, et leur épée fine en acier inflige des dommages graves. Bien que leur cuirasse et leur casque ne puissent être retirés du corps, les armes et la clé du palais peuvent leur être enlevées.

CONSEILS:

- Si vous êtes un citoyen respectueux des lois, profitez de la compagnie et n'essayez pas de vous faufiler dans les zones restreintes du palais. Les paladines vous avertiront une fois.
- Si le combat est inévitable, utiliser la magie variée ou un arc pour affaiblir la paladine avant qu'ils ne se rapprochent.
- Rappelez-vous que leur armure ne vous permet pas de prendre les parties les plus précieuses du champ de bataille, donc ne comptez pas sur elle comme butin.
