MESA BLACK WAREHOUSE, UNE FIN AVEC UNE DÉLAIS


Sam, tu es sorti des conduits d'aération, et j'ai immédiatement trébuché sur une tragédie. Quelque part à côté de vous se trouve un scientifique nommé Harold. Il a été tué par des soldats de l'UE. Il y a du sang sur sa robe, il respire, mais ses yeux... Mes yeux brûlent. Il tient toujours. Et il semble savoir ce dont vous avez le plus besoin.

Harold s'accroche à la conscience avec la dernière de ses forces.

Your task now is:

Pour écouter Harold. Il sait comment sortir d'ici. Mais son temps est compté.

Posez la question principale - "Comment sortir d'ici?" - et écoutez attentivement.

Souviens-toi de ça. Agissez vite.

Allez, Sam. Le temps tourne. Harold respire encore. Ça veut dire que tu as encore une chance.