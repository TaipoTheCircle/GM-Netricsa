VOLTIGORE DE LA DIMENSION X


CLASSE:      Voltigore
MÉTABOLISME: Prédateur bioélectrique
PERCEPTION: Bête de la course X
TAILLE:       10-12 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    Griffes, résistance au broyage, décharge de plasma électrique
RÉCOMPENSE:     600 FC
MENACE:     Très élevé

DESCRIPTION:

Le Voltigore est une bête quadrupède massive créée par Race X comme une artillerie lourde vivante. Son corps musculaire est recouvert d'une armure épaisse et chitine qui offre une excellente protection contre les armes conventionnelles. Les Voltigores sont extrêmement agressifs, se chargeant de leurs énormes griffes et de leur taille écrasante.

Leur capacité la plus dévastatrice est l'émission de plasmas bio-électriques, tirés d'un organe sur leur dos. Ces projectiles explosent avec une puissance dévastatrice, capables de détruire des véhicules blindés et d'effacer l'infanterie. Leurs rugissements terrifiants et leurs motifs lumineux indiquent une attaque imminente, leur donnant une présence presque démoniaque sur le champ de bataille.

Bien que suffisamment intelligents pour lutter en coordination avec d'autres créatures Race X, Voltigores sont principalement déployés comme armes de choc de terreur et de destruction.

CONSEILS:

- Gardez la distance maximale - leurs explosions plasmatiques sont dévastatrices dans les quartiers proches.
- Des explosifs, des roquettes ou des mitrailleuses lourdes sont nécessaires pour les faire tomber rapidement.
- Utilisez la couverture pour appâter leurs attaques plasmatiques avant de contrer.
- Ne jamais sous-estimer leur pouvoir de mêlée - s'ils se rapprochent, les chances de survie baissent fortement.
