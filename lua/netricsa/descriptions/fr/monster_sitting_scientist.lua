SCIENTIFIQUE DU SIÈGE BLACK MESA


CLASSE:      Black Mesa Scientifique, assis
MÉTABOLISME: Humain, Homme
PERCEPTION: Personnel scientifique Black Mesa
TAILLE:       ~6 pieds (assis)
ENDURANCE:  faible
HOSTILITÉ:  aucune
ARMES:    aucune
RÉCOMPENSE:     100 FC
MENACE:     négligeable

DESCRIPTION:

Le scientifique assis est un non-combattant stationnaire rencontré dans les laboratoires et les salles de contrôle de Black Mesa. Habituellement assis aux bureaux ou aux terminaux, ces scientifiques apportent à l'environnement un réalisme, accomplissant souvent des tâches telles que la surveillance de l'équipement ou la prise de notes.

Ils ne se livrent pas au combat et sont extrêmement vulnérables s'ils sont attaqués.

CONSEILS:

- Évitez de leur faire du mal si possible; ils ne se battent pas.
- Observer leur comportement peut donner des conseils sur les objectifs ou les dangers.
S'ils sont attaqués, ils ne peuvent s'échapper.
