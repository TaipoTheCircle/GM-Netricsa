MAUSER C96 M1921 "BOLO" PISTOL SEMI-AUTOMATIQUE


ARME: Mauser C96 M1921 Pistol semi-automatique "Bolo"
MUNITIONS:   7.63x25mm Mauser
CADENCE DE TIR:    ~120 tours/min

DESCRIPTION:

Pistolet semi-automatique allemand, c'est une variante abrégée du Mauser C96, développé par la société Mauser au début des années 1920. La création de cette version est due aux restrictions du traité de Versailles, qui interdit à l'Allemagne de fabriquer des pistolets d'une longueur supérieure à 100 mm. Le M1921 est doté d'un canon raccourci à 99 mm, d'une poignée plus petite et de dimensions globales plus compactes. En raison de sa taille, il a gagné le surnom "Bolo", une référence aux bolcheviks, parmi lesquels le pistolet était assez populaire.

L'arme fonctionne selon un principe de court-recoil et utilise un système de verrouillage avec un bloc de verrouillage pivotant. Il est en chambre pour la cartouche Mauser 7.63x25mm. Les munitions sont alimentées à partir d'un chargeur à boîte intégrale d'une capacité de 10 tours, qui est chargé depuis le haut à l'aide d'un clip de strip-teaseuse. Il est équipé de vues en fer ouvert et d'un marteau extérieur. L'étui en bois peut être fixé au pistolet pour servir d'épaule, ce qui permet un tir plus stable.

REMARQUES:

- L'étui peut servir d'épaule.
- Efficace contre les cibles individuelles et non armées à courte ou moyenne portée.
- Produit de 1921 à 1930.
- Le canon est raccourci à 99 mm.
- Le magazine tient 10 tours.
- Il a été utilisé par l'Armée rouge et diverses formations militaires en Europe de l'Est.
