OPS BLACK ASSASSIN


CLASSE:      Homme Black Ops Operative
MÉTABOLISME: Humain, Homme
PERCEPTION: Membre des Ops noires
TAILLE:       6 pieds de haut
ENDURANCE:  moyenne-élevée
HOSTILITÉ:  extrême
ARMES:    mP5, fusil à sniper (variante), grenades
RÉCOMPENSE:     1500 FC
MENACE:     très élevé 

DESCRIPTION:

Contrairement aux assassines féminines agiles et acrobatiques, les hommes des Ops noirs sont plus lourds, plus blindés et se spécialisent dans les fiançailles variées. Ils opèrent dans des équipes organisées, fournissant souvent des snipers surveillants ou des quartiers rapprochés ambushes avec des SMG silencieux.

Ils font partie de l'équipe Black Ops envoyée pour effacer complètement les preuves de l'incident de Black Mesa, y compris l'élimination des survivants de H.E.C.U. Leurs uniformes noirs et leurs masques leur donnent un regard odieux et sans visage - des soldats du secret, ne répondant qu'aux plus hauts ordres du gouvernement américain.

Mortement précis et implacable, ils représentent la prochaine étape de l'escalade lorsque la norme H.E.C.U. échoue. Faire face à eux signifie que vous êtes officiellement devenu une "fin tranquille".

CONSEILS:

- Continuez à bouger et à utiliser la couverture; rester debout est un suicide.
