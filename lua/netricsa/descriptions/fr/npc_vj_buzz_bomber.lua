BUZZ-BOMBRE DU MOBIUS


CLASSE:      Buzz-Bomber
MÉTABOLISME: Animal-Ion-Fuel
PERCEPTION: Bombardier tactique
TAILLE:       4 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Moyenne
ARMES:    Détonateur ferroviaire, Hull
RÉCOMPENSE:     400 FC
MENACE:     Moyenne

DESCRIPTION:

Quand le Dr Eggman décida de conquérir le ciel, il passa longtemps à choisir un prototype. Les guêpes régulières étaient trop vicieuses, les dragons étaient trop rapides, et les moustiques étaient trop petits. En fin de compte, le choix est tombé sur la Shrew Wasp. Ainsi, le Buzz-Bomber est né.

Après le tir, il s'envole, seulement pour revenir d'une direction différente après un court délai.

CONSEILS:

- Attaque en plantant. Pendant qu'il pose la piqûre.
