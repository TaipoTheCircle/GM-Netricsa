CARBINE AUTOCHTONE SIMONOV


ARME: Carbine autoportante Simonov (SKS)
MUNITIONS:   7,62x39mm
CADENCE DE TIR:    ~35-40 tours/min

DESCRIPTION:

Une carbine soviétique autochargeuse conçue par l'ingénieur des armes à feu Sergei Gavrilovich Simonov. Il a été adopté par l'armée soviétique en 1949. Il est devenu l'une des premières armes soviétiques produites en série pour la cartouche intermédiaire de 7,62x39mm. Il se caractérise par son poids relativement faible, son stock en bois et sa baïonnette pliante.

L'arme fonctionne selon un principe de piston à gaz, le culot étant verrouillé par l'inclinaison du boulon. Il utilise la cartouche intermédiaire de 7,62x39mm. Les munitions sont alimentées à partir d'un chargeur intégral de 10 tours, qui est chargé à l'aide d'un clip de strip-teaseuse. Il dispose de vues en fer, d'un système de recharge à gaz et d'une baïonnette pliante. Contrairement aux fusils d'assaut, il est capable de feu semi-automatique seulement, avec le vélo d'action automatiquement après chaque tir.

REMARQUES:

- Efficace contre les cibles individuelles et de groupe à courte ou moyenne portée.
- Adopté en 1949.
- Capacité du chargeur : 10 tours.
- Poids: environ 3,9 kg avec un chargeur chargé.
- Équipé d'une baïonnette pliante de style pointe ou lame.
- Conçu par Sergei Gavrilovich Simonov.
