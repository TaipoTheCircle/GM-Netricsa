DREYSE M1907 PISTOL SÉMI-AUTOMATIQUE


ARME: Dreyse M1907 Pistol semi-automatique
MUNITIONS:   7.65x17mm Browning (.32 ACP)
CADENCE DE TIR:    Capacité semi-automatique, 7 tours

DESCRIPTION:

Un pistolet semi-automatique allemand conçu par Louis Schmeisser entre 1905 et 1906. Il a été fabriqué par la société Rheinische Metallwaaren-und Maschinenfabrik à Sömmerda de 1907 à 1915. Il a été nommé d'après l'armurier Johann Nikolaus von Dreyse, bien qu'il n'ait aucune implication personnelle dans le développement du pistolet. Cette arme compacte était destinée à l'autodéfense et à être utilisée comme arme de poing par le personnel militaire et les policiers.

Le mécanisme fonctionne selon un principe de rétrogradation et utilise un système alimenté par un gréviste. Il est alimenté par un magazine détachable à une seule pile d'une capacité de sept 7.65mm Des cartouches brunes. Une caractéristique de conception unique est la fixation à charnières du récepteur (ensemble supérieur) au cadre: pour le nettoyage et le démontage, la partie supérieure du pistolet peut être inclinée vers l'avant. L'attaquant à saillie arrière sert également d'indicateur de coq.

REMARQUES:

- Conçu par Louis Schmeisser, père du célèbre designer d'armes à feu Hugo Schmeisser.
- Le poids du pistolet (déchargé) est d'environ 710 g.
- Les visions sont étalonnées pour l'engagement à des distances allant jusqu'à environ 25 mètres.
