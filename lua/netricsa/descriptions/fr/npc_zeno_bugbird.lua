BUGBIRD DU ZENOZOIK


CLASSE:      Bugbird
MÉTABOLISME: Xénobiologique
PERCEPTION: Xénobiologie formée
TAILLE:       1,3 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Moyenne
ARMES:    Bec piétiné, pieds griffés, saut d'attaques
RÉCOMPENSE:     40 FC
MENACE:     Moyenne

DESCRIPTION:

Une petite créature hybride populaire comme un animal de garde ou d'ornement dans les villes de Zenozoik. Il a une peau lisse brun-gris sur la tête, une bouche allongée en bec doublée de petites dents, et des yeux rouges vifs. Son corps est recouvert de fourrure brune avec de légères rayures ondulées. Il a quatre membres avec de grandes griffes et une queue pointue. Contrairement à ce que vous attendez d'un animal de compagnie, il se déplace dans un zigzag aigu, erratique, et quand il est menacé, il fait des sauts inattendus, ce qui en fait une cible difficile. Son régime alimentaire se compose probablement d'insectes (bogues), bien que cela n'ait pas été confirmé. En voyant un ennemi, il devient agressif, en utilisant sa vitesse et saute pour mordre rapidement.

CONSEILS:

- Si ça saute, tu peux donner un coup de pied puissant à la tête.
- Malgré sa vitesse, ses sauts sont prévisibles.
- Utiliser des armes à effet de surface (armes de chasse, grenades explosives à courte portée) ou des armes automatiques à feu rapide pour couvrir sa portée potentielle.
