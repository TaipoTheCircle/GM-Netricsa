WITCH DE L'EXPLOITATION MINECRAFT


CLASSE:      Sorcière
MÉTABOLISME: Humanoïde à sang chaud
PERCEPTION: Assistant intelligent Humanoïde
TAILLE:       6,2 pi
ENDURANCE:  Très élevé
HOSTILITÉ:  Haut
ARMES:    Potions (dommage, lent, poison, faiblesse)
RÉCOMPENSE:     400 FC
MENACE:     Haut

DESCRIPTION:

La sorcière est un représentant isolé d'une civilisation villageoise qui a choisi le chemin des potions, de l'alchimie et du mépris pur et simple de l'opinion publique. À l'extérieur, elle ressemble à une villageoise, mais les différences sont immédiatement visibles : un nez verruqueux, des vêtements sombres et un regard sévère.

La sorcière utilise des potions non seulement pour l'attaque, mais aussi pour la défense. Lorsqu'elle est menacée, elle boit instantanément des potions de résistance au feu, de résistance, de régénération et de respiration de l'eau, se transformant en un adversaire extrêmement résistant.

Elle vit dans des huttes dans les marais ou apparaît lors de raids, où elle agit comme un artilleur alchimique mobile, dévorant des ennemis avec des bouteilles de contenu extrêmement hostile.

CONSEILS:

- Analyse constamment la menace et sélectionne la bonne potion.
- Préfère user l'ennemi plutôt que de tuer rapidement.
- Jamais de panique. Jamais.
- Le lait élimine les effets, mais ne résout pas complètement le problème avec la sorcière.
