LECH DE XEN


CLASSE:      Feu
MÉTABOLISME: xénofaune parasite
PERCEPTION: Prédateur sous-marin du Xen
TAILLE:       1-2 pieds de long
ENDURANCE:  faible individuellement, moyenne en essaims
HOSTILITÉ:  élevé en cas de provocation ou en groupe
ARMES:    morsure, succion, tactique d'essaim
RÉCOMPENSE:     150 FC
MENACE:     faible individuellement, modérée en groupes

DESCRIPTION:

Les sangsues sont de petits prédateurs Xen semblables à des vers, essentiellement des ventouses vivantes avec des dents. Ils se cachent dans les piscines de liquide Xen, attendant que des proies non suspectes s'approchent. Une fois fixés, ils se verrouillent avec une force horrible et commencent à drainer l'énergie - une sangsue vivante littérale.

Malgré leur taille, les essaims de Leech peuvent immobiliser les grandes créatures par leur nombre, les rendant étonnamment dangereux. Leurs corps gélatineux, glissants et leurs mouvements grégaires les rendent difficiles à frapper, et leurs attaques soudaines sont un cauchemar pour les explorateurs qui se rapprochent trop des milieux aquatiques de Xen.

CONSEILS:

- Garder la distance, c'est risqué.
- Évitez de se tenir dans l'eau Xen ou les surfaces visqueuses où se cachent les Leeches.
- Les explosifs ou les tirs lourds peuvent disperser les essaims rapidement.