BARNACLE DE XEN


CLASSE:      Barnacle, Xen
MÉTABOLISME: prédateur d'embuscade carnivore
PERCEPTION: Plafond d'animaux prédateurs
TAILLE:       6-8 pieds (longueur de la langue jusqu'à 20 pieds)
ENDURANCE:  moyenne
HOSTILITÉ:  ampoule passive
ARMES:    langue collante, mâchoires écrasantes
RÉCOMPENSE:     150 FC
MENACE:     moyenne (élevée dans les espaces confinés)

DESCRIPTION:

Le Barnacle est un prédateur stationnaire originaire de Xen, souvent trouvé suspendu aux plafonds, grottes et structures industrielles. Elle s'étend sur une longue langue collante qui s'enchevêtre vers le sol, attendant que quoi que ce soit se brosse contre elle. Une fois le contact établi, la victime est tirée vers le haut vers une mare de dents déchiquetées, où elle est écrasée et dévorée entière. Bien qu'immobiles et prévisibles, les barnacles sont mortelles pour les imprudents, surtout dans les couloirs étroits ou lorsque les victimes sont distraits par d'autres menaces.

CONSEILS:

- Regardez les barnacles sont plus faciles à repérer à distance.
- Les utiliser contre les ennemis : attirer les zombies ou les combiner dans leur langue.
- Un feu court et contrôlé les tuera rapidement.
