STAR SI-35 SUBMACHINE GUN


ARME: Gun sous-machine Star Si-35
MUNITIONS:   9x23mm Largo
CADENCE DE TIR:    300/700 tours/min
POIDS: ~3,8 kg

DESCRIPTION:

Cette mitrailleuse espagnole a été développée par Star Bonifacio Echeverria en 1935. Il a été créé pour les forces armées espagnoles et présentait un design assez inhabituel pour son temps. Son cadre combinait des pièces métalliques avec un stock de bois, et le baril était logé dans un boîtier cylindrique distinctif.

Le Si-35 utilise un système à bouffées lentes et tire d'un boulon ouvert. La caractéristique principale de l'arme est son taux de sélecteur de feu séparé: le tireur pourrait sélectionner un tir à simple tir, environ 300 ou 700 tours par minute.

La conception était considérée comme assez fiable, mais elle était complexe et coûteuse à fabriquer. L'arme a été produite en quantités limitées et a finalement cédé la place à des conceptions plus simples. Un petit nombre de Si-35 ont été utilisés en Espagne pendant les derniers mois de la guerre civile.

REMARQUES:

- Trois modes de tir permettent différentes utilisations de l'arme : des tirs simples pour la précision, 300 cartouches par minute pour le tir contrôlé et 700 pour les rafales continues.
- Le design était assez complexe pour sa classe, ce qui était l'une des raisons d'abandonner le développement du Si-35.
- L'arme avait une baïonnette de type fusil, ce qui est assez important pour une mitrailleuse.
- Une mitrailleuse espagnole avec trois taux de tir: même l'arme a décidé que parfois vous voulez tirer un peu plus calmement.
