MITRAILLEUSE MITRAILLEUSE STAR SI-35


ARME : Mitraillette Star Si-35
MUNITIONS : 9x23 mm de grande taille
ROF : 300/700 tours/min
POIDS : ~3,8kg

DESCRIPTIF :

Cette mitraillette espagnole a été développée par Star Bonifacio Echeverria en 1935. Elle a été créée pour les forces armées espagnoles et présentait un design plutôt inhabituel pour l'époque. Son cadre combinait des pièces métalliques avec une crosse en bois, et le canon était logé dans un boîtier cylindrique distinctif.

Le Si-35 utilise un système à retour de flamme lent et tire à partir d'un verrou ouvert. La principale caractéristique de l'arme est son sélecteur de cadence de tir séparé : le tireur peut sélectionner un tir unique, environ 300 ou 700 coups par minute.

La conception était considérée comme assez fiable, mais sa fabrication était complexe et coûteuse. L'arme a été produite en quantités limitées et a finalement cédé la place à des conceptions plus simples. Un petit nombre de Si-35 furent utilisés en Espagne au cours des derniers mois de la guerre civile.

REMARQUES :

- Trois modes de tir permettent différentes utilisations de l'arme : tirs uniques pour la précision, 300 coups par minute pour un tir contrôlé et 700 pour des rafales continues.
- La conception était assez complexe pour sa classe, ce qui a été l'une des raisons pour lesquelles le développement ultérieur du Si-35 a été abandonné.
- L'arme était équipée d'une monture à baïonnette de type fusil, ce qui est assez important pour une mitraillette.
- Une mitraillette espagnole avec trois cadences de tir : même le pistolet a décidé que parfois on voulait tirer un peu plus sereinement.