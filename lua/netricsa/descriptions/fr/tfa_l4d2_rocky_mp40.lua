ORO FP9 CARBINE D'ASSAULT LUMIÈRE


ARME:     ORO FP9 Carbine légère d'assaut
CAMULATION: Parabellum 9x19mm
CADENCE DE TIR:        90 tours par minute

DESCRIPTION:

Cette arme compacte a été développée par ORO Defense dans le cadre d'un programme de standardisation des armes légères pour les entreprises militaires privées. Le 9e PC est basé sur des modèles MP5 anciens, mais l'accent est mis sur la réduction des coûts de fabrication : l'estampillage au lieu de la fraisage et les composants normalisés.

Il est fabriqué selon la même conception qu'une carbine automatique en chambre pour cartouches de pistolet. Le cadre est en acier estampillé d'une seule pièce avec une finition mate pour réduire la signature IR. Le mécanisme de déclenchement de type marteau permet un feu unique et continu. Il est alimenté par des magazines de 30 ronds, situés devant la poignée de pistolet.

Les vues ouvertes sont non réglables et conçues pour une gamme standard de 100 mètres. Ils sont largement utilisés par les unités de la Whiskey Company et les forces Mendel-Gruman.

Le client principal était Whiskey Company, qui a reçu le premier lot pour le contrôle des émeutes sur les mondes des ressources. Plus tard, les forces de Mendel-Gruman ont largement utilisé une planète terraforme.

REMARQUES:

- Un éclatement de 3-5 tours est garanti pour empêcher une cible.
- Le taux élevé d'incendie permet de supprimer un groupe de jusqu'à trois personnes avant qu'elles puissent se couvrir.
