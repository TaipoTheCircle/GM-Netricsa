REBEL ENGINEER


CLASSE:      Ingénieur rebelle
MÉTABOLISME: Humains
PERCEPTION: Technicien en résistance humaine
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Charge Bow, SPAS-12 Fusil de chasse, Combiner des tourelles déployables
RÉCOMPENSE:     350 FC
MENACE:     Moyenne-haute

DESCRIPTION:

L'ingénieur rebelle est une unité de soutien cruciale au sein de la Résistance humaine. Formés au combat et à l'ingénierie, ils manient une charge Bow pour des attaques de précision à longue portée et peuvent déployer Combiner des tourelles reprogrammées pour défendre les positions rebelles. Ces tourelles jouent le rôle d'appui-feu lourd stationnaire, fournissant un multiplicateur de force pour les petites escouades.

Rebel Engineers sont agiles et débrouillards, souvent flanquant des ennemis pour installer des tourelles ou sécuriser des positions stratégiques. Leur expertise technique leur permet de pirater et de réutiliser les machines Combiner, ce qui les rend indispensables aux opérations sur le terrain.

CONSEILS:

- Prioriser l'élimination des ingénieurs ennemis d'abord-ils peuvent tourner les défenses contre vous.
- Protégez les tourelles déployées - elles fournissent un soutien continu au feu.
- Utilisez leur mobilité pour placer des tourelles dans des endroits inattendus.
- Charge Bow est mortel à portée, capable de pénétrer l'armure légère.
