TURRET ARMÉ NOIR MESA


CLASSE:      Tourelle blindée noire Mesa
MÉTABOLISME: Construction mécanique
PERCEPTION: Unité de défense automatisée
TAILLE:       ~4 pi
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Mitrailleuse lourde à feu rapide
RÉCOMPENSE:     600 FC
MENACE:     Haut

DESCRIPTION:

Le Turret blindé Black Mesa est une unité de défense automatisée fortement renforcée conçue pour sécuriser les couloirs, les laboratoires et les installations sensibles. Contrairement aux tourelles sentinelles standard, il peut être monté à la fois au sol et inversé sur des plafonds, ce qui permet des angles de tir imprévisibles.

Son revêtement blindé offre une résistance aux armes légères, tandis que sa mitrailleuse lourde à feu rapide délivre un incendie mortel. Déployée dans des étranglements ou des couloirs étroits, la tourelle peut contrôler l'accès avec une efficacité dévastatrice, rendant les embuscades et les assauts frontaux extrêmement dangereux.

CONSEILS:

- Visez les points faibles structuraux; l'armure protège la plupart des zones frontales.
- Les explosifs ou la puissance de feu lourde sont efficaces contre elle.
- Surveillez les tourelles au plafond.
- Évitez de rester dans des espaces ouverts; leurs champs de feu sont mortels.
