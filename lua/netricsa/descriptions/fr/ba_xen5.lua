LE MONDE XEN FRONTIER, LE TUNER XEN


Voilà, Sam. Trouvé. Sans danger. Et, selon les normes de Xen, il semble même accueillant.

Il ne reste plus qu'à l'allumer.

Lorsque les scientifiques de Black Mesa bricolaient avec la téléportation, ils ont rapidement réalisé une chose : Xen était impliqué dans le processus.

La solution semblait élégante. Prenez une énorme formation de cristal Xénium, connectez l'appareil à lui, et transformez-le en un point focal. Ainsi, le Xen Tuner est né. Un nœud qui dirigerait la téléportation, comme une balise dans un monde où la direction elle-même est un concept relatif.

L'équipe de recherche envoyée ici pour installer l'appareil a disparu peu après avoir terminé leur travail. Rien de dramatique. Ils ont simplement cessé de communiquer. Les scientifiques sur Terre ont tiré les conclusions appropriées, ont conçu une méthode de ciblage différente, et... ont abandonné l'appareil. Xen, comme d'habitude, n'a pas objecté.

Avant d'être tuner. Un grand appareil. Une paire de tiges mobiles reliées à un cristal. Un petit générateur qui alimente tout. Les tiges sont contrôlées via une console et semblent être mieux laissées seules à moins d'être absolument nécessaires. Ce qui, bien sûr, est exactement ce que nous allons faire.

Ce relais faisait partie d'un réseau à trois éléments.

La première est le noyau du complexe Lambda.

La seconde est une fusée en orbite terrestre. (L'autre vous l'avez déjà fait.)

Le troisième, c'est lui. Voilà. Dans Xen.

Alors vas-y, Sam.

Allume l'appareil.

Faites savoir à Xen que vous jouez toujours selon ses règles.

Et où ça nous mènera...

Ce ne sont que des détails.