POURQUOI


ARME: Whisky
MUNITIONS:   Une seule boîte

DESCRIPTION:

Une boisson alcoolique servie avec de la glace, connue pour son puissant effet enivrant. Consommer progressivement la vision de l'utilisateur rend difficile la perception de l'environnement environnant.

L'effet s'éteint avec le temps; cependant, une consommation excessive sans interruption peut être fatale. Contrairement à la plupart des équipements, cette boisson constitue une menace directe pour son propre propriétaire.

REMARQUES:

- Servi avec de la glace.
- Fausse temporairement la vision sur la consommation.
- L'effet disparaît après un certain temps.
- La consommation continue peut entraîner la mort de l'utilisateur.
