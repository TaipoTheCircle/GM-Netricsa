Nous avons atteint une impasse. Littéralement. Le couloir se termine, ne laissant que quelques pièces, chacune un petit enfer personnel.

First room: une piscine de style Mesa noir

Le sol est inondé. L'eau est trouble et sent l'ozone et quelque chose de brûlant. Au milieu, dans la flaque, une lampe cassée flotte. Ça étincelle. Toutes les quelques secondes, il y a un flash, un craquelin, et l'eau s'anime avec une lumière bleue. Tu ne peux pas rester dedans. Nager ? N'y pense même pas.

The reason: la lampe est tombée dans l'eau et a maintenant transformé cette pièce en soupe électrique. Il ne produit presque aucune lumière, mais la tension est suffisante pour faire frire n'importe qui. Même toi, Sam. Même dans votre armure.

The solution: il y a un interrupteur sur le mur à droite de l'entrée. C'est vieux, rouillé, mais apparemment fonctionnel. Un clic, et la lampe sortira, l'eau tournera vers l'eau, et nous pourrons passer. Question: Pouvez-vous l'atteindre à temps avant que les étincelles transforment tout le plancher en une seule grande prise électrique?

Ensuite vient la dernière chambre. Et ici, Sam, ils nous attendent.

Des yeux croisés. Pas un, pas deux. Un nid entier. La décision, le cri, l'attente. Et parmi eux il y a des crânes. Petit, agile, le genre qui tombe habituellement du plafond au moment le plus inopportun.

La chambre est couverte d'eux. Comme un tapis. Chaque étape est un risque de se mettre sur la queue, chaque mouvement est une invitation à dîner. Ils ne dorment pas, ils ne sont pas partis pour trouver d'autres territoires. Ils sont là. Et ils ont faim.

Strategy Notes:

Disjoncteur. D'abord, éteins le courant. Nous pouvons essayer de tirer sur la lampe, mais cela pourrait seulement aggraver l'eau. Le mode manuel est plus fiable. Et plus vite. J'espère.

De l'eau. Après l'arrêt, ne rentrez pas. Qui sait ce qui flottait devant nous.

La chambre avec les créatures. Il n'y a pas le choix ici. C'est soit nous, soit eux. L'étroite ouverture à l'entrée est une chance de créer un couloir de la mort, mais les yeux de chien savent comment s'y prendre. Têtes de pied - sauter. La meilleure tactique est de lancer une grenade au centre et d'achever les survivants. Sauf si, bien sûr, la grenade roule dans un coin et les irrite encore plus.

L'interrupteur vous attend.
