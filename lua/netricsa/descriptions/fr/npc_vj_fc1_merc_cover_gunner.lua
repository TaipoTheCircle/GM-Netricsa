ARME:     M134
RÉCOMPENSE:     700 FC
MENACE:     Haut

DESCRIPTION:

Le soldat le plus commun et le plus reconnaissable de la compagnie militaire privée du Dr Krieger. Ce sont de grands professionnels physiquement forts recrutés dans le monde entier. Leur motivation est l'argent, pas l'idéologie. Ils portent différents uniformes et coiffures (berets, casques, casques), mais portent toujours une armure corporelle. Bien que beaucoup soient insatisfaits des conditions de service (chaleur, insectes, mauvaise nourriture, isolement), ils restent disciplinés et dangereux adversaires.

Un mercenaire Krieger spécialisé, faisant partie de l'équipage des hélicoptères de patrouille UH-60 Blackhawk. Il est monté à bord près de l'écoutille ouverte et contrôle un minigun rotatif à six barils. Sa mission est de supprimer les cibles au sol et de fournir une couverture aérienne pendant les atterrissages aériens. Il possède une excellente puissance de feu, mais il est extrêmement vulnérable en raison de sa position fixe et de son champ de tir limité. Il n'est protégé que partiellement par la coque de l'hélicoptère. Le désarmer prive l'hélicoptère de son principal armement offensif, le forçant à se retirer du champ de bataille.

CONSEILS:

- Armor protège la coque. La méthode la plus efficace est la prise de tête.
- Évitez les terrains ouverts dans son champ de feu.
- Le tireur est pratiquement à l'abri du feu. Des tirs précis de la tête ou du corps d'une arme sont efficaces.
- Tuer le tireur est le moyen le plus rapide pour neutraliser la menace d'hélicoptère sans utiliser d'armes lourdes.
