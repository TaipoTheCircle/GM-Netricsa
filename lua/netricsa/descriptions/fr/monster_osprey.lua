MENACE:     élevé 

DESCRIPTION:

Le V-22 Osprey est un avion tiltrotor utilisé par l'U.S.E.C. pour déployer rapidement des équipes dans les zones de combat. Sa conception permet le décollage vertical comme un hélicoptère, mais avec la vitesse et la portée d'un avion. Bien qu'il ne soit pas lourdement armé lui-même, son véritable danger réside dans la charge utile qu'il livre : des escadrons de marines prêts à envahir les survivants par des tactiques coordonnées.

Contrairement à l'Apache, l'Osprey s'engage rarement directement. Au lieu de cela, il tourne au-dessus du champ de bataille, dégorgeant les soldats par des cordes de rappel en points chauds. La détruire en milieu d'opération peut paralyser les renforts ennemis, mais son armure et ses manœuvres évasives en font une cible difficile.

CONSEILS:

- Concentrez le feu quand il vole pour déployer des troupes.
- Attendez-vous à des vagues de renforts.
- Les explosifs et les roquettes sont les compteurs les plus efficaces.
La prise d'un en bas nie les renforts ennemis - vaut le risque.