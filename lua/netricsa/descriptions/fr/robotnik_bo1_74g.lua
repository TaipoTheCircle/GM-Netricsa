FUSIL D'ASSAUT PLIANT KALASHNIKOV, 1974, RACCOURCI


ARME : Fusil d'assaut Kalachnikov pliable, 1974, raccourci
MUNITIONS : 5,45x39mm
ROF : 700 tr/min

DESCRIPTIF :

Version raccourcie du fusil d'assaut AKS-74, développé à la fin des années 1970 et au début des années 1980 pour armer les équipages des véhicules et avions de combat des forces armées soviétiques. Il a servi en Afghanistan et en Tchétchénie et est actuellement utilisé dans le district militaire soviétique. Il était également très populaire auprès des bandits russes dans les années 1990. Il est également utilisé par les forces de l'ordre de l'URSS/de la Fédération de Russie et d'autres pays de la CEI.

REMARQUES :

- Sa conception raccourcie permet à cette arme d'être transportée sans être détectée.
- La crosse peut être pliée pour la rendre encore plus courte.
- Très fiable, ne vous laissera pas tomber au combat.
