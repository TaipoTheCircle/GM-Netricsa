RPG


ARME:      RPG (Rocket-Propulsed Grenade Launcher)
MUNITIONS:        Fusées à forte explosion
CADENCE DE TIR:         ~4 fusées/min

DESCRIPTION:

Système d'armes anti-armures lourdes avec ciblage guidé par laser. Fournit une puissance destructrice extrême, capable de détruire des véhicules, des tourelles et de grands organismes hostiles.

REMARQUES:

- Énorme rayon de souffle, mortel pour les groupes.
- Le guidage laser assure des accès précis.
- Dangereux à tirer dans des espaces confinés.