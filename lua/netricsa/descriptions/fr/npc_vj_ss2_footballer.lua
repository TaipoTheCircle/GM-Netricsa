FOOTBALLEUR AMÉRICAIN ORC, ÉQUIPE JAUNE DE L'ORAZIO


CLASSE : footballeur orc américain, équipe jaune
MÉTABOLISME : Mammifère
PERCEPTION : Athlète professionnel
TAILLE : 12 pieds
ENDURANCE : Moyenne
HOSTILITÉ : Élevée
ARMES : Ballon de football (explosif), bélier
RÉCOMPENSE : 200 FC
MENACE : Élevée

DESCRIPTIF :

Certains orcs étaient trop grands et physiquement brutaux pour être enrôlés dans le corps d'infanterie de Mental. Au lieu de cela, ils ont été recrutés par la Sirius Athletic Association. Sans surprise, la plupart de leurs parties se terminent par des combats brutaux.

Ce sont en fait des clones de l'orc John A.J. Dibaggio, le pire footballeur de tous les temps. Il était si mauvais qu'il n'a jamais tapé dans un ballon, il s'est contenté de courir avec. Cependant, les dames l’aimaient, alors il resta. Sa carrière s'est terminée lorsqu'il a surpris les défenseurs en train de courir avec sa femme et les a tués.

Après un long procès et des preuves irréfutables contre lui, il a été déclaré non coupable. Plusieurs années plus tard, il a été révélé que certains des jurés avaient été soudoyés par Mental, qui l'aimait beaucoup et ne supportait pas l'idée qu'un de ses héros aille en prison.

La rumeur veut qu'il se trouve sur Sirius, où il entraîne les fils de Mental au football.

Bien que ce soit trop dur pour l'infanterie régulière, certains commandants embauchent toujours des footballeurs. Cependant, ils ne leur donnent pas d’ordres précis : ils les laissent simplement faire ce qu’ils veulent. Ils poursuivent des cibles et tentent de marquer ou de leur lancer des ballons de football explosifs.

CONSEILS :

- Leurs balles explosent à l'impact, mais elles peuvent être renversées en plein vol.
- Essayez de les tuer à distance ; leurs attaques sont difficiles à esquiver à bout portant.