MADSEN LUMIÈRE MACHINE GUN


ARME: Mitrailleuse légère Madsen
MUNITIONS:   6.5x55 mm / 7.92x57 mm / 7.62x54 mm R
CADENCE DE TIR:    ~450 tours/min

DESCRIPTION:

Une mitrailleuse légère danoise, conçue en 1890 et mise en série en 1900. Il est considéré comme la première mitrailleuse légère à être produite à l'échelle industrielle. En raison de son poids relativement faible et du fait qu'il pourrait être porté par un seul soldat, il a marqué une étape importante dans le développement des armes automatiques.

Le Madsen utilise un système d'exploitation à court-recoil et dispose d'un mécanisme de boulon très inhabituel. Il est alimenté à partir d'un box magazine situé sur le dessus du récepteur. Selon la variante, il utilisait des magazines d'une capacité de 25, 30 ou 40 tours. La mitrailleuse a été fabriquée pour divers calibres de fusil et exportée dans de nombreux pays.

REMARQUES:

- Un des pionniers parmi les mitrailleuses légères, apparaissant même avant la Première Guerre mondiale.
- Il a servi dans les armées d'une trentaine de pays.
- Le magazine haut de gamme lui donne une silhouette très distinctive.
- La production s'est poursuivie jusqu'au début des années 1950, véritable vétéran parmi les armes automatiques.
