BIOMASSE DE L'EAU


CLASSE:      Biomasse des marais
MÉTABOLISME: Xénobiologique
PERCEPTION: Structure du storm biologique
TAILLE:       Variable
ENDURANCE:  Pratiquement invulnérable
HOSTILITÉ:  Passif
ARMES:    Tissus corrosifs, phéromones défensifs
RÉCOMPENSE:     150 FC
MENACE:     Moyenne

DESCRIPTION:

La biomasse est le tissu organique vivant à partir duquel le Swarm construit des Swarms, des tunnels et d'autres grandes structures. Il se développe progressivement, couvrant les murs, les planchers et les plafonds avec une couche dense de chair fibreuse, transformant l'environnement environnant en une extension du Swarm lui-même.

On croit que la biomasse transforme toute matière organique disponible pour se développer. Les plantes, les animaux et même les êtres intelligents peuvent devenir des matériaux de construction pour de nouvelles sections du Swarm, perdant à jamais leur forme originale.

Malgré leur incapacité à se déplacer indépendamment, la biomasse demeure dangereuse. Sa surface est recouverte de sécrétions caustiques qui causent des brûlures chimiques au contact. De plus, certaines variétés peuvent sécréter des phéromones spéciales qui, lorsqu'elles sont endommagées ou brûlées, attirent les membres du Swarm à proximité pour défendre la zone infestée.

Les armes classiques ne causent pratiquement aucun dommage à la biomasse. Ses tissus résistent aux munitions cinétiques, aux explosions et à la plupart des armes énergétiques. La méthode de destruction la plus efficace reste l'exposition prolongée à des températures élevées, qui brûle littéralement la structure organique.

L'apparition de la biomasse est considérée comme l'un des premiers signes de la formation d'un Swarm à part entière. Si l'infestation n'est pas arrêtée à temps, ses défenseurs suivront bientôt la chair immobile.

CONSEILS:

- Brûler la biomasse avec des lance-flammes ou d'autres armes incendiaires.
- Ne touchez pas à sa surface sauf si nécessaire.
- Préparez-vous à un swarm après avoir détruit de grands amas.
- Plus il y a de biomasse, plus il est probable qu'un noyau de Swarm soit situé à proximité.
