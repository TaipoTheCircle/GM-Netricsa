VODKA DE RENFORCEMENT


ARME:      La vodka de force
CADENCE DE TIR:         Une bouteille

DESCRIPTION:

En buvant, donne une force surnaturelle sans intoxication. Les muscles se serrent, sens aiguisent, et le corps devient une arme à part.

REMARQUES:

- Aucun effet alcool.
- Enrichissement pur, parfait pour le combat.
- Durée limitée - disparaît après la bataille.