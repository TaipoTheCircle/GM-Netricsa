RIVEAU D'ACTION DE L'ARISAKA DE TYPE 38


ARME: Arisaka Type 38 Rifle d'action
MUNITIONS:   6,5x50mm SR Arisaka
CADENCE DE TIR:    ~10-15 tours/min

DESCRIPTION:

Un fusil à action de boulon japonais, développé en 1905 sur la base du modèle précédent de type 30 sous la supervision du général Nariake Arisaka. Il a été adopté par l'armée impériale japonaise la même année. Conçu pour les unités d'infanterie, il devient progressivement le fusil de service principal de l'armée japonaise. Par rapport à son prédécesseur, il présentait un boulon amélioré, une fiabilité accrue et un couvercle de poussière pour le récepteur afin de protéger contre la saleté et les débris.

Le fusil utilise un mécanisme d'action à boulons actionné manuellement. Il installe la cartouche 6.5x50mm SR Arisaka et dispose d'un chargeur interne de 5 ronds, qui est chargé à l'aide de clips stripper. Il est équipé d'un matériel en bois, de vues en fer ouvert et d'un support baïonnette. Grâce à son long baril et à son recul relativement doux, il offre une bonne précision et est confortable à tirer.

REMARQUES:

- Bien adapté pour engager des cibles individuelles à moyenne à longue portée.
- Efficace contre le personnel non armé.
- Présente un recul modéré et une bonne précision.
- Non destiné à être utilisé contre les véhicules blindés ou les fortifications lourdes.
- Service de scie pendant la Première Guerre mondiale et la Seconde Guerre mondiale.
- Il y avait une version abrégée, la Carbine de Type 38.
- Le fusil de sniper de type 97 a été développé à partir de celui-ci.
