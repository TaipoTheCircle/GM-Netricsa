FUSIL À DOUBLE CANON VULCAN 1270


ARME : Fusil à double canon Vulcan 1270
MUNITIONS : Calibre 12
ROF : ~40 tours/min

DESCRIPTIF :

Il s'agit essentiellement d'une version améliorée du fusil de chasse standard, tirant deux obus simultanément à partir des deux canons. Il utilise deux obus de calibre 12 et est conçu pour les engagements à courte portée.

Les doubles canons permettent de tirer deux coups rapides en succession rapide, après quoi l'arme doit être rechargée.

La puissance élevée de chaque tir rend le fusil de chasse particulièrement dangereux à courte portée. Son principal inconvénient est sa petite capacité et la nécessité de recharger après le tir.

REMARQUES :

- Deux barils, deux obus et aucune communication.
- Très haute puissance à courte portée.
- Deux tirs rapides vous permettent d'envoyer rapidement plusieurs cibles.
- Après le tir, vous devrez vous arrêter et recharger votre arme.
