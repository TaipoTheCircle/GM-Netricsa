DESCRIPTION:

C'est l'une des créatures les plus mystérieuses des univers connus. Personne ne sait d'où ils viennent, qui les a créés, ou pourquoi ils sont ici. Ils apparaissent comme des bâtonnets pixelisés de différentes couleurs: rouge, bleu, vert, jaune, etc. Ils sont plats, comme dessinés sur un morceau de papier, mais ils se déplacent dans l'espace tridimensionnel, en maintenant leur forme 2D.

Les premières apparitions documentées ont été enregistrées dans des environnements d'essai, des simulations abandonnées et des espaces numériques étranges qui défient la classification. D'où le nom "environnements d'essai". Le créateur, s'il existe, n'a laissé aucune trace.

En voyant n'importe quelle créature vivante, elle commence à se diriger vers la cible. Il ne court pas, ne se faufile pas, ou attaque-il marche simplement à une vitesse constante, prenant le chemin le plus court. Si un obstacle se dresse sur son chemin, il le contournera. Si une porte est verrouillée, elle se tiendra devant elle jusqu'à ce qu'elle soit ouverte.

Lorsque le Nextbot approche d'un objet d'intérêt, il s'arrête et commence à sauter. Elle saute joyeusement, avec enthousiasme. Il peut sauter indéfiniment, ne montrant aucun signe de fatigue ou d'agression.

À la mort, il disparaît tout simplement. Il ne laisse aucune trace.

La théorie la plus improbable est qu'ils essaient d'établir un contact mais ne savent pas comment, donc ils sautent tout simplement.

CONSEILS:

- Ces Nextbots sont inoffensifs. Ne gaspillez pas les munitions.
