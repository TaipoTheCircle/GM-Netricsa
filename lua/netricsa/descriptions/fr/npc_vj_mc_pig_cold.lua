LE PIG POLD DU MINECRAFT


CLASSE:      Porc froid
MÉTABOLISME: Chaleureux, résistant au froid
PERCEPTION: Animaux sauvages / domestiques
TAILLE:       3 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Faible
ARMES:    Aucune
RÉCOMPENSE:     30 FC
MENACE:     Faible

DESCRIPTION:

C'est une variation rare du porc commun, adapté à la vie dans les biomes froids. Contrairement à leurs homologues roses et tempérés, ces porcs ont développé une épaisse fourrure blanche ou gris clair qui les protège du froid.

Ils errent paisiblement dans le Cold en groupes de 2-4, grognent, creusent dans le Colddrivefts à la recherche de nourriture comestible, et sont complètement non agressifs. Comme c'est le cas chez les porcs, ils n'attaquent pas même lorsqu'ils sont blessés, préférant simplement fuir et devenir parents des injustices du monde.

Parce qu'ils vivent dans des régions froides, les porcs froids sont un peu plus résistants au froid que leurs parents logiques - ils ne prennent pas de dommages de Cold et peuvent marcher en toute sécurité sur les biomes glacés sans risquer de geler.

Elles peuvent être élevées, selles et utilisées comme source de porc et de cuir.

CONSEILS:

- Utilisez des carottes sur un bâton pour diriger un cochon froid sur une selle - c'est plus pratique dans le froid que de courir.
- Racontez-les avec des carottes, de la laitue ou des bougies pour une source alimentaire constante dans les biomes froids.
