EVOLUTION DE LA SURVEILLANCE MINECRAFT


CLASSE:      Évoker
MÉTABOLISME: Illager magiquement doué
PERCEPTION: Sorcier Élite / Evoker
TAILLE:       6,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrême
ARMES:    Magical "Fangs", Vex Invocation, Blue Sheep Red Transformation
RÉCOMPENSE:     600 FC
MENACE:     Extrême

DESCRIPTION:

C'est ce qui arrive quand un villageois abandonne le commerce, prend une robe sombre et se retire dans la forêt pour étudier la magie. C'est l'une des variétés Illager les plus dangereuses et agaçantes, capable de transformer une bataille en un enfer vivant si elle n'est pas tuée instantanément. Si le Vindicateur est la force brute, alors l'Evoker est l'intellect, la magie et le chaos pur.

Les évokers habitent dans des mansions boisées mystérieuses, qui se cachent au fond de ces structures sombres. Cependant, vous pouvez aussi les rencontrer dans les étapes ultérieures de Village Raids.

Malgré leur fragilité, leurs mains cachent un pouvoir mortel.

L'Evoker est un maître du contrôle du territoire. Ils gardent toujours leur distance, essayant de garder les ennemis à distance. Leur arsenal comprend trois sorts primaires, chacun capable de vous envoyer rapidement:

Vex Invocation (Purple Aura): Quand l'Evoker lève les mains et qu'ils brillent pourpre, ils invoquent 2 à 3 Vex volant. L'Evoker peut les reprendre si moins de 4 restent.

"Fangs" (Aura jaune): Si l'Evoker lève les mains et qu'elles brillent en jaune, une rangée de "Fangs" épique émerge du sol dans la direction ciblée ou autour de lui, percutant et infligeant des dégâts massifs. Cette attaque est rapide et douloureuse.

Transformation des moutons (« Volo-lo ») : La plus drôle, mais la plus inutile capacité. S'il y a un mouton bleu à proximité, l'Evoker peut perdre du temps à crier "Volo-lo!" pour le transformer en un mouton rouge.

CONSEILS:

- Tuez-le d'abord. Dans toute lutte contre les malades, l'Evoker devrait être la cible prioritaire numéro un. S'il reste vivant, il va spammer Vex sur tout le champ de bataille.
- Fermez la distance. Il est impuissant au combat. Dès que vous l'aurez vu, il arrêtera d'appeler Vex et d'essayer de se retirer. Ne le laisse pas faire ça.
- Attaque pendant le sort. Pendant que ses mains brillent et qu'il prépare son sort, il est sans défense. C'est le meilleur moment pour attaquer.
- Dodge les Fangs. Leurs attaques sont visibles à travers les particules du sol. Dès que vous voyez les particules jaunes, sautez immédiatement. Une ligne droite de Fangs est très dangereuse.
- Ignorez le Vex au début. Le Vex est en mauvaise santé et disparaît après un moment. Si vous commencez à vous concentrer sur eux, l'Evoker aura le temps d'appeler plus. Tuez-le d'abord, puis traitez avec le reste de son armée.
- Si vous tuez l'Evoker, il abandonnera l'expansion totem. Cet artefact peut vous sauver la vie au dernier moment.
