GASSER M1870 ARMY REVOLVER


ARME: Gasser M1870 Revolver de l'Armée de terre
MUNITIONS:   11,3x36mm R Gasser
CADENCE DE TIR:    Une seule action, capacité de 6 tours

DESCRIPTION:

Un revolver de l'armée austro-hongroise, conçu par l'armateur Leopold Gasser en 1870. Il était destiné principalement à être utilisé par la cavalerie et d'autres unités de l'Armée austro-hongroise. Il dispose d'une conception massive et ouverte, d'un long canon et d'une grande poignée en bois. Grâce à sa puissante cartouche, il possédait une puissance d'arrêt importante; cependant, sa taille et son poids substantiels en faisaient un bras latéral assez lourd.

Il fonctionne sur un mécanisme à action unique, exigeant que le marteau soit coiffé manuellement avant chaque tir. Il est alimenté à partir d'un cylindre à six ronds en chambre pour la cartouche R 11,3x36mm. Le chargement se fait par l'intermédiaire d'une barrière articulée située du côté droit du cadre, tandis que les douilles épuisées sont éjectées une par une à l'aide d'une tige d'extraction située sous le barillet. Le système d'observation de type ouvert consiste en une vue avant et une vue arrière.

REMARQUES:

- Conçu par Leopold Gasser en 1870.
- Servi avec la cavalerie austro-hongroise.
- Le cylindre contient 6 cartouches.
- Il pèse environ 1,3 kg et a une longueur hors tout de 375 mm.
- Des variantes avec des barils plus courts existaient également.
- La conception a servi de base à des modèles ultérieurs, dont le Gasser-Kropatschek M1876.
- Dans les Balkans, les revolvers du système Gasser se sont répandus, en particulier au Monténégro.
