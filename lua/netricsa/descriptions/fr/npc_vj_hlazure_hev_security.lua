BLACK MESA H.E.V. GUARD DE SÉCURITÉ



CLASSE:      Garde de sécurité noire Mesa H.E.V
MÉTABOLISME: Humain, Homme
PERCEPTION: Guerrier de sécurité de Mesa noir
TAILLE:       6 pieds
ENDURANCE:  Moyenne (protection contre les combinaisons H.E.V.)
HOSTILITÉ:  Variable (défensif, hostile lorsqu'il est menacé)
ARMES:    Serrez 17 bras.
RÉCOMPENSE:     250 FC
MENACE:     Faible à modéré

DESCRIPTION:

Bleu S.E.V. Les agents de sécurité sont des gardes Black Mesa équipés de costumes d'environnement dangereux. Leur équipement offre une durabilité supérieure à celle du personnel de sécurité standard, ce qui leur permet de survivre plus longtemps dans les zones hostiles et de résister à de légers tirs extraterrestres ou militaires.

Bien qu'ils soient moins entraînés que les forces militaires, ils sont des défenseurs fidèles de Black Mesa et se dressent souvent contre des créatures Xen, S.E.C.U., ou des agents hostiles. Leur armure HEV bleue distincte les rend reconnaissables sur le terrain.

CONSEILS:

- Ne comptez pas sur lui comme un tank - il est courageux, mais humain.
- Écoutez attentivement leurs cris - ils pourraient indiquer un danger à proximité.
