CYBORG ARACHNOID, ADULTE DU SCORPIUS


CLASSE:      Cyborg Arachnoid, adulte
MÉTABOLISME: Arthropode octotherme, amélioré cybernétiquement
PERCEPTION: Course sensible primitive
TAILLE:       20-25 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Charnière, piqûre de queue
RÉCOMPENSE:     8500 FC
MENACE:     Haut

DESCRIPTION:

Un guerrier sacré issu d'une race primitive a évolué à partir d'arthropodes. Très hostile en raison de leurs convictions religieuses.

Il porte un fusil à chaîne avec une seule main. Exoskeleton couvre tout le corps d'Arachnoid et offre une bonne protection contre les balles, les explosifs et le feu.

Les adultes sont des guerriers adultes, ayant un exosquelette rouge « mûr » et une taille beaucoup plus grande.

Un adulte cyborg arachnoid - un Scorpius Holy Warrior, volontairement (ou non) amélioré par la technologie de Mental.

Une partie du corps a été remplacée par des segments mécaniques, comme des membres renforcés, des servomoteurs, des stabilisateurs de recul et un exosquelette. Cette armure peut supporter plus de dommages qu'un exosquelette arachnoïde standard.

CONSEILS:

- Merde dangereuse - ne pas approcher trop près.
- Ils s'enfuient.
- C'est une mauvaise idée.
