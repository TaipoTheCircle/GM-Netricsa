RAPPORTEUR SPITTER DU PLANET TERRAFORMÉ


CLASSE:      Raptor d'araignée
MÉTABOLISME: Prédateur, Théropod
PERCEPTION: Utahraptor génétiquement modifié
TAILLE:       ~8,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrêmement élevé
ARMES:    Griffes, dents, cramoisi, cramoisi
RÉCOMPENSE:     600 FC
MENACE:     Haut

DESCRIPTION:

Cette espèce a émergé lorsque la société Mendel-Gruman a décidé que les Utahraptors normaux sur la planète n'étaient pas assez et tourné vers le génie génétique. La société voulait créer une arme plus efficace de destruction massive en produisant des rapaces qui pourraient cracher le venin tout en conservant toutes les habitudes des prédateurs sauvages.

Le rapace Spitter se distingue de ses frères par sa coloration grise, son manque complet de plumes, et une rangée de courtes pointes qui s'étend le long de son dos. En raison de ces pics et du sac sous sa gorge, il a été initialement appelé par erreur un bébé spinosaurus.

Ils ont un sac jaune et cuir sous leur cou qui stocke la toxine. Quand le sac est plein, il gonfle visiblement, avertissant un tireur attentif que le plaisir est sur le point de commencer.

CONSEILS:

- Ne bougez pas. La crache vole en ligne droite.
- Au combat, c'est aussi dangereux qu'un raptor normal. Ne vous encerclez pas.
