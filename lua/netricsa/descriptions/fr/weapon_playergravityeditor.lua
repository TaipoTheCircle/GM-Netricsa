MANIPULATEUR DE GRAVITÉ COMBINE


ARME: Mélanger le manipulateur de gravité
MUNITIONS:   Aucun
CADENCE DE TIR:    Modification de la direction gravitationnelle

DESCRIPTION:

Un appareil spécialisé Combiner, basé sur la matraque stun de tissu standard utilisée par Overwatch et Civil Protection. Contrairement à l'original, qui est conçu pour soumettre et neutraliser les délinquants, cette version modifiée permet au wielder de modifier la direction de la gravité agissant sur eux. Le dispositif est destiné à traverser des surfaces et des plafonds verticaux, permettant l'accès à des zones autrement inaccessibles par les unités d'infanterie standard.

Pour l'activer, l'utilisateur doit balancer le manipulateur vers une surface choisie. Au contact, la direction des déplacements gravitationnels de l'utilisateur leur permet de se déplacer le long des murs et des plafonds. Le dispositif n'a pas besoin d'être maintenu constamment une fois activé, laissant les mains du wielder libre d'utiliser des armes à feu ou d'autres équipements. Cependant, une mauvaise utilisation peut entraîner une perte de contrôle sur son mouvement, envoyant éventuellement un utilisateur peu averti qui vole dans la stratosphère.

REMARQUES:

- D'après la norme Combiner le bâton.
- Permet de se déplacer le long des murs et des plafonds.
- Ne nécessite pas de manipulation continue pour maintenir l'état gravitationnel altéré.
- Particulièrement utile pour contourner les obstacles et lancer des attaques sous des angles inattendus.
- La mauvaise utilisation peut entraîner un vol involontaire exceptionnellement long.
