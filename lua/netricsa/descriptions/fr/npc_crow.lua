CROISSANCE


CLASSE:      Crow
MÉTABOLISME: Oiseaux
PERCEPTION: Oiseaux sauvages
TAILLE:       ~1,5 ft
ENDURANCE:  Faible
HOSTILITÉ:  Faible (défendeur si menacé)
ARMES:    Bec, griffes
RÉCOMPENSE:     1 FC
MENACE:     Très faible

DESCRIPTION:

Les crows sont des oiseaux intelligents et méfiants que l'on trouve souvent dans les zones urbaines et rurales. Ils se rassemblent dans des troupeaux et peuvent semer des menaces potentielles, en utilisant des appels coordonnés pour alerter les autres. Bien qu'ils ne soient pas agressifs par défaut, leur présence peut signaler un danger ou un changement environnemental.

CONSEILS:

- Les verrous peuvent indiquer des ennemis ou des dangers à proximité.
