ALUDRAN REPTILOID, HAUT-LANDER


CLASSE:      Aludran Reptiloid, Highlander
MÉTABOLISME: sang-froid, comme un reptile
PERCEPTION: race primitive
TAILLE:       45 pieds
ENDURANCE:  élevé
HOSTILITÉ:  élevé
ARMES:    missiles magiques
RÉCOMPENSE:     25000 FC
MENACE:     élevé

DESCRIPTION:

Un grand reptile à quatre mains vivant à Aludran dans la constellation de Canis Major. Cette race primitive a accepté de se battre pour le Mental en échange des pouvoirs qu'elle leur a conférés.
Ils ont lancé des boules de feu autopropulsées avec des capacités primitives.
La race Highlander est significativement plus grande et plus dangereuse que celle des gens ordinaires vivant dans les plaines. Quand ils sont furieux, ils lancent leurs missiles en succession très rapide.

CONSEILS:

- Gardez-les sous un feu constant et essayez d'abattre leurs missiles dans l'air.
- Évitez leurs missiles indestructibles, et ne vous approchez pas trop d'eux.