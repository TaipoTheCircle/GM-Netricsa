UNCLE PLUS FAVORIS DU FAVERSHOLM


CLASSE:      Plus vite oncle
MÉTABOLISME: Marteaux de nuit
PERCEPTION: Tueur d'ambush
TAILLE:       5,6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Absolu
ARMES:    Lames prothétiques pour bras et jambes
RÉCOMPENSE:     260 FC
MENACE:     Haut

DESCRIPTION:

C'est l'un des monstres les plus frappants et effrayants, rencontré pour la première fois dans un immeuble résidentiel.

C'est un homme défiguré avec des pointes plus propres et plus lisses. Sa tête est obscurcie par des barres s'étendant de ses épaules, formant une cage protectrice-un coup de tête est impossible. Il manque d'armes et de jambes conventionnelles : au lieu de cela, il a des pointes métalliques longues et pointues. Il utilise ces lames pour frapper et poignarder ses victimes. Parce que les jambes ont des appendices similaires, un son de claquage métallique distinctif est entendu en marchant.

Le Quick One préfère opérer à partir d'embuscade. Il se cache dans les coins sombres ou derrière les obstacles, seulement pour sauter soudainement, casser la porte, et attaquer. En attaquant, il crie fort, en essayant d'intimider. Il court assez lentement, mais la soudaineté et les cris confondent l'ennemi.

Quand il est tué, le Quick One ne tombe pas. Il empale son cou avec des lames, émet un cri douloureux et triste, et tombe à terre.

Comme la plupart des monstres, le Quick One symbolise les blessures. Les pointes métalliques à la place des membres représentent un fauteuil roulant métallique. La tête en cage reflète un esprit "fermé" dans la folie et les problèmes émotionnels.

Il représente des gens de l'environnement qui ont été une source d'irritation et de douleur. L'acte de suicide du monstre à la mort est un parallèle direct aux tendances suicidaires.

CONSEILS:

- Soyez prudent dans de longs couloirs avec de nombreuses portes et coins sombres. Le Quick One aime sauter soudainement.
- Le monstre court assez lentement, mais les cris et la soudaineté rendent la panique facile. Ne paniquez pas.
- Frapper le Quick One est difficile en raison de sa vitesse. La meilleure tactique est d'attendre qu'il essaie de frapper, puis de reculer et de commencer à tirer avec un objectif prudent.
- Vous pouvez essayer le combat main dans la main: courir, frapper, et fuir. Mais c'est risqué.
- Si vous entendez un claquage métallique et un cri perçant, c'est à proximité. Préparez votre arme et regardez autour de vous.
