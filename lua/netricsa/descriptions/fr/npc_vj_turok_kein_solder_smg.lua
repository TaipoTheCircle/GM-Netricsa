SOLDAT GRUMAN MENDEL-GRUMAN


CLASSE : Soldat Grunt Mendel-Gruman
MÉTABOLISME : humain, masculin
PERCEPTION : Grunt standard
TAILLE : 5,9 pieds
ENDURANCE : Moyenne
HOSTILITÉ : Élevée
ARMES : Carabine d'assaut légère ORO FP9, grenades à fragmentation
RÉCOMPENSE : 200 FC
MENACE : Faible

DESCRIPTIF :

Ce Grunt est un représentant standard des forces armées de la société et constitue l'épine dorsale de ses unités Grunt. Extérieurement, il est pratiquement impossible à distinguer des autres variantes de Mendel-Gruman Grunt : la même armure de protection légère, le même équipement tactique et le même casque fermé avec une visière dynamique.

Son arme principale est la carabine d'assaut légère ORO FP9. Cette arme polyvalente permet au soldat de tirer efficacement à courte et moyenne portée sans l'obliger à se rapprocher constamment de l'ennemi. Contrairement à un soldat brandissant un fusil de chasse, le FP9 Grunt préfère maintenir une certaine distance et supprimer progressivement sa cible avec un tir soutenu.

Le soldat est également équipé de grenades à fragmentation, qu'il utilise contre les ennemis à couvert ou contre les groupes ennemis. Grâce à la combinaison de sa carabine et de ses grenades, il est capable d'effectuer la plupart des tâches standard des Grunts sans avoir besoin d'armes spécialisées.

Comme les autres soldats Mendel-Gruman standards, ce soldat ne se distingue pas par une durabilité individuelle exceptionnelle. Sa force réside principalement dans le nombre, la discipline et la coordination avec les autres unités. Généralement, plusieurs Grunts prennent position autour de la zone de combat, croisant les tirs et forçant progressivement l'ennemi à se mettre à couvert.

La visière dynamique sert d'indicateur supplémentaire de l'état du soldat : ​​le bleu indique une vigilance normale, le jaune indique une conscience accrue et le rouge indique une préparation au combat maximale.

Au combat, le FP9 Grunt est la version la plus polyvalente du soldat standard. Il n'a pas la puissance destructrice d'un fusil de chasse et ne peut pas supporter la même quantité de dégâts qu'une unité lourde, mais il n'a pratiquement aucune limitation en termes de portée.

CONSEILS :

- Ne les sous-estimez pas à cause de leurs armes conventionnelles. Plusieurs Grunt FP9 peuvent établir un barrage dense et soutenu.
- Utilisez une couverture, surtout si vous faites face à un grand groupe.
- Les grenades sont efficaces contre les groupes, car les Grunts opèrent souvent en petites escouades.
- À bout portant, essayez de ne pas les laisser vous entourer.
- Si des fusils de chasse ou des unités lourdes sont à proximité, envisagez d'abord les options les plus dangereuses, mais faites attention au Grunt FP9, qui continuera à tirer derrière eux.
- Une visière rouge signifie une préparation totale au combat. À ce stade, le soldat n’est plus disposé à prétendre que ce qui se passe ne le concerne pas.