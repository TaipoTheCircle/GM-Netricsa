MENDEL-GRUMAN GRUNT SOLDIER


CLASSE:      Mendel-Gruman Grunt Soldat
MÉTABOLISME: Humain, Homme
PERCEPTION: Grunt Standard
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    ORO FP9 Carbine légère, Frag Grenades
RÉCOMPENSE:     200 FC
MENACE:     Faible

DESCRIPTION:

Ce Grunt est un représentant standard des forces armées de la société et constitue l'épine dorsale de ses unités Grunt. De l'extérieur, il est pratiquement indissociable des autres variantes Mendel-Gruman Grunt : la même armure de protection légère, l'équipement tactique et le casque fermé avec une visière dynamique.

Son arme principale est le ORO FP9 Light Assault Carbine. Cette arme polyvalente permet au soldat de tirer efficacement à courte et moyenne portée sans le forcer à se refermer constamment sur l'ennemi. Contrairement à un soldat armé de fusils, le FP9 Grunt préfère maintenir une certaine distance et supprimer progressivement sa cible avec un feu soutenu.

Le soldat est également équipé de grenades à fragmentation, qu'il utilise contre des ennemis derrière la couverture ou contre des groupes ennemis. Grâce à la combinaison de sa carbine et de ses grenades, il est capable d'effectuer la plupart des tâches Grunt standard sans avoir besoin d'armes spécialisées.

Comme d'autres soldats standard Mendel-Gruman, ce soldat ne se distingue pas par sa durabilité individuelle exceptionnelle. Sa force réside principalement dans le nombre, la discipline et la coordination avec d'autres unités. En général, plusieurs Grunt prennent position autour de la zone de combat, croisent le feu et forcent progressivement l'ennemi hors de sa couverture.

La visière dynamique sert d'indicateur supplémentaire de l'état du soldat : le bleu indique une vigilance normale, le jaune indique une sensibilisation accrue et le rouge indique une disponibilité maximale au combat.

Au combat, le FP9 Grunt est la version la plus polyvalente du soldat standard. Il manque le pouvoir destructeur d'un fusil de chasse et ne peut pas supporter la même quantité de dommages qu'une unité lourde, mais il n'a pratiquement aucune limite en termes de portée.

CONSEILS:

- Ne les sous-estimez pas à cause de leurs armes conventionnelles. Plusieurs PC9 Grunt peut poser un barrage dense et soutenu.
- Utilisez une couverture, surtout si vous faites face à un grand groupe.
- Les grenades sont efficaces contre les groupes, car Grunt opère souvent en petites équipes.
- Essayez de ne pas les laisser vous entourer.
- Si les tireurs de chasse ou les unités lourdes sont à proximité, considérez d'abord les options les plus dangereuses, mais soyez attentifs au FP9 Grunt, qui continuera à tirer de derrière eux.
- Une visière rouge, c'est la pleine disponibilité au combat. À ce stade, le soldat n'est plus prêt à prétendre que ce qui se passe ne le concerne pas.
