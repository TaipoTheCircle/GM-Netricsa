DELTA BASE ZOMBIE HEADCRAB TECHNIQUE, COMMUN


CLASSE:      Delta Base Zombie Technicien en cambriolage, commun
MÉTABOLISME: Hôte humain + tête parasite de Xen
PERCEPTION: Entité zombifiée, ancien spécialiste technique
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Griffes, morsure, prise
RÉCOMPENSE:     200 FC
MENACE:     Haut

DESCRIPTION:

C'est techniquement le même que le headcrab zombie commun de la base Delta, juste dans un uniforme différent. Mais les survivants affirment qu'il y a des différences, et ils ne sont pas seulement en apparence.

Si les zombies réguliers à la base sont d'anciens scientifiques en manteau gris, alors les techniciens sont ceux qui ont utilisé pour fixer des générateurs, grimper à travers les systèmes de ventilation, et savoir où chaque levier est.

La principale différence entre un technicien et un scientifique n'est pas la force ou la vitesse, mais le comportement. Certains survivants jurent qu'ils en ont vu un qui réparait un climatiseur cassé. (Il s'est simplement cogné la tête contre le mur jusqu'à ce qu'il tombe.)

Un coup de tête détache la tête du technicien.

CONSEILS:

- Un zombie technicien n'est pas plus fort ou plus rapide qu'un zombie commun. Ils ont juste des vêtements différents.
- La tête se détache pour tuer comme un scientifique.
- Gardez vos distances, tirez, et ne les laissez pas vous entourer.
