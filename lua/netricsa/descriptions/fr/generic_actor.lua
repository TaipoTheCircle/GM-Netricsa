DESCRIPTION:

Acteurs génériques sont des entités xénobiologiques mystérieuses qui se cachent sous des visages familiers. Personne ne sait d'où ils viennent - certains spéculent qu'ils sont originaires de Xen, d'autres disent qu'ils sont un sous-produit de la cascade de résonance - mais une chose est certaine: ils peuvent parfaitement imiter n'importe quel être.

Ils apparaissent comme des scientifiques, des gardes de sécurité, ou même des monstres, se mélangeant parfaitement aux populations de Mesa noire ou de Xen. Bien que leur apparence extérieure puisse sembler inoffensive, ils sont imprévisibles et dangereux, utilisant souvent toutes les capacités que leur forme actuelle fournit.

Leur forme réelle est inconnue; certains chercheurs suggèrent qu'il pourrait s'agir d'une masse inébranlable de tissu psionique vivant, capable de scanner et de reproduire des modèles biologiques et comportementaux. Rencontrer quelqu'un c'est comme serrer la main avec un étranger qui pourrait mordre.

CONSEILS:

- Ne faites pas confiance aux apparences - n'importe quel visage familier pourrait être un acteur générique.
- Observer attentivement le comportement; les incohérences peuvent révéler le déguisement.
- Soyez prêt pour des attaques soudaines de sources inattendues.