MAISON DE BRICK, SYNDROME DE BRICK


Sam, le projet de construction du siècle est presque terminé. Celui qui a conçu ce complexe a été clairement inspiré par l'architecture des rêves - où tout est là, mais il n'y a pas de portes, et la brique rouge coexiste paisiblement avec le blanc, comme si elle était censée être.

Retrouvez la version finale de la légendaire Maison Brick.

Le paysage continue à évoluer. Il y a tout un village ici :

Étang. A droite de la maison, sur l'herbe plate, un étang éclabousse maintenant. Pas une piscine, pas une flaque, mais un étang complet. Il y a de l'eau, pas de poisson, mais qui sait ce qui la peuplera.

Un bâtiment en brique blanche de deux étages. Derrière la maison, à gauche, un colosse de deux étages s'est levé. Brique blanche, planchers en bois, et... pas d'escalier au deuxième étage. Juste les murs, le plancher et le plafond, et entre les planchers, le vide et les rêves.

First floor: 8 fenêtres. Beaucoup de lumière, beaucoup de verre, beaucoup de points d'entrée potentiels pour les snipers. Un mur, pour une raison quelconque, est rouge. Apparemment, ils ont décidé de ne pas jeter le vieux stock de briques.

Second floor: 6 fenêtres. Pas d'escalier.

Inside: le vide. Le vide absolu. Pas de table, pas de chaise, pas même une boîte de conserve. Juste des murs, du sol et des fenêtres. Et le mur rouge au premier étage vous regarde avec une question silencieuse: "Pourquoi suis-je ici?"

The first brick house: les mêmes pistolets cloués, les boîtes verrouillées, les fournitures de Sofia, et l'horloge sur le mur. Pas de porte, ils n'attendaient pas.

Garage: le moteur et la clé attendent toujours leur moment sur la table en bois.

Swimming pool: plein d'eau, prêt pour les harceleurs fatigués.

Four broken cars: garé, rouillé.

Eleven trees: debout autour du périmètre, un toujours dans son nouvel emplacement.

Tu es prêt.
