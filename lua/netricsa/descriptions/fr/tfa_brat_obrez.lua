MR-43-SO "Brat-2" BLANK-FIRING SAWED-OFF SHOTGUN


ARME: MR-43-SO « Brat-2 » Fusil de tir à blanc scié
MUNITIONS:   7.62x54R Cartouches blanches (bruit / flash)
CADENCE DE TIR:    Deux cartouches, rechargement manuel

DESCRIPTION:

Une arme à feu à feu blanche à double barre fabriquée par "Kurs-S" LLC, basée sur le fusil IZh-43 Smoothbore. Il s'agit d'une version abrégée d'un fusil de chasse classique à double barre, avec des meubles en bois distinctifs. Le modèle a acquis une renommée en raison de sa ressemblance avec le fusil à sciage utilisé par le personnage Danila Bagrov dans le film "Brother 2" ("Brat 2").

L'arme comporte deux barils, deux déclencheurs et un mécanisme de rechargement par rupture. Il utilise des cartouches vierges 7,62x54R, qui produisent un rapport fort accompagné de fumée et d'un flash de muselière. Il a une capacité de deux cartouches. Pour empêcher l'utilisation de munitions réelles, les barils sont équipés d'obstructions internes (baffles).

REMARQUES:

- Deux barils et deux déclencheurs.
- Le rechargement est effectué en brisant les barils.
- Une sécurité automatique s'engage pendant le processus de rechargement.
