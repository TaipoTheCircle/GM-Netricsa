SAIGA-12 SÉMI AUTOMATIQUE


ARME: Fusil semi-automatique Saiga-12
MUNITIONS:   12/70 mm
CADENCE DE TIR:    ~468 tours/min (S12)

DESCRIPTION:

Un fusil de chasse semi-automatique russe, développé sur la base de la conception Kalachnikov fusil d'assaut et fabriqué par l'usine de construction de machines Izhevsk depuis 1997. Il hérite de la disposition caractéristique de la famille AK, y compris une action à gaz et un boulon rotatif, adapté pour les cartouches de chasse de calibre 12.

Il utilise des magazines de boîtes amovibles de différentes capacités. Selon le modèle spécifique, il peut être équipé d'un stock fixe ou pliant, ainsi que de différents types de systèmes d'observation. Les versions compactes ont gagné en popularité en raison de leur combinaison de haute puissance et de dimensions relativement petites.

REMARQUES:

- Selon la conception du fusil d'assaut Kalachnikov.
- Chambre pour cartouches 12/70 mm et 12/76 mm "Magnum".
- Disponible avec des magazines 2-, 4-, 5- et 8-round, ainsi que des options de plus grande capacité.
- Certaines variantes sont à l'extérieur presque indissociables d'un fusil d'assaut Kalachnikov – jusqu'à ce que vous regardiez dans le canon.
- Mode semi-automatique.
- Un magazine standard de 10 tours; un magazine étendu de 14 tours est également disponible.
- Le taux de feu est d'environ 468 balles par minute.
- Aussi connu sous le nom de "S12", alors qu'une autre variante est désignée comme "Kamchatka-12".
