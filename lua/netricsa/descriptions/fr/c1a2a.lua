MESA BLACK, VOIE D'ADMINISTRATION


Sam, le bureau est devenu un champ de bataille interdimensionnel. D'un côté, les escouades des soldats de Mental s'emparent des cabines, en faisant sauter la cloison sèche et la paperasse. D'autre part, des créatures Xen, des chevreuils, des vortigaunts et des cauchemars variés, se déversent à travers de nouvelles failles, déchirant tout ce qui bouge.

Ce qui était autrefois une aile administrative ordonnée ressemble maintenant à une guerre.

Ce n'est plus seulement votre combat, c'est une lutte à trois sens entre l'humanité, les forces de Mental, et l'avant-garde de Nihilanth. L'envers ? Ils sont trop occupés à se tuer pour vous remarquer immédiatement. L'inconvénient ? Tu es toujours coincé au milieu d'une zone de guerre de bureau.

Recommendation: laisser les deux factions s'adoucir, puis se déplacer rapidement dans le chaos avant qu'ils se souviennent du vrai problème est-vous.