SKELETON HORSE DE L'EXTERIEUR MINECRAFT


CLASSE:      Cheval du squelette
MÉTABOLISME: Cheval non mort
PERCEPTION: Véhicule / Mob passif
TAILLE:       5,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Neutre
ARMES:    Aucune
RÉCOMPENSE:     300 FC
MENACE:     Faible

DESCRIPTION:

Une des deux variétés de chevaux non morts, avec des chevaux zombies. Contrairement à leurs homologues vivants, ces anguilles squelettiques ne paissent pas dans les prairies, mais sont plutôt créées par des éclairs lors d'orages.

Leur apparence s'explique par une condition spéciale appelée « piège à skeleton ». Lorsqu'un cheval normal est frappé par la foudre lors d'un orage, il se transforme en cheval squelette avec une étiquette spéciale appelée « SkeletonTrap ». Un cheval squelettique est un squelette de cheval entièrement formé flottant au-dessus du sol. Il fait les sons caractéristiques d'un cheval normal, mais à un pas inférieur avec un effet d'écho.

CONSEILS:

- Ne vous approchez pas trop d'un cheval solitaire pendant un orage à moins d'être prêt à combattre quatre archers squelettiques.
- La meilleure stratégie pour obtenir une telle montagne est de tuer les coureurs mais laisser les chevaux indemnes. Une fois les ennemis partis, les chevaux deviendront passifs et pourront être domptés.
- Un cheval squelettique est un support d'eau idéal. Contrairement aux chevaux normaux, il ne déloge pas son cavalier lorsqu'il est submergé et ne se noie pas.
- C'est une excellente monture pour explorer les Enfers et les Fins, comme contrairement aux autres mafia, les Chevaux du squelette ne sont pas affectés par la lumière du soleil et ne brûleront pas dedans.
- Rappelez-vous qu'en tant que créature non morte, Chevaux du squelette prennent des dommages de la guérison des potions et sont restaurés par les potions endommager.
