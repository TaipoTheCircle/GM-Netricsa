BRICKS, CHAMBRE ENTIÈRE


Sam, nous avons fini dans un endroit qui peut difficilement être appelé un endroit.

C'est plutôt un problème dans la matrice, un paradoxe géométrique, ou juste une blague vraiment bizarre.

Imaginez une seule pièce en brique rouge. Sans toit, sans fenêtre, sans porte. Les murs s'élèvent, mais il n'y a pas de ciel au-dessus d'eux.

La chambre est entourée de vide. Pas l'obscurité, mais le vide. Pas de son, pas de sens.

Qu'y a-t-il ici 

Les murs de briques sont le seul objet de cet univers. Rouge, dur, réel. Vous pouvez les toucher, les frapper, même essayer de les briser. Mais pourquoi ? Il n'y a rien derrière.

Un plafond ouvert ou plutôt l'absence d'un. Les murs tombent, et au-delà se trouve l'obscurité infinie. Aucune source, aucune direction. C'est juste.

Le sol est en brique ordinaire. Tu peux rester là.

Le vide au-delà des murs - si vous parvenez à vous échapper (et vous pouvez, Sam), il n'y a rien là-bas. Rien du tout. Juste toi et un vide sans fin.

Et qu'y a-t-il en bas ?

Et voilà où ça devient intéressant.

Si vous sautez (et vous le ferez certainement, je vous connais), l'infini commence.

Tu tombes, tu tombes, tu tombes. Les murs de la pièce ont disparu depuis longtemps. Seule la lumière noire entoure. Une minute, une heure, rien ne change.

Juste tomber. Pour nulle part. Sans s'arrêter. Sans fond. Sans espoir de toucher une surface solide.

Il n'y a pas de couverture ici, aucun moyen de gagner un point de vue, aucun moyen de se cacher. Vous êtes dans la pièce ou dans une chute sans fin.

Si tu amènes des ennemis ici, la bataille sera courte. Soit quelqu'un tombe dans l'abîme, soit tout le monde reste dans la pièce et se tire dessus jusqu'à ce qu'il n'y ait plus de munitions. Et reste là et regarde les briques.

L'aspect psychologique est la véritable arme. Cet endroit vous rend fou plus vite que n'importe quel crâne. Silence, vide, infinité au-delà de la pièce. Après une demi-heure, vous commencerez à parler aux briques. Et après une heure, les briques vont commencer à parler en retour.

Ne saute pas. Sérieusement, Sam. Je sais que tu es curieux, je sais que tu veux vérifier s'il y a un fond. Mais il n'y en a pas. J'ai calculé la trajectoire, la vitesse de votre chute, les résultats possibles. Il n'y a pas de fond. Tu tomberas pour toujours. Et je vais devoir t'écouter crier : "Quand allons-nous y arriver ?" pour toujours.

On ne survivra pas tous les deux.

Allons... mais où sommes-nous censés aller ? Il n'y a qu'une chambre ici.

Bon, restons là et regardons les briques. Ils sont magnifiques, au fait. Rouge. Tout ce qu'on a dans ce monde...
