LEVITATOR, FLYING DU MAGNOR


CLASSE:      Levitateur, en vol
MÉTABOLISME: Véhicule habité
PERCEPTION: Véhicule de reconnaissance
TAILLE:       74,8 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Moyenne
ARMES:    Cannon plasma
RÉCOMPENSE:     150 FC
MENACE:     Moyenne

DESCRIPTION:

Ce sont des aéroglisseurs conçus pour patrouiller les bases avant de Mental et scruter devant l'armée principale. Leurs moteurs leur permettent de naviguer sur n'importe quel terrain sans problème et même de voler à basse altitude. Cependant, pour léviter, ils ont besoin d'un cadre léger, donc ils ont une armure très légère.

Il semble qu'il s'agisse d'une femme alien humanoïde à peau bleue, suspendue dans une sphère translucide contenant une sorte de liquide. Cet extraterrestre peut être inoffensif tout seul, mais elle est dans un transport équipé d'un canon à plasma, qui, comme tous les canons, va essayer de vous finir. La structure sphérique peut planer, lui permettant de se déplacer librement dans l'air.

Les capsules de Levitator ont été développées après l'acquisition de Mental le Magnor, car il avait besoin de quelque chose pour fouiller les marais et localiser le médaillon. Ne laissant rien au hasard, Mental a également conçu les capsules pour fonctionner sous l'eau. Cependant, en raison du coût élevé de Zombie Soldiers dans les usines de Toyodo en Enfer, Mental a dû dégrader la qualité du matériel utilisé pour fabriquer les capsules, les rendant à partir de verre bon marché et fragile.

Les Levitateurs tirent leurs canons plasma de faible puissance sur les ennemis. Ils servent principalement de distraction pour l'armée principale, donc ils devraient être assez faciles à détruire.

Une caractéristique distinctive est la capacité du Levitator à régénérer sa santé. Mais encore une fois, cela arrive lentement, donc plus vite vous le détruirez, plus il sera probablement incapable de se régénérer.

CONSEILS:

- Éviter leurs attaques en s'enfuyant.
- Ils ont une armure très légère; quelques balles ou tout explosif suffira pour résoudre ce problème.
- Un coup de fusil à bout portant suffit pour les envoyer.
- Certains peuvent voler, d'autres restent près du sol.
