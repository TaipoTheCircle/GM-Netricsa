SURVIVALISTE NORME


ARME: Standard Survivalist Crossbow
MUNITIONS:   Acrobaties
CADENCE DE TIR:    ~1 prise / seconde

DESCRIPTION:

Une arbalète de survie de base, conçue pour un combat économique et fiable. Bien qu'il ne soit pas particulièrement puissant, il compense cela avec la disponibilité de munitions et un design simple.

L'arme tire des boulons simples et nécessite peu d'efforts pour fonctionner, ce qui en fait un produit populaire parmi les survivants novices. Avec l'habileté d'empoisonnement, il peut être modifié pour infliger des dommages supplémentaires au poison, affaiblissant progressivement la cible.

REMARQUES:

- Les boulons sont facilement fabriqués à partir de ferrailles.
- Peut causer des dommages au poison supplémentaires avec la compétence appropriée.
- Efficace à proximité et à moyenne distance.
- Faible dommage à la base par rapport aux arbalètes plus avancées.
- Un excellent choix en cas de pénurie de munitions.
