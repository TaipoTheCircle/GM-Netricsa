PERCEPTION: Fanboy enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:    Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     100 FC
MENACE:     Annoyance

DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils manifestent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan" ils gagnent le feu et les modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Erik Wolpaw est une légende vivante dans l'industrie du jeu, co-fondateur du site satirique Old Man Murray (OMM), et l'un des écrivains de jeux vidéo les plus célèbres depuis Marc Laidlaw. Croteam, avec son humour autodépréciateur caractéristique, l'immortalisa dans le jeu comme un cameo, lui accordant la HEAD BIGGEST de tous les fans secrets. Son crâne surdimensionné est le résultat direct de son énorme influence et de son esprit sarcastique, qu'il a d'abord utilisé pour critiquer l'industrie à travers OMM puis pour le transformer en écrivain à Valve.

Il a écrit le dialogue et l'intrigue dans des hits comme Portal (et sa chanson emblématique "Still Alive"), Portal 2 et Half-Life 2: Episode One et Episode Two.

Quand vous l'avez tué deux fois en Egypte antique, il s'est transformé en ange.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager le chemin.
- Sur la difficulté "Je suis Ugh-Zan", les éliminer à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.