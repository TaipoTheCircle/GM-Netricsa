POULET DU M'DIGBO


CLASSE:      Poulet
MÉTABOLISME: Oiseau chaud
PERCEPTION: Animal pacifique et ingrédient de Shawarma
TAILLE:       1,64 ft
ENDURANCE:  Très faible
HOSTILITÉ:  Aucune
ARMES:    Aucune
RÉCOMPENSE:     100 FC
MENACE:     Zéro

DESCRIPTION:

Ça ressemble à un poulet ordinaire, mais regarde dans son âme... bien sûr, c'est une affaire personnelle.

On dirait un poulet, c'est pour ça que c'est un poulet. Utilisé par Mental pour faire Shawarma.

CONSEILS:

- Le poulet est inoffensif. Ne gaspillez pas de munitions à moins de vouloir accumuler des points supplémentaires.
- La meilleure arme contre un poulet est une scie circulaire.
