VENDU DE LA PRISON TACTIQUE DE LA COMBINE


CLASSE:      Combinez le soldat tactique de la prison Overwatch
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner le Groupe de la sécurité et de la répression tactiques lourdes
TAILLE:       5,9 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    AR2 Rifle d'impulsions, SMG, Grenades
RÉCOMPENSE:     800 FC
MENACE:     Très élevé

DESCRIPTION:

Le soldat de la prison tactique Combine Overwatch est une version spécialisée du soldat tactique, formé et équipé pour le service à Nova Prospekt et des complexes pénitentiaires similaires. Contrairement aux unités de campagne, ces soldats sont entraînés à opérer dans des espaces confinés, entre les cellules, les couloirs et les zones de suppression massive des détenus.

Sa caractéristique principale est une visière jaune et un casque tactique renforcé avec une visière protectrice. La conception du casque neutralise complètement sa vulnérabilité aux coups de tête : les coups de tête n'ont pas d'effet critique, transformant les tentatives de tir précis en un gaspillage de munitions. Le Combine a délibérément rendu ces soldats aussi résistants que possible aux embuscades et aux attaques surprises dans les cellules de prison.

Leur armure est encore plus épaisse que celle des soldats tactiques. Les augmentations internes suppriment la douleur et maintiennent l'efficacité du combat même en cas de blessures graves.

CONSEILS:

- Les têtes sont complètement inutiles - ne perdez même pas votre temps sur eux.
- Les explosifs et les armes lourdes restent les seules solutions fiables.
- Il est particulièrement dangereux dans les couloirs étroits de Nova Prospekt.
- La visière jaune est très visible - mais ce n'est pas une faiblesse, c'est un avertissement.