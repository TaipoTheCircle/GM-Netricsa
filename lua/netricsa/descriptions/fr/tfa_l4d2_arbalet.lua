RIVEAU PNEUMATIQUE


ARME: Rifle pneumatique
MUNITIONS:   Flèches métalliques
CADENCE DE TIR:    Moyenne, semi-automatique

DESCRIPTION:

Une arme pneumatique artisanale, fabriquée par les habitants du métro et basée sur un style revolver. Il dispose d'un système multi-shot unique avec huit barils métalliques disposés dans une configuration tournante. Il utilise de l'air comprimé stocké dans un réservoir dédié, pour tirer des projectiles. L'arme est très précise, pratiquement silencieuse et permet la réutilisation des munitions.

Les flèches sont introduites dans la position de tir par l'intermédiaire du baril rotatif. Pour augmenter la puissance de tir, le réservoir doit être pressurisé (pumped up); cependant, l'excès de pression saigne progressivement. L'arme est configurée comme une arbalète et prend en charge la fixation de divers magazines, vues optiques et autres mécanismes. Il peut également tirer des flèches explosives.

REMARQUES:

- Le nom est une référence à l'arborescence du film "Van Helsing" (2004).
- Il utilise également un baril rotatif à huit coups.
- Les flèches peuvent être récupérées après avoir été tirées et utilisées à nouveau.
- La pression sur le réservoir augmente la puissance et la portée de tir.
- Des chargeurs de 1, 3, 6 et 8 boulons peuvent être fixés.
- Des boulons standard et explosifs sont disponibles.
