ANDRA FD-99 GUN DE SOUS-MACHINE


ARME: Gun sous-machine Andra FD-99
MUNITIONS:   5.7x28mm
CADENCE DE TIR:    ~900-1000 tours/min

DESCRIPTION:

Une mitrailleuse légère mise au point par la société Andra pour les unités armées de l'Armacham Technology Corporation. Conçu principalement pour le combat à proximité du quartier, il dispose d'une construction compacte, d'un stock pliant, d'un faible recul et d'un taux de feu élevé. Il est alimenté par un magazine de grande capacité de 50 tours.

Le FD-99 tire d'un boulon fermé et est équipé d'une vue à faible intensité rouge point (collimateur). Il offre un choix entre un feu entièrement automatique et des éclats à trois tours. Bien que les cartouches individuelles aient une puissance d'arrêt relativement faible, l'arme compense avec un volume élevé d'incendie, une excellente manutention et une grande capacité totale de munitions.

REMARQUES:

- Utilise la cartouche 5,7x28mm, un choix non conventionnel pour une mitrailleuse.
- Le magazine contient 50 cartouches, avec une capacité totale de munitions pouvant atteindre 500 cartouches.
- Le design du magazine est inspiré par le FN P90, tandis que l'extérieur du récepteur ressemble au FN F2000.
- Équipé d'une vue rouge point et d'une lumière tactique « LIGHTBRINGER » sur le côté.
- Son taux élevé d'incendie et de haute capacité magazine permettent à l'utilisateur de littéralement doucher un adversaire en tête.
