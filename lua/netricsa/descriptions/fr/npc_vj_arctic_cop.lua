LA PROTECTION CIVILE DES COMBINES


CLASSE:      Combiner la protection civile Arctic MetroCop
MÉTABOLISME: Humain, Homme
PERCEPTION: Combiner la protection civile
TAILLE:       5,9 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Moyenne
ARMES:    Stun-Stick, Pistol, SMG
RÉCOMPENSE:     150 FC
MENACE:     Faible

DESCRIPTION:

Le MetroCop arctique est une variante spécialisée du Soldat de protection civile Combiné, adapté au service dans les régions froides et enneigées. Habillé de camouflage gris et blanc, qui est destiné à le camoufler contre la glace et la neige, mais le plus souvent, il cache seulement la peur et la mauvaise formation.

Sur son uniforme, il porte un masque à gaz pour protéger contre le froid, la poussière, le gaz, et, la rumeur l'a, l'odeur de ses propres camarades après de longs déplacements. Comme les policiers du métro, il patrouille, disperse les civils, garde les installations et maintient l'ordre, surtout dans les zones où l'ordre est absent depuis longtemps.

CONSEILS:

- Il n'est presque pas seul, mais rarement seul.