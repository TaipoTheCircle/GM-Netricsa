CENTAUR, GUERRE D'ELLENIER


CLASSE:      Centaur, guerrier
MÉTABOLISME: Mammifère
PERCEPTION: Guerrier tribal
TAILLE:       12 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrême
WEAPOON:    Courbe et flèche
RÉCOMPENSE:     150 FC
MENACE:     Haut

DESCRIPTION:

Ce sont des guerriers tribaux extrêmement agressifs et territoriaux de la planète Ellenier. On les trouve souvent dans les territoires elfiques, en fouillant leurs villages et en pillant des trésors.

Au début, ils n'étaient pas moins hostiles aux forces d'invasion de Mental jusqu'à ce qu'ils soient recrutés dans son armée.

Mental a découvert ces créatures et a été impressionné par leur société inhabituelle, dominée par les hommes, mais a d'abord trouvé les faibles. Il les prit, les peignit de peinture de guerre, et leur donna des arcs, des flèches et des boucliers.

Après certification, ils ont été autorisés au combat.

Centaures tire rapidement des flèches sur leur cible tout en trottant vers elle. Ne les sous-estimez pas, malgré leurs armes dépassées, elles sont encore extrêmement dangereuses et très rapides.

CONSEILS:

- Vous pouvez esquiver leurs flèches en reculant ou sur le côté.
- Ils peuvent vous rattraper très rapidement.
- Ils vont essayer de vous entourer; essayez de ne pas laisser cela se produire si vous ne voulez pas être tiré sur de tous les côtés.
