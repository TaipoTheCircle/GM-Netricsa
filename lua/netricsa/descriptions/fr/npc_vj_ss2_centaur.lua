CENTAURE, GUERRIER D'ELLENIER


CLASSE : Centaure, Guerrier
MÉTABOLISME : Mammifère
PERCEPTION : Guerrier tribal
TAILLE : 12 pieds
ENDURANCE : Moyenne
HOSTILITÉ : Extrême
ARME : Arc et flèche
RÉCOMPENSE : 150 FC
MENACE : Élevée

DESCRIPTIF :

Ce sont des guerriers tribaux extrêmement agressifs et territoriaux de la planète Ellenier. On les trouve souvent dans les territoires elfiques, attaquant leurs villages et pillant leurs trésors.

Au début, ils n'étaient pas moins hostiles aux forces d'invasion de Mental jusqu'à ce qu'ils soient recrutés dans son armée.

Mental a découvert ces créatures et a été impressionné par leur société inhabituelle et dominée par les hommes, mais les a d'abord trouvées faibles. Il les prit, les peignit avec de la peinture de guerre et leur donna des arcs, des flèches et des boucliers.

Après certification, ils ont été autorisés à combattre.

Les centaures tirent rapidement des flèches sur leur cible tout en trottant vers elle. Ne les sous-estimez pas : malgré leurs armes obsolètes, ils restent extrêmement dangereux et très rapides.

CONSEILS :

- Vous pouvez esquiver leurs flèches en vous déplaçant vers l'arrière ou sur le côté.
- Ils peuvent vous rattraper très rapidement : détruisez-les à distance.
- Ils vont essayer de vous encercler ; essayez de ne pas laisser cela se produire si vous ne voulez pas vous faire tirer dessus de toutes parts.