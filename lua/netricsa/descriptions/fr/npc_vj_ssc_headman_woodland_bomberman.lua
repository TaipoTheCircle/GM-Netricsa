BOISLANDE BOMBERMAN


CLASSE:      Bomberman boisé décapité
MÉTABOLISME: Cyber-Zombie
PERCEPTION: Insensible, contrôlé par LCU
TAILLE:       6 pieds
ENDURANCE:  Très faible
HOSTILITÉ:  Très faible
ARMES:    Grenades à main
RÉCOMPENSE:     250 FC
MENACE:     Faible

DESCRIPTION:

Un soldat sirien exécuté, ressuscité d'entre les morts par Mental et télécommandé par l'Unité de contrôle de la vie.

Il transporte une grande quantité de grenades dans ses poches.

Le spécimen de bois tient constamment une seconde grenade dans son bras, lui permettant d'exploser à la mort.

Il porte un camouflage vert et tacheté, adapté aux milieux boisés. À en juger par l'état de l'uniforme et les marques sur le pantalon, le corps inférieur a été soumis à un traitement chirurgical brut pendant la résurrection - les organes reproducteurs sont manquants, ce qui indique une perte totale de la fonction biologique et la transformation en une ressource de combat durable.

Ils sont activement utilisés par les forces de Mental dans les forêts, les fourrés et les zones marécageuses, où l'apparence soudaine et la nature explosive de leurs attaques sont particulièrement efficaces.

CONSEILS:

- Attention, un Bomberman décapité explose.
- Détruisez-les de loin, de préférence avec un tir de précision.
- Soyez particulièrement vigilants dans la forêt - ils se camouflent souvent et sortent soudainement du couvert.
- Une concentration de plusieurs de ces soldats transforme la zone en un champ de mines mortel.