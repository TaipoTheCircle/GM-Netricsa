TROOPER AUTOMATON DU CYBERSTAIN


CLASSE:      Trooper automatique
MÉTABOLISME: Mécanique
PERCEPTION: Automaton Light Infantry
TAILLE:       5,9 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Absolu
ARMES:    Fusion Pulse mitrailleuse, Frag Grenades, Punch
RÉCOMPENSE:     200 FC
MENACE:     Faible-moyenne

DESCRIPTION:

C'est l'unité la plus commune et la plus faible de la faction Automaton.

Trooper Appearance: Un corps en métal fin, une forme humanoïde et des yeux rouges brillants. Le corps est gris, et la tête est blanche avec des yeux rouges. Les pantalons sont en métal chromé et glamour dans la lumière.

Au combat, les soldats comptent sur les chiffres. Leur tactique est simple : repérer un Helldiver, tirer des éclats à cinq tours, puis recharger (4 secondes de refroidissement). Si le Helldiver se cache derrière, le Trooper lance une grenade. Si le Helldiver est trop près, il frappe. Lorsqu'il est supprimé par le feu, le soldat commence à déplacer son arme de façon erratique, réduisant ainsi la précision.

CONSEILS:

- Les soldats ne sont pas une cible prioritaire, mais ils doivent être tués rapidement pour les empêcher d'appeler des renforts.
- La tête tue en un coup, mais c'est difficile à frapper. C'est plus facile de tirer sur le corps.
- Un bras coupé désarme le soldat, les forçant à se battre.
- Une jambe coupée immobilise le Trooper.
- Les explosifs (grenades, RPG, frappes aériennes) sont efficaces contre les amas.
- Les soldats qui exploitent des tourelles dans les avant-postes d'Automaton peuvent être tués et la tourelle peut être utilisée contre les ennemis.
