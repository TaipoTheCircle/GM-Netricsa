TAILLE:       Très grande
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES: Grand canon laser
RÉCOMPENSE:     2000000 FC
MENACE:     Extrême

DESCRIPTION:

Le SSS Centerprice est un vaisseau spatial sirien. Il y a plusieurs milliers d'années, les Siriens utilisaient le SSS Centerprice comme l'un de leurs principaux moyens de transport lors de leurs voyages interstellaires. Finalement, ils ont atteint le système solaire et découvert la Terre. Ils ont utilisé le navire pour visiter la Terre et survoler la Grande Pyramide en Égypte chaque fois que les Égyptiens participaient à leurs rituels religieux.

Peu après que les Siriens eurent appris l'attaque de Mental contre Sirius, les survivants ont repris le centrepice dans l'espace et l'ont abandonné sur la lune de Saturne Titan comme mesure temporaire. Ils croyaient que les humains étaient trop primitifs à l'époque pour maîtriser les voyages spatiaux, de sorte qu'ils abandonneraient le navire jusqu'à ce que l'humanité ait suffisamment avancé technologiquement pour le trouver et que Mental soit resté endormi.

Les Siriens ont créé un autre navire après que vous n'ayez pas réussi à répondre aux attentes et perdu le premier, l'écraser pendant une mission, mais maintenant il vise à vous éliminer.

Pour les Siriens, ce n'était pas seulement un "accident", mais une insulte à leur technologie.

