AK-12 RISQUE D'ASSAULT


ARME:      Fusil d'assaut AK-12
AMMUNITION:  5,45×39 mm
CADENCE DE TIR:         ~900 tours/min

DESCRIPTION:

Une modification moderne du fusil d'assaut emblématique, connu pour sa fiabilité et sa durabilité. Reconçu pour tirer des cartouches de 5,45×39 mm. Divers modules peuvent y être attachés. Développé en 2011 et présenté comme le fusil d'assaut de l'avenir pour les forces armées russes.

REMARQUES:

- Haute durabilité et facilité d'utilisation.
- Recul modéré; contrôlable lors de courtes rafales.
- Efficace contre les cibles non armées et légèrement blindées.
- La capacité des chargeurs nécessite un rechargement périodique pendant les combats prolongés.
- Ce fusil d'assaut peut être modifié à l'aide de différents modules.
- L'ergonomie améliorée, le fusil d'assaut est plus facile à tenir dans vos mains.