DESCRIPTIF :

The PPS-43, a submachine gun designed by Alexey Sudayev, was a Soviet weapon used during the Great Patriotic War. It was designed as a lighter, more compact, and less expensive alternative to the PPSh-41, particularly suitable for scouts, paratroopers, combat vehicle crews, and soldiers operating in cramped conditions.

La conception du PPS se caractérise par sa simplicité et l'utilisation intensive de pièces embouties, soudées et rivetées ensemble. L'arme fonctionne via une action de retour de flamme et tire en mode automatique uniquement. Dans le même temps, grâce à sa cadence de tir relativement faible, le PPS est facilement contrôlé par courtes rafales.

The PPS-43 features a folding metal stock and a box magazine. Its effective range is approximately 100-200 meters, and short bursts of 2-5 rounds are considered the most effective.

REMARQUES :

- Particulièrement efficace à courte et moyenne portée, où de courtes rafales permettent de contrôler l'arme.
- Thanks to its stamped design, the PPS is significantly simpler and less expensive to manufacture than many of its predecessors.
- The compact folding stock makes it especially convenient for scouts, paratroopers, and vehicle crews.
- The PPSh was heavy and consumed a lot of ammunition, but Sudayev looked at it and decided, "Surely we could make it simpler".
