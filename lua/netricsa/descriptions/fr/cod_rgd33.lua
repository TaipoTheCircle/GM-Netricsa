RGD-33 HAND GRENADE


ARME: RGD-33 Grenade à main
MUNITIONS:   Explosifs
CADENCE DE TIR:    Usage unique
POIDS: ~0,5 kg

DESCRIPTION:

Une grenade à main de fragmentation soviétique, développée en 1933 et utilisée par l'Armée rouge avant et pendant la Seconde Guerre mondiale. C'était une grenade offensive/défensive et pouvait être utilisée avec une veste de protection métallique supplémentaire.

La grenade avait un manche distinctif avec un mécanisme de déclenchement et une ogive cylindrique. Selon la configuration, il peut être utilisé sans la veste ou avec la veste de protection installée, ce qui augmente le nombre de fragments générés.

Le RGD-33 avait une conception assez complexe et devait être manipulé plus soigneusement que les grenades soviétiques ultérieures. Pour cette raison, il a été remplacé par le RG-42 plus simple et plus pratique.

REMARQUES:

- Le bon vieux soviétique "Pocket Artillery" avec beaucoup de caractère.
- Sans la veste de protection, la grenade était plus appropriée pour une utilisation offensive, mais avec la veste, il est devenu beaucoup plus dangereux pour l'ennemi.
- La conception s'est avérée si complexe qu'au fil du temps, l'armée a décidé : "Non, c'est tout, recommençons !".
- Le RGD-33 a été le théâtre de plusieurs conflits, dont Khalkhin Gol, la guerre d'hiver et la Grande Guerre patriotique.
