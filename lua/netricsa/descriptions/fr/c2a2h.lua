MESA BLACK, SILOS MISSILE


Sam, vous avez atteint le complexe de fusées. C'est ce dont parlait le scientifique : le site de lancement où un satellite doit être envoyé en orbite. Ce dispositif devrait aider le secteur Lambda à stabiliser la fracture dimensionnelle. Que ce soit la science, la magie ou simplement l'espoir désespéré, une chose est claire - ce lancement est critique.

Malheureusement, vous n'êtes pas le seul à le savoir. Les forces de l'U.S.E. se sont retranchées dans les silos, déterminées à empêcher le lancement.

Recommendation: Sam, tu n'as pas besoin de comprendre la science, assure-toi que la fusée monte. Si l'équipe de Lambda a raison, ce satellite pourrait nous donner l'avantage d'arrêter ce cauchemar. Et sinon... au moins les feux d'artifice seront spectaculaires.