PIT DRONE DE LA DIMENSION X


CLASSE:      Pit Drone
MÉTABOLISME: Carnivores
PERCEPTION: Infantrie légère de la course X
TAILLE:       5-6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Griffes de rasoir, pics de tête (projectile), attaque de charge rapide
RÉCOMPENSE:     200 FC
MENACE:     Moyenne

DESCRIPTION:

Les drones sont des créatures d'assaut vicieuses créées par Race X comme troupes de choc. Avec des caractéristiques reptiliennes, des griffes hameçonnées et des crêtes osseuses tapissant leur crâne, elles sont conçues pour la brutalité de la mêlée et la létalité variée. Leur capacité de signature est de lancer des pointes pointues en forme d'os à partir de leur front, capables de percer l'armure et la chair au milieu de gamme. Au combat étroit, ils frappent sans relâche avec des talons, souvent des soldats légèrement armés.

Malgré leur férocité, les Drones de Pit ne sont pas lourdement blindés, s'appuyant sur la vitesse et l'agression pures pour tuer des proies. Ils sont déployés en essaims, ce qui les rend particulièrement dangereux dans des espaces confinés où l'évasion est limitée. Sur Terre, ils ont d'abord été rencontrés lors de l'incident de Black Mesa, souvent en train de chasser en meute aux côtés de Shock Troopers.

CONSEILS:

- Continuer à se déplacer vous fait toujours une cible facile pour leurs pics de tête.
- Utilisez SHOTGUN ou MP5 pour les couper rapidement avant qu'ils ne se rapprochent.
- Les grenades ou les explosifs sont efficaces contre les groupes.
- Ne les laissez pas vous flanquer - ils travaillent mieux en nombre.
