OPS BLACK AH-64 GUNSHIP APACHE


CLASSE:      Opérations noires AH-64 Apache Gunship
MÉTABOLISME: aucun (mécanique, pilote d'élite)
PERCEPTION: Hélicoptère d'attaque secret
TAILLE:       ~58 pieds de long
ENDURANCE:  extrêmement haut (fortement blindé)
HOSTILITÉ:  extrême
ARMES:    canon à chaîne, fusées, charge utile possible de missiles
RÉCOMPENSE:     5000 FC
MENACE:     catastrophique

DESCRIPTION:

Le Black Ops Apache est une variante fortement modifiée de l'hélicoptère d'attaque standard AH-64, déployé par les forces secrètes du gouvernement. Contrairement à son homologue H.E.C.U., cette version présente des armures renforcées, de l'avionique amélioré et des charges utiles d'armes améliorées, lui permettant de dominer à la fois l'espace aérien et les rencontres au sol.

Peint en camouflage mat-noir avec signature radar réduite, il est construit à la fois pour l'intimidation et l'approche furtive. Lorsqu'il est rencontré, il délivre une puissance de feu écrasante, balayant le champ de bataille avec des canons à chaîne et des salves de roquettes. Les survivants font souvent état de leur poursuite acharnée et de leur exactitude irréfutable, rendant l'évasion presque impossible une fois qu'elle se verrouille.

Contrairement à l'Osprey axé sur le transport, le Black Ops Apache existe uniquement pour l'annihilation. Là où il vole, les survivants restent rarement.

CONSEILS:

- Restez à l'abri.
- Les fusées sont la méthode la plus fiable.
- Ne t'attarde pas après l'avoir endommagé - les représailles seront brutales.
- Écoutez l'écho du rotor, c'est votre seul avertissement.
