NIVEAU MESA DEVTEST, STRANGE


Au lieu d'expériences de routine et de bavardage inactif, le directement dans le chaos. Presque immédiatement, l'installation de Black Mesa est bombardée, avec des explosions qui secouent les couloirs, des tuiles de plafond qui s'écrasent et des sirènes d'urgence.

Dans le même temps, les créatures Xen commencent à apparaître - les ogives tombent de nulle part, les scientifiques gèrent à peine quelques cris avant d'être déchirés, et les gardes de sécurité essaient de se battre mais sont rapidement dépassés.