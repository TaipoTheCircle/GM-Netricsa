MODERNIZED KALASHNIKOV ASSAULT RIFLE


ARME : Modernized Kalashnikov Assault Rifle
MUNITIONS : 7.62x39
ROF : ~600 RPM

DESCRIPTIF :

This is a modified version of the AK-47, developed by Mikhail Timofeevich Kalashnikov in 1950 and adopted by the USSR in 1959. It is very popular with terrorists and guerrillas. It has seen action in almost every war in the world, including the Vietnam War, the Afghan War, the Chechen War, the Iraq War, and the Special Military Operation. It is a very reliable and popular assault rifle.

REMARQUES :

- It has greatly influenced the world, creating numerous copies and modifications.
- It is very well suited for assault.
- In the forests of Vietnam, the sound of its gunfire can be heard in the trees.
