RIFLE D'ASSAULT DE KALASHNIKOV MODERNISÉ


ARME: Plan d'assaut Kalashnikov modernisé
MUNITIONS:   7,62x39
CADENCE DE TIR:    ~600 RPM

DESCRIPTION:

Il s'agit d'une version modifiée de l'AK-47, développée par Mikhail Timofeevich Kalachnikov en 1950 et adoptée par l'URSS en 1959. Elle est très populaire auprès des terroristes et des guérilleros. Il a vu des actions dans presque toutes les guerres du monde, y compris la guerre du Vietnam, la guerre d'Afghanistan, la guerre de Tchétchénie, la guerre d'Irak et l'opération militaire spéciale. C'est un fusil d'assaut très fiable et populaire.

REMARQUES:

- Il a grandement influencé le monde, créant de nombreuses copies et modifications.
- Il est très bien adapté pour les agressions.
- Dans les forêts du Vietnam, le bruit de ses coups de feu peut être entendu dans les arbres.
