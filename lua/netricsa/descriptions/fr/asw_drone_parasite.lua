MOTEUR DE TRANSPORT


CLASSE:      Swarm Carrier Drone
MÉTABOLISME: Xénobiologique
PERCEPTION: Exemples d'agression
TAILLE:       6,5 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Très élevé
ARMES:    Griffes, Symbiote Parasite
RÉCOMPENSE:     120 FC
MENACE:     Haut

DESCRIPTION:

Le Swarm Carrier Drone est une variante rouge rare du drone commun, caractérisée par la présence d'un parasite adulte fermement attaché à son haut du corps. Contrairement à la plupart des cas connus de parasitisme, les deux organismes ne se font aucun mal, agissant comme une seule créature de combat.

Pendant le combat, le Swarm Carrier se comporte comme un drone commun, fermant rapidement la distance et attaquant sa proie avec de longues griffes en forme de faucille. Le parasite reste immobile, attendant la mort de son hôte.

Après la mort du drone, le parasite se détache immédiatement du corps et attaque la créature vivante la plus proche, tentant d'achever son cycle vital de la manière typique de son espèce. Ainsi, la destruction de l'hôte à proximité n'est souvent que le début d'une nouvelle menace.

L'origine de cette symbiose reste inconnue. Certains xénobiologistes considèrent qu'il s'agit d'un stade de développement naturel des drones individuels, tandis que d'autres croient que les parasites utilisent les abeilles adultes uniquement comme un moyen protégé de transport vers des proies potentielles. En tout état de cause, cette coopération augmente considérablement le taux de survie des deux organismes.

CONSEILS:

- Ne vous approchez pas de l'hôte après sa mort.
- Après avoir tué le drone, éliminez immédiatement le parasite séparé.
- Les armes automatiques vous permettent d'éliminer rapidement les deux menaces.
- Si possible, détruire l'hôte dans une zone ouverte pour rendre plus difficile pour le parasite de fermer la distance.
