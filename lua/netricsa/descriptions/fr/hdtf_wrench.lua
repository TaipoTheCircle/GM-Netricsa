PIPE WRENCH


ARME:      Clé à tuyaux
MUNITIONS:        Aucune
CADENCE DE TIR:         Variable - balançoire rapide (~60 balançoires/min) ou poussée (~20 balançoires/min)

DESCRIPTION:

Une clé à tuyaux industrielles robuste a été réutilisée comme une arme à meule pendant l'incident de Black Mesa. Réalise de puissants traumatismes contondants avec des frappes rapides ou un coup lourd dévastateur.

REMARQUES:

- Crise primaire : oscillations rapides pour des dommages modérés.
- Attaque secondaire : frappe chargée d'un dommage accru et d'un coup de poing.
- Arme silencieuse, utile pour conserver les munitions.
- Inefficient contre les ennemis lointains ou lourdement blindés.
- Durable et toujours disponible, ce qui en fait un outil fiable de dernier recours.