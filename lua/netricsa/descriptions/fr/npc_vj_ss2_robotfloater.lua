FLOATER DRONE DU SIRIUS


CLASSE:      Flotteur Drone 
MÉTABOLISME: Aéronefs sous contrôle Al
PERCEPTION: Al primaire
TAILLE:       2 pieds
ENDURANCE:  Très faible
HOSTILITÉ:  Moyenne
ARMES:    Gun laser
RÉCOMPENSE:     50 FC
MENACE:     Faible

DESCRIPTION:

Les unités de reconnaissance sont légères et volantes, bien qu'elles soient largement utilisées par la police siriane, et elles distribuent généralement des billets de vitesse aux conducteurs et aux pilotes imprudents.

Les flotteurs tourneront autour des ennemis et les tireront avec un pistolet laser à faible rendement. L'un d'eux est une menace minimale, mais ils transmettront un appel de détresse à tous les flotteurs avoisinants, ainsi qu'au QG local du commandement des drones.

Si vous êtes repéré par un mouchard, ne soyez pas surpris si vous voyez la majeure partie des forces de Mental venir renforcer la zone.

CONSEILS:

- Ils peuvent être facilement expédiés avec la plupart des armes, mais les tirs rapides et les dommages de zone fonctionnent mieux.
- Ils devraient être des cibles de faible priorité parmi d'autres ennemis, tant que vous êtes en mouvement et éviter leurs lasers.
