LE DIABLO


CLASSE:      Le Diablo
MÉTABOLISME: Fusion artificielle (anciens scientifiques + tissu chumtoad + ADN Vortigaunt + intégration cristalline Xen)
PERCEPTION: Expérimental Xen Chimera (Hybride de Pantereye)
TAILLE:       ~9 pieds de haut
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    Projection cristal de Xen: Feu de projectiles d'énergie cristal concentrée de sa crête dorsale.
RÉCOMPENSE:     5000 FC
MENACE:     Catastrophes

DESCRIPTION:

Le Diablo est une abomination imposante, artificiellement conçue, créée par l'épissage horrible de scientifiques humains, Chumtoads, l'ADN de Vortigaunt et la matière cristalline de Xen. Son corps brille faiblement d'énergie violette, tandis que son sang reste un rouge troublant, trahissant son origine humaine.

Contrairement à ses cousins de Pantereye, le Diablo n'est pas seulement un prédateur - c'est une arme vivante, conçue pour combiner la sauvagerie sauvage avec des attaques d'énergie cristalline. Son cadre massif se profile sur de petites créatures, presque deux fois la taille d'un Pantereye, avec un large dos blindé couronné par une crête cristalline pulsante qui canalise des projectiles destructeurs.

La présence du Diablo sur le champ de bataille est accablante : sa taille pure, sa coloration pourpre profonde et son sang cramoisi le rendent à la fois inspirant et horrifiant. Ce n'est pas une bête Xen naturelle, mais une expérience délibérée dans l'armement de l'évolution, un prédateur de dernière étape sans rival naturel.

CONSEILS:

- Prioriser la couverture - ses explosions de cristal sont mortelles à portée.
- Les munitions lourdes (roquettes, explosifs) sont essentielles pour les faire tomber.
- Continuez à bouger - sa portée de mêlée et saut attaque est enor
