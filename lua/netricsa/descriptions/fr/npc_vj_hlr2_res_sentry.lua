TURRET DE COMBINE HACKED


CLASSE:      Rebel-Hacked Combine Turret
MÉTABOLISME: Mécanisme entièrement synthétique, reprogrammé
PERCEPTION: Système automatisé de défense capté
TAILLE:       4,5 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrême
ARMES:    Canons à double impulsion
RÉCOMPENSE:     400 FC
MENACE:     Moyenne-haute

DESCRIPTION:

La tourelle Rebel-Hacked est une tourelle standard Combine la tourelle portable homme, capturée, grossièrement recodée et réintroduite par les forces de résistance. Son extérieur présente un travail de peinture modifié et des signes de réparation sur le terrain, mais ses intérieurs mortels restent les mêmes.

Après la reprogrammation, le système de reconnaissance des cibles ne considère plus Combiner les combattants comme des « amis ». Maintenant, tout soldat Metrocop ou Overwatch est automatiquement désigné comme cible prioritaire. La tourelle ouvre immédiatement le feu lorsqu'elle détecte le mouvement ennemi ou la signature thermique.

Les rebelles utilisent activement ces tourelles pour défendre la couverture, les bases souterraines, les couloirs et les points d'étouffement. Grâce à sa taille compacte et sa puissance de feu élevée, une seule tourelle peut occuper une position qui nécessiterait autrement une équipe entière.

Malgré le changement d'allégeance, la tourelle demeure une machine Combine par nature. Il ne fait pas de distinction entre les tactiques, ne conserve pas les munitions, et ne connaît aucune peur. La seule chose qui a changé est la liste des cibles.

CONSEILS:

- Placez les tourelles dans les points d'étranglement et sur les flancs - c'est là qu'elles sont les plus efficaces.
- Regardez la ligne de feu - la tourelle ne fait pas de discrimination entre les alliés s'ils se trouvent entre elle et la cible.
