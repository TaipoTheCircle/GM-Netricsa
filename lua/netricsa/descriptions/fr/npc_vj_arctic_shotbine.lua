COMBINE SURVEILLANCE ARCTIQUE


CLASSE:      Combiner Overwatch Arctic Shotgunner
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner les attaques de combat rapprochées
TAILLE:       5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Spas-12 fusil de combat, Grenades
RÉCOMPENSE:     700 FC
MENACE:     Haut

DESCRIPTION:

Le Combine Overwatch Arctic Shotgunner est une version modifiée de la norme Combinez un fusil d'assaut alternatif, adapté aux opérations dans les infrastructures froides, blizzards et glacées.

Dans le passé, bon nombre d'entre eux étaient des soldats, des policiers ou des militaires qui ont servi dans les régions du Nord avant l'arrivée du Combiné. Après la conquête de la Terre, leur expérience a été jugée précieuse, et leurs corps ont été jugés appropriés pour une augmentation importante. Leurs personnalités furent supprimées et leur physiologie reconstruite pour résister au froid constant.

Il porte un camouflage arctique blanc et gris avec des accents orange. Les systèmes de thermorégulation sont intégrés dans l'armure, permettant au soldat de se déplacer sans ralentir dans les zones où une personne normale gèlerait en quelques minutes.

Comme son homologue non-arctique, ce soldat n'est pas conçu pour le combat à longue portée. Son rôle est de combattre les quartiers proches agressifs, de violer les défenses et de nettoyer les salles gelées, les soutes et les tunnels.

CONSEILS:

- Il est aussi mortel que la version standard.
- Le camouflage blanc et gris le rend difficile à repérer dans la neige.
- Dans les couloirs de glace étroits, la retraite est souvent la seule chance de survie.