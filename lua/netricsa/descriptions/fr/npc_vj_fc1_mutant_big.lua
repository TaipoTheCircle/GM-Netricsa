FAT BOY DE L'ARCHIPELAGO KRIEGER


CLASSE:      Gros garçon
MÉTABOLISME: Mutant trigénique
PERCEPTION: Combattant droit
TAILLE:       7,2 pi
ENDURANCE:  Grande
HOSTILITÉ:  Agressifs
ARMES:    Lance-missile (intégré), pinces
RÉCOMPENSE:     1500 FC
MENACE:     Grande

DESCRIPTION:

Les gros garçons reçoivent leur nom de leur gigantesque construction et de gros stomps, des dizaines de mètres audibles. La plupart des spécimens sont équipés d'un lance-missile intégré dans leur bras droit, qui dispose d'un approvisionnement infini en munitions mais tire des missiles à tir lent. Leur poitrine est exposée pour permettre la ventilation de l'implant lumineux, leur principale zone vulnérable. Malgré leur uniforme militaire (tuyaux et bottes), leurs renseignements sont extrêmement primitifs : ils n'évitent pas les obstacles, mais ils grignotent littéralement leur chemin à travers eux, mourant parfois de leurs propres missiles dans des passages étroits.

Remarquablement, ce sont les seuls Trigens à garder la capacité de parler. Au combat, ils aboient des menaces comme "Vous avez échoué!" et "Vous avez fini!", bien que leurs tactiques soient limitées aux attaques frontales. Ils ne comprennent pas le concept de la mort parmi leur propre espèce - ils pourraient crier "Quelqu'un est mort!" en voyant la mort d'un autre mutant. Ils répondent aux sons et organisent des patrouilles, mais deviennent plus dangereux dans les espaces confinés en raison de l'impossibilité de s'échapper de leurs missiles.

CONSEILS:

- Viser l'implant lumineux sur les balles normales de la poitrine font peu de dommages à la chair mutée.
- Utiliser des missiles à faible maniabilité est facile à éviter dans les zones ouvertes.
- Méfiez-vous des couloirs - leurs missiles sont presque garantis pour atteindre leur cible là-bas.
- Il y a une variété non armée.
