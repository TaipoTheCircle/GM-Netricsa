OPS BLACK ASSASSIN


CLASSE:      Black Ops Robot Assassin
MÉTABOLISME: Systèmes mécanisés
PERCEPTION: Unité des opérations noires cybernétiques
TAILLE:       6 pieds 
ENDURANCE:  Extrêmement élevé
HOSTILITÉ:  Extrême
ARMES:    SMG, grenades, servomoteurs à meule renforcée
RÉCOMPENSE:     3000 FC
MENACE:     mortel

DESCRIPTION:

The Black Ops Robot Assassin est un soldat mécanisé expérimental - une fusion de tactiques de combat humaines et d'endurance robotique. Contrairement aux opérations normales des Black Ops, ces machines sont conçues pour une hésitation zéro, une peur zéro et une loyauté absolue aux paramètres de la mission.

Leur exosquelette blindée élégante imite la silhouette d'un assassin humain, mais cache des tableaux de ciblage avancés et des fibres musculaires synthétiques. Ils se déplacent avec une précision incroyable, combinant la furtivité de leurs prédécesseurs humains à l'efficacité inlassable des machines.

Les rumeurs indiquent que ces unités ont été prototypes par des projets parallèles liés, destinés à remplacer des agents non durables. On ignore si les esprits humains sont encore cachés dans leurs coquilles métalliques...

CONSEILS:

- Traitez-les comme des soldats et des machines - ils sont intelligents, mais aussi lourdement blindés.
- Les balles conventionnelles les ralentissent à peine; les explosifs ou les armes à énergie fonctionnent mieux.
- Ne jamais sous-estimer leur agilité - ils peuvent sprinter et sauter comme leurs homologues humains.
