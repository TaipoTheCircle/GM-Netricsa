SAITAMA, UN HOMME PUNCH


CLASSE:      Saitama, un homme de punch
MÉTABOLISME: Normal Humain (bien que sans limite)
PERCEPTION: Héros
TAILLE:       ~5,9 pi
ENDURANCE:  Infinite (immune aux dommages)
HOSTILITÉ:  Neutre (se bat seulement en s'ennuyant ou en s'ennuyant)
ARMES:    Son visage (un coup)
RÉCOMPENSE:     ??? (aucun ne survit pour recueillir, sauf le moustique)
MENACE:     Au-delà de l'apocalyptique

DESCRIPTION:

Aussi connu sous le nom de "Cap Baldy", Saitama est un héros ridiculement débordé qui a passé et a décidé d'aider l'Allemagne dans ses conflits. Pour la plupart, il ressemble à un homme chauve ordinaire dans un costume jaune avec une cape blanche - mais en vérité, il est capable de vaincre tout adversaire avec un seul coup de poing.

Contrairement aux autres combattants, Saitama n'a pas de véritable stratégie, aucun programme d'entraînement (autre que 100 pompes, 100 sit-ups, 100 squats, et une course de 10 km par jour) et aucune peur. Ses batailles se terminent souvent instantanément, laissant les alliés et les ennemis tout aussi confus.

Bien qu'invincible, sa plus grande faiblesse est son ennui - il prend rarement quelque chose au sérieux, et ne profite vraiment d'un combat quand il rencontre un adversaire qui semble (au moins brièvement) difficile.

CONSEILS:

- Ne vous attendez pas à un duel - le combat se terminera en un seul coup.
- S'il est de votre côté, félicitations, vous avez déjà gagné.
- Son plus grand ennemi est le moustique.