SURVEILLANCE DE LA COMBINE


CLASSE:      Combiner Overwatch Tactical Shotgunner
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner l'unité d'assaut lourde Melee
TAILLE:       5,9 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    SPAS-12 Fusil de combat, Grenades
RÉCOMPENSE:     800 FC
MENACE:     Très élevé

DESCRIPTION:

Le Soldat de fusil tactique Combine Overwatch est une version renforcée de l'Assault Trooper, conçu pour briser les défenses où les unités hybrides commencent à subir des pertes. Alors qu'il ressemble à un Trooper hybride en apparence, la différence clé se trouve sous l'armure.

Le casque tactique neutralise complètement la vulnérabilité aux coups de tête. Même des coups de tête précis n'empêchent pas le soldat. Le Combine a délibérément surchargé ces soldats d'armure, les transformant en béliers battants sans relâche.

Le SPAS-12 est utilisé comme outil de pression et de compensation. Le soldat avance sous le feu, ignorant les coups, se refermant sur la cible pour assurer la distance de mort. Les grenades servent à dégager les passages et à déloger l'ennemi des positions fortifiées.

CONSEILS:

- Les coups de tête sont inefficaces - viser le corps ou utiliser des explosifs.
- Ne le laissez pas fermer la distance - il est presque sûr d'être mortel à portée de main.
- Les armes lourdes et les pièges fonctionnent mieux.
- La retraite et la distance sont les clés de la survie.