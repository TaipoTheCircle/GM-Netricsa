KUNG FU ZOMBIE, APPRENTISSAGE DU CHI-FANG


CLASSE:      Kung Fu Zombie, Apprenti
MÉTABOLISME: Morts
PERCEPTION: Zombie Artiste Martial
TAILLE:       6 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Très élevé
ARMES:    Fists, Saw
RÉCOMPENSE:     100 FC
MENACE:     Moyenne

DESCRIPTION:

Ils servent à la fois comme policiers et comme serviteurs du prince Chang. Le mental a créé ces zombies en extrayant leurs entrailles et leurs cerveaux, et leur a inculqué une hostilité à tout ce qui bouge.

Bientôt, Mental avait amassé une importante armée de passionnés d'arts martiaux. Ils n'ont maîtrisé qu'un seul mouvement : un coup de pied volant. Et comme les zombies avaient pourri la chair, un coup de pied pourri les ferait tomber.

Mental a décidé qu'il serait plus facile de leur attacher des sabots.

Alors que la plupart des mineurs de Mental reçoivent une formation minimale, les Zombies de Kung Fu ont subi une formation approfondie en regardant des films de kung fu des années 80 et 90.

Mais même ce n'était pas suffisant, si tôt chacun d'eux a reçu une paire de shurikens mortels pour combattre les menaces à longue portée.

Maintenant, armés de la connaissance des scies et du cinéma centenaire, ils se précipitent dans la bataille et écrasent quiconque s'oppose à leur grand professeur, Sensei Mental.

Ils vous jetteront leurs scies de loin et vous frapperont à l'approche.

CONSEILS:

- Débarrassez-vous de leurs coups de pied.
- Sortez-les avec un fusil à double canon à portée de main.
- Les groupes plus importants peuvent être traités à l ' aide d ' armes à feu rapide et d ' explosifs.
