NT1 TRAVAILLEURS D'ENTREPRISE


CLASSE:      RTB Combiner surveiller Soldier Elite
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Infanterie transhumaine (unité d'élite)
TAILLE:       5,9 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    AR2 Fuseau d'impulsion, boules d'énergie
RÉCOMPENSE:     900 FC
MENACE:     Très élevé

DESCRIPTION:

La RTB Combine Overwatch Soldier Elite est l'unité terrestre la plus élevée déployée par la Combine on Earth. Reconnus par leur armure blanche et un seul œil rouge brillant, ils servent à la fois d'exécuteurs et de troupes de choc dans des opérations de grande envergure. Leurs implants synthétiques avancés leur confèrent des réflexes supérieurs, l'endurance et la sensibilisation au champ de bataille par rapport aux soldats Overwatch standard.

Les élites ne sont déployées que lorsque l'activité de résistance dépasse la capacité des unités ordinaires. Ils sont craints pour leur efficacité brutale, l'utilisation intensive du fusil à impulsion AR2, et leur tactique coordonnée, combinant souvent feu de suppression et boules d'énergie pour chasser les ennemis hors de la couverture.

Leur armure est renforcée contre le feu de petites armes, ce qui en fait des adversaires très résistants. Leur présence indique souvent que le Combine s'est déplacé vers l'extermination ou la suppression à grande échelle, laissant aux rebelles peu de place pour la retraite.

CONSEILS:

- Le feu d'impulsions est dévastateur - utilisez un couvercle et continuez à bouger.
- Les explosifs et les armes lourdes sont le moyen le plus efficace de les faire tomber.
- Ils opèrent souvent en escadrons - ne pensez jamais qu'une Elite travaille seule.
- La visière rouge peut donner leur position en faible lumière.
