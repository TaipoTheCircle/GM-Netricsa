CORE DE RÉACTEUR NOIR MESA, LAUNCH LAMBDA


C'est ça. La dernière étape avant Xen. Les scientifiques se sont rassemblés sur la plate-forme supérieure, regardant nerveusement les lectures d'un dispositif qui n'est pas censé exister ici - un Time-Lock, moteur inverse de la clé siriane de l'éternité et le jury-radarisé dans la grille de réacteur de Black Mesa. Une fois stabilisé, il ouvrira un pont contrôlé dans Xen.

The path to them is almost insultingly simple: l'équipe vous rencontrera. Mais ne le laissez pas vous tromper - le vrai défi commence quand la défense commence.

Mission Parameters:

Protégez le scientifique principal. Il est le seul à être entraîné à opérer le Time-Lock modifié. S'il meurt, la porte ne se stabilise jamais.

Attendez-vous à une forte incursion. Les forces de Mental et les créatures de Xen sentent la faille et jetteront tout ce qu'ils ont pour arrêter l'activation.

Maintenez jusqu'à stable. L'appareil nécessite un flux d'énergie continu pour la synchronisation; l'interrompre au milieu du cycle pourrait causer une résonance catastrophique.

Complications:

Des visages familiers. Justin Barnes, Adrian Shephard, et Gordon Freeman lui-même ont été vus en chemin. Le vrai Freeman - pas vous, pas la confusion. Mais ils sont en retard, et tu as déjà fait la lourde levage. S'ils arrivent du tout, ce ne sera pas à temps pour aider à ce combat.

Soutien limité. Les scientifiques ne peuvent vous fournir qu'un seul outil : un jetpack prototype, conçu pour les sauts prolongés. Il sera nécessaire une fois le portail stabilisé. Traite ça comme de l'or.