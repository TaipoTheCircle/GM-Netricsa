SERGEANT STORMTROOPER DU KAMINO


CLASSE:      Sergent Stormtrooper
MÉTABOLISME: Cybernétique Humain
PERCEPTION: Commandant Elite, la main gauche de Darth Vader
TAILLE:       6,5 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Absolu
ARMES:    Minigun, grenades, RPG, canon laser, systèmes expérimentaux, bouclier énergétique, robots
RÉCOMPENSE:     10000 FC
MENACE:     Absolu

DESCRIPTION:

Ce guerrier cybernétique d'élite sert d'aide de confiance à Darth Vader. Il combine les talents d'un officier de terrain, d'un ingénieur hautement qualifié et d'un mercenaire. Il conçoit personnellement des armes expérimentales, qu'il appelle ses « jouets ».

Sa construction puissante et sportive est renforcée par une armure de puissance massive en métal foncé. Les plaques angulaires, les pointes et les segments mobiles de l'armure non seulement fournissent une protection énorme, mais aussi servent d'excellent camouflage la nuit. L'identité du sergent reste un mystère : son visage est bien caché sous un casque high-tech avec une visière transparente, équipée de modules de capteurs supplémentaires.

L'arsenal du sergent est impressionnant dans son potentiel destructeur. Ses armes primaires sont un mini-gun à canons multiples et des systèmes d'assaut puissants, complétés par des grenades et des RPG. Au combat, il montre une agression débridée, commandant des unités d'infanterie et déployant ses propres robots sur les lignes de front. Sa supériorité technologique est soulignée par l'utilisation de boucliers d'énergie avancés et de plusieurs systèmes secrets, ce qui en fait un adversaire imprévisible.

Il est officiellement inscrit sur la liste de "Vader's Left Hand", mais la moitié de ses améliorations ont été installées illégalement.

Son casque n'a jamais été enlevé en public-même les médecins ne peuvent le voir que par des capteurs.

CONSEILS:

- N'attaquez pas le sergent. Ses robots et son mini-gun vous transformeront en tamis.
- Le sergent coordonne les brigades de tir.
- Ne vous approchez pas de ses jouets, de ses robots de combat.
- La mobilité est la clé dans un duel avec lui. Il est lent en raison de son armure lourde, mais ses armes couvrent une large zone.
