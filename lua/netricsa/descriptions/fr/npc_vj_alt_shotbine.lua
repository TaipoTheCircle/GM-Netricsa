AUTRE SURVEILLANCE COMBINE SHOTGUNNER


CLASSE:      Alternative Overwatch Combiner Shotgunner
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner l'unité de lutte rapprochée contre les agressions
TAILLE:       5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Spas-12 fusil de combat, Grenades
RÉCOMPENSE:     700 FC
MENACE:     Haut

DESCRIPTION:

L'Alternative Overwatch Combine Shotgunner est un Soldat Combine spécialisé conçu pour nettoyer les pièces, les tunnels et les environnements urbains denses. Contrairement aux unités d'élite standard, il porte un uniforme de couleur marécageuse conçu pour le camouflage dans les zones industrielles, les ruines et les zones contaminées. Sa visière brille d'orange.

Ce type de soldat n'est pas conçu pour les combats à longue portée. Son travail est simple et extrêmement frustrant : fermez rapidement la distance et transformez tout devant lui en un nuage de débris et de chair. Les augmentations renforcent ses réflexes et sa tolérance à la douleur, lui permettant d'avancer même sous un feu lourd.

CONSEILS:

- À portée de main, un fusil est mortel.
- Dans les couloirs étroits, il vaut mieux se retirer que de tester le nombre de tirs que vous pouvez prendre.
- La visière orange est très visible dans le noir - parfois c'est la seule chance de le voir en premier.