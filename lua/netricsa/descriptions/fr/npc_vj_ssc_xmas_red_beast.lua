L'ALUDRAN REPTILOID, CHRISTMES (RED)


CLASSE:      Aludran Reptiloid, sous-espèce de vacances
MÉTABOLISME: Sang froid, comme un reptile
DEFINITION: Race primitive, membre du culte du Nouvel An
TAILLE:       15 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Missiles magiques (balles de feu rouges)
RÉCOMPENSE:     5 500 FC
MENACE:     Moyenne

DESCRIPTION:

Un grand reptile à quatre mains vivant dans le système Aludran dans la constellation de Canis Major. Cette race primitive a accepté de se battre pour le Mental en échange des pouvoirs qu'elle leur a conférés.

Ils ont lancé des boules de feu autopropulsées avec des capacités primitives.

Le Reptiloïde d'Aludran rouge de Noël est une mutation rare et inquiétante des espèces des plaines. Contrairement à ses frères, cette sous-espèce a été doublement influencée : par la magie du Mental et par une entité connue sous le nom de Géant Snowman, qui a promis une nouvelle année éternelle. Le prix du marché s'est avéré symbolique et humiliant - le port obligatoire d'un chapeau du Père Noël Nouvel An.

They are easily recognizable in appearance: boules magiques rouges au lieu des boules vertes habituelles, le sang rouge, et un arc rouge brillant sur leurs poitrines massives, sécurisé par la magie brute. Malgré leur apparence comique, ils restent extrêmement dangereux dans la bataille.

Les reptiliens eux-mêmes croient sincèrement qu'ils se battent pour une fête éternelle. Ironiquement, la nouvelle année est vraiment sans fin pour eux - mais seulement jusqu'à ce qu'ils meurent en combattant pour la guerre de quelqu'un d'autre.

CONSEILS:

- Gardez-les sous un feu constant et essayez de descendre les missiles en l'air.
- Les boules rouges sont plus visibles, tirent de façon préventive.