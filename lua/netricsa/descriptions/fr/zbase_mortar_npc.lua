BUG MORTAIRE DE LA MER


CLASSE:        Bug de mortier de swarm
MÉTABOLISME:   Xénobiologique
ROLE:         Unité d'artillerie
TAILLE:         9,2 pi
DURABILITY:   Haut
HOSTILITÉ:    Haut
ARMES:      Projectiles biologiques explosifs
RÉCOMPENSE:       700 FC
MENACE:       Haut

DESCRIPTION:

Le Bug Mortar est une variante d'artillerie spécialisée du Swarm, conçue pour engager des cibles à longue portée. Au lieu des glandes acides typiques des Rangers, cette créature utilise des organes spécialisés qui produisent des charges explosives instables.

Lors de l'attaque, le Bug Mortar lance un volley de trois projectiles dans une trajectoire en relief. Au moment de l'impact, ils adhèrent à la surface et détonent après quelques secondes. Cela permet au Swarm de restreindre le mouvement ennemi, de bloquer les passages et de forcer les proies à s'abriter.

Malgré sa taille imposante et sa carapace épaisse, le Bug Mortar est mal adapté pour les combats à proximité. Sa principale menace réside dans ses armes à longue portée; par conséquent, ces créatures restent généralement derrière les forces principales du Swarm, protégées par les drones et d'autres sous-espèces agressives.

La peau du Bug Mortar est saturée de composés biologiques caustiques. Même après la mort, ses tissus restent dangereux à toucher pendant un certain temps, faisant de la récolte de carcasses une tâche extrêmement impopulaire parmi les chercheurs de terrain.

CONSEILS:

- Ne restez pas près des projectiles tombés.
- Éliminer les Bugs Mortar avant qu'ils puissent obtenir une position avantageuse.
- Faites preuve de prudence lorsque vous utilisez une couverture contre le feu d'arc.
- Si trois sphères organiques suspectes apparaissent soudainement sur le sol, il est préférable de quitter la zone immédiatement.
