KAMIKAZE, SUR LES DRAGS


CLASSE:      Kamikaze décapité, sur les drogues
MÉTABOLISME: cyber-zombie
PERCEPTION: insensible, contrôlé par LCU
TAILLE:       6 pieds
ENDURANCE:  très faible
HOSTILITÉ:  extrême
ARMES:    grenades à main
RÉCOMPENSE:     2500 FC
MENACE:     élevé

DESCRIPTION:

Un soldat syrien exécuté, ressuscité d'entre les morts à l'aide de drogues mentales et contrôlé à distance par une unité de contrôle de la vie.
Le chef du Kamikaze a été ruiné, donc il est employé pour des attaques suicidaires. Il porte deux bombes dans ses mains et les active quand elle est assez proche de la cible.

CONSEILS:

- Explose quand tues.