RÉVOLUTION DU ROI DE COBRA


ARME:    Colt King Cobra
AMMUNITION .357 Magnum
CADENCE DE TIR:       15 tours/min

DESCRIPTION:

Le revolver Colt King Cobra est un revolver à six prises avec un mécanisme de déclenchement à double action. Il a été introduit pour la première fois en 1986. Il a été développé et fabriqué par Colt's Manufacturing Company. Il était destiné aux organismes d'application de la loi et à la vente aux amateurs d'armes à feu. Disponible en acier bleu et inoxydable.

REMARQUES:

- Le revolver est une arme très fiable.
- Son grand calibre vous permet de tuer un ennemi très rapidement.
- Vous pouvez jouer la roulette russe avec si vous êtes sans peur.