DESCRIPTION:

Les Monster Generics sont les toiles blanches de la vie prédatrice de Xen et Black Mesa. Personne ne connaît leur vraie nature, parce qu'ils existent principalement en tant que modèles dans le monde - mais quand "spawned" dans le monde réel, ils prennent des formes de monstres réels, obéissant aux règles de leur environnement.

They can be anything: un extraterrestre qui craque, une créature qui souffle, ou un hybride bizarre, personne ne s'y attendait.

Certains chercheurs chuchotent que ces créatures sont les marionnettistes sous-jacents de tous les autres monstres et acteurs génériques - les archétypes invisibles à partir desquels chaque prédateur griffé, fangé ou tentaculé est copié. Rencontrer quelqu'un se sent comme rencontrer une créature à la fois générique et uniquement terrifiante.

CONSEILS:

- Attendez l'inattendu : l'apparence et les attaques varient sauvagement.
- Exploiter les pièges environnementaux, comme Monster Generics sont enclins à suivre tout le monde littéralement.
- Ne présumez pas la familiarité - chaque rencontre peut être différente.
