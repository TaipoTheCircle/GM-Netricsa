CHAINSAW


ARME: Chaînes
MUNITIONS:   Essence

DESCRIPTION:

Un puissant outil portatif avec chaîne tournante, conçu pour frapper des cibles à une portée extrêmement proche. La chaîne tourne en continu pendant le fonctionnement, permettant des frappes successives rapides sans avoir besoin de recharger.

Une tronçonneuse est particulièrement efficace contre les ennemis à portée de gamme, mais nécessite une consommation constante de carburant. Le principal inconvénient est la nécessité d'approcher la cible à une distance dangereusement proche.

REMARQUES:

- Ne nécessite pas de munitions, mais consomme constamment du carburant.
- Très efficace à très près.
- Produit un son fort et distinctif lorsqu'il est utilisé.
- L'essence est devenue plus précieuse.
