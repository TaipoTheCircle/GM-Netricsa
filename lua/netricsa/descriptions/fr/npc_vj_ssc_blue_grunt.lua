BLUE ZORG-LASER-GUNNER DE BEELMEZ IV


CLASSE:      Bleu Zorg-Laser-Gunner
MÉTABOLISME: mammifère
PERCEPTION: race des guerriers
TAILLE:       6,5 pieds
ENDURANCE:  faible
HOSTILITÉ:  faible
ARMES:    laser à éclat vert
RÉCOMPENSE:     500 FC
MENACE:     faible

DESCRIPTION:

Mental a transporté ces soldats sur Terre d'une partie inconnue de l'univers. Ils étaient autrefois une race de guerriers redoutables mais comme ils ont conquis plus de planètes qu'ils ne savaient quoi faire, ils ont décidé de ralentir pendant un certain temps. La plupart de la population a pris des vacances de longue date sur l'une des plus belles planètes tropicales de leur système; mais comme ils ont seulement bronzer de 10 à 16 heures, après quelques années, la plupart d'entre eux n'avaient plus de peau sur leur corps.

Their blue color comes from a tragic mistake: au lieu de l'écran solaire, ils ont accidentellement utilisé le colorant bleu industriel "Sin'ka". Cette tournure bizarre des événements les a tellement fait ressortir que Mental les a immédiatement réaffectés dans les rangs du terrible corps LASER-GUNNER.

CONSEILS:

- Essayez d'éviter leurs rayons laser rapides.