DROID DE LA COMBINE


CLASSE:      Mélanger le droïde
MÉTABOLISME: Entièrement synthétique
PERCEPTION: Combiner la plate-forme de combat robotique lourd
TAILLE:       ~8-10 pieds
ENDURANCE:  Extrêmement élevé
HOSTILITÉ:  Extrême
ARMES:    Force mécanique pure, lancer d'objets lourds
RÉCOMPENSE:     1200 FC
MENACE:     Très élevé

DESCRIPTION:

Le Droïde Combiné est la réponse directe, mais tordue, du Combiné au Chien de Résistance. Inspirés par les Rebels, les ingénieurs Overwatch l'ont redessiné, en supprimant l'improvisation « redondante » et la composante émotionnelle, transformant l'idée en une machine de combat parfaitement calibrée.

Contrairement au chien, le droïde est parfaitement proportionné : son corps est symétrique, ses mouvements sont mesurés et sa mécanique est dépourvue de gestes brusques, « vivants ». Sa tête est tournée dans la direction opposée. Son extérieur est peint un noir profond avec des accents rouges et blancs, et le logo Combine est clairement visible sur son corps.

Its purpose is simple: pour briser, écraser et détruire. Il peut jeter les voitures, arracher les tourelles de leurs montures, et briser les fortifications avec la même facilité que le chien, mais il le fait méthodiquement et avec précision.

Le Droid est intégré au réseau tactique Combine et travaille souvent en tandem avec les soldats Overwatch, fournissant une couverture, des passages de compensation, ou semant la panique parmi l'ennemi.

CONSEILS:

- Le combat direct est fortement découragé - son armure peut résister à d'énormes forces. - Utiliser l'environnement : effondrements, pièges et explosions puissantes.
