ZORG MERCENAIRE DE BELMEZ IV


CLASSE:      Mercénaire de Zorg
MÉTABOLISME: Mammifère
PERCEPTION: La race des guerriers
TAILLE:       6,5 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Faible
ARMES:    Laser de rupture
RÉCOMPENSE:     500 FC
MENACE:     Faible

DESCRIPTION:

Mental a transporté ces soldats sur Terre d'une partie inconnue de l'univers. Ils étaient autrefois une race de guerriers redoutables mais comme ils ont conquis plus de planètes qu'ils ne savaient quoi faire, ils ont décidé de ralentir pendant un certain temps. La plupart de la population a pris des vacances de longue date sur l'une des plus belles planètes tropicales de leur système; mais comme ils ne baignaient que du soleil de 10h à 16h, après quelques années, la plupart d'entre eux n'avaient plus de peau sur leur corps.

CONSEILS:

- Essayez d'éviter leurs rayons laser rapides.
