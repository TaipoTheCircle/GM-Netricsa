SYNTHÈSE DE L'ASSAULT


CLASSE:      Combiner la synth d'assaut
MÉTABOLISME: Synthétisation biomécanique
PERCEPTION: Synthétisation de la petite agression
TAILLE:       ~5 pi 
ENDURANCE:  Moyenne 
HOSTILITÉ:  Haut 
ARMES:    Canon synthé intégré
RÉCOMPENSE:     300
MENACE:     Moyenne

DESCRIPTION:

L'Assault Synth est une unité de concept Combine - une construction biomécanique rapide à quatre pattes conçue pour des frappes coordonnées sur le champ de bataille. Ces synthés, d'une hauteur d'environ 5 pieds, sont assez compacts pour s'emparer des forces d'infanterie. Leurs quatre membres agiles permettent une mobilité exceptionnelle, ce qui leur permet de courir à grande vitesse et de se défendre.

Ils sont souvent déployés aux côtés de Crab Synths, agissant comme des escarmouches rapides qui complètent le rôle d'assaut lourd de leur homologue. Bien que individuellement fragiles par rapport aux principaux synthés, dans les groupes ils deviennent une menace grave, harcelant l'infanterie et adoucissant les défenses pour les unités plus lourdes Combiner.

CONSEILS:

- Restez en alerte lorsque les Synths de Crabe sont présents - Synths d'assaut les accompagnent habituellement.
- Les armes à effet de surface (grenades, fusils de chasse) sont les plus efficaces.
