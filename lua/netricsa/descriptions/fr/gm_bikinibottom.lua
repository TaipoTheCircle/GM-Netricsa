BIKINI BOTTOM, VILLE SOUS-AGRICOLE


Sam, nous avons été aspirés dans une anomalie qui nous a transportés directement à la ville sous-marine de Bikini Bottom.

Il n'y a qu'un problème : soit l'armée de Mental vient de passer ici, soit...

Donc, ce ne sera pas calme ici.

Voilà :

Le Krusty Krab - l'attraction principale, un restaurant qui sert Krabby Patties.

Patrick's Rock - juste une pierre. Mais en dessous il y a un trou plein de... Je ne sais même pas de quoi un trou d'étoile de mer serait rempli.

La maison de Squidward - en forme de tête d'île de Pâques, et le dôme transparent de Sandy. Les deux endroits sont des cachettes parfaites pour les embuscades.

