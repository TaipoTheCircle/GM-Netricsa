SCRAPJACK


CLASSE:      Raccourci
MÉTABOLISME: Corps cousu modifié cybernétiquement
PERCEPTION: Guerrier de fusée cousu
TAILLE:       8 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Haut
ARMES:    2 lance-roquettes, coup écrasant
RÉCOMPENSE:     5000 FC
MENACE:     Haut

DESCRIPTION:

Un fantassin lourd de la Horde mentale, produit en masse et bon marché, littéralement assemblé à partir des parties du corps des soldats tombés et équipé de puissants lance-roquettes. Extrêmement lent et maladroit, mais compense avec une énorme réserve de graisse et de puissance de feu dévastatrice. Les fusées volent de manière prévisible : l'une directement à la cible, les autres tirent de façon préventive sur les flancs. Lorsqu'il est enragé, il tire plus fréquemment et avec plus de précision. À portée de main, il lance un coup dévastateur, capable de tuer en un seul coup.

CONSEILS:

- Ses missiles peuvent pénétrer dans les murs. Une grève rapprochée est fatale.
- A-24 "Devastator", pistolet éclair, C4 - Excellentes options pour le combattre.
