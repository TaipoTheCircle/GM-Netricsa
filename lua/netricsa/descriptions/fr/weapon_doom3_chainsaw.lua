Tronçonneuse


ARME : Tronçonneuse
MUNITIONS : Essence

DESCRIPTIF :

Un outil portatif puissant doté d'une chaîne rotative, conçu pour frapper des cibles à très courte distance. La chaîne tourne continuellement pendant le fonctionnement, permettant des frappes successives rapides sans avoir besoin de recharger.

A chainsaw is especially effective against enemies at close range, but requires constant fuel consumption. The main drawback is the need to approach the target at dangerously close range.

REMARQUES :

- Ne nécessite pas de munitions, mais consomme constamment du carburant.
- Très efficace à très courte distance.
- Produit un son fort et distinctif lors de son utilisation.
- L'essence a pris plus de valeur ces jours-ci.
