STROGGOS


PLANET:       Stroggos
TYPE:         Planète terrestre, monde industriel
CLIMATE:      Harsh, aride, atmosphère respirante pour les humains
MOONS:        3 lunes (une avec son propre système d'anneau)
TERRAIN:      Vastes friches industrielles, cratères, chaînes de montagnes, petits plans d'eau
LOCATION:     Système étoile inconnu
NATIVE RACES: Strog, restes de faune éteinte et assimilée
ALLIANCE:     L'Empire de Strogg
LOCATIONS:    Macron Palace, Colossus Landing Zone, Craters Majoris et Mineur, Base Lunaire Secret Strogg

DESCRIPTION:

Un monde inhospitalier, mais respirant, pour les humains, qui abrite la course cybernétique agressive Strogg. La planète est semblable en taille, gravité et composition atmosphérique à la Terre, mais son apparence a été complètement défiguré par des millénaires d'industrialisation incessante. De l'orbite, la planète apparaît comme un désert brun-orange, dépourvu de zones vertes importantes et d'eau libre.

Stroggos a probablement une fois vanté une riche biosphère avec des océans, de la végétation et de la faune diversifiée. Cependant, les Stroggos, en quête de militarisation totale, ont épuisé pratiquement toutes les ressources naturelles : métaux, minéraux et combustibles fossiles ont été extraits et transformés. La plupart des formes de vie indigènes sont mortes, mutées, ou ont été assimilées de force par les Stroggos-transformés en nourriture ou transformés en nouveaux soldats par le processus horrible de "Stroggification".

Le paysage de la planète est un vaste désert industriel, parsemé d'usines, d'usines de transformation et de bases militaires.

L'activité géologique est élevée, les cratères d'impact (comme Majoris et Minor) restant, et un système d'anneaux d'astéroïdes orbitant la planète-peut-être les restes d'une quatrième lune détruite dans une ancienne catastrophe.

Stroggos est entouré de trois lunes et d'une ceinture d'astéroïdes, qui contient la résidence secrète du leader Strogg, Macron, accessible uniquement par téléporteur de la surface.

KEY LOCATIONS:

- Palais de Macron : La structure centrale à la surface de Stroggos, couronnée par un téléporteur massif menant à la retraite d'astéroïde du leader. Le cœur de la machine de guerre Strogg.
- Zone d'atterrissage "Colossus" : Le site des premiers débarquements massifs des forces d'invasion de la Terre. Un lieu de combats acharnés, jonché de restes de véhicules et de corps.
- Craters Majoris et Mineur : Deux cratères d'impact énormes, probablement associés à la formation de la ceinture d'astéroïdes. D'importantes installations industrielles sont situées à proximité.
- Base Lunaire Secret Strogg: Un complexe souterrain massif sur la troisième lune, contenant des usines, des quais navals, et un bunker de commandement. Détruite dans une opération audacieuse des Marines de la Terre.
