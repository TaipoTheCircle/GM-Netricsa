BLACK MESA DEVTEST, OFFRE AU SUJET DE LIBRE-MAN


Dans le jeu de détail, ce chapitre marquait un tournant : l'U.S.E. a été ordonné d'abandonner l'installation, laissant le chaos derrière. De longues étendues de couloirs ruinés, d'embuscades de dernier stand et de structures s'effondrent ont rempli le chemin de Lambda.

La version E3 de Devtest coupe tout cela. Au lieu d'une retraite étirée, l'appareil est jeté directement dans un couloir bombardé, avec des conversations radio paniquées de soldats. En quelques instants, il devient clair : l'armée se retire, et vous n'êtes plus leur mission.

Ici, le but est immédiat - atteindre l'entrée de Lambda sous le feu.