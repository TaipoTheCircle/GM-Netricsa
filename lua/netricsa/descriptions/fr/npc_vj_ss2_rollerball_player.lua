DESCRIPTION:

Le Rollerball est l'une de ces merveilles d'ingénierie qui vous fait vous demander, "Qui était le génie qui est venu avec cela et où devraient-ils lui mettre un monument?" C'est une énorme balle, clouée avec des pointes, avec une personne qui court dedans. Littéralement courir comme un hamster sur une roue, seulement au lieu d'une roue de hamster, il y a une sphère de plusieurs tonnes de mort, écrasant tout sur son chemin.

The controls are incredibly simple: if you want to move, run. If you want to turn, lean. If you want to kill, accelerate and direct this colossus at the nearest cyclops. The impact pierces the spikes, shatters the flesh, and the rollerball rolls on, never slowing down.

La conception permet de sauter. Comment exactement vous pouvez sauter à l'intérieur de la balle et faire décoller ce colosse est un mystère, mais le fait reste: la balle roule comme une balle en caoutchouc remplie de colère et de pics.

This thing can be used in a variety of ways: comme une arme, comme un moyen de transport, comme un moyen d'échapper rapidement à une zone dangereuse, ou comme une attraction pour ceux qui ont toujours voulu se sentir comme un Terminator. La chose principale à retenir est que la balle prend des dommages aussi. Quelques collisions puissantes et tout ce qui reste c'est des pics et des souvenirs.

CONSEILS:

- Accélérer et frapper.
- La balle est rapide. Utilisez ceci pour éviter les missiles et les lasers.
- Parfois, il vaut mieux sauter sur un obstacle que de l'abattre.
- Si vous voyez une foule d'ennemis, roulez directement dedans. Une course coûte des milliers de balles.
- À ne pas confondre avec des homologues de l'IA.
