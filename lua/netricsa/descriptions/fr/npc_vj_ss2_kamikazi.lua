KAMIKAZE BOMBHEADÉ


CLASSE:      Kamikaze à tête de bombe
MÉTABOLISME: Cyber-Zombie
PERCEPTION: Insensible, contrôlé par LCU
TAILLE:       8 pieds
ENDURANCE:  Très faible
HOSTILITÉ:  Extrême
ARMES:    Bombe géante
RÉCOMPENSE:     50 FC
MENACE:     Haut

DESCRIPTION:

Contrairement aux Kamikazes typiques, le Kamikaze à tête de bombe est généralement utilisé pour des événements de "charité" tels que les marathons pour recueillir de l'argent pour les chiots malades de Fido.

Cependant, la vérité est que tout l'argent généré par ces événements va directement dans la machine de guerre de Mental.

Lorsqu'ils ne assistent pas à ces événements, les Kamikazes se chargent de la bataille et explosent sur quiconque s'oppose à leur seigneur.

CONSEILS:

- Explose quand tues.
- Ils sont dangereux quand ils sont mélangés avec d'autres ennemis.
- Restez loin, ils n'ont pas d'armes.
- S'il y en a beaucoup, le canon SBC et le Minigun vous aideront.
- S'ils sont regroupés avec d'autres ennemis, l'explosion peut les tuer.
- Contre une foule de kamikazes, un fusil de chasse, Uzi, ou toute autre arme est efficace, mais seulement si le groupe se compose uniquement de kamikazes, comme exploser l'un fera exploser les autres.
