SURVEILLANCE DE COMBINE "SKULLPIECE" VENDU


CLASSE:      Combiner le soldat Overwatch "Skullpiercer"
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner l'exécuteur d'assaut
TAILLE:       5,9 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    AR2 Pulse Rifle, SPAS-12 fusil de combat, Grenades
RÉCOMPENSE:     1200 FC
MENACE:     Très élevé

DESCRIPTION:

Le Soldier Combine Skullpiercer est une unité hybride d'assaut/exorciste rare et extrêmement méchante dans les rangs de Combine Overwatch. Contrairement à la plupart des unités, qui sont strictement spécialisées pour un seul rôle, les Skullbreakers subissent un entraînement de combat intensif, leur permettant d'opérer aussi efficacement à moyenne portée avec un AR2 et à portée pointue avec un fusil SPAS-12.

Leur équipement de couleur marécage avec des accents bleu terne Overwatch est conçu pour les opérations dans les ruines industrielles, les zones contaminées, les villes, les marais et les secteurs souterrains, où l'armure standard révèle rapidement leur position. Les visières oranges soulignent leur statut d'unités de répression des agressions.

CONSEILS:

- Dangereux à n'importe quelle portée.
- Les grenades sont utilisées pour abattre la couverture, pas pour terminer.
- La visière orange est visible dans l'obscurité.