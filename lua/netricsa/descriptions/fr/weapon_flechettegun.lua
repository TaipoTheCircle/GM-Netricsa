FLECHETTE GUN


ARME:      Flechette
MUNITIONS:        Flèches (petites fléchettes à grande vitesse)
CADENCE DE TIR:        ~250 tours/min

DESCRIPTION:

Arme rangée qui tire des projectiles compacts, comme des aiguilles à grande vitesse. Chaque flechette pénètre l'armure et la chair avec un recul minimal, rendant l'arme efficace pour une suppression précise ou des frappes chirurgicales.

REMARQUES:

- Les projectiles à grande vitesse peuvent percer plusieurs cibles en ligne.
- Capacité de munitions modérée; orientation prudente recommandée.
- Efficace à moyenne portée; moins utile dans les quartiers proches.
- Faible recul permet un suivi rapide.