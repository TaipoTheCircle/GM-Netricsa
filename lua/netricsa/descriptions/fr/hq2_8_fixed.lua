HALF-QUAKE 2, VIVRE AVEC UN HAMMER


Arrête ! Regarde cet écran.

Je pensais qu'on avait déjà vu toute la folie que les sadiques ont à offrir. Mais ils nous surprennent encore. Ils s'amusent avec leurs propres gardes.

Un énorme marteau. Chaque coup, et un autre garde est écrasé dans une pulpe.

Et tu sais ce qui est le plus fou ? Je commence à comprendre pourquoi ils font ça. Ils ne tuent pas seulement les leurs. Ils nous montrent, "Regarde, même les nôtres sont durables pour nous. Que pouvons-nous dire de vous ?"

Ils veulent qu'on ait peur. Donc nous savons que la même chose nous attend si nous échouons à leurs tests.

Mais ils ont un problème. Je t'ai vu traverser l'enfer. Je vous ai vu tuer Mardochée, Quongo, Zoom-Zoom, Nihilanth, et d'autres. Je t'ai vu survivre à Black Mesa.

Tu n'as pas peur des marteaux. Vous n'avez peur que d'une chose : ne pas appuyer sur la détente à temps.

Allez, Sam. Laissez-les s'amuser avec leurs gardes. On va leur montrer ce qu'est un VRAI SHOW !
