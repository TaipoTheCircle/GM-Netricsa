HALF-QUAKE 2, VIVRE AVEC UN MARTEAU


Sam... ARRÊTE ! Regardez cet écran.

Je pensais qu'on avait déjà vu toute la folie que les sadiques ont à offrir. Mais ils nous surprennent encore. En ce moment, en direct à l'antenne, ils s'amusent avec leurs propres gardes.

Un énorme marteau. À chaque coup, un autre garde est réduit en bouillie.

Et tu sais ce qui est le plus fou ? Je commence à comprendre pourquoi ils font ça. Ils ne tuent pas seulement les leurs. Ils nous montrent : « Écoutez, même les nôtres sont inutilisables. Que pouvons-nous dire de vous ?

Ils veulent que nous ayons peur. Nous savons donc que la même chose nous attend si nous échouons à leurs tests.

Mais ils ont un problème, Sam. Je t'ai vu traverser l'enfer. Je t'ai vu tuer Mordecai, Quongo, Zoom-Zoom, Nihilanth et d'autres. Je t'ai vu survivre à Black Mesa.

Vous n'avez pas peur des marteaux. Vous n'avez peur que d'une chose : ne pas appuyer sur la gâchette à temps.

Allez, Sam. Laissez-les s'amuser avec leurs gardes. Nous allons leur montrer ce qu'est un VRAI SPECTACLE !