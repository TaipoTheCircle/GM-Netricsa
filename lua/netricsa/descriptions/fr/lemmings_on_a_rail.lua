MESA BLACK, FREIGHT RAIL


Sam, l'alimentation est de retour en ligne, et le système ferroviaire de fret est à nouveau opérationnel. Contre toute attente, vous avez réussi à vous en sortir. Bonne nouvelle : le train fonctionne. La mauvaise nouvelle : tout le reste.

Dès que vous montez à bord et que vous frappez les commandes, la voiture de fret se branle en avant avec un gémissement de roues rouillées. La piste s'étend profondément dans le labyrinthe souterrain de Black Mesa, promettant à la fois une évasion et de nouveaux cauchemars.

Complications ahead:

Les patrouilles de l'U.C.E. ont des sections fortifiées de la ligne de chemin de fer. S'attendre à des embuscades à des points d'étranglement, des tourelles par des tunnels et des explosifs plantés sur les voies.

L'activité de l'alien est en augmentation-La faune Xen est en train d'évoluer directement sur les pistes, soit trop stupide pour se déplacer, soit assez intelligente pour bloquer votre chemin.