INVADER ROBOT, ASSAULT DE SHAIJU GANDHI



CLASSE:      Robot Invander, Assaut
MÉTABOLISME: Artificiel (noyau mécanique)
PERCEPTION: Guerrier automatique
TAILLE:       7-8 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    Fusil d'assaut laser, grenades à plasma renforcées, bras écrasés
RÉCOMPENSE:     1200 FC
MENACE:     Très élevé

DESCRIPTION:

L'unité d'assaut représente l'une des variantes les plus dangereuses des robots Invader de Shaidzu-Gandi. Contrairement aux modèles de base, ces machines sont entièrement équipées d'armes à portée avancée - notamment d'un fusil d'assaut laser à tir rapide, capable de couper des équipes de soldats en quelques secondes.

En outre, ils portent des grenades à plasma renforcées, conçues pour exploser avec une force dévastatrice, annihilant l'infanterie et déstabilisant des cibles blindées. Lorsqu'ils sont pressés dans des quartiers proches, ils peuvent encore compter sur leurs bras mécaniques écrasants, les rendant mortels à n'importe quelle distance.

Their arrival on Earth marked a turning point in the war: ils ne sont plus seulement des machines brutes, ils sont devenus une force d'invasion entièrement armée, terrifiant à la fois en puissance de feu et en résilience.

CONSEILS:

- Traitez-les comme des cibles hautement prioritaires - leurs grenades peuvent éliminer des groupes instantanément.
- Maintenez la couverture et utilisez des munitions lourdes pour briser leur armure.
- Leur fusil laser est précis : continuez de bouger pour réduire son efficacité.
