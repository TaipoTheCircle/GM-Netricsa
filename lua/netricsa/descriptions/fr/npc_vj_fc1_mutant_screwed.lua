MUTANT BERSERKER (CREWED) DE L'ARCHIPELAGO KRIEGER


CLASSE:      Mutant Berserker (à vis)
MÉTABOLISME: Mutation intermédiaire du trigène
PERCEPTION: Combattant inarrêtable
TAILLE:       8,1 pi
ENDURANCE:  Très élevé
HOSTILITÉ:  Absolu
ARMES: Lame osseuse (main droite)
RÉCOMPENSE:     1200 FC
MENACE:     Critique

DESCRIPTION:

Le Berserker est un lien évolutif entre les primates de Trigen et les mutants humains. De taille gigantesque, avec une lame osseuse massive remplaçant sa main droite et une cavité orale supplémentaire sur son visage. Il combine la fureur animale des petits Trigens avec le pouvoir destructeur des mutations tardives. Elle se dirige constamment vers sa cible, ignorant les obstacles.

Agit comme un bélier en vie. Au combat étroit, il provoque des frappes de lame dévastatrices, capables de détruire une cible en 2-3 coups. Sa taille repousse les ennemis, limitant leur maniabilité. Elle est vulnérable lors de sa balançoire.

CONSEILS:

- Cours et tire avant qu'il ne se rapproche.
- Dodge en zig-zag, pas en ligne droite.
