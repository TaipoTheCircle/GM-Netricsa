DELTA BASE ZOMBIE HEADCRAB DANS LA SUITE DANGER XEN, COMMUN


CLASSE:      Delta Base Zombie Headcrab Dans la combinaison de danger Xen, commune
MÉTABOLISME: Hôte humain + tête parasite de Xen
PERCEPTION: Entité zombifiée blindée
TAILLE:       6,2 pi
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    Griffes, Bite
RÉCOMPENSE:     600 FC
MENACE:     Très élevé

DESCRIPTION:

Ce spécimen est un ancien chercheur de la base Delta qui a été assez négligent pour se rendre à Xen ou travailler dans des environnements particulièrement dangereux portant la signature pourpre HAZARD SUIT. Sur le plan fonctionnel, elle est tout à fait identique à la H.E.V. de Black Mesa : scellement, amplification des impacts, radioprotection et autres délices du travail scientifique au bord de la réalité.

Même cela n'a pas sauvé certaines âmes malheureuses du crâne. Le parasite a trouvé un moyen de pénétrer le casque - ou peut-être l'hôte l'a enlevé à un moment critique - et a fait son sale travail. Maintenant la carcasse mobile dans le costume violet est un zombie, mais un zombie avec des avantages.

Le costume de protection lui donne un double avantage. D'abord, la survie. Les balles et les éclats sont absorbés par le tissu et les plaques renforcés de la combinaison. Deuxièmement, la force. Servos qui a aidé les scientifiques à soulever des équipements lourds amplifient maintenant les coups du zombie, les rendant dévastateurs.

Le costume pourpre est teinté de sang et de saleté, le casque est cassé ou manquant. Un coup de tête décapite la tête.

CONSEILS:

- Ce zombie a la plus haute armure de toutes les variétés standard. Un pistolet ordinaire est presque inutile.
- Visez la tête. Le costume protège le corps, mais pas la tête.
- Utilisez un fusil à bout portant ou une arme automatique à haut calibre.
- Un coup de tête détachera la tête, comme les autres.
- Tu ne peux pas enlever le costume et le remettre. Ça fait partie du monstre maintenant.
