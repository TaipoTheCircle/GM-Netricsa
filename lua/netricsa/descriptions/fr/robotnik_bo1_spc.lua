SPECTRE M4 SOUS-MACHINE


ARME: Spectre M4 pistolet sous-machine
MUNITIONS:   Parabellum 9x19mm
CADENCE DE TIR:    ~850 tours/min

DESCRIPTION:

Une mitrailleuse italienne développée par Roberto Teppa et Claudio Gritti en 1980. Il a été fabriqué par la société SITES à partir de 1984. Conçue pour le combat de quartiers rapprochés, l'arme possède une taille compacte, un stock repliable et un mécanisme de déclenchement unique.

Le Spectre M4 utilise une action de rappel et des feux d'un boulon fermé. L'une de ses caractéristiques principales est l'utilisation de magazines à quatre colonnes (quad-stack) d'une capacité de 30 ou 50 tours. Il comprend également une poignée pliante vers l'avant pour aider à manipuler l'arme.

REMARQUES:

- Le magazine de 50 tours est assez inhabituel pour un mitrailleur.
- Le stock se replie vers le haut, réduisant la longueur totale de l'arme à 350 mm.
- Le mécanisme de déclenchement permet de transporter l'arme en toute sécurité avec un tour dans la chambre.
- La production s'est poursuivie jusqu'en 2001, bien que l'usine italienne SITES ait fermé plus tôt.
