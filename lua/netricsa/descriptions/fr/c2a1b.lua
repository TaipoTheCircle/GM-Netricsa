MESA BLACK, ACID PIT ASCENT


Sam, afin de restaurer l'énergie du train de marchandises, vous devrez passer par l'une des sections les plus impitoyables de l'installation. Les niveaux inférieurs ont été complètement inondés de déchets toxiques, formant une fosse d'acide brillant qui mange à travers des grilles métalliques comme le papier. Une erreur, et vous allez vous dissoudre plus vite qu'un cube de sucre dans le café chaud.

La seule voie vers l'avant est un labyrinthe de passerelles étroites, de tuyaux rouillés et d'échelles de secours. Malheureusement, tu ne montes pas en paix. S.E.C.U. les soldats se sont déjà retranchés sur les niveaux supérieurs, en utilisant l'avantage vertical pour épingler n'importe quoi en bas.

Hazards:

Acid pit beneath you: mort instantanée si vous tombez.

Grenades et suppression des tirs des soldats en haut.