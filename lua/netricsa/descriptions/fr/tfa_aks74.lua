ROUGE DE KALASHNIKOV AKS-74 ASSAULT


ARME: Kalachnikov pliant AKS-74 Assault Rifle
MUNITIONS:   5,45x39mm
CADENCE DE TIR:    ~600-650 tours/min
POIDS: ~2,97 kg

DESCRIPTION:

Une version pliante du fusil d'assaut AK-74, spécialement conçu pour les troupes aéroportées et d'autres unités très mobiles. Il a été adopté en 1979. Contrairement à la norme AK-74, l'AKS-74 dispose d'un stock de métal pliant, ce qui facilite le transport et l'utilisation dans les espaces confinés.

Le fusil d'assaut utilise la cartouche de 5,45x39mm, a un chargeur de 30 tours, et est capable d'un seul tir et d'un feu automatique. Son taux de feu est d'environ 600-650 cartouches par minute. La plage d'efficacité est estimée à environ 300-400 mètres.

REMARQUES:

- Les parachutistes sont heureux.
- Conçu principalement pour les parachutistes et les unités hautement mobiles.
- Le matériel pliant facilite considérablement le transport du fusil d'assaut.
- La cartouche de 5,45x39mm fournit moins de recul que la chambre de 7,62x39mm de l'AKM.
