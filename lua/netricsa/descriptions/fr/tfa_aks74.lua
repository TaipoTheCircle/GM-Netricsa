FUSIL D'ASSAUT PLIANT KALASHNIKOV AKS-74


ARME : Folding Kalashnikov AKS-74 Assault Rifle
MUNITIONS : 5,45x39mm
ROF : ~600-650 rounds / min
POIDS : ~2,97 kg

DESCRIPTIF :

Une version pliable du fusil d'assaut AK-74, développée spécifiquement pour les troupes aéroportées et autres unités très mobiles. Il a été adopté en 1979. Contrairement à l'AK-74 standard, l'AKS-74 est doté d'une crosse métallique pliable, ce qui facilite son transport et son utilisation dans des espaces confinés.

The assault rifle uses the 5.45x39mm cartridge, has a 30-round magazine, and is capable of single-shot and automatic fire. Its rate of fire is approximately 600-650 rounds per minute. The effective range is estimated at approximately 300-400 meters.

