ROUTE, PATH À LA FENCE


Nous l'avons trouvé. Un endroit où le minimalisme est élevé à l'absolu, et le mot "design" a simplement été effacé du dictionnaire.

Avant nous est une ROUTE. Juste une route. Il s'étend tout droit, disparaissant dans l'horizon flou, et ne montrant aucun signe de tourner n'importe où.

De chaque côté, il y a une grosse FENCE. Grand, gris, impraticable.

Au début, il y a une clôture. Au bout, il y a une clôture. Sur les côtés se trouve une clôture. Le ciel est au-dessus. Ci-dessous est l'asphalte. Et toi.

Rien. Absolument rien. Pas de signes, pas de maisons, pas d'arbres, pas même une flaque perdue. Juste toi, la route, les clôtures, et la réalisation que tu es enfermé dans ce couloir pour toujours.

Si vous êtes déjà là, suivez la route. Lentement. Comptez vos pas. Tournez-vous et retournez-vous. Encore. Et encore. Peut-être qu'après mille passages, la clôture sera un peu plus proche ?
