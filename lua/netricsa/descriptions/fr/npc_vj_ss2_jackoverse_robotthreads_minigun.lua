ROBOT SÉRIEN, GUARD DU SIRIUS


CLASSE:      Robot Sirian, Garde
MÉTABOLISME: Mécanique, énergie
PERCEPTION: Unité d'assaut lourd, Plateforme de combat autonome
TAILLE:       9,85 pi
ENDURANCE:  Extrême
HOSTILITÉ:  Extrême
ARMES:    Deux mitrailleuses rotatives multi-barres de 7,62 mm M134
RÉCOMPENSE:     5000 FC
MENACE:     Absolu

DESCRIPTION:

Il s'agit d'une plate-forme de combat autonome de pointe, créée par des ingénieurs mentaux basés sur le robot Sirian Sentry standard. Contrairement aux gardes standard qui patrouillent les niveaux inférieurs de Siriuspolis et dispersent des intrus curieux, la Garde est construite pour la guerre. Une vraie guerre, où le but n'est pas d'effrayer, mais de détruire.

L'aspect du Gardien est approprié : un corps gris, mais au lieu de rouge, les parties vertes sont plus grandes, et les marches sont plus larges et plus massives. Au lieu d'un pistolet à caméra bleue, deux mitrailleuses multibarres de 7,62 mm M134 de Mental Electric sont montées de chaque côté de la tête, tirant jusqu'à 6 000 balles par minute. Chacun.

La tête est ovale, avec des yeux de capteur verts, une antenne et une crête de pics sur la couronne. Le cou est segmenté, presque comme un ressort, permettant à la tête de tourner à 360 degrés. Cependant, cela n'est plus nécessaire pour viser - les mitrailleuses sont déjà montées des deux côtés, donc simplement la rotation du corps est suffisante.

Le Gardien est largement utilisé en dehors de l'armée principale de Mental. Il est fourni aux alliés : l'Empire galactique, divers PMC, et même certains gouvernements planétaires qui peuvent se permettre un tel luxe. Le concept est basé sur le Terminator T-1, mais contrairement à ce tueur au métal liquide du futur, il est purement mécanique, sans une goutte de matière organique.

Ce n'est pas un chien de garde. C'est une machine pour le nettoyage total.

CONSEILS:

- N'attaque pas la tête.
- S'il commence à tirer, cache-toi derrière la couverture.
- Ne restez pas dans la ligne de feu.
