CHEMIN DE LOEK-III


CLASSE:      Marcheur
MÉTABOLISME: Une créature étrangère
PERCEPTION: Lume au sol
TAILLE:       ~5-6 pieds de haut
ENDURANCE:  Faible-moyenne
HOSTILITÉ:  Haut
ARMES:    Attaques de Melee 
RÉCOMPENSE:     300 FC
MENACE:     Moyenne

DESCRIPTION:

Le Walker est l'un des Lumes les plus communs. Ils viennent dans les hordes et poursuivent les Gardiens Core quand ils les repèrent. Individuellement, ils sont faibles et blindés mal, mais leur danger vient du nombre. Ces créatures frayent souvent dans de grands groupes, des défenses écrasantes par volume pur.

Les marcheurs n'ont pas de pouvoirs spéciaux ni d'attaques variées; ils marchent simplement en avant, balançant légèrement au fur et à mesure qu'ils se déplacent, essayant d'atteindre et de nuire au noyau. Leur point faible est une petite région rouge brillant sur leur devant, qui est plus difficile à frapper en raison de leur mouvement.

CONSEILS:

- Utilisez des tours de contrôle de foule ou des dégâts de zone pour réduire leur nombre.
- Ciblez le point faible rouge pour des meurtres plus rapides.
