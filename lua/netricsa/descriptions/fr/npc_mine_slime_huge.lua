SLIM DU MINECRAFT


CLASSE:      Slime énorme
PERCEPTION: Monstre slim
MÉTABOLISME: Organisme amorphe
TAILLE:       ~6,5 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Moyenne
ARMES:    Saut, crash
RÉCOMPENSE:     50 FC
MENACE:     Moyenne

DESCRIPTION:

L'Huge Slime est une créature amorphe et visqueuse qui semble n'avoir aucun sens de l'espace personnel. Il saute, se lance à tout ce qui vit, et parfois se divise en petits morceaux quand endommagé, créant des copies encore plus ennuyeux.

CONSEILS:

- Combattre de loin les plus grandes limaces.
- Les petites limaces ne posent aucune menace, mais dans un groupe elles peuvent causer le chaos.