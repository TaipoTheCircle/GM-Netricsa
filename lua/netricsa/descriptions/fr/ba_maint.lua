MESA BLACK, BREAKDOWNS DANS LE SECTEUR "C"


Vous êtes dans le secteur "C". Il y a un problème au panneau de commande. Un garde de sécurité et deux scientifiques essaient de réparer quelque chose. Les boutons ne répondent pas, les écrans clignotent, les fils fument. Le panneau est gravement cassé - quelqu'un a tiré les leviers non selon les instructions, quelqu'un était pressé.

L'odeur de l'ozone et l'isolation brûlée font mal au nez. Le sol tremble, et il y a ce froid, pas physique, qui rend mon dos teinté. Il est là.

L'homme en costume d'affaires est à proximité. Vous ne pouvez pas le voir, mais vous savez qu'il est là. Valise en main, souris comme une lame. Regarde. N'interfère pas. Il attend que le mécanisme se brise complètement.
