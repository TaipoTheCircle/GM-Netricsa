DÉPLACEMENT CANNON XV11382


ARME:      Déplacement du canon (projet XV11382)
MUNITIONS:        Cellules énergétiques dimensionnelles
CADENCE DE TIR:         ~1 shot/3 sec

DESCRIPTION:

Arme expérimentale de téléportation développée par Black Mesa avant l'incident à l'installation. Des explosions d'énergie concentrées qui peuvent déplacer des cibles vivantes et non vivantes sur de courtes distances. Le mode d'incendie alternatif téléporte l'utilisateur à un endroit aléatoire, permettant le repositionnement tactique ou l'évasion. Considéré comme très instable mais extrêmement polyvalent.

REMARQUES:

- Incendie primaire : téléporte des cibles à impact, causant des dommages importants.
- Autre feu : téléporte l'utilisateur à un point aléatoire sur la carte.
- Extrêmement puissant mais risqué; mauvais usage peut nuire à l'utilisateur.
- Disponibilité limitée; le projet est resté expérimental.
- Utilise un mini-réacteur d'uranium comme source d'énergie, semblable à Tau Cannon ou Gluon Gun.