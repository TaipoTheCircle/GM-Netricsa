ENGAGEMENT DE L'ÉQUIPEMENT DE MENDEL-GRUMAN


CLASSE:      Mendel-Gruman Armes lourdes Soldat
MÉTABOLISME: Humain, Homme
PERCEPTION: Infanterie lourde d'assaut
TAILLE:       6,2 pi
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
WEAPOON:    ORO cheval de guerre lourde rotative mitrailleuse
RÉCOMPENSE:     1000 FC
MENACE:     Très élevé

DESCRIPTION:

Des soldats lourds spécialisés de la société Mendel-Gruman, conçus pour détruire des cibles à haut risque et supprimer l'ennemi avec puissance de feu. Contrairement aux soldats réguliers du MG, qui opèrent en groupe avec des armes automatiques, ces combattants sont vraiment des équipages de mitrailleuses mobiles, qui, pour une raison quelconque, n'ont pas besoin d'un second homme.

Ils sont revêtus d'une lourde armure militaire vert terne. L'armure couvre la plupart du corps, a un col haut, poignets renforcés, et les cuisses blindées. Leurs visages sont complètement cachés derrière une visière gris brillant. Ils sont nettement plus lourds en apparence que les soldats standard Mendel-Gruman et appartiennent à la même catégorie lourde que Elite et Pyro.

L'arme principale de l'unité « ORO Warhorse » est une mitrailleuse rotative à six canaux. Il est capable de produire un flux de feu extrêmement dense à un taux élevé de feu. La mitrailleuse nécessite plusieurs instants pour faire tourner ses barils, après quoi elle transforme la ligne d'attaque en une zone plutôt désagréable pour tous les êtres vivants.

Par conséquent, l'éclatement d'un cheval de guerre peut créer une chaîne très méchante: plusieurs coups ralentissent la cible, après quoi les balles subséquentes commencent à atterrir encore plus facilement.

Malgré leur armure lourde, l'unité a une faiblesse notable : la tête. Un seul coup de feu à la tête peut immédiatement le détruire, de sorte que leur armure ne les rend pas invulnérables. Ils peuvent également survivre à un coup d'une flèche perforatrice partiellement tirée, soulignant leur protection nettement plus élevée que les soldats réguliers.

Au combat, les soldats d'armes lourdes sont généralement utilisés comme force de répression. Ils apparaissent relativement rarement, mais quand ils le font, leur tâche est simple : arrêter l'avancée de l'ennemi avec un barrage de feu. Quelques-uns de ces soldats peuvent littéralement transformer une zone ouverte en couloir de mitrailleuses.

CONSEILS:

- Ne vous exposez pas au feu de sa mitrailleuse. Le Warhorse inflige des dégâts énormes.
- Visez la tête. C'est leur principale vulnérabilité, malgré leur armure lourde.
- N'essayez pas de le tirer avec un fusil d'assaut. C'est un combat où un côté a clairement la mitrailleuse plus grande.
- Utilisez le couvercle et le flanc. Le soldat des armes lourdes est particulièrement dangereux là où il a la place pour tirer une longue explosion.
- Ne laissez pas plusieurs soldats d'armes lourdes concentrer le feu sur une seule cible. Leur puissance de feu devient beaucoup plus dangereuse quand ils attaquent ensemble.
- Si vous avez la possibilité d'utiliser des explosifs ou des armes puissantes, ne les gardez pas pour lui. C'est un de ces gars où le mot "lourd" devrait être pris littéralement.
