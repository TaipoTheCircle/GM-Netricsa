SOLDAT D'ARMES LOURDES MENDEL-GRUMAN


CLASSE : Soldat d'armes lourdes Mendel-Gruman
MÉTABOLISME : humain, masculin
PERCEPTION : Infanterie d'assaut lourd
TAILLE: 6,2 pieds
ENDURANCE : Très élevée
HOSTILITÉ : Extrême
ARME : ORO War Horse Mitrailleuse rotative lourde
RÉCOMPENSE : 1000 FC
MENACE : Très élevée

DESCRIPTIF :

Soldats lourds spécialisés de la société Mendel-Gruman, conçus pour détruire des cibles à haut risque et supprimer l'ennemi avec une puissance de feu. Contrairement aux soldats MG réguliers, qui opèrent en groupes équipés d'armes automatiques, ces combattants sont de véritables équipages de mitrailleuses mobiles qui, pour une raison quelconque, n'ont pas besoin d'un deuxième homme.

Ils sont vêtus d’une lourde armure militaire vert terne. L'armure couvre la majeure partie du corps, possède un col haut, des poignets renforcés et des cuisses blindées. Leurs visages sont complètement cachés derrière une visière gris-argent brillant. Ils sont visiblement plus lourds en apparence que les soldats Mendel-Gruman standard et appartiennent à la même catégorie lourde que l'Elite et le Pyro.

L'arme principale de l'unité "ORO Warhorse" est une mitrailleuse rotative de gros calibre à six canaux. Il est capable de délivrer un flux de tir extrêmement dense à une cadence de tir élevée. La mitrailleuse a besoin de quelques instants pour faire tourner ses canons, après quoi elle transforme la ligne d'attaque en une zone plutôt désagréable pour tous les êtres vivants.

Par conséquent, l'éclatement d'un Warhorse peut créer une chaîne très désagréable : plusieurs coups ralentissent la cible, après quoi les balles suivantes commencent à atterrir encore plus facilement.

Malgré son armure lourde, l'unité possède une faiblesse notable : la tête. Un seul coup bien ciblé dans la tête peut le détruire instantanément, donc leur armure ne les rend pas invulnérables. Ils peuvent également survivre à un tir d'une flèche perforatrice partiellement tirée, mettant en évidence leur protection nettement supérieure à celle des soldats ordinaires.

Au combat, les soldats armés d’armes lourdes sont généralement utilisés comme force de répression. Ils apparaissent relativement rarement, mais lorsqu'ils apparaissent, leur tâche est simple : stopper l'avancée de l'ennemi avec un barrage de tirs. Quelques-uns de ces soldats peuvent littéralement transformer une zone dégagée en couloir de mitrailleuses.

CONSEILS :

- Ne vous exposez pas à ses tirs de mitrailleuses. Le Warhorse inflige une énorme quantité de dégâts.
- Visez la tête. C'est leur principale vulnérabilité, malgré leur lourde armure.
- N'essayez pas de le surpasser avec un fusil d'assaut ordinaire. Il s’agit d’un combat dans lequel un camp possède clairement la plus grosse mitrailleuse.
- Utiliser le couvercle et le flanc. Le soldat aux armes lourdes est particulièrement dangereux là où il dispose de suffisamment d'espace pour tirer une longue rafale.
- Ne laissez pas plusieurs soldats d'armes lourdes concentrer leurs tirs sur une seule cible. Leur puissance de feu devient bien plus dangereuse lorsqu’ils attaquent ensemble.
- Si vous avez la possibilité d'utiliser des explosifs ou des armes puissantes, ne les réservez pas à ce type. Il fait partie de ces gars pour qui le mot « lourd » doit être pris au pied de la lettre.