ANNIHILATEUR DU CYBERSAN


CLASSE:      Réservoir d ' annihilateur
MÉTABOLISME: Mécanique
PERCEPTION: Armure lourde, démontage
TAILLE:       13 pieds
ENDURANCE:  Extrême
HOSTILITÉ:  Absolu
ARMES:    Cannon de bataille de pression terminale, Cycliste de fusion coaxial, Répéteur de fusion lourd à monture de coque
RÉCOMPENSE:     3000 FC
MENACE:     Absolu

DESCRIPTION:

C'est une forteresse en acier sur des pistes, que les Automatons ont copié sans vergogne à partir de modèles Super-Terre, mais, comme d'habitude, ils l'ont rendu pire. Le char est un véhicule de combat massif, lourdement armé, capable de détruire une équipe entière de Helldivers en quelques secondes. De l'avant, il semble presque invulnérable, mais comme tout véhicule, il a des points faibles.

The tank is armed with three types of weapons:

Le canon de combat à pression terminale est l'arme principale. Ce canon puissant est monté sur la tourelle et tire une fois toutes les 6 secondes. Il clignote rouge avant de tirer. Un coup direct tue un Helldiver instantanément.

Le Coaxial Fusion Cycler est une mitrailleuse bi-liée à fort taux de tir (1200 RPM). Il fait feu en 2,7 secondes, suivi d'un refroidissement de 1,5 seconde.

Le Hull-Monted Heavy Fusion Repeater est une mitrailleuse à tir avant intégrée dans la coque. Il tire plus lentement (400 RPM) et a un angle de tir limité.

The Annihilator Tank has several weak points that can be exploited for a quick kill:

Le moteur arrière, le radiateur de tourelle arrière et les pistes. (La destruction d'une voie immobilise le réservoir mais ne le détruit pas.) Il est également vulnérable au feu.

CONSEILS:

- En attaquant un char, approchez toujours de l'arrière ou du côté. Il est presque invulnérable de l'avant.
- Détruire les voies immobilise le réservoir mais ne le détruit pas. Utilisez ça si vous ne pouvez pas le tuer.
- Avant que le canon ne brûle, il clignote rouge. Dès que vous voyez le flash, prenez immédiatement la couverture ou plongez au sol.
- Le réservoir a une vitesse de traversée de tourelle lente. Utilise ça pour se mettre derrière le feu ennemi.
- Un réservoir détruit peut être utilisé comme couverture.
- Lorsqu'il est détruit, le réservoir explose dans un rayon de 8 mètres. Dégage.
- N'essayez pas de détruire un char avec un fusil standard. Tu vas gâcher tes munitions.
