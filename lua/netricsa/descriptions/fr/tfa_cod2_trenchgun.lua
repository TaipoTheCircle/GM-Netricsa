MODÈLE WINCHESTER 1897 POMMES D'ACTION


ARME: Winchester Modèle 1897 Pump-Action fusil de chasse
MUNITIONS:   12 calibres
CADENCE DE TIR:    ~60-70 tours/min
POIDS: ~3,6 kg

DESCRIPTION:

Le Winchester Model 1897, également connu sous le nom de M1897, est un fusil à pompe américain conçu par John Browning. Il a été produit de 1897 à 1957, avec plus d'un million d'unités produites pendant cette période. Le fusil est venu en plusieurs variantes, y compris la chasse, la police et les modèles militaires.

Le M1897 utilise un contre-bout et un magazine tubulaire. Le magazine standard tient cinq tours. Une caractéristique distinctive du design est l'absence d'un déconnecteur: en maintenant la détente vers le bas, les coups peuvent être tirés l'un après l'autre en utilisant l'avant-garde.

La version militaire du canon à tranchées comportait un canon de 20 pouces raccourci et était utilisée par les troupes américaines pendant la Première Guerre mondiale. Le Winchester M1897 fut par la suite servi pendant la Seconde Guerre mondiale, la guerre de Corée et la guerre du Vietnam.

REMARQUES:

- Particulièrement efficace à proximité, où la charge de tir permet une acquisition rapide de la cible.
- L'absence de déconnexion permet une répétition très rapide du feu tout en déplaçant la partie avant.
- La version Tranch Gun est devenue l'un des fusils de combat les plus célèbres et a acquis une large reconnaissance pour son utilisation dans la guerre des tranchées de la Première Guerre mondiale.
- Browning a créé un fusil à pompe, puis l'histoire a décidé de le tester dans presque toutes les guerres du 20ème siècle.
