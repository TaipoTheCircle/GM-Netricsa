FM 24/29 LUMIÈRE MACHINE GUN


ARME: Mitrailleuse FM 24/29
MUNITIONS:   7.5x54mm Français
CADENCE DE TIR:    ~450 cartouches / min, feu automatique

DESCRIPTION:

Une mitrailleuse légère française développée par le lieutenant-colonel Reibel avec l'aide du chef armurier Chassaud. Il a été créé au début des années 1920 à la Manufacture d'armes de Châtellerault* et adopté par l'armée française en 1925. Il a été conçu pour fournir aux escadrons d'infanterie un soutien-feu mobile. L'arme présente une configuration distinctive avec un chargeur haut de gamme, un stock en bois et un bipode.

Il fonctionne par l'intermédiaire d'un système actionné au gaz et des feux d'un boulon ouvert. Il utilise 7,5x54mm Des munitions françaises et un magazine de 25 tours. L'arme est équipée d'une poignée de pistolet, d'un bipode pliant et de vues en fer ouvert. Sa vitesse de feu modérée permet des éclatements contrôlés, fournissant un soutien efficace à une unité sur le champ de bataille.

REMARQUES:

- Adopté en 1925, il est resté au service de l'armée française jusqu'aux années 1960.
- Bien adapté pour supprimer les groupes d'infanterie et couvrir l'avance des forces amies.
- Efficace contre les cibles non armées à moyenne et longue distance.
- Capable de couvrir la lumière, mais pas conçu pour vaincre l'armure lourde.
- La vitesse du museau atteint environ 830 m/s.
- Il y avait une variante de la MAC 1931, montée en tank, avec un chargeur de tambour latéral d'une capacité de 150 tours.
