SKORPION SAMOPAL VZ. 61 SUBMACHINE GUN


ARME : Skorpion Samoral vz. 61 submachine gun
MUNITIONS : .32 ACP (7.65x17mm Browning SR), .380 ACP, and 9x19mm
ROF : 850 RPM
