LE MONDE FRONTIÈRE DE XEN, RETOUR


Bien sûr, Sam.

Les Houndeyes sont déjà là. Toujours là. Ils nous saluent comme si nous n'avions jamais quitté. C'est peut-être vrai.

Pour que le téléporteur fonctionne enfin comme prévu, nous devons activer le dispositif de contrôle de la téléportation. Où est-il ? Bonne question. La réponse, comme d'habitude, est dispersée à travers les plateformes et les restes de ceux qui ont déjà essayé. D'abord, trouvez-le. Alors activez-le. Alors j'espère que ça ne se rappelle pas comment ça s'est terminé la dernière fois.

Mais il y a une prise.

La horde de Mental prend déjà Xen.

Monde étranger, écosystème extraterrestre, règles extraterrestres. Et tout cela se transforme à nouveau en une halte. Mental, il semble, ne se soucie pas de la dimension qu'il brise, tant qu'il y a quelque chose à conquérir.

Donc le plan est simple.

Trouvez l'appareil.

Activez-le.

Survivre.