DELTA BASE ZOMBIE HEADCRAB, COMMUN


CLASSE:      Brouillard de la base Delta, commun
MÉTABOLISME: Hôte humain + tête parasite de Xen
PERCEPTION: Entité zombifiée, ancien scientifique
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Griffes, morsure, prise
RÉCOMPENSE:     200 FC
MENACE:     Modéré

DESCRIPTION:

C'est presque la même chose qu'un Zombie à tête commune, mais avec une différence importante : le corps de l'hôte appartient à un ancien scientifique qui travaillait à la base Delta classée dans le désert du Nevada. Au lieu des manteaux blancs de labo de leurs compétiteurs Black Mesa, ces gars portent des uniformes gris du personnel tatoués, déchirés, trempés dans du sang et de l'huile de machine.

The infection process is the same: a Le crâne s'enfonce dans le crâne, laissant un visage humain partiellement visible sous la coquille extraterrestre.

Ils sont tout aussi lents que leurs homologues blancs, et tout aussi implacables. Si un tel zombie repère une personne vivante, il les poursuivra jusqu'à ce qu'il ferme la distance.

Un coup de tête tue la tête d'un zombie.

CONSEILS:

- Gardez vos distances. Ils sont lents, mais s'ils se rapprochent, leurs griffes et leurs dents feront le tour.
- Les armes à feu sont efficaces. Ne gaspillez pas les munitions au combat.
- Un tir tue la tête d'un zombie.
- Ils sont dangereux en groupe. Un zombie n'est pas un problème. Trois personnes t'entourent déjà.
