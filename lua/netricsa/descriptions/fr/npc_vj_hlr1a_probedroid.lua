DROID BLACK MESA PROBE


CLASSE:      Droïde de sonde Mesa noir
MÉTABOLISME: noyau alimenté
PERCEPTION: Drone synthétique
TAILLE:       4 pieds
ENDURANCE:  moyenne
HOSTILITÉ:  modérée
ARMES:    faisceau de guérison (alliés), lanceur de fléchettes (ennemis), explosion d'autodestruction
RÉCOMPENSE:     600 FC
MENACE:     moyenne-élevée

DESCRIPTION:

Développé par Black Mesa en tant que drone de soutien polyvalent, le Probe Droid est une machine de vol stationnaire conçue pour aider les unités de combat sur le terrain. Sa fonction principale est de rechercher des formes de vie alliées et de les réparer ou de les stabiliser à l'aide d'un faisceau de guérison dirigé. Cependant, sa programmation comprend aussi des protocoles offensifs : lorsque des ennemis sont détectés, le droïde lance des fléchettes tranchantes, recouvertes de toxines qui peuvent percer l'armure légère. Au moment de la destruction, son noyau de puissance instable détone, envoyant une violente explosion, faisant de la perte d'un droïde une attaque finale contre les ennemis.

CONSEILS:

- Gardez votre distance - l'explosion d'autodestruction est mortelle dans les quartiers proches.
