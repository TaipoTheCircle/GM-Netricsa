PROTO-PANTHEREYE DE XEN


CLASSE:      Proto-Panthereye
MÉTABOLISME: Hybridation incomplète de l'ADN de la bête Xen
PERCEPTION: Predator Xen
TAILLE:       ~4 pieds de haut
ENDURANCE:  Faible
HOSTILITÉ:  Modéré
ARMES:    Morsure de fuite, coups de griffe de base, décharge d'énergie limitée 
RÉCOMPENSE:     500 FC
MENACE:     Modéré

DESCRIPTION:

L'Alpha Panthereye précoce représente une version prototype instable de l'espèce Panthereye, observée au cours de ses stades évolutifs de formation. Contrairement au Panthereye entièrement développé, cette sous-espèce manque de musculature raffinée, sa peau semble inégale.

Son corps est plus maigre et moins blindé, avec des pousses osseuses déchiquetées qui dépassent ses membres - preuve d'une stabilité génétique incomplète. Bien qu'il soit plus petit que ses homologues ultérieurs, l'Alpha Panthereye précoce est encore dangereux, s'appuyant sur des poumons sauvages et des attaques frénétiques pour submerger les proies.

On croit que des spécimens de ce genre ont été des expériences précoces de l'écosystème adaptatif de Xen, pouvant précéder la lignée de Panthereye perfectionnée. Certains chercheurs théorisent que des hybrides instables comme celui-ci ont ouvert la voie à des monstruosités plus avancées.

CONSEILS:

- Moins durable qu'un Panthereye complet, mais plus rapide et plus erratique.
