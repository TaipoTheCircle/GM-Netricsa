CUBBIE DE L'ENSEIGNEMENT DU PAPIER FONDAMENTAL


CLASSE:      Cubby
MÉTABOLISME: Organisme en papier, construction hybride
PERCEPTION: Apprentis de chat anthropomorphe
TAILLE:       4 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Aucune
ARMES:    Aucune
RÉCOMPENSE:     1 FC
MENACE:     Aucune

DESCRIPTION:

Cubby est un chat noir anthropomorphe dont le corps est un grand tailleur de crayons. Sa queue est un rasage long, courbé, et sa tête plane au-dessus de son "torso", sur lequel repose un livre ouvert. Il a de grands yeux expressifs. Sur le plan de la personnalité, il est un nerd typique : amical mais préfère garder un profil bas, immergé dans ses études ou ses propres pensées. Il a souvent trouvé avec son ami Kevin. Il ne participe pas aux conflits, préférant rester observateur. Comme toutes les créatures de papier, il est extrêmement vulnérable aux dommages physiques.

CONSEILS:

- Pas une menace.
- Son design unique (un tailleur de crayon au lieu d'un corps) en fait l'un des personnages les plus mémorables, symbolisant la nature créative et excentrique de Paper School.