T-REX, JUVENILE DE LA PLANTE TERRAFORME


CLASSE:      T-Rex, juvénile
MÉTABOLISME: Prédateur chaud
PERCEPTION: Prédateur Apex
TAILLE:       8,2 pi
ENDURANCE:  Haut
HOSTILITÉ:  Extrêmement élevé
ARMES:    Fangs, griffes, vitesse
RÉCOMPENSE:     800 FC
MENACE:     Haut

DESCRIPTION:

C'est la version adolescente du roi même des dinosaures que tout le monde craint. Il n'a pas encore atteint neuf mètres et huit tonnes, mais il est déjà assez capable de réduire un adulte à une tache sanglante sur le trottoir en quelques secondes.

Sur le plan de l'apparence, l'adolescent est très différent du prédateur adulte. Il est plus maigre, plus long et plus lent. Ses membres postérieurs sont longs, lui permettant d'atteindre une vitesse décente et de changer de direction rapidement.

Leurs mâchoires sont déjà puissantes, mais leurs dents ne sont pas encore celles des adultes.

les jeunes tyrannoses vivent dans la même jungle que les adultes. Mais contrairement aux spécimens matures, qui préfèrent les embuscades et les sprints courts, les juvéniles sont actifs et agressifs. Ils peuvent poursuivre leur proie pendant de longues périodes, en utilisant leur vitesse et leur endurance.

Dans une lutte, un tyrannosaur juvénile est dangereux précisément en raison de sa mobilité. Il ne restera pas immobile, il fléchira, mordra, claquera avec sa queue, et tentera d'attraper avec ses avant-bras.

CONSEILS:

- Ils sont rarement vus seuls. Si vous en voyez un, cela signifie que leur mère est à proximité. Et tu ne veux pas rencontrer leur mère.
