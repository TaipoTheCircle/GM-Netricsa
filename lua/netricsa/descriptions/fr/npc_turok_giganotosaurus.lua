GIGANOTOSAURUS DE LA PLANTE TERRAFORME


CLASSE:      Giganotosaurus
MÉTABOLISME: Carnivore, Théropode
PERCEPTION: Prédateur Apex
TAILLE:       23 pieds
ENDURANCE:  Extrême
HOSTILITÉ:  Absolu
ARMES:    Tête de cul, frappe de queue, mâchoires
RÉCOMPENSE:     7000 FC
MENACE:     Absolu

DESCRIPTION:

L'un des plus grands prédateurs terrestres à avoir jamais vécu sur la planète, dépassant même le célèbre Tyrannosaurus de taille. Il se trouve dans la Vallée de la Mort.

En apparence, le Giganotosaurus est un corps brun massif avec un crâne étroit, des crêtes au-dessus des yeux et des rayures le long de la colonne vertébrale.

Le Giganotosaurus utilise les mêmes techniques que les autres grands prédateurs.

CONSEILS:

- N'essayez pas de vous battre.
- Très dangereux.
