GRANDE ANGEL, CHET FALISEK


CLASSE:      Big-Head Angel, Chet Falisek
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:    Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     100 FC
MENACE:     Annoyance

DESCRIPTION:

Les grandes têtes sont des humanoïdes maigres avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme de Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan" ils gagnent le feu et les modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Chet Falisek est le co-fondateur du site satirique Old Man Murray (OMM), qu'il a co-créé avec Eric. Ensemble, ils donnent le ton au journalisme de jeu avec leur langage aigu, cynique et incroyablement drôle. Chet fait partie d'un duo que Croteam juge digne de l'immortalité comme des fans secrets avec des crânes gonflés. Alors qu'Eric était souvent en première ligne, c'est leur collaboration qui a créé la voix unique qui a tellement amusé et inspiré les développeurs. Sa présence dans le jeu est un hommage au journaliste.

Quand vous l'avez tué dans les cours sacrées, il s'est transformé en ange.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager un chemin. - Sur la difficulté "Je suis Ugh-Zan", les détruire à distance en raison de leurs modificateurs.
- Dans un groupe, un marteau avec une frappe horizontale est efficace.
