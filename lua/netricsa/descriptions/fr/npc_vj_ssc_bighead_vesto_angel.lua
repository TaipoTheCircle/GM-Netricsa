GRANDE ANGEL, VESTO


CLASSE:      Big-Head Angel, Vesto
MÉTABOLISME: Humanoïde, Homme
PERCEPTION: Fanatique enthousiaste
TAILLE:       5,9 pieds
ENDURANCE:    Faible
HOSTILITÉ:  Neutre
ARMES:    Aucune (sauf sur I Am Ugh-Zan difficulté)
RÉCOMPENSE:     100 FC
MENACE:     Annoyance

DESCRIPTION:

Les grandes têtes sont de minces humanoïdes avec des crânes exagérés contenant les cerveaux des développeurs de Croteam. Ils portent l'uniforme de Serious Sam, mais ont les caractéristiques faciales uniques de l'équipe de développement. Ils montrent un enthousiasme obsessionnel, vous poursuivant avec des cris de "Bonjour!" et "Hé, attendez!" Ils sont complètement inoffensifs, mais dans la difficulté "Je suis Ugh-Zan" ils gagnent le feu et les modificateurs de glace. Ils apparaissent spontanément dans les zones secrètes, bloquant les passages avec leur nombre.

Vesto est l'une des figures les plus énigmatiques et pures des crédits de Croteam. Contrairement à "Wassboy", dont le rôle est clairement défini, Vesto reste simplement un nom, écrit succinctement dans la catégorie Moral Boost. Son crâne surdimensionné est un vase de soutien silencieux mais puissant. Peut-être était-il cet ami qui a apporté du café à trois heures du matin, ou le collègue dont la confiance inébranlable dans le succès du projet était infectieuse.

Sa présence dans les crédits est un rappel que le moral de l'équipe est construit sur des dizaines de contributions grandes et petites, dont beaucoup ne peuvent pas être mesurées. Vesto est un symbole de tous ceux qui n'ont pas écrit de code ou de modèles de sculpture, mais dont la foi, la patience, ou la gentillesse humaine simple est devenue le fondement invisible sur lequel le monde fou et beau de Serious Sam a grandi.

Il était une fois vivant, mais après que quelqu'un l'ait tué, il a été ressuscité - devenir un ange.

CONSEILS:

- Utilisez un couteau de combat ou un pistolet pour dégager le chemin.
- Sur la difficulté "Je suis Ugh-Zan", les détruire à distance en raison de leurs modificateurs.
- Un lugehammer avec une frappe horizontale est efficace dans un groupe.
