BRONZE BUG DE ZENOZOIK


CLASSE:      Bug en bronze
MÉTABOLISME: Insecte, xénomorphe géant
PERCEPTION: Bug prédatoire forestier
TAILLE:       1,9 ft
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Des mandibules puissants, longs et courbés capables de couper la chair
RÉCOMPENSE:     80 FC
MENACE:     Haut

DESCRIPTION:

Un Bug géant sauvage, ressemblant à un Bug en bronze terrestre, mais significativement plus grand et plus agressif que son cousin. Il a une carapace chitineuse brun foncé ou bleu violet, une paire d'ailes transparentes, de longues jambes fines, et est recouvert de poils fins sur sa tête. Leur principal trait distinctif est leur énorme mandibule, saillante et excitée, capable de trancher facilement les proies. Leur habitat indigène est la forêt où vivent les Corvides, mais ces Bugs sont capables de migrer vers d'autres endroits, y compris les déserts. Ils montrent une agression sélective inexplicable, attaquant exclusivement Geth et ignorant toutes les autres créatures. Ce ne sont pas des animaux de compagnie entraînés. Ils agissent toujours en meute, en coordonnant les attaques aériennes.

CONSEILS:

- Un filet régulier ne marchera pas; prenez une arme et tirez sur eux; ils sont plus maniables en vol.
- Ils attaquent toujours en meute; essayez de toujours s'éloigner d'eux et de les éviter.
