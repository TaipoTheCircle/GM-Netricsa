MESA BLACK, SECTEUR ECHO


Encore une fois, l'homme avec la mallette est ici - silencieux, intouchable, regardant depuis un pont au-dessus. C'est ton plus grand fan... ou ton pire recruteur de RH.

This sector feels eerily familiar: corridors, laboratoires, machines - comme si Black Mesa avait copié et collé ses propres plans pour gagner du temps et de l'argent. Mais ne vous détendez pas trop. Certaines chambres sont différentes. Des angles qui ne correspondent pas. Des machines que vous n'avez pas vues. De nouveaux pièges dans un vieux labyrinthe.

Pensez-y comme déjà vu... seulement avec une chance légèrement plus élevée de mort.

Et il y a un problème: pour atteindre les bureaux - tant pour vous que pour cet autre Sam - le pouvoir doit être rétabli. Quelque part dans ce labyrinthe cache un levier qui contrôle l'électricité du secteur. Trouvez-le ou vous êtes coincés.

One more complication: a Panthereye rôde la zone. Il mange tout le monde