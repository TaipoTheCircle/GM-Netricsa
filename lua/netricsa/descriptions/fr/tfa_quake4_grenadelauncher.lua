GRENADE LAUNCHER


ARME: Lanceur de grenade
MUNITIONS:   Grenades
CADENCE DE TIR:    ~20 grenades/min


DESCRIPTION:

Le Lanceur de Grenade tire des grenades chronométrées ou d'impact qui détonent après avoir été lancé. Il donne de fortes zones d'effet endommagées, ce qui le rend idéal pour effacer les groupes ou détruire le couvert. Avec une visée précise, les grenades peuvent être lobées sur ou autour des obstacles.

REMARQUES:

- Les explosions peuvent blesser l'utilisateur si elles sont utilisées trop près.
- Efficace contre les amas et pour briser les barrières.
- L'utilisation du rebond et des angles est avantageuse dans les combats.
- Faites attention dans les zones confinées à cause des dommages causés par les éclaboussures.