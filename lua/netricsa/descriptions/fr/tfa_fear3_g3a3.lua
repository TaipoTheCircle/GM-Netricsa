RAKOW G3A3, FUSIL D'ASSAUT


ARME:           Rakow G3A3, fusil d'assaut  
MUNITIONS:      OTAN 7,62 x 51 mm  
CADENCE DE TIR: Rafales de 3 coups

DESCRIPTION:

Un fusil d'assaut moderne utilisé par les soldats de la société Armacham. Il est équipé d'une lunette optique à faible grossissement, offrant une grande précision lors des engagements à moyenne et longue portée.

Contrairement à la plupart des fusils automatiques, le G3A3 tire exclusivement par rafales de trois coups. Son chargeur contient 24 cartouches, soit huit rafales. Grâce à sa grande précision et à sa puissance, cette arme est efficace contre les adversaires lourdement protégés. Cependant, la faible capacité de son chargeur et sa maniabilité peu pratique lors du tir au jugé limitent son efficacité dans les combats rapprochés.

REMARQUES:

- À ne pas confondre avec le fusil allemand Heckler & Koch G3A3.
- Le boîtier porte une indication de calibre de 7,62 mm, bien que le type exact de munitions n'ait pas été officiellement confirmé.
- Trois coups par pression sur la détente, ce qui favorise l'économie de munitions.
- Avec une bonne précision, cette arme peut remplacer un fusil de précision à moyenne portée.
