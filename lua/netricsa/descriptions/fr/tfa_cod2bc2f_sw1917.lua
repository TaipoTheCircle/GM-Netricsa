MODÈLE SMITH & WESSON 1917 REVOLVER


ARME: Smith & Wesson Modèle 1917 Revolver
MUNITIONS:   45 ACP
CADENCE DE TIR:    ~40 tours/min
POIDS: ~1,1 kg

DESCRIPTION:

Ce revolver militaire américain a été développé pendant la Première Guerre mondiale en raison d'une pénurie de pistolets autochargeurs standard. Il a été adopté par l'armée américaine en 1917 et a été fabriqué par Smith & Wesson et Colt.

Le revolver utilise la puissante cartouche ACP .45 et dispose d'un cylindre à six tours. Étant donné que le .45 ACP était initialement destiné à des pistolets à chargement automatique, des clips semi-circulaires spéciaux ont été utilisés pour contenir trois cartouches, permettant le chargement et l'extraction simultanés.

Le modèle 1917 se distingue par sa grande conception robuste, sa bonne puissance d'arrêt et sa fiabilité relativement élevée. Après la Première Guerre mondiale, ces revolvers ont continué d'être utilisés par les soldats américains et la police, et certains sont restés en demande pendant de nombreuses années.

REMARQUES:

- Le puissant .45 ACP le rend bien adapté pour une prise de vue précise à proximité et à moyenne portée.
- La grande cartouche fournit une puissance d'arrêt élevée malgré son taux de feu relativement faible.
- L'utilisation de clips semi-circulaires permet un chargement rapide de trois tours à la fois.
