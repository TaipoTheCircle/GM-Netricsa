LE GOLEM DE NOW DU MINECRAFT


CLASSE:       Golem des neiges
PERCEPTION:  Gardien / défenseur contre les foules hostiles
MÉTABOLISME:  Pompe à neige
TAILLE:        5,9 pieds
ENDURANCE:   Faible
HOSTILITÉ:   Faible
ARMES:     Boules de neige
RÉCOMPENSE:      100 FC
MENACE:      Faible

DESCRIPTION:

Le Snow Golem est une mafia passive, construite par un joueur ou un dispensaire en plaçant deux blocs de neige avec une citrouille sculptée sur le dessus. Il lance des boules de neige sur des groupes hostiles à proximité, les attirant et les repoussant, mais les boules de neige causent rarement des dommages directs, à l'exception de Blazes.

Le Snow Golem n'attaquera pas les alliés, mais il réagit calmement à l'agression d'autres créatures, les poussant avec des boules de neige de jusqu'à 10 pâtés de maisons. En se déplaçant, il laisse une trace de couches de neige si le climat et les règles du monde le permettent. Il est également vulnérable dans les biomes humides ou chauds-l'eau, la pluie, et les températures élevées endommageront ou le tueront lentement.

Si vous coupez sa citrouille "tête", elle déposera la citrouille, révélant son visage en dessous.

CONSEILS:

- Le Golem de Neige est excellent comme un garde distrayant, surtout lorsqu'il est combiné avec les Golems de Fer.
- La neige qu'il laisse derrière peut être utilisée pour créer une ferme à neige.
- Gardez à l'esprit qu'il fond dans les biomes chauds, le rendant moins adapté pour la défense là-bas.