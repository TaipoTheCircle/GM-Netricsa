SOLDAT MENDEL-GRUMAN GRUNT AVEC FUSIL DE CHASSE


CLASSE : Soldat Grunt Mendel-Gruman
MÉTABOLISME : humain, masculin
PERCEPTION : infanterie standard, assaut au corps à corps
TAILLE : ~5,9 pieds
ENDURANCE : Moyenne
HOSTILITÉ : Élevée
ARMES : Fusil à pompe ORO "Enforcer", Grenades à fragmentation
RÉCOMPENSE : 250 FC
MENACE : Moyenne

DESCRIPTIF :

Ce Grunt est une variante spécialisée du soldat de société standard. Extérieurement, il est pratiquement impossible à distinguer du Grunt standard : la même armure de protection, le même casque avec une visière dynamique et le même équipement standard. La différence réside dans l'arme, car au lieu d'une arme légère standard, ce soldat reçoit l'Enforcer ORO.

L'Enforcer est conçu pour le combat rapproché et transforme ce Grunt en un dangereux soldat d'assaut. Contrairement à un soldat standard, qui s'épanouit à moyenne portée, un fusil de chasse nécessite de se rapprocher de l'ennemi, après quoi une seule volée bien placée peut causer de sérieux dégâts.

Pour cette raison, les tireurs de chasse ont tendance à être un peu plus agressifs que les autres Grunts. Ils tentent de réduire la distance, de couvrir les flancs et de forcer l'ennemi à se battre au corps à corps. Dans les couloirs étroits, les pièces et autres espaces confinés, ce soldat est particulièrement dangereux : la distance à laquelle un Grunt standard perd progressivement son efficacité devient une zone de mort idéale pour lui.

Cependant, le carabinier lui-même n'a pas de durabilité accrue. Son armure reste pratiquement la même que celle d'un Grunt standard, il ne devient donc pas un combattant lourd simplement parce qu'il possède un fusil de chasse. Mendel-Gruman a simplement pris un soldat régulier, lui a donné une arme qui disait : « Rapprochez-vous et tirez bien », et l'a envoyé chercher des ennuis.

Les fusils de chasse sont particulièrement efficaces dans les unités conventionnelles. Alors que certains soldats tirent à distance et forcent l'ennemi à se cacher à couvert, un carabinier équipé d'un Enforcer peut tenter de flanquer l'ennemi et d'attaquer à bout portant.

Comme les autres Mendel-Gruman Grunt, il utilise une visière dynamique. Le bleu indique un fonctionnement normal, le jaune indique une vigilance accrue et le rouge indique une préparation totale au combat.

CONSEILS :

- Ne le laissez pas s'approcher. Plus la distance est proche, plus l'Enforcer est dangereux.
- Dans les espaces ouverts, il est moins efficace qu'un carabinier ordinaire équipé d'une arme automatique.
- Surveillez vos flancs. Le fusil de chasse est particulièrement dangereux lorsqu'un soldat tente de se mettre à couvert. Les grenades sont efficaces contre les groupes, surtout si le tireur se trouve parmi plusieurs soldats réguliers.
- Si la visière devient rouge, le Grunt a déjà détecté une menace et est prêt à ouvrir le feu. Il est préférable de ne pas vérifier à quel point il veut se rapprocher.