TULA TOKAREV PISTOL MODEL 1933


ARME:    Tula Tokarev Pistol Modèle 1933
MUNITIONS:      7.62x25mm TT
CADENCE DE TIR:       ~30-40 tours/min.
POIDS:    ~0,85 kg.

DESCRIPTION:

Un pistolet soviétique à chargement automatique conçu par Fyodor Tokarev et adopté dans les années 1930. Il a été créé pour remplacer les revolvers périmés et les pistolets étrangers en service dans l'Armée rouge.

Le pistolet utilise une action de court-recoil avec verrouillage en baril incliné. La conception est relativement simple et facile à fabriquer, et la cartouche de 7,62x25mm a une vitesse de museau élevée.

Le TT est conçu principalement pour le combat à proximité. Le poids léger et la puissance relativement élevée des cartouches permettent un suivi rapide, et le design simple est bien adapté pour une utilisation militaire de masse. La portée efficace est d'environ 50 mètres.

REMARQUES:

- Particulièrement efficace à proximité, où la grande vitesse de la balle permet un engagement rapide de la cible.
- Le cadre léger et la cartouche puissante font du TT une arme assez nette et rapide dans les mains d'un tireur expérimenté.
- La simplicité de la conception était l'un des principaux avantages du pistolet, en particulier dans le contexte de la production militaire de masse.
