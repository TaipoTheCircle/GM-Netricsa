NEST HORNET DES XEN


CLASSE:      Nid Hornet
MÉTABOLISME: Xen Organisme biologique
PERCEPTION: Spawner stationnaire, tourelle biologique
TAILLE:       6,5 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Absolu
ARMES:    Hornets
RÉCOMPENSE:     150 FC
MENACE:     Haut

DESCRIPTION:

C'est une énorme croissance organique trouvée sur les murs, les planchers et les plafonds (et probablement dans d'autres endroits où les créatures de Xen ont atteint). Ça ressemble à un cône. À l'intérieur de cette croissance, de petites mais extrêmement méchantes créatures -Hornets - chaud.

Le mécanisme du nid est simple et terrifiant. Dès qu'une cible vivante approche du nid, elle s'active. L'un d'eux sort de la croissance et vole droit sur la cible.

Un Suicide Hornet ne vit que tant qu'il faut pour lancer une seule attaque. Il meurt après une attaque, mais le Nest en produit un nombre illimité. Une seconde après la destruction d'un Hornet, un autre vole hors du nid. Cela continue à l'infini, jusqu'à ce que le nid soit détruit ou que la cible quitte la zone de destruction.

CONSEILS:

- Détruisez le nid à distance. Les explosifs ou les armes lourdes sont vos meilleurs amis.
- Ne vous approchez pas trop du Nid. Les Hornets s'envolent avec un léger retard, mais si vous êtes dans la zone de mort, ils sont difficiles à éviter.
- Un seul Hornet est faible, mais le flux sans fin est épuisant. Tuez le Nest, et le problème disparaît.
- Lorsqu'il est détruit, le nid se désintègre en morceaux de chair, libérant parfois un nuage d'acide.
- Le Nid ne bouge pas. C'est un piège stationnaire, mais très efficace.
