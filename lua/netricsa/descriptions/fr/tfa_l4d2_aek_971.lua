AEK-971 RISQUE D'ASSAULT


ARME: AEK-971 Rifle d'assaut
MUNITIONS:   5,45x39 mm
CADENCE DE TIR:    ~900 tours/min

DESCRIPTION:

Un fusil d'assaut soviétique développé en 1978 à l'usine mécanique de Kovrov sous la direction du concepteur Stanislav Koksharov. Il a été créé pour les essais "Abakan" comme un remplacement potentiel pour la famille Kalachnikov de fusils. Il dispose d'une disposition traditionnelle et utilise une action automatique équilibrée conçue pour réduire le recul et améliorer la précision du tir.

Le fusil fonctionne selon un principe de piston à gaz avec un boulon rotatif. Sa principale caractéristique de conception est un balancier supplémentaire qui se déplace dans la direction opposée au groupe de boulons. Il est alimenté par des magazines 30-round standard et offre trois modes de tir: semi-automatique, entièrement automatique, et une explosion de trois-round.

REMARQUES:

- Conçu par Stanislav Koksharov.
- A participé au procès soviétique "Abakan", où il a perdu le fusil d'assaut AN-94.
- L'action automatique équilibrée réduit la montée du museau pendant le tir.
- L'exactitude pendant l'éclatement est 1,5 à 2 fois meilleure que celle de l'AK-74M.
- Les variantes comprennent l'AEK-972 (chambrée pour 5,56x45mm OTAN) et l'AEK-973 (chambrée pour 7,62x39mm).
