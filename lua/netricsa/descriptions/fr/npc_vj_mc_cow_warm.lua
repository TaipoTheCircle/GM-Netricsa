COUVERTURE DE L'EXTERIEUR MINECRAFT


CLASSE:      Vache rouge chaude
MÉTABOLISME: Mammifère à sang chaud
PERCEPTION: Animaux sauvages / domestiques
TAILLE:       5,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Faible
ARMES:    Aucune
RÉCOMPENSE:     50 FC
MENACE:     Faible

DESCRIPTION:

Cette vache chaude habite des biomes-savannes chaudes, des basses terres et des plaines vallonnées. Il se distingue par sa coloration rouge vif sans taches.

Un trait distinctif de cette espèce est le manque de taches et de cornes en forme de L debout sur sa tête, donnant à la vache une apparence fière et légèrement sauvage.

Les vaches rouges et rouges paissent en groupes, se nourrissent d'herbe et de feuilles, ont un tempérament calme et sont bien adaptées aux climats chauds.

CONSEILS:

- La traite est sans danger et produit du lait.
- La viande de vache rouge est nutritive, satiété et santé.
- Ils sont excellents pour garder en paddocks dans des biomes chauds - ils sont résistants à la chaleur et paissent bien.
