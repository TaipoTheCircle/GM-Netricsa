MÉDICAMENT DU REBEL


CLASSE:      Rebel Medic
MÉTABOLISME: Humain
PERCEPTION: Résistance Médicale
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
WEAPONALS:  Pistol, SMG, trousses de premiers soins
RÉCOMPENSE:     250 FC
MENACE:     Faible

DESCRIPTION:

Rebel Medics sont des résistants qui ont décidé que la survie de l'équipe est plus importante que leur compte de meurtre personnel. Ils apparaissent là où la bataille a déjà mal tourné et font tout pour changer ce plan. Leur arme principale est un kit de premiers secours, mais si nécessaire, ils peuvent fournir un feu de couverture pour eux-mêmes et les blessés.

Contrairement aux soldats réguliers, les médecins ont tendance à rester légèrement derrière la ligne de tir, se déplaçant constamment parmi leurs alliés et évaluant qui peut encore se battre et qui doit être ramené d'urgence dans le pli. Leur entraînement est limité, mais leur pratique est sans fin : chaque bataille est une nouvelle leçon d'anatomie sous le feu.

Bien qu'ils ne soient pas conçus pour des attaques directes, la présence d'un médecin augmente considérablement la survie de l'équipe. Les soldats de la résistance se battent avec une plus grande confiance en sachant qu'il y a quelqu'un à proximité qui peut les remettre sur pied même après un gros coup.

CONSEILS:

- Protégez-les : la perte d'un médecin réduit considérablement l'efficacité de combat du groupe.
- Un médecin sous le feu est un signe que le combat traîne.
