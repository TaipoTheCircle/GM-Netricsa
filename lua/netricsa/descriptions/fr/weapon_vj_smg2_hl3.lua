GUN DE SOUS-MACHINE SMG2 (MP7)


ARME: GUN DE SOUS-MACHINE SMG2 (MP7)
MUNITIONS:   4,6×30mm.
RR:     ~900 RPM
POIDS: 2,0 kg.

DESCRIPTION:

Le SMG2 est le pistolet sous-machine standard pour les unités d'assaut, utilisé dans les premiers stades des conflits d'unification. Conçu pour la suppression rapide des ennemis dans les zones densément peuplées et à bord des centres de transport.

Le taux élevé de feu assure un feu concentré et dissuade efficacement les forces numériquement supérieures. L'arme est conçue pour le combat mobile et de fréquents changements de position, la plage de sacrifice pour le contrôle à proximité.

REMARQUES:

- Optimisé pour les couloirs de combat et de dégagement à proximité
- Efficace pour supprimer les effectifs ennemis
- Grande capacité de munitions en fait une arme de soutien fiable
- Une précision légèrement inférieure à longue portée par rapport aux armes à longue portée