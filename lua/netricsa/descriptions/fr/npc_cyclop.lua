CYCLOPS POLYPHEMUS


CLASSE:      Polyphème des cyclopes
MÉTABOLISME: Géant, Homme
PERCEPTION: Savage Créature cannibale
TAILLE:       14,7 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    Fists, Grasp, Dents
RÉCOMPENSE:     1500 FC
MENACE:     Très élevé

DESCRIPTION:

Un énorme, brutal, cyclopes à un œil et des cannibales extrêmement dangereux qui ont capturé et dévoré les humains. Cette créature massive possède une force physique monstrueuse et est capable d'envoyer sans effort des adversaires ordinaires dans un combat rapproché.

Polyphème n'a pratiquement aucune distinction entre "ennemi" et "prey". Toute créature vivante à proximité peut attirer son attention. Il peut attraper un adversaire et tenter de les dévorer sur place, ce qui rend extrêmement dangereux d'approcher un cyclope.

Son œil unique offre une excellente vision, mais le principal avantage de Polyphemus reste sa taille et sa force physique.

Après avoir subi de graves dommages, il peut brusquement se précipiter sur son adversaire, rugissant fort et essayant de fermer la distance le plus rapidement possible.

Le polyphème est particulièrement dangereux dans les espaces restreints. Sa taille énorme peut entraver sa manœuvre, mais en même temps limite considérablement les capacités évasives de son adversaire. Dans un espace confiné, une rencontre avec lui se transforme rapidement d'un combat à un très mauvais repas.

CONSEILS:

- Éviter les combats étroits avec lui. C'est pratiquement une façon garantie de mettre fin à sa vie.
- Utilisez des armes variées et gardez toujours votre distance.
- Un Polyphème gravement blessé peut commencer à courir.
- Utilisez des obstacles et des passages étroits pour l'empêcher d'atteindre sa cible rapidement.
- Si Polyphemus commence à crier, fuyez aussi loin que possible.
