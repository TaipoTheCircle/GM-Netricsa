STEN SOUS-MACHINE GUN


ARME: Gun sous-machine STEN
MUNITIONS:   Parabellum 9x19mm
CADENCE DE TIR:    Automatique, ~500 tours / min
POIDS: ~3,18 kg

DESCRIPTION:

Une mitrailleuse britannique s'est développée en 1941 comme une arme simple, peu coûteuse et technologiquement avancée pour la production de masse. Sa conception est extrêmement simplifiée et se compose d'un petit nombre de pièces, permettant de produire rapidement le STEN même en temps de guerre.

L'arme est actionnée et alimentée par un chargeur de 32 tours monté sur le côté. Le STEN est capable d'un seul tir et d'un feu automatique. L'avantage principal de l'arme est sa simplicité et sa grande efficacité à proximité.

REMARQUES:

- Capable d'incendie simple et automatique. - Efficace principalement à proximité et à moyenne distance.
- La conception simple facilite l'entretien et la production.
- Portée efficace d'environ 100 mètres.
- Visages primitifs et manque de précision.
- Le surchargement du magazine peut retarder le tir.
