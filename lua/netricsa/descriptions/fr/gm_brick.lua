BRICK, TOUCHE DE BRICK


Sam, on l'a trouvé. L'endroit où l'architecte a finalement cessé d'être timide et s'est juste fracassé des briques.

Alors que les versions précédentes étaient sur l'expansion horizontale (maisons, garages, piscines), ici tout est devenu vertical. Sérieusement.

Tout est encastré dans une structure verticale. Ce n'est pas une maison, pas une tour, mais plutôt un labyrinthe de briques. Murs, plates-formes, passerelles, tous en brique. Et des escaliers partout. Beaucoup d'escaliers.

Main Mechanics:

Il y a une caractéristique clé ici qui transforme la carte en une expérience philosophique:

À un moment donné, tu décideras que tu en as assez vu et que tu sautes.

Et là-bas, vous êtes rencontré par... les mêmes escaliers.

You land and realize: les escaliers que vous venez de monter sont juste devant vous. Tu peux recommencer à grimper. Et saute encore. Et retrouvez-vous à son pied.

Faisons un marché: si dans une heure nous sommes encore au pied de ces escaliers, je vais commencer à soupçonner que nous sommes en enfer. Un enfer gris-rouge-jaune.
