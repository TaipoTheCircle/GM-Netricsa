RÉSULTAT DE L'EXERCICE MINECRAFT


CLASSE:      Wraith
MÉTABOLISME: Morts
PERCEPTION: La foule hostile, les Wraith volant
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Toucher
RÉCOMPENSE:     200 FC
MENACE:     Moyenne

DESCRIPTION:

Cette figure translucide et pâle avec un "mantra" flottant erre la nuit dans l'Overworld, émettant des gémissements d'eerie.

Contrairement à beaucoup d'autres mafia, les Wraith n'ont pas de corps physique. Il vole et ne rencontre pas d'autres créatures, ce qui en fait une cible difficile. Cependant, il est assez rapide et agressif: il peut repérer des ennemis de 12-16 mètres et attaquer en les touchant.

Les Wraiths réguliers apparaissent dans l'Overworld à des niveaux de lumière de 7 ou moins, comme les zombies ou les squelettes. Un Wraith régulier inflige des dommages simplement en le touchant.

Cependant, ils ont aussi des vulnérabilités. Comme tous les morts-vivants, les Wraiths craignent le soleil: en plein jour, ils commencent à prendre des dommages et à mourir, bien qu'ils ne prennent pas feu. Leur translucidité est une épée à double tranchant. D'une part, il leur permet de se fondre dans les murs de pierres des grottes, restant inaperçus. D'autre part, il révèle leur nature héroïque, permettant à leurs adversaires de repérer une menace dans le temps.

CONSEILS:

- Les Wraiths sont difficiles à repérer dans les grottes en raison de leur transparence, alors soyez vigilant et écoutez leurs gémissements d'aurore.
- Comme tous les morts-vivants, ils sont facilement tués avec des armes enchantées par l'enchantement du "Smite céleste".
- Puisqu'ils volent et n'entrent pas en collision avec des blocs, se cacher dans des coins serrés est inutile. Mieux vaut garder votre distance et utiliser un arc.
- Les Wraiths émettent un gémissement aigu lorsqu'ils sont frappés et un étrange cri sur terre lorsqu'ils meurent.
