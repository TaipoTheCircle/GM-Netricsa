BULLTANK BIOMÉCANOÏDE, GÉNÉRAL (GRAND)


CLASSE : Biomechanoid BullTank, général (grand)
MÉTABOLISATION : Cyborg endothermique
PERCEPTION : améliorée cybernétiquement et génétiquement
TAILLE : 67,3 pi
ENDURANCE : Très élevée
HOSTILITÉ : Très élevée
ARMES : Lanceurs de missiles
RÉCOMPENSE : 2000 FC
MENACE : Très élevée

DESCRIPTIF :

Suite à la création réussie des Biomechanoid Walkers, Mental a chargé ses scientifiques de trouver un moyen de convertir les troupes existantes en biomécanoïdes, afin qu'elles puissent continuer à servir Mental même après avoir subi de graves blessures. Le résultat fut le réservoir biomécanoïde.

Les bullsoldats qui ont été frappés d'incapacité au combat voient les parties endommagées de leur corps amputées et des augmentations cybernétiques sont implantées chirurgicalement à leur place. La carrosserie est ensuite reliée à un châssis de char capable de traverser la plupart des types de terrain, ce qui les rend très polyvalents.

Cette variante est appelée « Générale » : ils subissent non seulement une amélioration cybernétique mais également une modification génétique, augmentant considérablement leur taille et leur force. Leurs armes sont remplacées par des lance-missiles qui tirent des volées de roquettes, ce qui les rend excellents pour détruire les fortifications ennemies.

Certains généraux ont reçu des améliorations génétiques supplémentaires dans l'espoir d'augmenter encore leur force. Cependant, cela n’a fait qu’augmenter leur taille sans améliorer leur durabilité.

CONSEILS :

- Détruisez-le le plus rapidement possible avant d'être submergé par ses missiles.
- Les balles ne détruiront pas ces missiles ; utiliser des munitions plus lourdes.
- Gardez vos distances à tout moment.