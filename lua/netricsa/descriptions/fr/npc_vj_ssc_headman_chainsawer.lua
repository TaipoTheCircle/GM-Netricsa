APRÈS CHAINSAWER


CLASSE:      Chainière décapité
MÉTABOLISME: Cyber-Zombie
PERCEPTION: Insensible, contrôlé par LCU
TAILLE:       6 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Extrême
ARMES:    Chaînes
RÉCOMPENSE:     400 FC
MENACE:     Très élevé

DESCRIPTION:

Un soldat syrien exécuté, ressuscité des morts par Mental et télécommandé par une unité de contrôle de la vie (LCU).

He no longer needs a head: il n'y a rien à penser et rien à faire. Sa tâche est simple : couper tout pendant que les moteurs de ses scies tournent.

Après la décapitation, son système nerveux a été brutalement remorqué par l'USL, et ses mains sont maintenant fermement attachées à ses tronçonneuses.

Lorsqu'une scie à chaîne détecte une cible, elle s'accélère brusquement, comme si quelqu'un venait de tourner l'accélérateur jusqu'au sol, rendant presque impossible l'évasion.

Les groupes de tronçonneuses sont particulièrement dangereux. Lorsqu'ils sont regroupés, ils se transforment en une tornade mobile de lames, de sang et de moteurs, véritable ouragan de la mort qui écrase tout sur son chemin, y compris la couverture et les alliés de Mental.

CONSEILS:

- Très dangereux en raison de sa stupidité. Ne le laissez jamais se rapprocher.
- Le meilleur choix est un fusil à double canon ou un lance-roquettes.
- Dans un groupe, ils forment une grêle de violence mortelle.