SOLDATEUR D'ÉLITE HYBRID


CLASSE:      Combiner Overwatch Hybrid Elite
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Unité polyvalente Elite
TAILLE:       5,9 pieds
ENDURANCE:  Extrêmement élevé
HOSTILITÉ:  Extrême
ARMES:    AR2 Fuseau d'impulsions, Grenades, Stun-Stick
RÉCOMPENSE:     1000 FC
MENACE:     Critique

DESCRIPTION:

Le Combine Overwatch Hybrid Elite est le compromis du Combine entre l'élitisme ostentatoire et la brutalité pratique. Il combine les meilleurs éléments des soldats Elite standard et des unités alternatives, devenant un outil polyvalent pour supprimer la résistance dans tout environnement.

Leur armure est blanche, comme celle des soldats d'élite classiques, mais renforcée par des inserts composites noirs et une veste en flocons supplémentaire, donnant à leur silhouette une apparence plus lourde et plus menaçante. Ces soldats ont l'air d'être rassemblés non pas pour des défilés, mais pour survivre là où d'autres élites se briseraient.

Le béret sert non pas de décoration, mais de marqueur d'expérience et de droit à des décisions tactiques indépendantes.

Au combat, l'hybride agit de manière agressive et calculatrice. Le AR2 est utilisé pour la pression méthodique et la destruction des cibles, et les grenades sont utilisées pour détruire le couvert et perturber les formations ennemies. Ces soldats mènent le plus souvent l'assaut, étant les premiers à entrer dans la zone de contact et les derniers à partir, laissant derrière eux le silence et l'odeur de l'ozone.

Alors que l'autre soldat d'élite trompe les attentes et que l'étalon déborde par son apparence, l'hybride fait les deux simultanément, ne laissant ni temps ni illusions à l'ennemi.

CONSEILS:

- Armure renforcée noire absorbe mieux les dommages que l'armure standard.
- Les grenades sont utilisées avec précision et fraîcheur.