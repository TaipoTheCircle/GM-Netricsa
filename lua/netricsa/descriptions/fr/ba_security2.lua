MESA BLACK, INSIDER LE COMPLEXE DE SÉCURITÉ


Vous êtes à l'intérieur. Les murs sont oppressifs, l'air sent le métal et la désinfection - un quartier général de la sécurité typique. Maintenant nous devons prendre pied: ici chaque objet peut être la clé de la survie. Ou à l'échec.

What to do next:

Veste anti-balles

Il y a des rangées de gilets dans l'armurerie. Mets-en un. Pas pour la beauté : quand le désordre commencera, chaque assiette comptera. Oui, c'est dur, mais il vaut mieux transpirer que saigner.

Toilettes (au cas où)

Oui, même dans l'apocalypse, le surhomme a besoin de son propre espace. Mais rappelez-vous : je peux tout voir. La puce dans votre crâne traduit chaque étape. Ne traînez pas et n'essayez pas de cacher quelque chose dans le réservoir. Je sais déjà.

Une arme

Sans armes, c'est comme ne pas avoir de mains. Il y a un pistolet standard dans l'armurerie. Prends-le, vérifie le clip, mets la sécurité. Ne tirez pas inutilement, mais n'attendez pas que quelqu'un vous vise non plus.

Caméras de surveillance

Le panneau de commande est au deuxième étage. L'ascenseur est à proximité, le bouton d'appel est rouge clignotant. Levez-vous, asseyez-vous aux moniteurs et attendez que tout commence.