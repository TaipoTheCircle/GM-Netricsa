"ASHOT" PISTOL DE L'ÉCOLE


ARME: Pistolet "Astuce"
MUNITIONS:    12 x 70 mm
CADENCE DE TIR:     1 ronde, recharge manuelle

DESCRIPTION:

Un pistolet de fusil fait maison, largement utilisé parmi les habitants de la Russie post-nucléaire. Il est fabriqué à partir de matériaux improvisés, principalement des tuyaux métalliques et des composants mécaniques de base. Malgré son design primitif, il emballe un puissant poinçon à portée de main et est particulièrement efficace contre les mutants.

Le "Ashot" est une arme à tir unique dotée d'un mécanisme de rechargement par effraction. Il utilise des coquilles de chasse de calibre 12. En raison de sa construction simple, de sa taille compacte et de la disponibilité de munitions, il est très populaire parmi les harceleurs, les bandits et d'autres denis du métro. Il supporte diverses modifications, y compris des barils supplémentaires, un stock, des vues optiques, et un baril étendu.

REMARQUES:

- Un des types les plus courants d'armes artisanales dans le métro.
- La version de base ne contient qu'un seul tour.
- Dans *Metro Exode*, des variantes avec deux ou quatre barils sont disponibles.
- Un barillet étendu améliore la précision (groupage de tir) et la portée efficace.
- Un incendiaire spécial 12x70 mm rond.
