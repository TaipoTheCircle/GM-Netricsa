QUEEN "BETA"


CLASSE:      Swarm Reine "Beta"
MÉTABOLISME: Xénobiologique
PERCEPTION: Swarm Reine
TAILLE:       26,2 pi
ENDURANCE:  Extrêmement élevé
HOSTILITÉ:  Débordement
ARMES:    Tentacles d'ensemencement, projectiles acides, membres concassés
RÉCOMPENSE:     5000 FC
MENACE:     Apocalyptique

DESCRIPTION:

Le Swarm Queen "Beta" est la plus grande forme de vie connue de cet essaim et l'organisme central de toute la colonie. Le swarm est formé autour d'elle, et tous les autres individus existent uniquement pour protéger leur progéniteur et poursuivre le cycle de vie de l'essaim. La destruction de la Reine conduit à la désintégration progressive de la colonie, privée d'un seul centre de coordination.

Son corps massif est recouvert d'une épaisse armure chitineuse et soutenu par plusieurs membres puissants, lui permettant de bouger en toute confiance même sur des surfaces inégales. Malgré sa taille, la Reine est capable de changer rapidement sa position corporelle, en choisissant la position d'attaque la plus avantageuse.

Le trait le plus distinctif de la Reine est ses tentacules subterranéens. En les enterrant dans le sol, elle peut soudain se faire sentir sous son adversaire, les capturer et les tenir en place, tandis que de puissantes contractions des tentacules infligent des dommages dévastateurs. Même des combattants expérimentés peuvent avoir du mal à échapper à un tel piège.

À longue distance, la Reine prend une position stable et tire une volley de trois gros projectiles acides. Chaque impact s'accompagne d'une puissante libération de liquide biologique corrosif, capable de détruire rapidement les armures et les tissus vivants. En préparant le volley, sa mobilité est considérablement réduite, ce qui en fait le moment le plus opportun pour une contre-attaque.

Dans les quartiers proches, la Reine utilise des membres massifs capables d'écraser pratiquement n'importe quel adversaire avec un seul coup. Grâce à sa combinaison d'immense durabilité, de contrôle spatial et d'attaques dévastatrices, elle est considérée comme le membre le plus dangereux du Beta Swarm.

CONSEILS:

- Ne restez pas dans un endroit trop longtemps : les tentacules souterraines peuvent atteindre une cible fixe.
- En préparant son volley acide, la Reine change à peine la direction de son attaque. Utilisez ce moment pour repositionner.
- La Reine contrôle efficacement la plupart des champs de bataille avec ses tentacules.