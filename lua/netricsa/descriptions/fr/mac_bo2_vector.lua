KRISS K10 SUBMACHINE GUN


ARME: Gun sous-machine KRISS K10
MUNITIONS:   .45 ACP / 9x19mm / .40 S&W
CADENCE DE TIR:    ~1200 tours/min

DESCRIPTION:

Une mitrailleuse expérimentale américaine développée par KRISS USA en tant que version améliorée du vecteur KRISS. Il a été dévoilé pour la première fois en 2011. L'arme utilise le système breveté Super V à bouffées retardées, qui dirige le mouvement du boulon vers le bas, aidant à réduire le recul et la montée du museau.

Le K10 dispose d'un support télescopique, d'une poignée de recharge redessinée, de commandes ambidextres et de quatre rails Picatinny. Sa conception modulaire permet une conversion de calibre entre .45 ACP, 9×19mm, et .40 S&W. Il a été conçu pour utiliser des magazines de 13 ou 25 tours, avec la possibilité d'utiliser aussi des magazines élargis.

REMARQUES:

- Représente la deuxième génération de la famille KRISS Vector.
- La poignée de charge peut être configurée pour le côté gauche ou droit.
- Le système Super V aide à atténuer la montée du museau pendant le tir.
- Malgré sa conception avancée, le K10 est resté un prototype expérimental. Il semble que le Vector originel n'était pas prêt à céder la place à son frère cadet.
