STORMTROOPER DE CLONE, CHEF DU KAMINO


CLASSE:      Clone Stormtrooper, Shielder
MÉTABOLISME: Clone humain, Homme
PERCEPTION: Unité d ' intervention rapide en cas d ' agression
TAILLE:       5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Bouclier énergétique, Électrobaton, Grenades, Pistol impérial
RÉCOMPENSE:     1800 FC
MENACE:     Très élevé

DESCRIPTION:

Les boucliers sont des vétérans du Stormtrooper Corps et occupent l'un des grades les plus élevés de l'infanterie de ligne de l'Empire galactique. Leur armure presque entièrement noire et leur long manteau servent de signe d'un statut élevé et d'une vaste expérience de combat. Ces combattants sont chargés de percer les fortifications, de nettoyer les espaces confinés et d'éliminer les adversaires les plus dangereux.

La principale défense d'un bouclier est un bouclier d'énergie massif, capable de résister à pratiquement tout type de feu d'armes légères. Alors que le bouclier est entre le combattant et la cible, la plupart des attaques sont inefficaces. Cependant, la conception du bouclier laisse les jambes du wielder exposées et n'offre aucune protection du dos, un fait souvent exploité par des adversaires expérimentés.

Dans un combat rapproché, un bouclier utilise un bâton électrique. Quelques coups puissants suffisent habituellement pour briser les os, désactiver l'armure ou faire revenir la victime à plusieurs mètres. Lorsque l'ennemi maintient sa distance, le bouclier lance rapidement trois grenades de fragmentation sur le bouclier, les forçant à quitter la couverture.

Si la cible est hors de portée de la matraque et que les grenades sont dépensées, le bouclier tire un pistolet impérial. Le bouclier tire une courte série de trois coups rapides avec une précision étonnante, puis, avec un mouvement pratiqué, tourne l'arme sur son doigt et le retourne à l'étui. Cette façon ostensible de manipuler un pistolet est considérée comme une tradition particulière des unités d'élite de l'Empire et sert simultanément de démonstration de calme total face à l'ennemi suivant.

CONSEILS:

- Ne tirez pas sur le bouclier. Le bouclier s'en fiche.
- Flanque ou vise les jambes.
- Ne le laisse pas s'approcher. Un bâton étourdissant termine l'argument très rapidement.
- Si vous voyez trois grenades voler, il est temps de changer de position.
