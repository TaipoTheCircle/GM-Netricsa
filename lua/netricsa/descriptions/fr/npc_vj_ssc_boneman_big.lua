KLEER SKELETON, GROSSE


CLASSE:      Kleer Skeleton, Big
MÉTABOLISME: non décédés
PERCEPTION: créature magique
TAILLE:       15 pieds
ENDURANCE:  faible
HOSTILITÉ:  moyenne
ARMES:    projectiles à deux balles, griffes, cornes
RÉCOMPENSE:     1000 FC
MENACE:     moyenne

DESCRIPTION:

Le squelette non mort d'un membre d'une race éteinte de la planète Clear dans le système Alpha Canis Majoris. Il a des griffes pointues sur ses pattes avant et une longue queue.

De loin, il lance des boules métalliques reliées par une chaîne, et au combat étroit, il utilise ses griffes. Au cours des expériences de Mental sur la modification de la taille des créatures, ce squelette a été magiquement amélioré et agrandi à la taille d'un reptiloïde des plaines.

