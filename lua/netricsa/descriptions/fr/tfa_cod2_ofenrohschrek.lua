RPzB.43 "OFENROHR" ANTI-TANK GRENADE LAUNCHER


ARME:  RPzB.43 "Ofenrohr" Lanceur anti-tank Grenade
MUNITIONS:   Grenade antidérapante de 88mm
CADENCE DE TIR:    ~4-6 tours/min
POIDS: ~9,5 kg

DESCRIPTION:

Un lance-grenades antichar allemand de la Seconde Guerre mondiale. Il a été développé en 1943 comme un développement de la "Bazooka" américaine et a été destiné à combattre les chars et autres véhicules blindés.

La grenade est lancée à partir d'un tube en métal ouvert à l'aide d'un moteur de fusée. Contrairement au Panzerschreck plus tard, le RPzB.43 n'avait pas de bouclier de protection, exigeant que le tireur porte une protection spéciale du visage et des yeux. Lorsqu'il est tiré, un puissant jet de gaz chauds est généré derrière le tube, ce qui rend extrêmement dangereux de se tenir directement derrière le lance-grenades.

La grenade HEAT 88mm avait une forte pénétration d'armure et était capable de détruire la plupart des chars de l'époque. La portée de tir effective était d'environ 150 mètres.

REMARQUES:

- Conçu principalement pour détruire les chars et autres cibles blindées.
- Le jet sort directement de l'arrière du tube, exigeant du canonneur qu'il fasse preuve d'une extrême prudence.
- Contrairement au Panzerschreck, il n'y a pas de bouclier protecteur. Son introduction ultérieure a été une amélioration majeure de la conception.
- "Ofenrohr" se traduit par "stovepipe". Mais après le Panzerschreck, la situation est devenue encore plus ridicule: il y avait d'abord la poêle, puis est venu le Shrek. Apparemment, l'industrie antichar allemande a vraiment adopté une approche « équitable ».
