ARCHER BETA SKELETON DU MINECRAFT


CLASSE:      Beta Skeleton Archer
PERCEPTION: Non mort, unité variée
MÉTABOLISME: Magie soutenue non morte
TAILLE:       6,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Bow et flèches
RÉCOMPENSE:     200 FC
MENACE:     Moyenne

DESCRIPTION:

Le Beta Skeleton Archer est un exemple classique de la façon dont un minimum de chair ne compromet pas une irritation maximale. C'est une collection vivante d'os, tenue ensemble par la magie, la malice, et un excellent sens de la distance. Il n'aime pas les combats rapprochés, préférant transformer méthodiquement sa cible en coussin pour ses flèches.

En plein jour, le squelette brûle, qui, cependant, ne l'empêche pas d'essayer de vous terminer avec une flèche finale comme il brûle magnifiquement.

CONSEILS:

- Un bouclier est votre meilleure défense contre un archer.
- Utilisez une couverture, sinon la fusillade sera unilatérale.
- Si un squelette se trouve soudainement à monter sur une araignée, considérez-le comme une promotion.