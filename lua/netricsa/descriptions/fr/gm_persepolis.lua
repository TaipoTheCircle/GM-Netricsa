PERSEPOLIS, LE DUT DES CENTURES SUR LES BONES DES EMPIRES


Sam, C'est Persepolis, l'ancienne capitale de l'Empire achéménide, la "Ville des Perses", qu'Alexandre le Grand a transformée en un gigantesque feu de joie en 330 av. J.-C.

Maintenant il n'y a que le désert, le vent et les ruines qui se souviennent de la marche des peuples du Nil à l'Indus.

Imaginez une plaine sablonneuse sans fin, sur laquelle flotte une brume. Au milieu, sur une plate-forme de pierre massive, montez les squelettes de colonnes, d'escaliers et de portes.

The ruins retain traces of their former grandeur:

Apadana - la salle cérémonielle de Darius I. Il était une fois, 72 colonnes se levaient ici, soutenant le toit. Il ne reste plus que 13 personnes. Mais même ils sont stupéfiants. Des escaliers géants leur mènent, une fois utilisés par des chars et des délégations de peuples conquis portant des cadeaux.

Tachara est le palais résidentiel de Darius I. Seules les fondations, les portes et les parties inférieures des murs avec bas-reliefs restent.

La salle d'une centaine de colonnes est une immense chambre, dont seules les bases de colonnes et les portes de pierre avec des scènes de bataille restent.

Le Harem de Xerxès est vingt-deux petites pièces où les femmes et les enfants auraient pu vivre.

Le tombeau de Darius III est le tombeau inachevé et naturellement dévasté du dernier roi de la dynastie, qui a fui Alexandre et a été tué par son propre peuple.

Cette ville n'était pas seulement une capitale, mais un symbole d'un empire s'étendant de l'Egypte à l'Inde. Des artisans du monde entier, des Babyloniens, des Égyptiens, des Ioniens et des Assyriens. Cependant, le travail des esclaves n'était pas utilisé ici, une rareté à l'époque. La ville disposait d'un réseau complexe d'approvisionnement en eau et d'assainissement. Alexandre l'a brûlé au sol, soit dans une stupeur ivre, incitée par les Thais athéniens courtisane, ou délibérément, comme un acte de vengeance pour l'incendie de l'Acropole.

Des exemplaires inestimables de l'Avesta, écrits en encre d'or sur des peaux de boeuf, périrent dans le feu. Après cela, la ville a perdu sa signification, et Istakhr, le centre spirituel du Zoroastrianisme, a grandi à proximité. Les ruines de Persepolis sont maintenant un site du patrimoine mondial de l'UNESCO.
