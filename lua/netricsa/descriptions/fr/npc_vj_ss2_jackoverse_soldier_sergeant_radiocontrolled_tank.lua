LE ROBOT DE LA CR HUNTER DU SERGEANT


CLASSE:      Robot de chasseur RC du sergent Stormtrooper
MÉTABOLISME: Mécanique
PERCEPTION: Drone de combat tueur, le "jouet" du sergent
TAILLE:       5,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Absolu
ARMES:    Minigun intégré (à droite), fusil de chasse (à gauche), missile Pod (sur la tête)
RÉCOMPENSE:     1200 FC
MENACE:     Haut

DESCRIPTION:

C'est l'un des « jouets » que le sergent Stormtrooper a conçu et mis en production. Ce drone de combat est conçu pour les missions les plus dangereuses : reconnaissance, suppression des points de feu, chasse à des cibles uniques et soutien d'infanterie. Ce n'est pas autonome, il est contrôlé à distance par le sergent, mais ça ne le rend pas moins dangereux.

Le noyau du robot se compose de deux unités de marquage noir et vert foncé. Les pistes lui permettent de naviguer sur un terrain accidenté, en grimpant sur des rochers, des débris et même de petits murs. Un corps central est situé au-dessus des voies.

Deux bras de manipulateur articulés et d'aspect mécanique s'étendent du corps. Le bras droit est équipé d'une mitrailleuse tournante, et la gauche d'un fusil de chasse. Au-dessus de sa tête, un module sphérique avec une jante orange et un « œil » vert brillant porte un lanceur de missiles. Le robot peut utiliser n'importe quel type d'arme en fonction de la situation: la mitrailleuse pour le tir suppressif, le fusil de chasse pour le combat rapproché, et les missiles pour détruire des cibles blindées et couvrir.

Le cou du robot est flexible, permettant au module tête de tourner et de suivre les cibles sur une large gamme.

CONSEILS:

- Le robot est mobile sur ses traces, mais pas très vite. Couvrez-le et flanquez-le.
- La mitrailleuse et le fusil de chasse ont une efficacité variable à différents niveaux. Restez à une portée moyenne pour minimiser les dommages.
- Le module tête est un point faible. Quelques coups bien placés et il sera réduit à un tas de métal.
- N'attaquez pas le robot. Son arme couvre une large zone.
- Le robot est le jouet du sergent. Si vous le voyez sur le champ de bataille, le sergent est à proximité. Soyez prêt à le rencontrer directement.
