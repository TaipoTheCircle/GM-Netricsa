BÉBÉ DE LA FAMILLE


CLASSE:      Bébé
MÉTABOLISME: Marteaux de nuit
PERCEPTION: Horreur psychologique hostile
TAILLE:       2,6 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Absolu
ARMES:    Épine
RÉCOMPENSE:     50 FC
MENACE:     Moyenne

DESCRIPTION:

Un reflet des coins les plus sombres de la psyché. Ce petit adversaire rapide et extrêmement agressif symbolise l'irritation des pleurs des nouveau-nés. Innocent en forme, mais mortel en essence.

Le bébé apparaît comme une petite figure, pâle, nue.

Il se trouve dans les appartements. Il n'a aucune tactique sophistiquée, aucun arsenal, même pas un sentiment d'auto-préservation. Il n'a qu'un seul but : courir vers vous et s'empaler avec un pic qui sort de sa tête.

Oui, vous avez bien entendu. Le Kid se tue pour essayer de te tuer.

Il est plus rapide que la plupart des ennemis. S'il frappe sa cible, un pic long et aigu sort de sa tête, causant des dégâts. Le Kid lui-même est tué. Tu n'as pas besoin de le finir, il le fait lui-même.

Les dégâts causés par une seule attaque ne sont pas significatifs. Mais le problème est que ces gars apparaissent habituellement en groupes, pas individuellement. Si deux ou trois d'entre eux vous frappent de suite, votre santé va chuter.

CONSEILS:

- Le Kid meurt d'une arme. Même un pistolet.
- Ne le laisse pas se rapprocher. Gardez votre distance et tirez d'abord.
- Ils sont particulièrement dangereux dans les couloirs étroits, car il n'y a pas de place pour esquiver. Utilisez un fusil à bout portant.
- Si vous entendez un enfant pleurer et le battement de petits pieds, préparez votre arme. Ils courent déjà.
- N'attendez pas qu'ils arrivent. Courez vers eux et tirez-les à distance.
