SWARM SHIELDBUG "BETA"


CLASSE:      Swarm Shieldbug "Beta"
MÉTABOLISME: Xénobiologique
PERCEPTION: Organisme chargé d'assauts
TAILLE:       9,2 pi
ENDURANCE:  Très élevé
HOSTILITÉ:  Haut
ARMES:    Membres blindés, grève
RÉCOMPENSE:     1000 FC
MENACE:     Très élevé

DESCRIPTION:

Le Swarm Shieldbug "Beta" est un spécimen d'assaut spécialisé conçu pour violer les défenses ennemies et protéger les membres du Swarm moins résistants. Sa défense est basée sur deux membres blindés massifs, qui peuvent complètement couvrir la plupart du front de la créature.

En attaquant, le Bouclier tient instinctivement l'ennemi devant lui, en utilisant son bouclier naturel pour détourner les attaques. Grâce à sa conception unique, son armure frontale peut résister à des dommages qui seraient mortels pour la plupart des autres organismes du Swarm.

Ces plaques de protection servent également d'armes. Avec un mouvement aigu de ses membres, le Shieldfoot délivre des coups puissants capables de frapper des proies à une distance considérable. Cette attaque est particulièrement dangereuse dans les espaces confinés, sur les ponts et près des falaises.

Contrairement aux membres plus agiles de Swarm Beta, ce spécimen ne repose pas sur la vitesse, mais sur un mouvement continu vers l'avant. Ayant localisé une cible, le Shieldfoot fermera régulièrement la distance jusqu'à ce qu'il ait une ouverture pour frapper.

Comme la plupart des créatures surconfident dans leur propre invulnérabilité, ses organes les plus vulnérables sont situés précisément là où il s'attend le moins à une attaque.

CONSEILS:

- N'attaquez pas le Shieldfoot.
- Utilise sa lenteur pour le flanquer.
- Évitez les passages étroits pendant le combat.
- Plus son bouclier est grand, moins il aime être attaqué par derrière.
