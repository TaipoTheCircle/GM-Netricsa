SKELETON SWORDSMAN DU MINECRAFT


CLASSE:      Squelette Swordsman
PERCEPTION: Guerrière sans mort
MÉTABOLISME: Magie soutenue non morte
TAILLE:       6,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARME:     Épée de pierre
RÉCOMPENSE:     350 FC
MENACE:     Moyenne-haute

DESCRIPTION:

Le Skeleton Swordsman est un squelette qui a décidé que les arcs sont pour les faibles et les lâches, et que le vrai non mort devrait regarder leurs victimes dans les yeux... même si leurs yeux sont partis depuis longtemps. Armé d'une épée et d'une expérience de combat douteuse de l'au-delà, il charge la tête sans hésiter.

Parfois, il semble que le Skeleton Swordsman en veuille vraiment aux vivants-peut-être parce qu'ils ont encore la peau, les nerfs, et la capacité de ressentir la douleur.

CONSEILS:

- Ne le laissez pas s'approcher, il est plus dangereux qu'il ne semble.