HOMME GINGERBREAD DES GRANDES ÎLES DU GRAND LOLLY


CLASSE:       Sweet Island Gingerbread Homme
MÉTABOLISME:  Construction durable
PERCEPTION:  Protecteur et originaire des îles Sweet
TAILLE:        5,9 pieds
ENDURANCE:   Moyenne
HOSTILITÉ:   Haut
ARMES:     Combat étroit (coups et coups de corps)
RÉCOMPENSE:      450 FC
MENACE:      Moyenne

DESCRIPTION:

Le Sweet Island Gingerbread Man est l'un des principaux défenseurs de cette terre de cloître mais mortelle. Son corps est fait d'un pain d'épice dense, donnant l'impression trompeuse de douceur et de plomb. En réalité, il est beaucoup plus fort qu'il n'apparaît.

En apparence, il ressemble à un Gingerbread Man vivant : une tête ronde avec de grands yeux ronds, un nez rouge, un sourire gelé en permanence et trois boutons rouges sur l'estomac. Une bordure de sucre blanc longe le bord de son «vêtements», et des éléments rouges ronds ressemblant à des inserts de bonbons se trouvent sur ses bras et ses jambes. Ses membres semblent doux, mais lorsqu'ils sont frappés, ils agissent comme des clubs élastiques.

Le Gingerbread Man préfère le combat rapproché. Il essaie de fermer la distance et de faire tomber ses « poings » sur son adversaire, en utilisant sa masse corporelle et sa structure printanière.

Malgré son apparence « amicale », il est un défenseur dévoué de son territoire.

CONSEILS:

- Ne soyez pas dupe par les apparences - coups blessés.
- L'attaque à distance est plus efficace.
- En combat rapproché, il met rapidement le rythme.
- Son sourire n'indique rien.