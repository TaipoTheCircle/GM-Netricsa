G-2 ROBOT DE COMPAGNIE DE LA LOEK-III


CLASSE:      Robot compagnon G-2
MÉTABOLISME: Mécanique
PERCEPTION: Robot de défense automatisé
TAILLE:       ~3 pi
ENDURANCE:  Haut
HOSTILITÉ:  Haut
ARMES:    Grèves
RÉCOMPENSE:     1200
MENACE:     Haut

DESCRIPTION:

Le robot compagnon G-2 est un défenseur mécanisé, faisant partie de l'équipe de Core Guardian, utilisé lors des attaques de Lum horde. Son corps est peint par Sweet Autumn.

Il est armé d'armes capables de détruire les créatures extraterrestres de Lum au combat rapproché. Son IA lui permet de coopérer efficacement avec les Gardiens de base, en couvrant les étranglements et en assurant la suppression si nécessaire.

CONSEILS:

- Gardez le G-2 près des points d'étranglement pour une efficacité maximale.
- Fonctionne mieux avec Core Guardians et tourelles.
