ISAAC KLEINER


CLASSE:      Dr Isaac Kleiner
MÉTABOLISME: Humain, Homme
PERCEPTION: Chercheur humain / Résistance
TAILLE:       ~5,9 pi
ENDURANCE:  Faible (physiquement fragile, non combattant)
HOSTILITÉ:  Faible (amiable, défensive seulement)
ARMES:    Connaissances scientifiques, technologie de téléportation, fusil de chasse SPAS-12 occasionnelle
RÉCOMPENSE:     1000 FC
MENACE:     Faible (directement), Élevé (indirectement par des inventions)

DESCRIPTION:

Le Dr Isaac Kleiner est l'un des derniers scientifiques de Black Mesa survivants et une pierre angulaire des efforts scientifiques de la Résistance. Physicien excentrique mais brillant, Kleiner se consacre au développement de la technologie de téléportation et à la repurposition de la machine Combine au profit de l'humanité. Sa plus grande contribution est son laboratoire dans la ville 17, qui sert de centre vital pour les opérations de résistance.

Kleiner est dépourvu d'esprit et souvent éparpillé, enclin à parler de théories ou à se laisser détourner par sa tête de chat, Lamarr, qu'il garde affectueusement malgré sa tendance à provoquer le chaos. Malgré sa maladresse, l'esprit de Kleiner est vif, et ses inventions jouent un rôle crucial en donnant à la Résistance un avantage technologique.

Bien que physiquement fragile et inadapté au combat, le courage de Kleiner réside dans sa détermination inébranlable à résister au Combiné à l'intellect plutôt qu'à la force brute. Son mentor de Gordon Freeman reflète à la fois son admiration pour les compétences de Gordon et sa confiance en lui pour adopter les plans les plus audacieux de la Résistance.

CONSEILS:

- Protégez Kleiner à tout prix - ses inventions sont l'épine dorsale de la technologie de résistance.
- Ne laissez pas Lamarr errer ; le chaos a tendance à suivre.
Bien qu'inoffensif, ses excentricités sont vitales pour le moral des temps sombres.
- Il ne veut pas poster de mèmes sur le serveur Discord, donc il est dans la maison des fous.
