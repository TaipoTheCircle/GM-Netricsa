OBJECTIFS (T-REX)


CLASSE:      Vieille chèvre (T-rex)
MÉTABOLISME: Carnivore (mais se nourrit étrangement du butin et des humains)
PERCEPTION: Bête 
TAILLE:       ~30 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Comatiquement extrême
ARMES:    Mâchoires massives, coup de queue, "Goat Roar"
RÉCOMPENSE:     9999 FC + objet de quête cassé
MENACE:     Très élevé

DESCRIPTION:

Connu dans les chroniques MMO sous le nom de « Vieille Chèvre », ce mutant préhistorique a été accidentellement engendré à l'intérieur d'une toilette géante dans un monde médiéval RPG. Les joueurs pensaient à l'origine que c'était juste un œuf de Pâques, jusqu'à ce qu'il s'avère que la créature pouvait effacer un raid complet de 40 hommes en quelques secondes.

Il ressemble à un T-Rex classique et son style de combat mélange la fureur dinosaure.

CONSEILS:

- Si vous le voyez sur les toilettes - courir.
