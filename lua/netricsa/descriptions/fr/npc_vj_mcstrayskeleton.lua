STRAY SKELETON DE L'EXPÉRIENCE MINECRAFT


CLASSE:      Squelette en paille
PERCEPTION: Morts
MÉTABOLISME: Un mort-vivant magique
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Bow, flèches avec effet lent
RÉCOMPENSE:     150 FC
MENACE:     Moyenne

DESCRIPTION:

Le squelette Stray est un squelette qui a oublié que la neige est un piège mortel pour les non préparés.

Tout squelette pris dans la neige molle frissonne initialement comme si gelé, et après quelques secondes se transforme en Straya - une version gelée de lui-même avec un arc et des flèches qui ralentissent les ennemis pendant 30 secondes.

CONSEILS:

- N'essayez pas de jouer aux boules de neige avec Stray - vous allez perdre.
- Ses flèches vous ralentiront quand ils frapperont.