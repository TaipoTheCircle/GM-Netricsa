DIRECTION DE L'EXPLOITATION MINÉRALE


CLASSE:       Porc sale
MÉTABOLISME:  Mammifère à sang chaud
PERCEPTION:  Animal sauvage / domestique amical, lover de bain de boue
TAILLE:        ~3 pi
ENDURANCE:   Moyenne
HOSTILITÉ:   Faible
ARMES:     Aucune
RÉCOMPENSE:      35 FC
MENACE:      Minimal

DESCRIPTION:

Ce n'est pas une espèce séparée, mais un état d'esprit. Tout porc ordinaire peut se salir s'il trouve une flaque appropriée et y passe quelques secondes, se salir avec diligence.

Après la procédure, presque tout son corps est recouvert de terre, surtout ses jambes, et une fleur s'assoit sur sa tête, se moquant de propreté.

Dirt can be washed off a pig in two ways: l'attirer dans un lac ou un autre plan d'eau, ou tout simplement lui faire un seau d'eau. Après cela, le porc revient à son apparence normale, rose et propre, mais pas longtemps. S'il y a de la terre à proximité, elle reviendra et répétera la procédure. Apparemment, ils aiment ça.

CONSEILS:

- N'essayez pas de laver un cochon à moins de vouloir un cochon normal. Ce n'est pas une maladie, c'est le mode de vie d'un cochon.
- Un tel cochon sent... comme un cochon dans la boue.
- Si vous élevez des porcs et que vous voulez une descendance sale, laissez une flaque près du stylo. Ils s'arrangeront eux-mêmes.
