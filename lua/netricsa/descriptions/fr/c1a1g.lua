MESA BLACK, PROBLÈME DU SCIENTIFIQUE


Sam, scan visuel devant... Oh, ça n'a pas l'air bien. Un scientifique est debout sur ce qui reste d'une promenade. Et quand je dis "ce qui reste", je veux dire trois boulons rouillés, une prière, et beaucoup de gravité.

J'ai vérifié la probabilité de survie sur tous mes modèles. Résultat : 1% de chance qu'il y arrive. Et ce n'est que si un miracle se produit - comme un crâne qui se transforme soudainement en trampoline. Spoiler: peu probable.

Soyez prudent, car si vous vous approchez trop, les vibrations pourraient suffire à le faire descendre dans l'abîme. D'un autre côté... si tu ne t'approches pas, il tombera de toute façon. C'est un de ces scénarios de perte classique, sauf que ce n'est pas toi qui perds.

Strategic suggestion: ne gaspillez pas trop de munitions ou d'efforts ici. Si vous essayez de le sauver et de réussir, félicitations - vous venez de battre les maths. Mais je ne parierais pas mes charmantes baskets rouges dessus.