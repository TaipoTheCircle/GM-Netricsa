LOYALISTE DE COMBINE


CLASSE:      Mélanger la loyalist
MÉTABOLISME: Humains
PERCEPTION: Auxiliaires civils
TAILLE:       5,9 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Moyenne
ARMES:    Pistolet sous-machine (SMG), pistolet, stun Stun-Stick
RÉCOMPENSE:     200 FC
MENACE:     Faible

DESCRIPTION:

Combiner les loyalistes sont des civils qui ont volontairement pris parti avec le Combine, la sécurité commerciale, les rations, et l'illusion de stabilité pour la loyauté au régime. Ils sont facilement reconnus par leurs vêtements noirs et la démarche trop confiante des gens qui ont été promis « tout ira bien »

Contrairement aux soldats Overwatch, les loyalistes ne portent pas d'armure ni ne suivent un entraînement complet au combat. Leurs armes sont limitées aux SMG, aux pistolets et aux Stun-Sticks, ce qui en fait une force de soutien plus qu'un vrai combattant. Dans le combat direct, ils sont vulnérables et meurent rapidement - le Combine le sait et ne considère pas cela comme un problème.

Cependant, tous les loyalistes ne sont pas semblables. Beaucoup d'entre eux prétendent simplement être des partisans du régime. Ces doubles agents alimentent l'information de la Résistance, sabotent les ordres, et parfois tirent "accidentellement" dans la mauvaise direction. Le Combine le soupçonne, mais préfère fermer les yeux.

CONSEILS:

- Sans armure, ils sont extrêmement vulnérables - ne prolongez pas le combat.
- Tous les loyalistes ne sont pas vraiment un ennemi, mais découvrir au combat est une mauvaise idée.
- L'étourdissement Stun-Stick est dangereux, gardez vos distances.