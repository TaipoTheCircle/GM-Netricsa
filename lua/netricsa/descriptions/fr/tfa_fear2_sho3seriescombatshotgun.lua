SHO SERIES-3 ESSAIS DE LUTTE CONTRE LA PUMP-ACTION


ARME: SHO Série 3 Pompe de combat-Shotgun
MUNITIONS:   10 calibres
CADENCE DE TIR:    ~90 tours/min

DESCRIPTION:

Un puissant fusil à pompe de combat développé par la Armacham Technology Corporation (ATC). Conçu pour engager des adversaires à proximité, il dispose d'un canon à coffre lisse avec un étranglement de cylindre et un magazine tubulaire de 8 tours. Habillé pour des obus de 10 calibres, il offre une puissance d'arrêt exceptionnelle.

La SHO Series-3 est très puissante, bien qu'elle souffre d'une portée efficace limitée et d'une large diffusion. Il est rechargé manuellement, un shell à la fois. L'arme est équipée de vues en fer illuminées au tritium et d'une lampe de poche tactique « LIGHTBRINGER ». Il est principalement utilisé par des unités ATC lourdement armées.

REMARQUES:

- Utilise des munitions de calibre 10, plus puissantes que les munitions de calibre 12 plus courantes.
- Le magazine contient 8 coquilles.
- Son design intègre des éléments rappelant à la fois le Remington 870 et le Benelli M4.
- Capable de faire environ un tiers de plus de dégâts par tir que le Vollmer Ultra92.
- Recharge une coquille à la fois - mais puis à nouveau, chaque tir sert de rappel puissant de pourquoi fusils de chasse ont été inventés en premier lieu.
