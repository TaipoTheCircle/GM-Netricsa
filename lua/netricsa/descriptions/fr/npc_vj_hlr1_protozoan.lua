LE PROTOZOAN DE XEN


CLASSE:      Le protozoaire
MÉTABOLISME: filtre à gaz
PERCEPTION: Microbe aérien de Xen
TAILLE:       3-4 pieds de diamètre
ENDURANCE:  pour une durée indéterminée
HOSTILITÉ:  aucune
ARMES:    aucune
RÉCOMPENSE:     15 FC
MENACE:     aucune

DESCRIPTION:

Le protozoaire est un organisme passif et non hostile originaire de Xen. Il apparaît comme un orbe translucide, bleuâtre avec une petite sphère rougeâtre à l'intérieur, en orbite douce au-dessus du sol. Le protozoaire ne remplit aucune fonction de combat et ne présente aucune menace.

CONSEILS:

- Aucune action n'est nécessaire; le protozoaire ne s'engage ni ne présente aucun danger.
