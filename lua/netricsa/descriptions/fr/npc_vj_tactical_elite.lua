VENDU TACTIQUE DE L'ÉLITE DE COMBINE


CLASSE:      Combiner le soldat tactique Overwatch Elite
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: La force de frappe tactique la plus élevée du Combine
TAILLE:       5,9 pieds
ENDURANCE:  Extrêmement élevé
HOSTILITÉ:  Absolu 
ARMES:    AR2 Fuseau d'impulsions, Grenades
RÉCOMPENSE:     1000 FC
MENACE:     Critique

DESCRIPTION:

Le soldat tactique Combine Overwatch Elite est l'apogée des forces terrestres de Overwatch. Il porte le costume blanc standard Elite Soldier, surmonté d'une veste noire renforcée. Cette combinaison rend le soldat pratiquement invulnérable aux tirs d'armes légères et élimine complètement la vulnérabilité aux coups de tête : les coups de tête sont inefficaces en toutes circonstances.

Le Viseur Rouge n'est pas seulement une optique, mais une interface de combat liée aux protocoles centraux du Combine. Il suit les cibles, prédit les trajectoires et coordonne les actions avec d'autres unités d'élite. Un regard d'un tel soldat ressemble à une phrase prédéterminée.

Contrairement aux soldats d'élite standard, la variante tactique ne repose pas sur la surprise ou l'agression démonstrative. Il avance méthodiquement vers l'avant, contrôlant l'espace, supprimant la résistance avec un tir précis d'impulsion AR2, et défrichant les zones avec des grenades. Ses mouvements ne sont pas pressés, et les décisions sont prises plus rapidement que l'ennemi ne peut même reconnaître la menace.

CONSEILS:

- Oubliez les têtes de précision, c'est inutile.
- Utilisez des armes lourdes, des explosifs et des pièges.