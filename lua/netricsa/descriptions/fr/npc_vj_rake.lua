RAKE


CLASSE:      Râteau
MÉTABOLISME: Chasseur
PERCEPTION: Prédateur anthropomorphe nocturne
TAILLE:       5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Moyenne
ARMES:    Griffes, facteur surprise
RÉCOMPENSE:     100 FC
MENACE:     Haut

DESCRIPTION:

Le Rake est une créature qui n'existe que dans la mesure où une personne est prête à le croire. Une légende urbaine, enrichie par des témoignages oculaires, des discussions de forum et des expéditions de harceleurs. Pas une seule attaque mortelle documentée, mais des milliers d'histoires de quelque chose de mince, pâle, et griffé debout dans le coin d'une chambre et de regarder jusqu'à ce que vous ouvrez les yeux.

Selon la mythologie, le Reik est un humanoïde mince avec une peau pâle, de longues griffes pointues et parfois des traits canins. Il habite les forêts et les égouts, évitant la lumière du soleil en raison de sa peau mince. Il est actif exclusivement la nuit. Il se nourrit de carrions, le plus souvent vus sur les côtés des routes, où il prend le dessus. Il a peur des gens et essaie d'éviter de les rencontrer en personne.

Il y a plusieurs sous-espèces. Forest Reiks vivent profondément dans les forêts denses, soi-disant parlant et geste, sont faciles à communiquer et ne posent aucun danger. Sewer Reiks sont plus gris, ont une queue et un museau allongé, et se déplacent sur tous les quatre, se penchant sur leurs avant-bras, comme les gorilles. Ils sont considérés comme dangereux, même s'il n'existe aucune preuve à l'appui.

Les créatures qui visitent la nuit occupent une place spéciale dans la légende. Le Reik entre supposément dans les maisons, se tient près du lit, et regarde la personne endormie, attendant qu'ils se réveillent. Les scientifiques attribuent cela à la paralysie du sommeil : une personne rêve de ce qu'elle craint, et comme le Rake est effrayant, il apparaît. Stalkers, quant à lui, voyage à travers des bâtiments abandonnés et des forêts avec des caméras d'imagerie thermique, espérant l'attraper à la caméra.

CONSEILS:

- Si tu es dans la forêt et que tu vois une figure pâle à quatre pattes, ne cours pas. Le Rake est plus rapide.
- Dans les égouts, éloignez-vous des branches sombres - la sous-espèce des égouts est plus agressive que la forêt.
- Après avoir rencontré le Rake, vous aurez probablement des cauchemars. C'est normal. Il passera dans une semaine. Ou pas.
