CROISSANCE


ARME:      Acrobatie
MUNITIONS:        Bouchons en acier
CADENCE DE TIR:         Action du boulon, ~15 boulons/min

DESCRIPTION:

Arme de précision à longue portée équipée d'une portée. Incendie les boulons en acier silencieusement, le rendant efficace pour éliminer les cibles à distance avec une grande précision.

REMARQUES:

- Mortement précis à long terme.
- Recharge lente entre les tirs.
