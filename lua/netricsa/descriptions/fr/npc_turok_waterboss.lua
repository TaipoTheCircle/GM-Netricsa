BÊTE D'EAU DE LA PLANTE TERRAFORME


CLASSE:      Bête d'eau
MÉTABOLISME: Prédateur d'eau profonde
PERCEPTION: Ancien monstre souterrain
TAILLE:       60 pieds (partie principale)
ENDURANCE:  Extrême
HOSTILITÉ:  Absolu
ARMES:    Tentacles, jets de roche, stalactites
RÉCOMPENSE:     5000 FC
MENACE:     Absolu

DESCRIPTION:

Personne ne sait combien de temps cette créature a passé dans les grottes souterraines, mais à en juger par sa taille et son agressivité, elle est là depuis le temps des dinosaures, et elle ne s'est jamais plainte d'un manque de compagnons.

En apparence, la bête est un hybride d'une anguille, d'une pieuvre et d'un dunkléostée.

Au combat, la bête est immobile, elle est liée à son repaire sous-marin et ne peut quitter l'eau. Mais ça ne rend pas ça moins dangereux. Son attaque principale est une balle avant, essayant de dévorer sa cible. Entre les attaques, la bête crie avec ses tentacules, déchire les rochers du sol et les jette, et déchire les stalactites du plafond. Le dernier est le plus mortel.

À chaque explosion réussie, la bête saignera de plus en plus jusqu'à ce qu'elle périsse complètement.

CONSEILS:

- Ne bougez pas.
- Il y a une pause entre les attaques et l'utiliser pour recharger et reprendre votre souffle.
- Utilisez des explosifs.
