HALF-QUAKE 2, CABINE DE VIE ET DE MORT


Sam, attends ! Regardez ce que nous avons ici... Un autre "cadeau" de nos amis sadiques.

Ce sont des stands. Juste deux boutons : « Vie » et « Mort ». Appuyez sur "Vie" et vous serez complètement guéri. Les fractures, les blessures, même votre fatigue éternelle, tout passera. Appuyez sur "Mort"... eh bien, vous voyez l'idée. Une issue fatale. Aucune option.

...

Et oui, une seule fois. Vous ne pouvez pas le rejouer, vous ne pouvez pas demander une seconde chance. Comme dans la vraie vie, Sam. Sauf que dans la vraie vie, vous n'aviez pas de bouton intitulé "Mort".

Nous verrons ces stands tout au long du salon. Alors n'oubliez pas : si vous êtes à cran, appuyez sur « Vie ». Mais si jamais vous voulez tester si "Death" fonctionne, allez-y, laissez-moi tranquille. J'ai encore beaucoup à faire, comme analyser vos erreurs !

Passons à autre chose. Et ne pensez même pas à appuyer sur le bouton Mort par curiosité ! Sinon, à quel point es-tu sérieux ?