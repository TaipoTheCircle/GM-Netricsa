HALF-QUAKE 2, LA VIE ET LA MORT


Sam, attendez ! Regarde ce qu'on a ici... Un autre cadeau de nos amis sadiques.

Ce sont des cabines. Deux boutons : "La vie" et "La mort". Appuyez sur "Vie", et vous serez complètement guéri. Fractures, blessures, même votre fatigue éternelle, tout passera. Appuyez sur "Mort"... Eh bien, vous avez l'idée. Une issue fatale. Aucune option.

...

Et oui, une seule fois. Tu ne peux pas le rejouer, tu ne peux pas demander une seconde chance. Comme dans la vraie vie, Sam. Seulement dans la vraie vie, tu n'avais pas de bouton marqué "mort"

Nous verrons ces stands tout au long du spectacle. Alors rappelez-vous : si vous êtes sur le bord, appuyez sur "Vie". Mais si tu veux tester si "la mort" marche, vas-y, laisse-moi tranquille. J'ai encore beaucoup à faire, comme analyser vos erreurs !

Passons à autre chose. Et ne pensez même pas à appuyer sur le bouton Mort par curiosité ! Sinon, vous êtes sérieux ?
