EXCAVATIONS PROFESSIONNELLES, RECHERCHES PROFESSIONNELLES


Nous nous sommes retrouvés dans une fouille archéologique. Un centre de recherche qui creuse dans les ruines de quelque chose de très ancien. Et à en juger par ce qui est enterré ici, ils ne se contentaient pas de creuser.

Au centre se trouvent les restes d'un temple ou d'un monument antique, construit à partir de blocs de pierre massifs.

La chose principale ici est quelque chose d'autre - un secret qui mérite d'être creusé.

Quelque part dans le site de fouille, caché sous le symbole de résistance lambda, est un cube orange, clairement pas d'origine locale.

Brisez le cube. Briser la coquille extérieure, et les chutes... le légendaire The Orange Box. Oui, Sam, la même boîte qui a donné au monde Half-Life 2, Portal et Team Fortress 2.

Ouvre la boîte. Et c'est là que commence l'apocalypse. Une fois que l'Orange Box sera brisé en morceaux, Nuclear Mission Jam fera sauter à travers les haut-parleurs - cette piste épique qui transforme toute bataille en un abattage légendaire.

Allons chercher le cube.

And remember: ne l'écrasez pas, mais faites-le avec le sentiment. Avec but. Avec arrangement.
