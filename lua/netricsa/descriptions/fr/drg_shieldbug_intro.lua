SWARM SHIELDBUG


CLASSE:      Swarm Shieldbug
MÉTABOLISME: Xénobiologique
PERCEPTION: Organisme chargé d'assauts
TAILLE:       9,8 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Haut
ARMES:    Membres blindés, grève
RÉCOMPENSE:     1000 FC
MENACE:     Très élevé

DESCRIPTION:

Le Shieldbug est l'une des formes de combat les plus blindées du Swarm. L'avant de son corps est recouvert de plaques chitineuses massives capables de résister aux dommages colossaux. Cela permet à la créature d'avancer sous un feu lourd, couvrant des membres de Swarm moins durables.

L'arme principale du Shieldbug est son front élargi. Les utiliser comme un bélier vivant, il délivre des coups puissants capables de frapper les adversaires à une distance considérable. Il y a eu des cas où des victimes sont mortes non pas du coup lui-même, mais des collisions subséquentes avec des objets environnants ou des chutes de grandes hauteurs.

Malgré son armure frontale pratiquement impénétrable, le corps a des zones vulnérables. La zone la moins protégée reste l'arrière du corps, où se trouvent les principaux organes de survie. Pour cette raison, le Shieldfoot essaie instinctivement de garder son adversaire devant lui et est extrêmement réticent à se retourner pendant le combat.

Contrairement à la plupart des membres du Swarm, le Shieldfoot agit rarement chaotiquement. Une fois qu'il a localisé une cible, il peut la poursuivre méthodiquement pendant longtemps, ignorant les adversaires moins dangereux et se concentrant sur sa proie choisie.

CONSEILS:

- Ne gaspillez pas de munitions sur l'armure frontale.
- Essayez d'attaquer par les flancs ou par l'arrière.
- Ne laissez pas Shieldfoot vous conduire dans des précipices et des passages étroits.
- Si une créature de la taille d'un module de transport décide de vous suivre, ce n'est pas une raison d'être fière.
