BUREAUX DU MESA BLACK, PATH À L'ÉLÉVATEUR


On y est presque. Les escaliers sont derrière nous, nous avons contourné les forces de Mental, et maintenant nous sommes face au dernier tronçon avant l'ascenseur. Un couloir. Longue, sinueuse. Au bout, une porte ouverte. Dans l'ascenseur.

Problem: S.E.C.U. est dans le couloir. Ils sont là. Pas en haut, pas derrière les barricades, ici, entre nous et le puits. Ils savent que l'ascenseur est le seul moyen rapide. Et ils ne veulent pas que quelqu'un l'utilise. Ils se fichent de qui. Un scientifique, un extraterrestre, un spectateur. L'ordre est le même : personne ne passe.

Mais il y a de bonnes nouvelles. Les forces mentales ne viennent pas ici. Je sais pas pourquoi. Ils n'ont pas besoin de l'ascenseur, ou le couloir est trop étroit, ou ils ont simplement décidé que les Marines sont le problème de Sam Stone, pas le leur. Donc c'est juste vous et S.E.C.U.

L'ascenseur est notre billet au sommet. Peut-être à la sortie. Peut-être au niveau suivant de ce cirque. Mais nous devons y aller. Parce que là-haut, il y a le salut ou un autre combat. Et là-bas, il n'y a qu'un couloir plein de marines et un puits sans fond.

L'ascenseur attend. J'espère que ça marche encore.
