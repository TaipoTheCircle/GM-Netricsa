KLEER SKELETON, COMMUN


CLASSE:      Squelette kleer, commune
MÉTABOLISME: Morts
PERCEPTION: Créature magique
TAILLE:       9 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Moyenne
ARMES:    Projectiles à deux bals, griffes, cornes
RÉCOMPENSE:     100 FC
MENACE:     Moyenne

DESCRIPTION:

Un squelette non mort d'un être d'une race disparue de la planète Kleer, d'Alpha Canis Majoris. Il a de longues griffes pointues sur ses mains et une longue queue.

Ils attaquent soit en conjurant des projectiles, en frappant avec leurs griffes de la mêlée ou en sautant vers leur ennemi quand ils sont à portée de main.

Ces personnes ont été récemment levées de la tombe. Vous pouvez le dire par la couleur de leurs os et le manque d'odeur comme 5000 ans de cendres.

CONSEILS:

- Leur saut et les attaques variées sont mieux évités par le pas latéral.
- Un coup de fusil à double canon va les faire sauter.
- Le minigun est votre meilleur ami et leur pire cauchemar.
