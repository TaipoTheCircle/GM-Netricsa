UNE PLANTE MATÉRIELLE


PLANET:       La planète qui matérialise les pensées
TYPE:         Planète terrestre, monde psychotrope
CLIMATE:      Atmosphère impropre à la respiration
MOONS:        Inconnu
TERRAIN:      Surface rocheuse, volcans, complètement dépourvus de vie
LOCATION:     Système étoile inconnu
NATIVE RACES: Aucune (des pensées matérialisées peuvent apparaître temporairement)
ALLIANCE:     Inconnu
LOCATIONS:    Site d'atterrissage de Charolet Crash, réplique de la vallée de Chamomile

DESCRIPTION:

L'atmosphère de la planète est totalement inapte à respirer, et la surface est un paysage rocheux sans vie parsemé de nombreux volcans. Il n'y a pas de végétation, pas de vie animale et aucun signe de vie biologique.

La propriété unique de la planète est sa capacité à matérialiser les pensées de tout être sentient à sa surface. Ces pensées deviennent des objets très réels et tangibles qui existent dans l'espace proche de la planète. Cependant, ces objets dématérialisent complètement dès que leur créateur quitte la planète.

Quand le Charolet, épuisé de carburant, a fait un atterrissage d'urgence sur cette planète, un pilote nommé Pin, qui s'est retrouvé dessus, a utilisé cette propriété pour résoudre le problème. Il a matérialisé une réplique exacte de sa vallée de Chamomile, avec ses habitants, et ensuite, en utilisant les plans stockés dans l'appareil, a créé un moteur ionique, lui permettant de quitter la planète.

Alors qu'il quittait la planète, Pin laissa les copies matérialisées de ses amis avec des conseils : s'ils continuaient à penser les uns aux autres, ils seraient en mesure de maintenir leur existence après son départ.

Les chercheurs pensent que la planète peut posséder une intelligence collective inconsciente ou de terrain qui répond à l'activité mentale des visiteurs, mais la nature exacte de ce phénomène reste inconnue.

KEY LOCATIONS:

- Lieu d'atterrissage de Charolet Crash : La zone rocheuse où le navire s'est écrasé.
- Réplique de la vallée de la Camomille : Réplique exacte et matérialisée du village d'origine de Pin, créée par la puissance de la pensée et existant grâce à l'énergie mentale de son créateur. Comprend des répliques exactes de bâtiments et d'habitants, possédant un semblant de conscience.
