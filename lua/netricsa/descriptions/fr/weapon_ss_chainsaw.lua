DESCRIPTION:

Cette arme familière n'a l'air faite que sur Terre. Il semble que seul son design et son but ont été tirés du concept du design familier de la tronçonneuse. À l'intérieur du boîtier en alliage de titane, vous trouverez un synthétiseur de combustible de micro fusion autonome qui est capable de produire suffisamment de carburant pour 10000 ans de fonctionnement continu. Malheureusement, il n'y a qu'une garantie de 6 mois pour toutes les pièces mobiles et elles ont tendance à se casser très peu après cette période. Vraiment une merveille de l'ingénierie et de l'économie modernes.


