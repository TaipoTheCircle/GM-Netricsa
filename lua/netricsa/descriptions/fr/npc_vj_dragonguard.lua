GARANTIE IMPÉRIELLE DU DRAGON DE NIRN


CLASSE:      Garde impériale Dragon
MÉTABOLISME: Mer, Homme
PERCEPTION: Gardien de zone interdit / Garde impériale Elite
TAILLE:       5,9 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Très élevé
ARMES:    Longs mots, boucliers lourds, parfois magiques
RÉCOMPENSE:     10000 FC
MENACE:     Très élevé

DESCRIPTION:

Il ne s'agit pas simplement d'une unité d'élite de la Légion impériale, mais d'un mythe enveloppé de mystère. Contrairement à la Garde Royale Impériale, qui surveille visiblement l'Empereur et le Palais, ces gardes opèrent dans l'ombre. Leur travail est de patrouiller les fouilles interdites, les forts abandonnés, les tombes anciennes, et d'autres endroits dangereux où les simples mortels sont interdits d'entrer. On pense que cette unité a été formée par ordre personnel de l'empereur Uriel Septim VII avant la crise d'oblivion pour protéger des sites stratégiquement importants reliés à des artefacts sombres et des passerelles vers d'autres mondes.

Leur caractéristique la plus distinctive est le légendaire Dragon Armor Impérial. Cette armure unique était traditionnellement portée seulement par la garde spéciale qui protégeait personnellement l'Empereur et sa famille. Forgé des meilleurs matériaux disponibles à l'Empire, l'armure est considérée comme un symbole de la plus haute valeur et confiance. On sait qu'un tel procès a été présenté au héros de Kvatch en reconnaissance de son service.

Alors que l'information sur la Garde Impériale Dragon est extrêmement limitée, leurs origines sont probablement liées à une organisation encore plus ancienne:

Dragon Guard: Une organisation d'élite, le prédécesseur des Blades, qui gardait les empereurs de la dynastie Reman. Ils étaient plus que des gardes, mais une force spéciale et une armée personnelle pour l'empereur.

CONSEILS:

- Si vous voyez un garde dans Imperial Dragon Armor, vous êtes dans une zone restreinte. De rien. Partez avant qu'il ne soit trop tard.
- Ces gardes sont mortels au combat. Leur armure offre une résistance à la magie, au feu, au froid et à l'électricité. Les tactiques standard sont inutiles contre eux.
- La meilleure stratégie est la furtivité. Si tu es repéré, cours. Le combat direct avec une Garde Impériale Dragon est une mort certaine, même pour un aventurier chevronné.
