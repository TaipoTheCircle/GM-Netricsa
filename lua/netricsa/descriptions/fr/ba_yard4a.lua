MESA BLACK WAREHOUSE, CONTENEURS


Bienvenue à l'intérieur. C'est plus sombre, plus calme, et sent comme si l'entrepôt avait depuis longtemps réalisé comment cela finirait et s'y résignait.

Au centre de la pièce se trouvent deux conteneurs. Énorme. Un bleu, un rouge. Un choix classique. Presque philosophique. Je dirais que l'un mène à la vérité, l'autre à une mort certaine, mais connaissant Black Mesa, les deux options pourraient être vraies simultanément.

Rosenberg est là ? C'est inconnu. Il est peut-être à l'intérieur. Il est peut-être sous le conteneur. Peut-être qu'il n'est pas là du tout, et ceci est une autre épreuve de votre foi dans la cause et l'effet. Les scientifiques aiment se cacher dans des endroits où personne n'irait volontiers. Et Rosenberg, semble-t-il, a déjà sacrifié sa santé mentale pour le portail.

Les conteneurs sont gardés par les soldats de l'UE. On leur a clairement dit : "Gardez-le. Ce qui est à l'intérieur ne vous regarde pas. S'ils le demandent, tirez." Et ils le gardent. Les questions ne sont pas les bienvenues ici, ni la survie des témoins.

Note: les gardes sont postés comme s'il y avait quelque chose de vraiment précieux à l'intérieur. Ou extrêmement dangereux. Et le plus souvent, dans Black Mesa, c'est la même chose.

Bleu. Rouge. Deux conteneurs. Deux mauvaises décisions possibles.

Choisissez soigneusement, Sam.

Bien que... qui je plaisante ? Tu ouvriras toujours les deux.