SPRINGFIELD M1903 RIFLE


ARME : Springfield M1903 Rifle
MUNITIONS : .30-06 Springfield (7.62x63mm)
ROF : ~15-20 tours/min
POIDS : ~3,95 kg

DESCRIPTIF :

Ce fusil à répétition américain à verrou, basé sur le modèle Mauser, a été adopté par l'armée américaine au début du XXe siècle. La version la plus célèbre était chambrée pour la cartouche Springfield .30-06, utilisée pendant les deux guerres mondiales.

Le fusil est conçu pour un tir précis à moyenne et longue portée. Le mécanisme à verrou garantit un fonctionnement fiable et permet au tireur de chambrer manuellement le coup suivant après chaque tir. Le M1903 a également été produit en version tireur d'élite avec viseur optique.

Le Springfield M1903 combine une cartouche de fusil puissante, une bonne précision et un poids relativement léger. Cela le rendait adapté à la fois à l'infanterie régulière et aux tireurs d'élite spécialisés.

REMARQUES :

- Particulièrement efficace à moyenne et longue portée, là où brille la précision du M1903.
- When you need an old-school American rifle: no bursts, just a bolt, scope, and a very convincing argument.
- Sniper variants with optics allow the rifle to be used for engaging individual targets at long ranges.
- The .30-06 cartridge offers high power and good range.
