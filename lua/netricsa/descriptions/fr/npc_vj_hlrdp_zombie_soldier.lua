Y.S.M. ZOMBIE HEADCRAB, COMMUN


CLASSE:      A.M. Zombie Gras, Fréquent
MÉTABOLISME: Hôte humain + tête parasite de Xen
PERCEPTION: Entité zombifiée, ancien contractant
TAILLE:       6,2 pi
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    Griffes, Bite
RÉCOMPENSE:     500 FC
MENACE:     Très élevé

DESCRIPTION:

C'est ce que les mercenaires de la compagnie militaire privée Y.S.M. se transforment en après une rencontre malheureuse avec un crâne. Contrairement aux scientifiques en manteau gris, aux techniciens en couverture ou même aux gardes de la base Delta, ces hommes étaient à l'origine des soldats professionnels. Ils portaient une armure corporelle, des casques tactiques et savaient manier les armes. Cela ne les a pas sauvés de l'infection, mais cela les a rendus beaucoup plus dangereux adversaires dans leur forme zombifiée.

Leur armure protège partiellement leurs corps des tirs, les rendant plus résistants que les zombies réguliers. Le headcrab perché sur leur tête ressemble à celui d'autres variantes, mais son hôte est un corps musclé entraîné qui ne se détache pas d'un couple de coups.

Ils sont plus grands que les gardes de la base Delta, leur armure est plus épaisse, et leurs coups sont plus lourds. Même après que le headcrab prenne le contrôle, l'ancien mercenaire conserve la mémoire musculaire : ils se déplacent plus rapidement que les zombies réguliers. Leurs griffes percent l'armure, et leurs morsures déchirent des morceaux de chair.

Un coup de tête détache la tête.

CONSEILS:

- Les zombies Y.S.M. sont plus résistants que tous les autres zombies standard. Ne gâche pas les munitions.
- Son armure protège sa poitrine et ses épaules. Visez la tête, elle est vulnérable, comme tout le monde.
- Gardez votre distance-il est un peu plus rapide qu'un zombie normal.
- Ne pensez pas que les restes de son équipement tactique soient des trophées. Il n'en a plus besoin, et vous, certainement pas.
