LE MONDE FRONTIÈRE DE XEN, LES CAVES DE XEN


Xen a décidé de révéler son fonctionnement intérieur. Pas métaphoriquement. Littéralement.

Des grottes. Des labyrinthes. Des couloirs en pierre qui semblent avoir été conçus par quelqu'un qui détestait vraiment les lignes droites et les visiteurs.

C'est plein de créatures Xen. Ils bougent, respirent, crachent, et généralement vous considèrent comme une intrusion dans le paysage. Une horde de Mental erre parmi eux, explorant avec confiance ce monde extraterrestre, comme si Xen avait toujours fait partie de l'occupation. Deux types de chaos qui entrent en collision dans un espace confiné. Le résultat est prévisible : tout le monde tire.

Les grottes s'étendent vers l'intérieur et l'extérieur, déroutant des repères et des pensées. C'est facile de se perdre ici. Encore plus facile de trébucher sur quelque chose qui vous préférerait pas. Il semble que Xen lui-même ne se rappelle pas complètement où ses tunnels mènent. Il continue de les construire.

Et oui, il y a une autre grotte sous l'eau. Caché. Du calme. Les Chumtoads y vivent. Les créatures que vous découvrez habituellement après le fait.

Sois prudent, Sam.