BERETTA M1934 PISTOL


ARME : Beretta M1934 Pistol
MUNITIONS : 9x17mm Browning Short (.380 ACP)
ROF : ~30-40 rounds / min
POIDS : ~0,605 kg

DESCRIPTIF :

This Italian semi-automatic pistol was developed by Beretta and adopted in 1934. It was designed as a compact military sidearm and was widely adopted by the Italian armed forces. Production continued for decades, with over a million units produced.

Le pistolet utilise une action de retour de flamme et la glissière ouverte caractéristique de Beretta, laissant la majeure partie du canon visible. Le canon est fixé pendant le tir et le pistolet lui-même se caractérise par sa conception simple et sa facilité d'entretien.

The M1934's primary ammunition is the 9x17mm. Il existait également une variante étroitement liée, le Beretta M1935, chambré pour la cartouche 7,65x17 mm. Le M1934 a été utilisé par l'armée italienne pendant la Seconde Guerre mondiale, et certains exemplaires capturés ont été utilisés par d'autres pays.

REMARQUES :

- A compact and lightweight pistol, well-suited for close-quarters combat.
- La culasse ouverte est devenue l'une des caractéristiques les plus reconnaissables des pistolets Beretta classiques.
- The M1934 was produced in huge quantities and remained in production for many decades.
- Ce pistolet a même fait une apparition dans le cinéma soviétique : il était manié par le personnage principal, Semyon Semyonovich Gorbunkov, dans "Le bras de diamant".
