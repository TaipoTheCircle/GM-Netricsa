PISTOLET BERETTA M1934


ARME : Pistolet Beretta M1934
MUNITIONS : 9x17 mm Browning Short (.380 ACP)
ROF : ~30-40 tours/min
POIDS : ~0,605 kg

DESCRIPTIF :

Ce pistolet semi-automatique italien a été développé par Beretta et adopté en 1934. Il a été conçu comme une arme de poing militaire compacte et a été largement adopté par les forces armées italiennes. La production s'est poursuivie pendant des décennies, avec plus d'un million d'unités produites.

Le pistolet utilise une action de retour de flamme et la glissière ouverte caractéristique de Beretta, laissant la majeure partie du canon visible. Le canon est fixé pendant le tir et le pistolet lui-même se caractérise par sa conception simple et sa facilité d'entretien.

La munition principale du M1934 est la 9x17 mm. Il existait également une variante étroitement liée, le Beretta M1935, chambré pour la cartouche 7,65x17 mm. Le M1934 a été utilisé par l'armée italienne pendant la Seconde Guerre mondiale, et certains exemplaires capturés ont été utilisés par d'autres pays.

REMARQUES :

- Un pistolet compact et léger, bien adapté au combat rapproché.
- La culasse ouverte est devenue l'une des caractéristiques les plus reconnaissables des pistolets Beretta classiques.
- Le M1934 a été produit en grandes quantités et est resté en production pendant plusieurs décennies.
- Ce pistolet a même fait une apparition dans le cinéma soviétique : il était manié par le personnage principal, Semyon Semyonovich Gorbunkov, dans "Le bras de diamant".