BÉRETTA M1934 PISTOL


ARME: Beretta M1934 Pistol
MUNITIONS:   9x17mm Bruning Short (380 ACP)
CADENCE DE TIR:    ~30-40 tours/min
POIDS: ~0,605 kg

DESCRIPTION:

Ce pistolet semi-automatique italien a été développé par Beretta et adopté en 1934. Il a été conçu comme une arme militaire compacte et a été largement adopté par les forces armées italiennes. La production a continué pendant des décennies, avec plus d'un million d'unités produites.

Le pistolet utilise une action de rappel et la diapo signature de Beretta, laissant la plupart du canon visible. Le canon est fixé pendant le tir, et le pistolet lui-même se caractérise par sa conception simple et sa facilité d'entretien.

Les munitions primaires du M1934 sont les 9x17mm. Il y avait aussi une variante étroitement liée, la Beretta M1935, en chambre pour la cartouche de 7,65x17mm. Le M1934 a été utilisé par l'armée italienne pendant la Seconde Guerre mondiale, et certains exemples capturés ont été utilisés par d'autres pays.

REMARQUES:

- Un pistolet compact et léger, bien adapté pour le combat de quartier rapproché.
- La diapositive ouverte est devenue l'une des caractéristiques les plus reconnaissables des pistolets Beretta classiques.
- Le M1934 a été produit en grandes quantités et est resté en production pendant de nombreuses décennies.
- Ce pistolet a même fait une apparition dans le cinéma soviétique: il a été manié par le personnage principal, Semyon Semyonovitch Gorbunkov, dans "Le bras de diamant".
