GONARCH DE XEN


CLASSE:      Gonarque
MÉTABOLISME: surlord parasitaire
PERCEPTION: Matriarche à tête
TAILLE:       ~20 pieds de haut
ENDURANCE:  extrêmement élevé
HOSTILITÉ:  extrême
ARMES:    jambes écrasées, projectiles acides
RÉCOMPENSE:     2000 FC
MENACE:     catastrophique

DESCRIPTION:

Le Gonarque est l'étape finale et la plus terrifiante du cycle de vie du crâne. C'est une matriarche colossale, semblable à une araignée, avec un sac d'oeuf grotesque qui traîne sous son corps, produisant un nombre sans fin de cratères. Adorée ou redoutée par de petits parasites, elle sert à la fois de sélectionneur et de commandant de l'infestation. Rencontre dans les royaumes les plus profonds de Xen, le Gonarque charge sa proie de pattes imposantes, crache de l'acide et libère des griffes de crânes nouveau-nés. Ses écharpes déformées résonnent à travers des cavernes comme un cri de bataille cauchemardesque.

Les légendes suggèrent que chaque infestation de crânes finit par remonter à un Gonarque. Tuer quelqu'un n'est pas un petit exploit. Mais tu n'es pas un de ces chanceux, n'est-ce pas ?

CONSEILS:

- Concentrez le feu sur le sac pour l'affaiblir.
- Ses charges sont mortelles dans des espaces confinés.
- Soyez prêt pour des vagues sans fin de têtes pendant le combat.
