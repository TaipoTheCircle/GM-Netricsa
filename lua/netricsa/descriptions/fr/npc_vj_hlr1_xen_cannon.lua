XEN SENTRY CANNON


CLASSE:      Cannon Xen Sentry
MÉTABOLISME: Énergie électromagnétique
PERCEPTION: Plateforme de défense autonome de Xen
TAILLE:       Variable
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Faisceau d'énergie pivotant
RÉCOMPENSE:     400 FC
MENACE:     Moyenne-élevée

DESCRIPTION:

Le Xen Sentry Cannon est une tourelle autonome déployée par les Alien Grunts au sein de Xen. Il est doté d'une base métallique avec quatre longues branches qui pivotent dans n'importe quelle direction, libérant un formidable faisceau d'énergie bleue aux intrus. Malgré sa conception extraterrestre, le canon se comporte comme une plate-forme d'armes artificielles, lorsqu'il est détruit, sa structure s'écroule comme du béton.

CONSEILS:

- Approchez soigneusement-le canon s'active quand il détecte le mouvement.
- Utilisez des armes variées pour les détruire à distance.
- Les explosifs sont particulièrement efficaces pour les désactiver rapidement.
