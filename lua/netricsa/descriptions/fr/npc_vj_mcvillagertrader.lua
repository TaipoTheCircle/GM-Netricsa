VU LE COMMERCE DE L'EXTERIEUR MINECRAFT


CLASSE:      Marchands errants
MÉTABOLISME: Humain, Homme
PERCEPTION: Trader errant / Fournisseur exotique
TAILLE:       6,2 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Passif
ARMES:    Aucune
RÉCOMPENSE:     150 FC
MENACE:     Minimal

DESCRIPTION:

Une figure mystérieuse dans une robe à capuche bleue, dont les origines restent un mystère même pour les villageois. Ce vagabond énigmatique erre dans l'Overworld, cherchant des clients prêts à échanger des émeraudes contre des produits rares et exotiques.

L'apparence du commerçant est sensiblement différente de celle des villageois ordinaires. Au lieu des vêtements traditionnels, il porte une longue robe bleue avec une capuche qui cache son visage et une cape de la même couleur.

À chaque voyage, le trader est accompagné de deux lamas de trader, attachés à lui par des laisses. Ces animaux robustes ne portent pas seulement la charge mais protègent aussi leur maître : si le trader est touché, les lamas commencent immédiatement à cracher sur le délinquant. Les lamas eux-mêmes peuvent être apprivoisés après la mort de leur maître, attendre qu'ils se calment.

Contrairement aux villageois, le commerçant n'achète pas d'articles, il les vend seulement. Son inventaire est aléatoire et comprend des marchandises rares qui sont difficiles à obtenir.

L'astuce principale du trader est la survie. À la tombée de la nuit ou en voyant une foule hostile, il boit une potion invisible, devenant presque invisible, bien que les laisses de lalama soient encore visibles. À l'aube, il lave l'effet avec du lait. Si un zombie tue le trader, il ne deviendra pas un villager zombie.

Tuer un trader diminue votre réputation - les traders subséquents apparaîtront moins fréquemment, et leurs prix augmenteront.

CONSEILS:

- On a toujours des émeraudes à portée de main - on ne sait jamais ce qu'un trader apportera.
- Si vous avez besoin de ses lamas, il vaut mieux attendre que le trader disparaisse - alors les lamas resteront et pourront être domptés.
- En attaquant un trader, soyez prêt à être craqué par ses lamas.
- Si vous ne voyez que des laisses flottantes, cela signifie que le trader a consommé une potion d'invisibilité et est quelque part à proximité.
- Le trader est vulnérable la nuit - la potion d'invisibilité ne le rend pas complètement invulnérable, ça le cache.