PLANTE DES TROIS CAPTAINES


PLANET:       Planète des trois capitaines
TYPE:         Planète terrestre, Monde commémoratif
CLIMATE:      Entretien artificiel, respirant
MOONS:        Inconnu
TERRAIN:      A l'origine des roches sans vie; équipées de générateurs d'atmosphère
LOCATION:     Système étoile inconnu dans la galaxie de la Voie lactée
NATIVE RACES: Aucune (planète touristique)
ALLIANCE:     Complexe commémoratif intergalactique
LOCATIONS:    Statue de soixante mètres des trois capitaines, Musée de la cosmonautique

DESCRIPTION:

Un monde mémorial unique nommé en l'honneur de trois héros spatiaux légendaires qui ont accompli de nombreux exploits et découvertes remarquables lors de leurs voyages à travers la galaxie. Initialement, il s'agissait d'une planète inhabitée sans nom, complètement inhabitable en raison du manque d'atmosphère.

Pour perpétuer la mémoire de ces célèbres capitaines, la planète était spécialement équipée de puissants générateurs qui produisent de l'oxygène et créent des conditions respirantes, la rendant accessible aux touristes de tous les coins de la galaxie.

L'attraction principale et le symbole de la planète est une statue colossale en pierre de soixante mètres représentant les trois capitaines. Ce monument est visible de loin et sert de repère à tous ceux qui arrivent sur la planète.

À côté de la statue se trouve le Musée de la cosmonautique - une collection unique d'artefacts, de documents et de preuves de l'époque de la grande exploration spatiale. Le musée a été construit avec des dons volontaires recueillis de quatre-vingts planètes dans le système des étoiles, ce qui en fait un véritable repère galactique.

KEY LOCATIONS:

- La statue de soixante mètres des trois capitaines: Le monument principal de la planète, qui représente trois héros spatiaux légendaires, sert de repère et de symbole à la planète.
- Musée de la cosmonautique : Une collection unique d'artefacts et de documents dédiés à l'ère des grandes découvertes spatiales. Construit avec des dons des habitants de quatre-vingts planètes.
