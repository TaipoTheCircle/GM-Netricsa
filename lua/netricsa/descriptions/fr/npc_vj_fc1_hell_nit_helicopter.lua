HELL NIT UH-60 "BLACKHAWK" HÉLICOPTRE DE PATROL DE L'ARCHIPELAGO KRIEGER


CLASSE:      Hélicoptère de patrouille Hell Nit UH-60 "Blackhawk"
MÉTABOLISME: Esprit ardent, Essence immortel
PERCEPTION: La colère immortale du Moai
TAILLE:       ~16,7 pieds
ENDURANCE:  Absolu
HOSTILITÉ:  Absolu
WEAPONAGO:  Minigune hyperchargée
RÉCOMPENSE:     0 (la paye de l'hélicoptère a été brûlée)
MENACE:     Absolu

DESCRIPTION:

Ce n'est pas l'arme d'une compagnie. C'est l'archipel lui-même qui vient pour ce qui lui est dû. Et ça ne s'arrêtera pas avant qu'il ne prenne tout. C'est la manifestation ultime de la colère du Moaï non payé. Un esprit de rage immortel, matérialisé dans un hélicoptère UH-60 Blackhawk déformé, brillant de plasma volcanique pourpre. Toute la coque est repeinte d'un enfoiré d'enfer, de flammes insaisissables qui s'enflamment des fissures, et la bosse standard des moteurs est remplacée par le rugissement de la haine ancienne et insaisissable et de la musique génocidaire. Son arme principale est un mini-gun hyperchargé, dont les balles ne causent pas de dommages mais le concept absolu de mort. Son but n'est pas de patrouiller, mais le nettoyage complet de l'archipel de toute vie, y compris les mercenaires de Krieger, les Trigens, et, bien sûr, Jack Carver. Il vole le salaire pour trois jours de salaire non payé, élevé à l'absolu.

CONSEILS:

- Reste dehors. Une explosion, un obus, une mort garantie. La couverture, autre que massive, des roches indestructibles ou des bunkers souterrains, est inutile - ses tirs brûlent dans le béton et l'acier.
- C'est impossible de le détruire.
- L'attirer à des bases mercenaires ou à des groupes de Trigen. Sa rage est aveugle, et il attaquera tout, le distrait de vous.
