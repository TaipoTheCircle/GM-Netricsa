RPG-7


ARME:      RPG-7 (Launcheuse à grenade à roues)
MUNITIONS:        Fusées à forte explosion
CADENCE DE TIR:         ~4 fusées/min

DESCRIPTION:

Lance-roquettes anti-armes portables capables de tirer des fusées à forte explosion. Efficace contre les véhicules, les positions fortifiées et les groupes d'ennemis. Un système de visée simple permet d'utiliser à la fois des soldats entraînés et des insurgés.

REMARQUES:

- Dommages explosifs massifs dans la zone cible.
- Des munitions limitées; chaque fusée doit être soigneusement dirigée.
- Dostal peut être dangereux si tiré dans des espaces confinés.
- Recharge nécessaire après chaque tir.