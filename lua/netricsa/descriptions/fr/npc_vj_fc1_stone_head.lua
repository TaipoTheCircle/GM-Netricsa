FACE DE L'ARCHIPELAGO DE KRIEGER


CLASSE:      Visage maléfique de pierre
MÉTABOLISME: Pierre vivante
PERCEPTION: Moai non payé
TAILLE:       ~14,7 pieds
ENDURANCE:  Extrêmement élevé
HOSTILITÉ:  Extreme (en raison des salaires non payés)
ARMES:    2 M4 modifiés géants, écrasement de la tête
RÉCOMPENSE:     0 (pas de salaire)
MENACE:     Très élevé

DESCRIPTION:

Une ancienne idole de pierre, Moai, a donné vie à travers des circonstances inconnues et a habité profondément dans la jungle. Sa principale motivation est trois jours de salaire impayé comme un maçon de pierre, ce qui le pousse dans un état de rage. Malgré son manque d'armes, il manie et tire deux fusils d'assaut M4 massifs montés sur ses côtés. Son attaque principale est un stomp écrasant avec sa tête massive, causant une onde de choc et jetant des arbres et des sangliers. Il possède une longévité colossale.

CONSEILS:

- Un feu lourd de deux M4s de calibre élevé et une attaque dévastatrice qui provoque des tremblements de terre et des stons font de lui un adversaire dangereux.
- Les explosifs (les lance-grenades, C4) sont efficaces contre les structures en pierre.
- Potentiellement, il pourrait être "pacifié" en trouvant et en rendant son trésor - son "salaire non payé". Mais vous ne l'avez pas.
- Vous pouvez l'apaiser avec des pastèques.
