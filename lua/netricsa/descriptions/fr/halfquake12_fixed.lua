On est enfin arrivés au stand du réalisateur.

SOMOS se tient au centre de la pièce, entouré d'un bouclier énergétique, comme un roi effrayé par ses propres sujets. Les armes classiques sont inutiles ici. Les balles rebondissent, comme les plaintes du public sur la politique de l'émission.

Les sadiques se sont avérés non seulement sadiques, mais aussi ingénieurs. La machine maintient son état « divin » à travers un système de boutons. Quatre nœuds. Quatre points de douleur. Quatre arguments contre son éternité.

Les boutons sont gardés par les Vortigaunts.

The irony: ils ne savent même pas que les forces de Mental sont considérées comme des alliés. Ils ont donc battu tout le monde en vue, y compris ceux supposément "sous contrat".

Le chaos pur, l'environnement opérationnel parfait pour vous.

Désactivez les quatre premiers, et la prochaine porte s'ouvre. Il y a un bouton pour la deuxième étape du captcha.

Oui, Sam. Même cet enfer a mis en place l'authentification à deux facteurs.

Après ça, la dernière porte s'ouvre. Le bouton de relâchement du bouclier. Silence. Le moment de vérité.

Et SOMOS restera juste un gros, cher, et très vulnérable tas de métal.