CIRCULATION AUTOMATIQUE M1918 (BAR)


ARME: Rifle automatique Browning M1918 (BAR)
MUNITIONS:   .30-06 Springfield (7.62×63mm)
CADENCE DE TIR:    ~500-650 tours/min
POIDS: ~7,25 kg

DESCRIPTION:

Le Browning Automatic Rifle est une mitrailleuse américaine conçue par John Moses Browning. Développé pendant la Première Guerre mondiale, il combine la puissance de fusil de la cartouche .30-06 avec la capacité de tirer entièrement automatique.

La BAR se nourrit d'un magazine de 20 tours. L'arme est très puissante et précise, mais son poids considérable et son petit magazine rendent le feu prolongé et soutenu moins pratique. Au combat, la BAR peut être utilisée à la fois pour des tirs simples précis et des rafales courtes contre des groupes d'ennemis.

REMARQUES:

- Efficace à moyenne et longue portée grâce à sa puissante cartouche de fusil.
- La haute précision permet d'utiliser non seulement pour la suppression, mais aussi pour engager des cibles individuelles.
- Le magazine standard compte 20 tours.
- La puissante cartouche .30-06 est capable d'engager efficacement des cibles bien protégées et éloignées.
- Son poids lourd le rend mal à l'aise pour un tir prolongé.
- En tirant entièrement automatique, il est préférable d'utiliser des rafales courtes pour contrôler le recul et éviter de vider le magazine en quelques secondes.
- C'est plus un gros fusil automatique qu'une mitrailleuse légère.
- Si l'ennemi s'attend à ce qu'un fusil tire lentement, le BAR peut les décevoir.
