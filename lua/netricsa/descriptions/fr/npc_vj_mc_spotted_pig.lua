PIG SPOTLESS DE L'EXPLOITATION MINECRAFT


CLASSE:      Porc tacheté
MÉTABOLISME: Mammifère chaud
PERCEPTION: Animal passif gai
TAILLE:       3 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Faible
ARMES:    Aucune
RÉCOMPENSE:     30 FC
MENACE:     Minimal

DESCRIPTION:

Une des variétés les plus charmantes du porc commun, ce porc tacheté est incroyablement sucré. Il aime vivre avec ses amis cochons et chercher des gâteries avec eux à travers les plaines herbeuses.

Ce cochon a une apparence touchante et reconnaissable. Sa couleur de base est aussi terne que celle du porc pâle, mais des taches brunes rondes sont dispersées dans toute sa peau. On dirait qu'elle a été baignée de chocolat, mais pas complètement, juste dans des endroits, ou comme si le soleil l'avait embrassée à travers les feuilles.

She behaves no differently from a regular pig: elle erre dans les plaines herbeuses en compagnie de ses compagnons de porc, évite la lave et les falaises, et s'enfuit quelques secondes lorsqu'elle est endommagée. Mais sa principale activité est de chercher des bonbons et de profiter de la vie parmi ses compagnons.

CONSEILS:

- Le principal atout du cochon tacheté est sa beauté exceptionnelle.
- Racontez ces porcs pour obtenir la descendance avec la même coloration joyeuse.
- Le porc tacheté est superbe dans un stylo sur un habitat naturel herbeux.
- Si vous recherchez des bonbons à travers les plaines en compagnie de porcs repérés, vous avez déjà atteint Zen.
