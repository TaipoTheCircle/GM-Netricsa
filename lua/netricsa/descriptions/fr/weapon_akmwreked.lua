HOMEMADE AK ASSAULT RIFLE


ARME:      AK monté à la main
AMMUNITION:  7,62x39 mm
CADENCE DE TIR:         ~600 tours/min

DESCRIPTION:

Assemblé quelque part dans les sous-sols des séparatistes en Tchétchénie ou quelque part aux États-Unis par un sociopathe local, un Kalachnikov reste un Kalachnikov. Il tire des cartouches de calibre 7,62 mm. Il est efficace à portée moyenne et capable d'un feu soutenu pour la suppression ou l'engagement direct.

REMARQUES:

- Haute durabilité et facilité d'utilisation.
- Recul modéré; contrôlable en courts éclats.
- Efficace contre les cibles non armées et légèrement blindées.
- La capacité des chargeurs nécessite un rechargement périodique pendant les combats prolongés.
- Conception clairement peu fiable.