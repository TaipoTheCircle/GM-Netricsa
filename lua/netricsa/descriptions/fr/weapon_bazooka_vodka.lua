VODKA-BAZOOKA


ARME: Vodka-Bazooka
MUNITIONS:   Bouteilles de vodka pleine grandeur
CADENCE DE TIR:    1 tour par minute

DESCRIPTION:

La Vodka-Bazooka est une bouteille géante de vodka qui peut contenir d'autres bouteilles de vodka. Il fonctionne sur le principe d'une bouteille dans une bouteille, une bouteille dans l'ennemi.

Une fois tiré, la bouteille intérieure éjecte avec une force dévastatrice, brisant la cible et créant une zone de destruction totale de la vodka. À portée de main, l'effet est tellement mortel qu'il n'est pas du tout recommandé de tirer, car tout le monde mourra : ennemis, alliés et valeurs morales.

L'arme a été développée par un ingénieur ivre inconnu au XIXe siècle, surnommé "Jack le Loafer", qui voulait résoudre tous les conflits une fois pour toutes.

REMARQUES:

- Mortement efficace à proximité. Tellement que cette portée proche n'existe peut-être jamais. - Oui. Lorsqu'elle est frappée, la bouteille explose dans un nuage de verre et d'alcool.
- Le rechargement se produit en insérant une nouvelle bouteille dans la plus grande.
- Risque élevé d'autodestruction.
- Les armes sont interdites dans toutes les dimensions civilisées, y compris celles où la civilisation a cessé d'exister.
