MKIII GRENADE LAUNCHER


ARME:    Lanceur de grenade MKIII
MUNITIONS:      Ballons explosifs de 40 mm
CADENCE DE TIR:       variable

DESCRIPTION:

Un lance-grenades d'infanterie fiable à vitesse de lancement réglable. MKIII est conçu pour livrer des grenades hautement explosives sur les obstacles et autour des coins, tout en réduisant les chances que l'opérateur soit blessé par le projectile. Un détecteur d'impact intelligent fait exploser la grenade à l'impact avec une cible vivante, mais pas avec un mur.

REMARQUES:

- Appuyez sur la gâchette pour ralentir le lancement ou maintenez-la enfoncée pour livrer à des intervalles plus longs.
- Les explosions à grande portée sont efficaces contre de grandes masses d'ennemis.
- Bouffer des grenades autour des coins, ou les lober sur les murs.
