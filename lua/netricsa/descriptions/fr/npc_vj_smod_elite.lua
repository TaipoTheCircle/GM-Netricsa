ENGAGEMENT DE L'ÉLITE LOURCE ARROMÉ


CLASSE:      Combiner Overwatch Combiner le gros soldat armé Elite
MÉTABOLISME: Augmenté humain dans un exosquelette
PERCEPTION: Combiner l'unité de répression des agressions lourdes
TAILLE:       5,9 pieds
ENDURANCE:  Extrêmement élevé
HOSTILITÉ:  Extrême
ARMES:    AR2 Pulse Rifle, OICW
RÉCOMPENSE:     1200 FC
MENACE:     Critique

DESCRIPTION:

Le Soldat Heavy Elite Overwatch est une plate-forme de combat à pied, conçue pour briser les défenses et démontrer la domination absolue du Combine. Il est vêtu d'un exosquelette robotique massif, noir et gris avec des accents rouges, à l'intérieur duquel l'homme devient simplement un élément de contrôle de la machine de guerre.

Le costume couvre complètement le corps du soldat, y compris la tête. Le casque est scellé, ne laissant aucune zone vulnérable. La structure de l'armure révèle clairement les composants mécaniques : servos, joints renforcés, plaques blindées et nœuds de puissance.

L'exosquelette améliore considérablement les capacités physiques du soldat, lui permettant de porter des armes lourdes sans sacrifier sa mobilité. L'AR2 est utilisé pour supprimer le feu, tandis que l'OICW réduit la couverture et les concentrations ennemies à des déchets inutiles. Ce soldat ne cherche pas des positions avantageuses, il les crée lui-même, en progressant directement sur le champ de bataille.

Malgré son apparente invulnérabilité, la structure a un point de rupture. Un coup direct d'un RPG détruit l'exosquelette, transformant le véhicule d'élite en une pile de métal tordu.

CONSEILS:

- Les armes légères sont presque inutiles contre son armure.
- Utilisez des RPG ou des explosifs puissants - c'est sa principale et presque seule faiblesse.
Il ne recule pas.