PARASITE DE L'EAU


CLASSE:        Swarm Parasite
MÉTABOLISME:   Parasite xénobiologique
PERCEPTION:   Organisme infectieux
TAILLE:         0,9 ft
DURABILITY:   Très faible
HOSTILITÉ:    Extrême
ARMES:      Infection, fuite
RÉCOMPENSE:       50 FC
MENACE:       Haut

DESCRIPTION:

Le parasite est l'une des formes les plus nombreuses et les plus dangereuses de vie de swarm. Malgré leur petite taille et leurs corps fragiles, ces créatures constituent une grave menace pour les combattants bien équipés.

Leur principale méthode de chasse implique un saut rapide sur la victime. Après une attaque réussie, le parasite implante des larves dans le corps de l'hôte; ces larves commencent alors à se développer rapidement dans le tissu vivant. Au début, l'infection peut passer inaperçue, mais l'état de la victime se détériore rapidement au fil du temps.

Le cycle de vie de la créature présente un danger particulier. Si l'hôte infecté meurt, les larves terminent leur développement et sortent du corps, formant un nouvel essaim de parasites. Ainsi, même une seule attaque réussie peut entraîner une augmentation rapide de la population de Swarm.

Les parasites éclosent des œufs biologiques, habituellement déposés dans des endroits humides et protégés. L'intérieur des grappes d'oeufs est rempli d'un liquide biologique visqueux essentiel au développement des jeunes. Par conséquent, de grandes concentrations de parasites se trouvent le plus souvent dans des tunnels humides, des complexes souterrains et des colonies abandonnées.

CONSEILS:

- Détruire les parasites avant qu'ils ne sautent.
- Si vous découvrez un amas d'oeufs, détruisez-le le plus rapidement possible.
- Un seul parasite est rarement un problème. Les ennuis commencent généralement plus tard.
