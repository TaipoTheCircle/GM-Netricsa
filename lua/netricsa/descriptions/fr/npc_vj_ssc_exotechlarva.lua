EXOTECH LARVA


CLASSE:      Larve exotech
MÉTABOLISME: cyborg, arthropodes
PERCEPTION: génétiquement programmé
TAILLE:       30 pieds
ENDURANCE:  extrême
HOSTILITÉ:  élevé
ARMES:    canons plasma, biopodes, laser à haute énergie
RÉCOMPENSE:     750000
MENACE:     élevé

DESCRIPTION:

Le succès de sa première abomination de la nature - le biomécanoïde - a poussé Mental encore plus cette fois. Dans une tentative de créer un garde du corps parfait et obéissant, Mental a décidé de combiner des pièces robotiques avec une créature organique encore plus simple - des larves d'insectes. La larve était lourdement armée et mise dans un dispositif multiplicateur de force et devait garder Mental. Les choses n'ont pas fonctionné comme prévu. Après la 17e tentative d'assassinat de Larva sur Mental et de nombreuses heures passées à enseigner au cyborg la différence entre son maître et une chenille commune, Mental a finalement abandonné et a trouvé que c'était un animal de compagnie un nouveau travail : garder un portail qui pourrait apporter des problèmes sérieux à sa façon.

CONSEILS:

- La force de la larve provient de la force... des réacteurs. La créature rechargera ses batteries quand elle est faible en puissance, alors assurez-vous de vérifier les environs pour tout dispositif suspect.
- Utilisez les colonnes pour vous cacher de ses armes.