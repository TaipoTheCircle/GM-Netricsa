SCANNER COMBINE CLAW BATTLE


CLASSE:      Combiner le scanner des griffes
MÉTABOLISME: Synthét
PERCEPTION: Recon / Synth de combat, scanner de type II
TAILLE:       ~2,5 pi de diamètre 
ENDURANCE:  Moyenne 
HOSTILITÉ:  Haut
ARMES:    Déploiement de la mine Hopper, caméra flash aveuglante
RÉCOMPENSE:     450 FC
MENACE:     Haut

DESCRIPTION:

Le Scanner Combine Claw, aussi connu sous le nom de Scanner Shield ou Scanner Type II, est une sinistre variation prête au combat du Scanner City standard. Doté d'un bras de picotement caché, il peut déployer des mines de Hopper mortelles dans des couloirs étroits, des ruelles et d'autres zones stratégiques pour bloquer ou embusquer les forces de résistance.

Comme son homologue civil, il peut émettre un flash aveuglant avec son système de caméra, utilisé pour désorienter des cibles ou les forcer à se couvrir. Ces drones soutiennent les Striders et les unités au sol en marquant des cibles et en limitant les mouvements civils, donnant à la Combine un œil implacable dans le ciel.

CONSEILS:

- Le flash du scanner peut empêcher - éviter de regarder directement quand il charge.
- Un incendie grave ou des explosifs le désactiveront et empêcheront d'autres chutes de mines.
- Ces unités sont souvent vues en groupes ou à proximité des positions défensives.
