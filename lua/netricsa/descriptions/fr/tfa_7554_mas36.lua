RIVEAU D'ACTION DE MAS-36


ARME: MAS-36 Rifle d'action
MUNITIONS:   7.5x54mm Français
CADENCE DE TIR:    10 tours par minute

DESCRIPTION:

Un fusil à action de boulon français développé par une équipe de conception dirigée par le capitaine Monteil et adopté pour le service en 1936. Elle a été fabriquée par l'entreprise publique d'armements * Manufacture d'armes de Saint-Étienne* (MAS). Il était destiné à remplacer les fusils obsolètes Lebel et Berthier. Il se distingue par la forme inhabituelle de sa poignée de boulon – courbée vers l'avant et vers le bas – ainsi que par une conception simple et robuste conçue pour une utilisation dans des conditions exigeantes.

Le fusil fonctionne au moyen d'un mécanisme à boulon rotatif actionné manuellement. Il abrite la cartouche 7.5x54mm de fusil français et dispose d'un chargeur 5 ronds. Il est chargé depuis le haut, soit à l'aide d'un clip de strip-teaseuse ou en insérant des ronds individuels. Il est équipé d'une vue dioptère (ouverture) et d'une baïonnette à pointe cruciforme, qui est stockée dans un canal dédié sous le baril. Bien que le fusil soit fiable et précis, son taux de tir est inférieur à celui des armes semi-automatiques.

REMARQUES:

- Bien adapté pour engager des cibles individuelles à moyenne à longue portée.
- Non destiné à être utilisé contre des véhicules blindés ou des cibles lourdement blindées.
- La portée de tir est d'environ 400 mètres.
- Une variante de parachutiste, la CR39, a été produite avec un stock d'aluminium pliant.
- La puissante cartouche de fusil assure une grande efficacité contre le personnel non armé.
