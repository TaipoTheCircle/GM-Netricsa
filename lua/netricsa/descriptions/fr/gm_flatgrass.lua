GRASSE DE FLAT


Flat Grass est l'un des endroits les plus anciens et les plus emblématiques. Elle vit jusqu'à son nom : un vaste champ plat d'herbe entouré d'un ciel bleu sans fin.

Il n'y a aucune anomalie. L'herbe plate est utilisée pour fabriquer des dispositifs, tester des armes, contrôler des véhicules, ou simplement causer des ravages sans limites.

Key Features:

A sense of infinity: une vaste surface plane, parfaite pour la construction à grande échelle et les essais physiques.

Minimalist architecture: un seul bâtiment fraie, avec une pièce cachée et un toit pour l'observation.