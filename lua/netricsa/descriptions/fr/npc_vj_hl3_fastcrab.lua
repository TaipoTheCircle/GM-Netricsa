ARCTIC FAST HEADCRAB DE XEN


CLASSE:      Gratte-tête rapide (arctique)
MÉTABOLISME: Parasite résistant au froid extrême
PERCEPTION: Armes biologiques
TAILLE:       1,3 pi
ENDURANCE:  Très faible
HOSTILITÉ:  Haut
ARMES:    Sauts ultra rapides, morsure coupante
RÉCOMPENSE:     180 FC
MENACE:     Moyenne

DESCRIPTION:

La variété arctique de la tête rapide ZEN est une évolution encore plus alarmante d'un parasite déjà agressif. Ayant été introduite dans les biomes glacés de la Terre, cette espèce a développé un court manteau glacé qui protège ses muscles de l'hypothermie.

Son corps reste maigre et flexible, et ses membres sont développés pour des sauts rapides et répétés, même sur la glace et la neige. Grâce à sa musculature modifiée, l'Arctic Swift Headcrab peut repousser les surfaces glissantes, changer la direction en mi-vol, rendant ses attaques particulièrement difficiles à prédire.

En infectant un hôte, il crée un Zombie Swift arctique plus résistant au froid et moins sensible à la douleur que son homologue modéré. Ces zombies sont capables de traverser rapidement des zones neigeuses et d'escalader des structures glacées où la normale infectée perdrait de la traction.

CONSEILS:

- Ne restez pas immobile : leur vitesse est conçue pour une cible fixe.
- Ils changent souvent leur trajectoire de saut.
