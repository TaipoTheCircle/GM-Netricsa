PARASITE SWARM EGG


CLASSE:      Oeufs parasites
MÉTABOLISME: Xénobiologique
PERCEPTION: Incubateur parasite
TAILLE:       6,5 pieds
ENDURANCE:  Très faible
HOSTILITÉ:  Moyenne
ARMES:    Libération parasite
RÉCOMPENSE:     50 FC
MENACE:     Haut

DESCRIPTION:

L'œuf parasite Swarm est une chambre d'incubation spécialisée conçue pour le développement de parasites. Il est recouvert d'une fine membrane élastique, à l'intérieur de laquelle il y a un épais fluide nutritif nécessaire à la maturation de l'embryon.

Dans un état calme, les œufs restent immobiles, en attendant l'émergence d'organismes vivants. Lorsque la proie potentielle s'approche, la coquille s'ouvre instantanément, libérant le parasite, qui attaque immédiatement la cible la plus proche. Une fois éclos, l'œuf perd rapidement sa viabilité et n'est plus capable de produire de nouveaux oeufs.

Les oeufs sont généralement situés en groupes à l'intérieur des ruches, des puits de ventilation, des tunnels et d'autres zones humides où des conditions favorables sont maintenues pour le développement de la progéniture. On les trouve souvent à côté des cocons larvaires et d'autres incubateurs, formant des aires de reproduction à part entière.

Malgré leur immobilité, un grand nombre d'oeufs peuvent transformer un passage sûr en piège mortel. Même si les adultes sont détruits, les embrayages restants permettent au Swarm de rétablir rapidement son nombre.

CONSEILS:

- Détruisez les œufs avant de les approcher.
- Le feu vous permet de nettoyer en toute sécurité les zones contaminées avec un grand nombre d'embrayages.
- Après avoir ouvert la coquille, concentrez le feu sur le parasite éclos.
- S'il y a plusieurs œufs à proximité, essayez de ne pas les activer en même temps.
