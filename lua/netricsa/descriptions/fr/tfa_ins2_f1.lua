F-1 GRENADE DE FRAGMENTATION À LA MAIN


ARME: F-1 Grenade de fragmentation des mains
MUNITIONS:   Une Grenade
CADENCE DE TIR:    Un lancer par minute

DESCRIPTION:

Une grenade de fragmentation de la main défensive soviétique, développée en 1939 par le designer Fyodor Ivanovich Khramev, basée sur la grenade F-1 française (modèle 1915). Il est conçu pour neutraliser le personnel ennemi par la fragmentation de son boîtier. Il dispose d'un corps en fonte distinct avec une surface côtelée, qui lui a valu le surnom de "limonka" (petit citron). Il a été utilisé par l'Armée rouge pendant la Grande Guerre patriotique et est devenu par la suite l'un des pièces les plus reconnaissables de l'armement soviétique.

Les principaux composants comprennent un corps en fonte, une charge explosive et une fumée à retardement. Au fil des ans, on a utilisé diverses fusées, dont les modèles Koveshnikov, UZRG et UZRGM. La grenade s'est répandue en raison de sa conception relativement simple et de sa production de masse. Elle est restée en service bien après la fin de la Seconde Guerre mondiale.

REMARQUES:

- Destiné principalement à une utilisation défensive.
- C'est devenu un symbole de l'armement soviétique pendant la Grande Guerre Patriotique.
- Développé en URSS en 1939.
- Basé sur la conception de la grenade F-1 française.
- Le surnom "limonka" ("petit citron") fait référence à la forme caractéristique de son corps.
