MESA BLACK, FINALE LIBRE


Sam, le signal a été envoyé et les portes du réacteur sont maintenant ouvertes. Le complexe Lambda attend.

Mais avant de célébrer, il y a un dernier problème. Un scientifique survivant nous avertit qu'un Gargantua a été aperçu dans les couloirs. Il est déchirant à travers la sécurité comme le papier, et il vous suggère fortement d'éviter le contact direct à moins que vous aimez devenir un barbecue sérieux.

Ajoutant à l'étrangeté, ce mystérieux homme avec la mallette a de nouveau été repéré, cette fois calmement debout à côté d'une garde, regardant le chaos se dérouler comme une pièce de théâtre.

Your next step is simple: allez à l'ascenseur, descendez-le, et faites votre évasion. Au moins, c'est le plan.