MACHINE MARINE GUN


ARME: Pistolet automatique
MUNITIONS:   Bullets
CADENCE DE TIR:    ~600 tours/min

DESCRIPTION:

La mitrailleuse est un fusil automatique compact à tir sélectif utilisé par le Space Marine Corps comme fusil de service principal. Il comprend une lampe de poche sous le barillet et un mode de champ pour le feu de précision. L'arme peut être tirée en plein auto à partir de la hanche ou semi-auto lorsqu'elle est projetée, ce qui la rend polyvalente pour les combats de quartier rapproché et les rencontres de milieu de gamme.

REMARQUES:

- Le mode étendu fournit un feu semi-automatique avec une précision améliorée.
- Dommages par tir : ~15 normalement, ~20 lorsqu'il est projeté.
- Bon contre les ennemis faibles et moyens; de lourdes cibles blindées ou de patron nécessitent de nombreuses balles.
- La mise à jour de 80 tours de magazine améliore considérablement la puissance de maintien pendant les combats prolongés.