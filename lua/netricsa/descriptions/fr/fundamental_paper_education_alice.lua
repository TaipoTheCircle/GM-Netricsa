LICE DE L'ENSEIGNEMENT FONDAMENTAL


CLASSE:      Lice
MÉTABOLISME: Entité emprisonnée/détenue
PERCEPTION: Entité emprisonnée
TAILLE:       ~5,5 ft (forme normale), >11,4 ft (forme réelle)
ENDURANCE:  Absolu
HOSTILITÉ:  Extreme (vers tous sauf les quelques élus)
ARMES:    Pins noirs, télékinésie, griffes, tentacules, transformation
RÉCOMPENSE:     666666 FC
MENACE:     Catastrophes

DESCRIPTION:

La menace ultime, plus grande que le principal de l'école de papier elle-même, une entité emprisonnée dans une pièce séparée marquée de signes « NE PAS ENTRER ». Dans sa forme normale, elle apparaît comme une fille aux cheveux bruns courts, portant une couronne et un arc, mais ses vêtements sont déchirés, et sa peau est couverte de cicatrices et d'une étrange éruption. La vraie nature de la Lice est une créature démoniaque, semblable à une ombre avec sclérose rouge, des griffes énormes, des pics et des tentacules. Elle est agressive et meurtrière envers quiconque entre dans sa chambre, mais passive et même douce avec Oliver (son ami d'enfance et son petit ami). Son pouvoir dépasse même les enseignants les plus dangereux, les faisant craindre.

Elle a de pleins pouvoirs grâce à son pouvoir. (C'est pourquoi elle va parfois à la cafétéria avec Oliver =3) Son apparence transforme la réalité papier de l'école en quelque chose de plus tangible et terrifiant. Elle s'oppose à d'autres entités emprisonnées, comme HanseG. Elle considère l'école comme son territoire.

CONSEILS:

- JAMAIS entrer dans sa chambre. Même si la porte ressemble à une sortie, c'est un piège.
- Si vous n'avez pas le SBC Cannon autour: Courir est votre seule option. Elle est plus rapide, plus forte et contrôle l'espace autour d'elle. La confrontation directe est futile.
