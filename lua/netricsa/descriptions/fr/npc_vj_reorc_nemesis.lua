NEMESIS DE LA SOCIÉTÉ D'UMBRELLA


CLASSE:      Bioarmes (B.O.W.), Tyrant type T
MÉTABOLISME: Organisme muté infecté par le parasite NE-α
PERCEPTION: Assassin tactique, chasseur d'élite
TAILLE:       8,2 pi
ENDURANCE:  Extrême
HOSTILITÉ:  Absolu
ARMES:    Rocket Launcher, Minigun M-134, Flamethrower, Tentacles, Fists, Objets environnementaux
RÉCOMPENSE:     10000 FC
MENACE:     Absolu

DESCRIPTION:

Ce n'est pas une arme biologique ordinaire. C'est un cauchemar vivant, créé par la branche européenne de Umbrella Corporation dans un seul but : éliminer tous les membres survivants de l'équipe d'élite S.T.A.R.S. chargée d'exposer les crimes de la société.

Nemesis est le résultat de l'infection d'un Tyrant T-103 - le même modèle que M. X- avec un parasite expérimental appelé NE-α (Nemesis Alpha). Le parasite se développe littéralement dans le système nerveux de l'hôte, formant son propre cerveau et prenant le contrôle du corps. Cela confère au monstre non seulement la force surhumaine, mais aussi la capacité de prendre des décisions, de suivre des ordres complexes, et, le plus terrifiant, d'utiliser des armes.

En raison de la difficulté d'intégrer le parasite à l'hôte, le taux de réussite a été négligeable - environ un spécimen réussi sur 60 millions de candidats. Chaque spécimen est incroyablement précieux pour Parapluie.

Dans sa forme de base, Nemesis est un gigantesque humanoïde musclé, revêtu d'un long manteau noir et imperméable. Le manteau faisait à l'origine partie de leur équipement standard, conçu pour inhiber les mutations et protéger contre les balles.

Son visage est dépourvu de lèvres et les dents et les muscles sont visibles sous la peau tendue. Son œil droit est fermé avec des pointes chirurgicales grossières. Son corps est recouvert de cicatrices et de marques de dissection. Il porte des pantalons noirs, des bottes et des gants, et sur le côté gauche de sa poitrine est un dispositif de retenue en métal visible qui empêche son parasite de muter incontrôlablement.

Quand son manteau est endommagé, Nemesis mute : de longs tentacules puissants commencent à éclater de son corps, qu'il utilise pour attraper les victimes, poignarder et même se déplacer rapidement en s'accrochant aux murs des bâtiments.

La caractéristique principale de Nemesis des autres Tyrans est son intelligence, qui lui permet de gérer des armes complexes.

Son arme emblématique est un lance-roquettes lourd ou un lance-grenades multibarres monté sur son bras gauche. Nemesis démontre une précision incroyable, frappant facilement des cibles mobiles à de grandes distances.

Nemesis utilise également un puissant lance-flammes sac à dos, capable de cracher des jets de flamme et de lancer des boules de feu. Même après la destruction du réservoir de carburant, il continue à l'utiliser comme un club flamboyant.

La mitrailleuse à six canons Nemesis lui permet d'abattre des foules entières d'ennemis.

Même sans armes, Nemesis est mortel. Ses coups peuvent percer des murs en béton et déchirer des morceaux d'asphalte. Avec un seul coup, il peut envoyer une personne voler ou briser un cou.

Les tentacules de Nemesis ne font pas qu'infliger des dommages physiques. Lorsqu'elle est injectée, la victime est infectée par le virus T, causant une mutation ou une mort rapide. Il peut également implanter le parasite NE-α dans les corps des défunts, les transformant en monstres horribles et contrôlables.

Nemesis est un vrai monstre dans tous les sens du mot.

Il est capable de percer les murs de béton avec un seul coup, de couper les portes de leurs charnières, de lancer des voitures et de briser les planchers des bâtiments.

Il peut courir à des vitesses supérieures à 100 km/h (63 mi/h), évitant instantanément les tirs de grenade et de lance-roquette.

Son principal avantage est la régénération. Les balles, les éclats et les brûlures guérissent devant ses yeux. Nemesis peut être temporairement handicapé par une explosion ou une arme lourde, mais il va rapidement se lever et poursuivre la poursuite.

Il peut résister aux coups de lance-grenades, aux explosions de réservoir de carburant, aux chutes de grandes hauteurs et aux douses de métal acide et fondu.

Nemesis n'est pas une machine à tuer sans esprit. Il a un système opérationnel et des priorités. Sa cible principale et unique est l'équipe S.T.A.R.S.

Toute sa stratégie est axée sur le suivi et la destruction. Il ne reculera pas avant que sa cible soit morte ou qu'il soit lui-même détruit.

Nemesis est capable d'évoluer à la volée, en passant par plusieurs étapes terrifiantes.

First Form: Un Nemesis basique en manteau, armé d'un lance-roquettes/flamethrower. Intelligent, rapide et dangereux.

Second Form: Après avoir détruit son manteau et reçu des dommages critiques, Nemesis se transforme en une créature encore plus monstrueuse. Il tombe à quatre pattes, devient comme une bête gigantesque, se couvre de croissances osseuses, et grandit de longs tentacules semblables à des fouets.

Troisième forme (finale): le corps de Nemesis perd enfin le contrôle. Il se transforme en une énorme masse amorphe de chair, d'os et de tentacules, se déplaçant dans un mouvement rampant. Sous cette forme, il est pratiquement à l'abri des armes conventionnelles, continue de poursuivre sa cible, et jette des nuages d'acide toxique.

CONSEILS:

- Tire et cours. La némésis est (presque) impossible à tuer avec des armes classiques. Votre but est de le désactiver temporairement pour gagner un avantage et s'échapper.
- Utilisez l'environnement. Exploser des barils, des générateurs, des portes, des antennes dropables, ça peut le ralentir.
- Ne bougez pas. Il sait toujours où tu es. Tout arrêt signifie la mort.
- Détendez les missiles. Un coup direct de son lance-roquette tue instantanément, même en pleine armure.
- Surveillez vos armes. Le lance-roquettes est une menace à longue portée, le lance-flammes est une menace à moyenne portée. S'il court avec ses poings, vous devez augmenter votre distance.
- Souviens-toi des tentacules. S'il est proche, il peut t'attraper avec un tentacule même s'il ne te touche pas avec sa main.
