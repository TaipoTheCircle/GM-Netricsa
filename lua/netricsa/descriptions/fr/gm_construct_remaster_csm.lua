CSM CONSTRUCTE REMASTER, NON FINANCÉE


Sam, tu te souviens du chantier où on a commencé ? Vide, béton, avec quelques hangars et un chantier sans fin qui ne finirait jamais ? Quelqu'un a décidé que ça ne suffisait pas. Et a fait un remaster.

Pas une reconstruction. Pas terminé. Un remaster, exactement. Comme les vieux jeux: les mêmes emplacements, mais plus de textures, moins de bugs, et quelques fonctionnalités supplémentaires pour garder les anciens combattants divertit.

Le chantier est encore inachevé. Mais il y a maintenant des améliorations. De sérieux. Et étranges. Et, comme d'habitude, avec une prise.

Quoi de neuf ?

Le hangar a une porte.

Oui, Sam. Le même trou que nous avions l'habitude d'attendre que le pilonnage se termine. Et peut-être que le vent ne souffle pas.

Une chambre sombre - lumière et le bannissement d'une légende.

Souvenez-vous de cette pièce où il faisait toujours nuit, et nous avions peur que celui qui ne doit pas être nommé saute du coin ? Il y a un interrupteur. Tu le retournes, et il n'y a pas d'obscurité. Et la rumeur dit que le Meat Man a été banni de là. Ne demande pas qui c'est. Il n'y a rien à demander. Il n'y est plus. Ou peut-être qu'il a appris à mieux se cacher.

La chambre blanche - risque de cécité.

Il y a un avertissement à l'entrée. Tout le monde entre est conseillé de porter des lunettes. Parce que la lumière là-bas est si lumineuse, vous pourriez être laissé avec vos yeux fermés pour toujours. Je ne sais pas qui a fait une chambre qui pourrait vous aveugler, ou pourquoi. Mais Sam, nous serions entrés.

Des extincteurs.

Partout. Sur les murs, dans les coins, sur les tables. Apparemment, quelqu'un s'est rendu compte qu'ils étaient essentiels sur un chantier. Ou peut-être qu'ils se sont souvenus des précautions de sécurité. De toute façon, si quelque chose prend feu, tu n'auras pas à l'éteindre avec tes pieds.

Trous d'homme et trappes.

Oui.

Stationnement.

Enfin, vous pouvez garer votre voiture. Pas dans un champ, pas dans un hangar, mais dans un vrai parking. Avec des marques. Beaucoup d'espaces. Pas de voiture. Mais nous pouvons apporter les nôtres.

Et bien plus encore.

C'est trop long. Trop longtemps.

Jetez un coup d'œil sur le chantier. Beaucoup de choses ont changé. Certaines choses se sont améliorées, d'autres sont étrangères. Trouvez les lunettes devant la chambre blanche. Allumez la lumière dans la chambre noire. Regarde dans le puits. Garez la voiture. Et rappelez-vous : les extincteurs ne sont pas des jouets. Jusqu'à ce qu'il y ait un feu.

Allons faire un tour du chantier rénové. N'oublie pas tes lunettes. Sinon, tu deviendras aveugle. Qui tirera sur les têtes alors ?
