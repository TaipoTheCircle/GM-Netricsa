BLENJEEL


PLANET:       Blenjeel
TYPE:         Terrestre, planète désertique
CLIMATE:      Aride, dure
MOONS:        Inconnu
TERRAIN:      Vastes déserts en mouvement, affleurements rocheux instables
LOCATION:     Entre les planètes Ando et Kothlis, loin des grandes routes hyperspatiales
NATIVE RACES: Mineurs d'explosion de sable (créatures géantes semblables à des vers)
ALLIANCE:     Territoire neutre, répertorié dans les bases de données de la Nouvelle-République comme une planète dangereuse
LOCATIONS:    Lieu d'écrasement du navire marchand, site d'écrasement de la navette Yavin Runner II

DESCRIPTION:

Une planète déserte, perdue loin des voies spatiales occupées entre les systèmes Ando et Kothlis. Sa surface se compose de mers de sable sans fin, possédant une caractéristique unique: le sable est en constante évolution. Le paysage est en constante évolution : des affleurements rocheux qui semblaient un jour sûrs peuvent disparaître dans l'abîme sablonneux le suivant.

Le principal danger de Blenjeel se cache sous ses sables mouvants. La planète est habitée par de gigantesques créatures monstrueuses qui habitent dans les profondeurs du désert. Ces créatures émergent rapidement du sol, embuscadent des proies sans méfiance. Leur mouvement constant est la cause principale de l'instabilité de la surface : les tunnels creusés font bouger le sable et engloutissent les affleurements rocheux.

Dix ans après la bataille d'Endor, un navire marchand a été attaqué par un raideur impérial de classe 418 et s'est écrasé sur Blenjeel. Aspirant Jedi Jaden Korr a été envoyé en mission de sauvetage à bord du Yavin Runner II. Cependant, pendant l'atterrissage, sa navette a été frappée par la foudre et s'est également écrasée.

Jaden n'a pas pu sauver les membres de l'équipage survivants, dont le dernier a été dévoré par un ver de sable juste devant ses yeux. Cependant, les Jedi ont réussi à survivre dans le désert, évitant constamment le contact avec les prédateurs. Il atteint l'épave du navire marchand, récupère les pièces de rechange nécessaires, répare sa navette et quitte la planète. Après son retour à Yavin 4, Blenjeel a été inscrit dans les bases de données de la Nouvelle-République comme une planète dangereuse, non recommandée pour la visite.

KEY LOCATIONS:

- Zone de crash du navire marchand : La zone désertique où le navire marchand s'est écrasé après avoir été attaqué par un raideur impérial. L'emplacement du décès de l'équipage et la source des pièces de réparation nécessaires.
- Yavin Runner II Crash Site: Le désert où la navette de Jaden Korr s'est écrasée après avoir été frappée par la foudre. C'est là que son voyage vers la survie a commencé.
