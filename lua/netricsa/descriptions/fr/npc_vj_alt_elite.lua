VENDU D ' ÉLITE ALTERNATIVE POUR LES COMBINES


CLASSE:      Alternative Combiner Overwatch Elite Soldier
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Combiner Elite Shock Trooper
TAILLE:       5,9 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    AR2 Fuseau d'impulsion, boules d'énergie
RÉCOMPENSE:     900
MENACE:     Très élevé

DESCRIPTION:

Les Alternative Overwatch Elite Soldiers sont des soldats d'élite qui choisissent de ne pas se montrer. Contrairement à leurs homologues standard armés de blanc, ces soldats portent une salopette bleu foncé, qui est visuellement presque indissociable de l'uniforme des soldats réguliers Overwatch. La seule caractéristique évidente est leur visière bleu froid.

Bien qu'apparemment un soldat ordinaire, il est en fait un combattant d'élite avec les mêmes implants, réflexes et entraînement tactique. Il opère souvent dans le cadre d'unités standard, augmentant discrètement leur efficacité à un niveau inébranlable.

CONSEILS:

- Travaille souvent en tandem avec des troupes régulières, les faisant passer à des niveaux d'élite.
- Visière bleue peut révéler leur position dans des conditions de faible luminosité.