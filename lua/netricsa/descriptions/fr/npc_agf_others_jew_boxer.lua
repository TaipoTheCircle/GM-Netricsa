JOHN JEEWICH, LE BOXER NON RIVALÉ


CLASSE:      John Jeewich, le Boxer inégalé
MÉTABOLISME: Humain, Homme, Titan anabolique
PERCEPTION: Champion Brawler
TAILLE:       6,4 pieds
ENDURANCE:  Colossal
HOSTILITÉ:  Extrême (dans l'anneau - impitoyable)
ARMES:    Un coup de poing, des coups de poing, un coup de poing
RÉCOMPENSE:     9000 FC 
MENACE:     Apocalyptique

DESCRIPTION:

Ne défiez jamais John Jeewich, le Boxer inégalé, à moins que vous ne souhaitiez assister à l'effondrement de votre propre squelette. Cet homme peut écraser non seulement une noix mais des arbres entiers - et peut-être vos côtes - avec une seule main. Connu comme la peur de toute l'Allemagne, ses poings frappent comme des marteaux industriels forgés dans une tempête.

Legends say only one being can defeat him: Saitama - Un coup, une mort.

Cependant, vos poings suffiront dans une belle bagarre.

CONSEILS:

La motion est votre seule défense.
- Si tu n'es pas Saitama, tu ne survivras pas à un coup direct.
- Ses coups peuvent briser le métal et les os.
