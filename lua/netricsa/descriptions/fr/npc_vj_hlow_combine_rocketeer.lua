VENDU DE ROCKET SURVEILLANCE DE COMBINE


CLASSE:      Combiner le soldat Rocket Overwatch
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Suppression antivéhicule et des cibles lourdes
TAILLE:       9,5 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrême
ARMES:    Combiner RPG, arme secondaire
RÉCOMPENSE:     700 FC
MENACE:     Très élevé

DESCRIPTION:

Le Soldat Rocket Combine Overwatch est une unité d'incendie lourde conçue pour détruire les véhicules, les fortifications et les cibles à haut risque. Son apparence est facilement confondue avec celle d'un fusil de chasse : une armure semblable, une silhouette massive et une posture. Cette erreur est souvent fatale.

L'arme principale du soldat est un lance-roquettes Combine, qu'il porte en tout temps et utilise sans hésitation. Contrairement aux soldats antichars, il n'attend pas la cible parfaite : ses fusées sont utilisées de manière agressive, défrichent les murs, et suppriment les concentrations ennemies.

Il travaille souvent en tandem avec des soldats réguliers, qui le protègent pendant qu'il se prépare au feu.

Bien que son armure ne soit pas haut de gamme, un lancement réussi peut instantanément renverser la marée de la bataille.

CONSEILS:

- Ne le confondez pas avec le fusil de chasse.
- Le soldat Rocket est particulièrement dangereux dans les espaces confinés.
- Utilisez un couvercle qui peut résister à l'explosion, pas juste bloquer votre vue.