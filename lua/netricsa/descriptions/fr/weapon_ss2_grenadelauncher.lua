MKIV GRENADE LAUNCHER


ARME: Lanceur de grenade MKIV
MUNITIONS:   Grenades
CADENCE DE TIR:    60-200 tours/min selon la charge


DESCRIPTION:

Le lanceur MKIV Grenade est le successeur du MKIII. Chaque presse de déclenchement tire une seule grenade qui fait exploser un impact avec un ennemi ou trois secondes après le tir. Les Grenades rebondissent sur les murs. Retenir le bouton d'incendie charge le tir, augmentant la vitesse de lancement et la distance;


REMARQUES:

- Les tirs chargés sont utiles pour les engagements de moyenne à longue portée, voyageant plus rapidement et plus loin.
- Les grenades sont dangereuses si elles manquent, en particulier dans les zones étroites - les dommages par éclaboussure peuvent blesser l'utilisateur.
- Très efficace vs amas d'ennemis faibles à moyens; évitez d'utiliser des tirs chargés dans des espaces fermés.