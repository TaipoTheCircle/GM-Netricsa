"BETA" DRONE ÉLITE "LARGE"


CLASSE:        "Beta" Swarm Elite Drone, Grand
MÉTABOLISME:   Xénobiologique
PERCEPTION:   Prédateur à emballage lourd
TAILLE:         9,8 pieds
ENDURANCE:    Très élevé
HOSTILITÉ:    Extrême
ARMES:      Griffes, dents, masse corporelle
RÉCOMPENSE:       1200 FC
MENACE:       Très élevé

DESCRIPTION:

Le Grand Drone Elite est considéré comme l'une des variantes les plus dangereuses du Swarm "Beta". Il combine la taille pure d'un gros spécimen avec la résilience d'un drone d'élite, créant une créature que de nombreuses garnisons coloniales préféreraient ne jamais rencontrer.

Elle ne diffère de sa parenté que par sa coloration noir-charbon et sa taille imposante. Trois yeux balayent l'environnement, tandis que son corps massif est encastré en chitine dense capable de résister aux dommages qui se révéleraient fatals pour un drone ordinaire. Certains témoins oculaires ont confondu ces créatures avec les jeunes Hive Guards - seulement pour perdre rapidement l'intérêt pour les questions de classification par la suite.

L'apparition d'un tel spécimen au sein d'une ruche indique habituellement que la colonie existe depuis longtemps et possède des ressources importantes. Autrement dit, si le Swarm a réussi à produire un monstre comme celui-ci, il est florissant. On ne peut pas en dire autant de ses voisins.

Malgré son immense masse, la Grande Elite conserve l'agressivité et la vitesse caractéristiques du swarm "Beta". Il ne possède ni intelligence complexe ni capacités spéciales; il n'a pas besoin d'eux. L'évolution a conclu il y a longtemps que quatre griffes massives sont souvent plus convaincantes que toute tactique.

CONSEILS:

- Ne vous livrez à aucun combat.
- Les armes lourdes sont recommandées; les armes légères sont simplement sympathiques.
- Éliminez ce type de spécimen avant qu'il ne se rapproche de l'équipe.
- Si un drone standard est un problème, un drone lourd d'élite ressemble plus à un désastre naturel avec des griffes.
