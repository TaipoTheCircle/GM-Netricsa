LABORA FONTBERNAT M-1938 SUBMACHINE GUN


ARME: Labora Fontbernat M-1938 Gun sous-machine
MUNITIONS:   9x23mm Largo
CADENCE DE TIR:    ~750 tours/min
POIDS: ~4,38 kg

DESCRIPTION:

Le Labora Fontbernat M-1938, également connu sous le nom de Labora, est une mitrailleuse espagnole d'origine catalane. Il a été utilisé par les deux parties pendant la guerre civile espagnole, et un petit nombre d'armes ont continué à servir après la guerre. Environ 1 000 à 2 000 ont été fabriqués.

La mitrailleuse est faite principalement d'acier traité et utilise une action de rappel. L'arme est en chambre pour la puissante cartouche Largo 9x23mm espagnole et se nourrit d'un magazine de 36 ronds. Avec un taux d'incendie d'environ 750 rounds par minute, le Labora est capable de fournir une puissance de feu assez dense à proximité.

La conception du M-1938 est assez massive pour une mitrailleuse : avec un chargeur vide, l'arme pèse environ 4,38 kg. Toutefois, sa production était relativement limitée, de sorte que la Labora Fontbernat est aujourd'hui un exemple beaucoup moins connu d'armes de guerre civile espagnole.

REMARQUES:

- Seulement quelques milliers d'unités ont été produites, mais il a vu l'action avec pratiquement toutes les parties dans le conflit espagnol.
- Un taux d'incendie d'environ 750 cartouches par minute permet une puissance de feu très dense à proximité.
- L'arme a été utilisée par les républicains et les nationalistes pendant la guerre civile espagnole.
- La cartouche Largo 9x23mm est plus puissante que le Parabellum 9x19mm, mais cela rend l'arme assez spécifique.
