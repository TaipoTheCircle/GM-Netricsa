LA BOODE DE KLEER


CLASSE:      Base en bois Kleer
MÉTABOLISME: non décédés
PERCEPTION: créature magique
TAILLE:       9 pieds
ENDURANCE:  faible
HOSTILITÉ:  moyenne
ARMES:    griffes kleer en bois, griffes, cornes
RÉCOMPENSE:     520 FC
MENACE:     moyenne

DESCRIPTION:

Un squelette non mort d'un être d'une race disparue de la planète Kleer, d'Alpha Canis Majoris. Il a de longues griffes pointues sur ses mains et une longue queue.

Ils attaquent soit en conjurant des griffes en bois, soit en coupant leurs griffes de près.

Comme les Kleers osés connus, celui-ci obtient une mutation qui fait leurs os en bois, c'est pourquoi il est appelé base en bois.

CONSEILS:

- Leurs attaques de saut sont mieux évitées par le biais d'un faux pas.
- Jetant des griffes aussi à portée de main.