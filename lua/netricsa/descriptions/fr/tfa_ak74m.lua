RISQUE DE KALASHNIKOV AK-74M ASSAULT


ARME: Kalachnikov AK-74M Rifle d'assaut
MUNITIONS:   5,45x39mm
CADENCE DE TIR:    ~600 tours/min
POIDS: ~3,4 kg

DESCRIPTION:

Un fusil d'assaut soviétique et russe, développé comme une version modernisée de l'AK-74. Il a été adopté en 1991 et est devenu l'un des principaux fusils d'assaut des forces armées russes. L'AK-74M conserve les caractéristiques de fiabilité de la famille AK mais a reçu un certain nombre d'améliorations, notamment un support en plastique pliant et un rail latéral pour le montage optique et nocturne.

Le fusil d'assaut utilise la cartouche de 5,45x39mm et un chargeur de 30 tours. Grâce au poids relativement léger de la cartouche et à un recul modéré, l'AK-74M est facile à contrôler en cas d'éclatement. La conception est conçue pour fonctionner dans diverses conditions climatiques.

REMARQUES:

- Le fusil d'assaut russe standard dans la famille AK depuis de nombreuses années.
- La cartouche de 5,45x39mm produit moins de recul que la cartouche de 7,62x39mm.
- Le rail latéral permet l'installation de divers sites.
- L'AK-47 est le grand-père, l'AK-74 devient le fils, et l'AK-74M arrive au conseil familial avec un stock pliant.
