FUSIL D'ASSAUT KALASHNIKOV AK-74M


ARME : Fusil d'assaut Kalachnikov AK-74M
MUNITIONS : 5.45x39mm
ROF : ~600 tours/min
POIDS : ~3,4 kg

DESCRIPTIF :

Un fusil d'assaut soviétique et russe, développé comme une version modernisée de l'AK-74. Il a été adopté en 1991 et est devenu l'un des principaux fusils d'assaut des forces armées russes. L'AK-74M conserve les caractéristiques de fiabilité de la famille AK mais a reçu un certain nombre d'améliorations, notamment une crosse pliable en plastique et un rail latéral pour le montage de viseurs optiques et nocturnes.

Le fusil d'assaut utilise la cartouche 5,45x39 mm et un chargeur de 30 cartouches. Grâce au poids relativement léger de la cartouche et au recul modéré, l'AK-74M est facile à contrôler lors du tir en rafale. La conception est conçue pour fonctionner dans diverses conditions climatiques.

REMARQUES :

- The standard Russian assault rifle in the AK family for many years.
- La cartouche 5,45x39mm produit moins de recul que la 7,62x39mm.
- Le rail latéral permet l'installation de divers viseurs.
- The AK-47 was the grandfather, the AK-74 became the son, and the AK-74M arrived at the family council with a folding stock.
