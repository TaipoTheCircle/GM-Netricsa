FUSIL À POMPE M133


ARME : Fusil à pompe M133
Munitions : calibre 12
ROF : ~60 tours/min

DESCRIPTIF :

Une arme puissante au corps à corps, particulièrement efficace contre les adversaires normaux et les animaux.

Le M133 utilise un mécanisme de pompe manuel. Le chargeur contient généralement environ 7 cartouches et peut être agrandi avec une extension. Diverses variantes du M133 sont disponibles, y compris des versions raccourcies, et peuvent également être équipées de viseurs, d'un suppresseur et d'un chargeur étendu.

L'apparence du M133 est un mélange de plusieurs conceptions du monde réel. Il est basé sur le modèle russe Baikal MP-133, mais certains éléments, dont la partie avant, ressemblent à d'autres fusils à pompe.

REMARQUES :

- Idéal pour les combats rapprochés et le nettoyage des espaces restreints.
- Le mécanisme à pompe rend le tir plus lent que celui des fusils de chasse semi-automatiques, mais la conception est assez simple.
- Particulièrement adapté à la chasse aux animaux dangereux.