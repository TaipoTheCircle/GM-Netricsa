M133 POMMES D'ACTION


ARME: M133 Pump-Action fusil de chasse
MUNITIONS:   12 Gauge
CADENCE DE TIR:    ~60 tours/min

DESCRIPTION:

Une puissante arme de quartier rapproché, particulièrement efficace contre les adversaires et les animaux normaux.

Le M133 utilise un mécanisme manuel d'action de la pompe. Le magazine compte généralement environ 7 tours et peut être agrandi avec une extension. Diverses variantes M133 sont disponibles, y compris des versions abrégées, et peuvent également être équipées de vues, d'un suppresseur et d'un magazine étendu.

L'apparence du M133 est un mélange de plusieurs conceptions du monde réel. Il est basé sur le Baïkal russe MP-133, mais certains éléments, y compris l'avant, ressemblent à d'autres fusils à pompe.

REMARQUES:

- Idéal pour le combat et le nettoyage des espaces étroits.
- Le mécanisme d'action de la pompe rend la prise de vue plus lente que les fusils semi-automatiques, mais la conception est assez simple.
- Particulièrement adapté pour la chasse aux animaux dangereux.
