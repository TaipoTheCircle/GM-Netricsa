ZORAKI STALKER M906 PISTOL SIGNAL


ARME:      Zoraki Stalker M906
MUNITIONS:        Cartouches PAK 9MM 
CADENCE DE TIR:         ~15 tours/min

DESCRIPTION:

Pistolet automatique de signalisation de la marque turque Zoraki. Convient pour l'autodéfense, effrayer les animaux sauvages, et lancer des feux d'artifice (à l'aide d'un lanceur de fusée).

REMARQUES:

- Pas un pistolet de combat et ne peut tuer qu'à bout portant.
- Peut aveugler une personne si 9MM PAK Flash Defense cartouches sont insérées dans le magazine.
