STROGG VOEUX DES STROGGOS


CLASSE : Strogg Retch 
MÉTABOLISME : organisme cybernétique
PERCEPTION : Brute d'assaut au corps à corps
TAILLE : 6,8 pieds
ENDURANCE : Élevée
HOSTILITÉ : Extrême
ARMES : membres cybernétiques, bras en lame, armes intégrées, frappes éclair
RÉCOMPENSE : 900 FC
MENACE : Très élevée

DESCRIPTIF :

Un type de Strogg très rare et peu étudié, provenant d'un programme militaire inconnu de Stroggification. Son existence est pratiquement non documentée et les informations à son sujet ne subsistent que dans des documents isolés liés au développement expérimental de Strogg. À en juger par sa structure, il a été créé comme une machine de combat spécialisée pour le combat rapproché agressif.

Son comportement ressemble à celui d'un berserker Strogga. Le Retch préfère réduire immédiatement la distance avec son adversaire, en utilisant ses membres cybernétiques massifs et son armement intégré. Son corps est un mélange de tissus organiques et de composants mécaniques lourds, nombre de ses membres étant remplacés ou renforcés par des constructions cybernétiques.

Le Retch semble être plus spécialisé dans les attaques de mêlée. Son armement est intégré directement dans son corps, lui permettant de poursuivre l'attaque sans perdre la capacité d'utiliser ses systèmes d'armes intégrés. Au combat, il est extrêmement agressif, avance constamment et oblige son adversaire à battre en retraite.

CONSEILS :

- Ne le laissez pas s'approcher. En combat rapproché, le Retch est particulièrement dangereux et peut rapidement réduire la distance.
- Ne comptez pas l'épuiser lentement. Sa grande endurance lui permet de résister à des tirs importants.