STROGG RETENUES PAR LES STROGGOS


CLASSE:      Strogg Retch 
MÉTABOLISME: Organisme cybernétique
PERCEPTION: Close Combat Assault Brute
TAILLE:       6,8 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Membres cybernétiques, bras de lame, armes intégrées, coups de foudre
RÉCOMPENSE:     900 FC
MENACE:     Très élevé

DESCRIPTION:

Un type de strogg très rare et peu étudié, issu d'un programme de stroggification militaire inconnu. Son existence est pratiquement sans papiers, et l'information à son sujet reste seulement dans des documents isolés liés au développement expérimental de Strogg. À en juger par sa structure corporelle, il a été créé comme une machine de combat spécialisée pour le combat rapproché agressif.

Son comportement ressemble à celui d'un berker de Strogga. Le Retch préfère fermer immédiatement la distance avec son adversaire, en utilisant ses membres cybernétiques massifs et ses armes intégrées. Son corps est un mélange de tissus organiques et de composants mécaniques lourds, avec beaucoup de ses membres remplacés ou renforcés par des constructions cybernétiques.

Le Retch semble être plus spécialisé dans les attaques à la mêlée. Son armement est intégré directement dans son corps, lui permettant de poursuivre l'attaque sans perdre la capacité d'utiliser ses systèmes d'armes intégrés. Au combat, il est extrêmement agressif, avance constamment et force son adversaire à se retirer.

CONSEILS:

- Ne le laisse pas se rapprocher. Au combat rapproché, le Retch est particulièrement dangereux et peut rapidement fermer la distance.
- Ne comptez pas le porter lentement. Sa grande endurance lui permet de résister à d'importantes quantités de feu.
