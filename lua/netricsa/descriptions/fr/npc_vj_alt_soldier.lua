DÉPLACEMENT SUPPLÉMENTAIRE


CLASSE:      Combiner le soldat Alt Overwatch
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Standard Combiner l'infanterie
TAILLE:       5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    AR2 Rifle d'impulsion, SMG
RÉCOMPENSE:     600 FC
MENACE:     Haut

DESCRIPTION:

Le Soldat Alt Combine Overwatch est une version modifiée du soldat Overwatch standard, conçu pour des opérations dans des environnements où l'armure bleue des unités est un désavantage. Sa tenue combine camouflage foncé avec un torse noir et des protecteurs de manches, rendant sa silhouette moins visible dans les zones industrielles, les rues nocturnes et les environnements intérieurs.

CONSEILS:

- Travaille strictement en groupe et rarement seul.
- L'AR2 est dangereux même à portée moyenne, donc évitez de rester debout à l'extérieur.
- La visière bleue est visible dans l'obscurité.
