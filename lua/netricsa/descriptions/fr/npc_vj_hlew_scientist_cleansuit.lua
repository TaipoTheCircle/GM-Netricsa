SCIENTIFIQUE DES SUITS BLACK MESA CLEAN


CLASSE:      Black Mesa Clean Suit Scientifique
MÉTABOLISME: Humain, Homme
PERCEPTION: Personnel de recherche Black Mesa (Division des milieux dangereux)
TAILLE:       ~5,9 pi
ENDURANCE:  Moyenne
HOSTILITÉ:  Aucune
ARMES:    Aucune
RÉCOMPENSE:     50 FC 
MENACE:     Négligeable

DESCRIPTION:

Les scientifiques Clean Suit sont une branche spécialisée du personnel de recherche Black Mesa affecté à des environnements dangereux. Dotés de combinaisons de protection pour le corps entier, ils sont principalement déployés dans des zones présentant des dangers biologiques, chimiques ou radiologiques, où les vêtements de laboratoire normaux signifieraient une mort certaine. Leurs casques sont scellés, avec des systèmes respiratoires limités pour filtrer l'air contaminé.

Ces scientifiques travaillaient souvent sur des projets sensibles dans des zones réglementées, entretenaient du matériel ou manipulaient des matériaux volatils. Lorsque la Cascade de résonance a frappé, leurs costumes leur ont donné un léger avantage de survie contre les toxines et les spores de Xen, bien qu'elles demeurent tout aussi vulnérables aux menaces physiques.

Malgré leur formation professionnelle, ils ne sont pas des combattants - leur instinct de survie est de fuir et de chercher refuge, laissant les rôles de combat à la sécurité et aux forces de l'UE. Leurs connaissances sont toutefois inestimables : beaucoup ont accès à des codes d'autorisation, à des systèmes de confinement et à des laboratoires de mise au point d'armes cachés au fond de l'installation.

CONSEILS:

- Les protéger si possible - ils ont souvent des informations utiles.
- Ne vous attendez pas à ce qu'ils se battent; évitez de les utiliser comme boucliers.
- Écoutez attentivement leurs cris - ils pourraient indiquer un danger à proximité.
