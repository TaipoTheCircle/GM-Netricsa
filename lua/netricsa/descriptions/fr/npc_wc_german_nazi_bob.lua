BOB, VENDU NAZI


CLASSE:      Bob, soldat nazi
MÉTABOLISME: Humain, Homme
PERCEPTION: Infanterie Wehrmacht 
TAILLE:       6 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Faible 
ARMES:    MP-40
RÉCOMPENSE:     300 FC
MENACE:     Moyenne

DESCRIPTION:

Le Fuhrer a donné le soldat Bob à Ghostface. Depuis ce jour, Bob n'est plus seulement un nazi - il est le compagnon et ami éternel de Ghostface. Fidèle, discipliné et armé de son MP-40, Bob suit partout son nouveau maître, servant non par peur, mais par camaraderie incassable.

CONSEILS:

- Bob agit rarement seul - il est toujours près de Ghostface.
- Son MP-40 est très dangereux.
