SNARK NEST, EAU


ARME:      Nid noir, arme
MUNITIONS:        Des animaux étrangers
CADENCE DE TIR:        ~1 par seconde (vitesse de lancement)

DESCRIPTION:

Petits organismes exotiques agressifs lancés comme armes vivantes. Les pièges attaquent les ennemis voisins sans relâche jusqu'à ce qu'ils explosent.

REMARQUES:

- Agressivité infinie une fois libérée.
- Peut nuire à l'utilisateur si aucune cible n'est présente.
- Mieux utilisé pour le déni ou la distraction.