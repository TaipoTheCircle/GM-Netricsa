RIFLE SÉMI-ATOMATIQUE MAS-49


ARME: Rifle semi-automatique MAS-49
MUNITIONS:   7.5x54mm Français
CADENCE DE TIR:    Capacité semi-automatique, 10 tours

DESCRIPTION:

Un fusil semi-automatique français développé et fabriqué par l'entreprise publique Manufacture d'armes de Saint-Étienne (MAS). Il a été fondé sur des plans expérimentaux antérieurs par des armuriers français et adopté pour le service en 1949. En vue de remplacer les fusils à action de boulons obsolètes, il est devenu la principale arme individuelle de l'armée française dans l'après-guerre. Il dispose d'un stock de bois, d'un tube de gaz distinct positionné au-dessus du baril, et d'un design simple et fiable.

L'action fonctionne via un système direct d'impingement de gaz, où les gaz propulseurs sont dirigés directement vers le porte-boulons sans l'utilisation d'un piston à gaz séparé. La fente est verrouillée en inclinant le boulon. Il tire la cartouche 7.5x54mm de fusil français et utilise un chargeur de 10 ronds amovible. Il peut également être chargé à l'aide de pinces à strip-teaseuses à 5 tours, pour lesquelles des guides sont fournis sur le boulon. Un rail de montage pour une vision optique APX est situé sur le côté gauche du récepteur.

REMARQUES:

- Adopté par l'armée française en 1949.
- Peser environ 4,7 kg avec une longueur hors tout de 1100 mm.
- La vitesse du museau atteint environ 820 m/s.
- La portée de tir efficace est d'environ 400 mètres; avec une vue optique, cela peut s'étendre à 800 mètres.
- Il y a une variante raccourcie, le MAS-49/56, qui présente des dimensions plus compactes et la capacité de monter une baïonnette.
- Plus tard, le système direct d'impingement de gaz a été largement reconnu grâce à son utilisation dans la famille américaine de fusils AR-15.
