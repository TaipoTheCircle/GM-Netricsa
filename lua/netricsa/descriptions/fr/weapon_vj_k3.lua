RIFLE AUTOMATIQUE K-3


ARRÊT DE L'ARRIÈRE K-3
Rondes AMMO 5,45x39mm (compatibles avec les magazines AK-74)
ROF ~600 minutes

DESCRIPTION:

Le fusil d ' assaut arménien a été développé dans les années 90 sur la base du modèle AK-74. En vue de remplacer les anciens fusils des forces armées arméniennes, principalement destinés aux unités d ' opérations spéciales. Il est doté d'une disposition compacte, d'un mobilier en polymère et d'une compatibilité avec les magazines 30-round AK-74.

REMARQUES:

- Modes d'incendie semi-automatiques et entièrement automatiques.
- Portée efficace jusqu'à 500 mètres.
- Mécanisme à gaz avec boulon rotatif et piston à longue course.
- Équipé de vues en fer; la portée optique (PSO-1) peut être montée.
- Peut lancer des grenades avec l'adaptateur 3K-3.
- Conception légère et compacte adaptée aux quartiers proches et aux combats urbains.