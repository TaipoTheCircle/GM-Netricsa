GAUCHE DE MÉTHAMPHÉTAMINE


ARME: Sac de méthamphétamine "Blue Sky"
MUNITIONS:   Un paquet

DESCRIPTION:

Un sac contenant de la méthamphétamine avec une teinte bleue distinctive, appelée "Blue Sky". Lorsqu'il est consommé, il produit un puissant effet stimulant, augmentant significativement la vitesse de déplacement de l'utilisateur. En même temps, la perception qu'a l'utilisateur de son environnement est presque entièrement perturbée, ce qui rend l'orientation spatiale extrêmement difficile.

Une utilisation prolongée peut être fatale. La combinaison avec le whisky exacerbe encore les conséquences, rendant cette expérience particulièrement dangereuse.

REMARQUES:

- Cause une augmentation significative de la vitesse de l'utilisateur.
- Élimine virtuellement la perception de l'utilisateur de son environnement.
- Une utilisation prolongée peut entraîner la mort.
- La combinaison avec du whisky aggrave significativement les effets.
- "Jesse, nous devons cuisiner!".
