OLIVER DE L'ENSEIGNEMENT DU PAPIER FONDAMENTAL


CLASSE:       Oliver
MÉTABOLISME:  Organisme anthropomorphe modifié du papier
PERCEPTION:  Chef Bully
TAILLE:        6 pieds
ENDURANCE:   Haut
HOSTILITÉ:   Sadiste
ARMES:     Crayon au lieu d'une main droite, intelligence, connexion avec les poux
RÉCOMPENSE:      99 F
MENACE:      Très élevé

DESCRIPTION:

Le chef de l'école et l'un des "favorites" de Miss Circle, un ami d'enfance et un petit ami de Poux. Contrairement aux élèves ordinaires, lui et -lice ne sont pas des étudiants de Paper School au sens traditionnel, mais plutôt ses « invités spéciaux » ou une partie d'un système caché. Reconnaissable par ses longs cheveux blancs de la cheville, ses cornes noires, une note "A+" dans ses cheveux, et un crayon à la place de sa main droite. Sa langue est fourrée comme celle d'un serpent. Il porte une chemise noire avec un symbole en diamant (identique au symbole sur la poux). C'est un tyran sadique, arrogant et ludique, dépourvu d'empathie. Il aime tourmenter les autres et est capable de tuer pour s'amuser. Il possède clairement une durabilité accrue et peut-être d'autres capacités (manger des objets non comestibles comme le savon).

CONSEILS:

- C'est un maître de la manipulation et des pièges.
- Il est animé par l'ennui, le sadisme et la dévotion aux poux. Ne cherchez pas la logique ou la pitié dans ses actions.