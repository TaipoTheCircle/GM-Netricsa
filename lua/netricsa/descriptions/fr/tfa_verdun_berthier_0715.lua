BERTHIER 1907/15 RIFLE D'INFANTRY


ARME: Berthier 1907/15 Infantry Rifle
MUNITIONS:   8x50mm R Lebel
CADENCE DE TIR:    ~15-20 tours/min

DESCRIPTION:

Fusil français alimenté par des magazines, basé sur le système Berthier, adopté pour le service en 1915. Il a été conçu pour équiper les unités d'infanterie de l'armée française pendant la Première Guerre mondiale. Il dispose d'un mécanisme d'action de boulons, d'un stock en bois et d'un magazine de style Mannlicher. Il est devenu l'une des principales variantes de la série de fusils Berthier utilisée par l'armée française tout au long de la guerre.

Le fusil fonctionne à l'aide d'un mécanisme d'action à boulons actionné manuellement et côtoit la puissante cartouche de fusil R Lebel de 8x50mm. Il est alimenté à partir d'un chargeur interne avec une capacité de 3 tours, qui est chargé à l'aide d'un clip en-bloc spécialisé. Une fois les munitions épuisées, le clip est éjecté par une ouverture située au bas du récepteur. Il est équipé de vues en fer ouvert et d'une monture baïonnette. En 1916, la variante M1916 est présentée, avec un magazine élargi à 5 tours.

REMARQUES:

- Efficace contre des cibles individuelles à moyenne et longue distance.
- Le magazine tient 3 tours.
- Utilise un clip en bloc de style Mannlicher.
- Employé par l'armée française pendant la Première et la Seconde Guerres mondiales.
