STRIDER MINI METROCOP DE PROTECTION CIVILE DE LA COMBINE


CLASSE:      Combiner la protection civile Strider Mini Metrocop
MÉTABOLISME: Humain, Homme
PERCEPTION: Opérateur intégré de synthés de combat lourd
TAILLE:       0,9 ft
ENDURANCE:  Très faible
HOSTILITÉ:  Haut
ARMES:    Contrôle des armes primaires de Strider
RÉCOMPENSE:     400 FC
MENACE:     Faible

DESCRIPTION:

Le Strider Mini Metrocop est une forme encore plus radicale d'intégration humaine dans le synthé de combat Combine. Contrairement aux opérateurs MiniStrider, ces Metrocops sont pleinement intégrés dans le compartiment biomécanique central de la Strider et n'ont aucune autonomie en dehors de sa coque.

Leurs corps sont soumis à une compression constante, à une retenue et à une synchronisation neuronale avec le système de commande du marcheur. Toutes les fonctions vitales sont supportées uniquement par les systèmes embarqués du Strider. La vision, l'ouïe et l'orientation spatiale sont complètement remplacées par l'entrée sensorielle de la machine, qui se nourrit directement dans le système nerveux de l'opérateur.

Contrairement à la version intégrée dans MiniStrider, l'opérateur Strider ne peut pas être libéré, même théoriquement. Leur capsule de compression fait partie de la structure de support. Détruire le marcheur provoque immédiatement des pertes de survie, des connexions neurales coupées et la destruction critique du corps de l'opérateur. Le retour à la taille normale est impossible.

CONSEILS:

- Détruire le Strider garantit la destruction du conducteur à l'intérieur.
