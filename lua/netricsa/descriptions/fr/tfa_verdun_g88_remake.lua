GEWEHR 88/05 "KOMMISSIONSGEWEHR" RIFLE D'INFANTRY


ARME: Gewehr 88/05 "Kommissionsgewehr" Rifle d'infanterie
MUNITIONS:   7.92x57mm Mauser
CADENCE DE TIR:    ~12 tours/min

DESCRIPTION:

Fusil allemand alimenté par un magazine, il s'agit d'une version améliorée de la Gewehr 1888, qui a été initialement développée par la Commission allemande d'essais du Rifle (*Gewehr-Prüfungskommission*). La modernisation, qui a débuté en 1905, avait pour but d'adapter les fusils plus anciens à la nouvelle cartouche à bullet pointu, le *S-Patrone*. Le système de chargement a également été modifié, ce qui a permis au fusil d'utiliser des clips de strip-teaseuse à cinq tours standard. Il a été utilisé par l'armée allemande pendant la Première Guerre mondiale aux côtés de Gewehr 98 plus moderne.

Le fusil fonctionne à l'aide d'un mécanisme d'action à boulons actionné manuellement et sert de chambre à la cartouche Mauser 7.92x57mm. Il est alimenté à partir d'un magazine de boîte interne d'une capacité de 5 tours, chargé à partir du haut à l'aide d'un clip de strip-teaseuse. Contrairement à l'original Gewehr 1888, qui utilisait un clip *en-bloc* de style Mannlicher, cette version améliorée comporte des guides pour les clips de strip-teaseuse Mauser et une ouverture fermée où le clip *en-bloc* vide aurait été éjecté. Il est équipé d'un long tonneau encastré dans un manchon de protection, d'un stock en bois et de vues en fer.

REMARQUES:

- Efficace contre des cibles individuelles à moyenne et longue distance.
- Le magazine tient 5 tours.
- Il utilise la cartouche S-Patrone pointue.
- Environ 350 000 fusils Gewehr 88 ont été convertis à la norme 88/05.
