MISS BLOOMIE DE L'ENSEIGNEMENT DU PAPIER FONDAMENTAL


CLASSE:      Mlle Bloomie
MÉTABOLISME: Organisme de papier (enseignante mutante)
PERCEPTION: Professeur de sciences
TAILLE:       ~8,2 pi
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Lame de coupe-boîte (prothèse du bras gauche), griffes pointues et dents, langue de serpent fourchue
RÉCOMPENSE:     1000 FC
MENACE:     Haut

DESCRIPTION:

Elle enseigne la science (biologie, chimie, physique). Reconnaissable par ses cheveux courts, ses cornes noires de longueurs variables et son arc blanc. Sa main gauche est remplacée par une lame de coupe géante et tranchante, et sa main droite a des doigts pointus. Elle possède une langue de serpent fourchue, évoquant une nature prédatrice. Elle est plus réservée et sévère que Miss Circle, montrant moins de «joueur». Ses attaques sont précises.

CONSEILS:

- Sa lame prothétique est une arme pour les attaques rapides. Il est plus long qu'il ne semble et peut être utilisé à la fois pour les attaques de melee et pulmonaire.
- Elle travaille en trio avec Mlle Circle et Mlle Tavel. Elle est la plus courte des trois, mais pas moins dangereuse.