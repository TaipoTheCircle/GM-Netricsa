SLENDERMAN, L'HOMME SLIM (20 DOLLARS )


CLASSE:      Slenderman, l'homme mince (20 dollars)
MÉTABOLISME: Non biologique
PERCEPTION: Légende urbaine
TAILLE:       12 pieds
ENDURANCE:  Immesurable
HOSTILITÉ:  Absolu
ARMES:    Tentacles, téléportation, saut, télépathie, manipulation de mémoire, simple présence
RÉCOMPENSE:     2009 CF
MENACE:     Absolu

DESCRIPTION:

C'est un homme maigre en costume noir avec une chemise blanche. Sa peau est pâle, ses membres sont naturellement longs et peuvent se plier dans n'importe quelle direction. Des tentacules ou appendices noirs flexibles poussent parfois du dos. Et surtout, il est complètement sans visage. Là où son visage doit être, il y a un vide lisse. Pas d'yeux, pas de nez, pas de bouche.

Slenderman voyage par téléportation. Il apparaît et disparaît silencieusement. Au contact, il provoque de graves maux de tête, des interférences électroniques et un sentiment de terreur inexplicable. Il peut effacer ou modifier des souvenirs, transformer les gens en mandataires (puppets), et amener les enfants à un endroit inconnu.

CONSEILS:

- Si tu le vois, il te voit déjà. Courir est inutile, il téléporte.
- Ne le regarde pas dans les yeux. Il n'en a pas.
- Static sur votre appareil photo ou téléphone est le premier signe qu'il est à proximité. Éteignez votre appareil et partez.
- La seule façon de survivre est de ne pas penser à lui. Mais maintenant tu penses déjà à lui.
