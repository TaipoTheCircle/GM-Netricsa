RHINO CYBER-TOY


CLASSE:       Cyberjouet Rhino
MÉTABOLISME:  Mammifère amélioré par la cybernétique 
PERCEPTION:  Animal de guerre entraîné
TAILLE:        6,5 pieds
ENDURANCE:   Moyenne
HOSTILITÉ:   Extrême 
ARMES:     Cornes
RÉCOMPENSE:      300 FC
MENACE:      Haut

DESCRIPTION:

L'introduction de Cyber-Rhinos a été une malheureuse surprise pour l'armée humaine pendant la guerre contre le mental.

Ayant conquis de nombreuses planètes et amené des milliards d'êtres vivants sous son contrôle, Mental voulait garder le pouvoir entre ses propres mains, et il a donc été décidé de donner à chaque famille dans son gigantesque empire un jouet de rhinocéros.

La production de masse a commencé.

La joie et le bonheur remplissaient le monde de la souffrance et de la douleur que le mental avait créé.

Mais dès que la guerre avec la Terre a commencé, dès que Sam Stone a commencé à tirer sur les talons du méchant, libérant une planète après l'autre, les rhinocéros ont été équipés d'un moteur et d'un réservoir de carburant et jetés au combat !

Les rhinos sont plus agressifs et plus rapides que leurs cousins, grâce à des améliorations cybernétiques. La façon de les traiter est la même; restez en dehors de leur chemin et utilisez des explosifs. Mais il faudra être encore plus prudent.

CONSEILS:

- Pour éviter leurs attaques.
- Utilisez des explosifs pour les enlever.
