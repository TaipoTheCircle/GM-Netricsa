UNE VILLE POUR LES AMIS 2


La ville se compose de plusieurs bâtiments, dont un garage en briques et un amas de gratte-ciel, principalement composé de fenêtres sans porte. Certaines routes longent les toits, reliant les bâtiments. L'atmosphère est minimaliste - le ciel gris, l'herbe verte, et la ville vide créent un sentiment d'espace et un léger isolement.