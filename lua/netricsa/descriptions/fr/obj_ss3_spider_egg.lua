COCOONE ANTARÉSIENNE DE L'ESPÈCE D'ANTARES PRIME


CLASSE:      Cocoon d'araignée antarésienne
MÉTABOLISME: Capsule fixe organique
PERCEPTION: Capsule de protection
TAILLE:       1,6 ft
ENDURANCE:  Faible
HOSTILITÉ:  Passif
ARMES:    Délivre une araignée antarésienne lors de la destruction
RÉCOMPENSE:     10 FC
MENACE:     Moyenne

DESCRIPTION:

Une structure organique qui sert d'incubateur pour une seule araignée antarésienne. Il se compose d'un réseau de bioracines fortes et sinewy qui l'ancrent aux surfaces - le plus souvent des plafonds, des planchers ou des murs dans des endroits où les araignées se sentent en sécurité (caves, sous-sols, tunnels abandonnés). Le cocon n'attaque pas. Lorsqu'elle est détruite (par un tir, une explosion ou un impact), une araignée éclate et attaque immédiatement l'intrus.

CONSEILS:

- Après destruction, préparez-vous à une attaque immédiate. Prenez une position favorable avant.
