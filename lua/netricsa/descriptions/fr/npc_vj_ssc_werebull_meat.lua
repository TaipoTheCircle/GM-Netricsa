SIRIAN WEREBULL, VIANDE


CLASSE:      Sirian Werebull, Viande
MÉTABOLISME: Mammifère mutant
DEFINITION: Ébauche, animal à viande
TAILLE:       9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES: Cornes
RÉCOMPENSE:     3500 FC
MENACE:     Haut

DESCRIPTION:

Un hybride génétique d'une espèce de Sirian et d'une espèce bovine. Le comportement de Werebull est similaire à celui d'un taureau normal : il se charge à pleine vitesse, visant à gore son adversaire.

Le Werebull Meat Bull est le résultat de la conception de Mental: il a écorché plusieurs supports de werebull pour ses vêtements et ceux de ses collègues. Le taureau est complètement écorché, révélant muscles et tendons. Ses yeux sont absents, mais il est toujours incroyablement sensible aux menaces qui l'entourent. Il est aussi vicieux qu'un taureau normal, car chaque cellule de son corps ressent la douleur et la colère lorsqu'elle est exposée à l'air.

Au combat, il attaque avec une charge de course, jetant sa victime sur ses cornes et infligeant des lacérations. Malgré son apparence terrifiante, ce taureau est considéré comme une « délicatesse » sur la planète Sirius, bien que personne qui l'ait rencontré sur le champ de bataille n'ait été pressé de l'essayer.

CONSEILS:

- Sortez de la ligne de tir de l'attaque.
- On dirait un ragoût de loin, mais c'est en fait l'arme mortelle de Mental.