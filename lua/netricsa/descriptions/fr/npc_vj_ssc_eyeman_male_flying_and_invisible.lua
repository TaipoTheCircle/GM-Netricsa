MILLE GNAAR


CLASSE:      Gnaar, Homme
MÉTABOLISME: Mammifère
PERCEPTION: Animal de guerre entraîné
TAILLE:       4 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Faible
ARMES:    Morceaux, coups de poing
RÉCOMPENSE:     500 FC
MENACE:     Très faible

DESCRIPTION:

Un petit animal bipède sans tête, un œil et une grande bouche. Originaire de Sirius, et entraîné par Mental à attaquer les forces opposées. Les mâles sont plus petits, violets et pas aussi durs que les femelles.

CONSEILS:

- Ils n'ont pas d'armes.
- Certaines espèces peuvent léviter.
- Des spécimens rares ont été signalés comme invisibles.
