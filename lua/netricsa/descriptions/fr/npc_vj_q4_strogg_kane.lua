STRAG MATTHEW KANE DES STROGOGOS


CLASSE:      Strogg Matthew Kane
MÉTABOLISME: Cybernétique Human-Hybrid
PERCEPTION: Infanterie tactique Strogg
TAILLE:       5,9 pieds
ENDURANCE:  Haut (Armure + Améliorations cybernétiques)
HOSTILITÉ:  Extrême
ARMES:    Shotgun, Machine Gun, Hyper Blaster, Railgun
RÉCOMPENSE:     5200 FC
MENACE:     Haut

DESCRIPTION:

Ce... specimen... est assez inhabituel. Un cas unique parmi les Strogg. Il était autrefois un homme et un caporal dans le Space Marine Corps, servant dans l'unité d'élite "Rhino Squad". Après avoir été capturé par le Strogg, Kane a subi une procédure de stroggification, qui a conduit à une grande partie de son corps à être remplacé par des composants cybernétiques.

Cependant, Kane n'est pas devenu un Strogg normal. Sa transformation a été interrompue avant l'achèvement de l'étape la plus cruciale de la procédure, empêchant le neurocyte de prendre pleinement le contrôle de sa conscience. En conséquence, Kane conserva sa volonté et continua à lutter contre ceux qui l'avaient transformé en cyborg.

Après une stroggification partielle, son corps est devenu significativement plus fort que celui d'un humain. Les jambes cybernétiques ont augmenté sa vitesse et son endurance physique, et les systèmes intégrés lui permettent d'interagir avec la technologie Strogg, y compris leurs terminaux, téléporteurs et stations médicales. En outre, Kane est capable de passer en toute sécurité à travers certains systèmes laser défensifs de Strogg qui seraient mortels pour un humain normal.

Pour ce qui est des capacités de combat, Kane ressemble le plus à Tactic Strogg. Cela est particulièrement remarquable, car ces unités ont été créées à partir des personnes les plus qualifiées et conçues pour mener des opérations de combat complexes. Ils utilisent la couverture, les manœuvres d'accompagnement et coopèrent les uns avec les autres, plutôt que de simplement courir vers l'ennemi.

Kane, cependant, conserve les compétences d'un soldat chevronné. Il est capable de manipuler pratiquement toutes les armes dont il dispose, de changer rapidement d'armes selon la situation et d'utiliser l'environnement contre l'ennemi.

Mais la principale distinction de Kane n'est pas son armement; c'est sa compréhension de la façon dont les humains pensent. Et en même temps, il sait comment fonctionne le Strogg.

Simplement, pour le Strogg, il reste un élément dysfonctionnement qui conserve d'une manière ou d'une autre la capacité de prendre des décisions indépendamment.

CONSEILS:

- Sa désignation est 8462-9B.
Kane est un combattant extrêmement précieux pour l'unité humaine.
- Ne le confondez pas avec un Strogg. Malgré son apparence, Kane se bat du côté des humains.
- Si, pour une raison quelconque, Kane se trouve un ennemi, la situation devient beaucoup plus difficile que lorsqu'il fait face à un Strogg régulier.
- Kane combine tactiques humaines et capacités de Strogg.
