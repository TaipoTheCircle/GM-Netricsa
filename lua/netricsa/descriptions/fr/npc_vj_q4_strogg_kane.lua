STROGG MATTHEW KANE DES STROGGOS


CLASSE : Strogg Matthew Kane
MÉTABOLISME : Humain-Hybride Cybernétique
PERCEPTION : infanterie tactique Strogg
TAILLE : 5,9 pieds
ENDURANCE : Élevée (armure + améliorations cybernétiques)
HOSTILITÉ : Extrême
ARMES : Fusil de chasse, Mitrailleuse, Hyper Blaster, Railgun
RÉCOMPENSE : 5200 FC
MENACE : Élevée

DESCRIPTIF :

Ce... spécimen... est assez inhabituel. Un cas unique chez les Strogg. Il était autrefois humain et caporal dans le Space Marine Corps, servant dans l'unité d'élite « Rhino Squad ». Après avoir été capturé par les Strogg, Kane a subi une procédure de stroggification, qui a abouti au remplacement d'une partie importante de son corps par des composants cybernétiques.

Cependant, Kane n’est pas devenu un Strogg normal. Sa transformation a été interrompue avant que l’étape la plus cruciale de la procédure ne soit terminée, empêchant le neurocyte de prendre pleinement le contrôle de sa conscience. En conséquence, Kane a conservé sa volonté et a continué à lutter contre ceux qui l'avaient transformé en cyborg.

Après une stroggification partielle, son corps est devenu nettement plus fort que celui d'un humain. Les jambes cybernétiques ont augmenté sa vitesse et son endurance physique, et des systèmes intégrés lui permettent d'interagir avec la technologie Strogg, y compris leurs terminaux, téléporteurs et postes médicaux. De plus, Kane est capable de traverser en toute sécurité certains systèmes laser défensifs Strogg qui seraient mortels pour un humain normal.

En termes de capacités de combat, Kane ressemble le plus à Tactical Strogg. Ceci est particulièrement remarquable, car ces unités ont été créées à partir des individus les plus hautement qualifiés et conçues pour mener des opérations de combat complexes. Ils utilisent la couverture, les manœuvres de flanc et coopèrent les uns avec les autres, plutôt que de simplement courir vers l'ennemi.

Kane conserve cependant les compétences d’un soldat chevronné. Il est capable de manipuler pratiquement toutes les armes à sa disposition, de changer rapidement d'arme en fonction de la situation et d'utiliser l'environnement contre l'ennemi.

Mais la principale distinction de Kane ne réside pas dans son armement ; c'est sa compréhension de la façon dont les humains pensent. Et en même temps, il sait comment fonctionnent les Strogg.

En termes simples, pour le Strogg, il reste un élément défectueux qui conserve d’une manière ou d’une autre la capacité de prendre des décisions de manière indépendante.

CONSEILS:

- Sa désignation Strogg est 8462-9B.
- Kane est un combattant extrêmement précieux pour l'unité humaine.
- Ne le confondez pas avec un Strogg ordinaire. Malgré son apparence, Kane se bat aux côtés des humains.
- Si, pour une raison quelconque, Kane se retrouve comme un ennemi, la situation devient nettement plus difficile que face à un Strogg ordinaire.
- Kane combine tactiques humaines et capacités Strogg.
