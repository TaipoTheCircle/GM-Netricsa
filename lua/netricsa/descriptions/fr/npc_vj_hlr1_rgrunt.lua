S.E.C.U. GRUNT ROBOT


CLASSE:      S.E.C.U. Robot Grunt
MÉTABOLISME: Plateforme de combat pilotée par l'IA
PERCEPTION: Unité d'infanterie cybernétique (Prototype de l'U.S.E.C.)
TAILLE:       ~6,5 pi
ENDURANCE:  extrêmement élevé 
HOSTILITÉ:  extrême
ARMES:    MP5, lance-grenades, bras latéral
RÉCOMPENSE:     2800 FC
MENACE:     très élevé

DESCRIPTION:

Le Robot Grunt de l'U.S.C. est un remplacement mécanisé des soldats humains de l'Unité de combat pour l'environnement dangereux. Conçus pour des zones de combat dangereuses comme les incursions de Xen ou les sites de catastrophes de résonance, ces machines éliminent le « facteur humain » - pas de fatigue, pas d'hésitation, et pas de soucis moraux.

Leur conception imite les troupes standard de S.E.C.U. pour intimider et tromper les ennemis, mais sous le camouflage se trouve un exosquelette renforcé avec AI de combat qui calcule la tactique en temps réel. Contrairement à Robo Black Ops Assassins (optimisé pour la furtivité), les Grunts Robot de l'U.E.C. servent de boxeurs de choc, posant un feu suppressif avec une précision et une endurance inhumaines.

Des rumeurs à Black Mesa suggèrent que ces robots ont été testés sur le terrain pendant l'incident, remplaçant les équipes qui « ne sont jamais revenues ». Les survivants chuchotent que leurs voix froides et synthétiques appelant "Target acquis" étaient la dernière chose que beaucoup n'ont jamais entendue.

CONSEILS:

- Traitez-les comme des mini-tanks.
- les munitions explosives peuvent désactiver leurs systèmes plus rapidement que les balles.
Ils se battent jusqu'à destruction.
