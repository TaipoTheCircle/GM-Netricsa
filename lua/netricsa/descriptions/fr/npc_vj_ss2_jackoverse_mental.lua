MENTAL (TAH-UM)


CLASSE:      Mental (Tah-Um)
MÉTABOLISME: Dieu immortel
PERCEPTION: Dernier de la course Hum-Tah
TAILLE:       Inconnu
ENDURANCE:  Pratiquement illimité
HOSTILITÉ:  Absolu
ARMES:    Capacités psioniques, magie ancienne, technologie Hum-Tah, innombrables armées
RÉCOMPENSE:     Paix
MENACE:     Maximum

DESCRIPTION:

Mental, également connu sous son vrai nom, Tah-Um, est considéré comme la plus grande menace pour la vie intelligente dans la galaxie connue. Il est le dernier représentant connu de l'ancienne race des êtres immortels et divins, le Hum-Tah, qui possédait autrefois des connaissances bien supérieures à la technologie moderne de la plupart des civilisations.

On estime que le mental a des millions d'années. Pendant ce temps, il a conquis ou détruit d'innombrables mondes, essuyant des civilisations entières du visage de l'univers. Les peuples capturés sont soit complètement exterminés, soit intégrés à son armée sans fin par des modifications biologiques, mécaniques ou génétiques.

La plupart des armées connues de Mental ne sont pas composées de volontaires, mais d'êtres esclaves. Beaucoup de formes de vie ont été artificiellement modifiées spécifiquement pour la guerre. Les prisonniers sont souvent soumis à des expériences ou des exécutions cruelles, après quoi leurs corps sont utilisés pour créer de nouvelles unités de combat. C'est ainsi que de nombreux soldats sans tête, kamikazes et autres membres de ses forces ont été créés.

Malgré son pouvoir pratiquement illimité, Mental lui-même apparaît rarement sur le champ de bataille en personne. Au lieu de cela, il dirige la guerre par des généraux, des commandants et de nombreux gouverneurs, en coordonnant les actions de ses armées avec des capacités psioniques colossales. Sa forme observable n'est qu'une gigantesque projection sombre, tandis que la vraie apparence de Tah-Um reste inconnue.

En plus de son incroyable intelligence, Mental possède l'ancienne magie de Hum-Tah, la technologie d'une civilisation disparue, et les capacités psioniques qui lui permettent d'influencer l'esprit des autres, de contrôler de vastes armées et de coordonner les invasions à travers plusieurs systèmes étoiles.

Pendant des millénaires de guerre, le seul ennemi qui a déjoué ses plans à plusieurs reprises était "Sérieux" Sam Stone (Vous). C'est cette incapacité à éliminer complètement un seul individu qui a forcé Mental à recourir aux méthodes de guerre les plus radicales, y compris la destruction de planètes entières.

Malgré toutes les informations recueillies, les origines de Hum-Tah, les limites des pouvoirs de Tah-Um, et son emplacement réel restent inconnus.

CONSEILS:

- Si vous rencontrez Mental en personne, les événements ont pris un tour très défavorable.
- Ne sous-estimez pas l'ennemi juste parce qu'il s'engage rarement dans la bataille personnellement.
- Détendez-vous.
- Il ne peut pas jeter la Lune sur lui-même; laissez votre imagination courir sauvage!
