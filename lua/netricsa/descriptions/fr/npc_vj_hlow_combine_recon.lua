VENDU DE RÉCON SURVEILLANCE DE LA COMBINE


CLASSE:      Combiner le soldat Recon Overwatch
MÉTABOLISME: Augmenté Humain, Homme
PERCEPTION: Reconnaissance et appel en Combinez les renforts
TAILLE:       5,9 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Haut
ARMES:    SMG modifié (à simple tir), pistolet à fusée
RÉCOMPENSE:     350 FC
MENACE:     Très élevé

DESCRIPTION:

Le Soldat Combine Overwatch Recon est les yeux et les oreilles du Combine sur les lignes de front. Il n'est pas conçu pour un combat prolongé ou une confrontation directe. Sa mission principale est de localiser l'ennemi, de déterminer sa position et de transformer immédiatement un incident localisé en une opération punitive à grande échelle.

Il est armé d'une mitrailleuse modifiée qui ne tire qu'un seul coup. Cela augmente la précision, réduit le bruit et conserve les munitions. Cependant, l'outil principal du soldat est le pistolet à fusée bleue. Un tir dans le ciel, et peu de temps plus tard, une élite Combine transport portant une troupe de soldats apparaît dans la région.

L'armure de la reconnaissance est intentionnellement faible. Il doit se déplacer rapidement, se cacher, changer de position et éviter le feu direct. S'il n'est pas éliminé à temps, la situation va rapidement s'aggraver.

La recon se bat rarement à mort. Son but est de survivre assez longtemps pour demander des renforts. Après cela, il peut soit se retirer, soit fournir un feu d'appoint aux soldats qui arrivent.

CONSEILS:

- Éliminer le plus vite possible - une éruption peut tout gâcher.
- Sa faible armure le rend vulnérable même aux armes légères.
- Ne lui donnez pas de temps ni de distance pour manœuvrer.