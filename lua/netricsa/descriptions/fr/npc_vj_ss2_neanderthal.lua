BRUT PRIMTIF DE M'DIGBO


CLASSE:      Brute primaire
MÉTABOLISME: Mammifère
PERCEPTION: Être primitif
TAILLE:       6,8 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Moyenne
ARMES:    Club épicé, bouclier en bois
RÉCOMPENSE:     150 FC
MENACE:     faible

DESCRIPTION:

M'Digbo est parsemé d'innombrables tribus primitives, qui ont toutes un comportement très territorial et agressif. Ils attaquent presque tout le monde sous impulsion et ne sont pas plus intelligents qu'un tas de briques.

Ils sont une race humanoïde dirigée par le mystérieux "Mommy".

Lorsque les forces de Mental ont colonisé M'Digbo, les primitifs ont lancé des attaques contre eux. Ils sont tous morts. Après cela, ils ont commencé à adorer Mental comme un dieu de guerre et lui ont promis leur allégeance. Cela a été fait par peur et respect pour Mental, ainsi que la culotte léopard stylistique que Sirius Fashion Inc leur a fourni.

Leur arme la plus puissante est un simple club pointu, bien que certains portent également des boucliers en bois faits sur mesure de la planète Chi-Fang. Les tactiques sont inexistantes parmi eux, alors attendez-vous à ce qu'ils se précipitent après vous tout en oscillant avec colère leurs clubs.

CONSEILS:

- Ils se déplacent lentement et peuvent être enlevés relativement facilement, ils devraient être une faible priorité parmi d'autres ennemis.
- Ne sous-estimez pas leurs clubs, un gros coup sur la tête et vous aurez plus qu'un mal de tête. Gardez vos distances.
