MARQUE 1 ROBOT DE COMBAT, RÉALISÉ DE SHAIJU GANDHI


CLASSE:      MARK 1 Robot de combat amélioré
MÉTABOLISME: Artificiel (noyau du réacteur)
PERCEPTION: Machine de guerre lourde améliorée
TAILLE:       10 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Extrême
ARMES:    Minigunes doubles, mode berserk
RÉCOMPENSE:     5560 FC
MENACE:     Sévère

DESCRIPTION:

Développé par les ingénieurs de Lord Anton, le robot de combat MARK 1 a été conçu comme un gardien de première ligne des bases d'invasion. Son cadre est muni de deux mini-guns rotatifs, montés de chaque côté de son châssis blindé. Ces armes déclenchent des torrents dévastateurs de balles, déchiquetant à travers l'infanterie et les véhicules.

Cependant, cette puissance de feu accablante a un prix: les barils jumeaux sont sujets à la surchauffe après un feu soutenu. Lorsqu'il s'enflamme, la machine entre dans un mode berker brutal - ses systèmes enflammés d'énergie, la conduisant dans une rampe où elle ignore la logique tactique et charge les ennemis tête haute.

Le MARK 1 est craint non seulement pour son armement, mais aussi pour sa durabilité et son agression implacable. Partout où ces gardiens sont déployés, la survie devient un test d'incendie et d'acier.

Il est également intéressant de noter que cette machine est capable d'attraper les adversaires et de les renvoyer à des distances décentes. Il y a un point faible dans le dos.

CONSEILS:

- Utilisez la faiblesse de surchauffe : forcez-la à tirer continuellement jusqu'à ce que les systèmes s'effondrent.
- Évitez de fermer les quartiers lorsqu'il entre en mode berserk.
- Des explosifs lourds ou des armes à armure sont essentiels pour les faire tomber.
