UN SADISTE À LA MODE


CLASSE:      HALF-QUAKE Show Sadist
MÉTABOLISME: Humain, Homme
PERCEPTION: Hôte du spectacle sadique
TAILLE:       5,9 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Passif / contemplatif
ARMES:    Accès à d'énormes marteaux, systèmes de contrôle, indifférence
RÉCOMPENSE:     10000 FC
MENACE:     Moyenne

DESCRIPTION:

Ce ne sont pas seulement les hôtes du spectacle HALF-QUAKE, mais aussi les ingénieurs, les scénaristes, les bourreaux et les spectateurs. Ils cherchent des victimes partout dans le monde, les traînant de leur vie ordinaire et les livrant dans des arènes où ils doivent souffrir "pour leur terrible erreur dans la vie". Que cette erreur soit réelle ou inventée sur place, les sadiques s'en fichent.

La chose principale est que le processus va selon le script.

Les sadistes ont créé Somos, le Fils du sadisme, une intelligence supérieure qui contrôle tout ce qui se passe dans le spectacle.

Quand ils n'ont plus de victimes, ils engagent des gardes et les forcent à subir des tests, puis les regardent mourir d'épuisement ou de coups de marteau géant. Pour le public, bien sûr.

Ils ne se combattent pas eux-mêmes. Pourquoi ? C'est pour ça que sont les tourelles, les têtes et les vortigans.

