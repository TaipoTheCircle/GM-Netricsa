ORC SOLDIER, COMMANDANT DE L'ORAZIO


CLASSE:      Orc Soldat, commandant
MÉTABOLISME: Mammifère
PERCEPTION: Course guerrière primitive, ex-Zorgs
HEIGHT:     6,3 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Moyenne
ARMES:    Rifle plasma, Grenades pulsées
RÉCOMPENSE:     40 FC
MENACE:     Moyenne

DESCRIPTION:

C'est un exemple clair du dicton « ils voulaient le meilleur, mais il s'est avéré comme d'habitude ». Ils faisaient autrefois partie de la grande course Zorg de Bilmez IV, forte, féroce et, surtout, bronzée. Mais un bain de soleil constant a fait perdre aux Zorgs presque toute leur peau. En cherchant une solution, ils ont créé un mutagène qui restaurerait leur apparence ancienne. Au lieu de cela, le mutagène les a transformés en orcs...

La drogue a été immédiatement interdite, et les expérimentateurs, avec toutes les victimes, ont été exilés sur la planète isolée d'Orazio. Là, les exilés ont fait bon usage de leur temps, créant la société minière Altani et ont commencé à exploiter le minerai, tombant finalement entre les mains de Mental.

Mental recrute des orcs dans ses armées; la plupart ont fini dans les usines militaires de Mental, où ils ont aidé à produire des armes et des véhicules de combat. Les autres ont été envoyés à l'Académie militaire Solgar de Kronor, où ils ont été entraînés dans des tactiques de base et équipés d'armures et d'armes modernes.

Les Orcs qui ont obtenu leur diplôme avec honneur de l'académie ont été promus commandants. Ils portent une armure composite, qui offre une plus grande protection que l'armure orc standard, et utilisent deux types d'armes : un fusil à plasma et des grenades à impulsions.

Ils dirigent généralement des groupes d'autres orques et sont rarement seuls. Certains commandants utilisent aussi des gyrocopters, qui leur permettent de voler, ainsi que des montures de type lézard, qui augmentent leur mobilité.

CONSEILS:

- Contrairement à la plupart des minions de Mental, ils vont essayer de garder une distance quand près de vous.
- Leurs projectiles ont des capacités d'accueil mineures - restez loin d'eux.
- Les commandants qui utilisent des gyrocopters n'utilisent pas de grenades et ont une armure légèrement plus forte.
