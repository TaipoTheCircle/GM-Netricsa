PISTOLE DE WALTER P38


ARME: Pistolet Walther P38
MUNITIONS:   Parabellum 9x19mm
CADENCE DE TIR:    ~40-50 tours/min
POIDS: ~0,88 kg

DESCRIPTION:

Un pistolet semi-automatique allemand développé par Carl Walther et adopté par l'armée allemande en 1938. Il a été créé comme un remplacement plus moderne et technologiquement avancé du pistolet Luger P08 et est devenu l'un des principaux pistolets militaires allemands de la Seconde Guerre mondiale. Environ 1,2 million ont été produits.

Le pistolet utilise une action de court-recoil et une serrure de levier unique. Le mécanisme de déclenchement du marteau à double action permet de tirer le premier coup soit par action unique, soit manuellement. Il est alimenté par un magazine de 8 tours.

L'une des caractéristiques distinctives de la P38 est la sécurité de la diapositive, qui permet également une libération de déclenchement sûre. Le pistolet a acquis une réputation d'arme de poing militaire fiable et a continué à servir dans divers pays après la guerre, y compris l'Allemagne de l'Ouest, où son développement a été désigné P1.

REMARQUES:

- Après que le Luger était déjà devenu une légende, les Allemands ont décidé de créer un successeur plus moderne.
- Il est bien adapté pour la prise de vue à proximité, et son poids relativement léger le rend pratique pour le transport continu.
- Le système à double action permet un premier coup rapide sans premier coup de marteau.
- La serrure à levier est devenue l'une des caractéristiques techniques clés du P38 et le distinguait de nombreux pistolets contemporains.
