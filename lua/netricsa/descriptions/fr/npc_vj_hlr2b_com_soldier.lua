PERCEPTION: Prototype Transhuman Infantry
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    XM29 OICW, Frag Grenades
RÉCOMPENSE:     300 FC
MENACE:     Moyenne

DESCRIPTION:

Le Soldat Bêta Overwatch du Combine représente une première étape dans la tentative du Combine de créer une armée transhumaine fiable. Contrairement aux unités de Surveillance finalisées vues plus tard, ces prototypes ont conservé des caractéristiques humaines et utilisé des équipements plus volumineux et moins avancés. Leur armure est patchwork, offrant une protection modérée, et leur augmentation cybernétique est brute par rapport aux générations suivantes.

Bien que moins disciplinées et plus fragiles que les soldats Overwatch modernes, les unités Beta ont été déployées en grand nombre pendant les premières phases de l'occupation de Combine. Ils se sont appuyés sur une simple agression et sur des chiffres plutôt que sur des tactiques précises, souvent en se précipitant avec des armes dépassées et une mauvaise coordination.

Leur existence préfigurait le raffinement impitoyable de Combiner le design transhumain - les prédécesseurs imparfaits qui ont ouvert la voie aux forces Elite perfectionnées.

CONSEILS:

- Armure plus faible que fini Combiner des unités - la masse du centre de but.
- Moins précis à long terme mais mortel au combat rapproché.
