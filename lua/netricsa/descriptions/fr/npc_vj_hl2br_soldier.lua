VENDU DE SURVEILLANCE DE COMBINE


CLASSE:      Combiner le soldat Overwatch
MÉTABOLISME: Augmenté Humain, Homme / améliorations biomécaniques
PERCEPTION: Combiner l'infanterie
TAILLE:       5,9 pieds
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Pulse Rifle AR2, fusil de chasse, Grenades
RÉCOMPENSE:     450 FC
MENACE:     Haut

DESCRIPTION:

Les Soldats Overwatch, aussi connu sous le nom de Combine Soldiers, sont les garants de la règle du Combine sur Terre. Une fois humains, ils ont été modifiés chirurgicalement et cybernétiques pour servir d'infanterie transhumaine. Leurs corps sont modifiés pour l'endurance et la discipline, tandis que leurs esprits sont conditionnés pour une fidélité indéfectible au Combine Overwatch.

Ils portent une armure tactique sombre avec des respirateurs qui déforment leurs voix en tonalités mécaniques, leur donnant une présence inhumaine sur le champ de bataille. Fortement organisé et tactiquement compétent, les soldats Overwatch coordonnent les assauts avec précision, appelant souvent à l'appui de manhacks, de scanners ou d'unités plus lourdes.

Impitoyables et impitoyables, ils sont déployés partout où la résistance à l'autorité se manifeste, écrasant l'opposition avec une puissance de feu écrasante.

CONSEILS:

- Attentez-vous à une tactique d'embuscade et à un tir coordonné.
- Les explosifs sont très efficaces contre leurs équipes.
- Les têtes peuvent contourner leur armure.
