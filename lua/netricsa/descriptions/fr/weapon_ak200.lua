RISQUE D'ASSAULT AK-200


ARME:      AK-200 fusil d'assaut
AMMUNITION:  5,45×39 mm
CADENCE DE TIR:         ~900 tours/min

DESCRIPTION:

Une modification moderne du fusil d'assaut emblématique, connu pour sa fiabilité et sa durabilité. Reconçu pour tirer des cartouches de 5,45×39 mm. Divers modules peuvent y être attachés.

REMARQUES:

- Haute durabilité et facilité d'utilisation.
- Recul modéré; contrôlable lors de courtes rafales.
- Efficace contre les cibles non armées et légèrement blindées.
- La capacité des chargeurs nécessite un rechargement périodique pendant les combats prolongés.
- Ce fusil d'assaut peut être modifié à l'aide de différents modules.