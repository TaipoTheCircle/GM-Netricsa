VETTERLI-VITALI M1870/87 RIFLE DE MAGAZINE


ARME: Vetterli-Vitali M1870/87 Rifle magazine
MUNITIONS:   10,4x47mm R Vetterli
CADENCE DE TIR:    ~15 tours/min

DESCRIPTION:

Un fusil italien alimenté par des magazines, créé en 1887 en mettant à niveau le Vetterli M1870. Le développement de cette amélioration a été confié au capitaine d'artillerie Giuseppe Vitali, qui a proposé d'équiper le fusil d'un chargeur à quatre rangées. Cette modernisation a prolongé la durée de vie d'une conception autrement vieillissante, la rapprochant des exigences de l'infanterie moderne.

Le fusil fonctionne à l'aide d'un mécanisme à action manuelle. Il abrite la cartouche R Vetterli 10.4x47mm et dispose d'un chargeur intégral de quatre rondes. Le chargement se fait à l'aide d'un clip spécialisé, construit à partir de bois et de métal, qui est inséré entièrement dans le magazine et ensuite retiré en tirant un cordon attaché. Le fusil conserve les caractéristiques essentielles du modèle original, y compris sa cartouche à grand calibre et ses vues en fer. Plus tard, certains de ces fusils ont été convertis en chambre la cartouche Carcano 6,5x52mm et ont été rebaptisés Vetterli-Vitali M1870/87/15.

REMARQUES:

- Équipé d'un magazine de quatre tours conçu par Giuseppe Vitali.
- Utilise un clip à quatre tours spécialisé avec un cordon de traction pour l'enlèvement.
- Le taux de feu est d'environ 15 balles par minute.
- Convient à des cibles individuelles à moyenne ou longue portée.
- Efficace contre le personnel non protégé, bien qu'il soit court par rapport aux fusils plus modernes.
- Pendant la Première Guerre mondiale, certains de ces fusils ont été convertis en chambre de la cartouche Carcano 6.5x52mm.
