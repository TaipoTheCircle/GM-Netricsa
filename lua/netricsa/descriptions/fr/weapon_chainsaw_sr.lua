STIHL 041 CHAINSAW DE GAZOLINE AV


ARME: STIHL 041 scie à chaîne à essence AV
MUNITIONS:   Essence et huile moteur à deux étages
CADENCE DE TIR:    Fonctionnement continu

DESCRIPTION:

Une tronçonneuse à essence développée par la société allemande Andreas Stihl Maschinenfabrik. Produit de 1967 à 1986, il a été conçu pour l'abattage des arbres, la coupe du bois et l'exécution de tâches forestières lourdes. Il est équipé d'un monocylindre, d'un moteur à deux temps avec une cylindrée de 61 cc et d'un système de suspension antivibration, ce qui facilite le fonctionnement.

Le moteur produit environ 5,5 ch et conduit la chaîne de coupe par un embrayage centrifuge. La chaîne est lubrifiée automatiquement. La scie dispose d'un frein à chaîne mécanique, d'un système de démarrage automatique et d'une barre de guidage de 33 à 63 cm de longueur. Il fonctionne sur un mélange de carburant d'essence et d'huile de moteur à deux temps spécialisée.

REMARQUES:

- Particulièrement efficace contre le bois et d'autres matériaux doux.
- Convient pour couper de grands objets en bois.
- Peut être utilisé contre les adversaires non protégés – y compris les zombies – à très courte portée, bien qu'il nécessite un contact physique direct.
- Produit de 1967 à 1986.
- Cylindrée du moteur: 61 cc.
Puissance du moteur: environ 5,5 ch.
- Poids: environ 7,26 kg (y compris une barre de guidage et une chaîne de 33 cm).
