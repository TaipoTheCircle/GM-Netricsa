SPIDER DE CAVE DE L'EXTERIEUR MINECRAFT


CLASSE:      Cave Spider
MÉTABOLISME: Arthropodes
PERCEPTION: Prédateur venimeux souterrain
TAILLE:       1,9 ft
ENDURANCE:  Faible
HOSTILITÉ:  Haut
ARMES:    Bite venimeuse
RÉCOMPENSE:     600 FC
MENACE:     Moyenne

DESCRIPTION:

L'araignée de la grotte est une version compacte, en colère et extrêmement mécontente de l'araignée commune, trouvée exclusivement dans les mines abandonnées. C'est plus petit, plus rapide et, plus ennuyeux, plus venimeux.

CONSEILS:

- Ne sous-estimez pas sa taille. Le venin se fiche de ce que vous pensez.
- Les épées sont les meilleurs arguments en ce qui concerne cette créature.
