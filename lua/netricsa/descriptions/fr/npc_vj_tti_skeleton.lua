MÉTABOLISME: Maudits morts-vivants
PERCEPTION: Obsédé par un but perdu
TAILLE:       5,9 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Moyenne
ARMES:    Chanson maudite
RÉCOMPENSE:     650 FC
MENACE:     Moyenne

DESCRIPTION:

"Painty", également connu sous le nom de BurgerBeard, est un mort-vivant maudit de l'atoll de Bikini. Dans la vie, il était le fils d'un pirate sévère qui rêvait de faire de lui un vrai braqueur de mer. Cependant, BurgerBeard lui-même ne rêvait pas d'or et d'embarquement, mais de créer le burger parfait.

Ses rêves faisaient de lui une risée à l'école des pirates. Le ridicule et l'humiliation l'ont conduit à la folie. Pour tenter de changer son destin, Burger Beard a volé un livre magique au gardien du squelette de Bikini Atoll, dans l'intention de réécrire l'histoire de Bikini Bottom et d'obtenir la formule secrète pour le Crabby Patty.

Ayant obtenu son désir, il se dirige vers la terre sèche, où il commence à vendre des Crabby Patties d'un Burgermobile. Cependant, son plan fut ruiné après une longue bataille avec Bob l'éponge et ses amis, qui avaient pris les formes de superhéros. Plankton a finalement renvoyé Burger Beard à l'atoll de Bikini, où il a été maudit.

Même dans la mort, Burger Beard n'a pas trouvé la paix. Son squelette chante toujours "qui vit dans un ananas sous la mer?" au début de chaque jour, incapable de s'arrêter. Il porte un pantalon rouge et un bandana pirate rouge, les derniers vestiges de son rêve inachevé de devenir plus qu'un simple jester pirate.

CONSEILS:

- Détruire le squelette arrête de chanter.
- Des créatures dansent à sa chanson.