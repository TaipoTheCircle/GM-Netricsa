PENGUINE AVEC GRENADE


CLASSE:      Pingouin avec Grenade
MÉTABOLISME: Carnivore aviaire
PERCEPTION: Bio-armes
TAILLE:       2 pieds
ENDURANCE:  Moyenne faible
HOSTILITÉ:  Haut
ARMES:    Grenade piégée, attaque de peck
RÉCOMPENSE:     200 FC
MENACE:     Moyenne

DESCRIPTION:

Ce pingouin apparemment inoffensif a été armé. Une grenade est attachée à son dos, prête à exploser quand elle arrive à proximité d'une cible. Malgré sa petite taille, il est étonnamment rapide et agressif, fléchissant vers les ennemis avec une combinaison mortelle de pecks et d'explosifs. Des rencontres insouciantes peuvent être fatales, car la détonation peut endommager gravement le terrain et les alliés voisins.

CONSEILS:

- Gardez votre distance; la grenade peut exploser au contact.
- Utilisez des attaques variées pour le neutraliser avant qu'il ne vous atteigne.
- Évitez les regroupements - un pingouin peut déclencher une réaction en chaîne.
