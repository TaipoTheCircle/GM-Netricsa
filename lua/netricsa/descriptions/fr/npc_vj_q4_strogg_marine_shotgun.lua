STROGG GUARD DE STROGG


CLASSE:      Variante de la Garde de Strogg
MÉTABOLISME: Cybernétique (Human-Strogg Hybrid)
PERCEPTION: Ciblage visuel + suivi du mouvement
TAILLE:       6 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Haut
ARMES:    Mitrailleuse intégrée (bras droit), tir par balle
RÉCOMPENSE:     500 FC
MENACE:     Moyenne

DESCRIPTION:

Le Shotgun Guard est un soldat strogg légèrement blindé équipé d'un fusil greffé directement sur son bras droit. Conçus pour les combats à proximité du quartier général, ces unités comptent parmi les troupes de première ligne les plus agressives rencontrées.

Ils précipitent les ennemis avec une détermination téméraire, tirant des coups de feu à portée de point. Malgré leur tactique simple, un groupe de gardes-guns peut envahir des cibles non préparées par la simple proximité et le rythme des tirs.

CONSEILS:

- Gardez votre distance - leur fusil est mortel.
- Utilisez des explosifs ou des armes automatiques pour les couper avant qu'ils ne se rapprochent.