CROISSANCE M1900 PISTOL SÉMI-AUTOMATIQUE


ARME: Browning M1900 Pistol semi-automatique
MUNITIONS:   7.65x17mm Browning
CADENCE DE TIR:    ~35 tours/min

DESCRIPTION:

Un pistolet semi-automatique belge, conçu par l'inventeur américain John Moses Browning en 1896 et mis en série par Fabrique Nationale en 1900. Il est devenu l'un des premiers pistolets semi-automatiques commercialement réussi et a vu une utilisation généralisée parmi les militaires, la police et les civils. Il se caractérise par son design compact, sa diapositive distinctive et l'emplacement du ressort de recul au-dessus du barillet.

Le pistolet fonctionne sur un mécanisme de retour à l'eau et installe le 7.65x17mm Cartouche brune. Elle est alimentée par un magazine détachable à simple stack d'une capacité de 7 tours, logé dans la poignée. Il est doté d'un mécanisme à action unique, d'un feu de frappe, d'une sécurité manuelle du pouce et d'une vue en fer ouverte. Le ressort de recul est placé au-dessus du barillet et sert aussi de ressort d'attaque.

REMARQUES:

- Efficace contre des cibles individuelles et non armées à courte portée.
- Capacité du chargeur : 7 tours.
- Conçu par John Moses Browning.
- Fabriqué en Belgique de 1900 à 1912.
- Environ 700 000 unités ont été produites.
