BFG 9000 FRUIT MASSIF


ARME: BFG 9000 Fuseau massif
MUNITIONS:   Cellules BFG
CADENCE DE TIR:    ~24 tours/min

DESCRIPTION:

Une arme énergétique futuriste développée par la société UAC. C'est l'arme la plus puissante disponible, tirant un énorme boulon d'énergie verte. Le projectile peut endommager non seulement la cible au moment de l'impact, mais aussi les ennemis environnants avec des faisceaux d'énergie pendant son vol.

L'arme peut être chargée en tenant le bouton de tir. Plus la charge est longue, plus le tir est puissant, mais le tenir trop longtemps provoque une surcharge et peut tuer le tireur.

Le BFG est particulièrement efficace contre les adversaires forts et les grands groupes d'ennemis. Les munitions sont rares, donc l'utiliser contre chaque zombie que vous rencontrez serait comme utiliser une tronçonneuse pour couper le beurre.

REMARQUES:

- Une des armes les plus puissantes.
- Le boulon d'énergie endommage les ennemis avant qu'il explose.
- Ammo est rare, il est donc préférable d'enregistrer chaque charge pour des adversaires plus puissants.
