MOTO BUG DU MOBIUS


CLASSE:      Moto Bug
MÉTABOLISME: Batterie à gazole pour animaux
PERCEPTION: Scout des stocks
TAILLE:       4 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Moyenne
ARMES:    Hull, Ram
RÉCOMPENSE:     200 FC
MENACE:     Faible

DESCRIPTION:

Lorsqu'il s'agit de patrouiller les espaces ouverts, le Dr Eggman décide de ne pas réinventer la roue, mais de combiner ce qui était toujours à portée de main. Il a pris une coque de coccinelle, un animal, un moteur de tondeuse, une roue de brouette, et un processeur d'un jouet pour enfants appelé "Eh bien, juste vous attendez!" Le résultat a été le Bug Moto.

C'est la première tentative d'Eggman pour créer des unités mobiles et le Badnik le plus reconnaissable de l'empire. Le Moto Bug ne vole pas, ne tire pas, et n'explose pas. Il continue. Ça va aller. Encore et encore. S'il repère une cible, il essaie de rattraper, mais il le fait avec la grâce d'un centipède ivre.

CONSEILS:

- Un coup d'en haut le transforme en une pile de pièces.
- N'essayez pas de fuir en ligne droite - ses roues sont meilleures que son cerveau.

