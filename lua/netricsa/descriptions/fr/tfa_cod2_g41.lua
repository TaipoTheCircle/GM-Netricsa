FUSIL AUTO-CHARGEUR GEWEHR 41 (G.41)


WEAPONS: Self-loading rifle Gewehr 41 (G.41)
MUNITIONS : 7.92x57mm Mauser
ROF : ~15-20 shots / min
POIDS : ~4,9 kg

DESCRIPTIF :

The Gewehr 41, or G.41, was a German World War II self-loading rifle developed in 1941 by Mauser and Walther. It was created for the German army as a modern self-loading replacement for a conventional repeating rifle. The G.41(W) variant produced by Walther was eventually adopted.

The rifle uses gas-operated automatics and a powerful 7.92x57 mm Mauser rifle cartridge. The magazine is built-in, holds 10 rounds, and is replenished using standard clips. After the shot, the automatic system itself ejects the cartridge case and fires the next cartridge, so the shooter does not need to manually operate the bolt.

Gewehr 41 turned out to be quite heavy and complex. Troops reported sensitivity to contamination and various delays in firing. Already in 1943, it began to be replaced by the more advanced Gewehr 43, which was lighter and had a removable magazine.

REMARQUES :

- Well suited for medium and long range, where a powerful rifle cartridge reveals itself best.
- Automatic self-loading allows you to make repeat shots much faster than with the Karabiner 98k.
- The built-in 10-round magazine is loaded with clips, so there is no need to carry a separate detachable magazine.
