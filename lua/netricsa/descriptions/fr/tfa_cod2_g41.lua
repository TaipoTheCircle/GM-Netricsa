FUSIL AUTO-CHARGEUR GEWEHR 41 (G.41)


ARMES : Fusil à chargement automatique Gewehr 41 (G.41)
MUNITIONS : Mauser 7,92x57 mm
ROF : ~15-20 coups/min
POIDS : ~4,9 kg

DESCRIPTIF :

Le Gewehr 41, ou G.41, était un fusil à chargement automatique allemand de la Seconde Guerre mondiale développé en 1941 par Mauser et Walther. Il a été créé pour l'armée allemande en tant que remplacement moderne à chargement automatique d'un fusil à répétition conventionnel. La variante G.41(W) produite par Walther a finalement été adoptée.

Le fusil utilise des systèmes automatiques à gaz et une puissante cartouche de fusil Mauser de 7,92 x 57 mm. Le chargeur est intégré, contient 10 cartouches et est réapprovisionné à l'aide de clips standard. Après le tir, le système automatique éjecte lui-même la douille et tire la cartouche suivante, de sorte que le tireur n'a pas besoin d'actionner manuellement le verrou.

Le Gewehr 41 s'est avéré assez lourd et complexe. Les troupes ont signalé une sensibilité à la contamination et divers retards dans les tirs. Déjà en 1943, il commença à être remplacé par le Gewehr 43, plus avancé, plus léger et doté d'un chargeur amovible.

REMARQUES :

- Bien adapté aux moyennes et longues portées, où une cartouche de fusil puissante se révèle le mieux.
- Le chargement automatique vous permet de réaliser des tirs répétés beaucoup plus rapidement qu'avec le Karabiner 98k.
- Le chargeur intégré de 10 cartouches est chargé de clips, il n'est donc pas nécessaire de transporter un chargeur amovible séparé.