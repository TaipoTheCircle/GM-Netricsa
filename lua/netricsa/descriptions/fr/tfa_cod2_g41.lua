RIFLE AUTOCHTONE GEWEHR 41 (G.41)


ARMES: Fusil à chargement automatique Gewehr 41 (G.41)
MUNITIONS:    7.92x57mm Mauser
CADENCE DE TIR:     ~15-20 coups / min
POIDS:  ~4,9 kg

DESCRIPTION:

Le Gewehr 41, ou G.41, est un fusil à chargement automatique allemand développé en 1941 par Mauser et Walther. Il a été créé pour l'armée allemande comme un remplacement automatique moderne pour un fusil de répétition conventionnel. La variante G.41(W) produite par Walther a finalement été adoptée.

Le fusil utilise des automatiques à gaz et une puissante cartouche de fusil Mauser de 7,92x57 mm. Le magazine est intégré, contient 10 tours et est reconstitué à l'aide de clips standard. Après la prise de vue, le système automatique lui-même éjecte le boîtier de la cartouche et allume la cartouche suivante, de sorte que le tireur n'a pas besoin d'utiliser manuellement le boulon.

Gewehr 41 s'est avéré assez lourd et complexe. Les militaires ont signalé une sensibilité à la contamination et divers retards dans le tir. Déjà en 1943, il a commencé à être remplacé par le plus avancé Gewehr 43, qui était plus léger et avait un magazine amovible.

REMARQUES:

- Bien adapté pour une portée moyenne et longue, où une cartouche de fusil puissante se révèle le mieux.
- Autochargement automatique vous permet de faire des tirs répétés beaucoup plus rapidement qu'avec le Karabiner 98k.
- Le magazine intégré à 10 tours est chargé de clips, donc il n'est pas nécessaire de porter un magazine séparé.
