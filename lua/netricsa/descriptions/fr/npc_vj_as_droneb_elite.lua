"BETA" DRONE ELITE SWARM, PETIT


CLASSE:        "Beta" Swarm Elite Drone, Petit
MÉTABOLISME:   Xénobiologique
PERCEPTION:   Prédateur de conditionnement
TAILLE:         7,2 pi
ENDURANCE:    Haut
HOSTILITÉ:    Très élevé
ARMES:      Griffes, dents
RÉCOMPENSE:       450 FC
MENACE:       Haut

DESCRIPTION:

Les drones Elite sont beaucoup moins fréquents dans le swarm "Beta" que les spécimens standard. Ils sont facilement identifiés par leur chitine noir de charbon et trois yeux, capables de repérer des proies même dans l'obscurité quasi totale.

Physiquement, le drone d'élite diffère peu de ses membres, bien que sa musculature soit nettement plus dense et sa coquille extérieure beaucoup plus dure. Beaucoup de colons ont pris ces créatures à tort pour une espèce séparée jusqu'à découvrir que des spécimens d'élite émergent des mêmes ruches et obéissent aux mêmes instincts.

Une théorie commune parmi les xénobiologistes est que la coloration noire signifie maturité ou résulte de la survie prolongée dans des conditions particulièrement dangereuses. En d'autres termes, rencontrer un drone d'élite signifie qu'il a déjà survécu à de nombreuses situations qui auraient dû le tuer.

Contrairement aux drones standard, les spécimens d'élite succombent rarement aux premiers coups et poursuivent leur progression même après avoir subi de graves blessures. Malheureusement, le "Beta" Swarm considère une telle résilience comme une réalisation exceptionnelle plutôt qu'une raison de commencer à se préserver.

CONSEILS:

- Ne vous attendez pas à mourir aussi vite qu'un drone standard.
- Privilégier l'élimination des spécimens d'élite lorsqu'ils font face à un gros paquet.
- L'obscurité fonctionne à son avantage.
- Si un drone noir avec trois yeux brûlants se charge sur vous, cela signifie que la phase d'avertissement d'introduction est déjà terminée.
