MESA BLACK, DIRECTIVE SUR LES MISSIONS DE FER


Avant de monter dans le train, l'un des gardes survivants a transmis un message. Selon lui, un scientifique plus âgé-quelqu'un qui semble en savoir beaucoup plus qu'il ne devrait-insiste que Freeman doit atteindre les silos de missiles à l'extrémité de l'installation.

L'objectif ? Lancez une fusée satellite sur orbite. Le scientifique croit que cela permettra au Secteur Lambda de stabiliser la cascade de résonance, ou du moins d'affaiblir le lien dimensionnel inondant la base avec des formes de vie exotiques.

Maintenant, s'il vous a pris pour cette personne "Freeman", ou tout simplement ne se soucie pas tant que quelqu'un obtient le travail fait, peu importe. La mission est claire :

Restez sur le rail jusqu'au complexe de missiles.

Naviguez dans tout ce que les forces extraterrestres et S.E.C. ont mis en travers de votre chemin.

Trouvez un moyen de lancer la fusée.

Bien sûr, la prise est évidente : si l'armée réalise ce que vous essayez de faire, ils jetteront tout ce qu'ils ont pour vous arrêter. Et à en juger par l'augmentation des mouvements de troupes le long des pistes, ils le savent déjà.