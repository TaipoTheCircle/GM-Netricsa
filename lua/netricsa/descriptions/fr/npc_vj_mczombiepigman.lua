ZOMBIFIED PIGLIN SWORDSMAN DU RÉSEAU MINECRAFT


CLASSE:       Épées de Pigline zombifiées
MÉTABOLISME:  Un humanoïde de type cochon, non mort-vivant
PERCEPTION:  Une mafia neutre
TAILLE:        6,3 pieds
ENDURANCE:   Moyenne
HOSTILITÉ:   Conditionnel
ARMES:     Épée dorée
RÉCOMPENSE:      300 FC
MENACE:      Moyenne

DESCRIPTION:

Une carcasse de porc zombifiée bipédique, vêtue de débris d'armure une fois dorée.

C'est ce que deviennent les Piglin Swordsmen ordinaires s'ils restent dans l'Overworld ou la Fin pendant plus de 15 secondes. Ils s'appelaient auparavant Piglin Zombies, mais ce nom a ensuite été changé.

Contrairement à leur famille vivante, ces cochons se fichent de l'or. Ils se fichent de tout tant qu'ils restent seuls.

Ils peuvent aussi apparaître de porcs réguliers s'ils sont frappés par la foudre. Ou directement à partir des portails Nether dans le monde entier - plus le portail, le plus souvent.

Les porchines zombifiées sont immunisées contre le feu et la lave, elles brûlent mais ne brûlent pas. Cependant, ils se noient dans l'eau, comme il convient non mort.

Ils guérissent en endommageant les potions et endommagent la guérison.

CONSEILS:

- Ne frappez jamais avant, sauf si vous êtes prêt à frapper tout le monde. Un coup et tout le paquet est à toi.
- Gardez vos distances. Tout près, ils balancent leurs épées rapidement et douloureusement.
- Ils sont impuissants dans l'eau.
