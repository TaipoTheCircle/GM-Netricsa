LE RÉSEAU DU MINECRAFT


CLASSE:      Feu
MÉTABOLISME: Undead, enflammé entité Wraithly
PERCEPTION: Mob hostile, volant Flame Wraith
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Extrêmement élevé
ARMES:    Touche de flamme
RÉCOMPENSE:     400 FC
MENACE:     Très élevé

DESCRIPTION:

C'est une variante infernale de la Wraith commune, trouvée seulement dans la Nether. Contrairement à son pâle cousin de l'Overworld, cet esprit de feu ne cause pas seulement des dommages – il met sa victime sur Flame, transformant la bataille en une course à la mort par Flame.

La flamme est plus agressive et plus dangereuse en apparence. Leur toucher fait brûler leur adversaire pendant au moins 15 secondes-à peu près le même temps qu'il faut pour tomber dans la lave. En Enfer, où il fait déjà chaud, une telle brûlure est presque toujours fatale, surtout sans eau ni potion Flameproof à proximité.

Malgré leur nature ardente, ces wraiths sont paradoxalement vulnérables au soleil. Comme les wraiths normaux, ils meurent en plein soleil, bien qu'ils ne s'enflamment pas. Ils sont totalement immunisés contre la Flamme (ce qui est logique), mais sont tués par la lumière du jour normale.

Sinon, leur comportement est identique à celui des wraiths normaux : ils planent, émettent des gémissements d'eerie, attaquent au toucher, et ne entrent pas en collision avec d'autres créatures.

CONSEILS:

- Si vous allez à la Nether, soyez prêt à rencontrer ces créatures.
- Une gerbe de flamme est une cible prioritaire. Il ne devrait pas être ignoré, comme 15 secondes de brûlure en Enfer est presque garanti pour vous tuer. - Porter Des potions de résistance à la flamme. Ils vous feront immuniser contre Flame et nieront l'arme principale du Wraith.
- Un seau d'eau est inutile dans la Nether-l'eau s'évapore instantanément.
- Utilisez un arc ou une arbalète pour garder votre distance. En combat rapproché, il vous mettra sur Flame.
- Si vous vous installez sur Flame, essayez de vous retirer dans un endroit sûr et mangez rapidement une pomme dorée ou buvez une potion curative pour survivre aux dommages de Flame.
Contrairement aux Wraiths ordinaires, ceux-ci n'apparaissent pas dans l'Overworld, même la nuit. L'enfer est leur seule maison.
