GAUNLE


ARME: Gantelet
MUNITIONS:   Aucune
CADENCE DE TIR:    ~150 tranches/min 

DESCRIPTION:

Le Gauntlet est une arme à mélasse.

Au contact, il coupe la cible et applique un effet de retour pour repousser l'ennemi.

REMARQUES:

- 50 dégâts par tranche.
- Ne nécessite aucune munition - toujours disponible pour utilisation.
- Le mieux utilisé avec des manœuvres furtives, des embuscades ou des combats rapprochés agressifs.
Avec Quad Damage, une seule tranche peut tuer un ennemi en pleine santé.