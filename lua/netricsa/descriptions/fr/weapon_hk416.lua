RISQUE D'ASSAULT HK416


ARME:      HK416
AMMUNITION:  5.56×45mm Cartouches de l'OTAN
CADENCE DE TIR:         ~850 tours/min

DESCRIPTION:

Le HK416 a été développé à l'origine comme un module pour l'installation sur l'extrémité avant des fusils d'assaut M4 ou M16, mais a ensuite évolué en une carbine à part entière, puis un fusil. L'objectif était de remplacer les fusils d'assaut M4 et M16, qui formaient la base de l'arsenal des forces armées américaines et du Corps maritime, en raison de leur faible fiabilité, de leurs dysfonctionnements fréquents, de leur surchauffe et de leur susceptibilité à la contamination.

REMARQUES:

- Ce fusil est efficace à portée moyenne à longue.
- Bien adapté aux opérations intérieures ou urbaines.
- Il a un fort taux de feu.
