MANNLICHER-SCHÖNAUER M1903 RIFLE D'ACTION


ARME: Mannlicher-Schönauer M1903 Bolt-Action Rifle
MUNITIONS:   6,5x54mm Mannlicher-Schönauer
CADENCE DE TIR:    Manuel (action de culot), capacité 5 tours

DESCRIPTION:

Un fusil austro-hongrois, conçu par Ferdinand Mannlicher et Otto Schönauer en 1900 et adopté par l'armée grecque en 1903. Fabriqué par Steyr, le fusil a été remarqué pour sa qualité de construction élevée, sa fiabilité et un design de magazine qui n'était pas conventionnel pour son temps. Il était destiné à l'infanterie, tandis qu'une variante de carbine raccourcie était employée par la cavalerie et d'autres unités.

Le fusil utilise un boulon rotatif actionné manuellement. Sa caractéristique la plus distinctive est le magazine rotatif à cinq tours – un design Schönauer – hébergé dans le stock. Les cartouches sont placées dans un mécanisme rotatif qui assure une alimentation fiable. Le fusil est chargé depuis le haut, soit par un clip de strip-teaseuse, soit en insérant des cartouches individuelles. Il est équipé d'une vue en fer ouvert, avec une feuille de visée arrière réglable.

REMARQUES:

- Adopté par l'armée grecque en 1903.
- Chambre pour la cartouche Mannlicher-Schönauer 6.5x54mm.
- Le magazine rotatif tient 5 tours.
- Peser environ 3,77 kg, avec une longueur hors tout d'environ 1226 mm. La vue arrière est graduée jusqu'à 2000 mètres.
- Il existait aussi une version abrégée de la carbine de cavalerie.
- Le magazine rotatif Schönauer assure un alimentation en cartouches fluide et fiable, devenant ainsi l'une des caractéristiques clés de toute la conception.
