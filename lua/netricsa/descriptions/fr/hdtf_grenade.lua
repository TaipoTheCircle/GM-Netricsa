GRENADE COMBINE


ARME:      Mélanger la Grenade
MUNITIONS:        Charge explosive
CADENCE DE TIR:         Lancement manuel, ~10 lancers/min

DESCRIPTION:

Engin explosif standard utilisé par les soldats Combiner. Conçu pour la suppression tactique, il détone à l'impact ou après un fusible court, produisant des dommages élevés dans un petit rayon. Idéal pour la clairière ou pour perturber les formations ennemies.

REMARQUES:

- Efficace pour le déni de zone et l ' utilisation antipersonnel.
- Un fusible court nécessite un timing prudent.
- Ça peut être dangereux si on le jette à bout portant.