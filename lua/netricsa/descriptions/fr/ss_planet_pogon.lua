POGON


PLANET:       Pogon
TYPE:         Planète terrestre, Cryo-monde, Base militaire
CLIMATE:      Gel profond, gel sévère, vent froid constant
MOONS:        Inconnu
TERRAIN:      Hautes montagnes, plaines enneigées, plateaux glacés
LOCATION:     Quelque part entre les planètes Stroggos et la Terre
NATIVE RACES: Strogg (garçon)
ALLIANCE:     L'Empire de Strogg
LOCATIONS:    Base du général Faron, cols des montagnes, plaines enneigées

DESCRIPTION:

Un monde rude et enneigé situé à un point stratégique entre Stroggos et la Terre. Les conditions climatiques extrêmes font de cette planète une forteresse naturelle : des gels sévères, des vents perçants et des montagnes abruptes éliminent pratiquement la possibilité de raids aériens ou d'attaques d'artillerie de l'espace.

Le paysage de la planète est formé par de hautes montagnes inaccessibles, entre lesquelles s'étendent des plaines enneigées et des plateaux glacés. Des blizzards constants et une faible visibilité rendent la navigation extrêmement difficile, et toute trace de leur présence est rapidement masquée par la neige.

C'est ici, au plus profond de la chaîne de montagnes, que les Strogg ont établi une de leurs bases militaires clés. Le commandement de l'installation est exercé par le général Faron, un char strogg d'élite sur une plate-forme antigravité, une formidable unité de combat idéale pour la guerre dans des conditions hivernales difficiles.

Le choix de Pogon comme base a été dicté non seulement par son emplacement stratégique en route vers la Terre, mais aussi par la protection naturelle fournie par le climat. Alors que les blizzards et les températures de congélation entravent toute tentative d'invasion, les Strogg mènent leur travail sans entrave dans des complexes bien protégés et chauffés creusés dans la roche.

KEY LOCATIONS:

- Base du général Faron : la principale forteresse du Strogg sur la planète, un complexe de tunnels et de hangars cachés au fond de la montagne. De là, ils coordonnent leurs opérations et contrôlent le secteur.
- Les cols de montagne : Les seules voies potentielles de pénétration au sol vers la base, constamment patrouillées et minées. Impraticable pour la majeure partie de l'année en raison des chutes de neige.
- Plaines enneigées : Espaces ouverts au pied des montagnes, utilisés pour tester des équipements dans des conditions météorologiques extrêmes et lancer des drones de reconnaissance.
