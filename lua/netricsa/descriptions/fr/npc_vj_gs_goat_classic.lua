BON CLASSIQUE DE GOATVILLE


CLASSE:      Chèvre classique
MÉTABOLISME: Biologie standard des chèvres
PERCEPTION: Mammifères ongulés
TAILLE:       ~2,5-3 pi aux épaules
ENDURANCE:  Normal, mais étrangement durable
HOSTILITÉ:  Moyenne
ARMES:    Tête de cul, physique des ragdolls, destruction aléatoire
RÉCOMPENSE:     100 FC
MENACE:     Moyenne

DESCRIPTION:

La Classique peut ressembler à une simple chèvre de ferme, mais les apparences sont trompeuses. C'est sans aucun doute la chèvre la plus imprudente.

Contrairement à ses variantes "normales", la Classic est l'original - le chaos-bringer qui a tout commencé. Chaque bestiole, glitch, et ragdoll moment se sent amplifié quand cette chèvre est impliquée.

CONSEILS:

- Ne le laisse jamais tranquille.
- Les têtes peuvent envoyer des objets (et des gens) volant comme des missiles.
- Cette chèvre est la physique elle-même - sauvage, cassé, et inarrêtable.
