ARCHIPELAGO KRIEGER'S UH-60 "BLACKHAWK" HELICOPTER PATROL


CLASSE:       Hélicoptère de patrouille UH-60 de l'archipel Krieger
MÉTABOLISME:  Aéronefs (HP, Jet)
PERCEPTION:  Aéronef ennemi
TAILLE:        ~16,7 pieds
ENDURANCE:   Haut
HOSTILITÉ:   Haut
WEAPONATORY: Minigune de bord contrôlée par un tireur
RÉCOMPENSE:      1000 (l'hélicoptère a une paie)
MENACE:      Haut

DESCRIPTION:

L'hélicoptère multirôle primaire des forces de Krieger. Utilisé pour les patrouilles, le déploiement rapide de renforts et le soutien rapproché aux tirs. Il a un motif camouflage standard avec le logo de l'entreprise.

Le méchant Stone Face a capturé un hélicoptère de patrouille mercenaire Krieger UH-60. La couronne de Moai non payée est à sa hauteur - cette tête de pierre volante est encore plus dangereuse. Il patrouille des points clés à travers l'archipel, exigeant sans fin son salaire, et attaque quiconque en vue, qu'il s'agisse de mercenaires, de Trigens ou de Jack.

La tête du Moai est intégrée dans la position du mitrailleur, sa masse de pierre servant d'armure et de renforcement structurel. La tourelle M134 du côté gauche est contrôlée par la « vue » magique de l'idole, tirant avec une précision et une vitesse monstrueuses. C'est l'incarnation de la colère ancienne fusionnée avec la technologie militaire moderne.

CONSEILS:

- Évitez le barrage de balles du M134, qui perce le couvercle de lumière et inflige des dommages colossaux.