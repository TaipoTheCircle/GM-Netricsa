BOOMER DE LA MER


CLASSE:      Swarm Boomer
MÉTABOLISME: Xénobiologique
PERCEPTION: Explosifs vivants
TAILLE:       7,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Absolu
ARMES:    Autodétonation, capsules explosives
RÉCOMPENSE:     600 FC
MENACE:     Haut

DESCRIPTION:

Le Boomer est un spécimen de Swarm spécialisé, dont toute la biologie est consacrée à une tâche : livrer la quantité maximale d'explosifs le plus près possible de l'ennemi.

Au repos, le Boomer semble relativement inoffensif pour un spécimen de Swarm de sa taille. Toutefois, lorsqu'il détecte des proies, ses organes internes commencent à produire rapidement des composés chimiques instables. Le corps de la créature gonfle, se transformant en un réservoir vivant de biomasse explosive.

Pour fermer la distance, Boomer peut effectuer des attaques rapides et coulissantes, frapper les adversaires hors de position et bloquer les passages avec son propre corps. En atteignant une portée rapprochée, l'organisme détone, se détruisant lui-même et tout à proximité.

Les capsules explosives secondaires présentent un danger particulier. Après la mort d'un Boomer gonflé, ils se dispersent autour du site d'explosion et détonent quelques secondes plus tard. Par conséquent, même détruire avec succès la créature ne signifie pas toujours la fin de la menace.

Selon les xénobiologistes, Boomer est l'un des exemples les plus frappants de la mesure dans laquelle l'évolution peut aller lorsque l'instinct pour la conservation de soi est complètement abandonné.

CONSEILS:

- Détruisez les boomers avant qu'ils ne s'envolent.
- Après l'explosion, quittez immédiatement la zone dangereuse.
- Ne les laissez pas approcher du groupe.
- Si la créature semble sur le point d'éclater, il vaut mieux ne pas tester le caractère littéral de cette déclaration.