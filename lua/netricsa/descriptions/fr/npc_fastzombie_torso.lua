LE DERNIER TORSO DE ZOMBIE


CLASSE:      Gratte de tête Zombie, Torso rapide
MÉTABOLISME: Hôte parasitaire 
PERCEPTION: Entité zombifiée
TAILLE:       2,5 pieds
ENDURANCE:  Très rapide
HOSTILITÉ:  Extrême
ARMES:    La griffe saute, sauts frénétiques, morsure
RÉCOMPENSE:     120 FC
MENACE:     moyenne

DESCRIPTION:

Quand un Zombie rapide est coupé dans la bataille, le cauchemar ne se termine pas. Le crâne refuse de renoncer au contrôle, forçant le torse mutilé de son hôte à ramper avec une agilité horrible. Ces demi-formes conservent la vitesse et la frénésie de leur famille corsée, se lançant vers l'avant avec des cris shrilleux et osseux. Bien que fragiles et facilement expédiés, leurs poumons erratiques dans les espaces confinés peuvent même attraper des combattants assaisonnés hors de garde.

CONSEILS:

- Rester mobile-ils peuvent toujours tuer malgré les membres manquants.
- Ne gaspillez pas de munitions lourdes; un ou deux tirs suffisent.
- Les cris annoncent leur présence pour se préparer.
