FUSIL MAUSER M1893


ARME : Fusil Mauser M1893
MUNITIONS : 7x57mm Mauser
ROF : ~15-20 tours/min
POIDS : ~4 kg

DESCRIPTIF :

Le Mauser M1893, également connu sous le nom de Mauser espagnol, était un fusil à répétition allemand conçu par Paul Mauser et adopté par l'armée espagnole en 1893. Il est devenu l'un des premiers fusils Mauser les plus célèbres et a servi de base au développement ultérieur de la conception.

Le fusil utilise un mécanisme à verrou et la cartouche Mauser 7x57 mm. Le chargeur interne contient 5 cartouches et se charge par le haut à l'aide d'un clip. L'une des principales caractéristiques du M1893 était son chargeur compact, entièrement situé à l'intérieur de la crosse, ce qui rendait sa conception plus pratique que les modèles Mauser précédents.

Le M1893 a été largement utilisé au combat. Il est devenu particulièrement célèbre lors de la guerre hispano-américaine de 1898, où les troupes espagnoles l'ont utilisé pour produire un tir extrêmement dense et précis. L'expérience avec le M1893 a influencé le développement ultérieur des fusils militaires américains et a finalement conduit à la création du M1903 Springfield.

La conception du M1893 a eu un impact profond sur le développement des fusils à chargeur. D'autres modèles Mauser furent développés et en 1898, le célèbre Gewehr 98 fut créé.

REMARQUES :

- Caractérisé par une grande précision et de bonnes performances à moyenne et longue portée.
- Le chargeur à cinq coups peut être rechargé rapidement avec un seul clip.
- C'est pourquoi on l'appelle souvent le « Mauser espagnol ».
- Aucun rapport avec Mickey Mouse.