MAUSER M1893 RIFLE


ARME: Mauser M1893 Rifle
MUNITIONS:   7x57mm Mauser
CADENCE DE TIR:    ~15-20 tours/min
POIDS: ~4 kg

DESCRIPTION:

Le Mauser M1893, également connu sous le nom de Mauser espagnol, était un fusil à répétition allemand conçu par Paul Mauser et adopté par l'armée espagnole en 1893. Il est devenu l'un des fusils Mauser les plus célèbres et a servi de base pour le développement de la conception.

Le fusil utilise un mécanisme d'action du boulon et la cartouche Mauser 7x57mm. Le magazine interne contient 5 tours et est chargé du haut à l'aide d'un clip. L'une des caractéristiques clés du M1893 est son magazine compact, situé entièrement dans le stock, rendant le design plus pratique que les modèles précédents de Mauser.

Le M1893 a été largement utilisé au combat. Il est devenu particulièrement célèbre pendant la guerre hispano-américaine de 1898, où les troupes espagnoles l'ont utilisé pour produire des tirs extrêmement denses et précis. L'expérience du M1893 a influencé le développement ultérieur des fusils militaires américains et a finalement conduit à la création du M1903 Springfield.

Le modèle M1893 a eu un impact profond sur le développement de fusils alimentés par des magazines. D'autres modèles Mauser ont été développés, et en 1898, le célèbre Gewehr 98 a été créé.

REMARQUES:

- Caractérisée par une grande précision et une bonne performance à moyenne et longue gamme.
