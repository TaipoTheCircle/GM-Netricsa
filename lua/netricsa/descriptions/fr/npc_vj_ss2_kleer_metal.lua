SQUELETTE KLEER (MÉTAL)


CLASSE:      Squelette Kleer (Métal)
MÉTABOLISME: Mort-vivant
PERCEPTION:  Créature magique
TAILLE:      2,7 m (9 pieds)
ENDURANCE:   Très élevée
HOSTILITÉ:   Moyenne
ARMES:       Projectiles à deux boules, griffes, cornes
RÉCOMPENSE:  500 FC
MENACE:      Élevée

DESCRIPTION:

Une variante rare du squelette Kleer, composée non pas d'os, mais de métal et de nombreuses pointes.

Mental jugeait l'os ordinaire insuffisant pour créer un squelette Kleer plus résistant ; il a donc décidé de concevoir une version métallique. Malgré sa composition inhabituelle, le Kleer métallique conserve la forme et le comportement de son homologue osseux.

Grâce à sa structure métallique, il est nettement plus robuste que le squelette Kleer standard. Il ne peut être éliminé par une simple blessure mortelle ; le Kleer métallique ne meurt que lorsque son corps est entièrement pulvérisé.

CONSEILS:

- Ne cessez pas de tirer tant que la structure métallique ne s'est pas totalement disloquée.
- Son corps métallique est bien plus résistant que les os d'un squelette Kleer standard.
- S'il bouge encore après avoir subi des dégâts considérables, vous devez le fracasser avec encore plus de violence.
- Le Minigun reste votre meilleur allié ; il devra simplement tourner un peu plus longtemps cette fois-ci.
