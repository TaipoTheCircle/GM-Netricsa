KLEER SKELETON, METAL


CLASSE:      Squelette Kleer, métal
MÉTABOLISME: Morts
PERCEPTION: Créature magique
TAILLE:       9 pieds
ENDURANCE:  Très élevé
HOSTILITÉ:  Moyenne
ARMES:    Projectiles à deux bals, griffes, cornes
RÉCOMPENSE:     500 FC
MENACE:     Haut

DESCRIPTION:

Une variante rare du squelette de Kleer, composé non pas d'os, mais de métal et de nombreux pics.

Mental jugé os ordinaire insuffisant pour créer un Kleer Skeleton plus durable, il a donc décidé de concevoir une version métallique. Malgré son matériau inhabituel, le Metal Kleer conserve la même forme et le même comportement que son homologue osseux.

Grâce à sa construction métallique, il est nettement plus résistant que le Kleer Skeleton standard. Il ne peut pas être tué simplement en infligeant une blessure mortelle; le métal Kleer ne meurt qu'une fois son corps complètement brisé.

CONSEILS:

- Ne pas arrêter de tirer jusqu'à ce que la structure métallique s'effondre complètement.
- Son corps métallique est nettement plus résistant que les os d'un squelette Kleer standard.
- Si elle est toujours en mouvement après avoir subi des dommages massifs, vous devez l'écraser encore plus.
- Le Minigun reste votre meilleur ami; il doit juste travailler un peu plus cette fois.
