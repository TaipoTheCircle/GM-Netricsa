BIO-MÉCHANOID, MAJOR


CLASSE:      Biomécanoïde, major
MÉTABOLISME: cyborg endotherme
PERCEPTION: génétiquement programmé
TAILLE:       30 pieds debout
ENDURANCE:  élevé
HOSTILITÉ:  élevé
ARMES:    lance-roquettes
RÉCOMPENSE:     7500 FC
MENACE:     élevé

DESCRIPTION:

Un mécanisme biologique cultivé dans les réservoirs biologiques de Mental. Son génome est programmé pour lui donner biologiquement des parties mécaniques et des fentes latérales où les lance-roquettes sont attachés et directement connectés à son système nerveux.
Ajusté à l'attaque sans penser.

CONSEILS:

- Très dangereux, éliminez vite.
- Ou évitez les fusées ou tirez-les avant qu'ils ne vous atteignent.
