WARFARE ARCTIQUE L96A1


ARME: Guerre arctique / L96A1
MUNITIONS:   7,62×51 mm OTAN (308 Winchester)
CADENCE DE TIR:    12 tirs/min
POIDS: 7,5 kg
LENGTH: 1 200 mm

DESCRIPTION:

Le L96A1 (Arctic Warfare) est un fusil à sniper à action de boulons d'Accuracy International. Conçu pour la précision dans des environnements difficiles et froids, son châssis rigide, son barillet à froid et sa conception modulaire offrent une précision et une fiabilité constantes. Généralement équipée d'un stock réglable, d'un bipode et d'une optique, elle sert de plate-forme polyvalente pour les rôles anti-matériels et anti-personnels à longue portée.

REMARQUES:

- Interactions à longue portée de précision - efficaces entre 800 et 1 000 m selon les munitions et les conditions.
- Mécanisme de boulon robuste et composants modulaires simplifient la maintenance et l'adaptation sur le terrain.
- Largement utilisé par les unités de police et de snipers militaires dans le monde entier; adopté par plusieurs pays sous désignation nationale.
