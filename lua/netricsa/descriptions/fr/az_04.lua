MESA BLACK, LES HAUTES SUPÉRIEURS


The elevator ride ends with a charming little scene: un scientifique terrifié qui frappe sur une porte fermée, suppliant l'homme avec la mallette à l'intérieur de le laisser entrer. "Ils arrivent, s'il vous plaît, ouvrez la porte!"

Spoiler: c'est faux. L'homme de la mallette regarde, silencieux comme jamais. Le scientifique panique, court... et est immédiatement coupé par les tourelles de S.E.C.U.

Et oui, cela signifie que l'armée est ici maintenant. Pas pour sauver qui que ce soit, bien sûr, mais pour s'assurer que personne ne quitte la vie.