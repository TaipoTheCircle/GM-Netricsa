SCIENTIFIQUE DU STROGG


CLASSE:      Strogg Scientifique
MÉTABOLISME: Cybernétique/Human-Strogg hybride
PERCEPTION: Personnel scientifique de Strogg
TAILLE:       ~5,5 ft (hauteur du paillasson)
ENDURANCE:  Moyenne
HOSTILITÉ:  Moyen (bataille défensive / réticente)
ARMES:    Bras de scie mécanique, aiguilles sur les membres supplémentaires, grenade à gaz empoisonnée
RÉCOMPENSE:     700 FC
MENACE:     Moyenne

DESCRIPTION:

Le scientifique est une unité de Strogg chargée de la recherche médicale et du processus de Stroggification. Son corps inférieur est remplacé par un hover-pad, lui permettant de flotter silencieusement dans les laboratoires médicaux. Le torse est humain, mais avec un respirateur sur la bouche et des yeux brillants orange. Autour de son corps sont greffés des outils tranchants - une scie pour une main droite, des membres mécaniques tenant des aiguilles - utilisés à l'origine pour l'expérimentation, mais pressés dans le service quand attaqué.

Lorsqu'il sera coincé, le scientifique lobera une grenade à gaz toxique, qui explose et libère un nuage toxique qui endommage au fil du temps et contourne l'armure. Ses attaques avec des aiguilles et des scies sont brutales à portée de main. Il se faufile souvent autour des coins ou flotte au-dessus pour surprendre les intrus dans les installations médicales de Strogg.


CONSEILS:

- Garder la distance - ses outils de mêlée sont mortels.
- Évitez les nuages toxiques; ils désorientent et contournent l'armure.
- Utilisez des armes variables/automatiques pour les envoyer rapidement.
- Être alerte pour les mouvements en vol stationnaire ; le hover-pad rend plus difficile à détecter par le son.