FUSIL DE CHASSE ORO "ENFORCER"


ARME : Fusil à pompe ORO "Enforcer"
MUNITIONS : Fusil de chasse de calibre 12
ROF : ~70 tours/min.
POIDS : ~4 kg.

DESCRIPTIF :

L'ORO "Enforcer" est un puissant fusil de combat fabriqué par ORO, utilisé par l'armée de Mendel Gruman Corporation. Malgré sa portée efficace limitée, il offre une puissance d'arrêt considérable à courte portée et est conçu pour éliminer rapidement ses adversaires.

En plus de son mode de tir normal, le fusil de chasse possède une fonction spéciale de fusée éclairante. La fusée éclairante peut être tirée pour attirer l'attention des créatures proches, y compris les dinosaures, transformant ainsi l'arme en un moyen plutôt inhabituel de donner à votre adversaire une rencontre très désagréable.

REMARQUES :

- Dégâts très élevés à courte portée.
- Utilise des cartouches de fusil de chasse de calibre 12. - Efficace principalement à courte portée, là où la plupart des plombs touchent leur cible.
- Un mode spécial permet de lancer une fusée éclairante.
- La fusée éclairante peut attirer les dinosaures vers une zone cible.
- A longue portée, son efficacité chute fortement à cause de la dispersion des pellets.
- Particulièrement courant parmi les unités MG RPG, malgré le nom de l'unité impliquant l'utilisation d'un pistolet lance-fusées.