GRAVE ACM46 PISTOL


ARME: Pistolet Seegert ACM46
MUNITIONS:   Parabellum 9x19mm
ACTION: Semi-automatique

DESCRIPTION:

Un pistolet semi-automatique moderne développé par la Seegert Corporation pour les unités armées. Il sert d'arme latérale standard pour les soldats d'Armacham, les unités de la Force Delta et les forces de réplique.

L'ACM46 est doté d'un cadre en polymère à haute résistance, d'une glissière en acier inoxydable et d'une vue illuminée au tritium. Il fonctionne selon un principe de court-recoil avec un mécanisme de bouche verrouillée. Le magazine compte 18 tours. Il offre une bonne précision et une puissance d'arrêt décente, bien que sa portée de tir efficace reste limitée.

REMARQUES:

- Le magazine a une capacité de 18 tours.
- Équipé de vues tritium pour des conditions de faible luminosité.
- Comprend un système de montage universel pour les accessoires.
- ressemble à l'USP allemand Heckler & Koch en apparence.
- Bien qu'elle soit une arme secondaire, elle possède une puissance de feu importante.
