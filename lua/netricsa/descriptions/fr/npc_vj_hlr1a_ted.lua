TED BARNEY


CLASSE:      Ted Barney
MÉTABOLISME: Humain, Homme
PERCEPTION: Garde de sécurité Black Mesa
TAILLE:       6 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Défendeur / Allié
ARMES:    Glock-17, Baton
RÉCOMPENSE:     40 FC
MENACE:     Faible

DESCRIPTION:

Ted Barney est un fidèle garde de sécurité Black Mesa. Équipé d'armes classiques et d'armure légère, il aide à défendre le personnel et les zones d'installation. Il réagit rapidement aux menaces, mais n'est pas aussi entraîné ou résilient que l'U.S.E. ou les membres des forces spéciales.

Ted est fiable dans les situations de combat, mais devrait être soutenu dans des combats de plus grande envergure en raison de l'endurance limitée.

CONSEILS:

- Gardez-le près de lui.
Il ne peut pas survivre au feu.
- Efficace pour défendre les couloirs et les points de contrôle.
