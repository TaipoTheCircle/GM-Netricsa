SYNTHE DE CROBINE


CLASSE:      Mélanger le crab-synth
MÉTABOLISME: Biomécanique synthétique
PERCEPTION: Groupe des agressions graves
TAILLE:       7,2 pi
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Minigune rétractable, griffes, Ram
RÉCOMPENSE:     800 FC
MENACE:     Très élevé

DESCRIPTION:

Le Crab-synth est un véhicule de combat lourd Combine conçu pour supprimer les groupes ennemis bien armés et briser les positions fortifiées. Malgré sa construction relativement squat, le synthét possède une masse considérable et est capable de se déplacer rapidement sur un terrain accidenté en utilisant plusieurs membres puissants.

La caractéristique principale de cette entité est son mini-gun rétractable, dissimulé dans sa coque. Lors de la détection d'une cible, le mécanisme d'armes se déploie, déclenchant un flux dense de tirs sur l'ennemi. Le minigun est particulièrement efficace contre les groupes d'infanterie, les véhicules légers et les cibles qui restent en un seul endroit trop longtemps.

Dans un combat rapproché, le Crab Synthent peut utiliser ses propres membres comme armes. Cependant, son rôle principal n'est pas de chasser seul, mais de soutenir d'autres synthés. Il fonctionne généralement en conjonction avec Combine Assault Synths, qui fournit une couverture de flanc et empêche l'ennemi de concentrer tous ses tirs sur le véhicule lourd.

This tactic makes encounters with them particularly frustrating: while the Assault Synths keep the enemy on the move, the Crab Synthent methodically rakes the area with fire from its minigun. The Combine seems to really enjoy solving tactical problems by the "put another gun in."

CONSEILS:

- N'essayez pas de tirer un mini-gun en plein air.
- Changer constamment les positions, surtout si le synthé a déjà déployé son arme. - D'abord, éliminez les synthés d'assauts qui vous accompagnent s'ils perturbent votre concentration d'incendie.
- Utiliser la couverture et l'attaque des flancs ou arrière.
- De puissantes armes explosives sont particulièrement efficaces contre les lourdes coques.
- Si un Crab Synth est laissé seul, ne vous détendez pas : sa puissance de feu lui permet de transformer rapidement une zone ouverte en un endroit très difficile à marcher.
