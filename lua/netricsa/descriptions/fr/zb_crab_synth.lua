COMBINEZ CRABE-SYNTHÉ


CLASSE : Combiner Crabe-synthé
MÉTABOLISME : Biomécanique Synthétique
PERCEPTION : Unité d'assaut lourd
TAILLE : 7,2 pieds
ENDURANCE : Élevée
HOSTILITÉ : Extrême
ARMES : Minigun rétractable, griffes, bélier
RÉCOMPENSE : 800 FC
MENACE : Très élevée

DESCRIPTIF :

Le Crab-synth est un véhicule de combat lourd Combine conçu pour supprimer les groupes ennemis bien armés et percer les positions fortifiées. Malgré sa construction relativement trapue, le synthet possède une masse considérable et est capable de se déplacer rapidement sur un terrain accidenté à l'aide de plusieurs membres puissants.

La principale caractéristique de cette entité est son minigun rétractable, dissimulé dans sa coque. Dès la détection d'une cible, le mécanisme de l'arme se déploie, déclenchant un flux de tirs dense sur l'ennemi. Le minigun est particulièrement efficace contre les groupes d'infanterie, les véhicules légers et les cibles qui restent trop longtemps au même endroit.

En combat rapproché, le Crab Synthent peut utiliser ses propres membres comme armes. Cependant, son rôle premier n’est pas de chasser seul, mais de soutenir d’autres synthés. Il fonctionne généralement en conjonction avec des Combine Assault Synths, qui fournissent une couverture de flanc et empêchent l'ennemi de concentrer tous ses tirs sur le véhicule lourd.

Cette tactique rend les rencontres avec eux particulièrement frustrantes : pendant que les Assault Synths maintiennent l'ennemi en mouvement, le Crab Synthent ratisse méthodiquement la zone avec le feu de son minigun. Le Combine semble vraiment aimer résoudre les problèmes tactiques en « mettant une autre arme ».

CONSEILS :

- N'essayez pas de tirer plus vite qu'un minigun à l'air libre.
- Changez constamment de position, surtout si le synthé a déjà déployé son arme. - Tout d'abord, éliminez les synthés d'assaut qui les accompagnent s'ils interfèrent avec votre concentration de tir.
- Utilisez une couverture et attaquez depuis les flancs ou l'arrière.
- Les armes explosives puissantes sont particulièrement efficaces contre les coques lourdes.
- Si un Crab Synth est laissé seul, ne vous relâchez pas : sa puissance de feu lui permet toujours de transformer rapidement une zone dégagée en un endroit très difficile à parcourir.