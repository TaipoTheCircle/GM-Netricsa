C'est intéressant, Sam.

Le portail a fonctionné. La Terre. La gravité est familière. Mais il n'y a aucun indice de Black Mesa ici. Mais ça sent le spectacle.

Bienvenue à Half-Quake. Un spectacle sadique où la douleur est présentée comme un divertissement et la survie est considérée mauvaise forme. À en juger par le monologue d'ouverture de l'annonceur, trois étapes de "tests" nous attendent. Bien sûr, il voulait dire torture.

Le spectacle a longtemps été avide acheteur de matériel Black Mesa. Des tortues, Des créatures comme Xen, du matériel expérimental. Tout ce qui peut être utilisé pour infliger la souffrance et susciter des applaudissements. Quelqu'un a clairement décidé que le désastre est une opportunité d'affaires.

Regarde.

Derrière vous se trouve un grand bouton avec un symbole ">). Ça ressemble à une invitation. Il y a une porte devant. C'est fermé pour l'instant. La cage dans laquelle tu es attend le signal. Ils veulent que tu sois nerveux. Attendre. Pour souffrir à l'avance.

And the announcer also said the following:

"Nous ne sommes pas là pour sauver le monde." Freeman, a-t-il dit, le fait déjà. Ou, plus précisément, le premier Sam.

Et tu es là pour autre chose.

Vous êtes là pour souffrir.

Pour "une énorme erreur dans votre vie." Ils ne précisent pas exactement quoi. Apparemment, le format de l'émission ne permet pas les détails. Peut-être pour exister. Ou pour avoir exterminé des créatures Xen et sérieusement l'intention de finir Mental, au lieu de mourir magnifiquement selon le scénario.

Bad news: le spectacle est construit sur cela.

Good news: ils ont choisi le mauvais candidat.

Encore une nuance. Mental a déjà passé un marché avec les organisateurs. Ses troupes font maintenant partie du programme. Officiellement. Avec le but de « finir Sam une fois pour toutes ». C'est bon de savoir que vous avez une réputation stable.

Voici mon conseil, Sam.

Ils veulent leur donner la souffrance.

Mais pas le vôtre.