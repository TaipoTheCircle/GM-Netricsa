ABBIE DE L'ENSEIGNEMENT FONDAMENTAL


CLASSE:      Abbie
MÉTABOLISME: Organisme anthropomorphe du papier
PERCEPTION: Élève de l ' école de papier
TAILLE:       ~5 pi
ENDURANCE:  Très bas
HOSTILITÉ:  Aucune
ARMES:    Aucune
RÉCOMPENSE:     Je vous trouverai personnellement si vous posez un doigt sur lui FC
MENACE:     Aucune

DESCRIPTION:

Un étudiant de 15 ans de l'école de papier, mais aussi timide, anxieux et pas le plus brillant. Sa particularité est une tige de pomme avec une feuille sur le dessus. Il porte un uniforme d'école strict : une chemise blanche, un smoking noir avec une cravate et un short blanc. Ses yeux ne sont que de petites fentes noires. Canoniquement, il a été brutalement assassiné par son professeur, Mlle Circling, pour avoir échoué à un examen, mais dans un autre scénario, il peut être considéré vivant. Il a un taux de survie extrêmement faible en raison de sa nature de papier ; il déchire et se brise facilement. Il a des sentiments tendres pour sa camarade de classe, Lana. Il ne représente aucune menace, victime des circonstances et de l'atmosphère de l'école.

CONSEILS:

- Vulnérabilité à tout impact physique, explosion et incendie.
- En cas de danger, il tremblera, se retirera et tentera de s'échapper plutôt que de résister.
- Très sensible aux critiques et aux pressions.
