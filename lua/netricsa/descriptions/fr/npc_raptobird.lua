RAPTEUR-BIRD (RATH-BIRD, LIZARD-BIRD) DE ZENOZOIK


CLASSE:      Prédateur Zenozoik
MÉTABOLISME: Reptilien, sang-froid
PERCEPTION: Vision améliorée, réactivité des mouvements
TAILLE:       5,9 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
WEAPONALS:  Griffes, bec, saut d'attaque
RÉCOMPENSE:     400 FC
MENACE:     Haut

DESCRIPTION:

Raptor-Birds sont parmi les prédateurs les plus dangereux de la forêt Zenozoik, une région dense et abondante. Cette forêt est connue pour ses arbres et plantes exotiques, qui remplissent littéralement tout l'espace, créant les conditions idéales pour les chasseurs furtifs et rapides.

La créature ressemble à une croix entre un caméléon, un oiseau et un rongeur. Sa tête allongée est recouverte d'une peau épaisse et squameuse, semblable à celle d'un poisson. De grands yeux avec des pupilles rondes lui permettent de détecter instantanément le mouvement entre le feuillage et les ombres. Les projections en forme de corne, courbes en demi-cercles, s'étendent au-dessus de sa tête.

Le corps du raptor-oiseau est recouvert d'écailles foncées, dans des endroits se mêlant à la peau brune. Sa coloration va du brun et rouge aux taches blanches sales, ce qui le rend presque invisible parmi les racines, la mousse et la croissance des arbres de la forêt. Ses membres sont minces, avec de longs doigts et des griffes pointues, idéales pour grimper, sauter brusquement et se tenir sur des proies.

CONSEILS:

- Les fourrés sont son habitat naturel, pas le vôtre.
- Les coups de pied et les coups forts sont les meilleurs contre.
