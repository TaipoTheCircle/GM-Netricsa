GRENADE DE FRAGMENTATION


ARME: Fragmentation Grenade
MUNITIONS:   Grenade
CADENCE DE TIR:    ~30 lancers / min

DESCRIPTION:

Une grenade à fragmentation à main conçue pour détruire des cibles avec une explosion et des éclats. Il peut être utilisé contre des groupes d'ennemis et pour attaquer des cibles derrière la couverture. Après avoir été jetée, la grenade explose après quelques secondes.

La petite taille vous permet de transporter plusieurs grenades, mais l'approvisionnement est limité. Si elle est mal utilisée, l'explosion peut constituer un danger pour le lanceur.

REMARQUES:

- Tu ne peux pas tirer sur un ennemi ? - Jetez la grenade.
- Efficace contre des groupes d'ennemis.
- Vous permet de frapper des cibles derrière la couverture.
- Explose avec un léger retard après avoir été jeté.
