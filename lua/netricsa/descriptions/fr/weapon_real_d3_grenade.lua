GRENADE À FRAGMENTATION


ARME : Grenade à fragmentation
MUNITIONS : Grenade
ROF : ~30 lancers/min

DESCRIPTIF :

Une grenade à fragmentation portative conçue pour détruire des cibles avec une explosion et des éclats d'obus. Il peut être utilisé contre des groupes d’ennemis et pour attaquer des cibles à couvert. Après avoir été lancée, la grenade explose au bout de quelques secondes.

La petite taille permet de transporter plusieurs grenades, mais l'offre est limitée. Si elle est mal utilisée, l'explosion peut présenter un danger pour le lanceur.

REMARQUES :

- Vous ne pouvez pas tirer sur un ennemi dans un coin ? - Jetez simplement la grenade là-bas.
- Efficace contre les groupes d'ennemis.
- Vous permet de toucher des cibles à couvert.
- Explose avec un léger retard après avoir été lancé.
