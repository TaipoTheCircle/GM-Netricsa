HALF-QUAKE SHOW, JUMP ET RUN


Les sadiques semblent avoir décidé de changer de genre.

Maintenant c'est Parkour. Dans le noir.

Les chambres sont immergées dans la semi-obscurité, le genre où les murs apparaissent comme vous tombez déjà vers eux. Le sol est couvert de fosses à lave. Non marqué. Non éclairé. Tout simplement parce que les surprises donnent vie au spectacle. Ou vice versa.

Il ne s'agit pas de tirer. Il s'agit de mouvement. Sauter, courir, s'arrêter brusquement, sauter de nouveau. La lave en bas est patiente et sans hâte, sachant que tôt ou tard quelqu'un va trébucher.

Pour ouvrir la voie à suivre, vous devez trouver deux boutons pour deux générateurs. Ils sont cachés dans différentes parties de la pièce principale. Lorsque les deux générateurs sont activés, le chemin vers l'avant s'ouvre.

Et oui, conformément à la bonne vieille tradition, il y a des grenades cachées derrière un des murs. Le spectacle appelle cela "une récompense pour la curiosité".

Alors saute, Sam.

Cours. Danse.

Regardez votre pas, et un peu plus loin que vous le pensez.

Bonne chance.