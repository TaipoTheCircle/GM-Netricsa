GRENADE DE FRAGMENTATION M67


ARME: M67 grenade à main à fragmentation
MUNITIONS:   Remplissage des explosifs: Composition B (6.5 oz / 184 g)
CADENCE DE TIR:    4-5 s
POIDS: 400 g

DESCRIPTION:

Le M67 est la grenade à fragmentation standard américaine de baseball introduite à la fin des années 1960. Son corps en acier sphérique contient une membrane de fragmentation pré-encodée et environ 6,5 oz (=184 g) d'explosif Composition B; lors de la détonation, les fragments du corps produisent l'effet létale/shrapnel. La grenade est armée en retirant l'épingle de sécurité et en libérant le levier de sécurité (poon), après quoi la fusée pyrotechnique M213 brûle environ 4-5 secondes avant la détonation.

REMARQUES:

- Rayon létal couramment cité ~5 m; Rayon mort/efficace ~15 m; petits fragments peuvent être projetés des centaines de mètres dans de rares cas.
- La distance moyenne de lancer est de 30 à 35 m; soyez prudent avec des arcs de lancer dans des espaces confinés pour éviter les blessures amicales/auto.
- Classé comme une munition anti-personnel/effets de zone - efficace pour le nettoyage et la suppression de l'infanterie.