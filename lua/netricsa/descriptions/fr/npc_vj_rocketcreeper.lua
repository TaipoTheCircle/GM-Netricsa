CREEPER DE ROCKET DU MINECRAFT


CLASSE:      Crèche-rochettes
MÉTABOLISME: Produits végétaux chimiques
PERCEPTION: Créature de la poudre végétale
TAILLE:       5,5 pieds
ENDURANCE:  Faible
HOSTILITÉ:  Extrêmement élevé
ARMES:    Détonation de saut et de suivi
RÉCOMPENSE:     160 FC
MENACE:     Moyenne

DESCRIPTION:

C'est la preuve que la nature aime expérimenter les techniques d'auto-détonation. Alors qu'un rampant régulier approche et explose simplement, un rampant de fête jette des explosifs, la meilleure façon d'infliger des dommages est de débarquer spectaculairement la tête vers le bas sur sa victime.

Le comportement de la Rocket Creeper est unique. Comme un rampant régulier, il poursuit sa proie. Mais quand la distance se ferme, elle ne siffle ni ne s'enfuit. Au lieu de cela, il saute dans les airs et tombe en premier, droit à sa cible. L'explosion brise tout autour. L'explosion est aussi puissante que celle d'un rampant ordinaire, assez pour tuer une cible non armée.

Si un Rocket Creeper est frappé par la foudre, il devient chargé. Dans ce mode, la puissance de l'explosion double, comme un fluctuant chargé.

CONSEILS:

- On peut passer inaperçu.
- Le Rocket Creeper n'explose qu'à la fin de son saut. La fuite au dernier moment peut éviter la plupart des dégâts.
- Ne bougez pas. Pendant qu'il vole, vous avez le temps de vous déplacer sur le côté.
- C'est très dangereux. Son explosion peut détruire des structures même fortifiées. Si tu le vois, il vaut mieux rester loin.
- Comme tous les monstres, il ne meurt pas du soleil.
