FUSIL MASSIF BFG 9000


ARME : Fusil massif BFG 9000
MUNITIONS : BFG Cells
ROF : ~24 rounds / min

DESCRIPTIF :

A futuristic energy weapon developed by the UAC corporation. This is the most powerful weapon available, firing a huge green energy bolt. The projectile can damage not only the target upon impact, but also surrounding enemies with energy beams during its flight.

L'arme peut être chargée en maintenant le bouton de tir enfoncé. Plus la charge est longue, plus le tir est puissant, mais le maintenir trop longtemps provoque une surcharge et peut tuer le tireur.

Le BFG est particulièrement efficace contre des adversaires puissants et de grands groupes d'ennemis. Les munitions sont rares, donc les utiliser contre tous les zombies que vous rencontrez reviendrait à utiliser une tronçonneuse pour hacher du beurre.

REMARQUES :

- One of the most powerful weapons.
- L'éclair énergétique endommage les ennemis avant d'exploser.
- Les munitions sont rares, il est donc préférable de conserver chaque charge pour des adversaires plus puissants.
