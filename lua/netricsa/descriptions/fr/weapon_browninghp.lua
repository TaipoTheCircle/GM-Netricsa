PISTOLE D'AUTORISATION


ARME:     Browning Hi-Power
AMMUNITION: .40 cartouches SW
CADENCE DE TIR:        ~30 tours/min

DESCRIPTION:

Un pistolet auto-chargeur conçu par John Browning et Dieudonné Saëver avec un magazine à grande capacité. Le nom reflète la grande capacité du magazine - 13 tours. Le pistolet a été développé pour répondre aux spécifications techniques de l'armée française, mais n'a pas été adopté pour le service en France. Après la mort de Browning en 1926, le design a été affiné par Sev, designer en chef de la société belge Fabrique Nationale.

REMARQUES:

- Bien que la description indique que le magazine a 13 tours, il a en fait 10 tours.
- Le pistolet est bon et puissant.



