LE SELLER DE ROCK BLACK


CLASSE:      Le vendeur de Black Rock
MÉTABOLISME: Humain
PERCEPTION: Le trader de Black Rock
TAILLE:       ~5,9 pi
ENDURANCE:  Faible
HOSTILITÉ:  Faible
ARMES:    Aucune
RÉCOMPENSE:     40 FC
MENACE:     Très faible

DESCRIPTION:

Seller est un représentant de Black Rock Corporation, travaillant à bord du navire de recherche dans l'univers UH-1. Contrairement aux scientifiques, Seller se spécialise dans le commerce, l'acquisition et la logistique interne pour les projets de Black Rock. Il apparaît souvent dans des zones réglementées, négociant des transferts de ressources ou surveillant le transport des formes de vie de Xen capturées.

Bien qu'il ne soit pas un combattant, Seller est important pour les opérations de Black Rock, assurant que les technologies rares, les échantillons génétiques et les organismes Xen sont livrés aux bonnes mains. Comme beaucoup d'employés de Black Rock, il est gardé dans l'obscurité au sujet de la portée complète des transactions de l'entreprise, servant à la fois comme commerçant.

CONSEILS:

- Le vendeur évite le combat et fuit s'il est menacé.
- Protection du Vendeur peut accorder l'accès à des fournitures rares ou des informations restreintes.
- S'il est éliminé, Black Rock perd des liens précieux avec le marché des entreprises.
