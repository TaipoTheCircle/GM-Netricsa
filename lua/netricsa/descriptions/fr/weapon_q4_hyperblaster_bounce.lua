HYPERBLASTER


ARME: Hyperblasteur
MUNITIONS:   Cellules énergétiques
CADENCE DE TIR:    ~450 tours/min

DESCRIPTION:

L'Hyperblaster est une arme à haute puissance qui tire un plasma continu lorsque la détente est maintenue. Il a un taux d'incendie rapide et une portée solide. Le plasma apparaît comme une décharge de particules d'énergie bleue. Excellent pour les dommages subis et la suppression.

REMARQUES:

- Utilise des cellules énergétiques au lieu de munitions classiques.
- Le maintien continu de la gâchette permet un feu ininterrompu.
- Efficace à la fois contre des cibles uniques et contre le contrôle de la zone.