BRIGGS SMG


ARME:    Briggs SMG
MUNITIONS:      .40 S&W / 9x19mm
CADENCE DE TIR:       ~750 tours/min

DESCRIPTION:

Une mitrailleuse moderne basée sur la conception du Heckler & Koch UMP. Il dispose d'une haute précision, d'une puissance modérée et d'un fort taux de feu. L'arme est équipée d'une vue rouge-point qui comprend un système de reconnaissance de cible, qui change la couleur du réticule lorsqu'il vise un ennemi.

Le Briggs SMG utilise des magazines de 35 tours et est capable de feu entièrement automatique. Grâce à son excellente maniabilité, il est efficace à la fois dans les quartiers rapprochés et les combats à moyenne portée. Cependant, ses munitions ne sont pas particulièrement efficaces contre les armes lourdes.

REMARQUES:

- Basé sur la mitrailleuse allemande Heckler & Koch UMP.
- La vue est capable de distinguer entre ennemis et alliés.
- Le sélecteur de tir comprend un réglage pour un tir à simple tir, même si l'arme ne tire que par rafales ou complètement automatiquement.
