FEUILLE D'ACHRIMAN


CLASSE:      Sorcière d'Ahriman
MÉTABOLISME: Entité semi-corporelle
PERCEPTION: Sorceesse télékinétique
TAILLE:       7,4 pieds
ENDURANCE:  Moyenne
HOSTILITÉ:  Haut
ARMES:    Strangulation télékinétique, projection de débris/projectiles énergétiques, téléportation, déflexion du projectile
RÉCOMPENSE:     8000 FC
MENACE:     Haut

DESCRIPTION:

Une ancienne sorcière du Grand Concile, trompée et asservie par le Seigneur Achriman. Une entité piégée dans un limbo sémiotique entre les dimensions, la rendant invulnérable jusqu'à ce qu'elle se matérialise pour attaquer. Elle a une forme humanoïde femelle avec six tentacules sur le dos, un bikini en métal, et des souches au lieu de jambes. Sa tactique implique une téléportation constante et l'utilisation d'une puissante télékinésie pour attaquer : elle étrangle ses victimes de loin, soulève et casse des os, et leur lance des débris et des projectiles énergétiques. Elle est extrêmement dangereuse lorsqu'elle est combinée avec d'autres ennemis, car elle distrait et limite la mobilité.

CONSEILS:

- Il vaut mieux utiliser les fusils A-24 "Devastator" et sniper. Le canon du SBC tuera en un seul coup de feu.
- Son étranglement est interrompu si la ligne de vue est cassée (caché derrière la couverture) ou si elle est endommagée.
