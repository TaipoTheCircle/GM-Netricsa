FERREUSS WROUGHTNAUT DE L'EXERCICE MINECRAFT


CLASSE:      Métaux ferreux
MÉTABOLISME: Automate enchanté
PERCEPTION: Gardien oublié
TAILLE:       11 pieds
ENDURANCE:  Extrêmement élevé
HOSTILITÉ:  Absolu
WEAPONAUT:  Axe de mille métaux, Stompe magique
RÉCOMPENSE:     10000 FC
MENACE:     Maximum

DESCRIPTION:

Un gardien oublié, emprisonné pendant des siècles dans les chambres forgées. Ce n'est ni un homme ni une statue - c'est un morceau d'armure animée magique dont l'âme s'est disparue depuis longtemps, laissant seulement la rage aveugle et un devoir impossible. Il a oublié ce qu'il garde, qui il attend, et pour qui il pleure. Il ne se souvient que d'un seul ordre : détruire quiconque ose troubler la paix éternelle de ses salles. Il est complètement à l'abri de tous les dommages, à l'exception des frappes à un point vulnérable spécifique - une blessure sur le dos, qui n'est vulnérable que lors de son attaque la plus puissante, « Axe Strike », lorsqu'il plonge son arme dans le sol. En dehors du combat, son armure magique guérit instantanément tout dommage.

CONSEILS:

- Les dommages ne peuvent être infligés que lors de son attaque "Axe Strike", quand il s'arrête, plongeant sa hache dans le sol, exposant son dos. Visez précisément la blessure.
- L'attaque "Stomp" peut être esquivée en sautant au bon moment. Les coups de hache doivent être évités latéralement.
- L'amener dans "Axe Strike" en restant à portée moyenne. Après une erreur, bougez rapidement derrière lui et donnez des frappes précises. Éviter les combats rapprochés, ses boucliers sont inutiles contre ses attaques.
- Quand sa santé est faible, il effectue des combos de deux ou trois attaques, dont la dernière est une attaque tournante qui ne laisse presque aucune chance d'esquiver. À ce stade, il est préférable de reculer et d'attendre la prochaine occasion d'attaquer par derrière.
- A la défaite, vous recevez son Casque Forgé et la légendaire Axe des Mille Métaux.
