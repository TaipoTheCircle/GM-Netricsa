ARBALISTE DU PILLAGE DE L ' APERÇU MINECRAFT


CLASSE:      Arbaliste pillaire
MÉTABOLISME: Humain
PERCEPTION: Pillier avec arbalète, infanterie légère Illager
TAILLE:       6,2 pi
ENDURANCE:  Haut
HOSTILITÉ:  Extrême
ARMES:    Acrobatie
RÉCOMPENSE:     100 FC
MENACE:     Haut

DESCRIPTION:

L'une des variétés de villageois hostiles les plus courantes et reconnaissables, armée d'une arbalète et sans merci. Tandis qu'un villageois normal échange avec vous et construit des fermes, un Arbaliste Pilliger veut simplement vous transformer en un coussin de flèche.

Contrairement à leurs cousins de Vindicator, qui préfèrent les combats rapprochés, Pillanger Arbalist est un sniper naturel. Leur arme principale et unique est une arbalète, qu'ils tirent toutes les 3 secondes à une cible dans un rayon de 16 mètres. Lorsqu'elle est complètement submergée, Pilliger Arbalist passe au combat rapproché, car l'arbalète est inefficace sous l'eau.

Pillier Arbalist habite trois endroits, chacun d'eux promet des ennuis. Tout d'abord, il y a des patrouilles d'Arbalistes Pilliger-groupes de 2-5 maraudeurs qui errent dans le monde à la recherche de villages. Deuxièmement, il y a des avant-postes de Pillanger Arbalist avec des cages pour les golems de fer, autour desquels ces archers résident constamment. Et troisièmement, il y a des raids, où Pilliger Arbalist forme l'épine dorsale des premières vagues d'envahisseurs.

La principale caractéristique de Pilliger Arbalist est leur tactique lâche mais efficace. Ils ne se livrent jamais à un combat étroit, préférant garder leur distance et tirer méthodiquement sur leur cible. Si un joueur s'approche, l'Arbaliste Pilliger recule, essayant de maintenir sa distance. Dans les couloirs étroits, cela peut être fatal, car il est difficile d'éviter une flèche.

Parmi les Pilliger Arbalist, il y a des capitaines maraudeurs avec un drapeau odieux sur leur tête. Ils sont facilement reconnus par la bannière noire et blanche qui flotte au-dessus de leur capot. Tuer un tel capitaine inflige l'effet de statut "Bad Omen". Le niveau de l'effet dépend du nombre de capitaines tués. Avec cet effet de statut, un raid commence en entrant dans un village-une série de vagues dans lesquelles Pilliger Arbalist et autres Ilagers tentent d'éliminer tous les villageois.

Pendant les raids, Pilliger Arbalist est particulièrement agressif, s'attaquant spécifiquement aux villageois. S'ils parviennent à tuer un villageois ou à détruire une porte, ils laissent sortir un rire triomphant et sautent en place.

Pillier Arbalist peut apparaître monté sur des fauves-grandes bêtes qui détruisent tout sur leur chemin. Un coureur est un adversaire particulièrement dangereux, car il doit éviter les flèches et les béliers.

Dans les raids, Pilliger Arbalist laisse parfois tomber des émeraudes. Les capitaines laissent toujours derrière leur drapeau un trophée précieux et une source de problèmes.

Si les arbalètes d'un Pillier Arbalist se brisent (les arbalètes ont de la durabilité, comme tout outil), ils ne peuvent pas tirer et devenir impuissants, bien qu'ils restent techniquement hostiles.

CONSEILS:

- Un bouclier bloque complètement les flèches et vous permet de fermer sans faire de victimes.
- Ne cours pas directement chez un Arbaliste. Tirez en arrière avec un arc ou arbalète-vos flèches infligent les mêmes dommages que le leur.
- Ne vous démarquez pas en plein air dans des couloirs étroits - la flèche volera à droite.
- Si vous voyez un capitaine avec un drapeau, réfléchissez deux fois avant de les tuer. Le buff "Ill Omen" commencera un raid dès que vous entrerez dans le village.
- Le lait enlève le buff "Ill Omen" si vous n'êtes pas encore prêt pour un raid.
- Dans l'eau, l'Arbaliste Pilliger est impuissant et passe au combat, qui inflige moins de dégâts.
- Dans les raids, essayez de tuer l'Arbaliste Pilliger en premier - ils vous empêchent de vous concentrer sur des ennemis plus forts.
- Ne les laissez pas vous encercler.
- Si l'Arbaliste Pilliger est sur un Ravager, tuer l'archer en premier - la bête est moins dangereuse sans un pilote.
